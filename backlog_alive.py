def подлог_137():
    """Каталог перестаёт разбираться из шаблона — как если бы он переехал.

    Портится ОБЪЯВЛЕНИЕ (`const SETS =`), а не данные: это часть языка,
    а не строка каталога, и правкой сетов её не сдвинуть.
    """
    @contextlib.contextmanager
    def _переименовать():
        путь = os.path.join(КОРЕНЬ, "templates/enshrouded.html")
        было = io.open(путь, encoding="utf-8", newline="").read()
        assert "const SETS" in было, "объявления SETS нет — подлог опереться не на что"
        try:
            io.open(путь, "w", encoding="utf-8", newline="").write(
                было.replace("const SETS", "const SETS_ПЕРЕЕХАЛ", 1))
            yield
        finally:
            io.open(путь, "w", encoding="utf-8", newline="").write(было)

    return _переименовать()



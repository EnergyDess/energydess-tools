# ── ПОДЛОГИ: СПУТНИК ПРОБЫ, А НЕ ОТДЕЛЬНЫЙ ПЕРЕЧЕНЬ ──────────────────────
# Подлог живёт РЯДОМ с пробой и называется `подлог_<номер>`. Контроль
# находит их ПРИЗНАКОМ — по имени в модуле, — а не по своему списку
# (§6.0.7): список из трёх номеров {3, 121, 128} и был тем, что сломалось,
# — все три задачи закрылись, и контроль перестал проверять хоть что-то.
#
# Подлог обязан портить ПРЕДМЕТ, а не ответ пробы. Подделка ответа
# проверяла бы арифметику контроля, а не чувствительность пробы.

@contextlib.contextmanager
def _дописать(имя, хвост):
    """Дописать в конец файла и вернуть как было. Якоря НЕТ намеренно:

    якорь — строка чужого файла, и он протухает от любой правки рядом.
    Ровно так контроль 121 и умер: подлог опирался на устройство,
    которого после закрытия задачи не стало.
    """
    путь = os.path.join(КОРЕНЬ, имя)
    было = io.open(путь, encoding="utf-8", newline="").read()
    try:
        io.open(путь, "w", encoding="utf-8", newline="").write(было + хвост)
        yield
    finally:
        io.open(путь, "w", encoding="utf-8", newline="").write(было)


@contextlib.contextmanager
def _файл(имя, тело=b"x"):
    """Положить файл и убрать. Порча предмета для проб, читающих диск."""
    путь = os.path.join(КОРЕНЬ, имя)
    try:
        io.open(путь, "wb").write(тело)
        yield
    finally:
        if os.path.exists(путь):
            os.remove(путь)


def подлог_17():
    """Письмо, у которого длинное слово стоит И в теле, И в ЗАГОЛОВКЕ.

    Проба берёт слово из тела ПОСЛЕДНЕГО письма и ждёт, что поиск его
    не найдёт. Такое письмо поиск найдёт по заголовку — то есть ответ
    обязан перевернуться. Стенда это не требует сверх того, что уже
    нужно самой пробе: строка кладётся в ту же базу, которую читает
    поднятое приложение.
    """
    import sqlite3
    путь = os.environ.get("DB_PATH", os.path.join(КОРЕНЬ, "app.db"))
    бд = sqlite3.connect(путь)

    @contextlib.contextmanager
    def _вставить():
        слово = 'подложноеслово'
        # Строка копируется ЦЕЛИКОМ с подменой двух полей: перечислять
        # колонки руками значило бы завести перечень, который отстанет

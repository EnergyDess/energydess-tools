        # `job_text` NOT NULL уронил первую версию подлога.
        поля = [с[1] for с in бд.execute('PRAGMA table_info(cover_letters)').fetchall()]
        стр = dict(zip(поля, бд.execute('SELECT * FROM cover_letters ORDER BY id DESC LIMIT 1').fetchone()))
        стр['id'] = None
        стр['job_title'] = слово
        стр['letter_text'] = (слово + ' ') * 40
        стр['deleted_at'] = None
        кур = бд.execute(
            'INSERT INTO cover_letters (%s) VALUES (%s)'
            % (','.join(поля), ','.join('?' * len(поля))),
            [стр[к] for к in поля])
        бд.commit()

# ── ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ───────────────────────────────────────────────
# Проба, отвечающая одинаково на исправленном и на сломанном коде,
# не отвечает ни на что.
#
# КОНТРОЛЬ ИДЁТ ПО ЖИВОЙ ВЫДАЧЕ, А НЕ ПО ЗАШИТЫМ НОМЕРАМ. До 2026-08-22
# он дёргал ровно три пробы — 3, 121 и 128, — и все три задачи к тому дню
# ЗАКРЫЛИСЬ. Замер: живых проб под контролем было НОЛЬ из шести, то есть
# контроль отчитывался о пробах, которыми ревизия не пользуется, и молчал
# обо всех, которыми пользуется. Номера закрываются — значит перечень
# номеров держать нельзя (§6.0.7).
#
# Подлоги — спутники проб (`подлог_<номер>`), находятся ПРИЗНАКОМ.
# Закрытая задача выбывает из контроля сама; открытая, у которой подлога
# нет, НАЗЫВАЕТСЯ и роняет контроль: проба без контроля не гарантирует
# ничего, и молчать об этом — тот же немой отказ.

def _число(строка):
    """Все числа строки-объяснения. Сдвиг любого — доказательство отклика.

    Сравнивать по одному числу нельзя: у проб они разные по смыслу
    («отступов 49, кеглей 8»), и перечислять, какое из них главное,
    значило бы завести перечень внутри контроля.
    """
    return tuple(int(ч) for ч in re.findall(r"\d+", строка or ""))


def контроль(браузер=False):
    import backlog_open
    print("=" * 74)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОБ: подлог обязан перевернуть ответ")
    print("=" * 74)

    открытые = {int(н.rstrip("ab"))
                for н, _, ст, ос, _ in backlog_open.задачи()
                if backlog_open.состояние(ст, ос)[0] == "открыта"}
    живые = sorted((set(ПРОБЫ) & открытые) - set(ВНЕ_РЕВИЗИИ))
    print(f"  открытых задач: {len(открытые)}; из них с пробой и в ревизии: "
          f"{len(живые)} {живые}")
    print()

    ок, проверено, пропущено = True, 0, []
    for номер in живые:
        проба = ПРОБЫ[номер]
        подлог = globals().get(f"подлог_{номер}")
        зовём = (lambda: проба(браузер)) if номер == 125 else проба
        if СТЕНД.get(номер) and not браузер:
            пропущено.append(номер)
            print(f"  ..   {номер:>4}: пропущена — нужен стенд (--браузер)")
            continue


        try:
            жив_до, чем_до = зовём()
        except Exception as e:
            print(f"  НЕТ  {номер:>4}: проба упала ДО подлога — "
                  f"{type(e).__name__}: {e}")
            ок = False
            continue

        # Предмет вне кода: подлога не бывает, и это НАЗВАНО, а не пропущено.
        if жив_до is None:
            print(f"  --   {номер:>4}: вне контроля — {чем_до[:60]}")
            continue

        if подлог is None:
            print(f"  НЕТ  {номер:>4}: ПОДЛОГА НЕТ — проба ничего не гарантирует")
            ок = False
            continue

        try:
            with подлог():
                жив_после, чем_после = зовём()
        except Exception as e:
            print(f"  НЕТ  {номер:>4}: проба упала ПОД подлогом — "
                  f"{type(e).__name__}: {e}")
            ок = False
            continue

        сдвинулось = (жив_до != жив_после) or (_число(чем_до) != _число(чем_после))
        проверено += 1
        ок = ок and сдвинулось
        знак = "ok " if сдвинулось else "НЕТ"
        print(f"  {знак}  {номер:>4}: жив {жив_до} -> {жив_после}; "
              f"{чем_до[:44]} -> {чем_после[:44]}")

    print()
    if not проверено:
        print("ПРОВАЛЕН: не проверено НИ ОДНОЙ живой пробы. "
              "Пустой контроль неотличим от пройденного.")
        return 1
    print(f"  проверено живых проб: {проверено}"
          + (f"; пропущено без стенда: {пропущено}" if пропущено else ""))
    print("ПРОЙДЕН." if ок else "ПРОВАЛЕН: проба не реагирует на подлог.")
    return 0 if ок else 1



def контроль():
    """Три подлога, и каждый бьёт по своей половине разбора.

    Подлог кладётся в ТЕКСТ, а не в файл: разбор принимает текст
    аргументом, поэтому портить BACKLOG.md ради контроля незачем.
    Файл при этом читается настоящий — контроль на выдуманной строке
    доказывал бы работу регулярки, а не разбор рабочего документа.
    """
    исходный = ФАЙЛ.read_text(encoding="utf-8")

    def открытые(текст):
        return {н for н, _, ст, ос, _ in задачи(текст)
                if состояние(ст, ос)[0] == "открыта"}

    было = открытые(исходный)

    # ── 1. закрыть открытую: обязана исчезнуть ────────────────────────
    цель = sorted(было, key=ключ)[-1]
    m = re.search(r"^## " + re.escape(цель) + r"\. .+$", исходный, re.M)
    хвост = исходный[m.end():]
    m2 = re.search(r"^\*\*Статус:\*\*.*$", хвост, re.M)
    закрыто = (исходный[:m.end()] + хвост[:m2.start()]
               + "**Статус:** ВЫПОЛНЕНА 2026-01-01 (подлог контроля)"
               + хвост[m2.end():])
    стало_закрыто = открытые(закрыто)

    # ── 2. вернуть: обязана вернуться ────────────────────────────────
    вернулось = открытые(исходный)

    # ── 3. задача с номером и БЕЗ статуса: обязана быть показана ─────
    без_статуса = исходный + (
        "\n\n## 999. Подлог контроля: задача без строки статуса\n\n"
        "**Затрагивает:** ничего, это подлог\n")
    стало_без = открытые(без_статуса)

    # ── 4. незнакомая форма статуса: обязана быть показана с пометкой ─
    чужой = исходный + (
        "\n\n## 998. Подлог контроля: статус неизвестной формы\n\n"
        "**Статус:** ЖДЁТ ВЛАДЕЛЬЦА, форма, которой в списке нет\n")
    метка998 = [состояние(ст, ос)[1] for н, _, ст, ос, _ in задачи(чужой)
                if н == "998"]

    # ── 5. закрытая задача С ПОЛЕМ остатка: обязана быть показана ────
    с_остатком = исходный + (
        "\n\n## 997. Подлог контроля: закрыта, но остаток назван\n\n"
        "**Статус:** ВЫПОЛНЕНА 2026-01-01\n"
        "**Остаток:** боевая часть работы не сделана\n")
    стало_997 = открытые(с_остатком)

    цел = ФАЙЛ.read_text(encoding="utf-8") == исходный

    print("=" * 74)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ СПИСКА ОТКРЫТЫХ ЗАДАЧ")
    print("=" * 74)
    print()
    print("  открытых сейчас                        : %d" % len(было))
    print("  подлог 1: задача %s помечена ВЫПОЛНЕНА  : %d  (%s)"
          % (цель, len(стало_закрыто),
             "исчезла" if цель not in стало_закрыто else "ОСТАЛАСЬ — сломано"))
    print("  подлог снят                            : %d  (%s)"
          % (len(вернулось),
             "вернулась" if цель in вернулось else "НЕ ВЕРНУЛАСЬ — сломано"))
    print("  подлог 2: задача 999 БЕЗ строки статуса : %s"
          % ("показана" if "999" in стало_без else "ПРОГЛОЧЕНА — сломано"))
    print("  подлог 3: задача 998, форма статуса чужая: %s"
          % ("показана, метка «%s»" % метка998[0] if метка998 and "998" in
             открытые(чужой) else "ПРОГЛОЧЕНА — сломано"))
    print("  подлог 4: задача 997 закрыта, но с полем остатка: %s"
          % ("показана" if "997" in стало_997 else "ПРОГЛОЧЕНА — сломано"))
    print("  BACKLOG.md не тронут                   : %s"
          % ("да" if цел else "НЕТ"))

    ок = (цель not in стало_закрыто and цель in вернулось
          and "999" in стало_без and "998" in открытые(чужой)
          and метка998 and метка998[0] == "СТАТУС НЕ РАЗОБРАН"
          and "997" in стало_997 and цел)
    print()
    print("ПРОЙДЕН: закрытие прячет, возврат возвращает, незнакомое "
          "и безстатусное видно" if ок else
          "ПРОВАЛЕН: разбор глотает то, что обязан показывать")
    return 0 if ок else 1



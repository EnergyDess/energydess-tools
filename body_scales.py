def _мышцы(пол, рост_см):
    """Таблица holtek по росту и полу: у мужчины от 170 см — 49.5/59.4,
    ровно как на экране. Вариант xiaomi (49.4/59.5) экраном опровергнут."""
    if пол not in (ПОЛ_М, ПОЛ_Ж) or not рост_см:
        return None
    таблица = [
        (170, {ПОЛ_Ж: [36.5, 42.5], ПОЛ_М: [49.5, 59.4]}),
        (160, {ПОЛ_Ж: [32.9, 37.5], ПОЛ_М: [44.0, 52.4]}),
        (0,   {ПОЛ_Ж: [29.1, 34.7], ПОЛ_М: [38.5, 46.5]}),
    ]
    for порог, строка in таблица:
        if рост_см >= порог:
            return list(строка[пол])
    return None


def _кость(пол, вес_кг):
    """Таблица holtek по весу и полу, смещение [optimal, optimal+1].

    Смещение — ЗАМЕР, а не источник: код holtek строит [optimal-1,
    optimal+1], приложение на сверочном профиле (99.4 кг) показывает
    3.2/4.2 при optimal 3.2. Разбор и признанный риск — в шапке файла."""
    if пол not in (ПОЛ_М, ПОЛ_Ж) or not вес_кг:
        return None
    таблица = [
        ({ПОЛ_М: 75.0, ПОЛ_Ж: 60.0}, {ПОЛ_М: 3.2, ПОЛ_Ж: 2.5}),
        ({ПОЛ_М: 69.0, ПОЛ_Ж: 45.0}, {ПОЛ_М: 2.9, ПОЛ_Ж: 2.2}),
        ({ПОЛ_М: 0.0,  ПОЛ_Ж: 0.0},  {ПОЛ_М: 2.5, ПОЛ_Ж: 1.8}),
    ]
    for снизу, опорные in таблица:
        if вес_кг >= снизу[пол]:
            опорное = опорные[пол]
            return [round(опорное, 2), round(опорное + 1, 2)]
    return None


def _обмен(пол, возраст, вес_кг):
    """Коэффициенты holtek: порог = вес * коэффициент по возрасту и полу.

    Воспроизводит экран: 99.4 * 23 = 2286.2 против показанных 2287
    (расхождение 0.03 % — округление веса). Коэффициенты xiaomi дают 2147,
    формулы Миффлина и Харриса–Бенедикта — 2046 и 2173; ни одна не подходит."""
    if пол not in (ПОЛ_М, ПОЛ_Ж) or not возраст or not вес_кг:
        return None
    коэффициенты = {
        ПОЛ_Ж: [(12, 34), (15, 29), (17, 24), (29, 22), (50, 20), (120, 19)],
        ПОЛ_М: [(12, 36), (15, 30), (17, 26), (29, 23), (50, 21), (120, 20)],
    }
    for предел, коэффициент in коэффициенты[пол]:
        if возраст < предел:
            return [round(вес_кг * коэффициент, 1)]
    return None


def _идеальный(рост_см):
    """Пороги ИМТ, переведённые в килограммы ростом. Совпадает с экраном:
    при 190 см даёт 66.78/90.25/108.3 против показанных 66.80/90.30/108.3."""
    if not рост_см:
        return None
    метры = рост_см / 100.0
    return [round(имт * метры * метры, 2) for имт in ИМТ_ПОРОГИ]



# ── Границы: каждая функция возвращает список порогов либо None ────────────
#
# None означает «посчитать не из чего»: не хватает анкеты. Это НЕ ошибка
# и не пустой список — пустой список читался бы как «порогов ноль»,
# то есть как одна зона на всю шкалу.

def _жир(пол, возраст):
    """Таблица xiaomi по возрасту и полу. Воспроизводит экран: у мужчины
    18–40 лет приложение показывает ровно 11/17/22/27."""
    if пол not in (ПОЛ_М, ПОЛ_Ж) or not возраст:
        return None
    таблица = [
        (0, 12,   {ПОЛ_Ж: [12.0, 21.0, 30.0, 34.0], ПОЛ_М: [7.0, 16.0, 25.0, 30.0]}),
        (12, 14,  {ПОЛ_Ж: [15.0, 24.0, 33.0, 37.0], ПОЛ_М: [7.0, 16.0, 25.0, 30.0]}),
        (14, 16,  {ПОЛ_Ж: [18.0, 27.0, 36.0, 40.0], ПОЛ_М: [7.0, 16.0, 25.0, 30.0]}),
        (16, 18,  {ПОЛ_Ж: [20.0, 28.0, 37.0, 41.0], ПОЛ_М: [7.0, 16.0, 25.0, 30.0]}),
        (18, 40,  {ПОЛ_Ж: [21.0, 28.0, 35.0, 40.0], ПОЛ_М: [11.0, 17.0, 22.0, 27.0]}),
        (40, 60,  {ПОЛ_Ж: [22.0, 29.0, 36.0, 41.0], ПОЛ_М: [12.0, 18.0, 23.0, 28.0]}),
        (60, 200, {ПОЛ_Ж: [23.0, 30.0, 37.0, 42.0], ПОЛ_М: [14.0, 20.0, 25.0, 30.0]}),
    ]
    for снизу, сверху, строка in таблица:
        if снизу <= возраст < сверху:
            return list(строка[пол])
    return None


def _вода(пол):
    """Константа по полу, таблица xiaomi. Мужской вариант воспроизводит
    экран точно; женский из того же источника и живым замером НЕ проверен."""
    if пол == ПОЛ_М:
        return [55.0, 65.1]
    if пол == ПОЛ_Ж:
        return [45.0, 60.1]

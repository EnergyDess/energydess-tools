ГДЕ_ИСКАТЬ = [("templates", (".html",)), ("static", (".js",))]


def имена_из_кода():
    """Имена, написанные в разметке и скриптах буквально."""
    найдено = set()
    for каталог, расширения in ГДЕ_ИСКАТЬ:
        путь = os.path.join(КОРЕНЬ, каталог)
        for корень, _, файлы in os.walk(путь):
            for ф in файлы:
                if not ф.endswith(расширения):
                    continue
                текст = io.open(os.path.join(корень, ф), encoding="utf-8",
                                errors="replace").read()
                # ДВЕ ФОРМЫ, и обе обязательны. `значок('users')` —
                # значок, подставленный сервером в разметку; заготовка
                # `data-lucide="users"` — значок, который дорисует
                # скрипт уже после загрузки. Пропусти первую — и набор
                # схлопнется до трёх десятков имён, а страницы упадут
                # на рендере: ровно это и случилось при первой сборке.
                найдено |= set(re.findall(r"значок\(\s*'([a-z0-9-]+)'", текст))
                найдено |= set(re.findall(r'значок\(\s*"([a-z0-9-]+)"', текст))
                найдено |= set(re.findall(r'data-lucide="([a-z0-9-]+)"', текст))
                найдено |= set(re.findall(r"data-lucide',\s*'([a-z0-9-]+)'", текст))
                # ТРЕТЬЯ ФОРМА — значок, переданный ПАРАМЕТРОМ макросу
                # модалки: `{% call m.modal('x', 'Заголовок', icon='tag') %}`.
                # Внутри макроса он уходит в `значок(icon)`, то есть имени
                # там нет ни в одной из двух форм выше, и до 2026-08-24
                # такое имя в набор НЕ ПОПАДАЛО.
                #
                # Отказ был не молчащий, но и не там, где ищут: страница
                # падала пятисоткой при отрисовке, а причина («значка tag
                # нет в наборе») печаталась в журнал сервера, тогда как
                # сам голый прогон `build_icons.py` в это время говорил
                # «набор покрывает код». Два инструмента отвечали
                # по-разному на один вопрос.
                #
                # Пятая форма — эмодзи в том же параметре — сюда не
                # попадает по построению: регулярка берёт только
                # ASCII-имена, а макрос различает их тем же признаком.
                найдено |= set(re.findall(r"icon\s*=\s*'([a-z0-9-]+)'", текст))
                найдено |= set(re.findall(r'icon\s*=\s*"([a-z0-9-]+)"', текст))
    return найдено


def нужные():
    return sorted(имена_из_кода() | set(ИЗ_ДАННЫХ))


def собрать():
    """Готовый словарь имя → внутренняя разметка <svg>.

    РИСУЕТ САМ LUCIDE, В НАСТОЯЩЕМ БРАУЗЕРЕ, а не разбор его сборки:
    файл на unpkg минифицирован, имена значков там переименованы
    в однобуквенные (`Users:Ug`), и любая регулярка по нему — догадка.
    Здесь догадки нет: заготовки складываются на страницу, зовётся тот
    самый `createIcons`, и обратно читается то, что он нарисовал.
    Совпадение с прежним видом получается ПО ПОСТРОЕНИЮ.
    """
    from playwright.sync_api import sync_playwright
    имена = нужные()
    разметка = "".join('<i data-lucide="%s"></i>' % и for и in имена)
    страница = (
        "<!doctype html><meta charset=utf-8><body>" + разметка +
        '<script src="' + ИСТОЧНИК + '"></script>'
        "<script>lucide.createIcons();</script>")
    набор, потеряно = {}, []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        стр = бр.new_page()
        стр.set_content(страница, wait_until="load")
        стр.wait_for_timeout(500)
        собрано = стр.evaluate("""() => {
            const о = {};
            document.querySelectorAll('svg[data-lucide]').forEach(s => {
                о[s.getAttribute('data-lucide')] = s.innerHTML;
            });
            const ждут = [];
            document.querySelectorAll('i[data-lucide]').forEach(
                e => ждут.push(e.getAttribute('data-lucide')));
            return {о, ждут};
        }""")
        бр.close()
    набор = собрано["о"]
    потеряно = собрано["ждут"]
    # Пустое содержимое — тот же немой отказ, что и отсутствие имени:
    # <svg> есть, рисовать нечего.
    пустые = [и for и, т in набор.items() if not (т or "").strip()]
    return набор, sorted(set(потеряно) | set(пустые))


ШАПКА = '''// СОБРАН `build_icons.py` — РУКАМИ НЕ ПРАВИТЬ.
// Единственный источник данных о значках на обе стороны: сервер читает
// этот же файл (`icons.py`) и подставляет <svg> прямо в разметку, чтобы
// значок стоял на первом же нарисованном кадре; браузер берёт отсюда же
// значки для разметки, собранной скриптом уже после загрузки.
//
// Пришёл на смену `unpkg.com/lucide@latest`: 419 КБ и два обращения
// в чужую сеть, пока которые ехали, на экране стояли пустые заготовки.
window.LUCIDE_ICONS = %s;

// Замена заготовок `<i data-lucide>` на <svg>. Повторяет то, что делал
// `lucide.createIcons()`, включая класс `lucide lucide-<имя>` и перенос
// самого атрибута на <svg>: под эти имена написаны стили, и рисовать
// иначе значило бы поменять облик заодно с механикой.
window.рисоватьЗначки = function (корень) {
  var где = (корень && корень.querySelectorAll) ? корень : document;
  var список = где.querySelectorAll('[data-lucide]');
  for (var i = 0; i < список.length; i++) {
    var э = список[i];
    if (э.tagName.toLowerCase() === 'svg') continue;   // уже нарисован
    var имя = э.getAttribute('data-lucide');
    var тело = window.LUCIDE_ICONS[имя];
    // ИМЯ, КОТОРОГО НЕТ В НАБОРЕ, — НЕ МОЛЧАНИЕ. Пустое место вместо
    // значка выглядит как «так и задумано»; строка в консоли называет
    // имя и говорит, чем это чинится.
    if (тело === undefined) {
      console.warn('[значки] «' + имя + '» нет в наборе — добавьте его '
                 + 'в build_icons.py и пересоберите static/icons.js');
      continue;
    }
    var svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
    svg.setAttribute('width', '24');
    svg.setAttribute('height', '24');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('data-lucide', имя);
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('class', ('lucide lucide-' + имя + ' '
                               + (э.getAttribute('class') || '')).trim());
    // ОСТАЛЬНЫЕ АТРИБУТЫ ЗАГОТОВКИ ПЕРЕНОСЯТСЯ — так делал и Lucide.
    // Без этого молча терялись бы `id`, `title`, `aria-label` и всё,
    // за что цепляется чужой код: элемент на экране тот же, а найти
    // его по id уже нельзя, и ошибки при этом никакой.
    for (var j = 0; j < э.attributes.length; j++) {
      var а = э.attributes[j];
      if (а.name === 'class' || а.name === 'data-lucide') continue;
      svg.setAttribute(а.name, а.value);
    }
    svg.innerHTML = тело;
    э.replaceWith(svg);
  }
};

// Совместимость: страницы зовут `lucide.createIcons()` в двенадцати
// местах, и переписывать их все ради переименования нечего.
window.lucide = window.lucide || {};
window.lucide.createIcons = function () { window.рисоватьЗначки(document); };
'''


def записать(набор):
    текст = ШАПКА % json.dumps(набор, ensure_ascii=False, indent=0,
                               sort_keys=True)
    io.open(ВЫХОД, "w", encoding="utf-8", newline="\n").write(текст)
    return текст


def в_файле():
    """Имена, лежащие в собранном наборе. Разбор — у `icons.py`,
    второй реализации чтения того же файла в проекте нет."""
    import icons
    return set(icons.набор())



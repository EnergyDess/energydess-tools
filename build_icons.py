def _подложить(форма):
    строка = ("{{ значок('%s') }}" % ИМЯ_СЕРВЕР if форма == "сервер"
              else '<i data-lucide="%s"></i>' % ИМЯ_СКРИПТ)
    io.open(ПОДЛОЖЕННЫЙ, "w", encoding="utf-8",
            newline="\n").write(строка + "\n")


def _убрать():
    if os.path.exists(ПОДЛОЖЕННЫЙ):
        os.remove(ПОДЛОЖЕННЫЙ)


def доказать_подлог(знак, нужно):
    """ПОДЛОГ СОСТОЯЛСЯ — доказательство отдельно от вердикта (§6.0.3).

    Вердикт «имени нет в наборе» доказательством не является: ровно
    то же напечаталось бы, если бы подложенный файл не прочитали
    вовсе. Доказательство — подложенное имя ПРИСУТСТВУЕТ в множестве
    имён, собранных из кода. Не присутствует — читать было нечего,
    и вердикт про этот подлог не значит ничего.
    """
    return знак in нужно


def контроль():
    было = set(нужные()) - в_файле()
    случаи = [("значок() — серверная отрисовка", "сервер", ИМЯ_СЕРВЕР),
              ("data-lucide — дорисовка скриптом", "скрипт", ИМЯ_СКРИПТ)]
    итог = []
    try:
        for имя, форма, знак in случаи:
            _подложить(форма)
            нужно = set(нужные())
            нет = нужно - в_файле()
            итог.append((имя, доказать_подлог(знак, нужно), знак in нет,
                         len(было), len(нет)))
            _убрать()
    finally:
        _убрать()
    print("КОНТРОЛЬ ПРОВЕРКИ 25 — два подлога, у каждого ДОКАЗАТЕЛЬСТВО\n")
    print("  %-36s %10s %8s %8s %s"
          % ("подлог", "прочитан", "было", "стало", "итог"))
    ок = True
    for имя, прочитан, нашла, б, с in итог:
        ладно = прочитан and нашла and с == б + 1
        ок = ок and ладно
        print("  %-36s %10s %8d %8d %s"
              % (имя, "да" if прочитан else "НЕТ", б, с,
                 "ПРОЙДЕН" if ладно else "НЕ ПРОЙДЕН"))
    print()
    if ок:
        print("КОНТРОЛЬ ПРОЙДЕН: сверка видит имя, которого нет в наборе,")
        print("в ОБЕИХ формах записи.")
        return 0
    print("КОНТРОЛЬ НЕ ПРОЙДЕН: ноль этой проверки ничего не значит.")
    return 1


def main():
    # СВЕРКА — ДЕЙСТВИЕ ПО УМОЛЧАНИЮ, сборка — по явному ключу.
    # Не вкус: голый вызов стоит ПРОВЕРКОЙ 25 в ряду §6.0.2, а ряд
    # запускает команду ИМЕНЕМ СКРИПТА, отбрасывая ключи (`check_metrics`,
    # `[sys.executable, имя]`). С прежним умолчанием ряд на каждом
    # прогоне поднимал браузер и качал 419 КБ из чужой сети — и один
    # такой прогон уже дал код 2 там, где сверка даёт 0. Опасное
    # действие называется вслух, безопасное идёт само.
    if "--контроль" in sys.argv[1:]:
        return контроль()
    if "--собрать" not in sys.argv[1:]:
        return сверить()
    набор, потеряно = собрать()
    if потеряно:
        print("!! У Lucide НЕТ значков: %s" % ", ".join(потеряно))
        print("   Имя переименовано или опечатка — значок был бы пустым "
              "местом без единой ошибки.")
        return 1
    новый = записать(набор)
    print("static/icons.js собран: значков %d, %d КБ"
          % (len(набор), len(новый) // 1024))

def _условные():
    """УСЛОВНОЕ ПРЕДОСТЕРЕЖЕНИЕ: показывается ли, когда повод ЕСТЬ.

    «Без картинки N — баннер схлопнут» на сидированном стенде не видно
    ни разу: картинка есть у всех 90 сетов, и повода нет. Требовать
    эту строку в общем прогоне значило бы печатать находку про исправный
    экран (§8.0 — состояние, ПРОТИВОПОЛОЖНОЕ нужному), поэтому повод
    ЗАВОДИТСЯ здесь и возвращается в `finally`.

    Боевую базу не открывает: путь с `/data/` отвергается.
    """
    import sqlite3
    путь = os.environ.get("DB_PATH", "app.db")
    if "/data/" in путь.replace(chr(92), "/"):
        print("ПРОПУСК: путь похож на боевую базу — %s" % путь)
        return 2
    c = sqlite3.connect(путь)
    ряд = c.execute("SELECT id, img_ext FROM enshrouded_sets "
                    "WHERE img_ext IS NOT NULL AND img_ext <> '' "
                    "ORDER BY id LIMIT 1").fetchone()
    if not ряд:
        print("ПРОПУСК: на стенде нет ни одного сета С картинкой — "
              "заводить повод не из чего")
        c.close()
        return 2
    ид, было = ряд
    print("УСЛОВНОЕ: у сета %s снимаем картинку (было %r), вернём в конце."
          % (ид, было))
    try:
        c.execute("UPDATE enshrouded_sets SET img_ext = '' WHERE id = ?", (ид,))
        c.commit()
        снимки = _снять(1920, разделы=[("Enshrouded", "/admin/enshrouded")])
        ждём, нашли, потери = _предостережения(снимки, условные=True)
        print("  повод ЕСТЬ:  условных предостережений %d из %d" % (нашли, ждём))
        for раздел, ключ, что in потери:
            print("    ПОТЕРЯНО  %-12s %-10s — %s" % (раздел, ключ, что))
        видно = снимки["Enshrouded"]["текст"]
        print("  текст подвала: %s" % видно[:150])
    finally:
        c.execute("UPDATE enshrouded_sets SET img_ext = ? WHERE id = ?",
                  (было, ид))
        c.commit()
        c.close()
        print("  картинка возвращена сету %s" % ид)
    # ОБРАТНАЯ ПОЛОВИНА: без повода строки быть НЕ ДОЛЖНО. Проба, которая
    # печатает её всегда, прошла бы первую половину и не значила бы ничего.
    снимки = _снять(1920, разделы=[("Enshrouded", "/admin/enshrouded")])
    _, нашли_б, _ = _предостережения(снимки, условные=True)
    print("  повода НЕТ:  условных на экране %d (ожидается 0)" % нашли_б)
    return 0 if (нашли == ждём and нашли_б == 0) else 1



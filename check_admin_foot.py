def _снять(ширина, подлог=None, разделы=None):
    """Снимок подвала по КАЖДОМУ разделу за один подъём браузера."""
    from playwright.sync_api import sync_playwright
    разделы = разделы or РАЗДЕЛЫ
    итог = {}
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=False)
        кон = бр.new_context(viewport={"width": ширина, "height": 900},
                             has_touch=(ширина < 640), is_mobile=False,
                             device_scale_factor=1)
        стр = кон.new_page()
        ch._войти(стр)
        if подлог:
            стр.add_init_script(подлог)
        for имя, путь in разделы:
            стр.goto(БАЗА + путь, wait_until="load", timeout=45000)
            # Подпись рисует скрипт страницы: без ожидания меряется
            # пустой узел, и «строк 1» вышло бы у любого раздела.
            стр.wait_for_timeout(900)
            итог[имя] = стр.evaluate(ЗАМЕР)
        бр.close()
    return итог


def _печать(ширина, имя_раздела, о):
    print("\n" + "-" * 74)
    print("%s  —  ширина %d" % (имя_раздела.upper(), ширина))
    print("-" * 74)
    if не_подвал := (not о.get("подвал")):
        print("  общего подвала `.admin-foot` НЕТ — куски лежат врозь")
    else:
        п = о["подвал"]
        print("  подвал h=%.1f  фон=%s  рамка=%s  радиус=%s"
              % (п["h"], о["фон"], о["рамка"], о["радиус"]))
    for имя, ключ, ткл in (("подсказка", "нота", "нота_строк"),
                           ("расход", "реф", "реф_строк")):
        к, с = о.get(ключ), о.get(ткл)
        if not к:
            print("  %-10s блока НЕТ" % имя)
            continue
        print("  %-10s h=%.1f  строк ВИДНО: %s  (текст %.1f / межстрочный %.1f)"
              % (имя, к["h"], с["строк"], с["высота_текста"], с["межстрочный"]))
    if о.get("полоска"):
        л = о["полоска"]
        print("  полоска расхода: доля %.3f (%.1f из %.1f), цвет %s"
              % (л["доля"], л["ширина"], л["коробка"], л["цвет"]))
    else:
        print("  полоски расхода НЕТ")
    if о.get("тон"):
        print("  класс расхода: %s" % о["тон"])
    if о.get("моно"):
        print("  моноширинные числа: %s" % ", ".join(о["моно"]))
    if не_подвал and о.get("нота") and о.get("реф"):
        print("  ОБЩАЯ ВЫСОТА ДВУХ КУСКОВ: %.1f px"
              % (о["реф"]["y"] + о["реф"]["h"] - о["нота"]["y"]))
    return о


def _предостережения(снимки, условные=False):
    """Сколько предостережений ЖДЁМ и сколько НАШЛОСЬ в видимом тексте.

    Считается по `innerText`, то есть по нарисованному: кусок, спрятанный
    в подсказку по наведению, находкой НЕ будет, и это намеренно —
    предостережение обязано быть на виду.
    """
    import re
    ждём = нашли = 0
    потери = []
    for раздел, ключ, ядро, усл, что in ПРЕДОСТЕРЕЖЕНИЯ:
        if усл != условные:
            continue
        текст = (снимки.get(раздел) or {}).get("текст") or ""
        ждём += 1
        if re.search(ядро, текст, re.I):
            нашли += 1
        else:
            потери.append((раздел, ключ, что))
    return ждём, нашли, потери



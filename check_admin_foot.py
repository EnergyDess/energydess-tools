def _снять(ширина, подлог=None, разделы=None):
    """Снимок подвала по КАЖДОМУ разделу за один подъём браузера."""
    from playwright.sync_api import sync_playwright
    разделы = разделы or РАЗДЕЛЫ
    итог = {}
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=False)
        кон = бр.new_context(viewport={"width": ширина, "height": 900},
                             has_touch=(ширина < 640), is_mobile=False,
                             device_scale_factor=1)
        стр = кон.new_page()
        ch._войти(стр)
        if подлог:
            стр.add_init_script(подлог)
        for имя, путь in разделы:
            стр.goto(БАЗА + путь, wait_until="load", timeout=45000)
            # Подпись рисует скрипт страницы: без ожидания меряется
            # пустой узел, и «строк 1» вышло бы у любого раздела.
            стр.wait_for_timeout(900)
            итог[имя] = стр.evaluate(ЗАМЕР)
        бр.close()
    return итог



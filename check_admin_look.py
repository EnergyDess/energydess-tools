def _снять(ширина, высота, сенсор, лишних=0, подлог=None):
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        бр = p.chromium.launch()
        кон = бр.new_context(viewport={"width": ширина, "height": высота},
                             has_touch=сенсор, is_mobile=False,
                             device_scale_factor=1)
        стр = кон.new_page()
        ch._войти(стр)
        if лишних:
            стр.add_init_script(ЛИШНИЕ % лишних)
        if подлог:
            стр.add_init_script(подлог)
        стр.goto(f"{БАЗА}/admin/users", wait_until="load", timeout=45000)
        стр.wait_for_timeout(500)
        о = стр.evaluate(ЗАМЕР)
        бр.close()
    return о


def _проверить(о):
    """Ожидания против замера. Возвращает список нарушений строками."""
    плохо = []
    if not о.get("бар"):
        return ["панели `.admin-nav-bar` в дереве НЕТ"]
    доля = о["бар"]["w"] / о["экран"]
    if доля < ОЖИДАНИЯ["доля_экрана"] - 0.001:
        плохо.append("полоса занимает %.1f%% ширины страницы, а не всю"
                     % (доля * 100))
    if о.get("шапка") and abs(о["бар"]["w"] - о["шапка"]) > 1:
        плохо.append("полоса уже шапки сайта: %.1f против %.1f"
                     % (о["бар"]["w"], о["шапка"]))
    фон = (о.get("фон_бара") or "").replace(" ", "")
    if "rgba(0,0,0,0)" in фон or фон == "transparent":
        плохо.append("у полосы НЕТ подложки: %s" % о.get("фон_бара"))
    elif фон == (о.get("фон_страницы") or "").replace(" ", ""):
        плохо.append("подложка полосы равна фону страницы: %s" % фон)
    if о.get("липкость") != "sticky":
        плохо.append("полоса не липкая: position=%s" % о.get("липкость"))
    if о["экран"] >= 900:
        if (о["вкладка"] or {}).get("h", 0) < ОЖИДАНИЯ["высота_вкладки_мин"]:
            плохо.append("вкладка ниже порога: %.1f < %.1f"
                         % (о["вкладка"]["h"], ОЖИДАНИЯ["высота_вкладки_мин"]))
        if (о.get("кегль") or 0) < ОЖИДАНИЯ["кегль_вкладки_мин"]:
            плохо.append("кегль вкладки ниже порога: %.2f < %.1f"
                         % (о.get("кегль") or 0,
                            ОЖИДАНИЯ["кегль_вкладки_мин"]))
    # Выравнивание: левый край первой вкладки против левого края заголовка
    # страницы — то есть против того, чем ряд управляет.
    if о.get("заголовок") and о.get("вкладка"):
        разбег = abs(о["вкладка"]["x"] - о["заголовок"]["x"])
        if разбег > ОЖИДАНИЯ["разбег_с_контентом"]:
            плохо.append("вкладки не выровнены с содержимым: %.1f px"
                         % разбег)
    if о.get("рядов", 1) > 1:
        плохо.append("ряд СЛОМАЛСЯ переносом: строк %d" % о["рядов"])
    return плохо


def печать(о, заголовок):
    print("\n" + "=" * 68)
    print(заголовок)
    print("=" * 68)
    б, в, з = о.get("бар"), о.get("вкладка"), о.get("заголовок")
    print("  страница / окно       %d / %d" % (о["экран"], о["окно"]))
    if б:
        print("  полоса                x=%.1f w=%.1f h=%.1f — %.1f%% "
              "страницы, шапка сайта %.1f"
              % (б["x"], б["w"], б["h"], б["w"] / о["экран"] * 100,
                 о.get("шапка") or -1))
        print("  подложка / фон стр.   %s / %s"
              % (о.get("фон_бара"), о.get("фон_страницы")))
        print("  липкость              %s" % о.get("липкость"))
    if в:
        print("  вкладка               w=%.1f h=%.1f кегль=%.2f значок=%s"
              % (в["w"], в["h"], о.get("кегль") or 0, о.get("значок")))
        print("  левый край: вкладка %.1f, заголовок %.1f"
              % (в["x"], з["x"] if з else -1))
    print("  вкладок               %d, строк ряда %d"
          % (о.get("вкладок", 0), о.get("рядов", 0)))
    print("  ряд: содержимое %s, видно %s%s"
          % (о.get("ряд_содержимое"), о.get("ряд_видно"),
             " — ПРОКРУЧИВАЕТСЯ" if (о.get("ряд_содержимое") or 0)
             > (о.get("ряд_видно") or 0) else ""))
    if о.get("чип_высота"):
        print("  чип отбора, высота    %.1f" % о["чип_высота"])
    плохо = _проверить(о)
    for п in плохо:
        print("  !! " + п)
    if not плохо:
        print("  все ожидания выполнены")
    return len(плохо)



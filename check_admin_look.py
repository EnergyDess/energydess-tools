def доказать_подлог(выражение, подлог):
    """Свойство панели БЕЗ подлога и С ним. Замер СОСТОЯНИЯ, а не факта
    установки скрипта: «скрипт положен» и «эффект наступил» — разные
    утверждения, и расходятся они молча (§6.0.3)."""
    from playwright.sync_api import sync_playwright

    ответы = []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for текст in (None, подлог):
            кон = бр.new_context(viewport={"width": 2560, "height": 1400},
                                 device_scale_factor=1)
            стр = кон.new_page()
            ch._войти(стр)
            if текст:
                стр.add_init_script(текст)
            стр.goto(f"{БАЗА}/admin/users", wait_until="load", timeout=45000)
            стр.wait_for_timeout(600)
            ответы.append(стр.evaluate(выражение))
            кон.close()
        бр.close()
    return ответы[0], ответы[1]


def main():
    арг = sys.argv[1:]
    ширины = [(2560, 1400, False), (1920, 1200, False), (390, 844, True)]
    if "--ширина" in арг:
        ш = int(арг[арг.index("--ширина") + 1])
        ширины = [(ш, 1400, False)] if ш >= 900 else [(ш, 844, True)]
    лишних = 0
    if "--разделов" in арг:
        всего = int(арг[арг.index("--разделов") + 1])
        лишних = max(0, всего - 4)

    if "--контроль" in арг:
        print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: %d подлогов, каждый обязан быть "
              "назван" % len(ПОДЛОГИ))
        чисто = _снять(2560, 1400, False)
        д0 = печать(чисто, "БЕЗ ПОДЛОГА")
        if д0:
            print(chr(10) + "  КОНТРОЛЬ НЕДЕЙСТВИТЕЛЕН: на чистом прогоне "
                  "уже %d нарушений — подлог не отличить от своего "
                  "дефекта." % д0)
            return 2
        не_нашли, несостоявшихся = [], []
        for имя, текст in ПОДЛОГИ.items():
            # ШАГ ПЕРВЫЙ — ДОКАЗАТЬ, ЧТО ПОДЛОГ СОСТОЯЛСЯ (§6.0.3)
            выражение, что = ДОКАЗАТЕЛЬСТВА[имя]
            д_ч, д_п = доказать_подлог(выражение, текст)
            if д_ч == д_п:
                несостоявшихся.append(имя)
                print(chr(10) + "  ДОКАЗАТЕЛЬСТВО (%s): чисто=%r "
                      "с подлогом=%r → ПОДЛОГ НЕ СОСТОЯЛСЯ, пропущен"
                      % (что, д_ч, д_п))
                continue
            print(chr(10) + "  ДОКАЗАТЕЛЬСТВО (%s): чисто=%r с подлогом=%r "
                  "→ ПОДЛОГ СОСТОЯЛСЯ" % (что, д_ч, д_п))
            о = _снять(2560, 1400, False, подлог=текст)
            н = печать(о, "ПОДЛОГ: %s" % имя)
            if not н:
                не_нашли.append(имя)
        print(chr(10) + "  не найдено подлогов: %d из %d; не состоялось: %d"
              % (len(не_нашли), len(ПОДЛОГИ), len(несостоявшихся)))
        if не_нашли or несостоявшихся:
            if не_нашли:
                print("  КОНТРОЛЬ ПРОВАЛЕН — проба не видит: %s"
                      % ", ".join(не_нашли))
            if несостоявшихся:
                print("  КОНТРОЛЬ ПРОВАЛЕН — подлог не состоялся: %s"
                      % ", ".join(несостоявшихся))
            return 2
        print("  КОНТРОЛЬ ПРОЙДЕН")
        return 0

    всего_плохо = 0
    for ш, в, с in ширины:
        о = _снять(ш, в, с, лишних=лишних)
        всего_плохо += печать(
            о, "ШИРИНА %d%s%s" % (ш, " (сенсор)" if с else "",
                                  ", разделов %d" % (4 + лишних)
                                  if лишних else ""))
    print(chr(10) + "ИТОГО НАРУШЕНИЙ: %d" % всего_плохо)
    return 1 if всего_плохо else 0



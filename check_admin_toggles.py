def _пиксель(картинка, x, y):
    return картинка.getpixel((int(round(x * МАСШТАБ)), int(round(y * МАСШТАБ))))[:3]


def _rgb(строка):
    """'rgb(1, 2, 3)' / 'rgba(1, 2, 3, 0.5)' / 'color(srgb r g b / a)'
    → (R, G, B, альфа). Третью форму отдаёт `color-mix` — каналы в долях."""
    тело = строка[строка.index("(") + 1:строка.rindex(")")]
    доли = тело.startswith("srgb")
    if доли:
        тело = тело[len("srgb"):]
    ч = [float(x) for x in тело.replace("/", " ").replace(",", " ").split() if x]
    if доли:
        ч = [ч[0] * 255, ч[1] * 255, ч[2] * 255] + ч[3:]
    return (ч[0], ч[1], ч[2], ч[3] if len(ч) > 3 else 1.0)


def замер(база, подлог_css=""):
    """{'тумблеры': {вкл/выкл: точки}, 'строки': [...]}; снимки — числами."""
    from PIL import Image
    from auth import create_token
    from playwright.sync_api import sync_playwright
    c = sqlite3.connect(база)
    uid = c.execute("SELECT id FROM users WHERE email = ?", (ПОЧТА,)).fetchone()
    c.close()
    if not uid:
        raise ConnectionError("на копии стенда нет аккаунта %s — посейте стенд" % ПОЧТА)
    п, адрес = _стенд(база)
    итог = {"тумблеры": {}, "строки": []}
    try:
        with sync_playwright() as pw:
            бр = pw.chromium.launch(headless=True)
            к = бр.new_context(viewport={"width": 1600, "height": 1000},
                               device_scale_factor=МАСШТАБ)
            к.add_cookies([{"name": "access_token", "value": create_token(uid[0]),
                            "url": адрес}])
            с = к.new_page()
            с.goto(адрес + "/admin/users", wait_until="load", timeout=45000)
            if подлог_css:
                с.add_style_tag(content=подлог_css)
            # Указатель — за окно: подсветка строки `tr:hover` перекрасила
            # бы фон ячейки (§6.0.3, «физический указатель»).
            с.mouse.move(0, 0)
            с.evaluate("() => document.fonts.ready")
            с.wait_for_timeout(400)
            точки = с.evaluate(ТОЧКИ, "#rows tr:not([hidden]) .v2-toggle")
            for т in точки:
                if ("вкл" if т["вкл"] else "выкл") in итог["тумблеры"]:
                    continue
                клип = {"x": т["тд_x"], "y": т["тд_y"], "width": т["тд_w"],
                        "height": т["тд_h"]}
                снимок = Image.open(io.BytesIO(с.screenshot(clip=клип))).convert("RGB")
                x0, y0 = т["x"], т["y"]
                сер = y0 + т["h"] / 2
                ручка_л, ручка_п = (x0 + 10, сер), (x0 + 28, сер)
                итог["тумблеры"]["вкл" if т["вкл"] else "выкл"] = {
                    "фон": _пиксель(снимок, x0 - 6, сер),
                    # Заливка — там, где бегунка НЕТ: у включённого слева,
                    # у выключенного справа.
                    "заливка": _пиксель(снимок, *(ручка_л if т["вкл"] else ручка_п)),
                    "ручка": _пиксель(снимок, *(ручка_п if т["вкл"] else ручка_л)),
                    "рамка": _пиксель(снимок, x0 + т["w"] / 2, y0 + 0.25),
                    "заливка_css": _rgb(т["заливка"]),
                }
            for р in с.evaluate(СТРОКИ):
                клип = {"x": р["x"], "y": р["y"], "width": р["w"], "height": р["h"]}
                снимок = Image.open(io.BytesIO(с.screenshot(clip=клип))).convert("RGB")
                итог["строки"].append({
                    "доступ": р["доступ"] == "yes",
                    "полоска": _пиксель(снимок, 1, р["h"] / 2),
                    "фон": _пиксель(снимок, р["w"] - 4, р["h"] - 3),
                    "почта": _rgb(р["цвет"])[:3],
                })
            бр.close()
    finally:
        п.kill()
    return итог


def оценить(з):
    т = з["тумблеры"]
    есть = int("вкл" in т and "выкл" in т)
    вкл, выкл = т.get("вкл"), т.get("выкл")
    if not есть:
        шаг("тумблеры на экране", False,
            "ЗАМЕР НЕ СОСТОЯЛСЯ: нужны включённый и выключенный, найдено %s"
            % sorted(т), собрано=0)
        return
    к_залит = контраст(вкл["заливка"], вкл["фон"])
    к_против = контраст(вкл["заливка"], выкл["заливка"])
    к_выкл_заливка = контраст(выкл["заливка"], выкл["фон"])
    к_выкл_рамка = контраст(выкл["рамка"], выкл["фон"])
    шаг("вкл/залит", к_залит >= ПОРОГ,
        "заливка %s к фону %s — %.2f (порог %.1f)" % (вкл["заливка"], вкл["фон"],
                                                     к_залит, ПОРОГ), собрано=есть)
    шаг("вкл/против выкл", к_против >= ПОРОГ,
        "заливка вкл %s к заливке выкл %s — %.2f: различимы светлотой, а не "
        "только оттенком" % (вкл["заливка"], выкл["заливка"], к_против), собрано=есть)
    шаг("выкл/контур", к_выкл_заливка <= НЕТ and к_выкл_рамка >= ПОРОГ,
        "заливка к фону %.2f (≤ %.1f — заливки нет), рамка %s к фону %.2f"
        % (к_выкл_заливка, НЕТ, выкл["рамка"], к_выкл_рамка), собрано=есть)
    к_ручка_вкл = контраст(вкл["ручка"], вкл["заливка"])
    к_ручка_выкл = контраст(выкл["ручка"], выкл["фон"])
    шаг("бегунок/справа у вкл", к_ручка_вкл >= ПОРОГ,
        "справа %s к заливке — %.2f" % (вкл["ручка"], к_ручка_вкл), собрано=есть)
    шаг("бегунок/слева у выкл", к_ручка_выкл >= ПОРОГ,
        "слева %s к фону — %.2f" % (выкл["ручка"], к_ручка_выкл), собрано=есть)

    с = [р for р in з["строки"] if р["доступ"]]
    без = [р for р in з["строки"] if not р["доступ"]]
    обе = int(bool(с) and bool(без))
    if not обе:
        шаг("строки/полоска", False, "ЗАМЕР НЕ СОСТОЯЛСЯ: строк с доступом %d, без %d"
            % (len(с), len(без)), собрано=0)
        return
    мин_с = min(контраст(р["полоска"], р["фон"]) for р in с)
    макс_без = max(контраст(р["полоска"], р["фон"]) for р in без)
    шаг("строки/полоска", мин_с >= ПОРОГ and макс_без <= НЕТ,
        "с доступом (%d) полоска к фону ≥ %.2f, без доступа (%d) ≤ %.2f"
        % (len(с), мин_с, len(без), макс_без), собрано=обе)
    яркость_с = min(светлота(р["почта"]) for р in с)
    яркость_без = max(светлота(р["почта"]) for р in без)
    шаг("строки/почта ярче", яркость_с > яркость_без,
        "светлота почты с доступом ≥ %.3f, без доступа ≤ %.3f" % (яркость_с, яркость_без),
        собрано=обе)
    return {"залит": к_залит, "против": к_против, "выкл_рамка": к_выкл_рамка}


def доказать_подлог(з):
    """Независимо от вердикта: заливка включённой дорожки полупрозрачна."""
    вкл = з["тумблеры"].get("вкл")
    return bool(вкл) and вкл["заливка_css"][3] < 1.0


def main_():
    база, каталог = _копия()
    try:
        if "--контроль" in sys.argv:
            print("ПОДЛОГ №2: прежний вид включённого (заливка --v2-tool-dim)")
            з = замер(база, ПОДЛОГ_ПРЕЖНИЙ)
            оценить(з)
            док = доказать_подлог(з)
            упал = any(и in ("вкл/залит", "вкл/против выкл") and исход == "ПЛОХО"
                       for и, исход, _ in шаги)
            print("  доказательство: заливка вкл полупрозрачна (альфа %.2f) → %s; "
                  "шаг упал: %s" % (з["тумблеры"].get("вкл", {}).get("заливка_css", (0, 0, 0, 0))[3],
                                    док, упал))
            print("КОНТРОЛЬ: %s" % ("ловит" if док and упал else "НЕ ловит"))
            return 0 if док and упал else 1
        з = замер(база)
        оценить(з)
        плохо = [ш for ш in шаги if ш[1] == "ПЛОХО"]
        пропуск = [ш for ш in шаги if ш[1] == "ПРОПУСК"]
        print("ИТОГ: шагов %d, плохих %d, пропусков %d" % (len(шаги), len(плохо), len(пропуск)))
        if плохо:
            return 1
        return 2 if пропуск else 0
    finally:
        shutil.rmtree(каталог, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main_())

def _лин(к):
    к /= 255.0
    return к / 12.92 if к <= 0.04045 else ((к + 0.055) / 1.055) ** 2.4


def светлота(rgb):
    r, g, b = rgb[:3]
    return 0.2126 * _лин(r) + 0.7152 * _лин(g) + 0.0722 * _лин(b)


def контраст(а, б):
    x, y = светлота(а), светлота(б)
    if x < y:
        x, y = y, x
    return (x + 0.05) / (y + 0.05)



# -*- coding: utf-8 -*-
"""Проверка 9: задача со статусом «не начата», в которую ведут коммиты с кодом.

Зачем. Восемь проверок ходят по коду и по документации дизайн-системы.
Ни одна не смотрит на BACKLOG.md, а он врёт иначе, чем design-system.md:
там устаревает не имя класса, а **утверждение о состоянии работы**.
Проверка 7 такое не берёт по построению — она сверяет имена и значения
с кодом, а «не начата» никакого представления в коде не имеет.

Сводка 2026-08-11 нашла девять таких расхождений из сорока семи задач,
и ни одно не было опечаткой: код писали, коммит называл номер задачи,
шапку в BACKLOG не поправляли. Дальше сводка бэклога читается как
достоверная, потому что так написано в отчёте, — ровно тот же класс
отказа, что «|| true» в §6.0.1.

КАК УСТРОЕНО. Для каждой задачи со статусом «не начата» ищем коммиты,
называющие её номер, и делим их на две кучи:

  работа    — коммит менял не только *.md
  заведение — коммит менял только *.md («docs(backlog): задача 19 — …»)

Первая куча при статусе «не начата» и есть расхождение.

ДВА СУЖЕНИЯ, БЕЗ КОТОРЫХ ПРОВЕРКА ВРЁТ

1. **Номер ищется только в ТЕМЕ коммита, не в теле.** Перекрёстные ссылки
   живут в теле («см. BACKLOG №24», «причина — задача 19»), работа
   называет задачу в теме («— BACKLOG №13»). Без сужения проверка давала
   6 находок на 3 настоящих: 50% лжи, а это порог, за которым проверку
   перестают читать (тот же довод, что про `_admin_nav.html` в проверке 4).
   С сужением — 3 из 3.

2. **Трогаются только статусы, начинающиеся с «не начата».** «ЧАСТИЧНО»,
   «отложена», «ВЫПОЛНЕНА», «ЗАКРЫТА» — сознательно выбранные состояния,
   и коммиты в них ведут законно.

ГРАНИЦА — что проверка НЕ видит:
  * работа без упоминания номера в теме коммита. Это пропуск, а не ложь:
    все проверки проекта — whitelist'ы с названными слепыми пятнами;
  * задача, у которой устарел не статус, а **содержание**: перечислены
    файлы, которых нет, или план, который разошёлся с решением. Формы
    в коде у этого нет, автоматизировать нечем — §6.2, пункт про сводку;
  * «ЧАСТИЧНО», под которым на самом деле сделано всё;
  * статус, отставший в другую сторону: «ВЫПОЛНЕНА» там, где откатили.

Код возврата: 0 — расхождений нет, 1 — есть, 2 — сломан разбор.

Запуск:  py check_backlog.py    (ИМЕННО py: python на машине Дениса —
                                 заглушка Store, код 9009 без запуска)
"""
import re
import sys
import pathlib
import subprocess
import collections

import backlog_open as открытые    # BACKLOG №123: разбор один на проект

КОРЕНЬ = pathlib.Path(__file__).parent

# «BACKLOG №13», «BACKLOG.md, задача 8», «задачи 46, 47, 33», «№28»
ССЫЛКА = re.compile(
    r"(?:BACKLOG[ .]*(?:md)?[,]?\s*(?:№|#)?\s*|задач[аиуе]?м?и?\s+|№\s*)(\d+[a-z]?)"
    r"((?:\s*,\s*\d+[a-z]?)*)", re.I)


def git(*аргументы):
    готово = subprocess.run(["git", "-C", str(КОРЕНЬ), *аргументы],
                            capture_output=True, text=True, encoding="utf-8")
    if готово.returncode != 0:
        print("ОСТАНОВЛЕНО: git вернул", готово.returncode)
        print(готово.stderr.strip()[:400])
        sys.exit(2)
    return готово.stdout


def статусы_задач():
    """номер -> (статус, имя). РАЗБОР ОДИН НА ПРОЕКТ — BACKLOG №123.

    Здесь стояла ВТОРАЯ реализация разбора `BACKLOG.md`, и она отличалась
    от первой не стилем, а результатом: статус читался ОДНОЙ строкой,
    то есть у задачи с многострочным статусом (`## 27` — две строки)
    обрезался на полуслове. Тот же класс, что копии `names` и `pages`
    в §6.0.2: две копии расходятся молча, и по выводу этого не видно.

    Теперь и разбор, и правило «что считать закрытым» живут в одном
    месте — `backlog_open.py`. Здесь остаётся только своя ФОРМА ответа:
    этой проверке нужен словарь номер → статус, а не список.
    """
    return {номер: (статус if статус is not None else "—", имя)
            for номер, имя, статус, _остаток, _строка in открытые.задачи()}


def коммиты_по_задачам():
    """номер задачи -> [(хеш, тема, только_документация, файлы)].

    Разделители %x1e/%x1f, а не NUL: CreateProcess на Windows не принимает
    NUL в аргументах. Разделитель нужен потому, что тело коммита
    многострочное и по '\\n' его от списка файлов не отделить.
    """
    сырой = git("log", "--pretty=format:%x1e%h%x1f%s%x1f", "--name-only", "--all")
    итог = collections.defaultdict(list)
    for кусок in сырой.split("\x1e"):
        if not кусок.strip():
            continue
        поля = кусок.split("\x1f")
        if len(поля) < 3:
            continue
        хеш, тема, хвост = поля[0], поля[1], поля[2]
        файлы = [f.strip() for f in хвост.split("\n") if f.strip()]
        только_док = bool(файлы) and all(f.endswith(".md") for f in файлы)
        номера = set()
        # ИМЕННО тема: перекрёстная ссылка в теле — не работа по задаче
        for m in ССЫЛКА.finditer(тема):
            номера.add(m.group(1))
            номера.update(re.findall(r"\d+[a-z]?", m.group(2) or ""))
        for н in номера:
            итог[н].append((хеш, тема, только_док, файлы))
    return итог


def main():
    статусы = статусы_задач()
    коммиты = коммиты_по_задачам()

    не_начатых = [н for н, (ст, _) in статусы.items()
                  if ст.lower().startswith("не начата")]
    расхождения = []
    for н in не_начатых:
        рабочие = [c for c in коммиты.get(н, []) if not c[2]]
        if рабочие:
            расхождения.append((н, статусы[н][1], рабочие))

    print("Проверка 9 — статус задачи против истории коммитов\n")
    print(f"  задач в BACKLOG.md:            {len(статусы)}")
    print(f"  со статусом «не начата»:       {len(не_начатых)}")
    print(f"  из них с коммитами по коду:    {len(расхождения)}\n")

    if not расхождения:
        print("Расхождений нет.")
        return 0

    print("--- РАСХОЖДЕНИЕ: статус «не начата», а коммиты с кодом есть ---")
    for н, имя, рабочие in расхождения:
        print(f"  задача {н}. {имя[:60]}")
        for хеш, тема, _, файлы in рабочие:
            print(f"      {хеш} {тема[:70]}")
            print(f"          {', '.join(файлы[:6])}"
                  f"{' …' if len(файлы) > 6 else ''}")
    print("\nЧто делать: открыть код по этим коммитам и поправить статус —\n"
          "либо, если работа была отменена, сказать это в самой задаче.\n"
          "Разбор — CLAUDE.md §6.0.2, «Проверка 9».")
    return 1


if __name__ == "__main__":
    sys.exit(main())

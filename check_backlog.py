# ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ — BACKLOG №222, F.1.
#
# До 2026-09-01 его не было ВОВСЕ, и ключ `--контроль` проверка молча
# игнорировала: прогон с ним печатал обычное «Расхождений нет» и код 0.
# Это хуже, чем у соседей по ряду: весь способ работы держится на том,
# что бэклог печатается командой и ей верят больше, чем письму, —
# а слепая проверка тихо разрешала бы задачам исчезать.
#
# ПОДЛОГ КЛАДЁТСЯ В ИСТОЧНИКИ, А НЕ В ВЫВОД. Настоящих коммитов
# завести нельзя (историю этот заход не трогает — решение владельца),
# поэтому подставляются РАЗОБРАННЫЕ источники: словарь статусов
# и словарь коммитов. Тот же приём, что у контроля проверки 13,
# и по той же причине: рабочие документы не трогаются вовсе.
#
# ПОДЛОГОВ ТРИ, И ТРЕТИЙ ОБЯЗАТЕЛЕН.
#   1. «не начата» + коммит С КОДОМ            — обязана НАЙТИ
#   2. «не начата» + коммит ТОЛЬКО С .md       — обязана ПРОПУСТИТЬ
#      (заведение задачи — не работа по ней)
#   3. «выполнена» + коммит с кодом            — обязана ПРОПУСТИТЬ
# Без второго и третьего контроль доказывал бы, что проверка видит
# хоть что-то, а не что она РАЗЛИЧАЕТ. Проверка, объявляющая
# расхождением всякий коммит, перестала бы читаться на третий раз.
#
# ДОКАЗАТЕЛЬСТВО ПОДЛОГА отдельно от вердикта (§6.0.3): подставленный
# номер обязан ПРИСУТСТВОВАТЬ в разобранных статусах. Не присутствует —
# подлог не состоялся, и вердикт про него не значит ничего.
НОМЕР_ПОДЛОГА = "99901"


def _расхождения(статусы, коммиты):
    """Тот же отбор, что в main — второй реализации тут быть не должно."""
    не_начатых = [н for н, (ст, _) in статусы.items()
                  if ст.lower().startswith("не начата")]
    из_ = []
    for н in не_начатых:
        рабочие = [c for c in коммиты.get(н, []) if not c[2]]
        if рабочие:
            из_.append(н)
    return из_


def контроль():
    статусы = статусы_задач()
    коммиты = коммиты_по_задачам()
    было = _расхождения(статусы, коммиты)
    случаи = [
        ("«не начата» + коммит С КОДОМ", "НЕ НАЧАТА",
         [("deadbeef", "feat(99901): подлог", False, ["main.py"])], True),
        ("«не начата» + коммит ТОЛЬКО с .md", "НЕ НАЧАТА",
         [("deadbee1", "feat(99901): подлог", True, ["BACKLOG.md"])], False),
        ("«ВЫПОЛНЕНА» + коммит с кодом", "ВЫПОЛНЕНА 2026-09-01",
         [("deadbee2", "feat(99901): подлог", False, ["main.py"])], False),
    ]
    print("КОНТРОЛЬ ПРОВЕРКИ 9 — три подлога, у каждого ДОКАЗАТЕЛЬСТВО\n")
    print("  %-40s %8s %8s %10s %s"
          % ("подлог", "было", "стало", "подставлен", "итог"))
    ок = True
    for имя, статус, ком, ждём_находку in случаи:
        с2 = dict(статусы)
        с2[НОМЕР_ПОДЛОГА] = (статус, "подложенная задача")
        к2 = dict(коммиты)
        к2[НОМЕР_ПОДЛОГА] = ком
        стало = _расхождения(с2, к2)
        подставлен = НОМЕР_ПОДЛОГА in с2
        нашла = НОМЕР_ПОДЛОГА in стало
        сошлось = (нашла == ждём_находку) and len(стало) == len(было) + (
            1 if ждём_находку else 0)
        ок = ок and подставлен and сошлось
        print("  %-40s %8d %8d %10s %s"
              % (имя, len(было), len(стало), "да" if подставлен else "НЕТ",
                 "ПРОЙДЕН" if (подставлен and сошлось) else "НЕ ПРОЙДЕН"))
    print()
    if ок:
        print("КОНТРОЛЬ ПРОЙДЕН: проверка находит работу под статусом")
        print("«не начата» и НЕ считает работой ни заведение задачи,")
        print("ни коммиты по уже закрытой.")
        return 0
    print("КОНТРОЛЬ НЕ ПРОЙДЕН: ноль этой проверки ничего не значит.")
    return 1


def main():
    статусы = статусы_задач()
    коммиты = коммиты_по_задачам()

    не_начатых = [н for н, (ст, _) in статусы.items()
                  if ст.lower().startswith("не начата")]
    расхождения = []
    for н in не_начатых:
        рабочие = [c for c in коммиты.get(н, []) if not c[2]]
        if рабочие:
            расхождения.append((н, статусы[н][1], рабочие))

    print("Проверка 9 — статус задачи против истории коммитов\n")
    print(f"  задач в BACKLOG.md:            {len(статусы)}")
    print(f"  со статусом «не начата»:       {len(не_начатых)}")
    print(f"  из них с коммитами по коду:    {len(расхождения)}\n")

    if not расхождения:
        print("Расхождений нет.")
        return 0

    print("--- РАСХОЖДЕНИЕ: статус «не начата», а коммиты с кодом есть ---")
    for н, имя, рабочие in расхождения:
        print(f"  задача {н}. {имя[:60]}")
        for хеш, тема, _, файлы in рабочие:
            print(f"      {хеш} {тема[:70]}")
            print(f"          {', '.join(файлы[:6])}"
                  f"{' …' if len(файлы) > 6 else ''}")
    print("\nЧто делать: открыть код по этим коммитам и поправить статус —\n"
          "либо, если работа была отменена, сказать это в самой задаче.\n"
          "Разбор — CLAUDE.md §6.0.2, «Проверка 9».")
    return 1


if __name__ == "__main__":
    sys.exit(контроль() if "--контроль" in sys.argv else main())

# -*- coding: utf-8 -*-
"""ПРОВЕРКА 11: синхронный блокирующий вызов внутри async-обработчика.

Пока такой вызов считает, event loop не исполняет НИЧЕГО: ни другие
запросы, ни таймеры, ни отправку уже готовых ответов. Отказ немой —
ни ошибки, ни трейсбека, ни строки в журнале, приложение просто
перестаёт отвечать целиком, включая `/health`, по которому Fly решает,
жива ли машина.

═══════════════════════════════════════════════════════════════════════
ПОЧЕМУ ПРОВЕРКА, А НЕ «БУДЕМ ПОМНИТЬ»
═══════════════════════════════════════════════════════════════════════

Это ТРЕТИЙ случай одного класса подряд, и каждый раз он находился
замером после того, как код объявили рабочим:

  задача 22 (2026-08-18)  синхронная работа с базой под `async` —
                          тридцать одновременных входов, `/health`
                          не отвечает вовсе, в журнале ни строки;
  задача 103 (2026-08-18) bcrypt 151 мс в `POST /login` — десять
                          одновременных входов уводят медиану `/health`
                          с 1.13 мс на 967 мс;
  тем же заходом          синхронный httpx в `zepp_client` с timeout=30 —
                          молчащий сервис Zepp кладёт САЙТ ЦЕЛИКОМ
                          на полминуты. Это на два порядка хуже bcrypt,
                          и в постановке задачи 103 этого не было.

Последняя строка и есть довод. Задача называла bcrypt; обход графа
вызовов нашёл втрое больше мест, и худшее из них — не bcrypt. Правило,
которое надо не забыть соблюсти, — это гарантия, что следующий
обработчик его не получит (та же причина, по которой гейт подтверждения
почты сделан ОДНИМ middleware, `CLAUDE.md` §5.3).

═══════════════════════════════════════════════════════════════════════
КАК УСТРОЕНА
═══════════════════════════════════════════════════════════════════════

Не греп по одному имени: имя `verify_password` грепается, а
`zepp_client.login`, внутри которого синхронный httpx, — нет. Поэтому
строится граф вызовов по модулям проекта, и от каждого async-обработчика
идёт обход вглубь до известных блокирующих примитивов.

`asyncio.to_thread(функция, …)` разрывает ребро само собой: имя функции
там — аргумент, а не вызов, узла графа не возникает. То есть проверка
не знает про «правильное лечение» ничего лишнего — она видит ровно
то, что исполняется в цикле событий.

ГРАНИЦА — что проверка НЕ видит (называется, а не умалчивается):

  • вызов через переменную (`fn = verify_password; fn(...)`) — имени
    в узле нет;
  • блокирующее в стороннем пакете, которого нет в БЛОКИРУЮЩИЕ: список
    примитивов — whitelist, и незнакомый блокирующий вызов для неё
    невидим ровно так же, как имя не из `names` для проверки 1;
  • ДЛИТЕЛЬНОСТЬ. Проверка отвечает «в цикле или в потоке», а не
    «сколько миллисекунд». Стоимость меряется отдельно и записана
    в `main.py` рядом с `_пауза`;
  • работа с базой. Запрос к SQLite стоит 0.1 мс, `commit` под WAL —
    1.6 мс (замеры 2026-08-18 и 2026-08-20), и в поток это не уносится
    намеренно: иначе проверка печатала бы сотню находок, и её перестали
    бы читать на третий раз. Чем это НЕ является: дорогими были не сами
    запросы, а очередь за соединением в пуле (до 30 с) и `commit` при
    открытом чужом чтении под journal_mode=delete (5527 мс). Обоих больше
    нет — очередь выключена, журнал WAL (задача 105, `CLAUDE.md` §6.0.6),
    и лечится это настройкой движка, а не потоком.

Отрицательный контроль встроен и обязателен (`CLAUDE.md` §6.0.3):
`--контроль` подкладывает заведомо блокирующий обработчик и требует,
чтобы проверка его нашла. Не нашла — сломана проверка, а не код
исправен.

Запуск:

    py check_blocking.py              # код 1, если есть находка вне списка
    py check_blocking.py --контроль   # код 1, если НЕ нашло подложенное
    py check_blocking.py --все        # печатать и законные, с причинами
"""

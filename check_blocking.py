def main():
    # Подмена потока вывода — здесь, а не на импорте: файл импортируют
    # тесты, а подменённый на импорте sys.stdout ломает перехват вывода
    # в pytest (весь прогон падает с ValueError на закрытом файле)
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8",
                                  errors="replace")
    р = argparse.ArgumentParser(add_help=True)
    р.add_argument("--контроль", action="store_true",
                   help="подложить заведомо блокирующий обработчик; "
                        "код 1, если проверка его НЕ нашла")
    р.add_argument("--все", action="store_true",
                   help="печатать и законные исключения с причинами")
    args = р.parse_args()

    г = построить(ПОДЛОГ if args.контроль else None)
    строки = собрать(г)

    if args.контроль:
        нашли = [с for с in строки if с[0] == "контрольный_обработчик"]
        print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: подложен async-обработчик "
              "с прямым bcrypt.checkpw")
        if нашли:
            for имя, маршрут, кат, что, стр, цепь in нашли:
                print("  НАЙДЕНО: [%s] %s -> %s (строка %d)" % (кат, имя, что, стр))
            print("Проверка видит блокирующий вызов. Код 0.")
            return 0
        print("  НЕ НАЙДЕНО. Проверка СЛОМАНА — её вывод про настоящий код")
        print("  ничего не значит.")
        return 1

    долг, законные = [], []
    for с in строки:
        имя, _маршрут, кат, что, _стр, _цепь = с
        (законные if (имя, кат, что) in ИСКЛЮЧЕНИЯ else долг).append(с)

    print("=" * 74)
    print("ПРОВЕРКА 11: блокирующее в async-обработчике")
    print("=" * 74)
    print("обработчиков async: %d   модулей в графе: %d"
          % (len(г.обработчики), len(МОДУЛИ)))
    print()

    if законные and args.все:
        print("ЗАКОННЫЕ (с причиной):")
        for имя, _маршрут, кат, что, _стр, _цепь in законные:
            print("  [%s] %s — %s" % (кат, имя, что))
            print("        причина: %s" % ИСКЛЮЧЕНИЯ[(имя, кат, что)])
        print()

    if not долг:
        print("Находок нет: ни один async-обработчик не достаёт до")
        print("блокирующего примитива в обход потока.")
        print("законных исключений: %d (показать: --все)" % len(законные))
        return 0

    print("НАХОДКИ — %d:" % len(долг))
    for имя, маршрут, кат, что, стр, цепь in долг:
        print("  [%-10s] %-28s %s" % (кат, имя, маршрут[:36]))
        print("               %s (строка %d)" % (что, стр))
        print("               путь: %s" % цепь)
    print()
    print("по категориям:", dict(collections.Counter(с[2] for с in долг)))
    print()
    print("Лечится переносом в поток: await asyncio.to_thread(функция, …).")
    print("Разбор и стоимость каждого примитива — main.py, правило")
    print("«Блокирующее в async-обработчике» рядом с _пауза.")
    return 1


if __name__ == "__main__":
    sys.exit(main())

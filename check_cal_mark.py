def _разобрать(цвет):
    """Цвет из вычисленных стилей -> (r, g, b, alpha) в шкале 0..255.

    Форм ТРИ, и третью пришлось добавить по замеру: `color-mix()`
    разрешается браузером не в `rgb()`, а в `color(srgb 0.05 0.45 0.32)`
    с долями от единицы. Разбор, знавший две формы, падал на ней
    `ValueError` — то есть проверка ломалась ровно там, где в системе
    появился вычисляемый цвет."""
    цвет = цвет.strip()
    if цвет.startswith("color("):
        ч = цвет[цвет.index("(") + 1:цвет.rindex(")")].replace("/", " ").split()
        # первое слово — пространство (srgb); дальше доли 0..1
        числа = [float(x) for x in ч[1:]]
        a = числа[3] if len(числа) > 3 else 1.0
        return (числа[0] * 255, числа[1] * 255, числа[2] * 255, a)
    ч = цвет[цвет.index("(") + 1:цвет.index(")")].replace("/", ",").split(",")
    ч = [x.strip() for x in ч if x.strip()]
    a = float(ч[3]) if len(ч) > 3 else 1.0
    return (float(ч[0]), float(ч[1]), float(ч[2]), a)


def _поверх(перед, зад):
    """Композит полупрозрачного цвета на непрозрачном фоне."""
    r1, g1, b1, a = перед
    r2, g2, b2, _ = зад
    return (r1 * a + r2 * (1 - a), g1 * a + g2 * (1 - a), b1 * a + b2 * (1 - a), 1.0)


def _ярк(цвет):
    def к(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b, _ = цвет
    return 0.2126 * к(r) + 0.7152 * к(g) + 0.0722 * к(b)


def _подложка(слои):
    """Список слоёв фона снизу вверх -> один непрозрачный цвет.

    Складывается С КОНЦА: последний слой — непрозрачный, на него ложатся
    те, что ближе к элементу. Без этого «выбранный день» давал фоном
    `rgba(16,185,129,0.15)`, и контраст считался к краске в банке."""
    цвет = _разобрать(слои[-1])
    for слой in reversed(слои[:-1]):
        цвет = _поверх(_разобрать(слой), цвет)
    return цвет


def контраст(перед, слои_фона):
    """Контраст цвета к фону. И цвет, и фон приводятся к непрозрачным:
    число обязано описывать то, что видно, а не то, чем красили."""
    если_список = isinstance(слои_фона, (list, tuple))
    з = _подложка(слои_фона) if если_список else _разобрать(слои_фона)
    п = _разобрать(перед)
    if п[3] < 1.0:
        п = _поверх(п, з)
    a, b = _ярк(п), _ярк(з)
    if a < b:
        a, b = b, a
    return (a + 0.05) / (b + 0.05)



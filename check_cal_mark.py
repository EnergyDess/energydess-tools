def доказать_подлог(выражение, css="", js=""):
    """Состояние клетки БЕЗ подлога и С ним, на десктопной ширине.

    Замер СОСТОЯНИЯ, а не факта установки: «стиль добавлен» и «стиль
    применился» — разные утверждения, и расходятся они молча.
    """
    from playwright.sync_api import sync_playwright

    ответы = []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for с_подлогом in (False, True):
            к = бр.new_context(viewport={"width": 1440, "height": 900})
            стр = к.new_page()
            ch._войти(стр)
            стр.goto(ch.БАЗА + "/nutrition", wait_until="domcontentloaded",
                     timeout=45000)
            стр.wait_for_timeout(2200)
            if с_подлогом and css:
                стр.add_style_tag(content=css)
            стр.click("[data-tab='history']")
            стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 1400)
            if с_подлогом and js:
                стр.evaluate(js)
                стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА)
            ответы.append(стр.evaluate(выражение))
            к.close()
        бр.close()
    return ответы[0], ответы[1]


def снять(добавка_css="", добавка_js="", тихо=False):
    """Возвращает {ширина: данные}. Наведение — навязыванием через CDP."""
    from playwright.sync_api import sync_playwright
    итог = {}
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for ш, в, сенсор in ch.отобрать_ширины(ШИРИНЫ):
            к = бр.new_context(viewport={"width": ш, "height": в},
                               has_touch=сенсор, is_mobile=сенсор)
            стр = к.new_page()
            cdp = к.new_cdp_session(стр)
            if сенсор:
                ch._включить_сенсор(cdp)
            ch._войти(стр)
            if сенсор:
                ch._включить_сенсор(cdp)
            стр.goto(ch.БАЗА + "/nutrition", wait_until="domcontentloaded",
                     timeout=45000)
            стр.wait_for_timeout(2200)
            if добавка_css:
                стр.add_style_tag(content=добавка_css)
            стр.click("[data-tab='history']")
            стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 1400)
            if добавка_js:
                стр.evaluate(добавка_js)
            ch._сверить(стр, сенсор, f"{ш}: перед замером")
            д = стр.evaluate(ЗАМЕР)

            # НАВЕДЕНИЕ — только там, где оно бывает. На сенсорной ширине

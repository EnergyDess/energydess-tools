            д["состояния"]["наведение"] = None
            if not сенсор:
                cdp.send("DOM.enable")
                cdp.send("CSS.enable")
                # Помечаем ТУ ЖЕ клетку, которую выбирает `проба`
                нашлась = стр.evaluate(
                    "() => { for (const к of document.querySelectorAll("
                    "'.cal-c:not(.is-pad):not(.is-today):not(.is-sel)')) {"
                    "  const б = к.querySelector('.cal-bar');"
                    "  if (!б) continue;"
                    "  const т = getComputedStyle(б).boxShadow;"
                    "  if (t_пусто(т)) continue;"
                    "  к.setAttribute('data-навести', '1'); return true; }"
                    " return false;"
                    " function t_пусто(т) { return !т || т === 'none'; } }")
                if нашлась:
                    корень = cdp.send("DOM.getDocument")["root"]["nodeId"]
                    узел = cdp.send("DOM.querySelector", {
                        "nodeId": корень, "selector": "[data-навести]"})["nodeId"]

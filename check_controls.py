# -*- coding: utf-8 -*-
"""ДОКАЗАН ЛИ ПОДЛОГ — опись отрицательных контролей проекта.

═══════════════════════════════════════════════════════════════════════
ЗАЧЕМ
═══════════════════════════════════════════════════════════════════════

Отрицательный контроль отвечает на вопрос «а видит ли проба дефект».
Он ломает что-то нарочно и требует, чтобы проба это назвала. Но у него
есть СВОЙ немой отказ, и проект на него наступил.

Замер 2026-08-24, `check_medkit_ui.py`, подлог «молчаливое-удаление».
Он был записан как `window.АПТ.удаляем = id; window.аптУдалить()`,
а `АПТ` объявлен через `const` на верхнем уровне классического скрипта —
`const` свойства `window` НЕ СОЗДАЁТ вовсе. Подлог падал `TypeError`
на первой строке и не удалял НИЧЕГО: карточек было 21 и осталось 21.
Шаг «удаление-спрашивает» при этом честно проваливался — окно
подтверждения не открывалось, потому что не открывалось НИЧЕГО, —
и контроль печатал «НАЙДЕН».

То есть слепая проба и зрячая дали ОДИНАКОВОЕ число, и это число
приняли за доказательство.

═══════════════════════════════════════════════════════════════════════
ПРИЗНАК, И ОН МЕХАНИЧЕСКИЙ
═══════════════════════════════════════════════════════════════════════

Контроль считается ДОКАЗАННЫМ, если он объявляет ДОКАЗАТЕЛЬСТВО ПОДЛОГА
ИМЕНЕМ — модульным словарём `ДОКАЗАТЕЛЬСТВА` либо функцией
`доказать_подлог`. Доказательство — это независимый замер состояния
объекта ДО и ПОСЛЕ наложения подлога, показывающий, что подлог изменил
ровно то, что собирался.

Судить «по смыслу», читая тело контроля, здесь нельзя: ровно так
и родилась ошибка выше — тело выглядело исправным. Поэтому признак
не «в контроле есть что-то похожее на замер», а «контроль ОБЪЯВИЛ
замер именем, которое видно снаружи».

Разбор — СИНТАКСИЧЕСКИМ ДЕРЕВОМ, не грепом: слово «ДОКАЗАТЕЛЬСТВА»
в комментарии — это рассказ о доказательстве, а не доказательство
(§6.0.7, «комментарий — не код»).

═══════════════════════════════════════════════════════════════════════
МЕХАНИЗМ ПОДЛОГА — ВТОРАЯ КОЛОНКА, И ОНА ВАЖНЕЕ ПЕРВОЙ
═══════════════════════════════════════════════════════════════════════

Не всякий подлог умеет провалиться молча, и требовать доказательства
одинаково со всех значило бы завести работу там, где риска нет.

| механизм | может ли провалиться молча |
|---|---|
| `add_init_script` / `add_style_tag` — В СТРАНИЦУ | **ДА**: исключение внутри страницы наружу не выходит |
| запись файла на диск | нет: неудачная запись бросает исключение в самом контроле |
| строка в базе | нет: то же самое |
| подмена имени в памяти процесса | нет: имени нет — `AttributeError` |

Первая строка — это все браузерные пробы, и медкитовский случай ровно
оттуда. Поэтому опись печатает две кучи: где доказательство ОБЯЗАНО
быть и где оно желательно.

═══════════════════════════════════════════════════════════════════════
ЗАПУСК
═══════════════════════════════════════════════════════════════════════

    py check_controls.py            # опись
    py check_controls.py --кратко   # только числа

Код возврата — ВСЕГДА 0: это МЕРКА, а не проверка (§6.0.4). Сколько
контролей должно быть доказано — решение о работе, а не о коде,
и порог тут назначать нечему.
"""
import ast
import glob
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))

# Имена, которыми контроль ОБЪЯВЛЯЕТ доказательство подлога.
# Модульный уровень: словарь либо функция.
ИМЕНА_ДОКАЗАТЕЛЬСТВА = {"ДОКАЗАТЕЛЬСТВА", "доказать_подлог"}

# ПОДЛОГ КЛАДЁТСЯ В СТРАНИЦУ — признак «проба водит браузер».
#
# ЗДЕСЬ СТОЯЛ ПЕРЕЧЕНЬ ВЫЗОВОВ (`add_init_script`, `add_style_tag`),
# и он был неверен: `check_exercises_ui` кладёт свои три подлога через
# `evaluate`, то есть в перечень не попадал и числился безопасным.
#
# Способов провалиться молча у браузерного подлога ДВА, и перечень
# вызовов ловил только первый:
#
#   · `add_init_script` — исключение внутри страницы наружу НЕ выходит.
#     Ровно случай `check_medkit_ui` (разбор в шапке файла);
#   · `evaluate` — исключение как раз выходит, но подлог может
#     оказаться ПУСТОЙ ОПЕРАЦИЕЙ: отработал без ошибки и не изменил
#     ничего. Ровно случай `check_exercises_ui`, где первая версия
#     подлога «фильтр по странице» резала уже отфильтрованное.
#
# Общее у них не вызов, а то, что эффект подлога живёт ВНУТРИ страницы
# и наружу сам собой не сообщается. Значит признак — «проба водит
# браузер», а не список имён (§6.0.7: класс вместо перечня).
БРАУЗЕР = "playwright"


def _строка_ключа(узел):
    return (isinstance(узел, ast.Constant) and isinstance(узел.value, str)
            and узел.value.startswith("--контроль"))


def _есть_ключ_контроля(дерево):
    """Ключ `--контроль*` РАЗБИРАЕТСЯ кодом — то есть отрицательный
    контроль существует КАК РЕЖИМ, а не как слово в докстроке.

    СПОСОБОВ ОБЪЯВИТЬ ЕГО В ПРОЕКТЕ ДВА, и первая версия этой функции
    знала только один — `argparse`. Замер: она нашла ТРИ скрипта
    из двадцати семи, потому что двадцать четыре пишут
    `'--контроль' in sys.argv`. То есть опись немых отказов сама
    страдала немым отказом: печатала «контролей всего 3» и выглядела
    исправной.

    Поймано сверкой с грепом, а не чтением. Отсюда признак — не «вызван
    add_argument», а «строка `--контроль` УЧАСТВУЕТ В РАЗБОРЕ»: либо
    аргументом `add_argument`, либо операндом `in` (проверка вхождения
    в `sys.argv`). Слово в докстроке и в комментарии не считается
    ни там, ни там — они не узлы `Call` и не операнды `Compare`.
    """
    for узел in ast.walk(дерево):
        # 1) argparse: ap.add_argument("--контроль", …)
        if isinstance(узел, ast.Call) \
           and getattr(узел.func, "attr", None) == "add_argument":
            if any(_строка_ключа(а) for а in узел.args):
                return True
        # 2) руками: "--контроль" in sys.argv
        if isinstance(узел, ast.Compare) and _строка_ключа(узел.left):
            if any(isinstance(о, ast.In) for о in узел.ops):
                return True
    return False


def _объявлено_доказательство(дерево):
    """Модульный уровень: `ДОКАЗАТЕЛЬСТВА = …` либо `def доказать_подлог`.

    Только модульный уровень: имя, спрятанное внутри функции, снаружи
    не видно, а признак обязан читаться описью без исполнения кода.
    """
    for узел in дерево.body:
        if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if узел.name in ИМЕНА_ДОКАЗАТЕЛЬСТВА:
                return узел.name
        elif isinstance(узел, ast.Assign):
            for цель in узел.targets:
                if isinstance(цель, ast.Name) and цель.id in ИМЕНА_ДОКАЗАТЕЛЬСТВА:
                    return цель.id
        elif isinstance(узел, ast.AnnAssign):
            цель = узел.target
            if isinstance(цель, ast.Name) and цель.id in ИМЕНА_ДОКАЗАТЕЛЬСТВА:
                return цель.id
    return None


def _подлог_в_страницу(дерево):
    """Водит ли проба браузер — то есть умеет ли её подлог провалиться
    молча (разбор у объявления `БРАУЗЕР`).

    По ИМПОРТУ, а не по вызову: имя вызова у подлога бывает разное,
    а браузер в проекте один.
    """
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            if any(а.name.split(".")[0] == БРАУЗЕР for а in узел.names):
                return True
        elif isinstance(узел, ast.ImportFrom):
            if (узел.module or "").split(".")[0] == БРАУЗЕР:
                return True
    return False


def опись():
    """Все скрипты проекта с отрицательным контролем.

    Множество ОТКРЫТОЕ — новый инструмент появляется решением о коде,
    а не решением об этом списке, — поэтому выводится с диска,
    а не перечисляется (§6.0.7).
    """
    строки = []
    свой = os.path.basename(__file__)
    for путь in sorted(glob.glob(os.path.join(КОРЕНЬ, "*.py"))):
        имя = os.path.basename(путь)
        if имя == свой:
            continue
        try:
            дерево = ast.parse(open(путь, encoding="utf-8").read())
        except SyntaxError:
            continue
        if not _есть_ключ_контроля(дерево):
            continue
        строки.append({
            "файл": имя,
            "в_страницу": _подлог_в_страницу(дерево),
            "доказательство": _объявлено_доказательство(дерево),
        })
    return строки


def main():
    кратко = "--кратко" in sys.argv
    строки = опись()
    опасных = [с for с in строки if с["в_страницу"]]
    доказано = [с for с in строки if с["доказательство"]]
    доказано_опасных = [с for с in опасных if с["доказательство"]]

    print("ОТРИЦАТЕЛЬНЫЕ КОНТРОЛИ — доказан ли подлог")
    print("=" * 70)
    print()
    print("  контролей всего:                 %d" % len(строки))
    print("  подлог кладётся В СТРАНИЦУ:      %d  <- умеет провалиться молча"
          % len(опасных))
    print("  доказательство ОБЪЯВЛЕНО:        %d" % len(доказано))
    print("  из них среди опасных:            %d из %d"
          % (len(доказано_опасных), len(опасных)))
    print()

    if кратко:
        return 0

    print("-- ПОДЛОГ В СТРАНИЦУ: доказательство ОБЯЗАТЕЛЬНО --")
    for с in sorted(опасных, key=lambda x: (not x["доказательство"], x["файл"])):
        знак = ("ДОКАЗАН (%s)" % с["доказательство"]) if с["доказательство"] \
               else "НЕ ДОКАЗАН — свидетельство одно: проба что-то напечатала"
        print("  %-26s %s" % (с["файл"], знак))
    print()

    прочие = [с for с in строки if not с["в_страницу"]]
    print("-- ПОДЛОГ НЕ В СТРАНИЦУ: провалиться молча не умеет --")
    print("   (файл, база, память процесса — неудача бросает исключение")
    print("    в самом контроле, а не растворяется внутри страницы)")
    for с in sorted(прочие, key=lambda x: x["файл"]):
        знак = ("ДОКАЗАН (%s)" % с["доказательство"]) if с["доказательство"] else "—"
        print("  %-26s %s" % (с["файл"], знак))
    print()
    print("Код возврата 0 всегда: это МЕРКА, а не проверка (§6.0.4).")
    return 0


if __name__ == "__main__":
    sys.exit(main())

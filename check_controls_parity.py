def _git_show(коммит, путь):
    r = subprocess.run(["git", "show", f"{коммит}:{путь}"], cwd=КОРЕНЬ,
                       capture_output=True)
    if r.returncode != 0:
        return None
    return r.stdout.decode("utf-8")


def _читать(путь, коммит=None):
    if коммит:
        return _git_show(коммит, путь)
    p = КОРЕНЬ / путь
    return p.read_text(encoding="utf-8") if p.exists() else None


def собрать_текст(путь, коммит=None, _видено=None):
    """Шаблон с раскрытыми include своих партиалов (каркас не раскрывается)."""
    _видено = _видено or set()
    текст = _читать(путь, коммит)
    if текст is None:
        return None
    _видено.add(путь)

    def вставить(m):
        имя = m.group(1)
        if имя in КАРКАС:
            return ""
        п = "templates/" + имя
        if п in _видено:
            return ""
        return собрать_текст(п, коммит, _видено) or ""
    return re.sub(r"{%-?\s*include\s+['\"]([^'\"]+)['\"][^%]*%}", вставить, текст)


def _без_комментариев(т):
    т = re.sub(r"{#.*?#}", " ", т, flags=re.S)
    т = re.sub(r"<!--.*?-->", " ", т, flags=re.S)
    return т


def _атр(атрибуты, имя):
    m = re.search(r'(?<![\w-])' + re.escape(имя) + r'\s*=\s*("([^"]*)"|\'([^\']*)\')',
                  атрибуты)
    if not m:
        return ""
    return (m.group(2) if m.group(2) is not None else m.group(3)).strip()


def _текст(html):
    т = re.sub(r"{{.*?}}|{%.*?%}|\$\{[^}]*\}", " ", html, flags=re.S)
    т = re.sub(r"<[^>]+>", " ", т)
    т = re.sub(r"[\s·→←✕×]+", " ", т).strip().lower()
    return т


def _действие(onclick):
    return re.sub(r"\s+", "", onclick.replace("event.stopPropagation();", ""))


def _вкладка(т, поз):
    """Вкладка органа — последняя `id="tab-…"` выше него в тексте. Нужна,
    чтобы ПЕРЕЕЗД между вкладками одной страницы назывался переездом,
    а не молчал (№352, «питание-2»: «Прогресс тела» из «Профиля» в «Вес»)."""
    м = None
    for м in re.finditer(r'<section[^>]*id="(tab-[\w-]+)"', т[:поз]):
        pass
    # Орган ПОСЛЕ закрытия вкладки (модалка, скрипт) ей не принадлежит
    if not м or "</section>" in т[м.end():поз]:
        return ""
    return м.group(1)


def органы(текст):
    """Кнопки и ссылки-действия, поля ввода, адреса запросов."""
    т = _без_комментариев(текст)
    кнопки, поля = [], []
    for m in re.finditer(r"<(button|a)\b([^>]*)>(.*?)</\1\s*>", т, flags=re.S | re.I):
        тег, атр, внутри = m.group(1).lower(), m.group(2), m.group(3)
        onclick = _атр(атр, "onclick")
        da = _атр(атр, "data-action")
        href = _атр(атр, "href")
        if тег == "a" and not (onclick or da or href.startswith("#")
                               or href.startswith("javascript")):
            continue
        # ПОДПИСЬ data-* РАЗЛИЧАЕТ ОРГАНЫ С ОДНИМ ОБРАБОТЧИКОМ: у вкладок
        # дневника у всех `switchTab(this)`, и без неё шесть вкладок
        # схлопывались в одну.
        данные = ",".join(sorted(
            f"{k}={v}" for k, v in re.findall(r'(?<![\w-])(data-[\w-]+)\s*=\s*"([^"{$]*)"', атр)
            if k != "data-action"))
        кнопки.append({"id": _атр(атр, "id"), "действие": _действие(onclick),
                       "da": da, "данные": данные, "текст": _текст(внутри),
                       "вкладка": _вкладка(т, m.start())})
    for m in re.finditer(r"<(input|textarea|select)\b([^>]*)>", т, flags=re.I):
        атр = m.group(2)
        тип = _атр(атр, "type")
        if тип in ("hidden",):
            continue
        поля.append({"id": _атр(атр, "id"), "name": _атр(атр, "name"),
                     "тип": m.group(1).lower() + (":" + тип if тип else ""),
                     "подсказка": _атр(атр, "placeholder"),
                     "вкладка": _вкладка(т, m.start())})
    адреса = set()
    for m in re.finditer(r"([`'\"])(/[a-z][^`'\"\s]*)\1", т):
        адрес = m.group(2)
        if "/api/" not in адрес and not re.search(r"\b(fetch|api)\(\s*$",
                                                   т[max(0, m.start() - 12):m.start()]):
            continue
        адрес = re.sub(r"\$\{[^}]*\}", "{}", адрес).split("?")[0]
        адреса.add(адрес.rstrip("/") or "/")
    # ОПРЕДЕЛЕНИЕ функции — не вызов: без этого `copyLetter()` находился
    # в `function copyLetter() {` и снятая кнопка считалась живой.
    сплошной = re.sub(r"function\s+[\w$]+\s*\(", "function@(", т)
    return кнопки, поля, адреса, re.sub(r"\s+", "", сплошной)


def _кнопка_ключ(к):
    основа = к["действие"] or к["da"] or ("#" + к["id"] if к["id"] else "") or к["текст"]
    return основа + (" [" + к["данные"] + "]" if к["данные"] and основа else "")


def сравнить(старый, новый):
    """Пропавшее и появившееся по смыслу."""
    ск, сп, са, _ = органы(старый)
    нк, нп, на, сплошной = органы(новый)
    н_id = {к["id"] for к in нк if к["id"]} | {п["id"] for п in нп if п["id"]}
    н_да = {к["da"] for к in нк if к["da"]}
    н_текст = {к["текст"] for к in нк if к["текст"]}
    н_пары = {(к["действие"], к["данные"]) for к in нк}

    def жива(к):
        if к["id"] and к["id"] in н_id:
            return True
        if к["действие"] and к["данные"]:
            if (к["действие"], к["данные"]) in н_пары:
                return True
        elif к["действие"] and к["действие"] in сплошной:
            return True
        if к["da"] and к["da"] in н_да:
            return True
        # ТЕКСТ — только для органа без действия, id и data-action. Иначе
        # «Копировать» в истории спасало снятую «Копировать» под письмом.
        if not (к["id"] or к["действие"] or к["da"]) and к["текст"] in н_текст:
            return True
        return False

    пропало = []
    видено = set()
    for к in ск:
        ключ = _кнопка_ключ(к)
        if not ключ or ключ in видено:
            continue
        видено.add(ключ)
        if not жива(к):
            пропало.append(("кнопка", ключ, к["текст"]))
    н_name = {п["name"] for п in нп if п["name"]}
    н_подсказка = {п["подсказка"] for п in нп if п["подсказка"]}
    for п in сп:
        ключ = п["id"] or п["name"] or п["подсказка"]
        if not ключ or ключ in видено:
            continue
        видено.add(ключ)
        if not ((п["id"] and п["id"] in н_id) or (п["name"] and п["name"] in н_name)
                or (not п["id"] and not п["name"] and п["подсказка"] in н_подсказка)):
            пропало.append(("поле", ключ, п["тип"]))
    for а in sorted(са - на):
        пропало.append(("адрес", а, ""))
    return пропало, _появилось(ск, нк, са, на)


def переехало(старый, новый):
    """Органы, живые в обеих версиях, но сменившие вкладку. Сопоставление
    по id либо по действию: у переехавшего органа оба остаются прежними."""
    ск, сп, _, _ = органы(старый)
    нк, нп, _, _ = органы(новый)
    где = {}
    for о in нк + нп:
        for ключ in (о.get("id"), о.get("действие")):
            if ключ:
                где.setdefault(ключ, о["вкладка"])
    итог, видено = [], set()
    for о in ск + сп:
        ключ = о.get("id") or о.get("действие")
        if not ключ or ключ in видено or ключ not in где:
            continue
        видено.add(ключ)
        if о["вкладка"] and где[ключ] and о["вкладка"] != где[ключ]:
            итог.append((ключ, о["вкладка"], где[ключ]))
    return итог


def _появилось(ск, нк, са, на):
    с_ключи = {_кнопка_ключ(к) for к in ск}
    появилось = [("кнопка", _кнопка_ключ(к), к["текст"]) for к in нк
                 if _кнопка_ключ(к) and _кнопка_ключ(к) not in с_ключи]
    появилось += [("адрес", а, "") for а in sorted(на - са)]
    return появилось


def прогон(имя, показать_новое=False):
    опис = ИНСТРУМЕНТЫ[имя]
    старый = собрать_текст(опис["шаблон"], опис["до"])
    новый = собрать_текст(опис["шаблон"])
    if старый is None or новый is None:
        print(f"[{имя}] СРАВНИВАТЬ НЕЧЕГО: шаблон или коммит {опис['до']} не найден")
        return None
    пропало, появилось = сравнить(старый, новый)
    # ОБЪЯВЛЕННЫЕ ПЕРЕЕЗДЫ — КАЖДЫЙ ПРОВЕРЯЕТСЯ ПО НОВОМУ КЛЮЧУ
    нк, нп, _, _ = органы(новый)
    живые = ({_кнопка_ключ(к) for к in нк} | {к["действие"] for к in нк if к["действие"]}
             | {"#" + к["id"] for к in нк if к["id"]}
             | {"#" + п["id"] for п in нп if п["id"]}
             | {п["id"] for п in нп if п["id"]})
    # ОРГАН, СОБРАННЫЙ СКРИПТОМ, — ТОЖЕ ЖИВОЙ ОРГАН (№352, «аптечка-2»).
    #
    # `органы` разбирает РАЗМЕТКУ, и кнопки, которые строит JS
    # (`кн.id = 'apt-drug-del'`, `кн.onclick = () => аптСпросить(п.id)`),
    # ей не видны вовсе. Пока такие кнопки были только внутри блоков,
    # это ничего не меняло; с переездом удаления в панель лекарства
    # проверка объявила бы ПОТЕРЕЙ орган, который стоит на экране
    # и работает, — то есть напечатала бы находку про исправный код.
    #
    # Вопрос от этого РАСШИРЯЕТСЯ, а не сужается: множество живых
    # ключей только растёт, и пропажу настоящего органа это скрыть
    # не может — у пропавшего нет ни разметки, ни присваивания.
    живые |= {"#" + i for i in re.findall(r'\.id\s*=\s*["\']([\w-]+)["\']',
                                          новый)}
    живые |= {и + "()" for и in re.findall(
        r'onclick\s*=\s*\(\)\s*=>\s*([\wЀ-ӿ]+)\s*\(', новый)}
    потеряны = []
    for (инстр, что), ключ in ПЕРЕЕЗДЫ.items():
        if инстр != имя:
            continue
        жив = ключ in живые
        print(f"   {'переехал' if жив else 'ПОТЕРЯН '} {что} → {ключ}")
        if not жив:
            потеряны.append((что, ключ))
    долг = [п for п in пропало if (имя, п[0], п[1]) not in ПРИНЯТЫЕ]
    долг += [("переезд", что, ключ) for что, ключ in потеряны]
    print(f"[{имя}] до={опис['до']}  пропало {len(пропало)}, "
          f"из них не принято {len(долг)}, появилось {len(появилось)}")
    for вид, ключ, пояс in пропало:
        причина = ПРИНЯТЫЕ.get((имя, вид, ключ))
        метка = "принято" if причина else "ПРОПАЛО"
        print(f"   {метка:8} {вид:6} {ключ[:70]}" + (f"  «{пояс[:40]}»" if пояс else "")
              + (f" — {причина}" if причина else ""))
    for ключ, было, стало in переехало(старый, новый):
        print(f"   переехал {ключ[:60]}  {было} → {стало}")
    if показать_новое:
        for вид, ключ, пояс in появилось:
            print(f"   +       {вид:6} {ключ[:70]}" + (f"  «{пояс[:40]}»" if пояс else ""))
    return долг


def контроль():
    """Подлог: убрать из текущего hh.html рабочую кнопку «Копировать» в памяти."""
    новый = собрать_текст("templates/hh.html")
    m = re.search(r"<button\b[^>]*onclick=\"copyLetter\([^\"]*\)\"[^>]*>.*?</button>",
                  новый, flags=re.S)
    if not m:
        print("КОНТРОЛЬ: кнопки copyLetter в hh.html нет — подложить нечего")
        return 2
    испорчен = новый[:m.start()] + новый[m.end():]
    чисто, _ = сравнить(новый, новый)
    пропало, _ = сравнить(новый, испорчен)
    # Доказательство подлога — независимо от вердикта: вызова больше нет в тексте.
    было = новый.count("copyLetter(")
    стало = испорчен.count("copyLetter(")
    print(f"КОНТРОЛЬ: чисто пропавших {len(чисто)}; подлог: вызовов copyLetter "
          f"{было} → {стало}; пропавших {len(пропало)}")
    for п in пропало:
        print("   назван:", п[0], п[1])
    ок = not чисто and any("copyLetter" in п[1] for п in пропало)
    print("КОНТРОЛЬ:", "ЛОВИТ" if ок else "НЕ ЛОВИТ")
    return 0 if ок else 1


def контроль_переезда():
    """Подлог: вместо ПЕРЕЕЗДА «Прогресса тела» — пропажа. Блок удаляется
    из текущего nutrition.html в памяти; сверка обязана назвать его органы
    ПРОПАВШИМИ, а в чистом прогоне — ПЕРЕЕХАВШИМИ."""
    опис = ИНСТРУМЕНТЫ["nutrition"]
    старый = собрать_текст(опис["шаблон"], опис["до"])
    новый = собрать_текст(опис["шаблон"])
    m = re.search(r'<div class="card card-static wt-wide wt-photos">.*?id="compare-view"></div>\s*</div>',
                  новый, flags=re.S)
    if not m:
        print("КОНТРОЛЬ ПЕРЕЕЗДА: блока «Прогресс тела» во вкладке «Вес» нет — подложить нечего")
        return 2
    испорчен = новый[:m.start()] + новый[m.end():]
    ключи = ("photo-front", "uploadBodyPhotos()", "compare-date-old")
    чисто_переехало = [к for к, _, _ in переехало(старый, новый) if к in ключи]
    чисто_пропало = [п[1] for п in сравнить(старый, новый)[0] if п[1] in ключи]
    подлог_пропало = [п[1] for п in сравнить(старый, испорчен)[0] if п[1] in ключи]
    print(f"КОНТРОЛЬ ПЕРЕЕЗДА: чисто — переехало {чисто_переехало}, пропало {чисто_пропало};"
          f" подлог (блок снят, вызовов uploadBodyPhotos {новый.count('uploadBodyPhotos(')}"
          f" → {испорчен.count('uploadBodyPhotos(')}) — пропало {подлог_пропало}")
    ок = len(чисто_переехало) == 3 and not чисто_пропало and len(подлог_пропало) == 3
    print("КОНТРОЛЬ ПЕРЕЕЗДА:", "ЛОВИТ" if ок else "НЕ ЛОВИТ")
    return 0 if ок else 1



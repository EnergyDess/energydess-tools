# -*- coding: utf-8 -*-
"""ПРОВЕРКА 27: СОЕДИНЕНИЕ К БАЗЕ, ЗАНЯТОЕ НА ВРЕМЯ ПОХОДА В СЕТЬ.

═══════════════════════════════════════════════════════════════════════
ЗАЧЕМ, И ЭТО ЖИВОЙ СЛУЧАЙ, А НЕ ПРЕДОСТОРОЖНОСТЬ
═══════════════════════════════════════════════════════════════════════

Замер захода 244: `POST /medkit/api/assist` шёл 34 453 мс, а параллельный
`GET /medkit` в это время упал `database is locked` за 32 789 мс. То есть
пока ассистент думает, САЙТ В СОСЕДНЕЙ ВКЛАДКЕ ОТДАЁТ ПЯТИСОТКУ.
Владелец этого не ловил, потому что работает один и в одной вкладке;
в круге аптечки на двоих оно поймается с первого дня.

МЕХАНИЗМ ЗАМЕРЕН, А НЕ ВЫВЕДЕН (2026-09-07, трасса SQL по соединениям):

    [соединение А] DELETE FROM chat_messages … created_at < ?   ← уборка
    [соединение А] SELECT chat_messages …
    … 35 секунд ожидания ответа модели …
    [соединение Б] DELETE FROM medkit_buy_items …  ← ждёт 30 с и падает

Ленивая уборка старых реплик — ЗАПИСЬ. Она открывает в SQLite
транзакцию записи, и транзакция не закрывается до конца обработчика,
то есть висит весь поход в сеть. Второй писатель ждёт `busy_timeout`
(30 с) и получает `database is locked`.

Отказ немой ровно наполовину: у ЖДУЩЕГО он громкий (500 и трасса),
а у виновника — ни строки. По журналу видно «GET /medkit упал», и в нём
нет ничего, что связало бы это с соседним запросом.

═══════════════════════════════════════════════════════════════════════
ПОЧЕМУ ПРОВЕРКОЙ, А НЕ ПРАВКОЙ ОДНОГО МЕСТА
═══════════════════════════════════════════════════════════════════════

Это ЧЕТВЁРТЫЙ случай одного класса: задача 22 (очередь за соединением),
задача 103 (bcrypt и синхронный httpx в цикле), задача 105 (журнал
и очередь пула) — и теперь сеть под открытой транзакцией. Каждый раз
чинили экземпляр, каждый раз следующий находился замером. Значит
закрывается КЛАСС (§6.0.7): мест, где async-обработчик с сессией идёт
в сеть, в проекте не одно и не два, и перечислять их руками — гарантия,
что следующее не попадёт в перечень.

═══════════════════════════════════════════════════════════════════════
КАК УСТРОЕНА
═══════════════════════════════════════════════════════════════════════

Не греп по имени: `_апт_спросить_модель` грепается, а `medkit_dosage`,
который ходит в сеть через четыре звена, — нет. Поэтому:

1. СЕТЕВЫЕ ФУНКЦИИ ВЫВОДЯТСЯ, А НЕ ПЕРЕЧИСЛЯЮТСЯ. Сетевая — та, в чьём
   теле стоит `httpx.AsyncClient`/`httpx.Client`, плюс транзитивно все,
   кто их зовёт. Перечень отстал бы от первого же нового вызова.

2. ОБХОД ТЕЛА ОБРАБОТЧИКА ПО ПОРЯДКУ. Флаг «соединение занято» —
   True после любого упоминания `db` (запрос, `db.add`, передача `db`
   аргументом), False после `db.close()` либо после `_сеть`/`_в_потоке`/
   `_пауза`, которые соединение отдают. Сетевой `await` при поднятом
   флаге — находка.

3. ГРАНИЦА НАЗВАНА, а не умолчана:
   • порядок берётся по номеру строки. Прямой код разбирается верно,
     а `db` внутри ветки `if`, исполняемой не всегда, поднимет флаг
     и на пути, где её нет: проверка склонна к ЛОЖНОЙ находке, а
     не к пропуску — и это выбор, обратная ошибка стоит пятисотки;
   • вызов через переменную (`fn = _апт_страница; await fn()`) невидим;
   • сетевая функция из стороннего пакета, не через httpx, невидима;
   • ДЛИТЕЛЬНОСТЬ. Проверка отвечает «занято или нет», а не «сколько
     миллисекунд держали». Это меряет `--живьём`.

ЖИВОЙ ЗАМЕР — ОТДЕЛЬНЫМ КЛЮЧОМ И ОТВЕЧАЕТ НА ДРУГОЙ ВОПРОС. Статическая
опись говорит «соединение занято», живая — «сколько ждал сосед и упал
ли». Свести их нельзя: первая читается без стенда и стоит секунду,
вторая поднимает приложение с заглушкой вместо OpenRouter.

Запуск:

    py check_db_hold.py              # код 1, если есть находка
    py check_db_hold.py --контроль   # код 1, если НЕ нашло подложенное
    py check_db_hold.py --живьём     # замер: ждёт ли сосед и падает ли
"""
import argparse
import ast
import io
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))

# Функции, ОТДАЮЩИЕ соединение. Перечень тут законен и мал по построению:
# каждая заведена решением и объявлена в `main.py` рядом с соседками;
# новая такая — это новая строка кода, а не имя, взявшееся само.
ОТДАЮТ = {"_сеть", "_в_потоке", "_пауза"}

# Имя параметра сессии у обработчика.
ИМЕНА_СЕССИИ = {"db"}


def _разобрать(путь):
    return ast.parse(io.open(путь, encoding="utf-8").read(), filename=путь)


def _вызовы(узел):
    """Имена всех вызовов внутри узла — и f(), и x.f()."""
    имена = set()
    for n in ast.walk(узел):
        if isinstance(n, ast.Call):
            f = n.func
            if isinstance(f, ast.Name):
                имена.add(f.id)
            elif isinstance(f, ast.Attribute):
                имена.add(f.attr)
    return имена


def сетевые_функции(дерево):
    """Множество имён, доходящих до сети. ВЫВОДИТСЯ, а не перечисляется."""
    функции = {}
    for у in ast.walk(дерево):
        if isinstance(у, (ast.FunctionDef, ast.AsyncFunctionDef)):
            функции.setdefault(у.name, []).append(у)
    сеть = set()
    for имя, узлы in функции.items():
        for у in узлы:
            for n in ast.walk(у):
                if (isinstance(n, ast.Attribute)
                        and isinstance(n.value, ast.Name)
                        and n.value.id == "httpx"
                        and n.attr in ("AsyncClient", "Client")):
                    сеть.add(имя)
    менялось = True
    while менялось:
        менялось = False
        for имя, узлы in функции.items():
            if имя in сеть:
                continue
            if any(_вызовы(у) & сеть for у in узлы):
                сеть.add(имя)
                менялось = True
    return сеть - ОТДАЮТ


def _есть_имя(узел, имя):
    return any(isinstance(n, ast.Name) and n.id == имя for n in ast.walk(узел))


def _передаёт_свою_сессию(вызов, сессия):
    """`f(…, db)` либо `f(…, db=db)` — своя сессия уехала внутрь."""
    for а in вызов.args:
        if isinstance(а, ast.Name) and а.id == сессия:
            return True
    for к in вызов.keywords:
        if isinstance(к.value, ast.Name) and к.value.id == сессия:
            return True
    return False


def отпускающие_функции(дерево):
    """Функции, ОТПУСКАЮЩИЕ соединение САМИ.

    Такая снимает находку у вызывающего — но только когда ей передали
    ЕГО ЖЕ сессию: закрыть чужую она не может по построению.

    Признак структурный и транзитивный, а не перечень имён: `db.close()`
    на собственном параметре либо передача его дальше в уже известную
    отпускающую. Ровно так же `check_detached.py` выводит множество
    отдающих соединение — перечень из трёх имён там оказался неверен
    в день написания (§6.0.7).
    """
    функции = {}
    for у in ast.walk(дерево):
        if isinstance(у, (ast.FunctionDef, ast.AsyncFunctionDef)):
            функции.setdefault(у.name, []).append(у)
    отпускают = set(ОТДАЮТ)
    менялось = True
    while менялось:
        менялось = False
        for имя, узлы in функции.items():
            if имя in отпускают:
                continue
            for у in узлы:
                доводы = [а.arg for а in у.args.args + у.args.kwonlyargs]
                сессия = next((и for и in доводы if и in ИМЕНА_СЕССИИ), None)
                if not сессия:
                    continue
                for n in ast.walk(у):
                    if not isinstance(n, ast.Call):
                        continue
                    if _отдаёт_соединение(n, сессия):
                        отпускают.add(имя)
                        менялось = True
                        break
                    f = n.func
                    цель = (f.id if isinstance(f, ast.Name)
                            else f.attr if isinstance(f, ast.Attribute)
                            else None)
                    if (цель in отпускают
                            and _передаёт_свою_сессию(n, сессия)):
                        отпускают.add(имя)
                        менялось = True
                        break
                if имя in отпускают:
                    break
    return отпускают


def _отдаёт_соединение(вызов, сессия):
    """db.close() либо _сеть/_в_потоке/_пауза(db, …)."""
    f = вызов.func
    if (isinstance(f, ast.Attribute) and f.attr == "close"
            and isinstance(f.value, ast.Name) and f.value.id == сессия):
        return True
    if isinstance(f, ast.Name) and f.id in ОТДАЮТ:
        return (bool(вызов.args) and isinstance(вызов.args[0], ast.Name)
                and вызов.args[0].id == сессия)
    return False


def проверить(путь="main.py"):
    """Находки: (строка, обработчик, что зовёт)."""
    дерево = _разобрать(os.path.join(КОРЕНЬ, путь))
    сеть = сетевые_функции(дерево)
    отпускают = отпускающие_функции(дерево)
    находки = []
    for у in ast.walk(дерево):
        if not isinstance(у, ast.AsyncFunctionDef):
            continue
        if у.name in ОТДАЮТ:
            continue
        доводы = [а.arg for а in у.args.args + у.args.kwonlyargs]
        сессия = next((и for и in доводы if и in ИМЕНА_СЕССИИ), None)
        if not сессия:
            continue
        события = []
        for n in ast.walk(у):
            if isinstance(n, ast.Call):
                события.append((n.lineno, n.col_offset, "вызов", n))
            elif isinstance(n, ast.Await):
                события.append((n.lineno, n.col_offset, "await", n))
            elif isinstance(n, ast.AsyncWith):
                for э in n.items:
                    вэ = э.context_expr
                    if (isinstance(вэ, ast.Call)
                            and isinstance(вэ.func, ast.Attribute)
                            and isinstance(вэ.func.value, ast.Name)
                            and вэ.func.value.id == "httpx"):
                        события.append((n.lineno, n.col_offset,
                                        "сеть-прямо", n))
        события.sort(key=lambda э: (э[0], э[1]))
        занято = False
        for строка, _кол, вид, n in события:
            if вид == "вызов":
                if _отдаёт_соединение(n, сессия):
                    занято = False
                    continue
                f = n.func
                цель = (f.id if isinstance(f, ast.Name)
                        else f.attr if isinstance(f, ast.Attribute) else None)
                if (цель in отпускают
                        and _передаёт_свою_сессию(n, сессия)):
                    занято = False
                    continue
                if _есть_имя(n, сессия):
                    занято = True
                continue
            if вид == "сеть-прямо":
                if занято:
                    находки.append((строка, у.name, "httpx напрямую"))
                continue
            цель = n.value
            имя = None
            if isinstance(цель, ast.Call):
                f = цель.func
                if isinstance(f, ast.Name):
                    имя = f.id
                elif isinstance(f, ast.Attribute):
                    имя = f.attr
            # Отпускающая функция, получившая НАШУ сессию, находкой
            # не является: соединение отпущено внутри неё.
            if (имя in отпускают and isinstance(цель, ast.Call)
                    and _передаёт_свою_сессию(цель, сессия)):
                занято = False
                continue
            if имя and имя in сеть and занято:
                находки.append((строка, у.name, имя))
    видели, свод = set(), []
    for строка, обработчик, что in находки:
        ключ = (обработчик, что)
        if ключ in видели:
            continue
        видели.add(ключ)
        свод.append((строка, обработчик, что))
    return sorted(свод)


ПОДЛОГ = '''

@app.post("/проба-подлога")
async def _проба_подлога(db: Session = Depends(get_db)):
    """Подлог контроля: запрос к базе, затем сеть."""
    n = db.query(User).count()
    текст = await _апт_текст_страницы("http://пример")
    return {"n": n, "t": текст}


@app.post("/проба-подлога-чисто")
async def _проба_подлога_чисто(db: Session = Depends(get_db)):
    """Обратный: соединение отдано ДО сети — находкой быть не должен."""
    n = db.query(User).count()
    db.close()
    текст = await _апт_текст_страницы("http://пример")
    return {"n": n, "t": текст}
'''


def доказать_подлог(путь):
    """НЕЗАВИСИМЫЙ ЗАМЕР ТОГО, ЧТО ПОДЛОГ СОСТОЯЛСЯ (§6.0.3).

    Вердикт проверки доказательством не является: «НАЙДЕН» выходит
    и у слепой пробы, если подлог не сработал по другой причине.
    Здесь спрашивается СОСТОЯНИЕ ОБЪЕКТА — обе подложенные функции
    обязаны появиться в разобранном дереве `main.py`.
    """
    д = _разобрать(путь)
    есть = {у.name for у in ast.walk(д)
            if isinstance(у, ast.AsyncFunctionDef)}
    return "_проба_подлога" in есть and "_проба_подлога_чисто" in есть


def контроль():
    """Подлог обязан быть найден, обратный — пропущен (§6.0.3)."""
    путь = os.path.join(КОРЕНЬ, "main.py")
    было = io.open(путь, encoding="utf-8", newline="").read()
    исход = 0
    try:
        io.open(путь, "w", encoding="utf-8",
                newline="").write(было + ПОДЛОГ)
        найдено = {о for _с, о, _ч in проверить()}
        доказано = доказать_подлог(путь)
        print("ДОКАЗАТЕЛЬСТВО ПОДЛОГА: обе пробы в дереве — %s"
              % ("ДА" if доказано else "НЕТ, подлог не состоялся"))
        if not доказано:
            return 2
        if "_проба_подлога" in найдено:
            print("  ПОДЛОГ НАЙДЕН: запрос к базе, затем сеть")
        else:
            print("  ПОДЛОГ НЕ НАЙДЕН — проверка слепа")
            исход = 1
        if "_проба_подлога_чисто" in найдено:
            print("  ЛОЖНАЯ НАХОДКА: обратный подлог назван находкой")
            исход = 1
        else:
            print("  ОБРАТНЫЙ ПРОПУЩЕН: соединение отдано — не находка")
    finally:
        io.open(путь, "w", encoding="utf-8", newline="").write(было)
    return исход


def main():
    р = argparse.ArgumentParser(add_help=False)
    р.add_argument("--контроль", action="store_true")
    р.add_argument("--живьём", action="store_true")
    а, лишнее = р.parse_known_args()
    if лишнее:
        print("НЕЗНАКОМЫЙ КЛЮЧ: %s" % " ".join(лишнее))
        return 2
    # `--живьём` разбирается ПЕРВЫМ: у живого замера свой контроль,
    # и `--живьём --контроль` обязан уйти туда, а не в статический.
    if а.живьём:
        import check_db_hold_live
        return check_db_hold_live.замер()
    if а.контроль:
        return контроль()
    находки = проверить()
    print("СОЕДИНЕНИЕ К БАЗЕ ЗАНЯТО НА ВРЕМЯ ПОХОДА В СЕТЬ")
    print("=" * 70)
    if not находки:
        print("находок нет")
        return 0
    for строка, обработчик, что in находки:
        print("  main.py:%-6d %-30s -> %s" % (строка, обработчик, что))
    print()
    print("НАХОДОК: %d" % len(находки))
    return 1


if __name__ == "__main__":
    sys.exit(main())

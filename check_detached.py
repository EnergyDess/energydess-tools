# -*- coding: utf-8 -*-
"""ПРОВЕРКА 15: запись в ОТЦЕПЛЕННЫЙ объект ORM после `_в_потоке`/`_пауза`.

ЧТО ЗА ОТКАЗ. `_в_потоке(db, …)` и `_пауза(db, …)` отдают соединение
(`db.close()`) — это и есть их смысл (§6.0.5, §6.0.6). Побочный эффект
назван в docstring обеих: объекты ORM ОТЦЕПЛЯЮТСЯ. Читать их поля можно
по-прежнему, а записать — уже нет: присваивание проходит, `db.commit()`
проходит, ошибки нет, до базы не доезжает НИЧЕГО.

То есть обработчик отвечает 200, и ответ — неправда.

ТРИ СЛУЧАЯ ЗА ТРИ ДНЯ, И ВСЕ ТРИ НАЙДЕНЫ РУКАМИ:

  1. смена адреса (2026-08-20): `user.pending_email` писался сразу после
     проверки пароля. Эндпоинт отвечал 200, письмо уходило, в базе пусто.
     Поймал тест, проверявший ГЛАВНОЕ свойство;

  2. правило записано в `CLAUDE.md` §6.0.5 и всё равно нарушено в том же
     заходе — тем же автором, в соседней функции;

  3. загрузка аватара (найдено 2026-08-20 замером): файл ложится на диск,
     `user.avatar_updated_at` НЕ доезжает. Ответ `{"ok":true,"v":…}`,
     а страница профиля рисует букву-инициал вместо фотографии, и кнопка
     «Убрать фото» остаётся спрятанной. Человек загрузил фото, увидел
     предпросмотр, обновил страницу — фото нет. Ни ошибки, ни строки в логе.

Три раза руками — значит, правило в документе своей работы не делает,
и класс надо закрывать машиной (§6.0.7).

КАК ИЩЕТ. Обходом синтаксического дерева, не грепом: греп видит строку
`user.pending_email = …` и не знает, был ли выше `await _в_потоке`
и переспрашивали ли объект из базы. Внутри каждой `async def`:

  1. запоминаются имена, связанные ДО первого отдающего соединение await;
  2. после такого await имя считается ОТЦЕПЛЕННЫМ, пока его заново
     не свяжут (`user = db.get(...)`, `db.query(...).first()` и т.п.);
  3. присваивание атрибуту отцепленного имени — находка.

ЧЕГО НЕ ВИДИТ, названо честно:
  • объект, полученный не через имя (`список[0].поле = …`);
  • имя, переданное в чужую функцию, которая пишет в него уже там;
  • отцепление через собственный `db.close()` на месте, без `_в_потоке`;
  • `db.refresh(obj)` как способ прицепить обратно — считается
    перепривязкой, и это верно, но список таких способов — перечень.

Запуск, код читается БЕЗ конвейера (§6.0.1):

    py check_detached.py;            echo "код=$?"   # 0 — находок нет
    py check_detached.py --контроль; echo "код=$?"   # 0 — проверка видит подлог
"""

import ast
import io
import sys

# МНОЖЕСТВО ОТДАЮЩИХ СОЕДИНЕНИЕ ВЫВОДИТСЯ ИЗ КОДА, А НЕ ПЕРЕЧИСЛЯЕТСЯ
# (§6.0.7). Первая версия этого файла держала здесь перечень из трёх имён —
# и он тут же оказался неверным: `_sync_scale_в_потоке` соединение
# НЕ отдаёт, он уносит сессию в поток целиком. Проверка дала четыре
# ложных находки на `scale_sync`, то есть пять находок при одной
# настоящей — ровно тот процент лжи, за которым проверку перестают
# читать (§6.0.2, довод про `_admin_nav.html`).
#
# Признак вместо списка: async-функция, у которой в теле стоит `.close()`
# на собственном параметре. Заведут четвёртую такую — она попадёт сюда
# сама, и это разница между «забыли дописать» и «не бывает».
def _отдающие_соединение(деревья):
    имена = set()
    for дерево in деревья:
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.AsyncFunctionDef):
                continue
            параметры = {а.arg for а in узел.args.args}
            for под in ast.walk(узел):
                if (isinstance(под, ast.Call) and isinstance(под.func, ast.Attribute)
                        and под.func.attr == "close"
                        and isinstance(под.func.value, ast.Name)
                        and под.func.value.id in параметры):
                    имена.add(узел.name)
    return имена


ОТДАЮТ_СОЕДИНЕНИЕ = set()          # наполняется в `проверить`

# Выражения, которые ПРИВЯЗЫВАЮТ объект заново. Тоже перечень, и тоже
# закрытый: способов взять объект из сессии в SQLAlchemy ровно столько.
ПРИВЯЗЫВАЮТ = {"get", "first", "one", "one_or_none", "scalar", "refresh", "merge"}

ФАЙЛЫ = ["main.py"]


def _зовут(узел):
    """Имя вызываемого: `f(...)` → 'f', `a.b(...)` → 'b'."""
    if not isinstance(узел, ast.Call):
        return None
    ф = узел.func
    if isinstance(ф, ast.Name):
        return ф.id
    if isinstance(ф, ast.Attribute):
        return ф.attr
    return None


def _отдаёт_соединение(узел):
    """Есть ли внутри выражения await у функции, отдающей соединение."""
    for под in ast.walk(узел):
        if isinstance(под, ast.Await) and _зовут(под.value) in ОТДАЮТ_СОЕДИНЕНИЕ:
            return _зовут(под.value)
    return None


def _привязывает(значение):
    """Похоже ли выражение на «взять объект из сессии заново»."""
    for под in ast.walk(значение):
        if _зовут(под) in ПРИВЯЗЫВАЮТ:
            return True
    return False


def _проверить_функцию(функция, файл, находки):
    """Имена, связанные ДО первого отдающего await, становятся отцепленными."""
    связанные = {арг.arg for арг in (функция.args.args
                                     + list(функция.args.posonlyargs)
                                     + list(функция.args.kwonlyargs))}
    отцеплены = set()

    # ПО ПОРЯДКУ, а не обходом дерева: важно именно то, что стоит ПОСЛЕ
    def пройти(тело, отдал):
        # nonlocal: `отцеплены |= …` ниже — присваивание, и без объявления
        # оно завело бы ЛОКАЛЬНОЕ множество в каждом вызове, то есть
        # отцепление не переживало бы вложенный блок
        nonlocal отцеплены
        for оператор in тело:
            кто = _отдаёт_соединение(оператор)

            if isinstance(оператор, (ast.Assign, ast.AnnAssign)):
                цели = (оператор.targets if isinstance(оператор, ast.Assign)
                        else [оператор.target])
                for цель in цели:
                    if (isinstance(цель, ast.Attribute)
                            and isinstance(цель.value, ast.Name)
                            and цель.value.id in отцеплены):
                        находки.append((файл, оператор.lineno, цель.value.id,
                                        цель.attr, отдал, функция.name))
                for цель in цели:
                    имена = ([цель] if isinstance(цель, ast.Name)
                             else list(цель.elts) if isinstance(цель, ast.Tuple) else [])
                    for имя in имена:
                        if isinstance(имя, ast.Name):
                            связанные.add(имя.id)
                            отцеплены.discard(имя.id)

            for под in ast.walk(оператор):
                if isinstance(под, ast.Call) and _зовут(под) in ("refresh", "merge", "add"):
                    for арг in под.args:
                        if isinstance(арг, ast.Name):
                            отцеплены.discard(арг.id)

            if кто:
                отдал = кто
                отцеплены |= связанные

            for поле in ("body", "orelse", "finalbody"):
                вложенное = getattr(оператор, поле, None)
                if isinstance(вложенное, list) and вложенное and isinstance(
                        вложенное[0], ast.stmt):
                    отдал = пройти(вложенное, отдал)
            for обработчик in getattr(оператор, "handlers", []):
                отдал = пройти(обработчик.body, отдал)
        return отдал

    пройти(функция.body, None)


def проверить(файлы=ФАЙЛЫ):
    global ОТДАЮТ_СОЕДИНЕНИЕ
    деревья = {файл: ast.parse(io.open(файл, encoding="utf-8").read())
               for файл in файлы}
    ОТДАЮТ_СОЕДИНЕНИЕ = _отдающие_соединение(деревья.values())
    находки = []
    for файл, дерево in деревья.items():
        for узел in ast.walk(дерево):
            if isinstance(узел, ast.AsyncFunctionDef):
                _проверить_функцию(узел, файл, находки)
    return находки


def _контроль():
    """Подлог во временном файле: проверка ОБЯЗАНА его найти, и обязана
    НЕ найти соседний случай, где объект переспрошен из базы."""
    import os
    import tempfile
    путь = os.path.join(tempfile.gettempdir(), "detach_control.py")
    io.open(путь, "w", encoding="utf-8").write('''
async def _в_потоке(db, функция, *аргументы):
    db.close()                         # вот по этой строке она и опознаётся
    return await asyncio.to_thread(функция, *аргументы)

async def _уносит_сессию_в_поток(db, conn):
    return await asyncio.to_thread(что_то, db, conn)   # НЕ отдаёт соединение

async def плохо(db, user):
    ид = user.id
    хеш = await _в_потоке(db, hash_password, "x")
    user.password_hash = хеш          # ← ЗАПИСЬ В ОТЦЕПЛЕННЫЙ
    db.commit()

async def хорошо(db, user):
    ид = user.id
    хеш = await _в_потоке(db, hash_password, "x")
    user = db.get(User, ид)
    user.password_hash = хеш          # переспрошен — законно
    db.commit()

async def тоже_хорошо(db, user):
    user.поле = 1                      # до всякого await — законно
    await _в_потоке(db, что_то)

async def и_это_хорошо(db, conn):
    итог = await _уносит_сессию_в_поток(db, conn)
    conn.поле = итог                   # сессия не отдавалась — законно
''')
    находки = проверить([путь])
    строки = {н[1] for н in находки}
    ошибки = []
    if not any(н[3] == "password_hash" and н[5] == "плохо" for н in находки):
        ошибки.append("подлог НЕ найден — проверка сломана")
    if any(н[5] == "хорошо" for н in находки):
        ошибки.append("ложная находка: объект переспрошен из базы")
    if any(н[5] == "тоже_хорошо" for н in находки):
        ошибки.append("ложная находка: запись ДО await")
    if any(н[5] == "и_это_хорошо" for н in находки):
        ошибки.append("ложная находка: функция соединение НЕ отдаёт "
                      "(та самая, из-за которой перечень заменён признаком)")
    if "_в_потоке" not in ОТДАЮТ_СОЕДИНЕНИЕ:
        ошибки.append("отдающая функция не опознана по признаку")
    if "_уносит_сессию_в_поток" in ОТДАЮТ_СОЕДИНЕНИЕ:
        ошибки.append("не отдающая функция опознана как отдающая")
    os.unlink(путь)
    print("КОНТРОЛЬ ПРОВЕРКИ 15")
    print(f"  находок в подлоге: {len(находки)} (строки {sorted(строки)})")
    for о in ошибки:
        print(f"  ✗ {о}")
    if not ошибки:
        print("  ✓ подлог найден, законные случаи пропущены")
    return 1 if ошибки else 0


def main():
    if "--контроль" in sys.argv:
        return _контроль()
    находки = проверить()
    if not находки:
        print("ЗАПИСЬ В ОТЦЕПЛЕННЫЙ ОБЪЕКТ: не найдено")
        return 0
    print(f"ЗАПИСЬ В ОТЦЕПЛЕННЫЙ ОБЪЕКТ ORM — {len(находки)}:")
    for файл, строка, имя, поле, отдал, функция in находки:
        print(f"  {файл}:{строка}  {имя}.{поле} = …   "
              f"(соединение отдал {отдал}, функция {функция})")
    print()
    print("  Запись не доедет до базы. Ошибки не будет, commit пройдёт.")
    print("  Лечится одной строкой: взять объект из базы заново после await.")
    return 1


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())

#
# Задача 99. До 2026-08-19 `собрать_известное` читала файлы как плоский
# текст, и любое имя, названное в пояснении, считалось существующим
# наравне с селектором. Строка
#
#     /* .save-btn здесь больше нет — это .btn-primary .btn-block */
#
# объявляла `.save-btn` живым классом. То же самое делали docstring
# в *.py и комментарии в *.js и в шаблонах.
#
# ЦЕНА БЫЛА НЕ В ЛИШНЕЙ СТРОКЕ ВЫВОДА, А В МОЛЧАНИИ. Проход A ищет
# имена, ОПИСАННЫЕ в документе и ОТСУТСТВУЮЩИЕ в коде; имя, оживлённое
# комментарием, из находок исчезало — то есть документ мог сколько угодно
# ссылаться на удалённый класс, пока в коде оставалось пояснение о том,
# что класс удалён. Ровно тот немой отказ, ради поимки которого проверка
# и написана (CLAUDE.md §6.0.1).
#
# ЛЕЧИТСЯ РАЗБОРОМ, А НЕ БОЛЕЕ ХИТРЫМ ГРЕПОМ. Греп по строке уже дважды
# ловил ложное на комментариях самого проекта (§6.0.2, признанные
# пробелы), и третья попытка отличалась бы только формой регулярки.
# Ниже — четыре разбора по типу файла, каждый снимает ровно ту форму
# комментария, которая в этом языке бывает.


def _css_код(текст):
    """CSS без комментариев. `/* … */` не вкладываются, поэтому нежадного
    снятия достаточно и второй проход не нужен."""
    return re.sub(r'/\*.*?\*/', ' ', текст, flags=re.S)


def _js_код(текст):
    """JS без блочных и строчных комментариев.

    Строчные снимаются ТОЛЬКО когда `//` открывает строку: `//` внутри
    строкового литерала (а это каждый `https://…` в коде) иначе съел бы
    остаток строки вместе с настоящим кодом."""
    текст = re.sub(r'/\*.*?\*/', ' ', текст, flags=re.S)
    return re.sub(r'(?m)^\s*//[^\n]*', ' ', текст)


def _html_код(текст):
    """Разметка без `<!-- … -->`."""
    return re.sub(r'<!--.*?-->', ' ', текст, flags=re.S)


def _py_литералы(текст):
    """Строковые литералы Python СПИСКОМ — без комментариев и без docstring.

    Списком, а не склейкой, и это существенно. После разбора у литерала
    больше нет кавычек вокруг, а прежние регулярки искали именно их:
    `'.card'` и `'--dry-run'` опознавались по кавычке перед точкой
    и после дефисов. Склей литералы в текст — и селектор в `main.py`
    стал бы неотличим от точки в середине фразы. Целый литерал строже
    любой кавычки: `.card` — это селектор ровно тогда, когда он и есть
    вся строка.

    Разбирается синтаксическое дерево, а не текст: комментариев в дереве
    нет вовсе, и снимать их регуляркой (со всеми `#` внутри литералов)
    не приходится. Docstring — тоже литерал, но это проза: имена классов
    в шапке `main.py` и в пояснениях `body_scales.py` встречаются
    десятками, и считать их разметкой значит вернуть ровно ту болезнь,
    которую правка лечит.

    Литералы нужны целиком: в `main.py` внутри строк лежат страницы
    (`STATIC_PAGES`) с настоящими `class="…"`, а в скриптах — селекторы
    вида `querySelector('.card')`. Это использование, а не проза.

    Файл, который не разбирается, пропускается молча — но не тихо:
    считать его прозой целиком было бы неверно, а падать посреди сверки
    документации из-за чужого синтаксиса незачем."""
    куски = []
    for кусок in текст.split(РАЗДЕЛИТЕЛЬ):
        try:
            дерево = ast.parse(кусок)
        except SyntaxError:
            continue
        проза = set()
        for узел in ast.walk(дерево):
            тело = getattr(узел, 'body', None)
            if not isinstance(узел, (ast.Module, ast.ClassDef,
                                     ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if (тело and isinstance(тело[0], ast.Expr)
                    and isinstance(тело[0].value, ast.Constant)
                    and isinstance(тело[0].value.value, str)):
                проза.add(id(тело[0].value))
        for узел in ast.walk(дерево):
            if (isinstance(узел, ast.Constant) and isinstance(узел.value, str)
                    and id(узел) not in проза):
                куски.append(узел.value)
    return куски


# Файлы склеиваются в одну строку, а разбирать Python надо пофайлово:
# склейка двух модулей может не быть синтаксически верной. Разделитель
# ставится при чтении и режет обратно перед `ast.parse`.
РАЗДЕЛИТЕЛЬ = "\n# ─── следующий файл ───\n"


# Ставится только меркой ниже: она считает, сколько имён оживлял
# собственный список исключений, и для этого ей нужен прежний вход.
_БЕЗ_СЕБЯ = False


def читать_py():
    """*.py в корне, ПОМИНУТНО check_docs.py.

    Себя проверка не читает, и это не мелочь: её собственный словарь
    `ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ` — это строковые литералы, то есть по любому
    разбору «настоящий код». Замер 2026-08-19: девять токенов из списка
    (`--grad-btn`, `--max-w`, `--shadow-glow` и другие) считались
    существующими ИМЕННО потому, что названы здесь как несуществующие.
    Список исключений оживлял сам себя, и удалить оттуда строку значило
    бы получить находку на ровном месте."""
    куски = []
    for путь in sorted(КОРЕНЬ.glob('*.py')):
        if путь.name == pathlib.Path(__file__).name:
            continue
        куски.append(путь.read_text(encoding='utf-8'))
    return РАЗДЕЛИТЕЛЬ.join(куски)


def блоки(текст):
    """Кодовые блоки: (язык, тело, номер строки открывающей ограды)."""
    результат, строки, i = [], текст.split('\n'), 0
    while i < len(строки):
        m = re.match(r'^\s*```(\w*)', строки[i])
        if m:
            язык, начало, буфер = m.group(1), i + 1, []
            i += 1
            while i < len(строки) and not re.match(r'^\s*```\s*$', строки[i]):
                буфер.append(строки[i])
                i += 1
            результат.append((язык, '\n'.join(буфер), начало))
        i += 1
    return результат


def собрать_известное(чисто=True):
    """Что в коде существует: классы и токены.

    `чисто=False` — ПРЕЖНЕЕ поведение, до задачи 99: файлы читаются
    плоским текстом, и всё, названное в комментарии или в docstring,
    считается существующим. Оставлено ровно для мерки (`--мерка` ниже):
    разница двух прогонов и есть та ложь, которую сняла правка.

    Второй реализации тут нет — регулярки одни и те же, отличается
    только вход. Развести их значило бы завести две копии, которые
    разойдутся молча, — ту самую болезнь, ради которой весь §6.0.2.
    """
    if чисто:
        css = _css_код(читать('static/*.css'))
        js = _js_код(читать('static/*.js'))
        # Внутри литералов `main.py` лежат целые страницы (`STATIC_PAGES`)
        # с настоящими `class="…"` — их ищем в тексте литералов…
        литералы = _py_литералы(читать_py())
        разметка = _html_код(читать('templates/*.html')) + "\n" + "\n".join(литералы)
    else:
        css = читать('static/*.css')
        js = читать('static/*.js')
        свои = ('check_docs.py',) if _БЕЗ_СЕБЯ else ()
        сырой_py = читать('*.py', кроме=свои)
        литералы = []
        разметка = читать('templates/*.html') + "\n" + сырой_py

    # класс считается объявленным, если встретился в позиции селектора
    объявлены = set(re.findall(r'\.([a-zA-Z][a-zA-Z0-9_-]*)(?=[\s,{:.\[>+~)])', css))
    # и использованным, если встретился в разметке или в скрипте
    использованы = set()
    for значение in re.findall(r'class="([^"]*)"', разметка):
        for слово in re.split(r'[\s{}%]+', значение):
            if re.fullmatch(r'[a-zA-Z][a-zA-Z0-9_-]*', слово or ''):
                использованы.add(слово)
    всё = css + "\n" + js + "\n" + разметка
    использованы |= set(re.findall(r"classList\.[a-zA-Z]+\(\s*'([a-zA-Z][a-zA-Z0-9_-]*)'", всё))
    использованы |= set(re.findall(r"['\"]\.([a-zA-Z][a-zA-Z0-9_-]*)['\"]",
                                   css + "\n" + js if чисто else всё))
    # …а селектор — это ЦЕЛЫЙ литерал `.имя`, и ничто другое
    использованы |= {л[1:] for л in литералы
                     if re.fullmatch(r'\.[a-zA-Z][a-zA-Z0-9_-]*', л)}

    # Токен считается существующим в трёх случаях, а не в одном:
    #   объявлен в CSS      --x: значение
    #   прочитан из CSS     var(--x, запасное)   — так живёт --assistant-top,
    #                       которому значение пишет скрипт, а не файл
    #   записан скриптом    setProperty('--x', …)
    токены = set(re.findall(r'(--[a-z0-9-]+)\s*:', css))
    токены |= set(re.findall(r'var\(\s*(--[a-z0-9-]+)', css))
    токены |= set(re.findall(r"setProperty\(\s*['\"](--[a-z0-9-]+)['\"]", js + разметка))

    # Флаг командной строки — не токен. Отличаются они не формой, а тем,
    # что флаг разбирает Python: --dry-run из dump_exercises.py попадал
    # в вывод как «несуществующий токен» ровно потому, что искали по форме.
    флаги = ({л for л in литералы if re.fullmatch(r'--[a-z0-9-]+', л)} if чисто
             else set(re.findall(r"['\"](--[a-z0-9-]+)['\"]", сырой_py)))
    return объявлены | использованы, токены | флаги




def разобрать_root(текст):
    """{имя токена: значение} из первого блока :root { … }."""
    m = re.search(r':root\s*\{(.*?)\n\}', _css_код(текст), re.S)
    if not m:
        return {}
    пары = {}
    for имя, значение in re.findall(r'(--[a-z0-9-]+)\s*:\s*([^;]+);', m.group(1)):
        пары[имя] = ' '.join(значение.split())
    return пары


def скелет_документа(текст):
    """:root из ВСЕХ блоков ```css документа, объединённые.

    Именно объединение, а не первый попавшийся блок. Токены объявляются
    по разделам — поверхности в 1.1, отступы в 1.7, — и полный скелет §13
    идёт последним. Первая версия брала первый блок с `:root` и объявляла
    недостающими 53 токена из пятидесяти трёх: проверка нашла не документ,
    а собственную ошибку.
    """
    скелет = {}
    for язык, тело, _ in блоки(текст):
        if язык == 'css' and ':root' in тело:
            скелет.update(разобрать_root(тело))
    return скелет


def геометрия_кода():
    """{класс: {(ширина, высота)}} — только там, где ОБА размера заданы в px.

    Селектор берётся, только если он целиком `.имя` или `тег.имя`: у правила
    `.toggle .track::after` размер принадлежит дорожке, а не тумблеру, и
    приписывать 16×16 классу .toggle было бы враньём наоборот.
    """
    css = _css_код(читать('static/*.css'))
    размеры = {}
    for селектор, тело in re.findall(r'([^{}]+)\{([^{}]*)\}', css):
        ш = re.search(r'(?:^|;)\s*width\s*:\s*(\d+)px', тело)
        в = re.search(r'(?:^|;)\s*height\s*:\s*(\d+)px', тело)
        if not (ш and в):
            continue
        for часть in селектор.split(','):
            m = re.fullmatch(r'\s*[a-z]*\.([a-zA-Z][a-zA-Z0-9_-]*)\s*', часть)
            if m:
                размеры.setdefault(m.group(1), set()).add((int(ш.group(1)), int(в.group(1))))
    return размеры


def проза(текст):
    """Строки документа ВНЕ кодовых блоков: (номер, строка)."""
    внутри = False
    for номер, строка in enumerate(текст.split('\n'), 1):
        if строка.lstrip().startswith('```'):
            внутри = not внутри
            continue
        if not внутри:
            yield номер, строка


def сверить_токены(документ, текст):
    """Проход B: значения токенов и полнота скелета."""
    скелет = скелет_документа(текст)
    if not скелет:
        return []
    код = разобрать_root((КОРЕНЬ / 'static' / 'style.css').read_text(encoding='utf-8'))
    расхождения = []
    for имя, значение in sorted(скелет.items()):
        if имя not in код:
            расхождения.append((имя, 'в скелете есть, в :root style.css нет'))
        elif код[имя] != значение:
            расхождения.append((имя, '%s → в коде %s' % (значение, код[имя])))
    for имя in sorted(код):
        if имя not in скелет and имя not in ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ:
            расхождения.append((имя, 'объявлен в :root, но скелет его не называет'))
    return расхождения


def сверить_геометрию(текст, размеры_кода):
    """Проход C: «36×36» на строке, где назван класс."""
    расхождения = []
    for номер, строка in проза(текст):
        пары = {(int(a), int(b))
                for a, b in re.findall(r'(?<!\d)(\d{1,3})\s*×\s*(\d{1,3})(?!\d)', строка)}
        пары = {p for p in пары if max(p) <= ПОТОЛОК_ГЕОМЕТРИИ}
        if not пары:
            continue
        for кл in re.findall(r'`\.([a-zA-Z][a-zA-Z0-9_-]*)`', строка):
            если_есть = размеры_кода.get(кл)
            if если_есть and not (если_есть & пары):
                расхождения.append((
                    '.' + кл,
                    'строка %d: назван %s, в коде %s' % (
                        номер,
                        ' и '.join('%d×%d' % p for p in sorted(пары)),
                        ' и '.join('%d×%d' % p for p in sorted(если_есть)))))
    return расхождения


def сверить_пути(текст):
    """Проход D: имя файла в инлайновом спане — существует ли на диске.

    Только относительные пути: `/app/make_backup.py` и `/data/app.db` живут
    на машине Fly, а не здесь, и проверять их нечем.

    Имя без каталога (`hh.css`, `_header.html`) документ пишет постоянно
    и это не небрежность: каталог там ясен из абзаца. Поэтому такое имя
    ищется по всему дереву, а путь с косой чертой — ровно по нему.
    """
    расхождения, виденные = [], set()
    for номер, строка in проза(текст):
        for спан in re.findall(r'`([^`]+)`', строка):
            спан = спан.strip()
            if not re.fullmatch(r'[A-Za-z0-9_./-]+\.(css|js|py|html|md|json|toml|yml|svg)', спан):
                continue
            if спан.startswith('/') or спан in ИЗВЕСТНЫЕ_ФАЙЛЫ or спан in виденные:
                continue
            виденные.add(спан)
            если_есть = ((КОРЕНЬ / спан).exists() if '/' in спан
                         else any(КОРЕНЬ.glob('**/' + спан)))
            if not если_есть:
                расхождения.append((спан, 'строка %d: файла нет' % номер))
    return расхождения


def классы_с_правилом():
    """Классы, у которых в static/*.css ЕСТЬ ПРАВИЛО, а не только имя.

    ПРОХОД E, заведён 2026-08-21. Проход A считает имя существующим,
    если оно встретилось в коде ХОТЬ ГДЕ — в том числе в разметке.
    Для ссылки в прозе этого довольно, а для КОМПОНЕНТА — нет: задача 115
    описала `.empty-state` разделом в `design-system.md`, расставила класс
    по 32 местам в семи шаблонах и НЕ НАПИСАЛА НИ ОДНОГО ПРАВИЛА в CSS.
    Проход A промолчал по построению: имя в разметке есть.

    Снаружи это выглядело так: у пустого приёма пищи пропали
    центрирование, весь вертикальный воздух и половина высоты
    (53 → 26 px), у пустой таблицы админки — 47 % высоты, у пустого
    экрана HH плитка значка стала 32×32 без фона и рамки.
    """
    имена = set()
    for файл in (КОРЕНЬ / 'static').glob('*.css'):
        текст = re.sub(r'/\*.*?\*/', '', файл.read_text(encoding='utf-8'),
                       flags=re.S)
        for сел, _ in re.findall(r'([^{}]+)\{([^{}]*)\}', текст):
            if сел.strip().startswith('@'):
                continue
            имена.update(re.findall(r'\.([a-zA-Z][a-zA-Z0-9_-]*)', сел))
    return имена


def объявленные_в_документе(текст):
    """Классы, которые документ объявляет ПРАВИЛОМ: `.имя … { … }`.

    Не всякое имя в css-блоке: только субъект правила. Упоминание
    `.card` внутри чужого селектора описывает контекст, а не заводит
    компонент, и требовать правило для него было бы ложной тревогой.
    """
    имена = set()
    for язык, тело, номер in блоки(текст):
        if язык != 'css':
            continue
        for строка in тело.splitlines():
            m = re.match(r'\s*\.([a-zA-Z][a-zA-Z0-9_-]*)'
                         r'(?:[.:][a-zA-Z0-9_-]+|\([^)]*\))*\s*[,{]', строка)
            if m:
                имена.add((m.group(1), номер))
    return имена


def сверить_объявленные(текст, с_правилом):
    """ПРОХОД E: документ объявил компонент — в CSS обязано быть правило."""
    расхождения = []
    for имя, номер in sorted(объявленные_в_документе(текст)):
        if имя in с_правилом or имя in ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ:
            continue
        расхождения.append((имя, 'объявлен правилом в документе (строка %d), '
                                 'а в static/*.css правила НЕТ' % номер))
    return расхождения


def проверить(документ, классы_кода, токены_кода):
    текст = (КОРЕНЬ / документ).read_text(encoding='utf-8')
    строки = текст.split('\n')
    найдено = {}

    def запомнить(имя, строка):
        найдено.setdefault(имя, []).append(строка)

    for язык, тело, номер in блоки(текст):
        if язык == 'css':
            for кл in re.findall(r'\.([a-zA-Z][a-zA-Z0-9_-]*)(?=[\s,{:.\[)]|$)', тело):
                запомнить(кл, номер)
        if язык in ('html', 'jinja'):
            for значение in re.findall(r'class="([^"]*)"', тело):
                for слово in значение.split():
                    if re.fullmatch(r'[a-zA-Z][a-zA-Z0-9_-]*', слово):
                        запомнить(слово, номер)
        if язык in ('css', 'html', 'jinja'):
            for т in re.findall(r'(--[a-z0-9-]+)', тело):
                запомнить(т, номер)

    # инлайновые спаны в прозе — именно там жил мёртвый .modal
    внутри_блока = False
    for номер, строка in enumerate(строки, 1):
        if строка.lstrip().startswith('```'):
            внутри_блока = not внутри_блока
            continue
        if внутри_блока:
            continue
        for спан in re.findall(r'`([^`]+)`', строка):
            спан = спан.strip()
            m = re.fullmatch(r'\.([a-zA-Z][a-zA-Z0-9_-]*)', спан)
            if m:
                запомнить(m.group(1), номер)
            m = re.fullmatch(r'(--[a-z0-9-]+)', спан)
            if m:
                запомнить(m.group(1), номер)

    расхождения = []
    for имя, где in sorted(найдено.items()):
        если_токен = имя.startswith('--')
        есть = имя in (токены_кода if если_токен else классы_кода)
        if есть or имя in ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ:
            continue
        расхождения.append((имя, где[:5]))
    return расхождения


def мерка_исключений():
    """Сколько имён из `ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ` код считает существующими —
    и сколько из них считались бы существующими ТОЛЬКО из-за прозы.

    Печатается всегда и командой, а не лежит числом в тексте
    (CLAUDE.md §6.0.4). Второе число — прямая мерка задачи 99: пока
    сборщик читал файлы плоским текстом, оно равнялось 29 из 61,
    то есть почти половина списка «жила» комментариями о собственной
    смерти. Уедет оно обратно вверх — значит кто-то вернул грепу
    неочищенный вход.

    Первое число — про ОБРАТНУЮ сторону, которая проверкой пока
    не закрыта: имя, названное в документе удалённым, а в коде живое.
    Разбор, почему не закрыта, — в шапке файла.

    ПРИЧИН ОЖИВЛЕНИЯ БЫЛО ДВЕ, и одно число их смешивало, поэтому
    считаются они врозь:

      проза       имя стоит в комментарии CSS/JS/HTML или в docstring —
                  «.save-btn здесь больше нет» объявляло `.save-btn`
                  живым классом;
      свой список сам этот файл попадал под `читать('*.py')`, и строка
                  `'--grad-btn': 'legacy-словарь §11'` объявляла токен
                  существующим. Список исключений оживлял себя сам:
                  строку из него нельзя было удалить, не получив
                  находку на ровном месте.
    """
    классы, токены = собрать_известное(чисто=True)
    сырые = собрать_известное(чисто=False)
    global _БЕЗ_СЕБЯ
    _БЕЗ_СЕБЯ = True
    try:
        сырые_без_себя = собрать_известное(чисто=False)
    finally:
        _БЕЗ_СЕБЯ = False

    def жив(имя, пара):
        к, т = пара
        return имя in (т if имя.startswith('--') else к)

    живых = sum(жив(и, (классы, токены)) for и in ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ)
    от_прозы = sum(жив(и, сырые_без_себя) for и in ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ) - живых
    от_себя = (sum(жив(и, сырые) for и in ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ)
               - sum(жив(и, сырые_без_себя) for и in ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ))
    return живых, от_прозы, от_себя


def контроль():
    """Отрицательный контроль: проверка обязана НЕ считать прозу кодом.

    Без него «0 расхождений» ничего не значит — ровно тот же ноль
    печатала версия, которая считала живым любое имя из комментария
    (CLAUDE.md §6.0.3, «у проверки обязан быть отрицательный контроль»).

    Проверяется каждый разбор ОТДЕЛЬНО и в обе стороны: имя из
    комментария пропасть обязано, имя из настоящего кода — остаться.
    Проверка «пропало» в одиночку прошла бы и на разборе, который
    выбрасывает вообще всё.
    """
    случаи = [
        ('CSS', _css_код,
         '/* .ghost-css здесь больше нет */\n.real-css { color: red }',
         'ghost-css', 'real-css'),
        ('JS', _js_код,
         '// .ghost-js удалён\n/* и .ghost-js2 тоже */\n'
         "el.querySelector('.real-js');",
         'ghost-js', 'real-js'),
        ('HTML', _html_код,
         '<!-- <div class="ghost-html"> когда-то было -->\n'
         '<div class="real-html"></div>',
         'ghost-html', 'real-html'),
    ]
    беды = []
    for имя, разбор, вход, призрак, живой in случаи:
        вышло = разбор(вход)
        if призрак in вышло:
            беды.append(f'{имя}: комментарий не снят — «{призрак}» остался')
        if живой not in вышло:
            беды.append(f'{имя}: разбор съел настоящий код — «{живой}» пропал')

    исходник = ('"""Шапка про .ghost-doc — это проза."""\n'
                '# и .ghost-comment тоже\n'
                'ПУТЬ = ".real-literal"\n'
                'def f():\n'
                '    """И тут .ghost-doc2."""\n'
                '    return "--real-flag"\n')
    литералы = _py_литералы(исходник)
    for призрак in ('.ghost-doc', '.ghost-comment', '.ghost-doc2'):
        if any(призрак in л for л in литералы):
            беды.append(f'Python: «{призрак}» уцелел — это docstring или комментарий')
    for живой in ('.real-literal', '--real-flag'):
        if живой not in литералы:
            беды.append(f'Python: «{живой}» пропал — это настоящий литерал')

    # Третья форма оживления: проверка читает СЕБЯ, и её собственный
    # список исключений объявляет мёртвые имена существующими
    # Маркер — строка, которая есть ТОЛЬКО в этом файле. Искать имя файла
    # нельзя: его упоминает check_metrics.py, и контроль срабатывал бы
    # на честном дереве — то есть врал бы ровно так же, как проверка,
    # которую он сторожит
    if 'ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ = {' in читать_py():
        беды.append('check_docs читает сам себя — список исключений оживляет себя')

    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ (задача 99)")
    for случай in случаи:
        print(f"   {случай[0]:<5} комментарий снят, код цел")
    print("   PY    docstring и # сняты, литералы целы")
    print("   SELF  собственный файл в источники не входит")
    if беды:
        print("\nНЕ ПРОЙДЕН:")
        for б in беды:
            print("   ·", б)
        return 1
    живых, от_прозы, от_себя = мерка_исключений()
    print(f"\nПройден. Мерка на текущем дереве: имён {len(ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ)}, "
          f"живых по-настоящему {живых}, ожило бы прозой {от_прозы}, "
          f"собственным списком {от_себя}")
    return 0



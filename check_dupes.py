# -*- coding: utf-8 -*-
"""ДУБЛИ ВНЕ ПЕРЕПИСИ — правила, совпавшие ТЕЛОМ при разных селекторах.

═══════════════════════════════════════════════════════════════════════
ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ РАЗОВЫМ ОБХОДОМ
═══════════════════════════════════════════════════════════════════════

Задача 126 нашла 26 групп дублей с видом на 61 месте и записала мерку
словами: «прогон того же признака обязан дать меньше 26 групп». Прогонять
было НЕЧЕМ: признак жил разовым скриптом, которого в репозитории нет.
Ровно тот же случай, что с пиксельным дифом, — инструмент существовал
один заход, а число из него переехало в текст и стало неопровержимым.

Здесь он лежит в репозитории, и мерка печатается командой (§6.0.4).

═══════════════════════════════════════════════════════════════════════
ПРИЗНАК: ТЕЛО, А НЕ ИМЯ
═══════════════════════════════════════════════════════════════════════

Два правила — дубль, если совпадает МНОЖЕСТВО объявлений
(свойство: значение) и в нём не меньше трёх штук, а селекторы разные.
Три — порог осмысленности: пара `display:flex; gap:8px` совпадает
у половины проекта и компонентом не является.

РАЗДЕЛЕНИЕ ОБЯЗАТЕЛЬНО, ИНАЧЕ ЧИСЛО НИЧЕГО НЕ ЗНАЧИТ. Совпавшее тело
из одних раскладочных свойств — не дублированный компонент, а один
и тот же идиом ряда; сводить его в утилитарный класс значило бы менять
архитектуру, а не убирать долг.

Признак разделения НЕ ИЗОБРЕТАЕТСЯ ЗДЕСЬ: берётся `check_ids.РАСКЛАДКА`,
тот же, которым проверка 8 отделяет законную строку от долга, а
`check_metrics` — раскладку экземпляра от переопределения. Вторая
реализация разошлась бы молча (§6.0.7).

═══════════════════════════════════════════════════════════════════════
ЧТО НЕ СЧИТАЕТСЯ
═══════════════════════════════════════════════════════════════════════

  · демо-страницы §6.0.2 — решение владельца, BACKLOG №27;
  · `templates/enshrouded.html` — раздел живёт мимо системы целиком
    (BACKLOG №2, №38, №45), и сводить его правила к системным нельзя,
    пока он не переписан;
  · комментарии — снимаются РАЗБОРОМ по языкам, а не одной регуляркой
    поверх файла: `/*` внутри `accept="image/*"` съел бы 165 000 знаков
    шаблона (задача 18).

═══════════════════════════════════════════════════════════════════════
ЗАПУСК
═══════════════════════════════════════════════════════════════════════

    py check_dupes.py               # срез: группы, места, разбивка
    py check_dupes.py --контроль    # признак обязан различать две кучи

Код возврата — ВСЕГДА 0: это МЕРКА, а не проверка. Понятия «правильно»
у неё нет — сколько дублей допустимо, решает владелец, а не скрипт
(тот же случай, что у `check_metrics` и `check_load`).
"""
import glob
import io
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")

import check_docs                      # noqa: E402  — разбор по языкам
import check_ids                       # noqa: E402  — признак раскладки
import project_lists as списки         # noqa: E402  — список демо-страниц

МИН_ОБЪЯВЛЕНИЙ = 3

# Enshrouded: не демо, но и не под системой. Причина строкой — список
# без причин за полгода превращается в свалку (§6.0.7).
ВНЕ_СИСТЕМЫ = {
    "templates/enshrouded.html":
        "раздел живёт мимо дизайн-системы целиком (BACKLOG №2, №38, №45); "
        "сводить его правила к системным нельзя до переписывания",
}


def _файлы():
    пути = sorted(glob.glob("static/*.css")) + sorted(glob.glob("templates/*.html"))
    демо = {п.replace("\\", "/") for п in списки.исключённые_страницы()}
    итог = []
    for п in пути:
        н = п.replace("\\", "/")
        if н in демо or н in ВНЕ_СИСТЕМЫ:
            continue
        итог.append(н)
    return итог


def _css_из(путь):
    """Текст стилей файла БЕЗ комментариев. Разбор по языку, не регулярка."""
    текст = io.open(путь, encoding="utf-8").read()
    if путь.endswith(".html"):
        куски = re.findall(r"<style[^>]*>(.*?)</style>", текст, re.S)
        текст = "\n".join(куски)
    return check_docs._css_код(текст) if текст.strip() else ""


def _правила(путь):
    """[(строка, селектор, {свойство: значение})] — плоские правила файла.

    Вложенные блоки (`@media`, `@supports`) раскрываются тем, что внешний
    селектор в них не совпадает ни с чем: берутся только тела без скобок.
    """
    css = _css_из(путь)
    итог = []
    for м in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        сел = " ".join(м.group(1).split())
        if not сел or сел.startswith("@") or "@" in сел[:1]:
            continue
        тело = {}
        for об in м.group(2).split(";"):
            if ":" not in об:
                continue
            имя, _, знач = об.partition(":")
            имя, знач = имя.strip().lower(), " ".join(знач.split())
            if имя and знач:
                тело[имя] = знач
        if len(тело) >= МИН_ОБЪЯВЛЕНИЙ:
            строка = css[:м.start()].count("\n") + 1
            итог.append((строка, сел, тело))
    return итог


def _только_раскладка(тело):
    """Идиом ряда: все свойства — про место элемента, ни одного про вид.

    Признак ТОТ ЖЕ, что у проверки 8: `check_ids.РАСКЛАДКА`. Переменные
    (`--x`) к виду не относятся — это ручки, а не оформление.
    """
    вид = [с for с in тело
           if s_не_раскладка(с)]
    return not вид


def s_не_раскладка(свойство):
    return свойство not in check_ids.РАСКЛАДКА and not свойство.startswith("--")


def собрать():
    """{отпечаток_тела: [(файл, строка, селектор, тело)]} — только группы."""
    все = []
    for путь in _файлы():
        for строка, сел, тело in _правила(путь):
            все.append((путь, строка, сел, тело))
    по_телу = {}
    for путь, строка, сел, тело in все:
        ключ = tuple(sorted(тело.items()))
        по_телу.setdefault(ключ, []).append((путь, строка, сел, тело))
    группы = []
    for ключ, места in по_телу.items():
        селекторы = {с for _, _, с, _ in места}
        if len(места) < 2 or len(селекторы) < 2:
            continue
        группы.append((ключ, места))
    return len(все), группы


def главная():
    правил, группы = собрать()
    раскладка = [г for г in группы if _только_раскладка(dict(г[0]))]
    с_видом = [г for г in группы if not _только_раскладка(dict(г[0]))]
    мест = sum(len(м) for _, м in с_видом)

    print("=" * 70)
    print("ДУБЛИ ВНЕ ПЕРЕПИСИ — правила, совпавшие ТЕЛОМ при разных селекторах")
    print("=" * 70)
    print(f"  правил с {МИН_ОБЪЯВЛЕНИЙ}+ объявлениями:        {правил}")
    print(f"  групп с совпавшим телом:          {len(группы)}")
    print(f"  — идиом раскладки (сводить НЕЛЬЗЯ): {len(раскладка)}")
    print(f"  — ДУБЛЕЙ С ВИДОМ:                   {len(с_видом)}, мест {мест}")
    print()
    print("  способ: тело — множество (свойство: значение); дубль — совпавшее")
    print("          тело при РАЗНЫХ селекторах. Раскладку от вида отделяет")
    print("          check_ids.РАСКЛАДКА — тот же признак, что у проверки 8")
    print()
    for ключ, места in sorted(с_видом, key=lambda г: -len(г[1])):
        тело = dict(ключ)
        вид = sorted(с for с in тело if s_не_раскладка(с))
        print(f"  {len(места)} мест · вид: {', '.join(вид)}")
        for путь, строка, сел, _ in места:
            print(f"        {путь}:{строка}  {сел[:64]}")
    return 0


def контроль():
    """Признак обязан РАЗЛИЧАТЬ две кучи, а не просто что-то печатать.

    Проверка «нашлось» в одиночку прошла бы и на признаке, который
    объявляет дублем всё подряд. Поэтому обе стороны: подложенная пара
    с ВИДОМ обязана попасть в дубли, подложенная пара из одной
    РАСКЛАДКИ — в идиомы, а пара с одинаковым селектором — никуда.
    """
    проба = "static/__контроль_дублей.css"
    io.open(проба, "w", encoding="utf-8").write(
        ".контроль-вид-а { background: #123456; border: 1px solid #654321;"
        " font-size: 0.8125rem; }\n"
        ".контроль-вид-б { background: #123456; border: 1px solid #654321;"
        " font-size: 0.8125rem; }\n"
        ".контроль-ряд-а { display: flex; gap: 8px; align-items: center; }\n"
        ".контроль-ряд-б { display: flex; gap: 8px; align-items: center; }\n"
        ".контроль-один { color: red; padding: 1px; margin: 2px; }\n")
    try:
        _, группы = собрать()
        вид = [г for г in группы if not _только_раскладка(dict(г[0]))]
        ряд = [г for г in группы if _только_раскладка(dict(г[0]))]
        нашли_вид = any("контроль-вид" in с for _, м in вид for _, _, с, _ in м)
        нашли_ряд = any("контроль-ряд" in с for _, м in ряд for _, _, с, _ in м)
        одиночка = any("контроль-один" in с
                       for _, м in группы for _, _, с, _ in м)
        print("  подлог «пара с ВИДОМ»:      %s" %
              ("НАЙДЕН в дублях" if нашли_вид else "ПРОПУЩЕН"))
        print("  подлог «пара РАСКЛАДКИ»:    %s" %
              ("отнесён к идиомам" if нашли_ряд else "ПОПАЛ НЕ ТУДА"))
        print("  одиночное правило:          %s" %
              ("ПОПАЛО В ГРУППУ — признак врёт" if одиночка else "не в группах"))
        плохо = (not нашли_вид) + (not нашли_ряд) + bool(одиночка)
    finally:
        os.remove(проба)
    print("\n%s" % ("КОНТРОЛЬ ПРОЙДЕН" if not плохо else "КОНТРОЛЬ ПРОВАЛЕН"))
    return 0 if not плохо else 1


if __name__ == "__main__":
    sys.exit(контроль() if "--контроль" in sys.argv else главная())

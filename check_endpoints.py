"""Опись ВСЕХ эндпоинтов приложения: путь, метод, пишет ли, чем защищён.

ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ, А НЕ ГРЕП. Греп по декораторам `@app.post` видит
только то, что зарегистрировано декоратором в `main.py`. Мимо него проходят
маршруты, добавленные иначе: `app.mount`, `add_api_route`, роутеры, а также
служебные `/docs`, `/openapi.json`, которые FastAPI заводит сам. Разница
между двумя способами счёта — не мелочь: именно в ней прячется эндпоинт,
о котором никто не помнит, а он принимает запросы.

Источником правды здесь является `app.routes` — то, что приложение
действительно обслуживает. Греп считается вторым числом и печатается
рядом: разошлись — значит что-то регистрируется мимо декоратора,
и это надо посмотреть глазами, а не выбирать меньшее число молча.

ЧТО СКРИПТ НЕ УМЕЕТ (границы названы, чтобы им не доверяли больше, чем он
заслуживает):

  • «пишет ли данные» для GET определяется разбором тела на `db.add`,
    `db.commit`, присваивание полю модели. Запись через вызов вспомогательной
    функции (`_purge_deleted_letters(db)`) отсюда не видна — такие места
    перечислены в ЗАПИСЬ_ЧЕРЕЗ_ВЫЗОВ поимённо;
  • проверка доступа опознаётся по зависимостям и по обращениям в теле.
    Проверка, спрятанная в вызываемую функцию, видна не будет —
    поэтому `_verification_gate` внесён в разбор явно;
  • динамические маршруты (`/{slug}`) считаются одной строкой, как они
    и зарегистрированы.

Запуск:  py check_endpoints.py            — таблица целиком
         py check_endpoints.py --csv      — то же в CSV
         py check_endpoints.py --lists    — только три списка §1.1
Код возврата: 0 — эндпоинтов записи без проверки is_verified нет;
              1 — есть, они перечислены.
"""

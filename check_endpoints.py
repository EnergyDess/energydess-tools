# ── Разбор main.py: тело каждого обработчика ────────────────────────────────

class Обходчик(ast.NodeVisitor):
    """Собирает по каждой функции-обработчику: зависимости и признаки проверок."""

    def __init__(self):
        self.функции = {}   # имя -> словарь признаков

    def visit_FunctionDef(self, node):
        self._разобрать(node)
        self.generic_visit(node)

    def visit_AsyncFunctionDef(self, node):
        self._разобрать(node)
        self.generic_visit(node)

    def _разобрать(self, node):
        зависимости = set()
        for арг in list(node.args.args) + list(node.args.kwonlyargs):
            pass
        # Depends(...) стоит в значениях по умолчанию
        for умолч in list(node.args.defaults) + list(node.args.kw_defaults):
            if умолч is None:
                continue
            for под in ast.walk(умолч):
                if isinstance(под, ast.Call) and getattr(под.func, 'id', '') == 'Depends':
                    if под.args:
                        зависимости.add(ast.unparse(под.args[0]))

        # ast.unparse даёт КОД без комментариев — и это здесь принципиально.
        # Греп по исходнику принимал за проверку роли фразу из комментария
        # «Исключений по is_admin нет и быть не должно» в отдаче медиа
        # и объявлял защищённым ровно тот эндпоинт, где такой ветки нет
        # по замыслу (CLAUDE.md §5.1). Docstring узлом кода остаётся,
        # поэтому его вырезаем отдельно.
        тело_без_docstring = list(node.body)
        if (тело_без_docstring and isinstance(тело_без_docstring[0], ast.Expr)
                and isinstance(тело_без_docstring[0].value, ast.Constant)
                and isinstance(тело_без_docstring[0].value.value, str)):
            тело_без_docstring = тело_без_docstring[1:]
        текст = '\n'.join(ast.unparse(у) for у in тело_без_docstring) or ''

        # ЧТЕНИЕ атрибута is_admin — это проверка роли. ПРИСВАИВАНИЕ
        # (`is_admin=is_first` при регистрации первого аккаунта) проверкой
        # не является, а прежний детектор считал их одним и тем же.
        читает_is_admin = any(
            isinstance(у, ast.Attribute) and у.attr == 'is_admin'
            and isinstance(у.ctx, ast.Load)
            for у in ast.walk(node))

        признаки = {
            'зависимости': зависимости,
            # аутентификация
            'есть_user': any('get_current_user' in з for з in зависимости),
            'проверяет_user': bool(re.search(r'\bif not user\b|\buser is None\b', текст)),
            # роль: либо своими руками, либо общей заставой админки
            'проверяет_админа': читает_is_admin or '_admin_guard' in текст,
            # подтверждение почты
            'проверяет_verified': bool(re.search(r'\bis_verified\b', текст)),
            'зовёт_гейт': '_verification_gate' in текст,
            'зависит_от_проверенного': any('проверенный_пользователь' in з or
                                           'require_verified' in з for з in зависимости),
            # Принадлежность записи спрашивающему — проверка из §5.1.
            # ОБЕ формы сравнения, и это не педантизм: первая версия искала
            # только `==`, а в коде стоит отказ по `!=` («не совпало — 404»),
            # и детектор объявил незащищёнными ровно те два эндпоинта,
            # которые защищены образцово: /media и /avatar. Три ложных
            # срабатывания из трёх — проверка, которую после такого
            # перестают читать вовсе.
            'проверяет_владельца': bool(re.search(
                r'user_id\s*[!=]=\s*user\.id|user\.id\s*[!=]=\s*\w+\.user_id|'
                r'user_id\s*[!=]=\s*user_id|user\.id\s*[!=]=\s*user_id|'
                r'user_id=user\.id', текст)),
            # секрет в заголовке — тоже проверка доступа, просто не по сессии
            'проверяет_секрет': bool(re.search(
                r'headers\.get\(["\']X-[\w-]+|DEPLOY_SECRET|require_agent_key', текст)),
            # запись
            'пишет_в_теле': bool(re.search(r'db\.add\(|db\.commit\(|db\.delete\(|db\.merge\(', текст)),
            'строка': node.lineno,
        }
        self.функции[node.name] = признаки


def разобрать_исходник():
    дерево = ast.parse(io.open(ФАЙЛ, encoding='utf-8').read())
    о = Обходчик()
    о.visit(дерево)
    return о.функции


def грепом():
    """Второе число: сколько маршрутов видно грепом по декораторам."""
    текст = io.open(ФАЙЛ, encoding='utf-8').read()
    return len(re.findall(r'^@app\.(get|post|put|patch|delete)\(', текст, re.M))


def разбор_расхождения(строки):
    """ПОЧЕМУ два способа счёта дают разные числа — поимённо, а не разницей.

    Меньшее число выбирать молча нельзя: в разнице сидят настоящие
    эндпоинты, которых греп не видит, и один из них принимает POST
    без аутентификации.
    """
    служебные = [с for с in строки if с['служебный'] or с['метод'] == '(mount)']
    через_api_route = [с for с in строки
                       if с['путь'] in ('/health', '/botamin', '/robots.txt')]
    из_роутера = [с for с in строки if с['путь'].startswith('/api/agent/')]
    return {
        'служебные FastAPI и mount': служебные,
        '@app.api_route вместо @app.get': через_api_route,
        'APIRouter через include_router': из_роутера,
    }


def гейт_исключён(main, путь: str, метод: str) -> bool:
    """Закрыт ли путь гейтом — СПРАШИВАЕМ У ПРИЛОЖЕНИЯ, а не у своей копии.

    Шаблон маршрута (`/verify/{token}`) приводится к образцу фактического
    пути, потому что middleware сравнивает именно фактический.
    """
    if метод not in main.ГЕЙТ_МЕТОДЫ:
        return True   # гейт не про этот метод
    образец = re.sub(r'\{[^}]+\}', 'x', путь)
    return main._гейт_путь_исключён(образец)


def собрать():
    os.environ.setdefault('DB_PATH', 'app.db')
    import main  # noqa: E402  — импорт после настройки окружения
    функции = разобрать_исходник()

    строки = []
    for маршрут in main.app.routes:
        путь = getattr(маршрут, 'path', None)
        if путь is None:
            continue
        методы = getattr(маршрут, 'methods', None)
        имя_обработчика = getattr(getattr(маршрут, 'endpoint', None), '__name__', '')
        if методы is None:
            # Mount (например, /static) — метода нет, обслуживает все
            строки.append({
                'путь': путь, 'метод': '(mount)', 'обработчик': имя_обработчика or '—',
                'пишет': 'нет', 'доступ': 'никакой (статика)',
                'раздел': 'Статика', 'служебный': True,
            })
            continue
        # Зависимости УРОВНЯ РОУТЕРА: у APIRouter(dependencies=[...]) защита
        # стоит на всей группе, а в самом обработчике её не видно. Так
        # `/api/agent/*` выглядели незащищёнными, хотя закрыты ключом агента.
        зависимости_роутера = set()
        for з in (getattr(маршрут, 'dependencies', None) or []):
            вызов = getattr(з, 'dependency', None)
            if вызов is not None:
                зависимости_роутера.add(getattr(вызов, '__name__', str(вызов)))

        for метод in sorted(методы - {'HEAD', 'OPTIONS'}):
            п = функции.get(имя_обработчика, {})
            служебный = путь in СЛУЖЕБНЫЕ

            # ── пишет ли данные ──
            если_пишет = метод in ПИШУЩИЕ_МЕТОДЫ or п.get('пишет_в_теле')
            причина_записи = ''
            if (путь, метод) in ЗАПИСЬ_ЧЕРЕЗ_ВЫЗОВ:
                если_пишет = True
                причина_записи = ЗАПИСЬ_ЧЕРЕЗ_ВЫЗОВ[(путь, метод)]
            # Пишущий метод, который в базу не пишет: расход есть (внешний
            # вызов, деньги на модель), записи нет. Гейт таким нужен, но
            # смешивать их с записью в БД в одной графе — терять различие.
            в_базу = bool(п.get('пишет_в_теле')) or bool(причина_записи)

            # ── чем защищён ──
            защита = []
            if п.get('зависит_от_проверенного'):
                защита.append('is_verified (зависимостью)')
            if п.get('есть_user'):
                защита.append('аутентификация' if п.get('проверяет_user')
                              else 'аутентификация (не проверена в теле)')
            if п.get('проверяет_админа'):
                защита.append('роль админа')
            if п.get('проверяет_владельца'):
                защита.append('принадлежность записи')
            if п.get('проверяет_секрет') or зависимости_роутера:
                секрет = ', '.join(sorted(зависимости_роутера)) or 'секрет в заголовке'
                защита.append(f'ключ/секрет ({секрет})')
            if п.get('зовёт_гейт'):
                защита.append('is_verified (плашка на странице)')
            elif п.get('проверяет_verified') and not п.get('зависит_от_проверенного'):
                защита.append('is_verified (вручную в теле)')
            if not защита:
                защита.append('НИКАКОЙ' if not служебный else 'никакой (служебный)')

            # Закрыт ли гейтом — по факту, у самого приложения
            под_гейтом = (метод in main.ГЕЙТ_МЕТОДЫ
                          and not гейт_исключён(main, путь, метод))
            if под_гейтом:
                защита.insert(0, 'is_verified (гейт middleware)')

            строки.append({
                'путь': путь, 'метод': метод, 'обработчик': имя_обработчика or '—',
                'пишет': 'пишет' if если_пишет else 'читает',
                'в_базу': в_базу,
                'причина_записи': причина_записи,
                'доступ': ' + '.join(защита),
                'раздел': 'Служебное' if служебный else раздел(путь),
                'служебный': служебный,
                'под_гейтом': под_гейтом,
                'признаки': п,
            })
    строки.sort(key=lambda с: (с['раздел'], с['путь'], с['метод']))
    return строки


def главное():
    строки = собрать()
    только_списки = '--lists' in sys.argv

    if '--csv' in sys.argv:
        print('путь;метод;пишет/читает;проверка доступа;раздел;обработчик')
        for с in строки:
            print(f"{с['путь']};{с['метод']};{с['пишет']};{с['доступ']};"
                  f"{с['раздел']};{с['обработчик']}")
    elif not только_списки:
        текущий = None
        print(f'{"путь":<44}{"метод":<8}{"пишет?":<9}{"проверка доступа"}')
        print('─' * 118)
        for с in строки:
            if с['раздел'] != текущий:
                текущий = с['раздел']
                print(f'\n■ {текущий}')
            звёздочка = ' *' if с.get('причина_записи') else ''
            print(f"  {с['путь']:<42}{с['метод']:<8}{с['пишет']+звёздочка:<9}{с['доступ']}")
        print()
        for (п, м), причина in ЗАПИСЬ_ЧЕРЕЗ_ВЫЗОВ.items():
            print(f'  * {м} {п}: {причина}')

    # ── три списка §1.1 ──
    # ① ПРЕДМЕТ ЗАДАЧИ 24 — запись от имени вошедшего пользователя без гейта.
    #    Исключения названы поимённо (ГЕЙТ_НЕЛЬЗЯ), а не отфильтрованы молча:
    #    список, из которого что-то тихо выпало, через полгода печатает
    #    «чисто» про то, что никто не проверял.
    запись_без_verified = [с for с in строки
                           if с['пишет'] == 'пишет' and not с['служебный']
                           and с['метод'] in ПИШУЩИЕ_МЕТОДЫ
                           and 'is_verified' not in с['доступ']
                           and 'аутентификация' in с['доступ']
                           and с['путь'] not in ГЕЙТ_ПРИЧИНЫ]
    исключено = [с for с in строки if с['путь'] in ГЕЙТ_ПРИЧИНЫ]

    # Пишущие GET — отдельной строкой, а НЕ в списке ①. Гейт закрывает
    # только меняющие методы, и это его объявленная граница (§5.3):
    # считать GET находкой значит завести вечную ложную тревогу, после
    # которой код возврата перестают читать вовсе.
    пишущие_get = [с for с in строки
                   if с['метод'] == 'GET' and с['пишет'] == 'пишет'
                   and not с['служебный'] and с['путь'] not in ГЕЙТ_ПРИЧИНЫ]
    запись_без_auth = [с for с in строки
                       if с['пишет'] == 'пишет' and not с['служебный']
                       and 'аутентификация' not in с['доступ']
                       and 'ключ/секрет' not in с['доступ']]

    # ③ Чтение чужих данных без проверки принадлежности. Берутся только
    #    маршруты с параметром пути — то есть те, где спрашивающий НАЗЫВАЕТ
    #    запись. Без параметра выборка идёт по user.id и чужого вернуть
    #    не может по построению.
    чтение_чужого = [
        с for с in строки
        if с['пишет'] == 'читает' and not с['служебный']
        and re.search(r'\{[^}]+\}', с['путь'])
        and not с.get('признаки', {}).get('проверяет_владельца')
        and 'аутентификация' in с['доступ']
        and с['путь'] not in НЕ_ИДЕНТИФИКАТОР
    ]

    print('\n' + '═' * 118)
    служ = sum(1 for с in строки if с['служебный'] or с['метод'] == '(mount)')
    print(f'ВСЕГО СТРОК В ОПИСИ (обход app.routes): {len(строки)}   '
          f'(из них служебных/статики: {служ})')
    print(f'Второе число — греп по декораторам @app.<метод>: {грепом()}')
    print('\nРАСХОЖДЕНИЕ ДВУХ СПОСОБОВ РАЗЛОЖЕНО ПОИМЁННО:')
    итого = грепом()
    for причина, список in разбор_расхождения(строки).items():
        пути = ', '.join(sorted({f"{с['метод']} {с['путь']}" for с in список}))
        print(f'  +{len(список):<3} {причина}')
        print(f'        {пути}')
        итого += len(список)
    print(f'  = {итого}   (сходится с описью: {итого == len(строки)})')

    print(f'\n① Эндпоинты ЗАПИСИ от имени вошедшего БЕЗ проверки is_verified: '
          f'{len(запись_без_verified)}')
    for с in запись_без_verified:
        в_бд = 'в БД' if с.get('в_базу') else 'вовне'
        print(f'    {с["метод"]:<7}{с["путь"]:<44}{в_бд:<6}{с["доступ"]}')
    print(f'\n    Исключены осознанно (гейт заперал бы аккаунт): {len(исключено)}')
    for с in исключено:
        print(f'      {с["метод"]:<7}{с["путь"]:<40}'
              f'{ГЕЙТ_ПРИЧИНЫ[с["путь"]]}')
    print(f'\n② Эндпоинты ЗАПИСИ без аутентификации вообще: {len(запись_без_auth)}')
    for с in запись_без_auth:
        print(f'    {с["метод"]:<7}{с["путь"]:<44}{с["доступ"]}')
    print(f'\n③ Чтение по названному идентификатору без проверки принадлежности: '
          f'{len(чтение_чужого)}')
    for с in чтение_чужого:
        print(f'    {с["метод"]:<7}{с["путь"]:<44}{с["доступ"]}')

    print(f'\n④ Пишущие GET — вне границы гейта по замыслу (§5.3): '
          f'{len(пишущие_get)}')
    for с in пишущие_get:
        print(f'    {с["метод"]:<7}{с["путь"]:<44}'
              f'{ЗАПИСЬ_ЧЕРЕЗ_ВЫЗОВ.get((с["путь"], с["метод"]), "запись в теле")}')

    return 1 if запись_без_verified else 0



"""ШИРОКИЙ РЕЖИМ ОДНОГО ИНСТРУМЕНТА (№352, «enshrouded-2»).

Проба ширины: Enshrouded получает СВОЙ потолок колонки содержимого
(`body.v2-wide`), остальные инструменты остаются на общем `--v2-content`.
Главный вопрос пробы один и он про НЕВМЕШАТЕЛЬСТВО: «ширина остальных
инструментов не изменилась ни на пиксель». Ответить на него можно
только СРАВНЕНИЕМ ДВУХ СОСТОЯНИЙ, поэтому устройство то же, что
у `check_regress`: снимок «до», правка, снимок «после», сверка.

    py check_ens_wide.py --снять ФАЙЛ      замер текущего кода
    py check_ens_wide.py --сверить ДО ПОСЛЕ
    py check_ens_wide.py --пороги ФАЙЛ     только колонки: эталон не нужен
    py check_ens_wide.py --контроль ДО     подлог: общий токен вместо частного

ПОРОГИ КОЛОНОК СПРАШИВАЮТСЯ У ШИРИНЫ СЕТКИ, А НЕ У ШИРИНЫ ОКНА.
Проверка 66 держит таблицу «окно → колонок» (1600 → 4, 1280 → 3,
390 → 1), и это верно, пока колонка содержимого у всех инструментов
одна: тогда ширина окна её однозначно задаёт. С частным потолком это
перестаёт быть правдой — одна и та же ширина окна даёт разную ширину
сетки в зависимости от того, чей это инструмент. Пороги здесь те же,
что в `@container` у `static/enshrouded.css`.

ИНСТРУМЕНТЫ И ЗАМЕР КОЛОНКИ БЕРУТСЯ У `check_v2_head` ИМПОРТОМ:
второй перечень экранов и второй способ находить контейнер разошлись
бы с первым молча (§6.0.7). Тот замер выводит контейнер ИЗ ШАПКИ,
а не ищет по списку классов, — это же нужно и здесь.

БРАУЗЕР ВИДИМЫЙ (§6.0.3): меряются ШИРИНЫ, а headless прячет полосу
прокрутки без изъятия места — колонка каркаса вышла бы на 15 px шире
на каждой ширине окна, и число колонок у порога 1800 разошлось бы
с тем, что видит человек.
"""
import json
import sys

import probe_guard  # noqa: F401  — «спросить нечем» словом, а не трассой
import browser_window  # noqa: F401  — видимое окно на второй монитор
import check_hover as ch
import check_v2_head as vh

ШИРИНЫ = (1440, 1600, 1920, 2560)

# Повторяет `@container` в static/enshrouded.css: (минимум ширины
# СЕТКИ, колонок). Сверху вниз — первый подошедший.
ПОРОГИ = ((1800, 5), (1400, 4), (1100, 3), (700, 2), (0, 1))

# Инструмент, которому широкий режим и заводится. Остальные обязаны
# совпасть с «до» ДО ПИКСЕЛЯ — в этом весь вопрос пробы.
ШИРОКИЙ = "enshrouded"

ЗАМЕР_СЕТКИ = """() => {
  const окр = (v) => Math.round(v * 100) / 100;
  const сетка = document.querySelector('.sets-grid');
  if (!сетка) return null;
  const ст = getComputedStyle(сетка);
  // Число колонок — по дорожкам, посчитанным БРАУЗЕРОМ: вписанное
  // в пробу разошлось бы с CSS молча (тот же довод, что в проверке 66).
  const колонок = ст.gridTemplateColumns.split(' ').filter(Boolean).length;
  const r = сетка.getBoundingClientRect();
  const карточка = сетка.querySelector('.set-card, .card');
  return {
    сетка: окр(r.width), колонок: колонок,
    карточка: карточка ? окр(карточка.getBoundingClientRect().width) : null
  };
}"""


def ожидаем_колонок(ширина_сетки):
    for минимум, сколько in ПОРОГИ:
        if ширина_сетки >= минимум:
            return сколько
    return 1


def шаг(имя, условие, подробность="", собрано=None):
    if собрано == 0:
        print("  ПРОПУСК %-38s %s" % (имя, подробность or "собрано 0"))
        return None
    print("  %-7s %-38s %s" % ("OK" if условие else "ПЛОХО", имя, подробность))
    return bool(условие)


def снять(подлог=None):
    """{ширина окна: {инструмент: {вкладка: {...}}, '__сетка__': {...}}}."""
    from playwright.sync_api import sync_playwright
    итог = {}
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=False)
        for ш in ШИРИНЫ:
            к = бр.new_context(viewport={"width": ш, "height": 1000})
            if подлог == "общий-токен":
                # ПОДЛОГ БЬЁТ ПО ОБЩЕМУ ТОКЕНУ — ровно та ошибка, ради
                # которой проба и написана: ширину подняли всем сразу,
                # а не одному инструменту.
                к.add_init_script(
                    "addEventListener('DOMContentLoaded', () => {"
                    " const s = document.createElement('style');"
                    " s.textContent = ':root { --v2-content: 1920px !important; }';"
                    " document.head.appendChild(s); });")
            стр = к.new_page()
            ch._войти(стр)
            по_ширине = {}
            for путь, имя in vh.ИНСТРУМЕНТЫ:
                стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
                стр.wait_for_timeout(400)
                вкладки = стр.evaluate(
                    "() => [...document.querySelectorAll('.v2-page-head .v2-tab')]"
                    ".map((t, i) => t.textContent.trim().slice(0, 18) || ('вкладка' + i))")
                места = {}
                if not вкладки:
                    к0 = стр.evaluate(vh.ЗАМЕР_КОЛОНКИ)
                    if к0:
                        места["(без вкладок)"] = к0
                for i, название in enumerate(вкладки):
                    кн = стр.locator(".v2-page-head .v2-tab").nth(i)
                    try:
                        кн.click(timeout=3000)
                        стр.wait_for_timeout(250)
                    except Exception:
                        continue
                    к0 = стр.evaluate(vh.ЗАМЕР_КОЛОНКИ)
                    if к0:
                        места[название] = к0
                по_ширине[имя] = места
                if имя == ШИРОКИЙ:
                    стр.wait_for_timeout(700)
                    по_ширине["__сетка__"] = стр.evaluate(ЗАМЕР_СЕТКИ)
            итог[str(ш)] = по_ширине
            к.close()
        бр.close()
    return итог


def сверить(до, после):
    """Остальные инструменты — до пикселя; Enshrouded вправе меняться."""
    расх = []
    пар = 0
    for ш, инстр in sorted(до.items()):
        for имя, места in инстр.items():
            if имя in (ШИРОКИЙ, "__сетка__"):
                continue
            для = после.get(ш, {}).get(имя, {})
            for вкладка, было in места.items():
                стало = для.get(вкладка)
                пар += 1
                if not стало:
                    расх.append("%s/%s/%s: вкладки нет в «после»" % (ш, имя, вкладка))
                elif стало["ширина"] != было["ширина"]:
                    расх.append("%s/%s/%s: %.1f -> %.1f" % (
                        ш, имя, вкладка, было["ширина"], стало["ширина"]))
    return пар, расх


def пороги(замер):
    плохо = []
    строки = []
    for ш in sorted(замер, key=int):
        с = замер[ш].get("__сетка__")
        if not с:
            continue
        ждём = ожидаем_колонок(с["сетка"])
        строки.append("    %-5s сетка %7.1f  колонок %d (ждём %d)  карточка %6.1f"
                      % (ш, с["сетка"], с["колонок"], ждём, с["карточка"] or 0))
        if с["колонок"] != ждём:
            плохо.append("%s: сетка %.1f -> колонок %d, ждём %d"
                         % (ш, с["сетка"], с["колонок"], ждём))
    return строки, плохо


def печать_ens(замер, заголовок):
    print(заголовок)
    for ш in sorted(замер, key=int):
        места = замер[ш].get(ШИРОКИЙ) or {}
        к = list(места.values())
        с = замер[ш].get("__сетка__") or {}
        print("    %-5s колонка %7.1f  сетка %7.1f  колонок %s  карточка %s"
              % (ш, к[0]["ширина"] if к else 0, с.get("сетка") or 0,
                 с.get("колонок"), с.get("карточка")))


def main():
    арг = sys.argv[1:]
    if "--снять" in арг:
        путь = арг[арг.index("--снять") + 1]
        з = снять()
        with open(путь, "w", encoding="utf-8") as f:
            json.dump(з, f, ensure_ascii=False, indent=1)
        печать_ens(з, "ЗАМЕР Enshrouded:")
        строки, _ = пороги(з)
        print("  пороги:")
        for с in строки:
            print(с)
        print("  снято в %s" % путь)
        return 0
    if "--пороги" in арг:
        путь = арг[арг.index("--пороги") + 1]
        з = json.load(open(путь, encoding="utf-8"))
        строки, плохо = пороги(з)
        for с in строки:
            print(с)
        ok = шаг("колонок-по-порогам-ширины-сетки", not плохо,
                 "; ".join(плохо) or "ширин без ожидаемого числа колонок нет",
                 собрано=len(строки))
        return 0 if ok else 1
    if "--сверить" in арг or "--контроль" in арг:
        ключ = "--сверить" if "--сверить" in арг else "--контроль"
        до = json.load(open(арг[арг.index(ключ) + 1], encoding="utf-8"))
        if ключ == "--сверить":
            после = json.load(open(арг[арг.index(ключ) + 2], encoding="utf-8"))
        else:
            print("  ПОДЛОГ: общий токен --v2-content вместо частного режима")
            после = снять(подлог="общий-токен")
        пар, расх = сверить(до, после)
        печать_ens(после, "Enshrouded после:")
        ok = шаг("ширина-остальных-не-изменилась", not расх,
                 "; ".join(расх[:6]) or "пар краёв %d, расхождений 0" % пар,
                 собрано=пар)
        строки, плохо = пороги(после)
        for с in строки:
            print(с)
        ok2 = шаг("колонок-по-порогам-ширины-сетки", not плохо,
                  "; ".join(плохо) or "ширин без ожидаемого числа колонок нет",
                  собрано=len(строки))
        if ключ == "--контроль":
            нашла = bool(расх)
            print("  ДОКАЗАТЕЛЬСТВО: расхождений у остальных %d (без подлога 0)"
                  % len(расх))
            print("  КОНТРОЛЬ: %s" % ("ЛОВИТ" if нашла else "НЕ ЛОВИТ"))
            return 0 if нашла else 1
        return 0 if (ok and ok2) else 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())

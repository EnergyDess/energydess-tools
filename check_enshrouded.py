def адрес_картинки(сет, png):
    """Имя файла картинки сета. ОДНО, а не цепочка.

    Отката больше нет и он больше не нужен: расширение стало ПОЛЕМ сета
    (`img_ext`), то есть тем же значением, по которому сервер строит
    адрес. Прежняя цепочка страховала от того, что расширение выводится
    из каталога один раз при импорте, — этого механизма не существует
    с 2026-08-22 (BACKLOG №137).
    """
    ext = сет.get("img_ext") or ("png" if сет["id"] in png else "jpg")
    return [сет["id"] + "." + ext]


def _состав(сет, слоты):
    if сет.get("custom"):
        ids = [c["id"] for c in сет["custom"]]
        if сет.get("pieces"):
            return ids, "объявлены И custom, И pieces — pieces не действуют"
        return ids, None
    ids = сет.get("pieces") or слоты
    плохие = [i for i in ids if i not in слоты]
    if плохие:
        return ids, "слот не объявлен в SLOT_DEFS: " + ", ".join(плохие)
    if not ids:
        return ids, "состав пуст — слотов на карточке ноль"
    if len(ids) != len(set(ids)):
        return ids, "один слот назван дважды"
    return ids, None



# ── Разбор JS-литерала ────────────────────────────────────────────────
def _разобрать_js(текст, поз=0):
    """Читает одно значение JS-литерала с позиции. Возвращает (значение, поз).

    Грепом это не делается: значения бывают вложенными и многострочными,
    а ключи — голыми идентификаторами, то есть json их не берёт.
    """
    def проп(i):
        while i < len(текст):
            if текст[i] in " \t\r\n":
                i += 1
            elif текст.startswith("//", i):
                i = текст.find("\n", i)
                if i < 0:
                    return len(текст)
            elif текст.startswith("/*", i):
                к = текст.find("*/", i)
                i = len(текст) if к < 0 else к + 2
            else:
                return i
        return i

    поз = проп(поз)
    ch = текст[поз]

    if ch in "'\"":
        кав, i, буф = ch, поз + 1, []
        while текст[i] != кав:
            if текст[i] == "\\":
                буф.append(текст[i + 1])
                i += 2
            else:
                буф.append(текст[i])
                i += 1
        return "".join(буф), i + 1

    if ch == "[":
        сп, i = [], проп(поз + 1)
        while текст[i] != "]":
            зн, i = _разобрать_js(текст, i)
            сп.append(зн)
            i = проп(i)
            if текст[i] == ",":
                i = проп(i + 1)
        return сп, i + 1

    if ch == "{":
        об, i = {}, проп(поз + 1)
        while текст[i] != "}":
            if текст[i] in "'\"":
                ключ, i = _разобрать_js(текст, i)
            else:
                м = re.match(r"[A-Za-z_$][\w$]*", текст[i:])
                ключ, i = м.group(0), i + м.end()
            i = проп(i)
            if текст[i] != ":":
                raise ValueError("ждали двоеточие: " + текст[i - 30:i + 30])
            зн, i = _разобрать_js(текст, i + 1)
            об[ключ] = зн
            i = проп(i)
            if текст[i] == ",":
                i = проп(i + 1)
        return об, i + 1

    м = re.match(r"-?\d+\.?\d*", текст[поз:])
    if м:
        s = м.group(0)
        return (float(s) if "." in s else int(s)), поз + м.end()
    м = re.match(r"true|false|null", текст[поз:])
    if м:
        return {"true": True, "false": False, "null": None}[м.group(0)], поз + м.end()
    raise ValueError("не разобрано у позиции %d: %r" % (поз, текст[поз:поз + 40]))


def _массив(имя, текст):
    м = re.search(r"\bconst\s+" + имя + r"\s*=\s*", текст)
    if not м:
        raise SystemExit("ОСТАНОВЛЕНО: в шаблоне нет объявления " + имя)
    зн, _ = _разобрать_js(текст, м.end())
    return зн



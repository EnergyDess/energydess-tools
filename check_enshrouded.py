# ── Разбор JS-литерала ────────────────────────────────────────────────
def _разобрать_js(текст, поз=0):
    """Читает одно значение JS-литерала с позиции. Возвращает (значение, поз).

    Грепом это не делается: значения бывают вложенными и многострочными,
    а ключи — голыми идентификаторами, то есть json их не берёт.
    """
    def проп(i):
        while i < len(текст):
            if текст[i] in " \t\r\n":
                i += 1
            elif текст.startswith("//", i):
                i = текст.find("\n", i)
                if i < 0:
                    return len(текст)
            elif текст.startswith("/*", i):
                к = текст.find("*/", i)
                i = len(текст) if к < 0 else к + 2
            else:
                return i
        return i

    поз = проп(поз)
    ch = текст[поз]

    if ch in "'\"":
        кав, i, буф = ch, поз + 1, []
        while текст[i] != кав:
            if текст[i] == "\\":
                буф.append(текст[i + 1])
                i += 2
            else:
                буф.append(текст[i])
                i += 1
        return "".join(буф), i + 1

    if ch == "[":
        сп, i = [], проп(поз + 1)
        while текст[i] != "]":
            зн, i = _разобрать_js(текст, i)
            сп.append(зн)
            i = проп(i)
            if текст[i] == ",":
                i = проп(i + 1)
        return сп, i + 1

    if ch == "{":
        об, i = {}, проп(поз + 1)
        while текст[i] != "}":
            if текст[i] in "'\"":
                ключ, i = _разобрать_js(текст, i)
            else:
                м = re.match(r"[A-Za-z_$][\w$]*", текст[i:])
                ключ, i = м.group(0), i + м.end()
            i = проп(i)
            if текст[i] != ":":
                raise ValueError("ждали двоеточие: " + текст[i - 30:i + 30])
            зн, i = _разобрать_js(текст, i + 1)
            об[ключ] = зн
            i = проп(i)
            if текст[i] == ",":
                i = проп(i + 1)
        return об, i + 1

    м = re.match(r"-?\d+\.?\d*", текст[поз:])
    if м:
        s = м.group(0)
        return (float(s) if "." in s else int(s)), поз + м.end()
    м = re.match(r"true|false|null", текст[поз:])
    if м:
        return {"true": True, "false": False, "null": None}[м.group(0)], поз + м.end()
    raise ValueError("не разобрано у позиции %d: %r" % (поз, текст[поз:поз + 40]))


def _массив(имя, текст):
    м = re.search(r"\bconst\s+" + имя + r"\s*=\s*", текст)
    if not м:
        raise SystemExit("ОСТАНОВЛЕНО: в шаблоне нет объявления " + имя)
    зн, _ = _разобрать_js(текст, м.end())
    return зн


def прочитать(путь=None, каталог=None):
    """Данные раздела ОДНИМ разбором. Второй реализации в проекте нет.

    РАСШИРЕНИЯ БЕРУТСЯ С ДИСКА, а не из шаблона. До 2026-08-22 в шаблоне
    лежал рукописный `PNG_ICONS` из четырёх имён; после того, как картинки
    забрали с вики, их стало 66, и перечень отстал бы на первом же сете,
    добавленном разговором (§6.0.7). Теперь список подставляет сервер
    (`main.ENSHROUDED_PNG`), и он тоже читает ЭТОТ каталог — двух правил
    нет, есть один вопрос к файловой системе, заданный с двух сторон.
    """
    текст = (путь or ШАБЛОН).read_text(encoding='utf-8')
    сеты = _массив("SETS", текст)
    крафтеры = _массив("CRAFTERS", текст)
    слоты = _массив("SLOT_DEFS", текст)
    кат = каталог or КАРТИНКИ
    png = {p.stem for p in кат.glob("*.png")} if кат.is_dir() else set()
    # Перечень не должен вернуться незамеченным: если в шаблоне снова
    # окажется литеральный набор, это перечень, а не подстановка.
    м = re.search(r"const\s+PNG_ICONS\s*=\s*new\s+Set\(\s*\[", текст)
    return {"sets": сеты, "crafters": крафтеры, "png": png,
            "slots": [s["id"] for s in слоты], "перечень_png": bool(м)}


# ── Адрес картинки: ровно то, что делает renderCard ───────────────────
def адрес_картинки(сет, png):
    """Цепочка МЕСТНЫХ имён файлов — ровно то, что делает renderCard.

    Чужого домена здесь больше нет: картинки забраны к себе 2026-08-22.
    Прежде функция возвращала ещё и вики-адрес, и он был ПЕРВЫМ
    источником у 80 сетов из 90.
    """
    sid = сет["id"]
    первый = sid + (".png" if sid in png else ".jpg")
    # Откат остаётся: расширение выводится из каталога СЕРВЕРОМ, и файл,
    # положенный без перезапуска, иначе давал бы схлопнутый баннер.
    return [первый] if первый.endswith(".png") else [первый, sid + ".png"]


def _состав(сет, слоты):
    if сет.get("custom"):
        ids = [c["id"] for c in сет["custom"]]
        if сет.get("pieces"):
            return ids, "объявлены И custom, И pieces — pieces не действуют"
        return ids, None
    ids = сет.get("pieces") or слоты
    плохие = [i for i in ids if i not in слоты]
    if плохие:
        return ids, "слот не объявлен в SLOT_DEFS: " + ", ".join(плохие)
    if not ids:
        return ids, "состав пуст — слотов на карточке ноль"
    if len(ids) != len(set(ids)):
        return ids, "один слот назван дважды"
    return ids, None


# ── Сама проверка ─────────────────────────────────────────────────────
def проверить(путь=None, каталог=None):
    д = прочитать(путь)
    каталог = каталог or КАРТИНКИ
    на_диске = {p.name for p in каталог.iterdir() if p.is_file()} if каталог.is_dir() else set()
    находки, использованы, видел = [], set(), set()

    for сет in д["sets"]:
        sid = сет.get("id", "?")
        имя = "%s «%s»" % (sid, сет.get("nameRu", "?"))

        if sid in видел:
            находки.append(("ДУБЛЬ_ID", имя, "id уже занят выше по списку"))
        видел.add(sid)

        кат = сет.get("crafter")
        if кат not in д["crafters"]:
            находки.append(("КАТЕГОРИЯ", имя, "crafter=%r не объявлен в CRAFTERS" % (кат,)))
        elif кат not in ПОРЯДОК_ГРУПП:
            находки.append(("КАТЕГОРИЯ", имя,
                            "crafter=%r объявлен, но его нет в порядке групп рендера" % (кат,)))

        if not сет.get("nameRu") or not сет.get("name"):
            находки.append(("БЕЗ_ИМЕНИ", имя, "нет nameRu или name"))

        # Латиница внутри русского названия. Поиск идёт подстрокой по nameRu:
        # набранное кириллицей такое слово не найдётся никогда.
        ru = сет.get("nameRu") or ""
        if re.search(r"[А-Яа-яЁё]", ru):
            for слово in re.findall(r"[^\s,.\-—()]+", ru):
                if re.search(r"[A-Za-z]", слово):
                    находки.append(("ЛАТИНИЦА", имя,
                                    "слово %r набрано латиницей внутри русского названия" % (слово,)))

        # Обратная сторона того же класса: кириллическая буква внутри
        # английского названия. Английское имя — то, чем сет ищут
        # в источниках игры и чем он подписан на карточке; кириллица
        # в нём так же немо выключает поиск, только с другой стороны.
        en = сет.get("name") or ""
        if re.search(r"[A-Za-z]", en):
            for слово in re.findall(r"[^\s,.\-—()]+", en):
                if re.search(r"[А-Яа-яЁё]", слово):
                    находки.append(("КИРИЛЛИЦА", имя,
                                    "слово %r набрано кириллицей внутри английского названия" % (слово,)))

        _, беда = _состав(сет, д["slots"])
        if беда:
            находки.append(("СОСТАВ", имя, беда))

        if кат in УРОВЕНЬ_ПОЛОЖЕН and not сет.get("lvl"):
            находки.append(("УРОВЕНЬ", имя, "категория %s — lvl положен, его нет" % кат))
        if кат == "special":
            находки.append(("БЕЗ_УРОВНЯ", имя,
                            "lvl отсутствует" if not сет.get("lvl")
                            else "lvl=%s стоит у «Спецпредметов»" % сет["lvl"]))

        цепь = адрес_картинки(сет, д["png"])
        есть = [ф for ф in цепь if ф in на_диске]
        использованы.update(есть)
        if not есть:
            находки.append(("БЕЗ_КАРТИНКИ", имя,
                            "местного файла нет: искали " + ", ".join(цепь)))

    if д.get("перечень_png"):
        находки.append(("ПЕРЕЧЕНЬ_PNG", "templates/enshrouded.html",
                        "const PNG_ICONS снова литеральный набор, а не подстановка сервера"))

    for ф in sorted(на_диске - использованы):
        находки.append(("СИРОТА", ф, "ни один сет на этот файл не ссылается"))

    return находки


def _печать(находки, подробно=False):
    долг = [н for н in находки if ВИДЫ[н[0]][1]]
    д = прочитать()
    файлов = len([p for p in КАРТИНКИ.iterdir() if p.is_file()]) if КАРТИНКИ.is_dir() else 0
    print("Сетов в данных: %d, файлов на диске: %d" % (len(д["sets"]), файлов))
    print("НАХОДОК: %d   ДОЛГ: %d" % (len(находки), len(долг)))
    print()
    for вид, (что, это_долг) in ВИДЫ.items():
        свои = [н for н in находки if н[0] == вид]
        метка = "ДОЛГ" if это_долг else "законно"
        print("  %-14s %-4d (%s) — %s" % (вид, len(свои), метка, что))
        if это_долг or подробно:
            for _, кто, почему in свои:
                print("      · %s: %s" % (кто, почему))
    return 1 if долг else 0


def _контроль():
    """Отрицательный контроль: подлог на КАЖДЫЙ вид долга.

    Пустой результат без пройденного контроля недействителен: ровно тот же
    ноль напечатала бы проверка, читающая не тот файл.
    """
    исходный = ШАБЛОН.read_text(encoding="utf-8")
    подлоги = [
        ("КАТЕГОРИЯ", "crafter:'blacksmith', lvl:5", "crafter:'tailor', lvl:5"),
        ("СОСТАВ", "pieces:['legs'] }", "pieces:['legs','wings'] }"),
        ("БЕЗ_ИМЕНИ", "name:'Fur Armor'", "name:''"),
        ("ЛАТИНИЦА", "nameRu:'Целитель'", "nameRu:'Целитель Healer'"),
        ("КИРИЛЛИЦА", "name:'Healer'", "name:'Healer Целитель'"),
        ("ДУБЛЬ_ID", "id:'bs_rf',", "id:'bs_fur',"),
        ("УРОВЕНЬ", "crafter:'huntress',   lvl:8", "crafter:'huntress'"),
        ("ПЕРЕЧЕНЬ_PNG", "new Set({{ ens_png|tojson }})", "new Set(['al_wiz'])"),
        ("БЕЗ_КАРТИНКИ", "@файл", "w_archer.jpg"),
        ("СИРОТА", "@сирота", "_контроль_сирота.jpg"),
    ]
    чисто = проверить()
    # Сравниваем НАБОРАМИ, а не счётчиками: подлог, вставший в списке ВЫШЕ
    # прежней находки того же вида, при счёте по индексу назвал бы прежнюю —
    # то есть контроль печатал бы «найден» про то, что нашлось и без него.
    было = set(чисто)
    print("Чистый прогон (без подлога): находок %d, долг %d"
          % (len(чисто), len([н for н in чисто if ВИДЫ[н[0]][1]])))
    print()
    ок = True
    врем = Path(tempfile.mkdtemp())
    try:
        for вид, было_стр, стало_стр in подлоги:
            if было_стр == "@сирота":
                файл = КАРТИНКИ / стало_стр
                файл.write_bytes(b"x")
                try:
                    поймано = [x for x in проверить()
                               if x[0] == вид and стало_стр in x[1] and x not in было]
                finally:
                    файл.unlink()
            elif было_стр == "@файл":
                # ссылка на местный файл есть, файла нет — уносим файл
                исх, куда = КАРТИНКИ / стало_стр, врем / стало_стр
                shutil.move(str(исх), str(куда))
                try:
                    поймано = [x for x in проверить()
                               if x[0] == вид and x not in было]
                finally:
                    shutil.move(str(куда), str(исх))
            else:
                if исходный.count(было_стр) < 1:
                    print("  %-14s ОСТАНОВЛЕНО: якоря подлога нет в шаблоне" % вид)
                    ок = False
                    continue
                ШАБЛОН.write_text(исходный.replace(было_стр, стало_стр, 1), encoding="utf-8")
                try:
                    поймано = [x for x in проверить()
                               if x[0] == вид and x not in было]
                finally:
                    ШАБЛОН.write_text(исходный, encoding="utf-8")
            знак = "НАЙДЕН" if поймано else "ПРОПУЩЕН — проверка сломана"
            ок = ок and bool(поймано)
            пример = (": %s — %s" % (поймано[0][1], поймано[0][2])) if поймано else ""
            print("  %-14s подлог %s%s" % (вид, знак, пример))
    finally:
        ШАБЛОН.write_text(исходный, encoding="utf-8")
        shutil.rmtree(str(врем), ignore_errors=True)

    после = проверить()
    совпало = len(после) == len(чисто)
    print()
    print("После уборки: находок %d, долг %d — совпало с чистым: %s"
          % (после and len(после) or 0,
             len([н for н in после if ВИДЫ[н[0]][1]]), "да" if совпало else "НЕТ"))
    return 0 if (ок and совпало) else 1


def _множества():
    """A.2: три множества и попарные расхождения. Печатает числа."""
    д = прочитать()
    на_диске = {p.name for p in КАРТИНКИ.iterdir() if p.is_file()}
    # -z обязателен: без него git экранирует кириллицу восьмеричными кодами
    # и «Лазутчик.jpg» под git превращается в имя, которого на диске нет, —
    # то есть мерка сама выдумывает расхождение (§6.0.1 внутри инструмента).
    вых = subprocess.run(["git", "ls-files", "-z", "static/enshrouded/"],
                         cwd=str(КОРЕНЬ), capture_output=True)
    в_репозитории = {с.decode("utf-8").rsplit("/", 1)[1]
                     for с in вых.stdout.split(b"\0") if с.strip()}

    # Первая ссылка — то, что браузер запросит ВСЕГДА. Откат по onerror —
    # то, что он запросит только после 404 предыдущей. Смешивать их нельзя:
    # запасное имя, которого нет на диске, дырой не является.
    первые, откат = set(), set()
    for сет in д["sets"]:
        цепь = адрес_картинки(сет, д["png"])
        первые.add(цепь[0])
        откат.update(цепь[1:])
    ссылки = первые | откат


def _png_ширины(ш, в):
    """Настоящий PNG заданного размера — восемь байт подписи, IHDR и IEND.

    Без Pillow: проверка размера читает шапку сама, и контроль обязан
    прогоняться в тех же условиях, что она (§6.0.1).
    """
    import struct
    import zlib

    def кусок(имя, тело):
        данные = имя + тело
        return (struct.pack(">I", len(тело)) + данные
                + struct.pack(">I", zlib.crc32(данные) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", ш, в, 8, 6, 0, 0, 0)
    строки = b"".join(bytes([0]) + bytes(4 * ш) for _ in range(в))
    return (bytes([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
            + кусок(b"IHDR", ihdr)
            + кусок(b"IDAT", zlib.compress(строки))
            + кусок(b"IEND", b""))


def _подлог_в_базе(sid, поле, знач, вид, было):
    """Подменить ОДНО поле сета, прогнать проверку, вернуть как было.

    Пишем СВОИМ подключением к тому же файлу, что читает `_из_базы`:
    второго представления каталога в проверке нет, и подлог обязан
    лежать там же, где настоящие данные, — иначе он проверял бы
    не то, что читают.
    """
    import sqlite3
    путь = os.environ.get("DB_PATH") or str(КОРЕНЬ / "app.db")
    conn = sqlite3.connect(путь)
    было_знач = conn.execute(
        f"SELECT {поле} FROM enshrouded_sets WHERE id=?", (sid,)).fetchone()
    if было_знач is None:
        print("  %-14s ОСТАНОВЛЕНО: сета %s в каталоге нет" % (вид, sid))
        conn.close()
        return []
    try:
        conn.execute(f"UPDATE enshrouded_sets SET {поле}=? WHERE id=?", (знач, sid))
        conn.commit()
        return [x for x in проверить() if x[0] == вид and x not in было]
    finally:
        conn.execute(f"UPDATE enshrouded_sets SET {поле}=? WHERE id=?",
                     (было_знач[0], sid))
        conn.commit()
        conn.close()


def _подлог_дубль(sid, вид, было):
    """Завести ВТОРУЮ строку с тем же id — чтобы каталог отдал дубль.

    Первичный ключ такого не разрешает, поэтому дубль подкладывается
    не в таблицу, а в то, что она отдаёт: строка с чужим id, чей
    `sort_order` ставит её рядом. Проверяемое свойство — «две записи
    каталога с одним id», и `_из_базы` возвращает именно список.
    """
    import sqlite3
    путь = os.environ.get("DB_PATH") or str(КОРЕНЬ / "app.db")
    conn = sqlite3.connect(путь)
    близнец = "_ctl_dupe"
    try:
        стр = conn.execute(
            "SELECT name_ru, name_en, crafter, lvl, pieces, custom, img_ext,"
            " sort_order FROM enshrouded_sets WHERE id=?", (sid,)).fetchone()
        if стр is None:
            print("  %-14s ОСТАНОВЛЕНО: сета %s в каталоге нет" % (вид, sid))
            return []
        conn.execute(
            "INSERT INTO enshrouded_sets (id, name_ru, name_en, crafter, lvl,"
            " pieces, custom, img_ext, sort_order) VALUES (?,?,?,?,?,?,?,?,?)",
            (близнец,) + стр)
        conn.commit()
        # Каталог отдаёт два разных id; чтобы получить именно ДУБЛЬ,
        # подменяем id близнеца на исходный уже в отданном списке —
        # ровно то, что случится, если кто-то заведёт сет тем же id
        # в обход первичного ключа (миграцией, восстановлением из семени).
        родной = _из_базы
        def подмена(*а, **к):
            из = родной(*а, **к)
            for з in из:
                if з["id"] == близнец:
                    з["id"] = sid
            return из
        globals()["_из_базы"] = подмена
        try:
            return [x for x in проверить() if x[0] == вид and x not in было]
        finally:
            globals()["_из_базы"] = родной
    finally:
        conn.execute("DELETE FROM enshrouded_sets WHERE id=?", (близнец,))
        conn.commit()
        conn.close()



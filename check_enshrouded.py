def _из_базы(db_path=None):
    """Каталог сетов из `enshrouded_sets`, в тех же полях, что были в JS.

    Имена оставлены прежними (`nameRu`, `name`, `crafter`, `lvl`,
    `pieces`, `custom`): весь разбор ниже уже умеет их читать, и
    переименование стоило бы правки девяти видов дыр без единой выгоды.
    """
    import sqlite3
    путь = db_path or os.environ.get("DB_PATH") or str(КОРЕНЬ / "app.db")
    if not os.path.exists(путь):
        print(f"БАЗЫ НЕТ: {путь} — каталог читать неоткуда")
        return []
    conn = sqlite3.connect(f"file:{путь}?mode=ro", uri=True)
    try:
        строки = conn.execute(
            "SELECT id, name_ru, name_en, crafter, lvl, pieces, custom, img_ext"
            " FROM enshrouded_sets ORDER BY sort_order, id").fetchall()
    except sqlite3.OperationalError as e:
        print(f"ТАБЛИЦЫ КАТАЛОГА НЕТ ({e}) — приложение её заводит миграцией")
        return []
    finally:
        conn.close()
    из = []
    for sid, ру, ен, крафт, lvl, pieces, custom, ext in строки:
        з = {"id": sid, "nameRu": ру, "name": ен, "crafter": крафт,
             "lvl": lvl, "img_ext": ext}
        if pieces:
            з["pieces"] = json.loads(pieces)
        if custom:
            з["custom"] = json.loads(custom)
        из.append(з)
    return из



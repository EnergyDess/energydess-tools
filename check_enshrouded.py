def _размер_картинки(путь):
    """Ширина и высота файла без Pillow: у PNG и JPEG они лежат в шапке.

    Без внешней зависимости намеренно — проверка ряда §6.0.2 обязана
    запускаться там же, где остальные, а Pillow в проекте стоит ради
    обработки фотографий, а не ради приёмки.
    """
    try:
        b = путь.read_bytes()
    except OSError:
        return None, None
    ПОДПИСЬ_PNG = bytes([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    if b[:8] == ПОДПИСЬ_PNG and b[12:16] == b"IHDR":
        return (int.from_bytes(b[16:20], "big"), int.from_bytes(b[20:24], "big"))
    if b[:2] == bytes([0xFF, 0xD8]):
        i = 2
        while i + 9 < len(b):
            if b[i] != 0xFF:
                i += 1
                continue
            маркер = b[i + 1]
            if маркер in (0xD8, 0x01) or 0xD0 <= маркер <= 0xD7:
                i += 2
                continue
            длина = int.from_bytes(b[i + 2:i + 4], "big")
            if 0xC0 <= маркер <= 0xCF and маркер not in (0xC4, 0xC8, 0xCC):
                return (int.from_bytes(b[i + 7:i + 9], "big"),
                        int.from_bytes(b[i + 5:i + 7], "big"))
            i += 2 + длина
    return None, None



def _уровни():
    """Что означает lvl: сверка с первоисточником, а не рассуждение.

    Вики пишет уровень сета ПРОЗОЙ: «The Knight Set is a level 18 Armor
    set». Это и есть ответ на вопрос «откуда берётся число у категории
    „Мир“»: оно списано оттуда и означает уровень САМОГО СЕТА, а не
    уровень найденного предмета — тот у мировых находок гуляет.

    Сети требует, в код возврата не идёт: чужой сайт нам не подчиняется,
    а расхождение с ним — повод для решения владельца, не долг.
    """
    import time
    import httpx

    д = прочитать()
    заг = {"User-Agent": "Mozilla/5.0 (integrity-check energydess.ru)"}
    адрес = "https://enshrouded.wiki.gg/api.php"

    def с_вики(кл, имя):
        for стр in (имя + "_Set", имя):
            try:
                отв = кл.get(адрес, params={"action": "parse", "page": стр,
                                            "prop": "wikitext", "format": "json",
                                            "redirects": 1})
            except Exception as e:
                return None, type(e).__name__
            тело = отв.json()
            if "parse" not in тело:
                continue
            wt = тело["parse"]["wikitext"]["*"]
            м = (re.search(r"is an?\s+(?:\[\[[^\]]*\]\]\s*)?level\s+(\d+)", wt, re.I)
                 or re.search(r"\blevel\s+(\d+)\s+\[\[Armor", wt, re.I))
            return (int(м.group(1)) if м else None), стр
        return None, "нет страницы"

    print("Сверка lvl с прозой вики. Пусто у вики — страница описывает")
    print("ОДИН предмет, а не сет: формы «is a level N set» там нет.")
    print()
    with httpx.Client(timeout=25, headers=заг, follow_redirects=True) as кл:
        for кат in ПОРЯДОК_ГРУПП:
            сеты = [s for s in д["sets"] if s["crafter"] == кат]
            совп = разн = молчит = 0
            расхождения = []
            for сет in сеты:
                вики, _ = с_вики(кл, сет["name"])
                наш = сет.get("lvl")
                if вики is None:
                    молчит += 1
                elif наш == вики:
                    совп += 1
                else:
                    разн += 1
                    расхождения.append((сет["id"], сет["nameRu"], наш, вики))
                time.sleep(0.08)
            print("  %-11s сетов %2d: совпало %2d, разошлось %2d, вики молчит %2d"
                  % (кат, len(сеты), совп, разн, молчит))
            for sid, ru, наш, вики in расхождения:
                print("        · %-11s %-30s у нас %-4s у вики %s" % (sid, ru, наш, вики))
    return 0


def _том():
    """A.3: файлы, существующие ТОЛЬКО на томе Fly.

    Ответ по построению пустой, и это стоит печатать, а не подразумевать:
    static/ уезжает в ОБРАЗ (его нет в .dockerignore), том смонтирован
    в /data и держит только базу, аватары, вложения и кадры упражнений.
    Печатается замером, а не рассуждением: приложение на проде спрашивают
    напрямую.
    """
    прил = "energydess-tools"
    # Метки ЛАТИНИЦЕЙ (§6.0): русская метка проходит через flyctl и ssh
    # и возвращается мохнатой — «РєР°СЂС‚РёРЅРєРё» вместо «картинки».
    # Русское печатает Python у себя.
    вопросы = [
        ("vol_dir", "каталог раздела на ТОМЕ", "find /data -type d -name enshrouded | wc -l"),
        # Без скобок группировки: их пришлось бы экранировать трижды —
        # для Python, для flyctl и для sh на машине, и один из трёх слоёв
        # съедал бы экран (проверено: sh отвечал Syntax error).
        ("vol_jpg", "картинок jpg на ТОМЕ (всех, вместе с чужими)", "find /data -type f -name '*.jpg' | wc -l"),
        ("vol_png", "картинок png на ТОМЕ (всех, вместе с чужими)", "find /data -type f -name '*.png' | wc -l"),
        ("img_cnt", "картинок раздела в ОБРАЗЕ", "ls /app/static/enshrouded | wc -l"),
    ]
    команда = "; ".join("echo %s; %s" % (к, ц) for к, _, ц in вопросы)
    вых = subprocess.run(["flyctl", "ssh", "console", "-a", прил, "-C",
                          "sh -c \"%s\"" % команда], capture_output=True, text=True)
    ответы, ключ = {}, None
    for стр in вых.stdout.splitlines():
        стр = стр.strip()
        if not стр or стр.startswith("Connecting"):
            continue
        if any(стр == к for к, _, _ in вопросы):
            ключ = стр
        elif ключ:
            ответы[ключ] = стр
            ключ = None
    for к, подпись, _ in вопросы:
        print("  %-46s %s" % (подпись, ответы.get(к, "НЕ ОТВЕТИЛ")))
    if вых.returncode != 0 and "handle is invalid" not in (вых.stderr or ""):
        print("  ОСТАНОВЛЕНО: flyctl вернул %d — %s" % (вых.returncode, вых.stderr.strip()[:200]))
        return 2
    return 0



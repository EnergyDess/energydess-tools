# -*- coding: utf-8 -*-
"""Проверка 14: список исключений §6.0.2 ссылается на файл, которого нет.

ЗАЧЕМ ЭТА ПРОВЕРКА СУЩЕСТВУЕТ. Решением владельца 2026-08-20 (BACKLOG
№27) две страницы витрины тестового задания выведены из-под проверок:
они лежат в репозитории, к дизайн-системе отношения не имеют, правки
в них не вносятся. Технически это `demo="…"` в §6.0.2 и `grep -vF
"$skip"` на хвосте десяти грепов.

И ровно здесь заводится немой отказ НАОБОРОТ. Все прежние списки
проекта (`names`, `pages`, `ЭКРАНЫ`) молчали про то, чего в них НЕТ:
имени нет — проверка про него не спрашивает. Список исключений молчит
про то, что в нём ЕСТЬ: пока строка стоит, греп вычитает её из вывода.
Переименуй файл — и вычитаться станет нечего, вывод не изменится
ни на строку, ноль останется нулём. Отличить «исключение работает»
от «исключение промахнулось» по выводу нельзя вообще ничем: в обоих
случаях ноль.

Отсюда две вещи, которые проверка требует, и обе — про сам список:

  1. КАЖДЫЙ ПУТЬ ЛЕЖИТ НА ДИСКЕ и является файлом. Нет файла — код 1
     с именем: либо файл вернуть, либо строку из списка убрать,
     и решает это человек, а не молчание.
  2. НИ ОДНОГО ПОДСТАНОВОЧНОГО ЗНАКА. `templates/demo_*` вычло бы
     из вывода файл, которого сегодня нет, — то есть маска расширяла
     бы область молчания сама, без чьего-либо решения. Это и есть
     разница между перечнем и классом (§6.0): перечень допустим там,
     где множество конечно и названо поимённо, а список исключений —
     ровно такое множество.

ГРАНИЦА — чего проверка НЕ видит:
  * файл, который лежит на месте, но перестал быть демо-страницей
    (переписан во что-то рабочее). Буквального представления у «это
    всё ещё витрина тестового задания» в коде нет;
  * исключение, добавленное в обход `demo=` — прямым `grep -v` внутри
    команды. Это увидит человек в диффе §6.0.2, машине такое отличить
    не от чего;
  * лишний путь в списке при живом файле: файл есть, значит формально
    всё в порядке. Убирать исключения — решение владельца.

Запуск, и код читается БЕЗ конвейера (§6.0.1):

    py check_excluded.py;            echo "код=$?"   # 0 — список цел
    py check_excluded.py --контроль; echo "код=$?"   # 0 — проверка видит подлог
"""
import io
import os
import pathlib
import sys

sys.stdout.reconfigure(encoding="utf-8")

import project_lists as списки

КОРЕНЬ = pathlib.Path(__file__).parent

# Подстановочные знаки оболочки. `~` сюда не входит намеренно: это
# не маска, а домашний каталог, и путь с ним был бы просто неверным —
# его поймает проверка существования строкой выше.
МАСКА = set("*?[]{}")


def проверить(пути):
    """(находки, [(путь, состояние)]) — состояние словом, а не флагом."""
    находки, разбор = [], []
    for путь in пути:
        полный = КОРЕНЬ / путь
        if set(путь) & МАСКА:
            состояние = "ПОДСТАНОВОЧНЫЙ ЗНАК — список обязан быть поимённым"
            находки.append((путь, состояние))
        elif not полный.exists():
            состояние = "НА ДИСКЕ НЕТ — греп вычитает то, чего нет"
            находки.append((путь, состояние))
        elif not полный.is_file():
            состояние = "НЕ ФАЙЛ (каталог?) — это маска по смыслу"
            находки.append((путь, состояние))
        else:
            состояние = "на месте, %d байт" % полный.stat().st_size
        разбор.append((путь, состояние))
    return находки, разбор


def отчёт():
    пути = списки.исключённые_страницы()
    if not пути:
        print("ОСТАНОВЛЕНО: список исключений пуст. Пустой список —\n"
              "не «нечего исключать», а «разбор сломался»: строка demo=\n"
              "в §6.0.2 объявлена и обязана давать хотя бы один путь.")
        return 2

    находки, разбор = проверить(пути)

    print("Проверка 14 — список исключений §6.0.2 против диска\n")
    print("  путей в списке:        %d" % len(пути))
    print("  из них не на месте:    %d\n" % len(находки))
    for путь, состояние in разбор:
        метка = "!!" if любая(находки, путь) else "  "
        print("  %s %-34s %s" % (метка, путь, состояние))

    if not находки:
        print("\nСписок цел. Отдельно: этот ноль стоит чего-то только вместе\n"
              "с контролем — `py check_excluded.py --контроль`.")
        return 0

    print("\n--- ЧТО ДЕЛАТЬ ---")
    print("Либо вернуть файл на место, либо убрать строку из `demo=`")
    print("в CLAUDE.md §6.0.2. Оставить как есть нельзя: десять грепов")
    print("вычитают из вывода то, чего нет, и печатают ноль, неотличимый")
    print("от чистоты.")
    return 1


def любая(находки, путь):
    return any(п == путь for п, _ in находки)


def контроль():
    """Подлог: файл из списка временно уезжает под другое имя.

    Без этого «список цел» не отличается от «проверка ничего не читала» —
    ровно тот же довод, что у всех остальных контролей проекта.
    Переименование, а не удаление: содержимое обязано вернуться побайтово.
    """
    пути = списки.исключённые_страницы()
    цель = КОРЕНЬ / пути[0]
    было = io.open(цель, "rb").read()
    временное = цель.with_name(цель.name + ".контроль-переименован")

    находки_до, _ = проверить(пути)
    os.replace(цель, временное)
    try:
        находки_после, _ = проверить(пути)
    finally:
        os.replace(временное, цель)
    находки_обратно, _ = проверить(пути)
    цел = io.open(цель, "rb").read() == было

    # Вторая половина контроля — маска. Файла она не трогает: подлог
    # кладётся в СПИСОК, а не на диск.
    маска, _ = проверить(["templates/demo_*.html"])

    print("═" * 74)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОВЕРКИ 14")
    print("═" * 74)
    print("\nподлог 1: %s временно переименован в %s"
          % (пути[0], временное.name))
    print("  находок до       : %d" % len(находки_до))
    print("  находок при подлоге: %d   %s"
          % (len(находки_после),
             находки_после[0][1] if находки_после else ""))
    print("  находок после отката: %d" % len(находки_обратно))
    print("  файл восстановлен ПОБАЙТОВО: %s" % ("да" if цел else "НЕТ"))
    print("\nподлог 2: в список подставлена маска templates/demo_*.html")
    print("  находок: %d   %s"
          % (len(маска), маска[0][1] if маска else ""))

    ок = (len(находки_до) == 0 and len(находки_после) == 1
          and len(находки_обратно) == 0 and цел and len(маска) == 1)
    print("\n" + ("ПРОЙДЕН: пропажу файла и маску проверка называет, "
                 "после отката молчит" if ок else
                 "ПРОВАЛЕН: проверка не видит подлога — чинить её, "
                 "а не искать объяснение"))
    return 0 if ок else 1


if __name__ == "__main__":
    sys.exit(контроль() if "--контроль" in sys.argv else отчёт())

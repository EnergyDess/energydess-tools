def _разобрать(о, окно_мс):
    """Из слепков — числа и словесная причина.

    ТОЧКА ОТСЧЁТА — ПЕРВАЯ ОТРИСОВКА, а не первый тик пробы. Вопрос
    ставится ровно так: «что человек увидел на первом нарисованном кадре
    и что после этого поменялось у него на глазах». Изменение, успевшее
    случиться ДО первой отрисовки, находкой не является — его никто
    не видел; первая версия пробы этого не различала и печатала
    «подпись +-17 мс», то есть отрицательное опоздание.
    """
    первая = о.get("первая")
    значки = о.get("значки") or []
    подпись = о.get("подпись") or []
    if первая is None and значки:
        первая = значки[0][0]
    итог = {"первая_мс": round(первая, 1) if первая is not None else None,
            "тиков": len(значки),
            "всего_значков": значки[-1][1] if значки else 0}

    # СОСТОЯНИЕ НА ПЕРВОЙ ОТРИСОВКЕ — тик, ближайший к ней снизу: rAF
    # срабатывает ПЕРЕД отрисовкой, значит этот слепок и есть содержимое
    # первого кадра.
    def на_отрисовке(ряд):
        подходят = [з for з in ряд if з[0] <= (первая or 0)]
        return (подходят or ряд or [None])[-1]

    з0 = на_отрисовке(значки)
    итог["заготовок_на_отрисовке"] = з0[2] if з0 else 0

    # КОГДА ЗНАЧКИ ДОРИСОВАЛИСЬ. Значок, приехавший разметкой, не опаздывает
    # никогда, и приписывать ему ноль миллисекунд ожидания было бы неправдой
    # в другую сторону — поэтому вопрос задаётся только там, где на первом
    # кадре заготовки БЫЛИ.
    итог["значки_мс"] = None
    итог["значки_не_успели"] = False
    if итог["заготовок_на_отрисовке"] > 0:
        for t, всего, пусто, _сост in значки:
            if пусто == 0:
                итог["значки_мс"] = round(t - первая, 1)
                break
        if итог["значки_мс"] is None:
            итог["значки_мс"] = float(окно_мс)      # не успели за окно
            итог["значки_не_успели"] = True

    # ПОДПИСЬ: НАХОДКА — ЛЮБАЯ СМЕНА ЗНАЧЕНИЯ ПОСЛЕ ПЕРВОЙ ОТРИСОВКИ,
    # а не расхождение первого значения с последним.
    #
    # Сравнение «первое против последнего» пропускает главный случай —
    # СМЕНУ ТУДА И ОБРАТНО. Именно она и есть мигание: было длинно, стало
    # коротко, снова длинно; концы совпали, а человек увидел рывок.
    # Поймано отрицательным контролем: подлог, возвращавший прежнее
    # поведение, проба не находила, потому что подпись успевала вернуться
    # к исходной строке внутри окна.
    #
    # Значение ДО первой отрисовки не считается: его никто не видел.
    # Поля могло ещё не быть — первая отрисовка случается на первом же
    # нарисованном содержимом и бывает раньше, чем разбор дошёл до шапки.
    видимые = [(t, з) for t, з in подпись
               if з is not None and t >= (первая or 0)]
    итог["подпись_на_отрисовке"] = видимые[0][1] if видимые else None
    итог["подпись_итог"] = видимые[-1][1] if видимые else None
    итог["подпись_мс"] = None
    for t, з in видимые:
        if з != итог["подпись_на_отрисовке"]:
            итог["подпись_мс"] = round(t - первая, 1)
            итог["подпись_итог"] = з
            break
    return итог


def _возврат(кадры):
    """ВОЗВРАТ: кадр совпал с более ранним ЧЕРЕЗ отличающийся.

    Монотонное доезжание страницы (картинка загрузилась, список пришёл
    с сервера) даёт цепочку РАЗНЫХ кадров и находкой не является:
    там ничего не мигает, там достраивается.
    """
    from PIL import Image
    разобрано = []
    for t, d in кадры:
        try:
            им = Image.open(io.BytesIO(base64.b64decode(d))).convert("RGB")
        except Exception:
            continue
        разобрано.append((t, им.size, им.tobytes()))
    for i in range(len(разобрано)):
        for j in range(i + 2, len(разобрано)):
            if разобрано[i][2] == разобрано[j][2]:
                середина = [к for к in разобрано[i + 1:j]
                            if к[2] != разобрано[i][2]]
                if середина:
                    return (разобрано[i][0], середина[0][0], разобрано[j][0])
    return None



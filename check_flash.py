# ── ДОКАЗАТЕЛЬСТВА ПОДЛОГОВ (§6.0.3) ────────────────────────────────
#
# «Проба назвала вид» доказательством НЕ является: назвать его она могла
# по другой причине, а подлог кладётся В СТРАНИЦУ через `add_init_script`
# и умеет провалиться МОЛЧА — исключение внутри страницы наружу
# не выходит. Комментарий выше называет ДВА случая, когда так и вышло:
# `observe(null)` и `setTimeout` после `DOMContentLoaded`. Оба раза
# контроль печатал «проба слепа» ПРО ЗРЯЧУЮ ПРОБУ.
#
# Доказательство — СВОЙ замер раннего состояния страницы: через 60 мс
# после старта записываются два числа. Логикой пробы (окно от первой
# отрисовки, кадры CDP-скринкаста) он не пользуется вовсе.
ЗАМЕР_РАННЕГО = """
(() => {
  const снять = () => ({
    заготовок: document.querySelectorAll('i[data-lucide]').length,
    подпись: (document.getElementById('nav-search-input') || {}).placeholder
  });
  window.__ранний = null;
  setTimeout(() => { window.__ранний = снять(); }, 60);
})();
"""


def доказать_подлог(подлог, путь="/admin/users"):
    """Раннее состояние страницы БЕЗ подлога и С ним.

    Возвращает пару строк «заготовок N, подпись …». Обе половины сразу:
    подлог значков двигает первое число, подлог подписи — вторую.
    """
    from playwright.sync_api import sync_playwright

    тело_cdn = _тело_чужого_скрипта()
    ответы = []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for текст in (None, подлог):
            кон = бр.new_context(viewport={"width": 2560, "height": 1400},
                                 device_scale_factor=1)
            стр = кон.new_page()
            ch._войти(стр)
            стр.add_init_script(ЗАМЕР_РАННЕГО)
            if текст:
                стр.add_init_script(текст)
            cdp = кон.new_cdp_session(стр)
            cdp.send("Network.setCacheDisabled", {"cacheDisabled": True})
            if тело_cdn is not None:
                def _чужой(маршрут):
                    time.sleep(ЗАДЕРЖКА_CDN_МС / 1000.0)
                    маршрут.fulfill(
                        status=200, body=тело_cdn,
                        headers={"content-type": "application/javascript",
                                 "cache-control": "no-store"})
                стр.route(ЧУЖОЙ_СКРИПТ, _чужой)
            стр.goto(БАЗА + путь, wait_until="load", timeout=45000)
            стр.wait_for_function("() => window.__ранний !== null",
                                  timeout=15000)
            р = стр.evaluate("() => window.__ранний")
            ответы.append("заготовок %s, подпись %r"
                          % (р["заготовок"], р["подпись"]))
            кон.close()
        бр.close()
    return ответы[0], ответы[1]



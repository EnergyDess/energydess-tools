"""ПРОВЕРКА 22: орган управления без видимого отклика на ФОКУС.

═══════════════════════════════════════════════════════════════════════
ЗАЧЕМ, ЕСЛИ ЕСТЬ ПРОВЕРКА 10
═══════════════════════════════════════════════════════════════════════

`check_hover` спрашивает про НАВЕДЕНИЕ и про залипание после касания.
Про фокус не спрашивает никто, а состояний у органа управления четыре
(`CLAUDE.md` §6.0.3): покой, наведение, фокус, после касания. Три
из четырёх закрыты машиной, четвёртое до 2026-08-21 проверялось фразой
«обход табом — 0 элементов без видимого отклика», записанной в отчёте
сессии. Вывод, записанный только в отчёте, не существует.

Отказ, который это ловит, немой и полный: человек, идущий по странице
клавиатурой, не видит, где он находится. Ошибки нет, консоль чиста,
мышью всё работает.

═══════════════════════════════════════════════════════════════════════
ДВЕ ЛОВУШКИ, ОБЕ ЗАМЕРЕНЫ
═══════════════════════════════════════════════════════════════════════

**Первая: `el.focus()` — не Tab.** `:focus-visible` браузер ставит
по эвристике ИСТОЧНИКА фокуса: от программного вызова на кнопке
в Chromium он не загорается. Проверка, сделанная через `el.focus()`,
печатала бы «отклика нет» у совершенно исправного элемента. Поэтому
обход идёт НАСТОЯЩИМИ нажатиями `Tab`.

**Вторая: кольцо рисуется НЕ ВСЕГДА НА САМОМ элементе.** Замер
2026-08-21: у `.ds-day` (день в полоске дневника) стоит `outline: none`,
а кольцо получает потомок `.ds-c`. Первая версия пробы читала только
`document.activeElement` и дала **14 ложных находок** на исправном коде —
ровно тот класс, из-за которого в §6.0.3 записано «сначала ДО против
ДО». Лечится подписью элемента ВМЕСТЕ С ПОДДЕРЕВОМ.

═══════════════════════════════════════════════════════════════════════
ЧЕГО НЕ ВИДИТ
═══════════════════════════════════════════════════════════════════════

  · отклик, который меняет НЕ вид, а, например, курсор или подсказку;
  · орган, до которого Tab не доходит за отведённые шаги (печатается
    число пройденных, чтобы это было видно);
  · достаточность контраста кольца — это вопрос к WCAG 1.4.11
    и отдельная мерка;
  · порядок обхода: проверка спрашивает «видно ли фокус», а не
    «разумен ли путь».

    py check_focus.py;            echo "код=$?"   # 0 — все отвечают
    py check_focus.py --контроль; echo "код=$?"   # 0 — проверка видит подлог
"""

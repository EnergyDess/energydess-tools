def метрики(моно=False):
    """Отношение ширин на живом тексте — по каждому ЛИЦУ запаса."""
    from playwright.sync_api import sync_playwright
    лица = ([("Consolas", "Windows"), ("monospace", "прочие")] if моно
            else [("Arial", "Windows/macOS/Linux"), ("Roboto", "Android")])
    сколько = ШИРИНЫ_МОНО if моно else ШИРИНЫ_ТЕКСТА
    итог = {}
    with sync_playwright() as p:
        бр = p.chromium.launch()
        сессия = _сессия(бр)
        for имя_лица, где in лица:
            о = з = 0.0
            знаков = 0
            for путь, имя, нужен_вход in ЭКРАНЫ:
                кон = бр.new_context(viewport={"width": 1440, "height": 900},
                                     storage_state=сессия if нужен_вход else None)
                стр = кон.new_page()
                стр.goto(БАЗА + путь, wait_until="domcontentloaded", timeout=45000)
                try:
                    стр.wait_for_load_state("networkidle", timeout=15000)
                except Exception:
                    pass
                лицо_css = ("monospace" if имя_лица == "monospace"
                            else "'%s'" % имя_лица)
                r = стр.evaluate(сколько, лицо_css)
                о += r["основной"]; з += r["запасной"]; знаков += r["знаков"]
                кон.close()
            итог[имя_лица] = (о, з, знаков, где)
        бр.close()
    print("МЕТРИКИ ШИРИНЫ НА ЖИВОМ ТЕКСТЕ (пять экранов, ширина 1440)%s"
          % (" — МОНОШИРИННЫЙ" if моно else ""))
    print("  %-10s %-22s %9s %11s %11s %9s" %
          ("лицо", "платформа", "знаков",
           "моно,px" if моно else "Manrope,px", "запасной,px", "size-adj"))
    for лицо, (о, з, знаков, где) in итог.items():
        нужно = 100.0 * о / з if з else 0.0
        print("  %-10s %-22s %9d %11.0f %11.0f %8.2f%%" %
              (лицо, где, знаков, о, з, нужно))
    print()
    print("size-adjust = ширина(Manrope) / ширина(голый системный) — при нём")
    print("запасная гарнитура занимает столько же места, и подмена")
    print("перестаёт двигать соседей ПО ГОРИЗОНТАЛИ.")
    return 0



def доказать_подлог(итог_до, итог_после):
    """ДОКАЗАТЕЛЬСТВО ПОДЛОГА, отдельное от вердикта пробы (§6.0.3).

    Вердикт «сдвинулось больше элементов» доказательством НЕ является:
    ровно столько же напечатала бы проба, если бы подлог не состоялся,
    а число выросло по другой причине. Доказательство здесь — замер
    МАКСИМУМА сдвига до и после наложения: подлог возвращает единицу
    `ch`, и максимум обязан вырасти скачком (замер 2026-08-31:
    20.7 -> 52.2 px). Не вырос — подлог не состоялся, и вердикт пробы
    про него не значит ничего.
    """
    м0 = max(з[4] for з in итог_до) if итог_до else 0.0
    м1 = max(з[4] for з in итог_после) if итог_после else 0.0
    return м0, м1, (м1 > м0 + 5)


def печать(итог, всего_дв, всего_cls, заголовок):
    print(заголовок)
    print("  %-6s %-10s %7s %8s %6s %6s %9s %8s  %s" %
          ("ширина", "экран", "элем.", "СДВИНУЛ", "ГОРИЗ", "ВЕРТ",
           "макс,px", "макс-В", "CLS"))
    в_всего = 0
    for (ш, имя, всего, дв, макс, имя_макс, cls,
         гор, вер, макс_в, имя_в) in итог:
        в_всего += вер
        print("  %-6d %-10s %7d %8d %6d %6d %9.1f %8.1f  %.4f%s" %
              (ш, имя, всего, дв, гор, вер, макс, макс_в, cls,
               ("  <- " + (имя_в if вер else имя_макс)) if дв else ""))
    print("  ИТОГО сдвинулось элементов: %d (из них ВЕРТИКАЛЬ: %d),"
          " суммарный CLS: %.4f" % (всего_дв, в_всего, всего_cls))
    print("  ГОРИЗОНТАЛЬ — блок занял другую ширину, СТОЯ НА МЕСТЕ;")
    print("  ВЕРТИКАЛЬ — то самое «уехало вниз», ради чего задача 158.")
    return всего_дв



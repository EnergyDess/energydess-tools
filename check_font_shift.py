# КАКИЕ ГАРНИТУРЫ ПОДМЕНЯТЬ. Переменной, а не ключом: обычный прогон
# обязан мерить ОБЕ (иначе он слеп к моноширинному, разбор у `ПОДМЕНА`),
# а вопрос «сколько стоит ОДИН моноширинный» задаётся отдельно
СЕМЬИ_ОБЕ = ["Manrope", "JetBrains Mono"]


def прогон(прежний=False, контроль=False, вернуть_ch=False,
           семьи=None):
    from playwright.sync_api import sync_playwright
    итог, всего_дв, всего_cls = [], 0, 0.0
    with sync_playwright() as p:
        бр = p.chromium.launch()
        сессия = _сессия(бр)
        for ш in ШИРИНЫ:
            # СВЕЖИЙ КОНТЕКСТ НА КАЖДУЮ ШИРИНУ — это и есть «пустой кеш».
            # Один контекст на все экраны кешировал бы шрифт после первой
            # страницы, и замер отвечал бы про F5, а не про Ctrl+Shift+R.
            for путь, имя, нужен_вход in ЭКРАНЫ:
                кон = бр.new_context(viewport={"width": ш, "height": 900},
                                     storage_state=сессия if нужен_вход else None)
                стр = кон.new_page()
                # Шрифт отбивается ВСЕГДА: снимок «до» обязан быть
                # запасной гарнитурой, иначе подмену мерить не с чем.
                стр.route("**/fonts.googleapis.com/**", lambda r: r.abort())
                стр.route("**/fonts.gstatic.com/**", lambda r: r.abort())
                стр.route("**/static/fonts/**", lambda r: r.abort())
                if прежний:
                    # ПРЕЖНЕЕ ПОВЕДЕНИЕ: запасной стек БЕЗ подогнанных
                    # метрик, ровно как до задачи 158. Один стенд, одна
                    # харнесса, разница в ОДНОЙ переменной — это и есть
                    # честное «до» против «после».
                    стр.add_init_script(
                        "addEventListener('DOMContentLoaded',()=>{"
                        "const s=document.createElement('style');"
                        "s.textContent=':root{--font:Manrope,-apple-system,"
                        "BlinkMacSystemFont,sans-serif}';"
                        "document.head.appendChild(s);})")
                if вернуть_ch:
                    стр.add_init_script(ВЕРНУТЬ_CH)
                стр.add_init_script(ЗАМЕР)
                стр.goto(БАЗА + путь, wait_until="domcontentloaded", timeout=45000)
                # ДАЁМ СТРАНИЦЕ УСТОЯТЬСЯ ДО снимка. Прежде снимок «до»
                # брался сразу после domcontentloaded, и в разницу попадала
                # АСИНХРОННАЯ ДОГРУЗКА данных: карточки аптечки и дневник
                # рисуются после fetch. Числа от этого скакали на одном
                # и том же коде — 0 против 391 у одного экрана, — то есть
                # мерили не то, что подписано (§6.0.3).
                try:
                    стр.wait_for_load_state("networkidle", timeout=15000)
                except Exception:
                    pass
                стр.wait_for_timeout(700)
                до = стр.evaluate("window.__snap()")
                # ТЕПЕРЬ И ТОЛЬКО ТЕПЕРЬ подменяем гарнитуру — ровно то,
                # что делает браузер, когда доезжает шрифт при swap.
                if контроль:
                    # ПОДЛОГ: гарнитура меняется на заведомо другую
                    # по метрикам. Проба ОБЯЗАНА это увидеть; не увидела —
                    # она слепа, и её ноль на исправном коде не значит
                    # ничего (§6.0.3).
                    стр.evaluate(
                        "document.documentElement.style.setProperty("
                        "'--font', \"'Courier New', monospace\")")
                    стр.wait_for_timeout(400)
                else:
                    # перехват снимаем: иначе отбитым окажется и тот
                    # запрос, которым мы шрифт и подсовываем
                    стр.unroute("**/static/fonts/**")
                    стр.evaluate(ПОДМЕНА, семьи or СЕМЬИ_ОБЕ)
                    стр.wait_for_timeout(500)
                после = стр.evaluate("window.__snap()")
                cls = стр.evaluate("window.__cls") or 0.0
                (дв, макс, имя_макс, гор, вер,
                 макс_в, имя_в) = _сравнить(до, после, ПОРОГ)
                итог.append((ш, имя, len(до), дв, макс, имя_макс, cls,
                             гор, вер, макс_в, имя_в))
                всего_дв += дв
                всего_cls += cls
                кон.close()
        бр.close()
    return итог, всего_дв, всего_cls



# ── РЕЖИМ --метрики ──────────────────────────────────────────────────
# CSS ссылался на него с задачи 158, а В КОДЕ ЕГО НЕ БЫЛО: строка
# «py check_font_shift.py --метрики» стояла в шапке static/style.css,
# и прогон отвечал обычным замером — то есть документ обещал число,
# которого никто не считал. Заведён 2026-08-31 (задача 217).
#
# Считается отношение ширины НАСТОЯЩЕГО текста страниц: сколько
# занимает строка в Manrope и сколько — в ГОЛОМ системном шрифте
# (без size-adjust). Частное и есть искомый size-adjust: при нём
# запасная гарнитура занимает столько же места, сколько основная,
# и подмена перестаёт двигать соседей по горизонтали.
ШИРИНЫ_ТЕКСТА = """(async (лицо) => {
  const кир = new FontFace('MW', "url('/static/fonts/manrope-cyrillic.woff2')", {weight:'400 800'});
  const лат = new FontFace('MW', "url('/static/fonts/manrope-latin.woff2')", {weight:'400 800'});
  await Promise.all([кир.load(), лат.load()]);
  document.fonts.add(кир); document.fonts.add(лат);
  await document.fonts.ready;
  // ЖИВОЙ текст страницы, а не выдуманная проба: отношение ширин
  // зависит от набора знаков, и на прописных оно другое.
  const куски = [];
  document.querySelectorAll('body *').forEach(э => {
    if (э.children.length) return;
    const s = (э.textContent || '').trim();
    if (s.length > 2) куски.push([s, getComputedStyle(э).fontWeight,
                                  getComputedStyle(э).fontSize]);
  });
  const м = document.createElement('span');
  м.style.cssText = 'position:absolute;left:-9999px;top:0;white-space:pre;';
  document.body.appendChild(м);
  const мерь = (сем) => {
    let s = 0;
    for (const [txt, w, fs] of куски) {
      м.style.fontFamily = сем; м.style.fontWeight = w; м.style.fontSize = fs;
      м.textContent = txt; s += м.getBoundingClientRect().width;
    }
    return s;
  };
  const основной = мерь("'MW'");
  const запасной = мерь(лицо);
  м.remove();
  return {знаков: куски.reduce((a,[s])=>a+s.length,0), строк: куски.length,
          основной: основной, запасной: запасной};
})"""



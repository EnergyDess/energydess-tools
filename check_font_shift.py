def _сравнить(до, после, порог):
    """Что переехало между двумя снимками, В РАЗБИВКЕ ПО ОСЯМ.

    Ключ — ПОРЯДКОВЫЙ НОМЕР в дереве: класс не уникален, а по нему
    пары склеились бы неверно.

    РАЗБИВКА ЗАВЕДЕНА 2026-08-31 (задача 217), и без неё общее число
    отвечает не на тот вопрос. Замер: из 1176 находок 1071 (91 %) —
    ГОРИЗОНТАЛЬ, то есть текстовый блок занял другую ширину, стоя
    на месте. Владелец жаловался на ВЕРТИКАЛЬНЫЙ переезд («плашка
    уезжает вниз»), а их было 105, и все на одном экране. Голое
    «1176» читалось как «страница едет вся», и это неправда.
    """
    б = {э[0]: э for э in после}
    двинулось, макс, имя_макс = 0, 0.0, ""
    гориз, верт, макс_в, имя_в = 0, 0, 0.0, ""
    for э in до:
        п = б.get(э[0])
        if not п or п[1] != э[1]:
            continue
        dx, dy = abs(п[2] - э[2]), abs(п[3] - э[3])
        dw, dh = abs(п[4] - э[4]), abs(п[5] - э[5])
        д = max(dx, dy, dw, dh)
        if д <= порог:
            continue
        двинулось += 1
        if д > макс:
            макс, имя_макс = д, э[1]
        в = max(dy, dh)
        if в > порог:
            верт += 1
            if в > макс_в:
                макс_в, имя_в = в, э[1]
        else:
            гориз += 1
    return двинулось, макс, имя_макс, гориз, верт, макс_в, имя_в


def _сессия(бр):
    """Кука входа, снятая ОТДЕЛЬНЫМ контекстом.

    Иначе замер врал бы дважды. Без входа `/profile`, `/medkit`
    и `/nutrition` отдают страницу ВХОДА — прошлый прогон снял её
    трижды под тремя разными подписями. А войти в том же контексте,
    в котором меряем, значит СОГРЕТЬ КЕШ шрифта на странице входа:
    дальше мерился бы F5, а дефект живёт при Ctrl+Shift+R.
    """
    кон = бр.new_context(viewport={"width": 1280, "height": 900})
    стр = кон.new_page()
    стр.goto(БАЗА + "/login", wait_until="domcontentloaded", timeout=45000)
    стр.fill("input[name=email]", ПОЧТА)
    стр.fill("input[name=password]", ПАРОЛЬ)
    стр.click("button[type=submit]")
    стр.wait_for_load_state("domcontentloaded")
    стр.wait_for_timeout(700)
    if "/login" in стр.url:
        raise SystemExit("ВХОД НЕ ПРОШЁЛ: остались на %s" % стр.url)
    состояние = кон.storage_state()
    кон.close()
    return состояние



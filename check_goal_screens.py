# -*- coding: utf-8 -*-
"""СЪЁМКА ЭКРАНОВ ДНЕВНИКА: три состояния ЗНАМЕНАТЕЛЯ на трёх ширинах.

═══════════════════════════════════════════════════════════════════════
ЧТО СНИМАЕТСЯ И ЗАЧЕМ ИМЕННО ЭТО
═══════════════════════════════════════════════════════════════════════

С задачи 95 у дня дневника три РАЗНЫХ состояния знаменателя, и снаружи
они выглядят почти одинаково — в этом и была вся беда:

  · норма дня и есть действующая  → строки под кольцом НЕТ вовсе;
  · норма дня своя, более старая  → «Норма этого дня — 2100 ккал,
                                     действует с 21 июня»;
  · нормы за день не записано     → кольцо ПУСТОЕ, полоски макросов
                                     пустые, строка словами.

Клетка КАЛЕНДАРЯ сюда не входит с 2026-08-21: там доля считается
от действующей нормы, и знак от прочих не отличается (решение
владельца, CLAUDE.md §5.0.9). Этот скрипт снимает ЭКРАН ОДНОГО ДНЯ —
кольцо и строку под ним, — и на него отмена не распространяется.

Первое состояние — молчание, и его тоже надо увидеть: строка, которая
появляется всегда, перестаёт читаться на третий день.

═══════════════════════════════════════════════════════════════════════
ПОЧЕМУ ЭТО ФАЙЛ В РЕПОЗИТОРИИ, А НЕ СКРИПТ В СКРЕТЧПАДЕ
═══════════════════════════════════════════════════════════════════════

Та же причина, что у `check_hover.py` и `check_scale_screens.py`:
инструмент съёмки писался заново каждый заход, и знание о ловушках
эмуляции терялось трижды. Здесь оно не переписано и не скопировано —
ИМПОРТИРОВАНО из `check_hover`: `_включить_сенсор`, `_сверить`,
`_снимок`, `_войти`. Вторая копия разошлась бы с первой молча.

ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Не проверка: понятия «правильно» у неё нет, код
возврата всегда 0 (кроме падения). Снимает кадры и печатает числа,
смотрит на них человек. В ряд одиннадцати §6.0.2 не входит — ей нужны
браузер и поднятое приложение.

СОСТОЯНИЯ ЭЛЕМЕНТА (CLAUDE.md §6.0.3): покой, наведение с ожиданием
конца перехода, фокус НАСТОЯЩИМ Tab, состояние после касания.
Один снимок состоянием не является.

ДАННЫЕ. Даты берутся не из воздуха и не вписаны сюда числами:
`py make_local_user.py --seed` кладёт три строки журнала норм, и день
для каждого состояния ищется ПО ЖУРНАЛУ, прочитанному с сервера.
Вписанная руками дата разъехалась бы с сидированием молча — и съёмка
продолжила бы печатать кадры, просто уже не про то.

ЗАПУСК

    py make_local_user.py --seed
    py -m uvicorn main:app --port 8899
    py check_goal_screens.py
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")

import check_hover as ch     # noqa: E402

КУДА = os.environ.get("SHOTS_DIR", "C:/Temp/claude/goals")
ПАУЗА = ch.ПАУЗА_ПЕРЕХОДА

# Ширины: 1440 — обычный десктоп, 2560 — широкий монитор (у дневника там
# своя раскладка на `--nut-u`, CLAUDE.md §2.3), 390 с сенсором — телефон.
ШИРИНЫ = [(1440, 900, False), (2560, 1440, False), (390, 844, True)]


def _текст(стр, селектор):
    return стр.evaluate(
        "(с) => { const э = document.querySelector(с);"
        "  return (э && э.offsetParent !== null) ? э.innerText.trim() : null; }",
        селектор)


def _дни_состояний(стр):
    """Три дня — по одному на состояние знаменателя. Ищутся ПО ДАННЫМ.

    Берём журнал норм с сервера через тот же `/nutrition/api/diary`,
    которым живёт экран, и подбираем дни: до первой записи журнала,
    между первой и последней, и сегодня. Захардкодить их означало бы
    привязаться к сидированию, которое правится отдельно."""
    return стр.evaluate("""async () => {
        const сег = document.body.dataset.today
                 || (await (await fetch('/nutrition/api/diary-days')).json()).today;
        // Идём назад по дням и берём первый попавшийся каждого вида
        const найдено = {действующая: сег, старая: null, нет: null};
        for (let i = 1; i <= 130 && (!найдено.старая || !найдено.нет); i++) {
            const д = new Date(сег + 'T00:00:00');
            д.setDate(д.getDate() - i);
            const дата = д.toISOString().slice(0, 10);
            const о = await (await fetch('/nutrition/api/diary?date=' + дата)).json();
            if (!о.goals_meta) continue;
            if (!о.goals_meta.known && !найдено.нет) найдено.нет = дата;
            else if (о.goals_meta.known && !о.goals_meta.is_current && !найдено.старая)
                найдено.старая = дата;
        }
        return найдено;
    }""")


def _состояние_экрана(стр):
    """Что видно на экране прямо сейчас — числами, а не на глаз."""
    return стр.evaluate("""() => {
        const т = с => { const э = document.querySelector(с);
                         return э ? э.textContent.trim() : null; };
        const note = document.getElementById('goal-note');
        const кольцо = document.getElementById('ring-fill');
        return {
            строка_нормы: (note && !note.hidden) ? note.textContent.trim() : null,
            строка_скрыта: !note || note.hidden,
            неизвестна: !!(note && note.classList.contains('is-unknown')),
            крупное_число: т('#ring-remain'),
            подпись_кольца: т('#ring-lbl'),
            под_кольцом: т('#ring-eaten'),
            дуга_заполнена: кольцо
                ? Math.round(parseFloat(getComputedStyle(кольцо).strokeDashoffset)) <
                  Math.round(parseFloat(getComputedStyle(кольцо).strokeDasharray)) - 1
                : null,
            белок: т('#val-prot'),
            ширина_полосы_белка: (document.getElementById('bar-prot') || {}).style?.width,
            вода: т('#water-val'),
        };
    }""")


def _календарь(стр):
    return стр.evaluate("""() => {
        const клетки = [...document.querySelectorAll('#cal-grid .cal-c')];
        const без = клетки.filter(к => к.querySelector('.cal-bar.is-nogoal')).length;
        const с = клетки.filter(к => к.querySelector('.cal-bar-f')).length;
        const осн = document.getElementById('mo-basis');
        return {клеток: клетки.length, с_полоской: с, без_полоски: без,
                подпись: осн ? осн.textContent.trim() : null,
                титул_первой_без: (клетки.find(к => к.querySelector('.cal-bar.is-nogoal'))
                                   || {}).title || null};
    }""")


def снять(ширина, высота, сенсор):
    from playwright.sync_api import sync_playwright

    метка = f"{ширина}-{'touch' if сенсор else 'desk'}"
    отчёт = []
    os.makedirs(КУДА, exist_ok=True)
    with sync_playwright() as p:
        бр = p.chromium.launch()
        к = бр.new_context(viewport={"width": ширина, "height": высота},
                           has_touch=сенсор, is_mobile=сенсор)
        стр = к.new_page()
        cdp = к.new_cdp_session(стр)
        if сенсор:
            ch._включить_сенсор(cdp)
        ch._войти(стр)
        if сенсор:
            ch._включить_сенсор(cdp)

        стр.goto(f"{ch.БАЗА}/nutrition", wait_until="domcontentloaded", timeout=45000)
        стр.wait_for_timeout(2000)
        ch._сверить(стр, сенсор, f"{метка}: после загрузки дневника")

        дни = _дни_состояний(стр)
        отчёт.append(("дни состояний (найдены по данным)", дни))

        for имя in ("действующая", "старая", "нет"):
            дата = дни.get(имя)
            if not дата:
                отчёт.append((f"состояние «{имя}»",
                              "В ДАННЫХ НЕ НАЙДЕНО — сидирование не наполнило"))
                continue
            стр.evaluate("(д) => selectDay(д)", дата)
            стр.wait_for_timeout(1200)
            ch._сверить(стр, сенсор, f"{метка}: день {дата} ({имя})")
            отчёт.append((f"состояние «{имя}» — {дата}", _состояние_экрана(стр)))
            ch._снимок(стр, cdp, сенсор, f"{КУДА}/дневник-{имя}-{метка}.png")

            # ── ЧЕТЫРЕ СОСТОЯНИЯ ЭЛЕМЕНТА (§6.0.3) ──────────────────────
            # Строка про норму — не кнопка, но она стоит внутри карточки,
            # у которой есть и наведение, и фокус: снимать её в одном
            # состоянии значит не смотреть туда, где дефект живёт
            цель = "#goal-note"
            видна = стр.evaluate(
                "(с) => { const э = document.querySelector(с);"
                "  return !!э && !э.hidden && э.offsetParent !== null; }", цель)
            if not видна:
                # Состояние «норма дня и есть действующая»: строки НЕТ,
                # и это правильный вид, а не пропущенный элемент. Состояний
                # у скрытого элемента не бывает — записываем и идём дальше,
                # а не притворяемся, что сняли четыре
                отчёт.append((f"«{имя}»: состояния элемента",
                              "строки нет — снимать нечего (это и есть молчание)"))
            if видна:
                if not сенсор:
                    стр.hover(цель)
                    стр.wait_for_timeout(ПАУЗА)
                    ch._снимок(стр, cdp, сенсор,
                               f"{КУДА}/дневник-{имя}-{метка}-наведение.png")
                    стр.keyboard.press("Tab")
                    стр.wait_for_timeout(ПАУЗА)
                    ch._снимок(стр, cdp, сенсор,
                               f"{КУДА}/дневник-{имя}-{метка}-фокус-tab.png")
                else:
                    стр.tap(цель)
                    стр.wait_for_timeout(ПАУЗА)
                    ch._снимок(стр, cdp, сенсор,
                               f"{КУДА}/дневник-{имя}-{метка}-после-касания.png")
                ch._сверить(стр, сенсор, f"{метка}: после состояний элемента")

            # Перелив строки за карточку — на 390 главный вопрос
            отчёт.append((f"«{имя}»: строка вылезла вправо",
                          стр.evaluate("""(с) => { const э = document.querySelector(с);
                            if (!э || э.hidden) return 'строки нет';
                            const р = э.getBoundingClientRect();
                            return Math.round(р.right - document.documentElement.clientWidth);
                          }""", цель)))

        # ── Вкладка «История»: календарь ───────────────────────────────
        стр.click("[data-tab='history']")
        стр.wait_for_timeout(1400)
        ch._сверить(стр, сенсор, f"{метка}: вкладка История")
        отчёт.append(("подпись даты истории", _текст(стр, "#h-date-lbl")))
        отчёт.append(("строка нормы в истории", _текст(стр, "#h-goal-note")))

        # МЕСЯЦ НАДО ПЕРЕВЕСТИ ЯВНО, и это не мелочь. Календарь открывается
        # на ТЕКУЩЕМ месяце независимо от выбранного дня, а клетки без нормы
        # лежат в прошлом. Первая версия этой съёмки печатала «без полоски: 0»
        # и выглядела успешной — просто смотрела не на тот месяц (§6.0.3:
        # один снимок состоянием не является, и «не то место» тот же случай).
        for имя, месяц in (("текущий", None),
                           ("месяц дня без нормы", (дни.get("нет") or "")[:7])):
            if месяц:
                стр.evaluate("(м) => { S.calMonth = м; loadCalendar(); }", месяц)
                стр.wait_for_timeout(1200)
            отчёт.append((f"календарь, {имя}", _календарь(стр)))
            ch._снимок(стр, cdp, сенсор,
                       f"{КУДА}/история-{метка}-{'месяц-без-нормы' if месяц else 'текущий'}.png")

        # Горизонтальная прокрутка страницы — её быть не должно нигде
        отчёт.append(("горизонтальная прокрутка страницы",
                      стр.evaluate("() => document.documentElement.scrollWidth > "
                                   "document.documentElement.clientWidth")))
        ch._сверить(стр, сенсор, f"{метка}: в конце прогона")
        бр.close()
    return метка, отчёт


def главная():
    print("═" * 74)
    print("СЪЁМКА ДНЕВНИКА: три состояния знаменателя (задача 95)")
    print(f"кадры: {КУДА}")
    print("═" * 74)
    for ширина, высота, сенсор in ШИРИНЫ:
        метка, отчёт = снять(ширина, высота, сенсор)
        print(f"\n■ {метка}")
        for имя, значение in отчёт:
            print(f"   · {имя}: {значение}")
    print("\nКадры сняты. Это НЕ проверка — смотрит человек.")
    return 0


if __name__ == "__main__":
    sys.exit(главная())

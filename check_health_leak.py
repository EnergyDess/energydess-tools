def имена_из_базы(путь):
    """Названия позиций ЖИВЫХ людей. Возвращает (имена, всего, стендовых)."""
    if not os.path.exists(путь):
        return None, 0, 0
    c = sqlite3.connect("file:%s?mode=ro" % путь.replace("?", ""), uri=True)
    строки = c.execute("""
        SELECT m.name, u.email FROM medkit_items m
        JOIN users u ON u.id = m.user_id""").fetchall()
    c.close()
    живые, стенд = set(), 0
    for имя, почта in строки:
        if (почта or "").lower().endswith(СТЕНД):
            стенд += 1
        elif имя:
            живые.add(имя.strip())
    return живые, len(строки), стенд


def куски(имена):
    """Название целиком ПЛЮС его опознающие слова.

    Одного полного совпадения не хватает, и это замер, а не осторожность:
    у составного названия в текстах жило голое первое слово, и сверка
    по полным строкам напечатала «ноль» при четырёх десятках вхождений.
    """
    из = {}
    for имя in имена:
        для = {имя.lower()}
        for w in re.findall(r"[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z-]{4,}", имя):
            if w.lower() not in ОБЩИЕ:
                для.add(w.lower())
        for к in для:
            из.setdefault(к, имя)
    return из


ТРАНСЛИТ = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}
ТРАНСЛИТ_МИН = 6      # короче — ловит обычные латинские слова в путях


def транслит(с):
    """Латинское написание кириллического слова.

    Таблица одна и общая; официальное написание бренда с ней совпадает
    не всегда. Это ПРОПУСК, а не ложь: имя, набранное иначе, просто
    не найдётся, и на кириллический признак это не влияет.
    """
    return "".join(ТРАНСЛИТ.get(з, з) for з in с.lower())


def отслеживаемые():
    з = subprocess.run(["git", "ls-files", "-z"], capture_output=True).stdout
    return [f for f in з.decode("utf-8").split("\0") if f]


def признаки_имени(из):
    """Признаки для ИМЕНИ файла: кириллический кусок плюс его транслит."""
    поимени = {}
    for к, полное in из.items():
        поимени[к] = полное
        л = транслит(к)
        if len(л) >= ТРАНСЛИТ_МИН and л != к:
            поимени.setdefault(л, полное)
    return поимени


def найти(из, пропустить=()):
    """Находки ТЕКСТА и ИМЕНИ. Вид у находки свой: путь в отчёте один
    и тот же, а лечение разное — текст правится, файл переименовывают
    либо убирают из-под git вовсе."""
    поимени = признаки_имени(из)
    находки = []
    for f in отслеживаемые():
        if f in пропустить:
            continue
        путь = f.lower()
        for к, полное in поимени.items():
            if к in путь:
                находки.append((f, полное, к, 1, "имя"))
        try:
            t = io.open(f, encoding="utf-8", errors="ignore").read()
        except Exception:
            continue
        н = t.lower()
        for к, полное in из.items():
            c = н.count(к)
            if c:
                находки.append((f, полное, к, c, "текст"))
    return находки


def прогон(пропустить=()):
    имена, всего, стенд = имена_из_базы(БАЗА)
    if имена is None:
        print("НЕЧЕМ ПРОВЕРИТЬ: базы «%s» нет." % БАЗА)
        print("Проверка сверяет репозиторий с ЖИВОЙ базой; без неё")
        print("«утечки нет» и «не смотрели» неразличимы — код 2, не 0.")
        return 2, []
    if not имена:
        print("ПРОВЕРЯТЬ НЕЧЕГО: в базе «%s» нет позиций живых людей" % БАЗА)
        print("(записей всего %d, все стендовые: %d)." % (всего, стенд))
        print("Это НЕ «чисто»: стендовая база о боевых названиях молчит.")
        print("Укажите копию прода: MEDKIT_GUARD_DB=copy.db")
        return 2, []
    из = куски(имена)
    находки = найти(из, пропустить)
    print("позиций живых людей в базе: %d, признаков поиска: %d"
          % (len(имена), len(из)))
    if not находки:
        print("НАЗВАНИЙ ЛЕКАРСТВ ЖИВОГО ЧЕЛОВЕКА В РЕПОЗИТОРИИ НЕТ.")
        return 0, находки
    # Само название наружу НЕ печатаем: вывод попадает в журналы и отчёты.
    поф, вид = {}, {}
    for f, _полное, к, c, в in находки:
        поф[f] = поф.get(f, 0) + c
        вид.setdefault(f, set()).add(в)
    имён = sum(1 for f in поф if "имя" in вид[f])
    print("УТЕЧКА: файлов %d, вхождений %d (из них по ИМЕНИ файла: %d)"
          % (len(поф), sum(поф.values()), имён))
    for f, c in sorted(поф.items(), key=lambda x: -x[1]):
        print("  %-44s %4d  %s" % (f, c, "+".join(sorted(вид[f]))))
    print("Сами названия НЕ печатаются — вывод уходит в отчёты и журналы.")
    print("Найти их: MEDKIT_GUARD_SHOW=1 py check_health_leak.py")
    if os.getenv("MEDKIT_GUARD_SHOW"):
        for f, полное, к, c, в in находки:
            print("  %s [%s] : %s (по «%s») %d" % (f, в, полное, к, c))
    return 1, находки


def _подложить(путь, содержимое):
    io.open(путь, "w", encoding="utf-8").write(содержимое)
    subprocess.run(["git", "add", "-f", путь], capture_output=True)


def _убрать(путь):
    subprocess.run(["git", "rm", "-q", "-f", "--cached", путь],
                   capture_output=True)
    if os.path.exists(путь):
        os.remove(путь)


def контроль():
    """Отрицательный контроль. ПОДЛОГОВ ДВА, и они разной природы:
    настоящее имя из живой базы в СОДЕРЖИМОМ файла и оно же (плюс
    транслит) в ИМЕНИ файла. У каждого своё ДОКАЗАТЕЛЬСТВО (§6.0.3) —
    независимый замер того, что подлог вообще состоялся.

    Второй подлог заведён 2026-08-31 и НЕМЕДЛЕННО показал границу
    прежнего заслона: имя в имени файла он не ловил вовсе — код 0
    при двух подложенных файлах.
    """
    имена, _, _ = имена_из_базы(БАЗА)
    if not имена:
        print("КОНТРОЛЬ НЕВОЗМОЖЕН: в базе нет позиций живых людей.")
        return 2
    чисто, _ = прогон()
    if чисто != 0:
        print("КОНТРОЛЬ НЕДЕЙСТВИТЕЛЕН: репозиторий уже НЕ чист.")
        print("«Нашла подлог» и «нашла прежнее» на грязной основе неразличимы.")
        return 2
    имя = sorted(имена)[0]
    ладно = True

    print()
    print("ПОДЛОГ 1 — имя в СОДЕРЖИМОМ")
    путь = "_leak_control.md"
    _подложить(путь, "Временный файл отрицательного контроля.\n"
                     "Замер: %s, 2 упаковки.\n" % имя)
    было = io.open(путь, encoding="utf-8").read().lower().count(имя.lower())
    код, находки = прогон()
    _убрать(путь)
    поймано = any(f == путь and в == "текст" for f, _п, _к, _c, в in находки)
    print("  ДОКАЗАТЕЛЬСТВО: вхождений имени в подложенном файле %d" % было)
    print("  ВЕРДИКТ: код %d, файл %sназван видом «текст»"
          % (код, "" if поймано else "НЕ "))
    ладно = ладно and было and поймано and код == 1

    print()
    print("ПОДЛОГ 2 — имя в ИМЕНИ ФАЙЛА")
    слово = sorted(куски({имя}), key=len)[-1]
    пути = ["_leak_%s-390.png" % слово, "_leak_%s-390.png" % транслит(слово)]
    пути = list(dict.fromkeys(пути))
    # содержимое ДВОИЧНОЕ и имени НЕ содержит: иначе подлог доказывал бы
    # прежний путь поиска, а не новый.
    for п in пути:
        io.open(п, "wb").write(b"\x89PNG\r\n\x1a\n binary noise only")
        subprocess.run(["git", "add", "-f", п], capture_output=True)
    внутри = max(io.open(п, "rb").read().lower().count(
        слово.lower().encode("utf-8")) for п in пути)
    код2, находки2 = прогон()
    for п in пути:
        _убрать(п)
    названы = {f for f, _п, _к, _c, в in находки2 if в == "имя"}
    print("  ДОКАЗАТЕЛЬСТВО: подложено файлов %d, вхождений имени"
          " в их СОДЕРЖИМОМ %d (обязан быть 0)" % (len(пути), внутри))
    print("  ВЕРДИКТ: код %d, названо по имени %d из %d"
          % (код2, len(названы & set(пути)), len(пути)))
    ладно = (ладно and внутри == 0 and код2 == 1
             and (названы & set(пути)) == set(пути))

    print()
    if ладно:
        print("КОНТРОЛЬ ПРОЙДЕН: 2 подлога из 2.")
        return 0
    print("КОНТРОЛЬ НЕ ПРОЙДЕН.")
    return 1


def коммиты():
    """Коммиты, добавлявшие в историю названия из живой базы.

    Нужен затем, чтобы решение о переписывании истории принималось
    по СПИСКУ, а не по памяти. Имена сюда не печатаются — только
    хеши, даты и темы (§5.1: вывод уходит в отчёты)."""
    имена, _, _ = имена_из_базы(БАЗА)
    if not имена:
        print("НЕЧЕМ: в базе «%s» нет позиций живых людей." % БАЗА)
        return 2
    из = куски(имена)
    все = {}
    for к in из:
        з = subprocess.run(["git", "log", "--all",
                            "--format=%H\t%ad\t%s",
                            "--date=short", "-S", к],
                           capture_output=True)
        for стр in з.stdout.decode("utf-8", "ignore").split("\n"):
            if "	" in стр:
                х, дата, тема = стр.split("	", 2)
                все[х] = (дата, тема)
    print("КОММИТОВ, НЕСУЩИХ НАЗВАНИЯ ИЗ ЖИВОЙ БАЗЫ: %d" % len(все))
    for х, (дата, тема) in sorted(все.items(), key=lambda x: x[1][0]):
        print("  %s  %s  %s" % (х[:9], дата, тема[:64]))
    return 0 if not все else 1


if __name__ == "__main__":
    if "--коммиты" in sys.argv:
        sys.exit(коммиты())
    if "--контроль" in sys.argv:
        sys.exit(контроль())
    sys.exit(прогон()[0])

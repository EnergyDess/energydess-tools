    "новый", "актив", "кардио", "баланс", "мульти", "multi", "super", "orange",
    "sip", "гидро", "лакто", "холестерин", "кишечника", "кишечник",
    "желудка", "горла", "носа", "мега", "супер", "мульти", "максимум",
    # ── СЛОВА, КОТОРЫЕ ОКАЗАЛИСЬ ТЕХНИЧЕСКИМИ ТЕРМИНАМИ ─────────────
    #
    # Добавлены 2026-09-03 (BACKLOG №238) по ЗАМЕРУ, а не на глаз.
    # Аптечка выросла до 49 позиций, и среди названий появились такие,

    # вычитаются только из ОПОЗНАЮЩИХ. Цена названа честно и она есть:
    # название, СОСТАВЛЕННОЕ ЦЕЛИКОМ из общих слов, ловится теперь
    # только полной строкой. Проверено контролем — см. `--контроль`.
    "контейнер", "контейнеры", "стерильный", "стерильные",
    # ХИМИЧЕСКИЕ ОСТАТКИ. «Натрия» и «хлорид» стоят в составе десятков

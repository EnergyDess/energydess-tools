# -*- coding: utf-8 -*-
"""ПРОВЕРКА 26: НАЗВАНИЕ ЛЕКАРСТВА ЖИВОГО ЧЕЛОВЕКА В ОТСЛЕЖИВАЕМОМ ТЕКСТЕ.

Репозиторий публичный (§5.1), а названия лекарств — сведения о здоровье.
Утекают они ДВУМЯ путями, и прежде не закрывался ни один:

  · ФАЙЛОМ ДАННЫХ — кеш страниц справочника, дамп базы, снимок. Закрыт
    `.gitignore`, и это половина: игнор молчит про то, чего в нём нет;
  · ТЕКСТОМ — замер в `BACKLOG.md`, пример в комментарии, фикстура
    в тесте. Замер 2026-08-30 нашёл 21 боевое название на 428 местах
    в 22 файлах, и НИ ОДНА из проверок ряда этого не видела: они
    сверяют код с документами, а не документы с базой.

СПИСКА НАЗВАНИЙ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ. Вписать его значило бы
закоммитить ровно то, от чего защищаемся. Имена берутся ИЗ ЖИВОЙ БАЗЫ
при каждом прогоне и живут только в памяти процесса.

ЧЬИ ИМЕНА ПРОВЕРЯТЬ, РЕШАЕТСЯ СТРУКТУРНО, А НЕ ПЕРЕЧНЕМ. Позиция
принадлежит пользователю; аккаунты стенда — `@local.dev` (§8.0), их
позиции ЗАВОДИТ СЕМЯ и они лежат в репозитории законно. Всё остальное —
данные живого человека. Перечень исключаемых имён был бы лазейкой:
настоящее название, попавшее в семя, освобождалось бы от проверки
(§6.0.7). Здесь освобождает не имя, а ВЛАДЕЛЕЦ записи.

БАЗА НЕ НАЙДЕНА — код 2 И ГОВОРИТ ОБ ЭТОМ. «Проверить нечем»
и «утечки нет» обязаны различаться: молчаливый ноль тут — тот самый
немой отказ, ради которого файл и написан (§6.0.1).

    py check_health_leak.py                 # 0 — чисто, 1 — утечка, 2 — нечем
    MEDKIT_GUARD_DB=copy.db py check_health_leak.py    # против копии прода
    py check_health_leak.py --контроль      # отрицательный контроль
"""
import io, os, re, sqlite3, subprocess, sys

БАЗА = os.getenv("MEDKIT_GUARD_DB", "app.db")
СТЕНД = "@local.dev"          # признак синтетического аккаунта, §8.0

# Слова, которые сами по себе человека не опознают: форма выпуска, единица,
# общие части названий. Список ОБЩИЙ, не про конкретную аптечку, поэтому
# коммитится без вреда. Нужен затем, чтобы слово формы
# из составного названия не объявляло находкой каждое такое слово
# в проекте.
ОБЩИЕ = {
    "сироп", "таблетки", "капли", "капсулы", "мазь", "гель", "крем", "спрей",
    "раствор", "порошок", "суспензия", "свечи", "суппозитории", "пакетики",
    "ампулы", "комплекс", "экстракт", "корня", "корней", "густой", "форте",
    "ретард", "витамин", "витамины", "детей", "плюс", "макс", "для", "и",
    "новый", "актив", "кардио", "баланс", "мульти", "multi", "super", "orange",
    "sip", "гидро", "лакто", "холестерин", "кишечника", "кишечник",
    "желудка", "горла", "носа", "мега", "супер", "мульти", "максимум",
}

def имена_из_базы(путь):
    """Названия позиций ЖИВЫХ людей. Возвращает (имена, всего, стендовых)."""
    if not os.path.exists(путь):
        return None, 0, 0
    c = sqlite3.connect("file:%s?mode=ro" % путь.replace("?", ""), uri=True)
    строки = c.execute("""
        SELECT m.name, u.email FROM medkit_items m
        JOIN users u ON u.id = m.user_id""").fetchall()
    c.close()
    живые, стенд = set(), 0
    for имя, почта in строки:
        if (почта or "").lower().endswith(СТЕНД):
            стенд += 1
        elif имя:
            живые.add(имя.strip())
    return живые, len(строки), стенд


def куски(имена):
    """Название целиком ПЛЮС его опознающие слова.

    Одного полного совпадения не хватает, и это замер, а не осторожность:
    у составного названия в текстах жило голое первое слово, и сверка
    по полным строкам напечатала «ноль» при четырёх десятках вхождений.
    """
    из = {}
    for имя in имена:
        для = {имя.lower()}
        for w in re.findall(r"[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z-]{4,}", имя):
            if w.lower() not in ОБЩИЕ:
                для.add(w.lower())
        for к in для:
            из.setdefault(к, имя)
    return из


def отслеживаемые():
    з = subprocess.run(["git", "ls-files", "-z"], capture_output=True).stdout
    return [f for f in з.decode("utf-8").split("\0") if f]


def найти(из, пропустить=()):
    находки = []
    for f in отслеживаемые():
        if f in пропустить:
            continue
        try:
            t = io.open(f, encoding="utf-8", errors="ignore").read()
        except Exception:
            continue
        н = t.lower()
        for к, полное in из.items():
            c = н.count(к)
            if c:
                находки.append((f, полное, к, c))
    return находки


def прогон(пропустить=()):
    имена, всего, стенд = имена_из_базы(БАЗА)
    if имена is None:
        print("НЕЧЕМ ПРОВЕРИТЬ: базы «%s» нет." % БАЗА)
        print("Проверка сверяет репозиторий с ЖИВОЙ базой; без неё")
        print("«утечки нет» и «не смотрели» неразличимы — код 2, не 0.")
        return 2, []
    if not имена:
        print("ПРОВЕРЯТЬ НЕЧЕГО: в базе «%s» нет позиций живых людей" % БАЗА)
        print("(записей всего %d, все стендовые: %d)." % (всего, стенд))
        print("Это НЕ «чисто»: стендовая база о боевых названиях молчит.")
        print("Укажите копию прода: MEDKIT_GUARD_DB=copy.db")
        return 2, []
    из = куски(имена)
    находки = найти(из, пропустить)
    print("позиций живых людей в базе: %d, признаков поиска: %d"
          % (len(имена), len(из)))
    if not находки:
        print("НАЗВАНИЙ ЛЕКАРСТВ ЖИВОГО ЧЕЛОВЕКА В РЕПОЗИТОРИИ НЕТ.")
        return 0, находки
    # Само название наружу НЕ печатаем: вывод попадает в журналы и отчёты.
    поф = {}
    for f, _полное, к, c in находки:
        поф[f] = поф.get(f, 0) + c
    print("УТЕЧКА: файлов %d, вхождений %d" % (len(поф), sum(поф.values())))
    for f, c in sorted(поф.items(), key=lambda x: -x[1]):
        print("  %-44s %4d" % (f, c))
    print("Сами названия НЕ печатаются — вывод уходит в отчёты и журналы.")
    print("Найти их: MEDKIT_GUARD_SHOW=1 py check_health_leak.py")
    if os.getenv("MEDKIT_GUARD_SHOW"):
        for f, полное, к, c in находки:
            print("  %s : %s (по «%s») %d" % (f, полное, к, c))
    return 1, находки


def контроль():
    """Отрицательный контроль. Подлог — НАСТОЯЩЕЕ имя из живой базы,
    вписанное во ВРЕМЕННЫЙ отслеживаемый файл. Доказательство подлога
    отдельно от вердикта (§6.0.3): считаем вхождения в самом файле."""
    имена, _, _ = имена_из_базы(БАЗА)
    if not имена:
        print("КОНТРОЛЬ НЕВОЗМОЖЕН: в базе нет позиций живых людей.")
        return 2
    чисто, _ = прогон()
    if чисто != 0:
        print("КОНТРОЛЬ НЕДЕЙСТВИТЕЛЕН: репозиторий уже НЕ чист.")
        print("«Нашла подлог» и «нашла прежнее» на грязной основе неразличимы.")
        return 2
    имя = sorted(имена)[0]
    путь = "_leak_control.md"
    io.open(путь, "w", encoding="utf-8").write(
        "Временный файл отрицательного контроля.\nЗамер: %s, 2 упаковки.\n" % имя)
    subprocess.run(["git", "add", "-f", путь], capture_output=True)
    было = io.open(путь, encoding="utf-8").read().lower().count(имя.lower())
    код, находки = прогон()
    subprocess.run(["git", "rm", "-q", "-f", "--cached", путь], capture_output=True)
    os.remove(путь)
    поймано = any(f == путь for f, *_ in находки)
    print()
    print("ДОКАЗАТЕЛЬСТВО ПОДЛОГА: вхождений имени в подложенном файле %d"
          % было)
    print("ВЕРДИКТ ПРОБЫ: код %d, файл подлога %sназван"
          % (код, "" if поймано else "НЕ "))
    if было and поймано and код == 1:
        print("КОНТРОЛЬ ПРОЙДЕН.")
        return 0
    print("КОНТРОЛЬ НЕ ПРОЙДЕН.")
    return 1


def коммиты():
    """Коммиты, добавлявшие в историю названия из живой базы.

    Нужен затем, чтобы решение о переписывании истории принималось
    по СПИСКУ, а не по памяти. Имена сюда не печатаются — только
    хеши, даты и темы (§5.1: вывод уходит в отчёты)."""
    имена, _, _ = имена_из_базы(БАЗА)
    if not имена:
        print("НЕЧЕМ: в базе «%s» нет позиций живых людей." % БАЗА)
        return 2
    из = куски(имена)
    все = {}
    for к in из:
        з = subprocess.run(["git", "log", "--all",
                            "--format=%H\t%ad\t%s",
                            "--date=short", "-S", к],
                           capture_output=True)
        for стр in з.stdout.decode("utf-8", "ignore").split("\n"):
            if "	" in стр:
                х, дата, тема = стр.split("	", 2)
                все[х] = (дата, тема)
    print("КОММИТОВ, НЕСУЩИХ НАЗВАНИЯ ИЗ ЖИВОЙ БАЗЫ: %d" % len(все))
    for х, (дата, тема) in sorted(все.items(), key=lambda x: x[1][0]):
        print("  %s  %s  %s" % (х[:9], дата, тема[:64]))
    return 0 if not все else 1


if __name__ == "__main__":
    if "--коммиты" in sys.argv:
        sys.exit(коммиты())
    if "--контроль" in sys.argv:
        sys.exit(контроль())
    sys.exit(прогон()[0])

def прогон(экраны, сенсор, ширина, высота, контроль, старый, снимки,
           сорвать=False):
    from playwright.sync_api import sync_playwright

    находки, всего_целей = [], 0
    молчат = {}          # группа -> [(экран, селектор)] для итоговой сводки
    with sync_playwright() as p:
        бр = p.chromium.launch()
        к = бр.new_context(viewport={"width": ширина, "height": высота},
                           has_touch=сенсор, is_mobile=сенсор)
        стр = к.new_page()
        cdp = к.new_cdp_session(стр)
        cdp.send("DOM.enable")
        cdp.send("CSS.enable")
        # ЭМУЛЯЦИЯ ОБЪЯВЛЕНА — ЗНАЧИТ, ПРИМЕНЯЕТСЯ ЗДЕСЬ, а не «работает
        # сама» через has_touch у контекста. Разница видна на признаках,
        # которых has_touch не даёт вовсе: тема, анимации, дросселирование
        # приходят только через CDP, и CDP-сессия ПОСТРАНИЧНАЯ — новая
        # вкладка не наследует ничего (замер 2026-08-19).
        if сенсор:
            _включить_сенсор(cdp)

        # ГОСТЕВЫЕ ЭКРАНЫ ИДУТ ПЕРВЫМИ, И ЭТО НЕ ПОРЯДОК РАДИ ПОРЯДКА.
        # `/login` авторизованного редиректит на лаунчер (main.py:1686):
        # войди мы заранее — строка «вход» мерила бы совсем другую
        # страницу и была бы подписана «вход». Ровно тот же класс отказа,
        # ради которого весь этот файл: замер не того, что подписано.
        гостевые = [э for э in экраны if not э[2]]
        свои = [э for э in экраны if э[2]]
        порядок = гостевые + ([("__вход__", "", True, None)] if свои else []) + свои

        for путь, имя, вход, подготовка in порядок:
            if путь == "__вход__":
                _войти(стр)
                continue
            # domcontentloaded, а не networkidle: на `/nutrition` фоновые
            # запросы идут постоянно, и «сеть затихла» там не наступает
            # вовсе — переход отваливался по таймауту, то есть проверка
            # не доходила до половины экранов и падала вместо вывода.
            стр.goto(f"{БАЗА}{путь}", wait_until="domcontentloaded",
                     timeout=45000)
            стр.wait_for_timeout(2200)
            # Сверка ПОСЛЕ перехода, а не только перед замером: страница
            # — вторая точка, где эмуляция может не доехать. Переход
            # её переживает (замер), но утверждение об этом стоит
            # проверять, а не помнить.
            if not старый:
                _сверить(стр, сенсор, f"после перехода на «{имя}»")
            if подготовка:
                try:
                    стр.click(подготовка, timeout=4000)
                    стр.wait_for_timeout(1200)
                except Exception as e:
                    print(f"   · {имя}: вкладка не открылась ({type(e).__name__}) — пропуск")
                    continue

            if контроль:
                стр.evaluate("""(id) => {
                    document.getElementById(id)?.remove();
                    const э = document.createElement('button');
                    э.id = id;
                    э.textContent = 'контроль';
                    document.body.appendChild(э);
                }""", КОНТРОЛЬ_ID)
                стр.add_style_tag(content=КОНТРОЛЬНОЕ_ПРАВИЛО)
                стр.wait_for_timeout(150)

            # СТАРЫЙ ПОРЯДОК: снимок раньше замера, эмуляция не возвращается,
            # стражи нет. Ровно так инструмент и работал.
            if старый:
                стр.screenshot(path=f"{КУДА_СНИМКИ}/hover_{имя}.png",
                               full_page=True)

            # СРЫВ ПРИ ВКЛЮЧЁННОЙ СТРАЖЕ: то же разрушение, но `_сверить`
            # на месте. Проверка обязана упасть, а не напечатать число.
            if сорвать:
                стр.screenshot(path=f"{КУДА_СНИМКИ}/срыв_{имя}.png",
                               full_page=True)

            if снимки:
                _снимок(стр, cdp, сенсор, f"{КУДА_СНИМКИ}/hover_{имя}.png")

            if not старый:
                _сверить(стр, сенсор, f"перед замером «{имя}»")

            все_цели = _цели(стр)
            цели = _проредить(все_цели)
            пропущено = len(все_цели) - len(цели)
            всего_целей += len(цели)
            # Корень берётся ОДИН раз на экран. `DOM.getDocument` на каждый
            # элемент заставляет агента заново обходить дерево: на дневнике
            # это давало минуты вместо секунд, и «нет вывода» было
            # неотличимо от «ещё считает».
            корень = cdp.send("DOM.getDocument", {"depth": -1})["root"]["nodeId"]
            залипшие, отозвались, ответившие_сел = [], set(), set()
            for з in цели:
                менялось = _замер(стр, cdp, з["индекс"], корень,
                                  з.get("объявлено") or ())
                if менялось:
                    залипшие.append((з["селектор"], з["обёрнуто"], менялось))
                    отозвались.add(з["индекс"])
                    ответившие_сел.add(з["селектор"])

            метка = "сенсорная" if сенсор else "десктоп"
            if сенсор:
                печать = "ЗАЛИПАЕТ" if залипшие else "чисто"
                хвост = (f"  (ещё {пропущено} — те же правила)" if пропущено else "")
                print(f"   · {имя:<26} целей {len(цели):>3}   "
                      f"меняют вид {len(залипшие):>3}   {печать}{хвост}")
                for сел, обёрнуто, св in залипшие:
                    print(f"        {сел}  →  {', '.join(св)}"
                          f"   [{'в @media (hover: hover)' if обёрнуто else 'БЕЗ ОБЁРТКИ'}]")
                находки += [(имя, с, о, в) for с, о, в in залипшие]
            else:
                хвост = (f"  (ещё {пропущено} — те же правила)" if пропущено else "")
                # РАЗБИВКА МОЛЧАЩИХ. Без неё «отвечают 254 из 383» —
                # число, из которого нельзя сделать ни одного вывода.
                группы = {}
                for з in цели:
                    if з["индекс"] in отозвались:
                        continue
                    г = причина_молчания(з, ответившие_сел)
                    группы.setdefault(г, []).append(з["исходный"])
                    молчат.setdefault(г, []).append((имя, з["исходный"]))
                разбор = "  ".join("%s %d" % (г, len(в))
                                   for г, в in sorted(группы.items()))
                print(f"   · {имя:<26} целей {len(цели):>3}   "
                      f"отвечают {len(залипшие):>3}   молчат "
                      f"{len(цели) - len(залипшие):>3}   {разбор}{хвост}")
                находки += [(имя, с, о, в) for с, о, в in залипшие]

        бр.close()
    return находки, всего_целей, молчат


ПРОФИЛЬ_КОНТРОЛЯ = [{"name": "hover", "value": "none"},
                    {"name": "pointer", "value": "coarse"},
                    {"name": "any-hover", "value": "none"},
                    {"name": "prefers-reduced-motion", "value": "reduce"},
                    {"name": "prefers-color-scheme", "value": "dark"}]
ПРОФИЛЬ_ТРОТТЛИНГ = 4


def контроль_эмуляции():
    """ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ СТРАЖИ — по каждому признаку отдельно.

    Зачем отдельно по каждому. Стража, проверенная одним `hover`,
    доказывает, что видит `hover`. Про остальные признаки такой прогон
    не говорит НИЧЕГО — а слетают они по-разному и от разного (замер
    в шапке `_сверить`). Ровно так прошлый заход и объявил инструмент
    починенным: сорвали наведение, поймали наведение, отчитались
    за эмуляцию целиком.

    Профиль здесь ШИРЕ рабочего: пять медиапризнаков и дросселирование
    вчетверо. Сама проверка эмулирует три признака и не дросселирует —
    но стража выводит ожидание ИЗ ОБЪЯВЛЕНИЯ, и проверять её надо
    на полном наборе, иначе половина её кода не исполняется ни разу.

    Каждый признак срывается СВОИМ способом — тем, который его и роняет
    в жизни, а не одним общим «выключить всё»:

      hover / pointer / any-hover   выключением сенсорной эмуляции:
      сенсорные точки               именно она их и даёт, а `full_page`
                                    снимает именно её
      тема, анимации                очисткой списка медиапризнаков
      дросселирование               возвратом скорости на 1×

    Ожидание одно на все: стража обязана УПАСТЬ и НАЗВАТЬ слетевшее.
    """
    from playwright.sync_api import sync_playwright
    global ЭМУЛЯЦИЯ, ТРОТТЛИНГ, _ЦПУ_БЕЗ_ТРОТТЛИНГА
    рабочая_эмуляция, рабочий_троттлинг = ЭМУЛЯЦИЯ, ТРОТТЛИНГ
    ЭМУЛЯЦИЯ, ТРОТТЛИНГ = ПРОФИЛЬ_КОНТРОЛЯ, ПРОФИЛЬ_ТРОТТЛИНГ
    _ЦПУ_БЕЗ_ТРОТТЛИНГА = None

    print("═" * 72)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ СТРАЖИ ЭМУЛЯЦИИ (задача 104)")
    print("═" * 72)
    print("\n  профиль: %s + дросселирование ×%d"
          % (", ".join(ф["name"] for ф in ПРОФИЛЬ_КОНТРОЛЯ), ПРОФИЛЬ_ТРОТТЛИНГ))

    срывы = [
        ("сенсорные признаки и точки",
         lambda cdp, стр: cdp.send("Emulation.setTouchEmulationEnabled",
                                   {"enabled": False}),
         ["(hover: none)", "(pointer: coarse)", "(any-hover: none)",
          "сенсорных точек"]),
        ("снимок full_page (живая ловушка)",
         lambda cdp, стр: стр.screenshot(path=f"{КУДА_СНИМКИ}/страж_срыв.png",
                                         full_page=True),
         ["(hover: none)"]),
        ("тема и анимации",
         lambda cdp, стр: cdp.send("Emulation.setEmulatedMedia",
                                   {"features": []}),
         ["(prefers-reduced-motion: reduce)", "(prefers-color-scheme: dark)"]),
        ("дросселирование процессора",
         lambda cdp, стр: cdp.send("Emulation.setCPUThrottlingRate",
                                   {"rate": 1}),
         ["дросселирование"]),
    ]

    беды = []
    try:
        with sync_playwright() as p:
            бр = p.chromium.launch()
            к = бр.new_context(viewport={"width": 390, "height": 844},
                               has_touch=True, is_mobile=True)
            стр = к.new_page()
            cdp = к.new_cdp_session(стр)
            стр.goto(f"{БАЗА}/login", wait_until="domcontentloaded",
                     timeout=45000)
            _включить_сенсор(cdp)
            стр.wait_for_timeout(400)

            try:
                _сверить(стр, True, "исходное состояние")
                print("\n  исходное состояние: ЦЕЛО (стража молчит — так и надо)")
            except ЭмуляцияСлетела as e:
                беды.append("на целой эмуляции стража уже падает: %s" % e)
                print("\n  !! исходное состояние: стража падает на целом — %s" % e)

            for имя, сорвать, ждём_имена in срывы:
                сорвать(cdp, стр)
                стр.wait_for_timeout(200)
                try:
                    _сверить(стр, True, "после срыва «%s»" % имя)
                    беды.append("«%s»: стража НЕ заметила срыва" % имя)
                    print("  %-36s !! НЕ ЗАМЕЧЕНО" % имя)
                except ЭмуляцияСлетела as e:
                    текст = str(e)
                    пропущены = [н for н in ждём_имена if н not in текст]
                    знак = "поймано" if not пропущены else "поймано НЕ ВСЁ"
                    print("  %-36s %s: %s" % (имя, знак,
                                              текст.split(". ")[0][:150]))
                    if пропущены:
                        беды.append("«%s»: не названы признаки %s"
                                    % (имя, ", ".join(пропущены)))
                # вернуть всё на место перед следующим срывом
                _включить_сенсор(cdp)
                стр.wait_for_timeout(200)
                try:
                    _сверить(стр, True, "восстановление после «%s»" % имя)
                except ЭмуляцияСлетела as e:
                    беды.append("после «%s» эмуляция не вернулась: %s" % (имя, e))
            бр.close()
    finally:
        ЭМУЛЯЦИЯ, ТРОТТЛИНГ = рабочая_эмуляция, рабочий_троттлинг
        _ЦПУ_БЕЗ_ТРОТТЛИНГА = None

    print("\n" + "─" * 72)
    if беды:
        print("НЕ ПРОЙДЕН:")
        for б in беды:
            print("   ·", б)
        return 1
    print("ПРОЙДЕН: каждый признак сорван своим способом, каждый срыв\n"
          "пойман и назван поимённо, эмуляция после каждого восстановлена.")
    return 0


def главная():
    р = argparse.ArgumentParser(description=__doc__)
    р.add_argument("--контроль", action="store_true",
                   help="подложить заведомо залипающее правило и потребовать находку")
    р.add_argument("--старый", action="store_true",
                   help="прежний порядок: снимок full_page раньше замера")
    р.add_argument("--снимки", action="store_true",
                   help="снимать кадры через _снимок (с возвратом эмуляции)")
    р.add_argument("--сорвать", action="store_true",
                   help="ПРОВЕРКА САМОЙ ПРОВЕРКИ: сорвать эмуляцию при "
                        "включённой страже. Ожидание — падение с кодом 1")
    р.add_argument("--экран", help="только один экран по имени")
    р.add_argument("--контроль-эмуляции", action="store_true",
                   dest="контроль_эмуляции",
                   help="ПРОВЕРКА САМОЙ СТРАЖИ: сорвать КАЖДЫЙ эмулируемый "
                        "признак по отдельности и потребовать, чтобы стража "
                        "упала и назвала именно его")
    args = р.parse_args()

    if args.контроль_эмуляции:
        return контроль_эмуляции()

    # Список СОБИРАЕТСЯ здесь, а не лежит константой: часть его выводится
    # пробой по живому серверу (§6.0.7, «вывести множество из источника»).
    try:
        экраны = экраны_из_роутов()
    except (RuntimeError, OSError) as e:
        print("ОСТАНОВЛЕНО: список экранов вывести не удалось — %s" % e)
        print("Пустой или укороченный список напечатал бы «чисто» "
              "про непроверенное.")
        return 2
    print("")
    print("  экранов выведено из роутов: %d  (из них сцен-вкладок %d)"
          % (len(экраны), len(СЦЕНЫ)))
    if args.экран:
        экраны = [э for э in экраны if args.экран.lower() in э[1].lower()]
        if not экраны:
            print(f"экрана «{args.экран}» в списке нет")
            return 2

    заголовок = "ПРОВЕРКА 10: залипающая подсветка на сенсорной ширине"
    if args.старый:
        заголовок += "  [ПРЕЖНИЙ ПОРЯДОК — снимок раньше замера]"
    if args.контроль:
        заголовок += "  [ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ]"
    print("═" * 72)
    print(заголовок)
    print("═" * 72)

    try:
        print("\n■ ДЕСКТОП 1440×900 — положительный контроль: отклик обязан быть")
        деск, целей_д, молчат = прогон(экраны, False, 1440, 900,
                                       args.контроль, False, False)
        print("")
        print(f"  отвечают на наведение: {len(деск)} из {целей_д} целей")
        # МОЛЧАЩИЕ РАЗЛОЖЕНЫ ПО ПРИЧИНАМ, а не свалены в остаток.
        # Сумма групп обязана дать в точности число молчащих — иначе
        # какая-то из них считается дважды или не считается вовсе.
        всего_молчит = sum(len(в) for в in молчат.values())
        print(f"  молчат: {всего_молчит}   сумма обязана сойтись: "
              f"{len(деск)} + {всего_молчит} = {len(деск) + всего_молчит} "
              f"(целей {целей_д})")
        for группа, что in sorted(молчат.items(), key=lambda п: -len(п[1])):
            print(f"     {группа:<12} {len(что):>3}   {ОБЪЯСНЕНИЕ[группа]}")
        мёртвые = молчат.get("МЁРТВОЕ", [])
        if мёртвые:
            print("")
            print("  МЁРТВЫЕ ПРАВИЛА — правило дотягивается, свойства читаются,")
            print("  а вид не меняется. Это находки, а не граница инструмента:")
            видели = set()
            for экран, селектор in мёртвые:
                if селектор in видели:
                    continue
                видели.add(селектор)
                print(f"     {селектор}   (например, «{экран}»)")
        if not деск:
            print("  !! НА ДЕСКТОПЕ НЕ ОТВЕТИЛ НИКТО — сломана проверка, "
                  "а не страницы")
            return 1

        print("")
        print("■ СЕНСОРНАЯ 390×844 — здесь не должен отвечать никто")
        сенс, целей_с, _ = прогон(экраны, True, 390, 844,
                                  args.контроль, args.старый, args.снимки,
                                  args.сорвать)
    except ЭмуляцияСлетела as e:
        print(f"\n!! ЭМУЛЯЦИЯ СЛЕТЕЛА: {e}")
        print("   Кадр не снят и число не напечатано намеренно: проверка, "
              "не потрогавшая\n   проверяемое, обязана падать, а не "
              "отчитываться (CLAUDE.md §6.0.1).")
        return 1

    # Находка на правиле, КОТОРОЕ ОБЁРНУТО, — ложная по построению:
    # обёрнутое правило на сенсорной ширине сработать не может, значит
    # сработала не страница, а слетевшая эмуляция. Число ложных — это
    # мера испорченности замера, и печатать его обязательно: без него
    # «залипает 18» и «залипает 1» выглядят одинаково содержательно.
    ложных = [н for н in сенс if н[2]]
    настоящих = [н for н in сенс if not н[2]]
    print(f"\n  залипает: {len(сенс)} из {целей_с} целей"
          f"   (правил без обёртки {len(настоящих)}, "
          f"обёрнутых — то есть ЛОЖНЫХ — {len(ложных)})")
    if ложных:
        print("  !! Ложные находки означают, что замер шёл при сорванной "
              "эмуляции:\n     обёрнутое правило на сенсорной ширине "
              "сработать не может.")

    print("\n" + "─" * 72)
    if args.контроль:
        нашли = [н for н in сенс if КОНТРОЛЬ_ID in н[1]]
        if нашли and not ложных:
            print(f"ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОЙДЕН: подложенное правило "
                  f"найдено и названо ({len(нашли)} шт), ложных находок нет.")
            print("Проверка видит залипание и отличает его от обёрнутого "
                  "правила. Код 0.")
            return 0
        if нашли and ложных:
            print(f"!! КОНТРОЛЬ НЕ ЗАСЧИТАН: подложенное правило найдено, "
                  f"но вместе с ним {len(ложных)} ложных.")
            print("   Отличить настоящее залипание от ложного в таком выводе "
                  "нечем —\n   находка не значит, что проверка видит именно "
                  "то, что ищет.")
            return 1
        print("!! ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОВАЛЕН: подложенное правило "
              "НЕ найдено.")
        print("   Проверка сломана — её выводы про исправность ничего не стоят.")
        return 1

    if сенс:
        print(f"НАЙДЕНО ЗАЛИПАНИЕ: {len(сенс)}. Каждое названо выше.")
        return 1
    print("Залипания нет. Отдельно: это утверждение стоит чего-то только "
          "вместе с\nотрицательным контролем — `py check_hover.py --контроль`.")
    return 0


if __name__ == "__main__":
    sys.exit(главная())

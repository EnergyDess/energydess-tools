def _цели(стр):
    """Элементы, до которых `:hover` вообще может дотянуться.

    Берутся не «все видимые подряд», а ровно те, что совпадают
    с селектором какого-нибудь правила `:hover` из подключённых стилей.
    Заодно видно, обёрнуто ли правило в `@media (hover: hover)`, —
    это и есть объяснение находки, а не догадка о ней.
    """
    return стр.evaluate("""() => {
        const итог = new Map();
        const естьHover = (текст) => /hover\\s*:\\s*hover/.test(текст || '');
        const обойти = (правила, обёрнуто) => {
            for (const п of правила) {
                if (п.media) {
                    const внутри = естьHover(п.conditionText || п.media.mediaText);
                    обойти(п.cssRules || [], обёрнуто || внутри);
                } else if (п.cssRules && !п.selectorText) {
                    обойти(п.cssRules, обёрнуто);
                } else if (п.selectorText && п.selectorText.includes(':hover')) {
                    for (const часть of п.selectorText.split(',')) {
                        if (!часть.includes(':hover')) continue;
                        const чистый = часть.replace(/:hover/g, '').trim();
                        if (!чистый || чистый.includes('::')) continue;
                        let найденные = [];
                        try { найденные = document.querySelectorAll(чистый); }
                        catch (e) { continue; }
                        for (const э of найденные) {
                            const r = э.getBoundingClientRect();
                            if (r.width < 1 || r.height < 1) continue;
                            const cs = getComputedStyle(э);
                            if (cs.visibility === 'hidden' || cs.display === 'none') continue;
                            if (!итог.has(э)) итог.set(э, {селектор: чистый, обёрнуто: true});
                            итог.get(э).обёрнуто = итог.get(э).обёрнуто && обёрнуто;
                        }
                    }
                }
            }
        };
        for (const л of document.styleSheets) {
            let правила;
            try { правила = л.cssRules; } catch (e) { continue; }
            обойти(правила || [], false);
        }
        window.__цели = [...итог.keys()];
        return [...итог.values()].map((з, i) => ({...з, индекс: i}));
    }""")


НА_СЕЛЕКТОР = 3        # сколько элементов мерить у одного и того же правила


def _проредить(цели):
    """Одно правило — несколько замеров, а не сорок.

    Проверяется, применяется ли ПРАВИЛО, а не элемент: сорок строк
    списка недавних совпадают с `.r-item:hover` и дают сорок одинаковых
    замеров по полсекунды каждый. Первый полный прогон на этом и встал —
    экран «Добавить» не закончился за десять минут, и «нет вывода»
    выглядело ровно как «ещё считает». Проверка, способная зависнуть
    молча, — та же болезнь, ради которой писан весь файл.

    Берётся до НА_СЕЛЕКТОР штук на селектор, а не одна: элементы одного
    класса стоят в разном окружении, и правило потомка (`.карточка
    .r-item:hover`) поймает не первый попавшийся.
    """
    счёт, отобранные = {}, []
    for з in цели:
        к = з["селектор"]
        счёт[к] = счёт.get(к, 0) + 1
        if счёт[к] <= НА_СЕЛЕКТОР:
            отобранные.append(з)
    return отобранные


def _замер(стр, cdp, индекс, корень):
    """Навязать `:hover` одному элементу и вернуть изменившиеся свойства.

    Элемент помечается атрибутом, чтобы CDP нашёл его обычным селектором:
    доставать nodeId через приватные поля Playwright значит держать
    проверку на том, что не обещано и молча съедет с обновлением.
    """
    стр.evaluate("""(п) => {
        window.__цель = window.__цели[п.i];
        window.__цель.setAttribute(п.атрибут, '1');
    }""", {"i": индекс, "атрибут": ПРОБА})
    try:
        до = _вид(стр)
        узел = cdp.send("DOM.querySelector",
                        {"nodeId": корень, "selector": f"[{ПРОБА}]"})["nodeId"]
        if not узел:
            return []
        cdp.send("CSS.forcePseudoState",
                 {"nodeId": узел, "forcedPseudoClasses": ["hover"]})
        стр.wait_for_timeout(ПАУЗА_ПЕРЕХОДА)
        после = _вид(стр)
        cdp.send("CSS.forcePseudoState",
                 {"nodeId": узел, "forcedPseudoClasses": []})
        стр.wait_for_timeout(120)
    finally:
        стр.evaluate("(а) => window.__цель && window.__цель.removeAttribute(а)",
                     ПРОБА)
    if not до or not после:
        return []
    return [к for к in до if до[к] != после[к]]


def _войти(стр):
    стр.goto(f"{БАЗА}/login", wait_until="domcontentloaded", timeout=45000)
    стр.fill("input[name=email]", ПОЧТА)
    стр.fill("input[name=password]", ПАРОЛЬ)
    стр.click("button[type=submit]")
    стр.wait_for_timeout(2500)


def прогон(экраны, сенсор, ширина, высота, контроль, старый, снимки,
           сорвать=False):
    from playwright.sync_api import sync_playwright

    находки, всего_целей = [], 0
    with sync_playwright() as p:
        бр = p.chromium.launch()
        к = бр.new_context(viewport={"width": ширина, "height": высота},
                           has_touch=сенсор, is_mobile=сенсор)
        стр = к.new_page()
        cdp = к.new_cdp_session(стр)
        cdp.send("DOM.enable")
        cdp.send("CSS.enable")
        # ЭМУЛЯЦИЯ ОБЪЯВЛЕНА — ЗНАЧИТ, ПРИМЕНЯЕТСЯ ЗДЕСЬ, а не «работает
        # сама» через has_touch у контекста. Разница видна на признаках,
        # которых has_touch не даёт вовсе: тема, анимации, дросселирование
        # приходят только через CDP, и CDP-сессия ПОСТРАНИЧНАЯ — новая
        # вкладка не наследует ничего (замер 2026-08-19).
        if сенсор:
            _включить_сенсор(cdp)

        # ГОСТЕВЫЕ ЭКРАНЫ ИДУТ ПЕРВЫМИ, И ЭТО НЕ ПОРЯДОК РАДИ ПОРЯДКА.
        # `/login` авторизованного редиректит на лаунчер (main.py:1686):
        # войди мы заранее — строка «вход» мерила бы совсем другую
        # страницу и была бы подписана «вход». Ровно тот же класс отказа,
        # ради которого весь этот файл: замер не того, что подписано.
        гостевые = [э for э in экраны if not э[2]]
        свои = [э for э in экраны if э[2]]
        порядок = гостевые + ([("__вход__", "", True, None)] if свои else []) + свои

        for путь, имя, вход, подготовка in порядок:
            if путь == "__вход__":
                _войти(стр)
                continue
            # domcontentloaded, а не networkidle: на `/nutrition` фоновые
            # запросы идут постоянно, и «сеть затихла» там не наступает
            # вовсе — переход отваливался по таймауту, то есть проверка
            # не доходила до половины экранов и падала вместо вывода.
            стр.goto(f"{БАЗА}{путь}", wait_until="domcontentloaded",
                     timeout=45000)
            стр.wait_for_timeout(2200)
            # Сверка ПОСЛЕ перехода, а не только перед замером: страница
            # — вторая точка, где эмуляция может не доехать. Переход
            # её переживает (замер), но утверждение об этом стоит
            # проверять, а не помнить.
            if not старый:
                _сверить(стр, сенсор, f"после перехода на «{имя}»")
            if подготовка:
                try:
                    стр.click(подготовка, timeout=4000)
                    стр.wait_for_timeout(1200)
                except Exception as e:
                    print(f"   · {имя}: вкладка не открылась ({type(e).__name__}) — пропуск")
                    continue

            if контроль:
                стр.evaluate("""(id) => {
                    document.getElementById(id)?.remove();
                    const э = document.createElement('button');
                    э.id = id;
                    э.textContent = 'контроль';
                    document.body.appendChild(э);
                }""", КОНТРОЛЬ_ID)
                стр.add_style_tag(content=КОНТРОЛЬНОЕ_ПРАВИЛО)
                стр.wait_for_timeout(150)

            # СТАРЫЙ ПОРЯДОК: снимок раньше замера, эмуляция не возвращается,
            # стражи нет. Ровно так инструмент и работал.
            if старый:
                стр.screenshot(path=f"{КУДА_СНИМКИ}/hover_{имя}.png",
                               full_page=True)

            # СРЫВ ПРИ ВКЛЮЧЁННОЙ СТРАЖЕ: то же разрушение, но `_сверить`
            # на месте. Проверка обязана упасть, а не напечатать число.
            if сорвать:
                стр.screenshot(path=f"{КУДА_СНИМКИ}/срыв_{имя}.png",
                               full_page=True)

            if снимки:
                _снимок(стр, cdp, сенсор, f"{КУДА_СНИМКИ}/hover_{имя}.png")

            if not старый:
                _сверить(стр, сенсор, f"перед замером «{имя}»")

            все_цели = _цели(стр)
            цели = _проредить(все_цели)
            пропущено = len(все_цели) - len(цели)
            всего_целей += len(цели)
            # Корень берётся ОДИН раз на экран. `DOM.getDocument` на каждый
            # элемент заставляет агента заново обходить дерево: на дневнике
            # это давало минуты вместо секунд, и «нет вывода» было
            # неотличимо от «ещё считает».
            корень = cdp.send("DOM.getDocument", {"depth": -1})["root"]["nodeId"]
            залипшие = []
            for з in цели:
                менялось = _замер(стр, cdp, з["индекс"], корень)
                if менялось:
                    залипшие.append((з["селектор"], з["обёрнуто"], менялось))

            метка = "сенсорная" if сенсор else "десктоп"
            if сенсор:
                печать = "ЗАЛИПАЕТ" if залипшие else "чисто"
                хвост = (f"  (ещё {пропущено} — те же правила)" if пропущено else "")
                print(f"   · {имя:<26} целей {len(цели):>3}   "
                      f"меняют вид {len(залипшие):>3}   {печать}{хвост}")
                for сел, обёрнуто, св in залипшие:
                    print(f"        {сел}  →  {', '.join(св)}"
                          f"   [{'в @media (hover: hover)' if обёрнуто else 'БЕЗ ОБЁРТКИ'}]")
                находки += [(имя, с, о, в) for с, о, в in залипшие]
            else:
                хвост = (f"  (ещё {пропущено} — те же правила)" if пропущено else "")
                print(f"   · {имя:<26} целей {len(цели):>3}   "
                      f"отвечают {len(залипшие):>3}   ({метка}, ожидание > 0)"
                      f"{хвост}")
                находки += [(имя, с, о, в) for с, о, в in залипшие]

        бр.close()
    return находки, всего_целей



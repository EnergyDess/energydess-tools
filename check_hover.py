def _вид(стр, добавка=()):
    """Вычисленные значения СВОЙСТВА плюс то, что объявило само правило.

    Добавка закрывает КЛАСС, а не пополняет перечень (§6.0.7). Прежде
    список свойств был фиксированным, и правило, меняющее `filter`
    или `outline`, замер не видел по построению — цель молчала, и это
    было неотличимо от «правило мёртвое». Замер 2026-08-21 до правки:
    таких целей 5 на четырёх экранах.
    """
    return стр.evaluate(
        """(св) => {
             const э = window.__цель;
             if (!э) return null;
             const s = getComputedStyle(э);
             const о = {};
             for (const п of св) о[п] = s.getPropertyValue(п);
             return о;
           }""", list(СВОЙСТВА) + [п for п in добавка if п not in СВОЙСТВА])


def _цели(стр):
    """Элементы, до которых `:hover` вообще может дотянуться.

    Берутся не «все видимые подряд», а ровно те, что совпадают
    с селектором какого-нибудь правила `:hover` из подключённых стилей.
    Заодно видно, обёрнуто ли правило в `@media (hover: hover)`, —
    это и есть объяснение находки, а не догадка о ней.
    """
    return стр.evaluate("""() => {
        const итог = new Map();
        const естьHover = (текст) => /hover\\s*:\\s*hover/.test(текст || '');
        const обойти = (правила, обёрнуто, внешнее, обёрнутоМедиа) => {
            for (const п of правила) {
                if (п.media) {
                    const текст = п.conditionText || п.media.mediaText;
                    const внутри = естьHover(текст);
                    // «Чужой» медиазапрос — любой, кроме hover-обёртки:
                    // ширина, тема, печать. На текущей ширине он может
                    // не применяться, и тогда правило не сработает вовсе.
                    обойти(п.cssRules || [], обёрнуто || внутри,
                           внешнее || !внутри, обёрнутоМедиа || внутри);
                } else if (п.cssRules && !п.selectorText) {
                    обойти(п.cssRules, обёрнуто, внешнее, обёрнутоМедиа);
                } else if (п.selectorText && п.selectorText.includes(':hover')) {
                    // Свойства, которые правило ОБЪЯВЛЯЕТ, и место `:hover`
                    // в селекторе — без них непрошедшую цель нечем объяснить.
                    const объявлено = [];
                    for (let i = 0; i < п.style.length; i++) объявлено.push(п.style[i]);
                    for (const часть of п.selectorText.split(',')) {
                        if (!часть.includes(':hover')) continue;
                        const чистый = часть.replace(/:hover/g, '').trim();
                        if (!чистый || чистый.includes('::')) continue;
                        // `:hover` СТОИТ НА ПРЕДКЕ, а меняется потомок:
                        // `.card:hover .arrow { … }`. Навязать hover самой
                        // стрелке — не то же самое, что навести на карточку,
                        // и такая цель не отзовётся НИКОГДА.
                        const наПредке = !/:hover[^ >+~]*$/.test(часть.trim());
                        // Селектор ДО последнего `:hover` включительно —
                        // по нему ищется элемент, на который надо навести.
                        const доHover = часть.slice(
                            0, часть.lastIndexOf(':hover')).trim();
                        const форсСел = (доHover.replace(/:hover/g, '')
                                                .replace(/[>+~]\\s*$/, '').trim()
                                         || чистый);
                        // Правило в чужом @media (ширина, тема): на этой
                        // ширине оно может не применяться вовсе.
                        const вЧужомМедиа = внешнее && !обёрнутоМедиа;
                        let найденные = [];
                        try { найденные = document.querySelectorAll(чистый); }
                        catch (e) { continue; }
                        for (const э of найденные) {
                            const r = э.getBoundingClientRect();
                            if (r.width < 1 || r.height < 1) continue;
                            const cs = getComputedStyle(э);
                            if (cs.visibility === 'hidden' || cs.display === 'none') continue;
                            if (!итог.has(э)) итог.set(э, {
                                селектор: чистый, обёрнуто: true,
                                исходный: часть.trim(), объявлено: [],
                                наПредке: true, вЧужомМедиа: true,
                                форс: null, правил: 0});
                            const з = итог.get(э);
                            з.обёрнуто = з.обёрнуто && обёрнуто;
                            з.объявлено = [...new Set(з.объявлено.concat(объявлено))];
                            // «на предке» и «в чужом медиа» — только если
                            // ВСЕ правила, дотянувшиеся до элемента, таковы:
                            // одно прямое правило объясняет отклик само.
                            з.наПредке = з.наПредке && наПредке;
                            з.вЧужомМедиа = з.вЧужомМедиа && вЧужомМедиа;
                            // Сколько РАЗНЫХ правил `:hover` дотянулось
                            // до этого элемента. Больше одного и вид
                            // не меняется — значит, работает гасящий
                            // вариант (`.card-static` отменяет подъём
                            // `.card`), а не «правило мёртвое».
                            з.правил += 1;
                            // Наводить надо на ПРЕДКА, если `:hover` стоит
                            // на нём. `closest` берёт ближайшего подходящего
                            // — ровно того, на кого наведёт человек.
                            if (!з.форс && наПредке && форсСел) {
                                let п = null;
                                try { п = э.closest(форсСел); } catch (e) {}
                                if (п && п !== э) з.форс = п;
                            }
                        }
                    }
                }
            }
        };
        for (const л of document.styleSheets) {
            let правила;
            try { правила = л.cssRules; } catch (e) { continue; }
            обойти(правила || [], false, false, false);
        }
        window.__цели = [...итог.keys()];
        window.__форсы = [...итог.values()].map(з => з.форс);
        return [...итог.values()].map((з, i) => ({
            селектор: з.селектор, обёрнуто: з.обёрнуто, исходный: з.исходный,
            объявлено: з.объявлено, наПредке: з.наПредке,
            вЧужомМедиа: з.вЧужомМедиа, естьФорс: !!з.форс,
            правил: з.правил || 0, индекс: i}));
    }""")


НА_СЕЛЕКТОР = 3        # сколько элементов мерить у одного и того же правила


def _проредить(цели):
    """Одно правило — несколько замеров, а не сорок.

    Проверяется, применяется ли ПРАВИЛО, а не элемент: сорок строк
    списка недавних совпадают с `.r-item:hover` и дают сорок одинаковых
    замеров по полсекунды каждый. Первый полный прогон на этом и встал —
    экран «Добавить» не закончился за десять минут, и «нет вывода»
    выглядело ровно как «ещё считает». Проверка, способная зависнуть
    молча, — та же болезнь, ради которой писан весь файл.

    Берётся до НА_СЕЛЕКТОР штук на селектор, а не одна: элементы одного
    класса стоят в разном окружении, и правило потомка (`.карточка
    .r-item:hover`) поймает не первый попавшийся.
    """
    счёт, отобранные = {}, []
    for з in цели:
        к = з["селектор"]
        счёт[к] = счёт.get(к, 0) + 1
        if счёт[к] <= НА_СЕЛЕКТОР:
            отобранные.append(з)
    return отобранные


def _замер(стр, cdp, индекс, корень, добавка=()):
    """Навязать `:hover` и вернуть изменившиеся свойства.

    Элемент помечается атрибутом, чтобы CDP нашёл его обычным селектором:
    доставать nodeId через приватные поля Playwright значит держать
    проверку на том, что не обещано и молча съедет с обновлением.

    НАВОДИМ НА ОДИН ЭЛЕМЕНТ, СМОТРИМ НА ДРУГОЙ — и без этого треть целей
    молчала. Правило `.card:hover .arrow { … }` меняет вид СТРЕЛКИ, когда
    наводят на КАРТОЧКУ. Прежняя версия навязывала `:hover` самой стрелке
    и получала ноль изменений: замер 2026-08-21 до правки — 230 таких
    целей из 383, то есть большинство «молчащих». Это была не находка
    и не законное молчание, а граница инструмента, о которой он не знал.
    """
    стр.evaluate("""(п) => {
        window.__цель = window.__цели[п.i];
        window.__форс = (window.__форсы && window.__форсы[п.i]) || window.__цель;
        window.__форс.setAttribute(п.атрибут, '1');
    }""", {"i": индекс, "атрибут": ПРОБА})
    try:
        до = _вид(стр, добавка)
        узел = cdp.send("DOM.querySelector",
                        {"nodeId": корень, "selector": f"[{ПРОБА}]"})["nodeId"]
        if not узел:
            return []
        cdp.send("CSS.forcePseudoState",
                 {"nodeId": узел, "forcedPseudoClasses": ["hover"]})
        стр.wait_for_timeout(ПАУЗА_ПЕРЕХОДА)
        после = _вид(стр, добавка)
        cdp.send("CSS.forcePseudoState",
                 {"nodeId": узел, "forcedPseudoClasses": []})
        стр.wait_for_timeout(120)
    finally:
        стр.evaluate("(а) => window.__форс && window.__форс.removeAttribute(а)",
                     ПРОБА)
    if not до or not после:
        return []
    return [к for к in до if до[к] != после[к]]



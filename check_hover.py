def _ожидание(сенсор):
    """Что ДОЛЖНО быть — выводится из объявлений выше, а не из списка рядом.

    ЗАЧЕМ ИМЕННО ВЫВОДИТСЯ. Стража, у которой свой перечень признаков,
    это whitelist: добавили в `ЭМУЛЯЦИЯ` четвёртую строку — стража про
    неё молчит и продолжает печатать «чисто». Тот же класс отказа, что
    у `names` и `pages` в §6.0.2, только по оси признаков.
    """
    ждём = {}
    for ф in ЭМУЛЯЦИЯ:
        ждём["(%s: %s)" % (ф["name"], ф["value"])] = bool(сенсор)
    ждём["сенсорных точек"] = "> 0" if сенсор else "0"
    if ТРОТТЛИНГ > 1:
        ждём["дросселирование"] = "×%g" % ТРОТТЛИНГ
    return ждём


def _признаки(стр, сенсор):
    """Фактические значения тех же признаков, одним обходом страницы."""
    запросы = ["(%s: %s)" % (ф["name"], ф["value"]) for ф in ЭМУЛЯЦИЯ]
    факт = стр.evaluate(
        """(запросы) => {
             const о = {};
             for (const з of запросы) о[з] = matchMedia(з).matches;
             о['сенсорных точек'] = navigator.maxTouchPoints;
             return о;
           }""", запросы)
    факт["сенсорных точек"] = ("> 0" if факт["сенсорных точек"] > 0 else "0")
    if ТРОТТЛИНГ > 1:
        занято = стр.evaluate(ПРОБА_ЦПУ)
        global _ЦПУ_БЕЗ_ТРОТТЛИНГА
        if _ЦПУ_БЕЗ_ТРОТТЛИНГА is None:
            _ЦПУ_БЕЗ_ТРОТТЛИНГА = занято / ТРОТТЛИНГ
        медленнее = занято / max(_ЦПУ_БЕЗ_ТРОТТЛИНГА, 0.001)
        факт["дросселирование"] = ("×%g" % ТРОТТЛИНГ
                                   if медленнее >= ЦПУ_ПОРОГ else "выключено")
    return факт


def _сверить(стр, сенсор, где):
    """ВСЕ эмулируемые признаки — перед замером и ПОСЛЕ каждого снимка.

    Именно все, а не один `hover`. Замер 2026-08-19 показал, что признаки
    слетают ПО-РАЗНОМУ, и одна проверка за всех не отвечает:

      признак                     что его сбрасывает
      hover / pointer / any-hover  снимок full_page — через сенсорную
                                   эмуляцию, из которой они выводятся
      navigator.maxTouchPoints     он же
      prefers-reduced-motion       full_page НЕ трогает; теряется только
      prefers-color-scheme         вместе со страницей (CDP-сессия
      дросселирование ЦПУ          постраничная — новая вкладка чиста)

    То есть «сверил hover — значит цело» неверно: страница, открытая
    второй вкладкой, отдаёт правильный hover (он от контекста) и при
    этом теряет и тему, и анимации, и дросселирование.
    """
    ждём, факт = _ожидание(сенсор), _признаки(стр, сенсор)
    разошлись = [(к, ждём[к], факт.get(к)) for к in ждём if факт.get(к) != ждём[к]]
    if разошлись:
        части = ", ".join("%s: ждём %s, факт %s" % (к, ж, ф)
                          for к, ж, ф in разошлись)
        raise ЭмуляцияСлетела(
            "%s: %s. %s — замер показал бы поведение другого устройства"
            % (где, части,
               "Эмуляция слетела" if сенсор else "Лишняя эмуляция"))



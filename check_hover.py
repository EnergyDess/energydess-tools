        положить_контроль(стр)
        покой = стр.evaluate(ЧТО, КОНТРОЛЬ_ID)
        корень = cdp.send("DOM.getDocument")["root"]["nodeId"]
        узел = cdp.send("DOM.querySelector",
                        {"nodeId": корень,
                         "selector": "#" + КОНТРОЛЬ_ID})["nodeId"]

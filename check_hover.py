class ЭмуляцияСлетела(RuntimeError):
    """Медиапризнаки не те, что заказаны. Кадр снимать нельзя: он покажет
    десктопное поведение, а подписан будет сенсорным."""


def _сверить(стр, сенсор, где):
    """Признак сверяется ПЕРЕД замером и ПОСЛЕ снимка. Без этого проверка
    не может отличить исправную страницу от слетевшей эмуляции."""
    факт = стр.evaluate("() => matchMedia('(hover: hover)').matches")
    ждём = not сенсор
    if факт != ждём:
        raise ЭмуляцияСлетела(
            f"{где}: (hover: hover) совпадает = {факт}, ожидалось {ждём}. "
            f"{'Сенсорная эмуляция слетела' if сенсор else 'Лишняя эмуляция'} — "
            f"замер показал бы поведение другого устройства")



def ход_нажатия(браузер, экраны, ширина=1440, высота=900,
                подлог=None, порог=None):
    """Прогон по экранам и сценам. Отдаёт (находки, снято, разброс).

    разброс — фактические числа чистого прогона, из которых и берётся
    порог схлопа: вписанное руками число протухло бы (§6.0.4).
    """
    находки, снято, разброс = [], 0, []
    ctx = браузер.new_context(viewport={"width": ширина, "height": высота})
    if подлог:
        ctx.add_init_script(подлог)
    стр = ctx.new_page()
    _войти(стр)
    # СЦЕНЫ УЖЕ ЛЕЖАТ В `экраны`: `экраны_из_роутов` кладёт их
    # четвёртым элементом кортежа — селектором, которым состояние
    # открывается. Первая версия добавляла `СЦЕНЫ` ВТОРЫМ списком,
    # и каждая вкладка снималась ДВАЖДЫ: 29 экранов вместо 20.
    задания = [(э[0], э[1], э[3] if len(э) > 3 else None)
               for э in экраны if "{" not in э[0]]
    for путь, имя, сел in задания:
        try:
            стр.goto(БАЗА + путь, wait_until="domcontentloaded")
            стр.wait_for_timeout(700)
            if сел:
                стр.click(сел, timeout=4000)
                стр.wait_for_timeout(500)
        except Exception as e:                       # noqa: BLE001
            print("   %-34s не открылся: %s" % (имя[:34], str(e)[:38]))
            continue
        из = _ход_нажатия(стр)
        if из is None:
            print("   %-34s органов, меняющих состояние, нет" % имя[:34])
            continue
        сверх, просело, устояв, целей, кадров, кто = из
        снято += 1
        разброс.append((имя, сверх, просело, устояв))
        находка = ""
        if сверх > 0:
            находка += "  ПЕРЕЛИВ +%d (%s)" % (сверх, str(кто)[:24])
        if порог is not None and просело > порог:
            находка += "  СХЛОП -%d" % просело
        print("   %-34s перелив сверх %4d  просадка %5d  целей %d  "
              "кадров %4d%s" % (имя[:34], сверх, просело, целей,
                                кадров, находка))
        if находка:
            находки.append((имя, находка.strip()))
    ctx.close()
    return находки, снято, разброс


def причина_молчания(з, ответившие_селекторы=()):
    """`ответившие_селекторы` — те, у кого на ЭТОМ экране отозвался хоть
    один элемент. Без этого аргумента см. разбор группы ЭКЗЕМПЛЯР ниже."""
    """Почему цель не отозвалась на навязанный `:hover`. BACKLOG №1xx.

    ЗАЧЕМ. Десктопный проход печатал «отвечают 254 из 383» и про
    оставшиеся 129 не говорил НИЧЕГО. Треть целей не проверялась,
    и по выводу нельзя было отличить «здесь отклика законно нет»
    от «проверка до них не дотянулась» — то есть число «отвечают»
    значило не то, что о нём думали.

    Группы взаимоисключающие и проверяются В ЭТОМ порядке — первая
    подошедшая и есть ответ:

      ПРЕДОК     `:hover` стоит не на самом элементе, а на его предке
                 (`.card:hover .arrow`). Навязать hover стрелке — не то же
                 самое, что навести на карточку: правило не сработает
                 НИКОГДА, и это не дефект страницы, а граница инструмента;
      МЕДИА      правило лежит в чужом `@media` (ширина, тема), который
                 на этой ширине не применяется;
      ВНЕ СПИСКА правило меняет свойства, которых нет в `СВОЙСТВА`
                 (`filter`, `outline`, `border-width`…) — замер их
                 не читает по построению;
      МЁРТВОЕ    ничего из перечисленного: правило дотягивается, свойства
                 читаются, а вид не меняется. Значит, объявление
                 перекрыто более сильным правилом либо повторяет
                 значение покоя. ВОТ ЭТО и есть настоящая находка.
    """
    if (з.get("правил") or 0) > 1:
        # До элемента дотянулось НЕСКОЛЬКО правил `:hover`, и вид не менялся.
        # Это ровно то, ради чего заведены гасящие варианты: `.card-static`
        # отменяет подъём `.card`, `:hover` при этом «не работает» — и так
        # и задумано. Объявлять это находкой значило бы объявлять дефектом
        # работающий замысел.
        return "ПЕРЕКРЫТО"
    if з["селектор"] in ответившие_селекторы:
        # ПРАВИЛО РАБОТАЕТ, молчит ЭКЗЕМПЛЯР. Обычно потому, что у него
        # своё состояние (`.active`), объявленное позже и тем же весом:
        # активная вкладка не отзывается на наведение, и это замысел.
        # Без этой группы такие элементы попадали в МЁРТВОЕ и объявляли
        # находкой рабочее правило — то есть проверка врала бы ровно
        # тем способом, от которого её и лечили.
        return "ЭКЗЕМПЛЯР"
    if з.get("наПредке") and not з.get("естьФорс"):
        # Предок в дереве не нашёлся (правило написано под разметку,
        # которой на этом экране нет). Наводить не на кого — граница.
        return "ПРЕДОК БЕЗ ЭЛЕМЕНТА"
    if з.get("вЧужомМедиа"):
        return "МЕДИА"
    объявлено = set(з.get("объявлено") or [])
    if объявлено and not (объявлено & set(СВОЙСТВА)):
        # Имя свойства приводится к тому виду, который умеет читать замер.
        # ПРАВИЛОМ, а не списком исключений: браузер отдаёт объявления
        # РАЗВЁРНУТЫМИ по сторонам (`border-top-color`, `border-left-color`),
        # и перечислять их по одному значило бы завести перечень там,
        # где действует правило (§6.0.7).
        краткие = {"border": "border-color", "background": "background-color",
                   "text-decoration": "text-decoration-line"}

        def свести(имя):
            имя = краткие.get(имя, имя)
            for сторона in ("-top-", "-right-", "-bottom-", "-left-",
                            "-inline-", "-block-"):
                if сторона in имя:
                    имя = имя.replace(сторона, "-")
            return имя

        if not ({свести(п) for п in объявлено} & set(СВОЙСТВА)):
            return "ВНЕ СПИСКА"
    return "МЁРТВОЕ"


def _войти(стр):
    """Вход НА САМОМ ДЕЛЕ, а не отправка формы с надеждой.

    До 2026-08-21 здесь стояло «заполнить, нажать, подождать 2.5 с»
    и ни одной проверки исхода. Отказ был НЕМОЙ и худшего вида: вход
    не проходил — например, виджет Turnstile не успевал выдать токен
    и сервер отвечал 400 fail-closed (§8.1), — а харнесса шла дальше
    и снимала СТРАНИЦУ ВХОДА, подписывая кадры «дневник», «профиль»,
    «админка». То есть замер не того, что подписано, — ровно тот класс,
    ради которого написан весь этот файл.

    Поймано живым прогоном: два стенда одного проекта, на одном вход
    проходил, на другом молча нет, и разница в выводе была только
    в числах — не в словах.

    Две половины лечения, обе обязательны:
      · дождаться токена капчи, если виджет на странице ЕСТЬ. Пустое
        поле — это отказ 400 fail-closed, а не «капча не нужна»;
      · после отправки СВЕРИТЬ, что мы ушли с `/login`, и упасть
        с текстом ошибки страницы, если нет.
    """
    стр.goto(f"{БАЗА}/login", wait_until="domcontentloaded", timeout=45000)
    стр.fill("input[name=email]", ПОЧТА)
    стр.fill("input[name=password]", ПАРОЛЬ)
    # Виджета может не быть вовсе (ключ не задан) — тогда ждать нечего.
    if стр.locator(".cf-turnstile").count():
        try:
            стр.wait_for_function(
                "() => { const e = document.querySelector"
                "('[name=\"cf-turnstile-response\"]'); return e && e.value; }",
                timeout=20000)
        except Exception:
            # Не дождались — идём дальше и падаем ниже с внятной причиной,
            # а не молча снимаем страницу входа.
            pass
    стр.click("button[type=submit]")
    стр.wait_for_timeout(2500)
    if "/login" in стр.url:
        ошибка = ""
        for сел in (".alert", ".alert-error", ".auth-error"):
            if стр.locator(сел).count():
                ошибка = (стр.locator(сел).first.inner_text() or "").strip()
                break
        raise RuntimeError(
            f"ВХОД НЕ ПРОШЁЛ: остались на {стр.url}. Страница говорит: "
            f"{ошибка or '(сообщения на экране нет)'}. Снимать авторизованные "
            f"экраны нечем — прежняя версия этого не проверяла и снимала "
            f"страницу входа под чужими подписями.")


def прогон(экраны, сенсор, ширина, высота, контроль, старый, снимки,
           сорвать=False):
    from playwright.sync_api import sync_playwright

    находки, всего_целей = [], 0
    молчат = {}          # группа -> [(экран, селектор)] для итоговой сводки
    with sync_playwright() as p:
        бр = p.chromium.launch()
        к = бр.new_context(viewport={"width": ширина, "height": высота},
                           has_touch=сенсор, is_mobile=сенсор)
        стр = к.new_page()
        cdp = к.new_cdp_session(стр)
        cdp.send("DOM.enable")
        cdp.send("CSS.enable")
        # ЭМУЛЯЦИЯ ОБЪЯВЛЕНА — ЗНАЧИТ, ПРИМЕНЯЕТСЯ ЗДЕСЬ, а не «работает
        # сама» через has_touch у контекста. Разница видна на признаках,
        # которых has_touch не даёт вовсе: тема, анимации, дросселирование
        # приходят только через CDP, и CDP-сессия ПОСТРАНИЧНАЯ — новая
        # вкладка не наследует ничего (замер 2026-08-19).
        if сенсор:
            _включить_сенсор(cdp)

        # ГОСТЕВЫЕ ЭКРАНЫ ИДУТ ПЕРВЫМИ, И ЭТО НЕ ПОРЯДОК РАДИ ПОРЯДКА.
        # `/login` авторизованного редиректит на лаунчер (main.py:1686):
        # войди мы заранее — строка «вход» мерила бы совсем другую
        # страницу и была бы подписана «вход». Ровно тот же класс отказа,
        # ради которого весь этот файл: замер не того, что подписано.
        гостевые = [э for э in экраны if not э[2]]
        свои = [э for э in экраны if э[2]]
        порядок = гостевые + ([("__вход__", "", True, None)] if свои else []) + свои

        for путь, имя, вход, подготовка in порядок:
            if путь == "__вход__":
                _войти(стр)
                continue
            # domcontentloaded, а не networkidle: на `/nutrition` фоновые
            # запросы идут постоянно, и «сеть затихла» там не наступает
            # вовсе — переход отваливался по таймауту, то есть проверка
            # не доходила до половины экранов и падала вместо вывода.
            стр.goto(f"{БАЗА}{путь}", wait_until="domcontentloaded",
                     timeout=45000)
            стр.wait_for_timeout(2200)
            # Сверка ПОСЛЕ перехода, а не только перед замером: страница
            # — вторая точка, где эмуляция может не доехать. Переход
            # её переживает (замер), но утверждение об этом стоит
            # проверять, а не помнить.
            if not старый:
                _сверить(стр, сенсор, f"после перехода на «{имя}»")
            if подготовка:
                try:
                    стр.click(подготовка, timeout=4000)
                    стр.wait_for_timeout(1200)
                except Exception as e:
                    print(f"   · {имя}: вкладка не открылась ({type(e).__name__}) — пропуск")
                    continue

            if контроль and (not КОНТРОЛЬ_ТОЛЬКО_НА
                             or КОНТРОЛЬ_ТОЛЬКО_НА in имя.lower()):
                положить_контроль(стр)

            # СТАРЫЙ ПОРЯДОК: снимок раньше замера, эмуляция не возвращается,
            # стражи нет. Ровно так инструмент и работал.
            if старый:
                стр.screenshot(path=f"{КУДА_СНИМКИ}/hover_{имя}.png",
                               full_page=True)

            # СРЫВ ПРИ ВКЛЮЧЁННОЙ СТРАЖЕ: то же разрушение, но `_сверить`
            # на месте. Проверка обязана упасть, а не напечатать число.
            if сорвать:
                стр.screenshot(path=f"{КУДА_СНИМКИ}/срыв_{имя}.png",
                               full_page=True)

            if снимки:
                _снимок(стр, cdp, сенсор, f"{КУДА_СНИМКИ}/hover_{имя}.png")

            if not старый:
                _сверить(стр, сенсор, f"перед замером «{имя}»")

            все_цели = _цели(стр)
            цели = _проредить(все_цели)
            пропущено = len(все_цели) - len(цели)
            всего_целей += len(цели)
            # Корень берётся ОДИН раз на экран. `DOM.getDocument` на каждый
            # элемент заставляет агента заново обходить дерево: на дневнике
            # это давало минуты вместо секунд, и «нет вывода» было
            # неотличимо от «ещё считает».
            корень = cdp.send("DOM.getDocument", {"depth": -1})["root"]["nodeId"]
            залипшие, отозвались, ответившие_сел = [], set(), set()
            for з in цели:
                менялось = _замер(стр, cdp, з["индекс"], корень,
                                  з.get("объявлено") or ())
                if менялось:
                    залипшие.append((з["селектор"], з["обёрнуто"], менялось))
                    отозвались.add(з["индекс"])
                    ответившие_сел.add(з["селектор"])

            метка = "сенсорная" if сенсор else "десктоп"
            if сенсор:
                печать = "ЗАЛИПАЕТ" if залипшие else "чисто"
                хвост = (f"  (ещё {пропущено} — те же правила)" if пропущено else "")
                print(f"   · {имя:<26} целей {len(цели):>3}   "
                      f"меняют вид {len(залипшие):>3}   {печать}{хвост}")
                for сел, обёрнуто, св in залипшие:
                    print(f"        {сел}  →  {', '.join(св)}"
                          f"   [{'в @media (hover: hover)' if обёрнуто else 'БЕЗ ОБЁРТКИ'}]")
                находки += [(имя, с, о, в) for с, о, в in залипшие]
            else:
                хвост = (f"  (ещё {пропущено} — те же правила)" if пропущено else "")
                # РАЗБИВКА МОЛЧАЩИХ. Без неё «отвечают 254 из 383» —
                # число, из которого нельзя сделать ни одного вывода.
                группы = {}
                for з in цели:
                    if з["индекс"] in отозвались:
                        continue
                    г = причина_молчания(з, ответившие_сел)
                    группы.setdefault(г, []).append(з["исходный"])
                    молчат.setdefault(г, []).append((имя, з["исходный"]))
                разбор = "  ".join("%s %d" % (г, len(в))
                                   for г, в in sorted(группы.items()))
                print(f"   · {имя:<26} целей {len(цели):>3}   "
                      f"отвечают {len(залипшие):>3}   молчат "
                      f"{len(цели) - len(залипшие):>3}   {разбор}{хвост}")
                находки += [(имя, с, о, в) for с, о, в in залипшие]

        бр.close()
    return находки, всего_целей, молчат



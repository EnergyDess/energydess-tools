def _ход_нажатия(стр, предел=8):
    """Жмёт органы, меняющие состояние, и считает ПОКАДРОВО.

    Отдаёт (перелив_сверх, просадка, целей, кадров, кто) — где первые
    два числа это ХУДШЕЕ по всем нажатиям.

    МЕРИТСЯ КАЖДОЕ НАЖАТИЕ ОТДЕЛЬНО, и это не педантизм. Первая версия
    брала покой один раз на весь обход и сравнивала с ним общий
    минимум — а отбор по чипу законно УКОРАЧИВАЕТ список: проба
    объявила бы находкой обычную работу фильтра. Находка — это провал
    НИЖЕ ОБОИХ устоявшихся состояний, до нажатия и после: содержимое
    исчезло на кадр и вернулось.

    ЖМЁТ ПО-НАСТОЯЩЕМУ, а не шлёт событие: тот же урок, что у задачи
    226 — проба, слащая не то событие, печатает «хода нет»
    про неоткрывшийся орган. Открылось ли состояние, видно по числу
    кадров и по тому, что величины вообще менялись.
    """
    цели = стр.evaluate("""(данные) => {
      const [органы, предел] = данные;
      const из = [];
      for (const сел of органы) {
        for (const э of document.querySelectorAll(сел)) {
          if (из.length >= предел) break;
          const r = э.getBoundingClientRect();
          if (r.width < 8 || r.height < 8) continue;
          if (r.top < 0 || r.top > window.innerHeight - 8) continue;
          if (r.left < 0 || r.left > window.innerWidth - 8) continue;
          const cs = getComputedStyle(э);
          if (cs.visibility === 'hidden' || cs.display === 'none') continue;
          // ССЫЛКА, УВОДЯЩАЯ НА ДРУГОЙ ДОКУМЕНТ, ЗДЕСЬ НЕ ЦЕЛЬ.
          // Вкладки админки — это `<a href>`: нажатие сносит страницу
          // вместе с сэмплером, и проба падала «Cannot read properties
          // of undefined» на третьем же экране. Промежуток между ДВУМЯ
          // документами — вопрос check_nav_flash (§6.0.16), а не этот.
          const сс = э.closest('a[href]');
          if (сс) {
            const u = new URL(сс.href, location.href);
            if (u.pathname !== location.pathname || u.origin !== location.origin)
              continue;
          }
          из.push({x: Math.round(r.left + r.width / 2),
                   y: Math.round(r.top + r.height / 2)});
        }
      }
      return из;
    }""", [list(ОРГАНЫ_НАЖАТИЯ), предел])
    if not цели:
        return None
    перелив_сверх, просадка, кадров, кто, устояв, ушли = 0, 0, 0, "", 0, 0
    for ц in цели:
        до = стр.evaluate(ПОКОЙ_НАЖАТИЯ)
        стр.evaluate(СЭМПЛЕР_НАЖАТИЯ)
        try:
            стр.mouse.click(ц["x"], ц["y"])
        except Exception:                            # noqa: BLE001
            стр.evaluate("() => window.__нж.стоп()")
            continue
        стр.wait_for_timeout(300)
        # СТРАХОВКА, А НЕ ГЛУШЕНИЕ ОШИБКИ: сэмплера не станет, если
        # нажатие всё-таки увело страницу. Тогда переход измерить
        # нечем, и цель ПРОПУСКАЕТСЯ — но пропуск виден по числу
        # кадров, а не проглатывается молча (§6.0.1).
        итог = стр.evaluate(
            "() => { if (!window.__нж) return null;"
            " window.__нж.стоп(); return window.__нж; }")
        if итог is None:
            ушли += 1
            continue
        после = стр.evaluate(ПОКОЙ_НАЖАТИЯ)
        кадров += итог["кадров"]
        сверх = итог["макс"] - max(до["перелив"], после["перелив"])
        if сверх > перелив_сверх:
            перелив_сверх, кто = сверх, итог["кто"]
        пол = min(до["высота"], после["высота"])
        if пол > 0 and пол - итог["мин"] > просадка:
            просадка = пол - итог["мин"]
        # ТО ЖЕ САМОЕ, НО ГЛАЗАМИ ОБЫЧНОЙ ПРОБЫ: разница двух
        # УСТОЯВШИХСЯ состояний, до нажатия и после. Считается тем же
        # проходом — вторая реализация той же величины разошлась бы
        # с первой молча (§6.0.7). Нужна только контролю: «подлог
        # найден» стоит чего-то лишь рядом с «прежним способом он
        # не находится».
        устояв = max(устояв,
                     после["перелив"] - до["перелив"],
                     до["высота"] - после["высота"])
        # Escape возвращает состояние, если нажатие открыло окно: без
        # него следующее нажатие пришлось бы по подложке модалки,
        # и проба мерила бы не переход, а промах.
        try:
            стр.keyboard.press("Escape")
        except Exception:                            # noqa: BLE001
            pass
        стр.wait_for_timeout(180)
    return (перелив_сверх, просадка, устояв, len(цели) - ушли,
            кадров, кто)


# подсказке: у наведения есть ход на каждой цели каждого экрана,
# и спросить его можно тем же способом.
#
# МЕРИТСЯ ГОРИЗОНТАЛЬНЫЙ ПЕРЕЛИВ, А НЕ «ИЗМЕНИЛОСЬ ЛИ ЧТО-ТО».
# Наведение обязано менять вид — в том и смысл `:hover`. Незаконно
# другое: чтобы страница на время перехода становилась ШИРЕ окна.
# Это видно человеку как рывок полосы прокрутки и не видно ни одной
# прежней пробе.
# ЧТО ИМЕННО МЕРИТСЯ — ЭТО ЗАМЕР, А НЕ ВЫБОР ИЗ ГОЛОВЫ.
#
# ПЕРВАЯ ВЕРСИЯ СЧИТАЛА ПЕРЕЛИВ ДОКУМЕНТА и была СЛЕПА: у `html`
# и у `body` в проекте стоит `overflow-x: clip`, и `scrollWidth`
# документа не растёт ВООБЩЕ. Замер: вставка блока шириной 130vw
# даёт 1425/1440 до и 1425/1440 после — то есть подлог был виден
# глазом и невидим мерке. Поймало это ДОКАЗАТЕЛЬСТВО (находок чисто 0,
# с подлогом 0), а не вердикт: слепая проба и зрячая дали бы тот же
# ноль (§6.0.3).
#
# МЕРИТСЯ ПЕРЕЛИВ ПРОКРУЧИВАЕМЫХ БЛОКОВ — ровно та величина, которой
# задача 226 нашла живой перелив у ряда вкладок: там `overflow-x: auto`,
# и полоса прокрутки появляется и исчезает у человека на глазах.
#
# СПИСОК БЛОКОВ СОБИРАЕТСЯ КАЖДЫЙ КАДР, а не один раз до наведения:
# блок, ПОЯВИВШИЙСЯ на время перехода, при разовом сборе не попал бы
# в замер вовсе — то есть проба молчала бы ровно про тот случай,
# ради которого написана.
СЭМПЛЕР = """() => {
  window.__ход = {макс: 0, кадров: 0, кто: ''};
  const тик = () => {
    let м = 0, кто = '';
    for (const э of document.querySelectorAll('*')) {
      const cs = getComputedStyle(э);
      if (cs.overflowX !== 'auto' && cs.overflowX !== 'scroll') continue;
      const п = Math.round(э.scrollWidth - э.clientWidth);
      if (п > м) { м = п; кто = э.className || э.tagName; }
    }
    if (м > window.__ход.макс) { window.__ход.макс = м; window.__ход.кто = кто; }
    window.__ход.кадров++;
    window.__ход.таймер = requestAnimationFrame(тик);
  };
  window.__ход.стоп = () => cancelAnimationFrame(window.__ход.таймер);
  тик();
}"""

ПОКОЙ = """() => {
  let м = 0;
  for (const э of document.querySelectorAll('*')) {
    const cs = getComputedStyle(э);
    if (cs.overflowX !== 'auto' && cs.overflowX !== 'scroll') continue;
    м = Math.max(м, Math.round(э.scrollWidth - э.clientWidth));
  }
  return м;
}"""


def _ход_экрана(стр, имя, предел=14):
    """Наводит указатель на цели и считает перелив ПОКАДРОВО.

    Отдаёт (в покое, максимум за переход, целей, кадров).

    ЦЕЛИ БЕРУТСЯ ТЕ ЖЕ, что у основного прогона: элементы, до которых
    `:hover` вообще дотягивается. Спрашивать «все видимые подряд»
    значило бы водить мышью по тексту.
    """
    цели = стр.evaluate("""(предел) => {
      const из = [];
      for (const э of document.querySelectorAll('*')) {
        if (из.length >= предел) break;
        const r = э.getBoundingClientRect();
        if (r.width < 8 || r.height < 8) continue;
        if (r.top < 0 || r.top > window.innerHeight - 8) continue;
        if (r.left < 0 || r.left > window.innerWidth - 8) continue;
        const cs = getComputedStyle(э);
        if (cs.visibility === 'hidden' || cs.display === 'none') continue;
        if (!э.matches('button, a, [data-doses], .chip, .card, .hint, .tab-btn'))
          continue;
        из.push({x: Math.round(r.left + r.width / 2),
                 y: Math.round(r.top + r.height / 2)});
      }
      return из;
    }""", предел)
    if not цели:
        return None
    покой = стр.evaluate(ПОКОЙ)
    стр.evaluate(СЭМПЛЕР)
    for ц in цели:
        стр.mouse.move(ц["x"], ц["y"])
        стр.wait_for_timeout(220)
        стр.mouse.move(2, 2)
        стр.wait_for_timeout(260)
    итог = стр.evaluate(
        "() => { window.__ход.стоп(); return window.__ход; }")
    return покой, итог["макс"], len(цели), итог["кадров"], итог["кто"]


def ход(браузер, экраны, ширина=1440, высота=900, подлог=False):
    """Прогон режима «ход» по всем экранам. Отдаёт список находок."""
    находки, снято = [], 0
    ctx = браузер.new_context(viewport={"width": ширина,
                                              "height": высота})
    if подлог:
        # ПОДЛОГ ВОЗВРАЩАЕТ ДЕФЕКТ ЗАДАЧИ 226 В ЧИСТОМ ВИДЕ: на время
        # наведения страница СТАНОВИТСЯ ШИРЕ ОКНА и через сто с лишним
        # миллисекунд снова сужается. Устоявшееся состояние при этом
        # ЧИСТО и до, и после — увидеть такое может только покадровый
        # замер, и в том весь смысл режима.
        #
        # ЭЛЕМЕНТОМ, А НЕ ПРАВИЛОМ `::after`: первая версия подлога
        # растила псевдоэлемент внутри кнопки и НЕ СОСТОЯЛАСЬ —
        # находок 0 и чисто, и с подлогом. Поймало это ДОКАЗАТЕЛЬСТВО
        # (числа находок рядом), а не вердикт: слепая проба и зрячая
        # дали бы тот же ноль (§6.0.3).
        ctx.add_init_script(
            "document.addEventListener('DOMContentLoaded', () => {"
            "  document.addEventListener('mouseover', (e) => {"
            "    if (!e.target || !e.target.closest) return;"
            "    if (!e.target.closest('button, a')) return;"
            "    let я = null;"
            "    for (const э of document.querySelectorAll('*')) {"
            "      const cs = getComputedStyle(э);"
            "      if (cs.overflowX === 'auto' || cs.overflowX === 'scroll') {"
            "        if (э.clientWidth > 50) { я = э; break; }"
            "      }"
            "    }"
            "    if (!я) return;"
            "    const d = document.createElement('div');"
            "    d.style.cssText = 'width:130vw;height:1px;"
            "pointer-events:none;flex:0 0 auto';"
            "    я.appendChild(d);"
            "    setTimeout(() => d.remove(), 140);"
            "  }, true); });")
    стр = ctx.new_page()
    нужен_вход = any(в for _, _, _, в in экраны) if экраны and len(
        экраны[0]) > 3 else True
    if нужен_вход:
        _войти(стр)
    for э in экраны:
        путь, имя = э[0], э[1]
        if "{" in путь:
            continue
        try:
            стр.goto(БАЗА + путь, wait_until="domcontentloaded")
            стр.wait_for_timeout(600)
        except Exception as e:                       # noqa: BLE001
            print("   %-26s не открылся: %s" % (имя, str(e)[:50]))
            continue
        из = _ход_экрана(стр, имя)
        if из is None:
            continue
        покой, макс, целей, кадров, кто = из
        снято += 1
        метка = "  находка" if макс > покой else ""
        print("   %-26s покой %4d  ход %4d  целей %2d  кадров %4d%s%s"
              % (имя[:26], покой, макс, целей, кадров, метка,
                 ("  <- " + str(кто)[:28]) if макс > покой else ""))
        if макс > покой:
            находки.append((имя, покой, макс))
    ctx.close()
    return находки, снято



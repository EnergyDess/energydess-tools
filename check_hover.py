def _обработчики_экранов():
    """Имена функций, которые отдают HTML СТРАНИЦЕЙ. Разбором дерева.

    ФРАГМЕНТ — НЕ ЭКРАН, И ЭТО ПРИЗНАК, А НЕ СТРОКА В СПИСКЕ.
    Обработчик, отдающий ПАРТИАЛ (имя шаблона начинается с `_`),
    возвращает кусок разметки без шапки, футера и `<html>`: сетку
    карточек аптечки, строки каталога, панель участников. Снимать
    его как экран значило бы мерить обломок и подписывать его
    страницей — тот же класс, что «снимать /login с сессией»
    (разбор у `_нужен_ли_вход`).

    Найдено ЗАМЕРОМ 2026-09-02: `/admin/api/enshrouded/rows`
    (BACKLOG №161) попал в список экранов и на стенде «до» отвечал
    404 — `check_regress` честно назвал 60 «пропавших» элементов
    страницы 404. Перечнем это не лечится: следующий партиал попал бы
    туда так же молча (§6.0.7).
    """
    import ast
    дерево = ast.parse(io.open("main.py", encoding="utf-8").read())
    имена = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef)):
            текст = ast.unparse(узел)
            if "TemplateResponse" not in текст and "HTMLResponse" not in текст:
                continue
            фрагмент = ("name='_" in текст or 'name="_' in текст)
            страница = re.search(r"name=['\"][^_'\"]", текст)
            if фрагмент and not страница:
                continue
            имена.add(узел.name)
    return имена


def _нужен_ли_вход(пути):
    """путь -> нужен ли вход. ПРОБОЙ, а не догадкой.

    Экран, который авторизованному отвечает редиректом, — гостевой:
    `/login` залогиненного уводит на лаунчер, и снимая его с сессией
    мы мерили бы совсем другую страницу, а подписывали бы «вход».
    Ровно тот класс отказа, ради которого весь этот файл.
    """
    import httpx
    ответ = {}
    with httpx.Client(base_url=БАЗА, follow_redirects=False, timeout=30) as c:
        r = c.post("/login", data={"email": ПОЧТА, "password": ПАРОЛЬ})
        if r.status_code != 302:
            raise RuntimeError(
                "проба не вошла в аккаунт (%s): список экранов вывести "
                "нечем" % r.status_code)
        for путь in пути:
            try:
                ответ[путь] = c.get(путь).status_code < 300
            except httpx.HTTPError as e:
                print("   · %s: проба не ответила (%s) — снимаем с сессией"
                      % (путь, type(e).__name__))
                ответ[путь] = True
    return ответ


def экраны_из_роутов():
    """[(путь, имя, нужен_вход, подготовка)] — ВЫВЕДЕННЫЙ список."""
    os.environ.setdefault("DB_PATH", "app.db")
    import main

    отдают_html = _обработчики_экранов()
    пути = []
    for маршрут in main.app.routes:
        путь = getattr(маршрут, "path", None)
        методы = getattr(маршрут, "methods", None)
        if not путь or not методы or "GET" not in методы:
            continue
        имя = getattr(getattr(маршрут, "endpoint", None), "__name__", "")
        if имя not in отдают_html:
            continue
        if путь == "/{slug}":
            # Статические страницы — из САМОГО СЛОВАРЯ, а не списком:
            # заведут шестую, и она снимется сама.
            пути += ["/" + s for s in main.STATIC_PAGES]
            continue
        if "{" in путь:
            # Путь с параметром экраном не является: подставить туда
            # осмысленное значение машина не может (живой токен сброса,
            # slug демо-программы). Названо границей, а не пропущено молча.
            continue
        if путь in НЕ_ЭКРАНЫ:
            continue
        пути.append(путь)

    пути = sorted(set(пути))
    вход = _нужен_ли_вход(пути)
    итог = [(п, п.strip("/") or "лаунчер", вход[п], None) for п in пути]
    итог += [(п, имя, True, подготовка) for п, имя, подготовка in СЦЕНЫ]
    return отобрать_экраны(итог)


# ОТБОР ПРОГОНА: ЭКРАНЫ И ШИРИНЫ
#
# Решение владельца 2026-08-23 (BACKLOG №148): ряд стенда обходит ВСЕ
# экраны поэлементно и занимает больше получаса, а заход, тронувший
# админку, получает из этого полезного ровно столько, сколько в нём
# админки.
#
# СПИСОК ЭКРАНОВ ПРИ ЭТОМ НЕ СУЖЕН, и это главное. Без переменной
# обходится всё, как и раньше; сокращается ПРОГОН, и видно это
# в команде, а не в чужом файле. Тот же приём и та же причина, что
# у `DIFF_WIDTHS` и `REGRESS_WIDTHS` (§6.0.3): сужать сам ВОПРОС
# принимающей проверки нельзя, а объявить в окружении, что сегодня
# спрашиваем не всё, — можно.
#
#     STAND_SCREENS=admin py check_hover.py      подстроки через запятую
#     STAND_WIDTHS=2560,390 py check_overlap.py  ширины через запятую
#
# МЕСТО ОДНО НА ПЯТЬ ПРОВЕРОК: `check_focus`, `check_touch`,
# `check_overlap`, `check_regress` и сам `check_hover` берут список
# у `экраны_из_роутов()`. Пять копий отбора разошлись бы молча — ровно
# то, из-за чего перечень экранов и перестал быть перечнем (§6.0.7).

def отобрать_экраны(экраны):
    """Сузить прогон переменной STAND_SCREENS. Пусто — вернуть всё."""
    отбор = os.environ.get("STAND_SCREENS", "").strip()
    if not отбор:
        return экраны
    куски = [к.strip().lower() for к in отбор.split(",") if к.strip()]
    оставили = [э for э in экраны
                if any(к in э[0].lower() or к in э[1].lower() for к in куски)]
    if not оставили:
        # Пустой прогон напечатал бы «находок 0» про НЕПРОВЕРЕННОЕ,
        # то есть немой отказ внутри самой проверки (§6.0.1).
        raise RuntimeError(
            "STAND_SCREENS=%r не совпал НИ С ОДНИМ экраном из %d. "
            "Молчаливый пустой прогон был бы неотличим от чистого."
            % (отбор, len(экраны)))
    print("  STAND_SCREENS=%s — прогон сужен до %d экранов из %d"
          % (отбор, len(оставили), len(экраны)))
    return оставили


def отобрать_ширины(ширины):
    """Сузить прогон переменной STAND_WIDTHS. Пусто — вернуть всё.

    `ширины` — список кортежей, у которых ПЕРВЫЙ элемент число.

    ГДЕ ЭТО НЕ ПРИМЕНЯЕТСЯ И ПОЧЕМУ. У `check_hover` и `check_focus`
    десктопная ширина — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: «на десктопе не ответил
    никто» там означает сломанную проверку, а не чистые страницы.
    Выкинув её, мы получили бы проверку, которая не отличает «находить
    нечего» от «замер не дошёл». Поэтому обе там зашиты, и это решение,
    а не недоделка."""
    отбор = os.environ.get("STAND_WIDTHS", "").replace(" ", "")
    if not отбор:
        return ширины
    нужные = {int(ч) for ч in отбор.split(",") if ч}
    оставили = [ш for ш in ширины if ш[0] in нужные]
    if not оставили:
        raise RuntimeError("STAND_WIDTHS=%r не совпал ни с одной шириной из %s"
                           % (отбор, [ш[0] for ш in ширины]))
    return оставили



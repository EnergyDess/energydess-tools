# -*- coding: utf-8 -*-
"""Проверка 8: правило по id, меняющее системный компонент.

Зачем отдельная форма. Проверка 1 из CLAUDE.md §6.0.2 ищет системный класс
СУБЪЕКТОМ селектора — `.hero .btn-primary { … }`. Правило `#hero-cta { … }`
на том же элементе она не видит вовсе, а весит оно больше: id — это (1,0,0),
любой класс — (0,1,0). То есть форма и невидимая, и более сильная разом.

Отказ немой в обе стороны. Компонент рисуется не так, как в системе,
и понять это по коду нельзя: разметка верная, класс на месте, консоль
чистая. А починка компонента в style.css до такого элемента не доедет —
правило по id выигрывает и у медиазапроса, и у нового варианта.

ПОЧЕМУ СКРИПТ, А НЕ ВОСЬМОЙ ГРЕП. Разница между долгом и законной строкой
не видна в самом правиле. `#job-input { min-height: 300px }` законно
(высота экземпляра), `#job-input { font-size: … }` — долг (кегль
принадлежит компоненту), и отличает их не селектор, а ДВЕ вещи сразу:
какие свойства объявлены и носит ли элемент с этим id системный класс.
Второе лежит в разметке, а не в CSS. Замерено на живом дереве 2026-08-11:
правил по id в проекте 49, на элементе с системным классом — 4. Греп
без разбора разметки печатал бы 49 строк, из которых 45 — чужие: это
92% ложных, а проверка, которая врёт, перестаёт читаться на третий раз
(тот же довод, что про `_admin_nav.html` в проверке 4).

ДВА ШАГА:
  1. по разметке (templates/*.html и static/*.js — HTML собирает и Jinja,
     и скрипт шаблонными строками) собрать «какой id какие классы носит»;
  2. по CSS (static/*.css и инлайновые <style>) собрать правила, чей
     СУБЪЕКТ — #id. Субъект = последняя связка селектора: у `#x .card`
     субъект `.card`, и это уже случай проверки 1, не наш.

Пересечение классов элемента с компонентной базой и есть находка. Дальше
свойства правила делятся на две кучи, и делятся они по тому же критерию,
что первое число §6.0.2:

  раскладка экземпляра — width/height/min-*/max-*/flex/margin/position/…
      Место элемента в сетке родителя. Родитель распоряжается им
      по построению — законно, печатается и в код возврата не идёт.
  вид компонента — font-*/color/background/border/radius/padding/shadow
      Это уже сам компонент. Долг: либо вариант в системе, либо снять.

СПИСОК КОМПОНЕНТОВ НЕ ДУБЛИРУЕТСЯ. Он читается из строки `names='…'`
в CLAUDE.md §6.0.2 — там же, где его берёт проверка 1. Вторая копия
разошлась бы с первой молча, а это ровно та болезнь, которую §6.0.2
лечит. Нет строки — скрипт падает с кодом 2 и говорит об этом, а не
проходит с пустым списком: whitelist, который молча опустел, печатает
«чисто» про всё на свете.

ГРАНИЦА — что проверка НЕ видит:
  * класс, навешенный скриптом (`el.classList.add('card')`): в разметке
    его нет, а исполнять скрипт проверка не может;
  * id, собранный в рантайме (`id="row-" + n`): в исходнике такой строки
    не существует;
  * атрибут `style=` на том же элементе — это проверка 3, не эта;
  * правило по id в файле, который не .css и не <style> (в проекте
    таких нет).

Код возврата: 0 — долга нет (законные строки при этом печатаются),
1 — есть долг, 2 — сломан сам разбор (нет CLAUDE.md или строки names).

Запуск:  py check_ids.py     (ИМЕННО py: python на машине Дениса —
                              заглушка Store, код 9009 без запуска)
"""
import re
import sys
import pathlib
import collections

import project_lists as списки

КОРЕНЬ = pathlib.Path(__file__).parent

# Свойства, которыми родитель распоряжается по построению: они описывают
# МЕСТО элемента, а не вид компонента. Сверено с таблицей законных
# в CLAUDE.md §6.0.2 — там перечислены ровно эти основания.
РАСКЛАДКА = {
    'width', 'height', 'min-width', 'min-height', 'max-width', 'max-height',
    'flex', 'flex-grow', 'flex-shrink', 'flex-basis', 'order', 'align-self',
    'justify-self', 'grid-area', 'grid-column', 'grid-row',
    'margin', 'margin-top', 'margin-right', 'margin-bottom', 'margin-left',
    'position', 'top', 'right', 'bottom', 'left', 'z-index', 'display',
    'justify-content', 'align-items', 'gap', 'overflow', 'overflow-x',
    'overflow-y', 'resize',
}


def системные_классы():
    """Компонентная база — из строки names='…' в CLAUDE.md §6.0.2.

    Единственный источник, и читатель у него тоже один: разбор живёт
    в `project_lists`, оттуда же берёт список `check_metrics.py`.
    До 2026-08-19 разборов было два — свой здесь и своя копия строки
    там, — и вторая отстала на 23 имени.
    """
    return set(списки.имена_компонентов())


def классы_по_id():
    """id → набор классов на этом элементе, по всей разметке проекта."""
    итог = collections.defaultdict(set)
    файлы = (sorted((КОРЕНЬ / 'templates').glob('*.html'))
             + sorted((КОРЕНЬ / 'static').glob('*.js')))
    for f in файлы:
        for тег in re.findall(r'<[a-zA-Z][^>]*>', f.read_text(encoding='utf-8'), re.S):
            m_id = re.search(r'\bid\s*=\s*["\']([A-Za-z][\w-]*)["\']', тег)
            if not m_id:
                continue
            m_cls = re.search(r'\bclass\s*=\s*["\']([^"\']*)["\']', тег)
            if m_cls:
                итог[m_id.group(1)] |= set(m_cls.group(1).split())
    return итог


def правила_по_id():
    """Правила, чей субъект — #id. Возвращает список словарей."""
    итог = []
    файлы = (sorted((КОРЕНЬ / 'static').glob('*.css'))
             + sorted((КОРЕНЬ / 'templates').glob('*.html')))
    for f in файлы:
        текст = f.read_text(encoding='utf-8')
        if f.suffix == '.html':
            куски = [(к, текст[:текст.find(к)].count('\n') + 1)
                     for к in re.findall(r'<style[^>]*>(.*?)</style>', текст, re.S)]
        else:
            куски = [(текст, 0)]

        for кусок, сдвиг in куски:
            # комментарии вырезаем, сохраняя переводы строк — иначе номера уедут
            чисто = re.sub(r'/\*.*?\*/',
                           lambda m: '\n' * m.group(0).count('\n'), кусок, flags=re.S)
            for m in re.finditer(r'([^{}/]+?)\{([^{}]*)\}', чисто, re.S):
                селектор, тело = m.group(1).strip(), m.group(2)
                if '#' not in селектор or '@' in селектор:
                    continue
                строка = сдвиг + чисто[:m.start()].count('\n') + (1 if f.suffix == '.css' else 0)
                for один in (с.strip() for с in селектор.split(',')):
                    субъект = re.split(r'[\s>+~]+', один)[-1] if один else ''
                    m_id = re.match(r'^#([A-Za-z][\w-]*)', субъект)
                    if not m_id:
                        continue
                    итог.append({
                        'файл': str(f.relative_to(КОРЕНЬ)).replace('\\', '/'),
                        'строка': строка,
                        'селектор': один,
                        'id': m_id.group(1),
                        'свойства': [с.split(':')[0].strip()
                                     for с in тело.split(';') if ':' in с and с.strip()],
                    })
    return итог


def main():
    база = системные_классы()
    носители = классы_по_id()
    правила = правила_по_id()

    долг, законные = [], []
    for п in правила:
        свои = носители.get(п['id'], set()) & база
        if not свои:
            continue
        п['компонент'] = sorted(свои)
        вид = [с for с in п['свойства'] if с not in РАСКЛАДКА and not с.startswith('--')]
        (долг if вид else законные).append((п, вид))

    print('Проверка 8 — правила по id на системных компонентах\n')
    print(f'  правил по id в проекте:            {len(правила)}')
    print(f'  из них на системном компоненте:    {len(долг) + len(законные)}')
    print(f'  из них меняют ВИД компонента:      {len(долг)}\n')

    if законные:
        print('--- законные: только раскладка экземпляра ---')
        for п, _ in законные:
            print(f"  {п['файл']}:{п['строка']}  {п['селектор']}"
                  f"  на .{'/.'.join(п['компонент'])}")
            print(f"      {', '.join(п['свойства'])}")
        print()

    if долг:
        print('--- ДОЛГ: правило по id меняет вид компонента ---')
        for п, вид in долг:
            print(f"  {п['файл']}:{п['строка']}  {п['селектор']}"
                  f"  на .{'/.'.join(п['компонент'])}")
            print(f"      вид:       {', '.join(вид)}")
            прочее = [с for с in п['свойства'] if с not in вид]
            if прочее:
                print(f"      раскладка: {', '.join(прочее)}")
        print('\nЧто делать: либо свойство принадлежит компоненту и уезжает\n'
              'вариантом в style.css, либо оно лишнее и снимается. Разбор —\n'
              'CLAUDE.md §6.0.2, «Проверка 8».')
        return 1

    print('Долга нет.')
    return 0


if __name__ == '__main__':
    sys.exit(main())

def _имена_места(строка):
    """Файлы строки: сам файл и, у ролика, его первый кадр."""
    имена = ["%s-%s.%s" % (строка["slot_id"], строка["version"], строка["ext"])]
    if строка["ext"] == "mp4":
        имена.append("%s-%s.poster.webp" % (строка["slot_id"], строка["version"]))
    return имена


def снимок_мест(места, путь_базы):
    """{место: None | (строка, {имя: байты})} — ровно то, что лежит."""
    к = каталог_тома(путь_базы)
    c = sqlite3.connect(путь_базы)
    c.row_factory = sqlite3.Row
    try:
        снимок = {}
        for м in места:
            r = c.execute("SELECT * FROM landing_media WHERE slot_id=?", (м,)).fetchone()
            if r is None:
                снимок[м] = None
                continue
            строка = dict(r)
            файлы = {}
            for имя in _имена_места(строка):
                путь = os.path.join(к, имя)
                if os.path.exists(путь):
                    with open(путь, "rb") as ф:
                        файлы[имя] = ф.read()
            снимок[м] = (строка, файлы)
        return снимок
    finally:
        c.close()


def очистить_места(места, путь_базы):
    """Строка и её файлы уходят. Файл, которого уже нет, — не ошибка."""
    к = каталог_тома(путь_базы)
    c = sqlite3.connect(путь_базы)
    c.row_factory = sqlite3.Row
    try:
        for м in места:
            r = c.execute("SELECT * FROM landing_media WHERE slot_id=?", (м,)).fetchone()
            if r is None:
                continue
            c.execute("DELETE FROM landing_media WHERE slot_id=?", (м,))
            c.commit()
            for имя in _имена_места(dict(r)):
                try:
                    os.remove(os.path.join(к, имя))
                except FileNotFoundError:
                    pass
    finally:
        c.close()


def вернуть_места(снимок, путь_базы):
    """Возвращает места к снимку: нынешнее снимается, снятое кладётся."""
    очистить_места(list(снимок), путь_базы)
    к = каталог_тома(путь_базы)
    os.makedirs(к, exist_ok=True)
    c = sqlite3.connect(путь_базы)
    try:
        for м, было in снимок.items():
            if было is None:
                continue
            строка, файлы = было
            for имя, байты in файлы.items():
                with open(os.path.join(к, имя), "wb") as ф:
                    ф.write(байты)
            поля = sorted(строка)
            c.execute("INSERT INTO landing_media (%s) VALUES (%s)"
                      % (", ".join(поля), ", ".join("?" * len(поля))),
                      [строка[п] for п in поля])
        c.commit()
    finally:
        c.close()


def отпечатки_мест(места, путь_базы):
    """{место: 12 знаков sha256 строки и файлов | 'пусто'} — для сверки."""
    import hashlib
    итог = {}
    for м, было in снимок_мест(места, путь_базы).items():
        if было is None:
            итог[м] = "пусто"
            continue
        строка, файлы = было
        h = hashlib.sha256(repr(sorted(строка.items())).encode("utf-8"))
        for имя in sorted(файлы):
            h.update(имя.encode("utf-8"))
            h.update(файлы[имя])
        итог[м] = "%s (%s)" % (h.hexdigest()[:12], ", ".join(sorted(файлы)) or "файлов нет")
    return итог



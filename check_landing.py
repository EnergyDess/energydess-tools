def адрес_стенда(адрес, путь_базы):
    """Причина отказа строкой либо None. Спрашивается ДО любого запроса."""
    from urllib.parse import urlsplit
    хост = urlsplit(адрес).hostname
    if хост not in ХОСТЫ_СТЕНДА:
        return "хост %r не стенд (разрешены: %s)" % (хост, ", ".join(ХОСТЫ_СТЕНДА))

# -*- coding: utf-8 -*-
"""ФОН ГЛАВНОЙ: ВЕС И КАЧЕСТВО СЖАТОГО РОЛИКА (заход 342, блок A).

  py check_landing_bg.py ВЕРХ.mp4 НИЗ.mp4              # замер боевым конвейером
  py check_landing_bg.py ВЕРХ.mp4 НИЗ.mp4 --контроль   # подлог: пережать crf 42

Файлы можно не передавать, а объявить окружением: `BG_TOP`, `BG_BOTTOM`.
Не передано ничего — ПРОПУСК и код 2: мерить нечего (§6.0.1).

ЧТО МЕРЯЕТ — ТО, ЧТО ВИДИТ ЧЕЛОВЕК НА ФОНЕ, А НЕ РЕЗКОСТЬ.
Фон размытый и тёмный; сжатие на нём ломается первым на РОВНЫХ ТЁМНЫХ
участках — градиент начинает «кипеть» пятнами. Поэтому:
  · маска — блоки 8×8 ИСХОДНИКА, средняя яркость ниже 56 и разброс
    внутри блока ниже 2 уровней (ровное и тёмное);
  · ОШИБКА — средняя разница сжатого и исходника по блоку маски, p99;
  · КИПЕНИЕ — насколько яркость блока маски между соседними кадрами
    скачет у сжатого СВЕРХ того, как скачет у исходника, p99.9.
Сравнение на полном разрешении 1920 (сжатый растягивается бикубически,
как растянет браузер): уменьшенные кадры усредняют ровно тот шум,
который ищем.

ПОРОГ — ПРЕДЛОЖЕНИЕ, А НЕ ЗАКОН, И ОН ВЫВЕДЕН ЛЕСЕНКОЙ (landing_defs):
ошибка p99 и кипение p99.9 — не больше 3 уровней из 255. crf 30 лёгкого
режима даёт 2.0 и 2.2–2.4, crf 33 — 2.5–2.7 и 3.1–3.5. Решение
о размене за владельцем: пары кадров кладутся в `review_screenshots/342/`.

МЕРКА НЕ БЕРЁТ ДАННЫЕ У ПРОВЕРЯЕМОГО КОДА: сжимает боевой
`landing_media.обработать`, а качество, звук, длительность и стык считает
своим разбором кадров ffmpeg, без `разобрать_ролик`.

СТЫК ПЕТЛИ — СВЕДЕНИЕ ДЛЯ МОНТАЖА, в код возврата не идёт: разница
последнего и первого кадра против самой большой разницы соседних кадров.
Больше — стык виден, и это к монтажу, не к коду.
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
os.environ.setdefault("DB_PATH", "app.db")
import probe_guard  # noqa: E402,F401  ПРОПУСК вместо трассы (§6.0.1)

sys.stdout.reconfigure(encoding="utf-8")

ПОРОГ_ОШИБКИ = 3.0
ПОРОГ_КИПЕНИЯ = 3.0
W, H, B = 1920, 1072, 8          # 1072 — кратно 8, низ в 8 px в маску не идёт
КАТАЛОГ_КАДРОВ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "review_screenshots", "342")

ДОКАЗАТЕЛЬСТВА = {
    "фон пережат (crf 42)": "вес сжатого файла, КБ: обычный -> подлог (меньше)",
}

итог = {"плохо": 0, "пропуск": 0}


def шаг(имя, условие, подробность="", собрано=None, отрицание=""):
    if собрано is not None and not собрано and not отрицание:
        итог["пропуск"] += 1
        print("  %-7s %s — сбор пуст, мерить нечего" % ("ПРОПУСК", имя))
        return None
    if not условие:
        итог["плохо"] += 1
    print("  %-7s %s%s" % ("OK" if условие else "ПЛОХО", имя,
                           (" — " + подробность) if подробность else ""))
    return bool(условие)


def _ff():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def _сведения(путь):
    """(длительность, звук) по заголовку ffmpeg — свой разбор."""
    п = subprocess.run([_ff(), "-hide_banner", "-i", путь], capture_output=True,
                       text=True, encoding="utf-8", errors="replace")
    м = re.search(r"Duration: (\d+):(\d+):(\d+(?:\.\d+)?)", п.stderr)
    длит = int(м.group(1)) * 3600 + int(м.group(2)) * 60 + float(м.group(3)) if м else None
    return длит, bool(re.search(r"Stream #0:\d+[^\n]*: Audio:", п.stderr))


def _поток(путь):
    return subprocess.Popen([_ff(), "-hide_banner", "-loglevel", "error", "-i", путь,
                             "-vf", "scale=1920:1080:flags=bicubic,crop=%d:%d:0:0" % (W, H),
                             "-pix_fmt", "gray", "-f", "rawvideo", "-"], stdout=subprocess.PIPE)


def _кадр(поток):
    import numpy as np
    б = поток.stdout.read(W * H)
    return None if len(б) < W * H else np.frombuffer(б, np.uint8).reshape(H, W).astype(np.float32)


def _блоки(а):
    return а.reshape(H // B, B, W // B, B)


def маска(исходник):
    п = _поток(исходник)
    сум_ср, сум_разб, n = 0, 0, 0
    while (к := _кадр(п)) is not None:
        б = _блоки(к)
        сум_ср = сум_ср + б.mean(axis=(1, 3))
        сум_разб = сум_разб + б.std(axis=(1, 3))
        n += 1
    return (сум_ср / n < 56) & (сум_разб / n < 2.0)


def качество(исходник, сжатый, м):
    import numpy as np
    пи, пс = _поток(исходник), _поток(сжатый)
    прошл_и = прошл_с = None
    ошибки, кипение = [], []
    while True:
        и, с = _кадр(пи), _кадр(пс)
        if и is None or с is None:
            break
        ср_и, ср_с = _блоки(и).mean(axis=(1, 3)), _блоки(с).mean(axis=(1, 3))
        ошибки.append(_блоки(np.abs(с - и)).mean(axis=(1, 3))[м])
        if прошл_и is not None:
            кипение.append((np.abs(ср_с - прошл_с) - np.abs(ср_и - прошл_и))[м])
        прошл_и, прошл_с = ср_и, ср_с
    пи.kill()
    пс.kill()
    if not ошибки or not кипение:
        return None
    е, к = np.concatenate(ошибки), np.concatenate(кипение)
    return {"ошибка_p99": float(np.percentile(е, 99)), "кипение_p999": float(np.percentile(к, 99.9)),
            "кадров": len(ошибки), "блоков": int(м.sum())}


def стык(исходник):
    import numpy as np
    п = _поток(исходник)
    кадры = []
    while (к := _кадр(п)) is not None:
        кадры.append(к)
    if len(кадры) < 3:
        return None
    соседние = [float(np.abs(кадры[i + 1] - кадры[i]).mean()) for i in range(len(кадры) - 1)]
    return float(np.abs(кадры[0] - кадры[-1]).mean()), max(соседние), float(np.median(соседние))


def пары_кадров(метка, исходник, сжатый, м, пережатый=None):
    """Кусок самой ровной тёмной области: исходник | сжатый [| пережатый],
    сверху как есть, снизу с яркостью ×5 — иначе на тёмном не видно ничего."""
    import numpy as np
    from PIL import Image
    os.makedirs(КАТАЛОГ_КАДРОВ, exist_ok=True)
    # окно 480×270, где больше всего блоков маски
    ок_в, ок_ш = 270 // B, 480 // B
    плотн = np.lib.stride_tricks.sliding_window_view(м.astype(np.int32), (ок_в, ок_ш)).sum(axis=(2, 3))
    y, x = np.unravel_index(np.argmax(плотн), плотн.shape)
    y, x = y * B, x * B
    кадр_t = "00:00:04"
    куски = []
    for путь in [исходник, сжатый] + ([пережатый] if пережатый else []):
        п = subprocess.run([_ff(), "-hide_banner", "-loglevel", "error", "-ss", кадр_t, "-i", путь,
                            "-frames:v", "1", "-vf", "scale=1920:1080:flags=bicubic",
                            "-pix_fmt", "rgb24", "-f", "rawvideo", "-"], capture_output=True)
        а = np.frombuffer(п.stdout, np.uint8).reshape(1080, 1920, 3)[y:y + 270, x:x + 480]
        куски.append(а)
    холст = Image.new("RGB", (480 * len(куски), 540))
    for i, а in enumerate(куски):
        холст.paste(Image.fromarray(а), (480 * i, 0))
        холст.paste(Image.fromarray(np.clip(а.astype(np.int32) * 5, 0, 255).astype(np.uint8)), (480 * i, 270))
    путь = os.path.join(КАТАЛОГ_КАДРОВ, "bg-%s-flat.png" % метка)
    холст.save(путь)
    return путь, (x, y)


def прогон(верх, низ, контроль=False):
    import landing_defs as ld
    import landing_media as лм
    раб = tempfile.mkdtemp(prefix="bg342-")
    try:
        for место, исходник in (("bg-top", верх), ("bg-bottom", низ)):
            print("\n  ── %s: %s" % (место, os.path.basename(исходник)))
            копия = os.path.join(раб, место + "-in")
            shutil.copy2(исходник, копия)
            длит_и, звук_и = _сведения(копия)
            готовый, св, пред = лм.обработать(место, копия, os.path.basename(исходник))
            вес_и, вес_с = os.path.getsize(копия), os.path.getsize(готовый)
            длит_с, звук_с = _сведения(готовый)
            print("  вес: %.2f МБ -> %.2f МБ (%d КБ), %s; %dx%d" % (
                вес_и / 1048576, вес_с / 1048576, вес_с // 1024,
                "положен исходный" if св.get("kept_original") else "положен сжатый",
                св["width"], св["height"]))
            print("  длительность: %.2f с -> %.2f с; звук: %s -> %s" % (
                длит_и or 0, длит_с or 0, "есть" if звук_и else "нет", "есть" if звук_с else "нет"))
            постер = св.get("poster")
            print("  первый кадр: %s" % ("%d КБ" % (os.path.getsize(постер) // 1024) if постер else "НЕ СНЯТ"))
            if пред:
                print("  предупреждения конвейера: " + "; ".join(пред))
            шаг("%s: в сжатом нет звука" % место, not звук_с, "звук %s" % звук_с)
            шаг("%s: вес не больше %d МБ" % (место, ld.ВИДЕО_СЖАТИЕ["bg"]["итог_мб"]),
                вес_с <= ld.ВИДЕО_СЖАТИЕ["bg"]["итог_мб"] * 1048576, "%d КБ" % (вес_с // 1024))
            м = маска(копия)
            к = качество(копия, готовый, м)
            шаг("%s: ровные тёмные участки — ошибка p99 ≤ %.1f, кипение p99.9 ≤ %.1f уровня"
                % (место, ПОРОГ_ОШИБКИ, ПОРОГ_КИПЕНИЯ),
                к is not None and к["ошибка_p99"] <= ПОРОГ_ОШИБКИ and к["кипение_p999"] <= ПОРОГ_КИПЕНИЯ,
                ("ошибка %.2f, кипение %.2f, блоков маски %d, кадров %d"
                 % (к["ошибка_p99"], к["кипение_p999"], к["блоков"], к["кадров"])) if к else "кадров нет",
                собрано=int(м.sum()))
            с = стык(копия)
            if с:
                print("  стык петли: последний→первый %.2f при максимуме соседних %.2f (медиана %.2f) — %s" % (
                    с[0], с[1], с[2], "ВИДЕН, это к монтажу" if с[0] > с[1] else "в пределах движения"))
            пережатый = None
            if контроль:
                исходные = dict(ld.ВИДЕО_СЖАТИЕ["bg"])
                ld.ВИДЕО_СЖАТИЕ["bg"]["crf"] = 42
                try:
                    пережатый = os.path.join(раб, место + "-over.mp4")
                    г2, _, _ = лм.обработать(место, копия, "over.mp4")
                    shutil.copy2(г2, пережатый)
                finally:
                    ld.ВИДЕО_СЖАТИЕ["bg"].clear()
                    ld.ВИДЕО_СЖАТИЕ["bg"].update(исходные)
                вес_п = os.path.getsize(пережатый)
                print("  ПОДЛОГ crf 42: доказательство вес %d КБ -> %d КБ" % (вес_с // 1024, вес_п // 1024))
                кп = качество(копия, пережатый, м)
                поймал = кп is not None and (кп["ошибка_p99"] > ПОРОГ_ОШИБКИ or кп["кипение_p999"] > ПОРОГ_КИПЕНИЯ)
                print("  ПОДЛОГ: ошибка %.2f, кипение %.2f — %s" % (
                    кп["ошибка_p99"], кп["кипение_p999"], "ЛОВИТ" if поймал and вес_п < вес_с else "НЕ ЛОВИТ"))
                if not (поймал and вес_п < вес_с):
                    итог["плохо"] += 1
            путь, (x, y) = пары_кадров(место, копия, готовый, м, пережатый)
            print("  пара кадров ровной области (x=%d, y=%d): %s" % (x, y, путь))
    finally:
        shutil.rmtree(раб, ignore_errors=True)


def main():
    арг = [а for а in sys.argv[1:] if not а.startswith("--")]
    верх = арг[0] if len(арг) > 0 else os.environ.get("BG_TOP")
    низ = арг[1] if len(арг) > 1 else os.environ.get("BG_BOTTOM")
    контроль = "--контроль" in sys.argv
    print("ФОН ГЛАВНОЙ: вес и качество боевого сжатия%s" % (" · КОНТРОЛЬ" if контроль else ""))
    if not (верх and низ and os.path.exists(верх) and os.path.exists(низ)):
        probe_guard.сказать_пропуск("нет исходных роликов фона",
                                    "передайте два файла или BG_TOP и BG_BOTTOM")
        return 2
    прогон(верх, низ, контроль)
    print("\nИТОГ: ПЛОХО %d, ПРОПУСК %d" % (итог["плохо"], итог["пропуск"]))
    if итог["плохо"]:
        return 1
    return 2 if итог["пропуск"] else 0


if __name__ == "__main__":
    sys.exit(main())

def история(путь: str) -> int:
    """Письма владельца (user_id 1) в КОПИИ базы: сколько предлагают созвон,
    тестовое и упоминают зарплату. Считает все три раздела НЕЗАВИСИМО от
    настроек — вопрос «было ли», а не «было ли нарушением тогда»: какие
    настройки досье стояли в день письма, в базе не хранится.
    Текста писем не печатает; по разделу — дата и найденный кусок."""
    import sqlite3
    if "/data/" in путь.replace("\\", "/"):
        print("ПРОПУСК: путь к боевой базе — только копия")
        return 2
    if not os.path.exists(путь):
        print(f"ПРОПУСК: копии нет ({путь})")
        return 2
    c = sqlite3.connect(f"file:{путь}?mode=ro", uri=True)
    ф = lf.фразы()
    счёт = {"созвон": 0, "тестовое": 0, "зарплата": 0}
    первые = {}
    n = 0
    for lid, дата, текст in c.execute(
            "SELECT id, created_at, letter_text FROM cover_letters "
            "WHERE user_id = 1 AND deleted_at IS NULL ORDER BY id"):
        n += 1
        for раздел in счёт:
            м = lf._первое(текст or "", ф[раздел])
            if м:
                счёт[раздел] += 1
                первые.setdefault(раздел, (lid, (дата or "")[:10], м.group(0)))
    if not n:
        print("ПРОПУСК: писем владельца в копии нет")
        return 2
    print(f"ПИСЕМ ВЛАДЕЛЬЦА: {n}; созвон или встреча {счёт['созвон']}, "
          f"тестовое {счёт['тестовое']}, зарплата {счёт['зарплата']}")
    for раздел, (lid, дата, кусок) in первые.items():
        print(f"  {раздел}: первое — письмо {lid} от {дата}, совпало {кусок!r}")
    return 0



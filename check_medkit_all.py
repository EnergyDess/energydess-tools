def включить_кеш():
    """Подменяет СЕТЬ, и только её. Ни один шаг сопоставления не тронут."""
    os.makedirs(КЕШ, exist_ok=True)
    родная = main._апт_страница

    async def кеширующая(клиент, адрес):
        имя = os.path.join(
            КЕШ, hashlib.sha256(адрес.encode()).hexdigest()[:32] + ".html")
        if os.path.exists(имя):
            return open(имя, encoding="utf-8", errors="replace").read()
        текст = await родная(клиент, адрес)
        open(имя, "w", encoding="utf-8", errors="replace").write(текст)
        return текст

    main._апт_страница = кеширующая



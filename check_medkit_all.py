    нашлось = счёт.get("НАШЛОСЬ", 0)
    print("   %-16s %d из %d" % ("ИТОГО нашлось", нашлось, всего))
    # ── ОХВАТ ПОКАЗАНИЙ (BACKLOG №227, A.10) ────────────────────────
    #
    # ЧИСЛА ТРИ, А НЕ ОДНО, и третье важнее первых двух: позиция,
    # у которой НЕТ СХЕМЫ, не может иметь и показаний — они с той же
    # страницы. Свалив её в общее «нет показаний», замер объявил бы
    # долгом то, что долгом не является.
    с_пок = sum(1 for с in строки if с["пок_знаков"])
    без_пок_при_схеме = sum(1 for с in строки
                            if с["нашлось"] and not с["пок_знаков"])
    без_страницы = сумма_без_страницы = всего - нашлось
    print()
    print("ПОКАЗАНИЯ («от чего это»):")
    print("   %-40s %d из %d" % ("показания НАШЛИСЬ", с_пок, всего))
    print("   %-40s %d" % ("схема есть, раздела показаний НЕТ",
                           без_пок_при_схеме))
    print("   %-40s %d" % ("страницы препарата нет вовсе "
                           "(показаний быть не может)", без_страницы))

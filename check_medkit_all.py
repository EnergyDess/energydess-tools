ФОРМА_РУС = {ф["id"]: ф["имя"] for ф in опр.ФОРМЫ}


def доза_словом(вещество):
    """Дозировка из поля вещества — то же, что читает сопоставление."""
    ч = дозы.числа(вещество or "")
    return ", ".join(sorted("%s %s" % (a, b) for a, b in ч)) if ч else ""


def вещество_словом(вещество):
    return re.split(r"[,;(]", (вещество or "").strip())[0].strip()


async def прогон(поз):
    return await main._апт_найти_дозы(поз)


def таблица(из):
    строки, счёт = [], {}
    for п in из:
        итог, причина, вид, подсказка = asyncio.run(прогон(п))
        нашлось = bool(итог)
        ключ = "НАШЛОСЬ" if нашлось else (вид or "—")
        счёт[ключ] = счёт.get(ключ, 0) + 1
        строки.append({
            "id": п.id, "название": " ".join((п.name or "").split()),
            "вещество": вещество_словом(п.substance),
            "форма": ФОРМА_РУС.get(п.form, п.form or "—"),
            "доза": доза_словом(п.substance),
            "нашлось": нашлось, "вид": "" if нашлось else (вид or "—"),
            "причина": " ".join((причина or "").split())[:160],
            "подсказка": подсказка or "",
            "знаков": len(итог[0]) if итог else 0,
            # ── ПОКАЗАНИЯ ЕДУТ ТЕМ ЖЕ КОРТЕЖЕМ (BACKLOG №227, A.10) ──
            # Своего разбора у замера НЕТ: показания извлекает
            # `_апт_найти_дозы` с той же страницы, что схему. Спроси
            # мы их тут отдельно — число «нашлось у N» относилось бы
            # к поведению, которого на бою нет (§6.0.7)
            "показания": (итог[4 - 1] if итог else ""),
            "пок_знаков": len(итог[3]) if итог and итог[3] else 0,
        })
    return строки, счёт



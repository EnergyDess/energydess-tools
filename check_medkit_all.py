# БЛОК D: ПРИЗНАК «СХЕМА ПРО ЧУЖУЮ ФОРМУ» — ПО СПОСОБУ ВВЕДЕНИЯ
# ═════════════════════════════════════════════════════════════════════
#
# ПЕРВАЯ ВЕРСИЯ ПРИЗНАКА («в тексте названа форма, которой у позиции
# нет») ДАЛА ТРИ НАХОДКИ И ВСЕ ТРИ ЛОЖНЫЕ:
#
#   Препарат В сироп   «по 1-2 капли»    — капля тут ЕДИНИЦА ДОЗЫ,
#                                       а не форма выпуска
#   Препарат М        «1 пакетика»      — фасовка порошка, тот же выпуск
#   Препарат Ц        «как аэрозоль»    — тот же концентрат, применённый
#                                       иначе («распылять, орошая»)
#
# То есть слова форм в схеме приёма живут ещё двумя жизнями — единицей
# дозирования и фасовкой, — и по слову их не разделить.
#
# СУЖЕНО ДО СПОСОБА ВВЕДЕНИЯ. Находка — когда названа группа, к которой
# позиция не относится, И СВОЕЙ группы не названо ни разу. Единица дозы
# и фасовка своей группы не меняют: «капли» внутрь и «сироп» внутрь —
# одна группа; «суппозитории ректально» на карточке таблеток — разные.
ГРУППЫ_ВВЕДЕНИЯ = {
    "внутрь": ("tablet", "capsule", "syrup", "drops", "sachet", "powder"),
    "ректально": ("suppository",),
    "наружно": ("ointment", "gel", "cream"),
    "местно": ("spray",),
    "инъекция": ("ampoule",),
}
ГРУППА_ФОРМЫ = {ф: г for г, фф in ГРУППЫ_ВВЕДЕНИЯ.items() for ф in фф}

# Слова, по которым группа опознаётся В ТЕКСТЕ: формы плюс наречия
# способа. У Флоренты слова «сироп» нет вовсе, а «принимать … во время
# еды» говорит про приём внутрь прямо.
СЛОВА_ГРУППЫ = {
    "внутрь": ("внутрь", "принимать", "принимают", "приема внутрь",
               "приёма внутрь", "запивать", "таблетк", "капсул", "сироп",
               "капл", "пакетик", "порошок", "гранул", "растворить",
               "рассасыв", "под язык", "во время еды", "после еды",
               "до еды", "чайной ложке", "столовую ложку"),
    "ректально": ("ректально", "суппозитор", "свеч", "в прямую кишку"),
    "наружно": ("наружно", "наносить", "мазь", "крем", "втирать",
                "на кожу", "гель"),
    "местно": ("распыл", "впрыскиван", "интраназальн", "орошая",
               "спрей", "аэрозол", "ингаля"),
    "инъекция": ("внутримышечн", "внутривенн", "ампул", "инъекц",
                 "подкожн"),
}


def группы_в_тексте(текст):
    низ = (текст or "").lower()
    return {г for г, слова in СЛОВА_ГРУППЫ.items()
            if any(с in низ for с in слова)}


def формы_расходятся(из, тихо=False):
    """БЛОК D: схема на карточке говорит про ЧУЖОЙ СПОСОБ ВВЕДЕНИЯ.

    ТОЛЬКО ПОКАЗАТЬ. Записи владельца не правятся и не удаляются:
    это его текст, и решение о нём — тоже его.
    """
    if not тихо:
        print()
        print("=" * 118)
        print("D.2 — СХЕМА НА КАРТОЧКЕ ГОВОРИТ ПРО ЧУЖОЙ СПОСОБ ВВЕДЕНИЯ")
        print("=" * 118)
    находки = []
    for п in из:
        своя = ГРУППА_ФОРМЫ.get(п.form)
        if not своя:
            continue
        for поле, текст in (("справочник", п.dosage_text),
                            ("своя запись", п.own_dosage_text)):
            т = (текст or "").strip()
            if not т:
                continue
            группы = группы_в_тексте(т)
            чужие = sorted(группы - {своя})
            if чужие and своя not in группы:
                находки.append((п, поле, чужие))
                if not тихо:
                    print("   id=%-3s %-28s форма карточки: %-12s [%s]"
                          % (п.id, " ".join((п.name or "").split())[:28],
                             ФОРМА_РУС.get(п.form, п.form), поле))
                    print("           своя группа: %-11s в тексте: %s"
                          % (своя, ", ".join(чужие)))
    if not тихо:
        print("-" * 118)
        print("   позиций с расхождением способа введения: %d" % len(находки))
        print("   НИЧЕГО НЕ ПРАВИЛОСЬ И НЕ УДАЛЯЛОСЬ — это записи владельца")
    return находки



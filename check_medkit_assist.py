async def _завести(pg, метка, текст, файл=None):
    """Один проход панели: от ввода до сохранения. Возвращает разбор."""
    await pg.evaluate("() => аптАИОткрыть()")
    await pg.wait_for_timeout(250)
    до = await pg.evaluate(ЧЕРНОВИК)
    до_подсказки = до["подсказкаПроДозу"]
    было_кнопок, было_сводок = до["кнопок"], до["сводок"]
    было_реплик = await pg.evaluate(
        "() => document.querySelectorAll('.apt-ai-msg').length")
    if файл is None:
        await pg.fill("#apt-ai-in", текст)
        await pg.evaluate("() => аптАИОтправитьТекст()")
    else:
        await pg.set_input_files(
            "#apt-ai-photo",
            {"name": "upakovka.png", "mimeType": "image/png", "buffer": файл})
    # ЖДЁМ НОВЫЙ ЧЕРНОВИК, А НЕ «ХОТЬ КАКОЙ-НИБУДЬ».
    #
    # ПЕРВАЯ ВЕРСИЯ ЖДАЛА `естьКнопка` И ВРАЛА НА ВСЕХ ПОЗИЦИЯХ, КРОМЕ
    # ПЕРВОЙ. Лента разговора не чистится между заведениями, кнопка
    # «Открыть карточку и проверить» от прошлого разбора остаётся
    # в ней — значит условие выполнялось СРАЗУ, до ответа модели,
    # и в форму уезжал ПРЕДЫДУЩИЙ черновик. Замер 2026-08-25:
    # тринадцать позиций, у двенадцати в базе оказалось имя соседа
    # («Омепразол» под входом «Виферон»), и вывод выглядел
    # правдоподобно — «модель путает названия».
    #
    # Ровно тот класс, ради которого написан §6.0.3: врала ХАРНЕССА,
    # а не проверяемое. Поймано не чтением, а тем, что ошибка была
    # ровно на одну позицию — сдвиг, а не путаница.
    #
    # Модель отвечает от секунды до полуминуты, поэтому ждём
    # по признаку, а не по часам.
    for _ in range(120):
        await pg.wait_for_timeout(500)
        с = await pg.evaluate(ЧЕРНОВИК)
        if с["кнопок"] > было_кнопок or с["сводок"] > было_сводок:
            break
        if len(с["плохо"]) > len(до["плохо"]):
            break
        n = await pg.evaluate(
            "() => document.querySelectorAll('.apt-ai-msg').length")
        if n > было_реплик + 2:      # ответил, но черновика не собрал
            break
    состояние = await pg.evaluate(ЧЕРНОВИК)
    состояние["новая_кнопка"] = состояние["кнопок"] > было_кнопок
    итог = {"метка": метка, "текст": текст, "черновик": состояние["пары"],
            "отказ": (состояние["плохо"][-1]
                      if len(состояние["плохо"]) > len(до["плохо"]) else None),
            "реплики": состояние["реплики"],
            "подсказка_до": до_подсказки,
            "подсказка_после": состояние["подсказкаПроДозу"]}
    if not состояние["новая_кнопка"]:
        итог["форма"] = None
        итог["в_базе"] = None
        await pg.evaluate("() => аптАИЗакрыть()")
        return итог

    await pg.evaluate(
        # ПОСЛЕДНЮЮ, А НЕ ПЕРВУЮ: кнопки прошлых разборов остаются
        # в ленте, и `find` брал бы самую старую
        "() => [...document.querySelectorAll('#apt-ai-log button')]"
        ".filter(б => б.textContent.includes('проверить')).pop().click()")
    await pg.wait_for_timeout(600)
    итог["форма"] = await pg.evaluate(ФОРМА)


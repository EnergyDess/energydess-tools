def _сверить(итог, эталон):
    """Заполнено верно / заполнено НЕВЕРНО / пропущено."""
    ф = (итог.get("форма") or {}).get("поля") or {}
    верно, неверно, пропущено = [], [], []
    for ключ, ждём in эталон.items():
        было = ф.get(ключ)
        число = isinstance(ждём, (int, float))
        пусто = (было in (None, "")) if not число else (было in (None, ""))
        if пусто:
            пропущено.append(ПОДПИСИ.get(ключ, ключ))
            continue
        if число:
            try:
                совпало = abs(float(было) - ждём) < 1e-6
            except (TypeError, ValueError):
                совпало = False
        else:
            совпало = str(было).strip().lower() == str(ждём).strip().lower()
            # НАЗВАНИЕ СВЕРЯЕТСЯ ВХОЖДЕНИЕМ, а не побайтово: «Нурофен
            # Форте» при «Нурофен» в тексте — не ошибка модели, а её
            # начитанность, и объявлять это дефектом значило бы мерить
            # не то. Остальные поля сверяются точно.
            if not совпало and ключ == "name":
                совпало = str(ждём).lower() in str(было).lower()
        if совпало:
            верно.append(ПОДПИСИ.get(ключ, ключ))
        else:
            неверно.append("%s: ждали %r, получили %r"
                           % (ПОДПИСИ.get(ключ, ключ), ждём, было))
    return верно, неверно, пропущено



СЧЁТ_КОПИЙ = [0]


def копия(исходная):
    """Своя копия для каждого прогона. Спутники WAL берутся тоже —
    без них копия открывается с ЧУЖИМ хвостом журнала (§9).

    КАЖДЫЙ ПРОГОН БЕРЁТ СВОЙ ФАЙЛ, а не перезаписывает общий: движок
    SQLAlchemy держит соединение открытым, и Windows не даёт заменить
    занятый файл. Первая версия падала `PermissionError` ровно на этом,
    то есть контроль не прогонялся вовсе."""
    путь = os.path.abspath(исходная).replace("\\", "/")
    if "/data/" in путь:
        raise SystemExit("БОЕВАЯ БАЗА НЕ ОТКРЫВАЕТСЯ — работаем на копии")
    СЧЁТ_КОПИЙ[0] += 1
    врем = os.path.join(tempfile.gettempdir(),
                        "medkit_borrow_%d.db" % СЧЁТ_КОПИЙ[0])
    for хвост in ("", "-wal", "-shm"):
        if os.path.exists(исходная + хвост):
            shutil.copy2(исходная + хвост, врем + хвост)
    return врем


def замер(файл):
    """(групп из нескольких пачек, ложных долгов, заимствовано,
        не заимствовано из-за расхождения). БОЕВЫМИ функциями."""
    os.environ["DB_PATH"] = файл
    # ДВИЖОК ПРЕЖНЕГО ПРОГОНА ЗАКРЫВАЕТСЯ, иначе он держит файл
    # открытым и следующая копия не ложится
    if "database" in sys.modules:
        try:
            sys.modules["database"].engine.dispose()
        except Exception as e:
            print("     [замер] движок не закрыт: %s" % e)
    for имя in [м for м in sys.modules if м in ("main", "database")]:
        del sys.modules[имя]
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import main
    from database import SessionLocal, MedkitItem, User

    db = SessionLocal()
    счёт = {}
    for (uid,) in db.query(MedkitItem.user_id).all():
        счёт[uid] = счёт.get(uid, 0) + 1
    if not счёт:
        db.close()
        raise SystemExit("В БАЗЕ НЕТ ПОЗИЦИЙ — мерить нечего")
    uid = max(счёт, key=счёт.get)
    user = db.query(User).filter(User.id == uid).first()
    карточки = main._апт_данные(db, user)["позиции"]

    групп = 0
    ложных = 0
    заимствовано = 0
    разошлись = 0
    for с in карточки:
        пачки = с.get("группа") or []
        if len(пачки) < 2:
            continue
        групп += 1
        свои = [(п.get("показания") or "").strip()
                or (п.get("своё_от_чего") or "").strip() for п in пачки]
        у_карточки = bool((с.get("показания") or "").strip()
                          or (с.get("своё_от_чего") or "").strip())
        есть_у_кого_то = any(свои)
        # ЛОЖНЫЙ ДОЛГ: текст в группе есть, а карточка молчит
        if есть_у_кого_то and not у_карточки:
            ложных += 1
        # ЗАИМСТВОВАНО: у первой пачки пусто, у карточки есть
        if есть_у_кого_то and not свои[0] and у_карточки:
            заимствовано += 1
        # РАСХОЖДЕНИЕ СЧИТАЕТСЯ ПО КАЖДОМУ ПОЛЮ ОТДЕЛЬНО — тем же
        # признаком, что у заслона (`СВЕРЯТЬ_ПРИ_ЗАИМСТВОВАНИИ`).
        # Первая версия складывала оба поля в одно значение
        # с приоритетом справочного, и подлог, разводивший СВОИ
        # тексты, не отражался в замере вовсе: у пачек стояли
        # ОДИНАКОВЫЕ справочные показания, и они перебивали. Поймало
        # ДОКАЗАТЕЛЬСТВО подлога, а не вердикт (§6.0.3)
        for поле in ("показания", "своё_от_чего"):
            непустые = {(п.get(поле) or "").strip() for п in пачки
                        if (п.get(поле) or "").strip()}
            if len(непустые) > 1:
                разошлись += 1
                break
    db.close()
    return {"групп": групп, "ложных_долгов": ложных,
            "заимствовано": заимствовано, "разошлись": разошлись,
            "карточек": len(карточки)}


def подлог_разные_тексты(файл):
    """Развести тексты двух пачек одной группы. ДОКАЗАТЕЛЬСТВО —
    возвращает, скольким строкам подложено и что именно."""
    c = sqlite3.connect(файл)
    try:
        строки = c.execute(
            "SELECT id, name, form, substance FROM medkit_items "
            "ORDER BY name, id").fetchall()
        по_ключу = {}
        for ид, name, form, subst in строки:
            по_ключу.setdefault((name.strip().lower(), form,
                                 (subst or "").strip().lower()), []).append(ид)
        пара = next((v for v in по_ключу.values() if len(v) > 1), None)
        if not пара:
            raise SystemExit("В БАЗЕ НЕТ ГРУППЫ ИЗ ДВУХ ПАЧЕК — "
                             "подложить нечего (§8.0)")
        # СПРАВОЧНЫЕ ПОКАЗАНИЯ ЧИСТЯТСЯ У ОБЕИХ: иначе решают ОНИ
        # (они одинаковы по построению — сняты с одной страницы),
        # и подлог, разводящий СВОИ тексты, не меняет ничего
        for ид in пара[:2]:
            c.execute("UPDATE medkit_items SET indications_text = NULL, "
                      "indications_blocks = NULL WHERE id = ?", (ид,))
        c.execute("UPDATE medkit_items SET own_indications_text = ? "
                  "WHERE id = ?", ("Текст с вкладыша ПЕРВОЙ пачки", пара[0]))
        c.execute("UPDATE medkit_items SET own_indications_text = ? "
                  "WHERE id = ?", ("Текст с вкладыша ВТОРОЙ пачки", пара[1]))
        c.commit()
        return {"пачки": пара, "тексты": "разные, справочные сняты"}
    finally:
        c.close()


def подлог_одинаковые(файл):
    """То же, но тексты СОВПАДАЮТ: заимствование обязано СРАБОТАТЬ.
    Без этого обратного случая «заслон ловит всё» неотличимо
    от «заимствования нет вовсе» (§6.0.3)."""
    c = sqlite3.connect(файл)
    try:
        строки = c.execute(
            "SELECT id, name, form, substance FROM medkit_items "
            "ORDER BY name, id").fetchall()
        по_ключу = {}
        for ид, name, form, subst in строки:
            по_ключу.setdefault((name.strip().lower(), form,
                                 (subst or "").strip().lower()), []).append(ид)
        пара = next((v for v in по_ключу.values() if len(v) > 1), None)
        if not пара:
            raise SystemExit("В БАЗЕ НЕТ ГРУППЫ ИЗ ДВУХ ПАЧЕК (§8.0)")
        # У ПЕРВОЙ ПУСТО, У ВТОРОЙ ТЕКСТ — ровно случай ложного долга
        for ид in пара[:2]:
            c.execute("UPDATE medkit_items SET indications_text = NULL, "
                      "indications_blocks = NULL, own_indications_text = NULL "
                      "WHERE id = ?", (ид,))
        c.execute("UPDATE medkit_items SET own_indications_text = ? "
                  "WHERE id = ?", ("Один и тот же текст", пара[1]))
        c.commit()
        return {"пачки": пара, "тексты": "у первой пусто, у второй есть"}
    finally:
        c.close()


def подлог_переворот(файл):
    """ПЕРЕВЕРНУТЬ ПОРЯДОК ПАЧЕК В ГРУППЕ, где текст только у одной.

    Прямое воспроизведение случая захода 254: порядок задаёт
    `_апт_порядок_пачек` (сначала вскрытая, потом по сроку), и пометка
    вскрытия у пустой пачки выводит её вперёд. До заимствования
    карточка показывала 0 знаков при живом тексте у соседки.
    """
    c = sqlite3.connect(файл)
    try:
        строки = c.execute(
            "SELECT id, name, form, substance, own_indications_text, "
            "indications_text, opened_on FROM medkit_items "
            "ORDER BY name, id").fetchall()
        по_ключу = {}
        for r in строки:
            по_ключу.setdefault((r[1].strip().lower(), r[2],
                                 (r[3] or "").strip().lower()), []).append(r)
        for пачки in по_ключу.values():
            if len(пачки) < 2:
                continue
            с_текстом = [p for p in пачки if (p[4] or p[5])]
            без = [p for p in пачки if not (p[4] or p[5])]
            if not с_текстом or не_пусто(без):
                # ГОДИТСЯ ГРУППА, где текст есть у ОДНОЙ пачки из двух
                c.execute("UPDATE medkit_items SET opened_on = '2026-01-01' "
                          "WHERE id = ?", (без[0][0],))
                c.commit()
                return {"вперёд_выведена": без[0][0],
                        "текст_у": с_текстом[0][0]}
        raise SystemExit("В БАЗЕ НЕТ ГРУППЫ «текст у одной пачки» (§8.0)")
    finally:
        c.close()


def не_пусто(с):
    return bool(с)



def итог_случая(ждём, ожидаемые, группа, модель, видно):
    """«ok» | «СХЕМА НЕЯСНОЙ ПАЧКИ» (+ «, выбор модели») | «УТОЧНЕНИЕ НАПРАСНО»
    | «ЛИШНЯЯ СХЕМА»."""
    if ждём == "нет схемы":
        свои = видно & группа
        if not свои:
            return "ok"
        return "СХЕМА НЕЯСНОЙ ПАЧКИ" + (", выбор модели" if свои <= set(модель) else "")
    if not (видно & ожидаемые):
        return "УТОЧНЕНИЕ НАПРАСНО"
    if ждём == "ровно" and (видно & группа) - ожидаемые:
        return "ЛИШНЯЯ СХЕМА"
    return "ok"



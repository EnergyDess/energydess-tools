def _норма(т):
    return " ".join((т or "").lower().split())


def _ключ(п):
    """Название, вещество с дозировкой, форма — количество НЕ различает."""
    return (_норма(п.get("name")), _норма(п.get("substance")), п.get("form"))


def _метки(позиции):
    копии = []
    for п in позиции:
        к = dict(п)
        к.update({"своя_схема": МЕТКА % п["id"], "своя_схема_дата": "",
                  "дозы": "", "дозы_блоки": [], "дозы_сгиб": None})
        копии.append(к)
    return копии


def случаи_из_данных(позиции):
    """[(вид, вопрос, позиции, модель, ждём, ожидаемые_ids, группа_ids)]."""
    по_имени = {}
    for п in позиции:
        по_имени.setdefault(_норма(п.get("name")), []).append(п)
    итог = []
    for имя, группа in по_имени.items():
        ids = frozenset(п["id"] for п in группа)
        ждём = "нет схемы" if len({_ключ(п) for п in группа}) > 1 else "схема"
        последняя = [группа[-1]["id"]]
        итог.append(("данные: названа словами", "как принимать " + группа[0]["name"],
                     позиции, последняя, ждём, ids, ids))
        итог.append(("данные: выбор модели", "как принимать это средство",
                     позиции, последняя, ждём, ids, ids))
    return итог



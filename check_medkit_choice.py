async def прогнать(случаи, подмены=None):
    """[(случай, тип тела, видимые id меток, текст пузыря)]."""
    from playwright.async_api import async_playwright
    пр.БАЗА = БАЗА
    итог = []
    async with async_playwright() as pw:
        бр = await pw.chromium.launch(headless=False)
        ctx = await бр.new_context(viewport={"width": 1440, "height": 900})
        pg = await ctx.new_page()
        await пр._войти(pg)
        for i, с in enumerate(случаи):
            if i % 40 == 0:
                await _открыть(pg)
            тело = await asyncio.to_thread(_тело, с, подмены)
            текст = await пр._пузырь(pg, тело)
            видно = frozenset(int(м) for м in re.findall(r"запись-пачки-(\d{5})", текст))
            итог.append((с, тело.get("тип"), видно, текст))
        await ctx.close()
        await бр.close()
    return итог


def сводка(итог, подпись=""):
    по_виду = {}
    for с, тип, видно, текст in итог:
        вид, _, _, модель, ждём, ожидаемые, группа = с
        р = "ЗАМЕР НЕ СОСТОЯЛСЯ" if not текст.strip() else итог_случая(
            ждём, ожидаемые, группа, модель, видно)
        в = по_виду.setdefault(вид, {"случаев": 0, "неясных": 0, "однозначных": 0,
                                    "схема неясной": 0, "выбор модели": 0,
                                    "напрасно": 0, "лишняя": 0, "не состоялся": 0})
        в["случаев"] += 1
        в["неясных" if ждём == "нет схемы" else "однозначных"] += 1
        if р.startswith("СХЕМА НЕЯСНОЙ"):
            в["схема неясной"] += 1
            в["выбор модели"] += р.endswith("выбор модели")
        в["напрасно"] += р == "УТОЧНЕНИЕ НАПРАСНО"
        в["лишняя"] += р == "ЛИШНЯЯ СХЕМА"
        в["не состоялся"] += р == "ЗАМЕР НЕ СОСТОЯЛСЯ"
        if р != "ok" and вид.startswith("С"):
            print("   %s%s: %s (тип тела «%s», меток на экране %d)"
                  % (подпись, вид, р, тип, len(видно)))
    for вид, в in по_виду.items():
        print("%s%-36s случаев %d (неясных %d, однозначных %d): схема неясной "
              "на экране %d, из них выбор модели %d · уточнение напрасно %d · "
              "лишняя схема %d · не состоялся %d"
              % (подпись, вид, в["случаев"], в["неясных"], в["однозначных"],
                 в["схема неясной"], в["выбор модели"], в["напрасно"], в["лишняя"],
                 в["не состоялся"]))
    return по_виду



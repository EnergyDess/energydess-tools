def _отпечаток(случаи):
    return hashlib.sha256(repr(sorted(
        (с[0], с[1], tuple(с[3]), с[4], tuple(sorted(с[5])), tuple(sorted(с[6])))
        for с in случаи)).encode("utf-8")).hexdigest()[:12]



def доступ_снять(uid):
    from database import SessionLocal, ToolAccess
    db = SessionLocal()
    try:
        n = (db.query(ToolAccess)
             .filter(ToolAccess.user_id == uid,
                     ToolAccess.tool_id == "medkit")
             .delete(synchronize_session=False))
        db.commit()
        return n
    finally:
        db.close()


def доступ_вернуть(uid):
    from database import SessionLocal, ToolAccess
    db = SessionLocal()
    try:
        if not (db.query(ToolAccess)
                .filter(ToolAccess.user_id == uid,
                        ToolAccess.tool_id == "medkit").first()):
            db.add(ToolAccess(user_id=uid, tool_id="medkit"))
            db.commit()
    finally:
        db.close()


def доступ_есть(uid):
    """НЕЗАВИСИМЫЙ ЗАМЕР — спрашивает БАЗУ, а не наш же код.

    Без него «приглашение отвергнуто» неотличимо от «отвергнуто
    по другой причине»: подлог, не снявший флаг, дал бы тот же
    вердикт (§6.0.3).
    """
    return один("SELECT COUNT(*) FROM tool_access "
                "WHERE user_id = ? AND tool_id = 'medkit'", uid) or 0



def контроль():
    """Каждый подлог — свой прогон, и каждый обязан быть НАЙДЕН."""
    import threading
    import time
    import uvicorn
    import main

    порт = int(os.getenv("MEDKIT_CONTROL_PORT", "8971"))
    global БАЗА
    БАЗА = "http://127.0.0.1:%d" % порт
    конфиг = uvicorn.Config(main.app, host="127.0.0.1", port=порт,
                            log_level="error")
    сервер = uvicorn.Server(конфиг)
    поток = threading.Thread(target=сервер.run, daemon=True)
    поток.start()
    for _ in range(100):
        if сервер.started:
            break
        time.sleep(0.1)
    if not сервер.started:
        print("ОСТАНОВЛЕНО: свой сервер не поднялся")
        return 0

    # ЧИСТЫЙ ПРОГОН ОБЯЗАТЕЛЕН ПЕРВЫМ. Долг, бывший и до подлога,
    # засчитался бы как находка подлога, и контроль не доказывал бы
    # ничего (§6.0.3)
    global шаги
    шаги = []
    print("── ЧИСТЫЙ ПРОГОН ──")
    прогон()
    грязные = [и for и, ок, _ in шаги if not ок]
    if грязные:
        print("\nОСТАНОВЛЕНО: на исправном коде уже красные шаги: %s"
              % ", ".join(грязные))
        return 1
    чистые_имена = {и for и, _, _ in шаги}

    найдено = 0
    for имя, что in ПОДЛОГИ.items():
        # СИД ВОЗВРАЩАЕТСЯ ПЕРЕД КАЖДЫМ ПОДЛОГОМ, А НЕ ТОЛЬКО В КОНЦЕ.
        # `прогон` начинается с `прибрать()` и распускает круг, то есть
        # со второго подлога доказательство спрашивалось на стенде БЕЗ
        # КРУГА. Поймано это не чтением, а самим доказательством:
        # «файл-только-своему» напечатал «подлог НЕ СОСТОЯЛСЯ · проба
        # НАШЛА» — вердикт был бы засчитан, замер разошёлся. Тот же
        # класс, что нашла задача 167: замер НЕ В ТОТ МОМЕНТ
        вернуть_сид()
        исходная = наложить(имя, main)
        доказан = доказать_подлог(имя, main)
        шаги = []
        try:
            прогон()
        except Exception as e:
            print("  проба упала: %s: %s" % (type(e).__name__, e))
        упали = [и for и, ок, _ in шаги if не_ок(ок)]
        снять(имя, main, исходная)
        видно = bool(упали) or len({и for и, _, _ in шаги} ^ чистые_имена)
        найдено += 1 if (доказан and видно) else 0
        print("\n%-34s подлог %s · проба %s\n   %s\n   упало: %s"
              % (имя, "ДОКАЗАН" if доказан else "НЕ СОСТОЯЛСЯ",
                 "НАШЛА" if видно else "СЛЕПА", что,
                 ", ".join(упали[:6]) or "ничего"))
    print("\nПОДЛОГОВ НАЙДЕНО: %d из %d" % (найдено, len(ПОДЛОГИ)))
    # СТЕНД ВОЗВРАЩАЕТСЯ И ЗДЕСЬ. Контроль гоняет `прогон` шесть раз,
    # и каждый распускает круг последним действием — без возврата
    # следующий инструмент снимал бы ЛИЧНУЮ аптечку вместо общей.
    # Ровно это и случилось при первом же применении: кадр «до»
    # пиксельного дифа ушёл без круга, и заметило это не чтение,
    # а число `medkit_circles = 0` в отладочной строке рядом
    # (§6.0.3, шестая причина неповторимости — чужая проба,
    # пишущая в ту же базу)
    print("стенд возвращён в сидированное: %s"
          % ("да" if вернуть_сид() else "НЕТ"))
    сервер.should_exit = True
    return 0 if найдено == len(ПОДЛОГИ) else 1


def не_ок(ок):
    return not ок


def main_():
    if "--контроль" in sys.argv:
        return контроль()
    # --сид: мерить круг, ЗАВЕДЁННЫЙ СИДИРОВАНИЕМ, а не пробой.
    # Основной прогон строит круг сам и потому о верности seed
    # не говорит ничего (BACKLOG №187)
    if "--сид" in sys.argv:
        прогон_сидированного()
    else:
        прогон()
        # СТЕНД ОСТАЁТСЯ СИДИРОВАННЫМ. `прогон` распускает круг
        # последним действием, и без этого следующий инструмент снимал
        # бы личную аптечку вместо общей — молча (§6.0.3)
        шаг("стенд-возвращён-в-сидированное", вернуть_сид())
    плохих = [и for и, ок, _ in шаги if not ок]
    print("\nШАГОВ: %d · КРАСНЫХ: %d" % (len(шаги), len(плохих)))
    if плохих:
        print("  " + "\n  ".join(плохих))
    return 1 if плохих else 0



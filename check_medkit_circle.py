def доказать_подлог(имя, main):
    """НЕЗАВИСИМЫЙ ЗАМЕР ТОГО, ЧТО ПОДЛОГ СОБИРАЛСЯ ИЗМЕНИТЬ.

    Вердикт пробы тут не годится: он получается «НАЙДЕН» и когда подлог
    не сработал, а шаг упал по другой причине (§6.0.3). Замер — прямой
    вопрос к подменённой функции.
    """
    if имя == "владелец-не-едет-на-карточку":
        из = main._апт_наружу.__doc__ or ""
        return "ПОДМЕНЕНА" in из
    if имя == "лента-не-пишется":
        return getattr(main._апт_событие, "_подлог", False)
    if имя == "круг-не-сужается-при-выходе":
        return getattr(main._апт_круг_прибрать, "_подлог", False)
    if имя == "чужой-убирает-владельца":
        return getattr(main._апт_круг, "_подлог", False)
    if имя == "доступа-как-будто-у-всех":
        # ДОКАЗАТЕЛЬСТВО — ПРЯМОЙ ВОПРОС К ПОДМЕНЁННОЙ ФУНКЦИИ,
        # а не флаг на ней: спрашиваем ровно тем же способом, каким
        # её спрашивает боевой код, и на аккаунте, у которого доступа
        # ЗАВЕДОМО нет. Флаг доказал бы, что подмена состоялась;
        # этот замер доказывает, что она ещё и МЕНЯЕТ ОТВЕТ
        from database import SessionLocal, User
        db = SessionLocal()
        try:
            u = db.query(User).filter(User.email == НЕПОДТВ[0]).first()
            без = один("SELECT COUNT(*) FROM tool_access "
                       "WHERE user_id = ? AND tool_id = 'medkit'", u.id)
            return без == 0 and main._апт_доступ(db, u) is True
        finally:
            db.close()
    return False


def наложить(имя, main):
    if имя == "владелец-не-едет-на-карточку":
        исходная = main._апт_наружу

        def без_владельца(*а, **кв):
            кв.pop("люди", None)
            if len(а) > 5:
                а = а[:5]
            п = исходная(*а, **кв)
            п["владелец"] = None
            return п
        без_владельца.__doc__ = "ПОДМЕНЕНА"
        main._апт_наружу = без_владельца
        return исходная
    if имя == "лента-не-пишется":
        исходная = main._апт_событие

        def молча(*а, **кв):
            return None
        молча._подлог = True
        main._апт_событие = молча
        return исходная
    if имя == "круг-не-сужается-при-выходе":
        исходная = main._апт_круг_прибрать

        def не_убирает(db, круг):
            return False
        не_убирает._подлог = True
        main._апт_круг_прибрать = не_убирает
        return исходная
    if имя == "чужой-убирает-владельца":
        # ПОДМЕНЯЕТСЯ НЕ ПРОВЕРКА, А ЕЁ ИСХОДНЫЕ ДАННЫЕ: круг возвращается
        # с владельцем, равным ТОМУ, КТО СПРАШИВАЕТ. Так проверка прав
        # остаётся ровно той же строкой кода — и всё равно пропускает
        # постороннего. Дописывать в боевой код флаг «а сейчас подлог»
        # значило бы завести дверь, которой в проде быть не должно
        исходная = main._апт_круг

        class _Круг:
            def __init__(с, id_, uid):
                с.id, с.user_id = id_, uid

        def чужой_владелец(db, user):
            круг, ids = исходная(db, user)
            if круг is None:
                return круг, ids
            return _Круг(круг.id, user.id), ids
        чужой_владелец._подлог = True
        main._апт_круг = чужой_владелец
        return исходная
    if имя == "доступа-как-будто-у-всех":
        исходная = main._апт_доступ

        def доступ_у_всех(db, u):
            return bool(u)
        доступ_у_всех._подлог = True
        main._апт_доступ = доступ_у_всех
        return исходная
    raise KeyError(имя)


def снять(имя, main, исходная):
    if имя == "чужой-убирает-владельца":
        main._апт_круг = исходная
        return
    if имя == "владелец-не-едет-на-карточку":
        main._апт_наружу = исходная
    elif имя == "лента-не-пишется":
        main._апт_событие = исходная
    elif имя == "круг-не-сужается-при-выходе":
        main._апт_круг_прибрать = исходная
    elif имя == "доступа-как-будто-у-всех":
        main._апт_доступ = исходная


def контроль():
    """Каждый подлог — свой прогон, и каждый обязан быть НАЙДЕН."""
    import threading
    import time
    import uvicorn
    import main

    порт = int(os.getenv("MEDKIT_CONTROL_PORT", "8971"))
    global БАЗА
    БАЗА = "http://127.0.0.1:%d" % порт
    конфиг = uvicorn.Config(main.app, host="127.0.0.1", port=порт,
                            log_level="error")
    сервер = uvicorn.Server(конфиг)
    поток = threading.Thread(target=сервер.run, daemon=True)
    поток.start()
    for _ in range(100):
        if сервер.started:
            break
        time.sleep(0.1)
    if not сервер.started:
        print("ОСТАНОВЛЕНО: свой сервер не поднялся")
        return 0

    # ЧИСТЫЙ ПРОГОН ОБЯЗАТЕЛЕН ПЕРВЫМ. Долг, бывший и до подлога,
    # засчитался бы как находка подлога, и контроль не доказывал бы
    # ничего (§6.0.3)
    global шаги
    шаги = []
    print("── ЧИСТЫЙ ПРОГОН ──")
    прогон()
    грязные = [и for и, ок, _ in шаги if not ок]
    if грязные:
        print("\nОСТАНОВЛЕНО: на исправном коде уже красные шаги: %s"
              % ", ".join(грязные))
        return 1
    чистые_имена = {и for и, _, _ in шаги}

    найдено = 0
    for имя, что in ПОДЛОГИ.items():
        исходная = наложить(имя, main)
        доказан = доказать_подлог(имя, main)
        шаги = []
        try:
            прогон()
        except Exception as e:
            print("  проба упала: %s: %s" % (type(e).__name__, e))
        упали = [и for и, ок, _ in шаги if не_ок(ок)]
        снять(имя, main, исходная)
        видно = bool(упали) or len({и for и, _, _ in шаги} ^ чистые_имена)
        найдено += 1 if (доказан and видно) else 0
        print("\n%-34s подлог %s · проба %s\n   %s\n   упало: %s"
              % (имя, "ДОКАЗАН" if доказан else "НЕ СОСТОЯЛСЯ",
                 "НАШЛА" if видно else "СЛЕПА", что,
                 ", ".join(упали[:6]) or "ничего"))
    print("\nПОДЛОГОВ НАЙДЕНО: %d из %d" % (найдено, len(ПОДЛОГИ)))
    сервер.should_exit = True
    return 0 if найдено == len(ПОДЛОГИ) else 1



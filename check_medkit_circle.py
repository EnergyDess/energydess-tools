def войти(op, пара):
    тело = urllib.parse.urlencode({"email": пара[0],
                                   "password": пара[1]}).encode()
    зп = urllib.request.Request(БАЗА + "/login", data=тело, method="POST")
    зп.add_header("Content-Type", "application/x-www-form-urlencoded")
    try:
        return op.open(зп).status
    except urllib.error.HTTPError as e:
        return e.code


def зов(op, путь, метод="GET", тело=None):
    данные = json.dumps(тело).encode() if тело is not None else None
    зп = urllib.request.Request(БАЗА + путь, data=данные, method=метод)
    if данные:
        зп.add_header("Content-Type", "application/json")
    зп.add_header("Accept", "application/json")
    try:
        о = op.open(зп)
        сырое, код = о.read().decode("utf-8", "replace"), о.status
    except urllib.error.HTTPError as e:
        сырое, код = e.read().decode("utf-8", "replace"), e.code
    try:
        return код, json.loads(сырое)
    except ValueError:
        return код, {"_сырое": сырое[:200]}



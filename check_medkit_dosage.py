def _разметка(кусок, текст, блоки, итог):
    """ЧТО ЗА РАЗМЕТКА НАШЛАСЬ В ИСТОЧНИКЕ И ЧТО ИЗ НЕЁ ВЗЯТО.

    BACKLOG №173, блок A. Печатается, потому что весь блок держится
    на одном допущении: структура В ИСТОЧНИКЕ УЖЕ ЕСТЬ, и выдумывать
    её не надо. Допущение проверяемое — вот оно и проверяется числом,
    а не утверждается прозой.

    ИНВАРИАНТ ПЕЧАТАЕТСЯ ПЕРВЫМ. Не сошёлся — блоков нет вовсе, экран
    показывает плоский текст, и это законный исход (постановка A.4),
    а не сбой разведки.
    """
    import re as _re
    теги = {}
    for з, имя in _re.findall(r"<(/?)([a-zA-Z][a-zA-Z0-9]*)[^>]*>", кусок):
        if not з:
            теги[имя.lower()] = теги.get(имя.lower(), 0) + 1
    итог["блоков"] = len(блоки)
    итог["сошлось"] = bool(блоки)
    print("  6. ИНВАРИАНТ (плоское чтение блоков == дословный текст): %s"
          % ("СОШЁЛСЯ" if блоки else "НЕ СОШЁЛСЯ — блоков не будет"))
    print("     разметка в источнике: %s"
          % ", ".join("%s×%d" % (т, н) for т, н in
                      sorted(теги.items(), key=lambda x: -x[1])))
    if not блоки:
        return
    виды = {}
    for б in блоки:
        к = б["вид"] + (str(б.get("уровень", "")) if б["вид"] == "заголовок"
                        else "")
        виды[к] = виды.get(к, 0) + 1
    print("     взято в блоки: %s"
          % ", ".join("%s×%d" % (в, н) for в, н in sorted(виды.items())))
    # ── СТРОКИ СО СХЕМОЙ ПРИЁМА (BACKLOG №177, B.1) ─────────────────
    #
    # ПЕЧАТАЮТСЯ ЦЕЛИКОМ, а не числом: ложное срабатывание здесь хуже
    # пропуска — выделенная не та строка утверждает, что доза именно
    # в ней. Числом «выделено 4» это не проверить; проверить это можно
    # только прочитав, ЧТО выделено.
    схемные = sorted(md.схемные(блоки))
    итог["схемных"] = len(схемные)
    print("     СТРОК СО СХЕМОЙ: %d из %d" % (len(схемные), len(блоки)))
    for i in схемные:
        print("       ██ %s" % блоки[i].get("текст", "")[:78])
    if not схемные:
        print("       (ни одной — признак требует количества, единицы"
              " и частоты сразу)")

    к = md.сгиб(блоки)
    итог["сгиб"] = к
    if к is None:
        print("     СГИБА НЕТ: ни двух заголовков верхнего уровня,")
        print("     ни строк схемы — прятать нечего, виден весь текст")
    else:
        print("     СГИБ на блоке %d из %d; сверху видно:" % (к, len(блоки)))
        for б in блоки[:к]:
            print("       · %s" % б.get("текст", "")[:80])


def доказать_подлог(настоящий, подложенный):
    """НЕЗАВИСИМЫЙ ЗАМЕР: подложенное и вправду отличается от истины.

    Подлог, совпавший с настоящим значением, ничего не доказывает:
    отказ сопоставления в этом случае означал бы дефект, а не работу
    контроля (§6.0.3).
    """
    поля = ("название", "форма", "доза", "вещество")
    return any(подложенный.get(п) != настоящий.get(п) for п in поля)



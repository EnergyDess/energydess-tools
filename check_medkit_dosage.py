def взять(адрес):
    з = {"User-Agent": UA, "Accept-Language": "ru,en;q=0.8"}
    r = urllib.request.urlopen(urllib.request.Request(адрес, headers=з),
                               timeout=30, context=_ctx)
    return r.status, r.read().decode("utf-8", "replace")



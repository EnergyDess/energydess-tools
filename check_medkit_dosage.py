def проверить(п, показать_текст=False):
    print("=" * 74)
    print("%s · %s · %s" % (п["название"], п["форма"], п["доза"]))
    print("=" * 74)
    итог = {"страница": False, "раздел": False, "форма": False,
            "доза": False, "знаков": 0, "адрес": ""}
    try:
        код, ссылки = найти_страницы(п["название"])
    except Exception as e:
        print("  поиск не ответил: %r" % (e,))
        return итог
    print("  1. поиск: HTTP %s, страниц препаратов найдено %d" % (код, len(ссылки)))
    for u, подпись in ссылки[:6]:
        print("       %-34s %s" % (u[:34], подпись[:38]))
    if not ссылки:
        return итог

    # ── СОПОСТАВЛЕНИЕ ПО ТРЁМ ПАРАМЕТРАМ ─────────────────────────────
    #
    # ВСЁ ТРИ ЛЕЖАТ В ОПИСАНИИ СТРАНИЦЫ, и это главная находка разведки.
    # Первая версия искала форму и дозу по ПЕРВЫМ ШЕСТИ ТЫСЯЧАМ знаков
    # плоского текста и врала на всех трёх препаратах: «Цетрин Л»
    # (таблетки 5 мг — ДРУГОЙ препарат) прошёл сопоставление, потому
    # что «10 мг» встретилось где-то в тексте страницы.
    #
    # Описание — это первая строка, которую Видаль печатает у каждой
    # карточки: «Cetrine L таблетки, покрытые пленочной оболочкой,
    # 5 мг», «Lasolvan раствор для приема внутрь 15 мг/5 мл», «Tantum
    # Verde спрей для местного применения дозированный 0.255 мг/1 доза».
    # Форма и дозировка стоят там ВСЕГДА и рядом — то есть это
    # структурное место, а не случайное совпадение слов.
    подходящие = []
    for u, _ in ссылки[:6]:
        try:
            _, стр = взять(БАЗА + u)
        except Exception:
            continue
        совпало_всё, детали = md.подходит(п, стр)
        подходящие.append((u, совпало_всё, детали, детали["описание"], стр))

    print("  2. сопоставление ПО ОПИСАНИЮ страницы"
          " (название / форма / пролонг / вещество; доза — справкой):")
    выбрана = None

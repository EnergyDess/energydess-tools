def позиции_базы(путь):
    """Позиции аптечки из ЛОКАЛЬНОЙ базы, только на чтение.

    `mode=ro` не для красоты: разведка ходит в чужой сайт и в базу
    владельца одновременно, и права на запись ей не нужны ни для чего.
    """
    import sqlite3
    из = []
    try:
        c = sqlite3.connect("file:%s?mode=ro" % путь, uri=True)
    except Exception as e:
        print("  базу не открыть: %r" % (e,))
        return из
    for id_, имя, вещ, форма in c.execute(
            "SELECT id,name,substance,form FROM medkit_items ORDER BY id"):
        из.append({"название": имя, "форма": форма,
                   "доза": вещ or "",
                   "вещество": re.split(r"[,;(]", (вещ or "").strip())[0].strip(),
                   "метка": "база #%d" % id_})
    return из


def по_позициям(путь):
    """СКОЛЬКО ПОЗИЦИЙ ПОЛУЧАЮТ СХЕМУ — по всей базе, а не по трём пробам.

    BACKLOG №178, A.4. Три препарата наверху отвечают на вопрос «умеет ли
    разбор читать источник»; этот режим — на другой: «скольким позициям
    владельца это доезжает». Без него правка блока A оценивалась бы
    рассуждением: правило про пустую дозировку выглядит полезным, а число
    позиций, которым оно помогло, может оказаться нулём — и оно им
    оказалось (замер в шапке `доза_совпала`).

    ПУТЬ ПОИСКА ТОТ ЖЕ, ЧТО У СЕРВЕРА: `имена_для_поиска` плюс `подходит`.
    Свой разбор здесь означал бы, что число относится к поведению,
    отличному от боевого.
    """
    поз = позиции_базы(путь) + ПОИМЁННО
    print("=" * 74)
    print("ПОЗИЦИИ НАСКВОЗЬ: %d (база %s плюс поимённо %d)"
          % (len(поз), путь, len(ПОИМЁННО)))
    print("=" * 74)
    свод = []
    for п in поз:
        запросы = md.имена_для_поиска(п["название"])
        адреса = []
        for з in запросы:
            try:
                _, т = взять(md.ИСТОЧНИК_ПОИСК % quote(з))
            except Exception as e:
                print("  %-26s поиск %r не ответил: %r"
                      % (п["название"][:26], з, e))
                continue
            for u in md.ссылки_поиска(т):
                if u not in адреса:
                    адреса.append(u)
        подошли, по_правилу_A1 = [], []
        for u in адреса:
            try:
                _, стр = взять(md.ИСТОЧНИК_БАЗА + u)
            except Exception:
                continue
            ок, _д = md.подходит(п, стр)
            if ок:
                подошли.append(u)
                # A.3: СТРАНИЦА ПРИНЯТА ИМЕННО НОВЫМ ПРАВИЛОМ, а не
                # прежним совпадением чисел. Считается отдельно, потому
                # что «правило полезно» и «правило хоть раз сработало» —
                # разные утверждения, и второе проверяемо числом
                if not md.числа(п["доза"]) and not md.числа(_д["описание"]):
                    по_правилу_A1.append(u)
        # ИСХОД ТОТ ЖЕ, ЧТО У СЕРВЕРА: ноль — молчим, один — показываем,
        # больше одного — ОТКАЗЫВАЕМСЯ ВЫБИРАТЬ (A.3)
        исход = ("СХЕМА" if len(подошли) == 1
                 else ("НЕОДНОЗНАЧНО %d" % len(подошли)) if подошли
                 else "нет")
        свод.append((п, запросы, len(адреса), len(подошли), исход,
                     len(по_правилу_A1)))
        print("  %-11s %-30s запросов %d, страниц %2d, подошло %d  -> %s"
              % (п["метка"], п["название"][:30], len(запросы),
                 len(адреса), len(подошли), исход))
    схем = sum(1 for x in свод if x[4] == "СХЕМА")
    неодн = sum(1 for x in свод if x[4].startswith("НЕОДНОЗНАЧНО"))
    print()
    print("ИТОГ: схема нашлась у %d, неоднозначно у %d, молчим у %d — из %d"
          % (схем, неодн, len(свод) - схем - неодн, len(свод)))
    # ── A.3: ЧЕМ РИСКУЕТ ПРАВИЛО «ПУСТО С ОБЕИХ СТОРОН» ───────────────
    #
    # Риск назван постановкой: два разных препарата с одинаковым
    # названием и формой, оба без дозировки, станут неразличимы.
    # Меряется он в лоб — сколько страниц принято ИМЕННО этим правилом
    # и у скольких позиций таких страниц больше одной.
    без_дозы = [x for x in свод if not md.числа(x[0]["доза"])]
    неодн_бд = sum(1 for x in без_дозы if x[4].startswith("НЕОДНОЗНАЧНО"))
    принято_A1 = sum(x[5] for x in свод)
    пар = sum(1 for x in свод if x[5] > 1)
    print("A.3: позиций без дозировки %d, из них неоднозначны %d"
          % (len(без_дозы), неодн_бд))
    print("A.3: страниц, принятых ИМЕННО правилом «пусто с обеих сторон»: %d"
          % принято_A1)
    print("A.3: позиций, у которых таких страниц больше одной (пары): %d"
          % пар)
    if пар:
        for x in свод:
            if x[5] > 1:
                print("       %s — %d страниц, экран ОБЯЗАН отказаться "
                      "выбирать" % (x[0]["название"], x[5]))
    return 0



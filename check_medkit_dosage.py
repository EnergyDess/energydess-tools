БАЗА = "https://www.vidal.ru"

# ТРИ ПРЕПАРАТА РАЗНЫХ ФОРМ, и первый — тот, что лежит у владельца.
# Форма и дозировка здесь ИСКОМЫЕ: проба обязана проверить, что нашла

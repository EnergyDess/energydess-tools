def _переписка_снять():
    import sqlite3
    с = sqlite3.connect(os.getenv("DB_PATH", "app.db"), timeout=30)
    try:
        uid = с.execute("SELECT id FROM users WHERE email=?", (ПОЧТА,)).fetchone()[0]
        кол = [r[1] for r in с.execute("PRAGMA table_info(chat_messages)")]
        строки = с.execute("SELECT %s FROM chat_messages WHERE tool='medkit' "
                           "AND user_id=?" % ",".join(кол), (uid,)).fetchall()
        return uid, кол, строки
    finally:
        с.close()


def _переписка_вернуть(снимок):
    import sqlite3
    uid, кол, строки = снимок
    с = sqlite3.connect(os.getenv("DB_PATH", "app.db"), timeout=30)
    try:
        с.execute("DELETE FROM chat_messages WHERE tool='medkit' AND user_id=?",
                  (uid,))
        с.executemany("INSERT INTO chat_messages (%s) VALUES (%s)"
                      % (",".join(кол), ",".join("?" * len(кол))), строки)
        с.commit()
    finally:
        с.close()



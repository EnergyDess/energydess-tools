# ЗАЛОГ НА ВЫХОДЕ НЕЗАВИСИМ ОТ МАРШРУТА ОСТАТКА: `--контроль-остатка` (276)
# ═════════════════════════════════════════════════════════════════════
#
# ПОДЛОГ ЛОМАЕТ МАРШРУТ: `_апт_маршрут_остатка` подменяется на «не
# распознал», и вопрос уходит в модель. Модель подложена и ставит тип
# «поиск» — единственный с кнопкой списания. Запрос идёт через настоящий
# эндпоинт, тело рисует боевой построитель, считаются КНОПКИ С ЧИСЛОМ:
#   V0 — ничего не сломано: тип «остаток», модель не звалась, кнопок 0;
#   V1 — маршрут сломан, залог на выходе на месте: тип «поиск», кнопок 0;
#   V2 — маршрут сломан, залог снят — ДОКАЗАТЕЛЬСТВО: кнопка доезжает
#        до экрана, то есть V1 держит именно залог, а не что-то ещё.
def _прогон_остатка(сломать_маршрут, снять_залог):
    import main
    from fastapi.testclient import TestClient
    from database import SessionLocal, User
    вызовы = []
    с = SessionLocal()
    user = с.query(User).filter(User.email == ПОЧТА).first()
    позиции, _ = main._апт_позиции_для_запроса(с, user)
    с.expunge(user)
    с.close()
    # ПАЧКА С ПОДПИСЬЮ ПРИЁМА И ЕДИНСТВЕННАЯ ПО ИМЕНИ: без подписи кнопке
    # взяться неоткуда, и V2 не доказал бы ничего
    имена = [п["name"] for п in позиции]
    пачка = next(п for п in позиции if п.get("подпись_приёма")
                 and имена.count(п["name"]) == 1
                 and п["состояние"] != "expired" and not п["is_rx"])
    вопрос = "сколько осталось " + пачка["name"]
    прежние = (main._апт_маршрут_остатка, main._апт_списание_при_остатке,
               main._апт_спросить_модель)

    async def модель(промпт, очищать=True, **прочее):
        вызовы.append(1)
        if "завести карточку" in промпт:
            return {"вид": "запрос"}, "", 200
        return {"тип": "поиск", "подходят": [пачка["id"]], "нет": "",
                "группа": ""}, "", 200

    main.app.dependency_overrides[main.get_current_user] = lambda: user
    main._апт_спросить_модель = модель
    try:
        if сломать_маршрут:
            main._апт_маршрут_остатка = lambda текст, db, user: None
        if снять_залог:
            main._апт_списание_при_остатке = lambda тело: тело
        клиент = TestClient(main.app)
        клиент.delete("/medkit/api/chat")
        тело = клиент.post("/medkit/api/assist", json={"text": вопрос}).json()
        клиент.delete("/medkit/api/chat")
    finally:
        (main._апт_маршрут_остатка, main._апт_списание_при_остатке,
         main._апт_спросить_модель) = прежние
        main.app.dependency_overrides.clear()
    return вопрос, тело, len(вызовы)



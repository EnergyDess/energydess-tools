# ── МЕРКА ДОЗИРОВКИ: ОТДЕЛЬНАЯ И ШИРЕ ЗАСЛОНА ────────────────────────
#
# «ДО» НЕ ВЗЯТО НАМЕРЕННО: «годен до 04.2028» стоит в каждой строке
# позиции, и мерка печатала бы находку про срок годности.
_ЧИСЛО = r"\d+(?:[.,]\d+)?(?:\s*[-–—]\s*\d+(?:[.,]\d+)?)?"
_ЕДИНИЦА = (r"(?:мкг|мг|гр?|мл|ме|ед|таблет\w*|табл|капсул\w*|капс|"
            r"кап(?:ел|л)\w*|доз\w*|впрыс\w*|пшик\w*|нажат\w*|пакет\w*|"
            r"саше|свеч\w*|суппозитор\w*|ампул\w*|ложк\w*|раз(?:а)?|"
            r"ч|час\w*|сут\w*|(?:дн|ден|дне)\w*|пастил\w*|леденц\w*)"
            r"(?![а-яёa-z])")
_СЛОВО_ЧИСЛА = (r"(?:одн\w*|полови\w*|четверт\w*|дв(?:е|а|ух|ум)\w*|"
                r"тр(?:и|ех|ёх)\w*|четыр\w*|пят\w*|шест\w*)")
_СЛОВО_ЕДИНИЦЫ = (r"(?:таблет|капсул|капл|кап|доз|раз|ложк|пакет|свеч|"
                  r"впрыс|пшик|ампул)")
МЕРКА = re.compile(
    r"(" + _ЧИСЛО + r"\s*" + _ЕДИНИЦА
    + r"|(?:каждые|через|раз\s+в|не\s+(?:более|больше|чаще)|максимум)\s+"
      r"(?:" + _ЧИСЛО + r"|" + _СЛОВО_ЧИСЛА + r")"
    + r"|" + _СЛОВО_ЧИСЛА + r"\s+" + _СЛОВО_ЕДИНИЦЫ
    + r"|дважды|трижды)", re.I)


def мерка(текст: str) -> list:
    return [м.group(0) for м in МЕРКА.finditer(текст or "")]


# ЧТО В ПУЗЫРЕ — ДАННЫЕ КАРТОЧКИ. Всё остальное считается ответом.
# Кнопки идут в карточку: «Принял 1 таблетку» — подпись приёма,
# собранная сервером из разовой дозы ВЛАДЕЛЬЦА (§5.8)
ЧТЕНИЕ_ПУЗЫРЯ = """(д) => {
  const весь = д.innerText;
  const копия = д.cloneNode(true);
  const карта = [];
  копия.querySelectorAll('.apt-ai-item-t, .apt-ai-item-w, .apt-ai-item-ind,'
      + ' .apt-ai-item-packs, button').forEach(у => {
    карта.push(у.textContent.trim()); у.remove(); });
  return {весь, карта: карта.join(' | '), ответ: копия.textContent};
}"""


async def _войти(pg):
    await pg.goto(БАЗА + "/login", wait_until="domcontentloaded")
    await pg.fill("input[name=email]", ПОЧТА)
    await pg.fill("input[name=password]", ПАРОЛЬ)
    if await pg.query_selector(".cf-turnstile"):
        for _ in range(60):
            if await pg.evaluate("() => { const t = document.querySelector("
                                 "'[name=\"cf-turnstile-response\"]');"
                                 " return t && t.value; }"):
                break
            await pg.wait_for_timeout(500)
    await pg.click("button[type=submit]")
    await pg.wait_for_load_state("networkidle")
    if "/login" in pg.url:
        raise SystemExit("ВХОД НЕ СОСТОЯЛСЯ — спрашивать нечего")


async def _спросить(pg, вопрос):
    await pg.evaluate("async () => { await fetch('/medkit/api/chat',"
                      " {method: 'DELETE'}); }")
    await pg.goto(БАЗА + "/medkit", wait_until="networkidle")
    await pg.evaluate("() => аптАИОткрыть()")
    await pg.wait_for_timeout(700)
    # ПУЗЫРЬ ОТВЕТА БЫВАЕТ ТРЁХ ВИДОВ: `ai`, `stop` (стоп-состояние)
    # и `bad` (отказ сервера). Ждать один `ai` значило бы на стоп-ответе
    # прочитать ПРОШЛЫЙ пузырь и напечатать про него
    ПУЗЫРИ = "'.apt-ai-msg-ai, .apt-ai-msg-stop, .apt-ai-msg-bad'"
    было = await pg.evaluate(
        "() => document.querySelectorAll(%s).length" % ПУЗЫРИ)
    await pg.fill("#apt-ai-in", вопрос)
    await pg.evaluate("() => аптАИОтправитьТекст()")
    await pg.wait_for_timeout(400)
    # ЖДЁМ И РАЗБЛОКИРОВКИ КНОПКИ, И НОВОГО ПУЗЫРЯ: по таймеру в замер
    # попадало бы «Смотрю…», а по одной кнопке — прошлый пузырь
    for _ in range(240):
        готово = await pg.evaluate(
            "(было) => {const к = document.getElementById('apt-ai-send');"
            " return к && !к.disabled && document.querySelectorAll("
            "%s).length > было;}" % ПУЗЫРИ, было)
        if готово:
            break
        await pg.wait_for_timeout(500)
    await pg.wait_for_timeout(500)
    пузырь = await pg.evaluate_handle(
        "() => [...document.querySelectorAll(%s)].pop() || null" % ПУЗЫРИ)
    if not await pg.evaluate("(д) => !!д", пузырь):
        return {"весь": "", "карта": "", "ответ": "", "маршрут": {},
                "беда": "пузыря ответа нет"}
    прочтено = await pg.evaluate(ЧТЕНИЕ_ПУЗЫРЯ, пузырь)
    ошибка = await pg.evaluate(
        "(д) => д.classList.contains('apt-ai-msg-bad') ? д.innerText : ''",
        пузырь)
    # МАРШРУТ — ИЗ ХРАНИМОЙ РЕПЛИКИ, а не из догадки по тексту
    маршрут = await pg.evaluate(
        "async () => { const о = await (await fetch('/medkit/api/chat'))"
        ".json(); const р = (о['реплики'] || []).filter(р => р['роль'] !="
        " 'user').pop(); const т = (р && р['ответ']) || {};"
        " return {вид: т['вид'] || '', тип: т['тип'] || '',"
        " повод: т['повод'] || '', доза_отброшена: !!т['доза_отброшена']}; }")
    прочтено["маршрут"] = маршрут
    прочтено["ошибка"] = ошибка
    return прочтено


async def прогон(путь):
    from playwright.async_api import async_playwright
    итоги = []
    async with async_playwright() as pw:
        # ГОЛОВНОЙ БРАУЗЕР (§6.0.3): правило захода, и ширина пузыря
        # тут не главное — главное, что замер делается тем же путём,
        # что у человека
        бр = await pw.chromium.launch(headless=False)
        ctx = await бр.new_context(viewport={"width": 1440, "height": 900})
        pg = await ctx.new_page()
        await _войти(pg)
        for i, (намерение, вопрос) in enumerate(ВОПРОСЫ, 1):
            р = await _спросить(pg, вопрос)
            в_ответе = мерка(р.get("ответ"))
            в_карте = мерка(р.get("карта"))
            м = р.get("маршрут") or {}
            итоги.append({"n": i, "намерение": намерение, "вопрос": вопрос,
                          "вид": м.get("вид"), "тип": м.get("тип"),
                          "повод": м.get("повод"),
                          "доза_отброшена": м.get("доза_отброшена"),
                          "весь": р.get("весь"), "ответ": р.get("ответ"),
                          "карта": р.get("карта"),
                          "ошибка": р.get("ошибка") or р.get("беда") or "",
                          "в_ответе": в_ответе, "в_карте": в_карте})
            print("─" * 72)
            print("%2d. [%s] «%s»" % (i, намерение, вопрос))
            print("    маршрут: вид=%s тип=%s повод=%s доза_отброшена=%s"
                  % (м.get("вид") or "—", м.get("тип") or "—",
                     м.get("повод") or "—", м.get("доза_отброшена")))
            if итоги[-1]["ошибка"]:
                print("    ОШИБКА НА ЭКРАНЕ: %s" % итоги[-1]["ошибка"])
            print("    ВИДИТ ЧЕЛОВЕК ЦЕЛИКОМ:")
            for строка in (р.get("весь") or "— ПУСТО —").splitlines():
                if строка.strip():
                    print("      " + строка.strip())
            print("    ДОЗИРОВКА В ТЕКСТЕ ОТВЕТА: %s"
                  % (в_ответе if в_ответе else "нет"))
            print("    числа в данных карточки: %s"
                  % (в_карте if в_карте else "нет"))
        await ctx.close()
        await бр.close()
    _сводка(итоги)
    if путь:
        io.open(путь, "w", encoding="utf-8").write(
            json.dumps(итоги, ensure_ascii=False, indent=1))
        print("сохранено: %s" % путь)
    return 0



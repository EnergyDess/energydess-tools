# ПОДЛОГ ЛОМАЕТ ПРОВЕРЯЕМОЕ ЗВЕНО — БЕЛЫЙ СПИСОК `main.АПТ_ТИПЫ_СО_СПИСАНИЕМ`:
# в него возвращаются «схема» и «иное», то есть кнопка возвращается
# в ответ «как принимать» ровно тем путём, каким жила до правки. Тело
# рисует боевой построитель панели в головном браузере, считаются
# КНОПКИ С ЧИСЛОМ на экране. Три числа на случай:
#   сырое  — тело без заслона: ДОКАЗАТЕЛЬСТВО, что подпись доезжает
#            до экрана вовсе (ноль тут значил бы, что мерить нечего);
#   правило — через заслон с исправным списком;
#   подлог — через заслон со сломанным списком.
# ОБРАТНЫЙ СЛУЧАЙ — «поиск»: кнопка обязана остаться при любом списке.
СЛУЧАИ_СПИСАНИЯ = (
    ("как принимать", "схема", False),
    ("иное (пачка названа, не жалоба)", "иное", False),
    ("ОБРАТНЫЙ: что есть от жалобы", "поиск", True),
)
ЧТЕНИЕ_КНОПОК = """(было) => [...document.querySelectorAll('.apt-ai-msg-ai')]
  .slice(было).map(д => [...д.querySelectorAll('button')]
    .map(к => к.textContent.trim()).join(' | ')).join(' | ')"""


async def _кнопки(pg, тело):
    было = await pg.evaluate("() => document.querySelectorAll("
                             "'.apt-ai-msg-ai').length")
    await pg.evaluate(РАЗВИЛКА, тело)
    await pg.wait_for_timeout(150)
    текст = await pg.evaluate(ЧТЕНИЕ_КНОПОК, было)
    return len(КНОПКА_СПИСАНИЯ.findall(текст))


async def контроль_списания():
    import main
    from playwright.async_api import async_playwright
    прежний = main.АПТ_ТИПЫ_СО_СПИСАНИЕМ
    плохо = 0
    async with async_playwright() as pw:
        бр = await pw.chromium.launch(headless=False)
        ctx = await бр.new_context(viewport={"width": 1440, "height": 900})
        pg = await ctx.new_page()
        await _войти(pg)
        await pg.goto(БАЗА + "/medkit", wait_until="networkidle")
        await pg.evaluate("() => аптАИОткрыть()")
        await pg.wait_for_timeout(600)
        print("%-36s %-7s %-8s %-7s %-8s %s" % ("случай", "сырое", "правило",
                                             "подлог", "снято", "вывод"))
        for имя, тип, ждём in СЛУЧАИ_СПИСАНИЯ:
            сырое = await _кнопки(pg, _запрос(тип=тип))
            правило = await _кнопки(pg, main._апт_заслон_выхода(_запрос(тип=тип)))
            main.АПТ_ТИПЫ_СО_СПИСАНИЕМ = frozenset({"поиск", "схема", "иное"})
            try:
                подлог = await _кнопки(
                    pg, main._апт_заслон_выхода(_запрос(тип=тип)))
            finally:
                main.АПТ_ТИПЫ_СО_СПИСАНИЕМ = прежний
            снято = await _кнопки(pg, main._апт_заслон_выхода(_запрос(тип=тип)))
            if ждём:
                верно = сырое == правило == подлог == снято == 1
                вывод = "КНОПКА НА МЕСТЕ" if верно else "ОТНЯТА ЗРЯ"
            else:
                верно = (сырое == 1 and правило == 0 and подлог == 1
                         and снято == 0)
                вывод = ("ПОДЛОГ ПОЙМАН ЧИСЛОМ" if верно else
                         "ПОДЛОГ НЕ СОСТОЯЛСЯ" if сырое == 0 or подлог == 0
                         else "ПРАВИЛО НЕ ГАСИТ")
            плохо += 0 if верно else 1
            print("%-36s %-7d %-8d %-7d %-8d %s" % (имя, сырое, правило,
                                                  подлог, снято, вывод))
        await ctx.close()
        await бр.close()
    print("КОНТРОЛЬ СПИСАНИЯ: случаев %d, неверных %d"
          % (len(СЛУЧАИ_СПИСАНИЯ), плохо))
    return 1 if плохо else 0



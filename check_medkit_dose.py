# и «остаток уменьшился» — разные утверждения. Отмена возвращает
# остаток, и это тоже спрашивается у базы: стенд уходит таким, каким
# был взят.
ВОПРОС_СПИСАНИЯ = "что у меня есть от кашля"


def _остаток(ид):
    import sqlite3
    from database import DB_PATH
    с = sqlite3.connect("file:%s?mode=ro" % DB_PATH, uri=True)
    try:
        return с.execute("SELECT qty_left, dose FROM medkit_items WHERE id=?",
                         (ид,)).fetchone()
    finally:
        с.close()



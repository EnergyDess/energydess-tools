# СПИСАНИЕ ПРЯМО ИЗ ОТВЕТА НЕ СЛОМАНО: `--списание` (задача 272, D.2)
# ═════════════════════════════════════════════════════════════════════
#
# Построитель карточки ответа вынесен в функцию, у кнопки инструкции
# сменилось имя — значит кнопку списания рядом надо НАЖАТЬ, а не
# прочитать. Результат берётся ИЗ БАЗЫ (§6.3): «кнопка нажалась»
# и «остаток уменьшился» — разные утверждения. Отмена возвращает
# остаток, и это тоже спрашивается у базы: стенд уходит таким, каким
# был взят.
ВОПРОС_СПИСАНИЯ = "что у меня есть от кашля"


def _остаток(ид):
    import sqlite3
    from database import DB_PATH
    с = sqlite3.connect("file:%s?mode=ro" % DB_PATH, uri=True)
    try:
        return с.execute("SELECT qty_left, dose FROM medkit_items WHERE id=?",
                         (ид,)).fetchone()
    finally:
        с.close()


async def списание():
    from playwright.async_api import async_playwright
    async with async_playwright() as pw:
        бр = await pw.chromium.launch(headless=False)
        ctx = await бр.new_context(viewport={"width": 1440, "height": 900})
        pg = await ctx.new_page()
        await _войти(pg)
        await _спросить(pg, ВОПРОС_СПИСАНИЯ)
        карточки = await pg.evaluate(
            "async () => { const о = await (await fetch('/medkit/api/chat'))"
            ".json(); const р = (о['реплики'] || []).filter(р => р['роль'] !="
            " 'user').pop(); const т = (р && р['ответ']) || {};"
            " return (т['нашлось'] || []).map(с => [с['id'], с['приём_подпись'],"
            " с['упаковок']]); }")
        цель = next((к for к in карточки if к[1] and (к[2] or 1) == 1), None)
        if not цель:
            print("СПИСАНИЕ: в ответе нет карточки с кнопкой списания — "
                  "НЕ ПРОВЕРЕНО (карточки: %r)" % (карточки,))
            await бр.close()
            return 2
        ид, подпись, _ = цель
        было = _остаток(ид)
        кнопка = pg.locator(".apt-ai-msg-ai").last.locator(
            "button.apt-ai-item-btn", has_text=подпись)
        await кнопка.click()
        await pg.wait_for_timeout(1500)
        после = _остаток(ид)
        # ПО `id`, А НЕ ПО ПОРЯДКУ: первым в полосе однажды оказалась
        # «В покупки», и проба жала не ту кнопку (§5.8)
        вернуть = pg.locator("#undo-bar-undo")
        await вернуть.click()
        await pg.wait_for_timeout(1500)
        отмена = _остаток(ид)
        await ctx.close()
        await бр.close()
    print("СПИСАНИЕ ИЗ ОТВЕТА: позиция %s, кнопка «%s»" % (ид, подпись))
    print("  остаток в базе: было %s, после нажатия %s, после «Вернуть» %s "
          "(разовая доза %s)" % (было[0], после[0], отмена[0], было[1]))
    верно = (после[0] == было[0] - (было[1] or 1) and отмена[0] == было[0])
    print("  %s" % ("РАБОТАЕТ: списалось ровно на дозу и вернулось" if верно
                    else "СЛОМАНО — разобрать числа выше"))
    return 0 if верно else 1



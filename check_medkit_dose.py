# ── ВЫЗОВЫ МОДЕЛИ СЧИТАЮТСЯ ПО ЖУРНАЛУ СТЕНДА, А НЕ ПО МАРШРУТУ ────────
#
# `_вызовов` ниже ВЫВОДИТ число из типа ответа: «остаток» — ноль, «запрос»
# — два. Для вопроса «вызывалась ли модель» это рассуждение, а не замер
# (§6.0.1): маршрут, сломанный так, что модель зовётся, а тип всё равно
# кодовый, дал бы ноль. Стенд, поднятый с журналом в файл
# (`py -u -m uvicorn … *> журнал`), печатает строку `[метка] finish=` на
# КАЖДЫЙ ответ модели (`_model_output`) — их и считаем до и после вопроса.
# Журнала нет — печатается «не мерено», а не ноль.
def _строк_вызова():
    путь = os.getenv("STAND_LOG")
    if not путь or not os.path.exists(путь):
        return None
    сырьё = io.open(путь, "rb").read()
    # `*>` в Windows PowerShell 5.1 пишет UTF-16 с меткой порядка байтов
    текст = (сырьё.decode("utf-16", errors="replace")
             if сырьё[:2] in (b"\xff\xfe", b"\xfe\xff")
             else сырьё.decode("utf-8", errors="replace"))
    return sum(1 for с in текст.splitlines() if "] finish=" in с)


# ── МЕРКА ДОЗИРОВКИ: ОТДЕЛЬНАЯ И ШИРЕ ЗАСЛОНА ────────────────────────
#
# «ДО» НЕ ВЗЯТО НАМЕРЕННО: «годен до 04.2028» стоит в каждой строке
# позиции, и мерка печатала бы находку про срок годности.
_ЧИСЛО = r"\d+(?:[.,]\d+)?(?:\s*[-–—]\s*\d+(?:[.,]\d+)?)?"
_ЕДИНИЦА = (r"(?:мкг|мг|гр?|мл|ме|ед|таблет\w*|табл|капсул\w*|капс|"
            r"кап(?:ел|л)\w*|доз\w*|впрыс\w*|пшик\w*|нажат\w*|пакет\w*|"
            r"саше|свеч\w*|суппозитор\w*|ампул\w*|ложк\w*|раз(?:а)?|"
            r"ч|час\w*|сут\w*|(?:дн|ден|дне)\w*|пастил\w*|леденц\w*)"
            r"(?![а-яёa-z])")
_СЛОВО_ЧИСЛА = (r"(?:одн\w*|полови\w*|четверт\w*|дв(?:е|а|ух|ум)\w*|"
                r"тр(?:и|ех|ёх)\w*|четыр\w*|пят\w*|шест\w*)")
_СЛОВО_ЕДИНИЦЫ = (r"(?:таблет|капсул|капл|кап|доз|раз|ложк|пакет|свеч|"
                  r"впрыс|пшик|ампул)")
МЕРКА = re.compile(
    r"(" + _ЧИСЛО + r"\s*" + _ЕДИНИЦА
    + r"|(?:каждые|через|раз\s+в|не\s+(?:более|больше|чаще)|максимум)\s+"
      r"(?:" + _ЧИСЛО + r"|" + _СЛОВО_ЧИСЛА + r")"
    + r"|" + _СЛОВО_ЧИСЛА + r"\s+" + _СЛОВО_ЕДИНИЦЫ
    + r"|дважды|трижды)", re.I)


def мерка(текст: str) -> list:
    return [м.group(0) for м in МЕРКА.finditer(текст or "")]



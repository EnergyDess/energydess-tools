# РАЗВИЛКА ПО ВИДУ — ТА ЖЕ, ЧТО В `аптАИПослать` (`medkit.html`). Там она
# стоит внутри функции отправки и отдельно не вызывается; повторена
# дословно по полю `вид`, а построители — боевые
РАЗВИЛКА = """(т) => {
  if (т['вид'] === 'стоп') { аптАИСтоп(т); return; }
  if (т['вид'] === 'запрос') { аптАИОтвет(т); return; }
  if (т['вид'] === 'непонятно') { аптАИСказать('ai', т['текст'] || ''); return; }
  аптАИПоказатьЧерновик(т);
}"""


async def _нарисовать(pg, тело, как=None):
    было = await pg.evaluate("() => document.querySelectorAll("
                             "'.apt-ai-msg-ai, .apt-ai-msg-stop, "
                             ".apt-ai-msg-bad').length")
    await pg.evaluate(РАЗВИЛКА, тело)
    await pg.wait_for_timeout(150)
    return await pg.evaluate(ЧТЕНИЕ_НОВЫХ, было)



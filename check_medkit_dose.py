def _вызовов(и):
    """Сколько живых вызовов модели стоил ответ.

    Если стенд пишет журнал (`STAND_LOG`), — ИЗМЕРЕННОЕ число строк
    `finish=`; иначе выведенное по маршруту, и это рассуждение."""
    if и.get("вызовов_модели") is not None:
        return и["вызовов_модели"]
    if и["вид"] == "стоп" or и["тип"] in ("доза", "остаток", "место"):
        return 0
    return 2 if и["вид"] == "запрос" else 1


def _сводка(итоги):
    print("=" * 72)
    print("СВОДКА")
    доза = [и for и in итоги if и["намерение"] == "доза"]
    print("вопросов всего %d, из них о дозировке %d"
          % (len(итоги), len(доза)))
    print("ответов с ЧИСЛОМ ДОЗИРОВКИ В ТЕКСТЕ ОТВЕТА: %d из %d "
          "(о дозировке: %d из %d)"
          % (sum(1 for и in итоги if и["в_ответе"]), len(итоги),
             sum(1 for и in доза if и["в_ответе"]), len(доза)))
    print("ответов о дозировке с КНОПКОЙ СПИСАНИЯ С ЧИСЛОМ под ними: %d из %d"
          % (sum(1 for и in доза if КНОПКА_СПИСАНИЯ.search(и["карта"] or "")),
             len(доза)))
    # ПО КАЖДОМУ НАМЕРЕНИЮ И ПО ФАКТИЧЕСКОМУ ТИПУ (задача 275, B): тип
    # решает, где кнопка уместна, а намерение — что человек спрашивал.
    # Два разреза, потому что тип может разойтись с намерением
    for разрез, ключ in (("намерению", lambda и: и["намерение"]),
                         ("типу ответа", lambda и: "%s/%s" % (
                             и["вид"] or "—", и["тип"] or "—"))):
        счёт = {}
        for и in итоги:
            к = ключ(и)
            счёт.setdefault(к, [0, 0])
            счёт[к][1] += 1
            if КНОПКА_СПИСАНИЯ.search(и["карта"] or ""):
                счёт[к][0] += 1
        print("КНОПКА СПИСАНИЯ С ЧИСЛОМ по %s: %s" % (разрез, ", ".join(
            "%s %d из %d" % (к, в[0], в[1]) for к, в in sorted(счёт.items()))))
    # ВОПРОС ОБ ОСТАТКЕ (задача 276): спросивший «сколько осталось» ничего
    # не принимал, и кнопка с разовой дозой под ответом — ровно тот случай
    остаток = [и for и in итоги if и["намерение"].startswith("остаток")]
    if остаток:
        print("ответов ОБ ОСТАТКЕ с КНОПКОЙ СПИСАНИЯ С ЧИСЛОМ под ними: %d из %d"
              % (sum(1 for и in остаток
                     if КНОПКА_СПИСАНИЯ.search(и["карта"] or "")),
                 len(остаток)))
        print("ответов ОБ ОСТАТКЕ с ЧИСЛОМ ДОЗИРОВКИ В ТЕКСТЕ: %d из %d"
              % (sum(1 for и in остаток if и["в_ответе"]), len(остаток)))
    # ВОПРОС О МЕСТЕ (задача 283): спросивший «где лежит» ничего
    # не принимал; модель тут может ошибиться там, где ошибиться нечем
    место = [и for и in итоги if и["намерение"] == "место"]
    if место:
        мерено = [и for и in место if и.get("вызовов_модели") is not None]
        print("ответов О МЕСТЕ с КНОПКОЙ СПИСАНИЯ С ЧИСЛОМ под ними: %d из %d"
              % (sum(1 for и in место
                     if КНОПКА_СПИСАНИЯ.search(и["карта"] or "")), len(место)))
        print("ответов О МЕСТЕ, где модель ВЫЗЫВАЛАСЬ (по журналу): %s"
              % ("не мерено" if not мерено else "%d из %d, вызовов всего %d"
                 % (sum(1 for и in мерено if и["вызовов_модели"]),
                    len(мерено), sum(и["вызовов_модели"] for и in мерено))))
    # ВОПРОСЫ-ЧТЕНИЯ ПОЛЯ (заход 290): по каждому полю — звали ли модель
    # и есть ли кнопка. Кнопка и вызов модели — два разных числа: залог
    # на выходе снимает кнопку и тогда, когда модель уже позвали
    поля = [и for и in итоги if и["намерение"] in ПОЛЯ]
    if поля:
        for поле in ПОЛЯ:
            свои = [и for и in поля if и["намерение"] == поле]
            if not свои:
                continue
            мерено = [и for и in свои if и.get("вызовов_модели") is not None]
            print("ПОЛЕ %-10s модель звали %s · кнопок с числом %d из %d"
                  % (поле, "не мерено" if not мерено else "%d из %d (вызовов %d)"
                     % (sum(1 for и in мерено if и["вызовов_модели"]),
                        len(мерено), sum(и["вызовов_модели"] for и in мерено)),
                     sum(1 for и in свои
                         if КНОПКА_СПИСАНИЯ.search(и["карта"] or "")),
                     len(свои)))
        мерено = [и for и in поля if и.get("вызовов_модели") is not None]
        print("ВСЕГО ПО ПОЛЯМ: модель звали %s · кнопок с числом %d из %d"
              % ("не мерено" if not мерено else "%d из %d (вызовов %d)"
                 % (sum(1 for и in мерено if и["вызовов_модели"]), len(мерено),
                    sum(и["вызовов_модели"] for и in мерено)),
                 sum(1 for и in поля if КНОПКА_СПИСАНИЯ.search(и["карта"] or "")),
                 len(поля)))
    врач = [и for и in доза if ВРАЧ_ПОВОДЫ.search(и["вопрос"])]
    print("ответов про ребёнка/беременность/алкоголь с ОГОВОРКОЙ: %d из %d"
          % (sum(1 for и in врач if ОГОВОРКИ.search(и["ответ"] or "")),
             len(врач)))
    print("живых вызовов модели по маршрутам: %d"
          % sum(_вызовов(и) for и in итоги))
    ошибки = [и for и in итоги if ОЖИДАЕМО[и["намерение"]] is not None
              and (и["вид"] or "", и["тип"] or "") != ОЖИДАЕМО[и["намерение"]]]
    print("ОШИБОК ОПРЕДЕЛЕНИЯ ТИПА: %d из %d%s"
          % (len(ошибки), len(итоги),
             "" if not ошибки else " — " + "; ".join(
                 "%d %s/%s" % (и["n"], и["вид"] or "—", и["тип"] or "—")
                 for и in ошибки)))
    print("ответов с ошибкой на экране: %d"
          % sum(1 for и in итоги if и["ошибка"]))
    виды = {}
    for и in итоги:
        ключ = "%s/%s" % (и["вид"] or "—", и["тип"] or "—")
        виды.setdefault(и["намерение"], {}).setdefault(ключ, 0)
        виды[и["намерение"]][ключ] += 1
    for нам, счёт in виды.items():
        print("  %-14s %s" % (нам, ", ".join(
            "%s×%d" % (к, в) for к, в in sorted(счёт.items()))))



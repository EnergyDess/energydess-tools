# КАКОЙ ТИП ОБЯЗАН ПОЛУЧИТЬ ВОПРОС ЭТОГО НАМЕРЕНИЯ (задача 272, C).
# «Не помогло» — стоп: подбор замены к врачу, и это решает код до модели
ОЖИДАЕМО = {"жалоба": ("запрос", "поиск"),
            "как_принимать": ("запрос", "схема"),
            "не_помогло": ("стоп", ""),
            "доза": ("запрос", "доза")}


def _вызовов(и):
    """Сколько живых вызовов модели стоил ответ — по маршруту."""
    if и["вид"] == "стоп" or и["тип"] == "доза":
        return 0
    return 2 if и["вид"] == "запрос" else 1


def _сводка(итоги):
    print("=" * 72)
    print("СВОДКА")
    доза = [и for и in итоги if и["намерение"] == "доза"]
    print("вопросов всего %d, из них о дозировке %d"
          % (len(итоги), len(доза)))
    print("ответов с ЧИСЛОМ ДОЗИРОВКИ В ТЕКСТЕ ОТВЕТА: %d из %d "
          "(о дозировке: %d из %d)"
          % (sum(1 for и in итоги if и["в_ответе"]), len(итоги),
             sum(1 for и in доза if и["в_ответе"]), len(доза)))
    print("ответов о дозировке с КНОПКОЙ СПИСАНИЯ С ЧИСЛОМ под ними: %d из %d"
          % (sum(1 for и in доза if КНОПКА_СПИСАНИЯ.search(и["карта"] or "")),
             len(доза)))
    врач = [и for и in доза if ВРАЧ_ПОВОДЫ.search(и["вопрос"])]
    print("ответов про ребёнка/беременность/алкоголь с ОГОВОРКОЙ: %d из %d"
          % (sum(1 for и in врач if ОГОВОРКИ.search(и["ответ"] or "")),
             len(врач)))
    print("живых вызовов модели по маршрутам: %d"
          % sum(_вызовов(и) for и in итоги))
    ошибки = [и for и in итоги
              if (и["вид"] or "", и["тип"] or "") != ОЖИДАЕМО[и["намерение"]]]
    print("ОШИБОК ОПРЕДЕЛЕНИЯ ТИПА: %d из %d%s"
          % (len(ошибки), len(итоги),
             "" if not ошибки else " — " + "; ".join(
                 "%d %s/%s" % (и["n"], и["вид"] or "—", и["тип"] or "—")
                 for и in ошибки)))
    print("ответов с ошибкой на экране: %d"
          % sum(1 for и in итоги if и["ошибка"]))
    виды = {}
    for и in итоги:
        ключ = "%s/%s" % (и["вид"] or "—", и["тип"] or "—")
        виды.setdefault(и["намерение"], {}).setdefault(ключ, 0)
        виды[и["намерение"]][ключ] += 1
    for нам, счёт in виды.items():
        print("  %-14s %s" % (нам, ", ".join(
            "%s×%d" % (к, в) for к, в in sorted(счёт.items()))))


def сравнить(а, б):
    до = json.load(io.open(а, encoding="utf-8"))
    после = json.load(io.open(б, encoding="utf-8"))
    print("%-3s %-14s %-22s %-22s %-6s %-6s" % ("n", "намерение", "маршрут ДО",
                                               "маршрут ПОСЛЕ", "доз ДО",
                                               "ПОСЛЕ"))
    for x, y in zip(до, после):
        print("%-3d %-14s %-22s %-22s %-6d %-6d  %s"
              % (x["n"], x["намерение"],
                 "%s/%s" % (x["вид"] or "—", x["тип"] or "—"),
                 "%s/%s" % (y["вид"] or "—", y["тип"] or "—"),
                 len(x["в_ответе"]), len(y["в_ответе"]), x["вопрос"]))
    print("ответов с дозировкой в тексте: ДО %d, ПОСЛЕ %d"
          % (sum(1 for x in до if x["в_ответе"]),
             sum(1 for y in после if y["в_ответе"])))
    for имя, ит in (("ДО", до), ("ПОСЛЕ", после)):
        print("── %s" % имя)
        _сводка(ит)
    return 0



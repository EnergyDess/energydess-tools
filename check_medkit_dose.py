# ПОДЛОГ ЛОМАЕТ РОУТЕР: распознаватель вопроса о дозе подменяется
# на «не распознал», и вопрос уходит в модель. Модель подложена
# и отвечает поиском с дозировкой в тексте. Внутренний заслон ветки
# запроса ГАСИТСЯ ТОЖЕ — иначе ноль на экране дал бы он, и про выходной
# заслон контроль не сказал бы ничего. Выходной берёт признак напрямую
# (`АПТ_СЛЕД_ДОЗЫ`), а не через подменённую функцию.
#
# ЗАПРОС ИДЁТ ЧЕРЕЗ НАСТОЯЩИЙ ЭНДПОИНТ (`TestClient`, тот же процесс),
# ответ рисуется боевым построителем в головном браузере. Три прогона:
#   V0 — ничего не сломано: тип «доза», модель не звалась;
#   V1 — роутер сломан, выходной заслон на месте;
#   V2 — роутер сломан, выходной заслон снят — ДОКАЗАТЕЛЬСТВО: доза
#        из подложенного ответа доезжает до экрана.
ВОПРОС_РОУТЕРА = "сколько Нурофена можно выпить за день"
ПОДЛОЖЕННЫЙ_ОТВЕТ = {"тип": "поиск", "подходят": [],
                     "нет": "Взрослым по 2 таблетки каждые 6 часов.",
                     "группа": ""}


def _прогон_роутера(сломать_роутер, снять_заслон):
    import main
    from fastapi.testclient import TestClient
    from database import SessionLocal, User
    вызовы = []
    прежние = (main._апт_вопрос_о_дозе, main._апт_след_дозы,
               main._апт_заслон_выхода, main._апт_спросить_модель)

    async def модель(промпт, очищать=True, **прочее):
        вызовы.append(1)
        if "завести карточку" in промпт:
            return {"вид": "запрос"}, "", 200
        return dict(ПОДЛОЖЕННЫЙ_ОТВЕТ), "", 200

    с = SessionLocal()
    user = с.query(User).filter(User.email == ПОЧТА).first()
    с.expunge(user)
    с.close()
    main.app.dependency_overrides[main.get_current_user] = lambda: user
    main._апт_спросить_модель = модель
    try:
        if сломать_роутер:
            main._апт_вопрос_о_дозе = lambda текст: None
            main._апт_след_дозы = lambda куски: []
        if снять_заслон:
            main._апт_заслон_выхода = lambda тело: тело
        клиент = TestClient(main.app)
        клиент.delete("/medkit/api/chat")
        тело = клиент.post("/medkit/api/assist",
                           json={"text": ВОПРОС_РОУТЕРА}).json()
        клиент.delete("/medkit/api/chat")
    finally:
        (main._апт_вопрос_о_дозе, main._апт_след_дозы,
         main._апт_заслон_выхода, main._апт_спросить_модель) = прежние
        main.app.dependency_overrides.clear()
    return тело, len(вызовы)


async def _нарисовать_все(тела):
    from playwright.async_api import async_playwright
    видно = []
    async with async_playwright() as pw:
        бр = await pw.chromium.launch(headless=False)
        ctx = await бр.new_context(viewport={"width": 1440, "height": 900})
        pg = await ctx.new_page()
        await _войти(pg)
        await pg.goto(БАЗА + "/medkit", wait_until="networkidle")
        await pg.evaluate("() => аптАИОткрыть()")
        await pg.wait_for_timeout(600)
        for тело in тела:
            видно.append(await _нарисовать(pg, тело))
        await ctx.close()
        await бр.close()
    return видно


def контроль_роутера():
    случаи = (("V0 ничего не сломано", False, False),
              ("V1 роутер сломан, заслон на месте", True, False),
              ("V2 роутер сломан, заслон СНЯТ", True, True))
    прогоны = [(имя,) + _прогон_роутера(р, з) for имя, р, з in случаи]
    видно = asyncio.run(_нарисовать_все([т for _, т, _ in прогоны]))
    итог = []
    print("%-36s %-8s %-6s %-9s %s" % ("прогон", "тип", "модель", "заслон",
                                       "доз на экране"))
    for (имя, тело, вызовов), текст in zip(прогоны, видно):
        дозы = мерка(текст)
        итог.append((тело.get("тип"), вызовов, bool(тело.get("заслон_выхода")),
                     len(дозы)))
        print("%-36s %-8s %-6d %-9s %d %s" % (имя, тело.get("тип") or "—",
                                             вызовов,
                                             "сработал" if тело.get(
                                                 "заслон_выхода") else "—",
                                             len(дозы), дозы or ""))
    v0, v1, v2 = итог
    верно = (v0[0] == "доза" and v0[1] == 0 and v0[3] == 0
             and v1[1] == 2 and v1[2] and v1[3] == 0
             and v2[1] == 2 and v2[0] == "поиск" and v2[3] >= 1)
    print("КОНТРОЛЬ РОУТЕРА: %s" % ("ЗАСЛОН НЕЗАВИСИМ ОТ РОУТЕРА" if верно
                                    else "НЕ ДОКАЗАНО — разобрать числа выше"))
    return 0 if верно else 1



# коробка отвечает на заданный вопрос ТОЧНО: мы знаем до знака, что
# на ней напечатано, и потому знаем, прочитала модель или дополнила.

def нарисовать(строки) -> bytes:
    from PIL import Image, ImageDraw, ImageFont
    им = Image.new("RGB", (900, 620), (250, 250, 248))
    d = ImageDraw.Draw(им)
    d.rectangle([20, 20, 880, 600], outline=(30, 60, 120), width=4)
    y = 70
    for текст, кегль in строки:
        try:
            ш = ImageFont.truetype("arial.ttf", кегль)
        except OSError:
            ш = ImageFont.load_default()
        d.text((60, y), текст, fill=(10, 10, 30), font=ш)
        y += кегль + 26
    буф = io.BytesIO()
    им.save(буф, format="JPEG", quality=92)
    return буф.getvalue()



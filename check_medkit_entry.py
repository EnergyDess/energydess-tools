_человеческое = _опр.человеческое


ПОЛЯ = ("name", "substance", "form", "unit", "qty_total", "qty_left",
        "expires_ym", "code_gtin")

ПОДПИСЬ = {"name": "название", "substance": "вещество",
           "form": "форма", "unit": "единица",
           "qty_total": "было в упаковке", "qty_left": "осталось",
           "expires_ym": "срок годности", "code_gtin": "штрих-код"}


def разложить(черновик: dict, ввод: str, что_на_картинке: str = None) -> list:
    """Каждое заполненное поле → откуда оно.

    `что_на_картинке` — для ветки фото: там ввод модели это ИЗОБРАЖЕНИЕ,
    и следом служит текст, который мы на него нанесли. Второго признака
    тут не заводится, он тот же самый.
    """
    источник_текста = что_на_картинке if что_на_картинке is not None else ввод
    строки = []
    for ключ in ПОЛЯ:
        зн = черновик.get(ключ)
        if зн in (None, ""):
            continue
        видно = any(_след(в, источник_текста) for в in _человеческое(ключ, зн))
        строки.append({
            "поле": ключ,
            "значение": зн,
            "источник": ("прочитано" if видно else "ИЗ ПАМЯТИ МОДЕЛИ"),
        })
    return строки



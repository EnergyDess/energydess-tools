async def сценарий(имя, описание, что_на_картинке=None, картинка=None):
    print("\n" + "─" * 70)
    print("СЦЕНАРИЙ: %s" % имя)
    print("─" * 70)
    if картинка is None:
        print("  ввод (текст): %r" % описание)
    else:
        print("  ввод (фото), напечатано на упаковке:")
        for с in что_на_картинке.split("\n"):
            print("      %s" % с)
    промпт = M._апт_промпт(описание)
    if картинка is not None:
        b64 = base64.b64encode(картинка).decode()
        try:
            текст = await M._call_vision(b64, "image/jpeg", промпт,
                                         M.MEDKIT_MAX_TOKENS)
        except Exception as e:
            print("  СБОЙ: %s" % e)
            return None
        try:
            сырой = M._extract_json(текст)
        except Exception:
            print("  ОТВЕТ НЕ РАЗОБРАЛСЯ: %r" % текст[:200])
            return None
    else:
        сырой, беда, код = await M._апт_спросить_модель(промпт, очищать=False)
        if беда:
            print("  СБОЙ %s: %s" % (код, беда))
            return None
    черновик = M._апт_очистить_черновик(сырой)

    # ИСТОЧНИК БЕРЁТСЯ ТОТ ЖЕ, ЧТО У БОЕВОГО ЭНДПОИНТА: у фото —
    # выписка модели, у текста — сам ввод. Свой источник тут значил бы,
    # что мерка отвечает про другое поведение
    выписка = str(сырой.get("видно") or "").strip()
    if картинка is not None:
        источник = выписка
        print("  выписка модели: %s"
              % (repr(выписка)[:120] if выписка else "ПУСТА — отсева не будет"))
    else:
        источник = описание

    строки = разложить(черновик, источник)
    if not строки:
        print("  ПОЛЕЙ НЕ ЗАПОЛНЕНО НИ ОДНОГО")
    for с in строки:
        метка = "  " if с["источник"] == "прочитано" else "!!"
        print("  %s %-18s %-34s %s"
              % (метка, ПОДПИСЬ[с["поле"]], repr(с["значение"])[:34],
                 с["источник"]))
    из_памяти = [с for с in строки if с["источник"] != "прочитано"]
    print("  ── ДО ЗАСЛОНА: полей %d, из памяти %d"
          % (len(строки), len(из_памяти)))

    # ── ЧТО ПЕРЕЖИЛО БОЕВОЙ ЗАСЛОН ──────────────────────────────────
    #
    # Зовётся ТА ЖЕ функция, что на бою. Своя копия отсева печатала бы
    # число про поведение, которого у владельца нет
    if источник:
        после, отсеяно = M._апт_отсеять_домыслы(черновик, источник)
    else:
        после, отсеяно = черновик, []
    осталось = разложить(после, источник)
    ещё_память = [с for с in осталось if с["источник"] != "прочитано"]
    print("  ── ПОСЛЕ ЗАСЛОНА: полей %d, из памяти %d%s"
          % (len(осталось), len(ещё_память),
             ("   отсеяно: " + ", ".join(ПОДПИСЬ.get(к, к) for к in отсеяно))
             if отсеяно else ""))
    if черновик.get("вопрос"):
        print("  вопрос модели: %r" % черновик["вопрос"])
    return {"до": строки, "после": осталось, "отсеяно": отсеяно,
            "выписка_пуста": (картинка is not None and not выписка)}


def _повторов() -> int:
    """Сколько раз прогнать каждый сценарий.

    ОДИН ПРОГОН НЕ ОТЛИЧАЕТ ДЕФЕКТ ОТ РАЗБРОСА МОДЕЛИ. `temperature`
    у разбора 0.1, то есть разброс мал, но не ноль, — а вывод «модель
    дополняет по памяти» стоит того, чтобы его подтвердить трижды.
    """
    if "--повторов" in sys.argv:
        return max(1, int(sys.argv[sys.argv.index("--повторов") + 1]))
    return 1


async def главное():
    контроль = "--контроль" in sys.argv
    повторов = _повторов()
    print("=" * 70)
    print("ЗАВЕДЕНИЕ КАРТОЧКИ: ОТКУДА ВЗЯЛОСЬ КАЖДОЕ ПОЛЕ")
    print("=" * 70)
    print("модель разбора: %s, прогонов на сценарий: %d"
          % (M.ANALYZE_MODEL, повторов))

    if контроль:
        return await контроль_признака()

    if повторов > 1:
        return await много_прогонов(повторов)

    итог = {}
    итог["фото, вещество НАПЕЧАТАНО"] = await сценарий(
        "фото, вещество НАПЕЧАТАНО на упаковке", ПОДСКАЗКА_ФОТО,
        что_на_картинке="\n".join(т for т, _ in ФОТО_С_ВЕЩЕСТВОМ),
        картинка=нарисовать(ФОТО_С_ВЕЩЕСТВОМ))

    итог["фото, вещества НЕТ"] = await сценарий(
        "фото, вещества на упаковке НЕТ", ПОДСКАЗКА_ФОТО,
        что_на_картинке="\n".join(т for т, _ in ФОТО_БЕЗ_ВЕЩЕСТВА),
        картинка=нарисовать(ФОТО_БЕЗ_ВЕЩЕСТВА))

    итог["текст без вещества"] = await сценарий(
        "ТЕКСТ: название и количество, вещества НЕТ", ТЕКСТ_БЕЗ_ВЕЩЕСТВА)

    итог["текст, выдуманное название"] = await сценарий(
        "ТЕКСТ: ВЫДУМАННОЕ название", ТЕКСТ_ВЫДУМАННЫЙ)

    print("\n" + "=" * 70)
    print("ИТОГ")
    print("=" * 70)
    for имя, исход in итог.items():
        if исход is None:
            print("  %-32s — сценарий не отработал" % имя)
            continue
        до = [с for с in исход["до"] if с["источник"] != "прочитано"]
        после = [с for с in исход["после"] if с["источник"] != "прочитано"]
        print("  %-32s ДО: полей %d, из памяти %d   ПОСЛЕ: полей %d, "
              "из памяти %d%s"
              % (имя, len(исход["до"]), len(до), len(исход["после"]),
                 len(после),
                 ("  → " + ", ".join(ПОДПИСЬ[с["поле"]] for с in до))
                 if до else ""))
    return 0


async def много_прогонов(повторов: int):
    """Тот же набор N раз — чтобы «дополняет по памяти» не оказалось
    разбросом модели. Печатается доля прогонов, где поле пришло
    из памяти, а не один исход."""
    набор = [
        ("фото, вещество НАПЕЧАТАНО", ПОДСКАЗКА_ФОТО,
         "\n".join(т for т, _ in ФОТО_С_ВЕЩЕСТВОМ),
         нарисовать(ФОТО_С_ВЕЩЕСТВОМ)),
        ("фото, вещества НЕТ", ПОДСКАЗКА_ФОТО,
         "\n".join(т for т, _ in ФОТО_БЕЗ_ВЕЩЕСТВА),
         нарисовать(ФОТО_БЕЗ_ВЕЩЕСТВА)),
        ("текст без вещества", ТЕКСТ_БЕЗ_ВЕЩЕСТВА, None, None),
        ("текст, выдуманное название", ТЕКСТ_ВЫДУМАННЫЙ, None, None),
    ]
    счёт = {имя: [] for имя, *_ in набор}
    for н in range(повторов):
        print("\n╔═══ ПРОГОН %d из %d ═══" % (н + 1, повторов))
        for имя, описание, картинка_текст, картинка in набор:
            счёт[имя].append(
                await сценарий(имя, описание, картинка_текст, картинка))
    print("\n" + "=" * 70)
    print("ИТОГ ПО %d ПРОГОНАМ" % повторов)
    print("=" * 70)
    for имя, исходы in счёт.items():
        живых = [и for и in исходы if и is not None]
        def _память(и, где):
            return [ПОДПИСЬ[с["поле"]] for с in и[где]
                    if с["источник"] != "прочитано"]
        до = [и for и in живых if _память(и, "до")]
        после = [и for и in живых if _память(и, "после")]
        поля = sorted({п for и in живых for п in _память(и, "до")})
        пустых = sum(1 for и in живых if и["выписка_пуста"])
        print("  %-32s ДО: %d из %d прогонов, ПОСЛЕ: %d из %d%s%s"
              % (имя, len(до), len(живых), len(после), len(живых),
                 ("  → " + ", ".join(поля)) if поля else "",
                 ("  [выписка пуста в %d]" % пустых) if пустых else ""))
    return 0


async def контроль_признака():
    """ПОДЛОГ КЛАДЁТСЯ В ОТВЕТ МОДЕЛИ, живых вызовов 0.

    Признак «след во вводе» обязан разделять в ОБЕ стороны: выдуманное
    вещество назвать памятью, прочитанное — пропустить. Проверка только
    первой половины прошла бы и у признака, который объявляет памятью
    ВСЁ подряд.
    """
    print("\nКОНТРОЛЬ ПРИЗНАКА «след во вводе» — живых вызовов 0\n")
    случаи = [
        ("вещество, которого во вводе НЕТ",
         {"name": "Цитрамон П", "substance": "Ацетилсалициловая кислота",
          "form": "tablet", "qty_total": 10},
         "занеси Цитрамон П, 10 таблеток", "substance", "ИЗ ПАМЯТИ МОДЕЛИ"),
        ("вещество, которое во вводе ЕСТЬ",
         {"name": "Цитрамон П", "substance": "Парацетамол 180 мг",
          "form": "tablet", "qty_total": 10},
         "занеси Цитрамон П, парацетамол 180 мг, 10 таблеток",
         "substance", "прочитано"),
        ("форма названа СЛОВОМ, id другой",
         {"name": "Терафлю", "form": "sachet", "qty_total": 12},
         "занеси Терафлю, 12 пакетиков", "form", "прочитано"),
        ("количество из ввода",
         {"name": "Терафлю", "qty_total": 12},
         "занеси Терафлю, 12 пакетиков", "qty_total", "прочитано"),
        # СЛУЧАЙ, НА КОТОРОМ МЕРКА СОВРАЛА ЧЕТЫРЬМЯ НАХОДКАМИ.
        # Единица `tablet` пишется в ответе латиницей, а во вводе
        # стоит «10 таблеток»: без склонений из `medkit_defs` признак
        # объявляет памятью законный разбор. Стоит ЗДЕСЬ, а не в прозе,
        # потому что имя ключа в чужом модуле может смениться снова
        ("единица названа СЛОВОМ, id латиницей",
         {"name": "Цитрамон П", "unit": "tablet", "qty_total": 10},
         "занеси Цитрамон П, 10 таблеток", "unit", "прочитано"),
        ("единица, которой во вводе НЕТ",
         {"name": "Цитрамон П", "unit": "ml"},
         "занеси Цитрамон П, 10 таблеток", "unit", "ИЗ ПАМЯТИ МОДЕЛИ"),
        ("срок, которого во вводе НЕТ",
         {"name": "Терафлю", "expires_ym": "2028-09"},
         "занеси Терафлю, 12 пакетиков", "expires_ym", "ИЗ ПАМЯТИ МОДЕЛИ"),
    ]
    ошибок = 0
    for имя, черновик, ввод, поле, ждём in случаи:
        строки = разложить(черновик, ввод)
        сказано = next((с["источник"] for с in строки if с["поле"] == поле),
                       "ПОЛЕ НЕ РАЗОБРАНО")
        ок = сказано == ждём
        ошибок += 0 if ок else 1
        print("  %s %-38s %-14s ждали %-16s сказано %s"
              % ("OK  " if ок else "ПЛОХО", имя, поле, ждём, сказано))
    print("\n  случаев %d, разошлось %d" % (len(случаи), ошибок))
    print("  %s" % ("признак РАЗДЕЛЯЕТ в обе стороны" if not ошибок
                    else "ПРИЗНАК НЕ РАЗДЕЛЯЕТ — мерке веры нет"))
    ошибок += контроль_заслона()
    return 0


def доказать_подлог(черновик: dict, поле: str) -> bool:
    """НЕЗАВИСИМЫЙ замер: было ли поле в черновике ДО отсева.

    Не «проба нашла», а «подлогу есть что ломать» (§6.0.3). Вердикт
    «отсеяно» на поле, которого в черновике не было, значил бы, что
    контроль прошёл на пустом месте: заслон ничего не сделал, а числа
    сошлись. Объявлена ИМЕНЕМ ровно затем, чтобы опись
    `check_controls.py` видела доказательство, а не рассказ о нём.
    """
    return поле in черновик


def контроль_заслона() -> int:
    """ПОДЛОГ КЛАДЁТСЯ В ОТВЕТ МОДЕЛИ, боевая функция отсева зовётся как есть.

    ЗАЧЕМ ОТДЕЛЬНО ОТ ПРИЗНАКА. После правки промпта модель перестала
    дополнять по памяти — живой прогон даёт 0 из 3 ещё ДО заслона.
    То есть на живых данных заслон не срабатывает ни разу, и «домыслов
    нет» у него неотличимо от «заслон слеп» (§6.0.3). Доказать его
    может только подлог.

    ДОКАЗАТЕЛЬСТВО НЕЗАВИСИМО ОТ ВЕРДИКТА: рядом печатается, что
    подлог собирался изменить, — было ли поле в черновике ДО отсева.
    «0 находок → 1 находка» это тот же вердикт, напечатанный дважды.
    """
    print("\nКОНТРОЛЬ ЗАСЛОНА `_апт_отсеять_домыслы` — живых вызовов 0\n")
    выписка = "ЦИТРАМОН П таблетки 10 таблеток Годен до 09.2028"
    случаи = [
        ("вещество из памяти — на упаковке его НЕТ",
         {"name": "Цитрамон П", "substance": "Ацетилсалициловая кислота",
          "form": "tablet", "unit": "tablet", "qty_total": 10},
         выписка, "substance", True),
        ("вещество НАПЕЧАТАНО на упаковке",
         {"name": "Цитрамон П", "substance": "Парацетамол 180 мг",
          "form": "tablet", "qty_total": 10},
         выписка + " Парацетамол 180 мг", "substance", False),
        ("срок, которого на упаковке НЕТ",
         {"name": "Цитрамон П", "expires_ym": "2031-04"},
         выписка, "expires_ym", True),
        ("срок, который НАПЕЧАТАН",
         {"name": "Цитрамон П", "expires_ym": "2028-09"},
         выписка, "expires_ym", False),
        ("количество из памяти",
         {"name": "Цитрамон П", "qty_total": 24},
         выписка, "qty_total", True),
    ]
    ошибок = 0
    for имя, черновик, источник, поле, ждём_отсева in случаи:
        было = доказать_подлог(черновик, поле)
        после, отсеяно = M._апт_отсеять_домыслы(dict(черновик), источник)
        отсеяли = поле in отсеяно
        ок = было and (отсеяли == ждём_отсева)
        ошибок += 0 if ок else 1
        print("  %s %-40s поле в черновике ДО: %-5s отсеян: %-5s ждали: %s"
              % ("OK  " if ок else "ПЛОХО", имя, было, отсеяли,
                 ждём_отсева))
        if не_осталось := (ждём_отсева and поле in после):
            print("       ПОДЛОГ НЕ СОСТОЯЛСЯ: поле осталось в черновике")
            ошибок += 1
        del не_осталось
    print("\n  случаев %d, разошлось %d" % (len(случаи), ошибок))
    print("  %s" % ("заслон ЛОВИТ домысел и ПРОПУСКАЕТ прочитанное"
                    if not ошибок else "ЗАСЛОН НЕ РАЗДЕЛЯЕТ"))
    return ошибок



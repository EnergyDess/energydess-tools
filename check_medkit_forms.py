"""ЧТО ЛЕЖИТ В ЗАВЕДЁННЫХ КАРТОЧКАХ: ФОРМА, ЕДИНИЦА, ШТРИХ-КОД.

═══════════════════════════════════════════════════════════════════════
ЧТО ЭТО И ЧЕМ НЕ ЯВЛЯЕТСЯ
═══════════════════════════════════════════════════════════════════════

МЕРКА, код возврата всегда 0. «Сколько позиций описаны не той формой» —
свойство ЧУЖИХ данных и чужого справочника, а не нашего кода: порога
тут назначать нечему.

НИЧЕГО НЕ ПРАВИТ И НЕ УДАЛЯЕТ. База открывается ТОЛЬКО НА ЧТЕНИЕ
(mode=ro), путь с /data/ отвергается до первого запроса. Решение
по каждой позиции принимает владелец — это его упаковки, и что
на них напечатано, видно только ему.

═══════════════════════════════════════════════════════════════════════
ДВА ВОПРОСА, ОДИН ЗАМЕР (BACKLOG №238, A.5 и D.1)
═══════════════════════════════════════════════════════════════════════

Постановка задаёт их порознь, а отвечает на них одно действие:

  A.5 «у скольких позиций форма выглядит неподходящей» — наша форма
      не описывает то, что лежит дома;
  D.1 «сколько позиций не находят схему ТОЛЬКО из-за формулировки
      формы» — наша форма не совпала со словом справочника, хотя
      препарат тот же самый.

Разница — в том, ЧТО ИМЕННО расходится. Если справочник знает препарат
и предлагает выпуск, слово которого не совпало с нашей формой, это либо
(а) у нас записана не та форма — случай A.5, либо (б) формы одинаковые,
а слова разные — случай D.1. Отличает их ПОДОБИЕ СПОСОБА ПРИЁМА:
«спрей» и «раствор для местного применения» — одно средство разными
словами, «капсулы» и «раствор» — нет. Решает это человек, а не мерка.

═══════════════════════════════════════════════════════════════════════
ПОЧЕМУ СОПОСТАВЛЕНИЕ БЕРЁТСЯ У БОЕВОГО КОДА
═══════════════════════════════════════════════════════════════════════

medkit_dosage.форма_совпала — та же функция, которой пользуется сервер.
Держи мерка свой разбор, её «расходится 7» относилось бы к поведению,
которого на бою нет (§6.0.7, довод check_medkit_all).

КЕШ СТРАНИЦ берётся у check_medkit_all ИМПОРТОМ: два прогона (до правки
и после) обязаны видеть ОДНУ выдачу, иначе разница «было 7, стало 2»
может оказаться правкой чужого сайта.

═══════════════════════════════════════════════════════════════════════
ЧЕГО МЕРКА НЕ ВИДИТ, И ЭТО НАЗВАНО
═══════════════════════════════════════════════════════════════════════

Позицию, которой справочник не знает ВООБЩЕ (добавки — 15 из 21
по замеру задачи 206), она не берёт: сравнивать не с чем. Форма там
может быть какой угодно неверной, и узнать это можно только с упаковки.

ЗАПУСК

    py check_medkit_forms.py --база <копия боевой базы>
    py check_medkit_forms.py --база <копия> --сеть   # без кеша
"""
import asyncio
import os
import sqlite3
import sys
import urllib.parse

# `reconfigure`, А НЕ ПОДМЕНА ОБЁРТКИ, и это записанная ловушка
# (CLAUDE.md §3, `shots_medkit_223.py`): соседний инструмент, который
# мы импортируем ниже, ставит СВОЙ `sys.stdout = TextIOWrapper(...)`,
# прежняя обёртка уходит в сборку мусора и ЗАКРЫВАЕТ общий буфер —
# первая же печать после импорта падает `I/O operation on closed file`.
# Поймано первым прогоном.
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
os.environ.setdefault("DB_PATH", "app.db")

import main                                              # noqa: E402
import medkit_dosage as дозы                             # noqa: E402
import medkit_defs as опр                                # noqa: E402
import check_medkit_all as всё                           # noqa: E402

ФОРМА_РУС = {ф["id"]: ф["имя"] for ф in опр.ФОРМЫ}

# ── ПЕРЕЧНЯ ПАР «НАША ФОРМА ↔ СЛОВО СПРАВОЧНИКА» ЗДЕСЬ НЕТ ───────────
#
# Соблазн был: выписать «спрей ↔ раствор для местного применения»
# и считать их совпадением. Но такой список — правило ОСЛАБЛЕНИЯ
# заслона, а заслон формы это тот самый код, который не даёт подставить
# схему свечей на таблетки. Заводить его вслепую, ДО замера, значит
# ослабить проверку раньше, чем узнал, нужно ли это, — постановка D.2
# прямо требует обратного порядка: сперва посчитать пары, потом решать.
#
# Поэтому мерка ПАРЫ ПЕЧАТАЕТ, а решение принимает человек.


def _база():
    if "--база" in sys.argv:
        п = sys.argv[sys.argv.index("--база") + 1]
    else:
        п = os.getenv("DB_PATH", "app.db")
    if "/data/" in п.replace(chr(92), "/"):
        print("БОЕВАЯ БАЗА НЕ ОТКРЫВАЕТСЯ. Снимите копию и укажите её.")
        sys.exit(0)
    return п


def позиции(путь):
    """Только чтение. Ни одного запроса на запись здесь нет."""
    c = sqlite3.connect("file:%s?mode=ro" % путь.replace(chr(92), "/"),
                        uri=True)
    c.row_factory = sqlite3.Row
    # КОЛОНКИ ОБЪЁМА СПРАШИВАЮТСЯ, А НЕ ПРЕДПОЛАГАЮТСЯ. Мерка ходит
    # по КОПИИ боевой базы, а копию снимают ДО выкатки: запрос,
    # написанный под новую схему, падал бы `no such column` ровно
    # на том прогоне, ради которого он и нужен — «что там лежало
    # до правки».
    есть = {с[1] for с in c.execute("PRAGMA table_info(medkit_items)")}
    поля = ["id", "name", "substance", "form", "unit", "qty_total", "dose",
            "code_gtin", "dosage_text", "dosage_miss_kind"]
    объёмные = [с for с in ("volume", "volume_unit") if с in есть]
    строки = c.execute("SELECT %s FROM medkit_items ORDER BY id"
                       % ", ".join(поля + объёмные)).fetchall()
    c.close()
    пусто = {с: None for с in ("volume", "volume_unit") if с not in есть}
    return [dict(dict(с), **пусто) for с in строки]


async def выпуски(поз):
    """Какие выпуски предлагает справочник по этому названию.

    Ходит ТЕМ ЖЕ путём, что сервер: имена для поиска, выдача, строки
    таблицы. Своего запроса не строит.
    """
    имена = дозы.имена_для_поиска(поз["name"])
    if not имена:
        return "название не разобралось", []
    import httpx
    async with httpx.AsyncClient(follow_redirects=True, timeout=30.0) as кл:
        выдача = await main._апт_страница(
            кл, дозы.ИСТОЧНИК_ПОИСК % urllib.parse.quote(имена[0]))
    if not выдача:
        return "справочник не ответил", []
    if not дозы.справочник_знает(выдача):
        return "справочник не знает названия", []
    пары, _ = дозы._строки_выдачи(выдача)
    return None, [о for _, о in пары if о]


def чужая_форма(опис):
    """Какие НАШИ формы узнают себя в этом описании выпуска."""
    return [ф["id"] for ф in опр.ФОРМЫ if дозы.форма_совпала(ф["id"], опис)]


async def главное():
    путь = _база()
    if "--сеть" not in sys.argv:
        всё.включить_кеш()
        print("[кеш] страницы берутся из %s" % всё.КЕШ)
    поз = позиции(путь)
    print("=" * 72)
    print("ФОРМА ВЫПУСКА: НАША ПРОТИВ СПРАВОЧНИКА")
    print("=" * 72)
    print("позиций в базе: %d" % len(поз))
    print()

    расхождения, не_знает, совпало, пусто = [], 0, 0, 0
    пары = {}
    for п in поз:
        причина, опис_список = await выпуски(п)
        if причина:
            не_знает += 1
            continue
        if not опис_список:
            пусто += 1
            continue
        наши_совпали = [о for о in опис_список
                        if дозы.форма_совпала(п["form"], о)]
        if наши_совпали:
            совпало += 1
            continue
        # НАША ФОРМА НЕ УЗНАЛА СЕБЯ НИ В ОДНОМ ВЫПУСКЕ. Смотрим, какая
        # УЗНАЛА БЫ: если чужая форма совпадает, значит расходится
        # СЛОВО, а не средство
        варианты = {}
        for о in опис_список:
            for ф in чужая_форма(о):
                варианты.setdefault(ф, о)
        if not варианты:
            # Ни одна наша форма не описывает то, что предлагает
            # справочник, — это НЕ пара слов, а дыра в списке форм
            варианты = {"—": опис_список[0]}
        расхождения.append((п, варианты))
        for ф, о in варианты.items():
            пары.setdefault((п["form"], ф), []).append(о)

    print("── ИТОГ ───────────────────────────────────────────────────")
    print("  наша форма совпала с выпуском справочника: %d" % совпало)
    print("  справочник названия не знает (сравнивать не с чем): %d"
          % не_знает)
    print("  выдача пуста: %d" % пусто)
    print("  ФОРМА РАСХОДИТСЯ: %d" % len(расхождения))
    print()
    if расхождения:
        print("── ЧТО РАСХОДИТСЯ (id — наша форма → формы выдачи) ────────")
        for п, варианты in расхождения:
            чужие = ", ".join(ФОРМА_РУС.get(ф, ф) for ф in варианты)
            print("  id %-4d %-30s → %s"
                  % (п["id"], ФОРМА_РУС.get(п["form"], п["form"]), чужие))
        print()
        print("── ПАРЫ СЛОВ (наша форма ↔ форма справочника), D.1 ───────")
        for (наша, чужая), примеры in sorted(пары.items(),
                                             key=lambda x: -len(x[1])):
            print("  %2d  %-30s ↔ %s"
                  % (len(примеры), ФОРМА_РУС.get(наша, наша),
                     ФОРМА_РУС.get(чужая, чужая)))
            print("      пример выдачи: %s" % примеры[0][:96])
    print()
    print("── ЕДИНИЦА ПРИЁМА (A.5, вторая половина) ─────────────────")
    # ЖИДКОСТЬ, СЧИТАЕМАЯ МИЛЛИЛИТРАМИ, — НЕ ДЕФЕКТ САМ ПО СЕБЕ: сироп
    # законно меряют миллилитрами. Кандидат — тот, у кого в тексте
    # назван ДРУГОЙ способ отмеривания (капли, дозы), а единица объёмная
    кап = 0
    for п in поз:
        текст = опр.нормаль(" ".join(str(п[k] or "")
                                     for k in ("name", "substance")))
        if п["unit"] == "ml" and ("капл" in текст or "доз" in текст):
            кап += 1
            print("  id %-4d %-24s единица «мл», а в тексте назван другой "
                  "способ отмеривания"
                  % (п["id"], ФОРМА_РУС.get(п["form"], п["form"])))
    if not кап:
        print("  единица объёма стоит вместо единицы приёма: 0")
    без_объёма = sum(1 for п in поз
                     if п["unit"] in ("drop", "dose", "spoon")
                     and not п["volume"])
    считают = sum(1 for п in поз if п["unit"] in ("drop", "dose", "spoon"))
    print("  считают каплями/дозами/ложками: %d, из них объём упаковки "
          "НЕ записан: %d" % (считают, без_объёма))
    print()
    print("── ШТРИХ-КОД: ВСЕ ЛИ ПРИВЕДЕНЫ К ОДНОМУ ВИДУ (C.5) ────────")
    # ПРИВЕДЁННЫЙ КОД — ЭТО GTIN-14, и проверяется он ТОЙ ЖЕ функцией,
    # которой сервер разбирает и сканер, и поле формы. Своего правила
    # тут нет: разойдись оно с боевым, мерка сказала бы «все приведены»
    # про вид, которого система не ждёт
    с_кодом = [п for п in поз if (п["code_gtin"] or "").strip()]
    кривые = []
    for п in с_кодом:
        сырой = п["code_gtin"].strip()
        приведённый = опр.gtin_из_кода(сырой)
        if приведённый != сырой:
            кривые.append((п["id"], сырой, приведённый))
    print("  позиций со штрих-кодом: %d из %d" % (len(с_кодом), len(поз)))
    print("  ПРИВЕДЕНЫ К GTIN-14: %d" % (len(с_кодом) - len(кривые)))
    print("  НЕ ПРИВЕДЕНЫ: %d" % len(кривые))
    for ид, сырой, привед in кривые:
        print("     id %-4d длина %2d → %s"
              % (ид, len(сырой),
                 ("стало бы %d знаков" % len(привед)) if привед
                  else "не разбирается вовсе"))
    if с_кодом and not кривые:
        print("  (несимметрии «сканер против рук» в базе нет: любой "
              "из путей ввода даёт один и тот же GTIN-14)")
    print()
    print("НИЧЕГО НЕ ИЗМЕНЕНО: база открывалась только на чтение.")


if __name__ == "__main__":
    asyncio.run(главное())

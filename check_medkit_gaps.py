import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
os.environ.setdefault("DB_PATH", "app.db")
import main  # noqa: E402

ПЛОХО = []


def шаг(имя, ок, что=""):
    print("%-5s %-52s %s" % ("OK" if ок else "ПЛОХО", имя, что))
    if not ок:
        ПЛОХО.append(имя)


# ── ОБРАЗЦЫ КАРТОЧЕК. Условные имена: файл в сеть НЕ ХОДИТ (класс-тест
# задачи 234 запрещает условные имена только тем, кто спрашивает
# чужой справочник), а настоящее имя тут было бы утечкой (§5.1).
ПОКАЗАНИЕ = ("Симптоматическая терапия при повышенной возбудимости, "
             "раздражительности, нарушениях засыпания.")
ПОЛНАЯ = {"id": 1, "name": "Препарат А", "substance": "вещество А",
          "дозы": "по 1 таблетке", "своя_схема": "", "показания": ПОКАЗАНИЕ,
          "своё_от_чего": "", "категории": [7], "photo": "",
          "группа_пачек": 1}
БЕЗ_ВСЕГО = {"id": 2, "name": "Препарат Б", "substance": "",
             "дозы": "", "своя_схема": "", "показания": "",
             "своё_от_чего": "", "категории": [], "photo": "",
             "группа_пачек": 1}
БЕЗ_КАТЕГОРИИ = dict(ПОЛНАЯ, id=3, name="Препарат В", категории=[])
СВОЯ_ЗАПИСЬ = dict(БЕЗ_ВСЕГО, id=4, name="Препарат Г",
                   своя_схема="по 1 ложке", своё_от_чего=ПОКАЗАНИЕ,
                   substance="вещество Г", категории=[7])


def признак():
    """Разделяет ли `_апт_долги_карточки` в обе стороны."""
    print("\n── ПРИЗНАК ДОЛГА ─────────────────────────────────────────")
    шаг("полная-карточка-долга-не-имеет",
        main._апт_долги_карточки(ПОЛНАЯ) == [],
        "долгов %d" % len(main._апт_долги_карточки(ПОЛНАЯ)))
    все = main._апт_долги_карточки(БЕЗ_ВСЕГО)
    шаг("пустая-карточка-должна-по-всем-видам",
        set(все) == {в for в, _п, _к in main.АПТ_ВИДЫ_ДОЛГА},
        ", ".join(все))
    шаг("нет-только-категории-—-долг-один",
        main._апт_долги_карточки(БЕЗ_КАТЕГОРИИ) == ["категория"])
    # СВОЯ ЗАПИСЬ С УПАКОВКИ СЧИТАЕТСЯ ЗАПОЛНЕННЫМ ПОЛЕМ: человек её
    # ВНЁС, и звать его дозаполнить то, что он уже вписал, — тот же
    # немой отказ наизнанку.
    шаг("своя-запись-закрывает-долг-схемы-и-показаний",
        main._апт_долги_карточки(СВОЯ_ЗАПИСЬ) == [],
        ", ".join(main._апт_долги_карточки(СВОЯ_ЗАПИСЬ)) or "долгов нет")


def _разбор(ответ, тексты=None, имена=("Успокоительное и сон", "ЖКТ")):
    тексты = тексты or {3: [(ПОКАЗАНИЕ, "справочник")]}
    return main._апт_кат_предложения_из_ответа(ответ, тексты, list(имена))


def контроль():
    """Четыре подлога, четвёртый ОБРАТНЫЙ. У каждого доказательство."""
    print("\n── ЗАСЛОН ПРЕДЛОЖЕНИЯ КАТЕГОРИИ ──────────────────────────")
    цитата = ПОКАЗАНИЕ[10:60]

    print("\nПОДЛОГ 1 — предложение БЕЗ цитаты")
    ответ = {"предложения": [{"id": 3, "раздел": "Успокоительное и сон",
                              "цитата": ""}]}
    док = len(ответ["предложения"][0]["цитата"])
    вышло = _разбор(ответ)
    print("  ДОКАЗАТЕЛЬСТВО: знаков в цитате %d (обязан быть 0)" % док)
    шаг("без-цитаты-отброшено", док == 0 and вышло == [],
        "прошло %d" % len(вышло))

    print("\nПОДЛОГ 2 — цитата из ЧУЖОЙ позиции")
    чужое = "Применяется при изжоге и тяжести в желудке."
    ответ = {"предложения": [{"id": 3, "раздел": "ЖКТ", "цитата": чужое}]}
    док = чужое in ПОКАЗАНИЕ
    вышло = _разбор(ответ)
    print("  ДОКАЗАТЕЛЬСТВО: цитата встречается в показаниях позиции: %s"
          % ("ДА" if док else "НЕТ"))
    шаг("чужая-цитата-отброшена", not док and вышло == [],
        "прошло %d" % len(вышло))

    print("\nПОДЛОГ 3 — раздел ВНЕ набора")
    ответ = {"предложения": [{"id": 3, "раздел": "Космос",
                              "цитата": цитата}]}
    вышло = _разбор(ответ)
    print("  ДОКАЗАТЕЛЬСТВО: раздел «Космос» в наборе: %s"
          % ("ДА" if "Космос" in ("Успокоительное и сон", "ЖКТ") else "НЕТ"))
    шаг("чужой-раздел-отброшен", вышло == [], "прошло %d" % len(вышло))

    print("\nПОДЛОГ 4 — ОБРАТНЫЙ: законное предложение обязано ПРОЙТИ")
    ответ = {"предложения": [{"id": 3, "раздел": "Успокоительное и сон",
                              "цитата": цитата}]}
    док = цитата in ПОКАЗАНИЕ
    вышло = _разбор(ответ)
    print("  ДОКАЗАТЕЛЬСТВО: цитата дословно есть в показаниях: %s, знаков %d"
          % ("ДА" if док else "НЕТ", len(цитата)))
    шаг("законное-предложение-прошло", док and len(вышло) == 1,
        "прошло %d" % len(вышло))
    if вышло:
        шаг("метка-источника-названа", вышло[0]["откуда"] == "справочник",
            вышло[0]["откуда"])

    print("\nПОДЛОГ 5 — номер ВНЕ посланного набора")
    ответ = {"предложения": [{"id": 999, "раздел": "ЖКТ",
                              "цитата": цитата}]}
    вышло = _разбор(ответ)
    print("  ДОКАЗАТЕЛЬСТВО: номер 999 среди посланных: НЕТ")
    шаг("чужой-номер-отброшен", вышло == [], "прошло %d" % len(вышло))


if __name__ == "__main__":
    print("=" * 70)

def _три_состояния(путь):
    """B.3: сколько позиций может попасть в группу, а сколько нет."""
    if "/data/" in путь.replace("\\", "/"):
        print("БОЕВАЯ БАЗА НЕ ОТКРЫВАЕТСЯ. Снимите копию.")
        return
    с = sqlite3.connect("file:%s?mode=ro" % путь.replace("\\", "/"), uri=True)
    всего = с.execute("SELECT COUNT(*) FROM medkit_items").fetchone()[0]
    с_пок = с.execute(
        "SELECT COUNT(*) FROM medkit_items WHERE indications_text IS NOT NULL"
        " AND TRIM(indications_text) <> ''").fetchone()[0]
    спрашивали = с.execute(
        "SELECT COUNT(*) FROM medkit_items"
        " WHERE indications_blocks IS NOT NULL").fetchone()[0]
    дл = [r[0] for r in с.execute(
        "SELECT LENGTH(indications_text) FROM medkit_items"
        " WHERE indications_text IS NOT NULL AND TRIM(indications_text)<>''")]
    дл.sort()
    print("ТРИ СОСТОЯНИЯ ПОКАЗАНИЙ (B.3), база: %s" % os.path.basename(путь))
    print("=" * 70)
    print("  позиций всего                       %d" % всего)
    print("  показания ЕСТЬ (могут попасть в группу)   %d" % с_пок)
    print("  показаний НЕТ (в группу не попадут)       %d" % (всего - с_пок))
    print("     из них СПРАШИВАЛИ и не нашли           %d"
          % max(0, спрашивали - с_пок))
    print("     из них НЕ СПРАШИВАЛИ ни разу           %d"
          % (всего - спрашивали))
    if дл:
        print("  длина показаний: медиана %d, макс %d, сумма %d"
              % (дл[len(дл) // 2], дл[-1], sum(дл)))
    print()
    print("  ЧТО ИЗ ЭТОГО СЛЕДУЕТ. Позиции без показаний в группу")
    print("  не попадут ПО ПОСТРОЕНИЮ, и назвать их «показания есть,")
    print("  но не сошлись» было бы неправдой про %d позиций из %d."
          % (всего - с_пок, всего))
    с.close()


def _прежний_отбор(путь, вопросы):
    """СКОЛЬКО ПОЗИЦИЙ ДАЛ БЫ ДОСЛОВНЫЙ ОТБОР — замер «до».

    Признак берётся у БОЕВЫХ `_апт_основы_вопроса`
    и `_апт_показание_по_вопросу` — тех самых, что делали отбор
    до задачи 245. Свой разбор дал бы число про поведение, которого
    в проекте не было (§6.0.7).

    Число ДЕТЕРМИНИРОВАНО: живой модели тут не нужно, и потому
    сравнимо между прогонами — в отличие от числа групп, которое
    зависит от ответа модели.
    """
    from main import _апт_основы_вопроса, _апт_показание_по_вопросу
    с = sqlite3.connect("file:%s?mode=ro" % путь.replace("\\", "/"), uri=True)
    позиции = [{"id": r[0], "показания": r[1] or ""} for r in с.execute(
        "SELECT id, indications_text FROM medkit_items")]
    с.close()
    print("СКОЛЬКО ДАВАЛ ПРЕЖНИЙ ДОСЛОВНЫЙ ОТБОР (замер «до», B.1)")
    print("=" * 70)
    for вопрос, _зачем in вопросы:
        основы = _апт_основы_вопроса(вопрос)
        сошлось = sum(1 for п in позиции
                      if _апт_показание_по_вопросу(п, основы))
        print("  %-42s сошлось дословно: %d из %d"
              % ('«' + вопрос[:40] + '»', сошлось, len(позиции)))
    print()


def _показания_из_базы(путь):
    """{id позиции: полный текст показаний} — для сверки цитат."""
    с = sqlite3.connect("file:%s?mode=ro" % путь.replace("\\", "/"), uri=True)
    итог = {r[0]: (r[1] or "") for r in с.execute(
        "SELECT id, indications_text FROM medkit_items")}
    с.close()
    return итог



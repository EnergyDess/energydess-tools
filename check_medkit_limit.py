def _наивный_обрывок(текст):
    """Подлог 2: «резать после любого дочитанного значения».

    Настоящая наивная версия, а не выдуманная: ровно так написал бы
    разбор тот, кто не подумал про число, обрубленное посередине.
    """
    начало = текст.find("{")
    if начало < 0:
        return None
    т = текст[начало:]
    for i in range(len(т), 0, -1):
        кусок = т[:i].rstrip().rstrip(",")
        for хвост in ("", "]}", "}", "]", "}]}"):
            try:
                г = json.loads(кусок + хвост)
            except Exception:
                continue
            if isinstance(г, dict) and (г.get("подходят") or г.get("группы")):
                return г
    return None



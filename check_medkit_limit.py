    тело = подмена if подмена is not None else _тело(ОБРЫВОК)

    class Клиент:
        def __init__(self, *a, **k):
            pass

        async def __aenter__(self):
            return self

        async def __aexit__(self, *a):
            return False

        async def post(self, *a, **k):
            class Ответ:
                @staticmethod
                def json():
                    return тело
            return Ответ()

    main.httpx.AsyncClient = Клиент
    try:
        return asyncio.run(main._апт_спросить_модель(
            "промпт", очищать=False,
            потолок=потолок or main.MEDKIT_QUERY_MAX_TOKENS,
            допустить_обрыв=обрыв, совет=совет))
    finally:
        main.httpx.AsyncClient = сохранено



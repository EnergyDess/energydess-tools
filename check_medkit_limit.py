    п("=" * 70)
    вызовы = _вызовы()
    п("  веток, зовущих модель: %d" % len(вызовы))
    без = [л for л, с in вызовы if not с]
    if без:
        п("  ПЛОХО: совет не назван в строках %s" % (без,))
        беда += 1
    тексты = [с for _л, с in вызовы if с]
    for л, с in вызовы:
        п("     строка %-6d %s" % (л, (с or "НЕ НАЗВАН")[:62]))
    if len(set(тексты)) != len(тексты):
        п("  ПЛОХО: две ветки делят один текст обрыва")
        беда += 1
    return беда, вызовы



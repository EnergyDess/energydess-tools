def _вызовы():
    """Ветки, зовущие модель, и текст обрыва у каждой.

    Разбором СИНТАКСИЧЕСКОГО ДЕРЕВА, а не грепом: строка в комментарии —
    рассказ о совете, а не совет.
    """
    дерево = ast.parse(io.open(os.path.join(КОРЕНЬ, "main.py"),
                               encoding="utf-8").read())
    вызовы = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        имя = getattr(узел.func, "id", None) or getattr(узел.func, "attr", None)
        if имя != "_апт_спросить_модель":
            continue
        совет = None
        for kw in узел.keywords:
            if kw.arg != "совет":
                continue
            зн = kw.value
            if isinstance(зн, ast.Constant):
                совет = str(зн.value)
            elif isinstance(зн, ast.JoinedStr):
                совет = " ".join(str(v.value) for v in зн.values
                                 if isinstance(v, ast.Constant))
        вызовы.append((узел.lineno, совет))
    return вызовы


def _советы(тихо=False):
    """A.1: сколько веток зовут модель и одинаков ли у них текст обрыва."""

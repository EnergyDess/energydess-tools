    print("   («ничего не найдено» на бессмыслице обязано отличаться")
    print("    от ответа на настоящее вещество, иначе признак не разделяет)")
    for имя, шаб in СПРАВОЧНИКИ:
        строки = []
        for с in ЕСТЬ + [БЕССМЫСЛИЦА]:
            try:
                r = _взять(шаб % quote(с))
            except Exception as e:
                строки.append((с, "ОШИБКА " + type(e).__name__, None))
                continue
            t = текстом(r.text)
            пусто = bool(re.search(
                r"ничего не найден|не найдено|нет результат", t, re.I))
            строки.append((с, "пусто" if пусто else "содержательно",
                           len(r.content)))
        print("  %s:" % имя)
        for с, знак, байт in строки:
            print("     %-14s %-14s %s"
                  % (с, знак, ("байт %d" % байт) if байт else ""))
        настоящие = [з for с, з, _ in строки if с != БЕССМЫСЛИЦА]
        чушь = [з for с, з, _ in строки if с == БЕССМЫСЛИЦА]
        # ── ИСХОДОВ ТРИ, А НЕ ДВА (BACKLOG №233) ────────────────────
        #
        # Здесь стояло `годен = all(...) and чушь == ["пусто"]`, то есть
        # СЕТЕВАЯ ОШИБКА печаталась как «НЕ ГОДЕН: признак не разделяет».
        # Это §6.0 в чистом виде, и хуже обычного: инструмент оценивает
        # ИСТОЧНИКИ, то есть врёт ровно про то, чему мы доверяем решения
        # о подключении. «Сайт не ответил» и «сайт отвечает одинаково
        # на всё» — разные факты с разными выводами: первый лечится
        # повтором, второй означает, что источник встроился бы немым

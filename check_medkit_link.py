def _взять(url):
    import httpx
    return httpx.get(url, timeout=25, follow_redirects=True,
                     headers={"User-Agent": UA, "Accept-Language": "ru-RU,ru;q=0.9"})


def текстом(html):
    """Разметка в обычный текст. Скрипты и стили выбрасываются ЦЕЛИКОМ:
    у `apteka.magnit.ru` внутри `<script>` лежит состояние приложения
    на четыре мегабайта, и без этого «текст страницы» состоял бы из него.
    """
    t = re.sub(r"<script.*?</script>|<style.*?</style>", " ", html, flags=re.S)
    t = re.sub(r"<[^>]+>", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def _ld(html):
    """Объекты `schema.org` со страницы — сколько их и что в них."""
    поля = set()
    сколько = 0
    for м in re.finditer(
            r"<script[^>]*application/ld\+json[^>]*>(.*?)</script>", html, re.S):
        try:
            д = json.loads(м.group(1).strip())
        except Exception:
            continue
        for о in (д if isinstance(д, list) else [д]):
            if isinstance(о, dict) and о.get("@type") in ("Product", "Drug"):
                сколько += 1
                поля |= set(о.keys())
    return сколько, поля



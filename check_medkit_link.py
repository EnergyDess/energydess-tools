def контроль():
    global СПРАВОЧНИКИ
    было = list(СПРАВОЧНИКИ)
    print("=" * 72)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: спросить НЕ УДАЛОСЬ")

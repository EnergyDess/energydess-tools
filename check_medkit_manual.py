def подлог_пишет_в_ручную(m):
    """Обход пишет найденное В ПОЛЕ РУЧНОЙ ЗАПИСИ — то есть затирает
    человека ровно тем, чего владелец и опасается."""
    родная = m._апт_записать_итог_доз

    def порченая(поз, итог, причина, вид="", подсказка=""):
        родная(поз, итог, причина, вид, подсказка)
        if итог:
            поз.own_dosage_text = итог[0]
    m._апт_записать_итог_доз = порченая
    return родная



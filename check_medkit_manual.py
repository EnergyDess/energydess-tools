def обход(m, кука, предел=0, тихо=False):
    import httpx

    async def гнать():
        транспорт = httpx.ASGITransport(app=m.app)
        async with httpx.AsyncClient(transport=транспорт,
                                     base_url="http://probe",
                                     cookies={"access_token": кука},
                                     timeout=180) as кл:
            о = await кл.get("/medkit/api/dosage/pending")
            если = о.json()
            ждут = если.get("ждут", [])
            if предел:
                ждут = ждут[:предел]
            нашлось = 0
            for i, ж in enumerate(ждут, 1):
                р = await кл.post("/medkit/api/items/%d/dosage" % ж["id"])
                т = р.json() if р.status_code == 200 else {"нет": "HTTP"}
                if not т.get("нет"):
                    нашлось += 1
                if not тихо:
                    print("   %2d/%d  %-36s %s"
                          % (i, len(ждут), (ж["name"] or "")[:36],
                             "нашлось" if not т.get("нет") else "нет"))
            return если, ждут, нашлось
    return asyncio.run(гнать())



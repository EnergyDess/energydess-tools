def вернуть_копию(врем, исх):
    """ВЕРНУТЬ КОПИЮ В ИСХОДНОЕ — И УБРАТЬ СПУТНИКИ ЖУРНАЛА.

    `shutil.copy2` по живой базе её НЕ ВОЗВРАЩАЕТ: журнал WAL остаётся
    рядом файлами `-wal` и `-shm`, и при следующем открытии страницы
    из него накатываются ПОВЕРХ подложенного файла. Первая версия
    контроля делала ровно это, и второй подлог гонялся по базе,
    где уже лежали записи первого, — то есть его «НАЙДЕН» мог
    означать чужой след. Контроль на грязной основе недействителен
    (§6.0.3); ловушка записана в §9 про восстановление базы.

    Движок закрывается ДО подмены: открытое соединение допишет
    свой хвост обратно.
    """
    import database
    database.engine.dispose()
    for хвост in ("", "-wal", "-shm"):
        if хвост and os.path.exists(врем + хвост):
            os.remove(врем + хвост)
    shutil.copy2(исх, врем)


def прогон(m, врем, кука, до, предел):
    print("\nОБХОД (боевые эндпоинты, как из браузера):")
    если, ждут, нашлось = обход(m, кука, предел)
    print("   всего %d, ждали перепроверки %d, обошли %d, схема нашлась у %d"
          % (если.get("всего", 0), len(если.get("ждут", [])), len(ждут),
             нашлось))

    после = снимок(врем)
    print()

    # A.2 — ГЛАВНОЕ: побайтно
    разошлись = [i for i in до
                 if до[i]["своя"] != после.get(i, {}).get("своя")]
    шаг("число-ручных-записей-совпало", ручных(до) == ручных(после),
        "было %d, стало %d" % (ручных(до), ручных(после)))
    шаг("каждая-ручная-запись-побайтно-та-же", not разошлись,
        "разошлось %d из %d" % (len(разошлись), ручных(до)))
    даты = [i for i in до
            if до[i]["своя_дата"] != после.get(i, {}).get("своя_дата")]
    шаг("дата-своей-записи-не-тронута", not даты, "разошлось %d" % len(даты))

    # A.3 — ручная запись не выдаётся за справочник
    подмена = [i for i in после
               if после[i]["выдержка_сырьё"]
               and после[i]["выдержка_сырьё"] == после[i]["своя_сырьё"]]
    шаг("ручная-запись-НЕ-выдана-за-выдержку", not подмена,
        "совпавших текстов %d" % len(подмена))
    чужой = [i for i in после
             if после[i]["выдержка"] != "NULL" and not после[i]["источник"]]
    шаг("у-каждой-выдержки-назван-источник", not чужой,
        "без источника %d" % len(чужой))

    пары = [i for i in после
            if после[i]["выдержка"] != "NULL" and после[i]["своя"] != "NULL"]
    шаг("обе-записи-живут-рядом", True, "позиций с ОБЕИМИ: %d" % len(пары))
    print("   выдержек было %d, стало %d" % (выдержек(до), выдержек(после)))

    плохих = sum(1 for _, л in шаги if not л)
    print("\nшагов %d, плохих %d" % (len(шаги), плохих))
    return 1 if плохих else 0


def счётчик(m, кука, предел):
    """БЛОК E — сколько ушло наружу, сколько взято из кеша, где предел.

    КЕШ ЗДЕСЬ БОЕВОЙ, А НЕ ПРОБНЫЙ: `--счётчик` НЕ подменяет
    `_апт_страница` (в отличие от обычного прогона), иначе числа
    относились бы к кешу пробы, а не к тому, что стоит на бою.
    """
    print("предел месяца: %d" % m.REF_MONTH_CAP)
    print("ПРОГОН 1 — холодный кеш")
    если, ждут, нашлось = обход(m, кука, тихо=True)
    п1 = dict(m._реф_счёт)
    print("   позиций обошли %d, схема нашлась у %d" % (len(ждут), нашлось))
    print("   ушло в сеть %(сеть)d, взято из кеша %(кеш)d" % п1)
    за_день, за_месяц, осталось = m._реф_остаток()
    print("   счётчик базы: за сутки %d, за месяц %d, осталось %d"
          % (за_день, за_месяц, осталось))
    if осталось == 0:
        print("   ПРЕДЕЛ ИСЧЕРПАН — обход обязан был остановиться")
        return 0

    print("ПРОГОН 2 — тот же обход, кеш тёплый")
    m._реф_счёт["сеть"] = 0
    m._реф_счёт["кеш"] = 0
    обход(m, кука, тихо=True)
    п2 = dict(m._реф_счёт)
    print("   ушло в сеть %(сеть)d, взято из кеша %(кеш)d" % п2)
    доля = (100.0 * п2["кеш"] / max(1, п2["кеш"] + п2["сеть"]))
    print("   из кеша во втором прогоне: %.0f%%" % доля)
    за_день2, за_месяц2, _ = m._реф_остаток()
    print("   счётчик базы вырос на %d (кеш наружу не ходит)"
          % (за_месяц2 - за_месяц))
    return 0


def контроль(m, врем, исх, кука, до):
    """A.4 — каждый подлог обязан быть НАЙДЕН и каждый ДОКАЗАН.

    ПЕРЕД КАЖДЫМ подлогом основа возвращается в исходное И СВЕРЯЕТСЯ
    с ним: «нашла» и «нашла подлог» неотличимы, когда находка лежала
    в базе ещё до него.
    """
    print("\n=== ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ===")
    найдено = 0
    for имя, положить, ждём in ПОДЛОГИ:
        вернуть_копию(врем, исх)
        чисто = снимок(врем)
        print("\n%s" % имя)
        if чисто != до:
            print("   ОСТАНОВЛЕНО: копия не вернулась в исходное")
            return 2
        родная = положить(m)
        док = ДОКАЗАТЕЛЬСТВА[имя](m)
        состоялся = док == ждём
        print("   ДОКАЗАТЕЛЬСТВО: %r (ждали %r)" % (док, ждём))
        if not состоялся:
            print("   ПОДЛОГ НЕ СОСТОЯЛСЯ — контроль недействителен")
        else:
            # ОБХОД ЦЕЛИКОМ, А НЕ ТРЕМЯ ПОЗИЦИЯМИ. Первая версия брала
            # `предел=3`, и подлог `пишет-в-ручную` НЕ СОСТОЯЛСЯ: он
            # пишет только при НАЙДЕННОЙ схеме, а первые три позиции
            # списка по алфавиту — все «нет». Подлог, которому не на чём
            # сработать, неотличим от слепой пробы (§6.0.3).
            обход(m, кука, тихо=True)
            после = снимок(врем)
            if имя == "пишет-в-ручную":
                видит = (ручных(до) != ручных(после)
                         or any(до[i]["своя"] != после.get(i, {}).get("своя")
                                for i in до))
            else:
                видит = any(после[i]["выдержка_сырьё"]
                            and после[i]["выдержка_сырьё"]
                            == после[i]["своя_сырьё"] for i in после)
            print("   проба: %s" % ("НАЙДЕН" if видит else "НЕ НАЙДЕН"))
            найдено += 1 if видит else 0
        m._апт_записать_итог_доз = родная
    вернуть_копию(врем, исх)
    print("\nподлогов %d, найдено %d" % (len(ПОДЛОГИ), найдено))
    return 0 if найдено == len(ПОДЛОГИ) else 1



def отпечаток(v):
    """Побайтный отпечаток значения колонки. NULL и пустая строка —
    РАЗНОЕ: «записи нет» и «запись стёрли» это два разных факта."""
    if v is None:
        return "NULL"
    return hashlib.sha256(v.encode("utf-8")).hexdigest()[:16] + ":%d" % len(v)


def снимок(путь):
    """Что лежит в колонках схемы у каждой позиции — ИЗ БАЗЫ, а не
    из ответа сервера: ответ показывает намерение, база — факт."""
    c = sqlite3.connect("file:%s?mode=ro" % путь.replace("\\", "/"), uri=True)
    c.row_factory = sqlite3.Row
    из = c.execute("SELECT id, name, own_dosage_text, own_dosage_at, "
                   "dosage_text, dosage_source FROM medkit_items "
                   "ORDER BY id").fetchall()
    c.close()
    return {r["id"]: {"name": r["name"],
                      "своя": отпечаток(r["own_dosage_text"]),
                      "своя_дата": str(r["own_dosage_at"]),
                      "своя_сырьё": r["own_dosage_text"],
                      "выдержка": отпечаток(r["dosage_text"]),
                      "выдержка_сырьё": r["dosage_text"],
                      "источник": r["dosage_source"]} for r in из}


def ручных(с):
    return sum(1 for д in с.values() if д["своя"] != "NULL")


def выдержек(с):
    return sum(1 for д in с.values() if д["выдержка"] != "NULL")



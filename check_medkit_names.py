def _сводка_заслона(путь):
    сеты = разрешённые_из_базы(путь)
    слов = set().union(*сеты) if сеты else set()
    несклоняемых = sum(1 for с in слов if not re.fullmatch(r"[а-я]+", _норма(с)))
    print("наборов разрешённых слов %d · слов %d (латиница, цифры, дефис: %d — "
          "генератор их не склоняет, формы только сами слова)"
          % (len(сеты), len(слов), несклоняемых))
    return сеты


def заслон_(путь):
    сеты = _сводка_заслона(путь)
    сумма = {}
    for слова, (позиции, кат) in sorted(сеты.items(), key=lambda к: len(к[0])):
        н = наборы_заслона(слова)
        for подпись, подмены in (("ДО", {"_апт_имя_знакомо": _прежнее_правило}),
                                 ("ПОСЛЕ", {})):
            with _правило(**подмены):
                знакомо, прошли, чужие = замер_звена(слова, н)
                видно = замер_видимого(позиции, кат, н)
            с = сумма.setdefault(подпись, {"форм": 0, "знакомо": 0, "чужие": set(),
                                           "прошли": {}, "выдумок": {}, "видно": {}})
            с["форм"] += len(н["формы"])
            с["знакомо"] += знакомо
            с["чужие"].update(чужие)
            for о, вв in н["выдумки"].items():
                с["прошли"][о] = с["прошли"].get(о, 0) + прошли[о]
                с["выдумок"][о] = с["выдумок"].get(о, 0) + len(вв)
            for к, ч in видно.items():
                с["видно"][к] = с["видно"].get(к, 0) + ч
    for подпись in ("ДО", "ПОСЛЕ"):
        с = сумма.get(подпись)
        if not с:
            print("%-6s наборов нет — мерить нечего" % подпись)
            continue
        print("%-6s звено: настоящих форм %d, знакомы %d · выдумок прошло: %s"
              % (подпись, с["форм"], с["знакомо"], " · ".join(
                  "%s %d/%d" % (о, с["прошли"][о], с["выдумок"][о]) for о in с["выдумок"])))
        print("%-6s видно на экране: настоящих форм %d/%d · выдумок: %s"
              % ("", с["видно"].get("форма", 0), с["форм"], " · ".join(
                  "%s %d/%d" % (о, с["видно"].get(о, 0), с["выдумок"][о])
                  for о in с["выдумок"])))
    if "ДО" in сумма and "ПОСЛЕ" in сумма:
        потеряно = сумма["ПОСЛЕ"]["чужие"] - сумма["ДО"]["чужие"]
        обретено = сумма["ДО"]["чужие"] - сумма["ПОСЛЕ"]["чужие"]
        print("настоящих форм, знакомых ДО и чужих ПОСЛЕ (цена сужения): %d · "
              "чужих ДО и знакомых ПОСЛЕ: %d" % (len(потеряно), len(обретено)))
        if потеряно and "--подробно" in sys.argv:
            print("   потеряны: %s" % ", ".join(sorted(потеряно)))
    return 0



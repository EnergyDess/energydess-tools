def прежняя(ревизия, без_дописанного=False):
    исходник = subprocess.run(["git", "show", "%s:main.py" % ревизия],
                              capture_output=True, check=True).stdout.decode("utf-8")
    куски = []
    for у in ast.parse(исходник).body:
        имя = (у.name if isinstance(у, ast.FunctionDef) else
               у.targets[0].id if isinstance(у, ast.Assign)
               and isinstance(у.targets[0], ast.Name) else None)
        if имя in НУЖНЫ:
            куски.append(ast.get_source_segment(исходник, у))
    место = {"re": re, "_апт_опр": main._апт_опр}
    exec("\n\n".join(куски), место)

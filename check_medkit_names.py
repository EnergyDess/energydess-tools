def _все_хвосты(имя):
    буквы = "абвгдежзийклмнопрстуфхцчшщыьэюя"
    return tuple(буквы) + tuple(a + b for a in буквы for b in буквы)


def контроль(позиции, имена, н):
    итог = True
    # 1. НЕЗАВИСИМОСТЬ ГЕНЕРАТОРА — разбор дерева
    дерево = ast.parse(open(__file__, encoding="utf-8").read())
    обращений = sum(1 for у in дерево.body if isinstance(у, ast.FunctionDef)
                    and у.name in ГЕНЕРАТОР
                    for х in ast.walk(у) if isinstance(х, ast.Name) and х.id == "main")
    print("НЕЗАВИСИМОСТЬ, дерево: обращений к main в функциях генератора %d" % обращений)
    итог &= обращений == 0
    # 2. НЕЗАВИСИМОСТЬ — отпечаток при испорченных правилах main
    чисто = отпечаток(н)
    было = {к: getattr(main, к) for к in ("АПТ_СМЕНА_ОКОНЧАНИЯ", "АПТ_ХВОСТ_ПАДЕЖА",
                                          "_апт_дописанные_окончания") if hasattr(main, к)}
    try:
        main.АПТ_СМЕНА_ОКОНЧАНИЯ = ((("а",), ("зз",)),)
        if "АПТ_ХВОСТ_ПАДЕЖА" in было:  # с захода 296 в main его нет
            main.АПТ_ХВОСТ_ПАДЕЖА = 99
        main._апт_дописанные_окончания = _все_хвосты
        порч = отпечаток(наборы(имена))
    finally:
        for к, з in было.items():
            setattr(main, к, з)
    print("НЕЗАВИСИМОСТЬ, отпечаток: чисто %s, правила main испорчены %s — %s"
          % (чисто, порч, "СОВПАЛ" if чисто == порч else "РАЗОШЁЛСЯ"))
    итог &= чисто == порч

    чист_ф, чист_в = замер(позиции, н, main._апт_названия_в_вопросе)
    печать("чисто", чист_ф, чист_в, н)
    итог &= sum(чист_в.values()) == 0

    def подлог(подпись, ставим, образцы):
        nonlocal итог
        прежние = {к: getattr(main, к) for к in ставим}
        try:
            for к, з in ставим.items():
                setattr(main, к, з)
            ф, в = замер(позиции, н, main._апт_названия_в_вопросе)
        finally:
            for к, з in прежние.items():
                setattr(main, к, з)
        печать(подпись, ф, в, н)
        выросло = all(в[о] > чист_в[о] for о in образцы)
        print("   %s: %s — %s" % (подпись, ", ".join("%s %d → %d" % (о, чист_в[о], в[о])
                                                    for о in образцы),
                               "ЗВЕНО ДОКАЗАНО" if выросло else "НЕ ДОКАЗАНО"))
        итог &= выросло

    сов = main._апт_совпадение_слова

    # W1 ЛОМАЕТ ЗВЕНО «ЗАКРЫТЫЙ СПИСОК ДОПИСАННЫХ ОКОНЧАНИЙ»: любые хвосты
    # до двух знаков — ровно прежнее правило задачи 291
    подлог("W1 хвосты", {"_апт_дописанные_окончания": _все_хвосты},
           ["дописанная буква"])

    def _нечётко(слово, имя):
        р = сов(слово, имя)
        if р or len(слово) != len(имя) or len(имя) < 4:
            return р
        разн = [i for i in range(len(имя)) if слово[i] != имя[i]]
        if len(разн) == 1:
            return "точно"
        if (len(разн) == 2 and разн[1] == разн[0] + 1
                and слово[разн[0]] == имя[разн[1]] and слово[разн[1]] == имя[разн[0]]):
            return "точно"
        return ""

    # W2 ЛОМАЕТ ЗВЕНО «СРАВНЕНИЕ ТОЧНОЕ»: одна буква и перестановка соседних
    подлог("W2 нечётко", {"_апт_совпадение_слова": _нечётко},
           ["подменённая буква", "переставленные буквы"])

    def _начало(слово, имя):
        р = сов(слово, имя)
        return р or ("точно" if len(имя) >= 4 and len(слово) >= 5
                     and слово[:4] == имя[:4] else "")

    # W3 ЛОМАЕТ ТО ЖЕ ЗВЕНО С ДРУГОЙ СТОРОНЫ: общее начало в четыре знака
    подлог("W3 начало", {"_апт_совпадение_слова": _начало},
           ["выдуманное слово в падеже"])
    print("КОНТРОЛЬ: %s" % ("ВСЕ ЗВЕНЬЯ ДОКАЗАНЫ, ГЕНЕРАТОР НЕЗАВИСИМ" if итог
                            else "НЕ ДОКАЗАНО"))
    return 0 if итог else 1



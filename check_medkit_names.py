def _слова_имени(и):
    return " ".join(_норма(и).split()).split()


def наборы_названо(имена):
    """{"формы": [(текст, имя, многословное, род)],
        "выдумки": {(место, образец): [(текст, имя)]}}.

    Формы — именительный и падежи ПЕРВОГО слова. Выдумки — четыре образца
    в первом слове и, у многословного, в последнем; выдумка, совпавшая
    с настоящей формой любого слова аптечки, в набор не входит."""
    настоящие = set()
    for и in имена:
        for с in _слова_имени(и):
            настоящие.add(с)
            з, д = парадигма(с)
            настоящие.update(з)
            настоящие.update(д)
    формы, выдумки, видели = [], {}, set()
    for и in sorted(set(имена)):
        сл = _слова_имени(и)
        if len(" ".join(сл)) < 5:
            continue
        мн = len(сл) >= 2
        з, д = парадигма(сл[0])
        for род, фф in (("именительный", [сл[0]]), ("заменённое", з), ("дописанное", д)):
            for ф in фф:
                т = " ".join([ф] + сл[1:])
                if (т, и) not in видели:
                    видели.add((т, и))
                    формы.append((т, и, мн, род))
        места = [("первое", 0)] + ([("последнее", len(сл) - 1)] if мн else [])
        for место, к in места:
            if not re.fullmatch(r"[а-я]{4,}", сл[к]):
                continue
            for образец, слово in _выдумки(сл[к]):
                if слово in настоящие:
                    continue
                т = " ".join(сл[:к] + [слово] + сл[к + 1:])
                спис = выдумки.setdefault((место, образец), [])
                if (т, и) not in спис:
                    спис.append((т, и))
    return {"формы": формы, "выдумки": выдумки}



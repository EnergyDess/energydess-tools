ГЛАСНЫЕ = "аеиоуыэюя"
СОГЛАСНЫЕ = "бвгджзклмнпрстфхцчшщ"
ЗАДНЕЯЗ_ШИП = "гкхжшчщ"   # после них «и», а не «ы»
ШИПЯЩИЕ = "жшчщ"          # после них «ей» во мн. ч., «ем» в творительном
НЕ_ОКОНЧАНИЯ_1 = "нклтсрдпзв"
НЕ_ОКОНЧАНИЯ_2 = ("ин", "ол", "ик", "ан", "ек")


def _норма(т):
    return (т or "").lower().replace("ё", "е")


def парадигма(с):
    """(заменённые, дописанные) падежные формы слова — по русской грамматике.

    Не склоняются: слово на «о», «е», «и», «у», «ы», «э», «ю», латиница, цифры.
    Беглые гласные («уголь» → «угля») не порождаются: форма, которой генератор
    не знает, в замер не входит — и это граница, а не находка."""
    if not с or not re.fullmatch(r"[а-я]+", с):
        return [], []
    if с.endswith(("ый", "ий", "ой", "ое", "ее")):
        о = с[:-2]
        мягк = с.endswith(("ий", "ее"))
        return [о + к for к in (("его", "ему", "им", "ем") if мягк
                                else ("ого", "ому", "ым", "ом"))], []
    if с.endswith(("ая", "яя")):
        о = с[:-2]
        return [о + к for к in (("ей", "юю") if с.endswith("яя")
                                else ("ой", "ую"))], []
    п = с[-1]
    о = с[:-1]
    if п == "а":
        ы = "и" if о[-1:] in ЗАДНЕЯЗ_ШИП else "ы"
        return [о + к for к in (ы, "е", "у", "ой")], [с + к for к in ("м", "ми", "х")]
    if п == "я":
        return [о + к for к in ("и", "е", "ю", "ей")], [с + к for к in ("м", "ми", "х")]
    if п == "ь":
        return [о + к for к in ("я", "ю", "е", "ем", "и", "ей")], [с + "ю"]
    if п == "й":
        return [о + к for к in ("я", "ю", "е", "ем", "и", "ев")], []
    if п in СОГЛАСНЫЕ:
        кон = ["а", "у", "е", "ам", "ах"]
        кон.append("и" if п in ЗАДНЕЯЗ_ШИП else "ы")
        if п in ШИПЯЩИЕ:
            кон += ["ем", "ом", "ей"]
        elif п == "ц":
            кон += ["ем", "ев"]
        else:
            кон += ["ом", "ов"]
        return [], [с + к for к in кон]
    return [], []


def _вопрос(слова, первое):
    return "где лежит " + " ".join([первое] + слова[1:])


def наборы(имена):
    """{"формы": [(вопрос, имя, род)], "выдумки": {образец: [вопрос]}}."""
    настоящие = set()
    for и in имена:
        for сл in _норма(и).split():
            настоящие.add(сл)
        сл = _норма(и).split()
        if сл:
            з, д = парадигма(сл[0])
            настоящие.update(з)
            настоящие.update(д)
    формы, видели = [], set()
    выдумки = {"дописанная буква": [], "подменённая буква": [],
               "переставленные буквы": [], "выдуманное слово в падеже": []}
    вид_выдумки = set()

    def выдумка(образец, слова, слово):
        if слово in настоящие or len(слово) < 4:
            return
        в = _вопрос(слова, слово)
        if в not in вид_выдумки:
            вид_выдумки.add(в)
            выдумки[образец].append(в)

    for и in имена:
        сл = _норма(и).split()
        if not сл:
            continue
        с = сл[0]
        з, д = парадигма(с)
        for род, фф in (("заменённое", з), ("дописанное", д)):
            for ф in фф:
                в = _вопрос(сл, ф)
                if (в, и) not in видели:
                    видели.add((в, и))
                    формы.append((в, и, род))
        if not re.fullmatch(r"[а-я]{4,}", с):
            continue
        for образец, слово in _выдумки(с):
            выдумка(образец, сл, слово)
    return {"формы": формы, "выдумки": выдумки}


def _выдумки(с):
    """[(образец, слово)] — выдумки из слова `с` (кириллица, от четырёх букв),
    БЕЗ отсева настоящих. Один построитель на оба режима: у опознания пачки
    и у заслона чужих имён выдумки обязаны быть одними и теми же."""
    итог = [("дописанная буква", с + х)
            for х in list(НЕ_ОКОНЧАНИЯ_1) + list(НЕ_ОКОНЧАНИЯ_2)]
    середина = len(с) // 2
    # подменённая буква: следующая по алфавиту СОГЛАСНАЯ (гласная на месте
    # гласной дала бы соседнее настоящее окончание у коротких слов)
    буква = с[середина]
    замена = next(б for б in СОГЛАСНЫЕ + СОГЛАСНЫЕ[:1]
                  if б != буква and б > буква) if буква < "щ" else "б"
    подм = с[:середина] + замена + с[середина + 1:]
    итог.append(("подменённая буква", подм))
    итог += [("подменённая буква", ф) for ф in sum(парадигма(подм), [])[:1]]
    if с[середина - 1] != с[середина]:
        пер = с[:середина - 1] + с[середина] + с[середина - 1] + с[середина + 1:]
        итог.append(("переставленные буквы", пер))
        итог += [("переставленные буквы", ф) for ф in sum(парадигма(пер), [])[:1]]
    основа = с[:4] + "ор"
    итог += [("выдуманное слово в падеже", ф) for ф in парадигма(основа)[1][:2]]
    return итог


def наборы_заслона(слова):
    """{"формы": [слово], "выдумки": {образец: [слово]}} по СЛОВАМ, которые
    сервер разрешает писать модели с заглавной (заход 296, задача 294).

    Настоящие — само слово и его падежные формы по СВОЕЙ грамматике;
    выдумка, совпавшая с настоящей формой ЛЮБОГО разрешённого слова,
    в набор не входит: признать её знакомой — правда, а не дыра."""
    настоящие = set()
    for с in слова:
        с = _норма(с)
        настоящие.add(с)
        з, д = парадигма(с)
        настоящие.update(з)
        настоящие.update(д)
    выдумки = {"дописанная буква": [], "подменённая буква": [],
               "переставленные буквы": [], "выдуманное слово в падеже": []}
    for с in sorted({_норма(с) for с in слова}):
        if not re.fullmatch(r"[а-я]{4,}", с):
            continue
        for образец, в in _выдумки(с):
            if len(в) >= 4 and в not in настоящие and в not in выдумки[образец]:
                выдумки[образец].append(в)
    return {"формы": sorted(настоящие), "выдумки": выдумки}



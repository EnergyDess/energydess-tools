def замер(позиции, н, функция):
    """{вопрос: (своей, чужих, спорных)} для форм, {образец: опознано} для выдумок."""
    формы = {}
    for в, имя, род in н["формы"]:
        названы, спорные = функция(в, позиции)
        имена_н = {_норма(х["name"]) for х in названы}
        формы[(в, имя)] = (_норма(имя) in имена_н,
                           bool(имена_н - {_норма(имя)}), bool(спорные), род)
    выдумки = {}
    for образец, вв in н["выдумки"].items():
        выдумки[образец] = sum(1 for в in вв if any(функция(в, позиции)))
    return формы, выдумки


def печать(подпись, формы, выдумки, н):
    всего = len(формы)
    своих = sum(1 for ф in формы.values() if ф[0])
    чужих = sum(1 for ф in формы.values() if ф[1])
    спорных = sum(1 for ф in формы.values() if ф[2])
    по_роду = {р: (sum(1 for ф in формы.values() if ф[3] == р and ф[0]),
                   sum(1 for ф in формы.values() if ф[3] == р)) for р in ("дописанное", "заменённое")}
    print("%-12s форм %d: своей %d (дописанных %d/%d, заменённых %d/%d), чужой %d, "
          "спорных %d" % (подпись, всего, своих, по_роду["дописанное"][0],
                          по_роду["дописанное"][1], по_роду["заменённое"][0],
                          по_роду["заменённое"][1], чужих, спорных))
    print("%-12s выдумок: %s" % ("", " · ".join(
        "%s %d/%d" % (о, выдумки[о], len(н["выдумки"][о])) for о in выдумки)))
    return sum(выдумки.values())



"""ОПОЗНАНИЕ ПАЧКИ ПО НАЗВАНИЮ В ПАДЕЖЕ — ПО ВСЕЙ АПТЕЧКЕ (заход 290, №289).

МЕРКА, код возврата всегда 0 (кроме `--контроль`). Спрашивает боевую
`main._апт_названия_в_вопросе` и её ПРЕЖНЮЮ версию — взятую из HEAD
разбором синтаксического дерева, а не переписанную: своя копия «до»
разошлась бы с настоящей молча.

ЧТО СЧИТАЕТСЯ, ПО КАЖДОМУ НАЗВАНИЮ АПТЕЧКИ:
  · падежные формы с ЗАМЕНЁННЫМ окончанием, построенные из тех же
    правил флексий, — сколько опознаны своей пачкой ДО и ПОСЛЕ;
  · ЛОЖНЫЕ опознания — форма опознала пачку с ДРУГИМ названием;
  · СПОРНЫЕ — форма подошла к двум разным названиям (просьба уточнить);
  · ВЫДУМАННЫЕ имена: у основы меняется одна внутренняя буква, затем
    ставится падежное окончание. Опознаний обязано быть НОЛЬ.

НАЗВАНИЯ НЕ ПЕЧАТАЮТСЯ — только числа (§8.0): мерка гоняется и по копии
боевой базы. Базу открывает только на чтение, путь с `/data/` отвергает.

    py check_medkit_names.py                    # база стенда
    py check_medkit_names.py --база <копия>     # копия прода
    py check_medkit_names.py --контроль         # подлог: огрубление без
                                                # закрытого списка флексий
"""
import ast
import os
import re
import sqlite3
import subprocess
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
os.environ.setdefault("DB_PATH", "test_medkit_query.db")

import main  # noqa: E402

ГЛАСНЫЕ = "аеиоуыэюя"
# СПИСОК ФЛЕКСИЙ ДЛЯ ГЕНЕРАТОРА ФОРМ ФИКСИРУЕТСЯ ДО ПОДЛОГА. Первая версия
# брала его у `main` на лету: подлог «флексии любые» подменял и генератор,
# все выдумки попадали в «законные окончания» и отфильтровывались —
# «выдуманных 0» при подлоге, то есть контроль не прогонялся вовсе
ОКОНЧАНИЯ = main.АПТ_СМЕНА_ОКОНЧАНИЯ


def _прежняя():
    """`_апт_названия_в_вопросе` как она была в HEAD — (названы, [])."""
    исходник = subprocess.run(["git", "show", "HEAD:main.py"], capture_output=True,
                              check=True).stdout.decode("utf-8")
    нужны = {"_апт_слово_совпало", "_апт_позиции_в_вопросе"}
    куски = [ast.get_source_segment(исходник, у) for у in ast.parse(исходник).body
             if isinstance(у, ast.FunctionDef) and у.name in нужны]
    if len(куски) != 2:
        raise SystemExit("ОСТАНОВЛЕНО: в HEAD не найдены обе прежние функции")
    место = {"re": re, "_апт_опр": main._апт_опр,
             "АПТ_ХВОСТ_ПАДЕЖА": main.АПТ_ХВОСТ_ПАДЕЖА}
    exec("\n\n".join(куски), место)
    return lambda вопрос, позиции: (место["_апт_позиции_в_вопросе"](вопрос, позиции), [])


def _названия(путь):
    if "/data/" in путь.replace("\\", "/"):
        raise SystemExit("ОСТАНОВЛЕНО: боевую базу не открываю — нужна копия")
    с = sqlite3.connect("file:%s?mode=ro" % путь, uri=True)
    try:
        return sorted({р[0] for р in с.execute(
            "SELECT name FROM medkit_items WHERE name IS NOT NULL")})
    finally:
        с.close()


def _основа(имя):
    """(первое слово, основа без окончания, замены) — либо None.

    ТОЛЬКО ПЕРВОЕ СЛОВО, и это не упрощение: первая версия склоняла
    первое СКЛОНЯЕМОЕ слово и у «Нурофена для детей» портила «детей»,
    после чего короче название «Нурофен» законно опознавалось — и мерка
    записывала это ЛОЖНЫМ опознанием в колонку «до» (4 на стенде)."""
    слова = (имя or "").split()
    if not слова:
        return None
    н = слова[0].lower().replace("ё", "е")
    for концы, замены in ОКОНЧАНИЯ:
        конец = next((к for к in концы if н.endswith(к)), None)
        if конец is None:
            continue
        основа = н[:-len(конец)]
        return (слова, основа, замены) if len(основа) >= 4 else None
    return None


def _формы(имя):
    """Падежные формы названия: окончание первого слова заменено."""
    р = _основа(имя)
    if not р:
        return []
    слова, основа, замены = р
    return [" ".join([основа + з] + слова[1:]) for з in замены]


# ВЫДУМКА — ТА ЖЕ ОСНОВА С НЕ-ОКОНЧАНИЕМ. Это ровно то, чем огрубление
# могло бы стать «похоже на»: «Смектин», «Смекто» при «Смекте». Первая
# версия меняла букву ВНУТРИ основы — такое имя не опознаётся ни при каком
# списке флексий, и подлог «флексии любые» его не открывал: контроль
# печатал «НЕ ДОКАЗАНО» про звено, которого выдумка не касалась
НЕ_ОКОНЧАНИЯ = ("ин", "ол", "ан", "ик", "о", "ек")


def _выдумки(имя):
    р = _основа(имя)
    if not р:
        return []
    слова, основа, замены = р
    # «СМЕКТАН» — НЕ ВЫДУМКА ДЛЯ ЭТОГО ЗВЕНА: он начинается с полного
    # «смекта», и опознаёт его ПРЕЖНЕЕ правило дописанного окончания
    # (одинаково до и после правки). Замер «опознано 4» до и 4 после
    # мерил именно его, а не замену окончания
    первое = слова[0].lower().replace("ё", "е")
    return [" ".join([основа + х] + слова[1:])
            for х in НЕ_ОКОНЧАНИЯ
            if х not in замены and not (основа + х).startswith(первое)]


def замер(путь, функция, подпись):
    имена = _названия(путь)
    позиции = [{"id": i, "name": н} for i, н in enumerate(имена, 1)]
    склоняемых = форм = своих = ложных = спорных = выдумок = выдумки_опознаны = 0
    for п in позиции:
        формы = _формы(п["name"])
        if формы:
            склоняемых += 1
        for ф in формы:
            форм += 1
            названы, спорные = функция("где лежит " + ф, позиции)
            имена_назв = {(х["name"] or "").lower() for х in названы}
            if (п["name"] or "").lower() in имена_назв:
                своих += 1
            if имена_назв - {(п["name"] or "").lower()}:
                ложных += 1
            if спорные:
                спорных += 1
        for в in _выдумки(п["name"]):
            # выдумка, совпавшая с НАСТОЯЩИМ названием аптечки, — не выдумка
            if в.split()[0] in {(x["name"] or "").lower().replace("ё", "е")
                                .split()[0] for x in позиции if x["name"]}:
                continue
            выдумок += 1
            названы, спорные = функция("где лежит " + в, позиции)
            if названы or спорные:
                выдумки_опознаны += 1
    print("%-6s названий %d, склоняемых %d · форм с заменой окончания %d: "
          "опознаны своей пачкой %d, ложных %d, спорных %d · выдуманных %d: "
          "опознано %d" % (подпись, len(имена), склоняемых, форм, своих, ложных,
                           спорных, выдумок, выдумки_опознаны))
    return своих, ложных, выдумки_опознаны


def main_():
    путь = (sys.argv[sys.argv.index("--база") + 1] if "--база" in sys.argv
            else os.path.join(os.path.dirname(os.path.abspath(__file__)), "app.db"))
    if "--контроль" in sys.argv:
        # ПОДЛОГ ЛОМАЕТ ПРОВЕРЯЕМОЕ ЗВЕНО — ЗАКРЫТЫЙ СПИСОК ФЛЕКСИЙ: вместо
        # списка «любые два знака после основы». Выдуманные имена обязаны
        # начать опознаваться; иначе проба слепа к тому, ради чего написана
        прежний = main.АПТ_СМЕНА_ОКОНЧАНИЯ
        чисто = замер(путь, main._апт_названия_в_вопросе, "чисто")
        ЛЮБЫЕ = tuple(a + b for a in ГЛАСНЫЕ + "клнтр"
                      for b in ("",) + tuple(ГЛАСНЫЕ + "клнтр"))
        main.АПТ_СМЕНА_ОКОНЧАНИЯ = tuple((к, ЛЮБЫЕ) for к, _ in прежний)
        try:
            подлог = замер(путь, main._апт_названия_в_вопросе, "подлог")
        finally:
            main.АПТ_СМЕНА_ОКОНЧАНИЯ = прежний
        верно = чисто[2] == 0 and подлог[2] > 0
        print("КОНТРОЛЬ: выдуманных опознано чисто %d, с подлогом %d — %s"
              % (чисто[2], подлог[2], "ПРОБА ВИДИТ ОСЛАБЛЕНИЕ" if верно
                 else "НЕ ДОКАЗАНО"))
        return 0 if верно else 1
    замер(путь, _прежняя(), "ДО")
    замер(путь, main._апт_названия_в_вопросе, "ПОСЛЕ")
    return 0


# ДОКАЗАТЕЛЬСТВО объявлено ИМЕНЕМ для описи `check_controls.py`

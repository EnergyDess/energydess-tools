class _правило:
    """Подменяет имена в `main` на время замера и возвращает их при выходе."""
    def __init__(self, **подмены):
        self.подмены, self.было = подмены, {}

    def __enter__(self):
        for к, з in self.подмены.items():
            self.было[к] = getattr(main, к)
            setattr(main, к, з)

    def __exit__(self, *а):
        for к, з in self.было.items():
            setattr(main, к, з)


def замер_звена(слова, н):
    """(знакомых форм, {образец: выдумок прошло}, [формы, признанные чужими])."""

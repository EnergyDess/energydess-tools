def _функция_из(исходник, подмены=(), место=None):
    """`_апт_названо_в_тексте` из исходника; подмена — строго одна замена
    на каждую пару, иначе ОСТАНОВЛЕНО (подлог, не нашедший якоря, не подлог)."""
    куски = []
    for у in ast.parse(исходник).body:
        имя = (у.name if isinstance(у, ast.FunctionDef) else
               у.targets[0].id if isinstance(у, ast.Assign)
               and isinstance(у.targets[0], ast.Name) else None)
        if имя in ЗАВИСИМОСТИ_НАЗВАНО:
            куски.append(ast.get_source_segment(исходник, у))
    текст = "\n\n".join(куски)

НУЖНЫ = ("_апт_совпадение_слова", "_апт_слово_совпало", "_апт_названия_в_вопросе",
         "_апт_дописанные_окончания", "АПТ_СМЕНА_ОКОНЧАНИЯ", "АПТ_ХВОСТ_ПАДЕЖА",
         "АПТ_СОГЛАСНЫЕ", "_апт_слова_сравнения")


def _чего_не_хватает(исходник, перечень, место_имена=()):
    """Имена, которые собранные куски зовут, а взять их неоткуда.

    ПОЛНОТА ПЕРЕЧНЯ — СВОЙСТВО, А НЕ НАДЕЖДА: дописали боевой функции
    зависимость, и версия «ДО» падает `NameError` при первом вызове,
    то есть проба молча перестаёт прогоняться (BACKLOG №305, №307).
    """
    д = ast.parse(исходник)
    куски = {}
    for у in д.body:
        имя = (у.name if isinstance(у, ast.FunctionDef) else
               у.targets[0].id if isinstance(у, ast.Assign)
               and isinstance(у.targets[0], ast.Name) else None)
        if имя:
            куски[имя] = у
    нужно, очередь = set(перечень), list(перечень)
    while очередь:
        у = куски.get(очередь.pop())
        if у is None:
            continue
        for n in ast.walk(у):
            if isinstance(n, ast.Name) and n.id in куски and n.id not in нужно:
                нужно.add(n.id)
                очередь.append(n.id)
    return sorted(нужно - set(перечень) - set(место_имена))



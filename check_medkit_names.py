    # боевой базы дал 2 → 2 при исправном подлоге. Мерить надо там, где
    # проверка 5 — единственный заслон, то есть при пустой мишени.
    with _правило(_апт_слова_названий=lambda поз: set()):
        _, св3 = _замер_названо(путь, {"ЧИСТО": main._апт_названо_в_тексте,
                                       "П3": п3})
    в_а = len(выд_нач & св3["ЧИСТО"]["видно"]["начало"])
    в_б = len(выд_нач & св3["П3"]["видно"]["начало"])
    ок = в_б > в_а
    print("   П3 кусок снят (вторая ветка проверки 3 выключена): выдумок "
          "на экране (начало фразы) %d → %d — %s"
          % (в_а, в_б, "ЗВЕНО ДОКАЗАНО" if ок else "НЕ ДОКАЗАНО"))
    итог &= ок
    for подпись, подмена, образцы in (
            ("П2а нечётко", _нечётко, [("первое", "подменённая буква"),
                                      ("первое", "переставленные буквы")]),
            ("П2б начало", _начало, [("первое", "выдуманное слово в падеже")])):
        with _правило(_апт_совпадение_слова=подмена):
            _, опознано = _звено(main._апт_названо_в_тексте,
                                 [{"id": i, "name": и} for i, и in enumerate(имена, 1)], н)
        выросло = all(len(опознано[к]) > len(чисто["опознано"][к]) for к in образцы
                      if к in опознано)
        print("   %s (правило окончаний ослаблено): %s — %s" % (подпись, ", ".join(
            "%s/%s %d → %d" % (к[0], к[1], len(чисто["опознано"].get(к, ())),
                               len(опознано.get(к, ()))) for к in образцы),
            "ЗВЕНО ДОКАЗАНО" if выросло else "НЕ ДОКАЗАНО"))
        итог &= выросло
    # ── ПОДЛОГИ ВТОРОЙ ВЕТКИ ЗАСЛОНА ЧУЖИХ ИМЁН (заход 303, задача 301) ──
    #
    # Каждый ломает СВОЁ звено, и доказательство — числом выдумок,
    # дошедших до ЭКРАНА в том положении, за которое звено отвечает.
    # Место замера — «начало» и «строчное»: в середине с заглавной
    # работает ПЕРВАЯ ветка, и подлог второй там ничего не изменит.
    п_чисто = сводка["ЧИСТО"]
    подлоги = (
        ("П4 мишень пуста", dict(_апт_слова_названий=lambda поз: set()),
         "второй ветке не с чем сравнивать"),
        ("П5 правки сняты", dict(АПТ_ПОХОЖЕ_ПРАВОК=0),
         "остаётся только общая основа"),
        ("П6 основа снята", dict(АПТ_ПОХОЖЕ_ОСНОВА=99),
         "остаются только правки"),
    )
    for подпись, подмена, чем in подлоги:
        with _правило(**подмена):
            _, св = _замер_названо(путь, {"П": main._апт_названо_в_тексте})
        строки = []
        выросло = False
        for место in ("начало", "строчное"):
            а = len(выд_нач & п_чисто["видно"][место])
            б = len(выд_нач & св["П"]["видно"][место])
            строки.append("%s %d → %d" % (место, а, б))
            выросло |= б > а
        print("   %s (%s): выдумок на экране %s — %s"
              % (подпись, чем, ", ".join(строки),
                 "ЗВЕНО ДОКАЗАНО" if выросло else "НЕ ДОКАЗАНО"))
        итог &= выросло
    # ── ПОДЛОГ ЗАДАЧИ 300: ЗАМЕНЁННОЕ ОКОНЧАНИЕ У ОДНОСЛОВНОГО ──────
    п7 = _функция_из(исходник, ((
        "кусок.startswith(имя) or _апт_совпадение_слова(кусок, имя)",
        "кусок.startswith(имя)"),))
    од = {(т, и) for т, и, мн, _ in н["формы"] if not мн}
    а = len(п_чисто["найдено"] & од)
    б = len(_звено(п7, [{"id": i, "name": и} for i, и in enumerate(имена, 1)], н)[0] & од)
    ок = б < а
    print("   П7 замена окончания снята: однословных форм найдено звеном "
          "%d → %d из %d — %s" % (а, б, len(од),
                                  "ЗВЕНО ДОКАЗАНО" if ок else "НЕ ДОКАЗАНО"))
    итог &= ок
    print("КОНТРОЛЬ «НАЗВАНО»: %s" % ("ВСЕ ЗВЕНЬЯ ДОКАЗАНЫ, НАБОР НЕЗАВИСИМ" if итог
                                     else "НЕ ДОКАЗАНО"))
    return 0 if итог else 1



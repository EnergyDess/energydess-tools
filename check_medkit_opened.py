# -*- coding: utf-8 -*-
"""ЧТО СТАЛО С ДАТАМИ ВСКРЫТИЯ ПОСЛЕ ОТКАТА ПРАВИЛА — постановка A.4.

═══════════════════════════════════════════════════════════════════════
ЗАЧЕМ

Блок A вернул поля вскрытия всем формам и запретил заполнять их без
человека. У тех, кто заводил карточки РАНЬШЕ, в базе уже лежат даты
и числа дней, проставленные не ими:

  · `opened_days` подставляла ФОРМА — умолчание 28/90 дней, взятое
    из формы выпуска, а не с упаковки;
  · `opened_on` проставляла КНОПКА ПРИЁМА — первое нажатие писало
    сегодняшний день.

Правка меняет то, КАК эти числа читаются, и у части позиций сменится
состояние срока. Прямая цитата постановки: «НЕ ЧИСТИ БАЗУ САМ.
Напечатай, какие записи затронуты и что с ними станет».

═══════════════════════════════════════════════════════════════════════
ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ

НЕ ПРОВЕРКОЙ: кода «правильно» у неё нет, код возврата всегда 0.
Затронутые записи — не находка и не долг: это законные данные, решение
по которым принимает владелец.

НЕ МИГРАЦИЕЙ: скрипт открывает базу ТОЛЬКО НА ЧТЕНИЕ (`mode=ro`),
и ни одной команды записи в нём нет. Проверяется это не обещанием
в шапке, а режимом открытия — попытка записи упадёт.

═══════════════════════════════════════════════════════════════════════
ЗАПУСК

    py check_medkit_opened.py                    # локальная база
    DB_PATH=/data/app.db py check_medkit_opened.py   # на машине Fly

Состояние срока считает `main._апт_состояние` — та же функция, что
рисует карточку. Свой расчёт здесь разошёлся бы с экраном молча,
и опись показывала бы не то, что увидит владелец (§6.0.7).
"""
import io
import os
import sqlite3
import sys
from datetime import date

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8",
                              errors="replace")

БАЗА = os.environ.get("DB_PATH", "app.db")


class Поз:
    """Позиция для `_апт_состояние`: поля БЕРУТСЯ ИЗ МОДЕЛИ, а не
    перечисляются здесь. Перечень отстал бы от схемы при первой же новой
    колонке — ровно так уже случилось с заглушкой в тестах (§6.0.7)."""

    def __init__(self, строка, колонки):
        for имя, значение in zip(колонки, строка):
            setattr(self, имя, значение)


def главное():
    import main

    conn = sqlite3.connect("file:%s?mode=ro" % БАЗА, uri=True)
    try:
        колонки = [r[1] for r in conn.execute("PRAGMA table_info(medkit_items)")]
        строки = conn.execute(
            "SELECT %s FROM medkit_items WHERE opened_on IS NOT NULL "
            "OR opened_days IS NOT NULL ORDER BY user_id, name"
            % ", ".join(колонки)).fetchall()
    finally:
        conn.close()

    сегодня = date.today()
    print("=" * 72)
    print("ДАТЫ ВСКРЫТИЯ В БАЗЕ %s" % os.path.abspath(БАЗА))
    print("=" * 72)
    if not строки:
        print("\nЗаписей с датой вскрытия или сроком после вскрытия НЕТ.")
        print("Правка блока A ничего в этой базе не меняет.")
        return 0

    # ЧТО БЫЛО ДО ПРАВКИ: срок укорачивался только у форм, которые
    # «портятся», и отметка «вскрыт» глушилась у остальных. Список
    # ЗАШИТ ЗДЕСЬ НАМЕРЕННО — в коде его больше нет, а сравнить
    # с прежним поведением надо
    ПОРТИЛИСЬ = {"syrup", "drops", "spray", "ointment", "gel", "cream"}

    меняются, без_изменений = [], 0
    for строка in строки:
        поз = Поз(строка, колонки)
        сейчас = main._апт_состояние(поз, сегодня)

        # Прежнее поведение воспроизводим подменой полей: у формы,
        # которая «не портилась», вскрытие не значило ничего
        портилась = поз.form in ПОРТИЛИСЬ
        if поз.form == "powder":
            портилась = поз.unit == "g"
        if портилась:
            было = сейчас
        else:
            копия = Поз(строка, колонки)
            копия.opened_on = None
            копия.opened_days = None
            было = main._апт_состояние(копия, сегодня)

        if было["id"] == сейчас["id"] and было["подпись"] == сейчас["подпись"]:
            без_изменений += 1
            continue
        меняются.append((поз, было, сейчас))

    print("\nВсего записей с проставленным вскрытием: %d" % len(строки))
    print("Из них состояние НЕ меняется: %d" % без_изменений)
    print("Состояние МЕНЯЕТСЯ у: %d" % len(меняются))

    if меняются:
        print("\n" + "-" * 72)
        print("ЗАТРОНУТЫЕ ЗАПИСИ")
        print("-" * 72)
        for поз, было, стало in меняются:
            print("\n  id %-4s %s" % (поз.id, поз.name))
            print("    форма %s/%s, годен до %s, вскрыто %s, дней после %s"
                  % (поз.form, поз.unit, поз.expires_ym, поз.opened_on,
                     поз.opened_days))
            print("    БЫЛО:  %-8s «%s»" % (было["id"], было["подпись"]))
            print("    СТАЛО: %-8s «%s»" % (стало["id"], стало["подпись"]))

        print("\n" + "-" * 72)
        print("ЧТО С ЭТИМ ДЕЛАТЬ — РЕШАЕТ ВЛАДЕЛЕЦ")
        print("-" * 72)
        print("""
Эти даты проставлены не человеком: `opened_days` подставляла форма
выпуска, `opened_on` — первое нажатие кнопки приёма. Ни одно из двух
больше не происходит, но СТАРЫЕ ЧИСЛА ОСТАЛИСЬ, и теперь они читаются
как ваша отметка.

Убрать их можно карточка за карточкой — открыть правку и очистить оба
поля. Скрипт этого НЕ делает намеренно: часть дат может быть настоящей
(вы вправду вскрывали пачку), и отличить их от подставленных нечем.

Стереть все разом, если решите, что настоящих среди них нет:

    UPDATE medkit_items SET opened_on = NULL, opened_days = NULL;
""")
    return 0


if __name__ == "__main__":
    sys.exit(главное())

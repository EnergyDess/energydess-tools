ЗАМЕР_ШАПКИ = """(ид) => {
  const окно = document.querySelector(ид);
  if (!окно) return {ошибка: 'окна нет'};
  const шапка = окно.querySelector('.modal-hdr');
  if (!шапка) return {ошибка: 'шапки нет'};
  const справка = шапка.querySelector('.hint-btn, .hint');
  const крестик = шапка.querySelector('.modal-x');
  const короб = э => { const r = э.getBoundingClientRect();
    return {л: r.left, п: r.right, в: r.top, н: r.bottom,
            ш: Math.round(r.width), вы: Math.round(r.height)}; };
  // ОБЛАСТЬ НАЖАТИЯ, А НЕ РАЗМЕР ЭЛЕМЕНТА (§6.0.11): доборный слой
  // `::after` видим только через `elementFromPoint`.
  const область = э => {
    if (!э) return null;
    const r = э.getBoundingClientRect();
    const цx = (r.left + r.right) / 2, цy = (r.top + r.bottom) / 2;
    // ТОЧКА ПРИНАДЛЕЖИТ ЭЛЕМЕНТУ ИЛИ ЕГО ПОТОМКУ, НО НЕ ПРЕДКУ.
    // Первая версия принимала и предка (`п.contains(э)`) — и область
    // разрасталась на ВСЮ ШАПКУ: замер давал крестику 76x86 при самой
    // шапке в 48 px высотой. «Наложение 0» на таких числах не значило
    // ничего: обе области были фикцией.
    const свой = т => { const п = document.elementFromPoint(т[0], т[1]);
      return !!п && (п === э || э.contains(п)); };
    let л = цx, п = цx, в = цy, н = цy;
    for (let i = 0; i < 60 && свой([л - 1, цy]); i++) л--;
    for (let i = 0; i < 60 && свой([п + 1, цy]); i++) п++;
    for (let i = 0; i < 60 && свой([цx, в - 1]); i++) в--;
    for (let i = 0; i < 60 && свой([цx, н + 1]); i++) н++;
    return {ш: Math.round(п - л) + 1, в: Math.round(н - в) + 1,
            л: л, п: п, вх: в, нх: н};
  };
  const с = справка ? короб(справка) : null;
  const к = крестик ? короб(крестик) : null;
  const ос = область(справка), ок = область(крестик);
  let наложение = 0;
  if (ос && ок) {
    const пересечение = Math.min(ос.п, ок.п) - Math.max(ос.л, ок.л);
    naloj = 0;
    naloj = Math.min(ос.нх, ок.нх) - Math.max(ос.вх, ок.вх);
    наложение = (пересечение > 0 && naloj > 0) ? Math.round(пересечение) : 0;
  }
  // КРЕСТИК НУЛЕВОГО РАЗМЕРА — ЭТО ОТСУТСТВУЮЩИЙ КРЕСТИК. На сенсорной
  // ширине окно закрывает жест (задача 189, C), и `.modal-x` там
  // спрятан: элемент в дереве есть, коробка 0x0. Считать его живым
  // значило бы печатать «промежуток -356 px» — число, из которого
  // не следует ничего.
  const крестик_жив = !!(к && к.ш > 0 && к.вы > 0);
  return {
    есть_справка: !!справка, есть_крестик: крестик_жив,
    промежуток: (с && крестик_жив) ? Math.round(к.л - с.п) : null,
    справка: с ? (с.ш + 'x' + с.вы) : null,
    крестик: к ? (к.ш + 'x' + к.вы) : null,
    обл_справки: ос ? (ос.ш + 'x' + ос.в) : null,
    обл_крестика: ок ? (ок.ш + 'x' + ок.в) : null,
    наложение: наложение,
  };
}"""


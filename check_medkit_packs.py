def main():
    for к in sys.argv[1:]:
        if к not in ("--полосы", "--шапка", "--контроль", "--все"):
            print("Незнакомый ключ: %s" % к)
            return 2
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("playwright не установлен — прогон НЕ СОСТОЯЛСЯ")
        return 2

    набито = 0
    if ПОЛОСЫ and not ВСЕ:
        # ЛЕНТА НАБИВАЕТСЯ ДО ПРОГОНА И УБИРАЕТСЯ ПОСЛЕ — разбор в шапке.
        # СВОЯ набивка, а не импорт из `check_medkit_look`: тот модуль
        # ПОДМЕНЯЕТ `sys.stdout` на импорте, и прежняя обёртка уходит
        # в сборку мусора, закрывая общий буфер (§3, `shots_medkit_223`).
        набито = _ленту_набить(60)
        print("ЛЕНТА НАБИТА: строк событий в базе %s (стенд, не прод)" % набито)

    беда = 0
    try:
        with sync_playwright() as p:
            # ГОЛОВНОЙ БРАУЗЕР — §6.0.3, разбор в шапке
            br = p.chromium.launch(headless=False)
            ctx = br.new_context(viewport={"width": 1920, "height": 1000})
            pg = ctx.new_page()
            войти(pg)
            if ВСЕ:
                for ш in (2560, 390):
                    беда += печать_всех(прогон_всех(pg, ш), ш)
            elif ПОЛОСЫ:
                for ш in (2560, 390):
                    беда += печать_полос(прогон_полос(pg, ш), ш)
            elif ШАПКА:
                for ш in ШИРИНЫ:
                    # СЕНСОРНАЯ ЭМУЛЯЦИЯ НА УЗКОЙ ШИРИНЕ ОБЯЗАТЕЛЬНА
                    # (§6.0.3). Доборный слой до 44 px объявлен внутри
                    # `@media (pointer: coarse)`, и без `has_touch`
                    # его нет вовсе: замер давал области 30x30 там, где
                    # у живого телефона 44x44, — то есть проба печатала
                    # находку про исправное. Ширина сама по себе
                    # признака не переключает: это пустышка `is_mobile`,
                    # разобранная в §6.0.3.
                    if ш <= 640:
                        ctx2 = br.new_context(
                            viewport={"width": ш, "height": 900},
                            has_touch=True)
                        pg2 = ctx2.new_page()
                        войти(pg2)
                        печать_шапки(прогон_шапки(pg2, ш), ш)
                        ctx2.close()
                    else:
                        печать_шапки(прогон_шапки(pg, ш), ш)
            else:
                печать_окна(прогон_окна(pg))
            br.close()
    finally:
        if набито:
            print("\nЛЕНТА ВОЗВРАЩЕНА: убрано строк %d" % _ленту_подрезать())

    if КОНТРОЛЬ:
        return 1 if беда else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())

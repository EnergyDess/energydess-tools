def _ленту_набить(сколько):
    """Набить ленту круга — иначе прокрутки в ней нет и мерить нечего.

    Строки кладутся ПРЯМО В БАЗУ, а не действиями: шестьдесят списаний
    через интерфейс — работа не про то, а вопрос тут к раскладке,
    а не к пути записи. Помечены именем, по которому и убираются.
    """
    import sqlite3
    from database import DB_PATH
    c = sqlite3.connect(DB_PATH)
    try:
        круг = c.execute("SELECT id FROM medkit_circles").fetchone()
        участник = c.execute(
            "SELECT user_id FROM medkit_members LIMIT 1").fetchone()
        if not круг or not участник:
            return 0
        for i in range(сколько):
            c.execute("INSERT INTO medkit_events "
                      "(circle_id, user_id, kind, name, created_at) "
                      "VALUES (?, ?, 'take', ?, datetime('now'))",
                      (круг[0], участник[0], "проба ленты %d" % i))
        c.commit()
        return c.execute("SELECT COUNT(*) FROM medkit_events").fetchone()[0]
    finally:
        c.close()


def _ленту_подрезать():
    """Убрать СВОИ строки ленты — по имени, которым их клали.

    Проба, оставившая за собой мусор, ломает не свой прогон, а следующий
    (§6.0.3, шестая причина неповторимости): пиксельный диф назвал бы
    находкой шестьдесят чужих записей.
    """
    import sqlite3
    from database import DB_PATH
    c = sqlite3.connect(DB_PATH)
    try:
        n = c.execute("DELETE FROM medkit_events "
                      "WHERE name LIKE 'проба ленты%'").rowcount
        c.commit()
        return n
    finally:
        c.close()



async def _покупка(pg, тело):
    """Причина, которая ляжет в строку списка покупок, — ровно та, что
    уедет на сервер при нажатии. Сама запись подменена: список владельца
    стенда проба не трогает."""
    await pg.evaluate("() => { window.__причина = null; window.аптКупить = async (о) =>"
                      " { window.__причина = о.why; return null; }; }")
    было = await pg.evaluate("() => document.querySelectorAll('.apt-ai-buy').length")
    await pg.evaluate(РАЗВИЛКА, тело)
    await pg.wait_for_timeout(200)
    кнопок = await pg.evaluate("() => document.querySelectorAll('.apt-ai-buy').length")
    if кнопок <= было:
        return "!!КНОПКИ «В ПОКУПКИ» НЕТ — мерить нечего"
    await pg.evaluate("() => [...document.querySelectorAll('.apt-ai-buy')].pop().click()")
    await pg.wait_for_timeout(200)
    return await pg.evaluate("() => window.__причина") or "!!ПРИЧИНА НЕ УШЛА"



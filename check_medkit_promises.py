def _подменить(позиции, ответ, показано=None):
    """Модель, база и переписка подменены; путь кода дальше боевой."""
    async def модель(промпт, очищать=True, **прочее):
        return ответ, "", 200
    main._апт_спросить_модель = модель
    main._апт_позиции_для_запроса = lambda db, user: (позиции, {})
    main._апт_чат_реплики = lambda db, user: []
    if показано is not None:
        прежний = main._апт_промпт_запроса.__wrapped__ if hasattr(
            main._апт_промпт_запроса, "__wrapped__") else main._апт_промпт_запроса

        def урезано(*а, **к):
            промпт, _ = прежний(*а, **к)
            return промпт, показано
        урезано.__wrapped__ = прежний
        main._апт_промпт_запроса = урезано


def _запрос(вопрос, позиции, ответ, показано=None):
    исходные = {к: getattr(main, к) for к in (
        "_апт_спросить_модель", "_апт_позиции_для_запроса", "_апт_чат_реплики",
        "_апт_промпт_запроса")}
    try:
        _подменить(позиции, ответ, показано)
        тело = asyncio.run(main._апт_ответ_на_запрос(вопрос, None, _Юзер()))
        return main._апт_заслон_выхода(тело)
    finally:
        for к, з in исходные.items():
            setattr(main, к, з)



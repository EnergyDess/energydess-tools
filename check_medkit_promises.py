def _разметка(старое, новое):
    async def поставить(pg):
        async def обработать(route):
            ответ = await route.fetch()
            текст = await ответ.text()
            замен = текст.count(новое)
            СОСТОЯЛИСЬ.append(замен)
            await route.fulfill(response=ответ, body=текст.replace(новое, старое))
        await pg.route(re.compile(r".*/medkit$"), обработать)
    return поставить



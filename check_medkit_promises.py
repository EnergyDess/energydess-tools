async def прогнать(случаи, подмена_страницы=None):
    """[(имя, случай, обещание_видно, видимый_текст)]."""
    from playwright.async_api import async_playwright
    итог = []
    async with async_playwright() as pw:
        бр = await pw.chromium.launch(headless=False)
        ctx = await бр.new_context(viewport={"width": 1440, "height": 900})
        pg = await ctx.new_page()
        await _войти(pg)
        if подмена_страницы:
            await подмена_страницы(pg)
        for имя, что, сборщик, признак, где in случаи:
            await _открыть(pg)
            if где == "пузырь":
                видно = await _пузырь(pg, await asyncio.to_thread(сборщик))
            elif где == "покупка":
                видно = await _покупка(pg, await asyncio.to_thread(сборщик))
            else:
                видно = await _перепроверка(pg, обрыв=где.endswith("обрыв"))
            if видно.startswith("!!") or not видно.strip():
                итог.append((имя, что, None, видно))
            else:
                итог.append((имя, что, bool(re.search(признак, видно)), видно))
        await ctx.close()
        await бр.close()
    return итог


def печать(итог):
    обещаний = несостоялось = 0
    for имя, что, есть, видно in итог:
        if есть is None:
            несостоялось += 1
        обещаний += 1 if есть else 0
        print("  %-12s %-40s %s" % ("ЗАМЕР НЕ СОСТ." if есть is None
                                    else "ОБЕЩАЕТ" if есть else "по факту",
                                    имя, что))
        if есть or есть is None or "--подробно" in sys.argv:
            print("       видно: %s" % " ".join(видно.split())[:260])
    print("ТЕКСТОВ С НЕОБЕСПЕЧЕННЫМ ОБЕЩАНИЕМ: %d из %d (замер не состоялся: %d)"
          % (обещаний, len(итог), несостоялось))
    return обещаний, несостоялось



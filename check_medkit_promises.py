    плохо = 0
    for (имя, что, сборщик, признак, где), (_, _, было, _) in zip(СЛУЧАИ, итог_чисто):
        подлог = ПОДЛОГИ.get(имя)
        if подлог is None:
            print("  %-40s ПОДЛОГА НЕТ" % имя)
            плохо += 1
            continue
        серверный, страничный = подлог
        сняли = {}
        СОСТОЯЛИСЬ.clear()
        try:
            for к, з in (серверный or {}).items():
                if not hasattr(main, к):
                    raise SystemExit("ПОДЛОГ НЕ СОСТОЯЛСЯ: в main нет %s" % к)
                сняли[к] = getattr(main, к)
                setattr(main, к, з)
            с_подлогом = (await прогнать([(имя, что, сборщик, признак, где)],
                                         страничный))[0][2]
        finally:
            for к, з in сняли.items():
                setattr(main, к, з)
        состоялся = bool(серверный) or (СОСТОЯЛИСЬ and all(з == 1 for з in СОСТОЯЛИСЬ))
        после = (await прогнать([(имя, что, сборщик, признак, где)]))[0][2]
        верно = было is False and с_подлогом is True and после is False and состоялся
        плохо += 0 if верно else 1
        print("  %-40s чисто %s → подлог %s → возврат %s%s — %s"
              % (имя, int(bool(было)), int(bool(с_подлогом)), int(bool(после)),
                 "" if серверный else " (замен в разметке %s)" % СОСТОЯЛИСЬ,
                 "ДОКАЗАНО" if верно else "НЕ ДОКАЗАНО"))
    print("КОНТРОЛЬ: текстов %d, не доказано %d" % (len(СЛУЧАИ), плохо))
    return 1 if плохо else 0



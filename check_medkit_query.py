# ── ДОЗИРОВКА В ВОЛЬНОМ ТЕКСТЕ (C.8) ─────────────────────────────────
#
# Спрашивается ПРИЗНАКОМ, а не глазом: «дозировок не назвал» на глаз
# и «дозировок не назвал» замером — разные утверждения, и первое
# не переживает следующего прогона.
#
# Смотрим ТОЛЬКО текст модели. Строку позиции собрал сервер из записи,
# и «Ибупрофен, 200 мг» в ней — сила таблетки из базы, а не назначение
import re as _re

СЛЕД_ДОЗЫ = _re.compile(
    r"(по\s+\d|\d+\s*(раз|табл|капл|мл\b|мг\b)|раз(а|ов)?\s*в\s*(день|сут))",
    _re.I)


def _дозы_в_тексте(тело):
    куски = [тело.get("вступление") or "", тело.get("нет") or "",
             тело.get("группа") or ""]
    for имя in ("нашлось", "просрочено", "рецептурные"):
        куски += [(п.get("почему") or "") for п in (тело.get(имя) or [])]
    return [к for к in куски if СЛЕД_ДОЗЫ.search(к)]


async def _вход(клиент):
    await клиент.post(БАЗА + "/login",
                      data={"email": ПОЧТА, "password": ПАРОЛЬ})
    if not клиент.cookies.get("access_token"):
        raise SystemExit("ВХОД НЕ СОСТОЯЛСЯ — спрашивать нечего")


async def _спросить(клиент, текст):
    о = await клиент.post(БАЗА + "/medkit/api/assist",
                          json={"text": текст}, timeout=90.0)
    try:
        return о.status_code, о.json()
    except ValueError:
        return о.status_code, {"error": о.text[:200]}


def _напечатать(вопрос, зачем, код, тело):
    print("─" * 70)
    print("ВОПРОС: «%s»" % вопрос)
    print("  (смотрим: %s)" % зачем)
    print("  HTTP %s, вид: %s" % (код, тело.get("вид") or "—"))
    if тело.get("error"):
        print("  ОТКАЗ: %s" % тело["error"])
        return
    if тело.get("вид") == "стоп":
        print("  повод: %s" % тело.get("повод"))
        print("  ТЕКСТ ЧЕЛОВЕКУ:")
        print("    " + (тело.get("текст") or ""))
        return
    if тело.get("вид") != "запрос":
        print("  УШЛО В ЗАВЕДЕНИЕ (маршрут решил «упаковка»)")
        print("  поля: %r" % (тело.get("поля"),))
        return
    print("  ВСТУПЛЕНИЕ: %s" % (тело.get("вступление") or "—"))
    for имя, метка in (("нашлось", "ГОДНОЕ"), ("просрочено", "ПРОСРОЧЕНО"),
                       ("рецептурные", "РЕЦЕПТУРНОЕ")):
        куча = тело.get(имя) or []
        if not куча:
            continue
        print("  %s (%d):" % (метка, len(куча)))
        for п in куча:
            print("    · %s" % п["строка"])
            if п.get("почему"):
                print("      почему: %s" % п["почему"])
            if п.get("дозы"):
                print("      (кнопка «Приём» есть — схема приёма сохранена)")
    if тело.get("группа"):
        print("  ГРУППА ДЛЯ АПТЕКИ: %s" % тело["группа"])
    if тело.get("нет"):
        print("  НЕТ: %s" % тело["нет"])
    if тело.get("подложено"):
        print("  ПОЙМАНО ИМЁН ВНЕ АПТЕЧКИ: %r" % (тело["подложено"],))
    следы = _дозы_в_тексте(тело)
    print("  C.8 след дозировки в тексте модели: %s"
          % ("НЕТ" if not следы else "ЕСТЬ — %r" % (следы,)))


# ── ЧИСЛА ПРОТИВ БАЗЫ ────────────────────────────────────────────────
#
# «Нашлось три» само по себе не значит ничего: три из скольких? Число
# в категории берётся ИЗ БАЗЫ тем же запросом, каким его берёт экран
def _в_базе():
    import sqlite3
    from database import DB_PATH
    c = sqlite3.connect("file:%s?mode=ro" % DB_PATH, uri=True)
    строки = c.execute("""
        SELECT k.name, COUNT(*) FROM medkit_categories k
          JOIN medkit_item_categories ic ON ic.category_id = k.id
          JOIN medkit_items i ON i.id = ic.item_id
         WHERE i.user_id = (SELECT id FROM users WHERE email = ?)
         GROUP BY k.name ORDER BY k.name""", (ПОЧТА,)).fetchall()
    всего = c.execute(
        "SELECT COUNT(*) FROM medkit_items WHERE user_id = "
        "(SELECT id FROM users WHERE email = ?)", (ПОЧТА,)).fetchone()[0]
    c.close()
    return всего, строки


async def прогон():
    import httpx
    async with httpx.AsyncClient(follow_redirects=True, timeout=90.0) as к:
        await _вход(к)
        for вопрос, зачем in ВОПРОСЫ:
            код, тело = await _спросить(к, вопрос)
            _напечатать(вопрос, зачем, код, тело)



def _в_базе():
    import sqlite3
    from database import DB_PATH
    c = sqlite3.connect("file:%s?mode=ro" % DB_PATH, uri=True)
    строки = c.execute("""
        SELECT k.name, COUNT(*) FROM medkit_categories k
          JOIN medkit_item_categories ic ON ic.category_id = k.id
          JOIN medkit_items i ON i.id = ic.item_id
         WHERE i.user_id = (SELECT id FROM users WHERE email = ?)
         GROUP BY k.name ORDER BY k.name""", (ПОЧТА,)).fetchall()
    всего = c.execute(
        "SELECT COUNT(*) FROM medkit_items WHERE user_id = "
        "(SELECT id FROM users WHERE email = ?)", (ПОЧТА,)).fetchone()[0]
    c.close()
    return всего, строки



def доказать_подлог(имя, поз_по_имени):
    """НЕЗАВИСИМЫЙ замер того, что подлог собирался изменить.

    Не «скрипт подставился», а «состояние отличается»: подлог, который
    не состоялся, даёт ровно тот же вердикт, что слепая проба (§6.0.3).
    Замер идёт ПО БАЗЕ, мимо всей цепочки ответа.
    """
    if имя == "номер-вне-аптечки":
        # Есть ли в аптечке строка с таким номером
        return ("номер 99999 в аптечке", 99999 in поз_по_имени["номера"])
    if имя == "имя-вне-аптечки":
        # Есть ли такие названия среди позиций человека
        имена = {и.lower() for и in поз_по_имени["имена"]}
        return ("«парацетамол»/«но-шпа»/«ибуклин» среди названий",
                sorted(имена & {"парацетамол", "но-шпа", "ибуклин"}))
    if имя == "просроченное-как-вариант":
        return ("просроченных позиций в базе", len(поз_по_имени["просрочены"]))
    if имя == "дозировка-в-тексте":
        # ДОКАЗАТЕЛЬСТВО НЕЗАВИСИМО ОТ ВЕРДИКТА ПРОБЫ: спрашиваем сам
        # признак — видит ли он дозу в подложенных строках. Не видит —
        # ломать нечего, и «НАЙДЕН» после такого подлога означал бы
        # только то, что ответ отбросили по ДРУГОЙ причине
        import main as _m
        строки = [ПОДЛОГИ[имя]["нет"]]
        return ("строк с дозировкой в подлоге", len(_m._апт_след_дозы(строки)))
    if имя == "свойство-в-подписи":
        # ДОКАЗАТЕЛЬСТВО НЕЗАВИСИМО ОТ ВЕРДИКТА: слова «спазмолитик»
        # не должно быть НИ В ОДНОЙ карточке. Есть — подлог не подлог,
        # а правдивая подпись, и ловить его было бы не за что
        подпись = ПОДЛОГИ[имя]["почему"]["1"].lower()
        поля = " ".join(поз_по_имени["текст_карточек"]).lower()

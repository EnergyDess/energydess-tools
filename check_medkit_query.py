ПОДЛОГИ = {
    "номер-вне-аптечки": {
        "вступление": "Вот что подойдёт.",
        "подходят": [99999, 1],
        "почему": {"99999": "подходит", "1": "подходит"},
    },
    "имя-вне-аптечки": {
        "вступление": "У вас есть Парацетамол и Но-шпа, оба подойдут.",
        "подходят": [1],
        "почему": {"1": "рядом лежит Ибуклин"},
    },
    "просроченное-как-вариант": {
        "вступление": "Вот что подойдёт.",
        "подходят": ["ПРОСРОЧЕННЫЙ"],
        "почему": {},
    },
}


def доказать_подлог(имя, поз_по_имени):
    """НЕЗАВИСИМЫЙ замер того, что подлог собирался изменить.

    Не «скрипт подставился», а «состояние отличается»: подлог, который
    не состоялся, даёт ровно тот же вердикт, что слепая проба (§6.0.3).
    Замер идёт ПО БАЗЕ, мимо всей цепочки ответа.
    """
    if имя == "номер-вне-аптечки":
        # Есть ли в аптечке строка с таким номером
        return ("номер 99999 в аптечке", 99999 in поз_по_имени["номера"])
    if имя == "имя-вне-аптечки":
        # Есть ли такие названия среди позиций человека
        имена = {и.lower() for и in поз_по_имени["имена"]}
        return ("«парацетамол»/«но-шпа»/«ибуклин» среди названий",
                sorted(имена & {"парацетамол", "но-шпа", "ибуклин"}))
    if имя == "просроченное-как-вариант":
        return ("просроченных позиций в базе", len(поз_по_имени["просрочены"]))
    return ("нечего доказывать", None)


async def контроль():
    os.environ.setdefault("DB_PATH", "app.db")
    import main
    from database import SessionLocal, User

    db = SessionLocal()
    user = db.query(User).filter(User.email == ПОЧТА).first()
    if not user:
        raise SystemExit("аккаунта съёмки нет — контролю не на чём работать")
    позиции, _ = main._апт_позиции_для_запроса(db, user)
    факты = {
        "номера": {п["id"] for п in позиции},
        "имена": {п["name"] for п in позиции},
        "просрочены": [п for п in позиции if п["состояние"] == "expired"],
    }
    print("НА СТЕНДЕ: позиций %d, просроченных %d"
          % (len(позиции), len(факты["просрочены"])))
    if not факты["просрочены"]:
        print("ОСТАНОВЛЕНО: просроченных на стенде нет — третьему подлогу "
              "ломать нечего. Контроль без прогона всех трёх недействителен.")
        return 0

    найдено = 0
    не_состоялось = 0
    for имя, ответ in ПОДЛОГИ.items():
        подстановка = json.loads(json.dumps(ответ))
        if подстановка.get("подходят") == ["ПРОСРОЧЕННЫЙ"]:
            подстановка["подходят"] = [факты["просрочены"][0]["id"]]

        что, значение = доказать_подлог(имя, факты)
        # ПОДЛОГ СОСТОЯЛСЯ, ЕСЛИ ЕМУ БЫЛО ЧТО ЛОМАТЬ. Номер 99999 обязан
        # отсутствовать в базе, названия — тоже, просроченное — быть.
        # Не сошлось — подлог пустая операция, и «НАЙДЕН» после него
        # неотличим от вердикта слепой пробы (§6.0.3)
        состоялся = (значение is False) or (значение == []) or (
            isinstance(значение, int) and значение > 0)
        print("─" * 70)
        print("ПОДЛОГ «%s»" % имя)
        print("  доказательство: %s = %r → подлог %s"
              % (что, значение, "состоялся" if состоялся else "ПУСТОЙ"))
        if not состоялся:
            не_состоялось += 1
            print("  ПОДЛОГ НЕ СОСТОЯЛСЯ — ломать было нечего, вердикт "
                  "пробы ничего не значит")
            continue

        было = main._апт_спросить_модель

        async def подделка(промпт, очищать=True, _о=подстановка):
            return _о, "", 200

        main._апт_спросить_модель = подделка
        try:
            итог = asyncio.get_event_loop() and await main._апт_ответ_на_запрос(
                "болит живот", db, user)
        finally:
            main._апт_спросить_модель = было

        поймал = False
        if имя == "номер-вне-аптечки":
            все = [п["id"] for куча in ("нашлось", "просрочено", "рецептурные")
                   for п in итог[куча]]
            поймал = 99999 not in все
            print("  проба: номеров в ответе %r — 99999 %s"
                  % (все, "ВЫБРОШЕН" if поймал else "ПРОЕХАЛ"))
        elif имя == "имя-вне-аптечки":
            поймал = bool(итог["подложено"])
            print("  проба: имена вне аптечки %r, вступление наружу: %r"
                  % (итог["подложено"], итог["вступление"][:60]))
        else:
            поймал = (not итог["нашлось"]) and bool(итог["просрочено"])
            print("  проба: годных %d, просроченных %d"
                  % (len(итог["нашлось"]), len(итог["просрочено"])))
        print("  %s" % ("НАЙДЕН" if поймал else "НЕ НАЙДЕН — проба слепа"))
        найдено += 1 if поймал else 0
    db.close()
    print("─" * 70)
    print("ИТОГ КОНТРОЛЯ: найдено %d из %d, не состоялось подлогов %d"
          % (найдено, len(ПОДЛОГИ), не_состоялось))
    return 0


def main_():
    if КОНТРОЛЬ:
        return asyncio.run(контроль())
    всего, по_категориям = _в_базе()
    print("АПТЕЧКА СТЕНДА: позиций %d" % всего)
    for имя, n in по_категориям:
        print("   %-24s %d" % (имя, n))
    print()
    asyncio.run(прогон())
    print("─" * 70)
    print("Код возврата 0 всегда: это МЕРКА, а не проверка. Ответ модели "
          "не наш код, и порога тут назначать нечему.")
    return 0


if __name__ == "__main__":
    sys.exit(main_())

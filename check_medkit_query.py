def _вызовов(тело):
    """СКОЛЬКО ЖИВЫХ ВЫЗОВОВ МОДЕЛИ СТОИЛ ЭТОТ ОТВЕТ.

    Считается ПО МАРШРУТУ, который ответ и прошёл, а не по намерению
    кода: стоп-состояние решает заслон до модели (0), заведение —
    один вызов, запрос — два (маршрут плюс сам запрос). Число,
    вписанное руками, протухло бы на первой же правке маршрута.
    """
    вид = тело.get("вид")
    if вид == "стоп":
        return 0
    return 2 if вид == "запрос" else 1


def _видимое(тело):
    """ЧТО ЧЕЛОВЕК ПРОЧИТАЕТ, а не что лежит в ответе сервера.

    Повторяет сборку строки в `аптАИПоказатьЗапрос` (`medkit.html`):
    печатать поле `нет`, которого браузер не показывает, значило бы
    мерить не тот экран. Ровно этим дефект A.3 и оказался — сервер
    слал объяснение, а фронт его выбрасывал, когда карточка нашлась.
    """
    if тело.get("вид") == "стоп":
        return тело.get("текст") or ""
    if тело.get("вид") != "запрос":
        return "(заведение карточки)"
    сколько = sum(len(тело.get(к) or [])
                  for к in ("нашлось", "просрочено", "рецептурные"))
    пусто = not сколько
    части = [тело.get("вступление") or ""]
    if тело.get("нет"):
        части.append(тело["нет"])
    if пусто and тело.get("группа"):
        части.append("Искать в аптеке: " + тело["группа"])
    видно = " ".join(ч for ч in части if ч).strip()
    if сколько:
        видно = (видно + "  [карточек: %d]" % сколько).strip()
    return видно



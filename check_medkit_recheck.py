ЗНАКОВ_В_КАРТОЧКЕ_WER = 634927


def страница(n=ЗНАКОВ_В_КАРТОЧКЕ_WER):
    """Строка ТОГО ЖЕ ВЕСА В ПАМЯТИ, что боевая страница.

    ЗНАК ВНЕ BMP ОБЯЗАТЕЛЕН, и это нашла сама проба. Кириллица
    лежит в памяти по ДВА байта на знак (UCS-2), а боевая страница
    wer.ru — по ЧЕТЫРЕ: 634 927 знаков против 2480 КБ, замер
    с прода. Значит на ней есть знак вне BMP, и Python держит
    ВСЮ строку в UCS-4.

    Без него проба занижала вес ВДВОЕ — то есть мерила бы кеш
    вполовину легче боевого и объявляла бы порядок там, где его нет.
    """
    return "😀" + "я" * (n - 1)


def вес_кеша_мб():
    return M._реф_кеш_вес() / 1048576.0


def налить(сколько, размер=ЗНАКОВ_В_КАРТОЧКЕ_WER):
    """Положить в кеш `сколько` страниц ТЕМ ЖЕ путём, что и сервер."""
    M._реф_кеш.clear()
    for i in range(сколько):
        M._реф_кеш["http://проба/%d" % i] = (M.time.time(), страница(размер))
        M._реф_кеш_подрезать()


def проверка_память():
    """ВОПРОС 1: держится ли кеш в потолке при страницах боевого веса."""
    print("=" * 62)
    print("ПАМЯТЬ: кеш страниц против объявленного потолка")
    print("=" * 62)
    потолок = M.REF_CACHE_MB
    print("потолок объявлен: %.0f МБ (MEDKIT_REF_CACHE_MB)" % потолок)
    print("страница подаётся боевого веса: %d знаков, %.2f МБ объектом"
          % (ЗНАКОВ_В_КАРТОЧКЕ_WER, sys.getsizeof(страница()) / 1048576.0))
    беда = 0
    for сколько in (10, 50, 200, 400):
        налить(сколько)
        вес = вес_кеша_мб()
        плохо = вес > потолок + 0.01
        беда += плохо
        print("   налито %3d страниц -> в кеше %3d, вес %6.1f МБ  %s"
              % (сколько, len(M._реф_кеш), вес,
                 "ВЫШЕ ПОТОЛКА" if плохо else "в потолке"))
    # ВТОРАЯ ПОЛОВИНА: кеш обязан ОСТАВАТЬСЯ ПОЛЕЗНЫМ. Потолок, при
    # котором в кеше не держится ни одной страницы, — это отсутствие
    # кеша, и он прошёл бы первую половину с блеском
    налить(3)
    if len(M._реф_кеш) < 3:
        print("   ПЛОХО: три страницы подряд не удержались — кеша нет")
        беда += 1
    else:
        print("   три страницы подряд держатся — кеш работает")
    M._реф_кеш.clear()
    return беда



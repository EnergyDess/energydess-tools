# -*- coding: utf-8 -*-
"""РАСХОД ЧУЖОГО СПРАВОЧНИКА: числа — В АДМИНКЕ, предупреждение — в аптечке.

ЗДЕСЬ БЫЛА МЕРКА СТРОКИ «733/3000» НА ЭКРАНЕ АПТЕЧКИ (BACKLOG №315),
и она отвечала на вопросы «виден ли расход без нажатий» и «не показан
ли постороннему». Решением владельца (№352, «аптечка-1», блок 2.3)
числа переехали на `/admin/usage`, а в аптечке осталось ПРЕДУПРЕЖДЕНИЕ
и только при ≥90 % предела. Вопросы поэтому сменились, а не исчезли:

  1. ЧИСЛА НА МЕСТЕ. Строка на `/admin/usage` есть, называет то же
     число, что лежит в журнале `ref_requests` за месяц, и предел.
  2. НА ЭКРАНЕ АПТЕЧКИ ЧИСЕЛ НЕТ. Ни строки, ни полоски — ни владельцу,
     ни участнику круга. Спрашиваются ОБА: «нет у соседа» прошло бы
     и у пробы, которая ничего не видит (§6.0.3).
  3. ПРЕДУПРЕЖДЕНИЕ ПОЯВЛЯЕТСЯ ПО ДОЛЕ, и порог тот же, что у сервера:
     до 90 % его нет, от 90 % есть, при исчерпании текст ДРУГОЙ —
     «не сработает», а не «может не сработать». Доля меняется числом
     В ЖУРНАЛЕ СТЕНДА и возвращается в `finally`: признак считает
     сервер, и подстановкой в страницу его не проверить — пришлось бы
     подменить ровно то, что проверяется.
  4. ВИДЯТ ВСЕ. Предупреждение — предсказание отказа для того, кто
     нажмёт «Поискать в справочнике», поэтому оно есть и у участника
     круга, не только у владельца (отличие от прежней строки с числами).

МЕРКА, код возврата 0 (кроме `--контроль`), 2 — спросить нечем.
Боевую базу не открывает: путь с `/data/` отвергается.

ГОЛОВНОЙ БРАУЗЕР НЕ НУЖЕН: ширины здесь ничего не решают — спрашивается
наличие строки и её текст, а не раскладка (§6.0.3, обратная сторона
правила: видимое окно только у замеров вёрстки).

    py check_medkit_ref.py             # все четыре вопроса
    py check_medkit_ref.py --контроль  # подлог: предупреждения нет при пределе
"""
import datetime
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
os.environ.setdefault("DB_PATH", "app.db")

import check_hover as ch     # noqa: E402
import make_local_user as _сид  # noqa: E402
import probe_guard  # noqa: F401

sys.stdout.reconfigure(encoding="utf-8")

NL = chr(10)
БАЗА = os.environ.get("STAND", "http://127.0.0.1:8899")
ПРЕДЕЛ = int(os.environ.get("MEDKIT_REF_MONTH_CAP", "3000"))

# ПОДЛОГ ЛОМАЕТ ЗВЕНО, КОТОРОЕ ПРОВЕРЯЕТСЯ: предупреждение при
# исчерпанном пределе. Узел остаётся в дереве, но не показывается —
# ровно тот немой отказ, ради которого мерка и написана.
ПОДЛОГ = """
(() => {
  addEventListener('DOMContentLoaded', () => {
    const s = document.createElement('style');
    s.textContent = '.apt-ref-warn { display: none !important; }';
    document.head.appendChild(s);
  });
})();
"""

# ДОКАЗАТЕЛЬСТВО ПОДЛОГА (§6.0.3) — независимо от вердикта мерки.
# «Предупреждения не видно» это её вердикт; доказательство спрашивает
# ДРУГОЕ: лежит ли узел в дереве. Отсутствие узла и погашенный узел —
# разные случаи, и различить их может только этот замер.
ДОКАЗАТЕЛЬСТВО = ("""() => {
  const э = document.querySelector('.apt-ref-warn');
  if (!э) return 'узла .apt-ref-warn в дереве НЕТ';
  return 'узел есть, display=' + getComputedStyle(э).display
       + ', высота ' + э.getBoundingClientRect().height.toFixed(1);
}""", "узел предупреждения: есть ли он в дереве и чем погашен")

ЗАМЕР_АПТЕЧКИ = r"""
() => {
  const пред = document.querySelector('.apt-ref-warn');
  const видно = э => !!э && getComputedStyle(э).display !== 'none'
                  && э.getBoundingClientRect().height > 0;
  return {
    // ЧИСЕЛ НА ЭКРАНЕ БЫТЬ НЕ ДОЛЖНО: ни прежней строки, ни полоски
    строка_чисел: !!document.querySelector('.apt-quota'),
    полоска: !!document.querySelector('.apt-quota-meter'),
    предупреждение: видно(пред),
    текст: пред ? пред.innerText.replace(/\s+/g, ' ').trim() : null,
  };
}
"""

ЗАМЕР_АДМИНКИ = r"""
() => {
  const э = document.getElementById('usage-ref');
  if (!э) return {есть: false};
  return {есть: true,
          текст: э.innerText.replace(/\s+/g, ' ').trim(),
          видно: getComputedStyle(э).display !== 'none'};
}
"""


def _снять(адрес, замер, подлог=None, почта=None, пароль=None):
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=True)
        стр = бр.new_context(viewport={"width": 1440, "height": 900}).new_page()
        прежние = (ch.ПОЧТА, ch.ПАРОЛЬ)
        try:
            if почта:
                ch.ПОЧТА, ch.ПАРОЛЬ = почта, пароль
            ch._войти(стр)
        finally:
            ch.ПОЧТА, ch.ПАРОЛЬ = прежние
        if подлог:
            стр.add_init_script(подлог)
        стр.goto(БАЗА + адрес, wait_until="load", timeout=45000)
        стр.wait_for_timeout(600)
        о = стр.evaluate(замер)
        доказ = стр.evaluate(ДОКАЗАТЕЛЬСТВО[0]) if подлог else None
        бр.close()
    return о, доказ


def _журнал():
    """(соединение, месяц, прежние строки). Боевую базу не открываем."""
    путь = os.environ.get("DB_PATH", "app.db")
    if "/data/" in путь.replace(chr(92), "/"):
        return None, None, None
    месяц = datetime.datetime.now(datetime.UTC).strftime("%Y-%m") + "%"
    c = sqlite3.connect(путь)
    было = c.execute("SELECT id, day, host, n FROM ref_requests "
                     "WHERE day LIKE ?", (месяц,)).fetchall()
    return c, месяц, было


def _поставить(c, месяц, n):
    день = datetime.datetime.now(datetime.UTC).strftime("%Y-%m-%d")
    c.execute("DELETE FROM ref_requests WHERE day LIKE ?", (месяц,))
    c.execute("INSERT INTO ref_requests (day, host, n) VALUES (?,?,?)",
              (день, "проба", n))
    c.commit()


def _вернуть(c, месяц, было):
    c.execute("DELETE FROM ref_requests WHERE day LIKE ?", (месяц,))
    for _, d, h, n in было:
        c.execute("INSERT INTO ref_requests (day, host, n) VALUES (?,?,?)",
                  (d, h, n))
    c.commit()
    оста = c.execute("SELECT COALESCE(SUM(n),0) FROM ref_requests "
                     "WHERE day LIKE ?", (месяц,)).fetchone()[0]
    c.close()
    return оста


# Доли, на которых спрашивается предупреждение. 0.50 и 0.89 — «молчит»,
# 0.90 — граница, 1.00 — исчерпан (текст другой).
ДОЛИ = [("тихо", 0.50, False), ("почти порог", 0.89, False),
        ("порог 90 %", 0.90, True), ("исчерпан", 1.00, True)]


def главная():
    плохо = 0
    c, месяц, было = _журнал()
    if c is None:
        print("ПРОПУСК: путь похож на боевую базу — не открываю")
        return 2

    # ── 1. ЧИСЛА В АДМИНКЕ ──────────────────────────────────────────
    try:
        _поставить(c, месяц, 733)
        а, _ = _снять("/admin/usage", ЗАМЕР_АДМИНКИ)
        print("1. СТРОКА НА /admin/usage: %s" % ("есть" if а.get("есть") else "НЕТ"))
        print("   текст: %s" % а.get("текст"))
        ок1 = bool(а.get("есть")) and а.get("видно") and "733" in (а.get("текст") or "") \
            and str(ПРЕДЕЛ) in (а.get("текст") or "")
        print("   число из журнала (733) и предел (%d) названы: %s"
              % (ПРЕДЕЛ, "да" if ок1 else "НЕТ"))
        плохо += not ок1

        # ── 2. НА ЭКРАНЕ АПТЕЧКИ ЧИСЕЛ НЕТ ──────────────────────────
        вл, _ = _снять("/medkit", ЗАМЕР_АПТЕЧКИ)
        сос, _ = _снять("/medkit", ЗАМЕР_АПТЕЧКИ, почта=_сид.EMAIL_СОСЕД,
                        пароль=_сид.PASSWORD_СОСЕД)
        print(NL + "2. ЧИСЕЛ НА ЭКРАНЕ АПТЕЧКИ НЕТ:")
        print("   владелец: строка %s, полоска %s"
              % (вл["строка_чисел"], вл["полоска"]))
        print("   сосед:    строка %s, полоска %s"
              % (сос["строка_чисел"], сос["полоска"]))
        ок2 = not any((вл["строка_чисел"], вл["полоска"],
                       сос["строка_чисел"], сос["полоска"]))
        плохо += not ок2

        # ── 3–4. ПРЕДУПРЕЖДЕНИЕ ПО ДОЛЕ, И ВИДЯТ ЕГО ВСЕ ────────────
        print(NL + "3. ПРЕДУПРЕЖДЕНИЕ ПО ДОЛЕ (порог сервера — 90 %):")
        for имя, доля, ждём in ДОЛИ:
            _поставить(c, месяц, int(ПРЕДЕЛ * доля))
            о, _ = _снять("/medkit", ЗАМЕР_АПТЕЧКИ)
            сошлось = о["предупреждение"] == ждём
            плохо += not сошлось
            print("   %-12s %4.0f%%  предупреждение %-5s (ждём %-5s) %s"
                  % (имя, доля * 100, о["предупреждение"], ждём,
                     "" if сошлось else "  ← ПЛОХО"))
            if о["предупреждение"]:
                print("                текст: %s" % о["текст"])
                # ПРИ ИСЧЕРПАНИИ ТЕКСТ ДРУГОЙ: «не сработает» против
                # «может не сработать» — это разные обещания
                if доля >= 1.0:
                    строго = "не сработает" in (о["текст"] or "")
                    плохо += not строго
                    print("                при исчерпании сказано прямо: %s"
                          % ("да" if строго else "НЕТ"))
        # ВИДЯТ ВСЕ: на исчерпанном пределе спрашивается и сосед
        сос2, _ = _снять("/medkit", ЗАМЕР_АПТЕЧКИ, почта=_сид.EMAIL_СОСЕД,
                         пароль=_сид.PASSWORD_СОСЕД)
        print(NL + "4. ВИДЯТ ВСЕ: у соседа по кругу предупреждение %s"
              % сос2["предупреждение"])
        плохо += not сос2["предупреждение"]
    finally:
        print(NL + "   журнал возвращён: за месяц %d" % _вернуть(c, месяц, было))

    print(NL + "ИТОГ: плохих ответов %d" % плохо)
    return 0


def контроль():
    print("КОНТРОЛЬ: подлог гасит предупреждение при ИСЧЕРПАННОМ пределе.")
    print("Мерка обязана назвать это, а не промолчать." + NL)
    c, месяц, было = _журнал()
    if c is None:
        print("ПРОПУСК: путь похож на боевую базу — не открываю")
        return 2
    итог = {}
    try:
        _поставить(c, месяц, ПРЕДЕЛ)
        for метка, подлог in (("чисто", None), ("подлог", ПОДЛОГ),
                              ("возврат", None)):
            о, доказ = _снять("/medkit", ЗАМЕР_АПТЕЧКИ, подлог)
            итог[метка] = о["предупреждение"]
            print("  %-8s предупреждение %s" % (метка, о["предупреждение"]))
            if доказ:
                print("           ДОКАЗАТЕЛЬСТВО (%s): %s"
                      % (ДОКАЗАТЕЛЬСТВО[1], доказ))
    finally:
        _вернуть(c, месяц, было)
    ок = итог["чисто"] and not итог["подлог"] and итог["возврат"]
    print(NL + "  КОНТРОЛЬ: %s — %s -> %s -> %s"
          % ("ПОДЛОГ НАЙДЕН" if ок else "НЕ ДОКАЗАН",
             итог["чисто"], итог["подлог"], итог["возврат"]))
    return 0 if ок else 1


if __name__ == "__main__":
    sys.exit(контроль() if "--контроль" in sys.argv else главная())

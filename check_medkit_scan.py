# ── C.1.а: ОБРАЗЦЫ КОДОВ ──────────────────────────────────────────────
#
# СТРУКТУРА КОДА ЛЕКАРСТВА взята из открытой документации ГИС МТ
# («Честный знак»): это GS1 DataMatrix, а не EAN-13. Внутри — группы
# с идентификаторами применения:
#
#   (01) GTIN, 14 цифр       — ЧТО за товар. Единственная группа,
#                              одинаковая у всех пачек одного лекарства
#   (21) серийный, 13 знаков — уникален для КАЖДОЙ пачки
#   (91) ключ проверки, 4
#   (92) код проверки, 44    — криптоподпись
#
# Разделитель групп переменной длины — FNC1, он же <GS>, ASCII 29.
#
# ЭТО И ЕСТЬ ГЛАВНОЕ ОТЛИЧИЕ ОТ ЕДЫ: у еды весь код — это GTIN, и он
# один на все пачки. У лекарства GTIN занимает меньше четверти строки,
# а остальное у каждой пачки СВОЁ. Сканер, отдающий строку целиком,
# по ней не найдёт ничего даже в собственной базе — второй раз тот же
# препарат придёт с другим кодом.
GS = chr(29)
ОБРАЗЕЦ_ЛЕКАРСТВА = (
    "01046012345678902155aBcDeFgHiJ1" + GS + "91EE10" + GS
    + "92dGVzdC1jcnlwdG8tdGFpbC1mb3ItbWVhc3VyZW1lbnQ="
)
# EAN-13 с ВЕРНОЙ контрольной цифрой. Первая версия пробы взяла
# «4600000000000» с потолка, и декодер честно отказался — а вывод читался бы
# как «библиотека не умеет EAN», хотя не умела считать проба. Контрольная
# цифра теперь СЧИТАЕТСЯ, а не вписывается.
def _ean13_с_контролем(двенадцать: str) -> str:
    ц = [int(с) for с in двенадцать[:12]]
    сумма = sum(ц[::2]) + sum(ц[1::2]) * 3
    return двенадцать[:12] + str((10 - сумма % 10) % 10)


ОБРАЗЕЦ_ЕДЫ = _ean13_с_контролем("460000000000")   # как в дневнике питания


def _png_из_матрицы(матрица, масштаб=6, поле=4):
    """Чёрно-белый PNG из матрицы нулей и единиц. Поле обязательно:
    без тихой зоны декодер не находит код вовсе, и «не прочиталось»
    означало бы дефект картинки, а не библиотеки."""
    from PIL import Image
    h, w = len(матрица), len(матрица[0])
    img = Image.new("L", (w + поле * 2, h + поле * 2), 255)
    px = img.load()
    for y, ряд in enumerate(матрица):
        for x, б in enumerate(ряд):
            if б:
                px[x + поле, y + поле] = 0
    img = img.resize(((w + поле * 2) * масштаб, (h + поле * 2) * масштаб),
                     Image.NEAREST)
    буфер = io.BytesIO()
    img.save(буфер, "PNG")
    return буфер.getvalue()


def _картинка_datamatrix(данные: str):
    """PNG с DataMatrix. None — рисовать нечем, и это ГОВОРИТСЯ ВСЛУХ:
    отсутствие картинки нельзя показывать как «формат не читается»."""
    try:
        from ppf.datamatrix import DataMatrix
    except Exception as e:
        return None, f"ppf-datamatrix нет: {type(e).__name__}"
    try:
        return _png_из_матрицы(DataMatrix(данные).matrix), None
    except Exception as e:
        return None, f"кодирование упало: {type(e).__name__}: {e}"


# EAN-13 рисуется своими руками: python-barcode на машине нет, а таблица
# кодирования умещается в двадцать строк. Второй зависимости ради одного
# контрольного образца заводить незачем.
_EAN_L = ("0001101", "0011001", "0010011", "0111101", "0100011",
          "0110001", "0101111", "0111011", "0110111", "0001011")
_EAN_G = ("0100111", "0110011", "0011011", "0100001", "0011101",
          "0111001", "0000101", "0010001", "0001001", "0010111")
_EAN_R = ("1110010", "1100110", "1101100", "1000010", "1011100",
          "1001110", "1010000", "1000100", "1001000", "1110100")
_EAN_ЧЁТ = ("LLLLLL", "LLGLGG", "LLGGLG", "LLGGGL", "LGLLGG",
            "LGGLLG", "LGGGLL", "LGLGLG", "LGLGGL", "LGGLGL")


def _картинка_ean13(цифры: str):
    try:
        ц = [int(с) for с in цифры[:13]]
        if len(ц) != 13:
            return None, "нужно 13 цифр"
        биты = "101"
        схема = _EAN_ЧЁТ[ц[0]]
        for i, с in enumerate(ц[1:7]):
            биты += (_EAN_L if схема[i] == "L" else _EAN_G)[с]
        биты += "01010"
        for с in ц[7:]:
            биты += _EAN_R[с]
        биты += "101"
        матрица = [[int(б) for б in биты] for _ in range(60)]
        return _png_из_матрицы(матрица, масштаб=3, поле=10), None
    except Exception as e:
        return None, f"генерация упала: {type(e).__name__}: {e}"


def _картинка_шума():
    """ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: заведомо нечитаемое.

    Без него «прочитала N из N» неотличимо от пробы, объявляющей успех
    не глядя.
    """
    сл = random.Random(20260824)
    матрица = [[сл.choice((0, 1)) for _ in range(40)] for _ in range(40)]
    return _png_из_матрицы(матрица, масштаб=6, поле=4)



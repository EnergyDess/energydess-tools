def _крпт_подробно():
    """ОТВЕТ ЦРПТ ЦЕЛИКОМ И С ОТРИЦАТЕЛЬНЫМ КОНТРОЛЕМ.

    «Сервис ответил 200» само по себе не значит ничего: заглушка, отдающая
    один и тот же объект на что угодно, отвечает ровно так же. Поэтому
    рядом с выдуманным кодом ПРАВИЛЬНОЙ структуры идёт заведомый мусор:
    ответы обязаны РАЗОЙТИСЬ, иначе разбирать нечего.
    """
    import httpx
    import json as _js
    print("  ── ЦРПТ ПОДРОБНО: тело целиком плюс отрицательный контроль ──")
    print()
    случаи = [
        ("выдуманный код ПРАВИЛЬНОЙ структуры", ОБРАЗЕЦ_ЛЕКАРСТВА),
        ("заведомый мусор (контроль)", "нет-такого-кода-совсем"),
        ("пусто (контроль)", ""),
    ]
    тела = {}
    for имя, код in случаи:
        try:
            with httpx.Client(timeout=12) as c:
                r = c.post("https://mobile.api.crpt.ru/mobile/check",
                           json={"code": код})
            try:
                тело = r.json()
            except Exception:
                тело = {"_не_json": r.text[:200]}
            тела[имя] = тело
            print(f"    {имя}: HTTP {r.status_code}")
            print(f"      поля ответа ({len(тело)}): "
                  f"{', '.join(sorted(тело)) if isinstance(тело, dict) else '—'}")
            if isinstance(тело, dict):
                for к in ("codeFounded", "checkResult", "productName",
                          "productGroupId", "status", "errorMessage",
                          "errorCode"):
                    if к in тело:
                        print(f"      {к} = {тело[к]!r}")
        except Exception as e:
            print(f"    {имя}: НЕ ОТВЕТИЛ — {type(e).__name__}: {str(e)[:100]}")
        print()
    a = тела.get("выдуманный код ПРАВИЛЬНОЙ структуры")
    b = тела.get("заведомый мусор (контроль)")
    if isinstance(a, dict) and isinstance(b, dict):
        if _js.dumps(a, sort_keys=True, default=str) ==            _js.dumps(b, sort_keys=True, default=str):
            print("    ⚠ КОНТРОЛЬ ПРОВАЛЕН: на верную структуру и на мусор")
            print("      ответ ОДИНАКОВ — значит сервис код не разбирает,")
            print("      и «200» тут ничего не доказывает.")
        else:
            расх = sorted(set(a) ^ set(b)) or [
                к for к in a if к in b and a[к] != b[к]]
            print("    контроль пройден: ответы РАЗОШЛИСЬ, сервис код")
            print(f"      действительно разбирает. Разница по полям: {расх}")
    print()



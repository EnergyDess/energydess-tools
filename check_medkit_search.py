import os
import sqlite3
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
os.environ.setdefault("DB_PATH", "app.db")

import medkit_defs as опр                                # noqa: E402

# Запросы по умолчанию — четыре формы, названные постановкой E.3:
# одна буква, часть слова, слово целиком, слово из вещества
# ИМЕНА ВЗЯТЫ ОБЩЕИЗВЕСТНЫЕ И СВЕРЕНЫ С БОЕВОЙ БАЗОЙ (§8.0): ни одно
# не встречается ни в названиях, ни в веществах аптечки владельца.
# Первая версия несла имя, которое стоит в НАЗВАНИИ одной его
# позиции, и проверка 26 это немедленно нашла (+1 слово к 171)
ЗАПРОСЫ = ["п", "валид", "валидол", "корвалол"]


def главная():
    путь = "app.db"
    if "--база" in sys.argv:
        путь = sys.argv[sys.argv.index("--база") + 1]
    if "/data/" in путь.replace("\\", "/"):
        print("БОЕВАЯ БАЗА НЕ ОТКРЫВАЕТСЯ. Снимите копию и увезите.")
        return 0
    if not os.path.exists(путь):
        print("СПРОСИТЬ НЕЧЕМ: базы нет — %s" % путь)
        return 0
    свои = [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == "--запрос"]
    запросы = свои or ЗАПРОСЫ

    c = sqlite3.connect("file:%s?mode=ro" % путь, uri=True)
    c.row_factory = sqlite3.Row
    ряды = [dict(x) for x in c.execute("SELECT * FROM medkit_items")]
    кат = {x["id"]: x["name"] for x in c.execute(
        "SELECT * FROM medkit_categories")}
    связи = {}
    for x in c.execute("SELECT * FROM medkit_item_categories"):
        связи.setdefault(x["item_id"], []).append(кат.get(x["category_id"], ""))
    места = {x["id"]: x["name"] for x in c.execute("SELECT * FROM medkit_places")}

    def поля(п):
        ф = (опр.ФОРМА_ПО_ID.get(п["form"]) or {}).get("имя", "")
        общий = опр.нормаль(" ".join(y for y in (
            п["name"], п["substance"] or "", ф, п["note"] or "",
            п["code_gtin"] or "", места.get(п["place_id"], "") or "",
            " ".join(связи.get(п["id"], [])),
        ) if y))
        return общий, опр.нормаль(п["name"] or ""), опр.нормаль(п["substance"] or "")

    print("=" * 72)
    print("ПОИСК ПО АПТЕЧКЕ — %s" % путь)
    print("=" * 72)
    print("позиций: %d" % len(ряды))
    print()
    print("%-14s %6s %8s %8s %8s %8s" % ("запрос", "всего",
                                         "1 нач.", "2 назв.", "3 вещ.",
                                         "4 проч."))
    for q in запросы:
        н = опр.нормаль(q)
        ст = [0, 0, 0, 0]
        for п in ряды:
            общий, имя, вещ = поля(п)
            if н not in общий:
                continue
            if имя.startswith(н):
                ст[0] += 1
            elif н in имя:
                ст[1] += 1
            elif н in вещ:
                ст[2] += 1
            else:
                ст[3] += 1
        print("%-14s %6d %8d %8d %8d %8d"
              % (repr(q)[1:-1], sum(ст), ст[0], ст[1], ст[2], ст[3]))
    print()
    print("До правки порядок был порядком СЕТКИ (по сроку годности):")
    print("ступени не различались, и первым шло не то, что искали.")
    return 0


if __name__ == "__main__":
    sys.exit(главная())

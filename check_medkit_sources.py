def раздел_доз(текст_html):
    """Кусок между заголовком о дозировании и следующим того же уровня.

    ЗАГОЛОВКОМ, А НЕ ПОДСТРОКОЙ. У четырёх источников из двенадцати
    слова «способ применения» стоят в ОГЛАВЛЕНИИ страницы, а раздела
    на сервере нет вовсе — признак по подстроке объявил бы их годными
    (замер 2026-08-26).
    """
    for м in re.finditer(r"(?is)<(h[1-6])[^>]*>(.*?)</\1>", текст_html or ""):
        имя = re.sub(r"<[^>]+>", "", м.group(2)).strip().lower()
        if not any(с in имя for с in ЗАГОЛОВКИ_ДОЗ):
            continue
        уровень, начало = м.group(1), м.end()
        следующий = re.search(r"(?is)<%s[^>]*>" % уровень, текст_html[начало:])
        конец = начало + (следующий.start() if следующий else 6000)
        return имя, текст_html[начало:конец]
    return None, None


def заголовок_страницы(текст_html):
    м = re.search(r"(?is)<h1[^>]*>(.*?)</h1>", текст_html or "")
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", м.group(1))).strip() if м else ""


async def _страница(клиент, адрес):
    о = await клиент.get(адрес)

async def контроль(строки_чисто, позиции_, каталог, кеш):
    print()
    print("=" * 78)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ")
    print("=" * 78)

    # Для подлога годится позиция, чьё вещество СЕЙЧАС подтверждено

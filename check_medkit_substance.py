ПОДСКАЗКА = ("Это фотография упаковки лекарства. Прочитай с неё всё, что "
             "видно: название, действующее вещество, форму выпуска, "
             "количество в упаковке, срок годности.")


async def спросить_снимок(путь_к_фото):
    """Выписка модели по снимку — поле `видно`, как у боевого заслона.

    Промпт и вызов БОЕВЫЕ. Свой промпт дал бы ответ про поведение,
    которого на бою нет: заслон домыслов судит ровно по этой выписке.
    """
    b = open(путь_к_фото, "rb").read()
    b64 = base64.b64encode(b).decode()
    текст = await M._call_vision(b64, "image/jpeg", M._апт_промпт(ПОДСКАЗКА),
                                 M.MEDKIT_MAX_TOKENS)
    сырой = M._extract_json(текст)
    return str((сырой or {}).get("видно") or "").strip()



async def разобрать(поз, каталог_фото, кеш_выписок):
    """Один исход из пяти плюс всё, чем он обоснован."""
    вещество = (поз.get("substance") or "").strip()
    вердикт, со_страницы = await спросить_справочник(поз)

    выписка, снимок_был = None, False
    if каталог_фото and поз.get("image_path"):
        файл = os.path.join(каталог_фото, поз["image_path"] + ".jpg")
        if os.path.exists(файл):
            снимок_был = True
            ключ = поз["image_path"]
            if ключ in кеш_выписок:
                выписка = кеш_выписок[ключ]
            else:
                try:
                    выписка = await спросить_снимок(файл)
                except Exception as e:
                    print("   [снимок id=%s не прочитан: %r]"
                          % (поз["id"], e))
                    выписка, снимок_был = None, False
                else:
                    кеш_выписок[ключ] = выписка

    # СЛЕД ИЩЕТ БОЕВАЯ ФУНКЦИЯ, вторая реализация признака запрещена.
    на_упаковке = bool(выписка) and _опр.след(вещество, выписка)

    if вердикт == "совпало":
        исход = СПРАВОЧНИК
    elif на_упаковке:
        исход = УПАКОВКА
    elif вердикт == "другое":
        исход = РАСХОЖДЕНИЕ
    elif not снимок_был and вердикт in ("страницы нет", "не объявлено"):
        исход = НЕЧЕМ
    else:
        исход = ПОДОЗРИТЕЛЬНОЕ

    return {"id": поз["id"], "name": поз["name"], "вещество": вещество,
            "исход": исход, "справочник": вердикт,
            "со_страницы": со_страницы, "снимок": снимок_был,
            "видно_на_упаковке": на_упаковке, "выписка": выписка}



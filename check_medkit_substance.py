async def спросить_справочник(поз):
    """(вердикт, вещество_страницы) — что справочник знает о веществе.

    Вердикт: "совпало" | "другое" | "не объявлено" | "страницы нет".

    ОТБОР ИДЁТ БЕЗ ВЕЩЕСТВА, И ЭТО НЕ ОСЛАБЛЕНИЕ СВЕРКИ. Боевой
    `подходит` вещество учитывает — и правильно делает: он решает,
    показывать ли СХЕМУ, а чужая схема опаснее её отсутствия. Здесь
    вопрос обратный — «что справочник говорит про вещество этой
    пачки», — и отобрать страницу ПО ВЕЩЕСТВУ значило бы получить
    ответ «совпало» по построению, каким бы вещество ни было.
    """
    import httpx
    запросы = _дозы.имена_для_поиска(поз["name"])
    if not запросы:
        return "страницы нет", None
    искомое = {"название": поз["name"], "имена": запросы,
               "форма": поз.get("form"),
               "доза": поз.get("substance") or "",
               "вещество": ""}          # ← вещество НЕ участвует в отборе
    адреса = []
    async with httpx.AsyncClient(timeout=M.ДОЗЫ_ТАЙМАУТ,
                                 follow_redirects=True, verify=False) as кл:
        for запрос in запросы:
            try:
                выдача = await M._апт_страница(
                    кл, _дозы.ИСТОЧНИК_ПОИСК % quote(запрос))
            except Exception:
                continue
            if not _дозы.справочник_знает(выдача, искомое["форма"],
                                          искомое["доза"]):
                continue
            for u in _дозы.ссылки_поиска(выдача, искомое["форма"],
                                         искомое["доза"]):
                if u not in адреса:
                    адреса.append(u)
        if not адреса:
            return "страницы нет", None
        объявленные = []
        for u in адреса:
            try:
                стр = await M._апт_страница(кл, _дозы.ИСТОЧНИК_БАЗА + u)
            except Exception:
                continue
            _, детали = _дозы.подходит(искомое, стр)
            # Кандидат — совпавший по имени, форме и пролонгу.
            if not (детали["название"] and детали["форма"]
                    and детали["пролонг"]):
                continue
            if not детали["вещество_на_странице"]:
                continue
            объявленные.append(_дозы.вещество_страницы(стр))
    if not объявленные:
        return "не объявлено", None
    наше = _наше_вещество(поз)
    for в in объявленные:
        if в and _дозы.вещество_совпало(наше, "Активное вещество: %s" % в):
            return "совпало", в
    return "другое", объявленные[0]


def _наше_вещество(поз):
    """То же усечение, что делает боевой поиск схемы: до первой запятой."""
    return re.split(r"[,;(]", (поз.get("substance") or "").strip())[0].strip()



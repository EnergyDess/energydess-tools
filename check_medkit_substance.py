def печать(строки, всего, без_вещества):
    print()
    print("=" * 78)
    print("ОТКУДА ВЗЯЛОСЬ ВЕЩЕСТВО — %d позиций с заполненным полем "
          "(из %d)" % (len(строки), всего))
    print("=" * 78)
    print()
    for исход in ПОРЯДОК:
        свои = [с for с in строки if с["исход"] == исход]
        if not свои:
            continue
        print("-- %s: %d --" % (исход, len(свои)))
        for с in свои:
            хвост = ""
            if с["исход"] == РАСХОЖДЕНИЕ:
                хвост = "  <- справочник: %r" % (с["со_страницы"],)
            elif с["исход"] == ПОДОЗРИТЕЛЬНОЕ:
                хвост = "  (справочник: %s; снимок: %s)" % (
                    с["справочник"],
                    "прочитан, следа нет" if с["снимок"] else "нет")
            elif с["исход"] == НЕЧЕМ:
                хвост = "  (справочник: %s; снимка нет)" % с["справочник"]
            print("   %3d  %-34s  %-30s%s"
                  % (с["id"], (с["name"] or "")[:34],
                     с["вещество"][:30], хвост))
        print()
    print("-- ИТОГ ЧИСЛОМ --")
    print("   позиций всего:                %d" % всего)
    print("   без вещества (поле пустое):   %d" % без_вещества)
    for исход in ПОРЯДОК:
        print("   %-30s %d"
              % (исход.lower() + ":", sum(1 for с in строки
                                          if с["исход"] == исход)))
    print()



def позиции(путь):
    """Копия базы, только на чтение. Боевую не открываем вовсе."""
    полный = os.path.abspath(путь).replace(os.sep, "/")
    if "/data/" in полный:
        raise SystemExit(
            "ОСТАНОВЛЕНО: путь ведёт на том Fly. Это боевая база;\n"
            "снимите копию (make_backup.py) и укажите её.")
    c = sqlite3.connect("file:%s?mode=ro" % полный, uri=True)
    c.row_factory = sqlite3.Row
    поля = ("id name substance form unit dose qty_total image_path "
            "dosage_hint_substance").split()
    из = [dict((k, r[k]) for k in поля)
          for r in c.execute("SELECT * FROM medkit_items ORDER BY id")]
    c.close()
    return из



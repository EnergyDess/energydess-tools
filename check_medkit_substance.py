async def main_():
    р = argparse.ArgumentParser(add_help=True)
    р.add_argument("--база", required=True, help="копия базы, только чтение")
    р.add_argument("--фото", default=None, help="каталог со снимками")
    р.add_argument("--контроль", action="store_true")
    р.add_argument("--без-кеша", action="store_true")
    р.add_argument("--вывод", default=None,
                   help="куда положить json разбора (НЕ в репозиторий)")
    а = р.parse_args()

    if not а.без_кеша:
        _всё.включить_кеш()
        print("[кеш] страницы берутся из %s (см. шапку check_medkit_all)"
              % _всё.КЕШ)
    if not а.фото:
        print("[снимки] каталог не указан — ветка упаковки НЕ спрашивалась.")
        print("         «не проверялось» и «на фото не видно» — разные "
              "ответы (§6.0.1).")

    все = позиции(а.база)
    с_веществом = [p for p in все if (p.get("substance") or "").strip()]
    кеш, строки = {}, []
    for i, поз in enumerate(с_веществом, 1):
        print("  [%2d/%2d] id=%d" % (i, len(с_веществом), поз["id"]),
              end="\r", flush=True)
        строки.append(await разобрать(поз, а.фото, кеш))
    print(" " * 30, end="\r")

    печать(строки, len(все), len(все) - len(с_веществом))

    if а.вывод:
        json.dump(строки, open(а.вывод, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=1)
        print("[разбор] json: %s" % а.вывод)

    if а.контроль:
        await контроль(строки, с_веществом, а.фото, кеш)

    # МЕРКА: код возврата всегда 0.
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main_()))

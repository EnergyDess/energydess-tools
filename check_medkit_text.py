ПОДЛОГ = " Например: по 2 таблетки 3 раза в день."
ЯКОРЬ = "'Не разобрал ничего пригодного."
ДОКАЗАТЕЛЬСТВА = {"схема в запасной строке черновика":
                  "литералов medkit.html с подложенной фразой"}


def контроль():
    пр = признаки()
    отн = "templates/medkit.html"
    исход = io.open(os.path.join(КОРЕНЬ, отн), encoding="utf-8").read()
    if исход.count(ЯКОРЬ) != 1:
        print("КОНТРОЛЬ ОСТАНОВЛЕН: якорь запасной строки найден %d раз"
              % исход.count(ЯКОРЬ))
        return 2
    i = исход.index(ЯКОРЬ) + len(ЯКОРЬ)
    подложено = исход[:i] + ПОДЛОГ + исход[i:]

    def замер(подмена):
        сбор = источники(подмена)
        с_фразой = sum(1 for _, _, з in сбор[отн] if ПОДЛОГ.strip() in з)
        до_места = [ф for ф in находки(сбор, пр)
                    if ф[0] == отн and ПОДЛОГ.strip() in ф[3]]
        return с_фразой, до_места, len([ф for ф in находки(сбор, пр)
                                        if not ПРИНЯТЫЕ.get(
                                            (ф[0], _схлопнуть(ф[3])))])

    ч0 = замер(None)
    ч1 = замер({отн: подложено})
    ч2 = замер(None)
    print("%-10s %-22s %-22s %s" % ("прогон", "литералов с фразой",
                                    "находок на месте", "находок всего"))
    for имя, (ф, м, в) in (("чисто", ч0), ("подлог", ч1), ("снято", ч2)):
        print("%-10s %-22d %-22d %d" % (имя, ф, len(м), в))
    for файл, ном, место, знач, что in ч1[1]:
        print("  НАЗВАНО ПОИМЁННО: %s:%d [%s] %s" % (файл, ном, место, что))
    верно = (ч1[0] == 1 and len(ч1[1]) == 1 and ч0[0] == 0 and not ч0[1]
             and ч2 == ч0 and ч1[2] == ч0[2] + 1)
    print("КОНТРОЛЬ: %s" % ("подлог назван, после снятия находок столько же"
                            if верно else "НЕ ДОКАЗАНО — разобрать числа"))
    return 0 if верно else 1



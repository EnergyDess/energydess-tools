def _схлопнуть(т):
    return " ".join((т or "").split())


def _погасить(текст, шаблон, флаги=re.S):
    """Совпадения заменяются пробелами той же длины, переводы строк целы:
    номера строк после снятия остаются настоящими."""
    return re.sub(шаблон, lambda м: re.sub(r"[^\n]", " ", м.group(0)),
                  текст, flags=флаги)


def _строка(текст, поз):
    return текст.count("\n", 0, поз) + 1



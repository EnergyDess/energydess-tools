async def экран():
    import check_medkit_dose as д
    from playwright.async_api import async_playwright
    async with async_playwright() as pw:
        бр = await pw.chromium.launch(headless=False)
        ctx = await бр.new_context(viewport={"width": 1440, "height": 900})
        pg = await ctx.new_page()
        await д._войти(pg)
        await pg.evaluate("async () => { await fetch('/medkit/api/chat',"
                          " {method: 'DELETE'}); }")
        await pg.goto(д.БАЗА + "/medkit", wait_until="networkidle")
        await pg.click("#apt-ai-open")
        await pg.wait_for_timeout(800)
        привет = await pg.evaluate(
            "() => [...document.querySelectorAll('.apt-ai-msg-ai')]"
            ".map(д => д.innerText).join(' | ')")
        было = await pg.evaluate(
            "() => document.querySelectorAll('.apt-ai-msg-ai').length")
        await pg.evaluate("() => аптАИПоказатьЧерновик({'поля': {},"
                          " 'заполнено': []})")
        await pg.wait_for_timeout(200)
        черновик = await pg.evaluate(
            "(было) => [...document.querySelectorAll('.apt-ai-msg-ai')]"
            ".slice(было).map(д => д.innerText).join(' | ')", было)
        await ctx.close()
        await бр.close()
    for имя, текст in (("приветствие панели", привет),
                       ("пустой черновик", черновик)):
        print("%-20s доз: %d %s\n    «%s»" % (имя, len(д.мерка(текст)),
                                            д.мерка(текст) or "",
                                            _схлопнуть(текст)[:200]))
    return 0



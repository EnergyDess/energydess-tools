def находки(сбор, пр):
    """[(файл, строка, место, значение, {признак: фрагменты})]."""
    из = []
    for файл, строки in сбор.items():
        for ном, место, знач in строки:
            if not КИРИЛЛИЦА.search(знач or ""):
                continue
            что = {}
            for имя, выр in пр:
                ф = [м.group(0) for м in выр.finditer(знач)]
                if ф:
                    что[имя] = ф
            if что:
                из.append((файл, ном, место, знач, что))
    return из


def печать(сбор, все_находки, показывать_принятые):
    print("ИСТОЧНИКИ (строк с кириллицей / всего собрано):")
    пусто = []
    for файл, строки in сбор.items():
        кир = sum(1 for _, _, з in строки if КИРИЛЛИЦА.search(з or ""))
        print("  %-40s %5d / %d" % (файл, кир, len(строки)))
        if not строки:
            пусто.append(файл)
    долг, принято = [], []
    for ф in все_находки:
        причина = ПРИНЯТЫЕ.get((ф[0], _схлопнуть(ф[3])))
        (принято if причина else долг).append((ф, причина))
    print("\nНАХОДКИ ВНЕ ПРИНЯТЫХ: %d" % len(долг))
    for (файл, ном, место, знач, что), _ in долг:
        print("  %s:%d  [%s]  %s" % (файл, ном, место,
                                     "; ".join("%s=%s" % (к, в)
                                               for к, в in что.items())))
        print("      «%s»" % _схлопнуть(знач)[:160])
    print("ПРИНЯТЫХ: %d" % len(принято))
    if показывать_принятые:
        for (файл, ном, место, знач, что), причина in принято:
            print("  %s:%d  «%s»\n      причина: %s"
                  % (файл, ном, _схлопнуть(знач)[:100], причина))
    if пусто:
        print("\nПРОВЕРИТЬ НЕЧЕМ: у источников собрано ноль строк: %s"
              % ", ".join(пусто))
        return 2
    return 1 if долг else 0



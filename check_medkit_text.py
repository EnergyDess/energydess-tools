def js_литералы(текст):
    """(номер строки, значение) каждого строкового литерала JS.

    Токенизатор, а не регулярка: `'` внутри комментария и `//` внутри
    строки (каждый адрес) регулярку сбивают. Регулярное выражение
    опознаётся по предыдущему знаку — после него значения быть не может.
    Подстановка `${…}` у шаблонной строки вырезается: там данные."""
    из, i, n = [], 0, len(текст)
    пред = ""
    while i < n:
        c = текст[i]
        дальше = текст[i + 1] if i + 1 < n else ""
        if c == "/" and дальше == "/":
            j = текст.find("\n", i)
            i = n if j < 0 else j
            continue
        if c == "/" and дальше == "*":
            j = текст.find("*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        if c == "/" and (пред == "" or пред in "(,=:[!&|?{};+-*%<>~^"):
            j, в_классе = i + 1, False
            while j < n and текст[j] != "\n":
                if текст[j] == "\\":
                    j += 2
                    continue
                if текст[j] == "[":
                    в_классе = True
                elif текст[j] == "]":
                    в_классе = False
                elif текст[j] == "/" and not в_классе:
                    break
                j += 1
            i = j + 1
            пред = "x"
            continue
        if c in "'\"`":
            j, куски, глубина = i + 1, [], 0
            while j < n:
                ч = текст[j]
                if ч == "\\":
                    куски.append(текст[j:j + 2])
                    j += 2
                    continue
                if c == "`" and ч == "$" and j + 1 < n and текст[j + 1] == "{":
                    глубина, j = 1, j + 2
                    while j < n and глубина:
                        глубина += {"{": 1, "}": -1}.get(текст[j], 0)
                        j += 1
                    куски.append(" … ")
                    continue
                if ч == c:
                    break
                if ч == "\n" and c != "`":
                    break
                куски.append(ч)
                j += 1
            из.append((_строка(текст, i), "".join(куски)))
            i = j + 1
            пред = "x"
            continue
        if not c.isspace():
            пред = c if c in "(,=:[!&|?{};+-*%<>~^" else "x"
        i += 1
    return из


def шаблон_тексты(текст):
    """Узлы и атрибуты разметки плюс литералы её `<script>`."""
    т = _погасить(текст, r"\{#.*?#\}")
    т = _погасить(т, r"<!--.*?-->")
    т = _погасить(т, r"<style\b.*?</style>")
    из = []
    for м in re.finditer(r"(<script\b[^>]*>)(.*?)</script>", т, re.S):
        скрипт = _погасить(м.group(2), r"\{\{.*?\}\}|\{%.*?%\}")
        сдвиг = _строка(т, м.start(2)) - 1
        for ном, знач in js_литералы(скрипт):
            из.append((сдвиг + ном, "скрипт", знач))
    т = _погасить(т, r"<script\b.*?</script>")
    т = _погасить(т, r"\{%.*?%\}")
    т = re.sub(r"\{\{.*?\}\}", lambda м: " … " + re.sub(r"[^\n]", "", м.group(0)),
               т, flags=re.S)
    for тег in re.finditer(r"<[a-zA-Z][^>]*>", т):
        for ат in re.finditer(r"([\w:-]+)\s*=\s*(\"([^\"]*)\"|'([^']*)')",
                              тег.group(0)):
            знач = ат.group(3) if ат.group(3) is not None else ат.group(4)
            из.append((_строка(т, тег.start()), "атрибут " + ат.group(1), знач))
    for м in re.finditer(r">([^<]+)<", т):
        if м.group(1).strip():
            из.append((_строка(т, м.start(1)), "текст", м.group(1)))
    return из


ПРОПУСК_ВЫЗОВОВ = {"print"}
ПРОПУСК_МОДУЛЕЙ = {"re"}


def py_тексты(текст, фильтр_имён):
    """(строка, место, значение) пользовательских литералов Python."""
    дерево = ast.parse(текст)
    гасить = set()
    for узел in ast.walk(дерево):
        тело = getattr(узел, "body", None)
        if (isinstance(узел, (ast.Module, ast.ClassDef, ast.FunctionDef,
                              ast.AsyncFunctionDef))
                and тело and isinstance(тело[0], ast.Expr)
                and isinstance(тело[0].value, ast.Constant)):
            гасить.add(id(тело[0].value))
        if isinstance(узел, ast.Call):
            ф = узел.func
            if ((isinstance(ф, ast.Name) and ф.id in ПРОПУСК_ВЫЗОВОВ)
                    or (isinstance(ф, ast.Attribute)
                        and isinstance(ф.value, ast.Name)
                        and ф.value.id in ПРОПУСК_МОДУЛЕЙ)):
                for в in ast.walk(узел):
                    гасить.add(id(в))
        if isinstance(узел, ast.Dict):
            for к in узел.keys:
                if к is not None:
                    гасить.add(id(к))
        if isinstance(узел, ast.Subscript):
            for в in ast.walk(узел.slice):
                гасить.add(id(в))
        if isinstance(узел, ast.Compare):
            for в in ast.walk(узел):
                гасить.add(id(в))

    из = []

    def собрать(корень, место):
        for в in ast.walk(корень):
            if (isinstance(в, ast.Constant) and isinstance(в.value, str)
                    and id(в) not in гасить):
                из.append((в.lineno, место, в.value))

    for узел in дерево.body:
        имя = None
        if isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef,
                             ast.ClassDef)):
            имя = узел.name
        elif isinstance(узел, ast.Assign) and isinstance(узел.targets[0],
                                                         ast.Name):
            имя = узел.targets[0].id
        elif isinstance(узел, ast.AnnAssign) and isinstance(узел.target,
                                                            ast.Name):
            имя = узел.target.id
        if not имя or "промпт" in имя.lower():
            continue
        if фильтр_имён(имя):
            собрать(узел, имя)
    return из


def _имя_аптечки(имя):
    н = имя.lower()
    return "апт" in н or "medkit" in н


def источники(подмена=None):
    """{файл: [(строка, место, значение)]} — всё, что проверяется.

    `подмена` — {файл: текст} для отрицательного контроля: подлог живёт
    в памяти, рабочее дерево не трогается."""
    подмена = подмена or {}

    def читать(отн):
        if отн in подмена:
            return подмена[отн]
        return io.open(os.path.join(КОРЕНЬ, отн), encoding="utf-8").read()

    шаблоны = ["templates/medkit.html"] + sorted(
        os.path.relpath(п, КОРЕНЬ).replace("\\", "/")
        for п in glob.glob(os.path.join(КОРЕНЬ, "templates", "_medkit_*.html")))
    сбор = {}
    скрипты = []
    for отн in шаблоны + ["templates/_page_end.html"]:
        текст = читать(отн)
        скрипты += re.findall(r"st\('([^']+\.js)'\)", текст)
        if отн in шаблоны:
            сбор[отн] = шаблон_тексты(текст)
    for имя in sorted(set(скрипты)):
        отн = "static/" + имя
        сбор[отн] = [(н, "скрипт", з) for н, з in js_литералы(читать(отн))]
    сбор["main.py"] = py_тексты(читать("main.py"), _имя_аптечки)
    for отн in ("medkit_defs.py", "medkit_dosage.py"):
        сбор[отн] = py_тексты(читать(отн), lambda имя: True)
    return сбор


def признаки():
    import main

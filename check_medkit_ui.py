    # ЗАЧЕМ ОТДЕЛЬНЫМ ШАГОМ. Постулат постановки был такой: «поиск
    # пользуется тем же `lower()`, что и проба, значит „нурофен“
    # не найдёт „Нурофен“». Замер 2026-08-24 его ОПРОВЕРГ — строку

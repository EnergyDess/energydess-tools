    поля = ["#apt-f-name", "#apt-f-sub", "#apt-f-form", "#apt-f-left",
            "#apt-f-total", "#apt-f-exp", "#apt-f-dose",
            "#apt-f-code", "#apt-f-note", ".apt-photo-row label.btn",
            "#apt-save"]

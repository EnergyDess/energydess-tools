    # пустота: пробная позиция заводится формой, а форма поле вскрытия
    # больше не чистит — и введённое руками значение законно доезжает
    # до базы. Проверяем, что списание его НЕ ТРОГАЕТ
    вскрыто_до = _в_базе("SELECT opened_on FROM medkit_items WHERE id = ?",
                         (новый,))[0][0]
    await pg.evaluate("(id) => document.querySelector("
                      "'[data-take=\"' + id + '\"]').click()", новый)

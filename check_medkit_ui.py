    # ОРГАН ВЫБОРА ФОТО — МЕТКА, А НЕ САМО ПОЛЕ (правка 2026-08-25).
    # Родное `<input type="file">` рисовало во всю ширину формы СВОЮ
    # подпись системным языком браузера («Choose File») и спрятано;
    # нажимают теперь метку. Спрашивается ТО ЖЕ САМОЕ — можно ли
    # выбрать файл сразу, — просто у настоящего органа.
    фото = await pg.evaluate(ЖИВОЙ, ".apt-photo-row label.btn")
    о.шаг("фото-выбирается-сразу", фото.get("живой"),
          фото.get("причина", "кнопка выбора жива в НОВОЙ позиции"))
    родное = await pg.evaluate(
        "() => { const в = document.getElementById('apt-f-photo');"
        " return {скрыто: !!в.hidden,"
        "         подпись: (document.getElementById('apt-photo-name')"
        "                   || {}).textContent}; }")
    о.шаг("фото-без-чужой-подписи", родное.get("скрыто"),
          "родное поле спрятано, на кнопке %r" % родное.get("подпись"))


    await pg.click(".apt-add")
    await pg.wait_for_timeout(400)
    о.шаг("форма-открылась", await pg.evaluate(ОТКРЫТО, "apt-form"))
    # ОРГАН ВЫБОРА ФОТО — МЕТКА, А НЕ САМО ПОЛЕ (правка 2026-08-25).
    # Родное `<input type="file">` спрятано: оно рисовало во всю ширину
    # формы СВОЮ подпись системным языком браузера. Нажимают метку,
    # её и спрашиваем — вопрос «можно ли выбрать файл» тот же самый.
    # ПОЛЕЙ ВСКРЫТИЯ В ЭТОМ СПИСКЕ БОЛЬШЕ НЕТ — §6.0.3, четыре пункта.
    #
    # ПРЕЖНЯЯ ФОРМУЛИРОВКА: `#apt-f-open` спрашивался наравне
    # с остальными, то есть требовался ЖИВЫМ у любой формы выпуска.
    # НОВАЯ: поля вскрытия проверяются отдельным шагом
    # `вскрытие-только-где-портится`, и там их видимость — предмет
    # вопроса, а не предпосылка.
    # ПОЧЕМУ ПРЕЖНЯЯ СТАЛА НЕГОДНОЙ: решение владельца 2026-08-25
    # (BACKLOG №172, блок C) — у таблеток в блистере даты вскрытия
    # нет по смыслу, и поле там больше не рисуется. Прежний список
    # требовал видимости ровно того, что решено прятать, то есть
    # печатал бы «ПЛОХО» про исправный экран вечно.
    # ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ НА НОВОЙ: подлог `вскрытие-у-всех-форм`

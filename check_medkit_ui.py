    for сел in поля:
        ж = await pg.evaluate(ЖИВОЙ, сел)
        if not ж.get("живой"):
            мёртвые.append(f"{сел}: {ж.get('причина')}")
    о.шаг("форма-жива", not мёртвые, "; ".join(мёртвые) or f"полей {len(поля)}")

    # ── ПОЛЯ ВСКРЫТИЯ ВИДНЫ У ВСЕХ ФОРМ И ПУСТЫ У ВСЕХ ФОРМ (A.1/A.2)
    #
    # Здесь стоял обратный шаг — «вскрытие-только-где-портится», — и он
    # проверял МОЁ правило, которое владелец опроверг двумя упаковками
    # с полки: у спрея Нозефрин срока после вскрытия в инструкции нет
    # вовсе, а система его проставила; у капсул Креона он напечатан
    # на банке, а поля не было. Разбор — шапка ФОРМ в `medkit_defs`.
    #
    # Спрашиваются ОБЕ половины и по ВСЕМ формам, а не по двум: показ
    # без проверки значения прошёл бы на коде, который поля показывает

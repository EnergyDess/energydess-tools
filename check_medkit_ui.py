async def доказать_подлог(ширина, подлог, выражение, набор=None, устройства=False):
    """НЕЗАВИСИМЫЙ ЗАМЕР: состояние страницы без подлога и с ним.

    Отдельная короткая загрузка, а не шаг внутри сорокашагового прохода:
    замер, вплетённый в пробу, зависел бы от самой пробы, а он обязан
    быть свидетелем со стороны.

    Возвращает пару (чисто, с_подлогом). Совпали — подлог не состоялся,
    и вердикт пробы про него не значит НИЧЕГО (CLAUDE.md §6.0.3).
    """
    from playwright.async_api import async_playwright
    набор = набор or ПОДЛОГИ
    сенсор = ширина < 800
    значения = []
    async with async_playwright() as p:
        # УСЛОВИЯ ЗАМЕРА ОБЯЗАНЫ СОВПАДАТЬ С УСЛОВИЯМИ ПРОБЫ.
        # Первая версия поднимала браузер БЕЗ поддельных устройств,
        # и доказательство подлога «микрофон мёртв» давало False и на
        # чистом прогоне, и с подлогом: `getUserMedia` не отвечал ни там,
        # ни там. Совпадение при этом читалось как «подлог не состоялся»,
        # хотя не состоялся ЗАМЕР.
        b = await p.chromium.launch(
            args=КЛЮЧИ_УСТРОЙСТВ if устройства else [])
        for накладывать in (False, True):
            ctx = await b.new_context(
                viewport={"width": ширина, "height": 900 if not сенсор else 844},
                has_touch=сенсор, is_mobile=сенсор, device_scale_factor=1,
                permissions=["microphone"] if устройства else [])
            if накладывать:
                await ctx.add_init_script(набор[подлог][0])
            pg = await ctx.new_page()
            await _войти(pg)
            await pg.goto(БАЗА + "/medkit", wait_until="networkidle")
            # Подлоги на `setInterval` дорисовывают не сразу — ждём
            # заведомо дольше их шага (200 мс)
            await pg.wait_for_timeout(900)
            try:
                значения.append(await pg.evaluate(выражение))
            except Exception as e:
                значения.append("ЗАМЕР ОБОРВАЛСЯ: %s" % type(e).__name__)
            await ctx.close()
        await b.close()
    return значения[0], значения[1]



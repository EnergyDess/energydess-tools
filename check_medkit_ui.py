    # как его открывает человек: раскрыть и посмотреть, дотягивается ли
    # нажатие. Спрашивать живость закрытого `<details>` бессмысленно:
    # закрытый он и должен быть недостижим, и «мёртвым» его назвала бы
    # исправная разметка.
    #
    # ЭТО РАСШИРЕНИЕ ВОПРОСА, А НЕ СУЖЕНИЕ: раньше поле проверялось

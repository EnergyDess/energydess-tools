    после = _в_базе("SELECT qty_left, opened_on FROM medkit_items WHERE id = ?",
                    (новый,))[0]
    о.шаг("списание-сняло-дозу", после[0] == 8,
          f"в базе осталось {после[0]} (было 10, доза 2)")

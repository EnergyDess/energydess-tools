СКРИПТ = re.compile(r'^py\s+(\S+\.py)$')


def ряд_проверок():
    """Числа ряда — прогоном команд ИЗ CLAUDE.md, а не своей копией.

    Грепы считаются `| wc -l`, скрипты — кодом возврата. Что из них что,
    видно по самой команде: `py check_docs.py` — скрипт, всё остальное —
    конвейер оболочки.
    """
    присваивания, команды = списки.разобрать()
    значения, порядок = {}, []

    строки_bash = list(присваивания)
    for номер, команда in команды:
        порядок.append(номер)
        if not СКРИПТ.match(команда):
            строки_bash.append('echo "%s|$(%s | wc -l)"' % (номер, команда))

    try:
        вывод = subprocess.run(['bash', '-c', '\n'.join(строки_bash)],
                               capture_output=True, text=True, timeout=300)
        for строка in вывод.stdout.splitlines():
            if '|' in строка:
                имя, число = строка.split('|', 1)
                значения[имя.strip()] = число.strip()
    except (OSError, subprocess.SubprocessError) as e:
        print('  !! грепы не отработали: %s' % e)

    for номер, команда in команды:
        m = СКРИПТ.match(команда)
        if not m:
            continue
        try:
            значения[номер] = str(subprocess.run(
                [sys.executable, m.group(1)],
                capture_output=True, timeout=300).returncode)
        except (OSError, subprocess.SubprocessError) as e:
            значения[номер] = 'не запустился: %s' % e
    return значения, порядок


def первое_число_в_разбивке():
    """[(файл, строка, правило, долг?, свойства-вида)] по выводу проверки 1.

    ЗАЧЕМ. Первое число стояло 18 несколько заходов подряд и не двигалось
    ни от чего — ни до вывода демо-страниц из-под проверок, ни после.
    Голое число, которое не меняется, перестают читать на третий раз,
    а §6.0.2 прямо говорит, что оно НЕ РАВНО ДОЛГУ и читать его надо
    «по таблице в задаче 37».

    Таблица — это перечень, который никто не перечитывает (§6.0.7).
    Поэтому разделение делает машина, и тем же признаком, каким его
    делает `check_ids.py` для правил по id: объявлены свойства РАСКЛАДКИ
    (место элемента у родителя) — законно; объявлен ВИД компонента
    (кегль, цвет, фон, рамка, радиус, паддинг, тень) либо стоит
    `!important` — долг.

    Читать стоит ДОЛГ: он двигается от работы. Полное число двигается
    и от честной строки вида «оформить своё внутри системной карточки».
    """
    import re as _re
    import check_ids as ид
    присваивания, команды = списки.разобрать()
    команда = dict(команды).get('1')
    if команда is None:
        return None
    скрипт = '\n'.join(list(присваивания) + [команда])
    вывод = subprocess.run(['bash', '-c', скрипт],
                           capture_output=True, text=True, timeout=300)
    итог = []
    for строка in вывод.stdout.splitlines():
        m = _re.match(r'^(.+?):(\d+):(.*)$', строка)
        if not m:
            continue
        файл, номер, правило = m.group(1), m.group(2), m.group(3)
        тело = правило.split('{', 1)[1] if '{' in правило else ''
        тело = тело.split('}')[0]
        свойства = [c.split(':', 1)[0].strip().lower()
                    for c in тело.split(';') if ':' in c]
        вид = [c for c in свойства
               if c and c not in ид.РАСКЛАДКА and not c.startswith('--')]
        # `!important` — долг сам по себе, каким бы свойством ни был:
        # он бьёт систему весом, а не содержанием.
        итог.append((файл, номер, правило.strip(),
                     bool(вид) or '!important' in тело, вид))
    return итог



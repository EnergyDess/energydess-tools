def _тело_правила(путь, номер):
    """ТЕЛО ПРАВИЛА ЦЕЛИКОМ, а не первая его строка.

    ЗАЧЕМ. Греп проверки 1 печатает ОДНУ строку — ту, где стоит `{`, —
    и у многострочного правила в ней нет ни одного объявления. Разбор,
    читавший только её, объявлял ЗАКОННОЙ РАСКЛАДКОЙ любое правило,
    записанное в несколько строк: свойств не видно, значит вида нет,
    значит долга нет.

    Замер 2026-08-27 на подложенном правиле

        .nut-app .card {
          flex: 1;
          padding: 3px;      <- долг во ВТОРОЙ строке
          color: red;        <- долг в ТРЕТЬЕЙ
          min-width: 0;
          border-radius: 1px; <- долг в ПОСЛЕДНЕЙ
        }

    дал «долг 0»: все три не увидены. Долг по `border-color`, из-за
    которого задача 169 и заведена, прятался ровно так же — и нашёлся
    сверкой руками, а не проверкой.

    Возвращает содержимое от первой `{` до парной ей `}` (вложенность
    считается: у `@media` и вложенных правил её больше единицы).
    Файла нет или скобка не закрылась — отдаётся то, что было
    в исходной строке, то есть поведение прежнего разбора.
    """
    try:
        строки = io.open(путь, encoding="utf-8", errors="replace").read().splitlines()
    except OSError:
        return None
    i = int(номер) - 1
    if i < 0 or i >= len(строки):
        return None
    текст = chr(10).join(строки[i:i + 400])
    н = текст.find("{")
    if н < 0:
        return None
    глубина, тело = 0, []
    for знак in текст[н:]:
        if знак == "{":
            глубина += 1
            if глубина == 1:
                continue
        elif знак == "}":
            глубина -= 1
            if глубина == 0:
                return "".join(тело)
        тело.append(знак)
    return None


def первое_число_в_разбивке():
    """[(файл, строка, правило, долг?, свойства-вида)] по выводу проверки 1.

    ЗАЧЕМ. Первое число стояло 18 несколько заходов подряд и не двигалось
    ни от чего — ни до вывода демо-страниц из-под проверок, ни после.
    Голое число, которое не меняется, перестают читать на третий раз,
    а §6.0.2 прямо говорит, что оно НЕ РАВНО ДОЛГУ и читать его надо
    «по таблице в задаче 37».

    Таблица — это перечень, который никто не перечитывает (§6.0.7).
    Поэтому разделение делает машина, и тем же признаком, каким его
    делает `check_ids.py` для правил по id: объявлены свойства РАСКЛАДКИ
    (место элемента у родителя) — законно; объявлен ВИД компонента
    (кегль, цвет, фон, рамка, радиус, паддинг, тень) либо стоит
    `!important` — долг.

    Читать стоит ДОЛГ: он двигается от работы. Полное число двигается
    и от честной строки вида «оформить своё внутри системной карточки».
    """
    import re as _re
    import check_ids as ид
    присваивания, команды = списки.разобрать()
    команда = dict(команды).get('1')
    if команда is None:
        return None
    скрипт = '\n'.join(list(присваивания) + [команда])
    вывод = subprocess.run(['bash', '-c', скрипт],
                           capture_output=True, text=True, timeout=300)
    итог = []
    for строка in вывод.stdout.splitlines():
        m = _re.match(r'^(.+?):(\d+):(.*)$', строка)
        if not m:
            continue
        файл, номер, правило = m.group(1), m.group(2), m.group(3)
        # ТЕЛО ЧИТАЕТСЯ ИЗ ФАЙЛА, А НЕ ИЗ СТРОКИ ГРЕПА. Разбор строки
        # видит только то, что уместилось до перевода строки, — то есть
        # у многострочного правила НИЧЕГО (разбор в `_тело_правила`).
        тело = _тело_правила(файл, номер)
        if тело is None:
            тело = правило.split('{', 1)[1] if '{' in правило else ''
            тело = тело.split('}')[0]
        # КОММЕНТАРИЙ — НЕ КОД (§6.0.7). Первая версия чтения тела
        # целиком немедленно дала ложную находку: строка
        # `/* цвета здесь нет: .eyebrow сам читает … */` внутри правила
        # разобралась как объявление свойства «цвета здесь нет».
        # Проверка, врущая на честном комментарии, перестаёт читаться.
        тело = _re.sub('/\\*.*?\\*/', ' ', тело, flags=_re.S)
        # Объявления разделяются `;`, но последнее перед `}` его
        # не требует — и ровно оно чаще всего и есть долг: правило
        # дописывают снизу. Поэтому хвост берётся наравне с остальными.
        куски = [c for c in тело.replace(chr(10), ' ').split(';') if ':' in c]
        свойства = [c.split(':', 1)[0].strip().lower() for c in куски]
        свойства = [c.split()[-1] if c.split() else c for c in свойства]
        вид = [c for c in свойства
               if c and c not in ид.РАСКЛАДКА and not c.startswith('--')]
        # `!important` — долг сам по себе, каким бы свойством ни был:
        # он бьёт систему весом, а не содержанием.
        итог.append((файл, номер, правило.strip(),
                     bool(вид) or '!important' in тело, вид))
    return итог



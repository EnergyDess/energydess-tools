def hover_метрика():
    """ТРИ ЧИСЛА, а не одно, и это не избыточность.

    Опорным считается СРЕДНЕЕ — «правил»: селекторов с `:hover` внутри
    медиазоны. Блоки считают обёртки (в одной может лежать несколько
    правил), вхождения считают `:hover` в списках селекторов через запятую.
    Три ответа на один вопрос — ровно та причина, по которой число в тексте
    без указания способа ничего не значило.
    """
    файлы = sorted(glob.glob('static/*.css')) + sorted(glob.glob('templates/*.html'))
    блоков = правил = вхождений = 0
    по_файлам = {}
    for путь in файлы:
        текст = _прочитать(путь)
        б = пр = вх = 0
        for m in re.finditer(r'@media\s*\(\s*hover\s*:\s*hover\s*\)\s*\{', текст):
            б += 1
            i, глубина = m.end(), 1
            while i < len(текст) and глубина:
                if текст[i] == '{':
                    глубина += 1
                elif текст[i] == '}':
                    глубина -= 1
                i += 1
            for sm in re.finditer(r'([^{}]+)\{', текст[m.end():i - 1]):
                if ':hover' in sm.group(1):
                    пр += 1
                    вх += sm.group(1).count(':hover')
        if б:
            по_файлам[путь] = (б, пр, вх)
            блоков += б
            правил += пр
            вхождений += вх
    return блоков, правил, вхождений, по_файлам


def долг_дневника():
    """Задача 96. Способ — ГРЕП, потому что грепом его и проверяют.

    Разбор CSS даёт число на единицу меньше (комментарии), и однажды это
    уже стоило расхождения: в таблице задачи стояло число разбора,
    а в мерке готовности под ней — команда грепа.
    """
    текст = _прочитать('static/nutrition.css')
    отступы = len(re.findall(
        r'(^|[;{ ])(margin|padding|gap|row-gap|column-gap)'
        r'(-(top|bottom|left|right))?:\s*[0-9.]', текст, re.M))
    кегли = len(re.findall(r'font-size:\s*[0-9.]', текст))
    return отступы, кегли


def _снять_комментарии(текст):
    """Комментарий — НЕ КОД, и снимается ПО ЯЗЫКАМ, а не поверх всего файла.

    ЗАЧЕМ ВООБЩЕ. Первый прогон мерки насчитал 30 литералов, из которых
    8 были ПРОЗОЙ — цитатами удалённых цветов в пояснениях («Было:
    градиент на цифрах из старой палитры (#a78bfa/#60a5fa/#34d399)»).
    Тот же класс, что чинила задача 99 у проверки 7, только наоборот:
    там проза ОЖИВЛЯЛА удалённое, здесь она РАЗДУВАЛА долг.

    ЗАЧЕМ ПО ЯЗЫКАМ. Вторая версия снимала `/* … */` поверх ВСЕГО файла
    и съела 165 000 знаков `nutrition.html`: атрибут `accept="image/*"`
    открывает `/*`, а закрывается он ближайшим `*/` тремя тысячами строк
    ниже. Мерка печатала МЕНЬШЕ долга, чем есть, и отличить это
    от чистоты было нечем — немой отказ внутри самой мерки.

    Разборы берутся у `check_docs` ИМПОРТОМ: второй реализации снятия
    комментариев в проекте быть не должно (§6.0.7).
    """
    import check_docs
    # Jinja-комментарий: единственный, которого у check_docs нет —
    # там разбирают CSS, JS, разметку и Python, а шаблонный слой
    # до задачи 18 никто не считал.
    текст = re.sub(r"\{#.*?#\}", " ", текст, flags=re.S)
    текст = check_docs._html_код(текст)

    def внутри(тег, чем, текст):
        return re.sub(r"(<" + тег + r"[^>]*>)(.*?)(</" + тег + r">)",
                      lambda m: m.group(1) + чем(m.group(2)) + m.group(3),
                      текст, flags=re.S | re.I)

    текст = внутри("style", check_docs._css_код, текст)
    текст = внутри("script", check_docs._js_код, текст)
    return текст


ЦВЕТ = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)")


def legacy_в_шаблонах():
    """Задача 18. Способ назван, потому что чисел у вопроса несколько.

    СЧИТАЕТСЯ: литерал цвета в `templates/*.html` вне `<svg>` и вне
    HTML-комментария. Плюс отдельно — градиенты и блоки `<style>`
    с пометкой «TODO: перенести».

    НЕ СЧИТАЕТСЯ, и у каждого исключения причина:
      · `enshrouded.html` — раздел вне системы целиком, задача 2,
        правки в нём не вносятся решением владельца;
      · демо-страницы — выведены из-под проверок поимённо (BACKLOG №27);
      · содержимое `<svg>` — там цвет задаётся атрибутом `fill`,
        переменные не работают, и это иллюстрация, а не оформление.
        Именно из-за этого `landing.html` в первом, грубом замере
        выглядел худшим файлом проекта со 121 «хардкодом».
    """
    исключены = set(списки.исключённые_страницы()) | {"templates/enshrouded.html"}
    итог = {}
    for путь in sorted(glob.glob("templates/*.html")):
        ключ = путь.replace(os.sep, "/")
        if ключ in исключены:
            continue
        сырой = _прочитать(путь)
        текст = _снять_комментарии(сырой)
        без_svg = re.sub(r"<svg\b.*?</svg>", "", текст, flags=re.S | re.I)
        цвета = len(ЦВЕТ.findall(без_svg))
        град = len(re.findall(r"(linear|radial|conic)-gradient\(", без_svg))
        # Пометка «TODO» ищется в СЫРОМ тексте: она по природе своей
        # живёт в комментарии, и снятие прозы стёрло бы ровно тот
        # признак, ради которого её и считают.
        todo = len(re.findall(r"TODO:\s*перенести", сырой))
        if цвета or град or todo:
            итог[ключ] = (цвета, град, todo)
    return итог


def тесты():
    """Сколько тестов проходит. Способ — ПРОГОН pytest, а не подсчёт
    функций `def test_` грепом.

    Разница не косметическая: параметризованный тест — одна функция
    и десять прогонов, и два способа дают два разных числа. Опорным
    считается то, что печатает сам pytest, потому что именно оно
    называется в отчётах.
    """
    try:
        r = subprocess.run([sys.executable, '-m', 'pytest', 'tests/', '-q',
                            '--no-header', '-p', 'no:warnings'],
                           capture_output=True, text=True, encoding='utf-8',
                           errors='replace', timeout=900)
        m = re.search(r'(\d+) passed', r.stdout or '')
        f = re.search(r'(\d+) failed', r.stdout or '')
        return (m.group(1) if m else '?'), (f.group(1) if f else '0'), r.returncode
    except (OSError, subprocess.SubprocessError) as e:
        return f'не запустился: {e}', '?', '?'



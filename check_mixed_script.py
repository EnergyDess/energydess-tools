def файлы():
    п = subprocess.run(["git", "ls-files", "-z"], capture_output=True, cwd=КОРЕНЬ)
    return [ф for ф in п.stdout.decode("utf-8").split("\0") if ф]


def прочитать(ф):
    try:
        with open(os.path.join(КОРЕНЬ, ф), encoding="utf-8") as h:
            return h.read()
    except (UnicodeDecodeError, OSError):
        return None


def прогон(подмена=None, тихо=False):
    """(находки [(файл, строка, слово)], прочитано файлов)."""
    подмена = подмена or {}
    найдено, прочитано = [], 0
    for ф in файлы():
        текст = подмена.get(ф) if ф in подмена else прочитать(ф)
        if текст is None:
            continue
        прочитано += 1
        for стр, слово in находки_в_тексте(текст):
            найдено.append((ф, стр, слово))
    if not тихо:
        for ф, стр, слово in найдено:
            print("  %s:%d  %r" % (ф, стр, слово))
    return найдено, прочитано


def контроль():
    """Подлог ломает РОВНО проверяемое звено: одна кириллическая буква
    в тексте файла подменяется латинским двойником (в памяти, файл на
    диске не трогается). Доказательство независимо от вердикта: число
    латинских букв в подменённой строке до и после."""
    чисто, прочитано = прогон(тихо=True)
    if not прочитано:
        print("ПРОПУСК: читать нечего — git ls-files пуст")
        return 2
    if чисто:
        print("ОСТАНОВЛЕНО: основа грязная (%d находок) — контроль недействителен"
              % len(чисто))
        return 2
    цель = "CLAUDE.md"
    текст = прочитать(цель)
    слово = "захода"
    поз = текст.find(слово)
    if поз < 0:
        print("ОСТАНОВЛЕНО: в %s нет слова-мишени" % цель)
        return 2
    строка = текст.count(chr(10), 0, поз) + 1
    стало_слово = слово[:-1] + "a"
    подложено = текст[:поз] + стало_слово + текст[поз + len(слово):]
    лат_до = len(_ЛАТ.findall(текст.splitlines()[строка - 1]))
    лат_после = len(_ЛАТ.findall(подложено.splitlines()[строка - 1]))
    с_подлогом, _ = прогон({цель: подложено}, тихо=True)
    назвал = (цель, строка, стало_слово) in с_подлогом
    print("  ДОКАЗАТЕЛЬСТВО ПОДЛОГА: латинских букв в %s:%d %d -> %d"
          % (цель, строка, лат_до, лат_после))
    print("  чисто: находок %d; с подлогом: находок %d, место названо: %s"
          % (len(чисто), len(с_подлогом), назвал))
    ок = лат_после == лат_до + 1 and назвал and len(с_подлогом) == 1
    print("КОНТРОЛЬ %s" % ("ПРОЙДЕН" if ок else "НЕ ПРОЙДЕН"))
    return 0 if ок else 1


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    if "--контроль" in sys.argv:
        return контроль()
    найдено, прочитано = прогон()
    if not прочитано:
        print("ПРОПУСК: читать нечего — git ls-files пуст")
        return 2
    print("ПОДМЕН БУКВ-ДВОЙНИКОВ: %d (файлов прочитано %d)" % (len(найдено), прочитано))
    return 1 if найдено else 0


if __name__ == "__main__":
    sys.exit(main())

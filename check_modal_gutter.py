"""ДЁРГАНЬЕ СОДЕРЖИМОГО МОДАЛКИ ОТ ПОЯВЛЕНИЯ ПОЛОСЫ ПРОКРУТКИ.

BACKLOG №255, блок C. МЕРКА до правки, ПРОВЕРКА после (код 1, если
ширина содержимого меняется от появления полосы).

═══════════════════════════════════════════════════════════════════════
ПОЧЕМУ ОДНА ПРОБА НА ЧЕТЫРЕ ОКНА, А НЕ ЧЕТЫРЕ ОТДЕЛЬНЫЕ
═══════════════════════════════════════════════════════════════════════

Все четыре названных окна («Дополнительно» в форме, «Перепроверить всю
аптечку», «Инструкция», «Общая аптечка») используют ОДИН системный
скролл-контейнер — `.modal-body` в `templates/_modal.html`. Дёрганье —
не свойство контента конкретного окна, а свойство контейнера: он не
резервирует место под полосу прокрутки, и она отбирает свою ширину
у содержимого В МОМЕНТ ПОЯВЛЕНИЯ. Лечится ОДНИМ правилом в системном
CSS, и мерить его правильно ОДНОЙ пробой на всех потребителях сразу —
четыре копии проверки разошлись бы при первой же правке контейнера
(§6.0.7).

ПОЛОСА ВЫЗЫВАЕТСЯ ВЫСОТОЙ ОКНА БРАУЗЕРА, А НЕ КОНКРЕТНЫМ КОНТЕНТОМ.
`.modal-sh { max-height: 92vh }`, и содержимое каждого окна тем или
иным образом превышает эту высоту в обычном использовании (раскрытое
«Дополнительно», список найденных схем, длинная инструкция, лента
участников). Чтобы не гоняться за КОНКРЕТНЫМ состоянием, которое даёт
нужную высоту в каждом окне по-своему, полоса вызывается НАПРЯМУЮ —
уменьшением высоты вьюпорта до 480px, что подрезает `92vh` до 442px
и гарантированно включает прокрутку у любого нормально заполненного
окна. Метрика от этого не искажается: `.modal-body` устроен одинаково
при любой причине прокрутки, вопрос ровно к НЕЙ, а не к контенту.

ЗАМЕР — ШИРИНА ПОЛНОШИРОКОГО ДОЧЕРНЕГО ЭЛЕМЕНТА, а не самого
`.modal-body`: `clientWidth` контейнера меняется по определению (полоса
съедает трек), а вот дёргается ли из-за этого СОДЕРЖИМОЕ — вопрос
к элементу, который человек видит.

    py check_modal_gutter.py                 # три ширины, код 1 при находке
    py check_modal_gutter.py --контроль       # подлог: снять scrollbar-gutter
"""
import asyncio
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")

БАЗА = os.getenv("HOVER_BASE", "http://127.0.0.1:8899")
ПОЧТА = os.getenv("MEDKIT_EMAIL", "screenshot@local.dev")
ПАРОЛЬ = os.getenv("MEDKIT_PASSWORD", "Screenshot-Local-2026")
ШИРИНЫ = [int(ш) for ш in os.getenv("GUTTER_WIDTHS", "2560,1920,390").split(",")]

# (описание, JS-выражение открытия, id элемента для замера)
ОКНА = [
    ("форма — Дополнительно раскрыто", r"""() => {
        аптОткрытьФорму();
        document.getElementById('apt-extra').open = true;
    }""", "apt-form-el"),
    ("Перепроверить всю аптечку", r"""() => {
        открыть_модалку('apt-recheck-win'); аптДолгиЗагрузить();
    }""", "apt-recheck"),
    ("Инструкция (способ приёма)", r"""() => {
        const ц = АПТ_ПОЗИЦИИ.find(п => п.дозы || п.своя_схема) || АПТ_ПОЗИЦИИ[0];
        аптДозыОткрыть(ц.id);
    }""", "apt-doses-body"),
    ("Общая аптечка", "() => аптКругОткрыть()", "apt-circle-body"),
]


async def _войти(pg):
    await pg.goto(БАЗА + "/login", wait_until="domcontentloaded")
    await pg.fill("input[name=email]", ПОЧТА)
    await pg.fill("input[name=password]", ПАРОЛЬ)
    await pg.click("button[type=submit]")
    await pg.wait_for_load_state("networkidle")
    if "/login" in pg.url:
        raise SystemExit("ВХОД НЕ СОСТОЯЛСЯ — мерить нечего")
    await pg.goto(БАЗА + "/medkit", wait_until="networkidle")


ЗАМЕР_ШИРИНЫ = r"""(ид) => {
  const э = document.getElementById(ид);
  if (!э) return null;
  return Math.round(э.getBoundingClientRect().width);
}"""

ЗАКРЫТЬ_ВСЁ = r"""() => document.querySelectorAll('.modal-ov.open')
  .forEach(м => м.classList.remove('open'))"""


ЗАМЕР_ПОЛОСЫ = r"""(ид) => {
  const э = document.getElementById(ид);
  if (!э) return null;
  const тело = э.closest('.modal-body');
  if (!тело) return null;
  return {полоса: тело.scrollHeight > тело.clientHeight + 1,
          scrollHeight: тело.scrollHeight};
}"""


async def _замер_окна(pg, ширина, открыть_js, ид):
    """Ширина БЕЗ полосы (высокий вьюпорт) и С полосой (низкий), при
    ОДНОЙ и ТОЙ ЖЕ ширине окна и ОДНОМ и том же открытом состоянии —
    меняется только высота, то есть только наличие прокрутки.

    «БЕЗПОЛОСНАЯ» ВЫСОТА ВЫЧИСЛЯЕТСЯ ПО РЕАЛЬНОМУ `scrollHeight`,
    А НЕ ЗАДАЁТСЯ ЧИСЛОМ. Первая версия пробы брала фиксированные
    3200px «на глаз» — и список «Перепроверить всю аптечку» (35
    строк на сидированном стенде) оказался выше ЭТОГО потолка тоже:
    полоса стояла в обоих состояниях, сравнение шло «полоса против
    полосы» и не отвечало ни на что. Теперь высота меряется ДЕЙСТВИЕМ
    (открыть при заведомо огромном вьюпорте 6000px, прочесть
    `scrollHeight`) и сравнение делается против неё же плюс запас."""
    await pg.evaluate(ЗАКРЫТЬ_ВСЁ)
    await pg.set_viewport_size({"width": ширина, "height": 6000})
    await pg.evaluate(открыть_js)
    await pg.wait_for_timeout(300)
    без = await pg.evaluate(ЗАМЕР_ШИРИНЫ, ид)
    if без is None:
        return None, None, None, None
    полоса = await pg.evaluate(ЗАМЕР_ПОЛОСЫ, ид)
    if полоса is None:
        return None, None, None, None
    полоса_была = полоса["полоса"]
    высокая = min(полоса["scrollHeight"] + 400, 9000)  # 9000 — потолок viewport
    if полоса_была:
        # Контента больше, чем 6000px даёт даже с запасом, — берём
        # высоту ПОД САМ scrollHeight и перемеряем «без полосы» заново
        await pg.set_viewport_size({"width": ширина, "height": высокая})
        await pg.wait_for_timeout(300)
        без = await pg.evaluate(ЗАМЕР_ШИРИНЫ, ид)
        полоса = await pg.evaluate(ЗАМЕР_ПОЛОСЫ, ид)
        полоса_была = полоса["полоса"] if полоса else True
    await pg.set_viewport_size({"width": ширина, "height": 480})
    await pg.wait_for_timeout(300)
    с = await pg.evaluate(ЗАМЕР_ШИРИНЫ, ид)
    полоса2 = await pg.evaluate(ЗАМЕР_ПОЛОСЫ, ид)
    полоса_стала = полоса2["полоса"] if полоса2 else False
    return без, с, полоса_была, полоса_стала


async def главное():
    from playwright.async_api import async_playwright
    контроль = "--контроль" in sys.argv
    находок = 0
    async with async_playwright() as p:
        # ГОЛОВОЙ БРАУЗЕР, А НЕ HEADLESS — И ЭТО НЕ ВКУС, А ЗАМЕР.
        # Headless Chromium передаёт клиенту `--hide-scrollbars`, и полоса
        # прокрутки перестаёт занимать место: `clientWidth === offsetWidth`
        # даже когда `scrollHeight` вдвое больше `clientHeight`, то есть
        # прокрутка ЕСТЬ, а места не отбирает — ровно то поведение,
        # которого у владельца на десктопе НЕТ. Замер headless/headed
        # на одном и том же коде: 858/858 (headless, разницы не видно)
        # против 843/858 (headed, разница 15px — настоящий след полосы).
        # Проба, которая мерит headless, была бы слепа к дефекту.
        br = await p.chromium.launch(headless=False)
        pg = await br.new_page()
        await _войти(pg)

        if контроль:
            # ПОДЛОГ: снять `scrollbar-gutter` резервирование у системного
            # контейнера прямо в живом DOM — кода не трогаем, инжектируем
            # правило с более высокой специфичностью
            await pg.add_style_tag(content=
                ".modal-body { scrollbar-gutter: auto !important; }")
            print("[контроль] подлог наложен: .modal-body { "
                  "scrollbar-gutter: auto !important }")

        print("=" * 72)
        print("ДЁРГАНЬЕ СОДЕРЖИМОГО ОТ ПОЛОСЫ ПРОКРУТКИ" +
              (" (КОНТРОЛЬ)" if контроль else ""))
        print("=" * 72)
        не_проверено = 0
        for метка, js, ид in ОКНА:
            for ш in ШИРИНЫ:
                без, с, была, стала = await _замер_окна(pg, ш, js, ид)
                if без is None:
                    print("  %-32s %5dpx  ЭЛЕМЕНТ #%s НЕ НАЙДЕН"
                          % (метка, ш, ид))
                    continue
                # ИСХОД «БАЗА НЕ УСТАНОВЛЕНА» — ОТДЕЛЬНО ОТ «ЧИСТО».
                # Если полоса стоит уже на высоком вьюпорте, сравнение
                # идёт «полоса против полосы» и ничего не доказывает —
                # печатать здесь «ok» значило бы утверждать то, чего
                # не проверяли (§6.0.1).
                if была:
                    не_проверено += 1
                    print("  %-32s %5dpx  ПОЛОСА УЖЕ НА ВЫСОКОМ ВЬЮПОРТЕ "
                          "(3200px) — база не установлена, вопрос не задан"
                          % (метка, ш))
                    continue
                if not стала:
                    не_проверено += 1
                    print("  %-32s %5dpx  НА НИЗКОМ ВЬЮПОРТЕ (480px) ПОЛОСЫ "
                          "НЕТ — сравнивать нечего" % (метка, ш))
                    continue
                разница = без - с
                плохо = разница != 0
                находок += плохо
                print("  %-32s %5dpx  без полосы %4dpx, с полосой %4dpx, "
                      "разница %3dpx  %s"
                      % (метка, ш, без, с, разница,
                         "НАЙДЕНО" if плохо else "ok"))
        await br.close()
    print()
    if не_проверено:
        print("НЕ ПРОВЕРЕНО: %d случаев — база сравнения не установлена, "
              "вывод по ним не делается" % не_проверено)
    if контроль:
        if находок:
            print("КОНТРОЛЬ: подлог НАЙДЕН (%d случаев) — проба видит "
                  "поломку" % находок)
            return 0
        print("КОНТРОЛЬ: подлог НЕ НАЙДЕН — проба слепа")
        return 1
    if находок:
        print("НАЙДЕНО: %d случаев дёрганья" % находок)
        return 1
    print("ЧИСТО: содержимое не дёргается ни в одном из %d окон на %d "
          "ширинах" % (len(ОКНА), len(ШИРИНЫ)))
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(главное()))

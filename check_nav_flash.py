ШИРИНЫ = [(2560, 1400), (1920, 1000), (390, 800)]

# ── ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ─────────────────────────────────────────────
# Возвращает поведение ДО правки, СНИМАЯ САМО ПРАВИЛО из отдаваемого
# файла стилей. Подлог живёт в ответе прокси; ни репозиторий, ни диск
# не трогаются.
#
# ПЕРВАЯ ВЕРСИЯ КОНТРОЛЯ ОТМЕНЯЛА ПЕРЕХОД ЧЕРЕЗ `skipTransition()`
# НА `pageswap` — И БЫЛА НЕГОДНОЙ. Замер: пустых кадров 0 из 12,
# то есть «проба слепа» про исправную пробу. Причина в том, что
# `skipTransition()` отменяет АНИМАЦИЮ, а удержание кадра к тому моменту
# уже назначено, — значит пре-правочного поведения он не восстанавливает.
# Разница видна только замером: по названию метода она не читается.
КОНТРОЛЬ_ЧТО_СНЯТЬ = "@view-transition { navigation: auto; }"

# ВТОРАЯ ПОЛОВИНА КОНТРОЛЯ, и без неё он перестал воспроизводить дефект.
# Пока шрифты подключались `@import`-ом из style.css, хватало снять одно
# правило перехода. С 2026-08-24 они грузятся НЕ БЛОКИРУЯ отрисовку
# (BACKLOG №157), и снятие одного лишь `@view-transition` даёт 0 пустых
# кадров из 12 — то есть «проба слепа» про исправную пробу.
# Дореформенное состояние — это ДВА условия сразу: перехода нет
# И чужой файл шрифтов блокирует отрисовку. Возвращаем оба.
КОНТРОЛЬ_БЛОКИРУЮЩИЙ = (
    ' media="print"\n'
    "        onload=\"this.media='all'; this.onload=null\""
)

# Метки перехода: без них «пустых кадров нет» неотличимо от «переход
# не состоялся, просто повезло».
МЕТКИ_ПЕРЕХОДА = (
    "(()=>{const w=window;w.__vt=[];"
    "addEventListener('pagereveal',(e)=>{w.__vt.push(!!e.viewTransition);});})();")


def _поднять_прокси(цель_хост, цель_порт, задержка_мс, снять_правило=False,
                    поток=None, сломать_onload=False, подменять_шрифты=True):
    встало_html = [False]
    """Свой прокси перед стендом: задерживает ТОЛЬКО ответы text/html.

    Зачем не `page.route` и не родное торможение — в шапке файла.
    Возвращает (адрес_базы, остановить)."""
    import http.client
    import http.server
    import socketserver
    import threading

    ХОП = {"connection", "keep-alive", "proxy-authenticate", "transfer-encoding",
           "proxy-authorization", "te", "trailers", "upgrade", "content-length"}

    class Ручка(http.server.BaseHTTPRequestHandler):
        protocol_version = "HTTP/1.1"

        def log_message(self, *а):
            pass

        def handle_one_request(self):
            # Браузер обрывает соединение на каждой навигации — это
            # НОРМА, а не сбой прокси. Без этого http.server печатает
            # трассу на пол-экрана и топит ею вывод замера.
            try:
                http.server.BaseHTTPRequestHandler.handle_one_request(self)
            except (ConnectionAbortedError, ConnectionResetError,
                    BrokenPipeError):
                self.close_connection = True

        def _вперёд(self):
            # Подменённый адрес шрифтов обслуживает сам прокси: так
            # задержка чужого origin воспроизводится БЕЗ перехвата
            # маршрутов, который выключает переход (см. шапку файла).
            if self.path.startswith(ШРИФТЫ_ПОДМЕНА):
                time.sleep(ШРИФТЫ_МС / 1000.0)
                тело = b"/* fonts stub */"
                self.send_response(200)
                self.send_header("Content-Type", "text/css")
                self.send_header("Cache-Control", "no-store")
                self.send_header("Content-Length", str(len(тело)))
                self.end_headers()
                self.wfile.write(тело)
                return
            длина = int(self.headers.get("Content-Length") or 0)
            тело = self.rfile.read(длина) if длина else None
            с = http.client.HTTPConnection(цель_хост, цель_порт, timeout=60)
            заг = {k: v for k, v in self.headers.items()
                   if k.lower() not in ХОП}
            заг["Host"] = "%s:%d" % (цель_хост, цель_порт)
            try:
                с.request(self.command, self.path, body=тело, headers=заг)
                о = с.getresponse()
                данные = о.read()
                тип = о.getheader("Content-Type") or ""
                # АДРЕС ЧУЖИХ ШРИФТОВ УВОДИТСЯ НА СЕБЯ — и в css, и
                # в html: с 2026-08-24 он подключается тегом в <head>
                # (BACKLOG №157), а не `@import`-ом из style.css. Ищем
                # в обоих: проба, знающая только про один способ, после
                # переезда молча перестала бы задерживать что-либо
                # и печатала бы «чисто» про непрогнанный замер.
                if подменять_шрифты                         and ("css" in тип or тип.startswith("text/html"))                         and ЧУЖИЕ_ШРИФТЫ.encode() in данные:
                    вышло = b""
                    остаток = данные
                    while ЧУЖИЕ_ШРИФТЫ.encode() in остаток:
                        л = остаток.index(ЧУЖИЕ_ШРИФТЫ.encode())
                        # конец адреса — ближайшая кавычка любого вида
                        концы = [i for i in (остаток.find(b"'", л),
                                             остаток.find(b'"', л)) if i > 0]
                        п = min(концы) if концы else len(остаток)
                        вышло += остаток[:л] + ШРИФТЫ_ПОДМЕНА.encode()
                        остаток = остаток[п:]
                    данные = вышло + остаток
                if сломать_onload and тип.startswith("text/html"):
                    # ПОДЛОГ: срезаем ПРЕДЗАГРУЗКУ шрифта. Прежде здесь
                    # срезался `onload` у неблокирующего тега чужих
                    # шрифтов — механизма, который убрала задача 158;
                    # подлог перестал вставать и честно падал бы,
                    # а подлог, который не встал, неотличим от слепой
                    # пробы (§6.0.3).
                    маяк = b'rel="preload" as="font"'
                    if маяк not in данные:
                        raise RuntimeError(
                            "ПОДЛОГ НЕ ВСТАЛ: предзагрузки шрифта нет "
                            "в разметке дословно")
                    поз = данные.index(маяк)
                    н = данные.rindex(b"<link", 0, поз)
                    к = данные.index(b">", поз) + 1
                    данные = данные[:н] + данные[к:]
                if снять_правило and тип.startswith("text/html"):
                    if КОНТРОЛЬ_БЛОКИРУЮЩИЙ.encode("utf-8") not in данные:
                        # Подлог, который не встал, неотличим от слепой
                        # пробы: и там и там «находок нет».
                        raise RuntimeError(
                            "ПОДЛОГ НЕ ВСТАЛ: строки неблокирующей "
                            "загрузки шрифтов нет в разметке дословно")
                    данные = данные.replace(
                        КОНТРОЛЬ_БЛОКИРУЮЩИЙ.encode("utf-8"), b"")
                    встало_html[0] = True
                if снять_правило and "css" in тип:
                    было = данные
                    данные = данные.replace(
                        КОНТРОЛЬ_ЧТО_СНЯТЬ.encode("utf-8"), b"")
                    if len(данные) == len(было) and b"view-transition" in было:
                        # Правило есть, а снять не вышло — контроль
                        # не прогнан, а не пройден.
                        raise RuntimeError(
                            "ПОДЛОГ НЕ ВСТАЛ: строка правила в CSS "
                            "не совпала дословно")
                # ЗАДЕРЖКА ТОЛЬКО РАЗМЕТКЕ. Стили и скрипты идут мгновенно —
                # на проде они лежат в кеше браузера (§2.2), и тормозить
                # их значило бы мерить другую беду.
                if задержка_мс and тип.startswith("text/html"):
                    time.sleep(задержка_мс / 1000.0)
                self.send_response(о.status)
                for k, v in о.getheaders():
                    if k.lower() in ХОП:
                        continue
                    self.send_header(k, v)
                self.send_header("Content-Length", str(len(данные)))
                self.end_headers()
                # ТЕЛО РАЗМЕТКИ ИДЁТ ПОТОКОМ, А НЕ ОДНИМ КУСКОМ.
                # Замерено: буферизованная отдача по петле пустого кадра
                # не даёт ВООБЩЕ — браузер получает документ целиком
                # и рисует его целиком. На настоящей сети 68 КБ приезжают
                # за несколько оборотов, и разбор ждёт посреди документа;
                # ровно в этом ожидании и рисуется одна шапка.
                if поток and тип.startswith("text/html") and len(данные) > КУСОК:
                    for н in range(0, len(данные), КУСОК):
                        self.wfile.write(данные[н:н + КУСОК])
                        self.wfile.flush()
                        time.sleep(КУСОК / float(поток))
                else:
                    self.wfile.write(данные)
            except Exception as e:
                # Молча отдать 200 значило бы объявить сбой прокси
                # исправной страницей (§6.0.1).
                self.send_response(502)
                тело_ош = ("прокси пробы: %s" % e).encode("utf-8")
                self.send_header("Content-Type", "text/plain; charset=utf-8")
                self.send_header("Content-Length", str(len(тело_ош)))
                self.end_headers()
                self.wfile.write(тело_ош)
            finally:
                с.close()

        do_GET = do_POST = do_PUT = do_DELETE = do_PATCH = do_HEAD = _вперёд

    class Сервер(socketserver.ThreadingTCPServer):
        daemon_threads = True
        allow_reuse_address = True

    с = Сервер(("127.0.0.1", 0), Ручка)
    порт = с.server_address[1]
    п = threading.Thread(target=с.serve_forever, daemon=True)
    п.start()
    return "http://127.0.0.1:%d" % порт, с.shutdown


def _доля_непустых(им, y0=ШАПКА):
    """Доля пикселей ниже y0, отличающихся от фона страницы.

    Фон берётся из левого нижнего угла кадра: это заведомо подложка
    страницы на любом из четырёх экранов админки. Шаг 4 по обеим осям —
    считать каждый пиксель кадра 2560x1400 сорок раз за прогон незачем,
    а разделяющая способность (два порядка между 0.0% и 15%) от шага
    не зависит.
    """
    им = им.convert("RGB")
    ш, в = им.size
    if y0 >= в:
        return 0.0
    фон = им.getpixel((3, в - 3))
    п = им.load()
    иных = всего = 0
    for y in range(y0, в, 4):
        for x in range(0, ш, 4):
            всего += 1
            r, g, b = п[x, y]
            if abs(r - фон[0]) + abs(g - фон[1]) + abs(b - фон[2]) > 24:
                иных += 1
    return иных / всего if всего else 0.0



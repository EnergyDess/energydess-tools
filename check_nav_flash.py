# -*- coding: utf-8 -*-
"""ПУСТОЙ КАДР МЕЖДУ ДВУМЯ ДОКУМЕНТАМИ.

ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ `check_flash.py`, И ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ.
`check_flash` меряет ПЕРВЫЙ КАДР ОДНОГО документа: что в нём уже
нарисовано и что доедет позже. Он ходит по экранам поодиночке и про
промежуток МЕЖДУ документами не спрашивает вовсе — его «0 из 21»
честное число про другое явление.

Дефект, ради которого написан этот файл, живёт ровно в промежутке:
человек нажимает вкладку админки, старый документ уходит, новый ещё
не готов, и браузер рисует кадр, на котором есть ТОЛЬКО шапка сайта —
ни панели разделов, ни таблицы, ни аватара. Владелец снял это на видео
и разложил покадрово; ни одна из двадцати пяти проверок проекта этого
не видела, потому что ни одна не задавала такого вопроса.

ПОЧЕМУ СКРИНКАСТ, А НЕ `page.screenshot` В ЦИКЛЕ — тот же довод, что
в `check_flash`: снимок Playwright сам занимает десятки миллисекунд
и сам дёргает конвейер отрисовки. Скринкаст отдаёт кадр ТОГДА, КОГДА
БРАУЗЕР ЕГО НАРИСОВАЛ.

ЧТО СЧИТАЕТСЯ НАХОДКОЙ. Кадр, у которого НИЖЕ ШАПКИ доля непустых
пикселей меньше `ПУСТО`, при том что последний кадр перехода
содержателен (иначе «пусто» означало бы «страница пуста», а не
«страница не нарисовалась»). Порог взят замером, а не назначен:
у готовых страниц админки доля ниже шапки 15–72%, у неполного кадра —
ровно 0.0%. Между ними два порядка, и любое число в промежутке
разделяет одинаково.

ЗАМЕР ВРЕМЕНИ — вторая половина, и она не менее нужна. `--времена`
печатает, сколько миллисекунд проходит от нажатия до УСТОЯВШЕГОСЯ
кадра новой страницы. Без него правка, убравшая пустой кадр ценой
вдвое более долгого перехода, выглядела бы победой.

ЗАДЕРЖКУ ДАЁТ СВОЙ ПРОКСИ, А НЕ ПЕРЕХВАТ МАРШРУТА, И ЭТО НЕ ВКУС.
Первая версия тормозила документ через `page.route` — и замер показал,
что ПЕРЕХВАТ САМ ВЫКЛЮЧАЕТ ПЕРЕХОД: `pageswap` на старой странице
сообщал `viewTransition`, а `pagereveal` на новой приходил уже
с `false`, то есть Chromium переход пропускал. Проба при этом печатала
пустые кадры и на исправленном коде — то есть врала ровно тем способом,
ради поиска которого написана (§6.0.3). Проверено в обе стороны:
асинхронный API без блокировки цикла даёт тот же результат, оконный
режим тоже, значит дело в самом перехвате, а не в блокировке.

ШТАТНОЕ ТОРМОЖЕНИЕ СЕТИ (`Network.emulateNetworkConditions`) НЕ ГОДИТСЯ
ПО ДРУГОЙ ПРИЧИНЕ: оно задерживает ВСЁ, включая css. Дефект живёт там,
где документ медленный, а стили уже в кеше — а между вкладками админки
именно так и есть: `?v=` с отпечатком содержимого делает их
`immutable` (§2.2). Замер: при родном торможении 120 мс пустых кадров
НОЛЬ и до правки, и после — то есть маскируется сам предмет замера.

Поэтому проба поднимает СВОЙ прокси и задерживает только ответы
`text/html`. Это ровно прод: документ идёт по сети, стили лежат
в кеше браузера.

ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ВОЗВРАЩАЕТ ДВА УСЛОВИЯ СРАЗУ, и это выяснилось
замером, а не рассуждением. Он снимает из отдаваемого CSS правило
`@view-transition` И возвращает шрифтам блокирующую загрузку (убирает
`media="print"` из тега в разметке). Одного первого НЕ ХВАТАЕТ: после
того как шрифты перестали блокировать отрисовку, снятие одного лишь
правила перехода даёт 0 пустых кадров из 12 — то есть контроль сообщал
бы «проба слепа» про исправную пробу.

Подлог живёт в ответе прокси; ни репозиторий, ни диск не трогаются.
Не встал — исключение, а не тихий пропуск: подлог, который не применился,
неотличим от слепой пробы. Контроль обязан найти пустой кадр; не нашёл —
зелёный результат недействителен.

Браузер и поднятое приложение; в ряды §6.0.2 НЕ входит.
"""

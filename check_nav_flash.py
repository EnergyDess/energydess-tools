ЧУЖИЕ_ШРИФТЫ = "https://fonts.googleapis.com/css2"
ШРИФТЫ_ПОДМЕНА = "/__fonts_probe.css"

# Разделы админки. Переходы — ВСЕ упорядоченные пары: дефект нашли
# на паре «Пользователи -> Продукты», но ничто не обещает, что он живёт

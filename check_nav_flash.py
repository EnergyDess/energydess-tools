def _подпись_менялась(кадры, рект, масштаб):
    """B.3: менялась ли ПОДПИСЬ ПОИСКА на кадрах перехода.

    Прежняя проба (`check_flash`) спрашивала про первый кадр ГОТОВОГО
    документа и на широком экране печатала «чисто»: к моменту, когда
    её инструментовка могла прочитать дерево, встроенный скрипт уже
    отработал. Пиксели говорили другое — на кадрах ПЕРЕХОДА подпись
    была короткой (замер: 2 случая из 5 на 2560, 1 из 5 на 1920).

    Поэтому вопрос задаётся кадрам, и задаётся ПИКСЕЛЯМ: вырез поля
    сравнивается с ним же на последнем кадре. Отличие — либо подпись
    сменилась, либо сменился шрифт; и то и другое человек видит рывком.

    ПОРОГ ВЗЯТ ЗАМЕРОМ, А НЕ НАЗНАЧЕН. Настоящая смена подписи
    (длинная -> «Поиск») даёт отличие 4.08; два снимка одного и того же
    текста — 0.00; кадр скринкаста, отмасштабированный до 1600 и
    отличающийся от финального субпиксельным сдвигом, — около 1.0.
    Первая версия брала общий порог `СОВПАЛ` (0.4) и на этом сдвиге
    давала ЛОЖНЫЕ находки: 50 «смен подписи» подряд на одном переходе.
    """
    if not рект or len(кадры) < 2:
        return None
    л, в, п, н = [int(x * масштаб) for x in рект]
    фин = кадры[-1][2]
    ш, вы = фин.size
    л, п = max(0, min(ш - 1, л)), max(1, min(ш, п))
    в, н = max(0, min(вы - 1, в)), max(1, min(вы, н))
    if п <= л or н <= в:
        return None
    эталон = фин.crop((л, в, п, н))
    менялась = []
    for t, доля, им in кадры:
        if доля < ПУСТО:
            continue   # пустой кадр считает другая мерка
        о = _отличие(им.crop((л, в, п, н)), эталон)
        if о > ПОДПИСЬ_СМЕНИЛАСЬ:
            менялась.append((t, round(о, 2)))
    return менялась


def _переход(стр, cdp, собрано, куда_селектор):
    """Один переход: нажать и собрать кадры. Возвращает [(мс, доля, кадр)]."""
    from PIL import Image
    собрано.clear()
    cdp.send("Page.startScreencast",
             {"format": "png", "everyNthFrame": 1, "maxWidth": 1600})
    t0 = time.time()
    стр.click(куда_селектор)
    while (time.time() - t0) * 1000 < ОКНО_МС:
        стр.wait_for_timeout(16)
    cdp.send("Page.stopScreencast")
    кадры = []
    for t, d in list(собрано):
        им = Image.open(io.BytesIO(base64.b64decode(d)))
        кадры.append((round((t - t0) * 1000, 1), _доля_непустых(им), им))
    return кадры


def _отличие(a, b):
    """Средняя абсолютная разница двух кадров, 0..255. Кадры уменьшаются
    до 160 по ширине: полноразмерное сравнение 2560x1400 сорок раз
    за прогон ничего не добавляет к ответу «изменился ли кадр»."""
    from PIL import Image, ImageChops, ImageStat
    if a.size != b.size:
        return 255.0
    м = (160, max(1, int(160 * a.size[1] / a.size[0])))
    x = ImageChops.difference(a.convert("RGB").resize(м, Image.BILINEAR),
                              b.convert("RGB").resize(м, Image.BILINEAR))
    return sum(ImageStat.Stat(x).mean) / 3.0


# Ниже этого среднего отличия кадр считается совпавшим с финальным.
# Замер: у двух соседних кадров УСТОЯВШЕЙСЯ страницы отличие 0.00–0.03,
# в середине кроссфейда — единицы и десятки.
СОВПАЛ = 0.4

# Отличие выреза поля поиска, выше которого подпись считается сменившейся.
# Замер: настоящая смена 4.08, тот же текст 0.00, субпиксельный сдвиг
# отмасштабированного кадра ~1.0. Взято 2.0 — между шумом и находкой.
ПОДПИСЬ_СМЕНИЛАСЬ = 2.0


def _разбор(кадры):
    """Пустые кадры и время до устоявшегося. Без кадров — честно None.

    «УСТОЯЛСЯ» — ПЕРВЫЙ кадр, ПОСЛЕ которого доля больше не уходит
    от финальной. Не «первый, дотянувший до финальной»: у пары
    «Продукты -> Пользователи» целевая страница СОДЕРЖИТ МЕНЬШЕ
    исходной (таблица на три строки против двадцати двух), и кадр
    СТАРОЙ страницы порог финальной перекрывал с запасом — проба
    печатала «устоялся 26 мс» про переход, который занял 870.
    Поймано на собственном отрицательном контроле.
    """
    if not кадры:
        return None
    финал = кадры[-1][1]
    пустые = [(t, д) for t, д, _ in кадры if д < ПУСТО]
    порог = max(финал * (1 - УСТОЯЛСЯ), ПУСТО)
    устоялся = None
    for i, (t, д, _) in enumerate(кадры):
        if all(abs(д2 - финал) <= порог for _, д2, _ in кадры[i:]):
            устоялся = t
            break
    # ДОРИСОВАЛСЯ — строгая мерка: первый кадр, ПОСЛЕ которого картинка
    # больше не отличается от финальной. «Устоялся» отвечает на вопрос
    # «когда приехало содержимое», а этот — «когда кончилось движение»,
    # и без второго правка, удлинившая переход анимацией, выглядела бы
    # бесплатной: доля непустых пикселей дотягивает до порога уже
    # на середине кроссфейда.
    финкадр = кадры[-1][2]
    дорисовался = None
    отличия = [_отличие(им, финкадр) for _, _, им in кадры]
    for i, (t, _, _) in enumerate(кадры):
        if all(o <= СОВПАЛ for o in отличия[i:]):
            дорисовался = t
            break
    return {"кадров": len(кадры), "финал": финал, "пустые": пустые,
            "устоялся": устоялся, "дорисовался": дорисовался}


def _прогон(ширина, высота, подлог=False, сохранять=None, пары=None,
            задержка=ЗАДЕРЖКА_ПРОДА_МС):
    from playwright.sync_api import sync_playwright
    from urllib.parse import urlparse
    отчёт = []
    пары = пары if пары is not None else [
        (a, b) for a in РАЗДЕЛЫ for b in РАЗДЕЛЫ if a[0] != b[0]]

    у = urlparse(БАЗА)
    база, стоп = _поднять_прокси(у.hostname, у.port or 80, задержка,
                                 снять_правило=подлог, поток=ПОТОК)
    # Вход идёт ЧЕРЕЗ ТОТ ЖЕ адрес: кука привязана к origin, и войдя
    # напрямую, мы получили бы неавторизованный прокси и страницу входа
    # под подписью «админка» — ровно то, что чинил `ch._войти`.
    прежняя = ch.БАЗА
    ch.БАЗА = база
    переходов_с_переходом = 0
    try:
        with sync_playwright() as p:
            бр = p.chromium.launch()
            кон = бр.new_context(viewport={"width": ширина, "height": высота},
                                 device_scale_factor=1)
            стр = кон.new_page()
            ch._войти(стр)
            стр.add_init_script(МЕТКИ_ПЕРЕХОДА)

            cdp = кон.new_cdp_session(стр)
            собрано = []

            def приёмка(п):
                собрано.append((time.time(), п.get("data")))
                try:
                    cdp.send("Page.screencastFrameAck",
                             {"sessionId": п["sessionId"]})
                except Exception:
                    pass
            cdp.on("Page.screencastFrame", приёмка)

            for (имя_a, путь_a), (имя_b, путь_b) in пары:
                try:
                    стр.goto(база + путь_a, wait_until="load", timeout=60000)
                    стр.wait_for_timeout(700)
                    рект = _поле_поиска(стр)
                    кадры = _переход(стр, cdp, собрано,
                                     'a.tab-btn[href="%s"]' % путь_b)
                    р = _разбор(кадры)
                    if р is not None and кадры:
                        масштаб = кадры[-1][2].size[0] / float(ширина)
                        р["подпись"] = _подпись_менялась(кадры, рект, масштаб)
                    if р is not None:
                        метки = стр.evaluate("window.__vt || []")
                        р["с_переходом"] = bool(метки and метки[-1])
                        if р["с_переходом"]:
                            переходов_с_переходом += 1
                    if р and сохранять and р["пустые"]:
                        for t, д, им in кадры:
                            if д < ПУСТО:
                                им.save(os.path.join(
                                    сохранять,
                                    "pusto_%d_%s-%s_%s.png"
                                    % (ширина, имя_a, имя_b,
                                       str(t).replace(".", "_"))))
                                break
                    отчёт.append((имя_a, имя_b, р, None))
                except Exception as e:
                    отчёт.append((имя_a, имя_b, None,
                                  "%s: %s" % (type(e).__name__, e)))
            бр.close()
    finally:
        ch.БАЗА = прежняя
        стоп()
    return отчёт, переходов_с_переходом


def _печать(заголовок, отчёт):
    print(заголовок)
    находок = слепых = 0
    for a, b, р, ош in отчёт:
        if ош:
            print("  %-11s -> %-11s  СБОЙ: %s" % (a, b, ош))
            слепых += 1
            continue
        if р is None or р["кадров"] == 0:
            # Ноль кадров — не «чисто». Молчание пробы обязано отличаться
            # от пройденного перехода, иначе слепая проба зелена (§6.0.1).
            print("  %-11s -> %-11s  ИНСТРУМЕНТОВКА НЕ ОТРАБОТАЛА: кадров 0"
                  % (a, b))
            слепых += 1
            continue
        подпись = р.get("подпись") or []
        метка = "ПУСТОЙ КАДР" if р["пустые"] else (
            "ПОДПИСЬ" if подпись else "чисто")
        доп = ""
        if подпись:
            доп += "  подпись поиска менялась на %s мс" % (
                ", ".join(str(t) for t, _ in подпись))
        if р["пустые"]:
            доп = "  на %s мс (доля %.1f%%)" % (
                ", ".join(str(t) for t, _ in р["пустые"]),
                100 * min(д for _, д in р["пустые"]))
            находок += 1
        elif подпись:
            находок += 1
        print("  %-11s -> %-11s  %-11s  кадров %2d, финал %5.1f%%, "
              "содержимое %s мс, движение до %s мс%s"
              % (a, b, метка, р["кадров"], 100 * р["финал"],
                 р["устоялся"], р["дорисовался"], доп))
    return находок, слепых


def _времена(ширина, высота, повторов, пара, задержка=ЗАДЕРЖКА_ПРОДА_МС):
    """A.2: сколько миллисекунд от нажатия до устоявшегося кадра.

    Все повторы идут ОДНОЙ сессией браузера: `_прогон` возвращается
    на исходный раздел перед каждой парой, поэтому один и тот же переход,
    поданный списком, честно меряется столько раз, сколько попросили.
    Отдельный запуск браузера на каждый повтор стоил бы восьми секунд
    входа и мерил бы заодно холодный старт.
    """
    о, _ = _прогон(ширина, высота, пары=[пара] * повторов, задержка=задержка)
    ряд = [(р["устоялся"] if р and р["устоялся"] is not None else None)
           for _, _, р, _ in о]
    ряд2 = [(р["дорисовался"] if р and р["дорисовался"] is not None else None)
            for _, _, р, _ in о]
    return (ряд, sorted(x for x in ряд if x is not None),
            ряд2, sorted(x for x in ряд2 if x is not None))


# ── ШРИФТ ДОЕХАЛ ДО ЭКРАНА (§6.0, НЕМОЙ ОТКАЗ) ─────────────────────────
# Приём `media="print"` плюс `onload` СНИМАЕТ БЛОКИРОВКУ ОТРИСОВКИ, но
# сам по себе он немой: не сработает `onload` — носитель останется
# печатным, шрифт не применится НИКОГДА, и ни ошибки, ни строки
# в журнале при этом не будет. Страница просто нарисуется запасной
# гарнитурой, и отличить это от «файл ещё едет» нечем.
#
# Поэтому вопрос задаётся ЖИВОЙ странице, и задаётся ТРИЖДЫ:
#   · носитель тега стал `all` — то есть `onload` отработал;
#   · `document.fonts.check('1em Manrope')` — то есть браузер
#     ДЕЙСТВИТЕЛЬНО может рисовать этой гарнитурой;
#   · ширина одного и того же текста в Manrope и в запасной гарнитуре
#     РАЗЛИЧАЕТСЯ — то есть подмена дошла до пикселей, а не только
#     до состояния объекта.
#
# Третье не избыточно: `fonts.check` отвечает про ЗАГРУЖЕННОСТЬ, а не
# про то, что этой гарнитурой что-то нарисовано.
ФОНТ_ЗАМЕР = r"""
() => {
  const о = {};
  // ЧУЖИХ ТЕГОВ ШРИФТА БЫТЬ НЕ ДОЛЖНО ВОВСЕ — задача 158 убрала их.
  о.чужих = [...document.querySelectorAll('link')]
      .filter(l => /fonts\.(googleapis|gstatic)\.com/.test(l.href || '')).length;
  // СВОЙ preload — он и делает «успел к первой отрисовке» частым.
  о.предзагрузок = [...document.querySelectorAll('link[rel=preload][as=font]')]
      .length;
  о.статус = document.fonts.status;
  // ЛИЦА ИЗ ПРИМЕНЁННОЙ ТАБЛИЦЫ, а не `fonts.check`: последний отвечает
  // «умеет ли браузер рисовать этой гарнитурой» и даёт true, когда шрифт
  // просто УСТАНОВЛЕН В СИСТЕМЕ (замер на машине разработчика).
  о.лиц = document.fonts.size;
  о.лиц_manrope = [...document.fonts].filter(f => f.family === "Manrope").length;
  о.подогнанных = [...document.fonts]
      .filter(f => f.family.indexOf("Manrope Fallback") === 0).length;
  const мерка = (сем) => {
    const s = document.createElement('span');
    s.textContent = 'Проверка ширины шрифта 0123456789';
    s.style.cssText = 'position:absolute;left:-9999px;top:0;'
                    + 'font-size:32px;white-space:nowrap;font-family:' + сем;
    document.body.appendChild(s);
    const w = s.getBoundingClientRect().width;
    s.remove();
    return Math.round(w * 100) / 100;
  };
  о.ширина_manrope = мерка("Manrope");
  о.ширина_подогнанной = мерка("'Manrope Fallback'");
  о.ширина_системной = мерка("sans-serif");
  return о;
}
"""


# ── ДОКАЗАТЕЛЬСТВА ПОДЛОГОВ (§6.0.3) ────────────────────────────────
#
# Подлоги здесь кладутся НЕ В СТРАНИЦУ, а в БАЙТЫ ответа прокси, и «не
# встал» ловится исключением на месте (`ПОДЛОГ НЕ ВСТАЛ» выше). Этого
# довольно, чтобы подлог не провалился МОЛЧА, и НЕ довольно, чтобы
# утверждать, что он изменил СТРАНИЦУ: между вырезанным байтом и тем,
# что применил браузер, лежит его собственный разбор.
#
# Поэтому рядом стоит НЕЗАВИСИМЫЙ ЗАМЕР — у уже загруженной страницы
# спрашивается ровно то, что подлог собирался снять: носитель тега
# шрифтов (подлог `--шрифт`) и наличие правила перехода в применённых
# стилях (подлог основного контроля).
ДОКАЗАТЕЛЬСТВО_ШРИФТА = """
() => {
  // Спрашиваем ровно то, что подлог собирался снять, — ПРЕДЗАГРУЗКУ
  // своего шрифта. Прежде спрашивался носитель чужого тега; после
  // задачи 158 такого тега нет вовсе, и доказательство отвечало
  // «тега нет» и до подлога, и после, то есть не различало ничего.
  const т = [...document.querySelectorAll('link[rel=preload][as=font]')];
  return 'предзагрузок шрифта: ' + т.length
       + (т.length ? ' (' + т[0].href.split('/').pop() + ')' : '');
}
"""

ДОКАЗАТЕЛЬСТВО_ПЕРЕХОДА = """
() => {
  let есть = 0;
  for (const л of document.styleSheets) {
    let правила;
    try { правила = л.cssRules; } catch (e) { continue; }
    for (const п of правила || []) {
      if ((п.cssText || '').includes('view-transition')) есть++;
    }
  }
  const ш = [...document.querySelectorAll('link')]
    .filter(l => (l.href || '').includes('fonts.googleapis.com'));
  return 'правил @view-transition: ' + есть
       + ' | носитель шрифтов: ' + (ш.length ? (ш[0].media || 'all') : 'тега нет');
}
"""


def доказать_подлог(выражение, **подлог):
    """Состояние загруженной страницы БЕЗ подлога и С ним.

    Прокси поднимается дважды — чистый и с подлогом, — и обоим задаётся
    ОДИН и тот же вопрос. Ни кадры скринкаста, ни счёт пустых кадров
    в замере не участвуют.
    """
    from playwright.sync_api import sync_playwright
    from urllib.parse import urlparse

    у = urlparse(БАЗА)
    прежняя = ch.БАЗА
    ответы = []
    try:
        for класть in (False, True):
            ключи = dict(подлог) if класть else {}
            ключи.setdefault("подменять_шрифты", False)
            база, стоп = _поднять_прокси(у.hostname, у.port or 80, 0, **ключи)
            ch.БАЗА = база
            try:
                with sync_playwright() as p:
                    бр = p.chromium.launch()
                    кон = бр.new_context(viewport={"width": 1280,
                                                   "height": 800})
                    стр = кон.new_page()
                    ch._войти(стр)
                    стр.goto(база + РАЗДЕЛЫ[0][1], wait_until="load",
                             timeout=60000)
                    стр.wait_for_timeout(1200)
                    ответы.append(стр.evaluate(выражение))
                    бр.close()
            finally:
                стоп()
    finally:
        ch.БАЗА = прежняя
    return ответы[0], ответы[1]


def _проверить_шрифт(подлог=False):
    """Пункт 1 приёмки владельца: доехал ли шрифт до экрана.

    ВОПРОС СМЕНИЛСЯ ВМЕСТЕ С МЕХАНИЗМОМ — задача 158. Прежде шрифт
    приезжал с чужого домена неблокирующим тегом, и проверка спрашивала,
    отработал ли `onload`: не отработал — носитель остался печатным,
    шрифта нет, и ни ошибки, ни строки в журнале. Теперь шрифты СВОИ,
    правилами `@font-face`, и того тега нет вовсе — прежний вопрос
    отвечал бы «плохо» на исправном коде, что и случилось при первом
    прогоне после правки.

    Спрашивается пять вещей: чужих тегов и чужих запросов НЕТ вовсе;
    предзагрузка на месте; лица Manrope применены; подогнанная запасная
    гарнитура объявлена; свой файл не скачан дважды.

    `подлог=True` — контроль: прокси срезает из разметки предзагрузку.
    Проверка ОБЯЗАНА это назвать.
    """
    from playwright.sync_api import sync_playwright
    from urllib.parse import urlparse

    у = urlparse(БАЗА)
    # Адрес шрифтов НЕ подменяется: проверка спрашивает про настоящее
    # поведение страницы, а не про поведение заглушки.
    база, стоп = _поднять_прокси(у.hostname, у.port or 80, 0,
                                 сломать_onload=подлог,
                                 подменять_шрифты=False)
    прежняя = ch.БАЗА
    ch.БАЗА = база
    плохих = 0
    try:
        with sync_playwright() as p:
            бр = p.chromium.launch()
            кон = бр.new_context(viewport={"width": 1280, "height": 800},
                                 device_scale_factor=1)
            стр = кон.new_page()
            ch._войти(стр)
            # ОБРАБОТЧИК ВЕШАЕТСЯ ОДИН РАЗ. Первая версия навешивала его
            # внутри цикла, и каждый следующий слушатель дописывал в ТОТ ЖЕ
            # список (замыкание берёт переменную, а не значение): счётчик
            # рос 1, 2, 3, 4 и объявлял двойной загрузкой собственную
            # ошибку. Поймано тем, что число совпало с номером страницы.
            запросы = []
            стр.on("request", lambda r: запросы.append(r.url))
            for имя, путь in РАЗДЕЛЫ:
                запросы.clear()
                стр.goto(база + путь, wait_until="load", timeout=60000)
                стр.wait_for_timeout(1200)
                о = стр.evaluate(ФОНТ_ЗАМЕР)
                чужие = [u for u in запросы
                         if "fonts.googleapis.com" in u or "fonts.gstatic.com" in u]
                свои = [u for u in запросы if "/static/fonts/" in u]
                беды = []
                if о["чужих"]:
                    беды.append("в разметке %d тегов ЧУЖОГО шрифта" % о["чужих"])
                if чужие:
                    беды.append("%d запросов в ЧУЖУЮ сеть за шрифтом" % len(чужие))
                if о["предзагрузок"] == 0:
                    беды.append("предзагрузки шрифта нет — «успеть к первой "
                                "отрисовке» станет редкостью")
                if о["лиц_manrope"] == 0:
                    беды.append("ни одного лица Manrope в document.fonts — "
                                "правила @font-face НЕ ПРИМЕНЕНЫ")
                if о["подогнанных"] == 0:
                    беды.append("подогнанной запасной гарнитуры НЕТ — "
                                "подмена снова будет двигать раскладку")
                # СРАВНИВАЕМ ПУТЬ, А НЕ ПОЛНЫЙ АДРЕС. Первая версия
                # сравнивала адреса целиком и ПРОПУСТИЛА настоящий
                # двойной скач: preload шёл через `st()` с `?v=`,
                # а @font-face — без него. Адреса разные, файл один.
                пути = [u.split("?")[0] for u in свои]
                if len(пути) != len(set(пути)):
                    беды.append("файл шрифта скачан дважды: %d запросов, "
                                "%d разных путей" % (len(пути), len(set(пути))))
                метка = "ПЛОХО" if беды else "ok"
                print("  %-5s %-18s лиц=%d (Manrope %d, подогнанных %d)  "
                      "своих=%d чужих=%d%s"
                      % (метка, путь, о["лиц"], о["лиц_manrope"],
                         о["подогнанных"], len(свои), len(чужие),
                         ("  — " + "; ".join(беды)) if беды else ""))
                if беды:
                    плохих += 1
                стр.remove_listener("request", стр.listeners("request")[-1]) \
                    if hasattr(стр, "listeners") else None
            бр.close()
    finally:
        ch.БАЗА = прежняя
        стоп()
    return плохих


def главная():
    аргв = sys.argv[1:]
    контроль = "--контроль" in аргв
    if "--шрифт" in аргв:
        # Пункт приёмки владельца: приём `media="print"` + `onload`
        # снимает блокировку отрисовки, но сам по себе НЕМОЙ.
        if контроль:
            print("КОНТРОЛЬ ШРИФТА: прокси срезает ПРЕДЗАГРУЗКУ шрифта — "
                  "проверка ОБЯЗАНА это назвать")
            # ШАГ ПЕРВЫЙ — ДОКАЗАТЬ, ЧТО ПОДЛОГ СОСТОЯЛСЯ (§6.0.3)
            д_ч, д_п = доказать_подлог(ДОКАЗАТЕЛЬСТВО_ШРИФТА,
                                       сломать_onload=True)
            print("  доказательство (предзагрузка шрифта в разметке):")
            print("     чисто      = %s" % д_ч)
            print("     с подлогом = %s" % д_п)
            if д_ч == д_п:
                print("     → ПОДЛОГ НЕ СОСТОЯЛСЯ: срезать было нечего, "
                      "вердикт проверки ничего не значит.")
                return 1
            print("     → ПОДЛОГ СОСТОЯЛСЯ")
            плохих = _проверить_шрифт(подлог=True)
            print("" + chr(10) + "страниц с находкой: %d из %d" % (плохих, len(РАЗДЕЛЫ)))
            if плохих != len(РАЗДЕЛЫ):
                print("ПРОВЕРКА СЛЕПА: сломанный `onload` обязан быть найден "
                      "на КАЖДОЙ странице. Зелёный результат без пройденного "
                      "контроля недействителен.")
                return 1
            print("Проверка видит немой отказ.")
            return 0
        print("ШРИФТ ДОЕХАЛ ДО ЭКРАНА (свой домен, гарнитура "
              "применена, двойной загрузки нет)")
        плохих = _проверить_шрифт()
        print(chr(10) + "страниц с находкой: %d из %d"
              % (плохих, len(РАЗДЕЛЫ)))
        return 1 if плохих else 0
    времена = "--времена" in аргв
    сохранять = None
    if "--снимки" in аргв:
        сохранять = ch.КУДА_СНИМКИ
        os.makedirs(сохранять, exist_ok=True)

    задержка = ЗАДЕРЖКА_ПРОДА_МС
    for i, a in enumerate(аргв):
        if a == "--задержка" and i + 1 < len(аргв):
            задержка = int(аргв[i + 1])
        if a == "--шрифты" and i + 1 < len(аргв):
            globals()["ШРИФТЫ_МС"] = int(аргв[i + 1])

    ширины = ch.отобрать_ширины(ШИРИНЫ)

    if времена:
        повторов = 10
        for i, a in enumerate(аргв):
            if a == "--времена" and i + 1 < len(аргв) and аргв[i + 1].isdigit():
                повторов = int(аргв[i + 1])
        пара = (РАЗДЕЛЫ[0], РАЗДЕЛЫ[1])
        print("ВРЕМЯ ПЕРЕХОДА %s -> %s, прогонов %d, "
              "подставленная задержка документа %d мс"
              % (пара[0][0], пара[1][0], повторов, задержка))
        for ш, в in ширины:
            ряд, годные, ряд2, годные2 = _времена(ш, в, повторов, пара,
                                                  задержка)
            for метка, р, г in (("содержимое приехало", ряд, годные),
                                ("движение кончилось ", ряд2, годные2)):
                if not г:
                    print("  ширина %4d  %s: НИ ОДНОГО ГОДНОГО ЗАМЕРА"
                          % (ш, метка))
                    continue
                n = len(г)
                мед = г[n // 2] if n % 2 else (г[n // 2 - 1] + г[n // 2]) / 2
                print("  ширина %4d  %s: min %6.1f  медиана %6.1f  "
                      "max %6.1f  (годных %d из %d)  ряд=%s"
                      % (ш, метка, г[0], мед, г[-1], n, повторов, р))
        return 0

    хвост = ("  (КОНТРОЛЬ: правило @view-transition снято из CSS; "
             "документ %d мс, чужие шрифты %d мс)"
             % (задержка, ШРИФТЫ_МС)) if контроль else             ("  (документ %d мс, чужие шрифты %d мс)"
             % (задержка, ШРИФТЫ_МС))
    if контроль:
        # ШАГ ПЕРВЫЙ — ДОКАЗАТЬ, ЧТО ПОДЛОГ СОСТОЯЛСЯ (§6.0.3).
        # Контроль снимает ДВА условия сразу — правило перехода из CSS
        # и неблокирующую загрузку шрифтов, — и спрашивать надо оба:
        # одного мало (замер 2026-08-24, §6.0.16).
        д_ч, д_п = доказать_подлог(ДОКАЗАТЕЛЬСТВО_ПЕРЕХОДА,
                                   снять_правило=True, подменять_шрифты=True)
        print("  доказательство (правило перехода и носитель шрифтов):")
        print("     чисто      = %s" % д_ч)
        print("     с подлогом = %s" % д_п)
        if д_ч == д_п:
            print("     → ПОДЛОГ НЕ СОСТОЯЛСЯ: снимать было нечего, "
                  "вердикт пробы ничего не значит.")
            return 1
        print("     → ПОДЛОГ СОСТОЯЛСЯ")

    всего_находок = всего_слепых = всего_переходов = всего_пар = 0
    for ш, в in ширины:
        отчёт, с_переходом = _прогон(ш, в, подлог=контроль,
                                     сохранять=сохранять, задержка=задержка)
        н, с = _печать("=== ширина %d%s ===" % (ш, хвост), отчёт)
        всего_находок += н
        всего_слепых += с
        всего_переходов += с_переходом
        всего_пар += len(отчёт)

    print()
    print("Навигаций с состоявшимся переходом: %d из %d"
          % (всего_переходов, всего_пар))
    if контроль:
        if всего_переходов:
            print("КОНТРОЛЬ НЕДЕЙСТВИТЕЛЕН: он обязан ОТМЕНЯТЬ переход, "
                  "а %d навигаций его сохранили." % всего_переходов)
            return 1
        print("КОНТРОЛЬ: переходов с пустым кадром %d, слепых %d"
              % (всего_находок, всего_слепых))
        if всего_находок == 0:
            print("ПРОБА СЛЕПА: подложенный тормоз обязан был дать пустой "
                  "кадр, а не дал. Зелёный результат без пройденного "
                  "контроля недействителен.")
            return 1
        print("Проба видит дефект.")
        return 0

    if всего_пар and всего_переходов == 0:
        # Ноль пустых кадров при непроизошедшем переходе значил бы
        # «повезло», а не «починено» (§6.0.1).
        print("ПЕРЕХОД НЕ СОСТОЯЛСЯ НИ РАЗУ — правило @view-transition "
              "не работает либо браузер его не поддерживает. Число ниже "
              "о правке не говорит ничего.")
    print("Переходов с ПУСТЫМ КАДРОМ: %d" % всего_находок)
    if всего_слепых:
        print("Не замерено (сбой или ноль кадров): %d" % всего_слепых)
    return 1 if (всего_находок or всего_слепых) else 0


if __name__ == "__main__":
    sys.exit(главная())

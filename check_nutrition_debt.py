def вкладки_для(имена, карта):
    """Множество вкладок, где эти классы встречались на живой странице."""
    где, видели = set(), False
    for имя in имена:
        for вкладка, классы in карта.items():
            if имя in классы:
                видели = True
                где.add("_вне" if вкладка == "_вне_вкладок" else вкладка)
    return где, видели


def графа(где, видели):
    """Одна вкладка / общий / вне вкладок / не наблюдался."""
    if not видели:
        return "не наблюдался"
    свои = sorted(в for в in где if в != "_вне")
    if len(свои) == 1:
        return ИМЕНА[свои[0]]
    if len(свои) > 1:
        return "общий"
    return "вне вкладок"


def секции_шаблона():
    """Разметка каждой вкладки — кусок между её <section> и следующей.

    ЗАПАСНОЙ ХОД ДЛЯ ГРАФЫ «НЕ НАБЛЮДАЛСЯ»: живой DOM видит только то,
    что открыто, — запись голоса, меню вложений и карточки находок
    в момент съёмки закрыты.

    НА СЕГОДНЯ ОН ДОБИРАЕТ НОЛЬ, и это честный результат, а не поломка:
    остаток целиком собирается ШАБЛОННЫМИ СТРОКАМИ СКРИПТА, то есть
    в статической разметке этих классов нет тоже. Число добранного
    печатается в выводе отдельной пометкой — станет ненулевым, если
    разметку однажды перенесут в шаблон.

    Статика слабее живого DOM (класс в разметке может не дожить
    до экрана), поэтому она НЕ заменяет карту, а только добирает то,
    чего карта не видела.

    ГРАНИЦА СЕКЦИИ ЗАКРЫВАЕТСЯ ПО `</section>`, А НЕ ПО НАЧАЛУ СЛЕДУЮЩЕЙ.
    Первая версия брала кусок «от секции до следующей», и последняя
    вкладка («Ассистент») забирала себе ВЕСЬ ХВОСТ ФАЙЛА — нижнюю панель,
    все модалки и полторы тысячи строк скрипта. Разбивка после этого
    приписывала «Ассистенту» 32 отступа вместо одного, и среди них были
    `.water-log-*` (вода, «Дневник»), `.brand-more` (поиск, «Добавить»)
    и `.wt-*` («Вес»). Ложная привязка выглядела правдоподобно и прошла
    бы, не будь она разложена по классам поимённо.
    """
    текст = _прочитать(ШАБЛОН)
    блоки = {}
    for m in re.finditer(
            r"<section class=\"nut-tab[^\"]*\" id=\"tab-([a-z]+)\">", текст):
        i, глубина = m.end(), 1
        while i < len(текст) and глубина:
            сл = re.search(r"<section\b|</section>", текст[i:])
            if not сл:
                break
            глубина += 1 if сл.group(0).startswith("<section") else -1
            i += сл.end()
        блоки[m.group(1)] = текст[m.start():i]
    return блоки


def графа_статикой(имена, блоки):
    наш = set()
    for вкладка, блок in блоки.items():
        for с in имена:
            if re.search(r"[\"\s]" + re.escape(с) + r"[\"\s]", блок):
                наш.add(вкладка)
    if len(наш) == 1:
        return ИМЕНА[наш.pop()]
    if len(наш) > 1:
        return "общий"
    return None


def разложить(записи, карта, добирать=True):
    блоки = секции_шаблона() if добирать else {}
    по_графам = {}
    for з in записи:
        имена = субъект(з["селектор"])
        где, видели = вкладки_для(имена, карта)
        г = графа(где, видели)
        з["добор"] = False
        if г == "не наблюдался" and блоки:
            с = графа_статикой(имена, блоки)
            if с:
                г, з["добор"] = с, True
        з["где"] = где
        з["графа"] = г
        по_графам.setdefault(г, []).append(з)
    return по_графам


def ближайшая(значение, ступени):
    лучшая, сдвиг = None, None
    for имя, px in ступени.items():
        d = abs(значение - px)
        if сдвиг is None or d < сдвиг:
            лучшая, сдвиг = имя, d
    return лучшая, сдвиг


def в_пиксели(текст):
    """rem -> px по корню 16. em и % не переводятся: их база не корневая
    и снаружи неизвестна — назвать её значило бы выдумать число."""
    m = re.match(r"^(-?\d*\.?\d+)\s*(px|rem)?$", текст.strip())
    if not m:
        return None
    ч = float(m.group(1))
    ед = m.group(2) or ("px" if ч == 0 else None)
    if ед == "px":
        return ч
    if ед == "rem":
        return ч * 16
    return None


def инвентарь(записи):
    """значение -> сколько раз, на каких вкладках, какими свойствами."""
    свод = {}
    for з in записи:
        for кусок in з["значение"].split():
            if not re.match(r"^-?[0-9.]", кусок):
                continue
            свод.setdefault(кусок, {"раз": 0, "вкладки": set(),
                                    "свойства": set(), "строки": []})
            с = свод[кусок]
            с["раз"] += 1
            с["вкладки"].add(з["графа"])
            с["свойства"].add(з["свойство"])
            с["строки"].append(з["строка"])
    return свод



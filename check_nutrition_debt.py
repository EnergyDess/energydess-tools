# ── ЕДИНИЦА СЧЁТА. ТРИ ЧИСЛА У ОДНОГО ВОПРОСА, И ОНИ НЕ РАВНЫ ────────────────
#
# Отчёт 2026-08-20 положил рядом «Отступы, всего: 218» и «2 из 217 отступов»,
# а таблица инвентаря под ними дала в сумме 283. Три числа выглядели тремя
# редакциями одного, а были ответами на ТРИ РАЗНЫХ ВОПРОСА:
#
#   218  строк, где греп увидел свойство с цифрой — ВКЛЮЧАЯ текст комментариев
#   217  ОБЪЯВЛЕНИЙ в разобранном CSS (комментарии сняты)
#   283  ЗНАЧЕНИЙ внутри этих объявлений: `padding: 0.5rem 0.75rem` — два
#
# Ровно та болезнь, что §6.0.4 лечил у `:hover` (123 блока / 129 правил /
# 134 вхождения): число без названного способа счёта не значит ничего,
# и три человека получат три разных ответа. Поэтому печатаются все три
# сразу, с арифметикой, которая их связывает.


def числа_значения(з):
    """Числовые куски объявления. `padding: 0.5rem 0.75rem` — два."""
    return [к for к in з["значение"].split() if re.match(r"^-?[0-9.]", к)]


def единицы(отступы, кегли):
    """Связка «объявления ↔ значения» с разбросом, который их связывает."""
    разброс = {}
    for з in отступы:
        n = len(числа_значения(з))
        разброс[n] = разброс.get(n, 0) + 1
    return {
        "объяв_о": len(отступы), "объяв_к": len(кегли),
        "знач_о": sum(len(числа_значения(з)) for з in отступы),
        "знач_к": sum(len(числа_значения(з)) for з in кегли),
        "разброс": разброс,
        "сумма_разброса": sum(k * v for k, v in разброс.items()),
    }


def прозой():
    """Строки, где отступ увидел ТОЛЬКО греп, — то есть внутри комментария.

    Разница «218 против 217» держалась на честном слове «расхождение —
    комментарии». Слово проверяемо: строку можно назвать поимённо, и она
    называется. Класс тот же, что чинила задача 99 у проверки 7, только
    этажом ниже: там проза ОЖИВЛЯЛА удалённый класс, здесь она РАЗДУВАЕТ
    долг — цитата удалённого кода в пояснении считается работой.
    """
    текст = _прочитать(CSS)
    чистый = _без_комментариев(текст)
    рег = re.compile(r"(^|[;{ ])(margin|padding|gap|row-gap|column-gap)"
                     r"(-(top|bottom|left|right))?:\s*[0-9.]", re.M)
    было = [текст[:m.start()].count("\n") + 1 for m in рег.finditer(текст)]
    стало = [чистый[:m.start()].count("\n") + 1 for m in рег.finditer(чистый)]
    остаток, из_прозы = list(стало), []
    for n in было:
        if n in остаток:
            остаток.remove(n)
        else:
            из_прозы.append(n)
    строки = текст.split("\n")
    return [(n, строки[n - 1].strip()) for n in из_прозы]


def сбросы_в_ноль(отступы):
    """Сброс в ноль в ДВУХ единицах сразу — иначе вычитать нечего.

    «Сброс в ноль — 70» стоит в таблице ЗНАЧЕНИЙ, а суммарные 217/218 —
    это ОБЪЯВЛЕНИЯ. Вычесть одно из другого нельзя: нули сидят в меньшем
    числе объявлений, и лишь часть этих объявлений не содержит НИЧЕГО,
    кроме нулей. Вычесть 70 из 217 значило бы объявить несуществующим
    кусок работы размером в треть задачи.
    """
    значений, целиком, вперемешку = 0, [], []
    for з in отступы:
        ч = числа_значения(з)
        значений += sum(1 for к in ч if в_пиксели(к) == 0)
        if ч and all(в_пиксели(к) == 0 for к in ч):
            целиком.append(з)
        elif any(в_пиксели(к) == 0 for к in ч):
            вперемешку.append(з)
    return значений, целиком, вперемешку


def группы_инвентаря(отступы, карта, ступени):
    """Инвентарь, разложенный на четыре кучи. Возвращает (кучи, все_значения).

    ОДНА функция на печать и на контроль полноты. Две реализации разошлись
    бы молча — та же причина, по которой суммарное число берётся у
    `check_metrics` импортом.
    """
    по_графам = разложить(отступы, карта)
    инв = инвентарь([з for зз in по_графам.values() for з in зз])
    строки = []
    for знач in инв:
        с = инв[знач]
        px = в_пиксели(знач)
        if px is None:
            строки.append((знач, с, None, None, None))
        else:
            ст, сдвиг = ближайшая(px, ступени)
            строки.append((знач, с, px, ст, сдвиг))
    строки.sort(key=lambda r: (-r[1]["раз"], r[0]))
    кучи = {
        "СБРОС В НОЛЬ": [r for r in строки if r[2] == 0],
        "ТОЧНО": [r for r in строки if r[2] != 0 and r[4] == 0],
        "ДО 2px": [r for r in строки
                   if r[2] != 0 and r[4] is not None and 0 < r[4] <= 2],
        "БОЛЬШЕ 2px": [r for r in строки
                       if r[2] != 0 and r[4] is not None and r[4] > 2],
        "НЕ В px": [r for r in строки if r[2] != 0 and r[4] is None],
    }
    return кучи, строки


def контроль_групп():
    """ПОЛНОТА РАЗБИЕНИЯ: каждое значение ровно в одной куче — и подлог.

    Зачем отдельно от `--контроль`. Тот сторожит СЧЁТ и ПРИВЯЗКУ: сдвинулась
    ли сумма на единицу и в ту ли вкладку. Полноту разбиения он не трогает
    вовсе, а именно она и вызвала подозрение: куча «сдвиг больше 2px»
    оказалась почти пуста, и пустая группа при несходящейся сумме читается
    как «часть значений до классификации не доехала».

    Проверяется ТРИ вещи, и порознь каждая проходит на сломанном разбиении:
      1. сумма вхождений по кучам равна числу ЗНАЧЕНИЙ (не объявлений);
      2. ни одно значение не попало в две кучи и ни одно не потерялось;
      3. подлог заведомо далёким значением появляется в куче «больше 2px».
    """
    карта = карта_вкладок()
    if карта is None:
        print("!! карты нет, сначала --собрать-карту")
        return 2
    ступени = шкала_отступов()

    отступы, кегли = находки()
    кучи, строки = группы_инвентаря(отступы, карта, ступени)
    знач_всего = sum(len(числа_значения(з)) for з in отступы)
    в_кучах = sum(r[1]["раз"] for куча in кучи.values() for r in куча)
    имена_в_кучах = [r[0] for куча in кучи.values() for r in куча]
    дублей = len(имена_в_кучах) - len(set(имена_в_кучах))
    потеряно = {r[0] for r in строки} - set(имена_в_кучах)

    # ── подлог: значение, заведомо далёкое от любой ступени ───────────────
    исходный = io.open(CSS, "rb").read()
    # ЗНАЧЕНИЕ ПОДЛОГА ВЫБРАНО ЗАМЕРОМ, А НЕ НА ГЛАЗ. Первая версия брала
    # 4.4375rem — «заведомо кривое» число, — и контроль ПРОВАЛИЛСЯ: 71px

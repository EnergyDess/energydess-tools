def собрать_карту():
    """Снять карту класс->вкладка с ЖИВОЙ страницы."""
    sys.path.insert(0, os.path.abspath("."))
    import check_hover as ch
    from playwright.sync_api import sync_playwright

    сбор = """(id) => {
      const s = document.getElementById(id);
      if (!s) return [];
      const out = new Set();
      s.querySelectorAll('*').forEach(e => e.classList.forEach(c => out.add(c)));
      s.classList.forEach(c => out.add(c));
      return [...out];
    }"""
    вне = """() => {
      const o = new Set();
      document.querySelectorAll('body *').forEach(e => {
        if (!e.closest('.nut-tab')) e.classList.forEach(c => o.add(c));
      });
      return [...o];
    }"""
    карта = {}
    with sync_playwright() as p:
        бр = p.chromium.launch()
        ctx = бр.new_context(viewport={"width": 1440, "height": 900})
        стр = ctx.new_page()
        ch._войти(стр)
        стр.goto(ch.БАЗА + "/nutrition", wait_until="networkidle",
                 timeout=45000)
        стр.wait_for_timeout(1500)
        for ключ in ИМЕНА:
            стр.click("[data-tab='" + ключ + "']")
            стр.wait_for_timeout(1200)
            карта[ключ] = sorted(стр.evaluate(сбор, "tab-" + ключ))
        карта["_вне_вкладок"] = sorted(стр.evaluate(вне))
        бр.close()
    os.makedirs(os.path.dirname(КАРТА), exist_ok=True)
    json.dump(карта, io.open(КАРТА, "w", encoding="utf-8"),
              ensure_ascii=False, indent=1, sort_keys=True)
    for к in sorted(карта):
        print("  %-16s классов %d" % (к, len(карта[к])))
    print("\nкарта записана: " + КАРТА)
    return 0



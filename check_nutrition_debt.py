def _прочитать(путь):
    try:
        return io.open(путь, encoding="utf-8").read()
    except OSError:
        return ""


def шкала_отступов():
    """Ступени --space-* в пикселях, из style.css."""
    ступени = {}
    for m in re.finditer(r"--space-(\d+)\s*:\s*([0-9.]+)px",
                         _прочитать(ШКАЛА_ИЗ)):
        ступени["--space-" + m.group(1)] = float(m.group(2))
    return ступени


def _без_комментариев(текст):
    """Комментарии вырезаются, но ДЛИНА СОХРАНЯЕТСЯ.

    Замена на пустую строку сдвинула бы все смещения ниже, и номер строки
    в выводе указывал бы не туда — находка, которую нельзя открыть,
    читается как ложная.
    """
    def затереть(m):
        return re.sub(r"[^\n]", " ", m.group(0))
    return re.sub(r"/\*.*?\*/", затереть, текст, flags=re.S)


def правила(текст):
    """Плоский список (селектор, тело, номер строки) с учётом вложенности.

    @media и @container телом правила НЕ являются: их содержимое
    разбирается дальше, иначе `@media (...) { .x { padding: 8px } }`
    выглядело бы одним правилом с селектором «@media».
    """
    чистый = _без_комментариев(текст)
    найдено = []

    def обход(кусок, сдвиг):
        i = 0
        while i < len(кусок):
            о = кусок.find("{", i)
            if о < 0:
                return
            заголовок = кусок[i:о].strip()
            глубина, j = 1, о + 1
            while j < len(кусок) and глубина:
                if кусок[j] == "{":
                    глубина += 1
                elif кусок[j] == "}":
                    глубина -= 1
                j += 1
            тело = кусок[о + 1:j - 1]
            if заголовок.startswith("@") and "{" in тело:
                обход(тело, сдвиг + о + 1)
            elif not заголовок.startswith("@"):
                строка = чистый.count("\n", 0, сдвиг + i) + 1
                найдено.append((заголовок, тело, строка))
            i = j

    обход(чистый, 0)
    return найдено


ЧИСЛО = re.compile(r"-?\d*\.?\d+")


def находки():
    """Каждое ОБЪЯВЛЕНИЕ с числом: свойство, селектор, строка, значения.

    `var(--space-4)` и `calc(... * var(--nut-u))` числом НЕ являются и сюда
    не попадают: цифра обязана стоять сразу после двоеточия, ровно как
    в мерке задачи 96.
    """
    из_отступов, из_кеглей = [], []
    for селектор, тело, строка in правила(_прочитать(CSS)):
        for объявление in тело.split(";"):
            if ":" not in объявление:
                continue
            свойство, _, значение = объявление.partition(":")
            свойство = свойство.strip().lower()
            значение = значение.strip()
            if not значение or not re.match(r"[0-9.]", значение):
                continue
            корень = свойство.split("-")[0]
            запись = {"селектор": " ".join(селектор.split()),
                      "строка": строка, "свойство": свойство,
                      "значение": значение,
                      "числа": ЧИСЛО.findall(значение)}
            if свойство in ОТСТУПЫ or корень in ("margin", "padding"):
                из_отступов.append(запись)
            elif свойство == "font-size":
                из_кеглей.append(запись)
    return из_отступов, из_кеглей


КЛАСС = re.compile(r"\.(-?[_a-zA-Z][\w-]*)")


def субъект(селектор):
    """Классы СУБЪЕКТА — последней связки каждого селектора из списка.

    `.meal-card .fd-name` оформляет `.fd-name`, а `.meal-card` там только
    контекст. Приписать объявление предку значило бы отправить правку
    не на ту вкладку — то же уточнение, что делали проверке 1 в §6.0.2.
    """
    части = [ч.strip() for ч in селектор.split(",") if ч.strip()]
    имена = set()
    for часть in части:
        часть = re.sub(r"::?[a-zA-Z-]+(\([^)]*\))?", " ", часть)
        связки = [с for с in re.split(r"[\s>+~]+", часть) if с]
        if связки:
            имена.update(КЛАСС.findall(связки[-1]))
    return имена


def карта_вкладок():
    if not os.path.exists(КАРТА):
        return None
    return json.load(io.open(КАРТА, encoding="utf-8"))


def вкладки_для(имена, карта):
    """Множество вкладок, где эти классы встречались на живой странице."""
    где, видели = set(), False
    for имя in имена:
        for вкладка, классы in карта.items():
            if имя in классы:
                видели = True
                где.add("_вне" if вкладка == "_вне_вкладок" else вкладка)
    return где, видели


def графа(где, видели):
    """Одна вкладка / общий / вне вкладок / не наблюдался."""
    if not видели:
        return "не наблюдался"
    свои = sorted(в for в in где if в != "_вне")
    if len(свои) == 1:
        return ИМЕНА[свои[0]]
    if len(свои) > 1:
        return "общий"
    return "вне вкладок"


def секции_шаблона():
    """Разметка каждой вкладки — кусок между её <section> и следующей.

    ЗАПАСНОЙ ХОД ДЛЯ ГРАФЫ «НЕ НАБЛЮДАЛСЯ»: живой DOM видит только то,
    что открыто, — запись голоса, меню вложений и карточки находок
    в момент съёмки закрыты.

    НА СЕГОДНЯ ОН ДОБИРАЕТ НОЛЬ, и это честный результат, а не поломка:
    остаток целиком собирается ШАБЛОННЫМИ СТРОКАМИ СКРИПТА, то есть
    в статической разметке этих классов нет тоже. Число добранного
    печатается в выводе отдельной пометкой — станет ненулевым, если
    разметку однажды перенесут в шаблон.

    Статика слабее живого DOM (класс в разметке может не дожить
    до экрана), поэтому она НЕ заменяет карту, а только добирает то,
    чего карта не видела.

    ГРАНИЦА СЕКЦИИ ЗАКРЫВАЕТСЯ ПО `</section>`, А НЕ ПО НАЧАЛУ СЛЕДУЮЩЕЙ.
    Первая версия брала кусок «от секции до следующей», и последняя
    вкладка («Ассистент») забирала себе ВЕСЬ ХВОСТ ФАЙЛА — нижнюю панель,
    все модалки и полторы тысячи строк скрипта. Разбивка после этого
    приписывала «Ассистенту» 32 отступа вместо одного, и среди них были
    `.water-log-*` (вода, «Дневник»), `.brand-more` (поиск, «Добавить»)
    и `.wt-*` («Вес»). Ложная привязка выглядела правдоподобно и прошла
    бы, не будь она разложена по классам поимённо.
    """
    текст = _прочитать(ШАБЛОН)
    блоки = {}
    for m in re.finditer(
            r"<section class=\"nut-tab[^\"]*\" id=\"tab-([a-z]+)\">", текст):
        i, глубина = m.end(), 1
        while i < len(текст) and глубина:
            сл = re.search(r"<section\b|</section>", текст[i:])
            if not сл:
                break
            глубина += 1 if сл.group(0).startswith("<section") else -1
            i += сл.end()
        блоки[m.group(1)] = текст[m.start():i]
    return блоки


def графа_статикой(имена, блоки):
    наш = set()
    for вкладка, блок in блоки.items():
        for с in имена:
            if re.search(r"[\"\s]" + re.escape(с) + r"[\"\s]", блок):
                наш.add(вкладка)
    if len(наш) == 1:
        return ИМЕНА[наш.pop()]
    if len(наш) > 1:
        return "общий"
    return None


def разложить(записи, карта, добирать=True):
    блоки = секции_шаблона() if добирать else {}
    по_графам = {}
    for з in записи:
        имена = субъект(з["селектор"])
        где, видели = вкладки_для(имена, карта)
        г = графа(где, видели)
        з["добор"] = False
        if г == "не наблюдался" and блоки:
            с = графа_статикой(имена, блоки)
            if с:
                г, з["добор"] = с, True
        з["где"] = где
        з["графа"] = г
        по_графам.setdefault(г, []).append(з)
    return по_графам


def ближайшая(значение, ступени):
    лучшая, сдвиг = None, None
    for имя, px in ступени.items():
        d = abs(значение - px)
        if сдвиг is None or d < сдвиг:
            лучшая, сдвиг = имя, d
    return лучшая, сдвиг


def в_пиксели(текст):
    """rem -> px по корню 16. em и % не переводятся: их база не корневая
    и снаружи неизвестна — назвать её значило бы выдумать число."""
    m = re.match(r"^(-?\d*\.?\d+)\s*(px|rem)?$", текст.strip())
    if not m:
        return None
    ч = float(m.group(1))
    ед = m.group(2) or ("px" if ч == 0 else None)
    if ед == "px":
        return ч
    if ед == "rem":
        return ч * 16
    return None


def инвентарь(записи):
    """значение -> сколько раз, на каких вкладках, какими свойствами."""
    свод = {}
    for з in записи:
        for кусок in з["значение"].split():
            if not re.match(r"^-?[0-9.]", кусок):
                continue
            свод.setdefault(кусок, {"раз": 0, "вкладки": set(),
                                    "свойства": set(), "строки": []})
            с = свод[кусок]
            с["раз"] += 1
            с["вкладки"].add(з["графа"])
            с["свойства"].add(з["свойство"])
            с["строки"].append(з["строка"])
    return свод



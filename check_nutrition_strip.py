# ── СМАХИВАНИЕ ЛЕНТЫ ПАЛЬЦЕМ (№352, «мобильный-2», 2.5) ───────────────
# Прогон рукой на телефонных ширинах: касание идёт НАСТОЯЩИМ событием
# (CDP `Input.dispatchTouchEvent`) — браузер сам решает, жест это или
# нажатие, и сам применяет `touch-action`. Подделка `pointerup` из
# страницы этого не проверила бы: ровно `touch-action` и решает, дойдёт
# ли смахивание до кода или браузер заберёт его себе.
ШИРИНЫ_КАСАНИЯ = (360, 390, 430)
ОКНО_ДНЕЙ = "() => [...document.querySelectorAll('#ds-days .ds-day')].map(d => d.dataset.date)"
СТРЕЛКИ = """() => ['ds-prev', 'ds-next'].map(i => { const e = document.getElementById(i);
  return !!e && e.checkVisibility() && e.getBoundingClientRect().width > 0; })"""
# доказательство подлога №2 — сколько отпусканий пальца он съел
# (читается из страницы, независимо от вердикта шагов)
ДОКАЗАНО = {}


def _смахнуть(стр, cdp, x0, x1, y):
    """Палец ведёт ленту, ОСТАНАВЛИВАЕТСЯ и отпускает. Без остановки
    эмуляция считает жест броском, и следующее касание гасит «бросок»
    вместо клика: замер захода — после быстрого жеста следующий тап
    не давал клика в 4–5 случаях из 5, и так же после вертикальной
    прокрутки страницы и при выключенном коде ленты (то есть это
    свойство эмуляции, а не ленты); с остановкой — 5 из 5."""
    cdp.send("Input.dispatchTouchEvent", {"type": "touchStart", "touchPoints": [{"x": x0, "y": y}]})
    for i in range(1, 9):
        cdp.send("Input.dispatchTouchEvent", {"type": "touchMove",
                                              "touchPoints": [{"x": x0 + (x1 - x0) * i / 8, "y": y}]})
        стр.wait_for_timeout(16)
    стр.wait_for_timeout(150)
    cdp.send("Input.dispatchTouchEvent", {"type": "touchMove", "touchPoints": [{"x": x1, "y": y}]})
    стр.wait_for_timeout(150)
    cdp.send("Input.dispatchTouchEvent", {"type": "touchEnd", "touchPoints": []})
    стр.wait_for_timeout(400)


def смахивание(подлог=None):
    """Смахнуть вперёд и назад, выбрать день нажатием, вернуться к сегодня.
    Список по ширинам; пустой — замерить нечем."""
    from playwright.sync_api import sync_playwright
    итог = []
    ДОКАЗАНО.clear()
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=True)
        try:
            for ш in ШИРИНЫ_КАСАНИЯ:
                ctx = бр.new_context(viewport={"width": ш, "height": 800}, has_touch=True,
                                     device_scale_factor=2)
                стр = ctx.new_page()
                стр.add_init_script(ГЛУШИТЕЛЬ)
                if подлог:
                    стр.add_init_script(подлог)
                ch._войти(стр)
                стр.goto(ch.БАЗА + "/nutrition", wait_until="domcontentloaded")
                стр.wait_for_selector("#ds-days .ds-day", timeout=15000)
                стр.wait_for_timeout(800)
                cdp = ctx.new_cdp_session(стр)
                б = стр.locator("#ds-days").bounding_box()
                y = б["y"] + б["height"] / 2
                вперёд = (б["x"] + б["width"] * 0.75, б["x"] + б["width"] * 0.25)
                сегодня = стр.evaluate("S.today")
                выбран0 = стр.evaluate("S.date")
                окно0 = стр.evaluate(ОКНО_ДНЕЙ)
                # вперёд: палец справа налево через половину ленты
                _смахнуть(стр, cdp, *вперёд, y)
                окно1, выбран1 = стр.evaluate(ОКНО_ДНЕЙ), стр.evaluate("S.date")
                # назад: слева направо, дважды — окно уходит в прошлое за сегодня
                for _ in range(2):
                    _смахнуть(стр, cdp, вперёд[1], вперёд[0], y)
                окно2, выбран2 = стр.evaluate(ОКНО_ДНЕЙ), стр.evaluate("S.date")
                стрелки = стр.evaluate(СТРЕЛКИ)
                # выбрать день нажатием: левая клетка окна (не сегодня)
                день = окно2[0]
                стр.locator('#ds-days .ds-day[data-date="%s"]' % день).tap()
                стр.wait_for_timeout(500)
                выбран3 = стр.evaluate("S.date")
                # вернуться к сегодня: вперёд, пока сегодня не в окне, и нажать
                for _ in range(4):
                    if сегодня in стр.evaluate(ОКНО_ДНЕЙ):
                        break
                    _смахнуть(стр, cdp, *вперёд, y)
                if сегодня in стр.evaluate(ОКНО_ДНЕЙ):
                    стр.locator('#ds-days .ds-day[data-date="%s"]' % сегодня).tap()
                    стр.wait_for_timeout(500)
                ДОКАЗАНО[ш] = стр.evaluate("window.__съедено || 0")
                итог.append({"ш": ш, "сегодня": сегодня, "выбран0": выбран0, "окно0": окно0,
                             "окно1": окно1, "выбран1": выбран1, "окно2": окно2, "выбран2": выбран2,
                             "стрелки": стрелки, "день": день, "выбран3": выбран3,
                             "выбран4": стр.evaluate("S.date"), "окно4": стр.evaluate(ОКНО_ДНЕЙ)})
                ctx.close()
        finally:
            бр.close()
    return итог


def _шаги_смахивания(подлог=None):
    с = смахивание(подлог)
    if not с:
        шаг("смахивание-вперёд-сдвигает-ленту", False, "ленты нет", собрано=0)
        return
    кр = lambda о: "%s..%s" % (о[0], о[-1]) if о else "—"
    # ранний return выше проверка 33 не видит: пустой сбор — ПРОПУСК ключом у каждого шага
    шаг("смахивание-вперёд-сдвигает-ленту", all(x["окно1"][0] > x["окно0"][0] for x in с),
        "; ".join("%d: %s → %s" % (x["ш"], кр(x["окно0"]), кр(x["окно1"])) for x in с), собрано=len(с))
    шаг("смахивание-назад-сдвигает-ленту", all(x["окно2"][0] < x["окно1"][0] for x in с),
        "; ".join("%d: %s → %s" % (x["ш"], кр(x["окно1"]), кр(x["окно2"])) for x in с), собрано=len(с))
    шаг("смахивание-не-выбирает-день",
        all(x["выбран1"] == x["выбран0"] and x["выбран2"] == x["выбран0"] for x in с),
        "; ".join("%d: %s → %s → %s" % (x["ш"], x["выбран0"], x["выбран1"], x["выбран2"]) for x in с), собрано=len(с))
    шаг("стрелки-на-месте-при-смахивании", all(all(x["стрелки"]) for x in с),
        "; ".join("%d: %s" % (x["ш"], x["стрелки"]) for x in с), собрано=len(с))
    шаг("нажатие-после-смахивания-выбирает-день", all(x["выбран3"] == x["день"] for x in с),
        "; ".join("%d: нажат %s, выбран %s" % (x["ш"], x["день"], x["выбран3"]) for x in с), собрано=len(с))
    шаг("возврат-к-сегодня", all(x["выбран4"] == x["сегодня"] and x["сегодня"] in x["окно4"] for x in с),
        "; ".join("%d: выбран %s, окно %s" % (x["ш"], x["выбран4"], кр(x["окно4"])) for x in с), собрано=len(с))


def _печать(и):
    print("  (а) будущие дни:")
    for d in и["будущие"]:
        print("      %s  цифра %.2f  подпись %s  рамка %s  непрозр. %.2f" % (
            d["дата"], d["к_цифры"], d["к_подписи"], d["стиль_рамки"], d["непр"]))
    print("      прошлые: цифра %s" % [d["к_цифры"] for d in и["прошлые"]])
    к = и["коробки"]
    print("  (б) кнопка %dx%d, кружок %dx%d, зона наведения %s" % (
        к["кн"][2], к["кн"][3], к["кр"][2], к["кр"][3],
        "нет" if not и["зона"] else "%dx%d" % (и["зона"][2], и["зона"][3])))
    print("  (в) выбранный %s: без мыши [%s]" % (и["другой"], и["без_мыши"]))
    print("      под мышью  [%s]" % и["под_мышью"])
    с, в = и["сегодня_при_другом"], и["выбранный"]
    print("  (г) «сегодня» при выбранном другом: фон %s рамка %s цифра %s подпись «%s» %s" % (
        с["фон"], с["рамка"], с["цифра"], с["подпись_текст"], с["подпись_цвет"]))
    print("      выбранный:                     фон %s рамка %s цифра %s" % (
        в["фон"], в["рамка"], в["цифра"]))


def _прозрачный(цвет):
    return цвет.replace(" ", "") in ("rgba(0,0,0,0)", "transparent")


def проверка(подлог=None):
    global находок, пропусков, _строки
    находок = пропусков = 0
    _строки = []
    и = замер(подлог)
    if и is None:
        шаг("лента-на-месте", False, "дней нет", собрано=0)
        return находок, пропусков
    буд = и["будущие"]
    шаг("будущие-без-пунктира", all(d["стиль_рамки"] == "solid" for d in буд),
        "стили %s" % sorted({d["стиль_рамки"] for d in буд}), собрано=len(буд))
    шаг("цифра-будущего-контраст-4.5", all(d["к_цифры"] >= 4.5 for d in буд),
        "мин %.2f" % min((d["к_цифры"] for d in буд), default=0), собрано=len(буд))
    подп = [d["к_подписи"] for d in буд if d["к_подписи"] is not None]
    шаг("подпись-будущего-контраст-3", all(x >= 3 for x in подп),
        "мин %s" % (min(подп) if подп else None), собрано=len(подп))
    шаг("подпись-будущего-тусклее-цифры",
        all(d["к_подписи"] is None or d["к_подписи"] <= d["к_цифры"] for d in буд), собрано=len(буд))
    к, з = и["коробки"], и["зона"]
    кр = к["кр"]
    if з is None:
        шаг("наведение-подсвечивает-кружок", False, "подсветки нет вовсе")
    else:
        # сетка точек шагом 3 px: допуск ±4 px плюс шаг сетки
        откл = max(abs(з[0] - кр[0]), abs(з[1] - кр[1]),
                   abs((з[0] + з[2]) - (кр[0] + кр[2])), abs((з[1] + з[3]) - (кр[1] + кр[3])))
        шаг("зона-наведения-равна-кружку", откл <= 4 + 3,
            "зона %dx%d, кружок %dx%d, отклонение края %.1f px" % (з[2], з[3], кр[2], кр[3], откл))
    в = и["выбранный"]
    шаг("выбранный-залит", not _прозрачный(в["фон"]), "фон %s" % в["фон"])
    шаг("наведение-не-меняет-выбранный", и["под_мышью"] == и["без_мыши"],
        "под мышью [%s] без [%s]" % (и["под_мышью"], и["без_мыши"]))
    с = и["сегодня_при_другом"]
    шаг("сегодня-без-заливки-и-отлично-от-выбранного",
        _прозрачный(с["фон"]) and с["цифра"] != в["цифра"] and с["рамка"] != "",
        "сегодня фон %s цифра %s, выбранный фон %s" % (с["фон"], с["цифра"], в["фон"]))
    шаг("сегодня-цифра-и-подпись-цвета-питания",
        с["цифра"] == в["фон"] and с["подпись_цвет"] == в["фон"],
        "цифра %s подпись %s цвет выбранного %s" % (с["цифра"], с["подпись_цвет"], в["фон"]))
    зап = и["с_записями"]
    шаг("точка-у-дня-с-записями-видна", all(d["точка_видна"] for d in зап), собрано=len(зап))
    шаг("стрелка-сдвигает-ленту", и["сдвиг"][0] != и["сдвиг"][1], "%s → %s" % и["сдвиг"])
    шаг("клик-по-сегодня-в-центр", и["центр"] == и["сегодня"] and и["выбран_после"] == и["сегодня"],
        "в центре %s, выбран %s" % (и["центр"], и["выбран_после"]))
    _шаги_смахивания(подлог)
    return находок, пропусков


def _стиль(css):
    return """addEventListener('DOMContentLoaded', () => { const s = document.createElement('style');
      s.textContent = %r; document.head.appendChild(s); });""" % css


# «мобильный-2» №2: смахивание съедается — ровно прежний дефект (лента
# на жест не отвечала вовсе). Отпускание пальца над лентой гасится
# в фазе погружения на `window`, до обработчика ленты; нажатие по дню
# при этом живо — `click` отдельное событие.
ПОДЛОГ_СМАХИВАНИЕ = """addEventListener('pointerup', e => {
  if (e.pointerType !== 'mouse' && e.target.closest && e.target.closest('#ds-days')) {
    e.stopImmediatePropagation(); window.__съедено = (window.__съедено || 0) + 1; } }, true);"""


def _доказ_смахивания():
    return (bool(ДОКАЗАНО) and all(n > 0 for n in ДОКАЗАНО.values()),
            "съедено отпусканий по ширинам: %s" % ДОКАЗАНО)


ПОДЛОГИ = [
    ("пунктир у будущих", "будущие-без-пунктира",
     _стиль("#tab-diary .ds-day.is-fut .ds-c { border-style: dashed !important; }"), None),
    ("hover перебивает выбранный", "наведение-не-меняет-выбранный",
     _стиль("#tab-diary .ds-day.is-sel .ds-c:hover { background: transparent !important; }"), None),
    ("наведение на всю колонку", "зона-наведения-равна-кружку",
     _стиль("#tab-diary .ds-day:not(.is-sel):hover .ds-c { background: rgb(40, 80, 60) !important; }"), None),
    ("мобильный-2 №2: смахивание съедено", "смахивание-вперёд-сдвигает-ленту",
     ПОДЛОГ_СМАХИВАНИЕ, _доказ_смахивания),
]


def контроль():
    print("ЧИСТЫЙ ПРОГОН")
    н, п = проверка()
    if н or п:
        print("КОНТРОЛЬ НЕДЕЙСТВИТЕЛЕН: грязная основа (находок %d, пропусков %d)" % (н, п))
        return 2
    не_найдено = 0
    for имя, строка, код, доказ in ПОДЛОГИ:
        print("ПОДЛОГ: %s" % имя)
        проверка(код)
        упала = dict(_строки).get(строка) == "ПЛОХО"
        if доказ:
            состоялся, текст = доказ()
            print("  доказательство — %s%s" % (текст, "" if состоялся else " (ПОДЛОГ НЕ СОСТОЯЛСЯ)"))
            упала = упала and состоялся
        print("  → %s строку «%s»" % ("НАЙДЕН, уронил" if упала else "НЕ НАЙДЕН, не уронил", строка))
        не_найдено += not упала
    print("КОНТРОЛЬ: подлогов %d, не найдено %d" % (len(ПОДЛОГИ), не_найдено))
    return 1 if не_найдено else 0


def main():
    if "--замер" in sys.argv:
        и = замер()
        sys.exit(2 if и is None else 0)
    if "--контроль" in sys.argv:
        sys.exit(контроль())
    print("ЛЕНТА ДНЕЙ ДНЕВНИКА")
    н, п = проверка()
    print("ИТОГ: находок %d, пропусков %d" % (н, п))
    sys.exit(1 if н else (2 if п else 0))


if __name__ == "__main__":
    main()

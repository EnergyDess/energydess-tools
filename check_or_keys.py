"""КЛЮЧИ OPENROUTER: СТЕНД НЕ ПЛАТИТ С ПРОДА (BACKLOG №346, заход 3).

ПРОВЕРКА, код 1 при беде, 2 — спросить нечем. Три вопроса:

  1. ключ стенда ЕСТЬ и ОТЛИЧАЕТСЯ от ключа прода — по отпечаткам
     (12 знаков sha256), сами ключи не печатаются нигде. Ключа стенда
     нет — это НЕ пропуск, а отказ с причиной: пока его нет, стенд
     не делает живых вызовов вовсе, и об этом надо знать;
  2. правило `or_key.выбрать_ключ` на стенде без ключа стенда отдаёт
     ПУСТО, а не ключ прода — то есть молчаливого отката нет;
  3. ни один отслеживаемый файл не содержит значения ключа — ни прода,
     ни стенда — и ни одной строки вида ключа OpenRouter (`sk-or-`).

Ключ прода берётся из `.env` (локальная копия) либо окружения. Секрет
Fly отсюда не читается: его значение `flyctl` не отдаёт, и сверять
с ним нечем — сверяется то, что лежит у разработчика.

    py check_or_keys.py
"""
import os
import re
import subprocess
import sys

import probe_guard  # noqa: F401 — внешний отказ говорится словом (§3)
import or_key

ШАБЛОН = re.compile(r"sk-or-(v1-)?[0-9a-f]{16,}")


def _окружение():
    from dotenv import dotenv_values
    return {**dotenv_values(".env"), **os.environ}


def _файлы():
    вывод = subprocess.run(["git", "ls-files", "-z"], capture_output=True,
                           check=True).stdout.decode("utf-8")
    return [п for п in вывод.split("\0") if п]


def совпадения(значения) -> dict:
    """Путь → число вхождений значений ключей и шаблона ключа. Значения не печатаются."""
    итог = {}
    for путь in _файлы():
        try:
            with open(путь, "rb") as ф:
                данные = ф.read()
        except OSError:
            continue
        текст = данные.decode("utf-8", errors="ignore")
        n = sum(текст.count(з) for з in значения if з)
        n += len(ШАБЛОН.findall(текст))
        if n:
            итог[путь] = n
    return итог


def main() -> int:
    окр = _окружение()
    прод = окр.get(or_key.КЛЮЧ_ПРОДА_ИМЯ, "") or ""
    стенд = окр.get(or_key.КЛЮЧ_СТЕНДА_ИМЯ, "") or ""
    беды = []
    print("КЛЮЧИ OPENROUTER")
    print(f"  отпечаток ключа прода  : {or_key.отпечаток(прод)}")
    print(f"  отпечаток ключа стенда : {or_key.отпечаток(стенд)}")
    if not стенд:
        беды.append(f"ключа стенда нет — положите {or_key.КЛЮЧ_СТЕНДА_ИМЯ} "
                    "в .env (инструкция в BACKLOG №346)")
    elif стенд == прод:
        беды.append("ключ стенда совпадает с ключом прода")
    # 2. правило на стенде без ключа стенда
    без = {k: v for k, v in окр.items() if k not in ("FLY_APP_NAME", or_key.КЛЮЧ_СТЕНДА_ИМЯ)}
    ключ, причина = or_key.выбрать_ключ(без)
    print(f"  стенд без ключа стенда : ключ {'ПУСТ' if not ключ else 'ЕСТЬ'}; {причина or '—'}")
    if ключ:
        беды.append("на стенде без ключа стенда правило отдало ключ — откат на прод")
    # 3. значения в файлах
    найдено = совпадения([прод, стенд])
    print(f"  совпадений в отслеживаемых файлах: {sum(найдено.values())}"
          + (f" (файлов {len(найдено)}: {', '.join(sorted(найдено))})" if найдено else ""))
    if найдено:
        беды.append("значение либо шаблон ключа лежит в отслеживаемом файле")
    for б in беды:
        print("  БЕДА: " + б)
    print("ИТОГ: " + ("чисто" if not беды else f"бед {len(беды)}"))
    return 1 if беды else 0


if __name__ == "__main__":
    sys.exit(main())

"""ПРОВЕРКА 17: ПРОКРУЧИВАЕМЫЙ БЛОК, ДО КОТОРОГО НЕ ДОТЯНУТЬСЯ ПАЛЬЦЕМ.

═══════════════════════════════════════════════════════════════════════
ПОВОД: ЧЕТЫРЕ ДНЯ ПОДВАЛ ЛЕЖАЛ ПОВЕРХ ЧАТА, И НИ ОДИН ИНСТРУМЕНТ
НЕ МОГ ЭТОГО УВИДЕТЬ
═══════════════════════════════════════════════════════════════════════

2026-08-17 коммит 0c6579e принёс на `/nutrition` общий хвост страницы
(задача 70). Вместе с ним на страницу приехал `<footer>`, а в
`static/style.css` с незапамятных времён лежит легаси-правило ПО ТЕГУ:

    .nav, main, footer, .auth-wrap { position: relative; z-index: 1; }

Вкладка «Ассистент» на мобильной ширине — `position: fixed` без
z-index, то есть auto. `<main>` на странице нет вовсе, оба элемента
лежат в контексте наложения `<body>`, и слой 1 закрыл слой 0.

Снаружи это выглядело так: чат открывается, внутри него виден подвал
сайта, лента сообщений не листается. Замер: `elementFromPoint` в центре
ленты возвращал `P.footer-desc`.

ПОЧЕМУ ЭТОГО НЕ ВИДЕЛ НИ ОДИН ИНСТРУМЕНТ ПРИЁМКИ:

  · `check_hover` спрашивает про залипание подсветки, а не про то,
    кто лежит сверху;
  · `check_pixel_diff` сравнивает ДВА СОСТОЯНИЯ ОДНОГО экрана. Дефект
    был в обеих сборках — и до захода, и после, — то есть кадры
    совпадали, и диф честно печатал «расхождений 0»;
  · `check_regress` (проверка 16) сравнивает вычисленные свойства
    ДВУХ СБОРОК. Тот же довод: одинаковый дефект в обеих невидим;
  · тесты `pytest` браузера не поднимают вовсе.

Общее у всех четырёх — они спрашивают «изменилось ли». Никто
не спрашивал «а работает ли», и вопрос этот машине доступен: у него
есть буквальный ответ в дереве.

═══════════════════════════════════════════════════════════════════════
ЧТО ИМЕННО СПРАШИВАЕТСЯ
═══════════════════════════════════════════════════════════════════════

Берётся каждый блок со своей прокруткой — `overflow-y: auto|scroll`
и `scrollHeight` больше `clientHeight`, — и в пяти точках внутри него
спрашивается `document.elementFromPoint`. Ответ обязан быть самим
блоком или его потомком. Не он — значит, палец в этом месте попадёт
не туда, и прокрутить блок оттуда нельзя.

ЗАКОННЫЕ ПЕРЕКРЫТИЯ НАЗВАНЫ, А НЕ СПРЯТАНЫ. Модальное окно закрывает
страницу под собой намеренно; такие точки печатаются отдельной строкой
со словом «модалка» и в код возврата не идут.

ЧЕГО ПРОВЕРКА НЕ ВИДИТ:
  · блок, который прокручивается, но `overflow` ему поставил скрипт
    в момент, до которого мы не дошли;
  · перекрытие, которое случается только после жеста;
  · частичное перекрытие меньше пятой части площади — точек всего пять.

ЗАПУСК

    py check_overlap.py                # код 1, если есть незаконное
    py check_overlap.py --контроль     # обязана найти подложенную накладку
"""
import sys

sys.stdout.reconfigure(encoding="utf-8")

import check_hover as ch     # noqa: E402

# Сенсорная ширина стоит первой не для порядка: перекрытие мешает пальцу
# сильнее, чем колесу мыши, — колесом прокручивается блок под курсором
# только если курсор в него попал, а на телефоне другого способа нет.
ШИРИНЫ = [(390, 844, True), (1440, 900, False)]

ЗАМЕР_JS = r"""
() => {
  const итог = [];
  // ЭФФЕКТИВНАЯ ПРОЗРАЧНОСТЬ, А НЕ СВОЯ. Закрытая модалка остаётся
  // разложенной: у её ленты сообщений есть и размер, и `visibility:
  // visible`, — невидимой её делает `opacity: 0` НА ПРЕДКЕ. Без обхода
  // вверх проверка нашла бы «перекрытие» у окна, которого на экране нет,
  // и это была бы ровно та ложь, из-за которой проверки перестают читать.
  const прозрачен = (el) => {
    for (let n = el; n && n.nodeType === 1; n = n.parentElement) {
      const s = getComputedStyle(n);
      if (parseFloat(s.opacity) < 0.05) return true;
      if (s.visibility !== 'visible') return true;
    }
    return false;
  };
  document.querySelectorAll('*').forEach(el => {
    const s = getComputedStyle(el);
    if (!/(auto|scroll)/.test(s.overflowY)) return;
    if (el.scrollHeight <= el.clientHeight + 4) return;
    if (прозрачен(el)) return;
    if (el.closest('[inert]')) return;
    const r = el.getBoundingClientRect();
    if (r.width < 20 || r.height < 20) return;
    if (r.bottom < 0 || r.top > innerHeight) return;
    const точки = [[0.5, 0.2], [0.5, 0.5], [0.5, 0.8], [0.25, 0.5], [0.75, 0.5]];
    const чужие = [];
    точки.forEach(([fx, fy]) => {
      const x = Math.round(r.left + r.width * fx);
      const y = Math.round(r.top + r.height * fy);
      if (x < 0 || y < 0 || x > innerWidth || y > innerHeight) return;
      const цель = document.elementFromPoint(x, y);
      if (!цель) return;
      if (цель === el || el.contains(цель)) return;
      чужие.push({
        x: x, y: y,
        кто: цель.tagName.toLowerCase() + '.' + (цель.getAttribute('class') || ''),
        модалка: !!цель.closest('.modal-ov, [aria-modal="true"], dialog')
      });
    });
    if (чужие.length) {
      итог.push({
        блок: el.tagName.toLowerCase() + '.' + (el.getAttribute('class') || ''),
        id: el.id || '',
        размер: Math.round(r.width) + '×' + Math.round(r.height),
        точек: точки.length, чужих: чужие.length, чужие: чужие
      });
    }
  });
  return итог;
}
"""

# ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: накладка ровно того вида, что и была, — обычный
# элемент в потоке со слоем выше нуля, а не `position: fixed` во весь экран.
# Заведомо более лёгкий случай проверка обязана видеть тем более.
ПОДЛОГ = """
  .nut-content, .chat-msgs, .modal-body, body {
    --подлог: 1;
  }
  body::after {
    content: ''; position: fixed; inset: 0; z-index: 2;
    background: rgba(255, 0, 0, .02); pointer-events: auto;
  }
"""


# ── ДОКАЗАТЕЛЬСТВО ПОДЛОГА (§6.0.3) ─────────────────────────────────
#
# «Проба нашла больше находок» доказательством НЕ является: находок
# могло прибавиться по любой другой причине, а могло и не прибавиться
# при исправной пробе — если подлог не встал. Стилевой подлог кладётся
# В СТРАНИЦУ и умеет провалиться молча ровно так же, как скриптовый:
# `add_style_tag` с негодным CSS исключения не бросает, браузер молча
# выбрасывает нераспознанное правило.
#
# Поэтому рядом стоит НЕЗАВИСИМЫЙ ЗАМЕР ТОГО, ЧТО ПОДЛОГ СОБИРАЛСЯ
# СДЕЛАТЬ, и он не пользуется логикой пробы вовсе: спрашивается, КТО
# лежит в середине окна. Накладка `body::after` во весь экран обязана
# отвечать на этот вопрос сама собой; без неё отвечает содержимое.
ДОКАЗАТЕЛЬСТВО_JS = r"""
() => {
  const цель = document.elementFromPoint(
      Math.round(innerWidth / 2), Math.round(innerHeight / 2));
  if (!цель) return 'в середине окна НИКОГО';
  return цель.tagName.toLowerCase()
       + (цель.id ? '#' + цель.id : '')
       + '.' + (цель.getAttribute('class') || '');
}
"""


def доказать_подлог(добавка_css):
    """Кто лежит в середине окна — без подлога и с ним.

    Замер СОСТОЯНИЯ, а не факта установки: «стиль добавлен» и «накладка
    легла сверху» — разные утверждения, и расходятся они молча.
    """
    from playwright.sync_api import sync_playwright

    ответы = []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for css in ("", добавка_css):
            к = бр.new_context(viewport={"width": 1440, "height": 900})
            стр = к.new_page()
            ch._войти(стр)
            стр.goto(f"{ch.БАЗА}/nutrition", wait_until="domcontentloaded",
                     timeout=45000)
            стр.wait_for_timeout(2200)
            if css:
                стр.add_style_tag(content=css)
                стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА)
            ответы.append(стр.evaluate(ДОКАЗАТЕЛЬСТВО_JS))
            к.close()
        бр.close()
    return ответы[0], ответы[1]


def прогон(добавка_css="", тихо=False):
    from playwright.sync_api import sync_playwright

    экраны = ch.экраны_из_роутов()
    гостевые = [э for э in экраны if not э[2]]
    свои = [э for э in экраны if э[2]]
    находки, законных = [], 0

    with sync_playwright() as p:
        бр = p.chromium.launch()
        for ширина, высота, сенсор in ch.отобрать_ширины(ШИРИНЫ):
            к = бр.new_context(viewport={"width": ширина, "height": высота},
                               has_touch=сенсор, is_mobile=сенсор)
            стр = к.new_page()
            cdp = к.new_cdp_session(стр)
            if сенсор:
                ch._включить_сенсор(cdp)
            for путь, имя, вход, подготовка in (
                    гостевые + [("__вход__", "", True, None)] + свои):
                if путь == "__вход__":
                    ch._войти(стр)
                    if сенсор:
                        ch._включить_сенсор(cdp)
                    continue
                стр.goto(f"{ch.БАЗА}{путь}", wait_until="domcontentloaded",
                         timeout=45000)
                стр.wait_for_timeout(2200)
                if добавка_css:
                    стр.add_style_tag(content=добавка_css)
                if подготовка:
                    try:
                        стр.click(подготовка, timeout=5000)
                        стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 700)
                    except Exception:
                        continue
                стр.mouse.move(ширина - 2, высота - 2)
                стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА)
                for н in стр.evaluate(ЗАМЕР_JS):
                    законно = all(ч["модалка"] for ч in н["чужие"])
                    if законно:
                        законных += 1
                        continue
                    находки.append((ширина, имя, н))
            к.close()
        бр.close()

    if not тихо:
        print(f"  законных перекрытий (модалка поверх страницы): {законных}")
        print(f"  НАХОДОК: {len(находки)}")
        for ширина, имя, н in находки:
            print(f"     [{ширина}] {имя}")
            print(f"        блок {н['блок'][:70]}{('#' + н['id']) if н['id'] else ''} {н['размер']}, "
                  f"чужих точек {н['чужих']} из {н['точек']}")
            for ч in н["чужие"][:3]:
                print(f"          ({ч['x']},{ч['y']}) → {ч['кто'][:70]}")
    return находки


def контроль():
    print("=" * 74)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: накладка поверх страницы обязана найтись")
    print("=" * 74)
    # ШАГ ПЕРВЫЙ — ДОКАЗАТЬ, ЧТО ПОДЛОГ СОСТОЯЛСЯ (§6.0.3)
    д_чисто, д_подлог = доказать_подлог(ПОДЛОГ)
    состоялся = д_чисто != д_подлог
    print("  доказательство (кто в середине окна): чисто=%r с подлогом=%r"
          % (д_чисто, д_подлог))
    print("  → %s" % ("ПОДЛОГ СОСТОЯЛСЯ" if состоялся
                      else "ПОДЛОГ НЕ СОСТОЯЛСЯ"))
    if not состоялся:
        print()
        print("ПРОВАЛЕН: ломать было нечего — вердикт пробы про этот "
              "подлог не значит ничего.")
        return 1

    чисто = прогон(тихо=True)
    подлог = прогон(добавка_css=ПОДЛОГ, тихо=True)
    print(f"  без подлога:  {len(чисто)} находок")
    print(f"  с подлогом:   {len(подлог)} находок")
    ok = len(подлог) > len(чисто)
    print()
    print("ПРОЙДЕН." if ok else
          "ПРОВАЛЕН: проверка не увидела накладку — её ноль ничего не значит.")
    return 0 if ok else 1


if __name__ == "__main__":
    арг = sys.argv[1:]
    if "--база" in арг:
        ch.БАЗА = арг[арг.index("--база") + 1]
    if "--контроль" in арг:
        sys.exit(контроль())
    sys.exit(1 if прогон() else 0)

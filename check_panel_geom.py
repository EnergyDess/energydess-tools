"""ПРОВЕРКА 63: ГЕОМЕТРИЯ ПАНЕЛЕЙ ОДНА НА ВЕСЬ ПРОЕКТ (№352, «аптечка-4»).

ПРОВЕРКА, код 1 при находке, 2 — спросить нечем (стенда нет, панелей 0).

ЗАЧЕМ. Владелец: «Перепроверить» начинается от самого верха страницы,
ассистент — ниже верхней полосы, ширины отличаются, и при переключении
содержимое страницы прыгает. Замер до правки на 1600: ассистент аптечки
верх 64 ширина 432, соседи верх 0 ширина 420 — то есть переключение
двигает страницу на 12 px и переставляет панель по вертикали на 64.

ЧТО СПРАШИВАЕТСЯ — ТРИ ЧИСЛА У КАЖДОЙ ПАНЕЛИ, замером живой страницы:

  1 ШИРИНА панели,
  2 КООРДИНАТА ВЕРХА,
  3 СДВИГ СОДЕРЖИМОГО страницы (`padding-right` у `.v2-shell`).

Критерий — РАСХОЖДЕНИЕ МЕЖДУ ПАНЕЛЯМИ, а не совпадение с числом:
вписанное число разошлось бы с токеном молча, а «все панели одинаковы»
переживает любую правку ширины. Допуск 1 px — субпиксельная раскладка.

ВЕРХ СПРАШИВАЕТСЯ ЕЩЁ И НА СОВПАДЕНИЕ С НИЗОМ ВЕРХНЕЙ ПОЛОСЫ
(№352, «аптечка-5», 1.1, решение владельца). Одинаковости мало:
все четыре панели стояли на нуле ОДИНАКОВО и одинаково накрывали
строку с поиском и аватаром — то есть прежний критерий такое
поведение считал исправным. Сравнение идёт с ЖИВОЙ полосой
(`.v2-top`), а не с числом: разойдись оно с токеном, панель встала
бы внахлёст либо с щелью, и проба молчала бы про это.
На ≤768 полосы над панелью нет — там верх обязан быть нулевым,
и это спрашивается отдельным утверждением, а не исключением.

ПАНЕЛЬ ОТКРЫВАЕТСЯ НАЖАТИЕМ, а не вызовом функции: ровно на этом
проба 62 однажды пропустила перекрытие (§6.3, орган считается живым,
если до него дотягивается нажатие).

СЦЕНЫ — ПЕРЕЧЕНЬ, И ЭТО ЗАКОННО: «чем открыть панель» из разметки
не выводится (§6.0.7, тот же довод, что у `СЦЕНЫ` проверки 62).
САМИ ПАНЕЛИ перечня не имеют — берутся по `[data-panel]`, и пятая
попадёт под замер сама.

БРАУЗЕР ВИДИМЫЙ (§6.0.3): меряются ширины, а headless прячет полосу
прокрутки без изъятия места — сдвиг содержимого вышел бы не тем.

    py check_panel_geom.py
    py check_panel_geom.py --контроль   # подлоги: своя ширина, верх у края
"""
import os
import sys

try:
    import probe_guard  # noqa: F401  ПРОПУСК вместо трассы (§6.0.1)
except ImportError:
    pass

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import browser_window  # noqa: F401,E402  видимое окно — на второй монитор
import check_hover as ch  # noqa: E402

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# ШИРИНЫ — ТЕ, ЧТО НАЗВАЛ ВЛАДЕЛЕЦ. 390 обязателен отдельно: там панель
# на весь экран, сдвига нет вовсе, и правило «одинаковость» проверяет
# другое утверждение — что все панели одинаково развернулись.
ШИРИНЫ = [(1600, 1000), (1280, 900), (390, 844)]
УЗКАЯ = 768  # ≤768 — панель на весь экран (v2.css)

# (путь, имя сцены, [(подпись панели, селектор кнопки, селектор панели)])
СЦЕНЫ = [
    ("/medkit", "аптечка", [
        ("ассистент", "#apt-ai-open", "#apt-ai"),
        ("перепроверить", "#apt-recheck-open", "#apt-recheck-panel"),
        ("лекарство", "[data-doses]", "#apt-drug"),
    ]),
    ("/nutrition", "питание", [
        ("ассистент", "#nut-assist-open", "#nut-assist"),
    ]),
]

ЗАМЕР = r"""(сел) => {
  const О = {opacityProperty: true, visibilityProperty: true, contentVisibilityAuto: true};
  const п = document.querySelector(сел);
  if (!п) return {есть: false};
  const b = п.getBoundingClientRect();
  const видна = (п.checkVisibility ? п.checkVisibility(О) : true)
                && b.width > 0 && b.height > 0;
  const об = document.querySelector('.v2-shell');
  const pr = об ? parseFloat(getComputedStyle(об).paddingRight) || 0 : null;
  // НИЗ ВЕРХНЕЙ ПОЛОСЫ — У ЖИВОГО УЗЛА, а не из токена: токен может
  // разойтись с фактической высотой полосы (перенос, свой padding),
  // и тогда сверка с ним печатала бы «совпало» про щель на экране.
  // На странице инструмента полосу носит `.site-header.v2-top-bar`
  // (разметка `_header.html`); `.v2-top` — её вид на витрине v2.
  const пол = document.querySelector('.v2-top-bar, .v2-top');
  const bп = пол ? пол.getBoundingClientRect() : null;
  return {
    есть: true,
    видна: видна,
    низ_полосы: bп ? Math.round(bп.bottom * 10) / 10 : null,
    ширина: Math.round(b.width * 10) / 10,
    верх: Math.round(b.top * 10) / 10,
    сдвиг: pr === null ? null : Math.round(pr * 10) / 10,
    окно: document.documentElement.clientWidth,
  };
}"""

# ПОДЛОГ: одной панели задана СВОЯ ширина вместо переменной оболочки.
# Ровно тот дефект, который и чинится: «Перепроверить» шире соседей.
# Доказательство НЕЗАВИСИМО от вердикта — фактическая ширина панели
# в пикселях до и после наложения (§6.0.3).
ПОДЛОГ_ШИРИНА = """addEventListener('DOMContentLoaded', () => {
  const s = document.createElement('style');
  s.textContent = '#apt-recheck-panel { width: 372px !important; }';
  document.head.appendChild(s);
});"""

# ПОДЛОГ: одной панели возвращён прежний верх — от края окна.
# Ровно то поведение, которое чинит 1.1: панель накрывает верхнюю
# полосу. Доказательство НЕЗАВИСИМО от вердикта — координата верха.
ПОДЛОГ_ВЕРХ = """addEventListener('DOMContentLoaded', () => {
  const s = document.createElement('style');
  s.textContent = '#apt-recheck-panel { top: 0 !important; }';
  document.head.appendChild(s);
});"""

ДОКАЗАТЕЛЬСТВА = {
    "своя-ширина": "ширина панели «перепроверить» на 1600, px",
    "верх-ноль": "координата верха панели «перепроверить» на 1600, px",
}
ПОДЛОГИ = {"своя-ширина": ПОДЛОГ_ШИРИНА, "верх-ноль": ПОДЛОГ_ВЕРХ}

находок = 0
пропусков = 0
шагов = 0


def шаг(имя, условие, подробность="", собрано=None, отрицание=None):
    global находок, пропусков, шагов
    шагов += 1
    if собрано is not None and not собрано:
        пропусков += 1
        print("  ПРОПУСК %-52s %s" % (имя, отрицание or "мерить нечего"))
        return
    if условие:
        print("  OK      %-52s %s" % (имя, подробность))
    else:
        находок += 1
        print("  ПЛОХО   %-52s %s" % (имя, подробность))


def прогон(подлог=None):
    """Возвращает {(ширина, сцена, панель): {ширина, верх, сдвиг}}."""
    from playwright.sync_api import sync_playwright
    собрано = {}
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=False)
        try:
            for w, h in ШИРИНЫ:
                к = бр.new_context(viewport={"width": w, "height": h},
                                   has_touch=(w <= УЗКАЯ))
                if подлог:
                    к.add_init_script(ПОДЛОГИ[подлог])
                стр = к.new_page()
                ch._войти(стр)
                for путь, экран, панели in СЦЕНЫ:
                    for подпись, кнопка, сел in панели:
                        # С ЧИСТОГО ЛИСТА НА КАЖДУЮ ПАНЕЛЬ: закрытая
                        # соседка оставляет за собой сдвиг страницы.
                        стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
                        стр.wait_for_timeout(500)
                        try:
                            стр.click(кнопка, timeout=5000)
                        except Exception:
                            continue
                        стр.wait_for_timeout(700)
                        з = стр.evaluate(ЗАМЕР, сел)
                        if not з.get("есть") or not з.get("видна"):
                            continue
                        собрано[(w, экран, подпись)] = з
                стр.close()
                к.close()
        finally:
            бр.close()
    return собрано


def разбор(собрано):
    """Печатает таблицу и считает находки."""
    for w, _ in ШИРИНЫ:
        ряд = {к[1] + "·" + к[2]: v for к, v in собрано.items() if к[0] == w}
        print("\n  ── ширина окна %d" % w)
        if not ряд:
            шаг("%d: панели открылись" % w, False, "ни одной",
                собрано=0, отрицание="ни одна панель не открылась")
            continue
        for имя in sorted(ряд):
            з = ряд[имя]
            print("     %-24s ширина %7.1f  верх %6.1f  сдвиг %s"
                  % (имя, з["ширина"], з["верх"],
                     "—" if з["сдвиг"] is None else "%.1f" % з["сдвиг"]))
        for поле, подпись in (("ширина", "ширина"), ("верх", "верх"),
                              ("сдвиг", "сдвиг содержимого")):
            числа = [з[поле] for з in ряд.values() if з.get(поле) is not None]
            # ОДИН ВЫЗОВ, А НЕ ВЕТКА С `True`: при одной панели сравнивать
            # не с чем, и шаг обязан стать ПРОПУСКОМ, а не успехом
            # (§6.0.1, проверка 33). Меньше двух чисел — `собрано` пусто.
            разброс = (max(числа) - min(числа)) if len(числа) >= 2 else None
            шаг("%d: %s одинакова у всех панелей" % (w, подпись),
                разброс is not None and разброс <= 1.0,
                "" if разброс is None else
                "разброс %.1f px (%s)" % (разброс,
                                          ", ".join("%.1f" % ч for ч in числа)),
                собрано=len(числа) if len(числа) >= 2 else 0,
                отрицание="панель на экране одна, сравнивать не с чем")
        # ── ВЕРХ ОТНОСИТЕЛЬНО ВЕРХНЕЙ ПОЛОСЫ (1.1). Утверждения два
        #    и они разные: на десктопе панель начинается ПОД полосой,
        #    на ≤768 её нет вовсе и панель идёт от края.
        узкая = w <= УЗКАЯ
        низ = [з["низ_полосы"] for з in ряд.values()
               if з.get("низ_полосы") is not None]
        if узкая:
            плохо = [и for и, з in ряд.items() if abs(з["верх"]) > 1.0]
            шаг("%d: панель от края окна" % w, not плохо,
                "не от края: %s" % (", ".join(плохо) or "—"),
                собрано=len(ряд), отрицание="панели не открылись")
        else:
            плохо = [и for и, з in ряд.items()
                     if з.get("низ_полосы") is None
                     or abs(з["верх"] - з["низ_полосы"]) > 1.0]
            шаг("%d: панель начинается под верхней полосой" % w, not плохо,
                "полоса кончается на %s; не совпали: %s"
                % ("—" if not низ else "%.1f" % низ[0],
                   ", ".join("%s (верх %.1f)" % (и, ряд[и]["верх"])
                             for и in плохо) or "—"),
                собрано=len(низ),
                отрицание="верхней полосы на странице нет")


def доказать(подлог, поле="ширина"):
    """НЕЗАВИСИМЫЙ замер того, что подлог собирался изменить."""
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=False)
        try:
            к = бр.new_context(viewport={"width": 1600, "height": 1000})
            if подлог:
                к.add_init_script(ПОДЛОГИ[подлог])
            стр = к.new_page()
            ch._войти(стр)
            стр.goto(ch.БАЗА + "/medkit", wait_until="domcontentloaded")
            стр.wait_for_timeout(500)
            стр.click("#apt-recheck-open", timeout=5000)
            стр.wait_for_timeout(700)
            з = стр.evaluate(ЗАМЕР, "#apt-recheck-panel")
            return з.get(поле)
        finally:
            бр.close()


def контроль():
    """Каждый подлог — со СВОИМ независимым доказательством и своим
    прогоном: общий прогон на оба показал бы, что проба видит ХОТЬ
    ЧТО-ТО, а находка от ширины закрыла бы собой молчание про верх
    (§6.0.3)."""
    global находок, пропусков, шагов
    итог = 0
    for имя, поле in (("своя-ширина", "ширина"), ("верх-ноль", "верх")):
        print("=" * 74)
        print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ — подлог «%s»" % имя)
        print("=" * 74)
        чисто = доказать(None, поле)
        грязно = доказать(имя, поле)
        print("\n  ДОКАЗАТЕЛЬСТВО (%s): без подлога %s, с подлогом %s"
              % (ДОКАЗАТЕЛЬСТВА[имя], чисто, грязно))
        if чисто == грязно:
            print("  ПОДЛОГ НЕ СОСТОЯЛСЯ — ломать нечего, "
                  "вердикт ничего не значит")
            итог = 1
            continue
        находок = пропусков = шагов = 0
        print("\n  ── прогон БЕЗ подлога")
        разбор(прогон())
        было = находок
        находок = пропусков = шагов = 0
        print("\n  ── прогон С подлогом")
        разбор(прогон(подлог=имя))
        стало = находок
        print("\n  ИТОГ: находок без подлога %d, с подлогом %d"
              % (было, стало))
        if было == 0 and стало > 0:
            print("  ЛОВИТ")
        else:
            print("  НЕ ЛОВИТ")
            итог = 1
    return итог


def main():
    if "--контроль" in sys.argv:
        sys.exit(контроль())
    print("=" * 74)
    print("ПРОВЕРКА 63 — геометрия панелей одна на весь проект")
    print("=" * 74)
    разбор(прогон())
    print("\n  шагов %d, находок %d, пропусков %d" % (шагов, находок, пропусков))
    if шагов == пропусков:
        print("  СПРОСИТЬ НЕЧЕМ — ни одна панель не открылась")
        sys.exit(2)
    sys.exit(1 if находок else 0)


if __name__ == "__main__":
    main()

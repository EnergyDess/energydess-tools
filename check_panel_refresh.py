def видна_ли(pg, сц, орган):
    """Видна ли цель сцены. У панели ВНУТРИ повторяющейся карточки цель
    ищется ОТ ОРГАНА (`цель_в`), а не глобальным селектором: глобальный
    находит первую такую панель на странице, а нажимали мы другую."""
    пара = сц.get("цель_в")
    if пара and орган:
        return bool(орган.evaluate(
            "(о, п) => { const к = о.closest(п[0]); if (!к) return false; "
            "const э = к.querySelector(п[1]); "
            "return !!э && э.checkVisibility(%s); }" % ОПЦИИ_JS, пара))
    return bool(pg.evaluate(
        "(с) => { const э = document.querySelector(с); "
        "return !!э && э.checkVisibility(%s); }" % ОПЦИИ_JS, сц["цель"]))



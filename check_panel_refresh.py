def разобрать(итог):
    """Находки: панель открылась, а перечитывания нет ничем."""
    находки, строки = [], []
    for с in итог:
        if с["исход"] != "открыта":
            строки.append("  ?  %-38s %s" % (с["сцена"], с["почему"]))
            находки.append(("НЕ ПРОВЕРЕНА", с["сцена"], с["почему"]))
            continue
        объявлены = [к for к in с["корни"] if к["объявлена"]]
        ошибки = [к for к in с["корни"] if к["ошибка"]]
        перечитала = с["позвал"] > 0 or с["запросов"] > 0
        знак = "OK " if перечитала and not ошибки else "НЕТ"
        строки.append(
            "  %s %-38s слой звал %d, запросов %d, объявлено %d%s"
            % (знак, с["сцена"], с["позвал"], с["запросов"], len(объявлены),
               ", ОШИБКА СЛОЯ" if ошибки else ""))
        for к in с["корни"]:
            строки.append("        %-34s объявлена: %s" % (к["имя"], "да" if к["объявлена"] else "НЕТ"))
        if ошибки:
            находки.append(("ОШИБКА СЛОЯ", с["сцена"], "имя обновления не найдено"))
        elif not перечитала:
            находки.append(("НЕ ПЕРЕЧИТЫВАЕТ", с["сцена"],
                            "открылась, слой не звал, запросов 0%s"
                            % (" — а `data-refresh` СТОИТ" if объявлены else "")))
    return находки, строки



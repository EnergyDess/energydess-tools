"""ПРОВЕРКА 62: МЕСТО ДЛЯ ПАНЕЛИ ОДНО (№352, «аптечка-2», блок 1.1).

ПРОВЕРКА, код 1 при находке, 2 — спросить нечем (стенда нет, панелей 0).

ЗАЧЕМ. Владелец открыл «AI-ассистент», затем «Перепроверить» — панели
легли одна на другую у правого края: верхняя закрыла нижнюю вместе
с её крестиком. Замер до правки: видимых панелей после двух открытий —
ДВЕ. Ни ошибки, ни признака на экране.

ЧТО СПРАШИВАЕТСЯ, и каждое — замером живой страницы:

  1 ОДНА ЗА РАЗ. Открыть панель А, затем панель Б — видимых панелей
    ровно одна, и это Б. Видимость спрашивается `checkVisibility`
    с опциями И ненулевым размером: закрытая модалка отвечает на голый
    вызов `true` (замер задачи 263), а панель с нулевой высотой —
    не панель.
  2 ESCAPE закрывает открытую панель, и фокус возвращается на ОРГАН,
    которым её открыли.
  3 ЗАТЕМНЕНИЕ. Клик по нему закрывает — там, где оно объявлено
    (`data-panel-backdrop`). У панели без затемнения этот шаг —
    ПРОПУСК, а не успех: закрывать нечего, и «прошло» тут значило бы
    «не спрашивали».
  4 ОБЪЯВЛЕНИЕ. У каждой видимой панели есть `data-panel-close`, и
    функция с таким именем на странице ЕСТЬ. Иначе слой молча
    не закрывает ничего (`window.__соло.ошибок`).

СЦЕНЫ — ПЕРЕЧЕНЬ, И ЭТО ЗАКОННО: «чем открыть панель» из разметки
не выводится, это знание об устройстве экрана (§6.0.7, тот же приём,
что `СЦЕНЫ` у `check_hover`). А вот САМИ ПАНЕЛИ перечня не имеют —
слой и проба берут их по признаку `[data-panel]`, и четвёртая панель
попадает под проверку сама.

В БАЗУ НЕ ПИШЕТ: открытие панели — чтение (`/medkit/api/gaps`,
переписка ассистента). Поэтому проба годится в ряд стенда.

БРАУЗЕР НЕВИДИМЫЙ (§6.0.3): здесь спрашивается логика, а не ширины.

    py check_panel_solo.py
    py check_panel_solo.py --контроль   # два подлога, каждый роняет СВОЙ шаг
"""
import os
import sys

try:
    import probe_guard  # noqa: F401  ПРОПУСК вместо трассы (§6.0.1)
except ImportError:
    pass

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_hover as ch  # noqa: E402

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

# ШИРИНА 1920, И ЭТО УСЛОВИЕ ЗАМЕРА. Панель стоит у правого края
# и занимает 420 px; кнопки шапки — там же. На 1280 вторая кнопка
# оказывается ПОД открытой панелью, и нажать её нельзя вовсе
# (замер: playwright «intercepts pointer events»), то есть наложить
# панели на узком экране невозможно по построению. Дефект владелец
# видел на широком мониторе — там кнопки левее панели.
ШИРИНА, ВЫСОТА = 1920, 1000

# (путь, имя сцены, [(подпись панели, селектор кнопки, селектор панели)])
# ПАРЫ ПЕРЕБИРАЮТСЯ В ОБЕ СТОРОНЫ, и это правка «аптечки-3» (2.1):
# прежняя версия открывала панели ОДНОЙ последовательностью и дефект
# пропустила. Владелец нашёл его руками: из «Перепроверить» ассистент
# открывался, обратно — нет.
СЦЕНЫ = [
    ("/medkit", "аптечка", [
        ("перепроверить", "#apt-recheck-open", "#apt-recheck-panel"),
        ("ассистент", "#apt-ai-open", "#apt-ai"),
        ("лекарство", "[data-doses]", "#apt-drug"),
    ]),
    ("/nutrition", "питание", [
        ("ассистент", "#nut-assist-open", "#nut-assist"),
    ]),
]

# ВТОРАЯ ПАНЕЛЬ ОТКРЫВАЕТСЯ НАСТОЯЩИМ НАЖАТИЕМ, а не вызовом функции,
# и это ГЛАВНАЯ правка проверки.
#
# ЗДЕСЬ СТОЯЛО ОБРАТНОЕ: «нажать вторую кнопку при открытой первой
# нельзя ни в одну сторону — панель накрывает кнопку». Замер был верен
# (панель «Перепроверить» [1490, 1910], кнопка «AI-ассистент»
# [1507, 1680] под ней), а вывод из него сделан неверный: проба
# обошла дефект вызовом функции, и дефект прожил до владельца.
#
# Теперь страница СЖИМАЕТСЯ под открытую панель (`panel-solo.сдвиг`),
# кнопки уезжают левее — замер после правки: при любой открытой панели
# все три кнопки шапки отдают нажатие себе. Проба жмёт их, как человек,
# и накрытая кнопка снова станет находкой.
ЗАМЕР = r"""() => {
  const О = {opacityProperty: true, visibilityProperty: true, contentVisibilityAuto: true};
  const вид = e => {
    if (!e.isConnected) return false;
    if (e.checkVisibility && !e.checkVisibility(О)) return false;
    const b = e.getBoundingClientRect();
    return b.width > 0 && b.height > 0;
  };
  const все = [...document.querySelectorAll('[data-panel]')];
  return {
    всего: все.length,
    видимые: все.filter(вид).map(e => e.id || e.className),
    без_имени: все.filter(e => !e.getAttribute('data-panel-close')).map(e => e.id),
    мёртвое_имя: все.filter(e => {
      const и = e.getAttribute('data-panel-close');
      return и && typeof window[и] !== 'function';
    }).map(e => e.id),
    фокус: document.activeElement ? (document.activeElement.id || document.activeElement.tagName) : '',
    ошибок_слоя: (window.__соло || {}).ошибок,
  };
}"""

# ── ПОДЛОГИ ──────────────────────────────────────────────────────────
# (а) ДВЕ ПАНЕЛИ РАЗОМ: слой видит панель, но закрыть её нечем —
#     снят `data-panel-close`. Доказательство — число объявленных
#     имён закрытия в дереве: было N, стало 0.
#
#     ПЕРВАЯ ВЕРСИЯ ПОДЛОГА СНИМАЛА `data-panel` — и НЕ БЫЛА НАЙДЕНА,
#     потому что ломала не слой, а ИЗМЕРИТЕЛЬ: проба берёт панели тем же
#     признаком, и все шаги уходили в ПРОПУСК «панелей на экране нет».
#     Подлог, ломающий пробу вместе с кодом, ничего не доказывает.
ПОДЛОГ_БЕЗ_СЛОЯ = """addEventListener('DOMContentLoaded', () => {
  setTimeout(() => document.querySelectorAll('[data-panel-close]')
    .forEach(э => э.removeAttribute('data-panel-close')), 0); });"""

# (б) Escape до слоя не доходит: обработчик в фазе захвата ставится
#     РАНЬШЕ слоя (init-script исполняется до скриптов страницы)
#     и глушит событие. Доказательство — что обработчик стоит.
# СЧЁТ ПЕРЕХВАТОВ — В `sessionStorage`, А НЕ В `window`: проба между
# шагами ПЕРЕЗАГРУЖАЕТ страницу (разбор в прогоне), и счётчик в окне
# обнулялся бы вместе с ней — доказательство печатало бы ноль
# при сработавшем подлоге.
ПОДЛОГ_ESCAPE = """document.addEventListener('keydown', e => {
  if (e.key === 'Escape') {
    try { sessionStorage.setItem('подлог_escape',
      String(+(sessionStorage.getItem('подлог_escape') || 0) + 1)); } catch (x) {}
    e.stopImmediatePropagation(); } }, true);"""

ДОКАЗАТЕЛЬСТВА = {
    "без-слоя": "панелей с объявленным закрытием в дереве",
    "escape": "перехватов Escape до слоя",
}

находок = 0
пропусков = 0


def шаг(имя, условие, подробность="", собрано=None, отрицание=None):
    """Три исхода: OK, ПЛОХО, ПРОПУСК (§6.0.1 — «спросить нечем» ≠ успех)."""
    global находок, пропусков
    if собрано is not None and not собрано:
        пропусков += 1
        print("  ПРОПУСК %-52s %s" % (имя, отрицание or "мерить нечего"))
        return
    if условие:
        print("  OK      %-52s %s" % (имя, подробность))
    else:
        находок += 1
        print("  ПЛОХО   %-52s %s" % (имя, подробность))


def прогон(подлог=None):
    from playwright.sync_api import sync_playwright
    итог = {"панелей": 0}
    with sync_playwright() as p:
        бр = p.chromium.launch()
        try:
            к = бр.new_context(viewport={"width": ШИРИНА, "height": ВЫСОТА})
            if подлог == "без-слоя":
                к.add_init_script(ПОДЛОГ_БЕЗ_СЛОЯ)
            if подлог == "escape":
                к.add_init_script(ПОДЛОГ_ESCAPE)
            стр = к.new_page()
            ch._войти(стр)
            for путь, экран, панели in СЦЕНЫ:
                print("\n  ── %s (%s)" % (экран, путь))
                стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
                стр.wait_for_timeout(600)
                з = стр.evaluate(ЗАМЕР)
                итог["панелей"] += з["всего"]
                шаг("%s: панели объявили, чем их закрыть" % экран,
                    not з["без_имени"] and not з["мёртвое_имя"],
                    "всего %d, без имени %s, имя мёртвое %s"
                    % (з["всего"], з["без_имени"] or "нет", з["мёртвое_имя"] or "нет"),
                    собрано=з["всего"], отрицание="панелей на экране нет")
                if not з["всего"]:
                    continue

                # 1. ВСЕ УПОРЯДОЧЕННЫЕ ПАРЫ, В ОБЕ СТОРОНЫ
                for i, (подпись_a, кнопка_a, сел_a) in enumerate(панели):
                    for j, (подпись_b, кнопка_b, сел_b) in enumerate(панели):
                        if i == j:
                            continue
                        # КАЖДАЯ ПАРА — С ЧИСТОГО ЛИСТА: панель, закрытая
                        # предыдущей парой, оставляет за собой сдвиг
                        # страницы и фокус, и вторая пара мерила бы
                        # не свой случай.
                        стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
                        стр.wait_for_timeout(500)
                        стр.click(кнопка_a)
                        стр.wait_for_timeout(600)
                        имя_b = сел_b.lstrip("#")
                        try:
                            стр.click(кнопка_b, timeout=4000)
                            дошло = True
                        except Exception as e:
                            дошло = False
                            причина = str(e).splitlines()[0][:80]
                        стр.wait_for_timeout(600)
                        з = стр.evaluate(ЗАМЕР)
                        шаг("%s: %s → %s (нажатием)"
                            % (экран, подпись_a, подпись_b),
                            дошло and len(з["видимые"]) == 1
                            and з["видимые"][0] == имя_b,
                            "видимы: %s%s" % (", ".join(з["видимые"]) or "ни одной",
                                              "" if дошло else
                                              "; до кнопки не дотянуться: " + причина))

                # 2. ESCAPE И ФОКУС — на панели, открытой НАЖАТИЕМ:
                #    слой запоминает последний нажатый орган, и у панели,
                #    открытой вызовом, органа нет по построению.
                # СОСТОЯНИЕ СБРАСЫВАЕТСЯ ПЕРЕЗАГРУЗКОЙ, а не закрытием:
                # при подлоге закрыть панель нечем по построению, и проба
                # повисла бы на затемнении ассистента (замер: 56 попыток
                # нажатия, «#apt-ai-back intercepts pointer events»).
                # Перезагрузка от объявлений панели не зависит вовсе.
                стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
                стр.wait_for_timeout(600)
                стр.click(панели[0][1])
                стр.wait_for_timeout(600)
                кнопка_последней = панели[0][1].lstrip("#")
                стр.keyboard.press("Escape")
                стр.wait_for_timeout(400)
                з = стр.evaluate(ЗАМЕР)
                шаг("%s: Escape закрыл панель" % экран, not з["видимые"],
                    "видимы: %s" % (", ".join(з["видимые"]) or "ни одной"))
                шаг("%s: фокус вернулся на кнопку, открывшую панель" % экран,
                    з["фокус"] == кнопка_последней,
                    "фокус на «%s», ждали «%s»" % (з["фокус"], кнопка_последней))

                # 3. ЗАТЕМНЕНИЕ
                for подпись, кнопка, сел in панели:
                    # каждая панель — с чистого листа, разбор выше
                    стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
                    стр.wait_for_timeout(500)
                    фон = стр.evaluate(
                        "с => { const э = document.querySelector(с);"
                        " return э ? э.getAttribute('data-panel-backdrop') : null; }", сел)
                    стр.click(кнопка)
                    стр.wait_for_timeout(500)
                    if фон:
                        стр.evaluate("с => document.querySelector(с).click()", фон)
                        стр.wait_for_timeout(400)
                        з = стр.evaluate(ЗАМЕР)
                        шаг("%s · %s: клик по затемнению закрыл" % (экран, подпись),
                            not з["видимые"],
                            "видимы: %s" % (", ".join(з["видимые"]) or "ни одной"))
                    else:
                        # УСЛОВИЕ — ФАКТ, А НЕ ЛИТЕРАЛ `True` (проверка 33):
                        # шаг всё равно уходит в ПРОПУСК по `собрано=0`,
                        # но константа в условии означала бы шаг, который
                        # не может провалиться ни при каких данных.
                        шаг("%s · %s: клик по затемнению" % (экран, подпись),
                            фон is None, собрано=0,
                            отрицание="затемнения у панели нет — закрывать нечего")
                шаг("%s: слой не жаловался на мёртвые имена" % экран,
                    not з["ошибок_слоя"], "ошибок слоя %s" % з["ошибок_слоя"])
            if подлог:
                if подлог == "без-слоя":
                    итог["доказательство"] = стр.evaluate(
                        "() => document.querySelectorAll('[data-panel-close]').length")
                else:
                    итог["доказательство"] = стр.evaluate(
                        "() => +(sessionStorage.getItem('подлог_escape') || 0)")
            к.close()
        finally:
            бр.close()
    return итог


def контроль():
    global находок, пропусков
    print("КОНТРОЛЬ: два подлога, каждый роняет СВОЙ шаг\n")
    плохо = 0
    чисто_панелей = None
    for подлог in (None, "без-слоя", "escape"):
        находок = пропусков = 0
        print("─" * 70)
        print("ПОДЛОГ: %s" % (подлог or "нет (чистый прогон)"))
        итог = прогон(подлог)
        if подлог is None:
            чисто_панелей = итог["панелей"]
            print("\n  чисто: находок %d" % находок)
            if находок:
                print("  ОСНОВА ГРЯЗНАЯ — контроль недействителен")
                плохо += 1
        else:
            print("\n  доказательство подлога: %s = %s (чисто — %s)"
                  % (ДОКАЗАТЕЛЬСТВА[подлог], итог.get("доказательство"),
                     чисто_панелей if подлог == "без-слоя" else 0))
            print("  находок с подлогом: %d" % находок)
            if not находок:
                print("  ПОДЛОГ НЕ НАЙДЕН — проба слепа")
                плохо += 1
    return плохо


def main():
    global находок
    арг = sys.argv[1:]
    if "--контроль" in арг:
        плохо = контроль()
        print("\nКОНТРОЛЬ: %s" % ("НЕ ПРОЙДЕН" if плохо else "пройден"))
        return 1 if плохо else 0
    print("ПРОВЕРКА 62: место для панели одно. Стенд %s" % ch.БАЗА)
    итог = прогон()
    if not итог["панелей"]:
        print("\nПРОПУСК: панелей с `data-panel` не нашлось ни на одном экране")
        return 2
    print("\nитог: находок %d, пропусков %d, панелей на экранах %d"
          % (находок, пропусков, итог["панелей"]))
    return 1 if находок else 0


if __name__ == "__main__":
    sys.exit(main())

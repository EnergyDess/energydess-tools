# и вешать на этом весь прогон нельзя — тогда кадр просто снимется без неё,
# но одинаково во всех прогонах.
def _догрузить_картинки(стр, потолок=8000, целиком=True):
    # ЛЕНИВОСТЬ СНИМАЕТСЯ ТОЛЬКО У ПОЛНОГО КАДРА. У сцены, снимаемой
    # видимой частью, за кадром картинок не видно — а снятая ленивость
    # заставляет браузер выкачать их ВСЕ: у раздела Enshrouded это
    # 90 файлов по мегабайту на каждую из трёх ширин, и один прогон
    # повторяемости занял СОРОК МИНУТ вместо трёх.
    if целиком:
        стр.evaluate("() => document.querySelectorAll('img[loading=\"lazy\"]')"
                     ".forEach(и => { и.loading = 'eager'; })")
    try:
        стр.wait_for_function(
            "() => Array.from(document.images).every(и => и.complete)",
            timeout=потолок)
    except Exception:
        # Не дождались — печатаем, а не проглатываем: молчание тут
        # неотличимо от «всё загрузилось» (§6.0.1).
        осталось = стр.evaluate(
            "() => Array.from(document.images).filter(и => !и.complete).length")
        print(f"   · картинки не догрузились: осталось {осталось}")


def _закрепить_приём(стр, вкладка):
    """Приём выбирается ЯВНО, и блок «Недавнее» перерисовывается.

    Нажатия по чипу НЕ ХВАТАЕТ, и это стоило одного ложного расхождения:
    `выделитьПриём` меняет подсветку чипа и `S.searchMeal`, но список
    недавних не трогает — заголовок «— добавляете сюда» остаётся тем,
    с которым блок нарисовался, то есть выбранным ПО ЧАСАМ. Замер:
    в кадре «до» стояло «Обед», в кадре «после» — «Ужин», и разница
    была только во времени съёмки (пороги 11 / 16 / 21).

    Поэтому после нажатия блок перезагружается той же функцией, которой
    его рисует сам экран.
    """
    if вкладка != "search":
        return
    чип = стр.locator(f"#meal-chips [data-meal='{ПРИЁМ_ДЛЯ_КАДРА}']")
    if not чип.count():
        print("   · чип приёма не найден — кадр пойдёт по часам")
        return
    чип.first.click()
    стр.evaluate("() => loadSearchTab(S.searchTab)")
    стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 1200)
    # Сверяем, что закрепление ДОЕХАЛО до разметки, а не только до чипа.
    сюда = стр.evaluate(
        "() => { const э = document.querySelector('.a-group-t.is-here span');"
        " return э ? э.textContent : null; }")
    ждём = {"breakfast": "Завтрак", "lunch": "Обед",
            "dinner": "Ужин", "snack": "Перекус"}[ПРИЁМ_ДЛЯ_КАДРА]
    if сюда and not сюда.startswith(ждём):
        raise RuntimeError(
            f"приём не закрепился: в разметке «{сюда}», ждали «{ждём}». "
            f"Кадр пошёл бы по стенным часам — это неповторимо.")


def _папка(метка):
    return os.path.join(КУДА, метка)


def снять(метка, добавка_css=""):
    """18 кадров в папку `метка`. Возвращает список имён."""
    from playwright.sync_api import sync_playwright

    папка = _папка(метка)
    shutil.rmtree(папка, ignore_errors=True)
    os.makedirs(папка, exist_ok=True)
    имена = []

    with sync_playwright() as p:
        бр = p.chromium.launch()
        for ширина, высота, сенсор in ШИРИНЫ:
            к = бр.new_context(viewport={"width": ширина, "height": высота},
                               has_touch=сенсор, is_mobile=сенсор)
            стр = к.new_page()
            cdp = к.new_cdp_session(стр)
            if сенсор:
                ch._включить_сенсор(cdp)
            ch._войти(стр)
            if сенсор:
                ch._включить_сенсор(cdp)

            стр.goto(f"{ch.БАЗА}/nutrition", wait_until="domcontentloaded",
                     timeout=45000)
            стр.wait_for_timeout(2500)
            стр.add_style_tag(content=ГЛУШИТЕЛЬ + добавка_css)
            ch._сверить(стр, сенсор, f"{ширина}: после загрузки")

            for вкладка in ВКЛАДКИ:
                стр.click(f"[data-tab='{вкладка}']")
                стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 900)
                _закрепить_приём(стр, вкладка)
                # УКАЗАТЕЛЬ УВОДИТСЯ. Без этой строки кадр активной
                # вкладки снимался то в `:hover`, то нет — и это давало
                # 3 расхождения из 18 на ОДНОМ И ТОМ ЖЕ коде.
                стр.mouse.move(ширина - 2, высота - 2)
                _догрузить_картинки(стр)
                стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА)
                имя = f"{вкладка}-{ширина}.png"
                путь = os.path.join(папка, имя)
                # animations="disabled" — вторая половина повторяемости:
                # переходы досчитываются, а не ловятся в середине.
                стр.screenshot(path=путь, full_page=True,
                               animations="disabled")
                if сенсор:
                    ch._включить_сенсор(cdp)
                ch._сверить(стр, сенсор, f"после кадра {имя}")
                имена.append(имя)

            # Остальные экраны — тем же контекстом и той же ширины
            for путь, подпись, подготовка, *хвост in СЦЕНЫ:
                целиком = хвост[0] if хвост else True
                стр.goto(f"{ch.БАЗА}{путь}", wait_until="domcontentloaded",
                         timeout=45000)
                стр.wait_for_timeout(2200)
                стр.add_style_tag(content=ГЛУШИТЕЛЬ + добавка_css)
                if подготовка:
                    try:
                        стр.click(подготовка, timeout=4000)
                        стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 700)
                    except Exception as e:
                        print(f"   · {подпись}: не открылось ({type(e).__name__})")
                        continue
                стр.mouse.move(ширина - 2, высота - 2)
                _догрузить_картинки(стр, целиком=целиком)
                стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА)
                имя = f"{подпись}-{ширина}.png"
                стр.screenshot(path=os.path.join(папка, имя), full_page=целиком,
                               animations="disabled")
                if сенсор:
                    ch._включить_сенсор(cdp)
                ch._сверить(стр, сенсор, f"после кадра {имя}")
                имена.append(имя)
            к.close()
        бр.close()
    return имена


def сверить(а, б, тихо=False):
    """(расхождений, всего, [(имя, что)]). Сравнение ПОБАЙТОВОЕ по пикселям."""
    from PIL import Image, ImageChops

    па, пб = _папка(а), _папка(б)
    имена = sorted(set(os.listdir(па)) | set(os.listdir(пб)))
    расхождения = []
    for имя in имена:
        фа, фб = os.path.join(па, имя), os.path.join(пб, имя)
        if not (os.path.exists(фа) and os.path.exists(фб)):
            расхождения.append((имя, "кадра нет в одной из папок"))
            continue
        ia, ib = Image.open(фа).convert("RGB"), Image.open(фб).convert("RGB")
        if ia.size != ib.size:
            расхождения.append((имя, f"размер {ia.size} против {ib.size}"))
            continue
        рамка = ImageChops.difference(ia, ib).getbbox()
        if рамка:
            ш, в = рамка[2] - рамка[0], рамка[3] - рамка[1]
            расхождения.append((имя, f"область {ш}×{в} в {рамка}"))
    if not тихо:
        print(f"  кадров: {len(имена)}   расхождений: {len(расхождения)}")
        for имя, что in расхождения:
            print(f"     {имя}: {что}")
    return len(расхождения), len(имена), расхождения


def повторяемость(сколько):
    """N прогонов ОДНОГО кода. Каждый обязан совпасть с первым.

    Это НЕ приложение к дифу, а условие его применения. Один чистый
    прогон ничего не значит: дефект был именно в нестабильности,
    и он воспроизводился в 3 кадрах из 18 через раз.
    """
    print("=" * 74)
    print(f"ПОВТОРЯЕМОСТЬ ХАРНЕССЫ: {сколько} прогонов ОДНОГО И ТОГО ЖЕ кода")
    print("=" * 74)
    print()
    метки = []
    for i in range(сколько):
        метка = f"повтор{i + 1}"
        снять(метка)
        метки.append(метка)
        print(f"  прогон {i + 1}: снято")
    print()
    всё_ноль = True
    for i in range(1, сколько):
        n, всего, подробно = сверить(метки[0], метки[i], тихо=True)
        значок = "ok " if n == 0 else "ШУМ"
        print(f"  {значок} прогон 1 против прогона {i + 1}: {n} из {всего}")
        for имя, что in подробно:
            print(f"         {имя}: {что}")
        всё_ноль = всё_ноль and n == 0
    print()
    if всё_ноль:
        print("ПРОЙДЕНА: харнесса повторима, её показаниям можно верить.")
    else:
        print("ПРОВАЛЕНА: два прогона одного кода разошлись. Чинить харнессу,")
        print("а не искать правку — расхождения выше НЕ являются находками.")
    return 0 if всё_ноль else 1



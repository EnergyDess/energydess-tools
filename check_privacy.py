# -*- coding: utf-8 -*-
"""
Сверка политики конфиденциальности со схемой базы.

Запуск локально (базы не касается, только читает схему и текст):
    python check_privacy.py

Отвечает на один вопрос: названа ли в политике каждая таблица
с пользовательскими данными. Прогонять при добавлении любой такой
таблицы — полный перечень обрабатываемых данных требует закон,
а забыть категорию легко: таблица объявляется в database.py,
а называть её нужно в тексте внутри main.py.

Так однажды и выпал целый инструмент: трекер Enshrouded не упоминался
в политике вовсе, хотя данные по нему хранились.

Проверка не судит формулировки, только наличие. Если текст переписан
и слово поменялось — поправьте PRIVACY_MENTIONS в database.py.
Код выхода 1 при расхождениях: годится для CI.
"""
import sys

from database import (check_privacy_coverage, PRIVACY_MENTIONS,  # noqa: E402
                      PRIVACY_NOT_PERSONAL, Base)
from main import STATIC_PAGES                                    # noqa: E402

политика = STATIC_PAGES.get("privacy", {}).get("content") or ""
if not политика:
    print("Текста политики нет — STATIC_PAGES['privacy']['content'] пуст.")
    raise SystemExit(1)

# ── ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ (BACKLOG №218, вторая половина) ───────────
#
# «Ноль расхождений» без пройденного контроля не значит ничего: сломай
# признак — и проверка напечатает тот же ноль (§6.0.1). До 2026-09-01
# у этой проверки контроля не было ВООБЩЕ, и её зелёный держался
# на добросовестности.
#
# ПОДЛОГИ ДВА, И ОНИ ЛОМАЮТ РАЗНЫЕ ПОЛОВИНЫ ПРИЗНАКА:
#
#   1. ТАБЛИЦА ЕСТЬ, В ПОЛИТИКЕ ЕЁ НЕТ — прямой предмет проверки:
#      завели модель с `user_id` и забыли назвать её категорию;
#   2. КАТЕГОРИЯ НАЗВАНА, А ТАБЛИЦЫ БОЛЬШЕ НЕТ — обратная сторона:
#      таблицу удалили, а политика продолжает обещать её хранение.
#
# ДОКАЗАТЕЛЬСТВО ПОДЛОГА НЕЗАВИСИМО ОТ ВЕРДИКТА (§6.0.3): печатается
# то, что подлог собирался изменить, — число таблиц в схеме и число
# проверяемых категорий. Подлог, не состоявшийся молча, даёт тот же
# «НАЙДЕН», что слепая проверка.
def доказать_подлог(что, было, стало):
    """НЕЗАВИСИМЫЙ ЗАМЕР ТОГО, ЧТО ПОДЛОГ СОБИРАЛСЯ ИЗМЕНИТЬ.

    Объявлена ИМЕНЕМ на модульном уровне, а не напечатана внутри
    ветки: опись контролей (`check_controls.py`) читает синтаксическое
    дерево, и доказательство, спрятанное в теле `if`, для неё
    не существует — то есть числилось бы необъявленным.
    """
    состоялся = было != стало
    print("   доказательство (%s): %s -> %s  ->  %s"
          % (что, было, стало,
             "ПОДЛОГ СОСТОЯЛСЯ" if состоялся else "НЕ СОСТОЯЛСЯ"))
    return состоялся


if "--контроль" in sys.argv:
    from sqlalchemy import Column, Integer, String

    было_таблиц, было_категорий = len(Base.metadata.tables), len(PRIVACY_MENTIONS)
    исходов = []

    class _ПодложеннаяТаблица(Base):
        __tablename__ = "zz_контроль_приватности"
        id = Column(Integer, primary_key=True)
        user_id = Column(Integer)
        секрет = Column(String)

    print("ПОДЛОГ 1 «таблица есть, в политике её нет»")
    доказать_подлог("таблиц в схеме", было_таблиц, len(Base.metadata.tables))
    нашла = bool(check_privacy_coverage(политика))
    исходов.append(нашла)
    print("   проверка: %s" % ("НАШЛА" if нашла else "НЕ НАШЛА — ПРОВЕРКА СЛЕПА"))

    Base.metadata.remove(_ПодложеннаяТаблица.__table__)

    ключ = sorted(PRIVACY_MENTIONS)[0]
    хранил = PRIVACY_MENTIONS.pop(ключ)
    PRIVACY_MENTIONS["zz_таблицы_такой_нет"] = хранил
    print("ПОДЛОГ 2 «категория названа, а таблицы больше нет»")
    доказать_подлог("ключ категории", ключ, "zz_таблицы_такой_нет")
    нашла2 = bool(check_privacy_coverage(политика))
    исходов.append(нашла2)
    print("   проверка: %s" % ("НАШЛА" if нашла2 else "НЕ НАШЛА — ПРОВЕРКА СЛЕПА"))
    PRIVACY_MENTIONS.pop("zz_таблицы_такой_нет")
    PRIVACY_MENTIONS[ключ] = хранил

    # ОБРАТНЫЙ КОНТРОЛЬ: на чистой схеме находок быть не должно,
    # иначе «нашла» выше означало бы «находит всегда»
    чисто = not check_privacy_coverage(политика)
    print("ОБРАТНЫЙ КОНТРОЛЬ: на чистой схеме находок нет: %s" % чисто)
    print("КОНТРОЛЬ: найдено %d из 2%s"
          % (sum(исходов), "" if чисто else "; НО обратный контроль ПРОВАЛЕН"))
    sys.exit(0)

расхождения = check_privacy_coverage(политика)

print("Таблиц в схеме: %d, из них без персональных данных: %d"
      % (len(Base.metadata.tables), len(PRIVACY_NOT_PERSONAL)))
print("Проверено категорий: %d" % len(PRIVACY_MENTIONS))
for имя, причина in sorted(PRIVACY_NOT_PERSONAL.items()):
    print("  вне перечня: %-14s — %s" % (имя, причина))

print("")
if расхождения:
    print("РАСХОЖДЕНИЯ (%d):" % len(расхождения))
    for с in расхождения:
        print("  -", с)
    sys.exit(1)

print("Все таблицы с пользовательскими данными названы в политике.")

def флаги(путь):
    """Флаги пробы БЕЗ значения. Параметр (`--база X`) не флаг: запуск
    без значения дал бы отказ argparse, то есть ложную находку."""
    with io.open(путь, encoding="utf-8", errors="replace") as ф:
        текст = ф.read()
    try:
        дерево = ast.parse(текст)
    except SyntaxError:
        return []           # файл не разбирается — это сама находка
    флаг, параметр = set(), set()
    for у in ast.walk(дерево):
        if (isinstance(у, ast.Call) and isinstance(у.func, ast.Attribute)
                and у.func.attr == "add_argument"):
            имена = [a.value for a in у.args
                     if isinstance(a, ast.Constant) and isinstance(a.value, str)
                     and a.value.startswith("--")]
            это_флаг = any(
                k.arg == "action" and isinstance(k.value, ast.Constant)
                and k.value.value in ("store_true", "store_false", "count")
                for k in у.keywords)
            for и in имена:
                (флаг if это_флаг else параметр).add(и)
        # `"--x" in sys.argv` — КАНДИДАТ в флаги, а не флаг
        if (isinstance(у, ast.Compare) and isinstance(у.left, ast.Constant)
                and isinstance(у.left.value, str)
                and у.left.value.startswith("--")
                and any(isinstance(о, ast.In) for о in у.ops)):
            флаг.add(у.left.value)
        # `sys.argv.index("--x") + 1` — ПАРАМЕТР, даже если рядом стоит
        # `"--x" in sys.argv`. Первый прогон дал 39 находок `IndexError:
        # list index out of range` — и все ЛОЖНЫЕ: проверка запускала
        # параметр без значения. Проба, врущая в трети находок,
        # перестаёт читаться (§6.0.2, довод проверки 4).
        if (isinstance(у, ast.Call) and isinstance(у.func, ast.Attribute)
                and у.func.attr == "index" and у.args
                and isinstance(у.args[0], ast.Constant)
                and isinstance(у.args[0].value, str)
                and у.args[0].value.startswith("--")):
            параметр.add(у.args[0].value)
    # ПОДЛОГИ НЕ ГОНЯЕМ, И ЭТО НАЙДЕНО НА СЕБЕ. Контроль правит
    # ИСХОДНИК (`main.py`, css, шаблон) и возвращает его в `finally` —
    # а обрыв по потолку `finally` не исполняет. Первый полный прогон
    # ОСТАВИЛ `main.py` СЛОМАННЫМ (`IndentationError` на строке подлога
    # `check_db_hold`), и следом 88 проб честно упали на его импорте.
    # У контролей свой запускатель — `run_controls.py`, он ждёт их
    # до конца; цена названа: «стартует ли контроль», эта проверка
    # не спрашивает.
    return sorted(ф for ф in (флаг - параметр)
                  if not ф.startswith("--контроль"))



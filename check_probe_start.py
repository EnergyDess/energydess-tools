def _сторож_взять(тихо=False):
    """Эталон — состояние ДО прогона. Оно же и БЕРЁТСЯ с диска, значит
    мусор, оставшийся от ПРЕДЫДУЩЕГО оборванного прогона, закрепится
    как «норма»: ровно это и случилось — эндпоинты `/проба-подлога`
    от контроля `check_db_hold` попали в эталон, и проверка 27 нашла
    их уже В РЯДУ, а не здесь.

    Поэтому расхождение с HEAD НАЗЫВАЕТСЯ строкой. Не запрет: `main.py`
    бывает законно изменён работой, и объявлять это находкой значило бы
    краснеть на каждой правке."""
    try:
        _эталон[0] = io.open(os.path.join(КОРЕНЬ, СТОРОЖИТЬ), "rb").read()
    except OSError:
        _эталон[0] = None
        return
    if тихо:
        return
    try:
        п = subprocess.run(["git", "diff", "--numstat", "--", СТОРОЖИТЬ],
                           capture_output=True, text=True, cwd=КОРЕНЬ,
                           timeout=20)
        строки = (п.stdout or "").split()
        if строки and (строки[0] != "0" or строки[1] != "0"):
            print("  ВНИМАНИЕ: %s отличается от HEAD (+%s/-%s строк). "
                  "Если это остаток оборванного подлога — верните его "
                  "ДО прогона, иначе он закрепится как эталон."
                  % (СТОРОЖИТЬ, строки[0], строки[1]), flush=True)
    except (OSError, subprocess.SubprocessError):
        pass


def _сторож_сверить():
    """True — файл цел. Изменён: возвращается эталон и говорится вслух."""
    if _эталон[0] is None:
        return True
    путь = os.path.join(КОРЕНЬ, СТОРОЖИТЬ)
    try:
        сейчас = io.open(путь, "rb").read()
    except OSError:
        return True
    if сейчас == _эталон[0]:
        return True
    io.open(путь, "wb").write(_эталон[0])
    return False


def прогнать(путь, флаг=None):
    """(вид, подробность, секунды) — один запуск."""
    команда = [sys.executable, путь] + ([флаг] if флаг else [])
    начало = time.monotonic()
    try:
        п = subprocess.run(команда, capture_output=True, text=True,
                           errors="replace", timeout=ПОТОЛОК,
                           env=_окружение(), cwd=КОРЕНЬ)
    except subprocess.TimeoutExpired:
        return "НЕ УСПЕЛА", "потолок %d с" % ПОТОЛОК, time.monotonic() - начало
    except OSError as e:
        return "УПАЛА-СВОЙ-КОД", "не запустился: %s" % e, time.monotonic() - начало
    вид, подробность = _исход(п)
    return вид, подробность, time.monotonic() - начало


def задания(быстро):
    """[(файл, флаг|None)] — что гнать."""
    сп = []
    for п in пробы():
        if (п, None) not in ОПАСНЫЕ:
            сп.append((п, None))
        if быстро:
            continue
        for ф in флаги(п):
            # ОПАСНОСТЬ БАЗОВОГО РЕЖИМА НАКРЫВАЕТ ВСЕ ФЛАГИ. Первая
            # версия исключала `run_controls.py` без ключей, а `--всё`
            # пропускала — и он оставил подлог в `main.py` ровно тем же
            # способом. Проба, опасная сама по себе, не становится
            # безопасной от ключа.
            if (п, ф) in ОПАСНЫЕ or (п, None) in ОПАСНЫЕ:
                continue
            сп.append((п, ф))
    return сп


def _журнал_прочитать():
    try:
        return json.loads(io.open(ЖУРНАЛ, encoding="utf-8").read())
    except (OSError, ValueError):
        return {}


def отметить(имя):
    """ОТМЕТКА ОБ УСПЕШНОМ ПРОГОНЕ. Пишет ТОТ, КТО ПРОГНАЛ: «дата
    успешного прогона» — свойство прогона, а не файла на диске."""
    ж = _журнал_прочитать()
    ж[имя] = time.strftime("%Y-%m-%d %H:%M")
    try:
        io.open(ЖУРНАЛ, "w", encoding="utf-8").write(
            json.dumps(ж, ensure_ascii=False, indent=1, sort_keys=True))
    except OSError:
        pass


def показать_журнал():
    ж = _журнал_прочитать()
    все = пробы()
    print("КОГДА КАЖДАЯ ПРОБА ПРОГОНЯЛАСЬ УСПЕШНО В ПОСЛЕДНИЙ РАЗ")
    print("=" * 72)
    if not ж:
        print("  ЖУРНАЛ ПУСТ — ни одного прогона через запускатель.")
        print("  Это НЕ «пробы не гонялись»: ручной прогон сюда не пишется.")
        return 0
    нет = [и for и in все if и not in ж]
    # ВОЗРАСТ ЧИСЛОМ, А НЕ ДАТОЙ. «Не гонялась десять дней» — вопрос,
    # ради которого журнал и заведён (BACKLOG №307, A4); дата отвечает
    # на него только вместе с сегодняшним числом в голове читающего.
    сейчас = time.time()
    for имя in sorted(ж, key=lambda к: ж[к]):
        try:
            дней = int((сейчас - time.mktime(
                time.strptime(ж[имя], "%Y-%m-%d %H:%M"))) // 86400)
            возраст = "%d дн. назад" % дней if дней else "сегодня"
        except ValueError:
            возраст = "?"
        print("  %-34s %s  %s" % (имя, ж[имя], возраст))
    print("\n  без отметки: %d из %d" % (len(нет), len(все)))
    for и in нет[:40]:
        print("    %s" % и)
    return 0


def прогон(быстро=False, тихо=False):
    """{вид: [(файл, флаг, подробность, секунды)]}"""
    сп = задания(быстро)
    _сторож_взять(тихо=тихо)
    итог = {}
    сделано = [0]
    if not тихо:
        print("Запусков: %d (потолок %d с, потоков %d)"
              % (len(сп), ПОТОЛОК, ПОТОК), flush=True)

    def один(з):
        путь, флаг = з
        вид, подр, сек = прогнать(путь, флаг)
        if not _сторож_сверить():
            # ВИНОВНИК НАЗВАН ТОЧНО, потому что пишущие пробы идут
            # В ОДИН ПОТОК (разбор — у `пишет_в_файл`)
            вид = "НЕ УБРАЛА ЗА СОБОЙ"
            подр = "оставила правку в %s (возвращён из эталона)" % СТОРОЖИТЬ
        сделано[0] += 1
        if not тихо and сделано[0] % 50 == 0:
            print("  … %d из %d" % (сделано[0], len(сп)), flush=True)
        return путь, флаг, вид, подр, сек

    # ПИШУЩИЕ — ПОСЛЕДОВАТЕЛЬНО И ПОСЛЕ ОСТАЛЬНЫХ. Без этого сторож
    # называет виновником того, кто просто завершился первым.
    пишут = {п for п, _ in сп if пишет_в_файл(п)}
    парал = [з for з in сп if з[0] not in пишут]
    один_за_другим = [з for з in сп if з[0] in пишут]
    if not тихо:
        print("  из них пишут в файлы (в один поток): %d"
              % len(один_за_другим), flush=True)

    with ThreadPoolExecutor(max_workers=ПОТОК) as пул:
        for путь, флаг, вид, подр, сек in пул.map(один, парал):
            итог.setdefault(вид, []).append((путь, флаг, подр, сек))
    for з in один_за_другим:
        путь, флаг, вид, подр, сек = один(з)
        итог.setdefault(вид, []).append((путь, флаг, подр, сек))
    return итог


def напечатать(итог):
    # СОРТИРОВКА ПО КЛЮЧУ, А НЕ ПО КОРТЕЖУ: флаг бывает `None`,
    # и голый `sorted` падал `TypeError` — то есть проверка против
    # падающих проб падала сама, ПОСЛЕ всех замеров и до печати.
    _ключ = lambda з: (з[0], з[1] or "")
    свои = sorted(итог.get("УПАЛА-СВОЙ-КОД", []), key=_ключ)
    внеш = sorted(итог.get("УПАЛА-ВНЕШНЕЕ", []), key=_ключ)
    ок = итог.get("СТАРТОВАЛА", []) + итог.get("НЕ УСПЕЛА", [])
    print("\nПРОБЫ, ПАДАЮЩИЕ ДО ПЕРВОГО ЗАМЕРА")
    print("=" * 72)
    print("  стартовали:          %d" % len(ок))
    print("  УПАЛИ (свой код):    %d   <- находки" % len(свои))
    print("  упали (внешнее):     %d   <- долг: обязаны говорить ПРОПУСК"
          % len(внеш))
    мусор = sorted(итог.get("НЕ УБРАЛА ЗА СОБОЙ", []), key=_ключ)
    print("  НЕ УБРАЛИ ЗА СОБОЙ:  %d   <- находки: подлог остался в %s"
          % (len(мусор), СТОРОЖИТЬ))
    if мусор:
        print(chr(10) + "  НАХОДКИ — проба оставила правку исходника:")
        for путь, флаг, подр, _ in мусор:
            print("    %-34s %-18s %s" % (путь, флаг or "(без ключей)", подр))
    if свои:
        print("\n  НАХОДКИ — падение в НАШЕМ коде:")
        for путь, флаг, подр, _ in свои:
            print("    %-34s %-18s %s" % (путь, флаг or "(без ключей)", подр))
    if внеш:
        print("\n  ДОЛГ — трасса вместо слова «ПРОПУСК» (внешнего мира нет):")
        for путь, флаг, подр, _ in внеш[:60]:
            print("    %-34s %-18s %s" % (путь, флаг or "(без ключей)", подр))
        if len(внеш) > 60:
            print("    … ещё %d" % (len(внеш) - 60))
    return 1 if (свои or мусор) else 0


def контроль():
    """ПОДЛОГ: проба ломается так, что падает ДО ПЕРВОГО ЗАМЕРА.

    Доказательство НЕЗАВИСИМО от вердикта: прямой запуск сломанной пробы
    обязан дать трассу `NameError`, а починенной — не дать. Иначе
    «проверка нашла» неотличимо от «проверка всегда находит».
    """
    жертва = "check_shell_names.py"
    исходный = io.open(жертва, "rb").read()
    print("КОНТРОЛЬ ПРОВЕРКИ 35")
    print("=" * 72)
    чисто = прогнать(жертва)
    print("  чисто:         %-16s %s" % (чисто[0], чисто[1]))
    нашла = False
    with_подлогом = ("", "", 0)
    try:
        текст = исходный.decode("utf-8")
        якорь = "def проверить("
        if текст.count(якорь) != 1:
            raise SystemExit("ОСТАНОВЛЕНО: якорь найден %d раз"
                             % текст.count(якорь))
        сломанный = текст.replace(
            якорь, "ИМЯ_КОТОРОГО_НЕТ()" + chr(10) * 3 + якорь, 1)
        io.open(жертва, "wb").write(сломанный.encode("utf-8"))
        with_подлогом = прогнать(жертва)
        print("  с подлогом:    %-16s %s" % (with_подлогом[0], with_подлогом[1]))
        итог = прогон(быстро=True, тихо=True)
        нашла = any(п == жертва for п, _, _, _ in итог.get("УПАЛА-СВОЙ-КОД", []))
        print("  ряд назвал жертву находкой: %s" % ("ДА" if нашла else "НЕТ"))
    finally:
        io.open(жертва, "wb").write(исходный)
    после = прогнать(жертва)
    print("  после отката:  %-16s %s" % (после[0], после[1]))
    плохо = (чисто[0] == "УПАЛА-СВОЙ-КОД"
             or with_подлогом[0] != "УПАЛА-СВОЙ-КОД"
             or not нашла
             or после[0] == "УПАЛА-СВОЙ-КОД")
    print("\n  ДОКАЗАТЕЛЬСТВО: подлог изменил исход %s -> %s -> %s"
          % (чисто[0], with_подлогом[0], после[0]))
    print("  КОНТРОЛЬ: %s" % ("НЕ ПРОЙДЕН" if плохо else "ПРОЙДЕН"))
    return 1 if плохо else 0


def main():
    if "--журнал" in sys.argv:
        return показать_журнал()
    if "--контроль" in sys.argv:
        return контроль()
    быстро = "--быстро" in sys.argv
    итог = прогон(быстро)
    код = напечатать(итог)
    for путь, флаг, _, _ in (итог.get("СТАРТОВАЛА", [])
                             + итог.get("НЕ УСПЕЛА", [])):
        if флаг is None:
            отметить(путь)
    return код


if __name__ == "__main__":
    sys.exit(main())

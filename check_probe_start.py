def имена_адреса_стенда():
    """Имена переменных окружения, которыми пробам задают адрес стенда.

    ВЫВОДЯТСЯ, А НЕ ПЕРЕЧИСЛЯЮТСЯ (§6.0.7). Их ШЕСТЬ, и перечень
    из одного `HOVER_BASE` стоил мусора на стенде: `check_ens_admin_ui`
    читает своё `ENS_ADMIN_BASE`, пошёл на ЖИВОЙ стенд, был оборван
    по потолку — и оставил там пробные сеты, которые нашла уже
    проверка 24 (`zz_proba_137`, `zz_ui_url`).

    Признак: `os.environ.get("ИМЯ", "http://127.0.0.1:<порт>")`.
    """
    имена = set()
    образец = re.compile(
        "os[.]environ[.]get[(]" + chr(92) + "s*[" + chr(34) + chr(39) + "]"
        "([^" + chr(34) + chr(39) + "]+)[" + chr(34) + chr(39) + "]"
        + chr(92) + "s*,"+ chr(92) + "s*"
        "[" + chr(34) + chr(39) + "]http://127[.]0[.]0[.]1:" + chr(92) + "d+")
    for путь in пробы():
        try:
            with io.open(путь, encoding="utf-8", errors="replace") as ф:
                текст = ф.read()
        except OSError:
            continue
        имена.update(образец.findall(текст))
    return sorted(имена)


def пишет_в_файл(путь):
    """Открывает ли проба хоть какой-то файл НА ЗАПИСЬ. Разбор дерева,
    не греп: строка «main.py» в комментарии записью не является.

    ЗАЧЕМ. Такие пробы гонятся В ОДИН ПОТОК, и это не осторожность:
    при параллельном прогоне расхождение видит ТОТ, кто завершился,
    а правил его СОСЕД. Первая версия сторожа назвала виновными
    `shots_medkit_190` и `193`, вторая — `shots_medkit_263`; все три
    поодиночке ЧИСТЫ. Подтверждение «одиночным перегоном» тоже не
    помогло — перегон шёл при работающих соседях, то есть одиночным
    не был.
    """
    try:
        with io.open(путь, encoding="utf-8", errors="replace") as ф:
            дерево = ast.parse(ф.read())
    except (OSError, SyntaxError):
        return True          # не разобрали — считаем пишущей, это дешевле
    for у in ast.walk(дерево):
        if not isinstance(у, ast.Call):
            continue
        имя = getattr(у.func, "attr", None) or getattr(у.func, "id", None)
        if имя in ("write_text", "write_bytes"):
            return True
        if имя == "open":
            режимы = [a.value for a in у.args
                      if isinstance(a, ast.Constant) and isinstance(a.value, str)]
            if any("w" in р or "a" in р or "+" in р for р in режимы):
                return True
        # ЗАПУСКАЕТ ДРУГОЙ ПРОЦЕСС — ТОЖЕ «ПИШУЩАЯ», И ЭТО ЗАМЕР.
        # Сама она файлов не трогает, а ЗАПУЩЕННАЯ ею проба трогает;
        # убитая по потолку, она оставляет дочерний процесс, и тот
        # дописывает `main.py` УЖЕ ПОСЛЕ её смерти — сторож ловит
        # расхождение у СЛЕДУЮЩЕЙ пробы и называет не того.
        # Так `enshrouded_cutout --оценка` и `shots_medkit_263`
        # числились виновными дважды, будучи чистыми поодиночке.
        if имя in ("run", "Popen", "call", "check_call", "check_output"):
            return True
    return False



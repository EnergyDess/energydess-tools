def _исход(п):
    """(вид, подробность) по завершившемуся процессу."""
    хвост = (п.stderr or "").strip()
    # ОШИБКА КОМПИЛЯЦИИ ИДЁТ БЕЗ СЛОВА `Traceback`, и первый же прогон
    # это нашёл: `shots_medkit_181.py` не разбирается вовсе, а признак
    # «есть трасса» его ПРОПУСКАЛ. Проверка, слепая к самому громкому
    # виду падения, хуже отсутствующей.
    сломан_разбор = bool(re.search(r"^(SyntaxError|IndentationError|TabError)",
                                   хвост, re.M))
    if "Traceback (most recent call last)" not in хвост and not сломан_разбор:
        return "СТАРТОВАЛА", ""
    строки = [с for с in хвост.splitlines() if с.strip()]
    подробность_сырая = строки[-1] if строки else ""
    имя = ""
    for с in reversed(строки):
        m = _ТРАССА.match(с.strip())
        if m:
            имя = m.group(1)
            break
    # ПРИЗНАК ВНЕШНЕГО — У СЛОЯ, А НЕ ВТОРОЙ СПИСОК ЗДЕСЬ. Разойдись
    # они, проверка числила бы долгом то, что слой всё равно не поймает,
    # — то есть печатала бы недостижимый долг (§6.0.7). Слой отвечает
    # по типу и тексту; сюда приходит только имя типа и последняя
    # строка, поэтому спрашиваем его тем же, чем располагаем.
    вид = ("УПАЛА-ВНЕШНЕЕ" if pg.внешнее_по_имени(имя, подробность_сырая)
           else "УПАЛА-СВОЙ-КОД")
    if имя == "SystemExit":
        вид = "СТАРТОВАЛА"    # `raise SystemExit("ОСТАНОВЛЕНО: …")` — слово
    return вид, подробность_сырая[:150]



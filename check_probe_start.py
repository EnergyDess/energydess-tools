def контроль():
    """ПОДЛОГ: проба ломается так, что падает ДО ПЕРВОГО ЗАМЕРА.

    Доказательство НЕЗАВИСИМО от вердикта: прямой запуск сломанной пробы
    обязан дать трассу `NameError`, а починенной — не дать. Иначе
    «проверка нашла» неотличимо от «проверка всегда находит».
    """
    жертва = "check_shell_names.py"
    исходный = io.open(жертва, "rb").read()
    print("КОНТРОЛЬ ПРОВЕРКИ 35")
    print("=" * 72)
    чисто = прогнать(жертва)
    print("  чисто:         %-16s %s" % (чисто[0], чисто[1]))
    нашла = False
    with_подлогом = ("", "", 0)
    try:
        текст = исходный.decode("utf-8")
        якорь = "def проверить("
        if текст.count(якорь) != 1:
            raise SystemExit("ОСТАНОВЛЕНО: якорь найден %d раз"
                             % текст.count(якорь))
        сломанный = текст.replace(
            якорь, "ИМЯ_КОТОРОГО_НЕТ()" + chr(10) * 3 + якорь, 1)
        io.open(жертва, "wb").write(сломанный.encode("utf-8"))
        with_подлогом = прогнать(жертва)
        print("  с подлогом:    %-16s %s" % (with_подлогом[0], with_подлогом[1]))
        итог = прогон(быстро=True, тихо=True)
        нашла = any(п == жертва for п, _, _, _ in итог.get("УПАЛА-СВОЙ-КОД", []))
        print("  ряд назвал жертву находкой: %s" % ("ДА" if нашла else "НЕТ"))
    finally:
        io.open(жертва, "wb").write(исходный)
    после = прогнать(жертва)
    print("  после отката:  %-16s %s" % (после[0], после[1]))
    плохо = (чисто[0] == "УПАЛА-СВОЙ-КОД"
             or with_подлогом[0] != "УПАЛА-СВОЙ-КОД"
             or not нашла
             or после[0] == "УПАЛА-СВОЙ-КОД")
    print("\n  ДОКАЗАТЕЛЬСТВО: подлог изменил исход %s -> %s -> %s"
          % (чисто[0], with_подлогом[0], после[0]))
    print("  КОНТРОЛЬ: %s" % ("НЕ ПРОЙДЕН" if плохо else "ПРОЙДЕН"))
    return 1 if плохо else 0


def контроль_стенда():
    """ПОДЛОГ СТОРОЖА СТЕНДА: в набор запусков возвращается `--очистить`.

    Всё идёт на ПЕРЕСЕЯННОЙ КОПИИ (`DB_PATH`), стенд не трогается.
    Доказательство НЕЗАВИСИМО от вердикта: позиции аптечки на копии
    считаются прямым запросом, а не `посев_счёт` сторожа. Обратный
    случай обязателен: тот же набор без опасного запуска обязан дать
    убыль 0 — иначе «сторож нашёл» неотличимо от «сторож находит всегда».
    """
    import shutil
    import sqlite3
    import tempfile
    global задания
    каталог = tempfile.mkdtemp(prefix="stand_ctl_")
    копия = os.path.join(каталог, "app.db")
    прежний_db = os.environ.get("DB_PATH")
    прежние_задания = задания
    безвредные = [("backlog_open.py", None), ("check_shell_names.py", None)]

    def позиций():
        c = sqlite3.connect("file:%s?mode=ro" % копия, uri=True)
        try:
            return c.execute("SELECT COUNT(*) FROM medkit_items").fetchone()[0]
        finally:
            c.close()

    def пересеять():
        env = dict(os.environ)
        env["DB_PATH"] = копия
        subprocess.run([sys.executable, "-c",
                        "from database import init_db, migrate_db; init_db(); "
                        "migrate_db(); import main; main._import_exercises_if_empty()"],
                       capture_output=True, timeout=300, env=env, cwd=КОРЕНЬ)
        subprocess.run([sys.executable, "make_local_user.py", "--seed"],
                       capture_output=True, timeout=300, env=env, cwd=КОРЕНЬ)

    print("КОНТРОЛЬ СТОРОЖА СТЕНДА (на копии %s)" % копия)
    print("=" * 72)
    плохо = False
    try:
        os.environ["DB_PATH"] = копия
        for имя, набор in (("чисто", безвредные),
                           ("подлог", безвредные
                            + [("check_medkit_assist.py", "--очистить")])):
            пересеять()
            до = позиций()
            задания = lambda быстро, н=набор: list(н)
            итог = прогон(быстро=True, тихо=True)
            после = позиций()
            виновные = sorted({"%s %s" % (п, ф or "") for п, ф, _, _
                               in итог.get("ИСПОРТИЛА СТЕНД", [])})
            print("  %-7s позиций %d -> %d · убыль у сторожа %d раз · виновные: %s"
                  % (имя, до, после, len(_стенд["убыль"]), виновные or "нет"))
            if имя == "чисто":
                плохо |= (после != до or bool(_стенд["убыль"]) or bool(виновные))
            else:
                плохо |= not (после < до and
                              виновные == ["check_medkit_assist.py --очистить"])
    finally:
        задания = прежние_задания
        if прежний_db is None:
            os.environ.pop("DB_PATH", None)
        else:
            os.environ["DB_PATH"] = прежний_db
        shutil.rmtree(каталог, ignore_errors=True)
    print("  КОНТРОЛЬ: %s" % ("НЕ ПРОЙДЕН" if плохо else "ПРОЙДЕН"))
    return 1 if плохо else 0



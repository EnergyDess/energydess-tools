def _стенд_счёт(путь):
    import sqlite3
    import check_stand_state as css
    c = sqlite3.connect("file:%s?mode=ro" % путь, uri=True)
    try:
        return css.посев_счёт(c, путь)
    finally:
        c.close()


def _стенд_взять(тихо=False):
    _стенд.update({"база": None, "видели": {}, "интервалы": [], "убыль": []})
    # ТА ЖЕ БАЗА, ЧТО У ПРОБ: они берут `DB_PATH` из унаследованного
    # окружения, и сторож, читающий другую, молчал бы про их запись
    путь = os.path.abspath(os.environ.get("DB_PATH") or os.path.join(КОРЕНЬ, "app.db"))
    if not os.path.exists(путь):
        if not тихо:
            print("  СТОРОЖ СТЕНДА: базы стенда нет — убыль спросить нечем",
                  flush=True)
        return
    try:
        было = _стенд_счёт(путь)
    except Exception as e:        # сторож не имеет права ронять проверку
        if not тихо:
            print("  СТОРОЖ СТЕНДА: не снят (%s) — убыль спросить нечем" % e,
                  flush=True)
        return
    _стенд.update({"база": путь, "видели": dict(было),
                   "чистая": time.monotonic()})
    if not тихо:
        print("  СТОРОЖ СТЕНДА: ключей посева на старте %d" % len(было),
              flush=True)


def _стенд_сверить(задание, начало, конец):
    """Записывает интервал запуска и новую убыль, если она есть."""
    if _стенд["база"] is None:
        return
    _стенд["интервалы"].append((задание, начало, конец))
    try:
        сейчас = _стенд_счёт(_стенд["база"])
    except Exception:
        return
    новая = {к: (n, сейчас.get(к, 0)) for к, n in _стенд["видели"].items()
             if сейчас.get(к, 0) < n}
    момент = time.monotonic()
    if новая:
        _стенд["убыль"].append((_стенд["чистая"], момент, новая))
        for к, (_, стало) in новая.items():
            _стенд["видели"][к] = стало
    _стенд["чистая"] = момент



# Общеизвестные препараты, которых в аптечке владельца НЕТ (§8.0).
# Разметка повторяет форму настоящей страницы: описание первой строкой,
# блок действующего вещества — как у источника
СТРАНИЦА_ИБУПРОФЕН = (
    "<html><body><p>Ибупрофен таблетки, покрытые оболочкой, 200 мг: "
    "10, 20 шт. - справочник препаратов</p>"
    "<p>Активное вещество: Ибупрофен</p></body></html>")

СТРАНИЦА_ЛАЗОЛВАН = (
    "<html><body><p>Лазолван раствор для приема внутрь и ингаляций "
    "15 мг/2 мл - справочник препаратов</p>"
    "<p>Активное вещество: Амброксол</p></body></html>")


class Поз:
    """Позиция без базы: спрашивается запись в поля, а не ORM."""

    def __init__(self, **кв):
        for к, з in кв.items():
            setattr(self, к, з)

    def __getattr__(self, имя):
        return None


def _подсказки(страница):
    """Тот же путь, что на бою: `_апт_подсказки_страницы`."""
    return main._апт_подсказки_страницы(страница)


# ═══════════════════════════════════════════════════════════════════
# СЛУЧАЙ 1: ВЕЩЕСТВО СО СТРАНИЦЫ ДРУГОГО ПРЕПАРАТА
# ═══════════════════════════════════════════════════════════════════

def случай_чужое_вещество(подлог=False):
    """Страница выбрана сопоставлением; вещество берётся ИЗ НЕЁ ЖЕ.

    ПОДЛОГ подменяет источник подсказки — берёт вещество со страницы
    другого препарата, как если бы кто-то завёл второй запрос
    за веществом. Обязано быть поймано тем, что подсказка приходит
    ОДНИМ кортежем со схемой и из одной страницы.
    """
    наша_страница = СТРАНИЦА_ИБУПРОФЕН
    чужая = СТРАНИЦА_ЛАЗОЛВАН

    if подлог:
        # Второй источник вещества — ровно то, чего быть не должно
        подсказка = _подсказки(чужая)
    else:
        подсказка = _подсказки(наша_страница)

    поз = Поз(form="tablet", name="Ибупрофен")
    main._апт_записать_итог_доз(
        поз, ("схема", "https://x/ibuprofen", None, "", None), "", "",
        подсказка)

    вещество_страницы = дозы.вещество_страницы(наша_страница)
    доказательство = ("в колонке %r, на НАШЕЙ странице %r"
                      % (поз.dosage_hint_substance, вещество_страницы))
    совпало = (поз.dosage_hint_substance or "") == (вещество_страницы or "")
    return совпало, доказательство


# ═══════════════════════════════════════════════════════════════════
# СЛУЧАЙ 2: ПОДСТАНОВКА БЕЗ НАЖАТИЯ ЧЕЛОВЕКА
# ═══════════════════════════════════════════════════════════════════

def случай_без_нажатия(подлог=False):
    """Запись итога поиска НЕ ИМЕЕТ ПРАВА трогать `substance` и `form`.

    ПОДЛОГ делает ровно это — кладёт подсказку прямо в поля карточки,
    как если бы кто-то решил «подставить верное молча». Обязано быть
    поймано: поля владельца меняет только нажатие.
    """
    подсказка = _подсказки(СТРАНИЦА_ЛАЗОЛВАН)
    поз = Поз(form="syrup", unit="ml", name="Лазолван",
              substance="")

    main._апт_записать_итог_доз(
        поз, None, "не подошло", "выпуски", подсказка)

    if подлог:
        # МОЛЧАЛИВАЯ ПОДСТАНОВКА — то, что запрещено (B.2)
        поз.substance = поз.dosage_hint_substance
        поз.form = поз.dosage_hint_form

    чисто = ((поз.substance or "") == ""
             and поз.form == "syrup")
    доказательство = ("substance=%r form=%r; подсказки: вещество=%r "
                      "форма=%r" % (поз.substance, поз.form,
                                    поз.dosage_hint_substance,
                                    поз.dosage_hint_form))
    return чисто, доказательство


# ═══════════════════════════════════════════════════════════════════
# СЛУЧАЙ 3: ВЫДУМАННОЕ ИМЯ НЕ ДАЁТ СТРАНИЦЫ (заслон №205)
# ═══════════════════════════════════════════════════════════════════

def случай_выдуманное_имя(подлог=False):
    """Заслон существования стоит ДО сбора адресов и выводится
    из ТОЙ ЖЕ выдачи, что список страниц (§5.8, задача 205).

    ПОДЛОГ ЗАМЕНЯЕТ ЗАСЛОН НЕРАЗДЕЛЯЮЩИМ ПРИЗНАКОМ — «в теле есть
    слово „препарат“», — а не выключает его. Выключить и убедиться,
    что всё прошло, доказывало бы лишь, что `True` истинно; а вот
    признак, стоящий и на странице «ничего не найдено», обязан
    пропустить выдуманное имя, и проба обязана это увидеть.

    Ровно на таком признаке отсеялись Горздрав, ГЭОТАР и РЛС.
    """
    # Выдача по ВЫДУМАННОМУ имени: слово «препарат» есть, карточек нет
    пусто = ("<html><body><p>По запросу ничего не найдено. "
             "Препарат с таким названием отсутствует.</p></body></html>")

    if подлог:
        # НЕРАЗДЕЛЯЮЩИЙ ПРИЗНАК вместо боевого заслона
        знает = "препарат" in пусто.lower()
        чем = "подложный признак «в теле есть слово препарат»"
    else:
        знает = дозы.справочник_знает(пусто)
        чем = "боевой `справочник_знает`"

    # ЧИСТО = выдуманное имя ОТВЕРГНУТО
    чисто = not знает
    доказательство = ("%s на выдаче без карточек: %r" % (чем, знает))
    return чисто, доказательство


# ═══════════════════════════════════════════════════════════════════
# СЛУЧАЙ 4 (ОБРАТНЫЙ): ЗАКОННАЯ ПОДСТАНОВКА ОБЯЗАНА ПРОЙТИ
# ═══════════════════════════════════════════════════════════════════

def случай_законная_подстановка(подлог=False):
    """Форма выведена однозначно — предложение обязано появиться.

    ПОДЛОГ ослепляет вывод формы (как если бы синонимы отстали от
    списка форм). Без этого случая проба, отвергающая всё подряд,
    прошла бы первые три и не значила бы ничего.
    """
    if подлог:
        сохранённые = dict(дозы.СИНОНИМЫ_ФОРМ)
        дозы.СИНОНИМЫ_ФОРМ.clear()
    try:
        подсказка = _подсказки(СТРАНИЦА_ЛАЗОЛВАН)
        поз = Поз(form="syrup", name="Лазолван")
        main._апт_записать_итог_доз(
            поз, None, "не подошло", "выпуски", подсказка)
        есть = bool(поз.dosage_hint_form)
        доказательство = ("подсказка формы %r, слово %r"
                          % (поз.dosage_hint_form,
                             поз.dosage_hint_form_word))
    finally:
        if подлог:
            дозы.СИНОНИМЫ_ФОРМ.update(сохранённые)
    return есть, доказательство


СЛУЧАИ = [
    ("вещество-с-чужой-страницы", случай_чужое_вещество),
    ("подстановка-без-нажатия", случай_без_нажатия),
    ("выдуманное-имя-не-даёт-страницы", случай_выдуманное_имя),
    ("ОБРАТНЫЙ:законная-подстановка", случай_законная_подстановка),
]


def главная():
    контроль = "--контроль" in sys.argv
    print("=" * 72)
    print("ПОДСТАНОВКА ИЗ СПРАВОЧНИКА — %s"
          % ("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ" if контроль else "ПРОХОД"))
    print("=" * 72)
    if контроль:
        print("Каждый подлог ОБЯЗАН быть найден. Рядом — независимое")
        print("ДОКАЗАТЕЛЬСТВО того, что подлог состоялся (§6.0.3).")
    print()

    плохо = 0
    for имя, fn in СЛУЧАИ:
        чисто_без, док_без = fn(подлог=False)
        if not контроль:
            метка = "OK  " if чисто_без else "ПЛОХО"
            print("  %s %-34s %s" % (метка, имя, док_без))
            if not чисто_без:
                плохо += 1
            continue

        чисто_с, док_с = fn(подлог=True)
        # ПОДЛОГ НАЙДЕН, если чистый прогон чист, а подложенный — нет
        найден = чисто_без and not чисто_с
        метка = "НАЙДЕН    " if найден else "НЕ НАЙДЕН "
        print("  %s %-34s" % (метка, имя))
        print("      чисто:  %s" % док_без)
        print("      подлог: %s" % док_с)
        if док_без == док_с:
            print("      ВНИМАНИЕ: доказательства СОВПАЛИ — подлог "
                  "не состоялся, вердикт ничего не значит")
        if not найден:
            плохо += 1

    print()
    print("  %s: %d из %d"
          % ("подлогов найдено" if контроль else "шагов чисто",
             len(СЛУЧАИ) - плохо, len(СЛУЧАИ)))
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(главная())

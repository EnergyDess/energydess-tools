# -*- coding: utf-8 -*-
"""СКОЛЬКО ПОЛЕЙ ДОБАВЛЯЕТ ПОДСТАНОВКА ИЗ СПРАВОЧНИКА (№239, B.7).

═══════════════════════════════════════════════════════════════════════
МЕРКА, код возврата всегда 0
═══════════════════════════════════════════════════════════════════════

«Сколько полей знает справочник» — свойство ЧУЖОГО сайта, и красный
тут значил бы «у них поменялось».

═══════════════════════════════════════════════════════════════════════
ЖИВЫХ ВЫЗОВОВ МОДЕЛИ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ
═══════════════════════════════════════════════════════════════════════

Постановка B.7 просит завести десять препаратов ТЕКСТОМ и сравнить
заполненность. Половина этого уже замерена и не здесь: сколько полей
разбирает модель из текста, печатает `check_medkit_entry.py`
(замер №232: по тексту домыслов 0 из 3, поля заполняются по сказанному).

Здесь спрашивается ДРУГАЯ половина, к модели отношения не имеющая:
**сколько полей может дать СПРАВОЧНИК** сверх того, что человек сказал
словами. Гонять ради этого живые вызовы значило бы платить кредитами
за ответ, который к вопросу не относится (§5.8, довод режима
`--маршрут` у `check_medkit_query`).

═══════════════════════════════════════════════════════════════════════
ЧТО СЧИТАЕТСЯ И ПОЧЕМУ ИМЕННО ТАК
═══════════════════════════════════════════════════════════════════════

    БЕЗ ПОДСТАНОВКИ  поля, названные во ВВОДЕ. Считается по самому
                     набору, а не по ответу модели: набор и есть то,
                     что человек сказал словами
    С ПОДСТАНОВКОЙ   те же плюс поля, которые предложил справочник
                     и которых во вводе НЕ БЫЛО
    СХЕМА            нашлась ли выдержка о дозировании

СОВПАВШЕЕ ПРЕДЛОЖЕНИЕ НЕ СЧИТАЕТСЯ ПРИБАВКОЙ: если справочник называет
вещество так же, как человек, вписывать нечего, и числить это выгодой
значило бы считать шум.

    py check_ref_gain.py            # весь набор
    py check_ref_gain.py --сколько 10
"""
import asyncio
import io
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
os.environ.setdefault("DB_PATH", "app.db")

import medkit_defs as опр                                # noqa: E402
import main                                              # noqa: E402

НАБОР = "medkit_new_batch.json"


class Поз:
    """Позиция без базы: боевому поиску нужны только поля."""

    def __init__(self, **кв):
        for к, з in кв.items():
            setattr(self, к, з)

    def __getattr__(self, имя):
        return None


def _сколько():
    if "--сколько" in sys.argv:
        return int(sys.argv[sys.argv.index("--сколько") + 1])
    return 10


async def главная():
    набор = json.load(io.open(НАБОР, encoding="utf-8"))[:_сколько()]
    print("=" * 74)
    print("ЧТО ДОБАВЛЯЕТ ПОДСТАНОВКА ИЗ СПРАВОЧНИКА (B.7)")
    print("=" * 74)
    print("препаратов в замере: %d (общеизвестные, в аптечке владельца"
          " их НЕТ — §8.0)" % len(набор))
    print()
    print("  %-22s %6s %7s %8s  %s"
          % ("препарат", "было", "стало", "схема", "что предложил справочник"))
    print("  " + "-" * 70)

    было_всего = стало_всего = со_схемой = 0
    предложено_вещество = предложено_форма = 0
    # СПИСКОМ, а не числом: замыкание в async-теле пишет в него
    стало_со_схемой = [0]

    for зап in набор:
        поз = Поз(name=зап.get("name", ""), form=зап.get("form", ""),
                  substance=(зап.get("substance") or "").strip(),
                  unit=зап.get("unit", ""))
        # ПОЛЯ, НАЗВАННЫЕ ВО ВВОДЕ. Название и форма есть всегда —
        # без них карточку не завести; считаем ВЕЩЕСТВО, потому что
        # ровно оно и решает, найдётся ли схема
        было = sum(1 for к in ("name", "form", "substance")
                   if (getattr(поз, к) or "").strip())

        итог, причина, вид, подсказка = await main._апт_найти_дозы(поз)
        в, ф, фс = main._апт_подсказки_разобрать(подсказка)

        # ПРИБАВКА — только то, чего во вводе НЕ БЫЛО либо что названо
        # ИНАЧЕ. Совпавшее предложение выгодой не является
        добавка = []
        if в and в.lower() != (поз.substance or "").lower():
            добавка.append("вещество «%s»" % в)
            предложено_вещество += 1
        if ф and ф != поз.form:
            имя = (опр.ФОРМА_ПО_ID.get(ф) or {}).get("имя", ф)
            добавка.append("форма «%s»" % имя)
            предложено_форма += 1

        стало = было + sum(1 for д in добавка
                           if д.startswith("вещество") and not поз.substance)
        схема = "ДА" if итог else "нет"
        со_схемой += 1 if итог else 0
        было_всего += было
        стало_всего += стало

        # ── ГЛАВНЫЙ ВОПРОС B.7: НАЙДЁТСЯ ЛИ СХЕМА ПОСЛЕ ПОДСТАНОВКИ ──
        #
        # Считать «сколько полей заполнено» мало: поле — средство,
        # а нужен человеку ОТВЕТ. Поэтому там, где справочник что-то
        # предложил, а схемы не было, поиск гоняется ЗАНОВО с уже
        # подставленными значениями — ровно так, как это произойдёт
        # после нажатия
        после = ""
        if добавка and not итог:
            вторая = Поз(name=поз.name, unit=поз.unit,
                         form=(ф or поз.form),
                         substance=(в or поз.substance))
            итог2, _, _, _ = await main._апт_найти_дозы(вторая)
            if итог2:
                после = "ПОСЛЕ ПОДСТАНОВКИ СХЕМА НАШЛАСЬ"
                стало_со_схемой[0] += 1
            else:
                после = "и после подстановки схемы нет"

        print("  %-22s %6d %7d %8s  %s"
              % (зап.get("name", "")[:22], было, стало, схема,
                 ", ".join(добавка) or "—"))
        if после:
            print("  %-22s %25s  %s" % ("", "", после))

    print()
    print("  ── ИТОГ ─────────────────────────────────────────────────")
    print("  полей заполнено БЕЗ подстановки:  %d" % было_всего)
    print("  полей заполнено С подстановкой:   %d" % стало_всего)
    print("  схема приёма нашлась у:           %d из %d"
          % (со_схемой, len(набор)))
    print("  ДОБАВИЛА ПОДСТАНОВКА:             %d (стало %d из %d)"
          % (стало_со_схемой[0], со_схемой + стало_со_схемой[0], len(набор)))
    print()
    print("  справочник предлагает ВЕЩЕСТВО у: %d" % предложено_вещество)
    print("  справочник предлагает ФОРМУ у:    %d" % предложено_форма)
    print()
    print("  Прибавкой считается только НЕСОВПАВШЕЕ предложение:")
    print("  вещество, названное так же, вписывать нечего.")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(главная()))

import os
import sqlite3
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
os.environ.setdefault("DB_PATH", "app.db")

import main                                              # noqa: E402
import probe_guard  # noqa: F401  ПРОПУСК вместо трассы (§6.0.1)


class Поз:
    """Строка базы как предмет: боевому признаку нужны три поля."""

    def __init__(self, ряд):
        self.dosage_hint_substance = ряд["dosage_hint_substance"]
        self.dosage_hint_form = ряд["dosage_hint_form"]
        self.substance = ряд["substance"]
        self.form = ряд["form"]


def главная():
    путь = "app.db"
    if "--база" in sys.argv:
        путь = sys.argv[sys.argv.index("--база") + 1]
    if "/data/" in путь.replace("\\", "/"):
        print("БОЕВАЯ БАЗА НЕ ОТКРЫВАЕТСЯ. Снимите копию и увезите.")
        return 0
    if not os.path.exists(путь):
        print("СПРОСИТЬ НЕЧЕМ: базы нет — %s" % путь)
        return 0

    c = sqlite3.connect("file:%s?mode=ro" % путь, uri=True)
    c.row_factory = sqlite3.Row
    ряды = list(c.execute("SELECT * FROM medkit_items"))
    print("=" * 72)
    print("ПРЕДЛОЖЕНИЯ ИЗ СПРАВОЧНИКА — %s" % путь)
    print("=" * 72)
    print("позиций: %d" % len(ряды))
    print()

    пв = пф = ов = оф = 0
    со_схемой_и_подсказкой = 0
    for р in ряды:
        поз = Поз(р)
        в_иначе, ф_иначе = main._апт_подсказка_иначе(поз)
        есть_в = bool((р["dosage_hint_substance"] or "").strip())
        есть_ф = bool((р["dosage_hint_form"] or "").strip())
        пв += есть_в
        пф += есть_ф
        ов += в_иначе
        оф += ф_иначе
        if (р["dosage_text"] or "").strip() and (есть_в or есть_ф):
            со_схемой_и_подсказкой += 1

    print("ВЕЩЕСТВО")
    print("  подсказка от справочника есть: %d" % пв)
    print("  показывается (значения различны): %d" % ов)
    print("  МОЛЧИМ (совпало — вписывать нечего): %d" % (пв - ов))
    print()
    print("ФОРМА")
    print("  подсказка от справочника есть: %d" % пф)
    print("  показывается (значения различны): %d" % оф)
    print("  МОЛЧИМ (совпало — вписывать нечего): %d" % (пф - оф))
    print()
    print("ПОЗИЦИЙ, ГДЕ НАЖАТИЕ КАСАЕТСЯ НАЙДЕННОЙ СХЕМЫ: %d"
          % со_схемой_и_подсказкой)
    print("  (до BACKLOG №244 у всех них схема стиралась целиком)")
    return 0


if __name__ == "__main__":
    sys.exit(главная())

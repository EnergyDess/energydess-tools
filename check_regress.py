                for поле, подпись in (("pad", "паддинг"), ("цвет", "цвет"),
                                      ("кегль", "кегль"), ("радиус", "радиус")):
                    if x[поле] != y[поле]:
                        справка.append(f"{подпись} {x[поле]} → {y[поле]}")

        # В код возврата по-прежнему не идёт: перечень тут для человека,
        # решение «регресс или переезд» машине не выводится.
        for подпись, словарь in (("ПРОПАЛИ из разметки", пропали),
                                 ("ПОЯВИЛИСЬ в разметке", появились)):
            if not словарь:
                continue
            всего = sum(словарь.values())
            верх = sorted(словарь.items(), key=lambda п: -п[1])[:12]
            print(f"     {подпись}: {всего} видимых элементов, "
                  f"классов {len(словарь)}")

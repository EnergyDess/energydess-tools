# ── ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ───────────────────────────────────────────────
# Пять подлогов, по одному на вид. Проверка обязана назвать ВСЕ пять:
# назвавшая четыре из пяти — сломана, и без этого контроля отличить её
# от исправной нечем.
#
# Экран контроля — `/profile`, а не лаунчер, и это не вкус: подлог вида
# ПОЛОЖЕНИЕ обязан быть ТЕМ САМЫМ дефектом, который проверка пропустила
# 2026-08-21, а элемент `absolute` есть именно там — кнопка в углу
# аватара. Остальные четыре подлога бьют по общей шапке и на `/profile`
# работают так же, как на лаунчере.
ПОДЛОГ = """
  .site-header { text-align: right !important; }          /* ВЫРАВНИВАНИЕ */
  .site-header { border-bottom: 0 !important; }           /* РАМКА */
  .header-logo { min-height: 200px !important; }          /* ВЫСОТА */
  .nav-logo-symbol { display: none !important; }          /* ВИДИМОСТЬ */
"""

# ТОТ САМЫЙ дефект, отдельным подлогом: `position: relative`, наложенный
# на элемент, который стоял `absolute`. Держится ОТДЕЛЬНО от четырёх выше,
# потому что от него требуется не только сработать самому, но и не дать
# остальным видам приписать себе ЭТОТ ЖЕ элемент.
ПОДЛОГ_ПОЛОЖЕНИЯ = ".avatar-upload-btn { position: relative !important; }"

# ВТОРОЙ подлог того же вида — ЧИСТЫЙ СДВИГ: элемент остаётся `absolute`,
# меняется только его место в контейнере. Нужен потому, что первый подлог
# ответить на вопрос «не срабатывает ли вид на всё подряд» НЕ МОЖЕТ:
# элемент, вернувшийся в поток, честно растит родителя, и `ВЫСОТА`
# называет родителя по делу — замер контроля показывает `.avatar-edit`
# 96 → 128 px (+33 %). Это верное наблюдение о ДРУГОМ элементе, а не шум.
# Здесь же реflow не происходит вовсе, и от остальных четырёх видов
# требуется полное молчание.
ПОДЛОГ_СДВИГА = ".avatar-upload-btn { right: 40px !important; }"

ЭКРАН_КОНТРОЛЯ = [("/profile", "профиль", True, None)]


def _по_видам(а, б):
    """{вид: [(класс, что)]} — для чтения глазами в контроле."""
    находки, _ = _находки(а, б)
    итог = {}
    for _, _, _, вид, что, x, _ in находки:
        итог.setdefault(вид, []).append((x["кл"].split()[0], что))
    return итог



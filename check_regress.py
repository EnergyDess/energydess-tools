    for i in range(сколько):
        м = f"_повтор{i + 1}"
        снять(м)
        метки.append(м)
    всё_ноль = True
    for i in range(1, сколько):
        n = сверить(метки[0], метки[i], тихо=True)
        print(f"  {'ok ' if n == 0 else 'ШУМ'} снимок 1 против {i + 1}: {n} находок")

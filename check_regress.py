def снять(метка, добавка_css="", экраны=None):
    """Снимок вычисленных свойств по всем экранам и всем ширинам."""
    from playwright.sync_api import sync_playwright

    папка = _папка(метка)
    shutil.rmtree(папка, ignore_errors=True)
    os.makedirs(папка, exist_ok=True)

    if экраны is None:
        экраны = ch.экраны_из_роутов()
    гостевые = [э for э in экраны if not э[2]]
    свои = [э for э in экраны if э[2]]

    всего = 0
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for ширина, высота, сенсор in ШИРИНЫ:
            к = бр.new_context(viewport={"width": ширина, "height": высота},
                               has_touch=сенсор, is_mobile=сенсор)
            стр = к.new_page()
            cdp = к.new_cdp_session(стр)
            if сенсор:
                ch._включить_сенсор(cdp)
            данные = {}
            порядок = гостевые + [("__вход__", "", True, None)] + свои
            for путь, имя, вход, подготовка in порядок:
                if путь == "__вход__":
                    ch._войти(стр)
                    if сенсор:
                        ch._включить_сенсор(cdp)
                    continue
                стр.goto(f"{ch.БАЗА}{путь}", wait_until="domcontentloaded",
                         timeout=45000)
                стр.wait_for_timeout(2200)
                if добавка_css:
                    стр.add_style_tag(content=добавка_css)
                if подготовка:
                    try:
                        стр.click(подготовка, timeout=5000)
                        стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 700)
                    except Exception as e:
                        print(f"   · {имя}: сцена не открылась ({type(e).__name__})")
                        continue
                # Указатель уводится: иначе последний клик оставляет :hover,
                # и вычисленные свойства кадра зависят от того, куда попала
                # мышь. Та же причина, что в check_pixel_diff.
                стр.mouse.move(ширина - 2, высота - 2)
                стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА)
                ch._сверить(стр, сенсор, f"{ширина}: {имя}")
                данные[имя] = стр.evaluate(СНИМОК_JS)
                всего += len(данные[имя])
            io.open(os.path.join(папка, f"{ширина}.json"), "w",
                    encoding="utf-8").write(json.dumps(данные, ensure_ascii=False))
            к.close()
        бр.close()
    print(f"  снято: {метка} — элементов {всего}")
    return всего


def _находки(а, б):
    """[(ширина, экран, ключ, вид, что, до, после)] по четырём видам."""
    итог, пар_нет = [], 0
    пропали, появились = {}, {}
    for ширина, _, _ in ШИРИНЫ:
        фа = os.path.join(_папка(а), f"{ширина}.json")
        фб = os.path.join(_папка(б), f"{ширина}.json")
        if not (os.path.exists(фа) and os.path.exists(фб)):
            continue
        да = json.loads(io.open(фа, encoding="utf-8").read())
        дб = json.loads(io.open(фб, encoding="utf-8").read())
        for экран in sorted(set(да) & set(дб)):
            эа, эб = да[экран], дб[экран]
            # Пары без соответствия. Раньше здесь было только ЧИСЛО,
            # и элемент, ИСЧЕЗНУВШИЙ из разметки, был неотличим
            # от переехавшего по дереву: и то и другое — «пара без пары».
            # Теперь исчезнувшие называются классами: пропавший блок —
            # это регресс, а сдвинувшийся путь — нет, и различать их
            # по одному числу было нечем.
            for к in set(эа) - set(эб):
                if эа[к]["видим"]:
                    пропали.setdefault(эа[к]["кл"].split()[0], 0)
                    пропали[эа[к]["кл"].split()[0]] += 1
            for к in set(эб) - set(эа):
                if эб[к]["видим"]:
                    появились.setdefault(эб[к]["кл"].split()[0], 0)
                    появились[эб[к]["кл"].split()[0]] += 1
            пар_нет += len(set(эа) ^ set(эб))
            for ключ in sorted(set(эа) & set(эб)):
                x, y = эа[ключ], эб[ключ]
                виды = []
                if x["видим"] != y["видим"]:
                    виды.append(("ВИДИМОСТЬ",
                                 ("виден" if x["видим"] else "не виден") + " → " +
                                 ("виден" if y["видим"] else "не виден")))
                # Остальные три вида спрашиваются только у того, что видно
                # в обеих сборках: у скрытого элемента высота 0, и разговор
                # о ней был бы про пустое место.
                if x["видим"] and y["видим"]:
                    if x["align"] != y["align"] and (x.get("естьТекст") or y.get("естьТекст")):
                        виды.append(("ВЫРАВНИВАНИЕ", f"{x['align']} → {y['align']}"))
                    if x["рамка"] != y["рамка"]:
                        виды.append(("РАМКА",
                                     ("есть" if x["рамка"] else "нет") + " → " +
                                     ("есть" if y["рамка"] else "нет")))
                    ha, hb = x["h"], y["h"]
                    if max(ha, hb) and abs(ha - hb) / max(ha, hb) > ПОРОГ_ВЫСОТЫ:
                        доля = round(100 * (hb - ha) / ha) if ha else 0
                        виды.append(("ВЫСОТА", f"{ha} → {hb} px ({доля:+d}%)"))
                    # ПОЛОЖЕНИЕ. Спрашивается ТОЛЬКО у того, кто хотя бы
                    # в одной сборке вне потока (разбор и замер — у
                    # ПОРОГ_СДВИГА выше). Причин две, а строка ОДНА:
                    # у элемента, вернувшегося в поток, меняются обе сразу,
                    # и две находки на один дефект читались бы как два.
                    if (x.get("поз") in ВНЕ_ПОТОКА
                            or y.get("поз") in ВНЕ_ПОТОКА):
                        причины = []
                        if x.get("поз") != y.get("поз"):
                            причины.append("способ %s → %s"
                                           % (x.get("поз"), y.get("поз")))
                        ddx = abs(x.get("cx", 0) - y.get("cx", 0))
                        ddy = abs(x.get("cy", 0) - y.get("cy", 0))
                        if max(ddx, ddy) > ПОРОГ_СДВИГА:
                            причины.append(
                                "сдвиг в контейнере %+d,%+d px (было %d,%d)"
                                % (y.get("cx", 0) - x.get("cx", 0),
                                   y.get("cy", 0) - x.get("cy", 0),
                                   x.get("cx", 0), x.get("cy", 0)))
                        if причины:
                            виды.append(("ПОЛОЖЕНИЕ", "; ".join(причины)))
                for вид, что in виды:
                    итог.append((ширина, экран, ключ, вид, что, x, y))
    return итог, (пар_нет, пропали, появились)



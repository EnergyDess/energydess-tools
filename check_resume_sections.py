def шаг(имя, условие, подробно="", собрано=None, отрицание=""):
    if собрано is not None and собрано == 0:
        print("   ПРОПУСК %-44s %s" % (имя, подробно or "собрано 0"))
        ПЛОХО.append(("пропуск", имя))
        return
    print("   %-7s %-44s %s" % ("OK" if условие else "ПЛОХО", имя, подробно))
    if not условие:
        ПЛОХО.append(("плохо", имя))



def _мест(разделы):
    n = 0
    for р in разделы:
        if р["имя"] == "Опыт работы":
            n += len(rs.места_работы(р["тело"]))
    return n


def выдуманные():
    print("ВЫДУМАННЫЕ РЕЗЮМЕ")
    for имя, текст, ждём_разделов, ждём_мест in ВЫДУМАННЫЕ:
        разделы = rs.разобрать(текст)
        собрано = rs.собрать(разделы)
        мест = _мест(разделы)
        шаг("%s: собралось побайтно" % имя, собрано == текст,
            "длина %d → %d" % (len(текст), len(собрано)))
        шаг("%s: разделов %d" % (имя, len(разделы)), len(разделы) == ждём_разделов,
            "ждали %d" % ждём_разделов)
        шаг("%s: мест работы %d" % (имя, мест), мест == ждём_мест,
            "ждали %d" % ждём_мест)
        # Куски идут ПОДРЯД и без пропусков: дыра между ними — потерянный
        # текст, и по одной только склейке её видно не было бы, если бы
        # разбор терял кусок и тут же дублировал соседний.
        подряд = all(разделы[n]["конец"] == разделы[n + 1]["начало"]
                     for n in range(len(разделы) - 1))
        шаг("%s: куски без пропусков" % имя,
            bool(разделы) and подряд and разделы[0]["начало"] == 0
            and разделы[-1]["конец"] == len(текст),
            собрано=len(разделы) if текст else 0,
            отрицание="разделов нет вовсе — текст потерян целиком")

    # Незнакомый заголовок обязан ОСТАТЬСЯ телом соседнего раздела:
    # выброшенный, он исчез бы с экрана молча.
    разделы = rs.разобрать(С_НЕЗНАКОМЫМ)
    где = [n for n, р in enumerate(разделы) if "Рекомендации" in р["тело"]]
    # Пустой сбор здесь — не «чисто», а находка: разделов не осталось вовсе
    шаг("незнакомый заголовок не потерян", len(где) == 1,
        "лежит в разделе %r" % (разделы[где[0]]["имя"] if где else "—"),
        собрано=len(разделы))

    # Запасной вид называется СВОИМ именем: «разделов нет» и «резюме
    # пустое» — разные факты, и подменять один другим нельзя.
    з = rs.разобрать(БЕЗ_ЗАГОЛОВКОВ)
    шаг("запасной вид: один раздел на весь текст",
        len(з) == 1 and з[0]["имя"] == rs.ВЕСЬ_ТЕКСТ and з[0]["тело"] == БЕЗ_ЗАГОЛОВКОВ,
        "разделов %d" % len(з))


def правка():
    print("ПРАВКА РАЗДЕЛА")
    разделы = rs.разобрать(ПОЛНОЕ)
    for индекс, р in enumerate(разделы):
        новое = р["тело"] + "ХВОСТ\n"
        полный = rs.заменить_тело(ПОЛНОЕ, индекс, новое)
        # Всё, кроме этого куска, обязано остаться байт в байт
        до = ПОЛНОЕ[:р["начало"]] == полный[:р["начало"]]
        после = ПОЛНОЕ[р["конец"]:] == полный[р["начало"] + len(новое):]
        шаг("раздел %d (%s): тронут только он" % (индекс, р["имя"]), до and после,
            "длина %d → %d" % (len(ПОЛНОЕ), len(полный)))

    # Текст, который уйдёт в генерацию письма, — тот же полный текст
    правленый = rs.заменить_тело(ПОЛНОЕ, 0, разделы[0]["тело"])
    шаг("правка «тем же» не меняет текст", правленый == ПОЛНОЕ,
        "длина %d" % len(правленый))
    шаг("текст для генерации = склейка разделов",
        rs.собрать(rs.разобрать(правленый)) == правленый)

    # Индекс вне набора — ОТКАЗ, а не сохранение чужого куска
    try:
        rs.заменить_тело(ПОЛНОЕ, 99, "x")
        шаг("раздел вне набора — отказ", False, "исключения не было")
    except IndexError:
        шаг("раздел вне набора — отказ", True, "IndexError")


def боевые(путь):
    print("КОПИЯ БОЕВОЙ БАЗЫ (текст резюме НЕ печатается)")
    if "/data/" in путь.replace("\\", "/"):
        print("   ОСТАНОВЛЕНО: боевая база не открывается")
        sys.exit(2)
    if not os.path.exists(путь):
        print("   ПРОПУСК: копии базы нет — %s" % путь)
        return 0
    c = sqlite3.connect("file:%s?mode=ro" % путь.replace("\\", "/"), uri=True)
    строки = c.execute(
        "SELECT id, resume_text FROM resumes WHERE resume_text IS NOT NULL "
        "AND length(trim(resume_text)) > 0 ORDER BY id").fetchall()
    c.close()
    if not строки:
        print("   ПРОПУСК: резюме в копии нет")
        return 0
    for id_, текст in строки:
        разделы = rs.разобрать(текст)
        собрано = rs.собрать(разделы)
        мест = _мест(разделы)
        шаг("резюме #%d: собралось побайтно" % id_, собрано == текст,
            "длина %d → %d, разделов %d, мест %d"
            % (len(текст), len(собрано), len(разделы), мест))
        # Правка КАЖДОГО раздела на него же обязана вернуть исходный текст
        цел = all(rs.заменить_тело(текст, n, р["тело"]) == текст
                  for n, р in enumerate(разделы))
        шаг("резюме #%d: правка каждого раздела обратима" % id_, цел,
            "разделов %d" % len(разделы), собрано=len(разделы))
    return len(строки)


# ── Отрицательный контроль ───────────────────────────────────────────────────
# Подлог ломает ЗВЕНО, а доказательство снимается НЕЗАВИСИМО от вердикта
# пробы (§6.0.3): у первого — длина склейки, у второго — число разделов.

def контроль():
    print("КОНТРОЛЬ")
    родной_разобрать = rs.разобрать

    def сдвинутый(текст):
        """Подлог 1: граница раздела сдвинута на строку вниз.

        Текст между границами при этом ТЕРЯЕТСЯ, и видно это только
        побайтной сверкой: число разделов остаётся прежним.
        """
        разделы = родной_разобрать(текст)
        for р in разделы[1:]:
            сдвиг = текст.find("\n", р["начало"])
            if 0 <= сдвиг < р["конец"]:
                р["начало"] = сдвиг + 1
                р["тело"] = текст[р["начало"]:р["конец"]]
        return разделы

    rs.разобрать = сдвинутый
    доказательство = len(rs.собрать(rs.разобрать(ПОЛНОЕ)))
    было = len(ПОЛНОЕ)
    плохих_до = len(ПЛОХО)
    выдуманные()
    нашла1 = len(ПЛОХО) > плохих_до
    rs.разобрать = родной_разобрать
    print("   ПОДЛОГ 1 «граница сдвинута»: %s | доказательство: склейка %d → %d знаков"
          % ("НАЙДЕН" if нашла1 else "НЕ НАЙДЕН", было, доказательство))

    родной_вест = rs.ВЕСЬ_ТЕКСТ

    def без_запасного(текст):
        """Подлог 2: запасного вида нет — текст без заголовков теряется."""
        разделы = родной_разобрать(текст)
        if len(разделы) == 1 and разделы[0]["имя"] == родной_вест:
            return []
        return разделы

    rs.разобрать = без_запасного
    доказательство2 = len(rs.разобрать(БЕЗ_ЗАГОЛОВКОВ))
    del ПЛОХО[:]
    выдуманные()
    нашла2 = bool(ПЛОХО)
    rs.разобрать = родной_разобрать
    print("   ПОДЛОГ 2 «запасного вида нет»: %s | доказательство: разделов 1 → %d"
          % ("НАЙДЕН" if нашла2 else "НЕ НАЙДЕН", доказательство2))

    del ПЛОХО[:]
    выдуманные()
    правка()
    чисто = not ПЛОХО
    print("   ОСНОВА ЧИСТА: %s" % ("да" if чисто else "НЕТ"))
    return 0 if (нашла1 and нашла2 and чисто) else 1


def main():
    п = argparse.ArgumentParser()
    п.add_argument("--база", default="", help="копия боевой базы (только чтение)")
    п.add_argument("--контроль", action="store_true")
    а = п.parse_args()

    if а.контроль:
        sys.exit(контроль())

    выдуманные()
    правка()
    if а.база:
        боевые(а.база)

    print("ИТОГ: %s" % ("ЧИСТО" if not ПЛОХО else "ПЛОХО: %d" % len(ПЛОХО)))
    sys.exit(1 if ПЛОХО else 0)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()

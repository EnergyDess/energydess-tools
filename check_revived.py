# -*- coding: utf-8 -*-
"""Проверка 12: имя объявлено в документах удалённым, а в коде живёт.

ОБРАТНАЯ СТОРОНА ПРОВЕРКИ 7. Та ищет имя, ОПИСАННОЕ в документе
и ОТСУТСТВУЮЩЕЕ в коде. Обратный случай она пропускает по построению:
у неё есть список `ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ` — «про это имя написано,
что его нет», — и на этом она успокаивается. Верни класс в CSS, и
проверка 7 промолчит, а документ станет неправдой в другую сторону.

Найдено отрицательным контролем 2026-08-17: `.box-title` вернули
в шаблон, проверка дала 0.

ПОЧЕМУ ЗАВЕДЕНА ТОЛЬКО СЕЙЧАС. Довод против звучал «40 ложных
на 40 находок» и держался на плоском чтении источников: пока строка
`/* .save-btn здесь больше нет */` считалась объявлением класса,
почти весь список исключений «жил» комментариями о собственной
смерти. Задача 99 сняла это разбором, и мерка изменилась:
из 68 исключений в коде жили ДВЕ — `.f-input` и `.save-btn`,
и обе были настоящими находками, а не ложными. Их правила лежали
в `nutrition.css` в десктопном медиазапросе профиля и описывали
классы, которых в разметке нет с задачи 42. Удалены раньше, чем
заведена эта проверка: иначе первый же её прогон пришлось бы
объявлять исключением, а исключение в день рождения проверки
обесценивает её навсегда.

ЧТО СЧИТАЕТСЯ НАХОДКОЙ

  имя    ключ из `check_docs.ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ`, найденный в коде.
         Каждая запись там означает одно и то же: «этого имени в коде
         быть не должно» — удалён, сведён к системному, отвергнут,
         гипотетический пример. Живой ключ = документ врёт.
  файл   ключ из `check_docs.ИЗВЕСТНЫЕ_ФАЙЛЫ`, ЛЕЖАЩИЙ на диске.

ФАЙЛЫ РАЗДЕЛЕНЫ НА ДВА ВИДА, И БЕЗ ЭТОГО ПРОВЕРКА ВРАЛА БЫ. Словарь
`ИЗВЕСТНЫЕ_ФАЙЛЫ` смешивает «этого файла нет» (`SYSTEM.md`,
`effects.js`) и «файл есть, но проход D спотыкается о форму имени»
(`style.css` — короткое имя от `static/style.css`; `main.py` —
упоминается и как `/app/main.py`). Вторые существуют законно,
и считать их находками значило бы завести вечную ложную тревогу.
Их два, они названы ниже поимённо.

СПИСКОВ СВОИХ ЗДЕСЬ НЕТ. И имена, и файлы, и разбор источников
берутся у `check_docs` импортом: вторая копия разошлась бы с первой
молча, и проверка начала бы спрашивать не про те имена (тот же довод,
по которому `check_ids` читает компонентную базу из CLAUDE.md,
а `check_scale_screens` — состояния у `make_local_user`).

ГРАНИЦА — что проверка НЕ видит:
  * имя, которое документ называет удалённым, но в список исключений
    его не внесли: проверка 7 такое имя показывает сама, находкой
    прохода A, — то есть слепого пятна тут нет, вопрос задаёт соседняя
    проверка;
  * возвращение не имени, а ПОВЕДЕНИЯ: «смахивание убрано», «кнопка
    больше не открывает модалку». Буквального представления в коде
    у этого нет — та же граница, что у всей проверки 7;
  * имя, вернувшееся только в комментарий: разбор комментарии снимает,
    и это правильно — про мёртвый класс в пояснении и написано, что
    он мёртв.

Код возврата: 0 — находок нет, 1 — есть и названы, 2 — сломан разбор.

Запуск:  py check_revived.py             (ИМЕННО py: python на машине
                                          Дениса — заглушка Store)
         py check_revived.py --контроль   (отрицательный контроль)
"""
import sys

sys.stdout.reconfigure(encoding='utf-8')

import check_docs as док   # noqa: E402

# Файлы, которые в `ИЗВЕСТНЫЕ_ФАЙЛЫ` лежат НЕ как удалённые, а потому,
# что проход D спотыкается о форму их имени. Существуют законно.
ФАЙЛЫ_НЕ_ПРО_УДАЛЕНИЕ = {
    'style.css': 'короткое имя static/style.css — файл есть и должен быть',
    'main.py': 'лежит в корне, упоминается ещё и как /app/main.py',
}

# Отрицательный контроль пишет два настоящих файла: правило CSS с именем,
# объявленным удалённым, и файл, объявленный никогда не существовавшим.
# Латиница в имени: путь уходит в glob и в отчёт (CLAUDE.md §6.0).
ПРОБА_CSS = док.КОРЕНЬ / 'static' / 'zz-control-probe.css'
ПРОБА_КЛАСС = 'week-box'      # design-system.md §11: блок «7 дней» удалён
ПРОБА_ФАЙЛ = док.КОРЕНЬ / 'THEME-workout.md'   # «никогда не существовал»


def найти():
    """(живые имена, лежащие на диске файлы). Оба — с причиной из словаря."""
    классы, токены = док.собрать_известное(чисто=True)
    имена = [(и, п) for и, п in док.ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ.items()
             if и in (токены if и.startswith('--') else классы)]

    файлы = []
    for имя, причина in док.ИЗВЕСТНЫЕ_ФАЙЛЫ.items():
        if имя in ФАЙЛЫ_НЕ_ПРО_УДАЛЕНИЕ:
            continue
        есть = ((док.КОРЕНЬ / имя).exists() if '/' in имя
                else bool(list(док.КОРЕНЬ.glob('**/' + имя))))
        if есть:
            файлы.append((имя, причина))
    return имена, файлы


def напечатать(имена, файлы):
    print('Проверка 12 — имя объявлено удалённым, а в коде живёт\n')
    print('  имён в словаре исключений:     %d' % len(док.ИЗВЕСТНЫЕ_ИСКЛЮЧЕНИЯ))
    print('  из них живут в коде:           %d' % len(имена))
    print('  файлов в словаре:              %d   (не про удаление: %d)'
          % (len(док.ИЗВЕСТНЫЕ_ФАЙЛЫ), len(ФАЙЛЫ_НЕ_ПРО_УДАЛЕНИЕ)))
    print('  из них лежат на диске:         %d\n' % len(файлы))
    for имя, причина in имена:
        вид = 'токен' if имя.startswith('--') else 'класс'
        print('  %s %-28s документ: %s' % (вид, имя, причина))
    for имя, причина in файлы:
        print('  файл  %-28s документ: %s' % (имя, причина))


def контроль():
    """Подложить настоящее возвращение — проверка обязана его назвать.

    Контроль настоящий, а не подстановка множеств: файлы пишутся
    на диск и читаются тем же сборщиком, что и в обычном прогоне.
    Проверка, у которой контроль обходит чтение, доказывает работу
    своей арифметики, а не своего входа.

    Проверяются обе стороны, и обе обязательны: чистое дерево должно
    давать ноль, подложенное — находку. Одна сторона в одиночку
    проходит и у проверки, которая всегда молчит.
    """
    print('ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ (задача 109)\n')
    беды = []

    имена, файлы = найти()
    print('   чистое дерево:      имён %d, файлов %d' % (len(имена), len(файлы)))
    было_имён, было_файлов = len(имена), len(файлы)

    try:
        ПРОБА_CSS.write_text('.%s { color: red }\n' % ПРОБА_КЛАСС, encoding='utf-8')
        ПРОБА_ФАЙЛ.write_text('проба контроля\n', encoding='utf-8')
        имена2, файлы2 = найти()
        print('   с подлогом:         имён %d, файлов %d'
              % (len(имена2), len(файлы2)))
        if ПРОБА_КЛАСС not in [и for и, _ in имена2]:
            беды.append('вернувшийся класс .%s НЕ найден — проверка '
                        'не видит того, что ищет' % ПРОБА_КЛАСС)
        if ПРОБА_ФАЙЛ.name not in [и for и, _ in файлы2]:
            беды.append('вернувшийся файл %s НЕ найден' % ПРОБА_ФАЙЛ.name)
    finally:
        ПРОБА_CSS.unlink(missing_ok=True)
        ПРОБА_ФАЙЛ.unlink(missing_ok=True)

    имена3, файлы3 = найти()
    print('   после уборки:       имён %d, файлов %d' % (len(имена3), len(файлы3)))
    if (len(имена3), len(файлы3)) != (было_имён, было_файлов):
        беды.append('после уборки числа не вернулись — проба осталась на диске')

    if беды:
        print('\nНЕ ПРОЙДЕН:')
        for б in беды:
            print('   ·', б)
        return 1
    print('\nПройден: подложенное возвращение названо, чистое дерево — '
          'ноль, проба убрана.')
    return 0


def main():
    if '--контроль' in sys.argv:
        return контроль()
    имена, файлы = найти()
    напечатать(имена, файлы)
    if имена or файлы:
        print('\nЧто делать: либо имя вернулось законно — тогда правится\n'
              'документ (design-system.md §11 и список исключений\n'
              'check_docs.py), либо это остаток, и правится код.\n'
              'Разбор — CLAUDE.md §6.0.2, «Проверка 12».')
        return 1
    print('Находок нет. Отдельно: этот ноль стоит чего-то только вместе\n'
          'с отрицательным контролем — `py check_revived.py --контроль`.')
    return 0


if __name__ == '__main__':
    sys.exit(main())

# ═══════════════════════════════════════════════════════════════════
# БЕЛЫЙ СПИСОК ДОМЕНОВ (BACKLOG №200, C.1)
#
# Перечень тут ЗАКОНЕН (§6.0.7): новый член появляется решением
# владельца, и это решение и есть строка в списке. Маска была бы
# опаснее — она завтра проглотила бы маркетплейс.

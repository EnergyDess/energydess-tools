def _ключ():
    если = os.getenv("OPENROUTER_API_KEY")
    if если:
        return если
    try:
        for ln in io.open(".env", encoding="utf-8"):
            if ln.strip().startswith("OPENROUTER_API_KEY="):
                return ln.split("=", 1)[1].strip()
    except OSError:
        pass
    return ""


def _домен(адрес: str) -> str:
    try:
        return адрес.split("//", 1)[1].split("/", 1)[0].lower()
    except IndexError:
        return "?"


def искать(ключ, движок, текст, сколько=5):
    """Один запрос. Возвращает (адреса, стоимость, мс, ошибка).

    Модель тут — ТОЛЬКО СПОСОБ ДОБЫТЬ АДРЕСА. Её текст не читается
    и в дело не идёт: правило §5.8 «дословная выдержка, никакого
    пересказа» не ослабляется ни на знак, и ослабить его этот путь
    не может по построению — берутся `annotations`, то есть ссылки,
    а сам раздел мы потом забираем со страницы САМИ.
    """
    плагин = {"id": "web", "max_results": сколько}
    if движок:
        плагин["engine"] = движок
    тело = {
        "model": "anthropic/claude-haiku-4.5",
        "messages": [{"role": "user", "content":
                      f"Найди страницы про: {текст}. Ответь одним словом ok."}],
        "max_tokens": 16,
        "plugins": [плагин],
        "provider": {"data_collection": "deny", "zdr": True},
    }
    нач = time.monotonic()
    try:
        отв = httpx.post(OPENROUTER_URL, json=тело, timeout=120,
                         headers={"Authorization": f"Bearer {ключ}",
                                  "Content-Type": "application/json"})
        д = отв.json()
    except Exception as e:                              # noqa: BLE001
        мс = int((time.monotonic() - нач) * 1000)
        return [], 0.0, мс, f"{type(e).__name__}: {e}"
    мс = int((time.monotonic() - нач) * 1000)
    if "error" in д:
        return [], 0.0, мс, json.dumps(д["error"], ensure_ascii=False)[:160]
    сообщ = д["choices"][0]["message"]
    адреса = [a.get("url_citation", {}).get("url", "")
              for a in (сообщ.get("annotations") or [])]
    цена = float((д.get("usage") or {}).get("cost") or 0.0)
    return [a for a in адреса if a], цена, мс, ""


def главная() -> int:
    р = argparse.ArgumentParser()
    р.add_argument("--движок", default="", help="exa | native")
    а = р.parse_args()

    ключ = _ключ()
    print("ПОИСКОВИК — ЗАМЕР")
    print("=" * 74)
    if not ключ:
        print("  ключа OPENROUTER_API_KEY нет — замерить нечем")
        return 0

    движки = [а.движок] if а.движок else ["exa", "native"]
    print(f"  шаблон запроса: {ШАБЛОН}")
    print(f"  белый список:   {len(БЕЛЫЙ_СПИСОК)} доменов")
    print()

    for дв in движки:
        print(f"  ДВИЖОК {дв}")
        шапка = (f"    {'запрос':<22} {'ссылок':>6} {'бел':>4} {'иных':>5} "
                 f"{'$':>9} {'мс':>6}")
        print(шапка)
        всего_ц, всего_с, всего_б, всего_п = 0.0, 0, 0, 0
        for назв, форма, доза in НАЗВАНИЯ:
            текст = запрос_из_карточки(назв, форма, доза)
            адреса, цена, мс, ошибка = искать(ключ, дв, текст)
            if ошибка:
                print(f"    {назв:<22} ОШИБКА {ошибка[:60]}")
                continue
            домены = [_домен(a) for a in адреса]
            бел = sum(1 for d in домены if d in БЕЛЫЙ_СПИСОК)
            пр = sum(1 for d in домены if производитель(d))
            всего_ц += цена
            всего_с += len(адреса)
            всего_б += бел
            всего_п += пр
            print(f"    {назв:<22} {len(адреса):>6} {бел:>4} {пр:>5} "
                  f"{цена:>9.5f} {мс:>6}")
            for d in домены:
                метка = ("БЕЛЫЙ" if d in БЕЛЫЙ_СПИСОК
                         else "ЗАПРЕЩЁН" if d in ЗАПРЕЩЕНО else "иной")
                print(f"        {метка:<9} {d}")
        print(f"    ИТОГО ссылок {всего_с}, белых {всего_б}, "
              f"иных {всего_п}, ${всего_ц:.5f} за {len(НАЗВАНИЯ)} запросов")
        if всего_ц:
            за1000 = всего_ц / len(НАЗВАНИЯ) * 1000
            print(f"    цена за 1000 запросов: ${за1000:.2f}")
        print()

    print("  КАНДИДАТЫ БЕЗ КЛЮЧА — в замер не вошли, причина названа")
    for имя, цена, почему in БЕЗ_КЛЮЧА:
        print(f"    {имя:<20} {цена}")
        print(f"    {' ':<20} {почему}")
    print()
    print("  Код возврата 0 всегда: это МЕРКА, а не проверка.")
    return 0


if __name__ == "__main__":
    sys.exit(главная())

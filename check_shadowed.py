# -*- coding: utf-8 -*-
"""ПРОВЕРКА 21: правило состояния, перебитое соседом при РАВНОЙ специфичности.

═══════════════════════════════════════════════════════════════════════
ЧТО ЭТО ЗА КЛАСС
═══════════════════════════════════════════════════════════════════════

    @media (hover: hover) {
      .wk-home-btn:hover  { border-color: var(--border-strong); }
    }
    .wk-home-btn.active   { border-color: transparent; }

Специфичность у обоих (0,2,0): один класс плюс один псевдокласс против
двух классов. При равной специфичности побеждает тот, кто НИЖЕ, — значит
у активной кнопки наведение не меняет ничего. Отказ немой: правило
написано, синтаксис верен, консоль чиста, а на экране ничего.

`check_hover` (проверка 10) такое ловит — но только там, где на экране
приёмки НИ ОДИН элемент селектора не отозвался (группа МЁРТВОЕ). Пока
на странице есть хоть один неактивный экземпляр, правило считается
рабочим (группа ЭКЗЕМПЛЯР), и перебитое состояние не видно никому.
Эта проверка спрашивает то же самое у ТЕКСТА стилей, не открывая
браузера, и потому видит все экземпляры сразу.

ПРИЗНАК, А НЕ ПЕРЕЧЕНЬ (§6.0.7). Ищется пара правил в одном файле:

  · A: селектор, кончающийся псевдоклассом СОСТОЯНИЯ (`:hover`,
    `:focus`, `:focus-visible`, `:active`);
  · B: тот же селектор, но вместо состояния — обычный класс
    (`.active`, `.is-open`, `.selected` — любой);
  · специфичности равны, B стоит НИЖЕ A, и оба объявляют
    хотя бы одно общее свойство.

ЧЕГО НЕ ВИДИТ, и это названо, а не спрятано:
  · перебивание между РАЗНЫМИ файлами (`style.css` против `hh.css`) —
    порядок подключения там задаёт шаблон, а не текст стилей;
  · перебивание неравной специфичностью — это не «немой отказ»,
    а обычный каскад, и лечится он не тут;
  · случай, когда общего свойства нет: `background` у одного
    и `color` у другого друг другу не мешают;
  · `!important` — он ломает порядок, и пара с ним не разбирается.

Код возврата: 0 — ДОЛГА нет, 1 — есть и назван. Находки
делятся машиной: см. `разбивка`.

    py check_shadowed.py;            echo "код=$?"
    py check_shadowed.py --контроль; echo "код=$?"
"""
import glob
import io
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")

import project_lists as pl     # noqa: E402

СОСТОЯНИЯ = (":hover", ":focus-visible", ":focus", ":active")

# Комментарии снимаются РАЗБОРОМ, а не грепом: правило, процитированное
# в пояснении, правилом не является (§6.0.2, задача 99).
_КОММЕНТАРИЙ = re.compile(r"/\*.*?\*/", re.S)


def _файлы():
    """Все стили проекта: `static/*.css` и блоки <style> в шаблонах."""
    из = []
    for путь in sorted(glob.glob("static/*.css")):
        из.append((путь, io.open(путь, encoding="utf-8").read()))
    for путь in sorted(glob.glob("templates/*.html")):
        текст = io.open(путь, encoding="utf-8").read()
        куски = re.findall(r"<style[^>]*>(.*?)</style>", текст, re.S)
        if куски:
            из.append((путь, "\n".join(куски)))
    исключены = set(pl.исключённые_страницы())
    return [(п, т) for п, т in из
            if п.replace(os.sep, "/") not in исключены]


def специфичность(сел):
    """(id, класс+псевдокласс+атрибут, тег+псевдоэлемент). Без :not/:is —
    внутри них считается самый весомый аргумент, и такие пары мы
    не разбираем вовсе (см. `_годен`)."""
    id_ = len(re.findall(r"#[\w-]+", сел))
    кл = (len(re.findall(r"\.[\w-]+", сел))
          + len(re.findall(r"\[[^\]]*\]", сел))
          + len(re.findall(r"(?<!:):(?!:)[a-z-]+", сел)))
    тег = len(re.findall(r"(?:^|[\s>+~])([a-z][\w-]*)", сел))
    тег += len(re.findall(r"::[a-z-]+", сел))
    return (id_, кл, тег)


def _годен(сел):
    """Селекторы с :not/:is/:where не разбираются: их специфичность
    считается по самому весомому аргументу, и приблизительный счёт здесь
    дал бы ложные пары."""
    return not re.search(r":(not|is|where|has)\(", сел)


def правила(текст):
    """[(порядок, селектор, {свойство: значение})] — плоско, @media снят.

    `@media` не меняет ни специфичность, ни порядок внутри файла,
    поэтому обёртка просто разбирается насквозь."""
    текст = _КОММЕНТАРИЙ.sub("", текст)
    из = []
    for м in re.finditer(r"([^{}]+)\{([^{}]*)\}", текст):
        селекторы, тело = м.group(1), м.group(2)
        селекторы = селекторы.split("}")[-1].strip()
        if not селекторы or селекторы.startswith("@"):
            continue
        # хвост после закрытия @media может прилипнуть — берём последнюю строку
        селекторы = селекторы.lstrip("{").strip()
        свойства = {}
        for кусок in тело.split(";"):
            if ":" not in кусок:
                continue
            имя, знач = кусок.split(":", 1)
            имя = имя.strip().lower()
            if имя and not имя.startswith("--"):
                свойства[имя] = знач.strip()
        if not свойства:
            continue
        for с in селекторы.split(","):
            с = " ".join(с.split())
            if с:
                из.append((м.start(), с, свойства))
    return из


def найти(файлы=None):
    находки = []
    for путь, текст in (файлы if файлы is not None else _файлы()):
        все = правила(текст)
        состояния = []
        for порядок, сел, св in все:
            for сост in СОСТОЯНИЯ:
                if сел.endswith(сост) and _годен(сел):
                    состояния.append((порядок, сел, сел[:-len(сост)], сост, св))
                    break
        for порядок, сел, база, сост, св in состояния:
            for порядок2, сел2, св2 in все:
                if порядок2 <= порядок or not _годен(сел2):
                    continue
                # B — тот же селектор ПЛЮС обычный класс на том же
                # последнем компоненте: `.x.active` против `.x:hover`
                if not re.fullmatch(re.escape(база) + r"\.[\w-]+", сел2):
                    continue
                if специфичность(сел) != специфичность(сел2):
                    continue
                общие = [с for с in св
                         if с in св2
                         and "!important" not in св[с]
                         and "!important" not in св2[с]]
                if общие:
                    расходятся = sorted(
                        с for с in общие
                        if _норма(св[с]) != _норма(св2[с]))
                    находки.append((путь, сел, сел2, sorted(общие),
                                    расходятся))
    return находки


def _норма(значение):
    """Значение свойства без пробелов и регистра — для сравнения."""
    return " ".join(значение.lower().split())


def разбивка(находки):
    """(долг, законные) — РАЗДЕЛЯЕТ МАШИНА, признак назван.

    ЗАЧЕМ ДВА ЧИСЛА, А НЕ ОДНО. Проверка входит в ряд §6.0.2, а ряд
    из постоянно ненулевых чисел перестают читать целиком — ровно тот
    довод, из-за которого первое число ряда с 2026-08-21 печатается
    в разбивке, а в проверку 4 пришлось внести `_admin_nav.html`.

    ПРИЗНАК. Перебивание безвредно ровно тогда, когда сосед объявляет
    ТО ЖЕ САМОЕ значение: правило проигрывает каскад, но на экране
    не теряется ничего. Разошлись значения — замысел автора молча
    выброшен, и это долг.
    """
    долг = [н for н in находки if н[4]]
    законные = [н for н in находки if not н[4]]
    return долг, законные


def показать(находки):
    долг, законные = разбивка(находки)
    print("─" * 74)
    print("ПРАВИЛ СОСТОЯНИЯ, ПЕРЕБИТЫХ СОСЕДОМ ПРИ РАВНОЙ "
          "СПЕЦИФИЧНОСТИ: %d" % len(находки))
    print("   из них ДОЛГ %d   перебито тем же значением %d"
          % (len(долг), len(законные)))
    print("   способ: значения общего свойства РАЗОШЛИСЬ — долг;")
    print("           совпали — правило проигрывает каскад, но на экране")
    print("           не теряется ничего, и находкой это не является")
    print("─" * 74)
    for метка, куча in (("ДОЛГ", долг), ("то же значение", законные)):
        for путь, a, b, общие, расходятся in куча:
            print("  %-14s %s" % (метка, путь))
            print("     %s  →  перебито  %s" % (a, b))
            print("     общие свойства: %s%s" % (
                ", ".join(общие),
                "   РАСХОДЯТСЯ: " + ", ".join(расходятся) if расходятся else ""))
    return 1 if долг else 0


КОНТРОЛЬ = """
@media (hover: hover) {
  .подлог-кнопка:hover { border-color: red; color: white; }
}
.подлог-кнопка.active { border-color: transparent; }
/* А это перебиванием НЕ является: специфичность разная */
.подлог-два:hover { color: red; }
.обёртка .подлог-два.active { color: blue; }
/* И это тоже НЕ является: общих свойств нет */
.подлог-три:hover { color: red; }
.подлог-три.active { background: blue; }
/* А это находка, но ЗАКОННАЯ: значение у соседа ТО ЖЕ САМОЕ, и на
   экране перебивание не теряет ничего. Без этого случая признак
   разделения не прогоняется ни разу — то есть проверен рассуждением. */
.подлог-четыре:hover { color: RED; }
.подлог-четыре.active { color: red; }
"""


def контроль():
    н = найти([("<контроль>", КОНТРОЛЬ)])
    долг, законные = разбивка(н)
    имена = [a for _п, a, _b, _о, _р in н]
    имена_долга = [a for _п, a, _b, _о, _р in долг]
    имена_законных = [a for _п, a, _b, _о, _р in законные]
    надо = [".подлог-кнопка:hover", ".подлог-четыре:hover"]
    лишние = [и for и in имена if и not in надо]
    нет = [и for и in надо if и not in имена]
    print("подлог назван:      %s" % (не_пусто(имена) or "НИЧЕГО"))
    print("должно быть:        %s" % ", ".join(надо))
    print("пропущено:          %s" % (не_пусто(нет) or "нет"))
    print("ложных:             %s" % (не_пусто(лишние) or "нет"))
    print("в ДОЛГ:             %s" % (не_пусто(имена_долга) or "НИЧЕГО"))
    print("в законные:         %s" % (не_пусто(имена_законных) or "НИЧЕГО"))
    ок = (not нет and not лишние
          and имена_долга == [".подлог-кнопка:hover"]
          and имена_законных == [".подлог-четыре:hover"])
    print("КОНТРОЛЬ ПРОЙДЕН" if ок else "КОНТРОЛЬ ПРОВАЛЕН")
    return 0 if ок else 1


def не_пусто(с):
    return ", ".join(с) if с else ""


if __name__ == "__main__":
    if "--контроль" in sys.argv:
        sys.exit(контроль())
    sys.exit(показать(найти()))

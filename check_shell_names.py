def _не_ascii(с):
    return any(ord(б) > 127 for б in с)


class _Разбор:
    """Состояние одного прохода по тексту оболочки."""

    def __init__(self, т):
        self.т = т
        self.н = len(т)
        self.находки = []
        self.ожидают = []          # [(разделитель, в кавычках, срезать табы)]
        self.не_оболочка = []      # [(начало, конец)] тел heredoc в кавычках

    def _строка(self, i):
        return self.т.count("\n", 0, i) + 1

    def _найдено(self, вид, имя, i):
        self.находки.append({"вид": вид, "имя": имя, "строка": self._строка(i)})

    # ── подстановки ────────────────────────────────────────────────────
    def доллар(self, i):
        т, н = self.т, self.н
        сл = т[i + 1:i + 2]
        if сл == "{":
            м = re.compile(r"[#!]?([^\W\d]\w*)").match(т, i + 2)
            if м and _не_ascii(м.group(1)):
                self._найдено("подстановка", м.group(1), i)
            j = т.find("}", i)
            return н if j == -1 else j + 1
        if т.startswith("((", i + 1):
            return self.арифметика(i + 3)
        if сл == "(":
            return self.команды(i + 2, до_скобки=True)
        if сл == "'":
            j = i + 2
            while j < н and т[j] != "'":
                j += 2 if т[j] == "\\" else 1
            return min(н, j + 1)
        if сл == '"':
            return self.двойные(i + 2)
        м = ИМЯ.match(т, i + 1)
        if м:
            if _не_ascii(м.group(0)[0]):
                self._найдено("подстановка", м.group(0), i)
            return м.end()
        return i + 1

    def арифметика(self, i):
        """Тело `$((…))`: голое имя — переменная. Вложенная `$(…)`, кавычки
        и `$имя` разбираются своими путями — первая версия искала имена
        сплошняком до `))` и объявила находкой текст внутри
        `$(( $(grep -n 'СТОП_СИМПТОМЫ' …) + 40 ))`: 8 ложных из 36."""
        т, н = self.т, self.н
        глубина = 0
        while i < н:
            с = т[i]
            if т.startswith("))", i) and глубина == 0:
                return i + 2
            if с == "(":
                глубина += 1
                i += 1
            elif с == ")":
                глубина = max(0, глубина - 1)
                i += 1
            elif с == "$":
                i = self.доллар(i)
            elif с == "'":
                j = т.find("'", i + 1)
                i = н if j == -1 else j + 1
            elif с == '"':
                i = self.двойные(i + 1)
            elif с == "`":
                i = self.обратные(i)
            else:
                м = ИМЯ.match(т, i)
                if м:
                    if _не_ascii(м.group(0)):
                        self._найдено("арифметика", м.group(0), i)
                    i = м.end()
                else:
                    i += 1
        return н

    def обратные(self, i):
        """`…` — внутренность разбирается как команды."""
        т, н = self.т, self.н
        j = i + 1
        while j < н and т[j] != "`":
            j += 2 if т[j] == "\\" else 1
        вложенный = _Разбор(т[i + 1:j])
        вложенный.команды(0)
        сдвиг = self.т.count("\n", 0, i + 1)
        for ф in вложенный.находки:
            ф["строка"] += сдвиг
            self.находки.append(ф)
        return min(н, j + 1)

    def двойные(self, i):
        т, н = self.т, self.н
        while i < н:
            с = т[i]
            if с == "\\":
                i += 2
            elif с == '"':
                return i + 1
            elif с == "$":
                i = self.доллар(i)
            elif с == "`":
                i = self.обратные(i)
            else:
                i += 1
        return н

    def слово(self, i):
        """(конец, видимое без кавычек: закавыченное заменено нулём)."""
        т, н = self.т, self.н
        чистое = []
        while i < н:
            с = т[i]
            if с in КОНЕЦ_СЛОВА:
                break
            if с == "\\":
                чистое.append("\0")
                i += 2
            elif с == "'":
                j = т.find("'", i + 1)
                i = н if j == -1 else j + 1
                чистое.append("\0")
            elif с == '"':
                i = self.двойные(i + 1)
                чистое.append("\0")
            elif с == "`":
                i = self.обратные(i)
                чистое.append("\0")
            elif с == "$":
                i = self.доллар(i)
                чистое.append("\0")
            else:
                чистое.append(с)
                i += 1
        return i, "".join(чистое)

    # ── документы-heredoc ──────────────────────────────────────────────
    def тела(self, i):
        т, н = self.т, self.н
        for разделитель, в_кавычках, срезать in self.ожидают:
            нач_тела = i
            while i < н:
                j = т.find("\n", i)
                j = н if j == -1 else j
                строка = т[i:j]
                сравнить = строка.lstrip("\t") if срезать else строка
                if not в_кавычках:
                    к = i
                    while к < j:
                        if т[к] == "\\":
                            к += 2
                        elif т[к] == "$":
                            к = min(j, self.доллар(к))
                        elif т[к] == "`":
                            к = min(j, self.обратные(к))
                        else:
                            к += 1
                i = min(н, j + 1)
                if сравнить == разделитель:
                    break
            if в_кавычках:
                # тело НЕ оболочка: вложенный `bash -c` в нём — чужой текст
                self.не_оболочка.append((нач_тела, i))
        self.ожидают = []
        return i

    # ── команды ────────────────────────────────────────────────────────
    def команды(self, i, до_скобки=False):
        т, н = self.т, self.н
        позиция = True
        ждём = None               # "for" | "объявление" | "read"
        пропустить = False
        глубина = 0
        while i < н:
            с = т[i]
            if с == "\n":
                i = self.тела(i + 1)
                позиция, ждём = True, None
                continue
            if с in " \t":
                i += 1
                continue
            if с == "\\" and т[i + 1:i + 2] == "\n":
                i += 2
                continue
            if с == "#":
                j = т.find("\n", i)
                i = н if j == -1 else j
                continue
            if т.startswith(("&&", "||", ";;", "|&"), i):
                i += 2
                позиция, ждём = True, None
                continue
            if с in ";&|":
                i += 1
                позиция, ждём = True, None
                continue
            if с == "(":
                глубина += 1
                i += 1
                позиция, ждём = True, None
                continue
            if с == ")":
                i += 1
                if до_скобки and глубина == 0:
                    return i
                глубина = max(0, глубина - 1)
                позиция, ждём = True, None
                continue
            м = re.compile(r"\d*(<<<|<<-|<<|>>|>&|<&|>\||&>|<|>)").match(т, i)
            if м:
                оп = м.group(1)
                i = м.end()
                while i < н and т[i] in " \t":
                    i += 1
                if оп in ("<<", "<<-"):
                    нач = i
                    i, чистое = self.слово(i)
                    сырое = т[нач:i]
                    в_кав = any(к in сырое for к in "'\"\\")
                    разделитель = re.sub(r"['\"\\]", "", сырое)
                    self.ожидают.append((разделитель, в_кав, оп == "<<-"))
                else:
                    i, _ = self.слово(i)
                continue
            нач = i
            i, чистое = self.слово(i)
            if i == нач:
                i += 1
                continue
            if пропустить:
                пропустить = False
                continue
            if ждём == "for":
                if ИМЯ.fullmatch(чистое) and _не_ascii(чистое):
                    self._найдено("объявление", чистое, нач)
                ждём = None
                continue
            if ждём in ("объявление", "read"):
                if чистое.startswith(("-", "+")):
                    if ждём == "read" and чистое in READ_С_АРГУМЕНТОМ:
                        пропустить = True
                    continue
                мм = re.match(r"^([^\W\d]\w*)(?:=|$)", чистое)
                if мм and _не_ascii(мм.group(1)):
                    self._найдено("объявление", мм.group(1), нач)
                continue
            if позиция:
                мм = ПРИСВАИВАНИЕ.match(чистое)
                if мм:
                    if _не_ascii(мм.group(1)):
                        self._найдено("присваивание", мм.group(1), нач)
                        позиция = False
                    continue
                if чистое in СЛУЖЕБНЫЕ:
                    continue
                if чистое in ("for", "select"):
                    ждём = "for"
                elif чистое in ОБЪЯВЛЕНИЯ:
                    ждём = "объявление"
                elif чистое == "read":
                    ждём = "read"
                позиция = False
        return i


# ── вложенная оболочка: `bash -c '…'`, `sh -c "…"` (задача 319) ─────────
# Текст после `-c` для внешнего разбора — СЛОВО В КАВЫЧКАХ, то есть текст,
# а для вложенного интерпретатора — СКРИПТ. Замер захода 320: команда
# `bash -c 'проба=1; echo "$проба"'` проходила хук с нулём находок, а в
# транскриптах проекта таких вложений 118 у Bash и 1 у PowerShell. Носитель
# ищется по ТЕКСТУ, а не по позиции команды: `flyctl ssh console -C "sh -c
# '…'"` несёт скрипт АРГУМЕНТОМ, и разбор позиции его не увидел бы.
ВЛОЖЕННАЯ = re.compile(
    r"(?<![\w.-])(?:[\w.:~-]*[/\\])?(?:ba|da|z|k)?sh(?:\.exe)?[\"']?"
    r"[ \t]+(?:-[a-zA-Z]+[ \t]+)*?-[a-zA-Z]*c[ \t]+"
    r"(?:'((?:[^']|'\\'')*)'"                 # 1: в одинарных
    r"|\\\"((?:[^\\]|\\[^\"])*)\\\""          # 2: в экранированных двойных
    r"|\"((?:[^\"\\]|\\.)*)\")")              # 3: в двойных


def _вложенные(текст, пропуск=()):
    """[(номер строки начала, текст скрипта)] — скрипты после `-c`.
    `пропуск` — [(начало, конец)] участков, которые оболочкой не являются."""
    итог = []
    for м in ВЛОЖЕННАЯ.finditer(текст or ""):
        if any(а <= м.start() < б for а, б in пропуск):
            continue
        if м.group(1) is not None:
            скрипт = м.group(1).replace("'\\''", "'")
            нач = м.start(1)
        else:
            сырой = м.group(2) if м.group(2) is not None else м.group(3)
            нач = м.start(2) if м.group(2) is not None else м.start(3)
            скрипт = re.sub(r"\\([\"\\$`])", r"\1", сырой)
        итог.append((текст.count("\n", 0, нач) + 1, скрипт))
    return итог


def найти(текст, _глубина=0):
    """Находки в тексте оболочки: [{вид, имя, строка}]. Вложенные скрипты
    после `-c` разбираются тем же разбором; одна находка, видимая и снаружи
    (`sh -c "echo $код"` — подстановку раскроет уже внешняя оболочка),
    и изнутри, считается один раз."""
    р = _Разбор(текст or "")
    р.команды(0)
    итог = list(р.находки)
    if _глубина < 4:
        for строка, скрипт in _вложенные(текст, р.не_оболочка):
            for ф in найти(скрипт, _глубина + 1):
                итог.append(dict(ф, строка=ф["строка"] + строка - 1))
    видели, чистый = set(), []
    for ф in итог:
        ключ = (ф["вид"], ф["имя"], ф["строка"])
        if ключ not in видели:
            видели.add(ключ)
            чистый.append(ф)
    return чистый



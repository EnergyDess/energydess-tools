def _подлог_файла(путь, правка):
    """(код, находки) при подложенном файле; файл возвращается побайтно."""
    полный = os.path.join(КОРЕНЬ, путь)
    исходник = open(полный, "rb").read()
    try:
        open(полный, "wb").write(правка(исходник.decode("utf-8")).encode("utf-8"))
        return проверить(тихо=True)
    finally:
        open(полный, "wb").write(исходник)
        assert open(полный, "rb").read() == исходник, "файл не вернулся: " + путь


def _хук(инструмент, вход):
    п = subprocess.run([sys.executable, os.path.abspath(__file__), "--hook"],
                       input=json.dumps({"tool_name": инструмент, "tool_input": вход},
                                        ensure_ascii=False).encode("utf-8"),
                       capture_output=True)
    return п.returncode, п.stderr.decode("utf-8", "replace")



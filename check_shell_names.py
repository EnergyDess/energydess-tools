def тексты_оболочки(инструмент, вход):
    """[текст bash] из вызова инструмента: что исполнит оболочка bash."""
    к = (вход or {}).get(ПОЛЕ_КОМАНДЫ)
    if not isinstance(к, str) or not к:
        return []
    if инструмент in НЕ_BASH:
        return [скрипт for _, скрипт in _вложенные(к)]
    return [к]



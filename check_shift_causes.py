def доказать_подлог(было, стало):
    """ПОДЛОГ СОСТОЯЛСЯ — доказательство отдельно от вердикта (§6.0.3).

    Вердикт «сдвинулось больше элементов» доказательством не является:
    столько же напечаталось бы, если бы подлог не состоялся, а число
    выросло по другой причине. Доказательство — МАКСИМУМ смещения
    ПО СВОЕЙ ПРИЧИНЕ: подлог обязан двинуть именно её, и заметно.
    Порог 5 px взят выше шума растеризации (§6.0.3: два прогона одного
    кода расходятся в пределах пикселя).
    """
    return стало > было + 5


def контроль():
    """Три подлога, у каждого своё ДОКАЗАТЕЛЬСТВО (§6.0.3).

    Вердикт «сдвинулось больше» доказательством не является: столько же
    напечаталось бы, если бы подлог не состоялся, а число выросло
    по другой причине. Доказательство — МАКСИМУМ по своей причине:
    подлог обязан двинуть именно её, и заметно.
    """
    базис = прогон()
    б = {"скрипт": _сумма(базис, "скрипт"), "картинки": _сумма(базис, "картинки"),
         "шрифт": _сумма(базис, "шрифт")}
    итог = []
    for имя, ключ, под in (("текст подставлен скриптом", "скрипт", "скрипт"),
                           ("у плитки снята пропорция", "картинки", "картинки")):
        с = прогон(подлог=под)
        было, стало = б[ключ][1], _сумма(с, ключ)[1]
        итог.append((имя, ключ, было, стало,
                     доказать_подлог(было, стало)))
    # ТРЕТИЙ ПОДЛОГ — ШРИФТ. Он не «ещё один», а проверка того, что
    # шаг S3->S4 вообще зряч: если подсунуть гарнитуру с заведомо
    # другими метриками, максимум обязан вырасти скачком.
    с = прогон_шрифт_подлог()
    итог.append(("гарнитура подменена на Courier", "шрифт",
                 б["шрифт"][1], с, доказать_подлог(б["шрифт"][1], с)))
    print("КОНТРОЛЬ: три подлога, у каждого своё ДОКАЗАТЕЛЬСТВО")
    print("  %-32s %-10s %10s %10s  %s"
          % ("подлог", "причина", "макс ДО", "макс ПОСЛЕ", "состоялся"))
    ок = True
    for имя, ключ, было, стало, сост in итог:
        print("  %-32s %-10s %10.1f %10.1f  %s"
              % (имя, ключ, было, стало, "ДА" if сост else "НЕТ"))
        ок = ок and сост
    print()
    if ок:
        print("КОНТРОЛЬ ПРОЙДЕН: проба видит все три причины по отдельности.")
        return 0
    print("КОНТРОЛЬ НЕ ПРОЙДЕН: по какой-то причине проба слепа —")
    print("её ноль по этой причине не значит ничего.")
    return 1



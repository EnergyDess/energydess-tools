def _снимок(стр):
    return стр.evaluate("window.__snap()")


def _д(до, после):
    """(сдвинулось, максимум, ИМЯ) — сравнение общее с check_font_shift.

    Имя элемента печатается рядом с числом намеренно: «максимум
    1259 px» без имени не отвечает на единственный вопрос, который
    к нему возникает, — что именно уехало.
    """
    дв, макс, им, _г, _в, _мв, _ив = _сравнить(до, после, ПОРОГ)
    return дв, макс, им


def прогон(без_анимации=False, подлог=None):
    """Одна загрузка — четыре снимка. Возвращает строки по экранам."""
    from playwright.sync_api import sync_playwright
    строки = []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        сессия = _сессия(бр)
        for ш in ШИРИНЫ:
            for путь, имя, нужен_вход in ЭКРАНЫ:
                кон = бр.new_context(
                    viewport={"width": ш, "height": 900},
                    storage_state=сессия if нужен_вход else None,
                    reduced_motion="reduce" if без_анимации else "no-preference")
                стр = кон.new_page()
                # Отбиваем ОБА повода: и шрифт, и картинки. Снимок S1
                # обязан быть тем кадром, который человек видит первым.
                стр.route("**/*", lambda r: r.abort()
                          if (r.request.resource_type in ("font", "image")
                              or r.request.url.split("?")[0].lower()
                              .endswith(ШРИФТ_РАСШ))
                          else r.continue_())
                if подлог == "скрипт":
                    стр.add_init_script(ПОДЛОГ_СКРИПТ)
                if подлог == "картинки":
                    стр.add_init_script(ПОДЛОГ_КАРТИНКИ)
                стр.add_init_script(ЗАМЕР)
                стр.goto(БАЗА + путь, wait_until="domcontentloaded",
                         timeout=45000)
                s1 = _снимок(стр)
                try:
                    стр.wait_for_load_state("networkidle", timeout=15000)
                except Exception:
                    pass
                стр.wait_for_timeout(900)
                s2 = _снимок(стр)
                стр.unroute("**/*")
                картинок = стр.evaluate(ВЕРНУТЬ_КАРТИНКИ)
                стр.wait_for_timeout(400)
                s3 = _снимок(стр)
                стр.evaluate(ПОДСУНУТЬ_ШРИФТ)
                стр.wait_for_timeout(500)
                s4 = _снимок(стр)
                скрипт = _д(s1, s2)
                карт = _д(s2, s3)
                шрифт = _д(s3, s4)
                строки.append({"ширина": ш, "экран": имя, "элем": len(s1),
                               "картинок": картинок,
                               "скрипт": скрипт, "картинки": карт,
                               "шрифт": шрифт})
                кон.close()
        бр.close()
    return строки


def _сумма(строки, ключ):
    дв = sum(с[ключ][0] for с in строки)
    макс = max([с[ключ][1] for с in строки] or [0.0])
    где = sorted({с["экран"] for с in строки if с[ключ][0]})
    return дв, макс, где



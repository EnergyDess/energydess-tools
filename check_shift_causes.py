# ── РЕЖИМ --подстановки ─────────────────────────────────────────────
# S1 берётся ПОСЛЕ domcontentloaded, и синхронную подстановку из
# инлайнового скрипта он не видит по построению: та успевает
# отработать раньше. А владелец видел именно её — «Определяется…»
# сменяется на «Определён автоматически: Europe/Moscow», и выпадашка
# уезжает из ряда под подпись.
#
# ПЕРЕЧНЯ МЕСТ ТУТ НЕТ И БЫТЬ НЕ ДОЛЖНО (§6.0.7): наблюдатель
# ставится ДО скриптов страницы и записывает КАЖДУЮ смену текста.
# Место, заведённое завтра, попадёт в список само.
СЛЕДИТЬ = """
window.__подст = [];
(() => {
  const наб = new MutationObserver((зап) => {
    for (const з of зап) {
      if (з.type === 'characterData') {
        const э = з.target.parentElement;
        if (!э) continue;
        window.__подст.push({
          кто: э.id || (э.className || '').toString().split(' ')[0] || э.tagName,
          было: (з.oldValue || '').trim().slice(0, 60),
          стало: (з.target.textContent || '').trim().slice(0, 60)});
      } else if (з.type === 'childList' && з.removedNodes.length
                 && з.target.id) {
        const был = [...з.removedNodes]
          .map(n => (n.textContent || '').trim()).join(' ').trim();
        const стал = (з.target.textContent || '').trim();
        if (был && был !== стал && был.length < 200)
          window.__подст.push({кто: з.target.id, было: был.slice(0, 60),
                               стало: стал.slice(0, 60)});
      }
    }
  });
  // НАБЛЮДАТЬ НАДО ЗА `document`, А НЕ ЗА `documentElement`: в init-скрипте
  // второго ЕЩЁ НЕ СУЩЕСТВУЕТ, вызов бросает исключение, и вся вставка
  // молча не работает — проба печатает «подстановок 0» про страницу,
  // где их полтора десятка. Ровно та ловушка, что записана в §6.0.15.
  наб.observe(document, {subtree: true, childList: true,
    characterData: true, characterDataOldValue: true});
})();
"""

# Замер СМЕЩЕНИЯ от конкретной подстановки: вернуть прежний текст,
# снять раскладку, поставить нынешний, снять снова. Тот же приём,
# что у шрифта, — привести страницу в состояние первого кадра
# и применить ровно одно изменение.
# Аргумент у evaluate ОДИН, и разбирать пару надо распаковкой.
# Первая версия объявляла два параметра — второй приезжал
# undefined, элемент не находился, и режим печатал «подстановок 0»
# про страницу, на которой их две. Немой отказ внутри пробы,
# написанной для поиска немых отказов.
ВЕРНУТЬ_ТЕКСТ = """(([кто, было]) => {
  const э = document.getElementById(кто)
        || document.querySelector('.' + CSS.escape(кто));
  if (!э) return false;
  э.__нынешний = э.textContent;
  э.textContent = было;
  document.body.offsetHeight;
  return true;
})"""
ПРИМЕНИТЬ_ТЕКСТ = """((кто) => {
  const э = document.getElementById(кто)
        || document.querySelector('.' + CSS.escape(кто));
  if (!э || э.__нынешний === undefined) return false;
  э.textContent = э.__нынешний;
  document.body.offsetHeight;
  return true;
})"""


def подстановки(подлог_обёртки=False):
    """Все смены текста при загрузке — и сколько каждая двигает."""
    from playwright.sync_api import sync_playwright
    найдено = []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        сессия = _сессия(бр)
        for ш in ШИРИНЫ:
            for путь, имя, нужен_вход in ЭКРАНЫ:
                кон = бр.new_context(
                    viewport={"width": ш, "height": 900},
                    storage_state=сессия if нужен_вход else None)
                стр = кон.new_page()
                стр.add_init_script(СЛЕДИТЬ)
                стр.add_init_script(ЗАМЕР)
                if подлог_обёртки:
                    # ПОДЛОГ ВОЗВРАЩАЕТ ДЕФЕКТ, А НЕ ДОБАВЛЯЕТ СВОЙ.
                    # Первая версия «возвращала перенос» — а `flex-wrap:
                    # wrap` у ряда стоит и сейчас, то есть подлог был
                    # ПУСТОЙ ОПЕРАЦИЕЙ и доказывал бы ровно ничего.
                    # Дефект давала ОСНОВА колонки: пока она равна
                    # содержимому (`auto`), удлинение текста выдавливает
                    # выпадашку на следующую строку. Её и возвращаем.
                    стр.add_init_script(
                        "addEventListener('DOMContentLoaded',()=>{"
                        "const s=document.createElement('style');"
                        "s.textContent='.tz-row>*:first-child"
                        "{flex:0 1 auto!important;min-width:0!important}"
                        ".tz-row .setting-sub{min-height:0!important}';"
                        "document.head.appendChild(s);})")
                стр.goto(БАЗА + путь, wait_until="domcontentloaded",
                         timeout=45000)
                try:
                    стр.wait_for_load_state("networkidle", timeout=15000)
                except Exception:
                    pass
                стр.wait_for_timeout(900)
                список = стр.evaluate("window.__подст") or []
                # склеиваем по элементу: одна подстановка бывает
                # несколькими записями наблюдателя
                видано = {}
                for з in список:
                    if з["было"] and з["было"] != з["стало"]:
                        видано.setdefault(з["кто"], з)
                for кто, з in видано.items():
                    if not стр.evaluate(ВЕРНУТЬ_ТЕКСТ, [кто, з["было"]]):
                        continue
                    стр.wait_for_timeout(60)
                    до = _снимок(стр)
                    стр.evaluate(ПРИМЕНИТЬ_ТЕКСТ, кто)
                    стр.wait_for_timeout(60)
                    после = _снимок(стр)
                    дв, макс, им = _д(до, после)
                    найдено.append((ш, имя, кто, з["было"][:34],
                                    з["стало"][:34], дв, макс, им))
                кон.close()
        бр.close()
    return найдено


def печать_подстановок(найдено, заголовок):
    print(заголовок)
    print("  %-6s %-9s %-14s %-30s %5s %8s  %s"
          % ("ширина", "экран", "элемент", "было -> стало", "шт",
             "макс,px", "кто уехал"))
    for ш, имя, кто, было, стало, дв, макс, им in найдено:
        print("  %-6d %-9s %-14s %-30s %5d %8.1f  %s"
              % (ш, имя, кто[:14], (было + " -> " + стало)[:30], дв, макс, им))
    м = max([x[6] for x in найдено] or [0.0])
    print("  ВСЕГО подстановок: %d, максимум смещения: %.1f px"
          % (len(найдено), м))
    return м



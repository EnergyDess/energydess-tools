def образцы_источника(источник):
    """Сохранённые образцы страниц источника — (имя, разметка).

    Файловый замер вместо живого, и это условие применения: вопрос
    «верно ли мы разбираем вёрстку» к доступности сайта отношения
    не имеет, а живой прогон у wer.ru с машины разработчика невозможен
    вовсе — TCP-соединение не устанавливается (замер 2026-09-04).
    """
    из = []
    каталог = os.path.join(ОБРАЗЦЫ, источник.домен.replace(".", "_"))
    for путь in sorted(glob.glob(os.path.join(каталог, "*.html.gz"))):
        # ВЫДАЧИ СЮДА НЕ ВХОДЯТ: у них нет ни разделов, ни описания
        # выпуска, и проба страницы честно объявила бы разбор мёртвым
        if os.path.basename(путь).startswith("search_"):
            continue
        из.append((os.path.basename(путь), _прочитать(путь)))
    return из


def вёрстка(тихо=False):
    """Жив ли разбор на образцах вёрстки каждого источника."""
    беды = []
    if not тихо:
        print("=" * 72)
        print("B.4 ПРОБА ВЁРСТКИ — ЖИВ ЛИ РАЗБОР")
        print("=" * 72)
    for и in источники.ПОРЯДОК:
        образцы = образцы_источника(и)
        if not образцы:
            if not тихо:
                print("%-8s СПРОСИТЬ НЕЧЕМ: образцов нет в %s"
                      % (и.имя, os.path.join(ОБРАЗЦЫ,
                                             и.домен.replace(".", "_"))))
            беды.append((и.имя, "образцов нет"))
            continue
        плохих = 0
        for имя, html_ in образцы:
            признаки, дл, длп = вёрстка_по_странице(и, html_)
            # РАЗБОР СЧИТАЕТСЯ ЖИВЫМ, когда нашлись ОПИСАНИЕ, НАЗВАНИЕ
            # и РАЗДЕЛ О ДОЗИРОВАНИИ. Вещество и показания бывают
            # отсутствующими законно (замер: у Видаля блока вещества
            # нет у 12 страниц из 63), и требовать их значило бы
            # краснеть на исправном разборе
            живо = (признаки["описание"] and признаки["название"]
                    and признаки["раздел_доз"])
            if not живо:
                плохих += 1
                беды.append((и.имя, имя))
            if not тихо:
                print("  %-8s %-34s %s  доз %5d зн, показ %5d зн"
                      % (и.имя, имя[:32], "жив " if живо else "МЁРТВ",
                         дл, длп))
                if not живо:
                    нет = [к for к, v in признаки.items() if not v]
                    print("           не разобралось: %s" % ", ".join(нет))
        if not тихо and not плохих:
            print("  %-8s образцов %d, разбор жив на всех" % (и.имя,
                                                              len(образцы)))
    return беды



def _знаков_раздела(и, образцы):
    """ДОКАЗАТЕЛЬСТВО: сколько знаков раздела о дозах разобралось."""
    всего = 0
    for _имя, html_ in образцы:
        _з, кусок = и.раздел_доз(html_)
        всего += len(дозы.без_тегов(кусок)) if кусок else 0
    return всего


def _карточек_в_выдаче(и, выдачи):
    """ДОКАЗАТЕЛЬСТВО для подлога адреса: сколько ссылок нашлось."""
    return sum(len(и.карточки(h)) for h in выдачи)



# D.6 — ПРАВИЛА СОПОСТАВЛЕНИЯ ПОСЛЕ ПОДКЛЮЧЕНИЯ ВТОРОГО ИСТОЧНИКА
# ═════════════════════════════════════════════════════════════════════
#
# ЧТО СПРАШИВАЕТСЯ. Не «работает ли сопоставление вообще» — на это
# отвечает проход аптечки, — а НЕ ОСЛАБЛО ЛИ ОНО У ВТОРОГО ИСТОЧНИКА.
# Каждое правило прогоняется НА ОБОИХ источниках одним и тем же
# набором подлогов: правило, действующее у Видаля и молчащее
# у wer.ru, — это дыра ровно того размера, ради которого весь заход.
#
# СТРАНИЦЫ НАСТОЯЩИЕ, ПОДМЕНЯЕТСЯ ИСКОМОЕ. Так и выглядит ошибка
# на бою: страница честная, а карточка человека описывает другое.

ПРАВИЛА = (
    # (имя, чем портим искомое, какое поле обязано не сойтись)
    ("другая-форма", {"форма": "syrup"}, "форма"),
    ("другое-название", {"название": "Совершенно другой препарат",
                         "имена": ["Совершенно другой препарат"]},
     "название"),
    ("чужое-вещество", {"вещество": "левоцетиризин"}, "вещество"),
    ("пролонг-против-обычного", {"название": "%s Ретард"}, "пролонг"),
)


def правила():
    """Каждое правило сопоставления — НА ОБОИХ источниках."""
    print("=" * 72)
    print("D.6 ПРАВИЛА СОПОСТАВЛЕНИЯ — ОДИНАКОВО ЛИ У ДВУХ ИСТОЧНИКОВ")
    print("=" * 72)
    плохих = 0
    for и in источники.ПОРЯДОК:
        образцы = образцы_источника(и)
        if not образцы:
            print("%-8s СПРОСИТЬ НЕЧЕМ: образцов нет" % и.имя)
            плохих += 1
            continue
        print("%s (образцов %d)" % (и.имя, len(образцы)))
        for имя_стр, html_ in образцы:
            опис = и.описание(html_)
            своё = и.название(опис)
            if not своё:
                print("   %-30s название не разобралось — пропуск"
                      % имя_стр[:28])
                плохих += 1
                continue
            вещ = (и.вещество(html_) or "").split()[0] if и.вещество(html_) \
                else ""
            основа = {"название": своё, "имена": [своё],
                      "форма": дозы.форма_страницы(опис)[0],
                      "доза": "", "вещество": вещ}
            ок0, _д0 = дозы.подходит(основа, html_, и)
            строка = "   %-26s своё=%s" % (имя_стр[:24], "OK" if ок0 else "НЕТ")
            if not ок0:
                плохих += 1
            for правило, порча, поле in ПРАВИЛА:
                # ПРАВИЛО ВЕЩЕСТВА ПРИМЕНИМО, ТОЛЬКО ЕСЛИ СТРАНИЦА ЕГО
                # ОБЪЯВИЛА, и это §5.8 (задача 199), а не поблажка:
                # «блока нет» — незнание, и отвергать по незнанию
                # значит терять подходящие страницы. Замер на образцах
                # Видаля: блок есть у ОДНОЙ из четырёх.
                #
                # ПРОБА ОБЯЗАНА ЭТО РАЗЛИЧАТЬ. Первая версия объявляла
                # «ПРОПУСТИЛ» на трёх страницах из четырёх — то есть
                # ругалась на исправное поведение, а проверка, которая
                # врёт, перестаёт читаться на третий раз (§6.0.2).
                if поле == "вещество" and not вещ:
                    строка += "  %s=нечем" % правило.split("-")[0]
                    continue
                искомое = dict(основа)
                for к, v in порча.items():
                    искомое[к] = (v % своё) if "%s" in str(v) else v
                if правило == "пролонг-против-обычного":
                    искомое["имена"] = [искомое["название"]]
                ок, детали = дозы.подходит(искомое, html_, и)
                # ПОДЛОГ ОБЯЗАН БЫТЬ ОТВЕРГНУТ. Прошёл — правило
                # у этого источника не действует
                отверг = not ок
                if not отверг:
                    плохих += 1
                строка += "  %s=%s" % (правило.split("-")[0],
                                       "отверг" if отверг else "ПРОПУСТИЛ")
            print(строка)
    print()
    print("НЕ СРАБОТАЛО ПРАВИЛ: %d" % плохих)
    if not плохих:
        print("Все правила действуют одинаково у обоих источников.")
    return плохих



def _прочитать(путь):
    """Образец вёрстки с диска.

    СЖАТЫ, И ЭТО НЕ ЭКОНОМИЯ РАДИ ЭКОНОМИИ: карточка источника весит
    543–633 КБ, восемь образцов — 3.7 МБ ЧУЖОЙ разметки, которая легла
    бы в публичный репозиторий навсегда. Сжатие даёт 0.5 МБ, а
    содержимое остаётся тем же ДО ЗНАКА — обрезать образцы нельзя,
    иначе проба вёрстки перестанет проверять настоящую вёрстку.
    """
    if путь.endswith(".gz"):
        return gzip.open(путь, "rt", encoding="utf-8",
                         errors="replace").read()
    return open(путь, encoding="utf-8", errors="replace").read()


def страницы_кеша(предел=None):
    """Страницы Видаля из кеша: (имя файла, разметка).

    Выдачи поиска отсеиваются — у них нет ни разделов, ни описания
    выпуска, и сверять на них нечего.
    """
    из = []
    for путь in sorted(glob.glob(os.path.join(КЕШ, "*.html"))):
        текст = open(путь, encoding="utf-8", errors="replace").read()
        # Признак страницы препарата, а не выдачи: есть заголовок
        # с названием либо блок активного вещества
        if "инструкция по применению" not in текст.lower():
            continue
        из.append((os.path.basename(путь), текст))
        if предел and len(из) >= предел:
            break
    return из



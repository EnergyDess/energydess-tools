def лямбда_карточек(источник):
    """Замер «сколько карточек находится в выдаче» для одного источника.

    Выдачи у источника может не быть в образцах — тогда мерка отдаёт
    None, и это отличается от нуля: «спросить нечем» и «карточек нет»
    разные факты (§6.0.1).
    """
    выдачи = выдачи_источника(источник)

    def мерка():
        if not выдачи:
            return -1
        return _карточек_в_выдаче(источник, выдачи)
    return мерка


def вёрстка_карточек(тихо=False):
    """Находятся ли карточки в выдаче — своя проба под подлог адреса.

    ОТДЕЛЬНАЯ ОТ `вёрстка`, и это не дублирование: та спрашивает про
    СТРАНИЦУ препарата, а адрес карточки живёт в ВЫДАЧЕ. Подлог,
    ломающий регулярку адресов, страницу не трогает вовсе — и проба
    страницы честно осталась бы зелёной.
    """
    беды = []
    for и in источники.ПОРЯДОК:
        выдачи = выдачи_источника(и)
        if not выдачи:
            continue        # выдач нет в образцах — спрашивать нечем
        найдено = _карточек_в_выдаче(и, выдачи)
        if not найдено:
            беды.append((и.имя, "карточек в выдаче 0"))
        if not тихо:
            print("  %-8s карточек в выдаче: %d" % (и.имя, найдено))
    return беды



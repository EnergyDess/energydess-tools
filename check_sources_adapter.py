def сверка(тихо=False):
    """Прямые вызовы против переходника Видаля, ПОСИМВОЛЬНО."""
    стр = страницы_кеша()
    if not стр:
        print("СПРОСИТЬ НЕЧЕМ: в кеше %s нет ни одной страницы препарата."
              % КЕШ)
        print("Наберите его: py check_medkit_all.py")
        return None
    в = источники.ВИДАЛЬ
    расхождений, всего = [], 0
    for имя, html_ in стр:
        плоско = дозы.без_тегов(html_)
        пары = (
            ("описание", дозы.описание(плоско), в.описание(html_)),
            ("вещество", дозы.вещество_страницы(html_), в.вещество(html_)),
            ("раздел_доз", дозы.раздел_доз_html(html_), в.раздел_доз(html_)),
            ("показания", дозы.раздел_показаний_html(html_),
             в.раздел_показаний(html_)),
        )
        for поле, было, стало in пары:
            всего += 1
            if было != стало:
                расхождений.append((имя, поле))
        # название считается от описания, и описание уже сверено
        всего += 1
        if дозы.название_страницы(дозы.описание(плоско)) != в.название(
                в.описание(html_)):
            расхождений.append((имя, "название"))
    if not тихо:
        print("=" * 72)
        print("B.2 ПЕРЕЕЗД ВИДАЛЯ НА ПЕРЕХОДНИК — ПОБАЙТНАЯ СВЕРКА")
        print("=" * 72)
        print("страниц препаратов в кеше: %d" % len(стр))
        print("сверено величин:           %d" % всего)
        print("РАСХОЖДЕНИЙ:               %d" % len(расхождений))
        for имя, поле in расхождений[:20]:
            print("   %s / %s" % (имя, поле))
        if not расхождений:
            print()
            print("Ни одного знака не потеряно. Переходник Видаля")
            print("делегирует в тот же код, и это проверено, а не обещано.")
    return расхождений



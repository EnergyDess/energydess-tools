# B.4 — ПРОБА ВЁРСТКИ
# ═════════════════════════════════════════════════════════════════════
#
# ЧТО СПРАШИВАЕТСЯ. Разбирается ли СЕГОДНЯШНЯЯ страница источника:
# нашлось ли описание выпуска, название, вещество, раздел о дозировании.
# Не «сколько схем даёт источник» — на этот вопрос отвечает мерка,
# и она обязана молчать, пока разбор мёртв.
#
# ИСХОДА ТРИ, И ТРЕТИЙ ОБЯЗАТЕЛЕН: «спросить не удалось» — не то же
# самое, что «разбор мёртв» (§6.0.1, урок задачи 233).

def вёрстка_по_странице(источник, html_):
    """Что разобралось на ОДНОЙ странице: словарь признак → bool."""
    опис = источник.описание(html_)
    _з, кусок = источник.раздел_доз(html_)
    _зп, кусокп = источник.раздел_показаний(html_)
    текст = дозы.без_тегов(кусок) if кусок else ""
    текстп = дозы.без_тегов(кусокп) if кусокп else ""
    return {
        "описание": bool(опис),
        "название": bool(источник.название(опис)),
        "форма": дозы.форма_страницы(опис)[0] is not None,
        "вещество": bool(источник.вещество(html_)),
        "раздел_доз": bool(текст.strip()),
        "показания": bool(текстп.strip()),
    }, len(текст), len(текстп)



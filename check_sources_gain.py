# -*- coding: utf-8 -*-
"""ЧТО ДАЛ ВТОРОЙ ИСТОЧНИК — раскладка находок ПО ИСТОЧНИКАМ.

BACKLOG №207, блок F.1. МЕРКА, код возврата всегда 0: «сколько схем
есть у чужих сайтов» — свойство чужих сайтов.

═══════════════════════════════════════════════════════════════════════
ЧЕМ ОТЛИЧАЕТСЯ ОТ `check_medkit_all` И `check_wer_gain`
═══════════════════════════════════════════════════════════════════════

`check_medkit_all` отвечает «на скольких позициях схема нашлась»
и раскладывает отказы по видам. Про то, КТО ИМЕННО её дал, он молчит —
и молчал бы, даже если бы второй источник не работал вовсе.

`check_wer_gain` (задача 238) отвечает «есть ли у wer.ru раздел там,
где Видаль молчит», и это ВЕРХНЯЯ ОЦЕНКА: сопоставления по названию,
форме и веществу он не делает вовсе.

ЗДЕСЬ спрашивается то, чего не спрашивал никто: сколько позиций
закрыл КАЖДЫЙ источник ПОСЛЕ сопоставления, то есть на боевом пути.

═══════════════════════════════════════════════════════════════════════
БОЕВЫМ ПУТЁМ, А НЕ СВОИМ ОБХОДОМ
═══════════════════════════════════════════════════════════════════════

Зовётся `main._апт_найти_дозы` — тот же код, что зовёт браузер. Свой
обход дал бы число про поведение, которого на бою нет (§6.0.7), и это
уже случалось: разведка задачи 181 держала своё правило отбора
и печатала «ВЫБОР НЕОДНОЗНАЧЕН» там, где сервер показывал схему.

ИСТОЧНИК ОПРЕДЕЛЯЕТСЯ ПО АДРЕСУ выдержки, тем же `_апт_ист_по_адресу`,
которым его записывает сервер. Второго мнения не заводится.

═══════════════════════════════════════════════════════════════════════
КЕШ ОБЯЗАТЕЛЕН, И ЭТО УСЛОВИЕ ПРИМЕНЕНИЯ
═══════════════════════════════════════════════════════════════════════

Два прогона — до подключения и после — обязаны видеть ОДНУ выдачу,
иначе разница «было 10, стало 18» может оказаться правкой чужого
сайта. Кеш берётся у `check_medkit_all` импортом; второго нет.

НА МАШИНЕ ПРОДА НЕ ЗАПУСКАТЬ. Замер 2026-09-04: обход всех позиций
на машине с одним vCPU уронил health-check в critical, прод отдавал
HTTP 503. Копия базы снимается и увозится, прогон идёт локально.

    py check_sources_gain.py --база <копия боевой базы>
"""

import asyncio
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

if "--база" in sys.argv:
    os.environ["DB_PATH"] = sys.argv[sys.argv.index("--база") + 1]
os.environ.setdefault("DB_PATH", "app.db")
os.environ.setdefault("MEDKIT_CACHE", ".dosage_cache")

import check_medkit_all as общий      # noqa: E402
import main                           # noqa: E402
import medkit_sources as источники    # noqa: E402


def _проверить_путь():
    п = os.environ["DB_PATH"].replace(chr(92), "/")
    if "/data/" in п:
        print("БОЕВАЯ БАЗА НЕ ОТКРЫВАЕТСЯ. Снимите копию.")
        sys.exit(0)


async def главное():
    _проверить_путь()
    if "--без-кеша" not in sys.argv:
        общий.включить_кеш()
        print("[кеш] страницы берутся из %s" % общий.КЕШ)
    поз = общий.позиции(None)
    print("=" * 72)
    print("ЧТО ДАЛ КАЖДЫЙ ИСТОЧНИК (F.1)")
    print("=" * 72)
    print("позиций: %d" % len(поз))
    print()
    счёт = {и.имя: 0 for и in источники.ПОРЯДОК}
    отказы, всего_нашлось = {}, 0
    # ── ЧТО СКАЗАЛ КАЖДЫЙ ИСТОЧНИК ПО ОТДЕЛЬНОСТИ (F.2) ────────────
    #
    # Из общего итога этого НЕ ВИДНО: порядок жёсткий, и наружу уходит
    # отказ ПЕРВОГО источника. То есть «нет_названия» в сводке — это
    # ответ Видаля, а что на ту же позицию сказал wer.ru, там молчит.
    #
    # Вопрос не праздный: замер задачи 239 обещал 7 новых схем, и это
    # была ВЕРХНЯЯ ОЦЕНКА без сопоставления. Расхождение с боевым
    # числом объясняется только поисточниковой раскладкой.
    поотдельности = {и.имя: {} for и in источники.ПОРЯДОК}
    for п in поз:
        итог, _причина, вид, _подск = await main._апт_найти_дозы(п)
        if итог:
            всего_нашлось += 1
            кто = main._апт_ист_по_адресу(итог[1])
            счёт[кто.имя] = счёт.get(кто.имя, 0) + 1
        else:
            отказы[вид or "—"] = отказы.get(вид or "—", 0) + 1
        if "--по-источникам" in sys.argv:
            for и in источники.ПОРЯДОК:
                кл = main._апт_клиент(и)
                try:
                    база = await main._апт_базовая_линия(кл, и)
                except Exception:
                    база = None
                if база is None:
                    ключ = "спросить не удалось"
                else:
                    ит, _пр, вд, _пд = await main._апт_искать_в_источнике(
                        кл, п, и, база)
                    ключ = "НАШЁЛ" if ит else (вд or "—")
                поотдельности[и.имя][ключ] = (
                    поотдельности[и.имя].get(ключ, 0) + 1)
    print("── НАШЛОСЬ: %d из %d ──" % (всего_нашлось, len(поз)))
    for и in источники.ПОРЯДОК:
        print("   %-10s (%s): %d" % (и.имя, и.домен, счёт.get(и.имя, 0)))
    print()
    print("── НЕ НАШЛОСЬ: %d ──" % (len(поз) - всего_нашлось))
    print("   (вид отказа — от ПЕРВОГО источника: порядок жёсткий)")
    for вид, н in sorted(отказы.items(), key=lambda п: -п[1]):
        print("   %-18s %d" % (вид, н))
    if "--по-источникам" in sys.argv:
        print()
        print("── ЧТО СКАЗАЛ КАЖДЫЙ ИСТОЧНИК ПО ОТДЕЛЬНОСТИ ──")
        for и in источники.ПОРЯДОК:
            print("   %s (%s):" % (и.имя, и.домен))
            for ключ, н in sorted(поотдельности[и.имя].items(),
                                  key=lambda п: -п[1]):
                print("      %-22s %d" % (ключ, н))
    print()
    print("ЧИСЛО ВТОРОГО ИСТОЧНИКА — ЭТО «НОВЫЕ»: порядок жёсткий")
    print("(Видаль первым), и второй спрашивается ТОЛЬКО когда первый")
    print("не дал. Значит каждая его находка — позиция, которой без него")
    print("схемы не было бы вовсе.")
    print()
    print("ОТКАЗ «сеть» — НЕ СВОЙСТВО ИСТОЧНИКА, а замер момента:")
    print("рукопожатие TLS на машине с одним vCPU занимает 3–30 с")
    print("(разбор — CLAUDE.md §5.8). Повторите прогон, если их много.")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(главное()))

#     антибота спрашивается ТОЛЬКО у короткого тела либо у кода
#     403/429/432;
#   · признак содержимого считается ЧИСЛОМ ВХОЖДЕНИЙ, а не фактом.
#     Слово запроса стоит в поле поиска ВСЕГДА, даже когда не нашлось

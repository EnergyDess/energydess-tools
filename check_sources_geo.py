def _откуда() -> str:
    прил = os.getenv("FLY_APP_NAME")
    if прил:
        return f"ПРОД Fly · {прил} · регион {os.getenv('FLY_REGION', '?')}"
    return "машина разработчика"


def _классифицировать(код, тело, ошибка, слово):
    """Пять исходов, разбор по порядку — от самого сильного вывода."""
    if ошибка:
        return "СЕТЬ", ошибка, 0

    низ = тело.lower()
    вхождений = низ.count(слово.lower())

    if код == 451:
        return "ГЕОГРАФИЯ", f"HTTP 451, тело {len(тело)} байт", вхождений

    for сл in ГЕО:
        if сл in низ:
            return "ГЕОГРАФИЯ", f"HTTP {код}, оборот {сл!r}", вхождений

    # Заслон спрашивается у КОДА либо у КОРОТКОГО тела — разбор выше
    if код in (403, 429, 432, 503) or len(тело) < АНТИБОТ_ПОТОЛОК:
        for сл in АНТИБОТ:
            if сл in низ:
                return "АНТИБОТ", f"HTTP {код}, признак {сл!r}", вхождений
        if код in (403, 429, 432, 503):
            return "АНТИБОТ", (f"HTTP {код}, тело {len(тело)} байт, "
                               "признак не опознан"), вхождений

    if код != 200:
        return "НЕТ_СТРУКТУРЫ", f"HTTP {код}", вхождений
    if len(тело) < ПОРОГ_ПУСТОТЫ:
        return "ПУСТО", f"тело {len(тело)} байт (< {ПОРОГ_ПУСТОТЫ})", вхождений

    if вхождений >= ПОРОГ_ВХОЖДЕНИЙ:
        return "ОТВЕЧАЕТ", f"{слово!r} × {вхождений}", вхождений
    return "НЕТ_СТРУКТУРЫ", (f"текст есть ({len(тело)} байт), "
                             f"{слово!r} × {вхождений} — эхо запроса,"
                             " а не выдача"), вхождений


def главная() -> int:
    print("ЧТО ОТВЕЧАЕТ — ЗАМЕР")
    print("=" * 74)
    print(f"  откуда: {_откуда()}")
    print(f"  httpx:  {httpx.__version__}")
    print()
    print(f"  {'источник':<28} {'код':>4} {'мс':>6} {'байт':>8} "
          f"{'слово':>6}  исход")
    print("  " + "-" * 70)

    итог = {}
    for имя, адрес, слово in ЦЕЛИ:
        код, тело, ошибка = 0, "", ""
        нач = time.monotonic()
        try:
            with httpx.Client(headers=ГОЛОВА, timeout=25.0,
                              follow_redirects=True, verify=True) as кл:
                отв = кл.get(адрес)
                код = отв.status_code
                тело = отв.text
        except Exception as e:                       # noqa: BLE001
            ошибка = f"{type(e).__name__}: {e}"
        мс = int((time.monotonic() - нач) * 1000)

        исход, почему, вх = _классифицировать(код, тело, ошибка, слово)
        итог[имя] = исход
        print(f"  {имя:<28} {код:>4} {мс:>6} {len(тело):>8} {вх:>6}  "
              f"{исход:<14} {почему}")

    print()
    print("  СВОДКА ПО ИСХОДАМ")
    for вид in ("ОТВЕЧАЕТ", "НЕТ_СТРУКТУРЫ", "АНТИБОТ",
                "ГЕОГРАФИЯ", "ПУСТО", "СЕТЬ"):
        кто = [и for и, в in итог.items() if в == вид]
        print(f"    {вид:<14} {len(кто)}"
              + (f"  — {', '.join(кто)}" if кто else ""))
    print()
    print("  Код возврата 0 всегда: это МЕРКА, а не проверка.")
    return 0


if __name__ == "__main__":
    sys.exit(главная())

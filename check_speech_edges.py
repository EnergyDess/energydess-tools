def экран():
    """Доходит ли текст сервера до браузера. Требует стенда."""
    from playwright.sync_api import sync_playwright
    with sync_playwright() as pw:
        бр = pw.chromium.launch()
        ctx = бр.new_context(viewport={"width": 1440, "height": 900})
        pg = ctx.new_page()
        pg.goto(БАЗА + "/login", wait_until="domcontentloaded")
        pg.fill("input[name=email]", ПОЧТА)
        pg.fill("input[name=password]", ПАРОЛЬ)
        pg.click("button[type=submit]")
        pg.wait_for_load_state("networkidle")
        pg.goto(БАЗА + "/medkit", wait_until="networkidle")
        итог = pg.evaluate("""async () => {
          const blob = new Blob([new Uint8Array(2048)], {type: 'audio/wav'});
          const r = await голосВТекст(blob);
          /* ВТОРОЙ ИСХОД — «сервис ответил, но не расслышал» —
             спрашивается ОТДЕЛЬНО: живой сервис на мусор отвечает
             отказом, а пустой текст он даёт на ТИШИНЕ, и подделать
             её в браузере нечем. Фраза при этом обязана быть ДРУГОЙ. */
          const пусто = (typeof голосСказать === 'function')
            ? голосСказать({текст: '', ошибка: ''}) : '';
          return {тип: typeof r, текст: r && r.текст, ошибка: r && r.ошибка,
                  скажем: (typeof голосСказать === 'function')
                    ? голосСказать(r) : '(голосСказать не объявлена)',
                  приПустом: пусто};
        }""")
        ctx.close()
        бр.close()
    print("ЧТО ВЕРНУЛА `голосВТекст`: тип %s, текст %r"
          % (итог["тип"], итог["текст"]))
    print("ЧТО ПОКАЖЕМ ЧЕЛОВЕКУ: %s" % итог["скажем"][:140])
    print("ЕСЛИ СЕРВИС ОТВЕТИЛ, НО НЕ РАССЛЫШАЛ: %s" % итог["приПустом"][:140])
    print("   фразы РАЗНЫЕ: %s"
          % ("ДА" if итог["скажем"] != итог["приПустом"] else "НЕТ — исходы схлопнуты"))
    свой = bool(итог.get("ошибка"))
    print()
    print("ДОКАЗАТЕЛЬСТВО: текст пришёл С СЕРВЕРА: %s" % ("ДА" if свой else "НЕТ"))
    print("   до правки функция отдавала голую строку, и это поле")
    print("   не существовало вовсе — человек видел одну фразу на все исходы.")


if __name__ == "__main__":
    if "--экран" in sys.argv:
        экран()
    else:
        прогон()
    sys.exit(0)

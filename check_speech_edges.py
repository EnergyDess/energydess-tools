БАЗА = os.getenv("HOVER_BASE", "http://127.0.0.1:8899")
ПОЧТА = os.getenv("STAND_EMAIL", "screenshot@local.dev")
ПАРОЛЬ = os.getenv("STAND_PASSWORD", "Screenshot-Local-2026")


def _wav(секунд, громко=False):
    """WAV: тишина либо ровный тон. Настоящий контейнер, не мусор."""
    буф = io.BytesIO()
    with wave.open(буф, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(16000)
        кадров = int(16000 * секунд)
        данные = b"".join(
            struct.pack("<h", int(8000 * math.sin(2 * math.pi * 220 * i / 16000))
                        if громко else 0)
            for i in range(кадров))
        w.writeframes(данные)
    return буф.getvalue()


def _обрыв(байты):
    """Файл с ВЕРНЫМ заголовком и обрубленным телом.

    Отличается от мусора тем, что контейнер начинается правильно:
    разбор доходит до середины и падает там, а не на первом байте.
    """
    return байты[:max(64, len(байты) // 3)]


СЛУЧАИ = [
    ("тишина 3 с", lambda: _wav(3.0), "audio/wav"),
    ("очень короткая 0.1 с", lambda: _wav(0.1, True), "audio/wav"),
    ("обрыв записи (заголовок цел, тело обрублено)",
     lambda: _обрыв(_wav(3.0, True)), "audio/wav"),
    ("тон 2 с (контроль: вход заведомо годен)",
     lambda: _wav(2.0, True), "audio/wav"),
]


def прогон():
    c = httpx.Client(base_url=БАЗА, follow_redirects=False, timeout=180)
    r = c.post("/login", data={"email": ПОЧТА, "password": ПАРОЛЬ})
    if r.status_code != 302:
        print("ВХОД НЕ ПРОШЁЛ (%s) — замер не состоялся" % r.status_code)
        return
    print("%-46s %-6s %s" % ("случай", "HTTP", "что увидит человек"))
    print("-" * 100)
    for имя, дай, тип in СЛУЧАИ:
        данные = дай()
        o = c.post("/nutrition/api/transcribe",
                   files={"file": ("rec.wav", данные, тип)})
        try:
            тело = o.json()
        except ValueError:
            тело = {"error": "тело не JSON: " + o.text[:80]}
        видно = тело.get("error") or ("текст: %r" % (тело.get("text") or ""))
        print("%-46s %-6s %s" % ("%s (%d Б)" % (имя, len(данные)),
                                 o.status_code, видно[:120]))
    print()
    print("ПОТЕРЯ СЕТИ ПОСЕРЕДИНЕ здесь НЕ СПРАШИВАЕТСЯ и это названо:")
    print("  подделать её можно только подменой OPENROUTER_AUDIO_URL,")
    print("  то есть ПЕРЕЗАПУСКОМ приложения с другим окружением —")
    print("  внутри одного прогона это не делается. Разбор ветки сети")
    print("  и её текст — §2.5 и тесты обрыва соединения.")



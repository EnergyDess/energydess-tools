# ГЛАВНАЯ НАХОДКА ЗАХОДА, и найдена она замером, а не чтением: сервер
# сочиняет ЧЕЛОВЕЧЕСКИЙ текст с советом (§2.5, семь случаев задачи
# 128), а `голосВТекст` возвращала ГОЛУЮ СТРОКУ — у тела с полем

# -*- coding: utf-8 -*-
"""ПРОВЕРКА 30: обращение к переменной стенда через `window`.

═══════════════════════════════════════════════════════════════════
ЧТО ЭТО ЗА ДЕФЕКТ И ПОЧЕМУ ОН НЕ ЛЕЧИТСЯ ЗАПИСЬЮ В ПРАВИЛАХ
═══════════════════════════════════════════════════════════════════

`let` и `const` на верхнем уровне классического скрипта попадают
в ГЛОБАЛЬНУЮ ЛЕКСИЧЕСКУЮ ОБЛАСТЬ, но свойством `window` НЕ СТАНОВЯТСЯ.
То есть `page.evaluate("АПТ_ПОЗИЦИИ")` работает, а
`page.evaluate("window.АПТ_ПОЗИЦИИ")` возвращает `undefined`.

Отказ НЕМОЙ и выглядит как пробел в данных: проба печатает «на стенде
нет подходящей позиции» при тридцати семи подходящих и объявляет
пробелом seed собственную ошибку. Ни исключения, ни строки в журнале.

ЗАПИСАНО В §5.8 ДВАЖДЫ — задачами 201 и 249 — И СРАБОТАЛО В ТРЕТИЙ РАЗ
(задача 250, блок D). Текст правил эту ошибку не предотвращает: его
читают, но не исполняют. Значит закрывается КЛАСС машиной (§6.0.7).

═══════════════════════════════════════════════════════════════════
ПРИЗНАК ВЫВОДИТСЯ, А НЕ ПЕРЕЧИСЛЯЕТСЯ
═══════════════════════════════════════════════════════════════════

Список «вот эти имена через window не читаются» отстал бы от разметки
молча — ровно как отставали `names`, `pages` и `ЭКРАНЫ`. Поэтому:

  МНОЖЕСТВО ЛЕКСИЧЕСКИХ — имена, объявленные в шаблонах через
                          `let`/`const`;
  МНОЖЕСТВО ОКОННЫХ     — имена, объявленные через `function`/`var`
                          либо присвоенные `window.имя = …`.

Находка — обращение `window.ИМЯ` в пробе, где ИМЯ лежит в первом
множестве и НЕ лежит во втором. Имя, объявленное обоими способами,
находкой НЕ является: через `window` оно доступно законно.

ГРАНИЦА НАЗВАНА ЧЕСТНО. Уровень объявления здесь не разбирается:
`let` внутри функции тоже попадает в множество лексических, и
обращение `window.<такое имя>` будет названо находкой. Ошибка при этом
В БЕЗОПАСНУЮ СТОРОНУ — читать локальную переменную через `window`
нельзя и подавно, — а разбор области видимости потребовал бы парсера
JS, которого в проекте нет.

ПРОБЫ БЕРУТСЯ У GIT, а не обходом каталога: файл, лежащий рядом
и не отслеживаемый, к работе проекта не относится.
"""
import ast
import io
import os
import re
import subprocess
import sys
import probe_guard  # noqa: F401  ПРОПУСК вместо трассы (§6.0.1)

sys.stdout.reconfigure(encoding="utf-8")

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))

# Объявление переменной. Имя — латиница либо кириллица: соглашение
# проекта допускает и то и другое (§6.0 запрещает кириллицу только
# в машинном слое — shell, jq, имена файлов).
ИМЯ = r"[A-Za-zА-Яа-яЁё_$][A-Za-zА-Яа-яЁё0-9_$]*"
ЛЕКСИЧЕСКОЕ = re.compile(r"(?:^|[;{}\s])(?:let|const)\s+(" + ИМЯ + r")\s*[=;]")
ОКОННОЕ = re.compile(
    r"(?:^|[;{}\s])(?:function\s+(" + ИМЯ + r")\s*\(|var\s+(" + ИМЯ + r")\s*[=;]"
    r"|window\.(" + ИМЯ + r")\s*=)")
# Обращение из пробы: `window.ИМЯ` и `window['ИМЯ']`.
ОБРАЩЕНИЕ = re.compile(r"window\s*(?:\.\s*(" + ИМЯ + r")|\[\s*['\"](" + ИМЯ + r")['\"]\s*\])")


def _файлы(маска):
    """Отслеживаемые git файлы по маске."""
    try:
        вывод = subprocess.run(
            ["git", "-C", КОРЕНЬ, "ls-files", "-z", маска],
            capture_output=True, check=True).stdout
    except Exception:
        return []
    return [п for п in вывод.decode("utf-8").split("\0") if п]


def множества():
    """Имена стенда: лексические и оконные."""
    лекс, окон = set(), set()
    for путь in _файлы("templates/*.html") + _файлы("static/*.js"):
        полный = os.path.join(КОРЕНЬ, путь)
        try:
            т = io.open(полный, encoding="utf-8").read()
        except OSError:
            continue
        for м in ЛЕКСИЧЕСКОЕ.finditer(т):
            лекс.add(м.group(1))
        for м in ОКОННОЕ.finditer(т):
            окон.add(next(г for г in м.groups() if г))
    return лекс, окон


# ── ПРОЗА — НЕ КОД (урок задачи 99) ──────────────────────────────
#
# ПЕРВЫЙ ПРОГОН ДАЛ ВОСЕМЬ НАХОДОК, ИЗ НИХ ШЕСТЬ ЛОЖНЫХ: рассказ
# о ловушке в комментарии («Первая версия читала `window.АИ.черновик`»)
# ничем не отличался от обращения к стенду. Проверка, которая врёт
# в трёх случаях из четырёх, перестаёт читаться на третий раз.
#
# СНИМАЕТСЯ ДВУМЯ СЛОЯМИ, и оба обязательны:
#   PYTHON — разбором СИНТАКСИЧЕСКОГО ДЕРЕВА: комментариев в нём нет
#            вовсе, а JS-код проб лежит в строковых литералах;
#   JS     — `//` и `/* */` внутри самих литералов: пояснение к чужому
#            коду пишут там же, где код.
JS_СТРОЧНЫЙ = re.compile(r"//[^\n]*")
JS_БЛОЧНЫЙ = re.compile(r"/\*.*?\*/", re.S)


def _без_комментариев(текст):
    """JS-комментарии снимаются, длина сохраняется — номера строк целы."""
    def пусто(м):
        return re.sub(r"[^\n]", " ", м.group(0))
    return JS_СТРОЧНЫЙ.sub(пусто, JS_БЛОЧНЫЙ.sub(пусто, текст))


def _литералы(исходник):
    """Строковые литералы файла: (номер первой строки, текст)."""
    try:
        дерево = ast.parse(исходник)
    except SyntaxError:
        return []
    # ДОКСТРИНГ — ТОЖЕ ПРОЗА, и он тоже строковый литерал. Первый
    # прогон после снятия комментариев дал ЧЕТЫРЕ находки, и две
    # из них лежали в шапках проб — там, где ловушка ОПИСАНА, а не
    # допущена. AST отличает докстринг по месту: первый литерал
    # модуля, функции или класса.
    докстринги = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.Module, ast.FunctionDef,
                             ast.AsyncFunctionDef, ast.ClassDef)):
            тело = getattr(узел, "body", None) or []
            if (тело and isinstance(тело[0], ast.Expr)
                    and isinstance(тело[0].value, ast.Constant)
                    and isinstance(тело[0].value.value, str)):
                докстринги.add(id(тело[0].value))
    куски = []
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Constant) and isinstance(узел.value, str)
                and id(узел) not in докстринги):
            куски.append((узел.lineno, узел.value))
    return куски


def находки():
    """Обращения `window.ИМЯ`, где ИМЯ через window не читается."""
    лекс, окон = множества()
    цель = лекс - окон
    итог = []
    свой = os.path.basename(__file__)
    for путь in _файлы("check_*.py") + _файлы("shots_*.py") + _файлы("tests/*.py"):
        полный = os.path.join(КОРЕНЬ, путь)
        # СТРОКА ПРОВЕРКИ САМА СЕБЯ НЕ НАХОДИТ: здесь `window.ИМЯ`
        # стоит внутри регулярки, а не обращением к стенду.
        if os.path.basename(полный) == свой:
            continue
        try:
            исходник = io.open(полный, encoding="utf-8").read()
        except OSError:
            continue
        for первая, литерал in _литералы(исходник):
            чистый = _без_комментариев(литерал)
            for н, строка in enumerate(чистый.split("\n")):
                for м in ОБРАЩЕНИЕ.finditer(строка):
                    имя = м.group(1) or м.group(2)
                    if имя in цель:
                        итог.append({"файл": путь, "строка": первая + н,
                                     "имя": имя, "текст": строка.strip()[:90]})
    return итог, цель


def main():
    контроль = "--контроль" in sys.argv
    if контроль:
        return _контроль()

    итог, цель = находки()
    print("ПРОВЕРКА 30: переменные стенда через `window`")
    print("=" * 68)
    print("  имён, доступных ТОЛЬКО лексически: %d" % len(цель))
    if not итог:
        print("\n  ОБРАЩЕНИЙ ЧЕРЕЗ `window` НЕТ — чисто.")
        return 0
    print("\n  НАХОДКИ (%d):" % len(итог))
    for н in итог:
        print("    %s:%d  window.%s" % (н["файл"], н["строка"], н["имя"]))
        print("        %s" % н["текст"])
    print("\n  Через `window` эти имена читаются как `undefined`:"
          " `let`/`const` свойства окна не создают.")
    return 1


def _контроль():
    """Подлог: обращение через `window` кладётся в настоящий файл.

    ОБЕ ПОЛОВИНЫ ОБЯЗАТЕЛЬНЫ. «Находит подложенное» проходит и у пробы,
    которая ругается на всё подряд; поэтому вторая половина требует,
    чтобы ЗАКОННОЕ обращение (`window.<имя функции>`) осталось чистым.
    """
    # ПОДЛОГ КЛАДЁТСЯ В ФАЙЛ, КОТОРЫЙ ПРОВЕРКА ЧИТАЕТ. Первая версия
    # целила в свежий, ещё не добавленный в git, — а список проб берётся
    # у `git ls-files`, и подлог просто не попадал в область поиска.
    # Контроль печатал «НЕ НАЙДЕН», и поймало это ДОКАЗАТЕЛЬСТВО
    # (находок было 0, стало 0), а не вердикт (§6.0.3).
    пробы = _файлы("check_*.py")
    цель_файл = None
    for п in пробы:
        if os.path.basename(п) != os.path.basename(__file__):
            цель_файл = os.path.join(КОРЕНЬ, п)
            break
    if not цель_файл:
        print("ОСТАНОВЛЕНО: отслеживаемых проб нет — подложить некуда")
        return 2
    исходник = io.open(цель_файл, encoding="utf-8").read()
    лекс, окон = множества()
    лексическое = sorted(лекс - окон)
    оконное = sorted(окон & лекс) or sorted(окон)
    if not лексическое:
        print("ОСТАНОВЛЕНО: лексических имён не нашлось — подложить нечего")
        return 2
    if not оконное:
        print("ОСТАНОВЛЕНО: оконных имён не нашлось — обратный подлог невозможен")
        return 2

    до, _ = находки()
    плохих = 0
    try:
        for имя, ждём, метка in ((лексическое[0], True, "лексическое"),
                                 (оконное[0], False, "оконное (ОБРАТНЫЙ)")):
            io.open(цель_файл, "wb").write(
                (исходник + "\n_подлог = \"window.%s\"\n" % имя).encode("utf-8"))
            # подлог — строковый литерал: ровно та форма, в которой
            # обращение живёт в настоящих пробах
            после, _ = находки()
            новых = [н for н in после if н not in до]
            нашла = any(н["имя"] == имя for н in новых)
            # ИСХОД НАЗЫВАЕТСЯ СЛОВОМ, РАЗНЫМ ДЛЯ ДВУХ ПОЛОВИН:
            # у прямого подлога «НАЙДЕН» значит «проба зряча»,
            # у обратного то же слово значило бы «проба нашла лишнее».
            if нашла == ждём:
                знак = "НАЙДЕН" if ждём else "ЧИСТО (ложной находки нет)"
            else:
                знак = "НЕ НАЙДЕН" if ждём else "ЛОЖНАЯ НАХОДКА"
            print("  подлог %-22s имя=%-16s ждём=%-5s -> %s"
                  % (метка, имя, ждём, знак))
            print("      доказательство: находок было %d, стало %d"
                  % (len(до), len(после)))
            плохих += 0 if нашла == ждём else 1
    finally:
        # ВОЗВРАТ КОПИЕЙ ЦЕЛОГО ТЕКСТА, а не обратной заменой: якорь
        # обратной замены находится не там, где ждёшь (урок задачи 249).
        io.open(цель_файл, "wb").write(исходник.encode("utf-8"))

    чисто, _ = находки()
    if чисто != до:
        print("  ВОЗВРАТ НЕ СОСТОЯЛСЯ: находок %d вместо %d"
              % (len(чисто), len(до)))
        плохих += 1
    print("")
    print("  подлогов 2, беды %d" % плохих)
    return 1 if плохих else 0


if __name__ == "__main__":
    sys.exit(main())

def _инварианты(о, до=None, источник=None):
    """Что нарушено на ЦЕЛЕВОМ экране. Пусто — экран себе не противоречит.

    `до` и `источник` — отпечаток и вкладка, ОТКУДА пришли. Без них
    правило владельца 2026-08-22 не выражается вовсе: оно говорит
    не «дата всегда сегодняшняя», а «дата сбрасывается ИЗ ИСТОРИИ
    и сохраняется отовсюду ещё».
    """
    беды = []
    if о["вкладка"] == "diary":
        if о["is_sel"] != 1:
            беды.append(
                "ИНВ-1 представимость: клеток is-sel %s вместо 1 "
                "(дата %s, залитых клеток %s — залитая «сегодня» читается "
                "как выбранная)" % (о["is_sel"], о["дата"], о["залито"]))
        if источник == "history" and о["дата"] != о["сегодня"]:
            беды.append("ИНВ-2 сброс из «Истории»: пришли из истории, "
                        "а дневник открыт на %s при сегодня %s"
                        % (о["дата"], о["сегодня"]))
        if (источник and источник != "history" and до
                and abs(до["расстояние"]) <= до["окно"]
                and о["дата"] != до["дата"]):
            беды.append("ИНВ-2б сохранение дня: на «%s» был выбран %s "
                        "(в окне), а дневник открылся на %s — день отобран "
                        "без причины" % (источник, до["дата"], о["дата"]))
        if abs(о["расстояние"]) > о["окно"]:
            беды.append("ИНВ-3 окно: %s на %s дней от сегодня при окне ±%s"
                        % (о["дата"], abs(о["расстояние"]), о["окно"]))
    # СРАВНЕНИЕ ПО ВХОЖДЕНИЮ, А НЕ ПО НАЧАЛУ СТРОКИ. Первая версия
    # требовала `startswith` и дала 30 ложных находок из 30 на исправном
    # коде: подпись пути записи звучит «Запись пойдёт в дневник ЗА <дата>»,
    # то есть дату несёт хвостом. Проверка, которая врёт в ста процентах
    # случаев, не читается вовсе (§6.0.2, довод проверки 4), — и врала
    # именно она, а не экран.
    ожид = (о["ожидаемая_подпись"] or "").lower()
    for имя in ("подпись_полосы", "подпись_записи", "подпись_истории"):
        текст = о[имя]
        if текст and ожид and ожид not in текст:
            беды.append("ИНВ-4 согласованность: %s = %r, а S.date = %s (%r)"
                        % (имя, текст, о["дата"], ожид))
    return беды


def _вкладки(стр):
    """Список вкладок — ИЗ РАЗМЕТКИ, а не из строки в этом файле.

    Седьмая вкладка попадёт в матрицу сама. Перечень здесь был бы
    ровно тем `ЭКРАНЫ`, который в check_hover пришлось выводить
    из роутов после того, как пятнадцать страниц не снимались ни дня.
    """
    return стр.eval_on_selector_all(
        ".nut-nav-btn", "es => es.map(e => e.dataset.tab)")


def _открыть(стр, порча=""):
    стр.goto(ch.БАЗА + "/nutrition", wait_until="networkidle")
    стр.wait_for_timeout(1200)
    if порча:
        стр.evaluate(порча)


def _перейти(стр, вкладка):
    стр.click("[data-tab='%s']" % вкладка)
    стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 700)


def прогон(стр, порча=""):
    """(находок, долг, строки_отчёта, пар). Матрица всех упорядоченных пар."""
    _открыть(стр, порча)
    вкладки = _вкладки(стр)
    находок = долг = пар = 0
    отчёт = []
    # Что именно переживает переходы — по ключам. Нужно человеку, а не
    # коду: «194 находки» не отвечает на вопрос «что за состояние
    # и законно ли ему выживать», а перечень ключей отвечает сразу.
    по_ключам = {}
    for источник in вкладки:
        for цель in вкладки:
            if источник == цель:
                continue
            пар += 1
            # КАЖДАЯ ПАРА — С ЧИСТОЙ СТРАНИЦЫ. Иначе состояние предыдущей
            # пары доезжает до следующей, и находка приписывается не тому
            # переходу: проверка про перенос состояния сама им и болела бы.
            _открыть(стр, порча)
            _перейти(стр, источник)
            имя_воор, скрипт = ВООРУЖЕНИЕ.get(источник, ("без состояния", None))
            if скрипт:
                стр.evaluate(скрипт)
            до = стр.evaluate(ОТПЕЧАТОК)
            _перейти(стр, цель)
            после = стр.evaluate(ОТПЕЧАТОК)

            перенос = [к for к in до
                       if к not in СЛУЖЕБНЫЕ and до[к] == после[к]
                       and до[к] not in ("", None)]
            находок += len(перенос)
            for к in перенос:
                по_ключам[к] = по_ключам.get(к, 0) + 1
            беды = [(источник + " → " + цель, б)
                    for б in _инварианты(после, до, источник)]

            # ШАГ ВОЗВРАТА. Инварианты ИНВ-1…ИНВ-3 спрашиваются только
            # у «Дневника», значит пара, чья цель не он, проверяла бы
            # одну ИНВ-4 и молчала бы про главное правило. А утечка
            # ходит именно так: отмотал день на «Дневнике», ушёл
            # на «Добавить», вернулся — и день остался отмотанным.
            # Без этого шага подлог «возврат отключён» называл ОДНУ
            # пару из тридцати; с ним — двадцать (замер 2026-08-21).
            if цель != "diary":
                _перейти(стр, "diary")
                возврат = стр.evaluate(ОТПЕЧАТОК)
                # У ТРЕТЬЕГО шага источник — это `цель` второго, а его
                # отпечаток — `после`. Подставить сюда первый источник
                # значило бы спрашивать сброс там, где правило требует
                # сохранения, и наоборот.
                беды += [("%s → %s → diary" % (источник, цель), б)
                         for б in _инварианты(возврат, после, цель)]

            if беды:
                долг += len(беды)
                for путь, б in беды:
                    отчёт.append("  ДОЛГ  %s  (вооружено: %s)"
                                 % (путь, имя_воор))
                    отчёт.append("        " + б)
    if по_ключам:
        отчёт.append("")
        отчёт.append("  ЧТО ПЕРЕЖИВАЕТ ПЕРЕХОД (ключ: на скольких парах):")
        for к, n in sorted(по_ключам.items(), key=lambda п: -п[1]):
            отчёт.append("        %-10s %d" % (к, n))
    return находок, долг, отчёт, пар



def контроль(стр):
    """Проверка обязана НАЙТИ подлог и НАЗВАТЬ пару. Не нашла — сломана она.

    Без чистого прогона перед подлогами контроль ничего не доказывает:
    долг, который был и до подлога, засчитался бы как находка подлога.
    """
    плохо = 0
    чисто_н, чисто_д, _, пар = прогон(стр)
    print("  без подлога: пар %s, находок %s, ДОЛГ %s" % (пар, чисто_н, чисто_д))
    if чисто_д:
        print("  ОСТАНОВЛЕНО: долг есть и без подлога — контроль ничего "
              "не доказывает, пока код не чист")
        плохо += 1
    for имя, скрипт, ждём in ПОДЛОГИ:
        _, д, отчёт, _ = прогон(стр, скрипт)
        текст = "\n".join(отчёт)
        назван = all(м in текст for м in ждём)
        пары = sum(1 for с in отчёт if "→" in с)
        итог = "НАЙДЕН" if (д and назван) else "ПРОПУЩЕН"
        print("  подлог «%s»: долг %s, пар названо %s — %s" % (имя, д, пары, итог))
        if not (д and назван):
            плохо += 1
            print("        ждали %s, в отчёте:\n%s" % (ждём, текст[:500]))
    return плохо



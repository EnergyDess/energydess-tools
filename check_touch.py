def мелкий(з):
    """Находка или нет. Порог по площади разобран в шапке файла."""
    if з["перекрыт"]:
        return True
    if з["hw"] >= МИНИМУМ and з["hh"] >= МИНИМУМ:
        return False
    # Длинная полоса: одна сторона с запасом, площадь не меньше квадрата
    if з["hw"] * з["hh"] >= ПЛОЩАДЬ and max(з["hw"], з["hh"]) >= МИНИМУМ:
        return False
    return True


def _вид(з):
    """Имя вида — ВЕСЬ набор классов, а не первый.

    Первый класс склеивал в одну строку разные органы: `.btn-icon`
    с крестиком дневника (`.btn-icon-sm.food-del`, область 44) и кнопку
    строки таблицы админки (`.btn-icon` без вариантов, область 28).
    Худшее число тогда приписывалось обоим, и починенный орган выглядел
    несделанным."""
    к = з["класс"].split()
    if к:
        return "." + ".".join(к[:4])
    return з["тег"] + (("#" + з["id"]) if з["id"] else "")


def снять(добавка_css="", тихо=False, экраны=None):
    """[(экран, запись)] по всем экранам на сенсорной ширине."""
    from playwright.sync_api import sync_playwright

    экраны = экраны or ch.экраны_из_роутов()
    находки = []
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for нужен_вход in (True, False):
            свои = [э for э in экраны if bool(э[2]) is нужен_вход]
            if not свои:
                continue
            к = бр.new_context(viewport={"width": ШИРИНА, "height": ВЫСОТА},
                               has_touch=True, is_mobile=True)
            стр = к.new_page()
            cdp = к.new_cdp_session(стр)
            ch._включить_сенсор(cdp)
            if нужен_вход:
                ch._войти(стр)
                ch._включить_сенсор(cdp)
            for путь, имя, _вх, подготовка in свои:
                if путь in ВНЕ_РАЗБОРА:
                    if not тихо:
                        print("  %-30s пропуск: %s" % (имя, ВНЕ_РАЗБОРА[путь]))
                    continue
                try:
                    стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded",
                             timeout=45000)
                except Exception as e:
                    print("  %-30s НЕ ОТКРЫЛСЯ: %s" % (имя, type(e).__name__))
                    continue
                стр.wait_for_timeout(1800)
                if подготовка:
                    try:
                        стр.click(подготовка, timeout=4000)
                        стр.wait_for_timeout(ch.ПАУЗА_ПЕРЕХОДА + 700)
                    except Exception as e:
                        print("  %-30s сцена не открылась (%s)"
                              % (имя, type(e).__name__))
                        continue
                стр.add_style_tag(content=ГЛУШИТЕЛЬ + добавка_css)
                ch._сверить(стр, True, "%s: перед замером" % имя)
                д = стр.evaluate(ЗАМЕР, {"мин": МИНИМУМ, "сел": ОРГАНЫ})
                данные, обвязка = д["органы"], д["под_обвязкой"]
                мелкие = [з for з in данные if мелкий(з)]
                if not тихо:
                    print("  %-30s органов %3d   меньше %d: %3d   "
                          "под обвязкой: %d   вне требования: %d"
                          % (имя, len(данные), МИНИМУМ, len(мелкие), обвязка,
                             д["исключено"]))
                for з in мелкие:
                    находки.append((имя, з))
            к.close()
        бр.close()
    return находки


def разложить(находки):
    """вид -> сколько, где, худшая область."""
    свод = {}
    for экран, з in находки:
        в = _вид(з)
        с = свод.setdefault(в, {"n": 0, "экраны": set(), "мин": (999, 999),
                                "вид_размер": (з["w"], з["h"]),
                                "текст": з["текст"], "перекрыт": 0,
                                "воры": set()})
        с["n"] += 1
        с["экраны"].add(экран)
        с["перекрыт"] += 1 if з["перекрыт"] else 0
        if з.get("вор"):
            с["воры"].add(з["вор"])
        if з["hw"] * з["hh"] < с["мин"][0] * с["мин"][1]:
            с["мин"] = (з["hw"], з["hh"])
            с["вид_размер"] = (з["w"], з["h"])
    return свод


def проверить(находки, тихо=False):
    if not тихо:
        свод = разложить(находки)
        print("\n" + "─" * 74)
        print("ОРГАНОВ С ОБЛАСТЬЮ МЕНЬШЕ %d×%d: %d (видов %d)"
              % (МИНИМУМ, МИНИМУМ, len(находки), len(свод)))
        print("─" * 74)
        for вид, с in sorted(свод.items(), key=lambda x: -x[1]["n"]):
            пометка = ("  ПЕРЕКРЫТ ← " + ", ".join(sorted(с["воры"]))[:60]
                       if с["перекрыт"] else "")
            print("  %-28s ×%-3d область %d×%d при виде %g×%g%s"
                  % (вид, с["n"], с["мин"][0], с["мин"][1],
                     с["вид_размер"][0], с["вид_размер"][1], пометка))
            print("     %s" % ", ".join(sorted(с["экраны"]))[:110])
    return 1 if находки else 0



# Лишнее место у ПРИНЯТОГО вида: НАБОР КЛАССОВ ТОТ ЖЕ (иначе `_вид`
# даст другое имя, и подлог проверил бы обычную находку, а не рост
# принятого), а область ужимается АТРИБУТОМ — атрибут в имя вида

def _счёт(экраны, селектор, js=""):
    """НЕЗАВИСИМОЕ ДОКАЗАТЕЛЬСТВО: сколько таких элементов в дереве."""
    from playwright.sync_api import sync_playwright
    путь, _, вход, подготовка = экраны[0]
    with sync_playwright() as p:
        бр = p.chromium.launch()
        к = бр.new_context(viewport={"width": ШИРИНА, "height": ВЫСОТА},
                           has_touch=True, is_mobile=True)
        стр = к.new_page()
        cdp = к.new_cdp_session(стр)
        ch._включить_сенсор(cdp)
        if вход:
            ch._войти(стр)
            ch._включить_сенсор(cdp)
        стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded", timeout=45000)
        стр.wait_for_timeout(1500)
        if подготовка:
            try:
                стр.click(подготовка, timeout=4000)
                стр.wait_for_timeout(600)
            except Exception:                        # noqa: BLE001
                pass
        if js:
            стр.evaluate(js)
            стр.wait_for_timeout(150)
        n = стр.evaluate("(с) => document.querySelectorAll(с).length", селектор)
        бр.close()
    return n



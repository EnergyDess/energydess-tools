def _файлы():
    """Пробы, водящие браузер. shots_* не считаются: кадры смотрит
    человек, кода «правильно» у них нет вовсе (§6.0.4)."""
    из = []
    for имя in sorted(os.listdir(".")):
        if not имя.startswith("check_") or not имя.endswith(".py"):
            continue
        if имя in СВОИ:
            continue
        т = io.open(имя, encoding="utf-8").read()
        if "playwright" not in т:
            continue
        из.append((имя, т))
    return из


def _дерево(текст):
    """Разбирает файл и отмечает docstring: слово в пояснении —
    рассказ о сэмплере, а не сэмплер."""
    try:
        дерево = ast.parse(текст)
    except SyntaxError:
        return None, None
    строки = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.Module, ast.FunctionDef,
                             ast.AsyncFunctionDef, ast.ClassDef)):
            тело = getattr(узел, "body", [])
            if (тело and isinstance(тело[0], ast.Expr)
                    and isinstance(тело[0].value, ast.Constant)
                    and isinstance(тело[0].value.value, str)):
                строки.add(id(тело[0].value))
    return дерево, строки


def _инструментовка(дерево, докстринги):
    нашлось = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            if id(узел) in докстринги:
                continue
            for слово, как in ИНСТРУМЕНТОВКА.items():
                if слово in узел.value:
                    нашлось.add(как)
        elif isinstance(узел, ast.Attribute):
            for слово, как in ИНСТРУМЕНТОВКА.items():
                if слово == узел.attr:
                    нашлось.add(как)
    return sorted(нашлось)


def _переходы(дерево, докстринги):
    """Какие переходы проба СОВЕРШАЕТ — по вызовам playwright.

    Считаются ВЫЗОВЫ и строки-литералы кода: слово click
    в пояснении переходом не является.
    """
    имена = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Call):
            ф = узел.func
            if isinstance(ф, ast.Attribute):
                имена.add(ф.attr)
                if isinstance(ф.value, ast.Attribute):
                    имена.add(ф.value.attr + "." + ф.attr)
        elif isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            if id(узел) in докстринги:
                continue
            for слово in ("mouseover", "pointerenter", "mouseout"):
                if слово in узел.value:
                    имена.add(слово)
    из = []
    for группа, признаки in ПЕРЕХОДЫ:
        if any(п in имена or п.split(".")[-1] in имена for п in признаки):
            из.append(группа)
    return из


def опись():
    строки = []
    for имя, текст in _файлы():
        дерево, докстринги = _дерево(текст)
        if дерево is None:
            строки.append((имя, ["РАЗБОР НЕ УДАЛСЯ"], [], False))
            continue
        инстр = _инструментовка(дерево, докстринги)
        пер = _переходы(дерево, докстринги)
        строки.append((имя, инстр, пер, bool(инстр)))
    return строки



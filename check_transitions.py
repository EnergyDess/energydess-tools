    print("  %-38s %2d  %s" % ("переходов не совершает вовсе", len(без),
                               " ".join(и.replace("check_", "")
                                        .replace(".py", "") for и in без)))
    print("")
    print("  ГРУПП ЗАКРЫТО: %d, ОТКРЫТО: %d"
          % (len(ПЕРЕХОДЫ) - открытых, открытых))
    print("  МЕРКА, а не проверка: код возврата всегда 0 (§6.0.4).")
    return 0



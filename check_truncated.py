# -*- coding: utf-8 -*-
"""
Поиск ОБОРВАННЫХ ответов модели в том, что уже лежит в базе.

Запуск локально:
    py check_truncated.py
Запуск на проде:
    flyctl ssh console -a energydess-tools -C "python /app/check_truncated.py"

Зачем отдельный скрипт, а не строка в логе. `finish_reason` разбирается
с 2026-08-11 (_model_output в main.py), но всё, что сгенерировано ДО этого,
уехало в базу без единой проверки. У JSON обрыв ломает разбор и виден сразу;
у связного текста — нет: письмо доходит целым на вид, оборванным на середине
фразы, и уезжает в историю как готовое. Лимит письма был 1500 при фактическом
расходе 793 — то есть длинное письмо в 450 слов упиралось в потолок.

Четыре места, где значимая часть стоит В КОНЦЕ ответа:
  1. письмо целиком            (cover_letters.letter_text)
  2. блок ###FOOD_JSON###      (chat_messages, tool=nutrition)
  3. ###WORKOUT_ACTION###      (chat_messages, tool=workout)
  4. строка «МЕТКА:»           (chat_messages, tool=workout — разбор фото)

ВАЖНО про 2-4: блок из ответа ВЫРЕЗАЕТСЯ перед записью в базу, поэтому
искать в базе целый блок бессмысленно — его там не должно быть. Ищется
обратное: **осколок** блока. Обе регулярки в main.py требуют закрывающий
маркер, и оборванный на середине блок не вырезается — открывающий маркер
остаётся в тексте. Это точная подпись обрыва, а не догадка.

Только чтение, ничего не меняет и не удаляет.
"""
import os
import re
import sqlite3
import sys

# Консоль Windows по умолчанию cp1251 — вывод скрипта превращается в кашу
# и читается ровно никак. На проде (Linux, UTF-8) строка ничего не меняет.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

БД = os.getenv("DB_PATH", "app.db" if os.path.exists("app.db") else "/data/app.db")

# Отношение русского текста к токенам. Нужно, чтобы сравнить длину письма
# со СТАРЫМ потолком 1500 — в базе лежит текст, а не число токенов.
#
# ЗДЕСЬ СТОЯЛО 2.58, И ЭТО БЫЛА ОТСТАВШАЯ КОПИЯ. Цифра держалась
# на ОДНОМ замере (2049 символов / 793 токена, 2026-08-11); уточнение
# по четырнадцати письмам с прода дало 2,37–2,53 при среднем 2,45,
# и CLAUDE.md §2.1 с тех пор говорит 2,45, прямо называя 2,58 неверной.
# Здесь про это не узнали: величина записана в двух местах, а сверять
# их было нечем. Ошибка была в опасную сторону: чем больше символов
# на токен, тем меньше токенов выходит из того же текста — письмо
# казалось дальше от потолка, чем было. Замер на нынешней базе: самое
# длинное письмо 746 токенов по старой цифре против 786 по новой.
СИМВОЛОВ_НА_ТОКЕН = 2.45
СТАРЫЙ_ПОТОЛОК = 1500          # действовал до 2026-08-11
БЛИЗКО = 0.8                   # доля потолка, с которой запас считается кончившимся

# Чем ЗАКОНЧЕННЫЙ текст заканчивается. Обрыв по лимиту режет посреди слова
# или сразу после него — терминального знака там не будет.
КОНЦОВКА = re.compile(r'[.!?…)»"\'*\]\d:;–—-]\s*$')
# Подпись в конце письма. Первая версия проверки считала обрывом ЛЮБОЕ письмо
# без терминального знака — и поймала три из четырёх, все три законные:
# письмо заканчивается «С уважением,\nДенис», то есть буквой. Проверка,
# которая врёт в трёх случаях из четырёх, не читается вовсе (CLAUDE.md §6.0.2),
# поэтому подпись в хвосте снимает подозрение.
ПОДПИСЬ = re.compile(r"с уважением|заранее спасибо|буду рад|готов обсудить|"
                     r"жду (вашего )?ответа|с наилучшими|всего доброго", re.I)

ОСКОЛКИ = [
    ("FOOD_JSON",      re.compile(r"###FOOD_JSON###"),      re.compile(r"###END_FOOD_JSON###")),
    ("WORKOUT_ACTION", re.compile(r"###WORKOUT_ACTION###"), re.compile(r"###END_WORKOUT_ACTION###")),
]
# «МЕТКА:» вырезается по r"МЕТКА:\s*.+" — то есть остаётся, если после
# двоеточия обрыв не оставил ни одного символа, либо если обрыв случился
# внутри самого слова.
МЕТКА_ЦЕЛАЯ = re.compile(r"МЕТКА:\s*\S")
МЕТКА_ОСКОЛОК = re.compile(r"(?:^|\n)\s*(?:МЕТКА:?\s*$|М[ЕТКА]{1,4}$)")


def таблица_есть(c, имя):
    return bool(c.execute(
        "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (имя,)).fetchone())


def врезка(заголовок):
    print()
    print("=" * 70)
    print(заголовок)
    print("=" * 70)


c = sqlite3.connect("file:%s?mode=ro" % БД, uri=True)
c.row_factory = sqlite3.Row
print("база: %s" % БД)

# ── 1. Письма ────────────────────────────────────────────────────────────────
врезка("1. ПИСЬМА — обрыв на середине фразы")

подозрительных = []
всего_писем = 0
if таблица_есть(c, "cover_letters"):
    строки = c.execute("""SELECT id, user_id, created_at, edited,
                                 COALESCE(job_title,'') jt, COALESCE(company_name,'') cn,
                                 letter_text
                          FROM cover_letters ORDER BY id""").fetchall()
    всего_писем = len(строки)
    for r in строки:
        текст = (r["letter_text"] or "").strip()
        симв = len(текст)
        токенов = round(симв / СИМВОЛОВ_НА_ТОКЕН)
        концовка_цела = bool(КОНЦОВКА.search(текст)) if текст else True
        подпись_есть = bool(ПОДПИСЬ.search(текст[-400:]))
        if концовка_цела or подпись_есть:
            continue
        признаки = ["нет терминального знака в конце", "нет подписи"]
        if токенов >= СТАРЫЙ_ПОТОЛОК * БЛИЗКО:
            признаки.append("~%d токенов — у старого потолка %d" % (токенов, СТАРЫЙ_ПОТОЛОК))
        подозрительных.append((r, симв, токенов, признаки))

    print("  всего писем: %d" % всего_писем)
    print("  подозрительных (оборвана концовка): %d" % len(подозрительных))
    if подозрительных:
        print()
        for r, симв, токенов, признаки in подозрительных:
            заг = " — ".join(x for x in (r["jt"], r["cn"]) if x) or "‹без названия›"
            print("  #%-4s user=%-3s %s  %5d симв (~%d ток)%s" % (
                r["id"], r["user_id"], str(r["created_at"])[:16], симв, токенов,
                "  [правлено вручную]" if r["edited"] else ""))
            print("        %s" % заг[:60])
            print("        признаки: %s" % "; ".join(признаки))
            print("        …%s" % repr((r["letter_text"] or "")[-90:]))
            print()
    # Отдельно — длинные письма без оборванной концовки: они у потолка,
    # но целые. Это не находка, это подтверждение, что запас был на грани.
    длинных = [r for r in строки
               if len(r["letter_text"] or "") / СИМВОЛОВ_НА_ТОКЕН >= СТАРЫЙ_ПОТОЛОК * БЛИЗКО]
    print("  писем длиннее %d%% старого потолка: %d" % (int(БЛИЗКО * 100), len(длинных)))
    for r in длинных:
        print("      #%-4s ~%d токенов" % (r["id"], round(len(r["letter_text"] or "") / СИМВОЛОВ_НА_ТОКЕН)))
    самое = max((len(r["letter_text"] or "") for r in строки), default=0)
    print("  самое длинное письмо: %d симв (~%d токенов из %d)" % (
        самое, round(самое / СИМВОЛОВ_НА_ТОКЕН), СТАРЫЙ_ПОТОЛОК))
else:
    print("  таблицы cover_letters нет")

# ── 2-4. Реплики ассистентов: осколки хвостовых блоков ───────────────────────
врезка("2-4. РЕПЛИКИ АССИСТЕНТОВ — осколок хвостового блока")

находок_блоков = 0
if таблица_есть(c, "chat_messages"):
    реплики = c.execute("""SELECT id, user_id, tool, created_at, content
                           FROM chat_messages WHERE role='assistant' ORDER BY id""").fetchall()
    по_инструменту = {}
    for r in реплики:
        по_инструменту[r["tool"]] = по_инструменту.get(r["tool"], 0) + 1
    print("  реплик ассистента: %d  (%s)" % (
        len(реплики), ", ".join("%s=%d" % кв for кв in sorted(по_инструменту.items())) or "—"))

    for имя, начало, конец in ОСКОЛКИ:
        битые = [r for r in реплики
                 if начало.search(r["content"] or "") and not конец.search(r["content"] or "")]
        целые = [r for r in реплики if конец.search(r["content"] or "")]
        находок_блоков += len(битые)
        print("  ###%s###: осколков %d, невырезанных целых %d" % (имя, len(битые), len(целые)))
        for r in битые:
            print("      #%-4s user=%-3s %s tool=%s" % (
                r["id"], r["user_id"], str(r["created_at"])[:16], r["tool"]))
            print("        …%s" % repr((r["content"] or "")[-120:]))

    метки = [r for r in реплики
             if r["tool"] == "workout" and (МЕТКА_ЦЕЛАЯ.search(r["content"] or "")
                                            or МЕТКА_ОСКОЛОК.search(r["content"] or ""))]
    находок_блоков += len(метки)
    print("  «МЕТКА:» осколков: %d" % len(метки))
    for r in метки:
        print("      #%-4s %s  …%s" % (r["id"], str(r["created_at"])[:16], repr((r["content"] or "")[-90:])))

    # Обрыв, случившийся ДО открывающего маркера, подписи не оставляет вовсе.
    # Единственный доступный признак — та же оборванная концовка.
    оборванные = [r for r in реплики
                  if (r["content"] or "").strip() and not КОНЦОВКА.search((r["content"] or "").strip())]
    print("  реплик с оборванной концовкой: %d" % len(оборванные))
    for r in оборванные:
        print("      #%-4s user=%-3s %s tool=%-9s %4d симв" % (
            r["id"], r["user_id"], str(r["created_at"])[:16], r["tool"], len(r["content"] or "")))
        print("        …%s" % repr((r["content"] or "")[-90:]))
else:
    print("  таблицы chat_messages нет")

врезка("ИТОГ")
print("  писем с оборванной концовкой : %d из %d" % (len(подозрительных), всего_писем))
print("  осколков хвостовых блоков    : %d" % находок_блоков)
print()
print("  Ничего не удалено и не перегенерировано — скрипт только читает.")

c.close()

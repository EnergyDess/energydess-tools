def доказать_подлог(отн, было, стало):
    """НЕЗАВИСИМЫЙ ЗАМЕР ТОГО, ЧТО ПОДЛОГ СОБИРАЛСЯ ИЗМЕНИТЬ (§6.0.3).

    Вердикт пробы доказательством НЕ является: подлог, не сломавший
    ничего, даёт тот же результат, что подлог, сломавший не то. Здесь
    свидетель со стороны — число вызовов уменьшения в файле: подлог
    обязан его уменьшить.

    Возвращает `(было_вызовов, стало_вызовов)`; равенство означает,
    что ломать было нечего, и контроль обязан остановиться.
    """
    цель = os.path.join(КОРЕНЬ, *отн.split("/"))
    текст = io.open(цель, encoding="utf-8").read()
    порча = текст.replace(было, стало, 1)
    return (sum(текст.count(u) for u in УМЕНЬШЕНИЕ),
            sum(порча.count(u) for u in УМЕНЬШЕНИЕ))


def контроль():
    """ПОДЛОГ ДОКАЗЫВАЕТСЯ ОТДЕЛЬНЫМ ЗАМЕРОМ (§6.0.3).

    Находка пробы доказательством работы подлога НЕ ЯВЛЯЕТСЯ: подлог,
    который ничего не сломал, даёт тот же вердикт, что подлог,
    сломавший не то. Поэтому рядом с каждым — независимый замер того,
    что он собирался изменить: сколько вызовов уменьшения осталось
    в файле.
    """
    import shutil
    import tempfile

    чисто, _ = прогон(печатать=False)
    print("Чистый прогон: долга %d" % len(чисто))
    if чисто:
        print("ОСТАНОВЛЕНО: контроль на грязной основе недействителен — "
              "долг, бывший и до подлога, засчитался бы за находку")
        return 1

    беды = 0
    for метка, (отн, было, стало) in ПОДЛОГИ.items():
        цель = os.path.join(КОРЕНЬ, *отн.split("/"))
        текст = io.open(цель, encoding="utf-8").read()
        if было not in текст:
            print("  ПЛОХО  %s: якоря подлога нет — проба смотрит не туда"
                  % метка)
            беды += 1
            continue
        запас = tempfile.mktemp(suffix=".bak")
        shutil.copy2(цель, запас)
        try:
            # ДОКАЗАТЕЛЬСТВО СНИМАЕТСЯ ДО ЗАПИСИ ПОРЧИ. Первая версия
            # звала его ПОСЛЕ и читала файл заново — то есть считала
            # уже испорченный текст и печатала «0 и 0, ломать было
            # нечего» на состоявшемся подлоге. Свидетель, смотрящий
            # на результат вместо причины, свидетелем не является
            до, после = доказать_подлог(отн, было, стало)
            порча = текст.replace(было, стало, 1)
            io.open(цель, "w", encoding="utf-8").write(порча)
            if до == после:
                print("  ПЛОХО  %s: ПОДЛОГ НЕ СОСТОЯЛСЯ — вызовов "
                      "уменьшения как было %d, так и осталось" % (метка, до))
                беды += 1
                continue
            с_подлогом, _ = прогон(печатать=False)
            нашла = len(с_подлогом) > len(чисто)
            print(("   OK   " if нашла else "  ПЛОХО ")
                  + "%-26s долг %d -> %d  (доказательство: вызовов "
                    "уменьшения %d -> %d)"
                  % (метка, len(чисто), len(с_подлогом), до, после))
            if not нашла:
                беды += 1
        finally:
            shutil.copy2(запас, цель)
            os.unlink(запас)

    вернулось, _ = прогон(печатать=False)
    if len(вернулось) != len(чисто):
        print("  ПЛОХО  после уборки долг не вернулся: %d вместо %d"
              % (len(вернулось), len(чисто)))
        беды += 1
    print("Не найдено подлогов: %d из %d" % (беды, len(ПОДЛОГИ)))
    return 1 if беды else 0



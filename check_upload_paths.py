"""ПУТИ ЗАГРУЗКИ КАРТИНКИ: где снимок ужимается перед отправкой, где нет.

ЗАЧЕМ. Заход 2026-08-25 положил уменьшение фото в панель ассистента
аптечки и НЕ ПОЛОЖИЛ в форму карточки — второй путь того же экрана.
Владелец получил с телефона 502 ровно через форму. До этого та же
история была между дневником питания и аптечкой целиком.

Три раза подряд один дефект — значит закрывается КЛАСС, а не экземпляр
(§6.0.7). Перечень путей в прозе отстал бы на первом же новом поле
выбора файла, и отстал бы МОЛЧА: проверка продолжала бы печатать
«чисто», просто уже не про всё.

──────────────────────────────────────────────────────────────────────
ПРИЗНАК, И У НЕГО НАЗВАНА ГРАНИЦА

Путь загрузки — место, где картинка кладётся в `FormData` под тем
именем, под которым СЕРВЕР принимает `UploadFile`. Имена берутся
из `main.py`, а не перечисляются здесь: иначе поле `snapshot`,
заведённое завтра, молча выпало бы из-под проверки.

Место считается УЖИМАЮЩИМ, если системный компонент (`уменьшитьФото`
либо его прежнее имя `resizeImage`) вызван ЛИБО в теле той же функции,
ЛИБО раньше — и результат доехал сюда переменной. Второе обязательно:
в дневнике питания снимок ужимается при выборе файла, а отправляет его
другая функция минутой позже, и без трассировки признак давал ТРИ
ложные находки из семи.

Границы признака, и они настоящие:

  · функция определяется НАЗАД ПО ТЕКСТУ до ближайшего объявления.
    Вложенная функция внутри обработчика может обмануть разбор;
  · трасса переменной идёт по ИМЕНАМ в пределах файла, без области
    видимости: одноимённая переменная в другой функции даст ложное
    «ужато». Ослабление в опасную сторону, и названо оно у самой
    трассы;
  · путь, у которого файл вообще не картинка (резюме PDF в HH),
    сюда не относится и отсеивается по `accept` поля.

──────────────────────────────────────────────────────────────────────
ЗАКОННЫЕ ИСКЛЮЧЕНИЯ ПЕРЕЧИСЛЯЮТСЯ ПОИМЁННО, С ПРИЧИНОЙ У КАЖДОГО

Перечень тут законен по §6.0.7: новый член множества появляется только
решением человека, и это решение и есть строка в списке. Сторожит его
то же, что список `demo=`: путь, которого больше нет в коде, печатается
отдельной строкой, а не вычитается молча.

    py check_upload_paths.py              # код 1, если есть долг
    py check_upload_paths.py --контроль   # проба обязана увидеть подлог
    py check_upload_paths.py --замер      # СКОЛЬКО БАЙТ уходит на самом
                                          # деле: браузер, живой стенд
"""

import io
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))

# Где ищем. Шаблоны и СОБСТВЕННЫЕ скрипты — сам системный компонент
# исключён: он и есть уменьшение, требовать от него вызывать себя
# было бы бессмыслицей
ФАЙЛЫ = ["templates/*.html", "static/*.js"]
НЕ_СМОТРИМ = {"static/image-resize.js"}

# Имена системного компонента. Их два, потому что дневник питания звал
# его `resizeImage` до выделения в файл, и переписывать тот вызов вторым
# способом делать то же самое было незачем
УМЕНЬШЕНИЕ = ("уменьшитьФото", "resizeImage")

# Начало функции — назад по тексту ищем ближайшее из этого
НАЧАЛО_ФУНКЦИИ = re.compile(
    r"(?:^|\n)\s*(?:async\s+)?function\s|"
    r"(?:^|\n)\s*(?:const|let|var)\s+[\wА-Яа-яЁё$]+\s*=\s*(?:async\s*)?\(|"
    r"addEventListener\s*\(\s*['\"][a-z]+['\"]\s*,\s*(?:async\s*)?function|"
    r"addEventListener\s*\(\s*['\"][a-z]+['\"]\s*,\s*(?:async\s*)?\(|"
    r"onchange\s*=|\.onclick\s*=|=>\s*\{")

# Кладём что-то в форму запроса. Имя поля дальше сверяется с тем, под
# каким именем СЕРВЕР принимает файл, — см. `имена_файловых_полей`
ПОЛОЖИТЬ = re.compile(r"\.append\s*\(\s*(['\"])([\w\-]+)\1\s*,\s*([^,)]+)")

# Имя поля, под которым обработчик принимает `UploadFile`. ВЫВОДИТСЯ
# ИЗ `main.py`, а не перечисляется: заведи кто-нибудь эндпоинт с полем
# `snapshot`, и перечень молча перестал бы его видеть (§6.0.7, способ
# первый — вывести множество из источника).
ФАЙЛОВОЕ_ПОЛЕ = re.compile(r"(\w+)\s*:\s*UploadFile")


def имена_файловых_полей():
    текст = io.open(os.path.join(КОРЕНЬ, "main.py"), encoding="utf-8").read()
    имена = set(ФАЙЛОВОЕ_ПОЛЕ.findall(текст))
    if not имена:
        # Разбор не отработал — останавливаемся, а не идём с пустым
        # множеством: пустое дало бы «долга нет» про всё на свете
        raise SystemExit("ОСТАНОВЛЕНО: в main.py не найдено ни одного "
                         "UploadFile — сломан разбор, а не код чист")
    return имена

# Поле выбора файла с картинкой — им отсеиваем пути, где файл не картинка
ПОЛЕ_КАРТИНКИ = re.compile(r'<input[^>]*type="file"[^>]*>', re.S)

# ── ЗАКОННЫЕ ИСКЛЮЧЕНИЯ ──────────────────────────────────────────────
#
# Ключ — «файл:имя поля формы». Значение — ПРИЧИНА. Без причины список
# за полгода превращается в свалку, куда сваливают всё, что мешает
# проверке пройти.
ЗАКОННО = {
    "templates/hh.html:file":
        "резюме, а не картинка: PDF и DOC. Уменьшать нечего",
    "templates/admin_enshrouded.html:file":
        "картинка каталога, кладётся С МАШИНЫ ВЛАДЕЛЬЦА, а не с камеры: "
        "экран управления открывают с компьютера, файл берут из папки "
        "вики. Сервер ужимает его сам до потолка проверки 24 (§5.7)",
}


def _файлы():
    import glob
    из = []
    for шаблон in ФАЙЛЫ:
        for п in sorted(glob.glob(os.path.join(КОРЕНЬ, шаблон))):
            отн = os.path.relpath(п, КОРЕНЬ).replace("\\", "/")
            if отн not in НЕ_СМОТРИМ:
                из.append((отн, io.open(п, encoding="utf-8").read()))
    return из


def _картиночный(текст):
    """Есть ли в файле поле выбора КАРТИНКИ.

    Файл без такого поля картинок и не грузит: `FormData` там про
    что-то другое (текст анкеты, отметки). Отсекаем здесь, а не
    по имени поля формы, — имя `file` носят и резюме, и картинка.
    """
    for тег in ПОЛЕ_КАРТИНКИ.findall(текст):
        if 'type="file"' in тег and "image/" in тег:
            return True
    return False


def _только_pdf(текст):
    """Файл, у которого ВСЕ поля файла — не картинки."""
    поля = [т for т in ПОЛЕ_КАРТИНКИ.findall(текст) if 'type="file"' in т]
    return bool(поля) and not any("image/" in т for т in поля)


def _тело_функции(текст, конец):
    """Фрагмент от начала ближайшей функции до позиции `конец`."""
    начало = 0
    for м in НАЧАЛО_ФУНКЦИИ.finditer(текст, 0, конец):
        начало = м.start()
    return текст[начало:конец]


# ── УЖАТОЕ ДОЕЗЖАЕТ ЧЕРЕЗ ПЕРЕМЕННУЮ, И ЭТО НАДО ПРОСЛЕДИТЬ ──────────
#
# Первая версия признака смотрела только в тело функции, где стоит
# `append`, и дала ТРИ ЛОЖНЫЕ НАХОДКИ на дневнике питания: там снимок
# ужимается в обработчике выбора файла (`handlePhoto`, `onChatAttach`),
# кладётся в поле состояния, а отправляет его СОВСЕМ ДРУГАЯ функция
# минутой позже. Это законный порядок — превью показывают сразу, шлют
# по кнопке, — и объявлять его долгом значило бы врать в трёх случаях
# из семи. Проверка, которая врёт наполовину, не читается вовсе.
#
# Вносить их в список исключений было НЕЛЬЗЯ, хотя шапка это и
# разрешала: убери кто-нибудь уменьшение из `handlePhoto` — и строка
# исключения продолжала бы молчать про настоящий долг. Исключение
# закрывает решение человека, а здесь вопрос про КОД.
#
# Поэтому имя прослеживается до неподвижной точки: что получило
# результат уменьшения, что получило это, и так далее.
#
# ГРАНИЦА НАЗВАНА: трасса идёт по ИМЕНАМ в пределах файла, без области
# видимости. Одноимённая переменная в другой функции даст ложное
# «ужато» — ослабление в опасную сторону, и лечится оно только разбором
# настоящим парсером JS, которого в проекте нет.
ИЗ_УМЕНЬШЕНИЯ = re.compile(
    r"(?:const|let|var)\s*(\{[^}]*\}|[\wА-Яа-яЁё$]+)\s*=\s*await\s+"
    r"(?:%s)\s*\(" % "|".join(УМЕНЬШЕНИЕ))


def _границы_функций(текст):
    """Отрезки текста, каждый — одна функция (от объявления до следующего).

    Грубо, но достаточно: нужна не точная область видимости, а то,
    чтобы локальное `blob` из ОДНОЙ функции не объявляло ужатым
    одноимённое `blob` из другой.
    """
    точки = [м.start() for м in НАЧАЛО_ФУНКЦИИ.finditer(текст)]
    if not точки:
        return [(0, len(текст))]
    точки = [0] + точки + [len(текст)]
    return [(точки[i], точки[i + 1]) for i in range(len(точки) - 1)]


def _цели_уменьшения(кусок):
    """Имена, которым прямо здесь присвоен результат уменьшения."""
    имена = set()
    for м in ИЗ_УМЕНЬШЕНИЯ.finditer(кусок):
        цель = м.group(1)
        if цель.startswith("{"):
            # Деструктуризация: `const { blob, dataUrl } = await …`
            for ч in цель.strip("{}").split(","):
                ч = ч.split(":")[-1].strip()
                if ч:
                    имена.add(ч)
        else:
            имена.add(цель)
    return имена


# Имя, переживающее вызов функции: поле объекта состояния (`S.photoFile`)
# либо элемент коллекции (`bodyPhotoFiles[angle]`). Только через такие
# ужатость и может доехать до ДРУГОЙ функции — локальная переменная
# кончается вместе со своей.
ДОЛГОЖИВУЩЕЕ = re.compile(r"^[\wА-Яа-яЁё$]+(\.[\wА-Яа-яЁё$]+|\[)")


def _ужатые_имена(текст):
    """Имена, в которых лежит уже уменьшенный снимок.

    СЧИТАЕТСЯ ПО ФУНКЦИЯМ, а не по файлу целиком, и это не педантизм:
    в `nutrition.html` уменьшение зовут ТРИЖДЫ, и все три раза результат
    ложится в локальный `blob`. При счёте по файлу снятое уменьшение
    в одной функции пряталось за оставшимися в двух других — контроль
    показал это ДВУМЯ неувиденными подлогами из пяти.

    Наружу из функции ужатость выносят только долгоживущие имена —
    поле состояния или элемент коллекции.
    """
    имена = set()
    for a, b in _границы_функций(текст):
        кусок = текст[a:b]
        местные = _цели_уменьшения(кусок)
        if not местные:
            continue
        # Наружу — только то, что переживёт возврат из функции
        for _ in range(4):
            новые = set()
            for имя in list(местные):
                и = re.escape(имя)
                for шаблон in (
                    r"([\wА-Яа-яЁё$]+(?:\.[\wА-Яа-яЁё$]+)*(?:\[[^\]]*\])?)"
                    r"\s*=\s*" + и + r"(?:\.blob)?\s*[;,\n]",
                    r"([\wА-Яа-яЁё$]+(?:\.[\wА-Яа-яЁё$]+)*(?:\[[^\]]*\])?)"
                    r"\s*=\s*new\s+File\s*\(\s*\[\s*" + и + r"(?:\.blob)?",
                ):
                    for м in re.finditer(шаблон, кусок):
                        новые.add(м.group(1))
            if новые <= местные:
                break
            местные |= новые
        имена |= местные
        имена |= {и.split(".")[-1].split("[")[0]
                  for и in местные if ДОЛГОЖИВУЩЕЕ.match(и)}
    return имена


def _взято_из(тело, имя, ужатые):
    """Местная переменная получила ужатое ДОЛГОЖИВУЩЕЕ имя в этой функции.

    `const attachment = S.chatAttachment;` — снимок ужат при выборе
    файла, лежит в состоянии, а отправляющая функция берёт его себе
    под коротким именем. Без этого шага проба объявляла долгом два
    исправных пути переписки дневника.
    """
    короткое = имя.split(".")[-1].split("[")[0].strip()
    if not короткое:
        return False
    for м in re.finditer(r"(?:const|let|var)\s+" + re.escape(короткое)
                         + r"\s*=\s*([\wА-Яа-яЁё$.\[\]]+)\s*[;,\n]", тело):
        источник = м.group(1)
        if источник in ужатые or источник.split(".")[-1].split("[")[0] in ужатые:
            return True
    return False


def найти():
    """Все пути загрузки картинки: (файл, строка, поле, ужимает, тело)."""
    из = []
    файловые = имена_файловых_полей()
    ужатые = {}
    for имя, текст in _файлы():
        ужатые[имя] = _ужатые_имена(текст)
    for имя, текст in _файлы():
        картиночный = _картиночный(текст)
        pdfный = _только_pdf(текст)
        for м in ПОЛОЖИТЬ.finditer(текст):
            поле, что = м.group(2), м.group(3).strip()
            # Кладут не файл, а строку данных — не наш случай. Множество
            # имён взято У СЕРВЕРА, а не выдумано здесь
            if поле not in файловые:
                continue
            if not картиночный and not pdfный:
                continue
            строка = текст.count("\n", 0, м.start()) + 1
            тело = _тело_функции(текст, м.start())
            # Ужато либо прямо здесь, либо доехало сюда долгоживущим
            # именем — напрямую или через локальное, которому его
            # присвоили В ЭТОЙ ЖЕ функции (`const attachment =
            # S.chatAttachment`)
            свои = ужатые.get(имя, set())
            корень = что.split(".")[-1].split("[")[0].strip()
            ужимает = (any(u in тело for u in УМЕНЬШЕНИЕ)
                       or что in свои or корень in свои
                       or _взято_из(тело, что, свои))
            из.append({"файл": имя, "строка": строка, "поле": поле,
                       "что": что, "ужимает": ужимает,
                       "картинка": картиночный})
    return из


def _ключ(п):
    return "%s:%s" % (п["файл"], п["поле"])


def прогон(печатать=True):
    пути = найти()
    долг, законно = [], []
    for п in пути:
        к = _ключ(п)
        if п["ужимает"]:
            continue
        if к in ЗАКОННО:
            законно.append((п, ЗАКОННО[к]))
        else:
            долг.append(п)

    if печатать:
        print("ПУТИ ЗАГРУЗКИ КАРТИНКИ — где снимок ужимается перед отправкой")
        print("=" * 78)
        print("%-34s %6s %-10s %s" % ("файл", "строка", "поле", "уменьшение"))
        print("-" * 78)
        for п in пути:
            к = _ключ(п)
            метка = ("ЕСТЬ" if п["ужимает"]
                     else ("законно" if к in ЗАКОННО else "НЕТ — ДОЛГ"))
            print("%-34s %6d %-10s %s"
                  % (п["файл"], п["строка"], п["поле"], метка))
        print()
        if законно:
            print("ЗАКОННО БЕЗ УМЕНЬШЕНИЯ:")
            for п, причина in законно:
                print("  %s:%d — %s" % (п["файл"], п["строка"], причина))
            print()
        # Список исключений, ссылающийся на путь, которого нет, даёт ноль
        # находок, неотличимый от чистоты, — та же беда, что у `demo=`
        живые = {_ключ(п) for п in пути}
        мёртвые = [к for к in ЗАКОННО if к not in живые]
        if мёртвые:
            print("ИСКЛЮЧЕНИЕ ССЫЛАЕТСЯ НА ПУТЬ, КОТОРОГО НЕТ:")
            for к in мёртвые:
                print("  %s" % к)
            print()
        print("Путей всего: %d · ужимают: %d · законных без уменьшения: %d"
              % (len(пути), sum(1 for п in пути if п["ужимает"]), len(законно)))
        print("ДОЛГ (шлют оригинал камеры): %d" % len(долг))
        for п in долг:
            print("  %s:%d — поле %r, кладут %s"
                  % (п["файл"], п["строка"], п["поле"], п["что"]))
        if мёртвые:
            return долг, 1
    return долг, (1 if долг else 0)



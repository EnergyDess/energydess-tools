def токены_v2():
    """Имена `--v2-*`, объявленные в `:root` файла v2.css."""
    текст = open(os.path.join(КОРЕНЬ, "static", "v2.css"), encoding="utf-8").read()
    текст = re.sub(r"/\*.*?\*/", "", текст, flags=re.S)
    имена = set()
    for блок in re.finditer(r"(^|\})\s*:root\s*\{(.*?)\}", текст, flags=re.S):
        имена.update(re.findall(r"(--v2-[a-z0-9-]+)\s*:", блок.group(2)))
    return sorted(имена)



def контроль():
    профиль = [э for э in ce.ЭКРАНЫ if э[1] == "питание · профиль"]
    вес = [э for э in ce.ЭКРАНЫ if э[1] == "питание · вес"]
    print("ПОДЛОГ (а): фон #1e2240 у карточки профиля")
    до = sum(len(и[3]) for и in замер(профиль))
    после_и = замер(профиль, подлог=ПОДЛОГ_ФОН)
    после = sum(len(и[3]) for и in после_и)
    нашёл_а = any(н[2] == "rgb(30,34,64)" and н[1] == "background-color" for и in после_и for н in и[3])
    print("  находок %d → %d, подложенный фон назван: %s" % (до, после, нашёл_а))
    print("ПОДЛОГ (б): исключение графиков снято")
    с_искл = sum(len(и[3]) for и in замер(вес))
    без_и = замер(вес, исключены=["img", "video"])
    без = sum(len(и[3]) for и in без_и)
    на_графике = sum(1 for и in без_и for н in и[3] if "wt-svg" in н[0])
    print("  находок %d → %d, из них на графиках %d" % (с_искл, без, на_графике))
    print("ПОДЛОГ (в): на профиле аккаунта стальной акцент подменён цветом HH")
    аккаунт = [э for э in ce.ЭКРАНЫ if э[0] == "/profile"]
    до_в = замер(аккаунт)[0][4]
    после_в = замер(аккаунт, подлог=ПОДЛОГ_АКЦЕНТ)[0][4]
    доказан_в = bool(до_в and после_в) and до_в["акцент"] != после_в["акцент"]
    нашёл_в = bool(до_в and после_в) and до_в["ок"] and not после_в["ок"]
    print("  акцент каркаса %s → %s (подлог %s); стальной: %s → %s, чужих органов %d → %d" % (
        до_в and до_в["акцент"], после_в and после_в["акцент"], "СОСТОЯЛСЯ" if доказан_в else "НЕ СОСТОЯЛСЯ",
        до_в and до_в["ок"], после_в and после_в["ок"],
        len(до_в["чужие"]) if до_в else -1, len(после_в["чужие"]) if после_в else -1))
    ок = нашёл_а and на_графике > 0 and доказан_в and нашёл_в
    print("КОНТРОЛЬ: %s" % ("все три подлога найдены" if ок else "НЕ НАЙДЕН подлог"))
    return 0 if ок else 1



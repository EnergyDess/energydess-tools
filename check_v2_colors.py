        пометка = ("  · принято %d" % долг if долг and len(находки) <= долг
                   else ("  · ВЫРОСЛО: принято %d" % долг if len(находки) > долг and долг else ""))
        print("  %-26s проб %5d · находок %d%s" % (имя, проб, len(находки), пометка))
        for эл, св, зн, т, де in (находки if подробно else находки[:5]):
            print("      %s · %s · %s · ближе всех %s, ΔE %.1f" % (эл[-90:], св, зн, т, де))

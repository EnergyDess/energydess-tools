def _lab(r, g, b):
    def лин(c):
        c /= 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    R, G, B = лин(r), лин(g), лин(b)
    X = (R * 0.4124 + G * 0.3576 + B * 0.1805) / 0.95047
    Y = R * 0.2126 + G * 0.7152 + B * 0.0722
    Z = (R * 0.0193 + G * 0.1192 + B * 0.9505) / 1.08883
    f = lambda t: t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116  # noqa: E731
    fx, fy, fz = f(X), f(Y), f(Z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def _де(a, b):
    return sum((x - y) ** 2 for x, y in zip(a, b)) ** 0.5


def замер(экраны, подлог=None, исключены=None):
    from playwright.sync_api import sync_playwright
    import browser_window  # noqa: F401
    токены = токены_v2()
    исключены = ИСКЛЮЧЕНЫ if исключены is None else исключены
    итог = []
    with sync_playwright() as p:
        бр = p.chromium.launch(headless=True)
        try:
            ctx = бр.new_context(viewport={"width": ШИРИНА, "height": 900})
            стр = ctx.new_page()
            ch._войти(стр)
            for путь, имя, открыть in экраны:
                стр.goto(ch.БАЗА + путь, wait_until="networkidle", timeout=45000)
                if открыть:
                    стр.evaluate("() => { " + открыть + " }")
                стр.wait_for_timeout(900)
                if подлог:
                    стр.evaluate(подлог)
                д = стр.evaluate(ЗАМЕР, [токены, исключены])
                пал = [(т["т"], _lab(т["r"], т["g"], т["b"]), (т["r"], т["g"], т["b"])) for т in д["палитра"]]
                находки, видели = [], set()
                for п in д["пробы"]:
                    lab = _lab(п["r"], п["g"], п["b"])
                    ближ = min(пал, key=lambda т: _де(lab, т[1]))
                    де = _де(lab, ближ[1])
                    if де <= ДОПУСК:
                        continue
                    ключ = (п["эл"], п["св"], п["зн"])
                    if ключ in видели:
                        continue
                    видели.add(ключ)
                    находки.append((п["эл"], п["св"], "rgb(%d,%d,%d)" % (п["r"], п["g"], п["b"]), ближ[0], де))
                итог.append((имя, len(д["пробы"]), len(пал), находки))
            ctx.close()
        finally:
            бр.close()
    return итог



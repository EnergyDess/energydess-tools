def правила_шапки(текст):
    """Правила, чей селектор относится к шапке страницы.

    Разбор по фигурным скобкам, а не грепом: у многострочного правила
    на строке с именем стоит только селектор (урок задачи 169).
    Возвращает список (селектор, тело, номер первой строки).
    """
    без_коммент = re.sub(r"/\*.*?\*/",
                         lambda m: "\n" * m.group(0).count("\n"),
                         текст, flags=re.S)
    правила, поз = [], 0
    while True:
        о = без_коммент.find("{", поз)
        if о < 0:
            break
        селектор = без_коммент[поз:о].strip().split("}")[-1].strip()
        глубина, i = 1, о + 1
        while i < len(без_коммент) and глубина:
            глубина += (без_коммент[i] == "{") - (без_коммент[i] == "}")
            i += 1
        тело = без_коммент[о + 1:i - 1]
        if "v2-page-head" in селектор:
            строка = без_коммент[:о].count("\n") + 1
            правила.append((селектор, тело, строка))
        поз = i
    return правила



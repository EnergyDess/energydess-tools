# ШИРЕ ОБЩЕЙ КОЛОНКИ — ПО РЕШЕНИЮ, ПОИМЁННО И С ПРИЧИНОЙ (№352,
# «enshrouded-2»). Прежде правило звучало «ширина колонки содержимого
# ОДНА на все вкладки ВСЕХ инструментов», и оно было верно, пока потолок
# один (`--v2-content`). Владелец завёл частный потолок одному
# инструменту пробой — и прежняя формулировка стала печатать находку
# про исправное.
#
# СПИСОК ПУСТ С ПИСЬМА «ШИРОКИЙ РЕЖИМ ВЕЗДЕ» (№352): проба принята,
# потолок поднят ВСЕМ одним токеном, и частного режима не осталось —
# то есть прежнее правило «колонка одна у всех» снова действует
# в полном объёме, без исключений. Строку сюда возвращают только
# вместе с новым частным потолком, и тогда же назначают ей причину:
# запись без причины через полгода читается как случайная.
#
# ПРОВЕРКА ОТ ЭТОГО НЕ ОСЛАБЛЕНА: инструмент из списка обязан держать
# ОДНУ ширину на всех своих вкладках и вдобавок быть ШИРЕ общей — иначе
# режим не работает, а мы об этом не узнаем (то же «обратное» условие,
# что у контролей §6.0.3). Маской список закрывать нельзя: маска завтра
# проглотит инструмент, у которого ширина разъехалась по недосмотру
# (§6.0.7).
ШИРЕ_ПО_РЕШЕНИЮ = {}


def разбор_ширины(по_ширинам):
    """(строки отчёта, расхождений). Края сравниваются ВНУТРИ ширины."""
    строки, расхождений = [], 0
    for ш, инстр in sorted(по_ширинам.items()):
        края, свои = {}, {}
        for имя, места in инстр.items():
            куда = свои.setdefault(имя, {}) if имя in ШИРЕ_ПО_РЕШЕНИЮ else края
            for вкладка, к in места.items():
                куда[(имя, вкладка)] = (к["лево"], к["право"])
        if not края:
            строки.append("  %d: вкладок не найдено" % ш)
            continue
        набор = sorted(set(края.values()))
        строки.append("  %d: замеров %d, различных пар (лево, право): %d"
                      % (ш, len(края), len(набор)))
        if len(набор) > 1:
            расхождений += 1
            частота = {}
            for ключ, пара in края.items():
                частота.setdefault(пара, []).append(ключ)
            обычная = max(частота, key=lambda п: len(частота[п]))
            for пара, кто in частота.items():
                if пара == обычная:
                    continue
                for имя, вкладка in кто:
                    строки.append("     ВЫБИВАЕТСЯ %s / %s: %s вместо %s"
                                  % (имя, вкладка, пара, обычная))
        else:
            строки.append("     края у всех: %s" % (набор[0],))
        # Инструменты со своим потолком: одна пара краёв ВНУТРИ
        # инструмента плюс обратное условие «шире общей».
        общая = набор[0] if len(набор) == 1 else max(набор, key=lambda п: п[1] - п[0])
        for имя, места in sorted(свои.items()):
            пары = sorted(set(места.values()))
            if len(пары) > 1:
                расхождений += 1
                строки.append("     %s: пар краёв внутри инструмента %d — РАЗЪЕХАЛСЯ %s"
                              % (имя, len(пары), пары))
                continue
            моя = пары[0]
            шире = (моя[1] - моя[0]) > (общая[1] - общая[0])
            строки.append("     %s: %s, %s общей %s — %s"
                          % (имя, моя, "ШИРЕ" if шире else "НЕ ШИРЕ", общая,
                             ШИРЕ_ПО_РЕШЕНИЮ[имя]))
            if not шире:
                расхождений += 1
    return строки, расхождений



def разобрать_цвет(строка):
    """'rgb(10, 11, 18)' -> (10, 11, 18). Не разобралось — None."""
    ч = re.findall(r"[\d.]+", строка or "")
    if len(ч) < 3:
        return None
    return tuple(int(round(float(x))) for x in ч[:3])


def _картинка(кадр):
    from PIL import Image
    import io
    return Image.open(io.BytesIO(кадр)).convert("RGB")


def ступенька_в_свечении(полоса, фон):
    """(самый длинный участок одного цвета, сколько пикселей окрашено).

    Мера — та, которую назвал владелец: самый длинный участок одинакового
    цвета в горизонтальной строке. Плоский фон из счёта НЕ выбрасывается,
    и это не оплошность, а условие сравнимости: попытка считать только
    окрашенные пиксели дала у старого свечения «ступеньку 1 при зоне
    155 px», у нового — «7 при 1050» (замер 2026-09-20). Числа
    несравнимы, потому что зоны разные, — а вопрос был «стало ли меньше
    полос одного цвета в строке».

    Вторая величина (сколько окрашено) печатается РЯДОМ, а не вместо:
    без неё не видно, что заливка стала шире.
    """
    лучший, текущий, прежний = 0, 0, None
    окрашено = 0
    for п in полоса:
        if max(abs(a - b) for a, b in zip(п, фон)) > 0:
            окрашено += 1
        текущий = текущий + 1 if п == прежний else 1
        прежний = п
        лучший = max(лучший, текущий)
    return лучший, окрашено


def замер(ширина=1920, подлог=None, кадры=None):
    """{инструмент: {…}} — ступеньки, край свечения, цвета."""
    from playwright.sync_api import sync_playwright
    итог = {}
    with sync_playwright() as p:
        бр = p.chromium.launch()
        к = бр.new_context(viewport={"width": ширина, "height": 1000},
                           device_scale_factor=1)
        if подлог == "круг":
            к.add_init_script(
                "addEventListener('DOMContentLoaded', () => {"
                " const s = document.createElement('style');"
                " s.textContent = '.v2-page-head { background-image:"
                " radial-gradient(28% 60% at 28% 60%, var(--v2-tool-glow),"
                " transparent 100%) !important; }';"
                " document.head.appendChild(s); });")
        if подлог == "прежнее":
            # ПРЕЖНЕЕ СВЕЧЕНИЕ ЦЕЛИКОМ: круг на самой шапке, слоя `::after`
            # (линейная заливка плюс зерно) нет вовсе. Так снимается замер
            # «до» той же мерой, что и «после», без отката файла.
            к.add_init_script(
                "addEventListener('DOMContentLoaded', () => {"
                " const s = document.createElement('style');"
                " s.textContent = '.v2-page-head { background-image:"
                " radial-gradient(28% 60% at 28% 60%, var(--v2-tool-glow),"
                " transparent 100%) !important; }"
                " .v2-page-head::after { background-image: none !important; }';"
                " document.head.appendChild(s); });")
        стр = к.new_page()
        ch._войти(стр)
        for путь, имя in ИНСТРУМЕНТЫ:
            стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
            стр.wait_for_timeout(400)
            г = стр.evaluate(ЗАМЕР_ГЕОМЕТРИИ)
            if not г:
                итог[имя] = None
                continue
            кадр = стр.screenshot(animations="disabled")
            им = _картинка(кадр)
            # СТРОКА БЕРЁТСЯ В ВЕРХНЕМ ПОЛЕ ШАПКИ, А НЕ ПО ЕЁ СЕРЕДИНЕ:
            # посередине проходят заголовок, описание и кнопки, и каждый
            # их пиксель отличается от фона — замер 2026-09-20 дал «зону
            # свечения» 1910 px из 1920, то есть число про текст. В верхнем
            # поле (внутренний отступ шапки) текста нет, а свечение там
            # сильнее всего.
            y = int(г["шапка"]["y"] + 6)
            y = max(0, min(им.height - 1, y))
            # СТРОКА РЕЖЕТСЯ ПО ШАПКЕ: слева от неё боковое меню со своей
            # подложкой, и без этого «зона свечения» считала его тоже
            # (замер 2026-09-20: 1673 px при ширине шапки 1673 — совпало
            # случайно, а на 2560 разошлось бы).
            x0 = max(0, int(г["шапка"]["x"]))
            x1 = min(им.width, int(г["шапка"]["x"] + г["шапка"]["w"]))
            полоса = [им.getpixel((x, y)) for x in range(x0, x1)]
            низ = г["низ_вкладок"] or (г["шапка"]["y"] + г["шапка"]["h"])
            ниже = max(0, min(им.height - 1, int(низ + 20)))
            под_шапкой = им.getpixel((int(г["шапка"]["x"] + 40), ниже))
            фон = разобрать_цвет(г.get("фон_тела"))
            if фон is None:
                итог[имя] = None
                continue
            ступенька, зона = ступенька_в_свечении(полоса, фон)
            итог[имя] = {
                "ступенька": ступенька,
                "окрашено": зона,
                "строка_y": y,
                "ширина_кадра": им.width,
                "под_вкладками": list(под_шапкой),
                "фон_страницы": list(фон),
                "отклонение": max(abs(a - b) for a, b in zip(под_шапкой, фон)),
            }
            if кадры:
                os.makedirs(кадры, exist_ok=True)
                open(os.path.join(кадры, "head-%s-%d.png" % (имя, ширина)),
                     "wb").write(кадр)
        бр.close()
    return итог



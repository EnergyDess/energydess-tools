ЗАМЕР = r"""(свойства) => {
  // ── 1. КАКИЕ ТАБЛИЦЫ «СВОИ». Метка `@v2` первой строкой файла
  //    (признак проверки 47). Читается первое правило-комментарий
  //    нельзя (CSSOM комментарии выбрасывает), поэтому идём по href.
  const свой_лист = л => !!(л.href && /\/static\/(v2|v2_showcase)\.css/.test(л.href));

  // ── 2. СПЕЦИФИЧНОСТЬ. Готового API в браузере нет; считается так,
  //    как её считает каскад: id, класс/атрибут/псевдокласс, тег.
  //    `:not()`/`:is()` берутся по самому весомому аргументу.
  function спец(сел) {
    let s = сел.replace(/\\[^]/g, '');
    s = s.replace(/::[a-z-]+(\([^)]*\))?/g, 'ТЕГ');        // псевдоэлемент = тег
    s = s.replace(/:(not|is|has|where)\(([^)]*)\)/g, (м, ф, арг) => {
      if (ф === 'where') return '';
      const части = арг.split(',').map(ч => спец(ч.trim()));
      части.sort((a, b) => (b[0]-a[0]) || (b[1]-a[1]) || (b[2]-a[2]));
      const л = части[0] || [0,0,0];
      return 'І'.repeat(л[0]) + 'К'.repeat(л[1]) + 'Т'.repeat(л[2]);
    });
    const id = (s.match(/#[\w-]+/g) || []).length + (s.match(/І/g) || []).length;
    const кл = (s.match(/\.[\w-]+/g) || []).length
             + (s.match(/\[[^\]]*\]/g) || []).length
             + (s.match(/:[a-z-]+(\([^)]*\))?/g) || []).length
             + (s.match(/К/g) || []).length;
    const тег = (s.match(/(^|[\s>+~(,])[a-zA-Z][\w-]*/g) || []).length
              + (s.match(/Т/g) || []).length;
    return [id, кл, тег];
  }
  const больше = (a, b) => (a[0]-b[0]) || (a[1]-b[1]) || (a[2]-b[2]);

  // ── 3. ПЛОСКИЙ СПИСОК ПРАВИЛ В ПОРЯДКЕ КАСКАДА, с разворотом
  //    медиазапросов (берутся только ДЕЙСТВУЮЩИЕ на этой ширине).
  const правила = [];
  let порядок = 0;
  function обойти(набор, свой, лист) {
    for (const р of набор) {
      if (р.type === CSSRule.MEDIA_RULE || r_supports(р)) {
        try { if (р.media && !matchMedia(р.conditionText || р.media.mediaText).matches) continue; } catch (e) {}
        обойти(р.cssRules || [], свой, лист); continue;
      }
      if (р.type !== CSSRule.STYLE_RULE || !р.selectorText) continue;
      const объявл = {};
      for (const п of свойства) {
        const имя = (п === 'border-top-color') ? 'border-color' : п;
        let v = р.style.getPropertyValue(п) || р.style.getPropertyValue(имя);
        if (!v && п === 'background-color') v = р.style.getPropertyValue('background');
        if (!v && п === 'border-top-color') v = р.style.getPropertyValue('border');
        if (v) объявл[п] = {текст: v.trim(),
                            важно: !!(р.style.getPropertyPriority(п)
                                   || р.style.getPropertyPriority(имя))};
      }
      if (!Object.keys(объявл).length) continue;
      for (const сел of р.selectorText.split(',')) {
        const с = сел.trim();
        if (!с) continue;
        правила.push({сел: с, свой: свой, спец: спец(с), n: порядок++,
                      объявл: объявл, лист: лист});
      }
    }
  }
  function r_supports(р) { return р.type === CSSRule.SUPPORTS_RULE; }
  for (const л of document.styleSheets) {
    let набор; try { набор = л.cssRules; } catch (e) { continue; }
    if (!набор) continue;
    обойти(набор, свой_лист(л), (л.href || 'inline').split('/').pop().split('?')[0]);
  }

  // ── 4. ЭЛЕМЕНТЫ С КЛАССОМ v2-*, ВИДИМЫЕ НА ЭКРАНЕ.
  const О = {opacityProperty: true, visibilityProperty: true, contentVisibilityAuto: true};
  const видно = э => {
    if (э.checkVisibility && !э.checkVisibility(О)) return false;
    const b = э.getBoundingClientRect();
    return b.width > 0 && b.height > 0;
  };
  const элементы = [...document.querySelectorAll('[class]')].filter(
    э => /(^|\s)v2-/.test(э.className.baseVal || э.className || '') && видно(э));

  const находки = [];
  let проверено = 0;
  for (const э of элементы) {
    const подошли = правила.filter(р => { try { return э.matches(р.сел); } catch (e) { return false; } });
    if (!подошли.some(р => р.свой)) continue;
    for (const п of свойства) {
      const с_п = подошли.filter(р => р.объявл[п]);
      if (!с_п.length) continue;
      if (!с_п.some(р => р.свой)) continue;   // v2 это свойство не задаёт
      проверено += 1;
      // ПОБЕДИТЕЛЬ ПО ПРАВИЛАМ КАСКАДА: важность, затем специфичность,
      // затем порядок. Инлайновый стиль сильнее любого правила.
      let поб = null;
      for (const р of с_п) {
        if (!поб) { поб = р; continue; }
        const a = р.объявл[п].важно, b = поб.объявл[п].важно;
        if (a !== b) { if (a) поб = р; continue; }
        const d = больше(р.спец, поб.спец);
        if (d > 0 || (d === 0 && р.n > поб.n)) поб = р;
      }
      const инлайн = э.style.getPropertyValue(п)
                  || (п === 'background-color' && э.style.getPropertyValue('background'));
      if (инлайн) continue;                   // это ловит проверка 3
      if (поб.свой) continue;
      const свои = с_п.filter(р => р.свой);
      const старший = свои[свои.length - 1];
      const выч = getComputedStyle(э);
      находки.push({
        элемент: (э.tagName.toLowerCase() + (э.id ? '#' + э.id : '')
                  + '.' + String(э.className).trim().split(/\s+/).slice(0, 3).join('.')),
        свойство: п,
        ожидалось: старший.объявл[п].текст,
        фактически: выч.getPropertyValue(п),
        победитель: поб.сел + '  {' + поб.лист + '}',
        v2_правило: старший.сел,
      });
    }
  }
  // ОДНА НАХОДКА НА ПАРУ «ПОБЕДИТЕЛЬ + СВОЙСТВО»: один и тот же
  // проигрыш на двадцати одинаковых полях — один дефект, а таблица
  // из двадцати строк перестаёт читаться (§6.0.2, довод проверки 4).
  const свод = {};
  for (const н of находки) {
    const к = н.победитель + '|' + н.свойство;
    if (!свод[к]) { свод[к] = Object.assign({штук: 0}, н); }
    свод[к].штук += 1;
  }
  return {элементов: элементы.length, пар: проверено,
          находки: Object.values(свод), всего: находки.length};
}"""


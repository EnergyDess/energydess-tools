def шаг(имя, условие, подробность="", собрано=None, отрицание=None):
    global находок, пропусков, шагов
    шагов += 1
    if собрано is not None and not собрано:
        пропусков += 1
        print("  ПРОПУСК %-44s %s" % (имя, отрицание or "мерить нечего"))
        return
    if условие:
        print("  OK      %-44s %s" % (имя, подробность))
    else:
        находок += 1
        print("  ПЛОХО   %-44s %s" % (имя, подробность))


def прогон(подлог=None, только=None):
    from playwright.sync_api import sync_playwright
    итог = {}
    with sync_playwright() as p:
        бр = p.chromium.launch()
        try:
            к = бр.new_context(viewport={"width": ШИРИНА, "height": ВЫСОТА})
            if подлог == "старое-правило":
                к.add_init_script(ПОДЛОГ_СТАРОЕ)
            стр = к.new_page()
            ch._войти(стр)
            for путь, имя, нажать in ЭКРАНЫ:
                if только and имя not in только:
                    continue
                try:
                    стр.goto(ch.БАЗА + путь, wait_until="domcontentloaded")
                    стр.wait_for_timeout(500)
                    for сел in нажать:
                        стр.click(сел, timeout=5000)
                        стр.wait_for_timeout(600)
                    з = стр.evaluate(ЗАМЕР, list(СВОЙСТВА))
                except Exception as e:
                    итог[имя] = {"сбой": str(e).splitlines()[0][:70]}
                    continue
                итог[имя] = з
        finally:
            бр.close()
    return итог


def разбор(итог, печатать=True):
    всего = 0
    for имя, з in итог.items():
        if "сбой" in з:
            if печатать:
                print("  ПРОПУСК %-44s %s" % (имя, з["сбой"]))
            continue
        н = з.get("находки", [])
        всего += len(н)
        если_долг = ДОЛГ.get(имя)
        если_долг = 0 if если_долг is None else если_долг
        if печатать:
            метка = "OK     " if not н else ("ДОЛГ   " if len(н) <= если_долг else "ПЛОХО  ")
            print("  %s %-44s элементов %4d, пар %4d, находок %d"
                  % (метка, имя, з.get("элементов", 0), з.get("пар", 0), len(н)))
            for f in н:
                print("           %s · %s" % (f["элемент"], f["свойство"]))
                print("             ожидалось %s (правило v2: %s)"
                      % (f["ожидалось"], f["v2_правило"]))
                print("             фактически %s ← %s  ×%d"
                      % (f["фактически"], f["победитель"], f["штук"]))
    return всего


def контроль():
    global находок
    print("=" * 74)
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ — подлог «старое-правило»")
    print("=" * 74)
    сцена = ["аптечка · правка"]
    чисто = прогон(только=сцена)
    грязно = прогон(подлог="старое-правило", только=сцена)

    def фон(и):
        з = list(и.values())[0]
        for f in з.get("находки", []):
            if f["свойство"] == "background-color":
                return f["фактически"]
        return "(находок нет)"

    print("\n  ДОКАЗАТЕЛЬСТВО (%s): без подлога %s, с подлогом %s"
          % (ДОКАЗАТЕЛЬСТВА["старое-правило"], фон(чисто), фон(грязно)))
    было = разбор(чисто)
    стало = разбор(грязно)
    print("\n  ИТОГ КОНТРОЛЯ: находок без подлога %d, с подлогом %d" % (было, стало))
    if было == 0 and стало > 0:
        print("  ЛОВИТ")
        return 0
    print("  НЕ ЛОВИТ")
    return 1



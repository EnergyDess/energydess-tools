import measure_redesign as mr  # noqa: E402  меняет каталог на корень проекта

# СТАРТОВЫЙ ДОЛГ — замер блока 1 (`py measure_redesign.py`, раздел 2),
# 2026-09-19. Меняется ТОЛЬКО вниз и только тем коммитом, что долг
# уменьшил; поднимать его, чтобы проверка прошла, — значит отключить её.
ДОЛГ_НАЧАЛО = {"цвет": 45, "размер шрифта": 45, "отступ": 113,
               "скругление": 71, "тень": 28}

ЛИТЕРАЛ = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\(|hsla?\(|(?<![\w-])-?\d*\.?\d+(px|rem|em)\b")


def файлы_v2():
    return sorted(p.replace("\\", "/") for p in mr.glob.glob("static/*.css") if mr.помечен_v2(p))


def находки_v2(путь, текст=None):
    """(строка, что) для одного файла v2."""
    t = mr.читать(путь) if текст is None else текст
    найдено = [(i, f"{в}: {prop}: {val.strip()[:60]}")
               for в, i, prop, val, _ in mr.прямые_значения(путь, t)]
    # Токен со значением вне `:root`: строки, лежащие внутри `:root { … }`,
    # законны — это и есть одно место значений.
    чист = mr.без_комм(t)
    внутри = set()
    for m in re.finditer(r":root\s*\{", чист):
        глуб, j = 1, m.end()
        while j < len(чист) and глуб:
            глуб += чист[j] == "{"
            глуб -= чист[j] == "}"
            j += 1
        a = чист.count("\n", 0, m.start()) + 1
        b = чист.count("\n", 0, j) + 1
        внутри.update(range(a, b + 1))
    for i, line in enumerate(чист.split("\n"), 1):
        if i in внутри:
            continue
        for m in re.finditer(r"(--[a-zA-Z0-9_-]+)\s*:\s*([^;{}]+)", line):
            if ЛИТЕРАЛ.search(mr.очистить_var(m.group(2))):
                найдено.append((i, f"токен вне :root: {m.group(1)}: {m.group(2).strip()[:60]}"))
    return sorted(найдено)


def долг(подмена=None):
    """{вид: число} по старому коду. `подмена` — {путь: текст} для подлога."""
    итог = {в: 0 for в in ДОЛГ_НАЧАЛО}
    for p in mr.CSS:
        текст = (подмена or {}).get(p)
        for в, _, _, _, h in mr.прямые_значения(p, текст):
            итог[в] += h
    return итог


def прогон(подмена_v2=None, подмена_долга=None, печать=True):
    """Возвращает (код, находки v2, долг)."""
    файлы = файлы_v2()
    if not файлы:
        if печать:
            print("ПРОПУСК: файлов с меткой @v2 нет — проверять нечего (код 2)")
        return 2, [], {}
    находки = []
    for p in файлы:
        текст = (подмена_v2 or {}).get(p)
        for i, что in находки_v2(p, текст):
            находки.append(f"{p}:{i}  {что}")
    д = долг(подмена_долга)
    всего, было = sum(д.values()), sum(ДОЛГ_НАЧАЛО.values())
    вырос = всего > было
    if печать:
        print(f"Файлов v2: {len(файлы)} — {', '.join(файлы)}")
        print(f"Прямых значений в файлах v2: {len(находки)}")
        for н in находки:
            print("   " + н)
        print(f"ДОЛГ старого кода: {всего} (стартовый {было}) — "
              + ", ".join(f"{в} {д[в]}/{ДОЛГ_НАЧАЛО[в]}" for в in ДОЛГ_НАЧАЛО))
        if вырос:
            print(f"   ДОЛГ ВЫРОС на {всего - было}: новые прямые значения в старых файлах")
        print("ИТОГ:", "ЧИСТО" if not находки and not вырос else "ЕСТЬ НАХОДКИ")
    return (1 if находки or вырос else 0), находки, д


# ---------- отрицательный контроль ----------
ПОДЛОГ_ЦВЕТ = "  color: #ff00aa;"
ПОДЛОГ_СТАРЫЙ = "\n.zz-podlog { margin-top: 7px; }\n"


def доказать_подлог(имя, текст_до, текст_после, признак):
    """Подлог СОСТОЯЛСЯ, если признак подлога в тексте появился: 0 → ≥1.
    Независимо от вердикта проверки (§6.0.3)."""
    до, после = текст_до.count(признак), текст_после.count(признак)
    print(f"   доказательство «{имя}»: «{признак.strip()}» в тексте {до} → {после}")
    return до == 0 and после >= 1


def контроль():
    print("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ПРОВЕРКИ 47")
    код0, н0, д0 = прогон(печать=False)
    if код0 != 0:
        print(f"ГРЯЗНАЯ ОСНОВА: чистый прогон дал код {код0} — контроль недействителен")
        return 2
    print(f"чистый прогон: находок {len(н0)}, долг {sum(д0.values())}")
    итог = 0

    # 1. прямой цвет в стиле витрины — проверка называет файл и строку
    путь = "static/v2_showcase.css"
    до = mr.читать(путь)
    строки = до.split("\n")
    # вставляется ВНУТРЬ первого правила `.v2s {`, строкой ниже открывающей
    k = next(i for i, l in enumerate(строки) if l.startswith(".v2s {"))
    строки.insert(k + 1, ПОДЛОГ_ЦВЕТ)
    после = "\n".join(строки)
    ждём = f"{путь}:{k + 2}"
    сост = доказать_подлог("цвет в витрине", до, после, ПОДЛОГ_ЦВЕТ)
    код, н, _ = прогон(подмена_v2={путь: после}, печать=False)
    назван = any(x.startswith(ждём) for x in н)
    print(f"1. прямой цвет в {ждём}: код {код0} → {код}, находка названа: {назван}")
    for x in н:
        print("      " + x)
    if not (сост and код == 1 and назван):
        итог = 1

    # 2. прямое значение в старом файле — долг вырос, проверка падает
    путь2 = "static/hh.css"
    до2 = mr.читать(путь2)
    после2 = до2 + ПОДЛОГ_СТАРЫЙ
    сост2 = доказать_подлог("отступ в старом файле", до2, после2, "margin-top: 7px")
    код2, _, д2 = прогон(подмена_долга={путь2: после2}, печать=False)
    print(f"2. отступ в {путь2}: долг {sum(д0.values())} → {sum(д2.values())}, код {код0} → {код2}")
    if not (сост2 and код2 == 1 and sum(д2.values()) == sum(д0.values()) + 1):
        итог = 1

    # 3. ОБРАТНЫЙ: токен v2 вместо прямого значения — находки НЕТ
    после3 = после.replace(ПОДЛОГ_ЦВЕТ, "  color: var(--v2-text);")
    код3, н3, _ = прогон(подмена_v2={путь: после3}, печать=False)
    print(f"3. обратный — тот же цвет токеном: код {код3}, находок {len(н3)}")
    if код3 != 0:
        итог = 1

    print("КОНТРОЛЬ:", "ПОДЛОГИ НАЙДЕНЫ, ОБРАТНЫЙ ПРОШЁЛ" if итог == 0 else "ПРОВАЛЕН")
    return итог


if __name__ == "__main__":
    if "--контроль" in sys.argv:
        sys.exit(контроль())
    sys.exit(прогон()[0])

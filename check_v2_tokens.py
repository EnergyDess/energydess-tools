"""ПРОВЕРКА 47: СТИЛИ ПО v2 — ТОЛЬКО ПЕРЕМЕННЫЕ v2; ДОЛГ СТАРОГО КОДА НЕ РАСТЁТ.

BACKLOG №352, письмо 1, блок 3.

Две половины, и код возврата считается по обеим:

  1. ФАЙЛЫ v2 — `static/*.css` с меткой `@v2` в первой строке. В них
     НОЛЬ прямых значений цвета, кегля, отступа, скругления и тени —
     только `var(--v2-*)`. Плюс токен со значением-литералом вне
     `:root` (`--x: #fff` в правиле компонента) — тоже находка: значения
     v2 объявляются в одном месте, `static/v2.css`.
  2. ДОЛГ — прямые значения в залогиненных стилях, ещё не переведённых
     на v2. Число печатается, и проверка падает, если оно ВЫРОСЛО против
     стартового из замера блока 1 (`docs/redesign_before.md`). Уменьшаться
     ему можно и нужно: письма 2–8 переводят код на v2.

СЧЁТ ОДИН НА МЕРКУ И НА СТОРОЖ: `measure_redesign.прямые_значения`
(импортом). Вторая реализация разошлась бы с первой молча (§6.0.7),
и «долг вырос» значил бы разное в замере и в проверке.

Код возврата: 0 — чисто; 1 — находка в v2 либо долг вырос; 2 — файлов
v2 нет вовсе (проверять нечего: пустой сбор не равен чистоте).

    py check_v2_tokens.py              # проверка
    py check_v2_tokens.py --контроль   # два подлога, у каждого доказательство
"""

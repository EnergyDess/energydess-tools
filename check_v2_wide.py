ТОЧКИ_ЯРКОСТИ = (0.02, 0.10, 0.25, 0.50, 0.75)


def _свечение_инструмента(стр, им, г):
    """Доля окрашенной ширины и отклонения от фона в пяти точках."""
    import check_v2_head as vh2
    фон = vh2.разобрать_цвет(г.get("фон_тела"))
    if фон is None:
        return None
    y = max(0, min(им.height - 1, int(г["шапка"]["y"] + 6)))
    x0 = max(0, int(г["шапка"]["x"]))
    x1 = min(им.width, int(г["шапка"]["x"] + г["шапка"]["w"]))
    полоса = [им.getpixel((x, y)) for x in range(x0, x1)]
    окрашено = sum(1 for п in полоса
                   if max(abs(a - b) for a, b in zip(п, фон)) > 2)
    точки = []
    for доля in ТОЧКИ_ЯРКОСТИ:
        x = min(len(полоса) - 1, int(доля * len(полоса)))
        точки.append(max(abs(a - b) for a, b in zip(полоса[x], фон)))
    return {
        "шапка": round(г["шапка"]["w"], 1),
        "окрашено": окрашено,
        "доля": round(окрашено / max(1, len(полоса)), 3),
        "яркость": точки,
        # ПРОФИЛЬ — ЯРКОСТЬ В ДОЛЯХ ОТ ПЕРВОЙ ТОЧКИ. Цвет инструмента
        # в нём сокращается, и остаётся ФОРМА затухания: правило v2
        # обещает «одинаковая ширина и сила, отличается только цвет»,
        # а сравнивать сами каналы значило бы требовать одного цвета.
        "профиль": [round(з / точки[0], 2) if точки[0] else None
                    for з in точки],
    }



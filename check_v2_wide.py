def проверить(замер):
    """Шаги проверки по снятому замеру."""
    строк = []
    for ш in sorted(замер, key=int):
        for имя, д in замер[ш]["экраны"].items():
            строк.append((ш, имя, д["строка"]["худший"], д["прокрутка"]))
        for подпись, д in замер[ш]["тексты"].items():
            if д:
                строк.append((ш, подпись, д["строка"]["худший"], д["прокрутка"]))
    длинные = [(ш, имя, х) for ш, имя, х, _ in строк if х["знаков"] > ПОТОЛОК_СТРОКИ]
    шаг("строка текста не длиннее %d знаков" % ПОТОЛОК_СТРОКИ, not длинные,
        "худшее: %s" % ("; ".join("%s/%s %d зн. (%s)" % (ш, имя, х["знаков"], х["кто"])
                                  for ш, имя, х in длинные[:4]) or "нет"),
        собрано=len(строк))
    перелив = [(ш, имя, п) for ш, имя, _, п in строк if п["док"] > 1 or п["тело"] > 1]
    шаг("горизонтальной прокрутки нет", not перелив,
        "; ".join("%s/%s док %d тело %d" % (ш, имя, п["док"], п["тело"])
                  for ш, имя, п in перелив[:4]) or "0 из %d" % len(строк),
        собрано=len(строк))
    широкие = [(ш, имя, (д["колонка"] or {}).get("ширина") or 0)
               for ш in замер for имя, д in замер[ш]["экраны"].items()]
    за_потолком = [т for т in широкие if т[2] > ПОТОЛОК_КОЛОНКИ + 1]
    шаг("колонка не шире потолка %d" % ПОТОЛОК_КОЛОНКИ, not за_потолком,
        "; ".join("%s/%s %.1f" % т for т in за_потолком[:4]) or "0 из %d" % len(широкие),
        собрано=len(широкие))
    одна = {}
    for ш in замер:
        for имя, д in замер[ш]["экраны"].items():
            одна.setdefault(ш, {})[имя] = (д["колонка"] or {}).get("ширина") or 0
    разные = ["%s: %s" % (ш, ", ".join("%s %.0f" % (и, в) for и, в in sorted(м.items())))
              for ш, м in одна.items() if len(set(round(в) for в in м.values())) > 1]
    шаг("колонка ОДНА у всех инструментов", not разные,
        "; ".join(разные[:2]) or "по всем ширинам совпала", собрано=len(одна))
    return находок, пропусков


def сверить(до, после):
    пар = 0
    print("КОЛОНКА И СЕТКИ, до -> после:")
    print("  %-6s %-12s %17s %19s %13s" % ("окно", "инструмент", "колонка",
                                           "сетка", "колонок"))
    ужалось = []
    for ш in sorted(до, key=int):
        for имя, д0 in до[ш]["экраны"].items():
            д1 = после.get(ш, {}).get("экраны", {}).get(имя)
            if not д1:
                continue
            пар += 1
            к0 = (д0["колонка"] or {}).get("ширина") or 0
            к1 = (д1["колонка"] or {}).get("ширина") or 0
            с0 = (д0["сетки"] or [{}])[0]
            с1 = (д1["сетки"] or [{}])[0]
            print("  %-6s %-12s %7.1f -> %7.1f %8s -> %8s %5s -> %-5s" % (
                ш, имя, к0, к1, с0.get("ширина") or "—", с1.get("ширина") or "—",
                с0.get("колонок") or "—", с1.get("колонок") or "—"))
            if (с0.get("колонок") or 0) and (с1.get("колонок") or 0) < (с0.get("колонок") or 0):
                ужалось.append("%s/%s: %s -> %s" % (ш, имя, с0["колонок"], с1["колонок"]))
    print("СТРОКА ТЕКСТА, максимум знаков до -> после:")
    for ш in sorted(до, key=int):
        for подпись, д0 in до[ш]["тексты"].items():
            д1 = после.get(ш, {}).get("тексты", {}).get(подпись)
            if not д0 or not д1:
                continue
            print("  %-6s %-24s %3d -> %3d" % (
                ш, подпись, д0["строка"]["худший"]["знаков"],
                д1["строка"]["худший"]["знаков"]))
    шаг("число колонок нигде не уменьшилось", not ужалось,
        "; ".join(ужалось[:4]) or "ни на одной ширине из %d пар" % пар,
        собрано=пар)
    return ужалось



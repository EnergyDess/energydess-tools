ЗАМЕР_СТРОКИ = r"""(потолок) => {
  // САМАЯ ДЛИННАЯ ВИЗУАЛЬНАЯ СТРОКА. Символы группируются по `top`
  // своего прямоугольника: перенос делает браузер, и посчитать его
  // можно только у него же.
  //
  // ЦЕНА ЗАМЕРА ОГРАНИЧЕНА ДВУМЯ СУЖЕНИЯМИ, И ОБА БЕЗОПАСНЫ. Узел
  // короче `ПОТОЛОК_СТРОКИ` знаков не может дать строку длиннее
  // потолка по построению — такие не берутся вовсе; берутся САМЫЕ
  // ДЛИННЫЕ узлы страницы, и у каждого мерятся только первые
  // `СТРОК_НА_УЗЕЛ` строк: в тексте, выровненном по левому краю,
  // полные строки равны между собой, а последняя всегда короче.
  const СТРОК_НА_УЗЕЛ = 5;
  const УЗЛОВ = 60;
  const видим = (эл) => {
    const с = getComputedStyle(эл);
    if (с.display === 'none' || с.visibility === 'hidden') return false;
    const r = эл.getBoundingClientRect();
    return r.width > 1 && r.height > 1;
  };
  const обход = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(у) {
      const т = (у.nodeValue || '').replace(/\s+/g, ' ').trim();
      if (т.length < 40) return NodeFilter.FILTER_REJECT;
      const p = у.parentElement;
      if (!p || !видим(p)) return NodeFilter.FILTER_REJECT;
      if (p.closest('script, style, noscript, pre, code, textarea')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const узлы = [];
  let у;
  while ((у = обход.nextNode())) узлы.push(у);
  узлы.sort((a, b) => b.nodeValue.length - a.nodeValue.length);
  let худший = {знаков: 0, кто: null, ширина: 0, текст: ''};
  const r = document.createRange();
  for (const узел of узлы.slice(0, УЗЛОВ)) {
    const длина = узел.nodeValue.length;
    let строк = 0;
    let верх = null;
    let знаков = 0;
    for (let i = 0; i < длина; i += 1) {
      const зн = узел.nodeValue[i];
      if (зн === '\n' || зн === '\t') continue;
      r.setStart(узел, i); r.setEnd(узел, i + 1);
      const п = r.getBoundingClientRect();
      if (!п.width && !п.height) continue;
      const ключ = Math.round(п.top);
      if (верх === null) верх = ключ;
      if (ключ !== верх) {
        if (знаков > худший.знаков) {
          const p = узел.parentElement;
          худший = {
            знаков: знаков,
            кто: p.tagName.toLowerCase() + '.' + (p.className || '').toString().split(' ')[0],
            ширина: Math.round(p.getBoundingClientRect().width),
            текст: узел.nodeValue.trim().slice(0, 40)
          };
        }
        строк += 1;
        if (строк >= СТРОК_НА_УЗЕЛ) break;
        верх = ключ;
        знаков = 0;
      }
      знаков += 1;
    }
  }
  return {худший: худший, узлов: Math.min(узлы.length, УЗЛОВ), потолок: потолок};
}"""


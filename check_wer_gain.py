def _база_путь():
    if "--база" in sys.argv:
        п = sys.argv[sys.argv.index("--база") + 1]
    else:
        п = os.getenv("DB_PATH", "app.db")
    if "/data/" in п.replace(chr(92), "/"):
        print("БОЕВАЯ БАЗА НЕ ОТКРЫВАЕТСЯ. Снимите копию.")
        sys.exit(0)
    return п


def позиции(путь):
    c = sqlite3.connect("file:%s?mode=ro" % путь.replace(chr(92), "/"),
                        uri=True)
    c.row_factory = sqlite3.Row
    строки = c.execute(
        "SELECT id, name, form, substance, dosage_text "
        "FROM medkit_items ORDER BY id").fetchall()
    c.close()
    return [dict(с) for с in строки]


async def карточки(кл, запрос):
    """Ссылки на карточки товара по запросу."""
    try:
        r = await кл.get(ПОИСК % urllib.parse.quote(запрос))
    except Exception as e:
        return None, type(e).__name__
    if r.status_code != 200:
        return None, "HTTP %d" % r.status_code
    return set(КАРТОЧКА.findall(r.text)), None


async def раздел_есть(кл, путь):
    """Есть ли на странице СОДЕРЖАТЕЛЬНЫЙ раздел о дозировании.

    Признак берётся у `medkit_dosage` — тот же, что решает это
    у Видаля. Своего тут нет ни строки.
    """
    try:
        r = await кл.get(БАЗА + путь)
    except Exception:
        return False, ""
    if r.status_code != 200:
        return False, ""
    плоско = дозы.без_тегов(r.text)
    низ = плоско.lower()
    for заг in дозы.ЗАГОЛОВКИ_ДОЗ:
        поз = низ.find(заг)
        if поз < 0:
            continue
        кусок = плоско[поз:поз + 3000]
        if дозы.пустая_инструкция(кусок):
            continue
        return True, кусок[:120].replace("\n", " ")
    return False, ""



def _ключи_проверить():
    """НЕЗНАКОМЫЙ КЛЮЧ ОСТАНАВЛИВАЕТ ПРОГОН, а не проглатывается.

    Найдено на себе 2026-09-09 (заход 249). `main.py` ссылался
    на режим `--расхождения`, которого в этом файле НЕТ НИ ОДНОЙ
    строки, — и прогон с ним шёл ОБЫЧНЫМ путём, печатая числа
    про другой вопрос. То есть команда из документации «работала»
    и отвечала не на то, о чём её спросили: §6.0.1 в чистом виде,
    только ключ вместо кода возврата.

    Своё же имя ключа тут не перечень на открытом множестве
    (§6.0.7): новый режим появляется решением о КОДЕ, и строка
    в `КЛЮЧИ` — часть этого решения.
    """

def _дыры(поз):
    """Позиции, у которых ПОЛЯ НЕТ НИ ИЗ ОДНОГО ИСТОЧНИКА.

    Признак боевой: заглушка справочника (`пустая_инструкция`)
    заполненным полем НЕ СЧИТАЕТСЯ — её `_апт_выдержка` при чтении
    отбрасывает, и на экране у такой позиции пусто. Считай мы её
    заполненной, дыра выглядела бы закрытой ровно там, где человек
    видит пустоту.
    """
    без_схемы, без_показаний = [], []
    for п in поз:
        сво = (п["own_dosage_text"] or "").strip()
        спр = (п["dosage_text"] or "").strip()
        if not сво and (not спр or дозы.пустая_инструкция(спр)):
            без_схемы.append(п["id"])
        своиП = (п["own_indications_text"] or "").strip()
        спрП = (п["indications_text"] or "").strip()
        if not своиП and not спрП:
            без_показаний.append(п["id"])
    return без_схемы, без_показаний



def позиции(путь):
    c = sqlite3.connect("file:%s?mode=ro" % путь.replace(chr(92), "/"),
                        uri=True)
    c.row_factory = sqlite3.Row
    строки = c.execute(
        "SELECT id, name, form, substance, dose, dosage_text, "
        "own_dosage_text, indications_text, own_indications_text "
        "FROM medkit_items ORDER BY id").fetchall()
    c.close()
    return [dict(с) for с in строки]


async def карточки(кл, запрос):
    """Ссылки на карточки товара по запросу.

    ТРИ ИСХОДА, А НЕ ДВА (BACKLOG №239, A.1). Пустое множество
    и `None` означают РАЗНОЕ: первое — «источник ответил, карточек
    в выдаче нет», второе — «спросить не удалось». Прежняя версия
    возвращала пустое множество в обоих случаях, и «регулярка отстала»
    было неотличимо от «сайт лёг».
    """
    try:
        r = await кл.get(ПОИСК % urllib.parse.quote(запрос))
    except Exception as e:
        return None, type(e).__name__
    if r.status_code != 200:
        return None, "HTTP %d" % r.status_code
    наб = set(КАРТОЧКА.findall(r.text))
    # ДЛИНА ТЕЛА В ПОДРОБНОСТИ ОБЯЗАТЕЛЬНА: «карточек 0» при теле
    # в 200 КБ и при теле в 2 КБ — разные факты
    return наб, "тело %d КБ, карточек %d" % (len(r.text) // 1024, len(наб))


async def раздел_есть(кл, путь):
    """Есть ли на странице СОДЕРЖАТЕЛЬНЫЙ раздел о дозировании.

    Признак берётся у `medkit_dosage` — тот же, что решает это
    у Видаля. Своего тут нет ни строки.
    """
    try:
        r = await кл.get(БАЗА + путь)
    except Exception:
        return False, ""
    if r.status_code != 200:
        return False, ""
    плоско = дозы.без_тегов(r.text)
    низ = плоско.lower()
    for заг in дозы.ЗАГОЛОВКИ_ДОЗ:
        поз = низ.find(заг)
        if поз < 0:
            continue
        кусок = плоско[поз:поз + 3000]
        if дозы.пустая_инструкция(кусок):
            continue
        return True, кусок[:120].replace("\n", " ")
    return False, ""



    print()
    if подлог:
        print("КОНТРОЛЬ: закрытых обязано быть 0. Фактически %d — %s"
              % (len(закрыл),
                 "ЗАСЛОН ДЕРЖИТ" if not закрыл else "ПРОРЫВ"))
        print("Прорывов базовой линии: %d из %d" % (прорывов, len(БРЕД)))
    if обратный:
        print("КОНТРОЛЬ-ОБРАТНЫЙ: закрытых обязано быть %d (все дыры)."
              % len(ид_дыр))

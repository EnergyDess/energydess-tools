def только_местно(id_, команда=""):
    """Причина, по которой проверка не идёт в CI, либо None."""
    if нужно_окно(команда):
        return "видимое окно браузера (§6.0.3)"
    return МЕСТНО.get(id_)


def маски_проверки(id_, команда=""):
    """Маски проверки ПЛЮС её собственный файл.

    Правка `check_x.py` обязана прогнать `check_x.py`; выводится это
    из команды, а не вписывается в реестр отдельной строкой — забытая
    строка была бы немым пропуском.
    """
    запись = РЕЕСТР.get(id_)
    if запись is None or запись[0] == ВСЕГДА:
        return ВСЕГДА
    маски = list(запись[0])
    for слово in команда.split():
        if слово.endswith(".py") and слово not in маски:
            маски.append(слово)
    return маски


def уровень(id_):
    запись = РЕЕСТР.get(id_)
    return "быстрый" if запись is None else запись[1]


def нужно_окно(команда):
    """Нужно ли пробе ВИДИМОЕ окно — по `check_headed.ВЁРСТКА`.

    Перечень не дублируется: своя копия разошлась бы с проверкой 45
    молча, и быстрый ряд то поднимал бы лишнее окно, то не поднимал
    нужное (§6.0.7).
    """
    try:
        import check_headed
    except Exception:
        return True          # не прочитали перечень — окно поднимаем
    for слово in команда.split():
        if слово.endswith(".py") and слово in check_headed.ВЁРСТКА:
            return True
    return False


def подходит(путь, маски):
    """Путь (относительный, через '/') подпадает ли под маски."""
    if маски == ВСЕГДА:
        return True
    путь = путь.replace(os.sep, "/")
    for м in маски:
        if fnmatch.fnmatch(путь, м) or fnmatch.fnmatch(путь, м + "/*"):
            return True
    return False


def непокрытые(идентификаторы):
    """Проверки, которых в реестре нет: гоняются ВСЕГДА и называются."""
    return [i for i in идентификаторы if i not in РЕЕСТР]


def все_маски():
    """Объединение всех масок — что вообще имеет смысл хешировать."""
    итог = []
    for маски, _у, _о in РЕЕСТР.values():
        if маски == ВСЕГДА:
            continue
        for м in маски:
            if м not in итог:
                итог.append(м)
    return итог

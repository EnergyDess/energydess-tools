# ── ЛИЧНАЯ ФРАЗА (1.4) ────────────────────────────────────────────────
# Опыт ведущего, мнение, вопрос зрителю — не утверждение о фактах:
# ссылка [ист.] на такой фразе выдаёт личное за сказанное источником.
ЛИЧНОЕ_НАЧАЛО = re.compile(r"^\W*(?:я|мне|меня|мной|по-моему|по\s+мне|как\s+по\s+мне|лично|"
                           r"представ\w*|а\s+вы|а\s+ты|как\s+думаешь|как\s+думаете|пиши\w*|напиши\w*|"
                           r"ставь\w*|подпиш\w*|подпис\w*)\b", re.I)
ЛИЧНОЕ_ОПЫТ = re.compile(r"\b(?:я|мне)\b(?:\s+\S+){0,3}?\s+(?:представля|помн|играл|игра|кайф|офигев|"
                         r"люблю|думаю|кажется|считаю|нравит|жду|хочу|верю)", re.I)


def личная(текст: str) -> bool:
    """Личная фраза ведущего. Вопрос зрителю — тоже, если в нём нет чисел
    (вопрос с цифрой бывает подачей факта)."""
    т = (текст or "").strip()
    if ЛИЧНОЕ_НАЧАЛО.search(т) or ЛИЧНОЕ_ОПЫТ.search(т):
        return True
    return т.endswith("?") and not re.search(r"\d", т)


# ── ОБРАЗЦЫ РЕЧИ — ИНТОНАЦИЯ, НЕ ЗАГОТОВКИ (письмо B4, 1.4) ──────────
# В №59 и №70 стояло «Я представляю, как играл в Red Dead 2 и офигевал…» —
# начало цитаты из блока «Как я говорю», в №59 ещё «Многие будут вонять, что
# GTA уже не та». Правило: в пакете не больше ОДНОЙ почти дословной цитаты,
# и не той, на которую опирался последний собранный пакет.
#
# «ПОЧТИ ДОСЛОВНО» — по ОСНОВАМ слов (5 букв, слова от 3 букв, без служебных):
# общих с предложением цитаты не меньше 4 И они составляют не меньше 60 %
# основ строки либо 60 % основ предложения цитаты. Замер на строках №70:
# «Я представляю, как играл в Red Dead 2 и офигевал от зверья» — 6 общих
# из 8 (75 %), совпадение; «В Red Dead я мог часами просто смотреть на
# зверьё» — 3 общих (red, dead, прост), своими словами, не совпадение.

СЛУЖЕБНЫЕ_ЦИТАТ = {"что", "это", "уже", "так", "там", "тут", "или", "для", "его", "она", "они", "вот",
                   "все", "всё", "ещё", "еще", "нас", "вас", "мне", "меня", "тоже", "когда", "чтобы",
                   "если", "был", "была", "было", "были", "который", "котор", "этот", "эта", "эти"}
МНЕНИЕ = re.compile(r"\b(?:думаю|кажется|наверн\w*|может(?:\s+быть)?|предполага\w*|подозрева\w*|"
                    r"скорее\s+всего|похоже|надеюсь|не\s+удивлюсь|вангую|представ\w*|по-моему|"
                    r"мне\s+кажется|хочется\s+верить|ставлю\s+на\s+то|уверен|жду)\b", re.I)


def цитаты_стиля(стиль: str) -> list[str]:
    """Цитаты блока «Как я говорю»: строки «- «…»» после заголовка, до
    пустой строки либо следующего раздела."""
    i = (стиль or "").find("Как я говорю")
    if i < 0:
        return []
    итог = []
    for строка in стиль[i:].splitlines()[1:]:
        с = строка.strip()
        if not с:
            if итог:
                break
            continue
        м = re.match(r"^[-—•]\s*«(.+)»\s*\.?$", с)
        if not м:
            if итог:
                break
            continue
        итог.append(м.group(1))
    return итог


def _основы_цитаты(текст: str) -> set[str]:
    return {с[:5] for с in re.findall(r"[a-zа-яё]{3,}", (текст or "").lower().replace("ё", "е"))
            if с not in СЛУЖЕБНЫЕ_ЦИТАТ}


def цитата_в(текст: str, цитаты: list[str]) -> int | None:
    """Номер цитаты, которую строка повторяет почти дословно, иначе None."""
    о = _основы_цитаты(текст)
    if len(о) < 3:
        return None
    for i, ц in enumerate(цитаты):
        for пред in re.split(r"(?<=[.!?…])\s+", ц):
            оп = _основы_цитаты(пред)
            общие = о & оп
            if len(общие) >= 4 and (len(общие) >= 0.6 * len(о) or len(общие) >= 0.6 * len(оп)):
                return i
    return None


def строки_с_хуком(данные: dict) -> list[tuple[str, dict]]:
    хук = данные.get("hook") if isinstance(данные.get("hook"), dict) else None
    return ([("H", хук)] if хук and хук.get("text") else []) + list(строки_сценария(данные.get("script") or []).items())


def цитаты_пакета(данные: dict, цитаты: list[str]) -> list[int]:
    return sorted({ц for _, л in строки_с_хуком(данные) if (ц := цитата_в(л.get("text", ""), цитаты)) is not None})


def цитаты_прошлого_пакета(db, номер: int, цитаты: list[str]) -> set[int]:
    """Цитаты образца, на которые опирался последний собранный пакет (кроме
    этого же): повторять их второй пакет подряд нельзя."""
    if db is None or not цитаты:
        return set()
    п = (db.query(ContentPackage).filter(ContentPackage.state == "ok", ContentPackage.id != номер)
         .order_by(ContentPackage.finished_at.desc().nullslast(), ContentPackage.id.desc()).first())

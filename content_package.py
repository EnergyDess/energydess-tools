def слабые_основы(к: dict) -> set[str]:
    """Основы утверждений, у которых источник — ТОЛЬКО пересказ на YouTube
    (письмо B3, 1.2), за вычетом всего, что есть в официальных фактах
    и источниках: «питомец» у бразильского блогера — слабое, «170 видов»
    у IGN — нет. На таком название и превью не строятся."""
    по_id = {и["id"]: и for и in к.get("источники") or []}
    факты = (к.get("материал") or {}).get("list") or []
    сильное = set()
    for ф in факты:
        if ф.get("status") == СТАТУС_ОФИЦ:
            сильное |= основы_смысла(ф["text"])
    for и in по_id.values():
        if и.get("status") == СТАТУС_ОФИЦ:
            сильное |= основы_смысла(и["title"] + " " + (и.get("text") or ""))
    слабое, прочее = set(), set()
    for ф in факты:
        if ф["src"] and all(по_id.get(n, {}).get("platform") == "youtube" for n in ф["src"]):
            слабое |= основы_смысла(ф["text"])
        else:
            прочее |= основы_смысла(ф["text"])
    # Слова названия идеи, которых нет ни в одном факте источников («питомцы»
    # у идеи №70 — только в названии бразильского ролика): на них тоже нельзя
    if факты:
        идея = (к.get("idea") or {}).get("title") or ""
        # Рамка темы («трейлер», «разбор», «сравнение») — не утверждение
        слабое |= основы_смысла(ПО_СЛУХАМ.sub("", идея)) - сильное - прочее - ОБЩИЕ_ОСНОВЫ - РАМКА_ИДЕИ
    return слабое - сильное - прочее - ОБЩИЕ_СЛОВА



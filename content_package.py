def официальный_факт_строки(текст: str, src: list, факты: list[dict], по_id: dict) -> list[int]:
    """Строка сценария сослалась только на ролик, а факт, который она
    пересказывает, уже официальный (сверка выше): ссылка на официальную
    запись факта переходит в строку. Совпадение — общий источник и не меньше
    двух общих основ смысла (язык один — русский)."""
    основы_строки = основы_смысла(текст, 4)
    for ф in факты or []:
        if ф.get("status") != СТАТУС_ОФИЦ or not set(src) & set(ф.get("src") or []):
            continue
        if len(основы_строки & основы_смысла(ф["text"], 4)) >= 2:
            return [n for n in ф["src"] if n in по_id and n not in src
                    and (по_id[n].get("status") or (СТАТУС_ОФИЦ if по_id[n].get("official") else "")) == СТАТУС_ОФИЦ]
    return []



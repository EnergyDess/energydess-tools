async def текст_превью(клиент, к: dict, превью: dict) -> None:
    """Текст превью — до `thumb_words` слов. Длиннее — модель ПЕРЕПИСЫВАЕТ
    (до `rewrite_tries` раз); код не обрезает: «GTA 5 vs GTA» — обрубок,
    а не текст. Не уложилась — текст остаётся и помечен для чек-листа."""
    предел = int(к["настройки"].get("thumb_words", 4))
    слабое = слабые_основы(к)
    официально = bool(к["idea"].get("official"))

    def беда(текст):
        б = []
        if слов_превью(текст) > предел:
            б.append(f"длиннее {предел} слов — перепиши в {предел} слова или короче цельной фразой, не обрубком")
        if слабое_в(текст, слабое):
            б.append("стоит на утверждении только из ролика YouTube — построй на официальном факте")
        if официально and ОБОРОТ_СЛУХА.search(текст):
            б.append("основа официальная — без слуха")
        return б
    for _ in range(int(к["настройки"].get("rewrite_tries", 2))):
        текст = str(превью.get("text") or "").strip()
        if not беда(текст):
            превью.pop("too_long", None)
            return
        try:
            новый = await _модель(клиент, _система(к),
                                  f"Текст на превью «{текст}»: {'; '.join(беда(текст))}. Ролик: «{к['idea']['title']}». "
                                  'Ответ JSON: {"text": "текст превью"}', PACKAGE_SMALL_TOKENS)
        except Беда:
            break
        if str(новый.get("text") or "").strip():
            превью["text"] = str(новый["text"]).strip()
    превью["too_long"] = слов_превью(str(превью.get("text") or "")) > предел
    if беда(str(превью.get("text") or "")) and not превью["too_long"]:
        превью["weak"] = True


def слов_превью(текст: str) -> int:
    """Слова текста превью; число отдельным словом не считается — «GTA 6»
    это одно имя (пруф 2026-10-01: «GTA 5 против GTA 6» считалось 5 словами)."""
    return sum(1 for с in (текст or "").split() if not re.fullmatch(r"[\d.,:%+×x-]+", с))


def _таймкод(т) -> float | None:
    м = re.fullmatch(r"\s*(\d+):(\d{1,2})\s*", str(т or ""))
    return int(м.group(1)) * 60 + int(м.group(2)) if м else None


def проверить_сценарий(сегменты: list, источники: list[dict], к: dict) -> list[dict]:
    """Каждая фраза-факт — к записи источника. Нет привязки — «проверь»."""
    по_id = {и["id"]: и for и in источники}
    запрет = [с.lower() for с in к["формулировки"].get("forbidden_when_rumor") or []]
    итог = []
    for с in сегменты:
        if not isinstance(с, dict):
            continue
        строки = []
        for л in с.get("lines") or []:
            if isinstance(л, str):
                л = {"text": л, "fact": False, "src": []}
            if not isinstance(л, dict) or not str(л.get("text") or "").strip():
                continue
            src = [n for n in (л.get("src") or []) if isinstance(n, int) and n in по_id]
            факт = bool(л.get("fact")) or bool(л.get("src"))
            if src and статус_по(src, по_id, к["формулировки"], str(л["text"])) != СТАТУС_ОФИЦ:
                # Факт уже официальный по сверке (письмо B4, 1.3) — его ссылка в строку
                src = src + официальный_факт_строки(str(л["text"]), src,
                                                    (к.get("материал") or {}).get("list") or [], по_id)
            проверь = None
            if личная(str(л["text"])):
                # Личная фраза ведущего — без ссылки (письмо B3, 1.4)
                строки.append({"text": str(л["text"]).strip(), "fact": False, "src": [], "check": None,
                               "personal": True})
                continue
            if факт and not src:
                проверь = "нет источника"
            elif факт:
                # Опора для «официально» — официальный источник ЛИБО доверенное СМИ
                # из `wording` (правило A2): «Rockstar Confirms…» у IGN не слух.
                свои = set(к["формулировки"].get("official_sources") or []) | set(
                    к["формулировки"].get("trusted_media") or [])
                офиц = any((по_id[n]["official"] or по_id[n]["source"] in свои) and not по_id[n]["rumor"]
                           for n in src) or пересказ_официального(str(л["text"]), src, по_id, к["формулировки"]) is not None
                низ = str(л["text"]).lower()
                if not офиц and any(з in низ for з in запрет):
                    проверь = "слух подан как подтверждённый"
                elif all(по_id[n]["rumor"] or по_id[n]["leak"] for n in src) and not СЛУХ_ЯВНО.search(л["text"]):
                    проверь = "источник — слух: скажи, что это слух"
            сми = пересказ_официального(str(л["text"]), src, по_id, к["формулировки"])
            if сми and сми not in src:
                src = src + [сми]
            строки.append({"text": str(л["text"]).strip(), "fact": факт, "src": src, "check": проверь,
                           "status": статус_по(src, по_id, к["формулировки"], str(л["text"]))})
        итог.append({"from": str(с.get("from") or ""), "to": str(с.get("to") or ""),
                     "role": str(с.get("role") or ""), "purpose": str(с.get("purpose") or ""),
                     "lines": строки})
    return итог



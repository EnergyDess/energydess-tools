# -*- coding: utf-8 -*-
"""ПРОБА: ОТДЕЛИТЬ ПЕРСОНАЖА ОТ ФОНА У СОБСТВЕННЫХ СНИМКОВ ЭКРАНА.

НЕ ПРОВЕРКА и не часть выкатки — ПРОБА. Кода «правильно» у неё нет:
хорошо получилось или плохо, решает глаз владельца, а решение по
остальным картинкам принимает он же.

ЧТО ЗА ЗАДАЧА. Из 90 картинок каталога 66 пришли с вики и несут
настоящий альфа-канал (замер: `A.getextrema()[0] < 250`), а 24 — снимки
экрана из игры, с полом, стеной и всем, что было в кадре. В ряду
карточек они выделяются подложкой.

ПОЧЕМУ КЛАССИЧЕСКИЙ АЛГОРИТМ, А НЕ СЕТЬ. На машине есть PIL, numpy
и onnxruntime; НЕТ cv2, rembg, scipy и skimage. Сеть (u2net, isnet)
дала бы результат заметно лучше, но весит она около 180 МБ, тянется
из сети и в публичный репозиторий ей нельзя. Проба должна отвечать
на вопрос «стоит ли этим заниматься» тем, что есть.

СПОСОБ: ЗАЛИВКА ОТ КРАЁВ СО СВЯЗНОСТЬЮ.

  1. цвет фона берётся МЕДИАНОЙ рамки в 6px по всем четырём сторонам —
     медиана, а не среднее: одна яркая деталь у края не утащит оценку;
  2. маска «похоже на фон» — по расстоянию в RGB с допуском;
  3. из неё оставляется только то, что СВЯЗНО с краем кадра. Это
     и есть главное: серый доспех похож на серый фон по цвету, но
     до края кадра не дотягивается, и заливка его не съедает;
  4. край смягчается размытием альфы — иначе по контуру идёт лесенка
     и ореол цвета фона.

ЧТО СПОСОБ НЕ УМЕЕТ И НЕ БУДЕТ. Волосы, дым, полупрозрачные ткани,
и — главное — фон, который К ПЕРСОНАЖУ ПРИМЫКАЕТ ПО ЦВЕТУ: там связная
область перетекает в фигуру, и вырезается кусок персонажа. Ровно этот
случай и взят вторым образцом пробы, чтобы владелец видел ОБА исхода.

ИСХОДНИКИ НЕ ТРОГАЮТСЯ. Результат кладётся в отдельный каталог,
по умолчанию `C:/Temp/.../cutout`; исходный файл не открывается
на запись ни разу.

    py enshrouded_cutout.py --куда <каталог> sp_rose ht_sharp
    py enshrouded_cutout.py --куда <каталог> --список   # что вообще без альфы
"""
import os
import sqlite3
import sys
import time

sys.stdout.reconfigure(encoding="utf-8")
КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, КОРЕНЬ)

import numpy as np                                   # noqa: E402
from PIL import Image, ImageFilter                    # noqa: E402

БД = os.environ.get("DB_PATH") or os.path.join(КОРЕНЬ, "app.db")
РАМКА = 6           # ширина полосы у края, по которой оценивается фон
ДОПУСК = 46         # расстояние в RGB (сумма модулей), при котором «это фон»
СМЯГЧЕНИЕ = 1.4     # радиус размытия альфы, px
ПОДЖАТЬ = 1         # на столько пикселей ужать фигуру — снять ореол фона


def _путь(sid, ext):
    """Тем же правилом, что у сервера: том сильнее семени."""
    for кат in (os.path.join(КОРЕНЬ, "enshrouded"),
                os.path.join(КОРЕНЬ, "static", "enshrouded")):
        п = os.path.join(кат, f"{sid}.{ext}")
        if os.path.exists(п):
            return п
    return None


def _без_альфы():
    """Картинки БЕЗ настоящей прозрачности — кандидаты на отделение фона.

    Спрашивается не режим файла, а ЗНАЧЕНИЯ: PNG бывает RGBA с альфой,
    залитой единицами, и режим о прозрачности не говорит ничего.
    """
    c = sqlite3.connect(f"file:{БД}?mode=ro", uri=True)
    try:
        строки = c.execute("SELECT id, name_ru, img_ext FROM enshrouded_sets"
                           " ORDER BY id").fetchall()
    finally:
        c.close()
    из = []
    for sid, имя, ext in строки:
        п = _путь(sid, ext)
        if not п:
            continue
        im = Image.open(п)
        альфа = im.convert("RGBA").getchannel("A")
        if альфа.getextrema()[0] >= 250:
            из.append((sid, имя, п, im.size))
    return из


def _разлить(семя, можно, ось):
    """Пустить семя вдоль ОСИ внутри непрерывных участков `можно`.

    Один проход накрывает участок ЦЕЛИКОМ, а не сдвигает границу
    на пиксель: обычная итеративная дилатация на кадре 900x994 сходилась
    бы сотнями проходов. Здесь два `maximum.accumulate` на направление —
    вперёд и назад, — и заливка добегает до конца участка сразу.
    """
    s = np.moveaxis(семя, ось, 0)
    m = np.moveaxis(можно, ось, 0)
    n = s.shape[0]
    i = np.arange(n)[:, None]
    из = np.zeros_like(s)
    for назад in (False, True):
        sv, mv = (s[::-1], m[::-1]) if назад else (s, m)
        # позиция последней ПРЕГРАДЫ (не-`можно`) и последнего семени
        преграда = np.maximum.accumulate(np.where(mv, -1, i), axis=0)
        последнее = np.maximum.accumulate(np.where(sv, i, -1), axis=0)
        шаг = mv & (последнее > преграда)
        из |= шаг[::-1] if назад else шаг
    return np.moveaxis(из, 0, ось)


def отделить(путь, допуск=ДОПУСК):
    """(изображение RGBA, отчёт). Исходник открывается только на чтение."""
    начало = time.perf_counter()
    im = Image.open(путь).convert("RGB")
    a = np.asarray(im, dtype=np.int16)
    в, ш = a.shape[:2]

    рамка = np.concatenate([a[:РАМКА].reshape(-1, 3), a[-РАМКА:].reshape(-1, 3),
                            a[:, :РАМКА].reshape(-1, 3), a[:, -РАМКА:].reshape(-1, 3)])
    фон = np.median(рамка, axis=0)
    разброс = float(np.median(np.abs(рамка - фон).sum(axis=1)))

    похоже = np.abs(a - фон).sum(axis=2) < допуск

    # СЕМЯ — только пиксели НА КРАЮ кадра, похожие на фон. Отсюда
    # и берётся связность: область, не касающаяся края, фоном
    # не объявляется, чем бы она ни была покрашена.
    семя = np.zeros((в, ш), dtype=bool)
    семя[0], семя[-1], семя[:, 0], семя[:, -1] = (похоже[0], похоже[-1],
                                                   похоже[:, 0], похоже[:, -1])
    проходов = 0
    while True:
        новое = семя | _разлить(семя, похоже, 0) | _разлить(семя, похоже, 1)
        проходов += 1
        if новое.sum() == семя.sum() or проходов > 60:
            семя = новое
            break
        семя = новое

    альфа = np.where(семя, 0, 255).astype(np.uint8)
    доля_фона = float(семя.mean())

    сл = Image.fromarray(альфа, "L")
    if ПОДЖАТЬ:
        # Ужать фигуру: по контуру остаётся полоса пикселей, смешанных
        # с фоном, и без поджатия она читается ореолом на любой подложке.
        сл = сл.filter(ImageFilter.MinFilter(1 + 2 * ПОДЖАТЬ))
    сл = сл.filter(ImageFilter.GaussianBlur(СМЯГЧЕНИЕ))

    итог = im.convert("RGBA")
    итог.putalpha(сл)
    отчёт = {"фон": tuple(int(x) for x in фон), "разброс_рамки": round(разброс, 1),
             "доля_убрана": round(доля_фона, 3), "проходов": проходов,
             "размер": im.size, "секунд": round(time.perf_counter() - начало, 2)}
    return итог, отчёт


def в_клетку(im, клетка=16):
    """Положить результат на шахматку — иначе прозрачность не видно."""
    ш, в = im.size
    ф = Image.new("RGB", (ш, в), (235, 235, 235))
    т = Image.new("RGB", (клетка, клетка), (200, 200, 200))
    for y in range(0, в, клетка):
        for x in range(0, ш, клетка):
            if (x // клетка + y // клетка) % 2:
                ф.paste(т, (x, y))
    ф.paste(im, (0, 0), im)
    return ф


def главная(арг):
    куда = None
    if "--куда" in арг:
        куда = арг[арг.index("--куда") + 1]
        арг = [a for i, a in enumerate(арг)
               if i not in (арг.index("--куда"), арг.index("--куда") + 1)]
    if "--оценка" in арг:
        # ЧЕГО ЖДАТЬ НА ОСТАЛЬНЫХ — прогон алгоритма по ВСЕМ картинкам
        # без прозрачности, БЕЗ записи файлов. Признак исхода — сколько
        # площади ушло: у снимка в полный рост фон занимает больше
        # половины кадра, и «убрано 3%» означает, что заливка увязла.
        сп = _без_альфы()
        print("=" * 88)
        print("ОЦЕНКА ПО ВСЕМ СНИМКАМ БЕЗ ПРОЗРАЧНОСТИ — файлы не пишутся")
        print("=" * 88)
        print(f"  {'id':13}{'разброс':>8}{'убрано':>9}{'сек':>7}  исход")
        всего_сек, хорошо, средне, плохо = 0.0, 0, 0, 0
        for sid, имя, п, размер in сп:
            _, о = отделить(п)
            всего_сек += о["секунд"]
            д = о["доля_убрана"]
            if д >= 0.40:
                исход, х = "годится", "хорошо"; хорошо += 1
            elif д >= 0.20:
                исход, х = "наполовину — смотреть глазами", "средне"; средне += 1
            else:
                исход, х = "НЕ СРАБОТАЛО — фон остался", "плохо"; плохо += 1
            print(f"  {sid:13}{о['разброс_рамки']:8.0f}{д * 100:8.1f}%"
                  f"{о['секунд']:7.2f}  {исход}")
        print("")
        print(f"  годится {хорошо}, наполовину {средне}, не сработало {плохо}"
              f" — из {len(сп)}")
        print(f"  всё вместе заняло {всего_сек:.1f} с")
        return 0

    if "--список" in арг:
        сп = _без_альфы()
        print(f"КАРТИНОК БЕЗ НАСТОЯЩЕЙ ПРОЗРАЧНОСТИ: {len(сп)} из 90")
        for sid, имя, п, размер in сп:
            print(f"  {sid:12} {имя:26} {размер[0]}x{размер[1]}  {п}")
        return 0

    цели = [a for a in арг if not a.startswith("--")]
    if not цели or not куда:
        print(__doc__)
        return 2
    os.makedirs(куда, exist_ok=True)

    c = sqlite3.connect(f"file:{БД}?mode=ro", uri=True)
    print("=" * 88)
    print("ПРОБА ОТДЕЛЕНИЯ ФОНА — исходники не изменяются")
    print("=" * 88)
    for sid in цели:
        строка = c.execute("SELECT name_ru, img_ext FROM enshrouded_sets"
                           " WHERE id = ?", (sid,)).fetchone()
        if not строка:
            print(f"  {sid}: такого сета в каталоге нет")
            continue
        имя, ext = строка
        п = _путь(sid, ext)
        итог, отчёт = отделить(п)
        было = os.path.getsize(п)
        исход = os.path.join(куда, f"{sid}-исходник.png")
        Image.open(п).convert("RGB").save(исход)
        готово = os.path.join(куда, f"{sid}-результат.png")
        итог.save(готово)
        клетка = os.path.join(куда, f"{sid}-в-клетку.png")
        в_клетку(итог).save(клетка)
        стало = os.path.getsize(готово)
        print(f"\n  {sid} «{имя}»")
        print(f"     фон {отчёт['фон']}, разброс рамки {отчёт['разброс_рамки']},"
              f" проходов заливки {отчёт['проходов']}")
        print(f"     убрано {отчёт['доля_убрана'] * 100:.1f}% площади,"
              f" {отчёт['секунд']} с")
        print(f"     вес {было // 1024} КБ (jpg) -> {стало // 1024} КБ (png"
              f" с альфой)")
        print(f"     {готово}")
    c.close()
    return 0


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))

# -*- coding: utf-8 -*-
"""УСТРОЙСТВО РАЗДЕЛА ENSHROUDED: категории ремесленников и виды слотов.

ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ, А НЕ В `main.py`. Потребителей у этих двух
величин ТРИ, и у каждого своё условие запуска:

  · `main.py` — отдаёт их обоим шаблонам (раздел и экран управления);
  · `templates/enshrouded.html` — рисует ими карточки и вкладки;
  · `check_enshrouded.py` — проверка 24, и она стоит в ряду §6.0.2,
    то есть ОБЯЗАНА читаться без поднятого приложения. Импорт `main`
    потянул бы FastAPI, модели и всё окружение.

Модуль поэтому пустой: ни одного импорта, только данные.

ПОЧЕМУ РУССКИЕ НАЗВАНИЯ ЖИВУТ ЗДЕСЬ, А НЕ В КАЖДОМ ШАБЛОНЕ. До
2026-08-23 они были ТОЛЬКО в JS-литерале `templates/enshrouded.html`,
а экран управления показывал внутренние имена — `blacksmith`, `head` —
и в таблице, и в отборе, и в форме. Завести второй список рядом значило
бы получить два перечня, расходящихся молча: пятая категория,
дописанная в один, не появилась бы во втором, и отказа при этом
не было бы никакого (§6.0.7).

ПЕРЕЕЗЖАТЬ В БАЗУ ИМ НЕ НАДО, и это записанное решение (§5.7): пять
ремесленников и пять мест доспеха — не содержимое, а устройство игры.
Строка в базе, которую нечем изменить, хуже константы: она обещает
изменяемость, которой нет.
"""

# Порядок ЗНАЧИМ: в нём категории идут на экране раздела сверху вниз.
# `ico` — имя значка Lucide, а не эмодзи (design-system.md §8).
КАТЕГОРИИ = {
    "blacksmith": {"name": "Кузнец",         "sub": "Крафт",             "ico": "hammer"},
    "huntress":   {"name": "Охотница",       "sub": "Крафт",             "ico": "target"},
    "alchemist":  {"name": "Алхимик",        "sub": "Крафт",             "ico": "flask-conical"},
    "world":      {"name": "Найдено в мире", "sub": "Находка",           "ico": "map"},
    "special":    {"name": "Спецпредметы",   "sub": "События / Магазин", "ico": "sparkles"},
}

# Порядок ЗНАЧИМ: в нём слоты идут в ряду на карточке — сверху вниз
# по фигуре, от шлема к ботинкам.
СЛОТЫ = [
    {"id": "head",   "label": "Шлем"},
    {"id": "chest",  "label": "Нагрудник"},
    {"id": "gloves", "label": "Перчатки"},
    {"id": "legs",   "label": "Поножи"},
    {"id": "feet",   "label": "Ботинки"},
]

# Короткое название категории для таблицы и отбора: там колонка узкая,
# и «Найдено в мире» её распирает. Своим полем, а не обрезкой строки:
# обрезка дала бы «Найдено в м…», то есть неправду вместо краткости.
КОРОТКО = {"blacksmith": "Кузнец", "huntress": "Охотница",
           "alchemist": "Алхимик", "world": "Мир", "special": "Спецпредметы"}

ИДЕНТИФИКАТОРЫ_КАТЕГОРИЙ = list(КАТЕГОРИИ)
ИДЕНТИФИКАТОРЫ_СЛОТОВ = [с["id"] for с in СЛОТЫ]
ПОДПИСЬ_СЛОТА = {с["id"]: с["label"] for с in СЛОТЫ}


def словами(ids):
    """Состав сета словами по-русски: ['head','chest'] → 'Шлем, Нагрудник'.

    Незнакомый слот показывается КАК ЕСТЬ, а не пропускается: слот,
    выпавший из показа молча, — ровно та дыра, которую ищет проверка 24
    (вид СОСТАВ). Пропуск сделал бы её находку невидимой на экране.
    """
    return ", ".join(ПОДПИСЬ_СЛОТА.get(i, i) for i in ids)

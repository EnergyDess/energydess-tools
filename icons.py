# -*- coding: utf-8 -*-
"""ЗНАЧОК В РАЗМЕТКЕ, А НЕ ПОСЛЕ ЗАГРУЗКИ ЧУЖОГО СКРИПТА.

Читает `static/icons.js` — тот же файл, из которого значки берёт браузер, —
и отдаёт шаблонам глобал `значок('users')`, подставляющий готовый <svg>
прямо в разметку.

ПОЧЕМУ ЧИТАЕТСЯ JS-ФАЙЛ, А НЕ ЗАВЕДЁН СВОЙ СЛОВАРЬ. Стороны две: сервер
рисует значки, стоящие в разметке, браузер — те, что собирает скрипт уже
после загрузки. Два списка одних и тех же данных разошлись бы молча —
ровно то, что §6.0.7 разбирает на `names` и на копии `pages`. Поэтому
источник ОДИН, и он на диске: `static/icons.js`, собираемый
`build_icons.py`. Здесь только разбор.

ОТСУТСТВУЮЩЕЕ ИМЯ НЕ МОЛЧИТ. Значок, которого нет в наборе, — это пустое
место на экране, неотличимое от «так задумано». `значок()` в таком случае
поднимает исключение при рендере: страница падает громко, а не рисуется
наполовину.
"""
import io
import json
import os
import re

from markupsafe import Markup

_ФАЙЛ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "static", "icons.js")

# Разметка повторяет ту, что рисовал `lucide.createIcons()`, до атрибута:
# под класс `lucide lucide-<имя>` и под сам `data-lucide` в проекте
# написаны стили и проверки, и менять их заодно со способом отрисовки
# значило бы смешать две правки в одну.
_ШАБЛОН = ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
           'viewBox="0 0 24 24" fill="none" stroke="currentColor" '
           'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
           'data-lucide="{имя}" aria-hidden="true" '
           'class="lucide lucide-{имя}{доп}"{атрибуты}>{тело}</svg>')

_НАБОР = None


def набор():
    """Имя → внутренняя разметка <svg>. Читается один раз."""
    global _НАБОР
    if _НАБОР is None:
        текст = io.open(_ФАЙЛ, encoding="utf-8").read()
        м = re.search(r"window\.LUCIDE_ICONS\s*=\s*(\{.*?\});\s*\n", текст,
                      re.S)
        if not м:
            raise RuntimeError(
                "static/icons.js не содержит window.LUCIDE_ICONS — "
                "соберите его: py build_icons.py")
        _НАБОР = json.loads(м.group(1))
    return _НАБОР


def значок(имя, cls="", **атрибуты):
    """Готовый <svg> для шаблона. Незнакомое имя — исключение, не пустота.

    Лишние атрибуты передаются как есть (`значок('info', id='scale-result-icon')`):
    за `id` и `aria-label` цепляется чужой код, и молча потерять их значит
    получить элемент, который на экране тот же, а найти его уже нельзя.
    Подчёркивание в имени переводится в дефис — `aria_label` в Jinja
    записать можно, `aria-label` нет.
    """
    н = набор()
    тело = н.get(имя)
    if тело is None:
        raise KeyError(
            "значка «%s» нет в наборе (%d имён). Впишите его в build_icons.py "
            "и пересоберите static/icons.js — иначе на экране будет пустое "
            "место без единой ошибки." % (имя, len(н)))
    лишние = "".join(' %s="%s"' % (к.replace("_", "-"), v)
                     for к, v in атрибуты.items() if v is not None)
    return Markup(_ШАБЛОН.format(имя=имя, тело=тело, атрибуты=лишние,
                                 доп=(" " + cls) if cls else ""))

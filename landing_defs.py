# ── СЕКЦИИ ── порядок = порядок показа в панели и на странице ─────────
СЕКЦИИ = [
    ("feed", "Лента"),
    ("projects", "Проекты"),
    ("portrait", "Портрет"),
    ("decor", "Декор"),
]

# ── РОДЫ СОДЕРЖИМОГО ──────────────────────────────────────────────────
ВИДЕО = "video"
КАРТИНКА = "image"


def _лента():
    места = []
    for ряд in (1, 2):
        for н in range(1, 7):
            места.append({
                "id": "feed-%d-%d" % (ряд, н), "section": "feed",
                "kind": ВИДЕО, "ratio": "16 / 9", "fit": "cover",
                "alpha": False,
                "label": "Лента · ряд %d · место %d" % (ряд, н),
            })
    return места


def _проекты():
    # В карточке проекта ТРИ картинки: две стоят столбцом слева, одна
    # высокая справа на всю высоту карточки. Высокой дано 3:4 — сумма
    # двух 4:3 плюс зазор это ~2:3, а соотношение уточнит раскладка
    # лендинга; место с `object-fit: cover` переживёт любое.
    места = []
    for к in (1, 2, 3):
        for буква, где, соотн in (("a", "слева сверху", "4 / 3"),
                                  ("b", "слева снизу", "4 / 3"),
                                  ("c", "справа, высокая", "3 / 4")):
            места.append({
                "id": "project-%d-%s" % (к, буква), "section": "projects",
                "kind": КАРТИНКА, "ratio": соотн, "fit": "cover",
                "alpha": False,
                "label": "Проект %d · %s" % (к, где),
            })
    return места


def _портрет():
    # ПОРТРЕТ С ПРОЗРАЧНЫМ ФОНОМ, 1:1 (заход 339, блок A3, решение
    # владельца). Здесь стояло 4:5 и `cover`: портрет налезает на имя
    # снизу, и имя обязано проступать сквозь прозрачные части — поэтому
    # `contain` и признак прозрачности, как у декора: объект не обрезается,
    # подложки у заполненного места нет.
    return [{"id": "portrait", "section": "portrait", "kind": КАРТИНКА,
             "ratio": "1 / 1", "fit": "contain", "alpha": True,
             "label": "Портрет в первом экране"}]


def _декор():
    # ДЕКОРАТИВНЫЕ ОБЪЕКТЫ ЛЕЖАТ НА ПОЧТИ ЧЁРНОМ ФОНЕ, и прозрачность
    # у них обязательна: потерянная даст чёрный прямоугольник вокруг
    # объекта. Отсюда `alpha` и `contain` — объект не обрезается.
    return [{"id": "decor-%s" % к, "section": "decor", "kind": КАРТИНКА,
             "ratio": "1 / 1", "fit": "contain", "alpha": True,
             "label": "«О себе» · %s" % где}
            for к, где in (("tl", "левый верх"), ("bl", "левый низ"),
                           ("tr", "правый верх"), ("br", "правый низ"))]


МЕСТА = _лента() + _проекты() + _портрет() + _декор()
ПО_ID = {м["id"]: м for м in МЕСТА}


def места_секции(секция):
    return [м for м in МЕСТА if м["section"] == секция]



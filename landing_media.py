class ОтказЗагрузки(Exception):
    """Файл не принят. Текст — для человека, с числом там, где оно есть.

    `журнал` — ТЕХНИЧЕСКИЙ текст для журнала сервера: вывод ffmpeg, имя
    исключения. Человеку он не показывается (задача 330): «Conversion
    failed!» не говорит ни что случилось, ни что делать. Но и выбросить
    его нельзя — без него разбирать отказ нечем."""

    def __init__(self, текст, код=400, журнал=None):
        super().__init__(текст)
        self.текст = текст
        self.код = код
        self.журнал = журнал


def ffmpeg():
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


# Демультиплексоры, которыми ffmpeg открывает НЕПОДВИЖНУЮ картинку.
# Признак — «картинка», а не перечень расширений: `_pipe`-демультиплексоры
# у ffmpeg заведены ровно под одиночные изображения.
_ДЕМУКС_КАРТИНКИ = re.compile(r"(^|,)(image2|[a-z0-9]+_pipe|gif|apng)(,|$)")


def разобрать_ролик(путь):
    """{'format', 'duration', 'width', 'height'} по выводу `ffmpeg -i`.

    ffprobe в колесе нет, поэтому читается ЗАГОЛОВОК, который ffmpeg
    печатает при открытии файла; сам поток при этом не декодируется —
    это миллисекунды, а не прогон всего ролика."""
    п = subprocess.run([ffmpeg(), "-hide_banner", "-nostdin", "-i", путь],
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=60)
    вывод = п.stderr
    итог = {"format": None, "duration": None, "width": None, "height": None,
            "codec": None, "pix_fmt": None, "fps": None,
            "audio": bool(re.search(r"Stream #0:\d+[^\n]*: Audio:", вывод))}
    м = re.search(r"Input #0, ([^ ]+), from", вывод)
    if м:
        итог["format"] = м.group(1).rstrip(",")
    м = re.search(r"Duration: (\d+):(\d+):(\d+(?:\.\d+)?)", вывод)
    if м:
        итог["duration"] = (int(м.group(1)) * 3600 + int(м.group(2)) * 60
                            + float(м.group(3)))
    # Первая строка видеопотока. Размер — первая пара «ЧИСЛОxЧИСЛО» после
    # слова Video, не шестнадцатеричный код вида 0x31637661.
    м = re.search(r"Stream #0:\d+[^\n]*?: Video: [^\n]*?(\d{2,5})x(\d{2,5})", вывод)
    if м:
        итог["width"], итог["height"] = int(м.group(1)), int(м.group(2))
    строка = re.search(r"Stream #0:\d+[^\n]*?: Video: ([^\n]*)", вывод)
    if строка:
        видео = строка.group(1)
        м = re.match(r"(\w+)", видео)
        итог["codec"] = м.group(1) if м else None
        # Формат пикселей — первое слово после кодека, стоящее в списке через
        # запятую верхнего уровня: «h264 (High) (avc1 / …), yuv420p(tv, …), 640x360».
        глубина, кусок, куски = 0, "", []
        for з in видео:
            if з == "(":
                глубина += 1
            elif з == ")":
                глубина -= 1
            if з == "," and глубина == 0:
                куски.append(кусок.strip())
                кусок = ""
            else:
                кусок += з
        куски.append(кусок.strip())
        if len(куски) > 1:
            м = re.match(r"(\w+)", куски[1])
            итог["pix_fmt"] = м.group(1) if м else None
        м = re.search(r"(\d+(?:\.\d+)?) fps", видео)
        итог["fps"] = float(м.group(1)) if м else None
    return итог


def _это_ролик(разбор):
    return (разбор["width"] is not None and разбор["format"] is not None
            and not _ДЕМУКС_КАРТИНКИ.search(разбор["format"])
            and (разбор["duration"] or 0) >= 0.3)


def _это_картинка(путь):
    try:
        with Image.open(путь) as im:
            im.verify()
        return True
    except (UnidentifiedImageError, OSError, ValueError, SyntaxError):
        return False
    except Image.DecompressionBombError as e:
        # БОМБА — КАРТИНКА, И ОТКАЗ НАЗЫВАЕТ ПРИЧИНУ. Прежде исключение
        # уходило из признака необработанным, и панель получала 500
        # без единого слова (замер 2026-09-13, PNG 30000 на 30000)
        raise ОтказЗагрузки("Картинка слишком большая по числу точек — уменьшите "
                            "её (до нескольких тысяч по стороне) и загрузите снова",
                            413, журнал="%s: %s" % (type(e).__name__, e))


def _версия(путь):
    h = hashlib.sha256()
    with open(путь, "rb") as f:
        for кус in iter(lambda: f.read(1 << 20), b""):
            h.update(кус)
    return h.hexdigest()[:8]


def _мб(n):
    return n / 1024 / 1024


def _пик_памяти(pid, стоп, итог):
    """Пик резидентной памяти процесса ffmpeg по /proc (только Linux).

    Меряется, а не предполагается: машина прода — 512 МБ на всё,
    и приложение занимает из них больше сотни (§5.8)."""
    файл = "/proc/%d/status" % pid
    while not стоп.is_set():
        try:
            with open(файл) as f:
                for строка in f:
                    if строка.startswith("VmHWM:"):
                        итог[0] = max(итог[0], int(строка.split()[1]) // 1024)
        except OSError:
            return
        time.sleep(0.1)


# ПРИЧИНА СБОЯ ffmpeg — ПО ВЫВОДУ И КОДУ, А НЕ ПОСЛЕДНЕЙ СТРОКОЙ (задача 330).
#
# Нехватка памяти бывает двух видов, и оба замерены:
#   · Linux, прод: ядро убивает процесс — код −9 (SIGKILL), в выводе нет
#     ни слова о памяти, последней стоит строка прогресса «frame= 102 …»;
#   · аллокация не удалась внутри ffmpeg (Windows-стенд под потолком
#     Job Object): «malloc of size 3060037 failed», «get_buffer() failed»,
#     затем «Invalid data found» и «Conversion failed!».
# Признаки памяти спрашиваются ПЕРВЫМИ: при нехватке ffmpeg печатает
# и «Invalid data found», и назвать это повреждённым файлом значило бы
# соврать ровно в том случае, ради которого разбор заведён.
_ПАМЯТЬ = re.compile(r"malloc of size \d+ failed|cannot allocate memory|"
                     r"get_buffer\(\) failed|out of memory|enomem", re.I)
_НЕ_ЧИТАЕТСЯ = re.compile(r"invalid data found when processing input|"
                          r"moov atom not found|error while decoding|corrupt", re.I)
# Код, с которым процесс снят ядром либо системой за нехватку памяти:
# −9 у subprocess на POSIX, 137 — тот же SIGKILL через оболочку,
# 0xC0000017 — STATUS_NO_MEMORY у Windows
_КОДЫ_ПАМЯТИ = {-9, 137, 0xC0000017}


def причина_сбоя(код, вывод, разбор=None):
    """(текст человеку, текст журнала) по коду возврата и выводу ffmpeg."""
    строки = [с.strip() for с in (вывод or "").splitlines() if с.strip()]
    журнал = "ffmpeg код %s: %s" % (код, " | ".join(строки[-4:])[:600] or "(вывода нет)")
    размер = ""
    if разбор and разбор.get("width"):
        размер = " (%dx%d, %.1f с)" % (разбор["width"], разбор["height"],
                                      разбор.get("duration") or 0)
    if код in _КОДЫ_ПАМЯТИ or _ПАМЯТЬ.search(вывод or ""):
        return ("Сжатию не хватило памяти машины на этот ролик%s. Уменьшите "
                "разрешение (например, до 1280 по длинной стороне) или длительность "
                "и загрузите снова" % размер), журнал
    if _НЕ_ЧИТАЕТСЯ.search(вывод or ""):
        return ("Ролик не читается при сжатии — файл повреждён или записан "
                "неподдерживаемым кодеком. Пересохраните его в mp4 (H.264) "
                "и загрузите снова"), журнал
    return ("Ролик не удалось сжать, причина не распознана — подробности записаны "
            "в журнал сервера. Пересохраните ролик в mp4 (H.264) и загрузите снова"), журнал


def сжать_ролик(вход, выход, разбор=None):
    """Беззвучный mp4 H.264, длинная сторона не больше предела, до 30 к/с.

    `-threads 1` и `nice 19`: машина прода — один vCPU, и сжатие не имеет
    права отнять процессор у приложения, отвечающего на запросы."""
    д = ld.ВИДЕО_ДЛИННАЯ_СТОРОНА
    масштаб = ("scale=w=if(gte(iw\\,ih)\\,trunc(min(%d\\,iw)/2)*2\\,-2)"
               ":h=if(gte(iw\\,ih)\\,-2\\,trunc(min(%d\\,ih)/2)*2)" % (д, д))
    # ПАМЯТЬ ЗАМЕРЕНА НА БОЕВОЙ МАШИНЕ, 2026-09-13, исходник 1920x1080 5 с:
    #   `-preset medium`                         пик 226 МБ, 2.8 с, 524 КБ
    #   `-preset veryfast` + потоки 1 на входе   пик 135 МБ, 1.7 с, 462 КБ
    # при 316 МБ свободных на машине. Первая строка — это первая загрузка
    # на проде через панель (журнал `[landing]`): на ролике крупнее она
    # положила бы машину, как §5.8. Отсюда и потолок разрешения выше.
    команда = [ffmpeg(), "-hide_banner", "-nostdin", "-y", "-threads", "1", "-i", вход,
               "-map", "0:v:0", "-an", "-sn", "-dn", "-map_metadata", "-1",
               "-vf", масштаб, "-fpsmax", "30", "-filter_threads", "1",
               "-c:v", "libx264", "-preset", "veryfast", "-crf", "26",
               "-pix_fmt", "yuv420p", "-profile:v", "high",
               "-movflags", "+faststart", "-threads", "1", выход]
    доп = {}
    if os.name == "posix":
        доп["preexec_fn"] = lambda: os.nice(19)
    п = subprocess.Popen(команда, stdout=subprocess.DEVNULL,
                         stderr=subprocess.PIPE, **доп)
    пик = [0]
    стоп = threading.Event()
    если_linux = os.path.exists("/proc/%d/status" % п.pid)
    if если_linux:
        threading.Thread(target=_пик_памяти, args=(п.pid, стоп, пик),
                         daemon=True).start()
    try:
        _, ошибки = п.communicate(timeout=300)
    except subprocess.TimeoutExpired:
        п.kill()
        п.communicate()
        raise ОтказЗагрузки("Сжатие ролика не уложилось в 300 с — "
                            "ролик слишком длинный или тяжёлый", 413)
    finally:
        стоп.set()
    if п.returncode != 0 or not os.path.exists(выход):
        текст, журнал = причина_сбоя(п.returncode,
                                     (ошибки or b"").decode("utf-8", "replace"), разбор)
        raise ОтказЗагрузки(текст, 400, журнал=журнал)
    return пик[0] if если_linux else None


def _есть_прозрачность(im):
    if im.mode not in ("RGBA", "LA"):
        return False
    return im.getchannel("A").getextrema()[0] < 255


def сжать_картинку(вход, выход, место):
    """webp, длинная сторона не больше предела секции, прозрачность цела.

    `draft` ПЕРВЫМ ДЕЙСТВИЕМ: у JPEG он уменьшает при раскодировании,
    а после `convert` уже не работает — ровно на этом порядке прод
    получал 502 от снимка с телефона (§5.8)."""
    предел = ld.КАРТИНКА_ДЛИННАЯ_СТОРОНА[место["section"]]
    with Image.open(вход) as im:
        im.draft("RGB", (предел, предел))
        im = ImageOps.exif_transpose(im)
        if getattr(im, "n_frames", 1) > 1:
            im.seek(0)
        прозрачна = im.mode in ("RGBA", "LA", "PA") or "transparency" in im.info
        im = im.convert("RGBA" if прозрачна else "RGB")
        im.thumbnail((предел, предел), Image.LANCZOS)
        альфа = _есть_прозрачность(im)
        if not альфа and im.mode == "RGBA":
            im = im.convert("RGB")
        параметры = {"quality": 86, "method": 6}
        if альфа:
            # Прозрачность ЛОСЛЕСС при сжатом цвете: край объекта
            # на почти чёрном фоне виден сразу, а цвет прощает 86.
            параметры["alpha_quality"] = 100
            параметры["exact"] = False
        im.save(выход, "WEBP", **параметры)
        return im.width, im.height, альфа


# ═══ МЕНЬШИЙ ИЗ ДВУХ: СЖАТЫЙ ИЛИ ИСХОДНЫЙ (BACKLOG №328) ═══════════════
#
# Пересжатие не всегда уменьшает файл. Замер 2026-09-13: прозрачный PNG
# 9 КБ → webp 12 КБ; уже сжатый ролик 640 на 360, crf 30, 927 КБ → 1.0 МБ.
# Кладётся МЕНЬШИЙ — но исходник допускается к сравнению, ТОЛЬКО если
# страница покажет его так же, как сжатый, и он не несёт лишнего наружу.
# Главная — публичная страница, и метаданные исходника (координаты
# в EXIF снимка, имя автора в XMP, теги ролика) уехали бы к любому гостю.
#
# ЗВУК НЕ СРАВНИВАЕТСЯ (C3). Место под ролик беззвучное; исходник со звуком
# и сжатый без звука — разные вещи, и выбрать исходник значило бы отдать
# гостю звук. Такой исходник к сравнению не допускается, кладётся сжатый,
# даже если он тяжелее.

КАРТИНКА_ФОРМАТЫ = {"PNG": "png", "JPEG": "jpg", "WEBP": "webp"}
_МЕТАДАННЫЕ_КАРТИНКИ = ("exif", "xmp", "XML:com.adobe.xmp", "comment", "photoshop")


def исходник_картинки(путь, место):
    """(ext, ширина, высота, альфа) — если исходник годен лечь как есть;
    иначе (None, причина)."""
    предел = ld.КАРТИНКА_ДЛИННАЯ_СТОРОНА[место["section"]]
    with Image.open(путь) as im:
        ext = КАРТИНКА_ФОРМАТЫ.get(im.format)
        if ext is None:
            return None, "формат %s страница не показывает как есть" % im.format
        if getattr(im, "n_frames", 1) > 1:
            return None, "в файле больше одного кадра"
        if max(im.size) > предел:
            return None, "сторона %d больше предела %d" % (max(im.size), предел)
        лишнее = [к for к in _МЕТАДАННЫЕ_КАРТИНКИ if im.info.get(к)]
        if getattr(im, "text", None):
            лишнее.append("text")
        if лишнее:
            return None, "в файле метаданные (%s)" % ", ".join(лишнее)
        прозрачна = im.mode in ("RGBA", "LA", "PA") or "transparency" in im.info
        альфа = прозрачна and _есть_прозрачность(im.convert("RGBA"))
        return (ext, im.width, im.height, альфа), None


def исходник_ролика(разбор):
    """None — годен; иначе причина. Годен тот, что уже в формате места."""
    if "mp4" not in (разбор["format"] or ""):
        return "контейнер %s, а место отдаёт mp4" % разбор["format"]
    if разбор["codec"] != "h264":
        return "кодек %s, а место отдаёт H.264" % разбор["codec"]
    if разбор["pix_fmt"] != "yuv420p":
        return "пиксели %s, а браузеру нужен yuv420p" % разбор["pix_fmt"]
    if разбор["audio"]:
        return "в исходнике звук, а место беззвучное"
    if max(разбор["width"], разбор["height"]) > ld.ВИДЕО_ДЛИННАЯ_СТОРОНА:
        return "сторона больше %d" % ld.ВИДЕО_ДЛИННАЯ_СТОРОНА
    if (разбор["fps"] or 999) > 30:
        return "частота %s кадров, а место отдаёт до 30" % разбор["fps"]
    return None


def переупаковать_ролик(вход, выход):
    """Те же потоки без перекодирования: без метаданных, `faststart`.
    Это и есть «исходный» для сравнения — байты кадров исходника,
    а тегов и звука в нём нет."""
    п = subprocess.run([ffmpeg(), "-hide_banner", "-nostdin", "-y", "-i", вход,
                        "-map", "0:v:0", "-c", "copy", "-an", "-sn", "-dn",
                        "-map_metadata", "-1", "-movflags", "+faststart", выход],
                       capture_output=True, timeout=120)
    return п.returncode == 0 and os.path.exists(выход)


def обработать(место_id, временный, исходное_имя):
    """Готовит файл для места. Возвращает (путь_готового, сведения, предупреждения).

    Бросает `ОтказЗагрузки` — с числом там, где оно есть."""
    место = ld.ПО_ID.get(место_id)
    if место is None:
        raise ОтказЗагрузки("Такого места на странице нет", 404)
    исходный_вес = os.path.getsize(временный)
    предупреждения = []
    каталог = tempfile.mkdtemp(prefix="landing-")

    if место["kind"] == ld.ВИДЕО:
        if исходный_вес > ld.ВИДЕО_ПОТОЛОК_МБ * 1024 * 1024:
            raise ОтказЗагрузки("Ролик весит %.1f МБ при потолке %d МБ — не принят"
                                % (_мб(исходный_вес), ld.ВИДЕО_ПОТОЛОК_МБ), 413)
        разбор = разобрать_ролик(временный)
        if not _это_ролик(разбор):
            if _это_картинка(временный):
                raise ОтказЗагрузки("Это картинка, а место «%s» — под видео"
                                    % место["label"], 400)
            raise ОтказЗагрузки("Файл не распознан как видео — место «%s» "
                                "принимает только ролики" % место["label"], 400)
        сторона = max(разбор["width"], разбор["height"])
        if сторона > ld.ВИДЕО_ПОТОЛОК_СТОРОНА:
            raise ОтказЗагрузки("Ролик %dx%d — потолок %d по длинной стороне: сохраните "
                                "его в 1080p и загрузите снова"
                                % (разбор["width"], разбор["height"],
                                   ld.ВИДЕО_ПОТОЛОК_СТОРОНА), 413)
        if разбор["duration"] > ld.ВИДЕО_ПОТОЛОК_СЕК:
            raise ОтказЗагрузки("Ролик идёт %.1f с при потолке %d с — не принят"
                                % (разбор["duration"], ld.ВИДЕО_ПОТОЛОК_СЕК), 413)
        готовый = os.path.join(каталог, "out.mp4")
        пик = сжать_ролик(временный, готовый, разбор)
        итог = разобрать_ролик(готовый)
        сведения = {"kind": ld.ВИДЕО, "ext": "mp4",
                    "width": итог["width"], "height": итог["height"],
                    "duration_sec": round(итог["duration"] or разбор["duration"], 2),
                    "has_alpha": False, "peak_mb": пик}
        if сведения["duration_sec"] > ld.ВИДЕО_ПЕТЛЯ_СЕК:
            предупреждения.append("Петля идёт %.1f с — разумная до %d с"
                                  % (сведения["duration_sec"], ld.ВИДЕО_ПЕТЛЯ_СЕК))
        сжатый_вес = os.path.getsize(готовый)
        причина = исходник_ролика(разбор)
        сведения["compressed_bytes"] = сжатый_вес
        сведения["kept_original"] = False
        if причина is None:
            переупакован = os.path.join(каталог, "orig.mp4")
            if переупаковать_ролик(временный, переупакован) \
                    and os.path.getsize(переупакован) < сжатый_вес:
                готовый = переупакован
                сведения["kept_original"] = True
                сведения["width"], сведения["height"] = разбор["width"], разбор["height"]
                сведения["duration_sec"] = round(разбор["duration"], 2)
        сведения["original_skip"] = причина
        вес = os.path.getsize(готовый)
        if вес > ld.ВИДЕО_ИТОГ_МБ * 1024 * 1024:
            предупреждения.append("После сжатия %.1f МБ — для ленты разумно до %d МБ"
                                  % (_мб(вес), ld.ВИДЕО_ИТОГ_МБ))
    else:
        if исходный_вес > ld.КАРТИНКА_ПОТОЛОК_МБ * 1024 * 1024:
            raise ОтказЗагрузки("Картинка весит %.1f МБ при потолке %d МБ — не принята"
                                % (_мб(исходный_вес), ld.КАРТИНКА_ПОТОЛОК_МБ), 413)
        if not _это_картинка(временный):
            if _это_ролик(разобрать_ролик(временный)):
                raise ОтказЗагрузки("Это видео, а место «%s» — под картинку"
                                    % место["label"], 400)
            raise ОтказЗагрузки("Файл не распознан как картинка — место «%s» "
                                "принимает jpg, png, webp" % место["label"], 400)
        готовый = os.path.join(каталог, "out.webp")
        try:
            ш, в, альфа = сжать_картинку(временный, готовый, место)
        except (OSError, ValueError, Image.DecompressionBombError) as e:
            raise ОтказЗагрузки("Картинку не удалось разобрать — файл повреждён "
                                "или обрезан. Пересохраните её в jpg, png или webp "
                                "и загрузите снова", 400,
                                журнал="%s: %s" % (type(e).__name__, e))
        сведения = {"kind": ld.КАРТИНКА, "ext": "webp", "width": ш, "height": в,
                    "duration_sec": None, "has_alpha": альфа, "peak_mb": None}
        сжатый_вес = os.path.getsize(готовый)
        сведения["compressed_bytes"] = сжатый_вес
        сведения["kept_original"] = False
        try:
            годен, причина = исходник_картинки(временный, место)
        except (OSError, ValueError, Image.DecompressionBombError) as e:
            годен, причина = None, type(e).__name__
        if годен and исходный_вес < сжатый_вес:
            ext, ш, в, альфа = годен
            готовый = os.path.join(каталог, "orig." + ext)
            with open(временный, "rb") as вх, open(готовый, "wb") as вых:
                for кус in iter(lambda: вх.read(1 << 20), b""):
                    вых.write(кус)
            сведения.update({"ext": ext, "width": ш, "height": в, "has_alpha": альфа,
                             "kept_original": True})
        сведения["original_skip"] = причина
        if место["alpha"] and not сведения["has_alpha"]:
            предупреждения.append("У декоративного объекта нет прозрачности — "
                                  "на тёмном фоне будет виден прямоугольник")
        вес = os.path.getsize(готовый)
        if вес > ld.КАРТИНКА_ИТОГ_КБ * 1024:
            предупреждения.append("После сжатия %d КБ — разумно до %d КБ"
                                  % (вес // 1024, ld.КАРТИНКА_ИТОГ_КБ))

    сведения.update({"bytes": os.path.getsize(готовый),
                     "version": _версия(готовый),
                     "original_name": (исходное_имя or "")[:200],
                     "original_bytes": исходный_вес})
    return готовый, сведения, предупреждения

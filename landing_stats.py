"""ЧИСЛА КАРТОЧКИ 03 ГОСТЕВОЙ ГЛАВНОЙ — «масштаб работы» (письмо 4 задачи 343).

Каждое число считается КОМАНДОЙ, а не вписывается руками: вписанное
протухает молча (§6.0.4). Считаются ПРИ ВЫКЛАДКЕ — шагом deploy.yml
перед сборкой образа, — а не на каждый запрос: в образе нет ни `.git/`,
ни `*.md` (.dockerignore), считать там нечем. Результат — файл
`landing_stats.json` в корне сборки; в git он не лежит (.gitignore),
иначе число коммитов в нём отставало бы на коммит, который его записал.

    py landing_stats.py              — напечатать числа и способ счёта
    py landing_stats.py --записать   — записать landing_stats.json
    py landing_stats.py --контроль   — подлог: лишняя закрытая задача даёт +1

ЧИСЛА И СПОСОБ:
  · инструменты — пунктов списка раздела «Инструменты» гостевой главной
    (`class="pf-tool"` в templates/landing.html): ровно то, что видит гость;
  · задач закрыто — задачи BACKLOG.md, чей статус начинается словом
    «ВЫПОЛНЕНА» или «ЗАКРЫТА» и у которых нет поля `**Остаток:**`.
    Разбор — ЕДИНСТВЕННЫЙ в проекте, `backlog_open.задачи` и `состояние`
    (§6.0.7): свой разбор разошёлся бы с ним молча. «СНЯТА» не считается —
    снятая задача не сделана, а отменена; записи о решениях и замерах
    («ЗАПИСЬ О …») не считаются — это не работа. ЗДЕСЬ СТОЯЛИ «рабочие
    заходы» по темам коммитов — число было заниженной нижней границей
    (ранняя история номера не носит), заменено решением владельца
    (письмо 5 задачи 343);
  · коммиты — `git rev-list --count HEAD`;
  · автопроверки — проверок обоих рядов §6.0.2 (основной и ряд стенда,
    `project_lists`) плюс режимов пробы главной (`РЕЖИМЫ` в
    check_portfolio.py, разбором дерева — без импорта Playwright).

Любое число, которое посчитать не удалось, останавливает запись кодом 2:
карточка с выдуманным или пустым числом хуже карточки без выкладки.
"""
import ast
import io
import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent
ФАЙЛ = КОРЕНЬ / "landing_stats.json"


def _git(*арг):
    return subprocess.run(["git", *арг], cwd=КОРЕНЬ, capture_output=True, text=True,
                          encoding="utf-8", check=True).stdout


def инструменты():
    текст = io.open(КОРЕНЬ / "templates" / "landing.html", encoding="utf-8").read()
    return len(re.findall(r'<li class="pf-tool"', текст))


СЛОВА_СДЕЛАНО = ("выполнена", "закрыта")


def задач_закрыто(текст=None):
    """Задачи BACKLOG.md, закрытые работой. `текст` — для подлога контроля."""
    sys.path.insert(0, str(КОРЕНЬ))
    import backlog_open as бо
    if текст is None:
        текст = io.open(КОРЕНЬ / "BACKLOG.md", encoding="utf-8").read()
    закрыто = 0
    for _, _, статус, остаток, _ in бо.задачи(текст):
        сост, _ = бо.состояние(статус, остаток)
        if сост == "закрыта" and статус.lower().lstrip("*_ ").startswith(СЛОВА_СДЕЛАНО):
            закрыто += 1
    return закрыто


def контроль():
    """Лишняя закрытая задача в КОПИИ текста обязана дать ровно +1,
    а лишняя СНЯТАЯ — ноль (признак не считает отменённое сделанным)."""
    текст = io.open(КОРЕНЬ / "BACKLOG.md", encoding="utf-8").read()
    было = задач_закрыто(текст)
    сделана = текст + "\n## 9999. Подлог контроля\n\n**Статус:** ВЫПОЛНЕНА 2026-01-01\n"
    снята = текст + "\n## 9998. Подлог контроля\n\n**Статус:** СНЯТА 2026-01-01\n"
    с_сделанной, со_снятой = задач_закрыто(сделана), задач_закрыто(снята)
    print("задач закрыто: %d; с лишней выполненной %d; с лишней снятой %d"
          % (было, с_сделанной, со_снятой))
    ок = с_сделанной == было + 1 and со_снятой == было
    print("КОНТРОЛЬ: %s" % ("подлог пойман, обратный не засчитан" if ок else "НЕ ЛОВИТ"))
    return 0 if ок else 1


def коммиты():
    return int(_git("rev-list", "--count", "HEAD").strip())


def автопроверки():
    sys.path.insert(0, str(КОРЕНЬ))
    import project_lists as пл
    ряд = len(пл.разобрать()[1]) + len(пл.команды_стенда())
    дерево = ast.parse(io.open(КОРЕНЬ / "check_portfolio.py", encoding="utf-8").read())
    режимов = 0
    for узел in дерево.body:
        if isinstance(узел, ast.Assign) and any(getattr(ц, "id", "") == "РЕЖИМЫ" for ц in узел.targets):
            режимов = len(узел.value.elts)
    return ряд, режимов


def посчитать():
    ряд, режимов = автопроверки()
    return {"tools": инструменты(), "closed": задач_закрыто(), "commits": коммиты(),
            "checks": ряд + режимов, "checks_row": ряд, "checks_portfolio": режимов,
            "commit": _git("rev-parse", "--short", "HEAD").strip()}


def main():
    if "--контроль" in sys.argv[1:]:
        return контроль()
    ч = посчитать()
    print("инструменты %(tools)d · задач закрыто %(closed)d · коммиты %(commits)d · "
          "автопроверки %(checks)d (ряды §6.0.2 %(checks_row)d + режимы пробы главной "
          "%(checks_portfolio)d) · коммит %(commit)s" % ч)
    нули = [к for к in ("tools", "closed", "commits", "checks_row", "checks_portfolio") if not ч[к]]
    if нули:
        print("НЕ ПОСЧИТАНО: %s — файл не записан" % ", ".join(нули))
        return 2
    if "--записать" in sys.argv[1:]:
        ФАЙЛ.write_text(json.dumps(ч, ensure_ascii=False), encoding="utf-8")
        print("записано: %s" % ФАЙЛ.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""ГДЕ ЛЕЖАТ ФАЙЛЫ МЕСТ ГЛАВНОЙ И ПО КАКОМУ АДРЕСУ ИХ БРАТЬ (BACKLOG №325, B4).

ЭТО ЕДИНСТВЕННОЕ МЕСТО, КОТОРОЕ ЗНАЕТ, ГДЕ ЛЕЖИТ ФАЙЛ. Сервер, шаблоны
и проверка 37 спрашивают его, а не склеивают путь сами. Переезд
на внешнее хранилище — это замена ТЕЛ функций этого файла:

  `адрес()`     — вернуть адрес хранилища вместо `/landing-media/…`;
  `положить()`  — отправить файл туда вместо `shutil.move`;
  `удалить()`   — удалить там;
  `путь()`      — локальный путь, нужен только отдаче `/landing-media`;
                  после переезда отдача не нужна вовсе.

Сама строка, от которой зависит «где»:  `КАТАЛОГ` ниже — для тома,
`адрес()` — для страницы.

ПОЧЕМУ НА ТОМЕ, А НЕ В `static/`. Замер 2026-09-13 на боевой машине
(заход 325, блок A): файл, положенный в `/app` и `/tmp`, после выкатки
ПРОПАЛ, положенный в `/data` — ВЫЖИЛ. `static/` уезжает в образ,
и загруженное туда исчезло бы со следующим релизом МОЛЧА: загрузка
«сработала», а через день на странице пусто.

ИМЯ ФАЙЛА НЕСЁТ ВЕРСИЮ (`feed-1-3-1a2b3c4d.mp4`). Отсюда два свойства:
новый файл кладётся РЯДОМ со старым, а старый удаляется ПОСЛЕ записи
в базу — окна, в котором адрес ведёт в пустоту, нет; и адрес можно
отдавать с `immutable`, как у статики с отпечатком (§2.2).
"""

import os
import re
import shutil

from database import DB_PATH

КАТАЛОГ = os.path.join(os.path.dirname(DB_PATH) or ".", "landing")

# Имя файла места: опознаватель, дефис, 8 знаков версии, расширение.
# Только то, что сами выдаём: `..` и разделители пути сюда не пролезут.
ИМЯ_ФАЙЛА = re.compile(r"^([a-z0-9]+(?:-[a-z0-9]+)*)-([0-9a-f]{8})\.(mp4|webp|png|jpg)$")
# ТИП ОТДАЧИ ПО РАСШИРЕНИЮ. png и jpg появились с задачей 328: исходник
# ложится как есть, когда сжатие его не уменьшило.
ТИП = {"mp4": "video/mp4", "webp": "image/webp", "png": "image/png", "jpg": "image/jpeg"}

# ПЕРВЫЙ КАДР РОЛИКА (заход 342, блок B6) — `<место>-<версия>.poster.webp`.
# Версия та же, что у ролика: кадр живёт и умирает вместе с ним, и старый
# кадр после замены ролика отдаваться не может по построению.
ИМЯ_ПОСТЕРА = re.compile(r"^([a-z0-9]+(?:-[a-z0-9]+)*)-([0-9a-f]{8})\.poster\.webp$")


def имя_файла(slot_id, версия, ext):
    return "%s-%s.%s" % (slot_id, версия, ext)


def имя_постера(slot_id, версия):
    return "%s-%s.poster.webp" % (slot_id, версия)


def адрес_постера(slot_id, версия):
    return "/landing-media/" + имя_постера(slot_id, версия)


def путь(имя):
    """Локальный путь файла места. Имя проверяется: наружу — только наше."""
    if not (ИМЯ_ФАЙЛА.match(имя or "") or ИМЯ_ПОСТЕРА.match(имя or "")):
        raise ValueError("чужое имя файла места: %r" % (имя,))
    return os.path.join(КАТАЛОГ, имя)


def адрес(slot_id, версия, ext):
    """Адрес, по которому страница берёт файл места. ОДНА строка."""
    return "/landing-media/" + имя_файла(slot_id, версия, ext)


def положить(исходный, имя):
    """Переносит готовый файл в хранилище. Том и /tmp — разные файловые
    системы, поэтому `shutil.move`, а не `os.replace`: последний через
    границу файловых систем бросает OSError."""
    os.makedirs(КАТАЛОГ, exist_ok=True)
    цель = путь(имя)
    shutil.move(исходный, цель)
    return цель


def удалить(имя):
    """Удаляет файл места. Отсутствующий файл — не ошибка: запись о нём
    уже снята, и повторное удаление обязано проходить."""
    if not имя:
        return False
    # У ролика рядом лежит его первый кадр — уходит вместе с роликом,
    # иначе каждая замена оставляла бы сироту на томе.
    м = ИМЯ_ФАЙЛА.match(имя)
    if м and м.group(3) == "mp4":
        try:
            os.remove(путь(имя_постера(м.group(1), м.group(2))))
        except FileNotFoundError:
            pass
    try:
        os.remove(путь(имя))
        return True
    except FileNotFoundError:
        return False


def файлы():
    """Имена всех файлов в хранилище — для сверки с базой (сироты)."""
    if not os.path.isdir(КАТАЛОГ):
        return []
    return sorted(os.listdir(КАТАЛОГ))


def место():
    """(всего, свободно) байт на томе хранилища."""
    os.makedirs(КАТАЛОГ, exist_ok=True)
    u = shutil.disk_usage(КАТАЛОГ)
    return u.total, u.free

"""ПРОВЕРКА ГОТОВОГО ПИСЬМА HH: выдуманные технологии, потерянный репозиторий,
маркированные списки. BACKLOG №349, 2026-09-18.

Модуль ПУСТОЙ по импортам проекта: его зовут `main.generate_letter` (строка
`[letter-check]` в журнале после каждого письма) и проба `check_letter_facts.py`.
Вторая реализация в пробе разошлась бы с боевой молча (§6.0.7).

ТРИ ВОПРОСА, И У КАЖДОГО СВОЙ ИСТОЧНИК ПРАВДЫ

  1. ТЕХНОЛОГИЯ ВНЕ ДОСЬЕ. Словарь названий — файл `hh_tech_names.txt`
     (пополняется правкой файла). Допустимые — те из словаря, что написаны
     в досье или резюме ЭТОГО человека. Название из словаря в письме, которого
     там нет, разбирается ПО МЕСТУ УПОМИНАНИЯ (`разобрать`, шаблоны —
     `hh_tech_context.txt`). Находка — только приписка СЕБЕ («работаю
     с Groq») и выдуманное требование («у вас Groq» при Groq вне вакансии).
     НЕ находка: отрицание («с PostgreSQL не работал») и требование,
     которое есть в тексте вакансии («у вас в стеке Git»). Упоминание без
     признаков — «спорное»: проба 44 его печатает, журнал прода — нет
     (задача 346, заход 7: ложная находка засоряет счётчик на /admin/usage).

  2. РЕПОЗИТОРИЙ ПОТЕРЯН. Ссылки одного проекта (сайт и репозиторий) берутся
     из досье группой. Сайт проекта в письме есть, а его репозитория нет —
     находка. Проект в письме не упомянут вовсе — вопроса нет: правило досье
     «не приплетать нерелевантные проекты» законно убирает его целиком.

  3. МАРКИРОВАННЫЙ СПИСОК. Считается, но НАХОДКОЙ НЕ ЯВЛЯЕТСЯ с 2026-09-19:
     решение владельца — списки в письме допустимы. Число остаётся в строке
     журнала справкой.

  4. ЗАПРЕТЫ ДОСЬЕ (задача 346, заход 6). Решение владельца: письмо НИКОГДА
     не упоминает зарплату и не предлагает созвон или тестовое задание, если
     досье этого не разрешает. Словарь фраз — файл `hh_letter_phrases.txt`.
     Созвон разрешён, только когда в «Концовке письма» выбрано «Предлагать
     созвон» и не выбрано «только подпись»; тестовое — так же; зарплата
     запрещена, если в поле «Что не упоминать» есть слово раздела
     `запрет_зарплаты`.
"""
import os
import re

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
СЛОВАРЬ_ФАЙЛ = os.path.join(КОРЕНЬ, "hh_tech_names.txt")
ФРАЗЫ_ФАЙЛ = os.path.join(КОРЕНЬ, "hh_letter_phrases.txt")
КОНТЕКСТ_ФАЙЛ = os.path.join(КОРЕНЬ, "hh_tech_context.txt")
РАЗДЕЛЫ_КОНТЕКСТА = ("отрицание", "требование", "опыт")
РАЗДЕЛЫ_ФРАЗ = ("созвон", "тестовое", "зарплата", "запрет_зарплаты")

# Адрес в свободном тексте: со схемой либо github.com/владелец/репозиторий
_АДРЕС = re.compile(r"(?:https?://[^\s<>\"')\]]+|github\.com/[\w.-]+/[\w.-]+)", re.I)
_МАРКЕР = re.compile(r"^\s*(?:[-—–•*]|\d+[.)])\s+\S")


def словарь(путь: str = None) -> list:
    """[(каноническое, [варианты])] из файла. Пустой файл — исключение:
    проверка на пустом словаре молча печатала бы «чисто» про всё (§6.0.1)."""
    путь = путь or СЛОВАРЬ_ФАЙЛ
    записи = []
    with open(путь, encoding="utf-8") as ф:
        for строка in ф:
            строка = строка.strip()
            if not строка or строка.startswith("#"):
                continue
            варианты = [в.strip() for в in строка.split("|") if в.strip()]
            записи.append((варианты[0], варианты))
    if not записи:
        raise ValueError(f"словарь технологий пуст: {путь}")
    return записи


def _шаблон(вариант: str):
    # Целым латинским словом: соседняя кириллица допустима («Docker-е»,
    # «FastAPI-сервис»), соседняя латиница — нет («Git» внутри «GitHub»).
    return re.compile(r"(?<![A-Za-z0-9])" + re.escape(вариант) + r"(?![A-Za-z0-9])", re.I)


def найти(текст: str, записи: list) -> set:
    """Канонические имена из словаря, встреченные в тексте."""
    текст = текст or ""
    return {кан for кан, вар in записи if any(_шаблон(в).search(текст) for в in вар)}


def нормаль_адреса(адрес: str) -> str:
    а = адрес.strip().rstrip(".,;:!?»)").lower()
    а = re.sub(r"^https?://", "", а)
    а = re.sub(r"^www\.", "", а)
    return а.rstrip("/")


def адреса(текст: str) -> list:
    """Адреса из текста дословно, без хвостовой пунктуации."""
    return [a.rstrip(".,;:!?»)") for a in _АДРЕС.findall(текст or "")]


def ссылки_проектов(проекты) -> list:
    """Группы ссылок по проектам досье: поле url плюс адреса из описания.

    Порядок сохраняется, повторы снимаются по нормали. Проект без единой
    ссылки группы не даёт."""
    группы = []
    for п in проекты or []:
        if not isinstance(п, dict):
            continue
        кандидаты = ([п.get("url")] if п.get("url") else []) + адреса(п.get("description") or "")
        группа, виденные = [], set()
        for к in кандидаты:
            н = нормаль_адреса(к)
            if н and н not in виденные:
                виденные.add(н)
                группа.append(к.strip())
        if группа:
            группы.append(группа)
    return группы


def дополнить_парами(выбранные: list, группы: list) -> list:
    """Выбранные анализатором ссылки плюс остальные ссылки ТЕХ ЖЕ проектов.

    Анализатор видит сжатое досье, где у проекта один адрес — сайт; репозиторий
    живёт в описании и до него не доезжает. Отсюда пара: выбран сайт — рядом
    встаёт его репозиторий."""
    итог = list(выбранные or [])
    есть = {нормаль_адреса(a) for a in итог}
    for группа in группы:
        if any(нормаль_адреса(a) in есть for a in группа):
            for a in группа:
                if нормаль_адреса(a) not in есть:
                    есть.add(нормаль_адреса(a))
                    итог.append(a)
    return итог


def _репозиторий(адрес: str) -> bool:
    return нормаль_адреса(адрес).startswith(("github.com/", "gitlab.com/"))


def списков(письмо: str) -> int:
    """Число маркированных списков: две и больше строки с маркером подряд."""
    n, подряд = 0, 0
    for строка in (письмо or "").splitlines():
        if _МАРКЕР.match(строка):
            подряд += 1
            if подряд == 2:
                n += 1
        elif строка.strip():
            подряд = 0
    return n


def фразы(путь: str = None) -> dict:
    """{раздел: [скомпилированные шаблоны]} из файла фраз запретов."""
    return _файл_шаблонов(путь or ФРАЗЫ_ФАЙЛ, РАЗДЕЛЫ_ФРАЗ)


def _файл_шаблонов(путь: str, разделы) -> dict:
    """Разбор файла `[раздел]` + регулярки. Пустой раздел — исключение,
    а не «чисто»: проверка на пустом словаре печатала бы «нарушений нет»
    про любое письмо (§6.0.1)."""
    итог, раздел = {р: [] for р in разделы}, None
    with open(путь, encoding="utf-8") as ф:
        for строка in ф:
            строка = строка.strip()
            if not строка or строка.startswith("#"):
                continue
            if строка.startswith("[") and строка.endswith("]"):
                раздел = строка[1:-1]
                if раздел not in итог:
                    raise ValueError(f"незнакомый раздел фраз: {раздел}")
                continue
            if раздел is None:
                raise ValueError(f"шаблон вне раздела: {строка}")
            итог[раздел].append(re.compile(строка, re.I))
    пустые = [р for р, ш in итог.items() if not ш]
    if пустые:
        raise ValueError(f"разделы фраз пусты: {пустые}")
    return итог


def _первое(текст: str, шаблоны: list):
    """Первое совпадение (для отчёта о находке) либо None."""
    for ш in шаблоны:
        м = ш.search(текст or "")
        if м:
            return м
    return None


def разрешения(концовка, не_упоминать: str, ф: dict = None) -> dict:
    """Что досье РАЗРЕШАЕТ: {созвон, тестовое, зарплата} → bool.

    Нет поля «Концовка» вовсе — разрешений нет: решение владельца
    «никогда, если в досье не разрешено», то есть умолчание запрещает."""
    ф = ф or фразы()
    к = концовка if isinstance(концовка, dict) else {}
    только_подпись = bool(к.get("just_farewell"))
    return {
        "созвон": bool(к.get("suggest_call")) and not только_подпись,
        "тестовое": bool(к.get("suggest_test_task")) and not только_подпись,
        "зарплата": _первое(не_упоминать or "", ф["запрет_зарплаты"]) is None,
    }


def нарушения(письмо: str, концовка, не_упоминать: str, ф: dict = None) -> dict:
    """{раздел: найденный кусок} по запрещённым досье разделам."""
    ф = ф or фразы()
    можно = разрешения(концовка, не_упоминать, ф)
    итог = {}
    for раздел in ("созвон", "тестовое", "зарплата"):
        if можно[раздел]:
            continue
        м = _первое(письмо, ф[раздел])
        if м:
            итог[раздел] = м.group(0)
    return итог


def контекст(путь: str = None) -> dict:
    """Шаблоны отрицания, требования вакансии и опыта от первого лица —
    файл `hh_tech_context.txt`, тот же формат и тот же разбор, что у фраз."""
    return _файл_шаблонов(путь or КОНТЕКСТ_ФАЙЛ, РАЗДЕЛЫ_КОНТЕКСТА)


_ПРЕДЛОЖЕНИЕ = re.compile(r"(?<=[.!?])\s+|\n+")
_ОТРЕЗОК = re.compile(r"[,;]|\s[—–-]\s")


def _есть(текст: str, шаблоны: list) -> bool:
    return _первое(текст, шаблоны) is not None


def вид_упоминания(предложение: str, отрезок: str, в_вакансии: bool, к: dict) -> str:
    """Вид ОДНОГО упоминания технологии вне досье.

    Порядок — часть правила: отрицание рядом с названием сильнее всего
    («с PostgreSQL опыта не было» — и отрицание, и слово «опыт»), дальше
    отрезок, потом предложение целиком. Возвращает `отрицание`,
    `требование` (не находка), `выдуманное_требование`, `опыт` (находки)
    либо `спорное`."""
    if _есть(отрезок, к["отрицание"]):
        return "отрицание"
    for кусок in (отрезок, предложение):
        if _есть(кусок, к["требование"]):
            return "требование" if в_вакансии else "выдуманное_требование"
        if _есть(кусок, к["опыт"]):
            return "опыт"
    return "спорное"


_ВЕС = {"опыт": 3, "выдуманное_требование": 3, "спорное": 2, "требование": 1, "отрицание": 0}


def разобрать(письмо: str, имена: set, записи: list, вакансия_имена: set, к: dict = None) -> dict:
    """{имя: вид} для технологий вне досье. У имени, упомянутого несколько
    раз, берётся ХУДШИЙ вид: одна приписка опыта — находка, сколько бы
    рядом ни было отрицаний."""
    к = к or контекст()
    варианты = {кан: вар for кан, вар in записи if кан in имена}
    итог = {}
    for предл in _ПРЕДЛОЖЕНИЕ.split(письмо or ""):
        for отрез in _ОТРЕЗОК.split(предл):
            for имя, вар in варианты.items():
                if not any(_шаблон(в).search(отрез) for в in вар):
                    continue
                вид = вид_упоминания(предл, отрез, имя in вакансия_имена, к)
                if _ВЕС[вид] >= _ВЕС.get(итог.get(имя), -1):
                    итог[имя] = вид
    for имя in имена:  # название, разорванное разделителем, — не угадываем
        итог.setdefault(имя, "спорное")
    return итог


def допустимые(досье: str, резюме: str, записи: list = None) -> set:
    return найти((досье or "") + "\n" + (резюме or ""), записи or словарь())


def подпись_не_на_языке(письмо: str, lang: str) -> bool:
    """Английское письмо с кириллицей в подписи (№352, «питание-1», 1.4).

    Подпись — последние две непустые строки письма. Русское письмо
    не проверяется: русская подпись законна и в латинице не нуждается."""
    if lang != "en":
        return False
    строки = [с for с in (письмо or "").splitlines() if с.strip()]
    хвост = " ".join(строки[-2:])
    return any("\u0400" <= з <= "\u04ff" for з in хвост)


def проверить(письмо: str, досье: str, резюме: str, вакансия: str,
              группы_ссылок: list, записи: list = None,
              концовка=None, не_упоминать: str = "", lang: str = "ru") -> dict:
    """Находки по готовому письму. `чисто` — ни одной находки."""
    записи = записи or словарь()
    в_письме = найти(письмо, записи)
    можно = допустимые(досье, резюме, записи)
    в_вакансии = найти(вакансия, записи)
    виды = разобрать(письмо, в_письме - можно, записи, в_вакансии)
    вне = sorted(и for и, в in виды.items() if в in ("опыт", "выдуманное_требование"))
    из_вакансии = sorted(и for и, в in виды.items() if в == "требование")
    отрицание = sorted(и for и, в in виды.items() if в == "отрицание")
    спорное = sorted(и for и, в in виды.items() if в == "спорное")

    текст = нормаль_адреса(" ".join(адреса(письмо)))
    письмо_н = (письмо or "").lower()
    нет_репо = []
    for группа in группы_ссылок or []:
        сайты = [a for a in группа if not _репозиторий(a)]
        репо = [a for a in группа if _репозиторий(a)]
        if not сайты or not репо:
            continue
        сайт_есть = any(нормаль_адреса(a) in письмо_н or нормаль_адреса(a) in текст for a in сайты)
        репо_есть = any(нормаль_адреса(a) in письмо_н for a in репо)
        if сайт_есть and not репо_есть:
            нет_репо.append(репо[0])

    n_списков = списков(письмо)
    запреты = нарушения(письмо, концовка, не_упоминать)
    return {
        "вне_досье": вне,
        "из_вакансии": из_вакансии,
        "отрицание": отрицание,
        "спорное": спорное,
        "нет_репозитория": нет_репо,
        "списков": n_списков,
        "запреты": запреты,
        "допустимых": len(можно),
        "подпись_не_на_языке": подпись_не_на_языке(письмо, lang),
        "чисто": not вне and not нет_репо and not запреты
                 and not подпись_не_на_языке(письмо, lang),
    }


def строкой(итог: dict) -> str:
    """Одна строка для журнала — без текста письма (§2.7: текста не храним)."""
    return (f"вне досье {итог['вне_досье'] or 0} · из вакансии {итог['из_вакансии'] or 0} · "
            f"с отрицанием {итог.get('отрицание') or 0} · спорное {итог.get('спорное') or 0} · "
            f"нет репозитория {итог['нет_репозитория'] or 0} · "
            f"запреты досье {sorted(итог['запреты']) or 0} · списков {итог['списков']}")

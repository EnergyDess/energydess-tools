def _проверить_базу() -> str:
    """Отдаёт путь к базе или останавливает скрипт, если база не локальная.

    Признаков прода два, и проверяются оба: путь тома Fly (`/data`) и
    переменная окружения, которую Fly выставляет машине сам. Одного пути мало —
    базу можно смонтировать куда угодно; одной переменной мало — скрипт
    могут запустить с прод-базой, скачанной к себе.
    """
    путь = os.getenv("DB_PATH", "./app.db")
    причины = []
    if os.getenv("FLY_APP_NAME"):
        причины.append(f"FLY_APP_NAME={os.getenv('FLY_APP_NAME')} — это машина Fly")
    нормализованный = os.path.abspath(путь).replace("\\", "/")
    if _на_боевом_томе(нормализованный) or _на_боевом_томе(путь.replace("\\", "/")):
        причины.append(f"путь {путь} ведёт на том с боевой базой")
    if причины:
        print("ОСТАНОВЛЕНО: аккаунт для съёмки заводится только в локальной базе.")
        for п in причины:
            print(f"  — {п}")
        print("\nЭто вход с правами администратора и с паролем, записанным "
              "открытым текстом в CLAUDE.md. На проде такого быть не должно.")
        sys.exit(1)
    return путь


def _на_боевом_томе(путь: str) -> bool:
    return путь.startswith("/data/") or путь == "/data" or "/data/app.db" in путь



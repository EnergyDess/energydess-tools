def _сид_enshrouded(db, user_id: int) -> dict:
    """Отметки в трекере Enshrouded: собранные сеты, частичные, все пять
    редкостей, дубликаты, уровни.

    ДО 2026-08-22 таблица стояла в ПУСТО_ЗАКОННО с причиной «раздел живёт
    мимо дизайн-системы, данные ему заведут вместе со сносом». Снос
    состоялся (BACKLOG №2), и без данных не снимается НИ ОДНО состояние
    экрана: отметка собранного сета, цвет редкости у слота, значок
    дубликата, уровень в углу, счётчики в шапке, окно предмета
    у ОТМЕЧЕННОГО предмета. Пустой раздел при этом выглядит исправным —
    ровно тот класс, ради которого написан §8.0.

    Список сетов НЕ ПЕРЕЧИСЛЯЕТСЯ, а читается из шаблона тем же разбором,
    которым его читает проверка 24 (§6.0.7): вписанный руками id разошёлся
    бы с данными молча, и seed заполнял бы сет, которого нет.
    """
    import check_enshrouded as _ens
    from database import EnshroudedSlot

    д = _ens.прочитать()
    сеты = д["sets"]
    состав = {с["id"]: _ens._состав(с, д["slots"])[0] for с in сеты}
    по_кат = {}
    for с in сеты:
        по_кат.setdefault(с["crafter"], []).append(с)

    db.query(EnshroudedSlot).filter(EnshroudedSlot.user_id == user_id).delete()

    РЕДКОСТИ = ["common", "uncommon", "rare", "epic", "legendary"]
    положено = []   # (set_id, slot_id, rarity, level, duplicates)
    собрано, частично = [], []

    # СОБРАННЫЕ ЦЕЛИКОМ — по два в каждой крафтовой категории и один
    # в «Мире»: отметка сета должна быть видна и в сетке, и в счётчике.
    for кат, сколько in (("blacksmith", 2), ("huntress", 2),
                         ("alchemist", 2), ("world", 1), ("special", 1)):
        for с in по_кат.get(кат, [])[:сколько]:
            собрано.append(с["id"])

    # ЧАСТИЧНО СОБРАННЫЕ — полоска заполнения обязана показывать долю,
    # а не только 0% и 100%.
    for кат in ("blacksmith", "huntress", "alchemist", "world"):
        for с in по_кат.get(кат, [])[2:5]:
            частично.append(с["id"])

    ур = 5
    for i, sid in enumerate(собрано):
        for j, slid in enumerate(состав[sid]):
            # Все пять редкостей встречаются, и в одном сете они РАЗНЫЕ:
            # ряд одинаковых слотов не показал бы, что цвет вообще меняется.
            редк = РЕДКОСТИ[(i + j) % len(РЕДКОСТИ)]
            дубли = 2 if (i == 0 and j == 0) else (1 if j == 2 else 0)
            ур = ур + 3 if ур < 60 else 12
            положено.append((sid, slid, редк, ур, дубли))
    for i, sid in enumerate(частично):
        # Половина состава с округлением вниз, но не меньше одного.
        части = состав[sid]
        сколько = max(1, len(части) // 2)
        for j, slid in enumerate(части[:сколько]):
            положено.append((sid, slid, РЕДКОСТИ[(i + j) % len(РЕДКОСТИ)], None, 0))

    for sid, slid, редк, уровень, дубли in положено:
        db.add(EnshroudedSlot(user_id=user_id, set_id=sid, slot_id=slid,
                              owned=True, rarity=редк, level=уровень,
                              duplicates=дубли))
    db.flush()

    # ЧИСЛА СЧИТАЮТСЯ ПО БАЗЕ, а не по списку намерений (§8.0).
    строк = db.query(EnshroudedSlot).filter(
        EnshroudedSlot.user_id == user_id, EnshroudedSlot.owned.is_(True)).count()
    редкостей = {r for (r,) in db.query(EnshroudedSlot.rarity).filter(
        EnshroudedSlot.user_id == user_id).distinct()}
    with_dupes = db.query(EnshroudedSlot).filter(
        EnshroudedSlot.user_id == user_id, EnshroudedSlot.duplicates > 0).count()
    return {"сетов": len(сеты), "собрано": len(собрано), "частично": len(частично),
            "слотов": строк, "редкостей": len(редкостей), "дублей": with_dupes}



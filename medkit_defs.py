def склонение(n, формы):
    """«1 таблетку», «2 таблетки», «5 таблеток». Дробное — родительный
    единственного: «0,5 таблетки», и это тоже по-русски правильно.

    Правило то же, что у счётчика писем в HH-ассистенте: смотрим две
    последние цифры, 11–14 — особый случай.
    """
    if n != int(n):
        return формы[1]
    n = abs(int(n))
    две, одна = n % 100, n % 10
    if 11 <= две <= 14:
        return формы[2]
    if одна == 1:
        return формы[0]
    if 2 <= одна <= 4:
        return формы[1]
    return формы[2]


def число(n):
    """Число для человека: 1, а не 1.0; 0,5, а не 0.5.

    Запятая, а не точка: в русском тексте «0.5 таблетки» читается как
    опечатка, а поле ввода принимает и то и другое.
    """
    if n is None:
        return ""
    if float(n) == int(float(n)):
        return str(int(float(n)))
    return ("%g" % float(n)).replace(".", ",")


def нормаль(текст):
    """ОДИН способ привести строку к виду, в котором её сравнивают.

    Регистр плюс схлопывание пробельного: заметка человека приходит
    с переносами строк, и без схлопывания запрос «по 1 таблетке»
    не находил бы её, потому что между словами стоит перевод строки,
    а не пробел.

    ИМЕНЕМ, А НЕ ГОЛЫМ `.lower()` НА МЕСТЕ, и довод не в красоте.
    Python `.lower()` кириллицу приводит, а лежащий рядом SQLite —
    НЕТ: `lower()`, `upper()`, `LIKE` и даже `COLLATE NOCASE` у него
    работают только с латиницей (замер — `tests/test_medkit.py`).
    То есть перенос отбора в SQL-запрос выглядел бы одной строкой,
    а поиск при этом молча перестал бы находить «нурофен»
    по «Нурофен». Названная функция ставит на этом пути препятствие:
    `WHERE lower(name) LIKE …` не подставится вместо неё сама собой.

    Вторая половина договора — в браузере: он приводит ЗАПРОС
    тем же способом (`.trim().toLowerCase()`). Разойдись стороны —
    поиск отвечал бы «ничего не нашлось» при живых данных, и это
    сторожит шаг «поиск-регистр-и-кириллица» в `check_medkit_ui.py`.
    """
    return " ".join((текст or "").split()).lower()



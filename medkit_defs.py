# ПРИЗНАК СТРУКТУРНЫЙ: значение оставило след в источнике или нет.
# Источник — то, что модель ВЫПИСАЛА с упаковки, плюс то, что написал
# человек. Ни списка слов, ни перечня «подозрительных» веществ здесь
# нет и быть не может: множество названий открыто (§6.0.7).
#
# ЗДЕСЬ, А НЕ В `main.py`: потребителей у признака ДВА — сервер
# и мерка `check_medkit_entry.py`. Держи мерка свой разбор, её «из
# памяти 0» относилось бы к поведению, которого на бою нет (§6.0.7,
# тот же довод, что у `medkit_dosage.подходит`).

def _корни(текст):
    """Слова источника плюс их усечения на два и три знака.

    Русские окончания различают «пакетик» и «пакетиков», а сказано
    в них одно и то же. Обрезка грубая НАМЕРЕННО: тонкая морфология
    была бы вторым источником правды рядом со склонениями `ЕДИНИЦЫ`,
    а цена ошибки тут несимметрична — лишний отсев отнимает у человека
    верно прочитанное поле, и он решит, что разбор сломался.
    """
    # БЕЗ `re`, И ЭТО НЕ ВКУС: модуль объявлен пустым — ни одного
    # импорта, — потому что его читает проверка 24 из ряда §6.0.2,
    # а ряд обязан читаться без поднятого приложения. Свойство
    # держится тем, что его нечем нарушить незаметно
    годные = "0123456789абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
    годные += "abcdefghijklmnopqrstuvwxyz"
    # `str()` ОБЯЗАТЕЛЕН: количество приезжает от модели ЧИСЛОМ,
    # а `нормаль` зовёт `.split()`. Без приведения признак падал
    # `AttributeError` на самом обычном поле — поймал контроль
    чистое = "".join(з if з in годные else " " for з in нормаль(str(текст)))
    вышло = set()
    for слово in чистое.split():
        вышло.add(слово)
        if len(слово) > 4:
            вышло.add(слово[:-2])
        if len(слово) > 5:
            вышло.add(слово[:-3])
    return вышло


def след(значение, источник):
    """Оставило ли значение след в источнике.

    Хватает ОДНОГО совпавшего слова: «Парацетамол 180 мг» против
    выписки, где стоит только «парацетамол», — это прочитанное поле,
    а не домысел. Отсев срабатывает лишь там, где не совпало НИЧЕГО.
    """
    корни = _корни(источник)
    for слово in _корни(значение):
        if len(слово) < 3:
            # Короткое слово («мг», «20») ищем целиком: усечение
            # от него не оставило бы ничего, и совпало бы всё подряд
            if слово in корни:
                return True
            continue
        if слово in корни:
            return True
        for к in корни:
            if len(к) >= 3 and (к.startswith(слово) or слово.startswith(к)):
                return True
    return False


def человеческое(ключ, значение):
    """Значение поля плюс его русские имена — то, что и ищем в источнике.

    Форма и единица приезжают от модели ЛАТИНСКИМ id (`tablet`),
    а на упаковке напечатано «таблетки». Без склонений отсюда признак
    объявил бы домыслом законный разбор — и объявлял: первая версия
    мерки спрашивала у `ЕДИНИЦЫ` ключ `формы`, которого там нет,
    и дала четыре ложные находки из пяти.
    """
    варианты = [значение]
    if ключ == "form":
        ф = ФОРМА_ПО_ID.get(значение)
        if ф:
            варианты.append(ф["имя"])
    if ключ == "unit":
        е = ЕДИНИЦЫ.get(значение)
        if е:
            варианты.append(е.get("кратко") or "")
            варианты.extend(е.get("слово") or ())
            варианты.extend(е.get("слово_им") or ())
    return [в for в in варианты if в]


# Разделитель групп GS1. В коде с камеры приезжает как U+001D, но
# часть сканеров отдаёт его печатным `<GS>` либо не отдаёт вовсе.
# КОДОМ, А НЕ ЛИТЕРАЛОМ: невидимый знак в исходнике — тот же немой
# отказ, только в собственном коде (§2.6, ловушка с U+2028).
GS = chr(0x1D)


def gtin_из_кода(строка):
    """Строка со сканера → GTIN из 14 цифр, либо None.

    ЧЕТЫРЕ СЛУЧАЯ, И ТРЕТИЙ ОТ ЧЕТВЁРТОГО ОТЛИЧАЕТСЯ ПО ФОРМЕ,
    А НЕ ПО ДЛИНЕ ЦИФР:

      · `01` + 14 цифр (DataMatrix лекарства)   → эти 14 цифр;
      · ровно 14 цифр                            → они и есть GTIN;
      · ровно 13 цифр (EAN-13 с пачки)          → ведущий ноль плюс они.
        Это НЕ послабление: GTIN-14 потребительской единицы по GS1
        и есть `0` + GTIN-13, и замер на образце сходится —
        DataMatrix даёт `04600439931256`, штрих-код той же пачки
        `4600439931256`. То есть нормализация СВЯЗЫВАЕТ два формата
        одной пачки, а не путает разные;
      · `01` + МЕНЬШЕ 14 цифр                    → None, код оборван.

    Последний случай и есть тот, что назвала постановка задачи:
    обрезанный DataMatrix (`01` плюс 13 цифр — это 15 знаков)
    от честного EAN-13 (13 знаков) отличается ПРЕФИКСОМ, и потому
    различим. Отвергать всякую строку из 13 цифр значило бы
    не пускать обычный штрих-код обычной пачки.

    КОНТРОЛЬНОЙ ЦИФРЫ ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ, и это решение. Она
    отсекла бы случайный мусор, но ценой ложного отказа на пачке,
    чей код нестандартен, — а цена ошибок разная: лишний GTIN в базе
    не найдётся повторно и только, тогда как отвергнутый настоящий
    код читается человеком как «сканер сломан».
    """
    s = (строка or "").strip()
    if not s:
        return None
    # Печатные записи разделителя, которыми грешат сканеры
    for знак in (GS, "\u241d", "<GS>", "{GS}"):
        s = s.replace(знак, "\x00")
    голова = s.split("\x00", 1)[0]

    if голова.startswith("01"):
        цифры = ""
        for ch in голова[2:]:
            if not ch.isdigit():
                break
            цифры += ch
        # РОВНО 14: пятнадцатая цифра принадлежит уже следующему полю
        # только если между ними стоял разделитель, а его тут нет —
        # значит поле `01` фиксированной длины и читается по счёту
        return цифры[:14] if len(цифры) >= 14 else None

    только_цифры = "".join(ch for ch in голова if ch.isdigit())
    if только_цифры != голова.replace(" ", "").replace("-", ""):
        return None
    if len(только_цифры) == 14:
        return только_цифры
    if len(только_цифры) == 13:
        return "0" + только_цифры
    return None



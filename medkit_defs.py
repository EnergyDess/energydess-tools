def вскрытие_дней(form_id, unit=None):
    """Сколько дней живёт ВСКРЫТАЯ упаковка. `None` — вскрытие срока
    не меняет, и тогда у формы этого понятия нет вовсе.

    ЕДИНСТВЕННЫЙ ИСТОЧНИК ПРИЗНАКА «ФОРМА ПОРТИТСЯ ПОСЛЕ ВСКРЫТИЯ»
    на три стороны: сервер считает по нему состояние, форма по нему
    показывает или прячет два поля, проба по нему же строит набор.
    Второй список форм разошёлся бы с первым молча (§6.0.7).

    ПОЧЕМУ ВООБЩЕ ПОНАДОБИЛОСЬ. Поля «Вскрыто» и «Годен после вскрытия»
    показывались у ВСЕХ форм, включая таблетки в блистере. Блистер
    после вскрытия пачки не портится — таблетки годны до срока
    на упаковке, — и поле там не просто лишнее: владелец поставил дату
    наугад, и обе его карточки загорелись жёлтым «ВСКРЫТ 01.08».
    Ложная тревога, порождённая полем, которого там быть не должно.

    У ПОРОШКА ОТВЕТ ЗАВИСИТ ОТ ЕДИНИЦЫ, и это не тонкость: пакетик
    запечатан сам по себе, вскрытие коробки его не касается; банка
    после вскрытия стоит открытой. 30 дней — НАШЕ осторожное число
    по тому же правилу, что все остальные умолчания вскрытия (§5.8):
    смещено в меньшую сторону, потому что лишнее предупреждение
    дешевле молчания там, где предупредить было надо.
    """
    ф = ФОРМА_ПО_ID.get(form_id)
    if not ф:
        return None
    по_единице = ф.get("вскрытие_дней_по_единице") or {}
    if unit and unit in по_единице:
        return по_единице[unit]
    return ф["вскрытие_дней"]


def портится_после_вскрытия(form_id, unit=None):
    """Меняет ли вскрытие срок годности этой формы."""
    return вскрытие_дней(form_id, unit) is not None


def формы_для_экрана():
    """ФОРМЫ ПЛЮС ГОТОВЫЙ ОТВЕТ «сколько живёт вскрытая» ПО КАЖДОЙ
    ЕДИНИЦЕ этой формы.

    Готовый ответ, а не исходные поля: иначе браузеру пришлось бы
    ПОВТОРИТЬ правило (сперва посмотреть в таблицу по единице, потом
    откатиться на общее значение формы), и это был бы второй экземпляр
    правила — тот самый, что расходится молча. Здесь браузер только
    читает: `ф['вскрытие'][единица]`, `null` — поля вскрытия не нужны.
    """
    из = []
    for ф in ФОРМЫ:
        копия = dict(ф)
        копия["вскрытие"] = {е: вскрытие_дней(ф["id"], е) for е in ф["единицы"]}
        из.append(копия)
    return из


def склонение(n, формы):
    """«1 таблетку», «2 таблетки», «5 таблеток». Дробное — родительный
    единственного: «0,5 таблетки», и это тоже по-русски правильно.

    Правило то же, что у счётчика писем в HH-ассистенте: смотрим две
    последние цифры, 11–14 — особый случай.
    """
    if n != int(n):
        return формы[1]
    n = abs(int(n))
    две, одна = n % 100, n % 10
    if 11 <= две <= 14:
        return формы[2]
    if одна == 1:
        return формы[0]
    if 2 <= одна <= 4:
        return формы[1]
    return формы[2]


def число(n):
    """Число для человека: 1, а не 1.0; 0,5, а не 0.5.

    Запятая, а не точка: в русском тексте «0.5 таблетки» читается как
    опечатка, а поле ввода принимает и то и другое.
    """
    if n is None:
        return ""
    if float(n) == int(float(n)):
        return str(int(float(n)))
    return ("%g" % float(n)).replace(".", ",")


def нормаль(текст):
    """ОДИН способ привести строку к виду, в котором её сравнивают.

    Регистр плюс схлопывание пробельного: заметка человека приходит
    с переносами строк, и без схлопывания запрос «по 1 таблетке»
    не находил бы её, потому что между словами стоит перевод строки,
    а не пробел.

    ИМЕНЕМ, А НЕ ГОЛЫМ `.lower()` НА МЕСТЕ, и довод не в красоте.
    Python `.lower()` кириллицу приводит, а лежащий рядом SQLite —
    НЕТ: `lower()`, `upper()`, `LIKE` и даже `COLLATE NOCASE` у него
    работают только с латиницей (замер — `tests/test_medkit.py`).
    То есть перенос отбора в SQL-запрос выглядел бы одной строкой,
    а поиск при этом молча перестал бы находить «нурофен»
    по «Нурофен». Названная функция ставит на этом пути препятствие:
    `WHERE lower(name) LIKE …` не подставится вместо неё сама собой.

    Вторая половина договора — в браузере: он приводит ЗАПРОС
    тем же способом (`.trim().toLowerCase()`). Разойдись стороны —
    поиск отвечал бы «ничего не нашлось» при живых данных, и это
    сторожит шаг «поиск-регистр-и-кириллица» в `check_medkit_ui.py`.
    """
    return " ".join((текст or "").split()).lower()

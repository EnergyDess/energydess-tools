НАЗВАНИЕ_СТРАНИЦЫ = re.compile(r"(?is)^(.{0,80}?)\s+инструкция по применению")

# ═════════════════════════════════════════════════════════════════════
# ПРОЛОНГИРОВАННОЕ ВЫСВОБОЖДЕНИЕ — ЖЁСТКОЕ ИСКЛЮЧЕНИЕ (BACKLOG №181, A.2)
# ═════════════════════════════════════════════════════════════════════
#
# Сопоставление по дозировке снято (A.1), и без этого признака схема
# от Ретарда встала бы на карточку обычных таблеток. Замер на живых
# страницах Видаля показывает, насколько это разные схемы:
#
#   Необутин, таблетки 100 мг   «по 100-200 мг 3 раза/сут»
#   Необутин Ретард, 300 мг     «по 300 мг 2 раза/сут (с перерывом 12 ч)»
#
# Втрое большая разовая доза и другой интервал. Это ровно тот случай,
# ради которого написано правило «чужая схема хуже её отсутствия».
#
# ПРИЗНАК СЛОВАМИ, А НЕ АББРЕВИАТУРАМИ. Латинские SR/XR/XL/MR/CR/ER/LA
# в список НЕ ВОШЛИ, и это замер, а не осторожность: на 60 страницах
# Видаля (девять препаратов) они не встретились НИ РАЗУ — ни верно,
# ни ложно. Признак, который не срабатывает никогда, пользы не приносит,
# а риск ложного у двухбуквенного токена есть всегда (§6.0.7: не
# выдумывать член множества, которого замер не показал).
#
# ЗАМЕР СЛОВЕСНОГО ПРИЗНАКА, те же 60 страниц: срабатываний ТРИ, все три
# верные — «Необутин Ретард», «Лазолван МАКС» и «Тримедат форте»
# (у двух последних пролонгированное высвобождение написано в описании
# выпуска прямым текстом). Ложных ноль.
ПРОЛОНГ = re.compile(
    r"(?i)(?:пролонгированн|модифицированн|замедленн"
    r"|постепенн\w*\s+высвобожд|контролируем\w*\s+высвобожд"
    r"|длительного\s+действия|ретард|retard|\bдепо\b|депо-)")


def название_страницы(опис):
    """ТОРГОВОЕ НАЗВАНИЕ, которое объявляет сама страница.

    Признак — «<название> инструкция по применению» в описании
    страницы. Замер на 60 страницах Видаля (девять препаратов):
    сработал на ВСЕХ. Запасной путь через `<h1>` пробовали и
    отвергли — там `None` у 33 страниц из 42.

    Нужен затем, что сопоставление по дозировке снято (A.1), а без
    названия «Креон 10000» совпал бы с «Креон 25000» (форма одна,
    вещество одно), «Цетрин» — с «Цетрин Л», «Энтерол» —
    с «Энтеролактис Дуо». Замер: без этой проверки у пяти позиций
    владельца из девяти выбор стал бы неоднозначным.
    """
    м = НАЗВАНИЕ_СТРАНИЦЫ.match(опис or "")
    return м.group(1).strip().replace(chr(0xAE), "").strip() if м else None


def _норма_имени(с):
    return " ".join((с or "").replace(chr(0xAE), " ").split()).strip(" -,.").lower()


def название_совпало(имена, опис):
    """Название страницы — одно из тех, которыми мы её искали.

    Сравнение идёт с `имена_для_поиска`, а не с сырым полем карточки:
    человек пишет «Цетрин таб. п/о 10мг №20», и точное равенство
    не сошлось бы никогда. Чищеное имя при этом уже посчитано —
    второй реализации чистки не заводится.

    Не удалось прочитать название страницы — считаем НЕ совпавшим.
    Пропустить его значило бы вернуться к сопоставлению без названия,
    то есть молча отменить A.1 на той странице, чью разметку мы
    не разобрали (§6.0: где признак не сработал, отказ должен быть
    слышен, а не удобен).
    """
    имя = название_страницы(опис)
    if not имя:
        return False
    н = _норма_имени(имя)
    return any(н == _норма_имени(x) for x in (имена or ()) if x)


def пролонг(текст):
    """Признак пролонгированного (замедленного) высвобождения."""
    return bool(ПРОЛОНГ.search(текст or ""))


def пролонг_совпал(наше_название, опис):
    """Пролонг у страницы и у нас — одинаково, иначе схема чужая.

    Проверяется В ОБЕ СТОРОНЫ: страница-ретард не подходит обычной
    пачке, и обычная страница не подходит пачке ретарда. Второе
    не теоретическое — «Необутин Ретард» человек заведёт под этим же
    именем, и схема обычных таблеток дала бы ему втрое меньшую дозу.
    """
    return пролонг(наше_название) == пролонг(опис)


def раздел_доз_html(текст_html):
    """(заголовок, СЫРАЯ РАЗМЕТКА) раздела о дозировании.

    Признак — ЗАГОЛОВОК, а не класс и не id: класс у чужого сайта
    меняется при первом же редизайне, а заголовок раздела инструкции —
    часть самой инструкции.

    Отдаёт разметку, а не текст, потому что вся структура схемы приёма
    лежит именно в ней: «Взрослые» — это `<P><B><U>…`, а «по 10 мг
    1 раз/сут» — соседний `<P>`. Снять теги первым же действием значило
    бы выбросить единственный источник структуры и остаться перед
    выбором «полотно или догадка о смысле» (постановка A.2).
    """
    for м in re.finditer(r"(?is)<h([1-4])[^>]*>(.{0,160}?)</h\1>", текст_html):
        имя = " ".join(re.sub(r"<[^>]+>", "", м.group(2)).split()).lower()
        имя = html.unescape(имя).replace("®", "").strip()
        if not any(з in имя for з in ЗАГОЛОВКИ_ДОЗ):
            continue
        хвост = текст_html[м.end():]
        след = re.search(r"(?is)<h[1-%s][^>]*>" % м.group(1), хвост)
        тело = хвост[:след.start()] if след else хвост[:20000]
        return имя, тело
    return None, ""


def раздел_доз(текст_html):
    """(заголовок, дословный ПЛОСКИЙ текст) раздела о дозировании.

    Обёртка над `раздел_доз_html`. Оставлена отдельным именем, потому
    что разведка и тесты спрашивают именно текст, а плоское чтение
    разметки — ровно то, с чем сверяется инвариант блоков.
    """
    имя, тело = раздел_доз_html(текст_html)
    return имя, (без_тегов(тело) if тело else "")


def подходит(позиция, страница_html):
    """Страница описывает ИМЕННО эту позицию.

    `позиция` — словарь с ключами `название`, `форма`, `доза`,
    `вещество`. Вещество проверяется, только если оно у нас заполнено:
    в карточке это поле необязательное, и требовать его значило бы
    отказывать тем, кто его не вписал.

    ═══════════════════════════════════════════════════════════════════
    ДОЗИРОВКА БОЛЬШЕ НЕ БЛОКИРУЕТ (BACKLOG №181, A.1)
    ═══════════════════════════════════════════════════════════════════

    Прежнее правило требовало совпадения по форме, ДОЗИРОВКЕ и веществу.
    Владелец опроверг его тремя живыми страницами: схема приёма
    Необутина есть и у Видаля, и у аптечных справочников, а наш экран
    молчал.

    ПОЧЕМУ ПРАВИЛО БЫЛО НЕВЕРНЫМ. Доза считается в МИЛЛИГРАММАХ
    ВЕЩЕСТВА, а не в таблетках, и одна схема покрывает несколько
    выпусков сразу. Замер на странице таблеток Необутина показывает
    это буквально — она сама называет ОБА выпуска:

        «Таблетку 100 мг можно разломить при необходимости на 2 или
         4 части. Таблетку 200 мг можно разломить на 2 части.
         Взрослые и дети старше 12 лет: по 100-200 мг 3 раза/сут.»

    То есть я защищался от подмены, которой не существует: у страницы
    «таблетки 100 мг» и искомых «таблеток 200 мг» схема ОДНА И ТА ЖЕ.

    Вдобавок дозировка сверялась с ОПИСАНИЕМ страницы (короткая строка
    заголовка), а не с её текстом, — «200 мг» в описании нет, хотя
    в инструкции есть. Замер по девяти позициям владельца: `доза`
    не совпала НИ РАЗУ, в том числе у «Креон 10000» против страницы,
    которая так и называется.

    ═══════════════════════════════════════════════════════════════════
    ЧТО ВСТАЛО НА ЕЁ МЕСТО — ДВЕ ПРОВЕРКИ, А НЕ НОЛЬ
    ═══════════════════════════════════════════════════════════════════

    A.1 говорит «названия и формы достаточно», и НАЗВАНИЯ в прежнем
    сопоставлении не было вовсе — оно участвовало только в поиске.
    Сняв дозу и не добавив имя, мы получили бы «Креон 25000» на карточке
    «Креон 10000»: форма одна, вещество одно. Замер: без проверки имени
    у пяти позиций владельца из девяти выбор стал бы неоднозначным
    либо неверным.

    Вторая — `пролонг_совпал` (A.2), жёсткое исключение: у Ретарда
    схема втрое отличается по разовой дозе.

    ДОЗА ОСТАЁТСЯ В ДЕТАЛЯХ, но в решение не входит: её печатает
    разведка, и по ней видно, чем выпуск отличается от искомого.
    """
    плоско = без_тегов(страница_html)
    опис = описание(плоско)
    имена = позиция.get("имена") or имена_для_поиска(позиция.get("название"))
    н = название_совпало(имена, опис)
    ф = форма_совпала(позиция.get("форма"), опис)
    д = доза_совпала(позиция.get("доза"), опис)
    пр = пролонг_совпал(позиция.get("название"), опис)
    # ВЕЩЕСТВО УЧАСТВУЕТ, КОГДА ЕГО ЗНАЮТ ОБЕ СТОРОНЫ (BACKLOG №199).
    # Не заполнено у нас — не проверяем (поле необязательное); не
    # объявлено страницей — тоже не проверяем, и это разбор
    # у `вещество_объявлено`: 12 страниц из 63 блока не имеют, и отказ
    # по незнанию терял ровно те выпуски, что человек держит в руках
    объявлено = вещество_объявлено(плоско)
    в = (вещество_совпало(позиция["вещество"], плоско)
         if (позиция.get("вещество") and объявлено) else True)
    return (н and ф and пр and в), {"название": н, "форма": ф, "доза": д,
                                    "пролонг": пр, "вещество": в,
                                    "вещество_на_странице": объявлено,
                                    "описание": опис}


# ═════════════════════════════════════════════════════════════════════
# РАЗМЕТКА РАЗДЕЛА: ЗАГОЛОВКИ, АБЗАЦЫ, СПИСКИ, ТАБЛИЦЫ
# ═════════════════════════════════════════════════════════════════════
#
# BACKLOG №173, блок A. Выдержка приходила ОДНИМ ПОЛОТНОМ и не читалась:
# «Взрослые По 10 мг (1 таблетка) 1 раз/сут Особые группы пациентов
# Пациенты пожилого возраста …» — доза владельца вперемешку с формулами
# клиренса креатинина и таблицей дозирования при почечной недостаточности.
#
# ПРАВИЛО D.1 ПРОШЛОГО ЗАХОДА НЕ ОСЛАБЛЯЕТСЯ НИ НА ЗНАК. Модель этот
# текст не читает, не разбивает по смыслу, не переставляет и не
# группирует. Причина прежняя и она единственная в проекте: пересказ —
# то место, где выдуманное число опасно и при этом незаметно.
#
# ФОРМАТИРУЕМ РАЗМЕТКОЙ, А НЕ СМЫСЛОМ. Заголовки в источнике УЖЕ
# размечены, просто не тегом h — замер по трём препаратам:
#
#   <P><B><U>Взрослые</U></B></P>            заголовок, уровень 1
#   <P>По 10 мг (1 таблетка) 1 раз/сут.</P>  абзац
#   <P><B>Пациенты пожилого возраста</B></P> заголовок, уровень 2
#   <UL><LI>…</LI></UL>                      список
#   <TABLE><TR><TD>…                         таблица
#
# ПРИЗНАК ЗАГОЛОВКА — «ВЕСЬ АБЗАЦ ВНУТРИ ВЫДЕЛЕНИЯ», а не «есть <b>».
# Разница не педантизм, а замер: у Лазолвана и Тантума жирным выделено
# НАЧАЛО обычного абзаца —
#
#   <P><B>Взрослым</B> рекомендуется принимать по 10 мл 3 раза/сут.</P>
#
# — и признак «есть <b>» объявил бы заголовком ровно ту строку, которая
# несёт искомую дозу: она уехала бы в заголовок и осталась бы без текста
# под собой.
#
# ═════════════════════════════════════════════════════════════════════
# ИНВАРИАНТ: ПЛОСКОЕ ЧТЕНИЕ БЛОКОВ РАВНО ДОСЛОВНОМУ ТЕКСТУ
# ═════════════════════════════════════════════════════════════════════
#
# `плоско(блоки(x)) == без_тегов(x)` ПОСИМВОЛЬНО. Это не тест ради
# теста: разбор — единственное место, где текст дозировки проходит
# через наш код и мог бы измениться молча. Не сошлось — блоков НЕТ
# ВОВСЕ, наружу уходит плоский текст (постановка A.4): плохо
# оформленная дословная выдержка лучше красиво переставленной.
#
# Сегментация ПОВТОРЯЕТ `без_тегов` буквально — перевод строки на
# закрытии p, div, li, tr, h-тегов и на br, всё остальное пробелом.
# Инвариант от этого лишним не становится: он проверяет РЕЗУЛЬТАТ,
# а не намерение, и ловит в том числе подмену в самом хранилище.

_РАЗРЫВ = {"p", "div", "li", "tr",
           "h1", "h2", "h3", "h4", "h5", "h6", "h7", "h8", "h9"}
_ЖИРНЫЕ = {"b", "strong"}
_ПОДЧЁРК = {"u"}
_ЯЧЕЙКИ = {"td", "th"}
_ТОКЕН = re.compile(r"(?is)<(/?)([a-z][a-z0-9]*)[^>]*>|([^<]+)")
_СКРИПТЫ = re.compile(r"(?is)<(script|style)[^>]*>.*?</\1>")


def _норма(с):
    """Пробельное схлопывается — ровно так же, как в `без_тегов`."""
    return " ".join((с or "").split())


class _Разбор:
    """Состояние обхода разметки.

    Классом, а не замыканиями: вложенная функция, меняющая полдюжины
    переменных снаружи через `nonlocal`, читается хуже поля.
    """

    def __init__(self):
        self.из = []
        self.буфер = []          # [(текст, жирный, подчёркнутый)]
        self.жир = 0
        self.подч = 0
        self.список = 0
        # {"строки": [[ячейка, …]], "ряд": [(текст, жирный), …],
        #  "жир": [была ли строка целиком выделена, …]}
        self.таблица = None

    def _снять(self):
        """Накопленная строка плюс ответ, вся ли она внутри выделения."""
        текст = _норма("".join(т for т, _, _ in self.буфер))
        значимые = [(ж, п) for т, ж, п in self.буфер if т.strip()]
        self.буфер = []
        if not текст or not значимые:
            return None, False, False
        return текст, all(ж for ж, _ in значимые), all(п for _, п in значимые)

    def _строка(self):
        """Закрывает строку тем же событием, каким её закрывает `без_тегов`."""
        текст, жир, подч = self._снять()
        if not текст:
            return
        if self.таблица is not None:
            # Текст внутри таблицы, но вне ячейки — подпись либо заголовок
            # колонки в чужой вёрстке. Прижимаем к ряду, иначе он выпал бы
            # из инварианта молча
            self.таблица["ряд"].append((текст, жир))
        elif жир and подч:
            self.из.append({"вид": "заголовок", "уровень": 1, "текст": текст})
        elif жир:
            self.из.append({"вид": "заголовок", "уровень": 2, "текст": текст})
        elif self.список:
            self.из.append({"вид": "пункт", "текст": текст})
        else:
            self.из.append({"вид": "абзац", "текст": текст})

    def _ряд(self):
        """Закрывает строку таблицы.

        ШАПКА ОПОЗНАЁТСЯ ПО РАЗМЕТКЕ, А НЕ ПО НОМЕРУ СТРОКИ. У Видаля
        заголовки колонок набраны `<TD><B>…</B></TD>`, то есть источник
        сам говорит, какая строка шапка. «Первая строка — всегда шапка»
        было бы догадкой о смысле, и на таблице без заголовков она
        выделила бы жирным первую строку ДАННЫХ.
        """
        текст, жир, _ = self._снять()
        if текст:
            self.таблица["ряд"].append((текст, жир))
        ряд = [(т, ж) for т, ж in self.таблица["ряд"] if т]
        self.таблица["ряд"] = []
        if ряд:
            self.таблица["строки"].append([т for т, _ in ряд])
            self.таблица["жир"].append(all(ж for _, ж in ряд))

    def _закрыть_таблицу(self):
        if self.таблица is None:
            return
        self._ряд()
        if self.таблица["строки"]:
            self.из.append({"вид": "таблица",
                            "строки": self.таблица["строки"],
                            # Шапка есть, только если ПЕРВАЯ строка целиком
                            # выделена. Ниже по таблице выделение
                            # не проверяется: у Видаля жирным набрана
                            # и часть значений
                            "шапка": bool(self.таблица["жир"])
                                     and self.таблица["жир"][0]})
        self.таблица = None

    def шаг(self, закр, тег, текст):
        """Один токен разметки.

        РАЗРЫВ СТРОКИ СТАВИТСЯ ТАМ ЖЕ, ГДЕ ЕГО СТАВИТ `без_тегов`,
        а ЛЮБОЙ ДРУГОЙ ТЕГ ДАЁТ ПРОБЕЛ — и второе не мелочь. Первая
        версия склеивала соседние куски вплотную, и инвариант поймал
        это на двух страницах из трёх: «Лазолван ®» превращался
        в «Лазолван®», «КК сыворот.» в «ККсыворот.». Ни то ни другое
        не видно глазом в блоке текста, а посимвольное сравнение
        назвало обе строки сразу.
        """
        if текст is not None:
            self.буфер.append((html.unescape(текст), self.жир > 0,
                               self.подч > 0))
            return
        # Тег на месте текста — пробел. Разрыв строки ниже сам его съест
        self.буфер.append((" ", False, False))
        if тег == "br":
            self._строка()
            return
        if not закр:
            if тег in _ЖИРНЫЕ:
                self.жир += 1
            elif тег in _ПОДЧЁРК:
                self.подч += 1
            elif тег == "table":
                self.таблица = {"строки": [], "ряд": [], "жир": []}
            elif тег in ("ul", "ol"):
                self.список += 1
            return
        if тег in _ЖИРНЫЕ:
            self.жир = max(0, self.жир - 1)
        elif тег in _ПОДЧЁРК:
            self.подч = max(0, self.подч - 1)
        elif тег == "table":
            self._закрыть_таблицу()
        elif тег in ("ul", "ol"):
            self.список = max(0, self.список - 1)
        elif self.таблица is not None and тег in _ЯЧЕЙКИ:
            # Ячейка — не разрыв строки: `без_тегов` ставит здесь пробел,
            # и `плоско` склеивает ячейки ряда через пробел. Совпадает
            текст_я, жир_я, _ = self._снять()
            if текст_я:
                self.таблица["ряд"].append((текст_я, жир_я))
        elif self.таблица is not None and тег == "tr":
            self._ряд()
        elif тег in _РАЗРЫВ:
            self._строка()

    def конец(self):
        self._строка()
        self._закрыть_таблицу()
        return self.из


def блоки(кусок):
    """Раздел о дозировании как последовательность блоков разметки.

    Вид блока — `заголовок` (с уровнем), `абзац`, `пункт` списка либо
    `таблица` со строками ячеек. Текст в каждом дословный.

    Пустой список означает «разметки не хватило»; наружу тогда уходит
    плоский текст, и это законный исход, а не сбой.
    """
    состояние = _Разбор()
    for м in _ТОКЕН.finditer(_СКРИПТЫ.sub(" ", кусок or "")):
        состояние.шаг(м.group(1), (м.group(2) or "").lower(), м.group(3))
    return состояние.конец()


def плоско(блоки_):
    """Блоки обратно в плоский текст — ровно тот, что даёт `без_тегов`.

    ЕДИНСТВЕННОЕ, ЧТО ДОКАЗЫВАЕТ ЧЕСТНОСТЬ ФОРМАТИРОВАНИЯ. Сравнение
    посимвольное; расхождение означает, что разбор потерял, склеил или
    переставил текст, — и тогда блоков не будет вовсе.
    """
    строки = []
    for б in блоки_ or ():
        if б.get("вид") == "таблица":
            строки += [_норма(" ".join(р)) for р in б.get("строки") or ()]
        else:
            строки.append(_норма(б.get("текст")))
    return "\n".join(с for с in строки if с)


def разметить(кусок):
    """(плоский текст, блоки) — блоки пусты, если инвариант не сошёлся.

    ОДНА ДВЕРЬ НА ОБЕ СТОРОНЫ: сервер и разведка `check_medkit_dosage`
    зовут её же. Держи разведка свой разбор — её «сошлось» относилось бы
    к поведению, отличному от боевого (§6.0.7).
    """
    текст = без_тегов(кусок)
    из = блоки(кусок)
    return (текст, из) if плоско(из) == текст else (текст, [])


# ── СТРОКА СО СХЕМОЙ ПРИЁМА: ПРИЗНАК ПО ФОРМЕ ЗАПИСИ ─────────────────
#
# BACKLOG №177, блок B.1. Владелец увидел выдержку Энтерола простынёй,
# в которой не найти «по 1-2 капсулы 2 раза/сут»: заголовков
# в источнике нет, и разметке нечего было подхватить.
#
# ПРАВИЛО ДОСЛОВНОСТИ НЕ ОСЛАБЛЯЕТСЯ НИ НА ЗНАК. Строки НЕ переставляются,
# не пересказываются и не группируются; выделяется та, что стоит НА СВОЁМ
# МЕСТЕ. Признак — про ФОРМУ ЗАПИСИ, а не про смысл, и это не педантизм:
# «разбей по смыслу» означало бы, что доза может оказаться не под своим
# заголовком, а проверить это будет некому.
#
# ТРИ ЧАСТИ В ОДНОЙ СТРОКЕ, И ВСЕ ТРИ ОБЯЗАТЕЛЬНЫ:
#     КОЛИЧЕСТВО   10   1-2   2.5   1/2
#   + ЕДИНИЦА      мг   мл    капсулы   впрыскивания
#   + ЧАСТОТА      1 раз/сут   3 раза в день   каждые 6 ч
#
# Частота — та часть, что отсекает ложное. Без неё выделились бы:
#   «Иногда начальной дозы 5 мг (1/2 таблетки) может быть достаточно»
#   «1 доза (1 впрыскивание) соответствует 0.255 мг бензидамина»
#   «КК (мл/мин) = [140 - возраст (годы)] × масса тела (кг)/72»
# — три строки, из которых ни одна не говорит, сколько и как часто пить.
# Последняя хуже всех: формула клиренса рядом с дозой читается как доза.
#
# СЧИТАЕТСЯ ПРИ ЧТЕНИИ, А НЕ ПРИ ЗАПИСИ. Иначе выдержки, сохранённые
# до этой правки, остались бы без выделения навсегда, а правка признака
# требовала бы перетянуть их все у Видаля.

_КОЛИЧЕСТВО = r"\d+(?:[.,]\d+)?(?:\s*[-–—/]\s*\d+(?:[.,]\d+)?)?"

# Единица ИМЕННО ДОЗЫ. «мин», «дл», «кг», «лет», «дней» сюда не входят
# намеренно: они стоят в формулах и в сроках лечения, а не в схеме.
_ЕДИНИЦА_ДОЗЫ = (
    r"мг|мл|мкг|г|ЕД|МЕ|"
    r"таблет\w*|капсул\w*|капл\w*|доз\w*|пакетик\w*|саше|"
    r"впрыскиван\w*|ингаляц\w*|суппозитор\w*|свеч\w*|ампул\w*|"
    r"мерн\w+\s+ложк\w*|чайн\w+\s+ложк\w*|столов\w+\s+ложк\w*"
)

ДОЗА = re.compile(r"(?i)(?<![\w.,])(%s)\s*(%s)(?![\w-])"
                  % (_КОЛИЧЕСТВО, _ЕДИНИЦА_ДОЗЫ))

# ЧАСТОТА. Формы взяты С ЖИВЫХ СТРАНИЦ Видаля, а не придуманы:
# «1 раз/сут», «3 раза/сут», «2-3 раза/сут», «2 раза в день»,
# «каждые 6 ч». `сут` без точки — так пишет источник.
ЧАСТОТА = re.compile(
    r"(?i)(?:"
    r"%s\s*раз(?:а|ов)?\s*(?:/|в\s+)\s*(?:сут\w*|день|дня|дней|нед\w*|час\w*|мес\w*)"
    r"|раз(?:а|ов)?\s*(?:/|в\s+)\s*(?:сут\w*|день|нед\w*)"
    r"|каждые\s+%s\s*(?:ч%s|час\w*|мин\w*|дн\w*|сут\w*)"
    r"|\d+\s*[xх×]\s*/?\s*сут\w*"
    r")" % (_КОЛИЧЕСТВО, _КОЛИЧЕСТВО, _Г))


def строка_со_схемой(текст):
    """Похожа ли строка на схему приёма ПО ФОРМЕ ЗАПИСИ.

    Три части сразу: количество, единица дозы и частота приёма.
    Разбор — `check_medkit_dosage.py --схема`, там же замер по каждому
    препарату построчно.
    """
    т = текст or ""
    return bool(ДОЗА.search(т)) and bool(ЧАСТОТА.search(т))


def схемные(блоки_):
    """Номера блоков, которые ЯВЛЯЮТСЯ схемой приёма.

    Заголовки не берутся никогда: заголовок с числом («Дети от 2 до 6
    лет») дозой не является, а выделять его значило бы выделить
    не строку с дозой, а подпись над ней.
    """
    из = set()
    for i, б in enumerate(блоки_ or ()):
        if б.get("вид") in ("заголовок", "таблица"):
            continue
        if строка_со_схемой(б.get("текст")):
            из.add(i)
    return из


def сгиб(блоки_):
    """С какого блока прячем под «Показать полностью».

    ГРАНИЦА БЕРЁТСЯ ИЗ РАЗМЕТКИ, А НЕ ИЗ ДЛИНЫ И НЕ ИЗ СМЫСЛА
    (постановка A.3): это ВТОРОЙ заголовок верхнего уровня, то есть
    конец первого раздела инструкции. Владельцу почти всегда нужны
    первые строки («Взрослые — по 10 мг 1 раз/сут»), а пожилые,
    почечная недостаточность и формулы нужны редко.

    ВЕРХНИЙ УРОВЕНЬ ОТНОСИТЕЛЬНЫЙ. У Цетрина заголовки есть и
    с подчёркиванием, и без; у Лазолвана только без — и там верхним
    становится второй уровень. Привязка к «уровню 1» намертво оставила
    бы Лазолван без сгиба вовсе.

    ВИСЯЧИЙ ЗАГОЛОВОК В КОНЦЕ ВИДИМОЙ ЧАСТИ СДВИГАЕТ ГРАНИЦУ ВЛЕВО:
    заголовок, под которым ничего не показано, читается как потерянный
    текст. Замер на Лазолване — без этого видимая часть кончалась
    словом «Дети» и пустотой под ним.

    `None` — сгиба нет: заголовков верхнего уровня меньше двух,
    и прятать нечего.
    """
    номера = [i for i, б in enumerate(блоки_ or ())
              if б.get("вид") == "заголовок"]
    свои = []
    if номера:
        верх = min(блоки_[i]["уровень"] for i in номера)
        свои = [i for i in номера if блоки_[i]["уровень"] == верх]
    if len(свои) < 2:
        return _сгиб_без_заголовков(блоки_)
    к = свои[1]
    while к > 0 and блоки_[к - 1].get("вид") == "заголовок":
        к -= 1
    return к if 0 < к < len(блоки_) else None


def _сгиб_без_заголовков(блоки_):
    """ГРАНИЦА У ВЫДЕРЖКИ БЕЗ ЗАГОЛОВКОВ — ПО ПОСЛЕДНЕЙ СТРОКЕ СХЕМЫ.

    BACKLOG №177, блок B.2. У Энтерола заголовков в источнике нет
    ни одного, и сгиба не было вовсе: вся простыня сразу, «Показать
    полностью» не рисуется.

    ПОСТАНОВКА ГОВОРИЛА «первый блок показывается, остальное под
    раскрытие», И БУКВАЛЬНО ЭТО ВРЕДНО. Замер на Энтероле: первый
    блок — «Для приема внутрь.», а обе строки с дозой стоят третьей
    и четвёртой. Сгиб после первого спрятал бы РОВНО ТО, ради чего
    окно открывают. Эскиз владельца это и показывает: там видно пять
    абзацев и кнопка под ними, а не один абзац.

    Поэтому граница считается тем же признаком, что и выделение
    (`схемные`): видно всё по ПОСЛЕДНЮЮ строку схемы включительно,
    под сгиб уходят противопоказания, предупреждения и сроки лечения.
    Ни длина, ни смысл в решении не участвуют — правило A.3 в силе.

    Строк схемы нет ни одной — сгиба НЕТ. Резать по длине значило бы
    выдумать границу, которой в инструкции не существует; законный
    исход, тот же, что у Тантума в задаче 173.
    """
    с = схемные(блоки_)
    if not с:
        return None
    к = max(с) + 1
    # ВИСЯЧИЙ ЗАГОЛОВОК СДВИГАЕТ ГРАНИЦУ ВПРАВО, а не влево, как
    # в основном правиле: там граница стоит ПЕРЕД разделом, здесь —
    # ПОСЛЕ строки схемы, и заголовок сразу за ней уехал бы под сгиб
    # один, без своего текста. Забираем его вниз вместе с текстом.
    while к < len(блоки_) and блоки_[к].get("вид") == "заголовок":
        к += 1
    return к if 0 < к < len(блоки_) else None

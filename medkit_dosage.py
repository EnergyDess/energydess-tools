def чем_отличается(страница_html):
    """ЧТО ЗА ВЫПУСК ОПИСАН НА ЭТОЙ СТРАНИЦЕ — короткой строкой человеку.

    Нужна ровно в одном месте: когда страницы нашлись, а подошедших нет.
    Прежний отказ говорил «не совпали форма и дозировка» — верно
    и бесполезно, потому что из него не следует ни что справочник нашёл,
    ни почему мы молчим (постановка B.4).

    БЕРЁТСЯ ХВОСТ ОПИСАНИЯ, А НЕ ПЕРЕСКАЗ. Строка описания устроена как
    «<Название> инструкция по применению: … – описание <Latin> таблетки
    100 мг: 10, 15 … шт. (44740)», и всё нужное стоит после слова
    «описание» и латинского имени. Ни одного своего слова здесь
    не добавляется — правило дословности не знает исключений даже
    в тексте отказа.
    """
    опис = описание(без_тегов(страница_html or ""))
    поз = опис.find("– описание ")
    if поз < 0:
        поз = опис.find("- описание ")
    хвост = опис[поз + len("– описание "):] if поз >= 0 else опис
    # Латинское имя препарата в начале хвоста человеку не говорит ничего
    хвост = re.sub(r"^[A-Za-z][A-Za-z \-]{0,40} ", "", хвост).strip()
    # Артикул в скобках и перечень фасовок — тоже шум: спрашивают
    # «какой это выпуск», а не «по скольку штук в пачке»
    хвост = re.split(r": |\s\(\d+\)", хвост)[0].strip()
    # 100, а не 70: у «таблеток с пролонгированным высвобождением,
    # покрытых плёночной оболочкой, 300 мг» на семидесятом знаке
    # обрезается ровно ДОЗИРОВКА — то единственное, чем этот выпуск
    # отличается от искомого
    return хвост[:100]



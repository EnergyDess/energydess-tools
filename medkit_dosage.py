import html
import re

# ── ИСТОЧНИК ─────────────────────────────────────────────────────────
#
# ОДНОЙ КОНСТАНТОЙ, по той же причине, что `СПРАВОЧНИК_ВЕЩЕСТВА`
# в main.py: адрес чужого сайта на месте вызова нельзя ни грепнуть,
# ни поменять решением владельца.
#
# Видаль выбран не наугад: он ПРОШЁЛ ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ прошлого
# захода (три настоящих вещества дают содержательный ответ, заведомая
# бессмыслица — «ничего не найдено» и вчетверо более короткую страницу),
# тогда как РЛС его не прошёл: там «не найдено» показывается и на
# настоящем веществе, то есть признак не разделяет.
ИСТОЧНИК_ИМЯ = "Видаль"
ИСТОЧНИК_БАЗА = "https://www.vidal.ru"
ИСТОЧНИК_ПОИСК = ИСТОЧНИК_БАЗА + "/search?t=all&q=%s"

# Сколько страниц выдачи разбираем. Не «все»: у распространённого
# названия их бывает десяток, и каждая — отдельный запрос к чужому
# сайту. Шесть покрывает все замеренные случаи (у «Лазолвана» их 8,
# нужная — первая).
СТРАНИЦ_МАКС = 6

# ── КАК СПРАВОЧНИК НАЗЫВАЕТ НАШИ ФОРМЫ ───────────────────────────────
#
# ПЕРЕЧЕНЬ ТУТ ЗАКОННЫЙ (§6.0.7): множество наших форм конечно
# и объявлено в `medkit_defs.ФОРМЫ`, новый член появляется только
# решением о коде. Сверка ключей — `сверить_формы`, и она обязательна:
# опечатка иначе молча означала бы «эта форма не сопоставляется никогда».
#
# Синонимы — не наша выдумка, а замер: Лазолван-сироп у Видаля называется
# «раствор для приема внутрь», и поиск нашего слова «сироп» не находил
# его вовсе.
СИНОНИМЫ_ФОРМ = {
    "tablet": ("таблетк",),
    "capsule": ("капсул",),
    "suppository": ("суппозитор", "свеч"),
    "ampoule": ("ампул", "раствор для инъекц", "раствор для внутривен"),
    "sachet": ("порошок", "гранул", "пакетик"),
    "syrup": ("сироп", "раствор для приема внутрь", "раствор для приёма внутрь"),
    "drops": ("капли",),
    "spray": ("спрей", "аэрозол"),
    "powder": ("порошок", "гранул"),
    "ointment": ("мазь",),
    "gel": ("гель",),
    "cream": ("крем",),
}

# ЗАГОЛОВОК РАЗДЕЛА. Перечень формулировок, а не одна: инструкции
# называют его по-разному, и это не наша выдумка — так пишут сами
# производители («Режим дозирования» у Видаля, «Способ применения
# и дозы» в бумажном вкладыше).
ЗАГОЛОВКИ_ДОЗ = ("режим дозирования", "способ применения и дозы",
                 "способ применения", "дозирование")

АКТИВНОЕ = re.compile(r"(?i)активное вещество:\s*(.{0,80})")
ЧИСЛО_С_ЕДИНИЦЕЙ = re.compile(r"(\d+(?:[.,]\d+)?)\s*(мг|мл|мкг|г|ме)\b")


def сверить_формы():
    """Ключи словаря — те же, что в `medkit_defs`.

    Опечатка в ключе не сломала бы ничего заметного: форма просто
    перестала бы сопоставляться никогда, а наружу это выглядело бы
    как «у этого препарата схемы приёма нет» — немой отказ.
    """
    import medkit_defs
    наши = {ф["id"] for ф in medkit_defs.ФОРМЫ}
    лишние = sorted(set(СИНОНИМЫ_ФОРМ) - наши)
    без = sorted(наши - set(СИНОНИМЫ_ФОРМ))
    if лишние or без:
        raise RuntimeError(
            "словарь форм справочника разошёлся с medkit_defs: "
            "лишние %s, без синонимов %s" % (лишние or "—", без or "—"))
    return True


# Что в названии карточки НЕ является названием препарата. Человек
# пишет так, как напечатано на коробке: «Цетрин таб. п/о 10мг №20».
# Справочник по такой строке не находит ничего — замер: запрос целиком
# даёт ноль страниц, запрос «Цетрин» даёт три.
# ГРАНИЦЫ СЛОВА ОБЯЗАТЕЛЬНЫ, И ЗАПИСАНЫ ОНИ КОДОМ. Без границы «мг»
# срабатывает внутри слова, и «Мгновение» обрезалось бы до пустой
# строки — препарат с таким названием молча перестал бы искаться.
#
# Литерал собирается из частей, а `\b` подставляется через `chr(92)`:
# первая версия этой строки уехала в файл с НАСТОЯЩИМ символом
# BACKSPACE вместо границы слова — глазами в исходнике его не видно,
# регулярка выглядела рабочей и молча не отсекала ничего. Ровно та же
# ловушка, что с U+2028 в §2.6, и лечится тем же: где знак не виден
# глазом, он объявляется кодом.
_Г = chr(92) + "b"          # граница слова в регулярке
_СЛОВА_ФОРМ = ("мг|мл|мкг|шт|доз|таблетки|капсулы|сироп|спрей|капли|"
               "мазь|гель|крем|порошок|свечи|ампулы|пакетики")
ХВОСТ_НАЗВАНИЯ = re.compile(
    "(?i)" + chr(92) + "s*(?:" + chr(92) + "d|№|табл?" + chr(92) + ".|"
    "капс" + chr(92) + ".|п/о|амп" + chr(92) + ".|фл" + chr(92) + ".|"
    + _Г + "(?:" + _СЛОВА_ФОРМ + ")" + _Г + ").*$")


def имя_для_поиска(название):
    """Торговое название без дозировки, количества и сокращений формы.

    ОТРЕЗАЕМ, А НЕ ПЕРЕПИСЫВАЕМ: всё, что стоит после первой цифры или
    служебного сокращения, к названию отношения не имеет. Обратное —
    попытка угадать, что человек имел в виду, а угадывать здесь нечего.

    Пустой остаток означает, что искать не по чему: название вида
    «500 мг» это не название.
    """
    чисто = ХВОСТ_НАЗВАНИЯ.sub("", (название or "").strip()).strip(" -–,.")
    return чисто


def без_тегов(кусок):
    кусок = re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", " ", кусок)
    кусок = re.sub(r"(?i)<br\s*/?>", "\n", кусок)
    кусок = re.sub(r"(?i)</(p|div|li|tr|h\d)>", "\n", кусок)
    кусок = re.sub(r"<[^>]+>", " ", кусок)
    кусок = html.unescape(кусок)
    строки = [" ".join(с.split()) for с in кусок.split("\n")]
    return "\n".join(с for с in строки if с)


def ссылки_поиска(текст_html):
    """Адреса страниц препаратов из выдачи поиска.

    Список, а не первая: у одного названия бывает несколько форм,
    и выбирать между ними надо ПО ФОРМЕ, а не по порядку в выдаче.
    """
    из, видел = [], set()
    for u in re.findall(r'href="(/drugs/[^"#?]+)"', текст_html):
        # `/drugs/firm/`, `/drugs/company/` — производители, не препараты
        if u in видел or re.search(r"/drugs/(firm|company|products)/", u):
            continue
        видел.add(u)
        из.append(u)
    return из[:СТРАНИЦ_МАКС]


def описание(плоско):
    """Первая строка страницы — «<Название> <форма> <дозировка>».

    Именно она, а не весь текст: форма и дозировка стоят там рядом
    и всегда. По всему тексту совпадает что угодно (замер: «Цетрин Л»
    5 мг прошёл сверку с искомыми 10 мг).
    """
    первая = плоско.split("\n")[0] if плоско else ""
    for метка in (" - справочник препаратов", " | Расширенный поиск",
                  " - справочник лекарств"):
        поз = первая.find(метка)
        if поз > 0:
            первая = первая[:поз]
    return первая.strip()


def числа(текст):
    """Числа с единицей, приведённые к одному виду.

    ТОЧКА И ЗАПЯТАЯ — ОДНО И ТО ЖЕ. Замер: доза спрея записана у нас
    «0.255 мг», у Видаля «0.255 мг/1 доза», а первая версия пробы искала
    «0,255 мг» с запятой и не находила. Разделитель дробной части
    в чужом тексте — не наше дело.
    """
    return {(м.group(1).replace(",", "."), м.group(2))
            for м in ЧИСЛО_С_ЕДИНИЦЕЙ.finditer((текст or "").lower())}


def доза_совпала(искомая, опис):
    """ВСЕ числа искомой дозировки нашлись в описании страницы.

    Все, а не любое: «15 мг/5 мл» — это два числа, и совпадение одного
    означало бы, что «15 мг/10 мл» тоже подходит.
    """
    надо = числа(искомая)
    return bool(надо) and надо <= числа(опис)


def вещество_совпало(искомое, плоско):
    """Действующее вещество страницы — то же, что у нашей позиции.

    ДВА УСЛОВИЯ, и второе не менее важно первого: имя ищется
    в объявленном блоке активного вещества И ПО ГРАНИЦЕ СЛОВА.
    Подстрокой «цетиризин» находится внутри «левоцетиризин» — то есть
    сопоставление выбирало препарат с другим действующим веществом.
    Поймано отрицательным контролем, а не чтением.
    """
    м = АКТИВНОЕ.search(плоско or "")
    блок = (м.group(1) if м else "").lower()
    if not блок or not искомое:
        return False
    return bool(re.search(r"(?<![а-яёa-z])" + re.escape(искомое.lower())
                          + r"(?![а-яёa-z])", блок))


def форма_совпала(наша_форма, опис):
    слова = СИНОНИМЫ_ФОРМ.get(наша_форма)
    if not слова:
        return False
    низ = (опис or "").lower()
    return any(с in низ for с in слова)


def раздел_доз_html(текст_html):
    """(заголовок, СЫРАЯ РАЗМЕТКА) раздела о дозировании.

    Признак — ЗАГОЛОВОК, а не класс и не id: класс у чужого сайта
    меняется при первом же редизайне, а заголовок раздела инструкции —
    часть самой инструкции.

    Отдаёт разметку, а не текст, потому что вся структура схемы приёма
    лежит именно в ней: «Взрослые» — это `<P><B><U>…`, а «по 10 мг
    1 раз/сут» — соседний `<P>`. Снять теги первым же действием значило
    бы выбросить единственный источник структуры и остаться перед
    выбором «полотно или догадка о смысле» (постановка A.2).
    """
    for м in re.finditer(r"(?is)<h([1-4])[^>]*>(.{0,160}?)</h\1>", текст_html):
        имя = " ".join(re.sub(r"<[^>]+>", "", м.group(2)).split()).lower()
        имя = html.unescape(имя).replace("®", "").strip()
        if not any(з in имя for з in ЗАГОЛОВКИ_ДОЗ):
            continue
        хвост = текст_html[м.end():]
        след = re.search(r"(?is)<h[1-%s][^>]*>" % м.group(1), хвост)
        тело = хвост[:след.start()] if след else хвост[:20000]
        return имя, тело
    return None, ""


def раздел_доз(текст_html):
    """(заголовок, дословный ПЛОСКИЙ текст) раздела о дозировании.

    Обёртка над `раздел_доз_html`. Оставлена отдельным именем, потому
    что разведка и тесты спрашивают именно текст, а плоское чтение
    разметки — ровно то, с чем сверяется инвариант блоков.
    """
    имя, тело = раздел_доз_html(текст_html)
    return имя, (без_тегов(тело) if тело else "")


def подходит(позиция, страница_html):
    """Страница описывает ИМЕННО эту позицию: форма, доза и вещество.

    `позиция` — словарь с ключами `форма`, `доза`, `вещество`.
    Вещество проверяется, только если оно у нас заполнено: в карточке
    это поле необязательное, и требовать его значило бы отказывать
    тем, кто его не вписал.
    """
    плоско = без_тегов(страница_html)
    опис = описание(плоско)
    ф = форма_совпала(позиция.get("форма"), опис)
    д = доза_совпала(позиция.get("доза"), опис)
    в = (вещество_совпало(позиция["вещество"], плоско)
         if позиция.get("вещество") else True)
    return (ф and д and в), {"форма": ф, "доза": д, "вещество": в,
                             "описание": опис}



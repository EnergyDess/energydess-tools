def выбрать(подошедшие, искомая_доза):
    """КАКУЮ ИЗ ПОДОШЕДШИХ СТРАНИЦ ПОКАЗЫВАТЬ — ОДНО МЕСТО НА ДВОИХ.

    `подошедшие` — список пар (ключ, html) уже прошедших `подходит`.
    Отдаёт (ключ, вид), где вид — один из:

        ""              выбрана однозначно, ключ годен
        "нет_раздела"   ни у одной страницы раздела нет
        "неоднозначно"  схемы разные, и дозировка их не различает

    ═══════════════════════════════════════════════════════════════════
    ПОЧЕМУ ФУНКЦИЕЙ, А НЕ НА МЕСТЕ ВЫЗОВА

    Потребителей два — сервер и разведка, — и это ровно тот случай,
    что уже описан у самого сопоставления: держи разведка свой выбор,
    её «подошло 3, ВЫБОР НЕОДНОЗНАЧЕН» относилось бы к поведению,
    которого на бою нет. Замер на «Лазолване» показал это буквально:
    разведка печатала неоднозначность, а сервер показывал схему.

    ═══════════════════════════════════════════════════════════════════
    ТРИ ПРАВИЛА, И КАЖДОЕ ЗАМЕРЕНО

    1. СХЕМЫ СОВПАЛИ ДОСЛОВНО — показываем (A.3). Справочник держит
       один препарат несколькими карточками по регистрационным
       удостоверениям разных производителей, и раздел о дозировании
       у них ОДИН И ТОТ ЖЕ: «Нурофен» — две страницы, текст совпал
       посимвольно (1112 знаков); у «Полисорб МП» таких шесть.

    2. СХЕМЫ РАЗНЫЕ — РАЗЛИЧАЕМ ДОЗИРОВКОЙ. Это НЕ возврат прежнего
       правила и не ослабление A.1: дозировка не пускает и не отвергает
       в одиночку, она работает ТОЛЬКО здесь — где имя, форма
       и вещество уже сошлись у нескольких страниц. Найдено РЕГРЕССОМ:
       «Лазолван» потерял схему (929 знаков → отказ), потому что у него
       три страницы одного имени и формы с разной концентрацией.

    3. ОСТАЛОСЬ БОЛЬШЕ ОДНОЙ ЛИБО НИ ОДНОЙ — ОТКАЗ. Выбирать наугад
       между двумя схемами нельзя.

    СТРАНИЦЫ БЕЗ РАЗДЕЛА В СРАВНЕНИИ НЕ УЧАСТВУЮТ: показывать там
    нечего, а блокировать ими согласный ответ остальных значило бы
    отказывать из-за пустой карточки (замер: у «Солодки сиропа» одна
    такая из шести).
    """
    тексты = {}
    for ключ, html_ in подошедшие:
        _з, кусок = раздел_доз_html(html_)
        текст, _б = разметить(кусок) if кусок else ("", None)
        if текст.strip():
            тексты.setdefault(текст, ключ)
    if not тексты:
        return None, "нет_раздела"
    if len(тексты) == 1:
        return тексты[next(iter(тексты))], ""
    годные = {к for к, h in подошедшие
              if доза_совпала(искомая_доза, описание(без_тегов(h)))}
    свои = {т for т, к in тексты.items() if к in годные}
    if len(свои) == 1:
        только = next(iter(свои))
        return тексты[только], ""
    return None, "неоднозначно"



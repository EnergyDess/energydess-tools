def по_имени(имя):
    """Источник по его имени — для чтения того, что уже лежит в базе.

    Незнакомое имя даёт `None`, и вызывающий обязан это различать:
    в базе лежат записи, снятые до появления второго источника, и у них
    в метке стоит «Видаль».
    """
    for и in ПОРЯДОК:
        if и.имя == имя:
            return и
    return None

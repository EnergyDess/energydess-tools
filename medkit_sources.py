# ═════════════════════════════════════════════════════════════════════
# WER.RU — СВОЙ РАЗБОР
# ═════════════════════════════════════════════════════════════════════
#
# ЗАМЕР ВЁРСТКИ 2026-09-04, четыре живые карточки. Отличий от Видаля
# ТРИ, и каждое поймано замером, а не прочитано в чужом коде:
#
#   1. ЗАГОЛОВОК ЛЕЖИТ СНАРУЖИ БЛОКА. У Видаля заголовок раздела стоит
#      ВНУТРИ своего блока, и конец считается «до закрывающего минус
#      первого» (`_до_конца_блока`). Здесь иначе: заголовок h4, а следом
#      ОТДЕЛЬНЫЙ блок с текстом. То есть раздел — это СОДЕРЖИМОЕ
#      ПЕРВОГО блока ПОСЛЕ заголовка.
#
#      Правило Видаля, применённое сюда, тащит остаток страницы: замер
#      дал у показаний 7363 знака при полезных 588, у схемы 6738 при
#      1774. Ровно то число «7363 знака мусора», которое назвал заход
#      234 и которое считалось свойством ИСТОЧНИКА, — а это свойство
#      НАШЕГО правила, применённого не к той вёрстке.
#
#   2. НАЗВАНИЕ И ФОРМА — В ЗАГОЛОВКЕ h1, а не в первой строке
#      документа: «Цитрамон П таблетки 20 шт. Фармстандарт-Лексредства».
#
#   3. ЗАГОЛОВКИ ДУБЛИРУЮТСЯ. Замер: «Способ применения, курс
#      и дозировка» встречается на карточке ДВАЖДЫ, «Показания» —
#      тоже. Текст у пар СОВПАДАЕТ побайтно, то есть берётся первое
#      вхождение и второе не значит ничего. Признак «первое совпадение»
#      тут не удача, а решение: разойдись они — мы возьмём то, что
#      стоит выше, а это видимая часть страницы.
#
# ЧЕГО У ИСТОЧНИКА НЕТ, И ЭТО НАЗВАНО. Строки описания выпуска в том
# виде, в каком её даёт Видаль («… – описание Citramon таблетки 100 мг:
# 10, 15 шт.»), здесь не существует: форма и количество стоят в h1
# вперемешку с производителем. Поэтому описанием служит сам h1.
_ЗАГОЛОВОК = re.compile(r"(?is)<h([1-6])[^>]*>(.{0,400}?)</h\1>")
_ДИВ = re.compile(r"(?is)<(/?)div\b[^>]*>")
_H1 = re.compile(r"(?is)<h1[^>]*>(.{0,400}?)</h1>")

# ССЫЛКА НА КАРТОЧКУ. Путь `/catalog/`, а не `/product/`: замер
# 2026-09-03 (BACKLOG №239) — по старому пути HTTP 404, карточки
# переехали. Слэш на конце обязателен, и нашла это ПРОБА, а не чтение:
# без него регулярка находит ноль на живой выдаче в 202 КБ.
_КАРТОЧКА = re.compile(r'href="(/catalog/[a-z0-9_-]{4,}/?)"', re.I)

# Как источник называет блок действующего вещества. Замер 2026-09-04:
# заголовок «Действующее вещество» есть на всех четырёх живых карточках.
# ЗАХОД 234 УТВЕРЖДАЛ, ЧТО БЛОКА НЕТ ВОВСЕ, и это опровергнуто.
_ЗАГ_ВЕЩЕСТВА = ("действующее вещество",)

# ═════════════════════════════════════════════════════════════════════
# ЗАГОЛОВКИ РАЗДЕЛОВ — СВОЙСТВО ВЁРСТКИ, А НЕ ОБЩЕЕ ПРАВИЛО
# ═════════════════════════════════════════════════════════════════════
#
# НАШЁЛ ЭТО ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ, А НЕ ЧТЕНИЕ. Первая версия
# переходника брала `_общее.ЗАГОЛОВКИ_ДОЗ` для ОБОИХ источников,
# и подлог «у Видаля сменился заголовок раздела» СЛОМАЛ РАЗБОР
# И У WER.RU: знаков раздела 2852 -> 0, бед 4. То есть переходники
# выглядели независимыми и не были ими.
#
# Цена этого не теоретическая: правь кто-нибудь список под вёрстку
# одного источника — и молча менял бы поведение второго.
#
# ЗАМЕР 2026-09-04, ЧЕМ ОНИ РАЗЛИЧАЮТСЯ. У Видаля раздел называется
# «Режим дозирования» либо «Способ применения и дозы»; у wer.ru —
# «Способ применения, курс и дозировка». Общего слова у них нет,
# и подстрока «способ применения» ловила бы оба лишь по совпадению.
_ЗАГ_ДОЗ_WER = ("способ применения, курс и дозировка",
                "способ применения и дозы", "режим дозирования")
_ЗАГ_ПОКАЗАНИЙ_WER = ("показани",)


def _текст_заголовка(м):
    имя = " ".join(re.sub(r"<[^>]+>", "", м.group(2)).split()).lower()
    return имя.replace(chr(0xAE), "").strip()


def _первый_блок(хвост):
    """Содержимое ПЕРВОГО блока после заголовка, по балансу тегов.

    Отдаёт `None`, когда блока нет либо разметка не сбалансирована:
    подставить «весь остаток» значило бы вернуть кусок, про который мы
    не знаем, где он кончается, — и это ровно те 7363 знака мусора,
    ради которых функция и написана.
    """
    м = _ДИВ.search(хвост or "")
    if not м or м.group(1):
        return None
    глубина, поз = 1, м.end()
    for мм in _ДИВ.finditer(хвост, поз):
        глубина += -1 if мм.group(1) else 1
        if глубина == 0:
            return хвост[поз:мм.start()]
    return None


class _Wer:

    имя = "wer.ru"
    домен = "wer.ru"
    база = "https://wer.ru"
    # ВЫДУМАННОЕ ИМЯ ДАЁТ СТРАНИЦЫ — вычитание обязательно (блок A)
    базовая_линия_нужна = True
    пробное_имя = "Цитрамон"
    # ═══════════════════════════════════════════════════════════════
    # ИСТОЧНИК МЕДЛЕННЫЙ, И ЭТО ЗАМЕР, А НЕ ЗАПАС «НА ВСЯКИЙ СЛУЧАЙ»
    # ═══════════════════════════════════════════════════════════════
    #
    # Замер 2026-09-04 С ПРОДА: выдача 212 КБ приходит за секунды,
    # а КАРТОЧКА весит 543–633 КБ и отдаётся за 4.8, 5.4 и 13.9 с.
    # Первый прогон четырёх карточек подряд при таймауте 45 с дал
    # ReadTimeout на трёх из четырёх — то есть под нагрузкой источник
    # отвечает ещё медленнее.
    #
    # Общие 20 с резали бы его на самой обычной карточке, и выглядело
    # бы это как «источник ничего не знает»: отказ по таймауту
    # приходит в тот же `except`, что и всё остальное.
    таймаут = 45.0

    def адрес_поиска(self, запрос):
        from urllib.parse import quote
        return self.база + "/search/?q=" + quote(запрос)

    def карточки(self, выдача_html, форма=None, доза=None):
        """Пути карточек из выдачи.

        ОТБОРА ПО ВЫПУСКУ ЗДЕСЬ НЕТ, И ЭТО ЗАМЕР, А НЕ УПРОЩЕНИЕ.
        У Видаля выпуск назван в той же строке таблицы, что и ссылка,
        и `ссылки_поиска` этим пользуется. Здесь выдача — плитка
        карточек, где рядом со ссылкой стоят цена и остаток на складе;
        формы в разметке ссылки нет вовсе. Сортировать не по чему,
        и выдумать признак значило бы городить догадку о вёрстке.

        ПОРЯДОК ВЫДАЧИ СОХРАНЯЕТСЯ (`dict.fromkeys`, а не `set`):
        источник сортирует по релевантности, и перетасовать его
        значило бы поставить первым не то, что первым нашлось.
        """
        пути = list(dict.fromkeys(_КАРТОЧКА.findall(выдача_html or "")))
        return пути[:_общее.СТРАНИЦ_МАКС]

    def адрес_страницы(self, путь):
        return self.база + путь

    def описание(self, страница_html):
        """Заголовок h1 карточки — «Цитрамон П таблетки 20 шт. …».

        Ровно та роль, что у первой строки документа Видаля: строка,
        в которой рядом стоят название, форма и количество.
        """
        м = _H1.search(страница_html or "")
        if not м:
            return ""
        return " ".join(re.sub(r"<[^>]+>", " ", м.group(1)).split()).strip()

    def название(self, опис):
        """Торговое название из h1 — ТОЙ ЖЕ чисткой, что и наше поле.

        `имя_для_поиска` отрезает всё после первой цифры или слова
        формы. Замер на четырёх живых карточках: «Цитрамон П таблетки
        20 шт. Фармстандарт-Лексредства» → «Цитрамон П», «Но-шпа
        таблетки 40 мг 24 шт.» → «Но-шпа», и так все четыре.

        ОДНО ПРАВИЛО НА ОБЕ СТОРОНЫ, а не два похожих: `название_совпало`
        сравнивает наше чищеное имя с этим, и разойдись они — сверка
        начала бы отвергать совпадающее (§6.0.7).
        """
        чисто = _общее.имя_для_поиска(опис or "")
        return чисто or None

    def вещество(self, страница_html):
        """Блок «Действующее вещество» — дословно."""
        _з, кусок = self._раздел(страница_html, _ЗАГ_ВЕЩЕСТВА)
        if not кусок:
            return None
        плоско = " ".join(_общее.без_тегов(кусок).split())
        return плоско.strip(" .;,") or None

    def раздел_доз(self, страница_html):
        return self._раздел(страница_html, _ЗАГ_ДОЗ_WER)

    def раздел_показаний(self, страница_html):
        return self._раздел(страница_html, _ЗАГ_ПОКАЗАНИЙ_WER,
                            начинается=True)

    def _раздел(self, страница_html, заголовки, начинается=False):
        """(заголовок, СЫРАЯ РАЗМЕТКА) первого раздела с таким именем."""
        for м in _ЗАГОЛОВОК.finditer(страница_html or ""):
            имя = _текст_заголовка(м)
            подошёл = (any(имя.startswith(з) for з in заголовки)
                       if начинается else any(з in имя for з in заголовки))
            if not подошёл:
                continue
            тело = _первый_блок(страница_html[м.end():])
            if тело is None:
                # РАЗБОР НЕ СОШЁЛСЯ — «раздела нет», а не «весь остаток».
                # Вызывающий обязан различать эти два случая, и мы
                # обязаны не подсовывать ему кусок неизвестной длины
                return None, ""
            return имя, тело
        return None, ""



"""КЛЮЧ OPENROUTER: У ПРОДА И У СТЕНДА РАЗНЫЕ (BACKLOG №346, заход 3).

Единственное место правила на всех потребителей: `main.py` и живые пробы
(`check_search_api.py`). Модуль ПУСТОЙ, ни одного импорта сверх стандартной
библиотеки: его читают без поднятого приложения.

Ключ был один, и любой прогон проверок на стенде тратил деньги прода.
На проде (`FLY_APP_NAME` ставит сам Fly) ключ читается как прежде —
`OPENROUTER_API_KEY`. На стенде и в локальной разработке — ТОЛЬКО
`OPENROUTER_STAND_KEY`, со своим месячным лимитом в кабинете OpenRouter.

ОТКАТА НА КЛЮЧ ПРОДА НЕТ, И ЭТО ГЛАВНОЕ. Ключа стенда нет — ключ пуст,
и вызывающий отказывает с причиной. Молчаливый откат означал бы, что
проверки снова платят с прода, и узнать это было бы нечем, кроме счёта.
Ключ стенда, совпавший с ключом прода, тоже пуст: это та же трата
с прода, только названная по-другому.
"""
import hashlib

КЛЮЧ_СТЕНДА_ИМЯ = "OPENROUTER_STAND_KEY"
КЛЮЧ_ПРОДА_ИМЯ = "OPENROUTER_API_KEY"


def на_проде(окружение) -> bool:
    return bool(окружение.get("FLY_APP_NAME"))


def выбрать_ключ(окружение) -> tuple:
    """(ключ, причина пустоты или ''). Ключ прода на стенде не отдаётся никогда."""
    if на_проде(окружение):
        ключ = окружение.get(КЛЮЧ_ПРОДА_ИМЯ, "")
        return ключ, ("" if ключ else f"на проде не задан {КЛЮЧ_ПРОДА_ИМЯ}")
    ключ = окружение.get(КЛЮЧ_СТЕНДА_ИМЯ, "")
    if not ключ:
        return "", (f"на стенде нужен свой ключ {КЛЮЧ_СТЕНДА_ИМЯ}; "
                    "ключ прода здесь не используется")
    if ключ == окружение.get(КЛЮЧ_ПРОДА_ИМЯ, ""):
        return "", (f"{КЛЮЧ_СТЕНДА_ИМЯ} совпадает с ключом прода — "
                    "на стенде нужен отдельный ключ со своим лимитом")
    return ключ, ""


def отпечаток(ключ: str) -> str:
    """12 знаков sha256 — единственное, что про ключ разрешено печатать."""
    return hashlib.sha256(ключ.encode()).hexdigest()[:12] if ключ else "—"

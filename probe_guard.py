# -*- coding: utf-8 -*-
"""СЛОЙ ПРОБЫ: «спросить нечем» говорится СЛОВОМ, а не трассой.

ЗАЧЕМ. Проба без стенда, без сети или без базы вываливала стектрейс
и код 1 — то есть снаружи выглядела РОВНО так же, как проба, сломанная
в собственном коде. Замер 2026-09-12 (`py check_probe_start.py`):
запусков 279, трассу вместо слова давали 138. Разбирать, «нечем
проверить» это или «сломалось», приходилось человеку глазами, и ровно
на таком неразличении десять дней прожила задача 305.

Проект уже решил, чем эти два исхода различаются (§6.0.1, задачи 281,
293, 307): «спросить нечем» — код 2 и слово ПРОПУСК, находка — код 1.
Слой распространяет то же решение на ВНЕШНИЙ отказ.

КАК ПОДКЛЮЧАЕТСЯ — ОДНОЙ СТРОКОЙ:

    import probe_guard  # noqa: F401  (ПРОПУСК вместо трассы)

Импорт ставит `sys.excepthook`. В норме он не делает НИЧЕГО: хук
вызывается только у исключения, дошедшего до верха, то есть там, где
проба и так падала.

ПОЧЕМУ СТРОКОЙ, А НЕ САМО. Замер того же дня: `sitecustomize.py`,
положенный в корень проекта, интерпретатором НЕ подхватывается —
каталог скрипта попадает в `sys.path` уже после импорта `site`.
Тогда «по умолчанию» достигается не магией импорта, а тем, что
ЗАБЫВЧИВОСТЬ СТАНОВИТСЯ НАХОДКОЙ МАШИНЫ: `check_probe_start.py`
печатает пробы без слоя отдельным числом, разбором текста и без
прогона. Тот же приём, что у девятой панели в `check_panel_refresh`
(§5.8) — механизм не заставит объявить себя, а его отсутствие
перестаёт быть вопросом памяти.

ПРИЗНАК ВНЕШНЕГО УЗКИЙ, И ЭТО ГЛАВНОЕ СВОЙСТВО СЛОЯ. При сомнении
исключение считается СВОИМ — то есть проба падает трассой, как
падала. Обратная ошибка дороже: ПРОПУСК, проглотивший настоящую
поломку, прячет её и от человека, и от проверки 35, а это ровно тот
немой отказ, ради которого слой и написан.

Поэтому список ТИПОВ закрыт (`ВНЕШНИЕ`), а два типа, у которых один
и тот же класс означает и внешнее, и своё, сужены ПО ТЕКСТУ:

  · `sqlite3.OperationalError` — «unable to open database file» внешнее
    (файла нет), «no such table/column» СВОЁ (схема разошлась с кодом);
  · `playwright ... Error` — `net::ERR_*` и «Executable doesn't exist»
    внешнее, всё прочее СВОЁ: «Timeout ... waiting for locator» значит,
    что стенд ответил, а органа на экране нет, — это находка пробы.

ЧЕГО СЛОЙ НЕ ЗАКРЫВАЕТ, И ЭТО ГРАНИЦА, А НЕ УПУЩЕНИЕ:

  · исключение в ПОТОКЕ (`threading.excepthook`) и в неподнятом
    `asyncio`-обработчике: до `sys.excepthook` они не доходят;
  · падение ПОДПРОЦЕССА, который проба запустила сама, — там свой
    интерпретатор и свой хук, и если у запущенной пробы слоя нет,
    трасса придёт от неё;
  · проба, которая ловит отказ САМА и печатает своё, — слой до неё
    не доходит и не должен;
  · `atexit`-обработчики: выход идёт `os._exit(2)`, потому что
    из `excepthook` кодом возврата иначе не распорядиться. Блоки
    `finally` к этому моменту УЖЕ отработали (стек раскручен), а вот
    `atexit` — нет. В пробах проекта уборка стоит в `finally`
    (правило задачи 269), поэтому цена названа, а не замолчана.
"""
import os
import sys

# КОД «СПРОСИТЬ НЕЧЕМ» — тот же, что у проб проекта (§6.0.1).
КОД_ПРОПУСКА = 2

# ЗАКРЫТЫЙ СПИСОК ТИПОВ. Ключ — «модуль.Имя» либо просто «Имя» для
# встроенных; значение — ЧЕЛОВЕЧЕСКАЯ причина, которую увидит читающий.
# Перечень тут законен: новый член появляется решением о коде, а не сам
# собой (§6.0.7), и ошибка в сторону пропуска безопаснее ошибки
# в сторону проглатывания.
ВНЕШНИЕ = {
    # --- сеть ---
    "httpx.ConnectError": "сервис не отвечает",
    "httpx.ConnectTimeout": "сервис не ответил за таймаут",
    "httpx.ReadTimeout": "сервис не дочитал ответ за таймаут",
    "httpx.WriteTimeout": "сервис не принял запрос за таймаут",
    "httpx.PoolTimeout": "клиент не дождался соединения",
    "httpx.RemoteProtocolError": "сервис оборвал соединение",
    "httpx.ProxyError": "прокси не отвечает",
    "urllib.error.URLError": "адрес не отвечает",
    "socket.gaierror": "имя узла не разрешается",
    "ConnectionRefusedError": "порт закрыт",
    "ConnectionResetError": "соединение сброшено",
    "ConnectionAbortedError": "соединение оборвано",
    "ConnectionError": "нет связи",
    "requests.exceptions.ConnectionError": "сервис не отвечает",
    "requests.exceptions.Timeout": "сервис не ответил за таймаут",
}

# ЧТО В СПИСОК НЕ ВЗЯТО НАРОЧНО, И ЭТО ЗАМЕР, А НЕ ОСТОРОЖНОСТЬ.
# `FileNotFoundError` и `PermissionError` двусмысленны: «базы нет
# на месте» и «опечатка в пути» — один и тот же тип, а различить их
# нечем. Взяв их, слой ПРЯТАЛ БЫ настоящую поломку под словом ПРОПУСК,
# то есть заводил бы ровно тот немой отказ, ради которого написан.
# Цена названа и замерена: в долге 2026-09-12 (138 запусков) таких
# падений НОЛЬ, то есть сегодня отказ не стоит ничего; появятся —
# останутся находкой, а не пропуском.

# СУЖЕННЫЕ ПО ТЕКСТУ — один тип означает и внешнее, и своё. Разбор
# по строке тут не от хорошей жизни, и граница названа в шапке.
СУЖЕННЫЕ = {
    "sqlite3.OperationalError": (
        ("unable to open database file", "базы нет на месте"),
        ("no such file", "базы нет на месте"),
        ("database is locked", "база занята другим процессом"),
    ),
    "playwright._impl._errors.Error": (
        ("net::ERR_", "стенд не отвечает"),
        ("Executable doesn't exist", "браузер playwright не установлен"),
        ("Target page, context or browser has been closed",
         "браузер закрылся"),
    ),
    "playwright._impl._errors.TargetClosedError": (
        ("", "браузер закрылся"),
    ),
}


def полное_имя(тип):
    """«модуль.Имя» — либо голое «Имя» для встроенных."""
    модуль = getattr(тип, "__module__", "") or ""
    if модуль in ("builtins", "__main__", ""):
        return тип.__name__
    return модуль + "." + тип.__name__


def внешнее(тип, текст=""):
    """Причина словом, если отказ ВНЕШНИЙ; иначе None.

    Смотрит и на сам тип, и на его предков: `httpx.ConnectTimeout`
    наследует `httpx.TimeoutException`, а конкретное имя в трассе
    бывает у́же объявленного. Перечень от этого не растёт.
    """
    for к in (тип,) + tuple(getattr(тип, "__mro__", ())):
        имя = полное_имя(к)
        если = ВНЕШНИЕ.get(имя)
        if если:
            return если
        for маркер, причина in СУЖЕННЫЕ.get(имя, ()):
            if маркер == "" or маркер in текст:
                return причина
    return None


def внешнее_по_имени(имя, текст=""):
    """То же решение, но по ИМЕНИ типа из чужой трассы.

    Нужно `check_probe_start`: она видит не объект исключения, а строку
    из вывода подпроцесса. Признак ОДИН на обе стороны — иначе проверка
    числила бы долгом то, чего слой всё равно не поймает, и долг стал бы
    недостижимым (§6.0.7).

    ПО ПОЛНОМУ ИМЕНИ, А НЕ ПО ХВОСТУ: `sqlite3.OperationalError`
    и выдуманный `наш.OperationalError` — разные вещи, и сходство
    последнего слова о родстве не говорит. Предков у строки нет, значит
    подкласс, названный в трассе своим именем, сюда не попадёт, — это
    граница, и она в пользу находки, а не пропуска.
    """
    if имя in ВНЕШНИЕ:
        return ВНЕШНИЕ[имя]
    for маркер, причина in СУЖЕННЫЕ.get(имя, ()):
        if маркер == "" or маркер in (текст or ""):
            return причина
    return None


def _первая_строка(текст):
    стр = (текст or "").strip().splitlines()
    return стр[0] if стр else ""


def _сказать(текст):
    """Печать, не падающая от кодировки консоли.

    ЗАЧЕМ ТАК, А НЕ `print`. Пробу запускают и напрямую, и из другого
    процесса; `sys.stdout.reconfigure(encoding="utf-8")` есть не у всех,
    а сообщение слоя — кириллица. Упади печать `UnicodeEncodeError` —
    и слово ПРОПУСК не дошло бы до человека, то есть слой страдал бы
    ровно той болезнью, которую лечит (§6.0).
    """
    try:
        print(текст)
        return
    except UnicodeEncodeError:
        pass
    try:
        поток = getattr(sys.stdout, "buffer", None) or sys.stdout
        поток.write((текст + chr(10)).encode("utf-8", "replace"))
    except Exception:
        pass


def сказать_пропуск(причина, подробность=""):
    """Печать ПРОПУСКА. Отдельной функцией — её зовёт и хук, и проба,
    которая поймала отказ сама и хочет ответить тем же словом."""
    строка = "ПРОПУСК: %s" % причина
    if подробность:
        строка += " — %s" % подробность
    _сказать(строка)
    _сказать("  Замер НЕ СОСТОЯЛСЯ. Это не находка и не «чисто»: "
             "спросить было нечем.")


def _хук(вид, значение, трасса):
    причина = внешнее(вид, str(значение))
    if причина is None:
        # НЕ НАШ СЛУЧАЙ — отдаём как было: трасса и код 1. Пропуск,
        # проглотивший поломку, хуже отсутствующего слоя.
        sys.__excepthook__(вид, значение, трасса)
        return
    try:
        сказать_пропуск(причина, "%s: %s" % (полное_имя(вид),
                                             _первая_строка(str(значение))))
        sys.stdout.flush()
        sys.stderr.flush()
    except Exception:
        pass
    # `sys.exit` внутри хука кодом возврата не распоряжается: интерпретатор
    # всё равно вернёт 1. Выход только так; цена (`atexit`) в шапке.
    os._exit(КОД_ПРОПУСКА)


def поставить():
    """Идемпотентно. Возвращает True, если хук поставлен этим вызовом."""
    if getattr(sys.excepthook, "_probe_guard", False):
        return False
    _хук._probe_guard = True
    sys.excepthook = _хук
    return True


# KeyboardInterrupt под слой НЕ попадает: его нет ни в одном списке,
# и он уходит штатным путём.
поставить()



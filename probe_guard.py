# СЛУЧАЕВ ЧЕТЫРЕ, И ЧЕТВЁРТЫЙ ОБРАТНЫЙ. Три внешних отказа обязаны дать
# ПРОПУСК и код 2; НАСТОЯЩАЯ ПОЛОМКА обязана дать трассу и код 1.
# Без обратного «слой превращает отказ в ПРОПУСК» неотличимо
# от «слой превращает в ПРОПУСК ВСЁ», а второе прячет поломки — то есть
# заводит немой отказ ровно там, где мы его лечим (§6.0.3).
#
# ДОКАЗАТЕЛЬСТВО НЕЗАВИСИМО ОТ ВЕРДИКТА: каждый случай гоняется ДВАЖДЫ —
# со слоем и БЕЗ него, — и печатается пара кодов. «Со слоем 2» само
# по себе не говорит, что до слоя было иначе.
_СЛУЧАИ = (
    ("сеть",   'import httpx; httpx.get("http://127.0.0.1:9/x", timeout=2)',
     2, "ПРОПУСК"),
    ("база",   'import sqlite3; sqlite3.connect('
               '"file:/нет/такой/базы.db?mode=ro", uri=True).execute("select 1")',
     2, "ПРОПУСК"),
    ("стенд",  'import playwright._impl._errors as e\n'
               'raise e.Error("Page.goto: net::ERR_CONNECTION_REFUSED at '
               'http://127.0.0.1:8899/login")',
     2, "ПРОПУСК"),
    ("СВОЙ КОД (обратный)", 'ЗАБЫТОЕ_ИМЯ()', 1, "трасса"),
    ("своя база без таблицы (обратный)",
     'import sqlite3; sqlite3.connect(":memory:").execute("select * from нет_такой")',
     1, "трасса"),
)


def _контроль():
    import subprocess
    import tempfile
    корень = os.path.dirname(os.path.abspath(__file__))
    print("КОНТРОЛЬ СЛОЯ probe_guard")
    print("=" * 72)
    все_ок = True
    for имя, тело, ждём, слово in _СЛУЧАИ:
        коды = {}
        for со_слоем in (False, True):
            шапка = ("import sys\nsys.path.insert(0, %r)\n" % корень)
            if со_слоем:
                шапка += "import probe_guard\n"
            with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False,
                                             encoding="utf-8") as ф:
                ф.write(шапка + тело + "\n")
                путь = ф.name
            try:
                среда = dict(os.environ, PYTHONIOENCODING="utf-8")
                р = subprocess.run([sys.executable, путь], capture_output=True,
                                   text=True, encoding="utf-8", errors="replace",
                                   timeout=120, env=среда)
                коды[со_слоем] = (р.returncode, (р.stdout or "") + (р.stderr or ""))
            finally:
                os.unlink(путь)
        без, со = коды[False][0], коды[True][0]
        сказал = "ПРОПУСК" in (коды[True][1] or "")
        ок = (со == ждём) and (сказал == (слово == "ПРОПУСК"))
        все_ок = все_ок and ок
        print("  %-34s без слоя код=%d -> со слоем код=%d  ждали %d (%s)  %s"
              % (имя, без, со, ждём, слово, "OK" if ок else "ПЛОХО"))
    print()
    print("  ДОКАЗАТЕЛЬСТВО: у внешних отказов код меняется 1 -> 2 и приходит")
    print("  слово ПРОПУСК; у поломки в НАШЕМ коде код остаётся 1 и приходит")
    print("  трасса — то есть слой не проглатывает то, что чинить надо.")
    print("  КОНТРОЛЬ: %s" % ("ПРОЙДЕН" if все_ок else "ПРОВАЛЕН"))
    return 0 if все_ок else 1


if __name__ == "__main__":
    if "--контроль" in sys.argv:
        sys.exit(_контроль())
    print(__doc__)

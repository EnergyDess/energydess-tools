"""Списки и команды §6.0.2 — ОДИН ИСТОЧНИК, и он в CLAUDE.md.

ЗАЧЕМ ЭТОТ ФАЙЛ. `check_ids.py` читал компонентную базу из строки
`names='…'` в CLAUDE.md — именно затем, чтобы второй копии не было.
А `check_metrics.py`, который печатает опорный ряд, держал свою копию
той же строки, и она отстала на 23 имени: все `scale-*` и `hint-*`,
заведённые 2026-08-19. Следствие числом: копия давала 18 находок,
настоящий список — 19, и девятнадцатая была настоящим долгом
(`.hint` в `profile.css`).

Немой отказ в чистом виде: ряд печатался, число выглядело опорным,
по нему принимали работу, и молчал он ровно про то, что заведено
последним. Тот же класс, что у переменной `pages` и у самого
whitelist `names` — «имени нет в списке, проверка про него молчит», —
только этажом выше: молчал сам инструмент приёмки.

ЧТО ЗДЕСЬ ЕСТЬ. Разбор кодового блока ```bash из §6.0.2: присваивания
(`pages`, `names`, `tokens`) и команды проверок по номерам. Копий трёх
величин — списка компонентов, списка страничных файлов и самих
грепов — больше нет нигде: и `check_ids`, и `check_metrics` читают
отсюда, а отсюда читается CLAUDE.md.

ПОЧЕМУ ИСТОЧНИК — ДОКУМЕНТ, А НЕ КОД. Ряд девяти объявлен в §6.0.2
командами, которые человек может скопировать в терминал и получить
те же числа. Перенеси мы список в Python — в документе осталась бы
копия «для чтения», и разошлась бы она точно так же.

Останавливаемся с кодом 2, если разбор не удался: пустой whitelist
печатает «чисто» про всё на свете, а пустой список команд напечатал бы
ряд из вопросительных знаков и выглядел бы как поломка инструмента,
а не как отсутствие проверок.
"""
import io
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).parent
ДОКУМЕНТ = КОРЕНЬ / 'CLAUDE.md'

# Номера, которые в ряд НЕ идут: это подпроходы той же проверки. Здесь
# не копия данных, а решение о показе — какое из двух чисел проверки
# считается заголовочным. Сами команды и списки берутся из документа.
ПОДПРОХОДЫ = {'2b', '3a', '4b', '6b'}


def _остановиться(причина: str):
    print(f'ОСТАНОВЛЕНО: {причина}')
    sys.exit(2)


def текст_документа() -> str:
    if not ДОКУМЕНТ.exists():
        _остановиться('нет CLAUDE.md — брать списки §6.0.2 неоткуда')
    return io.open(ДОКУМЕНТ, encoding='utf-8').read()


def _блок(текст: str) -> str:
    """Тело кодового блока ```bash, в котором объявлен `pages`."""
    for m in re.finditer(r'```bash\n(.*?)```', текст, re.S):
        if re.search(r'^pages="templates/', m.group(1), re.M):
            return m.group(1)
    _остановиться('в CLAUDE.md §6.0.2 не найден блок ```bash с `pages="templates/…`')


def _разбор(текст: str = None):
    """(присваивания, [(номер, команда, стенд_ли)]) — полный разбор блока.

    Присваивание — строка вида `имя=…`; они уходят в прелюдию целиком,
    в порядке появления. `tokens=$(…)` стоит под комментарием «# 2.»,
    но командой проверки не является — иначе номер 2 запускал бы
    присваивание и считал его строки.

    МЕТКА `[стенд]` В КОММЕНТАРИИ НОМЕРА отделяет проверки, которым нужны
    браузер и поднятое приложение. Это не «ещё один список»: признак
    записан РЯДОМ С САМОЙ КОМАНДОЙ, в единственном источнике, и новая
    проверка попадает в свой ряд сама — ровно так же, как двенадцатая
    с тринадцатой попали в основной.
    """
    текст = текст if текст is not None else текст_документа()
    строки = _блок(текст).split('\n')
    присваивания, команды, номер, стенд = [], [], None, False
    for строка in строки:
        голая = строка.strip()
        if not голая:
            continue
        m = re.match(r'#\s*(\d+[a-z]?)\.\s*(\[стенд\])?\s', голая)
        if m:
            номер, стенд = m.group(1), bool(m.group(2))
            continue
        if голая.startswith('#'):
            continue
        if re.match(r'^[A-Za-z_][A-Za-z0-9_]*=', голая):
            присваивания.append(голая)
            continue
        if номер is None:
            continue
        if команды and команды[-1][0] == номер:
            команды[-1] = (номер, команды[-1][1] + ' ' + голая, стенд)
        else:
            команды.append((номер, голая, стенд))
    if not команды:
        _остановиться('в блоке §6.0.2 не нашлось ни одной команды с номером')
    return присваивания, команды


def разобрать(текст: str = None):
    """(присваивания, [(номер, команда)]) — РЯД, читаемый БЕЗ стенда.

    Проверки с меткой `[стенд]` сюда НЕ попадают, и это не умолчание,
    а условие существования ряда: он читается без браузера и без
    поднятого приложения (§6.0.2). Команда, требующая стенда, у всякого,
    кто его не поднял, давала бы постоянную единицу — а постоянная
    единица в ряду убивает сам ряд.
    """
    присваивания, команды = _разбор(текст)
    return присваивания, [(н, к) for н, к, с in команды if not с]


def команды_стенда(текст: str = None):
    """[(номер, команда)] — РЯД СТЕНДА: браузер и поднятое приложение.

    ЗАЧЕМ ОН ЗАВЕДЁН. До 2026-08-21 такие проверки не стояли НИГДЕ
    списком: §6.0.2 называл их прозой («номера 10, 11, 16 и 17 в ряду
    отсутствуют не по недосмотру»), и проза отставала — к тому дню их
    было уже шесть, а перечислено четыре. Проверка, которую негде
    увидеть, не существует: её не запускают и о ней не помнят.
    """
    _, команды = _разбор(текст)
    return [(н, к) for н, к, с in команды if с]


def имена_компонентов(текст: str = None) -> list:
    """Компонентная база — из строки `names='…'`, и только оттуда."""
    присваивания, _ = разобрать(текст)
    for строка in присваивания:
        m = re.match(r"^names='([^']+)'$", строка)
        if m:
            return m.group(1).split('|')
    _остановиться("в блоке §6.0.2 нет строки names='…' — "
                  'пустой whitelist печатает «чисто» про всё на свете')


def страничные_файлы(текст: str = None) -> list:
    """Что считается страничным файлом — из строки `pages="…"`."""
    присваивания, _ = разобрать(текст)
    for строка in присваивания:
        m = re.match(r'^pages="([^"]+)"$', строка)
        if m:
            return m.group(1).split()
    _остановиться('в блоке §6.0.2 нет строки pages="…"')


def исключённые_страницы(текст: str = None) -> list:
    """Файлы, которых проверки §6.0.2 НЕ считают — из строки `demo="…"`.

    ПОИМЁННО, И ЭТО ТРЕБОВАНИЕ, А НЕ ПРИВЫЧКА. Маска (`templates/demo_*`,
    «слово demo в имени») завтра проглотит файл, которого сегодня нет,
    и он молча выпадет из-под всех одиннадцати проверок — тот же немой
    отказ, что у `pages` и `names`, только с обратным знаком: там список
    молчал про новое, здесь маска замолчала бы про новое сама.

    Проверку самого списка — что каждый файл на месте и что в нём нет
    подстановочных знаков — делает `check_excluded.py` (номер 14 в ряду).
    Здесь только разбор: список, ссылающийся на несуществующий файл,
    даёт ноль находок, неотличимый от чистоты, и ловить это должна
    проверка с кодом возврата, а не функция чтения.
    """
    присваивания, _ = разобрать(текст)
    for строка in присваивания:
        m = re.match(r'^demo="([^"]+)"$', строка)
        if m:
            return m.group(1).split()
    _остановиться('в блоке §6.0.2 нет строки demo="…" — '
                  'список исключений задачи 27 брать неоткуда')


# Инструменты, которых нет НИ В ОДНОМ ряду. Не перечень — ВЫВОД: берётся
# всё, что лежит на диске под именем check_*.py, и вычитается то, что
# назвали команды обоих рядов.
#
# ЗАЧЕМ. Проза §6.0.2 перечисляла их руками («вне обоих рядов остаются
# check_regress и check_blocking») и отставала. Список, который печатает
# человек, устаревает молча; список, который печатает команда, — нет
# (§6.0.4). Пустота этого списка целью НЕ является: большинство здесь —
# МЕРКИ, у которых понятия «правильно» нет вовсе, и в ряд им нельзя.
def вне_рядов(текст: str = None):
    """[имя файла] — инструменты на диске, не названные ни одним рядом."""
    import glob
    _, без_стенда = разобрать(текст)
    со_стендом = команды_стенда(текст)
    названы = set()
    for _, к in list(без_стенда) + list(со_стендом):
        названы |= set(re.findall(r'(check_[a-z_]+\.py)', к))
    на_диске = {pathlib.Path(п).name for п in glob.glob('check_*.py')}
    return sorted(на_диске - названы)

if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    п, к = разобрать()
    print(f'присваиваний: {len(п)}')
    for с in п:
        print('   ', с[:90] + ('…' if len(с) > 90 else ''))
    ст = команды_стенда()
    print(f'\nкоманд без стенда: {len(к)}   '
          f'в ряду: {[н for н, _ in к if н not in ПОДПРОХОДЫ]}')
    for н, с in к:
        метка = 'подпроход' if н in ПОДПРОХОДЫ else 'РЯД'
        print(f'   {н:<3} [{метка}] {с[:80]}…')
    print(f'\nкоманд стенда: {len(ст)}   ряд стенда: {[н for н, _ in ст]}')
    for н, с in ст:
        print(f'   {н:<3} [СТЕНД] {с[:80]}…')
    вне = вне_рядов()
    print(f'\nвне обоих рядов: {len(вне)} — считается ВЫЧИТАНИЕМ '
          f'(что на диске минус что названо рядами)')
    for имя in вне:
        print(f'   {имя}')
    print(f'\nимён компонентов: {len(имена_компонентов())}')
    print(f'страничных целей: {len(страничные_файлы())}')
    print(f'исключённых страниц: {исключённые_страницы()}')

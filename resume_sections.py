"""РЕЗЮМЕ ПО РАЗДЕЛАМ: вид поверх текста (BACKLOG №352, письмо 3, блок 3).

ИСТОЧНИК ПРАВДЫ НЕ МЕНЯЕТСЯ. Хранится и уходит в генерацию писем ПОЛНЫЙ
текст резюме, как и раньше; разделы — это способ его ПОКАЗАТЬ и поправить
по частям. Отсюда главное свойство модуля, и оно проверяется побайтно:

    собрать(разобрать(текст)) == текст

Каждый кусок текста принадлежит РОВНО ОДНОМУ разделу, пропусков нет —
разделы покрывают строку целиком, включая переводы строк и хвост файла.
Правка раздела заменяет в тексте ровно его кусок (`заменить_тело`).

РАЗБОР ПРАВИЛАМИ, БЕЗ МОДЕЛИ. Резюме владельца всегда выгружено с hh.ru,
а у hh.ru постоянные заголовки разделов. Модель тут не нужна и вредна:
её ответ нельзя сверить с исходником побайтно, а цена ошибки — потерянный
кусок резюме.

ЗАГОЛОВКИ ЖИВУТ В ОДНОМ МЕСТЕ — `ЗАГОЛОВКИ` и `ЗАГОЛОВКИ_С_ХВОСТОМ`
ниже, у каждого списка свой разбор. Замер по двум боевым выгрузкам
2026-09-20: разделов 8 из 8, ложных 0, мест работы 9 и 4.

ПРИЗНАК СУЖАЛСЯ ЗАМЕРОМ, а не выбирался заранее. Широкий («строка
начинается с заголовка») дал ТРИ ЛОЖНЫХ РАЗДЕЛА — «Образование —
РАЖВиЗ…» внутри рассказа о себе, «Навыки  Midjourney…» (подзаголовок
списка ВНУТРИ раздела «Навыки») и «Портфолио: …» внутри «Обо мне».
Каждый такой раздел РАЗРЫВАЕТ содержимое надвое, и человек видит кусок
текста под чужой шапкой. Узкий («строка равна заголовку») потерял бы
два настоящих раздела из восьми: «Опыт работы» и «Обо мне» выгрузка
печатает с содержимым на той же строке. Взяты оба правила, каждое
со своим списком.

ЗАПАСНОЙ ВИД. Заголовков не нашлось ни одного — весь текст отдаётся
ОДНИМ разделом «Резюме». Ни строчки при этом не теряется: собрать()
по-прежнему даёт исходный текст до знака.
"""
import re

# Заголовки разделов выгрузки hh.ru. Перечень ЗАКОННЫЙ: это словарь ЧУЖОГО
# формата, а не открытое множество наших сущностей, — новый заголовок
# появляется, когда hh.ru меняет выгрузку, и добавляется сюда решением.
#
# ЗАГОЛОВОК ЗАНИМАЕТ СТРОКУ ЦЕЛИКОМ, и это не придирка, а замер: признак
# «строка НАЧИНАЕТСЯ с заголовка» дал на двух боевых выгрузках 2026-09-20
# ТРИ ЛОЖНЫХ РАЗДЕЛА из двенадцати — «Образование — РАЖВиЗ…» внутри рассказа
# о себе, «Навыки  Midjourney…» (подзаголовок списка ВНУТРИ раздела
# «Навыки») и «Портфолио: …» строкой внутри «Обо мне». Каждый такой раздел
# РАЗРЫВАЕТ содержимое надвое, и человек видит кусок текста под чужой
# шапкой.
ЗАГОЛОВКИ = [
    "Желаемая должность и зарплата",
    "Ключевые навыки",
    "Навыки",
    "Повышение квалификации, курсы",
    "Электронные сертификаты",
    "Тесты, экзамены",
    "Образование",
    "Высшее образование",
    "Среднее специальное образование",
    "Опыт вождения",
    "Дополнительная информация",
    "Портфолио",
]

# ДВА ЗАГОЛОВКА В ВЫГРУЗКЕ ИДУТ С СОДЕРЖИМЫМ НА ТОЙ ЖЕ СТРОКЕ, и оба
# названы поимённо: «Опыт работы — 11 лет 4 месяца» и «Обо мне <текст>».
# Свести их к точному совпадению нельзя — потеряются два раздела из восьми;
# распространить «начало строки» на все — вернутся три ложных (выше).
ЗАГОЛОВКИ_С_ХВОСТОМ = [
    "Опыт работы",
    "Обо мне",
]

# Верхний блок до первого заголовка: имя, пол и возраст, гражданство,
# способы связи. Имени у него в выгрузке нет — даём своё.
КОНТАКТЫ = "Контакты"

# Название раздела, когда заголовков hh.ru не нашлось вовсе.
ВЕСЬ_ТЕКСТ = "Резюме"

_МЕСЯЦЫ = ("Январь|Февраль|Март|Апрель|Май|Июнь|Июль|Август|"
           "Сентябрь|Октябрь|Ноябрь|Декабрь")
_ПЕРИОД = re.compile(r"^(?:%s)\s+\d{4}\s*$" % _МЕСЯЦЫ)
_ДЛИТЕЛЬНОСТЬ = re.compile(
    r"^\d+\s+(?:год|года|лет)(?:\s+\d+\s+месяц(?:а|ев)?)?\s*$|"
    r"^\d+\s+месяц(?:а|ев)?\s*$")


def _заголовок_строки(строка):
    """Какой заголовок в строке. Не заголовок — None."""
    ст = строка.strip()
    if not ст:
        return None
    if ст in ЗАГОЛОВКИ:
        return ст
    for з in sorted(ЗАГОЛОВКИ_С_ХВОСТОМ, key=len, reverse=True):
        # Следующий знак обязан быть разделителем — иначе «Обо мне»
        # поймалось бы внутри слова, начинающегося так же.
        if ст.startswith(з) and (len(ст) == len(з) or not ст[len(з)].isalnum()):
            return з
    return None


def разобрать(текст):
    """Список разделов: [{имя, заголовок, тело, начало, конец}].

    `начало` и `конец` — срез ИСХОДНОГО текста, принадлежащий разделу
    целиком (включая перевод строки в конце). Куски идут подряд и без
    пропусков: их склейка равна исходному тексту до знака.
    """
    if not текст:
        return []

    # Границы строк вместе с их переводами: работаем со СМЕЩЕНИЯМИ,
    # а не со списком строк, — склейка через "\n" потеряла бы сведения
    # о том, чем кончался файл, и собрать() дало бы другой текст.
    куски, поз = [], 0
    while поз < len(текст):
        конец = текст.find("\n", поз)
        конец = len(текст) if конец < 0 else конец + 1
        куски.append((поз, конец))
        поз = конец

    # КАЖДЫЙ ЗАГОЛОВОК БЕРЁТСЯ ПЕРВЫМ ВХОЖДЕНИЕМ. Повтор того же имени
    # ниже по тексту — это содержимое, а не новый раздел: у выгрузки
    # hh.ru разделы не повторяются, а слово «Портфолио» встречается
    # в рассказе о себе дважды подряд (замер 2026-09-20).
    границы, взятые = [], set()
    for i, (а, б) in enumerate(куски):
        з = _заголовок_строки(текст[а:б])
        if з and з not in взятые:
            взятые.add(з)
            границы.append((i, з))

    if not границы:
        return [{"имя": ВЕСЬ_ТЕКСТ, "заголовок": "", "тело": текст,
                 "начало": 0, "конец": len(текст)}]

    разделы = []
    первый = границы[0][0]
    if первый > 0:
        конец = куски[первый - 1][1]
        разделы.append({"имя": КОНТАКТЫ, "заголовок": "",
                        "тело": текст[0:конец], "начало": 0, "конец": конец})

    for n, (строка, з) in enumerate(границы):
        а = куски[строка][0]
        б = куски[границы[n + 1][0] - 1][1] if n + 1 < len(границы) else len(текст)
        разделы.append({"имя": з, "заголовок": з, "тело": текст[а:б],
                        "начало": а, "конец": б})
    return разделы


def собрать(разделы):
    """Обратная разбору склейка. Равна исходному тексту побайтно."""
    return "".join(р["тело"] for р in разделы)


def заменить_тело(текст, индекс, новое):
    """Новый полный текст: кусок раздела `индекс` заменён на `новое`.

    Заменяется РОВНО кусок раздела; остальное не трогается ни на знак,
    и это главное свойство правки по частям.
    """
    разделы = разобрать(текст)
    if not (0 <= индекс < len(разделы)):
        raise IndexError("раздела %r нет: их %d" % (индекс, len(разделы)))
    р = разделы[индекс]
    return текст[:р["начало"]] + новое + текст[р["конец"]:]


def места_работы(тело):
    """Места работы внутри раздела «Опыт работы».

    Признак — ФОРМА ЗАПИСИ выгрузки: строка-период («Июнь 2023»), за ней
    вторая строка периода либо «по настоящее время», затем строка
    длительности («2 года 5 месяцев»). Ни одно место не «угадывается»
    по смыслу: если признак не сошёлся, мест нет вовсе и раздел
    показывается сплошным текстом.

    Возвращает список {период, компания, должность, описание} — ТОЛЬКО
    для показа. Правка идёт по разделу целиком, а не по месту: иначе
    пришлось бы собирать текст обратно из полей, и побайтность потерялась
    бы на первом же лишнем пробеле.
    """
    строки = тело.split("\n")
    начала = []
    i = 0
    while i < len(строки):
        if not _ПЕРИОД.match(строки[i].strip()):
            i += 1
            continue
        хвост = [x.strip() for x in строки[i + 1:i + 4]]
        if not any(_ДЛИТЕЛЬНОСТЬ.match(x) for x in хвост if x):
            i += 1
            continue
        начала.append(i)
        # ПРЫГАЕМ ЗА СТРОКУ ДЛИТЕЛЬНОСТИ, а не на следующую строку:
        # у места работы с законченным сроком ВТОРАЯ строка периода
        # («Декабрь 2020») сама подходит под признак начала — замер
        # на выгрузке hh.ru давал ТРИ места там, где их два, то есть
        # одно место разрывалось надвое и показывалось двумя карточками.
        j = i + 1
        while j < len(строки) and j <= i + 3:
            if _ДЛИТЕЛЬНОСТЬ.match(строки[j].strip()):
                break
            j += 1
        i = j + 1
    места = []
    for n, i in enumerate(начала):
        конец = начала[n + 1] if n + 1 < len(начала) else len(строки)
        кусок = [с for с in строки[i:конец]]
        непустые = [с.strip() for с in кусок if с.strip()]
        период, компания, должность, описание = "", "", "", []
        for к, с in enumerate(непустые):
            if к == 0:
                период = с
                continue
            if к <= 2 and (_ПЕРИОД.match(с) or _ДЛИТЕЛЬНОСТЬ.match(с)
                           or с.lower().startswith("по настоящее")):
                период = (период + " — " + с) if к == 1 else период
                continue
            if not компания:
                компания = с
            elif not должность and len(с) < 80:
                должность = с
            else:
                описание.append(с)
        места.append({"период": период, "компания": компания,
                      "должность": должность, "описание": "\n".join(описание)})
    return места


def показ(раздел):
    """Текст раздела ДЛЯ ЭКРАНА: без строки заголовка над ним.

    ТЕЛО ПРИ ЭТОМ НЕ ТРОГАЕТСЯ НИ НА ЗНАК — правится и хранится оно целиком,
    и побайтная сборка от этого не зависит. Срезается только ПОКАЗ: имя
    раздела уже стоит шапкой карточки, и печатать его второй раз строкой
    ниже значит сказать одно и то же дважды (замер на выгрузке hh.ru:
    так выглядели семь разделов из восьми).

    У заголовка С ХВОСТОМ («Опыт работы — 11 лет 4 месяца») срезается
    ТОЛЬКО слово заголовка: хвост — это данные, и терять их нельзя.
    """
    тело = раздел["тело"]
    з = раздел.get("заголовок") or ""
    if not з:
        return тело
    конец = тело.find("\n")
    первая = тело if конец < 0 else тело[:конец]
    остаток = "" if конец < 0 else тело[конец + 1:]
    хвост = первая.strip()[len(з):].strip(" \u2014-\u2013:\t")
    return (хвост + "\n" + остаток) if хвост else остаток


def _строка_навыков(строка):
    ст = строка.strip()
    for з in ("Ключевые навыки", "Навыки"):
        if ст.startswith(з) and re.search(r"\s{2,}", ст[len(з):]):
            return True
    return False


def навыки(тело):
    """Отдельные навыки из раздела «Ключевые навыки» / «Навыки».

    ЧИПАМИ ПОКАЗЫВАЕТСЯ ТОЛЬКО ТА СТРОКА, ГДЕ hh.ru ПЕРЕЧИСЛИЛ НАВЫКИ
    через набеги пробелов. Признак «весь раздел — навыки» замер опроверг:
    внутри раздела «Навыки» выгрузка держит ещё и «Знание языков»
    обычными строками, и они уезжали в чипы наравне с Premiere Pro —
    то есть карточка утверждала, что «Русский — Родной» это навык.
    """
    for строка in тело.split("\n"):
        ст = строка.strip()
        for з in ("Ключевые навыки", "Навыки"):
            if not ст.startswith(з):
                continue
            хвост = ст[len(з):]
            if not re.search(r"\s{2,}", хвост):
                continue
            найдено = [к.strip() for к in re.split(r"\s{2,}|\t", хвост) if к.strip()]
            if len(найдено) > 1:
                return найдено
    return []


def остаток_без_навыков(текст):
    """Текст без той строки, что ушла в чипы: показать её дважды значит
    сказать одно и то же двумя способами."""
    строки = [с for с in текст.split("\n") if not _строка_навыков(с)]
    return "\n".join(строки)

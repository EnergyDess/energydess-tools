"""РЕЗЮМЕ ПО РАЗДЕЛАМ: вид поверх текста (BACKLOG №352, письмо 3, блок 3).

ИСТОЧНИК ПРАВДЫ НЕ МЕНЯЕТСЯ. Хранится и уходит в генерацию писем ПОЛНЫЙ
текст резюме, как и раньше; разделы — это способ его ПОКАЗАТЬ и поправить
по частям. Отсюда главное свойство модуля, и оно проверяется побайтно:

    собрать(разобрать(текст)) == текст

Каждый кусок текста принадлежит РОВНО ОДНОМУ разделу, пропусков нет —
разделы покрывают строку целиком, включая переводы строк и хвост файла.
Правка раздела заменяет в тексте ровно его кусок (`заменить_тело`).

РАЗБОР ПРАВИЛАМИ, БЕЗ МОДЕЛИ. Резюме владельца всегда выгружено с hh.ru,
а у hh.ru постоянные заголовки разделов. Модель тут не нужна и вредна:
её ответ нельзя сверить с исходником побайтно, а цена ошибки — потерянный
кусок резюме.

ЗАГОЛОВКИ ЖИВУТ В ОДНОМ МЕСТЕ — `ЗАГОЛОВКИ` и `ЗАГОЛОВКИ_С_ХВОСТОМ`
ниже, у каждого списка свой разбор. Замер по двум боевым выгрузкам
2026-09-20: разделов 8 из 8, ложных 0, мест работы 9 и 4.

ПРИЗНАК СУЖАЛСЯ ЗАМЕРОМ, а не выбирался заранее. Широкий («строка
начинается с заголовка») дал ТРИ ЛОЖНЫХ РАЗДЕЛА — «Образование —
РАЖВиЗ…» внутри рассказа о себе, «Навыки  Midjourney…» (подзаголовок
списка ВНУТРИ раздела «Навыки») и «Портфолио: …» внутри «Обо мне».
Каждый такой раздел РАЗРЫВАЕТ содержимое надвое, и человек видит кусок
текста под чужой шапкой. Узкий («строка равна заголовку») потерял бы
два настоящих раздела из восьми: «Опыт работы» и «Обо мне» выгрузка
печатает с содержимым на той же строке. Взяты оба правила, каждое
со своим списком.

ЗАПАСНОЙ ВИД. Заголовков не нашлось ни одного — весь текст отдаётся
ОДНИМ разделом «Резюме». Ни строчки при этом не теряется: собрать()
по-прежнему даёт исходный текст до знака.
"""
import re

# Заголовки разделов выгрузки hh.ru. Перечень ЗАКОННЫЙ: это словарь ЧУЖОГО
# формата, а не открытое множество наших сущностей, — новый заголовок
# появляется, когда hh.ru меняет выгрузку, и добавляется сюда решением.
#
# ЗАГОЛОВОК ЗАНИМАЕТ СТРОКУ ЦЕЛИКОМ, и это не придирка, а замер: признак
# «строка НАЧИНАЕТСЯ с заголовка» дал на двух боевых выгрузках 2026-09-20
# ТРИ ЛОЖНЫХ РАЗДЕЛА из двенадцати — «Образование — РАЖВиЗ…» внутри рассказа
# о себе, «Навыки  Midjourney…» (подзаголовок списка ВНУТРИ раздела
# «Навыки») и «Портфолио: …» строкой внутри «Обо мне». Каждый такой раздел
# РАЗРЫВАЕТ содержимое надвое, и человек видит кусок текста под чужой
# шапкой.
ЗАГОЛОВКИ = [
    "Желаемая должность и зарплата",
    "Ключевые навыки",
    "Навыки",
    "Повышение квалификации, курсы",
    "Электронные сертификаты",
    "Тесты, экзамены",
    "Образование",
    "Высшее образование",
    "Среднее специальное образование",
    "Опыт вождения",
    "Дополнительная информация",
    "Портфолио",
]

# ДВА ЗАГОЛОВКА В ВЫГРУЗКЕ ИДУТ С СОДЕРЖИМЫМ НА ТОЙ ЖЕ СТРОКЕ, и оба
# названы поимённо: «Опыт работы — 11 лет 4 месяца» и «Обо мне <текст>».
# Свести их к точному совпадению нельзя — потеряются два раздела из восьми;
# распространить «начало строки» на все — вернутся три ложных (выше).
ЗАГОЛОВКИ_С_ХВОСТОМ = [
    "Опыт работы",
    "Обо мне",
]

# Верхний блок до первого заголовка: имя, пол и возраст, гражданство,
# способы связи. Имени у него в выгрузке нет — даём своё.
КОНТАКТЫ = "Контакты"

# Название раздела, когда заголовков hh.ru не нашлось вовсе.
ВЕСЬ_ТЕКСТ = "Резюме"

_МЕСЯЦЫ = ("Январь|Февраль|Март|Апрель|Май|Июнь|Июль|Август|"
           "Сентябрь|Октябрь|Ноябрь|Декабрь")
_ПЕРИОД = re.compile(r"^(?:%s)\s+\d{4}\s*$" % _МЕСЯЦЫ)
# ДАТА НАЧАЛА В ВЫГРУЗКЕ ИДЁТ С ВИСЯЧИМ ТИРЕ: «Июнь 2025 —», и конец
# стоит СЛЕДУЮЩЕЙ строкой. Прежний признак `^Месяц Год$` её не ловил,
# и место опознавалось со ВТОРОЙ строки — дата начала оставалась выше,
# а человек видел «Апрель 2026 — 11 месяцев» вместо
# «Июнь 2025 — Апрель 2026 · 11 месяцев» (замер 2026-09-20, 13 мест
# из 13 на двух боевых выгрузках).
_ДАТА_НАЧАЛА = re.compile(r"^(?:%s)\s+\d{4}\s*[—–-]\s*$" % _МЕСЯЦЫ)
_ПО_СЕЙЧАС = re.compile(r"^по настоящее время\s*$", re.I)
_ДЛИТЕЛЬНОСТЬ = re.compile(
    r"^\d+\s+(?:год|года|лет)(?:\s+\d+\s+месяц(?:а|ев)?)?\s*$|"
    r"^\d+\s+месяц(?:а|ев)?\s*$")
# Подотрасль выгрузка печатает маркером; строка с ним — ЧАСТЬ ШАПКИ
# места, какой бы длинной ни была.
_ПОДОТРАСЛЬ = re.compile(r"^[•·]\s*")
# «Москва, example.ru/» — город и сайт компании: запятую и домен
# со слэшем печатает сама выгрузка. Это ЕДИНСТВЕННЫЙ признак, по которому
# город виден из строки.
_САЙТ = re.compile(r"[a-z0-9-]+\.[a-z]{2,}/?\s*$", re.I)
# КОЛОНТИТУЛ PDF: hh.ru печатает его на КАЖДОЙ странице, и в тексте он
# оказывается между разделами. В самом тексте его не трогаем — он часть
# резюме, — а при показе прячем и дату выводим один раз.
_КОЛОНТИТУЛ = re.compile(r"Резюме\s+обновлено\s+(.+)$", re.I)


def _заголовок_строки(строка):
    """Какой заголовок в строке. Не заголовок — None."""
    ст = строка.strip()
    if not ст:
        return None
    if ст in ЗАГОЛОВКИ:
        return ст
    for з in sorted(ЗАГОЛОВКИ_С_ХВОСТОМ, key=len, reverse=True):
        # Следующий знак обязан быть разделителем — иначе «Обо мне»
        # поймалось бы внутри слова, начинающегося так же.
        if ст.startswith(з) and (len(ст) == len(з) or not ст[len(з)].isalnum()):
            return з
    return None


def разобрать(текст):
    """Список разделов: [{имя, заголовок, тело, начало, конец}].

    `начало` и `конец` — срез ИСХОДНОГО текста, принадлежащий разделу
    целиком (включая перевод строки в конце). Куски идут подряд и без
    пропусков: их склейка равна исходному тексту до знака.
    """
    if not текст:
        return []

    # Границы строк вместе с их переводами: работаем со СМЕЩЕНИЯМИ,
    # а не со списком строк, — склейка через "\n" потеряла бы сведения
    # о том, чем кончался файл, и собрать() дало бы другой текст.
    куски, поз = [], 0
    while поз < len(текст):
        конец = текст.find("\n", поз)
        конец = len(текст) if конец < 0 else конец + 1
        куски.append((поз, конец))
        поз = конец

    # КАЖДЫЙ ЗАГОЛОВОК БЕРЁТСЯ ПЕРВЫМ ВХОЖДЕНИЕМ. Повтор того же имени
    # ниже по тексту — это содержимое, а не новый раздел: у выгрузки
    # hh.ru разделы не повторяются, а слово «Портфолио» встречается
    # в рассказе о себе дважды подряд (замер 2026-09-20).
    границы, взятые = [], set()
    for i, (а, б) in enumerate(куски):
        з = _заголовок_строки(текст[а:б])
        if з and з not in взятые:
            взятые.add(з)
            границы.append((i, з))

    if not границы:
        return [{"имя": ВЕСЬ_ТЕКСТ, "заголовок": "", "тело": текст,
                 "начало": 0, "конец": len(текст)}]

    разделы = []
    первый = границы[0][0]
    if первый > 0:
        конец = куски[первый - 1][1]
        разделы.append({"имя": КОНТАКТЫ, "заголовок": "",
                        "тело": текст[0:конец], "начало": 0, "конец": конец})

    for n, (строка, з) in enumerate(границы):
        а = куски[строка][0]
        б = куски[границы[n + 1][0] - 1][1] if n + 1 < len(границы) else len(текст)
        разделы.append({"имя": з, "заголовок": з, "тело": текст[а:б],
                        "начало": а, "конец": б})
    return разделы


def собрать(разделы):
    """Обратная разбору склейка. Равна исходному тексту побайтно."""
    return "".join(р["тело"] for р in разделы)


def заменить_тело(текст, индекс, новое):
    """Новый полный текст: кусок раздела `индекс` заменён на `новое`.

    Заменяется РОВНО кусок раздела; остальное не трогается ни на знак,
    и это главное свойство правки по частям.
    """
    разделы = разобрать(текст)
    if not (0 <= индекс < len(разделы)):
        raise IndexError("раздела %r нет: их %d" % (индекс, len(разделы)))
    р = разделы[индекс]
    return текст[:р["начало"]] + новое + текст[р["конец"]:]


def _описание_началось(с):
    """Первая строка описания: длинная либо с законченным предложением.

    Нужен, чтобы отделить ШАПКУ места (компания, город, отрасль,
    должность) от текста. Заголовочные строки выгрузки короткие и без
    точки в конце; описание — предложения. Строка подотрасли под признак
    не подпадает НИКОГДА: маркер «•» печатает формат, и без этой оговорки
    длинная подотрасль обрывала шапку, а должностью становилась отрасль
    (замер: 2 места из 13).
    """
    с = с.strip()
    if not с:
        return False
    if _ПОДОТРАСЛЬ.match(с):
        return False
    return len(с) > 70 or с.endswith(".") or ". " in с


def места_работы(тело):
    """Места работы внутри раздела «Опыт работы» — по ФОРМАТУ выгрузки.

    Порядок строк у hh.ru постоянный, и разбор идёт по нему, а не
    по догадке об одной строке:

        Июнь 2025 —              начало (висячее тире)
        Апрель 2026              конец либо «по настоящее время»
        11 месяцев               длительность
        Moon video               компания
        [Москва, site.ru/]       город и сайт — если выгрузка их дала
        [Видеопроизводство]      отрасль
        [• Фото- и видеоуслуги]  подотрасли, сколько угодно
        Инженер по зрению        должность
        …                        описание

    ГОРОД ОБЪЯВЛЯЕТСЯ ГОРОДОМ ТОЛЬКО ТАМ, ГДЕ ЭТО ВИДНО ИЗ СТРОКИ —
    по запятой с доменом. Одиночная строка без этих признаков городом
    и отраслью НЕРАЗЛИЧИМА: «Видеопроизводство» и «Санкт-Петербург»
    стоят на одном месте и одинаковы по виду, а список городов — перечень
    на открытом множестве (§6.0.7). Такая строка показывается приглушённо
    как отрасль, без утверждения, что это город. ЦЕНА НАЗВАНА: город
    без сайта отдельной строкой не выделится. Ошибка в обратную сторону
    дороже — прежний разбор объявлял городом что придётся, и у места без
    города город занимала отрасль либо должность (замер 2026-09-20:
    у 13 мест из 13 должность стояла не на своём месте).

    Возвращает список полей ТОЛЬКО ДЛЯ ПОКАЗА плюс `начало`/`конец` —
    срез внутри тела раздела: по ним правится ровно кусок одного места
    (`заменить_место`), и побайтность от этого не страдает.
    """
    строки = тело.split("\n")
    # Смещения строк внутри тела — чтобы отдать срез каждого места
    смещения, поз = [], 0
    for с in строки:
        смещения.append(поз)
        поз += len(с) + 1

    начала = []
    i = 0
    while i < len(строки):
        с = строки[i].strip()
        if not (_ДАТА_НАЧАЛА.match(с) or _ПЕРИОД.match(с)):
            i += 1
            continue
        хвост = [x.strip() for x in строки[i + 1:i + 4]]
        if not any(_ДЛИТЕЛЬНОСТЬ.match(x) for x in хвост if x):
            i += 1
            continue
        начала.append(i)
        # ПРЫГАЕМ ЗА СТРОКУ ДЛИТЕЛЬНОСТИ: вторая строка периода сама
        # подходит под признак начала, и без прыжка одно место
        # разрывалось надвое.
        j = i + 1
        while j < len(строки) and j <= i + 3:
            if _ДЛИТЕЛЬНОСТЬ.match(строки[j].strip()):
                break
            j += 1
        i = j + 1

    места = []
    for n, i in enumerate(начала):
        стоп = начала[n + 1] if n + 1 < len(начала) else len(строки)
        кусок = строки[i:стоп]
        # КОЛОНТИТУЛ PDF НЕ ПОКАЗЫВАЕТСЯ И ВНУТРИ МЕСТА. hh.ru печатает
        # подпись на каждой странице, и между местами работы она попадает
        # прямо в описание: человек читал «Имя • Резюме обновлено 27 мая
        # 2026» посреди рассказа о работе. В ТЕЛЕ строка остаётся (`тело`
        # ниже — дословный срез, им же правится место), убран только ПОКАЗ.
        непустые = [с.strip() for с in кусок
                    if с.strip() and колонтитул(с) is None]
        начало_д = конец_д = длительность = ""
        к = 0
        if к < len(непустые):
            начало_д = непустые[к].rstrip(" —–-").strip()
            к += 1
        if к < len(непустые) and (_ПЕРИОД.match(непустые[к])
                                  or _ПО_СЕЙЧАС.match(непустые[к])):
            конец_д = непустые[к]
            к += 1
        if к < len(непустые) and _ДЛИТЕЛЬНОСТЬ.match(непустые[к]):
            длительность = непустые[к]
            к += 1

        шапка = []
        for с in непустые[к:]:
            if шапка and _описание_началось(с):
                break
            шапка.append(с)
        описание = непустые[к + len(шапка):]

        компания = шапка[0] if шапка else ""
        остаток = шапка[1:]
        город = сайт = отрасль = должность = ""
        подотрасли = [с for с in остаток if _ПОДОТРАСЛЬ.match(с)]
        if подотрасли:
            первая = остаток.index(подотрасли[0])
            последняя = остаток.index(подотрасли[-1])
            if первая > 0:
                отрасль = остаток[первая - 1]
            до = остаток[:max(0, первая - 1)]
            после = остаток[последняя + 1:]
        else:
            до, после = остаток, []
        if после:
            должность = после[0]
            до = до + после[1:]
        elif до:
            должность = до[-1]
            до = до[:-1]
        прочее = []
        for с in до:
            if "," in с and _САЙТ.search(с) and not город:
                город, сайт = [ч.strip() for ч in с.split(",", 1)]
            else:
                прочее.append(с)
        if прочее and not отрасль:
            отрасль = прочее[0]
            прочее = прочее[1:]

        период = начало_д + (" — " + конец_д if конец_д else "")
        конец_среза = (смещения[стоп] if stop_ok(стоп, смещения) else len(тело))
        места.append({
            "период": период, "длительность": длительность,
            "компания": компания, "город": город, "сайт": сайт,
            "отрасль": отрасль, "подотрасли": подотрасли + прочее,
            "должность": должность, "описание": "\n".join(описание),
            "начало": смещения[i], "конец": конец_среза,
            "тело": тело[смещения[i]:конец_среза],
        })
    return места


def stop_ok(стоп, смещения):
    return стоп < len(смещения)


def заменить_место(текст, индекс_раздела, индекс_места, новое):
    """Заменить в полном тексте резюме кусок ОДНОГО места работы.

    Правка по карточкам мест (решение владельца 2026-09-20): раздел
    «Опыт работы» — самый длинный в резюме, и править его целиком значит
    держать перед глазами девять мест ради одной строки.

    Побайтность не страдает: место — это СРЕЗ внутри тела раздела,
    остальной текст не трогается ни на знак; проверяется тем же
    тождеством, что и раздел.
    """
    разделы = разобрать(текст)
    if not 0 <= индекс_раздела < len(разделы):
        raise IndexError("раздела нет")
    р = разделы[индекс_раздела]
    места = места_работы(р["тело"])
    if not 0 <= индекс_места < len(места):
        raise IndexError("места нет")
    м = места[индекс_места]
    тело = р["тело"][:м["начало"]] + новое + р["тело"][м["конец"]:]
    return заменить_тело(текст, индекс_раздела, тело)


def колонтитул(строка):
    """Дата из колонтитула PDF либо None.

    hh.ru печатает подпись на КАЖДОЙ странице выгрузки, и в тексте она
    оказывается между разделами: «Пётр Иванов  •  Резюме обновлено
    27 мая 2026». В ТЕКСТЕ ОНА НЕ ТРОГАЕТСЯ — это часть резюме, и побайтная
    сборка на ней держится; прячется только ПОКАЗ, а дата выводится один
    раз рядом с заголовком вкладки.
    """
    м = _КОЛОНТИТУЛ.search(строка or "")
    return м.group(1).strip() if м else None


def дата_обновления(текст):
    """Дата обновления резюме — из первого колонтитула. Нет — None."""
    for с in (текст or "").split("\n"):
        д = колонтитул(с)
        if д:
            return д
    return None


def без_колонтитулов(текст):
    """Текст без строк колонтитула — ДЛЯ ПОКАЗА."""
    return "\n".join(с for с in (текст or "").split("\n")
                     if колонтитул(с) is None)


_ЯЗЫК = re.compile(r"^\s*([^—–-]{2,40}?)\s*[—–-]\s*(.+?)\s*$")


def языки(тело):
    """Языки из блока «Знание языков»: [(язык, уровень)].

    Выгрузка держит их ВНУТРИ раздела «Навыки» обычными строками
    «Русский — Родной». Чипами навыков они быть не должны — карточка
    утверждала бы, что родной язык это навык, — и списком навыков тоже:
    у языка есть уровень, и пара «язык — уровень» это другая сущность.
    """
    найдено, внутри = [], False
    for строка in (тело or "").split("\n"):
        ст = строка.strip()
        if not ст:
            continue
        if ст.lower().startswith("знание языков"):
            внутри = True
            # ПЕРВЫЙ ЯЗЫК СТОИТ В ТОЙ ЖЕ СТРОКЕ, что и подпись блока:
            # выгрузка печатает «Знание языков Русский — Родной» одной
            # строкой (замер по двум боевым выгрузкам 2026-09-20).
            # Первая версия пропускала строку целиком и теряла язык.
            хвост = ст[len("знание языков"):].strip()
            м = _ЯЗЫК.match(хвост) if хвост else None
            if м:
                найдено.append((м.group(1).strip(), м.group(2).strip()))
            continue
        if not внутри:
            continue
        # Блок кончается там, где начинается следующий заголовок выгрузки
        if _строка_навыков(ст) or ст in ЗАГОЛОВКИ:
            break
        м = _ЯЗЫК.match(ст)
        if not м:
            break
        найдено.append((м.group(1).strip(), м.group(2).strip()))
    return найдено


def остаток_без_языков(текст):
    """Текст без блока языков: он показывается своим списком."""
    строки = (текст or "").split("\n")
    итог, внутри = [], False
    for с in строки:
        ст = с.strip()
        if ст.lower().startswith("знание языков"):
            внутри = True
            continue
        if внутри:
            if not ст:
                continue
            if _ЯЗЫК.match(ст) and not _строка_навыков(ст) and ст not in ЗАГОЛОВКИ:
                continue
            внутри = False
        итог.append(с)
    return "\n".join(итог)


def показ(раздел):
    """Текст раздела ДЛЯ ЭКРАНА: без строки заголовка над ним.

    ТЕЛО ПРИ ЭТОМ НЕ ТРОГАЕТСЯ НИ НА ЗНАК — правится и хранится оно целиком,
    и побайтная сборка от этого не зависит. Срезается только ПОКАЗ: имя
    раздела уже стоит шапкой карточки, и печатать его второй раз строкой
    ниже значит сказать одно и то же дважды (замер на выгрузке hh.ru:
    так выглядели семь разделов из восьми).

    У заголовка С ХВОСТОМ («Опыт работы — 11 лет 4 месяца») срезается
    ТОЛЬКО слово заголовка: хвост — это данные, и терять их нельзя.
    """
    тело = раздел["тело"]
    з = раздел.get("заголовок") or ""
    if not з:
        return тело
    конец = тело.find("\n")
    первая = тело if конец < 0 else тело[:конец]
    остаток = "" if конец < 0 else тело[конец + 1:]
    хвост = первая.strip()[len(з):].strip(" \u2014-\u2013:\t")
    return (хвост + "\n" + остаток) if хвост else остаток


def _строка_навыков(строка):
    ст = строка.strip()
    for з in ("Ключевые навыки", "Навыки"):
        if ст.startswith(з) and re.search(r"\s{2,}", ст[len(з):]):
            return True
    return False


def навыки(тело):
    """Отдельные навыки из раздела «Ключевые навыки» / «Навыки».

    ЧИПАМИ ПОКАЗЫВАЕТСЯ ТОЛЬКО ТА СТРОКА, ГДЕ hh.ru ПЕРЕЧИСЛИЛ НАВЫКИ
    через набеги пробелов. Признак «весь раздел — навыки» замер опроверг:
    внутри раздела «Навыки» выгрузка держит ещё и «Знание языков»
    обычными строками, и они уезжали в чипы наравне с Premiere Pro —
    то есть карточка утверждала, что «Русский — Родной» это навык.
    """
    for строка in тело.split("\n"):
        ст = строка.strip()
        for з in ("Ключевые навыки", "Навыки"):
            if not ст.startswith(з):
                continue
            хвост = ст[len(з):]
            if not re.search(r"\s{2,}", хвост):
                continue
            найдено = [к.strip() for к in re.split(r"\s{2,}|\t", хвост) if к.strip()]
            if len(найдено) > 1:
                return найдено
    return []


def остаток_без_навыков(текст):
    """Текст без той строки, что ушла в чипы: показать её дважды значит
    сказать одно и то же двумя способами."""
    строки = [с for с in текст.split("\n") if not _строка_навыков(с)]
    return "\n".join(строки)

"""ПРОГНАТЬ ВСЕ ОТРИЦАТЕЛЬНЫЕ КОНТРОЛИ И НАПЕЧАТАТЬ ТАБЛИЦУ.

BACKLOG №222, блок F.3. `check_controls.py` отвечает на вопрос
«ОБЪЯВЛЕНО ли доказательство» — то есть читает код и ничего не
запускает. Вопрос «а ловит ли подлог НА САМОМ ДЕЛЕ» ею не задаётся
по построению, и до 2026-09-01 его не задавал никто: контроли гоняли
поодиночке, когда трогали соответствующую пробу.

Разница не формальная. Объявленное доказательство может не сработать —
ровно это и показал заход 202 на трёх контролях сразу (подлог метил
в чужой элемент, замер шёл не в тот момент, мерился не тот элемент).
Опись сказала бы про них «ДОКАЗАН».

НЕ ПРОВЕРКА, А МЕРКА: код возврата всегда 0. Сколько контролей должно
проходить — решение о работе, а не о коде; плюс часть из них требует
стенда, живой модели или сети, и красный тут означал бы «условия
прогона не собраны», а не «контроль сломан».

ИСХОДОВ ЧЕТЫРЕ, А НЕ ДВА, и это главное в таблице:

  ЛОВИТ        контроль прогнался и объявил себя пройденным
  НЕ ЛОВИТ     прогнался и НЕ поймал подлог — находка
  НЕ ПРОГНАН   не собрались условия (нет стенда, сети, кредитов)
  ОБОРВАН      не уложился в потолок времени

«НЕ ПРОГНАН» и «ЛОВИТ» обязаны различаться: свести их значило бы
печатать зелёное про то, чего не спрашивали (§6.0.1).

  py run_controls.py             # все, кроме требующих живой модели
  py run_controls.py --всё       # включая те, что жгут кредиты
  py run_controls.py --только X  # один файл
"""
import os
import subprocess
import sys
import time

import check_controls as оп

ПОТОЛОК = int(os.environ.get("CONTROL_TIMEOUT", "900"))

# ЖИВАЯ МОДЕЛЬ — ОТДЕЛЬНЫМ КЛЮЧОМ. Эти контроли платят за каждый
# прогон кредитами, и гонять их «заодно» с остальными нельзя: заход
# 193 ровно так и выжег остаток (§5.8, разбор A.7 задачи 196).
ЖГУТ_КРЕДИТЫ = {"check_medkit_assist.py", "check_medkit_query.py",
                "check_model_errors.py"}

# ПИШУТ В БАЗУ СТЕНДА. Не исключаются, но называются: после них стенд
# надо пересеять, иначе следующая проба снимет чужой мусор
# (§6.0.3, шестая причина неповторимости).
ПИШУТ_В_БАЗУ = {"check_medkit_ui.py", "check_medkit_circle.py",
                "check_admin_ui.py", "check_ens_admin_ui.py",
                "check_exercises_ui.py", "check_medkit_dupe.py",
                "check_medkit_manual.py", "make_local_user.py"}


def прогнать(файл):
    т0 = time.time()
    try:
        р = subprocess.run([sys.executable, файл, "--контроль"],
                           capture_output=True, timeout=ПОТОЛОК)
    except subprocess.TimeoutExpired:
        return "ОБОРВАН", ПОТОЛОК, "не уложился в %d с" % ПОТОЛОК
    сек = time.time() - т0
    вывод = (р.stdout or b"").decode("utf-8", "replace")
    ошибки = (р.stderr or b"").decode("utf-8", "replace")
    низ = вывод.lower()
    # ПРИЗНАК БЕРЁТСЯ ИЗ ВЫВОДА, А НЕ ТОЛЬКО ИЗ КОДА ВОЗВРАТА: часть
    # контролей — мерки, у которых код всегда 0, и по нему одному
    # «прогнался» было бы неотличимо от «поймал».
    if "контроль не пройден" in низ or "не найден" in низ or \
       "проба слепа" in низ:
        return "НЕ ЛОВИТ", сек, "объявил себя непройденным"
    if "контроль пройден" in низ or "подлог найден" in низ or \
       "найдено подлогов: 0" in низ or "ловит" in низ:
        return "ЛОВИТ", сек, ""
    # условия не собрались — стенд, сеть, база
    подсказки = [
        ("остановлено", "проба остановилась сама"),
        ("вход не состоялся", "нет стенда либо не пускает вход"),
        ("connection refused", "стенд не поднят"),
        ("нужен стенд", "нет стенда"),
        ("econnrefused", "стенд не поднят"),
        ("net::err", "стенд не отвечает"),
        ("traceback", "упал с исключением"),
    ]
    для_поиска = низ + ошибки.lower()
    for метка, текст in подсказки:
        if метка in для_поиска:
            return "НЕ ПРОГНАН", сек, текст
    if р.returncode == 0:
        return "ЛОВИТ", сек, "код 0, явной строки нет"
    return "НЕ ПРОГНАН", сек, "код %d, разбирать вывод" % р.returncode


def main():
    всё = "--всё" in sys.argv
    один = None
    if "--только" in sys.argv:
        один = sys.argv[sys.argv.index("--только") + 1]
    # СПИСОК БЕРЁТСЯ У ОПИСИ, А НЕ СОБИРАЕТСЯ ЗАНОВО: у неё признак
    # структурный (обход синтаксического дерева), и вторая реализация
    # разошлась бы с ней молча — печатала бы «прогнали все» про другое
    # множество (§6.0.7).
    файлы = [с["файл"] for с in оп.опись()]
    файлы = [f for f in файлы if f != "run_controls.py"]
    if один:
        файлы = [один]
    print("ПРОГОН ОТРИЦАТЕЛЬНЫХ КОНТРОЛЕЙ — ловят ли они подлог")
    print("=" * 72)
    print("  потолок на контроль: %d с; живая модель: %s"
          % (ПОТОЛОК, "включена (--всё)" if всё else "ПРОПУЩЕНА"))
    print()
    print("  %-28s %-11s %7s  %s" % ("проба", "исход", "сек", "примечание"))
    счёт = {}
    for ф in файлы:
        if ф in ЖГУТ_КРЕДИТЫ and not всё:
            исход, сек, прим = "НЕ ПРОГНАН", 0.0, "жжёт кредиты, нужен --всё"
        else:
            исход, сек, прим = прогнать(ф)
        if ф in ПИШУТ_В_БАЗУ and исход != "НЕ ПРОГНАН":
            прим = (прим + "; " if прим else "") + "ПИШЕТ В БАЗУ — пересеять"
        счёт[исход] = счёт.get(исход, 0) + 1
        print("  %-28s %-11s %7.1f  %s" % (ф, исход, сек, прим))
    print()
    print("  ИТОГО: " + ", ".join("%s %d" % (к, счёт[к])
                                  for к in sorted(счёт)))
    print()
    print("«НЕ ЛОВИТ» — находка: ноль такой пробы не значит ничего.")
    print("«НЕ ПРОГНАН» — условия не собрались, и это НЕ зелёный:")
    print("вопрос не задавался (§6.0.1).")
    return 0


if __name__ == "__main__":
    sys.exit(main())

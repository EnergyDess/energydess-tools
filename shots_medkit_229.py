# -*- coding: utf-8 -*-
"""СНИМКИ ЗАХОДА 229: шторка «Способ приёма» во ВСЕХ ТРЁХ состояниях
показаний, карточка только со своей записью и ряд управления
с кнопкой перепроверки.

НЕ ПРОВЕРКА, кадры смотрит человек: код возврата всегда 0.

ПОЗИЦИИ ИЩУТСЯ ПО СОСТОЯНИЮ, А НЕ ПО НОМЕРУ. Первая карточка сегодня
одна, завтра другая; состояние же задано полями, и снимок с подписью
«не спрашивали» обязан показывать именно его — иначе кадр молча
показал бы соседнее состояние, а подпись под ним осталась бы прежней.

ТРИ СОСТОЯНИЯ, А НЕ ДВА, — в этом весь заход. «Показаний на странице
нет» и «мы их не спрашивали» выглядели на экране ОДИНАКОВО, и второе
печаталось как утверждение о чужой странице (BACKLOG №229, блок A).
На одном кадре эти два состояния неразличимы по построению.

ШИРИНЫ 2560 И 390 — их назвал владелец; 1440 среди них нет намеренно,
экрана такой ширины у него не существует (тот же довод, что у задачи
143).

    py shots_medkit_229.py
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from playwright.sync_api import sync_playwright   # noqa: E402

# ВХОД БЕРЁТСЯ У `check_hover`, А НЕ У `check_medkit_look`:
# у второго он АСИНХРОННЫЙ, и вызванный без `await` он молча
# ничего не делает — кадры вышли бы гостевыми, а подпись
# под ними осталась бы прежней (§6.0).
import check_hover as H                           # noqa: E402

БАЗА = os.environ.get("HOVER_BASE", "http://127.0.0.1:8899")
КУДА = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    "review_screenshots")

# СОСТОЯНИЕ ПОЗИЦИИ СЧИТАЕТСЯ ТЕМ ЖЕ ПРИЗНАКОМ, ЧТО У ЭКРАНА, —
# полем `показания_спрашивали` с сервера. Свой признак в снимке
# разошёлся бы с показом молча, и кадр подписывался бы не тем.
СОСТОЯНИЯ = """() => {
  const из = {};
  for (const п of АПТ_ПОЗИЦИИ) {
    const схема = (п['дозы'] || '').trim();
    const пок = (п['показания'] || '').trim();
    let к;
    if (!схема) к = (п['своя_схема'] || '').trim() ? 'только-своя' : null;
    else if (пок) к = 'показания-есть';
    else к = п['показания_спрашивали'] ? 'спросили-нет' : 'не-спрашивали';
    if (к && !из[к]) из[к] = {id: п.id, name: п.name};
  }
  return из;
}"""


def снять(стр, имя, ширина):
    os.makedirs(КУДА, exist_ok=True)
    путь = os.path.join(КУДА, "229-%s-%d.png" % (имя, ширина))
    стр.screenshot(path=путь)
    print("   %s" % os.path.basename(путь))


def прогон(бр, ширина, высота, тач):
    ctx = бр.new_context(viewport={"width": ширина, "height": высота},
                         has_touch=тач, is_mobile=тач)
    стр = ctx.new_page()
    H._войти(стр)
    стр.goto(БАЗА + "/medkit", wait_until="domcontentloaded")
    стр.wait_for_load_state("networkidle")
    стр.wait_for_timeout(700)

    print("── ширина %d ──" % ширина)
    # 1. РЯД УПРАВЛЕНИЯ С ЧЕТВЁРТОЙ КНОПКОЙ (блок C)
    стр.evaluate("() => document.querySelector('.apt-bar')"
                 ".scrollIntoView({block: 'center'})")
    стр.wait_for_timeout(300)
    снять(стр, "ряд-управления", ширина)

    # 2. ОКНО ПЕРЕПРОВЕРКИ: обещание стоит ДО кнопки
    стр.evaluate("() => открыть_модалку('apt-recheck-win')")
    стр.wait_for_timeout(500)
    снять(стр, "окно-перепроверки", ширина)
    стр.keyboard.press("Escape")
    стр.wait_for_timeout(300)

    # 3. ТРИ СОСТОЯНИЯ ПОКАЗАНИЙ ПЛЮС КАРТОЧКА ТОЛЬКО СО СВОЕЙ ЗАПИСЬЮ
    сост = стр.evaluate(СОСТОЯНИЯ)
    for ключ in ("показания-есть", "спросили-нет", "не-спрашивали",
                 "только-своя"):
        п = сост.get(ключ)
        if not п:
            # НЕ МОЛЧА: состояние, которого на стенде нет, обязано быть
            # названо — кадр без него выглядел бы просто отсутствующим
            print("   ! состояния «%s» на стенде нет" % ключ)
            continue
        стр.evaluate("(id) => аптДозыОткрыть(id)", п["id"])
        стр.wait_for_timeout(550)
        снять(стр, "шторка-" + ключ, ширина)
        стр.keyboard.press("Escape")
        стр.wait_for_timeout(300)
    ctx.close()


def main():
    print("СНИМКИ ЗАХОДА 229 → %s" % КУДА)
    with sync_playwright() as pw:
        бр = pw.chromium.launch()
        прогон(бр, 2560, 1440, False)
        прогон(бр, 390, 844, True)
        бр.close()
    print("готово")
    return 0


if __name__ == "__main__":
    sys.exit(main())

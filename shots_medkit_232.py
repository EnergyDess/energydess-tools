# -*- coding: utf-8 -*-
"""СНИМКИ ЗАХОДА 232 — то, что владелец увидит своими глазами.

НЕ ПРОВЕРКА, кадры смотрит человек. Код возврата всегда 0.

ЧТО СНИМАЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО:

  · ЗАВЕДЕНИЕ КАРТОЧКИ ТЕКСТОМ — главный кадр блока A. Владелец
    собирается заводить вторую половину аптечки, и вопрос кадра
    один: не дописала ли модель вещество, которого он не называл;
  · ПОДСТАНОВКА ВЕЩЕСТВА ИЗ СПРАВОЧНИКА — кнопка «Вписать» блока B.
    Она существует с задачи 199, но её никто не снимал;
  · ПЛАШКА ПЕРЕПРОВЕРКИ на трёх состояниях — пустая, ход с длинным
    именем, итог со списком изменённых позиций (блок C).

ОТВЕТ МОДЕЛИ ЖИВОЙ, и кадр ждёт разблокировки кнопки отправки,
а не таймера: подставленный показывал бы не то, что увидит владелец,
а снимок по таймеру поймал бы «Смотрю…».

ПЛАШКА НАБИВАЕТСЯ БОЕВЫМ ПОСТРОИТЕЛЕМ `аптПерепроверкаХод`, а полный
обход не гоняется: он ходит в чужой справочник по двадцати позициям,
и снимок не должен этого стоить. Итоговый список рисуется тем же
`аптПерепроверкаСписок`, что и на бою, — своя разметка показала бы
экран, которого нет.

    py -m uvicorn main:app --port 8899
    py shots_medkit_232.py
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

БАЗА = os.environ.get("MEDKIT_BASE", "http://127.0.0.1:8899")
ПОЧТА = "screenshot@local.dev"
ПАРОЛЬ = "Screenshot-Local-2026"
# ШИРИНЫ НАЗВАЛ ВЛАДЕЛЕЦ: у него два монитора, 2560 и телефон 390.
# 1440 среди них нет намеренно — экрана такой ширины у него не существует
ШИРИНЫ = [2560, 390]
КУДА = os.environ.get("SHOTS_DIR", "review_screenshots")

# ЧИСТКА ПЕРЕПИСКИ — БОЕВЫМ ЭНДПОИНТОМ, а не подстановкой в базу:
# подстановка показала бы не то состояние, которое рисует сервер
ЧИСТКА_ПЕРЕПИСКИ = (
    "async () => { await fetch('/medkit/api/chat',"
    " {method: 'DELETE'}); }")


def кадр(стр, имя, ширина, селектор=None):
    os.makedirs(КУДА, exist_ok=True)
    путь = os.path.join(КУДА, "232-%s-%d.png" % (имя, ширина))
    if селектор:
        эл = стр.query_selector(селектор)
        if эл is None:
            print("   [%d] %-34s ЭЛЕМЕНТА НЕТ — кадр не снят"
                  % (ширина, имя))
            return
        эл.screenshot(path=путь)
    else:
        стр.screenshot(path=путь)
    print("   [%d] %s" % (ширина, путь))


def войти(стр):
    стр.goto(БАЗА + "/login", wait_until="domcontentloaded")
    стр.fill("input[name=email]", ПОЧТА)
    стр.fill("input[name=password]", ПАРОЛЬ)
    стр.click("button[type=submit]")
    стр.wait_for_timeout(2500)
    if "/login" in стр.url:
        raise SystemExit("вход не состоялся — снимать нечего")


def заведение_текстом(стр, ширина):
    """ГЛАВНЫЙ КАДР БЛОКА A: что ассистент заполнил по одному тексту."""
    стр.goto(БАЗА + "/medkit", wait_until="load")
    стр.wait_for_timeout(1200)
    кн = стр.query_selector("#apt-ai-open") or стр.query_selector(
        "[onclick*='аптАИОткрыть']")
    if кн is None:
        print("   [%d] кнопки панели нет" % ширина)
        return
    кн.click()
    стр.wait_for_timeout(900)
    # ПЕРЕПИСКА ЧИСТИТСЯ ТЕМ ЖЕ ЭНДПОИНТОМ, ЧТО У КНОПКИ ЧЕЛОВЕКА:
    # кадр обязан показывать ответ на ЭТОТ вопрос, а не хвост прошлого
    # разговора, — и не заслон повтора, который срабатывает на второй
    # ширине, потому что переписка ОБЩАЯ (задача 193, блок B)
    стр.evaluate(ЧИСТКА_ПЕРЕПИСКИ)
    стр.reload(wait_until='load')
    стр.wait_for_timeout(1200)
    кн = стр.query_selector('#apt-ai-open')
    кн.click()
    стр.wait_for_timeout(900)
    # ПОЛЕ И КНОПКА — ПО id, а не по классу ряда: в том же ряду
    # лежат СКРЫТЫЕ поля файла, и `.apt-ai-row input` попадал
    # в первое из них — кадр падал по таймауту «element is not
    # visible», то есть проба ждала невидимое поле загрузки
    стр.wait_for_selector("#apt-ai-in", state="visible", timeout=15000)
    поле = стр.query_selector("#apt-ai-in")
    if поле is None:
        print("   [%d] поля ввода панели нет" % ширина)
        return
    поле.fill("занеси Цитрамон П, 10 таблеток")
    отпр = стр.query_selector("#apt-ai-send")
    отпр.click()
    # ЖДЁМ РАЗБЛОКИРОВКИ КНОПКИ, А НЕ ТАЙМЕРА: снимок по таймеру
    # поймал бы «Смотрю…» вместо ответа
    for _ in range(90):
        стр.wait_for_timeout(1000)
        if not отпр.is_disabled():
            break
    стр.wait_for_timeout(700)
    # ПАНЕЛЬ — `#apt-ai`, а не `.apt-ai-panel`: класса с таким
    # именем в разметке нет вовсе, и кадр молча не снимался
    кадр(стр, "заведение-текстом", ширина, "#apt-ai")


def подстановка_вещества(стр, ширина):
    """БЛОК B: кнопка «Вписать вещество из справочника».

    ПОЗИЦИЯ ИЩЕТСЯ ПО ФАКТУ ПОДСКАЗКИ, а не по номеру: карточка
    с исходом «вещество названо иначе» сегодня одна, завтра другая.
    """
    стр.goto(БАЗА + "/medkit", wait_until="load")
    стр.wait_for_timeout(1200)
    # `АПТ_ПОЗИЦИИ` ОБЪЯВЛЕН ЧЕРЕЗ `let`, И СВОЙСТВА `window` ОН
    # НЕ СОЗДАЁТ ВОВСЕ — та же ловушка, на которой не состоялись
    # подлоги задачи 181. Обращаемся по ИМЕНИ, а не через `window`
    id_ = стр.evaluate("""() => {
      try {
        const п = (АПТ_ПОЗИЦИИ || []).find(
          (x) => (x['вещество_подсказка'] || '').trim());
        return п ? п.id : 0;
      } catch (e) { return -1; }
    }""")
    if id_ == -1:
        print("   [%d] АПТ_ПОЗИЦИИ недоступен — кадр не снят" % ширина)
        return
    if not id_:
        print("   [%d] позиции с подсказкой вещества на стенде НЕТ — "
              "кадр не снят (§8.0)" % ширина)
        return
    стр.evaluate("(id) => аптДозыОткрыть(id)", id_)
    стр.wait_for_timeout(900)
    кадр(стр, "вещество-из-справочника", ширина, "#apt-doses .modal-sh")


def плашка(стр, ширина):
    """БЛОК C: три состояния окна перепроверки."""
    стр.goto(БАЗА + "/medkit", wait_until="load")
    стр.wait_for_timeout(1200)
    стр.evaluate("() => открыть_модалку('apt-recheck-win')")
    стр.wait_for_timeout(500)
    кадр(стр, "перепроверка-до-нажатия", ширина, "#apt-recheck-win .modal-sh")

    # ХОД С ДЛИННЫМ ИМЕНЕМ — то состояние, на котором окно скакало.
    # Зовётся БОЕВОЙ построитель, а не ставится текст напрямую
    стр.evaluate("""() => аптПерепроверкаХод(
        'Смотрю 7 из 20. Нашлось: 3.',
        'Флурибексин комплекс для кишечника усиленный с пребиотиком')""")
    стр.wait_for_timeout(300)
    кадр(стр, "перепроверка-ход", ширина, "#apt-recheck-win .modal-sh")

    # ИТОГ СО СПИСКОМ — тем же построителем, что на бою
    стр.evaluate("""() => {
      аптПерепроверкаХод('Готово. Перепроверено 20 из 34 — у остальных 14 '
        + 'схема уже есть. Схема нашлась у 3. Ваши записи с упаковки '
        + 'не тронуты.', '');
      аптПерепроверкаСписок(
        [{id: 1, name: 'Цитрамон П', 'своя': false},
         {id: 2, name: 'Мукалтин', 'своя': false},
         {id: 3, name: 'Валидол', 'своя': true}],
        [{id: 3, name: 'Валидол', 'своя': true}]);
    }""")
    стр.wait_for_timeout(400)
    кадр(стр, "перепроверка-итог-список", ширина,
         "#apt-recheck-win .modal-sh")


def main():
    from playwright.sync_api import sync_playwright
    print("СНИМКИ ЗАХОДА 232 → %s/" % КУДА)
    print("ВНИМАНИЕ: заводит позицию через ассистента — стенд пересеять")
    with sync_playwright() as p:
        бр = p.chromium.launch()
        for ш in ШИРИНЫ:
            кон = бр.new_context(viewport={"width": ш, "height": 1000},
                                 has_touch=(ш <= 640), is_mobile=(ш <= 640))
            стр = кон.new_page()
            войти(стр)
            плашка(стр, ш)
            подстановка_вещества(стр, ш)
            заведение_текстом(стр, ш)
            кон.close()
        бр.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())

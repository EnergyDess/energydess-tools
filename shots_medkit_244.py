import asyncio
import os
import sys
import probe_guard  # noqa: F401  ПРОПУСК вместо трассы (§6.0.1)

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

БАЗА = os.getenv("HOVER_BASE", "http://127.0.0.1:8899")
КУДА = "review_screenshots"
ПОЧТА = "screenshot@local.dev"
ПАРОЛЬ = "Screenshot-Local-2026"
ШИРИНЫ = [(2560, 1440), (390, 844)]


async def войти(pg):
    await pg.goto(БАЗА + "/login", wait_until="domcontentloaded")
    await pg.fill("input[name=email]", ПОЧТА)
    await pg.fill("input[name=password]", ПАРОЛЬ)
    await pg.click("button[type=submit]")
    await pg.wait_for_timeout(1200)


async def кадр(pg, имя, ш):
    путь = "%s/244-%s-%d.png" % (КУДА, имя, ш)
    await pg.screenshot(path=путь)
    print("   %s" % путь)


async def снять(pw, ш, в):
    br = await pw.chromium.launch()
    ctx = await br.new_context(viewport={"width": ш, "height": в},
                               has_touch=(ш < 700), is_mobile=(ш < 700))
    pg = await ctx.new_page()
    await войти(pg)
    print("── ширина %d ──" % ш)

    # ── 1. ШТОРКА СПОСОБА ПРИЁМА С ПРЕДЛОЖЕНИЕМ ─────────────────────
    #
    # Позиция ищется ПО ФАКТУ (есть и выдержка, и подсказка), а не
    # по номеру: первая карточка сегодня одна, завтра другая
    await pg.goto(БАЗА + "/medkit", wait_until="domcontentloaded")
    await pg.wait_for_timeout(900)
    ид = await pg.evaluate("""() => {
      const п = (АПТ_ПОЗИЦИИ || []).find(п =>
        п['дозы'] && (п['вещество_подсказка_иначе']
                      || п['форма_подсказка_иначе']));
      return п ? п.id : null;
    }""")
    if ид:
        await pg.evaluate("(id) => аптДозыОткрыть(id)", ид)
        await pg.wait_for_timeout(700)
        await кадр(pg, "шторка-подстановка", ш)
        await pg.evaluate("() => закрыть_модалку('apt-doses')")
    else:
        print("   ПРОПУЩЕНО: позиции со схемой И предложением на стенде нет")

    # ── 2. ОКНО УПАКОВОК НА ТРЁХ ПАЧКАХ ─────────────────────────────
    await pg.wait_for_timeout(300)
    группа = await pg.evaluate("""() => {
      const п = (АПТ_ПОЗИЦИИ || [])
        .find(п => (п['группа'] || []).length > 1);
      return п ? п.id : null;
    }""")
    if группа:
        await pg.evaluate("(id) => аптПачкиОткрыть(id)", группа)
        await pg.wait_for_timeout(600)
        await кадр(pg, "упаковки", ш)
        await pg.evaluate("() => закрыть_модалку('apt-packs-win')")
        await pg.wait_for_timeout(300)
        # ── 3. ФОРМА ПОСЛЕ «ЕЩЁ УПАКОВКА»: ПОЛЯ ЖИВЫЕ ───────────────
        await pg.evaluate(
            "(id) => { аптОткрытьФорму((АПТ_ПОЗИЦИИ || [])"
            "  .find(п => п.id === id), 'общее'); }", группа)
        await pg.wait_for_timeout(500)
        await pg.evaluate("() => аптЕщёУпаковка()")
        await pg.wait_for_timeout(500)
        погашено = await pg.evaluate(
            "() => ['apt-f-exp','apt-f-left','apt-f-total']"
            "  .filter(и => document.getElementById(и).disabled).length")
        print("   погашенных полей после «Ещё упаковка»: %d" % погашено)
        await кадр(pg, "форма-новой-пачки", ш)
        await pg.evaluate("() => закрыть_модалку('apt-form')")
    else:
        print("   ПРОПУЩЕНО: группы из нескольких пачек на стенде нет")

    # ── 4. ПОИСК ПО ОДНОЙ БУКВЕ ─────────────────────────────────────
    await pg.wait_for_timeout(300)
    await pg.fill("#apt-q", "п")
    await pg.wait_for_timeout(500)
    await кадр(pg, "поиск-одна-буква", ш)
    await pg.fill("#apt-q", "")
    await pg.wait_for_timeout(300)

    # ── 5. ОТВЕТ АССИСТЕНТА С ФОТО И ЦИТАТАМИ ───────────────────────
    #
    # Тело ПОДСТАВЛЯЕТСЯ, и это названо: живой вызов модели стоит
    # кредитов и отвечает каждый раз иначе, а вопрос кадра — «видно ли
    # фото, цитату и подзаголовок», то есть про ОТРИСОВКУ. Путь
    # отрисовки при этом боевой: рисует та же `аптАИОтвет`.
    await pg.evaluate("() => аптАИОткрыть()")
    await pg.wait_for_timeout(600)
    await pg.evaluate("""() => {
      const п = (АПТ_ПОЗИЦИИ || []).slice(0, 4);
      const стр = п.map((x, i) => ({
        id: x.id, 'строка': x['остаток_строкой']
          ? (x.name + ' · ' + x['остаток_строкой']) : x.name,
        'почему': x['форма_имя'] || '',
        'photo': x['photo'] || '',
        'показание': i < 2 ? 'Головная боль;' : '',
        'показания_есть': i < 3,
        'дозы': !!x['дозы'],
      }));
      аптАИОтвет({вид: 'запрос', тип: 'поиск',
        'вступление': 'Вот что по вашему запросу есть дома.',
        'нашлось': стр, 'просрочено': [], 'рецептурные': [],
        'разбивка': [], 'нет': '', 'группа': '',
        'по_показанию': 2, 'без_показаний': 1, 'подложено': [],
        'непросмотрено': 0, 'оговорка': ''});
    }""")
    await pg.wait_for_timeout(600)
    await кадр(pg, "ответ-ассистента", ш)
    await br.close()


async def главная():
    os.makedirs(КУДА, exist_ok=True)
    from playwright.async_api import async_playwright
    async with async_playwright() as pw:
        for ш, в in ШИРИНЫ:
            await снять(pw, ш, в)
    print("\nКадры смотрит человек — вердикта у этого прогона нет.")


if __name__ == "__main__":
    asyncio.run(главная())

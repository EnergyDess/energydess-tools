# -*- coding: utf-8 -*-
"""СВЕЖЕСТЬ ДАННЫХ СТЕНДА: «сегодня» у посева — сегодняшнее или вчерашнее.

═══════════════════════════════════════════════════════════════════════
ЗАЧЕМ (BACKLOG №322, заход 324)
═══════════════════════════════════════════════════════════════════════

Seed замораживает «сегодня» на дате посева: открытая тренировка, день
программы, съеденное за сегодня. Посеяли вечером, прогнали ряд стенда
после полуночи — и сцены «сегодня» показывают ВЧЕРАШНИЙ день. Проверка
20 на таких данных дала код 1: `.wk-ex-howto-toggle` ушёл на сцену,
где принятие не объявлено. Экран исправен, находка — про состояние
данных, а не про код (тот же класс, что задачи 281, 293, 309).

Решение владельца: пробу, чьи сцены зависят от «сегодня», на отставших
данных НЕ ГНАТЬ, а отвечать ПРОПУСКОМ с причиной. Принять орган на всех
сценах тренировок значило бы ослабить проверку навсегда ради случая,
который бывает раз в сутки.

═══════════════════════════════════════════════════════════════════════
ПРИЗНАК ОДИН, И ЖИВЁТ ОН ЗДЕСЬ
═══════════════════════════════════════════════════════════════════════

Прежде он жил внутри `make_local_user.опись` — и спросить его пробе
было нечем. Вторая копия в пробе разошлась бы с описью молча (§6.0.7):
опись говорила бы «отстали», проба мерила бы. Теперь опись и пробы
зовут `данные_отстали`.

Отстали — если у аккаунта съёмки последняя запись съеденного ИЛИ
последняя тренировка (не позже сегодня) датирована не сегодня.
Тренировки обязательны в признаке: у съеденного seed кладёт два
запланированных дня ВПЕРЁД, и вчерашний посев даёт запись «сегодня»
по плану — признак по одной еде вчерашний посев не видел бы.

Модуль ПУСТОЙ по зависимостям — только `sqlite3`: его импортирует
проба ряда стенда, и тянуть за собой `main` ради двух запросов нельзя.

═══════════════════════════════════════════════════════════════════════
КОМАНДЫ
═══════════════════════════════════════════════════════════════════════

    py stand_fresh.py                 # код 0 свежие, 1 отстали, 2 спросить нечем
    py stand_fresh.py --сдвинуть -1   # СОСТАРИТЬ посев на сутки (стенд!)
    py stand_fresh.py --сдвинуть 1    # вернуть
    py stand_fresh.py --контроль      # подлог на КОПИИ базы стенда

`--сдвинуть` нужен затем же, зачем `make_local_user --scale`: состояние,
которое нельзя поставить, не снимается и не проверяется (§8.0). Сдвиг
точен и обратим — даты сдвигаются арифметикой, по строке в порядке,
не задевающем уникальные ключи. Боевую базу не открывает вовсе.
"""
import os
import sqlite3
import sys
from datetime import date

ПОЧТА = "screenshot@local.dev"


def _путь(путь_базы=None):
    return путь_базы or os.environ.get("DB_PATH", "app.db")


def _боевая(путь):
    п = os.path.abspath(путь).replace(chr(92), "/")
    return (os.environ.get("FLY_APP_NAME") or "/data/" in п
            or "/data/" in путь.replace(chr(92), "/"))


def данные_отстали(путь_базы=None, сегодня=None):
    """[строка отставания]. Пусто — свежие ЛИБО спросить нечем.

    «Спросить нечем» (базы, аккаунта или записей нет) — не «отстали»:
    такой стенд проба встретит своим путём, и прятать его под ПРОПУСК
    по свежести значило бы соврать о причине."""
    путь = _путь(путь_базы)
    сегодня = сегодня or date.today().isoformat()
    if not os.path.exists(путь):
        return []
    try:
        c = sqlite3.connect("file:%s?mode=ro" % os.path.abspath(путь), uri=True)
    except sqlite3.Error:
        return []
    try:
        r = c.execute("SELECT id FROM users WHERE email=?", (ПОЧТА,)).fetchone()
        if not r:
            return []
        отставание = []
        for таблица, что in (("food_logs", "позиций съеденного"),
                             ("workout_sessions", "тренировок")):
            try:
                п = c.execute("SELECT MAX(log_date) FROM %s WHERE user_id=? "
                              "AND log_date <= ?" % таблица,
                              (r[0], сегодня)).fetchone()[0]
            except sqlite3.Error:
                continue
            if п and п != сегодня:
                отставание.append("%s: последняя дата %s" % (что, п))
        return отставание
    finally:
        c.close()


def пропуск_если_отстали(что_мерит, путь_базы=None):
    """True — данные отстали, ПРОПУСК уже сказан; вызывающий выходит кодом 2.

    Замер при этом НЕ ПРОВОДИТСЯ вовсе: мерить сцены «сегодня» на
    вчерашнем дне значит мерить не то, что подписано (§8.0). Настоящая
    находка тем самым не прячется — ПРОПУСК не равен «чисто», а на
    свежем посеве та же проба краснеет, как краснела."""
    отставание = данные_отстали(путь_базы)
    if not отставание:
        return False
    import probe_guard
    probe_guard.сказать_пропуск(
        "данные стенда отстали от суток — %s мерили бы вчерашний день"
        % что_мерит,
        "прогон %s; %s. Пересейте: py make_local_user.py --seed"
        % (date.today().isoformat(), "; ".join(отставание)))
    return True


def сдвинуть_дни(путь_базы, дни):
    """{таблица.колонка: строк}. Сдвигает ДАТЫ записей аккаунтов стенда.

    Берутся таблицы с `user_id` (и сами строки `users`) аккаунтов
    `@local.dev`, колонки, где лежит текст вида ГГГГ-ММ-ДД[...]. Порядок
    обхода зависит от знака: назад — от ранних к поздним, вперёд —
    наоборот, иначе `UNIQUE(user_id, дата)` упал бы на соседнем дне."""
    if _боевая(путь_базы):
        raise SystemExit("ОСТАНОВЛЕНО: боевая база не сдвигается.")
    c = sqlite3.connect(путь_базы, timeout=30)
    итог = {}
    try:
        ид = [r[0] for r in c.execute(
            "SELECT id FROM users WHERE email LIKE '%@local.dev'")]
        if not ид:
            return итог
        знаки = ",".join("?" * len(ид))
        сдвиг = "%+d day" % дни
        порядок = "ASC" if дни < 0 else "DESC"
        for (т,) in c.execute("SELECT name FROM sqlite_master "
                              "WHERE type='table'").fetchall():
            колонки = [r[1] for r in c.execute('PRAGMA table_info("%s")' % т)]
            ключ = ("id" if т == "users"
                    else "user_id" if "user_id" in колонки else None)
            if not ключ:
                continue
            for кол in колонки:
                строки = c.execute(
                    'SELECT rowid FROM "%s" WHERE "%s" IN (%s) AND '
                    'typeof("%s")=\'text\' AND "%s" GLOB '
                    '\'[12][0-9][0-9][0-9]-[01][0-9]-[0-3][0-9]*\' '
                    'ORDER BY "%s" %s' % (т, ключ, знаки, кол, кол, кол, порядок),
                    ид).fetchall()
                for (rid,) in строки:
                    c.execute('UPDATE "%s" SET "%s" = date(substr("%s",1,10),?)'
                              ' || substr("%s",11) WHERE rowid=?'
                              % (т, кол, кол, кол), (сдвиг, rid))
                if строки:
                    итог["%s.%s" % (т, кол)] = len(строки)
        c.commit()
    finally:
        c.close()
    return итог


def _отпечаток(путь):
    """Отпечаток всех строк аккаунтов стенда — для обратимости сдвига."""
    import hashlib
    c = sqlite3.connect(путь)
    h = hashlib.sha1()
    ид = [r[0] for r in c.execute(
        "SELECT id FROM users WHERE email LIKE '%@local.dev' ORDER BY id")]
    знаки = ",".join("?" * len(ид)) or "NULL"
    for (т,) in c.execute("SELECT name FROM sqlite_master WHERE type='table' "
                          "ORDER BY name").fetchall():
        колонки = [r[1] for r in c.execute('PRAGMA table_info("%s")' % т)]
        ключ = "id" if т == "users" else "user_id" if "user_id" in колонки else None
        if not ключ:
            continue
        for row in c.execute('SELECT * FROM "%s" WHERE "%s" IN (%s) ORDER BY rowid'
                             % (т, ключ, знаки), ид):
            h.update(repr(row).encode("utf-8"))
    c.close()
    return h.hexdigest()[:12]


def контроль():
    """ПОДЛОГ ЛОМАЕТ ПРИЗНАК СВЕЖЕСТИ, И ТОЛЬКО ЕГО — на КОПИИ базы.

    Три случая, у каждого своё доказательство (§6.0.3):
      · свежая копия — отставания нет;
      · сдвиг на сутки назад — отставание названо, доказательство:
        последняя дата тренировок до и после;
      · сдвиг обратно — отставания нет, отпечаток строк совпал с исходным.
    Базы нет либо в ней нет аккаунта — код 2, спросить нечем."""
    import shutil
    import tempfile
    исходная = _путь()
    if not os.path.exists(исходная) or not данные_на_месте(исходная):
        print("ПРОПУСК: базы стенда либо аккаунта съёмки нет — спросить нечем")
        return 2
    копия = os.path.join(tempfile.mkdtemp(), "fresh_ctrl.db")
    src = sqlite3.connect(исходная)
    dst = sqlite3.connect(копия)
    src.backup(dst)
    src.close()
    dst.close()
    try:
        ок = True
        было = данные_отстали(копия)
        отп0 = _отпечаток(копия)
        print("  исходная копия: отставание %d строк %s" % (len(было), было))
        if было:
            print("  ОСТАНОВЛЕНО: исходная база уже отстала — пересейте, "
                  "контроль на грязной основе недействителен")
            return 2
        д0 = последняя_тренировка(копия)
        сдвиг = сдвинуть_дни(копия, -1)
        стало = данные_отстали(копия)
        д1 = последняя_тренировка(копия)
        нашёл = bool(стало)
        print("  %s сдвиг -1 сутки: отставание %d строк %s; ДОКАЗАТЕЛЬСТВО: "
              "последняя тренировка %s -> %s, сдвинуто колонок %d"
              % ("OK   " if нашёл else "ПЛОХО", len(стало), стало, д0, д1,
                 len(сдвиг)))
        ок = ок and нашёл and д0 != д1
        сдвинуть_дни(копия, 1)
        вернулось = данные_отстали(копия)
        отп1 = _отпечаток(копия)
        верно = not вернулось and отп0 == отп1
        print("  %s сдвиг +1 сутки: отставание %d строк; отпечаток %s -> %s"
              % ("OK   " if верно else "ПЛОХО", len(вернулось), отп0, отп1))
        ок = ок and верно
        print("КОНТРОЛЬ %s" % ("ПРОЙДЕН" if ок else "НЕ ПРОЙДЕН"))
        return 0 if ок else 1
    finally:
        shutil.rmtree(os.path.dirname(копия), ignore_errors=True)


def данные_на_месте(путь):
    c = sqlite3.connect("file:%s?mode=ro" % os.path.abspath(путь), uri=True)
    try:
        return bool(c.execute("SELECT 1 FROM users WHERE email=?",
                              (ПОЧТА,)).fetchone())
    except sqlite3.Error:
        return False
    finally:
        c.close()


def последняя_тренировка(путь):
    c = sqlite3.connect("file:%s?mode=ro" % os.path.abspath(путь), uri=True)
    try:
        return c.execute("SELECT MAX(w.log_date) FROM workout_sessions w "
                         "JOIN users u ON u.id=w.user_id WHERE u.email=?",
                         (ПОЧТА,)).fetchone()[0]
    finally:
        c.close()


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    if "--контроль" in sys.argv:
        sys.exit(контроль())
    if "--сдвинуть" in sys.argv:
        и = sys.argv.index("--сдвинуть")
        дни = int(sys.argv[и + 1])
        итог = сдвинуть_дни(_путь(), дни)
        print("СДВИНУТО на %+d сут.: колонок %d, строк %d"
              % (дни, len(итог), sum(итог.values())))
        print("ПЕРЕЗАПУСКАТЬ СТЕНД НЕ НУЖНО: даты читаются из базы на запрос.")
        sys.exit(0)
    if not os.path.exists(_путь()) or not данные_на_месте(_путь()):
        print("ПРОПУСК: базы стенда либо аккаунта съёмки нет — спросить нечем")
        sys.exit(2)
    отставание = данные_отстали()
    if отставание:
        print("ДАННЫЕ ОТСТАЛИ ОТ СУТОК (сегодня %s): %s"
              % (date.today().isoformat(), "; ".join(отставание)))
        sys.exit(1)
    print("СВЕЖИЕ: «сегодня» у посева — %s" % date.today().isoformat())
    sys.exit(0)

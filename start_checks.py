def хук():
    if os.environ.get("START_CHECKS_BYPASS") == "1":
        with io.open(ЖУРНАЛ_ОБХОДОВ, "a", encoding="utf-8") as ж:
            ж.write("%s\tHEAD %s\tсессия %s\tОБХОД ЗАМКА\n" % (
                _dt.datetime.now().isoformat(timespec="seconds"),
                _head()[:12], _сессия() or "-"))
        sys.stderr.write("pre-commit: ОБХОД START_CHECKS_BYPASS=1 — записан "
                         "в start_checks_bypass.log\n")
        return 0
    if not os.path.exists(ОТМЕТКА):
        return _отказ("Отметки .start_checks.json нет")
    try:
        отметка = json.loads(io.open(ОТМЕТКА, encoding="utf-8").read())
    except ValueError:
        return _отказ("Отметка не читается")
    head = _head()
    if head and отметка.get("head") != head and _git(
            "merge-base", "--is-ancestor", отметка.get("head", ""), head
    ).returncode != 0:
        return _отказ("Отметка снята на %s, это не предок HEAD %s"
                      % (отметка.get("head", "?")[:7], head[:7]))
    сессия = _сессия()
    if сессия:
        if отметка.get("session") != сессия:
            return _отказ("Отметка снята в другой сессии")
    else:
        try:
            возраст = _dt.datetime.now() - _dt.datetime.fromisoformat(отметка["time"])
        except (KeyError, ValueError):
            return _отказ("В отметке нет времени")
        if возраст.total_seconds() > ВОЗРАСТ_ЧАСОВ * 3600:
            return _отказ("Отметка старше %d ч" % ВОЗРАСТ_ЧАСОВ)
    return 0


def деплой_готов():
    """Перед деплоем обязателен ПОЛНЫЙ ряд.

    Быстрый ряд отвечает «что задето правкой», и этого довольно между
    блоками сессии. Выкатка — другой вопрос: она увозит на прод ВЕСЬ
    код, включая то, чего сессия не трогала, а наследованный результат
    снят на прошлом коммите.
    """
    отметка = _прочитать_отметку()
    if not отметка:
        print("ДЕПЛОЙ НЕЛЬЗЯ: отметки нет")
        return 1
    if отметка.get("mode") != "полный":
        print("ДЕПЛОЙ НЕЛЬЗЯ: последняя отметка — %s ряд, нужен полный"
              % отметка.get("mode", "?"))
        return 1
    # МЕСТНАЯ ОТМЕТКА ЗАКРЫВАЕТ ТОЛЬКО ГРУППУ (б) — задача 357. Остальное
    # гоняет GitHub Actions, и его зелёный сверяет `deploy_gate.py`
    # у самой выкатки: два замка на двух площадках, каждый про своё.
    место = отметка.get("place", "все")
    if место not in ("все", "местно"):
        print("ДЕПЛОЙ НЕЛЬЗЯ: отметка снята рядом «%s», а не местным" % место)
        return 1
    head = _head()
    if head and отметка.get("head") != head and _git(
            "merge-base", "--is-ancestor", отметка.get("head", ""), head
    ).returncode != 0:
        print("ДЕПЛОЙ НЕЛЬЗЯ: полный ряд снят не на предке HEAD")
        return 1
    try:
        возраст = _dt.datetime.now() - _dt.datetime.fromisoformat(отметка["time"])
    except (KeyError, ValueError):
        print("ДЕПЛОЙ НЕЛЬЗЯ: в отметке нет времени")
        return 1
    if возраст.total_seconds() > ВОЗРАСТ_ЧАСОВ * 3600:
        print("ДЕПЛОЙ НЕЛЬЗЯ: полный ряд старше %d ч" % ВОЗРАСТ_ЧАСОВ)
        return 1
    print("ДЕПЛОЙ МОЖНО: полный %s ряд %s на %s, возраст %d мин"
          % (место, отметка["time"], отметка["head"][:7],
             возраст.total_seconds() // 60))
    if место == "местно":
        print("  остальное сверяет GitHub Actions: `deploy_gate.py` требует "
              "зелёного прогона checks у ЭТОГО коммита")
    return 0


def контроль():
    """ТРИ ПОДЛОГА ОТБОРА (задача 352, «аптечка-3», 1.6).

    Отбор решает, ЧТО НЕ ГОНЯТЬ, и ошибка в нём немая: ряд печатает
    зелёное про проверку, которой не было. Поэтому каждый случай
    сверяется ИМЕНАМИ проверок, а не их числом.

    Подлоги кладутся в ПАМЯТЬ (подменённая прошлая отметка), файлы
    на диске не трогаются.
    """
    сейчас = _отпечатки()
    всегда = {i for i, _п, к in _все_проверки()
              if реестр.маски_проверки(i, к) == реестр.ВСЕГДА
              and реестр.уровень(i) == "быстрый"}
    беды = []

    def прогон(файлы, зелёные=()):
        отметка = {"files": файлы, "mode": "быстрый",
                   "checks": [{"id": i, "code": "0"} for i in зелёные]}
        брать, _пропуск, _о = отобрать(отметка)
        return {i for i, _п, _к, _пр in брать}

    # (б) НИЧЕГО НЕ ТРОНУЛИ — в ряду только «всегда»
    б = прогон(dict(сейчас))
    print("  (б) без правок: %d проверок — %s" % (len(б), ", ".join(sorted(б))))
    if б != всегда:
        беды.append("(б) ждали только «всегда» (%s), пришло %s"
                    % (", ".join(sorted(всегда)), ", ".join(sorted(б))))

    # (а) ТРОНУЛИ ФАЙЛ, КОТОРЫЙ СТОРОЖИТ КОНКРЕТНАЯ ПРОВЕРКА
    цель = "static/medkit.css"
    прошлые = dict(сейчас)
    прошлые[цель] = "ПОДЛОГ"
    а = прогон(прошлые)
    ждём = {i for i, _п, к in _все_проверки()
            if реестр.подходит(цель, реестр.маски_проверки(i, к))}
    новые = а - б
    print("  (а) %s изменён: прибавилось %d — %s"
          % (цель, len(новые), ", ".join(sorted(новые))))
    if not новые or not ждём.issubset(а):
        беды.append("(а) сторожащие %s не попали в ряд: %s"
                    % (цель, ", ".join(sorted(ждём - а))))
    if "стенд:49" in новые or "стенд:51" in новые:
        беды.append("(а) в ряд попали чужие проверки HH")

    # (в) ПРОВЕРКА ЧИСЛИТСЯ ЗЕЛЁНОЙ, А ЕЁ ФАЙЛ ИЗМЕНЁН
    зелёные = [i for i, _п, _к in _все_проверки()]
    в = прогон(прошлые, зелёные)
    # пример берётся из тех, кто попал ПО МАСКЕ: проверка «всегда»
    # в ряду и так, и доказательством наследования она не является
    по_маске = sorted(ждём - всегда)
    пример = по_маске[0] if по_маске else None
    print("  (в) те же правки при ВСЕХ зелёных: %d проверок, %s в ряду: %s"
          % (len(в), пример, пример in в))
    if пример and пример not in в:
        беды.append("(в) зелёный статус увёл %s из ряда" % пример)

    print("КОНТРОЛЬ ОТБОРА: %s" % ("ЧИСТО" if not беды else "; ".join(беды)))
    return 1 if беды else 0



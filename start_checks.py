def _отпечатки(коммит=None):
    """{путь: git-blob-sha1} по отслеживаемым файлам, которые кто-то сторожит.

    Хешируются только подпадающие под маски реестра: 1778 картинок
    упражнений не сторожит никто, и считать их отпечаток каждый раз
    значило бы платить за вопрос, которого не задавали.

    ОТПЕЧАТОК — ХЕШ GIT, А НЕ СВОЙ: так состояние РАБОЧЕГО ДЕРЕВА
    сравнимо с состоянием ЛЮБОГО КОММИТА (`git ls-tree` отдаёт те же
    хеши даром), и отметку можно снять задним числом на стартовом
    коммите, не переснимая прогон.
    """
    маски = реестр.все_маски()
    итог = {}
    if коммит:
        вывод = _git("ls-tree", "-r", "-z", коммит).stdout
        for запись in вывод.split(chr(0)):
            if not запись.strip():
                continue
            голова, _таб, путь = запись.partition(chr(9))
            части = голова.split()
            if len(части) >= 3 and реестр.подходит(путь, маски):
                итог[путь] = части[2]
        return итог
    # НОВЫЙ ФАЙЛ, ЕЩЁ НЕ ЗАКОММИЧЕННЫЙ, ТОЖЕ СЧИТАЕТСЯ: правка живёт
    # в рабочем дереве, а не в индексе, и пропускать её значило бы
    # не гонять проверку ровно на том файле, который сейчас пишут.
    вывод = _git("ls-files", "-z").stdout + _git(
        "ls-files", "-z", "--others", "--exclude-standard").stdout
    for путь in вывод.split(chr(0)):
        путь = путь.strip()
        if not путь or not реестр.подходит(путь, маски):
            continue
        try:
            with open(os.path.join(КОРЕНЬ, путь), "rb") as ф:
                данные = ф.read()
        except OSError:
            итог[путь] = "НЕТ"
            continue
        # CRLF СНИМАЕТСЯ, КАК ЕГО СНИМАЕТ САМ GIT (`core.autocrlf=true`):
        # иначе тринадцать файлов с CRLF на диске числились бы
        # изменёнными КАЖДЫЙ прогон, и быстрый ряд тихо стал бы полным.
        # Двоичный файл (есть нулевой байт) git не трогает — и мы тоже.
        if bytes([0]) not in данные:
            данные = данные.replace(bytes([13, 10]), bytes([10]))
        итог[путь] = hashlib.sha1(
            b"blob " + str(len(данные)).encode() + bytes([0]) + данные).hexdigest()
    return итог


def _изменившиеся(прошлые, текущие):
    """Файлы, чей отпечаток разошёлся с прошлой отметкой (в обе стороны)."""
    изменились = set()
    for путь, хеш in текущие.items():
        if прошлые.get(путь) != хеш:
            изменились.add(путь)
    for путь in прошлые:
        if путь not in текущие:
            изменились.add(путь)
    return изменились


def _все_проверки(место=None):
    """[(id, подпись, команда)] — состав рядов, из CLAUDE.md.

    `место`: None — весь состав; "ci" — то, что гоняет GitHub Actions;
    "местно" — то, что остаётся на машине навсегда (видимое окно
    вёрстки и проверки, чей предмет — боевые данные либо `.env`).
    Разделение живёт в `checks_registry.только_местно`, второго
    перечня здесь нет (§6.0.7).
    """
    import project_lists as списки
    _пр, команды = списки.разобрать()
    состав = [("ряд:%s" % н, "ряд %s" % н, к) for н, к in команды]
    состав += [("стенд:%s" % н, "стенд %s" % н, к)
               for н, к in списки.команды_стенда()]
    состав += [("скрипт:%s" % имя, имя, "py " + имя)
               for имя in ("check_hh_owner.py", "check_v2_showcase.py")]
    состав.append(("pytest", "pytest", "pytest"))
    if место is None:
        return состав
    местные = место == "местно"
    return [(i, п, к) for i, п, к in состав
            if bool(реестр.только_местно(i, к)) == местные]


def отобрать(прошлая, место=None):
    """([(id, подпись, команда, причина)], пропущенные, изменившиеся).

    В ряд попадает проверка, у которой ЛИБО метка ВСЕГДА (и уровень
    позволяет гонять её в быстром ряду), ЛИБО изменился хоть один
    сторожимый файл. Пропущенная наследует свой прошлый результат.
    """
    текущие = _отпечатки()
    изменились = _изменившиеся(прошлая.get("files") or {}, текущие)
    брать, пропуск = [], []
    for id_, подпись, команда in _все_проверки(место):
        маски = реестр.маски_проверки(id_, команда)
        if маски == реестр.ВСЕГДА:
            if реестр.уровень(id_) == "быстрый":
                брать.append((id_, подпись, команда, "всегда"))
            else:
                пропуск.append((id_, подпись, "только в полном ряду"))
            continue
        задеты = sorted(п for п in изменились if реестр.подходит(п, маски))
        if задеты:
            брать.append((id_, подпись, команда, задеты[0]))
        else:
            пропуск.append((id_, подпись, "не менялось"))
    return брать, пропуск, текущие



/* ═══════════════════════════════════════════════════════════════════════
   СКАНЕР КОДА С КАМЕРЫ — СИСТЕМНЫЙ КОМПОНЕНТ (BACKLOG №163)
   ═══════════════════════════════════════════════════════════════════════

   ПОТРЕБИТЕЛЕЙ ДВА: штрих-код продукта в дневнике питания и код
   упаковки лекарства в аптечке. До 2026-08-28 механика жила ~90 строками
   ИНЛАЙНОМ в `templates/nutrition.html` при одном потребителе; копия
   для аптечки стала бы ровно тем дублем, против которого заведена
   задача 126 — и разошлась бы молча: сканер дневника уже пережил три
   правки (замороженный кадр прошлой сессии, гонка токенов, фонарик),
   и вторая реализация начала бы с тех же трёх дефектов.

   ЧТО ЗДЕСЬ СТРАНИЧНОГО — РОВНО ТРИ ВЕЩИ, И ВСЕ ТРИ ПАРАМЕТРЫ:
   какие ФОРМАТЫ читать, куда рисовать видоискатель, что сделать
   с прочитанным кодом. Разметку компонент не заводит: у дневника
   в окне стоит поле ручного ввода, у аптечки подпись про DataMatrix,
   и общего окна из них не выходит.

   ФОРМАТЫ — ПАРАМЕТР, И ЭТО НЕ ПРИДИРКА. Разведка задачи 163 показала,
   что библиотека DataMatrix ЧИТАЕТ (85 знаков за 29 мс), а сканер
   дневника его не видел — не потому, что не умеет, а потому что
   в `formatsToSupport` там перечислены восемь форматов и DATA_MATRIX
   среди них нет. Список сужен НАМЕРЕННО: без него библиотека путает
   полосы EAN-13 с QR-кодом и выдаёт случайный код. Значит выбор
   форматов принадлежит потребителю, а не компоненту.

   ═══════════════════════════════════════════════════════════════════════
   ЧУЖОЙ СКРИПТ ГРУЗИТСЯ ПО НАЖАТИЮ, А НЕ В ШАПКЕ

   `unpkg.com/html5-qrcode` — чужая сеть, и §6.0.17 запрещает такому
   файлу лежать на пути отрисовки. Здесь он не лежит: подгружается
   в момент открытия окна сканера, то есть после того, как человек
   нажал кнопку. Ни один кадр страницы его не ждёт.

   Отказ загрузки НЕ ПРОГЛАТЫВАЕТСЯ (§6.0.1): «камера не открылась»
   и «библиотека не приехала» — разные беды с разным лечением, и обе
   уходят в `отказ(причина)` названными.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var БИБЛИОТЕКА = 'https://unpkg.com/html5-qrcode@2.3.8/html5-qrcode.min.js';

  var текущий = null;   // живой экземпляр Html5Qrcode
  var метка = 0;        // ТОКЕН СЕССИИ, разбор ниже

  function загрузить(src) {
    return new Promise(function (готово, беда) {
      if (window.Html5Qrcode) return готово();
      var s = document.createElement('script');
      s.src = src;
      s.onload = function () { готово(); };
      s.onerror = function () { беда(new Error('скрипт не загрузился')); };
      document.head.appendChild(s);
    });
  }

  /* ПОЛНАЯ РАЗБОРКА, А НЕ ОДИН `stop()`. Сам по себе `stop()` оставляет
     в дереве <video>/<canvas> с ЗАМОРОЖЕННЫМ последним кадром, и новый
     экземпляр успевает считать именно его — отсюда был дефект «при новом
     сканировании показывается прошлый товар». Правка перенесена
     из дневника вместе с механикой: наступить на это второй раз
     в аптечке было бы обидно. */
  async function остановить() {
    if (!текущий) return;
    var sc = текущий;
    текущий = null;
    try { await sc.stop(); } catch (e) {}
    try { await sc.clear(); } catch (e) {}
  }

  function форматы(имена) {
    var F = window.Html5QrcodeSupportedFormats || {};
    return (имена || []).map(function (и) { return F[и]; })
                        .filter(function (v) { return v !== undefined; });
  }

  /* ФОНАРИК ПОКАЗЫВАЕТСЯ, ТОЛЬКО ЕСЛИ КАМЕРА ЕГО УМЕЕТ. Кнопка,
     которая ничего не делает, читается как поломка — то же правило,
     что у декоративных обещаний действия (§6.0.3). */
  function фонарик(кнопка) {
    if (!кнопка) return;
    кнопка.style.display = 'none';
    кнопка.classList.remove('on');
    try {
      var t = текущий.getRunningTrackCameraCapabilities().torchFeature();
      if (t.isSupported()) кнопка.style.display = 'flex';
    } catch (e) {}
  }

  async function переключитьФонарик(кнопка) {
    if (!текущий) return;
    try {
      var t = текущий.getRunningTrackCameraCapabilities().torchFeature();
      var было = кнопка.classList.contains('on');
      await t.apply(!было);
      кнопка.classList.toggle('on', !было);
    } catch (e) { console.log('[сканер] фонарик:', e); }
  }

  /* @param {object} п
       контейнер  — id элемента под видоискатель (обязателен)
       форматы    — имена из Html5QrcodeSupportedFormats, напр. ['EAN_13']
       рамка      — {width, height} видоискателя
       фонарикId  — id кнопки фонарика, если она есть в разметке
       готово(код)— что сделать с прочитанным
       отказ(что) — почему не завелось: 'библиотека' | 'камера'          */
  async function запустить(п) {
    await остановить();
    var моя = ++метка;
    if (!window.Html5Qrcode) {
      try { await загрузить(БИБЛИОТЕКА); }
      catch (e) {
        if (п.отказ) п.отказ('библиотека');
        return;
      }
    }
    /* Окно успели закрыть, пока грузился чужой скрипт: продолжать
       значило бы включить камеру у закрытого окна */
    if (моя !== метка) return;
    try {
      var sc = new Html5Qrcode(п.контейнер, {
        formatsToSupport: форматы(п.форматы),
        verbose: false,
      });
      текущий = sc;
      await sc.start(
        { facingMode: 'environment' },
        { fps: 10, qrbox: п.рамка || { width: 260, height: 130 } },
        async function (код) {
          if (моя !== метка) return;   // результат уже закрытой сессии
          метка++;
          await остановить();
          if (п.готово) п.готово(код);
        },
        function () {}
      );
      if (п.фонарикId) фонарик(document.getElementById(п.фонарикId));
    } catch (e) {
      /* start() не удался — камеры нет либо доступ отклонён. Ссылку
         СБРАСЫВАЕМ: иначе следующая остановка позовёт stop()
         на нерабочем экземпляре */
      текущий = null;
      console.log('[сканер] камера:', e);
      if (п.отказ) п.отказ('камера');
    }
  }

  window.СканерКода = {
    запустить: запустить,
    остановить: остановить,
    фонарик: переключитьФонарик,
    /* Гасит результаты незакрытой сессии, не трогая камеру: нужен там,
       где окно закрывают чужой рукой (подписка modal:close) */
    сбросить: function () { метка++; },
  };
})();

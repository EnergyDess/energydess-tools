/* /botamin — предупреждение о заблокированном виджете.

   ПОЧЕМУ ПРОВЕРКА ПЕРЕПИСАНА. Первая версия спрашивала
   customElements.get('elevenlabs-convai') — определён ли кастомный элемент.
   На искусственной блокировке домена это работало: скрипт не приходит,
   элемент не определяется, предупреждение всплывает. На живом браузере
   с блокировщиком не сработало ни разу, и причина в том, что блокировщики
   умеют не только резать запросы.

   Списки фильтров содержат косметические правила против виджетов чата —
   селектор вроде `elevenlabs-convai` с `display: none !important`. При таком
   правиле скрипт грузится, элемент определяется, теневое дерево строится,
   и любая проверка «загрузилось ли» отвечает «да». Не видно при этом ничего.
   То же самое даёт блокировка не самого виджета, а его бэкенда: код цел,
   рисовать нечего.

   Отсюда правило: проверять надо то же, что видит человек, — есть ли на
   экране непустая коробка виджета. Такая проверка накрывает разом сетевую
   блокировку, косметическую, сбой скрипта и отказ рендера, и не зависит
   от того, каким из способов сегодня пользуется расширение. */

(function () {
  'use strict';

  var ЭЛЕМЕНТ = 'elevenlabs-convai';
  var ПЕРВАЯ_ПРОВЕРКА = 3500;   // мс: запас на медленную сеть, чтобы не пугать зря
  var ПОВТОР = 1000;            // виджет мог просто задержаться — перепроверяем
  var ПРЕДЕЛ = 20000;           // дольше ждать бессмысленно: это уже не задержка

  var предупреждение = null;
  var приглашение = null;
  var начало = 0;

  function невидим(узел) {
    var с = window.getComputedStyle(узел);
    return с.display === 'none' || с.visibility === 'hidden' || с.opacity === '0';
  }

  /* Виджет считается живым, только если внутри теневого дерева есть хотя бы
     одна отрисованная коробка заметного размера. Порог 40×24 отсекает
     служебные нулевые обёртки, которых там десятки. */
  function виден() {
    var узел = document.querySelector(ЭЛЕМЕНТ);
    if (!узел || !window.customElements || !window.customElements.get(ЭЛЕМЕНТ)) {
      return false;
    }
    if (невидим(узел) || !узел.shadowRoot) {
      return false;
    }
    var потомки = узел.shadowRoot.querySelectorAll('*');
    for (var i = 0; i < потомки.length; i++) {
      if (невидим(потомки[i])) {
        continue;
      }
      var р = потомки[i].getBoundingClientRect();
      if (р.width >= 40 && р.height >= 24) {
        return true;
      }
    }
    return false;
  }

  /* Предупреждение и карточка-приглашение меняются местами: приглашение
     объясняет, где кнопка, и при отсутствующем виджете становится враньём. */
  function переключить(сломано) {
    if (!предупреждение) {
      return;
    }
    if (сломано) {
      предупреждение.removeAttribute('hidden');
      if (приглашение) {
        приглашение.setAttribute('hidden', '');
      }
    } else {
      предупреждение.setAttribute('hidden', '');
      if (приглашение) {
        приглашение.removeAttribute('hidden');
      }
    }
  }

  function проверить() {
    var живой = виден();
    переключить(!живой);
    // Пока не появился и не вышел срок — пробуем снова: медленная сеть
    // не должна оставить человека наедине с предупреждением навсегда.
    if (!живой && Date.now() - начало < ПРЕДЕЛ) {
      window.setTimeout(проверить, ПОВТОР);
    }
  }

  function запустить() {
    предупреждение = document.getElementById('widget-fallback');
    приглашение = document.querySelector('.bot-call');

    var кнопка = document.getElementById('widget-reload');
    if (кнопка) {
      кнопка.addEventListener('click', function () {
        window.location.reload();
      });
    }

    начало = Date.now();
    window.setTimeout(проверить, ПЕРВАЯ_ПРОВЕРКА);
  }

  // Отсчёт от полной загрузки страницы, а не от разбора разметки: тег скрипта
  // виджета помечен async и на момент DOMContentLoaded законно может быть ещё
  // в пути. Ветка на readyState нужна для случая, когда load уже прошёл, —
  // обработчик тогда не сработал бы никогда.
  if (document.readyState === 'complete') {
    запустить();
  } else {
    window.addEventListener('load', запустить);
  }
})();

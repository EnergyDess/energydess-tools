/* /botamin — предупреждение о заблокированном виджете.

   Скрипт виджета грузится с unpkg.com, а блокировщики рекламы режут этот
   домен целиком. Отказ при этом немой и худшего сорта: ошибки на странице
   нет, вёрстка цела, просто внизу пусто — и человек решает, что демо
   сломано. Воспроизведено на живом браузере с расширением.

   Проверяем не факт загрузки скрипта, а результат: определился ли кастомный
   элемент. Это единственный надёжный признак — скрипт мог прийти и упасть,
   мог прийти частично, мог быть подменён. customElements.get отвечает на
   вопрос «виджет реально готов работать», а не «файл приехал». */

(function () {
  'use strict';

  var ЭЛЕМЕНТ = 'elevenlabs-convai';
  var ЗАДЕРЖКА = 2500;   // мс: запас на медленную сеть, чтобы не пугать зря

  function проверить() {
    if (window.customElements && window.customElements.get(ЭЛЕМЕНТ)) {
      return;
    }
    var блок = document.getElementById('widget-fallback');
    if (блок) {
      блок.removeAttribute('hidden');
    }
  }

  // Отсчёт идёт от полной загрузки страницы, а не от разбора разметки:
  // тег скрипта помечен async, и на момент DOMContentLoaded он законно
  // может быть ещё в пути. Ветка на readyState нужна для случая, когда
  // load уже прошёл, — тогда обработчик не сработал бы никогда.
  if (document.readyState === 'complete') {
    window.setTimeout(проверить, ЗАДЕРЖКА);
  } else {
    window.addEventListener('load', function () {
      window.setTimeout(проверить, ЗАДЕРЖКА);
    });
  }
})();

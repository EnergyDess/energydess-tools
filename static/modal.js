// ── modal.js — поведение модальных окон (design-system.md, раздел 2.5) ───────
//
// Каркас — в templates/_modal.html, оформление — в style.css, поведение здесь.
// Страница не подключает ни onclick, ни свой обработчик клавиш: разметке
// достаточно `.modal-ov` с id и `[data-modal-close]` на кнопке закрытия.
//
// Что закрывает этот файл (замерено на дневнике питания до его появления):
//   • Escape не работал ни в одной из двенадцати модалок — обработчика
//     не существовало вовсе;
//   • фокус после закрытия оставался на невидимом поле ВНУТРИ закрытой
//     модалки: она не display:none, а opacity:0, и элемент остаётся живым;
//   • 73 фокусируемых элемента из 142 на странице лежали в закрытых
//     модалках и всегда были в порядке табуляции — четырнадцать нажатий
//     Tab с начала страницы попадали в них все четырнадцать;
//   • фон прокручивался под открытой модалкой и оставался на новом месте
//     после закрытия (390px: 292 → 1000);
//   • смахивание шторки вниз работало на ОДНОЙ странице из всех — оно
//     лежало функцией в скрипте дневника, а «ручку» компонент рисует
//     везде (перенесено сюда 2026-08-12, разбор ниже у зоны тяги).
//
// Публичный API: открыть_модалку(id) / закрыть_модалку(id).
//
// Имена намеренно кириллические, и это единственная причина их выбора.
// Раньше компонент назывался openModal/closeModal — ровно так же, как
// пара функций, объявленная внутри profile.html. Совпадали имена, но не
// сигнатуры: компонентная закрывает по id, профильная — по элементу.
// Подключение этого файла к профилю сломало бы обе его модалки МОЛЧА:
// closeModal(элемент) ушёл бы в компонентную, getElementById([object
// HTMLDivElement]) вернул бы null, функция вышла бы по первой проверке
// и не бросила бы ничего. Ни ошибки в консоли, ни следа в логах —
// просто кнопка «Закрыть» перестала бы закрывать.
//
// Пометки в бэклоге тут недостаточно: её читают один раз и невнимательно,
// а совпадение имени происходит само — openModal и closeModal напишет
// любой, кто делает модалку, не заглядывая в этот файл. Кириллица убирает
// не последствия, а саму возможность: случайно объявить функцию с таким
// именем нельзя, его нужно набрать намеренно.

(function () {
  'use strict';

  // Порядок открытия. Модалка над модалкой в дневнике — норма (поиск
  // ингредиента → порция, штрих-код → добавить вручную), поэтому Escape
  // обязан закрывать верхнюю, а не первую попавшуюся.
  var стек = [];
  // id → элемент, с которого модалку открыли. Сюда возвращается фокус.
  var фокус_до = {};

  function лист(м) { return м.querySelector('.modal-sh'); }

  // Блокировка прокрутки фона. Классом на <html>, тем же приёмом, что уже
  // применён для вкладки ассистента (html.assistant-mode) — не position:fixed
  // на body: тот сбрасывает scrollY, и страница прыгает при закрытии, а
  // в дневнике вдобавок поехала бы sticky-панель внизу.
  // Ширину скроллбара компенсировать не нужно: scrollbar-gutter: stable
  // в style.css резервирует место всегда, поэтому исчезновение полосы
  // не сдвигает вёрстку.
  function блокировать(нужно) {
    document.documentElement.classList.toggle('modal-open', !!нужно);
  }

  window.открыть_модалку = function (id) {
    var м = document.getElementById(id);
    if (!м || м.classList.contains('open')) return;

    фокус_до[id] = document.activeElement;
    // inert снимаем ДО показа: пока он висит, фокус внутрь не поставить
    м.removeAttribute('inert');
    м.classList.add('open');
    стек.push(id);
    блокировать(true);

    // Фокус — на сам лист, а не на первую кнопку: программа чтения с экрана
    // объявляет диалог с начала, а не с «Закрыть». Страницы, которым нужно
    // конкретное поле, ставят фокус сами через setTimeout после открытия —
    // их вызов идёт позже и перебивает этот, что и требуется.
    var л = лист(м);
    if (л) л.focus({ preventScroll: true });
  };

  window.закрыть_модалку = function (id) {
    var м = document.getElementById(id);
    if (!м || !м.classList.contains('open')) return;

    м.classList.remove('open');
    стек = стек.filter(function (x) { return x !== id; });

    // Порядок важен: фокус возвращаем ДО inert. Наоборот — inert снимет
    // фокус с потомка в никуда (на <body>), и возвращать станет неоткуда.
    var назад = фокус_до[id];
    delete фокус_до[id];
    if (назад && document.contains(назад) && !назад.closest('.modal-ov')) {
      назад.focus({ preventScroll: true });
    } else if (м.contains(document.activeElement)) {
      // Открывшего элемента больше нет (список перерисовали) — уводим фокус
      // хотя бы наружу, иначе он останется на невидимом поле
      document.activeElement.blur();
    }
    м.setAttribute('inert', '');

    if (!стек.length) блокировать(false);

    // Своя уборка страницы (остановить камеру сканера, сбросить состояние)
    // вешается сюда, а не подменяет закрытие: выход из окна должен быть
    // один на все способы закрытия и на любой глубине стопки. Событие
    // уходит безусловно, между ним и входом в функцию нет ни одного
    // return, поэтому «закрылось, но уборка не отработала» невозможно.
    м.dispatchEvent(new CustomEvent('modal:close', { bubbles: true }));
  };

  // ── Escape закрывает верхнюю открытую ──
  document.addEventListener('keydown', function (e) {
    if (e.key !== 'Escape' || !стек.length) return;
    window.закрыть_модалку(стек[стек.length - 1]);
  });

  // ── Клик вне окна и кнопка закрытия — одним делегатом ──
  // Делегат, а не onclick в разметке: обработчик перестаёт быть тем, что
  // можно забыть скопировать в тринадцатую модалку.
  document.addEventListener('click', function (e) {
    var кнопка = e.target.closest('[data-modal-close]');
    if (кнопка) {
      var свой = кнопка.closest('.modal-ov');
      if (свой) { window.закрыть_модалку(свой.id); return; }
    }
    // Именно сам оверлей, а не что-то внутри листа
    if (e.target.classList && e.target.classList.contains('modal-ov')) {
      window.закрыть_модалку(e.target.id);
    }
  });

  // ── Смахивание шторки вниз ──
  //
  // Приехало сюда 2026-08-12 из скрипта дневника питания, где лежало
  // функцией setupModalDragClose: она обходила .modal-ov ОДНОЙ своей
  // страницы. Механика была исправна и работала ровно там, где её вызвали;
  // на всех остальных страницах «ручка» была нарисована компонентом
  // и не делала ничего. Замер на HH до переноса: touchmove на 120px даёт
  // matrix(1,0,0,1,0,0) — лист не сдвинулся ни на пиксель, модалка
  // не закрылась; тот же жест в дневнике — matrix(1,0,0,1,0,120)
  // и закрытие. Элемент обещал жест, которого не было (CLAUDE.md §6.0.3).
  //
  // Делегат на document, а не обход элементов при загрузке, — по той же
  // причине, что у клика выше: модалка, добавленная в разметку позже,
  // получает поведение сама, а не ждёт, пока кто-нибудь вспомнит про вызов.
  var тяга = null;

  function зона_тяги(el) {
    if (!el || !el.closest) return null;
    if (el.closest('.modal-x')) return null;   // крестик — не зона жеста
    return el.closest('.modal-drag, .modal-hdr');
  }

  document.addEventListener('touchstart', function (e) {
    var зона = зона_тяги(e.target);
    if (!зона) return;
    var ов = зона.closest('.modal-ov');
    if (!ов || !ов.classList.contains('open')) return;
    // Только там, где лист действительно прижат к низу. С 640px компонент
    // рисует окно по центру (style.css), и тянуть его вниз незачем:
    // проверяется фактическая раскладка, а не ширина окна числом здесь —
    // порог живёт в одном месте, в CSS
    if (getComputedStyle(ов).alignItems !== 'flex-end') return;
    var л = лист(ов);
    if (!л) return;
    тяга = { ов: ов, л: л, y0: e.touches[0].clientY, dy: 0 };
    л.style.transition = 'none';
  }, { passive: true });

  document.addEventListener('touchmove', function (e) {
    if (!тяга) return;
    тяга.dy = Math.max(0, e.touches[0].clientY - тяга.y0);
    тяга.л.style.transform = 'translateY(' + тяга.dy + 'px)';
    тяга.л.style.opacity = String(Math.max(1 - тяга.dy / (тяга.л.offsetHeight * 0.8), 0.25));
  }, { passive: true });

  function отпустить() {
    if (!тяга) return;
    var т = тяга;
    тяга = null;
    т.л.style.transition = 'transform .2s ease, opacity .2s ease';
    if (т.dy > т.л.offsetHeight * 0.25) {
      // Уезжает вниз и затухает, и только потом убираем модалку
      т.л.style.transform = 'translateY(100%)';
      т.л.style.opacity = '0';
      setTimeout(function () {
        // Без развилки по id: своя уборка страницы приедет на modal:close
        window.закрыть_модалку(т.ов.id);
        т.л.style.transition = '';
        т.л.style.transform = '';
        т.л.style.opacity = '';
      }, 200);
    } else {
      // Не дотянули — плавно возвращается на место
      т.л.style.transform = '';
      т.л.style.opacity = '';
      setTimeout(function () { т.л.style.transition = ''; }, 200);
    }
  }

  document.addEventListener('touchend', отпустить);
  document.addEventListener('touchcancel', отпустить);

  // ── Закрытые модалки — вне порядка табуляции ──
  // inert стоит в разметке макроса, но страницы, собранные до компонента,
  // и любая динамика подстрахованы здесь.
  function расставить_inert() {
    document.querySelectorAll('.modal-ov').forEach(function (м) {
      if (!м.classList.contains('open')) м.setAttribute('inert', '');
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', расставить_inert);
  } else {
    расставить_inert();
  }
})();

// ── panel-refresh.js — ПАНЕЛЬ ПЕРЕЧИТЫВАЕТ ДАННЫЕ, КОГДА ЕЁ ОТКРЫЛИ ─────────
//
// BACKLOG №263. Болезнь чинили ТРИЖДЫ и каждый раз по одному месту:
// задача 193 (переписка ассистента тянулась один раз за загрузку страницы),
// задача 260 (лента круга рисовалась в первом кадре и не обновлялась),
// разведка задачи 262 нашла ЕЩЁ ВОСЕМЬ. Три появления — это не совпадение,
// а закономерность, и лечится она не четвёртой правкой по месту.
//
// ЧЕМ БОЛЕЗНЬ ОПАСНА. Панель показывает то, что приехало с ПЕРВОЙ загрузкой
// страницы. В общей аптечке список меняет ДРУГОЙ человек: сосед списал
// таблетку, владелец открывает окно упаковок и видит старый остаток — и
// списывает из пачки, которой уже нет. Ни ошибки, ни признака на экране;
// §6.0 в чистом виде.
//
// ── ПОЧЕМУ НАБЛЮДАТЕЛЬ ЗА ВИДИМОСТЬЮ, А НЕ ОБЩАЯ ТОЧКА ОТКРЫТИЯ ───────────
//
// Общей точки открытия у этих панелей НЕТ, и это свойство кода, а не
// недосмотр. Замер по восьми найденным местам — пять разных механик:
//
//   окно упаковок, окно категорий   `открыть_модалку()` → класс `.open`
//   список покупок «Купить»          <details open>
//   выбор участника «Отмечаю за»     hidden=false плюс переезд узла
//   график прогресса, «Техника»      свой класс `.show` / `.open`
//   «История писем», день программы  класс `.active` / `.expanded`
//
// Свести их к одной функции открытия значило бы переписать пять механик
// ради общего вызова — и девятая панель, открытая ШЕСТЫМ способом, всё
// равно осталась бы вне. Общий у всех ФАКТ, а не механизм: панель
// СТАНОВИТСЯ ВИДИМОЙ. Он-то машине и доступен.
//
// ── ВИДИМОСТЬ СПРАШИВАЕТСЯ С ОПЦИЯМИ, И БЕЗ НИХ СЛОЙ СЛЕП ────────────────
//
// Замер 2026-09-10 на живом стенде, `#apt-packs-win`:
//
//   состояние        checkVisibility()   checkVisibility(ОПЦИИ)
//   модалка закрыта      true  ← врёт          false
//   модалка открыта      true                  true
//
// Закрытая модалка — не `display:none`, а `opacity:0` (style.css, `.modal-ov`),
// и голый `checkVisibility()` считает её видимой в ОБОИХ состояниях. Слой,
// написанный на голом вызове, не заметил бы ни одного открытия модалки
// и молчал бы — то есть страдал бы ровно той болезнью, которую лечит.
//
// ── ЧТО ОБЪЯВЛЯЕТ ПАНЕЛЬ ─────────────────────────────────────────────────
//
//   data-refresh="имяФункции"   позвать функцию страницы по имени
//   data-refresh-url="/адрес"   сходить и подставить разметку — скрипта
//   data-refresh-into="#узел"   не нужно вовсе (по умолчанию — сам элемент)
//   data-refresh-key="html"     поле ответа с разметкой
//
// Вторая форма — для панелей, у которых построитель серверный (а в аптечке
// это правило, а не исключение): одна строка в шаблоне, ноль строк
// в скрипте. Первая — там, где применение сложнее подстановки.
//
// ── ПОЧЕМУ ИМЯ В `window`, А НЕ РЕЕСТР С РЕГИСТРАЦИЕЙ ────────────────────
//
// Реестр (`панель_обновляет(имя, fn)`) требовал бы, чтобы слой загрузился
// РАНЬШЕ страничного скрипта, — а он в хвосте страницы и грузится позже:
// вызов на верхнем уровне упал бы `TypeError`, и панель осталась бы
// без обновления. Поиск по имени этого условия не имеет вовсе: имя
// спрашивается в момент ОТКРЫТИЯ панели, когда загружено уже всё.
//
// ЧТО ИМЕННО ПОПАДАЕТ В `window` — ЗАМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО
// (2026-09-10, живой стенд, ловушка проверки 30):
//
//   `аптКатегорииПеречитать`, `аптПрименитьСетку`, `аптЗапрос`  function ✔
//   `АПТ_ПОЗИЦИИ`, `АПТ_УЧАСТНИКИ` (объявлены через `let`)      undefined ✘
//
// То есть `function` на верхнем уровне классического скрипта свойством
// `window` СТАНОВИТСЯ, а `let` и `const` — нет. Функция, лежащая внутри
// IIFE (весь скрипт `/workout` — одно замыкание), выставляется наружу
// одной строкой `window.имя = функция;` — она работает при любом порядке
// загрузки, в отличие от вызова чужого API.
//
// ── НЕЗНАКОМОЕ ИМЯ ГОВОРИТ ВСЛУХ ─────────────────────────────────────────
//
// Панель объявила `data-refresh="опечатка"` — слой напишет в консоль и
// пометит элемент `data-refresh-err`. Молчание тут было бы тем же немым
// отказом: атрибут стоит, выглядит осмысленно, не делает ничего.
//
// ── ЧЕГО СЛОЙ НЕ ДЕЛАЕТ ──────────────────────────────────────────────────
//
// Он не заставляет ДЕВЯТУЮ панель объявиться — этого не может ни один
// слой. Отсутствие объявления ловит ПРОВЕРКА (`check_panel_refresh.py`):
// она открывает панели действием и требует у каждой либо объявления,
// либо фактического запроса. Тот же приём, что у §6.0.7 везде в проекте:
// правило, которое нельзя забыть, — то, забывчивость о котором находит
// машина.
//
// Опроса по таймеру здесь тоже нет, и это решение задач 193 и 260:
// открытие панели — ровно тот момент, когда человек на неё смотрит,
// а таймер стучался бы в сервер при закрытой панели.

(function () {
  'use strict';

  var ОПЦИИ = {
    opacityProperty: true,
    visibilityProperty: true,
    contentVisibilityAuto: true,
  };

  var видно_было = new WeakMap();
  var запланировано = false;

  // Счётчик для проверки и отладки: сколько раз слой звал обновление.
  window.__панели = { обновлений: 0, последняя: null, ошибок: 0, имена: [] };

  function панели() {
    return document.querySelectorAll('[data-refresh], [data-refresh-url]');
  }

  function видно(эл) {
    // Панель вне документа видимой не считается: узел, вынутый из дерева
    // (список упаковок на время переезда), иначе давал бы ложное открытие
    if (!эл.isConnected) return false;
    if (эл.checkVisibility) return эл.checkVisibility(ОПЦИИ);
    // Запасной путь для браузера без checkVisibility. Он ХУЖЕ и назван
    // худшим: `offsetParent` не видит `opacity:0`, то есть модалку
    // пропустит. Chromium, Firefox и Safari метод знают с 2023 года.
    return эл.offsetParent !== null;
  }

  async function обновить(эл) {
    var имя = эл.getAttribute('data-refresh');
    var адрес = эл.getAttribute('data-refresh-url');
    window.__панели.обновлений++;
    window.__панели.последняя = имя || адрес;
    window.__панели.имена.push(имя || адрес);
    эл.dispatchEvent(new CustomEvent('panel:refresh', { bubbles: true }));
    try {
      if (имя) {
        var fn = window[имя];
        if (typeof fn !== 'function') {
          window.__панели.ошибок++;
          эл.setAttribute('data-refresh-err', 'нет функции с именем ' + имя);
          console.error('[panel-refresh] панель объявила data-refresh="' + имя +
                        '", а функции с таким именем на странице нет. ' +
                        'Объявлена через let/const внутри замыкания? ' +
                        'Тогда её надо выставить: window.' + имя + ' = функция;');
          return;
        }
        await fn(эл);
        return;
      }
      var ответ = await fetch(адрес, { headers: { 'Accept': 'application/json' } });
      if (!ответ.ok) throw new Error('HTTP ' + ответ.status);
      var тело = await ответ.json();
      var ключ = эл.getAttribute('data-refresh-key') || 'html';
      var куда = эл.getAttribute('data-refresh-into');
      var узел = куда ? document.querySelector(куда) : эл;
      if (узел && typeof тело[ключ] === 'string') узел.innerHTML = тело[ключ];
      if (window.рисоватьЗначки) window.рисоватьЗначки();
    } catch (e) {
      // ОТКАЗ НЕ ПРОГЛАТЫВАЕТСЯ (§6.0.1): панель осталась со старыми
      // данными, и об этом должно быть видно хотя бы в консоли.
      window.__панели.ошибок++;
      console.error('[panel-refresh] обновление «' + (имя || адрес) +
                    '» не удалось: ' + e.message);
    }
  }

  function пересчитать() {
    запланировано = false;
    var список = панели();
    for (var i = 0; i < список.length; i++) {
      var эл = список[i];
      var сейчас = видно(эл);
      var было = видно_было.get(эл);
      видно_было.set(эл, сейчас);
      // ПЕРВОЕ СОСТОЯНИЕ НЕ СЧИТАЕТСЯ ОТКРЫТИЕМ. Панель, видимая в первом
      // кадре, только что нарисована сервером — тянуть её заново значит
      // платить лишним запросом за каждую загрузку страницы.
      if (было === undefined) continue;
      if (сейчас && !было) обновить(эл);
    }
  }

  function запланировать() {
    if (запланировано) return;
    запланировано = true;
    // rAF, а не сразу: `аптСложить` меняет инлайновую высоту покадрово,
    // и без сглаживания пересчёт шёл бы на каждый кадр анимации.
    requestAnimationFrame(пересчитать);
  }

  // ── ОДНОГО rAF МАЛО, И ЭТО НАШЛА ПРОВЕРКА, А НЕ ЧТЕНИЕ ─────────────
  //
  // Замер 2026-09-10 на первой версии слоя: три панели из восьми
  // объявились и НЕ ПЕРЕЧИТАЛИСЬ — окно упаковок, окно категорий, день
  // программы. Общее у них — ПОЯВЛЕНИЕ АНИМИРОВАНО: `.modal-ov` играет
  // `transition: opacity .2s`, `.wk-day-body` — `animation: wkFadeIn`.
  //
  // В момент, когда мутация ставит класс, вычисленный `opacity` ещё 0,
  // то есть `checkVisibility` честно отвечает «не видно». Дальше opacity
  // растёт САМ, без единой мутации DOM, — наблюдателю просыпаться не от
  // чего, и панель так и остаётся для слоя закрытой.
  //
  // Отказ был бы немым в худшем виде: атрибут стоит, слой подключён,
  // человек видит открытое окно со старыми данными. Ровно та болезнь,
  // ради которой слой и написан, только внутри него самого.
  //
  // Лечится не таймером, а КОНЦОМ САМОЙ АНИМАЦИИ: оба события всплывают
  // до документа. Там, где движение выключено (`prefers-reduced-motion`
  // либо мгновенная смена `hidden`), их не будет вовсе — и не нужно:
  // opacity к первому же rAF уже равен единице.
  document.addEventListener('transitionend', запланировать, true);
  document.addEventListener('animationend', запланировать, true);

  // Ручной зов — для случая, когда панель открыли, а данные заведомо
  // устарели от собственного действия. Слой при этом остаётся один.
  window.панель_обновить = function (сел) {
    var эл = typeof сел === 'string' ? document.querySelector(сел) : сел;
    if (эл) обновить(эл);
  };

  function запустить() {
    // Начальное состояние снимается ДО наблюдения, чтобы первый кадр
    // не сработал открытием.
    панели().forEach(function (эл) { видно_было.set(эл, видно(эл)); });
    new MutationObserver(запланировать).observe(document.documentElement, {
      attributes: true,
      attributeFilter: ['class', 'hidden', 'open', 'style', 'inert'],
      subtree: true,
      childList: true,
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', запустить);
  } else {
    запустить();
  }
})();

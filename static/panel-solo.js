// ── panel-solo.js — МЕСТО ДЛЯ ПАНЕЛИ ОДНО ───────────────────────────────
//
// №352, «аптечка-2», блок 1.1. Владелец открыл «AI-ассистент», затем
// «Перепроверить» — панели легли одна на другую: обе стоят у правого
// края, и верхняя закрыла нижнюю. Ни ошибки, ни признака; нижнюю
// не закрыть, потому что её крестик под верхней.
//
// ── ПОЧЕМУ СЛОЙ, А НЕ ПРАВКА ДВУХ ФУНКЦИЙ ОТКРЫТИЯ ──────────────────────
//
// Дописать «закрой соседку» в `аптАИОткрыть` и `аптДолгиПанель` — это
// перечень из двух строк на открытом множестве (§6.0.7): третья панель
// (лекарство, блок 2 этого же письма) и четвёртая (тренировки) напишутся
// так же, как первые две, и про соседку забудут молча.
//
// Общей точки открытия у панелей НЕТ — тот же замер, что у
// `panel-refresh.js`: ассистент аптечки ставит класс `.open` себе
// и затемнению, панель долгов снимает `hidden` и вешает класс на `<html>`,
// ассистент питания снимает `hidden` и возвращает фокус сам. Общий у всех
// ФАКТ, а не механизм: панель СТАНОВИТСЯ ВИДИМОЙ. Дальше слою нужно одно —
// чем её закрыть, и это панель объявляет сама.
//
// ── ЧТО ОБЪЯВЛЯЕТ ПАНЕЛЬ ────────────────────────────────────────────────
//
//   data-panel                   «я панель, место у нас общее»
//   data-panel-close="имя"       функция страницы, которой её закрывают
//   data-panel-opener="#id"      орган, открывающий её (не обязателен:
//                                без него берётся последний нажатый)
//   data-panel-backdrop="#id"    затемнение, клик по которому закрывает
//
// ИМЯ В `window`, А НЕ РЕЕСТР — по той же причине, что у `panel-refresh`:
// слой лежит в общем хвосте и грузится ПОЗЖЕ страничного скрипта, то есть
// вызов `панель_зарегистрировать(...)` на верхнем уровне упал бы
// `TypeError`. Имя спрашивается в момент закрытия, когда загружено всё.
// Что попадает в `window`, замерено ловушкой проверки 30: `function`
// верхнего уровня свойством `window` становится, `let` и `const` — нет.
//
// ── ESCAPE ОДИН НА ВСЕ ПАНЕЛИ ───────────────────────────────────────────
//
// До слоя Escape обрабатывали страницы, каждая по-своему, и фокус
// возвращала одна панель из трёх. Здесь это одно место, а условие
// «поверх панели нет открытой модалки» и ФАЗА ЗАХВАТА сохранены
// дословно — разбор в medkit.html (задача 176, E.2): `modal.js` в фазе
// всплытия снимает класс `open` ПЕРВЫМ, и к моменту всплытия открытых
// модалок уже нет, то есть панель закрывалась заодно с окном.
//
// ФОКУС ВОЗВРАЩАЕТСЯ НА ОРГАН, КОТОРЫМ ПАНЕЛЬ ОТКРЫЛИ, и орган этот
// ЗАПОМИНАЕТСЯ, а не перечисляется: панель лекарства открывается кнопкой
// «Инструкция» И нажатием по карточке, то есть органов у неё столько,
// сколько карточек на экране. `data-panel-opener` остаётся для панелей
// с единственной кнопкой — там имя честнее памяти.
//
// ── ЧЕГО СЛОЙ НЕ ДЕЛАЕТ ─────────────────────────────────────────────────
//
// Он не закрывает панель по клику МИМО неё. У двух панелей из трёх
// затемнения нет вовсе (`.v2-assist-dock` стоит у края, страница слева
// видна и работает), и «клик мимо» там закрывал бы панель при нажатии
// по вкладке, кнопке и полю страницы — то есть менял бы поведение,
// которого никто не просил. Закрывает ровно затемнение и только там,
// где оно есть; у панели без затемнения остаются крестик и Escape.
//
// Он не заставляет ЧЕТВЁРТУЮ панель объявиться — этого не может ни один
// слой. Забывчивость ловит ПРОВЕРКА 62 (`check_panel_solo.py`): она
// открывает панели действием и считает видимые.

(function () {
  'use strict';

  var ОПЦИИ = {
    opacityProperty: true,
    visibilityProperty: true,
    contentVisibilityAuto: true
  };

  var видно_было = new WeakMap();
  var открывший = new WeakMap();
  var последний_орган = null;
  var запланировано = false;

  // Счётчик для проверки и отладки: что и чем слой закрывал.
  window.__соло = { закрыто: 0, последняя: null, имена: [], ошибок: 0 };

  function панели() {
    return document.querySelectorAll('[data-panel]');
  }

  function видно(эл) {
    if (!эл.isConnected) return false;
    if (эл.checkVisibility) return эл.checkVisibility(ОПЦИИ);
    return эл.offsetParent !== null;
  }

  function закрыть(эл) {
    var имя = эл.getAttribute('data-panel-close');
    var fn = имя && window[имя];
    if (typeof fn !== 'function') {
      // НЕЗНАКОМОЕ ИМЯ ГОВОРИТ ВСЛУХ. Молчание тут было бы немым
      // отказом: атрибут стоит, выглядит осмысленно, не делает ничего.
      window.__соло.ошибок++;
      эл.setAttribute('data-panel-err', 'нет функции с именем ' + имя);
      console.error('[panel-solo] панель объявила data-panel-close="' + имя +
                    '", а функции с таким именем на странице нет. ' +
                    'Объявлена через let/const внутри замыкания? ' +
                    'Тогда её надо выставить: window.' + имя + ' = функция;');
      return false;
    }
    window.__соло.закрыто++;
    window.__соло.последняя = имя;
    window.__соло.имена.push(имя);
    fn(эл);
    return true;
  }

  function вернуть_фокус(эл) {
    var явный = эл.getAttribute('data-panel-opener');
    var орган = явный ? document.querySelector(явный) : открывший.get(эл);
    if (орган && орган.isConnected && орган.focus) {
      орган.focus({ preventScroll: true });
    }
  }

  function открытые() {
    var из = [];
    var список = панели();
    for (var i = 0; i < список.length; i++) if (видно(список[i])) из.push(список[i]);
    return из;
  }

  // СТРАНИЦА СЖИМАЕТСЯ ПОД ОТКРЫТУЮ ПАНЕЛЬ-ДОК (№352, «аптечка-3»).
  //
  // Панель `fixed` у правого края накрывала шапку инструмента, и кнопка
  // соседней панели оказывалась ПОД ней — открыть вторую панель было
  // нельзя (замер: кнопка «AI-ассистент» [1507, 1680] под панелью
  // «Перепроверить» [1490, 1910] на 1920).
  //
  // Класс ставит СЛОЙ, а не каждая панель у себя: мест открытия пять
  // (§6.0.7), и шестое забыло бы про сдвиг молча. Решает ФАКТ —
  // видима ли хоть одна панель-док, — а не чьё-то намерение.
  function сдвиг() {
    // ПАНЕЛЬ-ДОК ВЫВОДИТСЯ ИЗ ГЕОМЕТРИИ, А НЕ ИЗ КЛАССА. Классов у них
    // уже два — системный `.v2-assist-dock` (питание, «Перепроверить»,
    // лекарство) и свой `.apt-ai` шириной 27rem, — и перечень отстал бы
    // на третьем (§6.0.7). Признак: панель стоит `fixed`, прижата
    // к правому краю окна и занимает НЕ ВЕСЬ экран. На узкой ширине
    // панель во весь экран, и условие снимает сдвиг само.
    var ширина = 0;
    var список = панели();
    for (var i = 0; i < список.length; i++) {
      var эл = список[i];
      if (!видно(эл)) continue;
      var ст = getComputedStyle(эл);
      if (ст.position !== 'fixed') continue;
      var b = эл.getBoundingClientRect();
      // ДОПУСК У ПРАВОГО КРАЯ — ШИРИНА ПОЛОСЫ ПРОКРУТКИ. Замер
      // на 1920: правый край панели 1910 при ширине окна 1920, потому
      // что страница держит резерв под полосу (`scrollbar-gutter:
      // stable`, задача 260). Строгое равенство не срабатывало
      // ни разу, и сдвиг молча не ставился.
      var окно = document.documentElement.clientWidth;
      if (b.right < окно - 24) continue;
      if (b.width > окно * 0.9) continue;
      if (b.width > ширина) ширина = b.width;
    }
    var корень = document.documentElement;
    корень.classList.toggle('v2-dock-open', ширина > 0);
    if (ширина > 0) корень.style.setProperty('--v2-dock-shift', Math.round(ширина) + 'px');
    else корень.style.removeProperty('--v2-dock-shift');
  }

  function пересчитать() {
    запланировано = false;
    сдвиг();
    var список = панели();
    var открылись = [];
    for (var i = 0; i < список.length; i++) {
      var эл = список[i];
      var сейчас = видно(эл);
      var было = видно_было.get(эл);
      видно_было.set(эл, сейчас);
      // ПЕРВОЕ СОСТОЯНИЕ ОТКРЫТИЕМ НЕ СЧИТАЕТСЯ: панель, видимая
      // в первом кадре, только что нарисована сервером.
      if (было === undefined) continue;
      if (сейчас && !было) {
        открылись.push(эл);
        открывший.set(эл, последний_орган);
      }
    }
    if (!открылись.length) return;
    var все = панели();
    for (var j = 0; j < все.length; j++) {
      if (открылись.indexOf(все[j]) === -1 && видно(все[j])) закрыть(все[j]);
    }
  }

  function запланировать() {
    if (запланировано) return;
    запланировано = true;
    requestAnimationFrame(пересчитать);
  }

  // Последний нажатый орган — им панель и открыли. Фаза захвата:
  // обработчик страницы может остановить всплытие.
  document.addEventListener('pointerdown', function (e) {
    var t = e.target;
    if (t && t.closest) {
      var о = t.closest('button, a, [role="button"], summary, [onclick]');
      if (о) последний_орган = о;
    }
  }, true);

  // ФАЗА ЗАХВАТА — разбор в шапке. Условие про открытую модалку общее:
  // окно поверх панели закрывается первым.
  document.addEventListener('keydown', function (e) {
    if (e.key !== 'Escape') return;
    if (document.querySelector('.modal-ov.open')) return;
    var из = открытые();
    if (!из.length) return;
    // Закрывается ВЕРХНЯЯ. Открытых панелей после этой правки одна,
    // но порядок назван явно, чтобы он не зависел от порядка в разметке.
    var верх = из[из.length - 1];
    if (закрыть(верх)) вернуть_фокус(верх);
  }, true);

  document.addEventListener('click', function (e) {
    var t = e.target;
    if (!t || !t.closest) return;
    var список = панели();
    for (var i = 0; i < список.length; i++) {
      var сел = список[i].getAttribute('data-panel-backdrop');
      if (!сел) continue;
      var фон = document.querySelector(сел);
      if (фон && (t === фон || фон.contains(t)) && видно(список[i])) {
        if (закрыть(список[i])) вернуть_фокус(список[i]);
        return;
      }
    }
  }, true);

  window.панель_закрыть_все = function () {
    открытые().forEach(закрыть);
  };

  function запустить() {
    панели().forEach(function (эл) { видно_было.set(эл, видно(эл)); });
    new MutationObserver(запланировать).observe(document.documentElement, {
      attributes: true,
      attributeFilter: ['class', 'hidden', 'open', 'style', 'inert', 'aria-hidden'],
      subtree: true,
      childList: true
    });
    // Появление панели анимировано (`.apt-ai` играет `transform`), и
    // в момент мутации вычисленная видимость ещё ложна — тот же замер,
    // что у `panel-refresh.js`: без конца анимации слой панель проспит.
    document.addEventListener('transitionend', запланировать, true);
    document.addEventListener('animationend', запланировать, true);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', запустить);
  } else {
    запустить();
  }
})();

def test_отклонение_вниз_и_вверх_у_жира_покрашено_одинаково():
    """Симметрия названа отдельным тестом, потому что это ИМЕННО ТО, что
    правка меняла. Жир 8 % и жир 30 % — оба сильное отклонение; жир 14 %
    и 24 % — оба отклонение. Раньше низ был на тон мягче верха."""
    def тон(значение):
        строки = bs.показатели({"body_fat_pct": значение}, "male", 28, 190.0)
        return строки[0]["тон"], строки[0]["категория"]
    assert тон(8.0)[0] == тон(30.0)[0] == "bad"
    assert тон(14.0)[0] == тон(24.0)[0] == "warn"
    assert тон(19.0)[0] == "ok"
    # Сторону отклонения называет СЛОВО, а не цвет, — иначе симметрия
    # была бы потерей сведений
    assert тон(8.0)[1] != тон(30.0)[1]
    assert тон(14.0)[1] != тон(24.0)[1]


def test_на_границе_зоны_цвет_берётся_у_верхней_зоны():
    """Отрицательный контроль по границе: значение РОВНО на пороге уходит
    вверх (правило `зона`), и цвет обязан уйти вместе с ним. Разъедься
    они — полоса говорила бы одно, слово другое."""
    for значение, категория, тон in [(11.0, "низкий", "warn"),
                                     (17.0, "норма", "ok"),
                                     (22.0, "выше среднего", "warn"),
                                     (27.0, "высокий", "bad")]:
        строка = bs.показатели({"body_fat_pct": значение}, "male", 28, 190.0)[0]
        assert (строка["категория"], строка["тон"]) == (категория, тон), значение



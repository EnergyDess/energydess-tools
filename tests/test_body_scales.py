def test_частичная_запись_даёт_только_пришедшее():
    """Три показателя из одиннадцати — ровно три строки. Строк «нет
    данных» здесь не бывает: отсутствие означает «весы не измеряли»."""
    строки = bs.показатели({"weight_kg": 99.4, "bmi": 27.5, "body_fat_pct": 28.4,
                            "visceral_fat": 12.0},
                           "male", 28, 190.0)
    assert [с["поле"] for с in строки] == ["bmi", "body_fat_pct", "visceral_fat"]



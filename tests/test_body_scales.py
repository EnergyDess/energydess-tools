# -*- coding: utf-8 -*-
"""Шкалы состава тела: границы норм, округление, категории, телосложение.

ГЛАВНЫЙ ТЕСТ ЗДЕСЬ — ПЕРВЫЙ. Он держит утверждение, на котором стоит весь
`body_scales.py`: пороги, которые мы считаем, — это те же пороги, которые
показывает приложение Zepp Life. Числа в нём сняты с живого экрана
приложения (сверочный профиль: мужской, 190 см, 99.4 кг, до 29 лет),
а не выведены из формул, которые тут же и проверяются. Разойдись
формула с экраном — упадёт именно он, и упадёт с именем показателя.

Остальное — про немой отказ в обе стороны:

  · показатель, которого в записи нет, не должен появиться нулём;
  · показатель без порогов не должен получить пустую полосу;
  · значение РОВНО на границе обязано попадать в одну и ту же зону
    всегда, а не туда, куда его отправит очередная ветка;
  · значение за краем крайней зоны обязано прижаться к краю полосы
    и НАЗВАТЬ крайнюю категорию, а не уехать за её пределы.

База не поднимается вовсе: `body_scales` — чистый модуль.
"""

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import body_scales as bs   # noqa: E402


# ── 1. Пороги приложения воспроизводятся ───────────────────────────────────

ПРОФИЛЬ = {"пол": "male", "возраст": 28, "рост_см": 190.0, "вес_кг": 99.4}

# Что показывает экран приложения. Числа сняты с него 2026-08-19
С_ЭКРАНА = [
    ("bmi",            [18.5, 25.0, 30.0]),
    ("body_fat_pct",   [11.0, 17.0, 22.0, 27.0]),
    ("water_pct",      [55.0, 65.1]),
    ("muscle_mass_kg", [49.5, 59.4]),
    ("protein_pct",    [16.0, 18.0]),
    ("bone_mass_kg",   [3.2, 4.2]),
    ("visceral_fat",   [10.0, 15.0]),
    ("bmr",            [2287.0]),
    ("ideal_weight_kg", [66.8, 90.3, 108.3]),
]


@pytest.mark.parametrize("поле,ожидание", С_ЭКРАНА)
def test_пороги_совпадают_с_экраном_приложения(поле, ожидание):
    спец = next(с for с in bs.ПОКАЗАТЕЛИ if с["поле"] == поле)
    посчитано = спец["пороги"](ПРОФИЛЬ)
    assert посчитано is not None, f"{поле}: порогов нет вовсе"
    assert len(посчитано) == len(ожидание), f"{поле}: {посчитано} против {ожидание}"
    for наш, их in zip(посчитано, ожидание):
        # Допуск двойной, и второе слагаемое не запас «на всякий случай».
        # Вес сверочного профиля известен с точностью до сотых (99.4 кг), а порог
        # обмена — это вес, умноженный на 23: те же 0.035 кг разницы дают
        # 0.8 ккал. Абсолютный допуск в 0.06 покрывает округление порогов,
        # относительный — неизвестность самого веса
        допуск = max(0.06, abs(их) * 0.0005)
        assert abs(наш - их) <= допуск, f"{поле}: {посчитано} против {ожидание}"


def test_шкала_идеального_веса_и_шкала_имт_это_одно_и_то_же():
    """Идеальный вес — те же пороги ИМТ, умноженные на рост в квадрате.
    Разъедься они, на одном экране стояли бы две шкалы, противоречащие
    друг другу: «ИМТ нормальный» и «вес избыточный» одновременно."""
    рост = 190.0
    имт = next(с for с in bs.ПОКАЗАТЕЛИ if с["поле"] == "bmi")["пороги"](ПРОФИЛЬ)
    вес = next(с for с in bs.ПОКАЗАТЕЛИ if с["поле"] == "ideal_weight_kg")["пороги"](ПРОФИЛЬ)
    assert len(имт) == len(вес)
    for и, в in zip(имт, вес):
        assert abs(и * (рост / 100) ** 2 - в) < 0.01


def test_у_каждого_показателя_зон_на_одну_больше_чем_порогов():
    """Структурная проверка на весь список разом. Ошибка тут немая:
    лишняя зона осталась бы без цвета, недостающая — без подписи,
    и увидеть это можно было бы только глазами и только на том
    показателе, который попал в кадр."""
    for спец in bs.ПОКАЗАТЕЛИ:
        пороги = спец["пороги"](ПРОФИЛЬ)
        if пороги is None:
            assert "зоны" not in спец or not спец.get("зоны")
            continue
        assert len(спец["зоны"]) == len(пороги) + 1, спец["поле"]
        assert len(спец["тона"]) == len(спец["зоны"]), спец["поле"]
        assert set(спец["тона"]) <= {"ok", "warn", "bad"}, спец["поле"]



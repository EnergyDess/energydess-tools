@pytest.mark.parametrize("балл,категория,тон", [
    (49, "очень низкая", "bad"),
    (50, "низкая", "warn"),          # ровно на пороге — в верхнюю зону
    (51, "низкая", "warn"),          # то самое «51 балл из 100» без ориентира
    (60, "средняя", "warn"),
    (79, "средняя", "warn"),
    (80, "хорошая", "ok"),
    (90, "отличная", "ok"),
    (100, "отличная", "ok"),
])
def test_у_оценки_тела_есть_слово_но_нет_полосы(балл, категория, тон):
    """«51 балл из 100» сам по себе не отвечает ни на что: 51 — это много
    или мало, из числа не следует. Пороги [50, 60, 80, 90] — из того же
    источника, что все остальные (`getBodyScoreScale`), полосы всё равно
    нет: балл это уже свёрнутая оценка."""
    строка = bs.показатели({"body_score": балл}, "male", 28, 190.0)[0]
    assert (строка["категория"], строка["тон"]) == (категория, тон)
    assert "пороги" not in строка and "положение" not in строка


def test_у_возраста_тела_слова_нет_и_взяться_ему_неоткуда():
    """Отрицательный контроль к предыдущему: у оценки тела пороги в
    источниках есть, у возраста тела — нет ни в одном. Появись у него
    категория, она была бы придуманной нами нормой."""
    строка = bs.показатели({"body_age": 40}, "male", 28, 190.0)[0]
    assert "категория" not in строка and "тон" not in строка


@pytest.mark.parametrize("возраст_тела,анкета,ожидание", [
    (40, 28, "в анкете — 28: на 12 лет больше"),
    (36, 34, "в анкете — 34: на 2 года больше"),
    (35, 34, "в анкете — 34: на 1 год больше"),
    (34, 34, "в анкете — 34: столько же"),
    (31, 34, "в анкете — 34: на 3 года меньше"),
    (23, 34, "в анкете — 34: на 11 лет меньше"),
])
def test_разницу_возрастов_считаем_мы(возраст_тела, анкета, ожидание):
    """Прежняя строка «в анкете — 28» была верна и бесполезна: рядом
    стоят два числа, и единственное, что с ними делают, — вычитают.
    Склонение проверяется на 1, 2, 3, 11 и 12 — там, где оно и ломается."""
    строка = bs.показатели({"body_age": возраст_тела}, "male", анкета, 190.0)[0]
    assert строка["сравнение"] == ожидание



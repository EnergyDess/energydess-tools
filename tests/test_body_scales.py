# ── 3. Границы зон ─────────────────────────────────────────────────────────

def test_значение_ровно_на_пороге_уходит_в_верхнюю_зону():
    """Правило одно на все показатели и записано в `зона`. Без него ответ
    на «жир ровно 17.0» зависел бы от того, кто писал ветку."""
    assert bs.зона(17.0, [11, 17, 22, 27]) == 2
    assert bs.зона(16.999, [11, 17, 22, 27]) == 1
    assert bs.зона(11.0, [11, 17, 22, 27]) == 1
    assert bs.зона(10.999, [11, 17, 22, 27]) == 0


def test_метка_на_пороге_стоит_ровно_на_стыке_зон():
    """Пять зон, порог второй — стык на 2/5. Проверяется числом, а не
    глазами: сдвиг на процент по картинке не виден вовсе."""
    assert bs.положение(17.0, [11, 17, 22, 27]) == pytest.approx(0.4)
    assert bs.положение(11.0, [11, 17, 22, 27]) == pytest.approx(0.2)
    assert bs.положение(27.0, [11, 17, 22, 27]) == pytest.approx(0.8)


def test_значение_за_краем_прижимается_к_краю_а_не_уезжает():
    """Жир 80 % и жир 1 % — оба вне крайних зон. Метка обязана остаться
    на полосе: доля больше единицы означала бы метку за пределами
    картинки, то есть невидимую."""
    for значение in (0.1, 1.0, 60.0, 200.0):
        доля = bs.положение(значение, [11, 17, 22, 27])
        assert 0.0 <= доля <= 1.0, значение
    assert bs.положение(200.0, [11, 17, 22, 27]) == 1.0
    assert bs.положение(0.1, [11, 17, 22, 27]) == 0.0


def test_за_краем_названа_крайняя_категория():
    строки = bs.показатели({"body_fat_pct": 80.0}, "male", 28, 190.0)
    жир = next(с for с in строки if с["поле"] == "body_fat_pct")
    assert жир["категория"] == "высокий"
    assert жир["тон"] == "bad"
    assert жир["положение"] == 1.0


def test_один_порог_две_зоны_метка_не_ломается():
    """У основного обмена порог один, внутренних промежутков нет вовсе —
    ширину крайним зонам взять неоткуда. Проверяем, что доля всё равно
    в пределах полосы."""
    for значение in (0.0, 1000.0, 2286.0, 5000.0):
        доля = bs.положение(значение, [2286.0])
        assert 0.0 <= доля <= 1.0, значение
    assert bs.положение(2286.0, [2286.0]) == pytest.approx(0.5)


# ── 4. Сборка блока ────────────────────────────────────────────────────────

ПОЛНАЯ = {"weight_kg": 99.4, "bmi": 27.53, "body_fat_pct": 28.473255,
          "water_pct": 52.1, "muscle_mass_kg": 67.5, "bone_mass_kg": 3.6485999,
          "protein_pct": 17.2, "visceral_fat": 12.0, "bmr": 2150.0,
          "body_age": 40, "body_score": 51, "ideal_weight_kg": 90.25}


def test_запись_без_состава_не_даёт_ни_одной_строки():
    """Отрицательный контроль: на записи, где из состава нет ничего,
    блок обязан быть пустым, а не показать одиннадцать прочерков."""
    assert bs.показатели({"weight_kg": 80.0}, **{"пол": "male", "возраст": 28,
                                                 "рост_см": 190.0}) == []


def test_частичная_запись_даёт_только_пришедшее():
    """Три показателя из одиннадцати — ровно три строки. Строк «нет
    данных» здесь не бывает: отсутствие означает «весы не измеряли»."""
    строки = bs.показатели({"weight_kg": 99.4, "bmi": 27.5, "body_fat_pct": 28.4,
                            "visceral_fat": 12.0},
                           "male", 28, 190.0)
    assert [с["поле"] for с in строки] == ["bmi", "body_fat_pct", "visceral_fat"]


def test_ноль_показывается_а_не_прячется():
    строки = bs.показатели({"weight_kg": 99.4, "visceral_fat": 0.0}, "male", 28, 190.0)
    assert len(строки) == 1 and строки[0]["значение"] == 0


def test_без_анкеты_остаются_значения_но_не_полосы():
    """Отрицательный контроль по анкете: пол, возраст и рост неизвестны.
    Персональные шкалы (жир, вода, мышцы, кость, обмен) полосы не
    получают; безличные (ИМТ, белок, висцеральный жир, идеальный вес
    без роста) ведут себя каждая по своему правилу."""
    строки = bs.показатели(ПОЛНАЯ)
    по_полю = {с["поле"]: с for с in строки}
    # значения на месте у всех
    assert len(строки) == len(ПОЛНАЯ) - 1     # weight_kg показателем не является
    for поле in ("body_fat_pct", "water_pct", "muscle_mass_kg",
                 "bone_mass_kg", "bmr", "ideal_weight_kg"):
        assert "пороги" not in по_полю[поле], f"{поле}: полоса без анкеты"
        assert "категория" not in по_полю[поле]
    # безличные шкалы работают всегда
    for поле in ("bmi", "protein_pct", "visceral_fat"):
        assert по_полю[поле]["пороги"], поле


def test_идеальный_вес_меряется_текущим_весом_а_не_собой():
    """Значение карточки — идеальный вес, а метку ставит ТЕКУЩИЙ вес.
    Подмени одно другим — полоса всегда показывала бы «среднее»."""
    строки = bs.показатели(ПОЛНАЯ, "male", 28, 190.0)
    идеал = next(с for с in строки if с["поле"] == "ideal_weight_kg")
    assert идеал["значение"] == 90.3           # standBodyWeight, округлённый
    assert идеал["категория"] == "избыточный"  # 99.4 кг между 90.25 и 108.3
    assert идеал["подпись_шкалы"]


def test_единица_склоняется_по_значению():
    строки = bs.показатели({"body_score": 51, "body_age": 41}, "male", 28, 190.0)
    по_полю = {с["поле"]: с for с in строки}
    assert по_полю["body_score"]["единица"] == "балл"
    assert по_полю["body_score"]["хвост"] == "из 100"
    assert по_полю["body_age"]["единица"] == "год"


def test_оценка_и_возраст_тела_идут_без_полосы():
    """Это уже готовые оценки. Вешать на них шкалу значит оценивать
    оценку — при том что пороги для оценки тела в источниках есть."""
    строки = bs.показатели({"body_score": 51, "body_age": 40}, "male", 28, 190.0)
    for с in строки:
        assert "пороги" not in с, с["поле"]


# ── 5. Телосложение ────────────────────────────────────────────────────────

def test_телосложение_показывается_только_при_совпадении():
    """Эталон SmartScaleConnect: bodyStyle=5 при жире 17.01 и мышцах
    50.96 у мужчины 172 см. Наш индекс для него — 4, то есть сдвиг
    на единицу; при совпадении слово выдаётся."""
    слово, почему = bs.телосложение(5, 17.01331, 50.961838, "male", 25, 172.0)
    assert слово == "среднее", почему


def test_несовпадение_даёт_молчание_и_причину():
    """Отрицательный контроль: то же измерение, но число другое. Слова
    быть не должно ни при каких условиях — угаданная категория хуже
    отсутствующей."""
    слово, почему = bs.телосложение(9, 17.01331, 50.961838, "male", 25, 172.0)
    assert слово is None
    assert "не подтверждено" in почему and "bodyStyle=9" in почему


def test_без_анкеты_телосложение_молчит():
    слово, почему = bs.телосложение(5, 17.0, 50.9, None, None, None)
    assert слово is None and "анкета" in почему


def test_без_числа_телосложения_молчит():
    слово, почему = bs.телосложение(None, 17.0, 50.9, "male", 25, 172.0)
    assert слово is None and почему == "нет данных"


def test_категорий_телосложения_ровно_девять():
    assert len(bs.ТЕЛОСЛОЖЕНИЕ) == 9
    assert len(set(bs.ТЕЛОСЛОЖЕНИЕ)) == 9

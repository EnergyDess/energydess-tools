# ── 3. Границы зон ─────────────────────────────────────────────────────────

def test_значение_ровно_на_пороге_уходит_в_верхнюю_зону():
    """Правило одно на все показатели и записано в `зона`. Без него ответ
    на «жир ровно 17.0» зависел бы от того, кто писал ветку."""
    assert bs.зона(17.0, [11, 17, 22, 27]) == 2
    assert bs.зона(16.999, [11, 17, 22, 27]) == 1
    assert bs.зона(11.0, [11, 17, 22, 27]) == 1
    assert bs.зона(10.999, [11, 17, 22, 27]) == 0


def test_метка_на_пороге_стоит_ровно_на_стыке_зон():
    """Пять зон, порог второй — стык на 2/5. Проверяется числом, а не
    глазами: сдвиг на процент по картинке не виден вовсе."""
    assert bs.положение(17.0, [11, 17, 22, 27]) == pytest.approx(0.4)
    assert bs.положение(11.0, [11, 17, 22, 27]) == pytest.approx(0.2)
    assert bs.положение(27.0, [11, 17, 22, 27]) == pytest.approx(0.8)


def test_значение_за_краем_прижимается_к_краю_а_не_уезжает():
    """Жир 80 % и жир 1 % — оба вне крайних зон. Метка обязана остаться
    на полосе: доля больше единицы означала бы метку за пределами
    картинки, то есть невидимую."""
    for значение in (0.1, 1.0, 60.0, 200.0):
        доля = bs.положение(значение, [11, 17, 22, 27])
        assert 0.0 <= доля <= 1.0, значение
    assert bs.положение(200.0, [11, 17, 22, 27]) == 1.0
    assert bs.положение(0.1, [11, 17, 22, 27]) == 0.0


def test_за_краем_названа_крайняя_категория():
    строки = bs.показатели({"body_fat_pct": 80.0}, "male", 28, 190.0)
    жир = next(с for с in строки if с["поле"] == "body_fat_pct")
    assert жир["категория"] == "высокий"
    assert жир["тон"] == "bad"
    assert жир["положение"] == 1.0


def test_один_порог_две_зоны_метка_не_ломается():
    """У основного обмена порог один, внутренних промежутков нет вовсе —
    ширину крайним зонам взять неоткуда. Проверяем, что доля всё равно
    в пределах полосы."""
    for значение in (0.0, 1000.0, 2286.0, 5000.0):
        доля = bs.положение(значение, [2286.0])
        assert 0.0 <= доля <= 1.0, значение
    assert bs.положение(2286.0, [2286.0]) == pytest.approx(0.5)



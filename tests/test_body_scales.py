def test_телосложение_показывается_только_при_совпадении():
    """Эталон SmartScaleConnect: bodyStyle=5 при жире 17.01 и мышцах
    50.96 у мужчины 172 см. Наш индекс для него — 4, то есть сдвиг
    на единицу; при совпадении слово выдаётся."""
    слово, почему = bs.телосложение(5, 17.01331, 50.961838, "male", 25, 172.0)
    assert слово == "среднее", почему


def test_несовпадение_даёт_молчание_и_причину():
    """Отрицательный контроль: то же измерение, но число другое. Слова
    быть не должно ни при каких условиях — угаданная категория хуже
    отсутствующей."""
    слово, почему = bs.телосложение(9, 17.01331, 50.961838, "male", 25, 172.0)
    assert слово is None
    assert "не подтверждено" in почему and "bodyStyle=9" in почему


def test_без_анкеты_телосложение_молчит():
    слово, почему = bs.телосложение(5, 17.0, 50.9, None, None, None)
    assert слово is None and "анкета" in почему


def test_без_числа_телосложения_молчит():
    слово, почему = bs.телосложение(None, 17.0, 50.9, "male", 25, 172.0)
    assert слово is None and почему == "нет данных"



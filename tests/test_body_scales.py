"""Шкалы состава тела: границы норм, округление, категории, телосложение.

ГЛАВНЫЙ ТЕСТ ЗДЕСЬ — ПЕРВЫЙ. Он держит утверждение, на котором стоит весь
`body_scales.py`: пороги, которые мы считаем, — это те же пороги, которые
показывает приложение Zepp Life. Числа в нём сняты с живого экрана
приложения (сверочный профиль: мужской, 190 см, 99.4 кг, до 29 лет),
а не выведены из формул, которые тут же и проверяются. Разойдись
формула с экраном — упадёт именно он, и упадёт с именем показателя.

Остальное — про немой отказ в обе стороны:

  · показатель, которого в записи нет, не должен появиться нулём;
  · показатель без порогов не должен получить пустую полосу;
  · значение РОВНО на границе обязано попадать в одну и ту же зону
    всегда, а не туда, куда его отправит очередная ветка;
  · значение за краем крайней зоны обязано прижаться к краю полосы
    и НАЗВАТЬ крайнюю категорию, а не уехать за её пределы.

База не поднимается вовсе: `body_scales` — чистый модуль.
"""


# -*- coding: utf-8 -*-
"""РЕЕСТР ПРОВЕРОК ПОКРЫВАЕТ ОБА РЯДА (задача 352, «аптечка-3», блок 1).

Проверка, которой в реестре нет, гоняется ВСЕГДА и называется в отчёте —
то есть быстрый ряд от неё не врёт. Но «всегда» у дорогой стендовой
пробы означает, что быстрый ряд перестаёт быть быстрым, и заметить это
можно только по времени. Пусть говорит тест, а не секундомер.
"""
import checks_registry as реестр
import project_lists as списки


def _все():
    _присваивания, команды = списки.разобрать()
    состав = [("ряд:%s" % н, к) for н, к in команды]
    состав += [("стенд:%s" % н, к) for н, к in списки.команды_стенда()]
    состав += [("скрипт:check_hh_owner.py", "py check_hh_owner.py"),
               ("скрипт:check_v2_showcase.py", "py check_v2_showcase.py"),
               ("pytest", "pytest")]
    return состав


def test_реестр_покрывает_оба_ряда():
    нет = реестр.непокрытые([i for i, _к in _все()])
    assert not нет, "в реестре нет: %s" % ", ".join(нет)


def test_в_реестре_нет_лишнего():
    """Обратная сторона: запись про проверку, которой в рядах уже нет.

    Такая запись не ломает прогон и потому живёт годами — ровно как
    жил перечень `ЭКРАНЫ` в `check_hover`, отставший на пятнадцать
    страниц (§6.0.7).
    """
    живые = {i for i, _к in _все()}
    лишние = [i for i in реестр.РЕЕСТР if i not in живые]
    assert not лишние, "в рядах таких проверок нет: %s" % ", ".join(лишние)


def test_свой_файл_проверки_входит_в_её_маски():
    """Правка `check_x.py` обязана прогнать `check_x.py`."""
    for id_, команда in _все():
        маски = реестр.маски_проверки(id_, команда)
        if маски == реестр.ВСЕГДА:
            continue
        for слово in команда.split():
            if слово.endswith(".py"):
                assert реестр.подходит(слово, маски), (
                    "%s не сторожит собственный файл %s" % (id_, слово))


def test_маска_не_ловит_чужое():
    """Признак должен РАЗДЕЛЯТЬ, а не совпадать со всем подряд.

    Маска, случайно ставшая `*`, дала бы быстрый ряд, равный полному,
    и молча: числа сошлись бы, время выросло, находок столько же.
    """
    посторонний = "static/exercises/1.jpg"
    широкие = []
    for id_, команда in _все():
        маски = реестр.маски_проверки(id_, команда)
        if маски != реестр.ВСЕГДА and реестр.подходит(посторонний, маски):
            широкие.append(id_)
    assert not широкие, "маска ловит картинку упражнения: %s" % ", ".join(широкие)

def _модель_b5(стенд, monkeypatch, ответы: dict):
    """Перехват вопросов B5: ключ — начало вопроса, значение — функция(вопрос) → dict."""
    прежняя = стенд["модель"]

    async def модель(клиент, инструмент, система, вопрос, потолок, модель=None, температура=0):
        for начало, ответ in ответы.items():
            if начало in вопрос:
                прежняя.вызовы.append(вопрос[:40])
                return json.dumps(ответ(вопрос), ensure_ascii=False), None
        return await прежняя(клиент, инструмент, система, вопрос, потолок, модель, температура)
    monkeypatch.setattr(ce, "_спросить", модель)



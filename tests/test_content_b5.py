ЧИСТО = {"H": "В GTA 6 больше 170 видов животных, и у каждого своя шерсть.",
         "T1": "170 видов животных GTA 6",
         "P": "170 видов",
         "S3.L1": "Итог: зверей больше, чем когда-либо.",
         "S4.L1": "Подписывайся, разберём охоту."}


def _перепиши(вопрос):
    строки = dict(re.findall(r"^(S\d+\.L\d+|H|T\d+|P) \([^)]*\): (.*)$", вопрос, re.M))
    итог = {}
    for к, т in строки.items():
        if к in ЧИСТО:
            итог[к] = ЧИСТО[к]
        elif к.startswith("T"):
            итог[к] = "Охота в GTA 6"
        else:
            итог[к] = ""        # связку — убрать
    return {"lines": итог}


def _с_питомцем(стенд, monkeypatch):
    _факты(стенд)
    м = стенд["модель"]
    м.поведение["хук"] = "В GTA 6 зоопарк и свой питомец."
    м.поведение["названия"] = [["Питомец в GTA 6", "Охота в GTA 6", "Все звери"]]
    м.поведение["доп_строки"] = [
        {"text": "По слухам, можно завести собаку.", "fact": True, "f": 3, "src": []},
        {"text": "Вспомни пса Чопа — тема с питомцем снова на месте.", "fact": False, "src": []}]
    м.поведение["доп_сегменты"] = [
        {"from": "9:40", "to": "10:30", "role": "вывод", "purpose": "итог",
         "lines": [{"text": "Итог: зверей море, и собака-питомец рядом.", "fact": False, "src": []}]},
        {"from": "10:30", "to": "11:00", "role": "призыв", "purpose": "подписка",
         "lines": [{"text": "Подписывайся, если ждёшь своего пса.", "fact": False, "src": []}]}]
    _модель_b5(стенд, monkeypatch, {
        "Слухи вне основной части": lambda в: {"hits": []},
        "Перепиши строки так, чтобы": _перепиши})


def test_питомец_не_в_крючке_выводе_призыве_названии(стенд, monkeypatch):
    _с_питомцем(стенд, monkeypatch)
    д = _данные(_собрать(стенд))
    питом = re.compile(r"питом|собак|пса\b|пёс", re.I)
    assert not питом.search(д["hook"]["text"]), д["hook"]
    assert not any(питом.search(т) for т in д["titles"]), д["titles"]
    for с in д["script"]:
        if с["role"] in ("вывод", "призыв", "крючок"):
            assert not any(питом.search(л["text"]) for л in с["lines"]), с
    тексты = [л["text"] for л in _строки(д)]
    assert "Вспомни пса Чопа — тема с питомцем снова на месте." not in тексты     # связка убрана
    assert "По слухам, можно завести собаку." in тексты                          # сам слух — в основной
    assert д["rumor_zones"]["found"] >= 5


def test_слух_по_смыслу_найден_моделью(стенд, monkeypatch):
    """Обратная сторона основ: «четвероногий друг» по словам не ловится,
    его называет смысловая сверка — и строка переписана."""
    _факты(стенд)
    м = стенд["модель"]
    м.поведение["доп_сегменты"] = [
        {"from": "9:40", "to": "10:30", "role": "вывод", "purpose": "итог",
         "lines": [{"text": "Итог: рядом будет четвероногий друг.", "fact": False, "src": []}]}]
    _модель_b5(стенд, monkeypatch, {
        "Слухи вне основной части": lambda в: {"hits": [
            {"line": к, "rumor": "R1"} for к in re.findall(r"^(S\d+\.L\d+): Итог: рядом", в, re.M)]},
        "Перепиши строки так, чтобы": _перепиши})
    д = _данные(_собрать(стенд))
    assert "Итог: рядом будет четвероногий друг." not in [л["text"] for л in _строки(д)]



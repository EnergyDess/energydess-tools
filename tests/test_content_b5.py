def test_факт_о_gta5_база_а_не_слух(стенд, monkeypatch):
    _факты(стенд)
    _база(стенд)
    стенд["модель"].поведение["доп_строки"] = [
        {"text": "В GTA 5 полиция искала тебя по звёздам розыска.", "fact": True,
         "src": [стенд["ид"]["слух"]]},
        {"text": "В GTA 5 можно было летать на дирижабле над Вайнвудом.", "fact": True, "f": "база", "src": []}]
    _модель_b5(стенд, monkeypatch, {"Фразы ниже — о вышедших частях": lambda в: {"lines": {
        к: "Помню, в пятёрке я любил кататься по Вайнвуду." for к in re.findall(r"^(S\d+\.L\d+):", в, re.M)}}})
    д = _данные(_собрать(стенд))
    строки = {л["text"]: л for л in _строки(д)}
    копы = строки["В GTA 5 полиция искала тебя по звёздам розыска."]
    assert копы["status"] == "база" and копы["kb"] and not копы["src"]
    assert "В GTA 5 можно было летать на дирижабле над Вайнвудом." not in строки
    память = строки["Помню, в пятёрке я любил кататься по Вайнвуду."]
    assert память.get("personal") and not память.get("status") and not память["src"]



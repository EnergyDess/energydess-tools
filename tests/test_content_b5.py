def test_проверь_перед_записью_собран(стенд):
    _факты(стенд)
    стенд["модель"].поведение["доп_строки"] = [
        {"text": "По слухам, можно завести собаку.", "fact": True, "f": 3, "src": []}]
    д = _данные(_собрать(стенд))
    почему = [р["why"] for р in д["review"]]
    # Письмо B6, 1.5 (задача 382) заменило прежнюю формулировку: крючок без
    # замечаний и слух, уже поданный как слух («По слухам…»), в список
    # больше не идут — список равен пометкам в тексте один к одному.
    assert not any(р["time"] == "0:00" and р["text"] == д["hook"]["text"] for р in д["review"])
    assert not any(р["text"] == "По слухам, можно завести собаку." for р in д["review"])
    assert any("нет источника" in в for в in почему)  # «Релиз перенесли на осень» без источника
    assert len(д["review"]) == cp.пометки_пакета(д)



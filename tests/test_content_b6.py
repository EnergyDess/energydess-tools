"""Пакет ролика, письмо B6 (задача 382): старая дата в кадрах, шум
в «Проверь перед записью», мелочи. Все правки — код по готовому пакету,
модель здесь не нужна. Контроли:
1. КАДР с «26 мая 2026» в описании Gemini — пометка и пункт «Проверь»;
   кадр без даты — без пометки. Строка текста со старой датой — «проверь»,
   рассказ о переносе — нет.
2. СЛУХИ после объявления блока («Дальше пойдут слухи…») — без «скажи, что
   это слух», и в следующем разделе тоже, пока не встретился официальный
   факт; слух без объявления — с пометкой.
3. «NPC» в строке сопоставляется с фактом про NPC; «мир» из составной
   сущности «подводный мир» не ловит «живой мир» в крючке.
4. «Лусия»/«Лусию» → «Люсия»/«Люсию»; соседний почти-повтор склеен;
   категория из факта не выпадает.
5. Пунктов «Проверь» ровно столько, сколько пометок в тексте.
"""
import asyncio
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))

import content_package as cp  # noqa: E402

БАЗА = """GTA VI (Rockstar Games):
- Главные герои — Джейсон и Люсия, пара.
- Релиз GTA 6 перенесён: дата 26 мая 2026 года на финальной плашке трейлера 2 устарела, актуальная дата — 19 ноября 2026 года.

Термины:
- rare → редкие
- unlockable → открываемые (не: открытые, открытых)
- legendary → легендарные
- common → обычные
- Lucia → Люсия (не: Лусия, Лючия)"""


def _к(факты=None, трейлеры=None):
    return {"база": БАЗА, "материал": {"list": факты or []}, "источники": [], "образцы": [],
            "трейлеры": трейлеры or [], "трейлеры_сбой": []}


def _л(текст, **поля):
    return {"text": текст, "fact": поля.pop("fact", False), "src": поля.pop("src", []), **поля}


# ── 1. Старая дата ────────────────────────────────────────────────────

def test_кадр_со_старой_датой_помечен_и_в_проверь():
    трейлер = {"yt_id": "VQRLujxTm3c", "title": "Grand Theft Auto VI Trailer 2", "scenes": [
        {"t": "2:36", "what": "Финальный логотип игры Grand Theft Auto VI с датой релиза: 26 мая 2026 г"},
        {"t": "2:33", "what": "Панорама шоссе и небоскрёбов на закате"}]}
    съём = [{"what": "Логотип GTA 6 с датой релиза для финала", "source": "трейлер", "where": "",
             "basis": "trailer:VQRLujxTm3c@2:36", "for": "6:40–7:00"},
            {"what": "Финальная панорама шоссе", "source": "трейлер", "where": "",
             "basis": "trailer:VQRLujxTm3c@2:33", "for": "6:00–6:40"}]
    итог = cp.обосновать_съёмки(съём, _к(трейлеры=[трейлер]))
    assert итог[0].get("old_date") == cp.ПОМЕТКА_СТАРОЙ_ДАТЫ
    assert not итог[1].get("old_date")
    данные = {"hook": {}, "script": [], "shots": итог}
    пункты = cp.перечитать(данные)
    assert len(пункты) == 1 and "старая дата" in пункты[0]["why"]


def test_строка_со_старой_датой_проверь_а_рассказ_о_переносе_нет():
    данные = {"hook": {}, "shots": [], "script": [{"from": "6:00", "lines": [
        _л("Выход игры — 26 мая 2026 года."),
        _л("Раньше обещали 26 мая, а теперь релиз 19 ноября 2026.")]}]}
    cp.доводка(данные, _к())
    a, b = данные["script"][0]["lines"]
    assert a.get("check") and "19 ноября 2026" in a["check"]
    assert not b.get("check")


# ── 2. Объявленный блок слухов ────────────────────────────────────────

def _слух(текст):
    return _л(текст, fact=True, status="слух", check=cp.СКАЖИ_СЛУХ)


def test_слухи_после_объявления_без_пометки_и_в_следующем_разделе():
    данные = {"hook": {}, "shots": [], "script": [
        {"from": "3:50", "lines": [_л("Дальше пойдут слухи. Их принёс ролик Davy Jones."),
                                   _слух("В игре будут зоопарки."), _слух("Питомец-собака.")]},
        {"from": "4:50", "lines": [_слух("Под водой акулы и киты."), _слух("Плюс сноркелинг.")]},
        {"from": "5:50", "lines": [_л("В игре более 170 видов животных.", fact=True, status="официально"),
                                   _слух("Говорят про игуан и кошек — инвазивные виды.")]},
    ]}
    cp.доводка(данные, _к())
    строки = [л for с in данные["script"] for л in с["lines"]]
    assert [bool(л.get("check")) for л in строки] == [False, False, False, False, False, False, True]


def test_слух_без_объявления_с_пометкой():
    данные = {"hook": {}, "shots": [], "script": [
        {"from": "1:00", "lines": [_л("Теперь про животных."), _слух("В игре будут зоопарки.")]}]}
    cp.доводка(данные, _к())
    assert данные["script"][0]["lines"][1]["check"] == cp.СКАЖИ_СЛУХ


# ── 3. Аббревиатуры и короткие приметы ────────────────────────────────

def test_строка_с_NPC_сопоставляется_с_фактом_про_NPC():
    факт = {"id": 10, "text": "Rockstar сделала самую детальную и разнообразную систему NPC в серии",
            "src": [5], "status": "официально"}
    л = _л("Rockstar называет это самой детальной и разнообразной системой NPC в серии",
           fact=True, src=[5], fid=10)
    данные = {"script": [{"from": "3:00", "role": "основная", "lines": [л]}]}
    к = {**_к([факт]), "формулировки": {}, "источники": [{"id": 5, "official": False, "rumor": False,
                                                          "leak": False, "source": "IGN"}]}
    asyncio.run(cp.разметить_статусы(None, к, данные))
    assert л["fid"] == 10 and л["status"] == "официально" and not л.get("review")


def test_мир_из_подводного_мира_не_ловит_живой_мир():
    факты = [{"id": 29, "status": "слух", "text": "В подводном мире акулы и киты",
              "entities": ["подводный мир", "акулы", "киты"]},
             {"id": 23, "status": "официально", "text": "Более 170 видов животных", "entities": ["виды"]}]
    сущ = cp.сущности_слухов(факты)
    assert not cp.слух_в("Rockstar реально сделали целый живой мир.", сущ)
    assert cp.слух_в("А под водой киты.", сущ) == [29]


# ── 4. Термины, повторы, категории ────────────────────────────────────

def test_Лусия_становится_Люсией_в_тексте_и_кадрах_со_склонением():
    данные = {"hook": {"text": "Джейсон и Лусия"}, "titles": [], "thumbnail": {},
              "script": [{"from": "0:00", "lines": [_л("Он встречает Лусию у тюрьмы, Лючия ждёт.")]}],
              "shots": [{"what": "Джейсон и Лусия на гидроцикле", "where": "Trailer 2, 2:19 — Лусия мчит"}]}
    cp.доводка(данные, _к())
    assert данные["script"][0]["lines"][0]["text"] == "Он встречает Люсию у тюрьмы, Люсия ждёт."
    assert данные["hook"]["text"] == "Джейсон и Люсия"
    assert "Люсия" in данные["shots"][0]["what"] and "Лусия" not in данные["shots"][0]["where"]


def test_соседний_почти_повтор_склеен():
    данные = {"hook": {}, "shots": [], "script": [{"from": "1:40", "lines": [
        _л("Животных поделили на категории.", src=[3]),
        _л("Животных поделили на категории: редкие, открываемые и легендарные.", src=[4]),
        _л("Это уже другое.")]}]}
    cp.доводка(данные, _к())
    строки = данные["script"][0]["lines"]
    assert len(строки) == 2 and "легендарные" in строки[0]["text"] and строки[0]["src"] == [3, 4]


def test_категория_из_факта_не_выпадает():
    факт = {"id": 24, "status": "официально", "src": [1],
            "text": "Животные делятся на категории: обычные, редкие, открываемые и легендарные"}
    данные = {"hook": {}, "shots": [], "script": [{"from": "1:40", "lines": [
        _л("Есть категории: редкие, открываемые и легендарные.", fact=True, fid=24)]}]}
    cp.доводка(данные, _к([факт]))
    assert "обычные, редкие, открываемые и легендарные" in данные["script"][0]["lines"][0]["text"]


# ── 5. Один к одному ─────────────────────────────────────────────────

def test_пунктов_проверь_столько_же_сколько_пометок():
    данные = {"hook": {"text": "Крючок", "review": "слух в крючок — убери предмет слуха"},
              "thumbnail": {"text": "Текст", "review": "длиннее 4 слов"},
              "review_dropped": [{"time": "2:00", "text": "убранная", "why": "убрана: язык"}],
              "script": [{"from": "1:00", "lines": [
                  _л("Дальше пойдут слухи."), _слух("Зоопарки."),
                  _л("Без источника", fact=True, check="нет источника"),
                  _л("Связка", review="номер факта не совпал с текстом строки — это связка, проверь"),
                  _л("Переписана мнением", bridge_fixed="утверждение без опоры — переписано мнением"),
                  _л("Слух без пометки", fact=True, status="слух")]}],
              "shots": [{"what": "Логотип", "where": "с датой релиза: 26 мая 2026 г"},
                        {"what": "Кадр", "unverified": "разбор недоступен"}, {"what": "Чистый"}]}
    cp.доводка(данные, _к())
    пункты = cp.перечитать(данные)
    assert len(пункты) == cp.пометки_пакета(данные) == 7



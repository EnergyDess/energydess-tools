# -*- coding: utf-8 -*-
"""СЕЛЕКТОР ПО `data-find` ОБЯЗАН БЫТЬ В ТОМ ЖЕ ВИДЕ, ЧТО И АТРИБУТ.

═══════════════════════════════════════════════════════════════════════
ЗАЧЕМ, И ЭТО ЗАМЕР, А НЕ ПРЕДОСТОРОЖНОСТЬ
═══════════════════════════════════════════════════════════════════════

`data-find` собирает СЕРВЕР через `medkit_defs.нормаль`, а та приводит
строку к нижнему регистру (§5.8: SQLite кириллицу не приводит, поэтому
сравнение живёт в Python). Отбор по атрибуту в CSS РЕГИСТРОЗАВИСИМ —
значит `[data-find*="препарат А"]` не совпадает НИ С ЧЕМ.

ЗАМЕР 2026-09-01 на живом стенде:

    [data-find*="препарат А"] [data-doses]   найдено 0
    [data-find*="препарат а"] [data-doses]   найдено 1

Сцена окна способа приёма в `check_hover` не открывалась НИ РАЗУ
с задачи 173 — то есть органы этого окна не проверялись на залипание
вовсе, а проверка при этом печатала «чисто». Немой отказ внутри
инструмента приёмки.

═══════════════════════════════════════════════════════════════════════
ПОЧЕМУ ТЕСТОМ, А НЕ ПРАВКОЙ ДВУХ МЕСТ
═══════════════════════════════════════════════════════════════════════

Правку регистра уже делали — она доехала до `check_pixel_diff`
и НЕ доехала до `check_hover` и `shots_medkit_187` (§6.0.7: правку
положили на путь, названный в постановке, а второй такой же остался).
Это ЧЕТВЁРТЫЙ случай одного класса за три захода, считая эталоны
`check_medkit_dosage` (задача 219) и разведку источников (задача 230).

Значит закрывается КЛАСС: любой селектор по `data-find` сверяется
с тем, что вернула бы `нормаль`. Перечня файлов здесь нет — они
берутся у git, и файл, заведённый завтра, попадает под правило сам.
"""
import re
import subprocess

import medkit_defs as опр

# Значение атрибута внутри селектора: [data-find*="..."] и его
# одинарнокавычечная форма. Ищем в ОТСЛЕЖИВАЕМЫХ файлах, а не
# по дереву: мусор скретчпада правилу не подчиняется
СЕЛЕКТОР = re.compile(r"""data-find\s*\*?=\s*\\?["']([^"'\\]+)""")


# ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ, И ОНО НАЗВАНО: свой же файл.
#
# Внутри него ЛЕЖАТ ЗАВЕДОМО НЕВЕРНЫЕ строки — фикстуры обратного
# контроля («Препарат А» с заглавной) и примеры в шапке. Без
# исключения проверка находит САМУ СЕБЯ, и её красный означает
# «контроль на месте», а не «в проекте дефект».
#
# ПОИМЁННО, А НЕ МАСКОЙ `tests/*`: маска завтра проглотит файл,
# которого сегодня нет, и он молча выпадет из-под правила (§6.0.7).
#
# НАЙДЕНО НЕ ЧТЕНИЕМ: первый прогон прошёл, потому что файл ещё
# не был закоммичен, — а список берётся У GIT. Красным он стал
# ровно в тот момент, когда попал в индекс.
СВОЙ_ФАЙЛ = "tests/test_data_find_selectors.py"


def _файлы():
    вывод = subprocess.run(["git", "ls-files", "-z"],
                           capture_output=True).stdout
    имена = вывод.decode("utf-8", "replace").split("\0")
    return [и for и in имена
            if и.endswith((".py", ".js", ".html")) and и != СВОЙ_ФАЙЛ]


def test_селекторы_по_data_find_в_нижнем_регистре():
    находки = []
    for имя in _файлы():
        try:
            текст = open(имя, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        for м in СЕЛЕКТОР.finditer(текст):
            значение = м.group(1)
            # Пропускаем подстановки — там значение считает код
            if "{" in значение or "$" in значение or "%" in значение:
                continue
            if значение != опр.нормаль(значение):
                находки.append("%s: %r (нормаль дала %r)"
                               % (имя, значение, опр.нормаль(значение)))
    assert not находки, (
        "селектор по data-find не совпадёт с атрибутом — сервер кладёт "
        "туда `нормаль`, а отбор по атрибуту регистрозависим:\n  "
        + "\n  ".join(находки))


def test_признак_РАЗДЕЛЯЕТ_а_не_молчит_всегда():
    """ОБРАТНЫЙ КОНТРОЛЬ: тест выше обязан находить подлог.

    Проверка, которая молчит на любом входе, неотличима от пройденной
    (§6.0.3). Здесь ломать нечего в файле — значит ломаем ПРИЗНАК
    на строке, и он обязан назвать её находкой.
    """
    плохо = 'стр.query_selector(\'.apt-card[data-find*="Препарат А"]\')'
    хорошо = 'стр.query_selector(\'.apt-card[data-find*="препарат а"]\')'
    нашли = [м.group(1) for м in СЕЛЕКТОР.finditer(плохо)]
    assert нашли == ["Препарат А"], нашли
    assert нашли[0] != опр.нормаль(нашли[0]), "подлог обязан отличаться"
    ок = [м.group(1) for м in СЕЛЕКТОР.finditer(хорошо)]
    assert ок == ["препарат а"], ок
    assert ок[0] == опр.нормаль(ок[0]), "законная строка обязана пройти"

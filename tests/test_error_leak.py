# -*- coding: utf-8 -*-
"""ОТВЕТ ЧУЖОГО СЕРВИСА НЕ ПОКАЗЫВАЕТСЯ ПОСТОРОННЕМУ (№244, C.2).

Владелец увидел на экране аптечки полный ответ OpenRouter с кодом 402,
советом уменьшить `max_tokens` и ссылкой на кабинет оплаты. Человеку,
который просто фотографирует упаковку, это не говорит ничего.

ДВА ТРЕБОВАНИЯ, И ВТОРОЕ ОБРАТНОЕ: подробности обязаны ПРОПАСТЬ
у обычного и обязаны ОСТАТЬСЯ у владельца. Проверка, требующая только
первого, прошла бы на функции, которая прячет всё подряд, — и отняла бы
у владельца единственный способ понять, что чинить.
"""
import os

os.environ.setdefault("DB_PATH", "app.db")

import main


class Человек:
    def __init__(self, admin):
        self.is_admin = admin


ЧУЖОЙ = main.СбойСервисаМоделей(
    "Ошибка ИИ (402): This request requires more credits, or fewer "
    "max_tokens. visit https://openrouter.ai/settings/credits")


def test_посторонний_не_видит_ответа_сервиса():
    т = main._сбой_наружу(ЧУЖОЙ, Человек(False))
    assert "402" not in т
    assert "credits" not in т
    assert "openrouter" not in т.lower()
    assert "позже" in т.lower()


def test_гость_без_учётной_записи_тоже_не_видит():
    т = main._сбой_наружу(ЧУЖОЙ, None)
    assert "402" not in т and "credits" not in т


def test_ОБРАТНЫЙ_владелец_видит_полностью():
    т = main._сбой_наружу(ЧУЖОЙ, Человек(True))
    assert "402" in т and "credits" in т


def test_наш_текст_проходит_как_есть_обоим():
    """Наши сообщения писаны для человека, и прятать их нельзя:
    «снимок весит 24 МБ» говорит, что делать, а «сервис недоступен»
    отправило бы чинить не то."""
    наш = RuntimeError("Снимок слишком большой для разбора: 9.7 МБ "
                       "при потолке 5 МБ. Сфотографируйте заново")
    for кто in (Человек(False), Человек(True), None):
        assert "9.7 МБ" in main._сбой_наружу(наш, кто)


def test_чужой_текст_поднимается_нужным_классом():
    """Заслон держится КЛАССОМ, а не разбором строки. Место, которое
    пересказывает чужой ответ, обязано поднимать его именем."""
    import io
    import re
    s = io.open("main.py", encoding="utf-8").read()
    i = s.index("async def _call_vision")
    j = s.index("\nasync def ", i + 10)
    тело = s[i:j]
    assert "СбойСервисаМоделей" in тело
    # и голого RuntimeError с чужим текстом там не осталось
    assert not re.search(r'raise RuntimeError\(f?"Ошибка ИИ', тело)


def test_чужого_текста_на_пути_наружу_НЕ_ОСТАЛОСЬ():
    """ПОЛНОТА, А НЕ ПЕРЕЧЕНЬ МЕСТ (§6.0.7).

    Первый заход закрыл точки, найденные глазами, и грепом немедленно
    нашлись ещё ДВЕ — генерация письма и разбор резюме в HH-ассистенте,
    где текст сервиса уходил наружу ЦЕЛИКОМ, даже без обрезки.
    Признак структурный: тело ответа не должно нести текст ответа
    чужого сервиса напрямую.
    """
    import io
    import re
    s = io.open("main.py", encoding="utf-8").read()
    плохие = [
        л.strip() for л in s.split("\n")
        if re.search(r'JSONResponse.*"error".*'
                     r'(response\.text|resp\.text|r\.text)', л)
    ]
    assert плохие == [], плохие

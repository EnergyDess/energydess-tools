"""Фасад видео упражнения: кадр отдаёт СВОЙ домен (BACKLOG №73).

Почему на это есть тесты. Смысл фасада в отрицательном утверждении —
«до нажатия к YouTube не уходит ни одного запроса», — а отрицательные
утверждения тихо перестают быть верными. Достаточно кому-нибудь вернуть
в шаблон `img.youtube.com`, и страница будет выглядеть ровно так же:
кадр на месте, ничего не сломано, обвязка снова грузится.

Проверяется ЧЕТЫРЁХ вещи, и каждая закрывает свой способ отказа:

  · чужой id не скачивается вовсе — иначе эндпоинт становится открытым
    прокси за картинками YouTube по любому id;
  · id не той формы не доходит до файловой системы — путь собирается
    из него, и `../` там был бы дырой;
  · кадра нет — отдаётся СВОЯ заглушка и `no-store`, а не ссылка наружу
    и не вечный кеш: разовый сбой сети иначе заморозил бы серую плашку
    у пользователя навсегда;
  · в шаблонах не осталось прямых ссылок на домены YouTube за картинкой.

Последний тест — единственный, который поймает возврат прямой ссылки.
Проверка 7 (`check_docs`) его не берёт: она сверяет имена из документов
с кодом, а тут речь про домен в разметке.

DB_PATH уводится во временный файл по той же причине, что в
`test_dossier_ready`: путь читается один раз при импорте и действует
на весь прогон.
"""


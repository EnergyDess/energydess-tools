# ── Разметка ────────────────────────────────────────────────────────────────

# Домен ищется В ПОЛОЖЕНИИ АДРЕСА — после `//`, — а не где угодно
# в тексте. Первая версия искала голую строку и падала на СОБСТВЕННОМ
# комментарии («i.ytimg.com — тот же YouTube»), то есть считала прозу
# кодом. Ровно то, что задача 99 чинила в check_docs; здесь та же
# ошибка обошлась дешевле только потому, что тест был новый.
ДОМЕНЫ_КАДРА = ("img.youtube.com", "i.ytimg.com", "i9.ytimg.com")
АДРЕС_КАДРА = re.compile(
    r"(?:https?:)?//(?:" + "|".join(re.escape(д) for д in ДОМЕНЫ_КАДРА) + r")")

# Шаблоны, показывающие видео упражнений. Список ЯВНЫЙ: файл, которого
# в нём нет, молча выпадает из-под проверки — тот же класс отказа, что
# у переменной `pages` в CLAUDE.md §6.0.2.
ШАБЛОНЫ_С_ВИДЕО = ("templates/workout.html", "templates/admin_exercises.html")


@pytest.mark.parametrize("имя", ШАБЛОНЫ_С_ВИДЕО)
def test_в_разметке_нет_прямой_ссылки_за_кадром(имя):
    """Кадр берётся только у своего эндпоинта.

    Это ЕДИНСТВЕННАЯ проверка, которая поймает возврат прямой ссылки:
    страница с `img.youtube.com` выглядит и работает точно так же,
    просто обвязка снова грузится.
    """
    текст = io.open(КОРЕНЬ / имя, encoding="utf-8").read()
    найдено = АДРЕС_КАДРА.findall(текст)
    assert not найдено, (
        f"{имя} тянет кадр с {найдено} — это тот же YouTube; "
        f"кадр отдаёт /exercise-preview/{{id}}.jpg")


@pytest.mark.parametrize("имя", ШАБЛОНЫ_С_ВИДЕО)
def test_кадр_берётся_у_своего_эндпоинта(имя):
    текст = io.open(КОРЕНЬ / имя, encoding="utf-8").read()
    assert "/exercise-preview/" in текст


def test_плеер_подставляется_только_по_нажатию():
    """`<iframe>` создаётся в обработчике нажатия, а не при раскрытии блока.

    До правки он появлялся, как только человек открывал «Как выполнять», —
    то есть у всякого, кто просто хотел прочитать текст техники.
    """
    текст = io.open(КОРЕНЬ / "templates/workout.html", encoding="utf-8").read()
    m = re.search(r"фасад\.addEventListener\('click'.*?\}\);", текст, re.S)
    assert m, "обработчика нажатия на фасад нет"
    assert "youtube-nocookie.com/embed/" in m.group(0), (
        "плеер создаётся не в обработчике нажатия")


def test_фасад_настоящая_кнопка():
    """Не div с onclick: до div нельзя дойти табом и нечем нажать."""
    for имя, класс in (("templates/workout.html", "wk-ex-video-facade"),
                       ("templates/admin_exercises.html", "ex-card-thumb")):
        текст = io.open(КОРЕНЬ / имя, encoding="utf-8").read()
        assert re.search(
            r"<button[^>]*class=\"[^\"]*" + класс, текст), (
            f"{имя}: {класс} должен быть <button>")

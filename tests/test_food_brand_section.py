"""Бренд весит меньше названия, и дубли считаются по видимому.

ЧТО БЫЛО. Живой прогон 2026-08-16, запрос «молоко простоквашино»:
восемнадцать находок, первые шесть — молоко, остальные двенадцать — весь
ассортимент бренда (кефир, сыр, зернёный творог, четыре сметаны, два
йогурта, сливки). Слова «молоко» в них нет ни в названии, ни в бренде:
они попали в выдачу только потому, что совпал бренд, — и в списке ничем
не отличались от точных попаданий.

Тесты идут по чистым функциям и без сети: `_off_search` ходит наружу,
а проверять надо разбор, а не доступность чужого сервиса.
"""

import os
import sys
import tempfile
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_бренд.db")

import main            # noqa: E402


def запись(name, brand="", kcal=50.0, source="off", barcode="", quantity="",
           protein=0.0, fat=0.0, carbs=0.0):
    return {"name": name, "brand": brand, "barcode": barcode, "quantity": quantity,
            "calories": kcal, "protein": protein, "fat": fat, "carbs": carbs,
            "source": source}


# Живая выдача по «молоко простоквашино», сокращённая до сути: четыре молока,
# два «через перевод и косвенно» и четыре чужих продукта того же бренда
ВЫДАЧА_МОЛОКО = [
    запись("Молоко Простоквашино 2.5%", "Простоквашино", 54.4),
    запись("Молоко Простоквашино 1,5% пастеризованное", "Простоквашино", 45.0),
    запись("Молоко топлёное", "Простоквашино", 60.0),
    запись("вершки 10% Простоквашино", "Простоквашино", 118.0),
    запись("Простоквашино ГРЕЧЕСКИЙ ГУСТОЙ ЙОГУРТ", "Простоквашино", 63.0),
    запись("Сметана Простоквашино 15%", "Простоквашино", 160.0),
    запись("Кефир", "Простоквашино", 37.0),
]


# ── Брендовое слово запроса ───────────────────────────────────────────────────

def test_бренд_опознан_по_выдаче_а_не_по_словарю():
    """«простоквашино» не встречается ни в одном названии, очищенном
    от собственного бренда записи, зато стоит в поле бренда у всех."""
    слова = main._слова_запроса("молоко простоквашино")
    assert main._брендовые_слова(слова, ВЫДАЧА_МОЛОКО, {}) == {"простоквашино"}


def test_продуктовое_слово_брендовым_не_становится():
    """Отрицательный контроль: без него правило «всё подряд — бренд»
    прошло бы тест выше."""
    слова = main._слова_запроса("молоко простоквашино")
    assert "молоко" not in main._брендовые_слова(слова, ВЫДАЧА_МОЛОКО, {})


def test_единственное_слово_запроса_брендовым_не_объявляется_никогда():
    """ГЛАВНЫЙ ОГРАНИЧИТЕЛЬ. У Open Food Facts восемь записей из двадцати
    четырёх по запросу «творог» имеют поле `brands` буквально равное
    «творог» — мусор справочника. Объяви его брендом, и весь творог уехал
    бы в секцию «другие продукты бренда Творог», а основная выдача сказала
    бы «по названию ничего не нашлось» про запрос, по которому нашлось всё."""
    выдача = [запись("Творог", "Творог", 121.0), запись("Творог 9%", "Дмитровский", 160.0)]
    assert main._брендовые_слова(main._слова_запроса("творог"), выдача, {}) == set()


def test_все_слова_брендовыми_быть_не_могут():
    """Продукт должен быть назван хоть чем-то, иначе делить выдачу не на что."""
    выдача = [запись("Кефир", "Домик в деревне"), запись("Сыр", "Домик в деревне")]
    assert main._брендовые_слова(main._слова_запроса("домик деревне"), выдача, {}) == set()


def test_бренд_напечатанный_в_названии_не_спасает_запись():
    """«Сметана Простоквашино 15%» — в названии бренд И ЕСТЬ бренд, а не
    описание продукта. Без вычитания собственного бренда из названия эта
    запись считалась бы совпавшей по названию и осталась бы в основной
    выдаче по запросу про молоко."""
    r = запись("Сметана Простоквашино 15%", "Простоквашино")
    assert "простоквашино" not in main._имя_без_бренда(r)
    assert "сметана" in main._имя_без_бренда(r)


def test_короткий_бренд_из_названия_не_вычитается():
    """Тот же порог, что у `_бренд_из_названия`: бренд «Б» выел бы букву
    из середины каждого слова."""
    assert main._имя_без_бренда(запись("Бородинский хлеб", "Б")) == "бородинский хлеб"


# ── Разделение выдачи ─────────────────────────────────────────────────────────

def test_ассортимент_бренда_уходит_в_секцию():
    осн, доп, бренд = main._разделить_по_бренду("молоко простоквашино", ВЫДАЧА_МОЛОКО, {})
    assert [r["name"] for r in осн] == [
        "Молоко Простоквашино 2.5%",
        "Молоко Простоквашино 1,5% пастеризованное",
        "Молоко топлёное",
    ]
    assert len(доп) == 4
    assert бренд == "Простоквашино"


def test_без_брендового_слова_выдача_не_делится():
    """Цена правила названа вслух: не опознали бренд — секции нет, выдача
    ровно такая же, какой была. Это пропуск, а не ложь."""
    выдача = [запись("Сыр Ламбер", "Ламбер"), запись("Сыр Ламбер", "ВБД")]
    осн, доп, бренд = main._разделить_по_бренду("сыр ламбер", выдача, {})
    assert (len(осн), доп, бренд) == (2, [], "")


def test_свой_продукт_в_секцию_бренда_не_уезжает():
    """Человек завёл его сам — прятать его под сворачиваемый заголовок
    значило бы спрятать ровно то, что он записал своими руками."""
    выдача = ВЫДАЧА_МОЛОКО + [запись("Кефир домашний", "Простоквашино", source="custom")]
    осн, доп, _ = main._разделить_по_бренду("молоко простоквашино", выдача, {})
    assert "Кефир домашний" in [r["name"] for r in осн]
    assert "Кефир домашний" not in [r["name"] for r in доп]


def test_имя_бренда_берётся_с_упаковки_а_не_из_запроса():
    """Человек пишет строчными, на упаковке — как на упаковке."""
    _, _, бренд = main._разделить_по_бренду("молоко простоквашино", ВЫДАЧА_МОЛОКО, {})
    assert бренд == "Простоквашино"


# ── Порядок внутри основной выдачи ────────────────────────────────────────────

def test_название_весит_больше_бренда():
    """Было `(-совпало, -в_названии)`: бренд весил столько же, сколько
    название. Стало `(-в_названии, -совпало)`."""
    выдача = [запись("Сметана Простоквашино 15%", "Простоквашино"),
              запись("Молоко Простоквашино 2.5%", "Простоквашино")]
    порядок = [r["name"] for r in main._rank_food_results("молоко простоквашино", выдача, {})]
    assert порядок[0] == "Молоко Простоквашино 2.5%"


def test_единственное_слово_запроса_тоже_ранжируется():
    """Прежний ранний выход `len(слова) < 2` оставлял порядок OFF как есть,
    и по запросу «творог» вторым номером стояло «Сваля зернистый
    с клубникой» — совпал бренд, который так и называется, «Творог»."""
    выдача = [запись("Сваля зернистый с клубникой", "Творог"),
              запись("Творог 9%", "Дмитровский")]
    порядок = [r["name"] for r in main._rank_food_results("творог", выдача, {})]
    assert порядок[0] == "Творог 9%"


def test_порядок_внутри_ступени_сохраняется():
    """Релевантность самой OFF мы не переоцениваем — только поднимаем то,
    что подходит запросу целиком."""
    выдача = [запись("Творог А", "х"), запись("Творог Б", "х"), запись("Творог В", "х")]
    assert [r["name"] for r in main._rank_food_results("творог", выдача, {})] == [
        "Творог А", "Творог Б", "Творог В"]


# ── Дубли по тому, что видно ──────────────────────────────────────────────────

def test_свой_продукт_и_запись_справочника_не_двоятся():
    """ГЛАВНЫЙ СЛУЧАЙ. Живой прогон: аккаунт со своим продуктом «Молоко
    Простоквашино 2.5%» получал по этому запросу ДВЕ одинаковые карточки.
    Склейка по штрих-коду их не видела — она живёт внутри `_off_search`,
    куда свои продукты не попадают вовсе."""
    было = [запись("Молоко Простоквашино 2.5%", "Простоквашино", 54.4, source="custom"),
            запись("Молоко Простоквашино 2.5%", "Простоквашино", 54.4,
                   barcode="0099990001920", quantity="100g")]
    стало = main._склеить_видимые(было)
    assert len(стало) == 1
    assert стало[0]["source"] == "custom", "переживает первая — своя запись человека"
    assert стало[0]["barcode"] == "0099990001920", "недостающее добирается у близнеца"


def test_разная_калорийность_это_разные_продукты():
    """Отрицательный контроль: замер 2026-08-13 по шести записям «Молоко»
    с калорийностью 44/52/60/64/66.2 — это разные товары."""
    было = [запись("Молоко", kcal=44), запись("Молоко", kcal=52)]
    assert len(main._склеить_видимые(было)) == 2


@pytest.mark.parametrize("поле, значение", [
    ("protein", 3.0), ("fat", 5.0), ("carbs", 7.0)])
def test_бжу_тоже_считается_видимым(поле, значение):
    """Калорийность может совпасть у разного состава — БЖУ в карточке видно."""
    a, b = запись("Творог"), запись("Творог")
    b[поле] = значение
    assert len(main._склеить_видимые([a, b])) == 2


def test_объём_различает_только_записи_без_бренда():
    """Он и показывается только вместо бренда (`подписьПродукта`). У записей
    с брендом объём не виден, и склеивать их по нему нельзя — иначе на экране
    останется одна карточка из двух неразличимых."""
    без_бренда = [запись("Молоко", quantity="100g"), запись("Молоко", quantity="930 мл")]
    assert len(main._склеить_видимые(без_бренда)) == 2, "объём виден — записи разные"
    с_брендом = [запись("Молоко", "Лента", quantity="100g"),
                 запись("Молоко", "Лента", quantity="930 мл")]
    assert len(main._склеить_видимые(с_брендом)) == 1, "объём не виден — карточки одинаковы"


def test_порядок_выдачи_склейкой_не_меняется():
    было = [запись("А"), запись("Б"), запись("А"), запись("В")]
    assert [r["name"] for r in main._склеить_видимые(было)] == ["А", "Б", "В"]

"""Дубли по ведущему нулю штрих-кода и бренд, спрятанный в названии.

ЧТО БЫЛО. Замер 2026-08-15 по запросу «молоко простоквашино»: Open Food
Facts отдавал 19 записей, две из которых — ОДИН товар, пришедший кодами
`0099990001920` и `99990001920`. Во всём остальном записи побайтово
совпадали: то же название, те же 54.4 ккал, тот же «100g». Снаружи это
выглядело как два разных молока, различить которые было нечем.

И у обеих в подписи стояло «бренд не указан», хотя слово «Простоквашино»
стояло в самом названии продукта и в поле `brands` семнадцати соседних
записей той же выдачи. То есть строка утверждала неправду о данных,
которые лежали рядом.

Тесты идут по чистым функциям и без сети: `_off_search` ходит наружу,
а проверять надо разбор, а не доступность чужого сервиса.
"""

import os
import sys
import tempfile
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_дубли.db")

import main            # noqa: E402


def запись(name, brand="", barcode="", quantity="", kcal=50.0):
    return {"name": name, "brand": brand, "barcode": barcode,
            "quantity": quantity, "calories": kcal,
            "protein": 0.0, "fat": 0.0, "carbs": 0.0}


# ── Нормализация кода ────────────────────────────────────────────────────────

@pytest.mark.parametrize("код, ожидание", [
    ("0099990001920", "99990001920"),
    ("99990001920",   "99990001920"),
    ("4607053473544", "4607053473544"),
    ("  0012345 ",    "12345"),        # пробелы и мусор выбрасываются
    ("00000000",      ""),             # код из одних нулей — не код
    ("",              ""),
    (None,            ""),
])
def test_нормализация_кода(код, ожидание):
    assert main._нормкод(код) == ожидание


# ── Склейка дублей ───────────────────────────────────────────────────────────

def test_ведущий_ноль_не_делает_второй_товар():
    """Главный случай, ради которого всё и заведено."""
    было = [запись("Молоко Простоквашино 2.5%", barcode="0099990001920", quantity="100g"),
            запись("Молоко Простоквашино 2.5%", barcode="99990001920", quantity="100g")]
    стало = main._склеить_дубли(было)
    assert len(стало) == 1
    assert стало[0]["barcode"] == "0099990001920", "остаётся ПЕРВАЯ запись выдачи"


def test_склейка_добирает_недостающие_поля():
    """У близнеца бренд может оказаться заполнен, и терять его из-за того,
    что он пришёл вторым, незачем."""
    стало = main._склеить_дубли([
        запись("Молоко", barcode="0099990001920"),
        запись("Молоко", barcode="99990001920", brand="Простоквашино", quantity="930 мл"),
    ])
    assert len(стало) == 1
    assert стало[0]["brand"] == "Простоквашино"
    assert стало[0]["quantity"] == "930 мл"


def test_разные_коды_не_склеиваются():
    """Отрицательный контроль: без него склейка «всего подряд» прошла бы
    все тесты выше."""
    было = [запись("Молоко А", barcode="4607053473544"),
            запись("Молоко Б", barcode="4607053473537")]
    assert len(main._склеить_дубли(было)) == 2


def test_записи_без_кода_не_склеиваются_никогда():
    """Пустой нормализованный код одинаков у всех — склейка по нему
    схлопнула бы в одну строку разные продукты. Замер 2026-08-13: шесть
    записей «Молоко» с калорийностью 44/52/60/64/66.2 — разные товары."""
    было = [запись("Молоко", kcal=44), запись("Молоко", kcal=52), запись("Молоко", kcal=60)]
    assert len(main._склеить_дубли(было)) == 3


def test_порядок_выдачи_сохраняется():
    """Ранжирование ниже опирается на порядок Open Food Facts как
    на исходное приближение — переставлять записи склейке нельзя."""
    было = [запись("А", barcode="111"), запись("Б", barcode="0222"),
            запись("В", barcode="333"), запись("Б-дубль", barcode="222")]
    assert [r["name"] for r in main._склеить_дубли(было)] == ["А", "Б", "В"]


# ── Бренд из названия ────────────────────────────────────────────────────────

def test_бренд_достаётся_из_названия_по_соседям():
    """Бренд не выдумывается и не берётся из словаря: он уже пришёл
    в этой же выдаче, у семнадцати записей из девятнадцати."""
    было = [запись("Молоко Простоквашино 2.5%"),
            запись("Кефир", brand="Простоквашино")]
    стало = main._дописать_бренды(было)
    assert стало[0]["brand"] == "Простоквашино"


def test_чужой_бренд_не_приписывается():
    """Отрицательный контроль: в названии бренда нет — поле остаётся пустым,
    и подпись честно скажет «бренд не указан»."""
    было = [запись("Молоко"), запись("Кефир", brand="Простоквашино")]
    assert main._дописать_бренды(было)[0]["brand"] == ""


def test_короткий_бренд_не_ищется_в_названии():
    """У Open Food Facts хватает мусорных однобуквенных `brands`. Бренд «Б»,
    найденный внутри слова, приписал бы случайное имя половине выдачи."""
    было = [запись("Бородинский хлеб"), запись("Что-то", brand="Б")]
    assert main._дописать_бренды(было)[0]["brand"] == ""


def test_из_нескольких_совпавших_берётся_самый_длинный():
    """«Простоквашино» точнее, чем «Прост»: короткое имя — часть длинного,
    и выбрать надо то, что сказано в названии целиком."""
    было = [запись("Молоко Простоквашино 2.5%"),
            запись("х", brand="Прост"), запись("у", brand="Простоквашино")]
    assert main._дописать_бренды(было)[0]["brand"] == "Простоквашино"


def test_существующий_бренд_не_перетирается():
    было = [запись("Молоко Простоквашино 2.5%", brand="Danone"),
            запись("Кефир", brand="Простоквашино")]
    assert main._дописать_бренды(было)[0]["brand"] == "Danone"


def test_регистр_не_мешает():
    было = [запись("МОЛОКО ПРОСТОКВАШИНО 2.5%"), запись("Кефир", brand="простоквашино")]
    assert main._дописать_бренды(было)[0]["brand"] == "простоквашино"


# ── Подпись продукта в разметке ──────────────────────────────────────────────

def test_штрихкод_не_показывается_человеку():
    """Строка «бренд не указан · 100g · 0099990001920» — техническая
    в лицо человеку. Проверяется исходником: подпись собирается в шаблоне."""
    шаблон = (Path(__file__).resolve().parent.parent
              / "templates" / "nutrition.html").read_text(encoding="utf-8")
    начало = шаблон.index("function подписьПродукта")
    тело = шаблон[начало:шаблон.index("}", шаблон.index("return", начало))]
    assert "barcode" not in тело, "штрих-код снова уехал в подпись продукта"
    assert "quantity" in тело, "объём упаковки — единственная примета записи без бренда"

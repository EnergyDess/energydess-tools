def test_сбой_переводчика_не_отменяет_поиск(monkeypatch):
    """Требование пункта: молча отдать пустоту нельзя.

    Без ключа модели функция обязана вернуть причину, а не пустоту
    без объяснения."""
    monkeypatch.setattr(main, "OPENROUTER_API_KEY", "")

    class _Сессия:
        def query(self, *a, **k): return self
        def filter(self, *a, **k): return self
        def all(self): return []

    переводы, сбой = asyncio.run(main._переводы_слов(["пастила"], _Сессия()))
    assert переводы == {}
    assert сбой, "причина обязана быть названа"


def test_латинское_слово_к_модели_не_ходит(monkeypatch):
    """«uvelka» и «protein» уже латиница — переводить нечего.

    Если бы ходило, каждый англоязычный запрос стоил бы вызова модели."""
    monkeypatch.setattr(main, "OPENROUTER_API_KEY", "ключ-есть")

    def _взорваться(*a, **k):
        raise AssertionError("модель не должна вызываться для латиницы")

    monkeypatch.setattr(main.httpx, "AsyncClient", _взорваться)

    class _Сессия:
        def query(self, *a, **k): return self
        def filter(self, *a, **k): return self
        def all(self): return []

    переводы, сбой = asyncio.run(main._переводы_слов(["protein", "whey"], _Сессия()))
    assert сбой == ""
    assert переводы == {"protein": "", "whey": ""}

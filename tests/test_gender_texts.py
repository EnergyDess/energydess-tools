import pytest

import main


def _файл(путь):
    return io.open(путь, encoding="utf-8").read()


# ── ПРАВИЛО ПОЛА ОДНО НА ВЕСЬ ПРОЕКТ ─────────────────────────────────

def test_по_полу_даёт_три_состояния():
    assert main.по_полу("m", "Устал", "Устала", "Нет сил") == "Устал"
    assert main.по_полу("f", "Устал", "Устала", "Нет сил") == "Устала"
    assert main.по_полу(None, "Устал", "Устала", "Нет сил") == "Нет сил"


def test_незнакомый_пол_даёт_НЕЙТРАЛЬНОЕ_а_не_мужское():
    """Умолчание нейтральное: место, забывшее передать пол, скажет
    нейтрально, а не назовёт человека мужчиной."""
    for мусор in ("", "male", "x", 0, [], {}):
        assert main.по_полу(мусор, "Принял", "Приняла", "Списать") == "Списать"


def test_аптечный_глагол_выражен_ЧЕРЕЗ_общее_правило():
    """Второго экземпляра правила быть не должно (§6.0.7): слова
    у мест разные, а решение «чей род и что при неизвестном» — одно."""
    исходник = _файл("main.py")
    i = исходник.index("def _апт_подпись_приёма")
    j = исходник.index("\ndef ", i + 10)
    assert "по_полу(" in исходник[i:j]


# ── РОД СИСТЕМЫ О СЕБЕ: НЕЙТРАЛЬНО, ПОЛА НИ У КОГО НЕ СПРАШИВАЕМ ─────

# У каждой строки — файл и то, чем она была. Система не человек
# и рода не имеет; согласовывать её с полом владельца значило бы
# приписать ей род, которого нет.
СИСТЕМА_О_СЕБЕ = [
    ("main.py", "Записано в дневник за", "Записал в дневник за"),
    ("main.py", "Просмотрена не вся аптечка", "Смотрел не всю аптечку"),
    ("main.py", "Такой пачки в аптечке нет.", "не нашёл."),
    ("main.py", "Снова не получается понять", "Снова не понял"),
    ("main.py", "не получилось понять. Переспросите", "не понял. Переспросите"),
    ("templates/workout.html", "Заменено на сегодня", "Заменил на сегодня"),
    ("templates/workout.html", "Убрано «", "Убрал «"),
    ("templates/workout.html", ": возвращено ", ": вернул "),
    ("templates/medkit.html", "карточка не сохранена", "карточку не сохранил"),
]


def _строки_кода(путь):
    """Строки БЕЗ комментариев: слово в пояснении — рассказ о правке,
    а не текст, который увидит человек. Без этого сужения тест
    объявил бы находкой собственный комментарий о том, что родовая
    формулировка убрана."""
    из = []
    for с in _файл(путь).splitlines():
        л = с.strip()
        if л.startswith("#") or л.startswith("//") or л.startswith("*"):
            continue
        из.append(с)
    return chr(10).join(из)


@pytest.mark.parametrize("путь,стало,было", СИСТЕМА_О_СЕБЕ)
def test_система_о_себе_говорит_без_рода(путь, стало, было):
    т = _строки_кода(путь)
    assert стало in т, "нейтральной формулировки нет: %r" % стало
    assert было not in т, "родовая формулировка вернулась: %r" % было



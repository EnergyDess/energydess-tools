"""Язык сопроводительного письма и разбор зарплаты.

Почему тесты нужны именно здесь. Определение языка — единственное место,
где решение принимается ДО модели и вместо неё. Ошибка в любую сторону
дорогая и немая: пропустили требование — человек отправит русское письмо
туда, где просили английское, и не узнает почему; сработали лишний раз —
получит английское письмо на русскую вакансию, где про язык не было
ни слова. Ни то ни другое не видно по коду и не падает.

База не поднимается: DB_PATH уводится в tmp ДО импорта main (см. conftest.py).
"""

import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_язык.db")

import main  # noqa: E402


# ── Когда английский ДОЛЖЕН включиться ───────────────────────────────────────

ТРЕБУЮТ_АНГЛИЙСКИЙ = [
    "Обязанности: писать код. Сопроводительное письмо просим прислать на английском языке.",
    "Требования: Python.\nCover letter in English is required.\nУсловия: удалёнка.",
    "Please apply in English.",
    "Ждём отклик с сопроводительным письмом на английском.",
    "We expect a motivation letter in English along with your CV.",
]


def test_требование_на_английском_ловится():
    for текст in ТРЕБУЮТ_АНГЛИЙСКИЙ:
        язык, причина = main._letter_language(текст)
        assert язык == "en", текст
        # Причина обязана быть куском САМОЙ вакансии, а не нашей формулировкой:
        # человек должен опознать это место глазами
        assert причина, текст
        assert причина.lower() in " ".join(текст.lower().split())


# ── Когда английский включаться НЕ должен ────────────────────────────────────
#
# Главный класс ложных срабатываний — требования к самому кандидату.
# «English B2» стоит в половине IT-вакансий и о языке ПИСЬМА не говорит ничего.

НЕ_ТРЕБУЮТ = [
    "Требования: английский язык на уровне B2, опыт с Python от трёх лет.",
    "Мы международная команда, общение на английском языке ежедневное.",
    "Обязанности: писать документацию на английском языке для зарубежных клиентов.",
    "Ждём сопроводительное письмо — расскажите о себе.",
    "Fluent English is a must. Send us your CV.",
    "",
    "   ",
]


def test_упоминание_английского_само_по_себе_не_включает():
    for текст in НЕ_ТРЕБУЮТ:
        язык, причина = main._letter_language(текст)
        assert язык == "ru", текст
        assert причина is None, текст


def test_слова_в_разных_предложениях_не_считаются():
    """«Сопроводительное» и «на английском» рядом, но про разное.

    Ровно тот случай, ради которого признак сужен до одного предложения:
    оба слова в тексте есть, требования писать письмо по-английски — нет.
    """
    текст = ("Пришлите сопроводительное письмо. "
             "Работа предполагает ежедневную переписку на английском языке.")
    assert main._letter_language(текст) == ("ru", None)


def test_причина_обрезается_и_не_тащит_перенос_строк():
    длинное = ("Сопроводительное письмо на английском языке " + "и ещё много слов " * 20
               + "\nследующая строка")
    язык, причина = main._letter_language(длинное)
    assert язык == "en"
    assert len(причина) <= 141        # 140 плюс многоточие
    assert "\n" not in причина


# ── Зарплата: односторонняя вилка ────────────────────────────────────────────
#
# Замер 2026-08-12 на hh.ru/vacancy/135237472: в JSON только `to: 75000`,
# hh рисует «до 75 000 ₽», а наш разбор отдавал «75 000 ₽ на руки» —
# то есть утверждал точный оклад там, где его в вакансии не написано.

def test_вилка_с_одной_границей_сохраняет_от_и_до():
    только_до = main._format_compensation({"to": 75000, "currencyCode": "RUR", "gross": False})
    только_от = main._format_compensation({"from": 60000, "currencyCode": "RUR", "gross": False})
    assert только_до.startswith("до 75 000")
    assert только_от.startswith("от 60 000")


def test_обе_границы_и_их_совпадение():
    вилка = main._format_compensation({"from": 250000, "to": 300000, "currencyCode": "RUR"})
    точная = main._format_compensation({"from": 78000, "to": 78000, "currencyCode": "RUR",
                                        "gross": False})
    assert вилка.startswith("250 000–300 000")
    # Совпавшие границы — это точная сумма, «от» и «до» здесь были бы ложью
    assert точная.startswith("78 000")
    assert not точная.startswith(("от", "до"))


def test_зарплата_не_указана_остаётся_пустой():
    assert main._format_compensation({}) == ""
    assert main._format_compensation({"noCompensation": True}) == ""

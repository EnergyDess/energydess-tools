def test_счёт_по_аккаунту_не_ведёт_ни_к_какому_отказу():
    """Единственные последствия счёта по аккаунту — задержка и письмо.

    Проверяем не текст комментария, а сам код: с чем вообще сравнивается
    счётчик аккаунта. Разрешён ровно один порог — тот, после которого
    уходит письмо владельцу. Любой другой означает, что кто-то завёл
    блокировку по аккаунту, и её надо снимать, а не объяснять.
    """
    пороги = set()
    for узел in ast.walk(_функция_входа()):
        if isinstance(узел, ast.Compare):
            имена = {u.id for u in ast.walk(узел) if isinstance(u, ast.Name)}
            if "неудач_акк" in имена:
                пороги |= имена - {"неудач_акк", "неудач"}
    assert пороги <= {"NOTICE_AFTER"}, (
        f"счётчик по аккаунту сравнивается с {sorted(пороги)} — это порог "
        f"чего-то ещё, кроме письма владельцу. Блокировки аккаунта в этом "
        f"проекте нет ни в каком виде: любой, зная чужой адрес, запирал бы "
        f"этим чужой вход")



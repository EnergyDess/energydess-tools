def test_запас_адреса_проверяется_внутри_отправки():
    """Проверка, которую надо не забыть дописать в каждом эндпоинте, —
    это гарантия, что следующий эндпоинт её не получит. Та же причина,
    по которой гейт подтверждённой почты сделан одним middleware (§5.3)."""
    дерево = ast.parse(io.open(КОРЕНЬ / "main.py", encoding="utf-8").read())
    отправка = next(у for у in ast.walk(дерево)
                    if isinstance(у, ast.AsyncFunctionDef) and у.name == "send_email")
    # Именно СРАВНЕНИЕ, а не упоминание имени: имя есть и в тексте ошибки,
    # и первая версия этого теста проходила на коде, где порог подменён
    # на миллиард. Отрицательный контроль это и показал
    сравнения = [
        у for у in ast.walk(отправка)
        if isinstance(у, ast.Compare)
        and any(isinstance(о, ast.Name) and о.id == "MAIL_MAX_PER_ADDR"
                for о in у.comparators)
    ]
    assert сравнения, (
        "внутри send_email счётчик писем ни с чем не сравнивается с "
        "MAIL_MAX_PER_ADDR — заслон либо снят, либо вынесен в эндпоинты, "
        "и следующий эндпоинт с отправкой окажется без него")



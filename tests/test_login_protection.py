def test_пустое_поле_капчи_это_отказ():
    """Fail-closed. ЭТО ГЛАВНАЯ ИЗ ДВУХ ВЕТОК — прежний код на пустом поле
    просто шёл дальше, и записанное следствие («бот, не отправляющий поле
    капчи, проходит её насквозь») замерено живьём: POST без поля прошёл
    и с верным паролем дал вход.

    Проверяется, что ветка ВОЗВРАЩАЕТ ответ, а не печатает строку и идёт
    дальше: разница между отказом и записью в лог — ровно один `return`,
    и снять его можно не заметив.
    """
    for узел in ast.walk(_функция_входа()):
        if not isinstance(узел, ast.If):
            continue
        условие = ast.unparse(узел.test).replace(" ", "")
        if условие == "notturnstile_token":
            assert any(isinstance(в, ast.Return) for в in узел.body), (
                "ветка «поля капчи нет» ничего не возвращает — значит, "
                "запрос без токена идёт дальше и проверяет пароль")
            return
    pytest.fail("в обработчике входа не нашлось ветки «поля капчи нет вовсе» — "
                "либо fail-closed убран, либо тест смотрит не туда")



def test_состояние_истекает_ровно_на_пороге():
    """Порог берётся из КОНСТАНТЫ, а не вписан числом: вписанные руками
    30 разошлись бы с кодом молча.

    Дни отсчитываются от КОНЦА МЕСЯЦА срока, поэтому «сегодня» тут
    считается назад от него, а не наоборот, — иначе тест проверял бы
    ещё и арифметику календаря заодно с порогом.
    """
    поз = Поз(expires_ym="2026-09")
    конец = date(2026, 9, 30)
    порог = конец - timedelta(days=опр.ДНЕЙ_ДО_ИСТЕЧЕНИЯ)
    assert main._апт_состояние(поз, порог)["id"] == "soon"
    assert main._апт_состояние(поз, порог - timedelta(days=1))["id"] == "ok"
    assert main._апт_состояние(поз, конец)["id"] == "soon"
    assert main._апт_состояние(поз, конец + timedelta(days=1))["id"] == "expired"



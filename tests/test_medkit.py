#
# Проверяется СЕРВЕРНАЯ половина договора. Вторая половина — приведение
# ЗАПРОСА в браузере — проверяется браузером же, шагом
# `поиск-регистр-и-кириллица` в `check_medkit_ui.py`: из Python
# `toLowerCase` не вызвать, и делать вид, что вызвали, нельзя.


def test_нормаль_приводит_КИРИЛЛИЦУ_а_SQLite_нет():
    """Ловушка, ради которой функция названа именем.

    SQLite `lower()`, `upper()`, `LIKE` и `COLLATE NOCASE` работают
    только с латиницей. Перенос отбора в SQL выглядел бы одной строкой
    и молча выключил бы поиск по кириллице.
    """
    import sqlite3
    assert опр.нормаль("Нурофен") == "нурофен"
    assert опр.нормаль("АЦЦ 200") == "ацц 200"
    assert опр.нормаль("Магне B6") == "магне b6"

    с = sqlite3.connect(":memory:")
    # ОТРИЦАТЕЛЬНАЯ ПОЛОВИНА: без неё тест доказывал бы только то,
    # что `.lower()` работает, — а он и так работает
    assert с.execute("SELECT lower('Нурофен')").fetchone()[0] == "Нурофен"
    assert с.execute("SELECT 'Нурофен' LIKE '%нурофен%'").fetchone()[0] == 0
    assert с.execute("SELECT 'Нурофен' = 'нурофен' COLLATE NOCASE"
                     ).fetchone()[0] == 0
    # …а с латиницей SQLite справляется — то есть отказ ИЗБИРАТЕЛЬНЫЙ
    # и потому незаметный на тестовых данных из латиницы
    assert с.execute("SELECT 'Aspirin' LIKE '%aspirin%'").fetchone()[0] == 1
    с.close()



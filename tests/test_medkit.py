def test_заканчивается_срабатывает_на_ПЕРЕХОДЕ_а_не_каждый_раз():
    """«Остаток ушёл в красную зону» — событие, а не состояние.

    Человек, допивающий пачку, иначе получал бы одно и то же
    предложение на каждую таблетку, а список, который навязывается,
    перестают открывать."""
    поз = Поз(form="tablet", unit="tablet", qty_total=30, dose=1.0)
    # 11 из 30 — жёлтая зона; 10 из 30 — ровно треть, красная
    поз.qty_left = 10
    переход = main._апт_кончается(поз, было=11)
    assert переход.get("кончается") is True
    assert переход.get("кончается_почему")
    # Второе списание ИЗ красной зоны предложения не повторяет
    поз.qty_left = 9
    assert main._апт_кончается(поз, было=10) == {}
    # Остаток в жёлтой зоне не предлагает ничего
    поз.qty_left = 20
    assert main._апт_кончается(поз, было=21) == {}



def test_срок_укорачивают_ДВА_поля_человека_а_не_форма_выпуска():
    """ОТКАТ ПРАВИЛА 2026-08-26 (постановка A).

    Здесь стоял `test_порошок_в_банке_портится_а_в_пакетиках_нет`:
    признак «портится ли форма после вскрытия» решал, укорачивать ли
    срок, и у порошка ответ зависел ещё и от единицы. Владелец опроверг
    правило двумя упаковками с полки — у спрея Нозефрин срока после
    вскрытия в инструкции НЕТ ВОВСЕ (а система его проставила),
    у капсул Креона он НАПЕЧАТАН НА БАНКЕ (а поля не было).

    Теперь срок укорачивают ровно два числа, которые ввёл человек,
    и форма выпуска в этом не участвует НИКАК: у таблеток с
    заполненными полями срок считается так же, как у сиропа."""
    таблетки = Поз(form="tablet", unit="tablet", expires_ym="2028-05",
                   opened_on="2026-08-01", opened_days=30)
    сироп = Поз(form="syrup", unit="ml", expires_ym="2028-05",
                opened_on="2026-08-01", opened_days=30)
    assert main._апт_годен_до(таблетки) == date(2026, 8, 31)
    assert main._апт_годен_до(сироп) == date(2026, 8, 31)
    # ОДНОГО ПОЛЯ НЕ ХВАТАЕТ: дата без числа дней ничего не укорачивает,
    # и это не придирка — ровно так лежат данные у тех, кто проставил
    # дату, когда поле «Годен после вскрытия» ещё заполнялось само
    одна_дата = Поз(form="tablet", unit="tablet", expires_ym="2028-05",
                    opened_on="2026-08-01", opened_days=None)
    assert main._апт_годен_до(одна_дата) == date(2028, 5, 31)



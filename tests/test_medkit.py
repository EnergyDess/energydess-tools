class Поз:
    """Позиция без базы: проверяется чистая арифметика, а не ORM.

    ПОЛЯ БЕРУТСЯ ИЗ МОДЕЛИ, А НЕ ПЕРЕЧИСЛЯЮТСЯ. Здесь стоял перечень
    с оговоркой «заглушка обязана иметь ВСЕ поля модели», и оговорка
    своей работы не сделала: колонка `dosage_blocks` (BACKLOG №173)
    уронила три теста `AttributeError` — то есть перечень отстал
    в первый же заход после того, как его написали.

    Множество колонок открытое: новая появляется решением о СХЕМЕ,
    а не решением об этом списке, — значит нужен признак, а не перечень
    (§6.0.7). Недостающее поле теперь появляется само со значением
    `None`, а перечень ниже задаёт только осмысленные умолчания пробы.
    """

    _КОЛОНКИ = tuple(к.name for к in database.MedkitItem.__table__.columns)

    def __init__(self, **поля):
        по_умолчанию = {к: None for к in self._КОЛОНКИ}
        по_умолчанию.update(dict(form="tablet", unit="tablet", qty_left=10,
                                 qty_total=20, scale=None, dose=1,
                                 expires_ym="2027-03", opened_on=None,
                                 opened_days=None, name="Проба"))
        по_умолчанию.update(поля)
        for к, з in по_умолчанию.items():
            setattr(self, к, з)



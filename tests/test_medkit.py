def test_срок_разворачивается_в_ПОСЛЕДНИЙ_день_месяца():
    """«годен до 03.2027» означает «включая весь март».

    Возьми мы первое число — инструмент объявлял бы просроченным месяц
    годного лекарства, и человек выбросил бы пачку по нашей ошибке.
    """
    assert main._апт_конец_месяца("2027-03") == date(2027, 3, 31)
    assert main._апт_конец_месяца("2028-02") == date(2028, 2, 29)  # високосный
    assert main._апт_конец_месяца("2027-02") == date(2027, 2, 28)



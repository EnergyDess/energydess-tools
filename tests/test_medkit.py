class ФальшБаза:
    """Только то, что нужно разбору: проверка принадлежности места."""

    def __init__(self, свои_места=(), свои_категории=()):
        self.свои_места = set(свои_места)
        self.свои_категории = set(свои_категории)

    def query(self, модель):
        return self

    def filter(self, *условия):
        return self

    def first(self):
        return None


class Юзер:
    id = 1


def _разбор(**поля):
    тело = dict(name="Нурофен", form="tablet", unit="tablet",
                qty_left="18", qty_total="20", dose="1",
                expires_ym="2027-03")
    тело.update(поля)
    return main._апт_проверить(тело, ФальшБаза(), Юзер())


def test_разбор_принимает_обычную_позицию():
    поля, ош = _разбор()
    assert ош is None, ош
    assert поля["qty_left"] == 18 and поля["expires_ym"] == "2027-03"


@pytest.mark.parametrize("правка,кусок", [
    ({"name": ""}, "название"),
    ({"name": "   "}, "название"),
    ({"expires_ym": ""}, "срок годности"),
    ({"expires_ym": "не-дата"}, "2027-03"),
    ({"form": "выдуманная"}, "формы выпуска нет"),
    ({"unit": "ml"}, "не считается в этих единицах"),
    ({"qty_left": "30"}, "больше, чем было"),
    ({"qty_total": ""}, "было в упаковке"),
    ({"qty_left": "не число"}, "ожидалось число"),
    ({"leaflet_url": "javascript:alert(1)"}, "начинающийся с http"),
    ({"code_gtin": "1" * 20}, "не GTIN"),
    ({"opened_on": "24.08.2026"}, "2026-08-24"),
])
def test_отказ_называет_поле(правка, кусок):
    """Одна фраза «проверьте данные» на пятнадцать причин заставляла бы
    искать не там — тот же довод, что у семи текстов сбоя модели (§2.5)."""
    поля, ош = _разбор(**правка)
    assert поля is None, правка
    assert кусок.lower() in ош.lower(), (ош, правка)



def test_перечень_выпусков_без_повторов_и_в_прежнем_порядке():
    """У «Солодки сиропа» шесть страниц справочника описывают ОДИН
    выпуск, и отказ читался как «сироп 4 г/100 г» трижды подряд.

    Порядок при этом обязан сохраниться: выдача отсортирована
    по релевантности, и `set` поставил бы первым не то, что первым
    нашлось."""
    в = main._апт_выпуски_словами(
        ["сироп 4 г/100 г", "сироп 4 г/100 г", "таблетки 10 мг",
         "сироп 4 г/100 г", "капли 20 мг"], 3)
    assert в == "сироп 4 г/100 г; таблетки 10 мг; капли 20 мг"
    # Пустые строки в перечень не идут: «; ; таблетки» читается как сбой
    assert main._апт_выпуски_словами(["", None, "мазь 5%"], 4) == "мазь 5%"

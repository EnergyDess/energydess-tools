def test_дата_вскрытия_БЕЗ_числа_дней_метит_но_срока_не_двигает():
    """ВТОРОЙ ОТКАТ ТОГО ЖЕ ТЕСТА, 2026-08-26 (постановка A).

    Утверждение переворачивалось дважды, и оба раза — решением
    владельца, поэтому история записана целиком.

    БЫЛО (до 2026-08-25): дата вскрытия у таблеток красила карточку
    янтарём. Владелец заплатил за это ложной тревогой — поле
    показывалось у всех форм, он поставил дату наугад.

    СТАЛО (2026-08-25, моя правка): признак «портится ли форма»
    глушил и цвет, и срок. Владелец опроверг ЭТО двумя упаковками:
    у капсул Креона срок после вскрытия напечатан на банке, а поля
    у них не было вовсе.

    СЕЙЧАС: поля показываются у всех форм и не заполняются никем,
    кроме человека. Значит дата в базе — это его отметка, и молчать
    про неё нельзя: карточка помечается «вскрыт». А вот СРОК одна
    дата не двигает — для этого нужно и число дней, которое человек
    берёт с упаковки."""
    поз = Поз(expires_ym="2028-05", opened_on="2026-07-15", opened_days=None)
    assert main._апт_годен_до(поз) == date(2028, 5, 31)
    с = main._апт_состояние(поз, date(2026, 8, 24))
    assert с["id"] == "opened" and с["тон"] == "warn"



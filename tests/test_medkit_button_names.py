# -*- coding: utf-8 -*-
"""ИМЯ КНОПКИ И ТЕКСТЫ, КОТОРЫЕ НА НЕЁ ССЫЛАЮТСЯ, — ОДНО ИМЯ.

Заход 249, блок C. Кнопка в ряду действий карточки переименована
из «Приём» в «Инструкция»: она стояла прямо под «Принял 1 таблетку»,
обе назывались про приём и делали РАЗНОЕ — одна списывает упаковку,
вторая открывает текст.

ЗАЧЕМ ТЕСТ, А НЕ РАЗОВЫЙ ГРЕП. Переименование кнопки — правка
в одном файле, а ссылок на неё СЕМЬ и лежат они в промпте модели,
в ответах ассистента, в подсказке экрана, в сидированной реплике
и в тестах. Забудь мы одну — ассистент послал бы человека к кнопке,
которой на экране НЕТ, и ошибки при этом не было бы никакой: просто
совет в никуда (§6.0.1).

ЧТО ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ И ПОЧЕМУ. Имя ПОЛЯ «Схема приёма» остаётся
и находкой не является (правило задачи 248, B): в окне лежат ДВА
поля — схема приёма и показания к применению, — и «Инструкция» это
имя ОКНА. Признак ловит ссылку НА КНОПКУ, а не слово «приём».
"""
import io
import os

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ССЫЛКА НА КНОПКУ, А НЕ СЛОВО «ПРИЁМ». Список закрыт: каждая строка —
# форма, которой человек или модель называет ИМЕННО ЭТУ кнопку
СТАРЫЕ = (
    "кнопкой «Приём»",
    "кнопкой Приём",
    "Приём</button>",
    "'Схема приёма · '",
    # ДВЕ ФОРМЫ ДОБАВЛЕНЫ ЗАДАЧЕЙ 272 — обе жили на экране: кнопка
    # в ответе ассистента (`textContent = 'Приём'`) и подставленный
    # сервером текст «нажмите на карточке «Приём»». Список их не знал,
    # и тест был зелёным при двух ссылках на кнопку, которой нет
    "textContent = 'Приём'",
    "карточке «Приём»",
    "«Приём» на карточке",
)
ИМЯ = "Инструкция"

РАСШИРЕНИЯ = (".py", ".html", ".js")
МИМО = (".git", "node_modules", "__pycache__", "review_screenshots",
        "backups", "static/fonts")


# ПРОВЕРКА НЕ ЧИТАЕТ САМА СЕБЯ. Здесь перечислены запрещённые формы,
# и без исключения она находит СВОЙ ЖЕ список — тот случай, что уже
# был у `check_docs` (§6.0.7, «список исключений оживлял себя сам»).
СЕБЯ = os.path.basename(__file__)


def _файлы():
    for корень, папки, файлы in os.walk(КОРЕНЬ):
        отн = os.path.relpath(корень, КОРЕНЬ).replace("\\", "/")
        if any(ч in отн for ч in МИМО):
            continue
        for ф in файлы:
            if ф.endswith(РАСШИРЕНИЯ) and ф != СЕБЯ:
                yield os.path.join(корень, ф)


def test_старого_имени_кнопки_не_осталось():
    нашлось = []
    for п in _файлы():
        try:
            т = io.open(п, encoding="utf-8").read()
        except (OSError, UnicodeDecodeError):
            continue
        for i, с in enumerate(т.split("\n"), 1):
            for о in СТАРЫЕ:
                if о in с:
                    нашлось.append("%s:%d  %s"
                                   % (os.path.relpath(п, КОРЕНЬ), i,
                                      с.strip()[:70]))
    assert not нашлось, (
        "ссылка на прежнее имя кнопки осталась в %d месте(ах):\n%s"
        % (len(нашлось), "\n".join(нашлось)))


def test_кнопка_называется_инструкцией():
    """ОБРАТНАЯ ПОЛОВИНА: запрет старого имени сам по себе прошёл бы
    и на странице, где кнопки нет вовсе."""
    п = os.path.join(КОРЕНЬ, "templates", "_medkit_grid.html")
    т = io.open(п, encoding="utf-8").read()
    assert "%s</button>" % ИМЯ in т, "кнопки «%s» нет в разметке" % ИМЯ
    assert 'aria-label="%s:' % ИМЯ in т, "подпись для чтения с экрана"


def test_заголовок_окна_называет_окно_а_не_поле():
    """В окне ДВА поля — схема приёма и показания. Заголовок,
    названный одним из них, у́же содержимого."""
    п = os.path.join(КОРЕНЬ, "templates", "medkit.html")
    т = io.open(п, encoding="utf-8").read()
    assert "m.modal('apt-doses', '%s'" % ИМЯ in т, "заголовок окна"
    assert "'%s · ' + п.name" % ИМЯ in т, "заголовок с названием пачки"


def test_имя_поля_схема_приёма_НЕ_тронуто():
    """ОБРАТНЫЙ КОНТРОЛЬ правила 248 (B): переименование окна
    не имеет права переименовать ПОЛЕ."""
    п = os.path.join(КОРЕНЬ, "templates", "medkit.html")
    т = io.open(п, encoding="utf-8").read()
    # ДВА, А НЕ ТРИ: столько МЕСТ, где поле называется на экране, —
    # кнопка «Схема приёма» в ряду действий окна и текст «Схема
    # приёма для этой упаковки ещё не искалась». Третьим был
    # ЗАГОЛОВОК ОКНА, и он именем поля быть перестал (C2).
    assert т.count("Схема приёма") >= 2, (
        "имя поля «Схема приёма» встречается %d раз — меньше, чем мест, "
        "где поле называется" % т.count("Схема приёма"))

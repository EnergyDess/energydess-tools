import io
import re

import pytest

РАЗМЕТКА = "templates/medkit.html"
СЕРВЕР = "main.py"


def _текст(путь):
    return io.open(путь, encoding="utf-8").read()


# ── ПРОЗА — НЕ КОД (тот же класс, что чинила задача 99) ──────────
#
# Слово «аптечки» в русской фразе, за которым стоит скобка («проход
# аптечки (шаги …)»), от вызова `аптечки(...)` не отличается ничем.
# Тест краснел на КОММЕНТАРИИ, то есть находкой была проза.
#
# Снимаются все три вида комментариев, какие бывают в этом файле:
# Jinja, HTML и JS. Длина сохраняется — номера строк остаются целы.
_КОММЕНТАРИИ = [
    re.compile(r"\{#.*?#\}", re.S),      # Jinja
    re.compile(r"<!--.*?-->", re.S),     # HTML
    re.compile(r"/\*.*?\*/", re.S),      # JS блочный
    re.compile(r"//[^\n]*"),             # JS строчный
]


def _без_комментариев(текст):
    def пусто(м):
        return re.sub(r"[^\n]", " ", м.group(0))
    for р in _КОММЕНТАРИИ:
        текст = р.sub(пусто, текст)
    return текст


def test_вызов_несуществующей_функции_апт():
    s = _без_комментариев(_текст(РАЗМЕТКА))
    объявлены = set(re.findall(r"function\s+(апт[\wА-Яа-яЁё]*)\s*\(", s))
    # `window.апт… =` — тоже объявление
    объявлены |= set(re.findall(r"window\.(апт[\wА-Яа-яЁё]*)\s*=", s))
    зовут = set(re.findall(r"\b(апт[\wА-Яа-яЁё]*)\s*\(", s))
    нет = sorted(зовут - объявлены)
    assert not нет, "зовут функции, которых нет: %s" % ", ".join(нет)


def test_предложение_читает_только_отданные_ключи():
    """Ключи позиции, читаемые в `аптДозыПредложения`, обязаны быть
    среди тех, что кладёт `_апт_наружу`."""
    s = _текст(РАЗМЕТКА)
    i = s.index("function аптДозыПредложения")
    j = s.index("\nfunction ", i + 10)
    тело = s[i:j]
    читает = set(re.findall(r"п\['([^']+)'\]", тело))
    читает |= set(re.findall(r"\bп\.([A-Za-zА-Яа-яЁё_][\w]*)\b", тело))
    читает -= {"id"}

    m = _текст(СЕРВЕР)
    a = m.index("def _апт_наружу")
    b = m.index("\ndef ", a + 10)
    отдаёт = set(re.findall(r'^\s{8}"([^"]+)":', m[a:b], re.M))
    нет = sorted(читает - отдаёт)
    assert not нет, (
        "предложение читает ключи, которых сервер не отдаёт: %s"
        % ", ".join(нет))


@pytest.mark.parametrize("ключ", ["substance", "form",
                                  "вещество_подсказка_иначе",
                                  "форма_подсказка_иначе"])
def test_ключи_решения_на_месте(ключ):
    """ОБРАТНЫЙ: проверка, которой нечего искать, прошла бы и на пустом
    файле. Названные ключи обязаны читаться — именно они чинят A.4."""
    s = _текст(РАЗМЕТКА)
    i = s.index("function аптДозыПредложения")
    j = s.index("\nfunction ", i + 10)
    assert ключ in s[i:j], "ключ %s больше не читается" % ключ


def test_снятие_комментариев_не_ест_код():
    """ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ снятия прозы, ОБЕ половины.

    Проба, выбрасывающая всё подряд, прошла бы первую половину
    и не значила бы ничего: поэтому вторая требует, чтобы НАСТОЯЩИЙ
    вызов из кода уцелел.
    """
    проза = "{# проход аптечки (шаги «x») #}\n<!-- аптДругое() -->\n"
    код = "аптНастоящая();\n"
    чисто = _без_комментариев(проза + код)
    зовут = set(re.findall(r"\b(апт[\wА-Яа-яЁё]*)\s*\(", чисто))
    assert "аптечки" not in зовут, "проза Jinja принята за вызов"
    assert "аптДругое" not in зовут, "проза HTML принята за вызов"
    assert "аптНастоящая" in зовут, "снятие комментариев съело код"

import asyncio
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("DB_PATH", "test_medkit_query.db")

import main  # noqa: E402

ОБЕЩАНИЯ = re.compile(r"написаны выше|под его карточкой|дословно из справочника|"
                      r"у каждого средства", re.I)


def _поз(ид, имя, справ="", своё=""):
    return {"id": ид, "name": имя, "substance": "", "показания": справ,
            "своё_от_чего": своё, "остаток_строкой": "Таблетки · 10 из 20",
            "состояние": "ok", "форма_имя": "Таблетки", "form": "tablet",
            "состояние_подпись": "до 03.2028", "expires_ym": "2028-03",
            "место": "", "is_rx": False, "дозы": "", "своя_схема": "",
            "категории": [], "подпись_приёма": "Принял 1 таблетку",
            "unit": "tablet", "dose": 1}


ПАЧКИ = [
    _поз(1, "Нурофен", справ="Головная боль, зубная боль."),
    _поз(2, "Супрастин", своё="Аллергический ринит."),
    _поз(3, "Лазолван", справ="Кашель с мокротой.", своё="От кашля."),
    _поз(4, "Мирамистин"),
]


def test_главный_текст_не_обещает_источника_и_наличия():
    assert not ОБЕЩАНИЯ.search(main.АПТ_ВЫБОР_ГЛАВНОЕ)
    assert "выше" not in main.АПТ_ВЫБОР_ГЛАВНОЕ


def test_без_оговорок_и_без_цифр():
    тексты = [main.АПТ_ВЫБОР_ГЛАВНОЕ, main.АПТ_ВЫБОР_ПОКАЗАНИЯ_ШАПКА,
              main.АПТ_ВЫБОР_ПОКАЗАНИЙ_НЕТ] + list(main.АПТ_ВЫБОР_ОТКУДА.values())
    for т in тексты:
        assert not re.search(r"\d", т), т
        assert not re.search(r"обычно|как правило|лучше уточн", т, re.I), т
    assert main._апт_след_дозы(тексты) == []


def _строки(ид_откуда):
    return [{"id": ид, "показание_откуда": откуда} for ид, откуда in ид_откуда]


def test_пункт_по_факту_каждой_карточки():
    по_id = {п["id"]: п for п in ПАЧКИ}
    шапка, пункты, счёт = main._апт_выбор_показания(
        _строки([(1, "справочник"), (2, "вкладыш"), (3, "справочник"), (4, "")]),
        по_id)
    assert шапка == main.АПТ_ВЫБОР_ПОКАЗАНИЯ_ШАПКА
    assert пункты == ["«Нурофен» — выдержка из справочника",
                      "«Супрастин» — ваша запись с вкладыша",
                      "«Лазолван» — выдержка из справочника и ваша запись с вкладыша",
                      "«Мирамистин» — показаний на карточке нет"]
    assert счёт == {"справочник": 1, "вкладыш": 1, "оба": 1, "нет": 1}


def test_ни_у_одной_нет_показаний_ни_шапки_ни_пунктов():
    """ПОДЛОГ задачи 282: карточка без показаний — обещания нет."""
    по_id = {4: ПАЧКИ[3]}
    assert main._апт_выбор_показания(_строки([(4, "")]), по_id)[:2] == ("", [])


def _ответ_выбора(monkeypatch, ids):
    async def модель(промпт, очищать=True, **прочее):
        return {"тип": "выбор", "подходят": ids, "нет": ""}, "", 200
    monkeypatch.setattr(main, "_апт_спросить_модель", модель)
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (ПАЧКИ, {}))
    monkeypatch.setattr(main, "_апт_чат_реплики", lambda db, user: [])

    class Юзер:
        id = 1
        timezone = "Europe/Moscow"
    return asyncio.run(main._апт_ответ_на_запрос("что из этого выбрать",
                                                 None, Юзер()))


def _видимое(тело):
    return "\n".join([тело["вступление"], тело["нет"], тело["показания_шапка"]]
                     + тело["показания_карточек"])


def test_ответ_выбора_без_показаний_не_обещает_их(monkeypatch):
    тело = _ответ_выбора(monkeypatch, [4])
    assert тело["тип"] == "выбор"
    assert тело["показания_карточек"] == [] and тело["показания_шапка"] == ""
    assert main.АПТ_ВЫБОР_ПОКАЗАНИЙ_НЕТ in тело["нет"]
    assert not ОБЕЩАНИЯ.search(_видимое(тело))


def test_обратный_старый_текст_обещание_возвращает(monkeypatch):
    """Возврат прежней фразы — обещание снова на экране: тест различает."""
    monkeypatch.setattr(main, "АПТ_ВЫБОР_ГЛАВНОЕ",
                        "Показания к применению у каждого средства написаны "
                        "выше, под его карточкой, дословно из справочника.")
    тело = _ответ_выбора(monkeypatch, [4])
    assert ОБЕЩАНИЯ.search(_видимое(тело))


def test_название_с_дозой_не_превращает_ответ_в_отказ(monkeypatch):
    """Пункты — данные карточки: «… 200 мг» в названии заслон не видит."""
    пачка = _поз(9, "Проверочный препарат 200 мг", справ="Боль.")
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: ([пачка], {}))

    async def модель(промпт, очищать=True, **прочее):
        return {"тип": "выбор", "подходят": [9], "нет": ""}, "", 200
    monkeypatch.setattr(main, "_апт_спросить_модель", модель)
    monkeypatch.setattr(main, "_апт_чат_реплики", lambda db, user: [])

    class Юзер:
        id = 1
        timezone = "Europe/Moscow"
    тело = asyncio.run(main._апт_ответ_на_запрос("что из этого выбрать",
                                                  None, Юзер()))
    assert тело["показания_карточек"], тело
    assert "показания_карточек" in main.АПТ_ДАННЫЕ_КАРТОЧКИ
    assert main._апт_заслон_выхода(тело)["вступление"] == тело["вступление"]



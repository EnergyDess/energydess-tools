def test_встречные_ссылки_описывают_все_колонки_на_users():
    """Колонка, указывающая на пользователя НЕ через `user_id`, обязана
    быть либо в `ВСТРЕЧНЫЕ_ССЫЛКИ`, либо не существовать.

    Перечень тут законен (§6.0.7) — множество конечно и объявляется
    решением о схеме, — но перечень без сторожа молча отстаёт. Признак
    механический: колонка кончается на `_user_id` и не равна `user_id`.
    """
    # ИСКЛЮЧЕНИЕ ОДНО И НАЗВАНО: `encrypted_zepp_user_id` — это номер
    # человека в ЧУЖОМ сервисе (Zepp Life), к нашей таблице `users`
    # он отношения не имеет вовсе. Перечнем, а не признаком: отличить
    # «наш пользователь» от «чужой идентификатор» по имени колонки
    # нельзя, а маска «всё, где есть zepp» завтра проглотила бы
    # настоящую ссылку
    ЧУЖИЕ = {("scale_connections", "encrypted_zepp_user_id")}
    названо = {(т, к) for т, к in database.ВСТРЕЧНЫЕ_ССЫЛКИ}
    найдено = set()
    for имя, т in database.Base.metadata.tables.items():
        for к in т.columns:
            if к.name.endswith("_user_id") and к.name != "user_id":
                найдено.add((имя, к.name))
    assert (найдено - ЧУЖИЕ) == названо, (найдено, названо)



def test_в_текстах_ленты_нет_глаголов_с_родом():
    """ПОЛА УЧАСТНИКА МЫ НЕ ЗНАЕМ, и угадывать его нельзя.

    Живой ответ ассистента на проде начинался словом «Посмотрела» —
    единственным местом во всём инструменте, где выбирался род. Лента
    пишет о ДРУГОМ человеке в каждой строке, то есть попала бы в ту же
    ловушку двенадцать раз. Признак — окончание прошедшего времени
    русского глагола у слова после подстановки имени.
    """
    родовые = ("завёл", "завела", "удалил", "удалила", "списал", "списала",
               "поправил", "поправила", "добавил", "добавила",
               "отметил", "отметила", "вышел", "вышла",
               "присоединился", "присоединилась")
    for вид, шаблон in main.АПТ_СОБЫТИЯ.items():
        низ = шаблон.lower()
        for сл in родовые:
            assert сл not in низ, (вид, сл)



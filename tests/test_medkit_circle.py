# ── ПРАВИЛО КРУГА ────────────────────────────────────────────────────

class _Ч:
    def __init__(с, id_):
        с.id = id_


def _чистая_сессия():
    database.init_db()
    db = database.SessionLocal()
    for м in (database.MedkitEvent, database.MedkitMember,
              database.MedkitInvite, database.MedkitBlock,
              database.MedkitCircle):
        db.query(м).delete(synchronize_session=False)
    db.commit()
    return db


def test_без_круга_видно_только_себя():
    """F.4 держится не оговоркой, а этим равенством: у человека без
    круга множество ровно `[user.id]`, то есть прежнее условие."""
    db = _чистая_сессия()
    try:
        круг, ids = main._апт_круг(db, _Ч(777))
        assert круг is None and ids == [777]
    finally:
        db.close()


def test_круг_из_одного_человека_считается_личной_аптечкой():
    """Круг, из которого ушёл предпоследний, — это личная аптечка,
    а не «общая с одним участником». Иначе у оставшегося навсегда
    осталась бы панель участников и лента собственных действий."""
    db = _чистая_сессия()
    try:
        к = database.MedkitCircle(user_id=777)
        db.add(к)
        db.flush()
        db.add(database.MedkitMember(circle_id=к.id, user_id=777))
        db.commit()
        круг, ids = main._апт_круг(db, _Ч(777))
        assert круг is None and ids == [777]
    finally:
        db.close()


def test_строка_участия_без_круга_не_роняет():
    """Сирота (круг удалён, участие осталось) обязана читаться как
    личная аптечка, а не как исключение: между удалением и уборкой
    проходит транзакция."""
    db = _чистая_сессия()
    try:
        db.add(database.MedkitMember(circle_id=999999, user_id=777))
        db.commit()
        круг, ids = main._апт_круг(db, _Ч(777))
        assert круг is None and ids == [777]
    finally:
        db.close()


def test_в_круге_видно_обоих():
    db = _чистая_сессия()
    try:
        к = database.MedkitCircle(user_id=777)
        db.add(к)
        db.flush()
        db.add(database.MedkitMember(circle_id=к.id, user_id=777))
        db.add(database.MedkitMember(circle_id=к.id, user_id=888))
        db.commit()
        круг, ids = main._апт_круг(db, _Ч(888))
        assert круг is not None
        assert sorted(ids) == [777, 888]
    finally:
        db.close()


def test_событие_в_личной_аптечке_не_пишется():
    """Проверка стоит ВНУТРИ `_апт_событие`, а не в десяти местах
    вызова: перечень мест, где надо не забыть спросить, — это перечень,
    из которого однажды выпадет одно."""
    db = _чистая_сессия()
    try:
        было = db.query(database.MedkitEvent).count()
        assert main._апт_событие(db, None, _Ч(777), "add", "Нурофен") is None
        assert db.query(database.MedkitEvent).count() == было
    finally:
        db.close()


def test_незнакомый_вид_события_не_пишется_молча(capsys):
    db = _чистая_сессия()
    try:
        к = database.MedkitCircle(user_id=777)
        db.add(к)
        db.commit()
        assert main._апт_событие(db, к, _Ч(777), "неведомое") is None
        assert "неизвестный вид" in capsys.readouterr().out
    finally:
        db.close()



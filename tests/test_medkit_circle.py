def test_круг_из_одного_человека_считается_личной_аптечкой():
    """Круг, из которого ушёл предпоследний, — это личная аптечка,
    а не «общая с одним участником». Иначе у оставшегося навсегда
    осталась бы панель участников и лента собственных действий."""
    db = _чистая_сессия()
    try:
        к = database.MedkitCircle(user_id=777)
        db.add(к)
        db.flush()
        db.add(database.MedkitMember(circle_id=к.id, user_id=777))
        db.commit()
        круг, ids = main._апт_круг(db, _Ч(777))
        assert круг is None and ids == [777]
    finally:
        db.close()



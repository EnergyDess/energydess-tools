def test_путь_к_файлу_считается_от_ВЛАДЕЛЬЦА_записи():
    """Пока право было «только своё», разницы не было. С приходом круга
    путь от спрашивающего давал бы 404 на КАЖДОЕ чужое фото ПРИ
    ПРОЙДЕННОЙ проверке права — немой отказ ровно там, где его чинили.

    Проверяется по исходнику обработчика: аргументом `_media_path`
    обязан идти `запись.user_id`.
    """
    import ast
    import inspect
    исходник = inspect.getsource(main.get_media)
    дерево = ast.parse(инден(исходник))
    аргументы = []
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Call)
                and getattr(узел.func, "id", "") == "_media_path"):
            аргументы = [ast.unparse(а) for а in узел.args]
    assert аргументы, "вызова _media_path в обработчике нет вовсе"
    assert аргументы[1] == "запись.user_id", аргументы


def инден(текст):
    """Снять общий отступ — `inspect.getsource` отдаёт функцию как есть,
    а `ast.parse` требует нулевого уровня."""
    import textwrap
    return textwrap.dedent(текст)



def test_пачка_в_вопросе_находится_по_словам_и_длиннейшая_побеждает():
    def ids(вопрос):
        return [п["id"] for п in main._апт_позиции_в_вопросе(вопрос, ПАЧКИ)]
    assert ids("сколько Нурофена можно выпить") == [1]
    assert ids("можно ли дать ребёнку Нурофен для детей") == [2]
    assert ids("максимум Препарата А в сутки") == [3]
    assert ids("сколько капель Альбуцида") == []


def test_отказ_о_дозе_без_кнопки_списания_и_без_модели(monkeypatch):
    """Кнопка «Принял 1 таблетку» под вопросом «сколько можно»
    читается как ответ на него. Живой замер «до»: такая кнопка стояла
    под 11 ответами о дозе из 13."""
    вызвана = []

    async def модель(*а, **к):
        вызвана.append(1)
        return {}, "", 200
    monkeypatch.setattr(main, "_апт_спросить_модель", модель)
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (ПАЧКИ, {}))
    тело = main._апт_ответ_о_дозе("сколько Нурофена можно выпить за день",
                                  "доза", None, None)
    assert вызвана == []
    assert тело["вид"] == "запрос" and тело["тип"] == "доза"
    assert [с["id"] for с in тело["нашлось"]] == [1]
    assert all(с["приём_подпись"] == "" for с in тело["нашлось"])
    assert main._апт_дозы_в_видимом(тело) == []
    assert main._апт_заслон_выхода(тело) is тело



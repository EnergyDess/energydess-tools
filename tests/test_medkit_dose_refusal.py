ОГОВОРКИ = re.compile(r"(обычно|как правило|лучше|скорее всего|"
                      r"в большинстве|как говорится)", re.I)


def test_отказ_не_называет_ни_одного_числа_и_без_оговорок():
    """Все поводы на все три случая пачки. Цифры запрещены ВОВСЕ,
    а не только «число с единицей»: отказ со «хотя бы 1 таблеткой»
    был бы тем, от чего он защищает."""
    for повод in ("доза", "ребёнок", "беременность", "алкоголь"):
        for названо, схема in ((False, False), (True, True), (True, False)):
            т = main._апт_текст_отказа_о_дозе(повод, названо, схема)
            assert not re.search(r"\d", т), (повод, т)
            assert main._апт_след_дозы([т]) == [], (повод, т)
            assert not ОГОВОРКИ.search(т), (повод, т)
            assert "не отвечаю" in т
            if повод != "доза":
                assert "врач" in т, (повод, т)



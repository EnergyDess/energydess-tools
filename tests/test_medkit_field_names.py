"""ДВА ПОЛЯ — ДВА ИМЕНИ, ОДИНАКОВЫЕ ВЕЗДЕ (BACKLOG №248, блок B).

Решение владельца: поле называется ПОЛНЫМ ИМЕНЕМ, и имя у него одно
на весь проект — «Схема приёма» и «Показания к применению». Кнопки
шторки, метки списка долгов, заголовки блоков, подписи форм и тексты
ассистента говорят одними и теми же словами.

ПОЧЕМУ ЭТО СТОРОЖИТ МАШИНА, А НЕ ВНИМАТЕЛЬНОСТЬ. Синоним заводится
не злым умыслом, а по ходу: заход 245 назвал поле «от чего», заход 246
написал «нет „от чего"» в списке долгов, заход 247 сделал кнопку
«Вписать „от чего"» — и каждый раз это выглядело осмысленным рядом
с соседним текстом того же файла. Увидеть расхождение можно, только
сложив все места вместе, а этого не делает никто (§6.0.7).

ГРАНИЦА НАЗВАНА. Тест смотрит на ВИДИМЫЕ строки шаблона аптечки
(комментарии снимаются разбором, а не грепом) и на перечень видов
долга. Он НЕ смотрит:

  · промпты — там «ОТ ЧЕГО» стоит именем колонки в списке для модели,
    и переименование его сломало бы разбор ответа;
  · слово «выдержка» — оно про ПРОИСХОЖДЕНИЕ текста («дословная
    выдержка из инструкции»), а не имя поля;
  · прозу комментариев и docstring — это рассказ, а не экран.
"""
import io
import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)

import main  # noqa: E402

# ЗАПРЕЩЁННЫЕ СИНОНИМЫ — только те, что человек видит на экране.
# «от чего» — оборот речи вместо имени поля; «способ приёма» —
# второе имя схемы, оставшееся от заголовка окна.
СИНОНИМЫ = ("от чего", "способ приём")

ЭТАЛОН_СХЕМА = "Схема приёма"
ЭТАЛОН_ПОКАЗАНИЯ = "Показания к применению"


def _видимое(путь):
    """Текст шаблона без комментариев. Номера строк сохраняются."""
    т = io.open(путь, encoding="utf-8").read()
    пусто = lambda m: re.sub(r"[^\n]", " ", m.group(0))     # noqa: E731
    т = re.sub(r"/\*.*?\*/", пусто, т, flags=re.S)
    return re.sub(r"<!--.*?-->", пусто, т, flags=re.S)


def test_в_видимых_строках_аптечки_синонимов_НЕТ():
    текст = _видимое(os.path.join(КОРЕНЬ, "templates", "medkit.html"))
    находки = [(н, с.strip()[:90])
               for н, с in enumerate(текст.split("\n"), 1)
               if any(x in с.lower() for x in СИНОНИМЫ)]
    assert not находки, (
        "поле названо синонимом на экране: %s" % (находки,))


def test_список_долгов_называет_поля_полными_именами():
    подписи = {и: п for и, п, _к in main.АПТ_ВИДЫ_ДОЛГА}
    assert подписи["схема"] == "нет схемы приёма", подписи
    assert подписи["показания"] == "нет показаний к применению", подписи


def test_эталонные_имена_стоят_в_разметке():
    """ОБРАТНАЯ ПОЛОВИНА: запрет синонима сам по себе проходит и на
    странице, где о полях не сказано вовсе."""
    текст = _видимое(os.path.join(КОРЕНЬ, "templates", "medkit.html"))
    for имя in (ЭТАЛОН_СХЕМА, ЭТАЛОН_ПОКАЗАНИЯ):
        assert текст.count(имя) >= 3, (
            "имя %r встречается %d раз — меньше, чем мест, где поле "
            "называется" % (имя, текст.count(имя)))


def test_глагола_в_подписи_кнопки_поля_нет():
    """Решение владельца: «вписать» и «изменить» из имени кнопки убраны."""
    текст = _видимое(os.path.join(КОРЕНЬ, "templates", "medkit.html"))
    for плохо in ("Вписать схему", "Изменить схему",
                  "Вписать «от чего»", "Изменить «от чего»"):
        assert плохо not in текст, "в подписи кнопки вернулся глагол: %r" % плохо

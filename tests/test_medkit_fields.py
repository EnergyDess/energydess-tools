def _имена(вопрос, *имена):
    поз = [{"id": i, "name": н} for i, н in enumerate(имена, 1)]
    названы, спорные = main._апт_названия_в_вопросе(вопрос, поз)
    return [п["name"] for п in названы], [п["name"] for п in спорные]


def test_заменённое_окончание_опознаётся():
    assert _имена("место хранения Смекты", "Смекта", "Тизин") == (["Смекта"], [])
    assert _имена("срок годности Теймуровой пасты", "Теймурова паста") == (
        ["Теймурова паста"], [])
    assert _имена("сколько осталось Настойки пустырника",
                  "Настойка пустырника") == (["Настойка пустырника"], [])
    # дописанное окончание — как было
    assert _имена("место хранения Регидрона", "Регидрон") == (["Регидрон"], [])


def test_выдуманное_имя_в_падеже_не_опознаётся():
    """Главный контроль блока B: огрубление — не «похоже на»."""
    for вопрос in ("место хранения Смектины", "где лежит Смекто",
                   "срок годности Смяктой", "сколько осталось Смек",
                   "где лежит Магна"):
        assert _имена(вопрос, "Смекта", "Магне") == ([], []), вопрос


def test_дописанное_окончание_только_из_закрытого_списка():
    """Задача 291: «Смектан» — не «Смекта», «Нурофенк» — не «Нурофен»."""
    for вопрос in ("где лежит Смектан", "где лежит Нурофенк",
                   "сколько осталось Нурофенин", "где лежит Регидронл",
                   "срок годности Настойкан пустырника", "где лежит Мазьк"):
        assert _имена(вопрос, "Смекта", "Нурофен", "Регидрон",
                      "Настойка пустырника", "Мазь") == ([], []), вопрос


def test_настоящие_дописанные_окончания_опознаются():
    for вопрос, имя in (("место хранения Регидрона", "Регидрон"),
                        ("где лежит Нурофеном", "Нурофен"),
                        ("сколько Нурофенов", "Нурофен"),
                        ("срок годности Нурофене", "Нурофен"),
                        ("где лежит мазью", "Мазь"),
                        ("всем Смектам", "Смекта"),
                        ("где лежат Стрепсилсы", "Стрепсилс")):
        assert _имена(вопрос, имя) == ([имя], []), вопрос
    # правописание после заднеязычной: «и», а не «ы»
    assert _имена("где лежат Бисаки", "Бисак") == (["Бисак"], [])
    assert _имена("где лежат Бисакы", "Бисак") == ([], [])


def test_два_названия_неразличимы_после_огрубления_спрашиваем():
    """B.2: «Ксилены» — это и «Ксилена», и «Ксилен»; выбирать нельзя."""
    assert _имена("где лежат Ксилены", "Ксилена", "Ксилен") == (
        [], ["Ксилена", "Ксилен"])
    # одинаковое название у двух пачек — не спор
    поз = [{"id": 1, "name": "Смекта"}, {"id": 2, "name": "Смекта"}]
    названы, спорные = main._апт_названия_в_вопросе("срок годности Смекты", поз)
    assert len(названы) == 2 and спорные == []


def test_спорное_название_даёт_просьбу_уточнить(monkeypatch):
    поз = [_поз(id=1, name="Ксилена"), _поз(id=2, name="Ксилен")]
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (поз, КАТ))
    for маршрут, вопрос in ((main._апт_маршрут_места, "где лежат Ксилены"),
                            (main._апт_маршрут_остатка, "сколько осталось Ксилены"),
                            (main._апт_маршрут_поля, "срок годности Ксилены")):
        тело = маршрут(вопрос, None, None)
        assert тело["тип"] == "уточнить", вопрос
        assert all(с["действия"] is False and с["приём_подпись"] == ""
                   for с in тело["нашлось"])
        assert not re.search(r"\d", тело["вступление"])

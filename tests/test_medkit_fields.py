def _ответ(вопрос, monkeypatch):
    вызвана = []

    async def модель(*а, **к):
        вызвана.append(1)
        return {}, "", 200
    monkeypatch.setattr(main, "_апт_спросить_модель", модель)
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (ПАЧКИ, КАТ))
    тело = main._апт_маршрут_поля(вопрос, None, None)
    assert вызвана == []
    return тело



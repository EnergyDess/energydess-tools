def _пачка(**поля):
    """Минимальная сводка позиции для группировки."""
    основа = {"id": 1, "name": "X", "substance": "s", "form": "tablet",
              "показания": "", "показания_блоки": [],
              "показания_спрашивали": False,
              "своё_от_чего": "", "своё_от_чего_дата": "",
              # ПОЛЯ, БЕЗ КОТОРЫХ ГРУППИРОВКА НЕ СОБИРАЕТСЯ. Перечень
              # тут не догадка: `_апт_сгруппировать` берёт их прямым
              # обращением, и падение по ключу — честный сигнал, что
              # заглушка отстала от сводки (тот же урок, что у `Поз`
              # в `tests/test_medkit.py`)
              "годен_до": "2030-01", "opened_on": "", "photo": "",
              "дозы": "", "своя_схема": "", "unit": "pcs",
              "qty_total": 20, "состояние": "ok",
              "qty_left": 10, "искать": "x"}
    основа.update(поля)
    return основа


def test_показания_объявлены_заимствуемыми():
    ведущие = {в for в, _группа in main.ЗАИМСТВУЕМЫЕ_ПОЛЯ}
    assert "показания" in ведущие
    assert "своё_от_чего" in ведущие


def test_показания_сверяются_перед_заимствованием():
    """Заслон E.2 объявлен ИМЕНЕМ, а не условием на месте: правило
    «эти поля берём только при совпадении» — одно, и место применения
    у него одно."""
    assert "показания" in main.СВЕРЯТЬ_ПРИ_ЗАИМСТВОВАНИИ
    assert "своё_от_чего" in main.СВЕРЯТЬ_ПРИ_ЗАИМСТВОВАНИИ


def test_форма_и_вещество_в_ключе_группы():
    """E.3: пачки группы совпадают по названию, веществу и форме —
    то есть заимствовать текст у соседа безопасно ровно потому, что
    препарат у них ОДИН. Перестань это быть верным — блок E теряет
    основание, и знать об этом надо сразу."""
    а = _пачка(name="Х", substance="в", form="tablet")
    б = _пачка(name="Х", substance="в", form="syrup")
    assert main._апт_ключ_группы(а) != main._апт_ключ_группы(б)
    в = _пачка(name="Х", substance="другое", form="tablet")
    assert main._апт_ключ_группы(а) != main._апт_ключ_группы(в)


def test_свой_текст_не_перезаписывается_чужим():
    """E.1: заимствование заполняет ПУСТОЕ место, а не подменяет."""
    пачки = [_пачка(id=1, своё_от_чего="моё"),
             _пачка(id=2, своё_от_чего="соседское")]
    сводка = main._апт_сгруппировать(пачки)[0]
    assert сводка["своё_от_чего"] == "моё"


def test_расхождение_текстов_НЕ_заимствуется():
    """E.2: тексты разошлись — не берём ничего. Выбрать «правильный»
    нечем: оба переписаны человеком с РАЗНЫХ вкладышей."""
    пачки = [_пачка(id=1, своё_от_чего=""),
             _пачка(id=2, своё_от_чего="первый"),
             _пачка(id=3, своё_от_чего="второй")]
    сводка = main._апт_сгруппировать(пачки)[0]
    assert сводка["своё_от_чего"] == ""


def test_ОБРАТНЫЙ_совпавшие_тексты_заимствуются():
    """Без обратного случая «заслон ловит всё» неотличимо
    от «заимствования нет вовсе» (§6.0.3)."""

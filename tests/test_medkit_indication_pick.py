# -*- coding: utf-8 -*-
"""ОТБОР ПО ТЕКСТУ ПОКАЗАНИЙ (BACKLOG №244, D.1, D.2, D.7).

Владелец спросил «болит голова в висках» и получил ВЕСЬ список
категории без единого признака отбора, а на «что из этого выбрать» —
тот же список второй раз. Отбор теперь идёт ПО ДОСЛОВНОМУ ТЕКСТУ
показаний, снятому со страницы справочника, и рядом печатается ТА
САМАЯ строка, где сошлось.

D.6 НЕ ОСЛАБЛЯЕТСЯ: модель этот текст не читает и в отборе
не участвует. Наоборот — отбор перестал опираться на её память.
"""
import os

os.environ.setdefault("DB_PATH", "app.db")

import main

ГОЛОВА = ("Головная боль; мигрень; зубная боль; невралгия. "
          "Лихорадочные состояния при простудных заболеваниях.")
ЖИВОТ = "Изжога, кислая отрыжка при погрешностях в диете."


def поз(текст, ид=1):
    return {"id": ид, "показания": текст}


def test_жалоба_находит_свою_строку_дословно():
    основы = main._апт_основы_вопроса("болит голова в висках, что выпить")
    ц = main._апт_показание_по_вопросу(поз(ГОЛОВА), основы)
    assert ц, "строка показаний не найдена"
    assert ц.rstrip("…").strip() in ГОЛОВА, "цитата не дословна"


def test_чужая_жалоба_не_находит_ничего():
    """Без этого «отбор» был бы разрешением показать что угодно."""
    основы = main._апт_основы_вопроса("болит голова в висках")
    assert main._апт_показание_по_вопросу(поз(ЖИВОТ), основы) == ""


def test_показаний_нет_вовсе_отличается_от_не_сошлось():
    """D.2: два разных факта с разными выводами. Пустая цитата
    сама по себе их не различает — различает `показания_есть`."""
    основы = main._апт_основы_вопроса("болит голова")
    assert main._апт_показание_по_вопросу(поз(""), основы) == ""
    assert main._апт_показание_по_вопросу(поз(ЖИВОТ), основы) == ""
    # и различие видно по самому полю
    assert bool(поз(ЖИВОТ)["показания"]) is True
    assert bool(поз("")["показания"]) is False


def test_ПОДЛОГ_текст_не_из_базы_не_проходит():
    """D.7. Утверждение о свойстве, которого в извлечённом тексте нет,
    обязано быть поймано инвариантом дословности — тем же, что стоит
    у остальных выдержек."""
    import medkit_dosage as дозы
    выдумка = "Помогает при головной боли напряжения и снимает спазм."
    assert not дозы.выдержка_дословна(выдумка, ГОЛОВА)


def test_ОБРАТНЫЙ_дословная_цитата_проходит():
    """Заслон, отвергающий всё подряд, прошёл бы предыдущий тест
    и не значил бы ничего."""
    import medkit_dosage as дозы
    assert дозы.выдержка_дословна("Головная боль;", ГОЛОВА)


def test_общие_слова_жалобы_не_ищутся():
    """«что выпить» не должно находить всё подряд по слову «пить»."""
    основы = main._апт_основы_вопроса("что выпить, болит")
    assert основы == [], "общие слова попали в основы: %r" % основы


def test_ступень_отбора_считает_сервер():
    """Признак живёт на сервере: второе мнение в браузере разошлось бы
    с первым молча (§6.0.7)."""
    import io
    s = io.open("main.py", encoding="utf-8").read()
    assert '"по_показанию": по_показанию' in s
    assert '"без_показаний": без_показаний' in s

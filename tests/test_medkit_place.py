def test_порядок_в_эндпоинте_доза_остаток_место_модель():
    исходник = inspect.getsource(main.medkit_assist)
    доза = исходник.index("_апт_вопрос_о_дозе(")
    остаток = исходник.index("_апт_маршрут_остатка(")
    место = исходник.index("_апт_маршрут_места(")
    модель = исходник.index("_апт_промпт(описание)")
    assert доза < остаток < место < модель



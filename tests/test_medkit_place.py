def _поз(**правки):
    п = {"id": 1, "name": "Тизин", "substance": "", "место": "Полка в ванной",
         "expires_ym": "2028-03", "состояние": "ok", "is_rx": False,
         "форма_имя": "Спрей", "form": "spray", "остаток_строкой": "Спрей",
         "состояние_подпись": "до 03.2028", "дозы": "", "своя_схема": "",
         "категории": [], "подпись_приёма": "Принял 1 дозу"}
    п.update(правки)
    return п


ПАЧКИ = [
    _поз(),
    _поз(id=2, name="Мирамистин", место=""),
    _поз(id=3, name="Магне B6", место="Полка в ванной", expires_ym="2027-11"),
    _поз(id=4, name="Магне B6", место="Кухонный шкаф", expires_ym="2028-05"),
]


def test_ответ_без_модели_и_без_действий(monkeypatch):
    вызвана = []

    async def модель(*а, **к):
        вызвана.append(1)
        return {}, "", 200
    monkeypatch.setattr(main, "_апт_спросить_модель", модель)
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (ПАЧКИ, {}))
    тело = main._апт_маршрут_места("где у меня Магне B6", None, None)
    assert вызвана == []
    assert тело["вид"] == "запрос" and тело["тип"] == "место"
    assert [с["id"] for с in тело["нашлось"]] == [3, 4]
    for с in тело["нашлось"]:
        assert с["приём_подпись"] == "" and с["действия"] is False
        assert с["показание"] == "" and с["photo"] == ""
    # ДВЕ ПАЧКИ ОДНОГО НАЗВАНИЯ РАЗЛИЧАЮТСЯ СРОКОМ, иначе строки одинаковы
    assert "место: Полка в ванной" in тело["нашлось"][0]["строка"]
    assert "срок 11.2027" in тело["нашлось"][0]["строка"]
    assert "Кухонный шкаф" in тело["нашлось"][1]["строка"]
    assert not re.search(r"\d", тело["вступление"])
    assert main._апт_заслон_выхода(тело) is тело



class _Юзер:
    id = 1
    timezone = "Europe/Moscow"


def _подменить_модель(ответ):
    async def подделка(промпт, очищать=True):
        return ответ, "", 200
    return подделка


def _прогнать(monkeypatch, позиции, ответ):
    monkeypatch.setattr(main, "_апт_спросить_модель", _подменить_модель(ответ))
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (позиции, {}))
    # ХВОСТ ПЕРЕПИСКИ ЗАГЛУШЕН, а не отключён в коде (BACKLOG №178, C.1).
    # Здесь проверяется РАСКЛАДКА ПО КУЧАМ, и база нужна ей только затем,
    # чтобы прочитать историю; подставлять сюда живую сессию значило бы
    # мерить заодно и её. Заглушка при этом ОБЯЗАНА быть: без неё тест
    # падал бы `AttributeError` на `None.query` — то есть напоминал бы
    # о новой зависимости, а не молчал
    monkeypatch.setattr(main, "_апт_чат_хвост", lambda db, user: "")
    return asyncio.run(main._апт_ответ_на_запрос("болит живот", None, _Юзер()))


def test_просроченное_уходит_в_свою_кучу_даже_если_модель_зовёт_его_годным(
        monkeypatch):
    """C.4 — СВОЙСТВО КОДА. Спроси мы об этом модель, правило держалось
    бы на её добросовестности."""
    итог = _прогнать(monkeypatch,
                     [_поз(id=5, состояние="expired",
                           состояние_подпись="истекло 01.2026", is_rx=False,
                           дозы="", категории=[])],
                     {"вступление": "Подойдёт.", "подходят": [5],
                      "почему": {"5": "подходит"}})
    assert итог["нашлось"] == []
    assert len(итог["просрочено"]) == 1



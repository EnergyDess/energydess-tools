# РАСКЛАДКА ПО КУЧАМ РЕШАЕТСЯ БАЗОЙ (C.4, C.5)
# ═════════════════════════════════════════════════════════════════════

class _Юзер:
    id = 1
    timezone = "Europe/Moscow"


def _подменить_модель(ответ):
    async def подделка(промпт, очищать=True):
        return ответ, "", 200
    return подделка


def _прогнать(monkeypatch, позиции, ответ, прошлое=()):
    monkeypatch.setattr(main, "_апт_спросить_модель", _подменить_модель(ответ))
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (позиции, {}))
    # ПЕРЕПИСКА ЗАГЛУШЕНА ОДНИМ МЕСТОМ — ЧТЕНИЕМ РЕПЛИК (BACKLOG №196).
    #
    # Здесь стояла заглушка `_апт_чат_хвост`, и она перестала покрывать
    # всё: с A.2 переписку читает ВТОРОЙ потребитель — `_апт_прошлый_ответ`,
    # заслон повтора. Тесты честно упали `AttributeError` на `None.query`,
    # то есть напомнили о новой зависимости, а не промолчали.
    #
    # Заглушается теперь ИСТОЧНИК, а не два его потребителя: подмени мы
    # снова хвост, третий читатель переписки опять уронил бы этот файл.
    # Пустой список — это «переписки не было», и оба потребителя ведут
    # себя на нём так же, как на живой пустой базе.
    monkeypatch.setattr(main, "_апт_чат_реплики",
                        lambda db, user: list(прошлое))
    тело = asyncio.run(
        main._апт_ответ_на_запрос("болит живот", None, _Юзер()))
    # ЗАСЛОН ПОВТОРА ЖИВЁТ НЕ ЗДЕСЬ (BACKLOG №197, B.4). Он переехал
    # в `_апт_повтор_если_тот_же`, который зовёт `_апт_чат_отдать` —
    # единственная точка, через которую проходит КАЖДЫЙ ответ. Помощник
    # повторяет боевой порядок: сперва собрали ответ, потом пропустили
    # через заслон. Оставь мы только первое — тесты повтора спрашивали
    # бы функцию, которая о повторе больше ничего не знает.
    return main._апт_повтор_если_тот_же(None, _Юзер(), тело)


def test_просроченное_уходит_в_свою_кучу_даже_если_модель_зовёт_его_годным(
        monkeypatch):
    """C.4 — СВОЙСТВО КОДА. Спроси мы об этом модель, правило держалось
    бы на её добросовестности."""
    итог = _прогнать(monkeypatch,
                     [_поз(id=5, состояние="expired",
                           состояние_подпись="истекло 01.2026", is_rx=False,
                           дозы="", категории=[])],
                     {"вступление": "Подойдёт.", "подходят": [5],
                      "почему": {"5": "подходит"}})
    assert итог["нашлось"] == []
    assert len(итог["просрочено"]) == 1



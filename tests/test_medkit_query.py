def test_список_режется_ПО_СТРОКАМ_и_обрезка_называется(monkeypatch):
    """Первая версия резала `[:СТРАНИЦА_ЗНАКОВ]` — по знакам и посреди
    строки: при большой аптечке часть позиций не доезжала до модели
    ВОВСЕ, и человек получал «от живота у вас три штуки», не узнав
    про четвёртую. Ни ошибки, ни строки в журнале."""
    monkeypatch.setattr(main, "АПТ_СПИСОК_ЗНАКОВ", 120)
    много = [_поз(id=i, name="Препарат%02d" % i, is_rx=False, дозы="",
                  категории=[]) for i in range(1, 21)]
    промпт, показано = main._апт_промпт_запроса("болит живот", много, {})
    assert 0 < показано < 20
    # РЕЖЕТСЯ ПО ГРАНИЦЕ СТРОКИ: последняя строка целая, обрывка нет
    блок = промпт.split("ЕГО АПТЕЧКА")[1].split("Верни ТОЛЬКО")[0]
    строки = [с for с in блок.splitlines() if с.strip() and с[0].isdigit()]
    assert len(строки) == показано
    for с in строки:
        assert с.count("—") == 4, с



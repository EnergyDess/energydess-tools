def test_показание_режется_и_по_точке_с_запятой():
    """Показания Видаля часто идут ОДНИМ предложением, где состояния
    разделены `;`. По одной точке такое не режется вовсе: замер по 13
    показаниям боевой аптечки дал max 600 знаков против 362 с `;`."""
    длинное = ("симптоматическое лечение боли и спазмов в области живота, "
               "связанных с заболеваниями органов ЖКТ и желчных путей: "
               "неэрозивная форма рефлюксной болезни; желчнокаменная "
               "болезнь; дисфункция желчевыводящих путей; синдром "
               "раздраженного кишечника; дисфункция сфинктера Одди.")
    в = main._апт_дозы.выдержка_показаний(длинное, 220)
    assert в.endswith("…")
    assert в[:-1].rstrip().endswith(";")
    # ДОСЛОВНОСТЬ НЕ ОСЛАБЛА: рез по-прежнему ПРЕФИКС
    assert main._апт_дозы.выдержка_дословна(в, длинное)
    assert длинное.startswith(в[:-1].rstrip())

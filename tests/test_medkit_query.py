class _Юзер:
    id = 1
    timezone = "Europe/Moscow"


def _подменить_модель(ответ):
    async def подделка(промпт, очищать=True):
        return ответ, "", 200
    return подделка


def _прогнать(monkeypatch, позиции, ответ, прошлое=()):
    monkeypatch.setattr(main, "_апт_спросить_модель", _подменить_модель(ответ))
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (позиции, {}))
    # ПЕРЕПИСКА ЗАГЛУШЕНА ОДНИМ МЕСТОМ — ЧТЕНИЕМ РЕПЛИК (BACKLOG №196).
    #
    # Здесь стояла заглушка `_апт_чат_хвост`, и она перестала покрывать
    # всё: с A.2 переписку читает ВТОРОЙ потребитель — `_апт_прошлый_ответ`,
    # заслон повтора. Тесты честно упали `AttributeError` на `None.query`,
    # то есть напомнили о новой зависимости, а не промолчали.
    #
    # Заглушается теперь ИСТОЧНИК, а не два его потребителя: подмени мы
    # снова хвост, третий читатель переписки опять уронил бы этот файл.
    # Пустой список — это «переписки не было», и оба потребителя ведут
    # себя на нём так же, как на живой пустой базе.
    monkeypatch.setattr(main, "_апт_чат_реплики",
                        lambda db, user: list(прошлое))
    return asyncio.run(main._апт_ответ_на_запрос("болит живот", None, _Юзер()))



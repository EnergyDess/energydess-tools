def _поз(**правки):
    п = {"id": 1, "name": "Нурофен", "substance": "Ибупрофен, 200 мг",
         "остаток_строкой": "Таблетки · 18 из 20", "состояние": "ok",
         "форма_имя": "Таблетки",
         "состояние_подпись": "до 03.2028", "expires_ym": "2028-03",
         "место": "Полка в ванной"}
    п.update(правки)
    return п


def test_строка_несёт_четыре_обязательных_поля():
    """Название, остаток, срок и место (C.2). Все четыре из записи —
    выдумать их нечем, потому что собирает строку не модель."""
    с = main._апт_строка_позиции(_поз())
    for кусок in ("Нурофен", "18 из 20", "03.2028", "Полка в ванной"):
        assert кусок in с


def test_срок_берётся_подписью_карточки_а_не_машинным_полем():
    """Первая версия печатала `expires_ym` как есть, и в ответ уезжало
    «годен до 2028-09» при «до 09.2028» на карточке — два формата одной
    даты на одном экране. Второго мнения о том, как называется срок,
    тут быть не должно (§6.0.7)."""
    с = main._апт_строка_позиции(_поз())
    assert "2028-03" not in с
    assert "годен до 03.2028" in с



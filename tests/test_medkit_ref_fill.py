def test_при_НАЙДЕННОЙ_схеме_подсказки_ОСТАЮТСЯ():
    """До №239 удача обнуляла подсказку вещества, и позиции с пустым
    веществом предложить было нечего — а схема находится и при пустом
    веществе: сверка его тогда не проверяет вовсе (§5.8).

    Замер по боевой аптечке: вещество пусто у 7 позиций из 49."""
    поз = Поз(form="tablet")
    main._апт_записать_итог_доз(
        поз, ("текст схемы", "https://x/y", None, "", None), "", "",
        {"вещество": "Ибупрофен", "форма": "tablet",
         "форма_слово": "таблетк"})
    assert поз.dosage_text == "текст схемы"
    assert поз.dosage_hint_substance == "Ибупрофен"
    assert поз.dosage_hint_form == "tablet"
    assert поз.dosage_hint_form_word == "таблетк"


def test_при_ОТКАЗЕ_подсказки_тоже_пишутся():
    поз = Поз(form="syrup")
    main._апт_записать_итог_доз(
        поз, None, "не нашлось", "выпуски",
        {"вещество": "Амброксол", "форма": "solution",
         "форма_слово": "раствор для приема внутрь"})
    assert поз.dosage_text is None
    assert поз.dosage_miss == "не нашлось"
    assert поз.dosage_hint_substance == "Амброксол"
    assert поз.dosage_hint_form == "solution"


def test_ПРАВКА_КАРТОЧКИ_чистит_подсказки_формы_тоже():
    """Подсказка получена со страницы ПРЕЖНЕГО препарата: оставить её
    значило бы предлагать вписать форму чужого выпуска."""
    поз = Поз(dosage_hint_substance="Ибупрофен", dosage_hint_form="tablet",
              dosage_hint_form_word="таблетк", own_dosage_text="своя запись")
    main._апт_забыть_дозы(поз)
    assert поз.dosage_hint_form is None
    assert поз.dosage_hint_form_word is None
    assert поз.dosage_hint_substance is None
    # A.5 задачи 177 не ослабляется ни на знак
    assert поз.own_dosage_text == "своя запись"



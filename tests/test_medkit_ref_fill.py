@pytest.mark.parametrize("опис,ждём", [
    ("Нурофен таблетки, покрытые оболочкой, 200 мг", "tablet"),
    ("Лазолван раствор для приема внутрь и ингаляций", "solution"),
    ("Тантум Верде спрей для местного применения", "spray"),
    ("Хлоргексидин раствор для местного и наружного применения",
     "solution_ext"),
    ("Називин капли в нос 0.05%", "drops"),
    ("Пенталгин гель для наружного применения 5%", "gel"),
    ("Виферон суппозитории ректальные", "suppository"),
])
def test_форма_выводится_из_слова_справочника(опис, ждём):
    код, слово = дозы.форма_страницы(опис)
    assert код == ждём, "%r -> %r, слово %r" % (опис, код, слово)
    assert слово, "слово источника обязано отдаваться вместе с кодом"


def test_САМЫЙ_ДЛИННЫЙ_синоним_а_не_первый_совпавший():
    """Длинная формулировка источника точнее короткой, и это свойство
    ИСТОЧНИКА: написав длиннее, справочник сказал точнее."""
    код, слово = дозы.форма_страницы(
        "Зодак капли для приема внутрь 10 мг/мл")
    assert код == "solution"
    assert слово == "капли для приема внутрь"


def test_НИЧЬЯ_даёт_отказ_а_слово_всё_равно_отдаётся():
    """Слово «порошок» стоит у sachet и powder — выбрать нечем.

    ОТКАЗ ОБЯЗАТЕЛЕН: подставь мы любую из двух, форма поехала бы
    молча, а единица приёма следует за формой."""
    код, слово = дозы.форма_страницы(
        "Смекта порошок для приготовления суспензии для приема внутрь")
    assert код is None, "ничья по длине обязана давать None"
    assert слово, "слово источника показывается и при отказе"


def test_пустое_описание_не_роняет_и_не_выдумывает():
    assert дозы.форма_страницы("") == (None, "")
    assert дозы.форма_страницы(None) == (None, "")


def test_код_формы_всегда_из_объявленного_списка():
    """Вывод не может дать формы, которой в проекте нет: иначе
    подстановка положила бы в карточку код, о котором не знает
    ни один экран."""
    коды = set(ф["id"] for ф in опр.ФОРМЫ)
    for опис in ("таблетки", "капсулы", "сироп", "мазь", "спрей",
                 "настойка", "гранулы", "эмульсия", "пена", "паста"):
        код, _ = дозы.форма_страницы(опис)
        if код is not None:
            assert код in коды, "%r -> %r вне списка форм" % (опис, код)



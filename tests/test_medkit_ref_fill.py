def test_слово_справочника_НЕ_ПЕРЕСКАЗЫВАЕТСЯ():
    """Между разбором страницы и колонкой нет ни одного преобразования
    текста, кроме обрезки по длине колонки. Появится здесь приведение
    к виду — правило дословности (§5.8, D.1) нарушено."""
    слова = ["раствор для местного и наружного применения",
             "капли для приема внутрь", "таблетки шипучие"]
    for сл in слова:
        _, отдано = дозы.форма_страницы("Препарат " + сл + " 100 мл")
        assert отдано in сл or сл.startswith(отдано), (
            "%r -> %r: слово источника изменено" % (сл, отдано))


def test_вещество_страницы_отдаётся_дословно():
    страница = ("<html><body><p>Активное вещество: Ацетилсалициловая "
                "кислота</p></body></html>")
    assert дозы.вещество_страницы(страница) == "Ацетилсалициловая кислота"

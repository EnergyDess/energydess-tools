def _ответ_модели(monkeypatch, тип):
    async def модель(промпт, очищать=True, **прочее):
        return {"тип": тип, "подходят": [1], "нет": ""}, "", 200
    monkeypatch.setattr(main, "_апт_спросить_модель", модель)
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: ([_поз()], {}))
    monkeypatch.setattr(main, "_апт_чат_реплики", lambda db, user: [])

    class Юзер:
        id = 1
        timezone = "Europe/Moscow"
    return asyncio.run(main._апт_ответ_на_запрос("про нурофен", None, Юзер()))


def test_тип_вне_набора_и_пустой_дают_иное_без_кнопки(monkeypatch):
    for тип in ("мусор", ""):
        тело = _ответ_модели(monkeypatch, тип)
        assert тело["тип"] == "иное", тип
        assert main._апт_заслон_выхода(тело)["нашлось"][0]["приём_подпись"] == ""



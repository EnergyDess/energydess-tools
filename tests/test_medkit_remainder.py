def _карточка():
    return {"id": 1, "строка": "Нурофен · Таблетки · 18 из 20",
            "почему": "Таблетки", "photo": "", "показание": "",
            "группа": "", "показания_есть": False, "дозы": True,
            "упаковок": 1, "приём_подпись": "Принял 1 таблетку"}


def _запрос(**правки):
    т = {"вид": "запрос", "тип": "поиск", "вопрос": "что у меня есть от кашля",
         "вступление": "", "нет": "", "группа": "", "группы": [],
         "нашлось": [_карточка()], "просрочено": [], "рецептурные": [],
         "оговорка": ""}
    т.update(правки)
    return т


def test_вопрос_об_остатке_в_поиске_кнопку_теряет():
    """Маршрут сломан, модель поставила «поиск» — залог на выходе."""
    итог = main._апт_заслон_выхода(_запрос(вопрос="сколько осталось Нурофена"))
    assert итог["нашлось"][0]["приём_подпись"] == ""
    assert итог["нашлось"][0]["строка"] == _карточка()["строка"]


def test_обратный_поиск_по_жалобе_тело_то_же():
    т = _запрос()
    assert main._апт_заслон_выхода(т) is т
    assert т["нашлось"][0]["приём_подпись"] == "Принял 1 таблетку"



def _поз(**правки):
    п = {"id": 1, "name": "Нурофен", "substance": "Проверочное вещество, 200 мг",
         "остаток_строкой": "Таблетки · 18 из 20", "состояние": "ok",
         "форма_имя": "Таблетки", "form": "tablet",
         "состояние_подпись": "до 03.2028", "expires_ym": "2028-03",
         "место": "Полка в ванной", "is_rx": False, "дозы": "",
         "своя_схема": "", "категории": [],
         "подпись_приёма": "Принял 1 таблетку"}
    п.update(правки)
    return п


ПАЧКИ = [
    _поз(),
    _поз(id=2, name="Препарат А", expires_ym="2027-11",
         состояние_подпись="до 11.2027", остаток_строкой="Таблетки · 7 из 20"),
    _поз(id=3, name="Препарат А", expires_ym="2027-08",
         состояние_подпись="до 08.2027", остаток_строкой="Таблетки · 14 из 20"),
    _поз(id=4, name="Левомеколь", form="ointment", остаток_строкой="Мазь"),
]


def test_ответ_по_пачке_на_карточку_без_действий_и_без_модели(monkeypatch):
    вызвана = []

    async def модель(*а, **к):
        вызвана.append(1)
        return {}, "", 200
    monkeypatch.setattr(main, "_апт_спросить_модель", модель)
    monkeypatch.setattr(main, "_апт_позиции_для_запроса",
                        lambda db, user: (ПАЧКИ, {}))
    тело = main._апт_маршрут_остатка("когда кончится Препарат А", None, None)
    assert вызвана == []
    assert тело["вид"] == "запрос" and тело["тип"] == "остаток"
    # ДВЕ ПАЧКИ — ДВЕ КАРТОЧКИ, по сроку: сводка группы отвечала бы
    # не на вопрос «сколько осталось»
    assert [с["id"] for с in тело["нашлось"]] == [3, 2]
    for с in тело["нашлось"]:
        assert с["приём_подпись"] == "" and с["действия"] is False
        assert с["показание"] == "" and с["photo"] == ""
        assert "Полка" not in с["строка"] and "вещество" not in с["строка"]
    assert "14 из 20" in тело["нашлось"][0]["строка"]
    assert "годен до 08.2027" in тело["нашлось"][0]["строка"]
    assert not re.search(r"\d", тело["вступление"])
    assert main._апт_дозы_в_видимом(тело) == []
    assert main._апт_заслон_выхода(тело) is тело



def test_полный_код_лекарства_даёт_gtin():
    """DataMatrix с пачки: `01` + 14 цифр + серийный номер + подпись."""
    код = "010460043993125621FBhTfvzoYnrEQ" + GS + "91EE07" + GS + "92dGVzdA=="
    assert gtin_из_кода(код) == "04600439931256"


def test_печатный_разделитель_тоже_понимается():
    """Часть сканеров отдаёт GS печатным `<GS>`, а не знаком U+001D."""
    assert gtin_из_кода("010460043993125621FBhTfvz<GS>91EE07") == "04600439931256"


def test_голый_gtin_остаётся_собой():
    assert gtin_из_кода("04600439931256") == "04600439931256"


def test_ean13_дополняется_ведущим_нулём():
    """GTIN-14 потребительской единицы по GS1 и есть `0` плюс GTIN-13.

    Это СВЯЗЫВАЕТ два кода одной пачки, а не путает разные: на пачке
    лекарства печатают и DataMatrix, и обычные полосы, и оба должны
    находить одну и ту же карточку. Замер на образце: DataMatrix даёт
    `04600439931256`, штрих-код той же пачки — `4600439931256`.
    """
    assert gtin_из_кода("4600439931256") == "04600439931256"
    assert gtin_из_кода("4600439931256") == gtin_из_кода("04600439931256")


@pytest.mark.parametrize("код", [
    "010460043993125",          # `01` плюс 13 цифр — код ОБОРВАН
    "01046004399312",           # `01` плюс 12
    "нет-такого-кода-совсем",   # шум
    "",                         # пусто
    None,                       # ничего
    "460043993125",             # 12 цифр — ни GTIN, ни EAN-13
    "046004399312567",          # 15 цифр
])
def test_негодное_отвергается(код):
    """Отвергнутое — это `None`, а не пустая строка и не догадка.

    Обрезанный DataMatrix (`01` плюс 13 цифр — ПЯТНАДЦАТЬ знаков)
    от честного EAN-13 (тринадцать знаков) отличается ПРЕФИКСОМ,
    и потому различим. Отвергать всякую строку из 13 цифр значило бы
    не пускать обычный штрих-код обычной пачки.
    """
    assert gtin_из_кода(код) is None


def test_разбор_живёт_в_ОДНОМ_месте():
    """Ни своей чистки кода, ни своей регулярки на месте вызова.

    Мест, где строка со сканера превращается в GTIN, три — форма,
    черновик ассистента и запрос по коду, — и три копии правила
    разошлись бы молча (§6.0.7). Признак: в `main.py` не должно быть
    ни одной чистки поля `code_gtin` регуляркой.
    """
    исходник = open("main.py", encoding="utf-8").read()
    свои_чистки = re.findall(
        r're\.sub\([^)]*\)\s*(?:#[^\n]*)?\n?[^\n]*code_gtin', исходник)
    прямые = re.findall(r'code_gtin[^\n]{0,40}re\.sub', исходник)
    assert not свои_чистки and not прямые, (
        "разбор кода вернулся на место вызова: %r" % (свои_чистки + прямые))
    assert исходник.count("_апт_опр.gtin_из_кода") >= 3, (
        "мест разбора стало меньше трёх — проверьте, не завелась ли "
        "своя чистка вместо общей")



def _форматы(файл, имя):
    текст = open(файл, encoding="utf-8").read()
    м = re.search(имя + r"\s*=\s*\[(.*?)\]", текст, re.S)
    assert м, "набор %s не найден в %s" % (имя, файл)
    return re.findall(r"'([A-Z_0-9]+)'", м.group(1))


def test_аптечка_читает_DataMatrix():
    """Ради этого одного члена задача и заводилась."""
    ф = _форматы("templates/medkit.html", "АПТ_ФОРМАТЫ_КОДА")
    assert "DATA_MATRIX" in ф, "DATA_MATRIX выпал из набора аптечки: %r" % ф


def test_аптечка_читает_и_обычный_штрихкод():
    """На пачке лекарства печатают ОБА кода, и человек наведёт на тот,
    который заметит первым."""
    ф = _форматы("templates/medkit.html", "АПТ_ФОРМАТЫ_КОДА")
    assert "EAN_13" in ф


def test_у_дневника_набор_НЕ_изменился():
    """Перенос механики в компонент поведения дневника не трогал.

    Список там сужен НАМЕРЕННО: без сужения библиотека путает полосы
    EAN-13 с QR-кодом и выдаёт случайный код. DATA_MATRIX в нём нет
    и появиться не должен — код лекарства дневнику не нужен, а его
    добавление поменяло бы поведение экрана, которого задача 163
    не касается.
    """
    ф = _форматы("templates/nutrition.html", "ФОРМАТЫ_ПРОДУКТА")
    assert ф == ["EAN_13", "EAN_8", "UPC_A", "UPC_E",
                 "CODE_128", "CODE_39", "ITF", "QR_CODE"], ф
    assert "DATA_MATRIX" not in ф


def test_механика_сканера_в_ОДНОМ_месте():
    """Ни у дневника, ни у аптечки своего `new Html5Qrcode` быть не должно.

    Второй экземпляр начал бы с тех же трёх дефектов, которые сканер
    дневника уже пережил: замороженный кадр прошлой сессии, гонка
    токенов, фонарик у камеры, которая его не умеет.
    """
    for файл in ("templates/nutrition.html", "templates/medkit.html"):
        текст = open(файл, encoding="utf-8").read()
        assert "new Html5Qrcode" not in текст, (
            "%s завёл свой экземпляр сканера" % файл)
    компонент = open("static/barcode-scan.js", encoding="utf-8").read()
    assert компонент.count("new Html5Qrcode") == 1



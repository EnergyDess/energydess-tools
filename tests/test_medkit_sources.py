def test_поиск_схемы_ОТДАЁТ_соединение_перед_сетью():
    """§6.0.6. Оба места, ходящие за схемой, обязаны закрыть сессию ДО
    похода к чужому сайту.

    НАЙДЕНО ПРОГОНОМ, А НЕ ЧТЕНИЕМ: в журнале стенда 2026-09-04 три
    строки «фоном для N оборвалось: OperationalError: database is
    locked» — фоновая задача не смогла записать СОБСТВЕННЫЙ итог,
    потому что соединение было занято всё время поиска.

    Дефект предсуществующий, но второй источник сделал его тяжелее
    в разы: у него таймаут 90 с против 20 у первого, и держать
    соединение стало можно МИНУТАМИ.
    """
    import ast
    исходник = io.open("main.py", encoding="utf-8").read()
    дерево = ast.parse(исходник)
    проверено = 0
    for узел in ast.walk(дерево):
        if not isinstance(узел, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        # ═══════════════════════════════════════════════════════════
        # ПО ДЕРЕВУ, А НЕ ПО ТЕКСТУ, И ЭТО НАШЁЛ КОНТРОЛЬ
        # ═══════════════════════════════════════════════════════════
        #
        # Первая версия искала подстроку `db.close()` в тексте тела
        # до вызова — и нашла её В КОММЕНТАРИИ, который сам же
        # и объясняет правило («СНИМОК ПОЛЕЙ, потом `db.close()`,
        # потом сеть»). Подлог «убрать закрытие» тест НЕ ПОЙМАЛ:
        # 22 passed и с ним, и без него.
        #
        # Ровно урок задачи 99 (§6.0.2): проза читается как код.
        # Здесь ищется ВЫЗОВ в синтаксическом дереве, и комментарий
        # рассказом о закрытии быть перестал.
        строка_вызова = None
        строка_закрытия = None
        for у in ast.walk(узел):
            if not isinstance(у, ast.Call):
                continue
            имя = getattr(у.func, "id", None) or getattr(у.func, "attr", None)
            if имя == "_апт_найти_дозы" and строка_вызова is None:
                строка_вызова = у.lineno
            if (имя == "close"
                    and getattr(getattr(у.func, "value", None), "id", "") == "db"):
                if строка_закрытия is None or у.lineno < строка_закрытия:
                    строка_закрытия = у.lineno
        if строка_вызова is None:
            continue
        проверено += 1
        assert строка_закрытия is not None and строка_закрытия < строка_вызова, (
            "%s ходит в сеть, не отдав соединение (§6.0.6): close на строке "
            "%s, вызов на %s" % (узел.name, строка_закрытия, строка_вызова))
    # ДВА МЕСТА, И ОБА ОБЯЗАНЫ БЫТЬ ПРОВЕРЕНЫ: фоновая задача при
    # заведении карточки и обработчик кнопки «Найти в справочнике».
    # Ноль означал бы, что тест ищет не то имя
    assert проверено >= 2, "мест найдено %d, ожидалось не меньше двух" % проверено



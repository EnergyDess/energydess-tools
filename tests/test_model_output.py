def test_текст_строится_из_причины_и_у_каждой_свой():
    обрыв = "Письмо не поместилось в лимит."
    тексты = {
        вид: _текст_сбоя(f"{вид}: подробности", обрыв)
        for вид in ("truncated", "empty", "service", "shape")
    }
    assert тексты["truncated"] == обрыв
    # Ни одного повтора: одинаковый текст на две причины — это и есть
    # утверждение, ложное в одном из двух случаев.
    assert len(set(тексты.values())) == 4



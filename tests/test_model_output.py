def _строки_кода_main():
    from pathlib import Path as _P
    исходник = (_P(__file__).resolve().parent.parent / "main.py").read_text(
        encoding="utf-8")
    # Пояснения не считаем: в них причина цитируется законно (§6.0.2,
    # задача 99 — проза кодом не является).
    return [с for с in исходник.splitlines()
            if not с.lstrip().startswith("#")]


def test_выбор_текста_по_причине_живёт_в_ОДНОМ_месте():
    """`сбой.startswith(...)` вне `_текст_сбоя` быть не должно.

    До 2026-08-21 разбор причины стоял на КАЖДОМ месте вызова — семь
    копий одного `if`, — и в двух местах его не было вовсе: там висела
    константа на все исходы. Заведи кто-нибудь восьмую причину, семь
    копий разъехались бы молча."""
    свои = [с for с in _строки_кода_main() if 'сбой.startswith(' in с]
    assert свои == [], свои


def test_фраза_обрыва_ассистента_объявлена_один_раз():
    """Дневник и тренер говорят про обрыв одно и то же — и берут это
    из одной константы, а не из двух почти одинаковых строк."""

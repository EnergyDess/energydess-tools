"""Разбор блоков еды, ранжирование поиска и нормы в контексте ассистента.

Почему тесты нужны именно здесь. Все три места отказывают МОЛЧА и все три
уже отказали. `_extract_food_block` брал первый блок из трёх и вырезал
из текста все — пользователь получал одно блюдо вместо трёх и уверение
ассистента, что записаны все. Порядок выдачи поиска не проверялся ничем,
и искомое стояло седьмым. Нормы уходили в промпт одной калорийностью,
остальные модель выдумывала. Ни одно из трёх не роняет запрос и не пишет
в лог.

База не поднимается: DB_PATH уводится в tmp ДО импорта main.
"""

import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_нутриция.db")

import main            # noqa: E402


def блок(имя, ккал=100, граммы=100):
    return ('###FOOD_JSON###\n'
            f'{{"name":"{имя}","brand":"","calories":{ккал},"protein":1,'
            f'"fat":2,"carbs":3,"estimated_grams":{граммы}}}\n'
            '###END_FOOD_JSON###')


# ── Разбор блоков еды ────────────────────────────────────────────────────────

def test_три_блока_дают_три_блюда():
    """Тот самый случай: одно сообщение — три блюда."""
    ответ = ("Записываю все три позиции:\n" + блок("Овсянка", 88, 200)
             + "\n" + блок("Яйцо", 155, 120) + "\n" + блок("Банан", 89, 120))
    текст, блюда = main._extract_food_blocks(ответ)
    assert [b["name"] for b in блюда] == ["Овсянка", "Яйцо", "Банан"]
    assert "###FOOD_JSON###" not in текст
    assert текст.startswith("Записываю")


def test_один_блок_остаётся_списком_из_одного():
    """Формат ответа один на любое количество: вторая ветка разбора и была
    тем местом, где терялись остальные блюда."""
    текст, блюда = main._extract_food_blocks("Вот блюдо:\n" + блок("Банан"))
    assert len(блюда) == 1 and блюда[0]["name"] == "Банан"
    assert текст == "Вот блюдо:"


def test_блоков_нет():
    текст, блюда = main._extract_food_blocks("Просто ответ без еды.")
    assert блюда == [] and текст == "Просто ответ без еды."


def test_битый_блок_не_уносит_соседей():
    """Битый JSON пропускается, но остальные блюда доезжают: терять их
    из-за соседа было бы хуже."""
    плохой = '###FOOD_JSON###\n{"name":"Обрыв",\n###END_FOOD_JSON###'
    текст, блюда = main._extract_food_blocks(блок("Овсянка") + "\n" + плохой
                                             + "\n" + блок("Банан"))
    assert [b["name"] for b in блюда] == ["Овсянка", "Банан"]
    assert "###" not in текст


# ── Ранжирование поиска ──────────────────────────────────────────────────────

ГРЕЧКА = [
    {"name": "Гречка", "brand": "Любимая Бабушкина кухня"},
    {"name": "Гречка", "brand": ""},
    {"name": "Гречка Fresco", "brand": "Georgia"},
    {"name": "Green buckwheat", "brand": "Увелка"},
    {"name": "Рис Басмати", "brand": "Увелка"},
]


# Переводы приходят ПАРАМЕТРОМ с 2026-08-15. Раньше на их месте стоял
# словарь ПОИСК_СИНОНИМЫ прямо в main.py, и ранжирование молча зависело
# от того, попало ли слово в тот список (BACKLOG.md, задача 76)
ПЕРЕВОДЫ = {"гречка": "buckwheat", "увелка": ""}


def test_совпало_по_двум_словам_идёт_первым():
    """Замер на живой выдаче: искомое стояло седьмым, стало первым.
    «Гречка» и «Увелка» лежат в РАЗНЫХ полях, поэтому слово ищется
    и в названии, и в бренде."""
    порядок = main._rank_food_results("гречка увелка", ГРЕЧКА, ПЕРЕВОДЫ)
    assert порядок[0]["name"] == "Green buckwheat"


def test_без_переводов_искомое_НЕ_поднимается():
    """Отрицательный контроль к предыдущему: подъём даёт именно перевод,
    а не что-то ещё в весе. Без него запись остаётся там, где была."""
    порядок = main._rank_food_results("гречка увелка", ГРЕЧКА, {})
    assert порядок[0]["name"] != "Green buckwheat"


def test_одно_слово_порядок_не_трогает():
    """При однословном запросе переоценивать релевантность Open Food Facts
    нечем — отдаём как пришло."""
    assert main._rank_food_results("молоко", ГРЕЧКА) == ГРЕЧКА


def test_порядок_внутри_ступени_сохраняется():
    """sorted устойчив: три «Гречки» с одним совпадением остаются в том же
    порядке, в котором пришли."""
    порядок = main._rank_food_results("гречка увелка", ГРЕЧКА, ПЕРЕВОДЫ)
    гречки = [r["brand"] for r in порядок if r["name"].startswith("Гречка")]
    assert гречки == ["Любимая Бабушкина кухня", "", "Georgia"]


def test_название_весит_больше_бренда():
    """При равном числе совпавших слов выше тот, у кого ОБА попали
    в название. У первой записи слова разнесены по двум полям — совпало
    столько же, но название говорит о продукте больше, чем бренд."""
    данные = [{"name": "Хлопья овсяные", "brand": "Рис"},
              {"name": "Рис хлопья", "brand": "Увелка"}]
    порядок = main._rank_food_results("рис хлопья", данные)
    assert порядок[0]["name"] == "Рис хлопья"


def test_окончание_слова_не_мешает():
    данные = [{"name": "Что-то другое", "brand": ""},
              {"name": "Каша гречневая с молоком", "brand": ""}]
    порядок = main._rank_food_results("гречневая молоко", данные)
    assert порядок[0]["name"].startswith("Каша")


def test_короткое_слово_не_обрезается():
    """«сок» → «со» совпало бы с чем угодно, поэтому режем от пяти знаков."""
    assert not main._слово_нашлось("сок", "соль поваренная")
    assert main._слово_нашлось("сок", "сок яблочный")


# ── Нормы в контексте ассистента ─────────────────────────────────────────────

class ПрофильЗаглушка:
    gender, age, weight_kg, height_cm = "male", 34, 82.4, 181.0
    goal, target_weight_kg = "lose", 76.0
    calorie_goal, protein_goal, fat_goal, carb_goal = 2200, 150, 70, 230
    water_goal_ml = 2500


class ЗаписьЗаглушка:
    def __init__(self, имя, приём, граммы, ккал):
        self.food_name, self.meal_type, self.grams = имя, приём, граммы
        self.calories, self.protein, self.fat, self.carbs = ккал, 10, 5, 20
        self.brand = None


def test_все_пять_норм_уходят_числами():
    """Уходила одна калорийность — остальные модель считала сама и на живом
    вызове назвала «130-150 г» при 150 г в анкете."""
    промпт = main._nut_chat_system("2026-08-13", [], 0, ПрофильЗаглушка())
    for число in ("2200", "150", "70", "230", "2500"):
        assert число in промпт, f"нормы {число} нет в промпте"


def test_записи_дневника_с_граммовкой_и_приёмом():
    логи = [ЗаписьЗаглушка("Овсянка", "breakfast", 200, 176)]
    промпт = main._nut_chat_system("2026-08-13", логи, 500, ПрофильЗаглушка())
    assert "завтрак: Овсянка" in промпт
    assert "200 г" in промпт


def test_правило_не_соглашаться_с_чужим_числом():
    """Согласие с неверным числом — главная поломка, не выдуманное число:
    модель согласилась бы точно так же, если бы ошибался пользователь."""
    промпт = main._nut_chat_system("2026-08-13", [], 0, ПрофильЗаглушка())
    assert "НЕ соглашайся" in промпт


def test_запрет_сообщать_о_записи():
    промпт = main._nut_chat_system("2026-08-13", [], 0, ПрофильЗаглушка())
    assert "НИКОГДА не пиши" in промпт
    assert "СТОЛЬКО блоков, сколько блюд" in промпт


def test_нормы_по_умолчанию_совпадают_с_выдачей_дневника():
    """Один источник на экран и на промпт: два набора чисел разошлись бы
    молча — кольцо рисовало бы одно, ассистент называл бы другое."""
    assert main.nut_goals(None) == main.NUT_DEFAULT_GOALS
    assert main.nut_goals(ПрофильЗаглушка())["protein"] == 150



"""Дата записи в дневник: проверка вместо подстановки.

Почему на это есть тесты. До навигации по дням дневник знал один день —
сегодня, — и дата в теле запроса ни на что не влияла. Теперь она решает,
в какой день ляжет еда, и ошибка здесь МОЛЧАЛИВАЯ в обе стороны:

  · `data.get("date", сегодня)` подставляет умолчание только когда ключа
    НЕТ. `null`, пустая строка и мусор ложились в текстовую колонку
    `log_date` как есть — запись не терялась, но не попадала ни в один
    день и становилась невидимой;
  · молчаливая замена кривой даты на сегодняшнюю не лучше: человек,
    отмотавший дневник на вчера, получил бы запись в сегодня и зелёную
    галочку. Это и есть порча данных без единого признака.

База не поднимается: DB_PATH уводится в tmp ДО импорта main.
"""

import os
import sys
import tempfile
from datetime import datetime, timedelta
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_дни.db")

import main            # noqa: E402


def день(сдвиг):
    return (datetime.now().date() + timedelta(days=сдвиг)).strftime("%Y-%m-%d")


def test_обычная_дата_проходит():
    assert main._нут_дата(день(0)) == день(0)
    assert main._нут_дата(день(-3)) == день(-3)
    assert main._нут_дата(день(3)) == день(3)


def test_пусто_это_сегодня():
    """Ключа нет — берём сегодня. Так вели себя все три эндпоинта до правки,
    и ломать это было бы регрессом для старых клиентов."""
    assert main._нут_дата(None) == день(0)
    assert main._нут_дата("") == день(0)


def test_кривой_формат_отвергается_а_не_подменяется():
    """Главное правило. Раньше такая строка уезжала в базу как есть."""
    for мусор in ("14.08.2026", "вчера", "2026-13-01", "0", "2026-08-14T10:00"):
        with pytest.raises(ValueError) as e:
            main._нут_дата(мусор)
        assert "YYYY-MM-DD" in str(e.value)


def test_дата_приводится_к_канонической_форме():
    """`strptime` принимает «2026-8-14» наравне с «2026-08-14», а log_date —
    колонка ТЕКСТОВАЯ и сравнивается строкой. Записанная как есть, такая
    дата не совпала бы ни с одним днём выдачи — запись стала бы невидимой,
    оставшись в базе. Отказывать не за что, дата разобралась однозначно."""
    д = datetime.now().date()
    кривовато = f"{д.year}-{д.month}-{д.day}"          # без ведущих нулей
    assert main._нут_дата(кривовато) == д.strftime("%Y-%m-%d")


def test_не_строка_тоже_отвергается():
    """`null` в JSON приходит как None и раньше означал бы «сегодня»,
    а число — падение внутри strptime."""
    for значение in (0, 20260814, [], {}, True):
        with pytest.raises(ValueError):
            main._нут_дата(значение)


def test_границы_окна_включительно():
    """Ровно ±NUT_DAY_RANGE принимается: полоска дней предлагает эти дни,
    и сервер обязан их принять. Иначе крайний кружок был бы нажимаем,
    а запись в него падала бы с ошибкой."""
    R = main.NUT_DAY_RANGE
    assert main._нут_дата(день(-R)) == день(-R)
    assert main._нут_дата(день(R)) == день(R)


def test_за_окном_отвергается():
    """Отрицательный контроль к тесту выше: на день дальше — отказ."""
    R = main.NUT_DAY_RANGE
    for сдвиг in (-R - 1, R + 1, 400, -400):
        with pytest.raises(ValueError) as e:
            main._нут_дата(день(сдвиг))
        assert str(R) in str(e.value)


def test_имя_поля_попадает_в_текст():
    """Сообщение читает человек в интерфейсе — оно должно называть,
    какое поле не понравилось."""
    with pytest.raises(ValueError) as e:
        main._нут_дата("мусор", поле="log_date")
    assert "log_date" in str(e.value)


def test_окно_сервера_и_полоски_дней_это_одно_число():
    """NUT_DAY_RANGE — единственный источник. Второе число в шаблоне
    разошлось бы с этим молча: полоска предлагала бы день, который сервер
    не принимает, и отказ выглядел бы поломкой."""
    шаблон = (Path(__file__).resolve().parent.parent
              / "templates" / "nutrition.html").read_text(encoding="utf-8")
    # в шаблоне диапазон не зашит числом, а приезжает с сервера
    assert "d.range" in шаблон, "полоска дней обязана брать диапазон у сервера"
    assert main.NUT_DAY_RANGE == 7

def записать_еду(uid, день, ккал):
    db = SessionLocal()
    db.add(FoodLog(user_id=uid, log_date=день, meal_type="lunch",
                   food_name="Тест", grams=100, calories=ккал,
                   protein=ккал / 20, fat=ккал / 40, carbs=ккал / 10))
    db.commit()
    db.close()


def норму_в_журнал(uid, день, ккал):
    """Строка журнала напрямую — так выглядит норма, записанная в прошлом."""
    db = SessionLocal()
    db.add(NutritionGoalPeriod(user_id=uid, effective_from=день, calories=ккал,
                               protein=100, fat=60, carbs=200, water_ml=2000,
                               origin="анкета"))
    db.commit()
    db.close()


def журнал(uid):
    db = SessionLocal()
    строки = [(п.effective_from, п.calories) for п in
              db.query(NutritionGoalPeriod).filter(
                  NutritionGoalPeriod.user_id == uid).order_by(
                  NutritionGoalPeriod.effective_from).all()]
    db.close()
    return строки


def дневник(c, день):
    r = c.get(f"/nutrition/api/diary?date={день}")
    assert r.status_code == 200, r.text
    return r.json()


def месяц(c, ym):
    r = c.get(f"/nutrition/api/history/month?month={ym}")
    assert r.status_code == 200, r.text
    return r.json()


def анкета(c, **поля):
    тело = {"gender": "male", "age": 34, "weight_kg": 82.0, "height_cm": 181.0,
            "goal": "maintain", "activity_level": "moderate"}
    тело.update(поля)
    r = c.post("/nutrition/api/profile", json=тело)
    assert r.status_code == 200, r.text
    return r.json()


# ── Главное: прошлое не переписывается ───────────────────────────────────────

def test_прошлый_день_считается_по_норме_того_дня(клиент):
    """У 23 июня своя норма 2100, у сегодня — 2600. День берёт свою."""
    норму_в_журнал(клиент.uid, "2026-06-01", 2100)
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-06-23", 1050)

    д = дневник(клиент, "2026-06-23")
    assert д["goals"]["calories"] == 2100
    assert д["goals_meta"] == {"known": True, "from": "2026-06-01",
                               "is_current": False}


def test_смена_анкеты_не_меняет_прошлое(клиент):
    """Главный дефект задачи. Съеденное то же, знаменатель обязан остаться."""
    норму_в_журнал(клиент.uid, "2026-06-01", 2100)
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-06-23", 1050)

    до = дневник(клиент, "2026-06-23")
    месяц_до = месяц(клиент, "2026-06")
    анкета(клиент, goal="gain", weight_kg=90.0)
    после = дневник(клиент, "2026-06-23")
    месяц_после = месяц(клиент, "2026-06")

    assert до == после, "прошлый день изменился от смены анкеты"
    assert месяц_до["days"] == месяц_после["days"]


def test_смена_анкеты_меняет_сегодня(клиент):
    """Обратная сторона: сегодняшний день ещё идёт, и он обязан
    пересчитаться. Тест парный к предыдущему — без него «ничего
    не изменилось» проходило бы и у кода, который не меняет вообще ничего."""
    было = дневник(клиент, "2026-08-20")["goals"]["calories"]
    новые = анкета(клиент, goal="gain", weight_kg=90.0)["targets"]["calories"]
    стало = дневник(клиент, "2026-08-20")["goals"]["calories"]
    assert стало == новые and стало != было



"""ИСТОРИЯ НОРМ КБЖУ (задача 95): прошлый день считается по норме, что
действовала ТОГДА.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО. Норма — знаменатель у каждой
полоски, кольца и процента на экране дневника. Пока она хранилась одним
текущим значением, смена цели переписывала ПРОШЛОЕ: замер на живых данных
2026-08-20 — день 23 июня с 3586 съеденными ккал показывал 163% от нормы,
а после смены цели с «похудение» на «набор» тот же день стал показывать
112%. Ни одна запись о еде при этом не менялась.

Глазами это не ловится в принципе: полоска нарисована, число рядом стоит,
экран выглядит исправным что до правки, что после. Отличить «норма была
такая» от «норма стала такой» можно, только зная, какой она была, — то есть
ровно то, чего в базе и не было.

Три способа соврать, каждый закрыт своим тестом:

  · посчитать прошлый день по СЕГОДНЯШНЕЙ норме — исходный дефект;
  · подставить сегодняшнюю норму дню, которого журнал не застал, — так
    делала первая версия этой правки, и отрицательный контроль её завалил:
    смена цели по-прежнему меняла показанное за 23 июня, просто рядом
    появлялась оговорка. Правильный ответ — «нормы нет», а не «вот
    сегодняшняя, имейте в виду»;
  · завести на один день ДВЕ строки журнала — тогда правильного ответа
    на вопрос «какая норма у этого дня» не существует вовсе.

Приложение поднимается настоящим TestClient на временной базе: норму
достаёт запрос к журналу, и проверять его подделкой в Python значило бы
проверять не то, что работает на проде.
"""


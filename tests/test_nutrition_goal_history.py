from datetime import date
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ.setdefault(
    "DB_PATH", str(Path(tempfile.gettempdir()) / f"hh_goals_{uuid.uuid4().hex}.db"))

import main                                                    # noqa: E402
from database import (SessionLocal, User, FoodLog,             # noqa: E402
                      NutritionProfile, NutritionGoalPeriod)
from fastapi.testclient import TestClient                      # noqa: E402
from auth import hash_password, create_token                   # noqa: E402

СЕГОДНЯ = date(2026, 8, 20)


@pytest.fixture()
def клиент():
    main.init_db()
    db = SessionLocal()
    u = User(email=f"goals-{uuid.uuid4().hex[:8]}@local.test",
             password_hash=hash_password("x"), is_verified=True,
             timezone="Europe/Moscow")
    db.add(u)
    db.commit()
    db.refresh(u)
    db.add(NutritionProfile(user_id=u.id, gender="male", age=34, weight_kg=82.0,
                            height_cm=181.0, goal="maintain",
                            activity_level="moderate",
                            calorie_goal=2600, protein_goal=164, fat_goal=72,
                            carb_goal=330, water_goal_ml=2870))
    db.commit()
    uid = u.id
    db.close()

    было = main._сегодня
    main._сегодня = lambda user: СЕГОДНЯ
    c = TestClient(main.app)
    c.cookies.set("access_token", create_token(uid))
    c.uid = uid
    yield c
    main._сегодня = было


def записать_еду(uid, день, ккал):
    db = SessionLocal()
    db.add(FoodLog(user_id=uid, log_date=день, meal_type="lunch",
                   food_name="Тест", grams=100, calories=ккал,
                   protein=ккал / 20, fat=ккал / 40, carbs=ккал / 10))
    db.commit()
    db.close()


def норму_в_журнал(uid, день, ккал):
    """Строка журнала напрямую — так выглядит норма, записанная в прошлом."""
    db = SessionLocal()
    db.add(NutritionGoalPeriod(user_id=uid, effective_from=день, calories=ккал,
                               protein=100, fat=60, carbs=200, water_ml=2000,
                               origin="анкета"))
    db.commit()
    db.close()


def журнал(uid):
    db = SessionLocal()
    строки = [(п.effective_from, п.calories) for п in
              db.query(NutritionGoalPeriod).filter(
                  NutritionGoalPeriod.user_id == uid).order_by(
                  NutritionGoalPeriod.effective_from).all()]
    db.close()
    return строки


def дневник(c, день):
    r = c.get(f"/nutrition/api/diary?date={день}")
    assert r.status_code == 200, r.text
    return r.json()


def месяц(c, ym):
    r = c.get(f"/nutrition/api/history/month?month={ym}")
    assert r.status_code == 200, r.text
    return r.json()


def анкета(c, **поля):
    тело = {"gender": "male", "age": 34, "weight_kg": 82.0, "height_cm": 181.0,
            "goal": "maintain", "activity_level": "moderate"}
    тело.update(поля)
    r = c.post("/nutrition/api/profile", json=тело)
    assert r.status_code == 200, r.text
    return r.json()


# ── Главное: прошлое не переписывается ───────────────────────────────────────

def test_прошлый_день_считается_по_норме_того_дня(клиент):
    """У 23 июня своя норма 2100, у сегодня — 2600. День берёт свою."""
    норму_в_журнал(клиент.uid, "2026-06-01", 2100)
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-06-23", 1050)

    д = дневник(клиент, "2026-06-23")
    assert д["goals"]["calories"] == 2100
    assert д["goals_meta"] == {"known": True, "from": "2026-06-01",
                               "is_current": False}


def test_смена_анкеты_не_меняет_прошлое(клиент):
    """Главный дефект задачи. Съеденное то же, знаменатель обязан остаться."""
    норму_в_журнал(клиент.uid, "2026-06-01", 2100)
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-06-23", 1050)

    до = дневник(клиент, "2026-06-23")
    месяц_до = месяц(клиент, "2026-06")
    анкета(клиент, goal="gain", weight_kg=90.0)
    после = дневник(клиент, "2026-06-23")
    месяц_после = месяц(клиент, "2026-06")

    assert до == после, "прошлый день изменился от смены анкеты"
    assert месяц_до["days"] == месяц_после["days"]


def test_смена_анкеты_меняет_сегодня(клиент):
    """Обратная сторона: сегодняшний день ещё идёт, и он обязан
    пересчитаться. Тест парный к предыдущему — без него «ничего
    не изменилось» проходило бы и у кода, который не меняет вообще ничего."""
    было = дневник(клиент, "2026-08-20")["goals"]["calories"]
    новые = анкета(клиент, goal="gain", weight_kg=90.0)["targets"]["calories"]
    стало = дневник(клиент, "2026-08-20")["goals"]["calories"]
    assert стало == новые and стало != было


# ── День, которого журнал не застал ──────────────────────────────────────────

def test_день_до_журнала_не_получает_никакой_нормы(клиент):
    """`goals: null`, а НЕ сегодняшняя норма и НЕ нули.

    Сегодняшняя означала бы утверждение «она действовала в мае», которого
    никто не проверял; нули означали бы «норма была ноль». Оба варианта
    выглядят на экране одинаково правдоподобно, и в этом вся беда."""
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-05-20", 1800)

    д = дневник(клиент, "2026-05-20")
    assert д["goals"] is None
    assert д["goals_meta"]["known"] is False
    assert д["totals"]["calories"] == 1800, "съеденное обязано остаться"


def test_день_до_журнала_не_шелохнётся_от_смены_анкеты(клиент):
    """Проба, которая завалила первую версию правки: там подставлялась
    сегодняшняя норма с оговоркой, и смена цели её меняла."""
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-05-20", 1800)

    до = дневник(клиент, "2026-05-20")
    анкета(клиент, goal="lose", weight_kg=70.0)
    assert дневник(клиент, "2026-05-20") == до


def test_клетка_календаря_без_своей_нормы_берёт_ДЕЙСТВУЮЩУЮ(клиент):
    """РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-08-21 — частичная отмена правила задачи 95,
    и только в КАЛЕНДАРЕ.

    Здесь стояло обратное: `goal is None`, полоски у клетки нет. Правило
    верно для экрана ОДНОГО дня и остаётся в силе (тест ниже), но
    календарь отвечает на другой вопрос — «как шёл месяц целиком».
    У живого владельца записанной нормы нет ни у одного исторического
    дня, и календарь выходил без единой заливки.

    Цена принята и НАЗВАНА: доля старого дня считается не от нормы того
    дня. Поле `goal_own` эту цену и держит — по нему подпись под сводкой
    говорит, у скольких дней знаменатель подставлен."""
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-05-20", 1800)
    м = месяц(клиент, "2026-05")
    клетка = м["days"]["2026-05-20"]
    assert клетка["goal"] == 2600           # подставлена действующая
    assert клетка["goal_own"] is False      # и это НАЗВАНО
    assert клетка["calories"] == 1800
    assert м["goals_unknown_days"] == 1


def test_клетка_со_СВОЕЙ_нормой_помечена_своей(клиент):
    """Отрицательный контроль к предыдущему: без него `goal_own: False`
    у всех подряд прошёл бы незамеченным, и подпись под сводкой считала
    бы подставленным каждый день."""
    норму_в_журнал(клиент.uid, "2026-05-01", 2100)
    записать_еду(клиент.uid, "2026-05-20", 1800)
    м = месяц(клиент, "2026-05")
    assert м["days"]["2026-05-20"]["goal"] == 2100
    assert м["days"]["2026-05-20"]["goal_own"] is True
    assert м["goals_unknown_days"] == 0


def test_нормы_нет_ВООБЩЕ_знаменателя_у_клетки_нет(клиент):
    """Случай «ни записанной, ни действующей»: анкеты нет вовсе.

    Показать тут долю было бы хуже, чем не показать: `nut_goals(None)`
    отдаёт `NUT_DEFAULT_GOALS`, то есть число, которого человек никогда
    не видел и не задавал. Доля от него — выдумка со знаком процента.

    Клетка получает `goal: null`, экран рисует ПУСТУЮ рамку: «записи
    есть, считать не от чего». От «съедено ноль» это отличается тем,
    что у второго заливка есть — в минимальную ширину (nutrition.css)."""
    db = SessionLocal()
    db.query(NutritionProfile).filter(
        NutritionProfile.user_id == клиент.uid).delete()
    db.commit()
    db.close()
    записать_еду(клиент.uid, "2026-05-20", 1800)
    клетка = месяц(клиент, "2026-05")["days"]["2026-05-20"]
    assert клетка["goal"] is None
    assert клетка["goal_own"] is False
    assert клетка["calories"] == 1800


def test_анкета_есть_знаменатель_есть_ОТРИЦАТЕЛЬНЫЙ_КОНТРОЛЬ(клиент):
    """Без него предыдущий тест прошёл бы и на коде, который всегда
    отдаёт null, — то есть не проверял бы ничего."""
    записать_еду(клиент.uid, "2026-05-20", 1800)
    assert месяц(клиент, "2026-05")["days"]["2026-05-20"]["goal"] == 2600


def test_кольцо_дня_без_нормы_по_прежнему_МОЛЧИТ(клиент):
    """Задача 95 отменена ЧАСТИЧНО: экран одного дня не изменился.

    Без этого теста «частично» превратилось бы в «целиком» первой же
    правкой, и никто бы не заметил — оба поведения выглядят исправными."""
    норму_в_журнал(клиент.uid, "2026-08-20", 2600)
    записать_еду(клиент.uid, "2026-05-20", 1800)
    д = дневник(клиент, "2026-05-20")
    assert д["goals"] is None
    assert д["totals"]["calories"] == 1800


def test_сегодня_норму_имеет_даже_при_пустом_журнале(клиент):
    """Единственное исключение, и оно не подстановка: «какая норма сейчас» —
    прямой ответ из анкеты, а не утверждение о прошлом. Без него новый
    пользователь увидел бы дневник без единой нормы."""
    assert журнал(клиент.uid) == []
    д = дневник(клиент, "2026-08-20")
    assert д["goals"]["calories"] == 2600
    assert д["goals_meta"]["known"] is True


# ── Запись в журнал ──────────────────────────────────────────────────────────

def test_сохранение_анкеты_заводит_строку_на_сегодня(клиент):
    новые = анкета(клиент, goal="lose")["targets"]
    assert журнал(клиент.uid) == [("2026-08-20", новые["calories"])]


def test_две_смены_за_день_дают_одну_строку(клиент):
    """У дня ровно одна норма: съеденное за день суммируется целиком,
    и делить утреннюю половину на одну норму, а вечернюю на другую нечем."""
    анкета(клиент, goal="lose")
    последние = анкета(клиент, goal="gain", activity_level="sedentary")["targets"]
    ж = журнал(клиент.uid)
    assert len(ж) == 1, f"на один день заведено строк: {len(ж)}"
    assert ж[0] == ("2026-08-20", последние["calories"])
    assert дневник(клиент, "2026-08-20")["goals"]["calories"] == последние["calories"]


def test_сохранение_анкеты_не_трогает_прошлые_строки(клиент):
    норму_в_журнал(клиент.uid, "2026-06-01", 2100)
    анкета(клиент, goal="gain")
    ж = журнал(клиент.uid)
    assert ("2026-06-01", 2100) in ж
    assert len(ж) == 2


def test_дата_строки_в_поясе_пользователя(клиент, monkeypatch):
    """`effective_from` берётся у `_сегодня(user)`, а не у часов процесса.
    На Fly процесс живёт в UTC, и в 01:30 по Москве строка ушла бы
    во вчерашний день — девятый источник неверной даты (§5.0.6)."""
    monkeypatch.setattr(main, "_сегодня", lambda user: date(2026, 8, 21))
    анкета(клиент, goal="lose")
    assert журнал(клиент.uid)[-1][0] == "2026-08-21"



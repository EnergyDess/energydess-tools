# ── Разбор журнала ───────────────────────────────────────────────────────────

def test_берётся_последняя_запись_не_позже_дня(клиент):
    """День границы берёт НОВУЮ норму (она действует С этого дня),
    день перед ней — предыдущую."""
    класс = type("П", (), {})

    def п(дата, ккал):
        o = класс()
        o.effective_from = дата
        o.calories = ккал
        o.protein = o.fat = o.carbs = o.water_ml = 0
        return o

    журнал_ = [п("2026-06-01", 2100), п("2026-07-01", 2300), п("2026-08-01", 2600)]
    assert main.норма_на_день(журнал_, "2026-06-30")[0]["calories"] == 2100
    assert main.норма_на_день(журнал_, "2026-07-01")[0]["calories"] == 2300
    assert main.норма_на_день(журнал_, "2026-07-31")[0]["calories"] == 2300
    assert main.норма_на_день(журнал_, "2026-08-01")[0]["calories"] == 2600
    assert main.норма_на_день(журнал_, "2026-05-31")[0] is None

def test_сохранение_анкеты_заводит_строку_на_сегодня(клиент):
    новые = анкета(клиент, goal="lose")["targets"]
    assert журнал(клиент.uid) == [("2026-08-20", новые["calories"])]


def test_две_смены_за_день_дают_одну_строку(клиент):
    """У дня ровно одна норма: съеденное за день суммируется целиком,
    и делить утреннюю половину на одну норму, а вечернюю на другую нечем."""
    анкета(клиент, goal="lose")
    последние = анкета(клиент, goal="gain", activity_level="sedentary")["targets"]
    ж = журнал(клиент.uid)
    assert len(ж) == 1, f"на один день заведено строк: {len(ж)}"
    assert ж[0] == ("2026-08-20", последние["calories"])
    assert дневник(клиент, "2026-08-20")["goals"]["calories"] == последние["calories"]


def test_сохранение_анкеты_не_трогает_прошлые_строки(клиент):
    норму_в_журнал(клиент.uid, "2026-06-01", 2100)
    анкета(клиент, goal="gain")
    ж = журнал(клиент.uid)
    assert ("2026-06-01", 2100) in ж
    assert len(ж) == 2


def test_дата_строки_в_поясе_пользователя(клиент, monkeypatch):
    """`effective_from` берётся у `_сегодня(user)`, а не у часов процесса.
    На Fly процесс живёт в UTC, и в 01:30 по Москве строка ушла бы
    во вчерашний день — девятый источник неверной даты (§5.0.6)."""
    monkeypatch.setattr(main, "_сегодня", lambda user: date(2026, 8, 21))
    анкета(клиент, goal="lose")
    assert журнал(клиент.uid)[-1][0] == "2026-08-21"



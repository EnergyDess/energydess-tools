def test_правка_отвечает_датой_и_приёмом(клиент):
    записать(клиент.uid, "2026-08-06", 500)
    db = SessionLocal()
    # Фильтр по пользователю обязателен: база у тестов одна на файл,
    # и без него берётся запись предыдущего теста, заведённая другим людям
    id_ = db.query(FoodLog).filter(FoodLog.user_id == клиент.uid,
                                   FoodLog.log_date == "2026-08-06").first().id
    db.close()
    r = клиент.put(f"/nutrition/api/log-food/{id_}",
                   json={"grams": 50, "calories": 100, "protein": 1,
                         "fat": 1, "carbs": 1, "meal_type": "snack"})
    assert r.json() == {"ok": True, "date": "2026-08-06", "meal_type": "snack"}


def test_вода_и_еда_имеют_одно_окно_записи(клиент):
    """Разъехавшись, окна дали бы день, в котором еду записать можно,
    а воду нельзя — при том что это одна запись одного дня. Замер до
    правки: выбрав в календаре 4 августа (13 дней назад) и вернувшись
    в дневник, кнопка «+200» отвечала отказом."""
    день = "2026-06-22"
    еда = клиент.post("/nutrition/api/log-food", json={
        "name": "Творог", "grams": 100, "calories": 100, "protein": 18,
        "fat": 2, "carbs": 3, "meal_type": "breakfast", "date": день})
    вода = клиент.post("/nutrition/api/water", json={"amount_ml": 200, "date": день})
    assert (еда.status_code, вода.status_code) == (200, 200)


def test_запись_в_день_двухмесячной_давности(клиент):
    """Добавление из истории. До правки окно записи было тем же, что
    у полоски дней, и такой запрос отвергался бы."""

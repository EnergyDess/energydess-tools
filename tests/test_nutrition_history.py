# ── Удаление отличимо от отказа ──────────────────────────────────────────────

def test_удаление_отвечает_датой(клиент):
    """Дата нужна, чтобы перерисовать ТОТ день, который изменился: удаляют
    и из дневника, и из истории, и открыт при этом может быть третий."""
    записать(клиент.uid, "2026-08-06", 500)
    db = SessionLocal()
    # Фильтр по пользователю обязателен: база у тестов одна на файл,
    # и без него берётся запись предыдущего теста, заведённая другим людям
    id_ = db.query(FoodLog).filter(FoodLog.user_id == клиент.uid,
                                   FoodLog.log_date == "2026-08-06").first().id
    db.close()
    r = клиент.delete(f"/nutrition/api/log-food/{id_}")
    assert r.status_code == 200
    assert r.json()["date"] == "2026-08-06"


def test_удаление_несуществующего_это_404(клиент):
    """Прежний `{"ok": true}` на любой исход означал, что интерфейс рисует
    «Удалено» и тогда, когда в базе всё осталось на месте."""
    r = клиент.delete("/nutrition/api/log-food/99999999")
    assert r.status_code == 404
    assert "error" in r.json()



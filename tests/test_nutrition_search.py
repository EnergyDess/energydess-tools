"""Области поиска, группировка недавних и удаление налитой воды.

Почему на это есть тесты. Все три вещи отказывают МОЛЧА:

  · вкладка стала ОБЛАСТЬЮ поиска, и отбор по запросу теперь делает
    сервер. Отбор, который сравнивает регистр как SQL, просто не находит
    кириллицу — выдача выходит пустой, и выглядит это как «у вас такого
    не было», а не как ошибка;
  · «Недавние» раскладываются по приёмам пищи. Дедупликация по одному
    имени схлопнула бы творог, съеденный и на завтрак, и на ужин, в один
    блок — то есть утверждала бы, что его едят только на завтрак;
  · удаление порции воды раньше отвечало `{"ok": true}` на любой исход,
    включая чужой и несуществующий id. Снаружи «удалено» и «не удалено»
    выглядели одинаково.

База не поднимается целиком: DB_PATH уводится в tmp ДО импорта main.
"""

import asyncio
import json
import os
import sys
import tempfile
from datetime import datetime, timedelta
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_поиск.db")

import main                                                    # noqa: E402
from database import (CustomRecipe, FoodLog, SessionLocal,     # noqa: E402
                      WaterLog, init_db)

init_db()

USER_ID = 900001
ДРУГОЙ = 900002


class Юзер:
    def __init__(self, uid=USER_ID):
        self.id = uid


def тело(ответ):
    return json.loads(ответ.body)


def позвать(корутина):
    return тело(asyncio.run(корутина))


@pytest.fixture
def сессия():
    db = SessionLocal()
    for таблица in (FoodLog, WaterLog, CustomRecipe):
        db.query(таблица).filter(таблица.user_id.in_([USER_ID, ДРУГОЙ])).delete(
            synchronize_session=False)
    db.commit()
    yield db
    for таблица in (FoodLog, WaterLog, CustomRecipe):
        db.query(таблица).filter(таблица.user_id.in_([USER_ID, ДРУГОЙ])).delete(
            synchronize_session=False)
    db.commit()
    db.close()


def еда(db, имя, приём, бренд="", когда=0, uid=USER_ID):
    """Строка истории. `когда` — сдвиг в минутах назад: порядок «недавних»
    считается по created_at, и без явного времени он был бы случайным."""
    lg = FoodLog(user_id=uid, log_date="2026-08-14", meal_type=приём,
                 food_name=имя, brand=бренд or None, grams=100,
                 calories=100, protein=10, fat=5, carbs=20,
                 created_at=datetime.utcnow() - timedelta(minutes=когда))
    db.add(lg)
    db.commit()
    return lg


# ── Отбор по запросу ──────────────────────────────────────────────────────

def test_кириллица_сравнивается_без_учёта_регистра():
    """Главная ловушка отбора. ilike в SQLite кириллицу к нижнему регистру
    не приводит, и «Творог» не нашёлся бы по «творог» — выдача вышла бы
    пустой без единого признака ошибки."""
    class Строка:
        food_name, brand = "Творог Зернёный", "ПРОСТОКВАШИНО"
    assert main._нут_совпало(Строка, "творог")
    assert main._нут_совпало(Строка, "ЗЕРНЁНЫЙ".lower())


def test_запрос_ищется_и_в_бренде():
    """«вкусвилл» — это запрос про производителя, и находить он должен
    его товары, а не ничего."""
    class Строка:
        food_name, brand = "Биточек куриный", "ВкусВилл"
    assert main._нут_совпало(Строка, "вкусвилл")
    assert not main._нут_совпало(Строка, "перекрёсток")


def test_пустой_запрос_пропускает_всё():
    """Область без запроса — это просто список. Пустая строка не должна
    вести себя как фильтр, иначе вкладка открывалась бы пустой."""
    class Строка:
        food_name, brand = "Что угодно", None
    assert main._нут_совпало(Строка, "")


# ── Недавние: группировка по приёмам ──────────────────────────────────────

def test_недавние_разложены_по_приёмам(сессия):
    еда(сессия, "Овсянка", "breakfast", когда=3)
    еда(сессия, "Биточек", "lunch", когда=2)
    d = позвать(main.nut_recent(q="", user=Юзер(), db=сессия))
    assert set(d["by_meal"]) == {"breakfast", "lunch"}
    assert [i["name"] for i in d["by_meal"]["breakfast"]] == ["Овсянка"]


def test_приём_без_записей_в_выдаче_отсутствует(сессия):
    """Пустой блок на экране не сообщает ничего: предлагать в нём нечего.
    Это отличается от карточки дня, где пустой приём значит «недоедено»."""
    еда(сессия, "Овсянка", "breakfast")
    d = позвать(main.nut_recent(q="", user=Юзер(), db=сессия))
    assert "dinner" not in d["by_meal"] and "snack" not in d["by_meal"]


def test_одно_блюдо_в_двух_приёмах_попадает_в_оба(сессия):
    """Ключ дедупликации включает приём. По одному имени творог схлопнулся
    бы в тот приём, где его съели первым, — то есть выдача утверждала бы,
    что на ужин его не едят."""
    еда(сессия, "Творог", "breakfast", когда=2)
    еда(сессия, "Творог", "dinner", когда=1)
    d = позвать(main.nut_recent(q="", user=Юзер(), db=сессия))
    assert [i["name"] for i in d["by_meal"]["breakfast"]] == ["Творог"]
    assert [i["name"] for i in d["by_meal"]["dinner"]] == ["Творог"]
    # А в плоском списке — один раз: там приём пищи не значит ничего
    assert [i["name"] for i in d["results"]] == ["Творог"]


def test_плоский_список_остался_для_окна_ингредиентов(сессия):
    """`results` питает подбор ингредиента рецепта, и убрать его, добавив
    `by_meal`, значило бы сломать другое окно молча."""
    еда(сессия, "Овсянка", "breakfast")
    d = позвать(main.nut_recent(q="", user=Юзер(), db=сессия))
    assert d["results"] and "calories" in d["results"][0]


def test_недавние_отбираются_запросом(сессия):
    еда(сессия, "Овсянка", "breakfast", когда=2)
    еда(сессия, "Биточек куриный", "lunch", когда=1)

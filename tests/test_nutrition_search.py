# ── Вода: удаление порции ─────────────────────────────────────────────────

def налить(db, мл, дата="2026-08-14", uid=USER_ID):
    w = WaterLog(user_id=uid, log_date=дата, amount_ml=мл)
    db.add(w)
    db.commit()
    return w


def test_удаление_возвращает_дату_и_новый_итог(сессия):
    """Итог считается сервером и приезжает в ответе. Вычитание на клиенте
    показало бы новую сумму и тогда, когда запись не удалилась."""
    налить(сессия, 200)
    лишняя = налить(сессия, 500)
    d = позвать(main.nut_delete_water(лишняя.id, user=Юзер(), db=сессия))
    assert d == {"ok": True, "date": "2026-08-14", "total_ml": 200}


def test_удаление_несуществующей_порции_это_404(сессия):
    """Прежний ответ был `{"ok": true}` на любой исход. Интерфейс рисовал
    успех, а в базе всё оставалось на месте."""
    ответ = asyncio.run(main.nut_delete_water(10_000_001, user=Юзер(), db=сессия))
    assert ответ.status_code == 404


def test_чужую_порцию_удалить_нельзя(сессия):
    """И отказ тот же 404, а не 403: отказ по правам подтвердил бы, что
    такая запись существует (CLAUDE.md §5.1)."""
    чужая = налить(сессия, 300, uid=ДРУГОЙ)
    ответ = asyncio.run(main.nut_delete_water(чужая.id, user=Юзер(), db=сессия))
    assert ответ.status_code == 404
    assert сессия.query(WaterLog).filter(WaterLog.id == чужая.id).first()


def test_удаление_не_трогает_другие_дни(сессия):
    """Удаление работает на любом дне, в том числе отмотанном, и считает
    итог того дня, к которому относилась запись."""
    налить(сессия, 200, дата="2026-08-13")
    вчерашняя = налить(сессия, 500, дата="2026-08-13")
    налить(сессия, 700, дата="2026-08-14")
    d = позвать(main.nut_delete_water(вчерашняя.id, user=Юзер(), db=сессия))
    assert d["date"] == "2026-08-13" and d["total_ml"] == 200
    итог_сегодня = sum(w.amount_ml for w in сессия.query(WaterLog).filter(
        WaterLog.user_id == USER_ID, WaterLog.log_date == "2026-08-14").all())
    assert итог_сегодня == 700

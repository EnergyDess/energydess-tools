"""«Сегодня» дневника считается в поясе пользователя, а не в поясе процесса.

ЧТО СЛОМАЛОСЬ И КАК ЭТО ВЫГЛЯДЕЛО. Сервер брал день через `datetime.now()`,
то есть в поясе процесса. На Fly это UTC, а человек живёт в своём поясе —
и каждую ночь с полуночи до смещения (в Москве до 03:00) дневник считал,
что идут вчерашние сутки. Воспроизведено живым прогоном 2026-08-15 в 00:57
по Москве: сайдбар показывал «Сб, 15 Авг.» (брал часы браузера), полоска
дней рисовала «сегодня» на 14-м, а 15-е — БУДУЩИМ днём с пунктиром.
Запись, сделанная в час ночи, уходила во вчера без единого признака.

ПОЧЕМУ ТЕСТ НА ЧИСТОЙ ФУНКЦИИ, А НЕ НА `_сегодня`. Граница суток —
единственное место, где дефект и жил, а прогон тестов в три часа дня
о поведении в 00:30 не говорит ничего. Поэтому момент времени передаётся
явно (`_день_в_поясе`), и проверяются обе стороны полуночи при
положительном и при отрицательном смещении.

База не поднимается: DB_PATH уводится в tmp ДО импорта main.
"""

import os
import sys
import tempfile
from datetime import datetime, timezone, date
from pathlib import Path
from zoneinfo import ZoneInfo

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_поясa.db")

import main            # noqa: E402


class Человек:
    """Ровно то, что читает `_пояс`: id для сообщения и сам пояс."""
    def __init__(self, tz):
        self.id = 1
        self.timezone = tz


def utc(строка):
    return datetime.strptime(строка, "%Y-%m-%d %H:%M").replace(tzinfo=timezone.utc)


# ── Граница суток ────────────────────────────────────────────────────────────

@pytest.mark.parametrize("момент, зона, ожидание, что", [
    # UTC+3: полночь наступает на три часа раньше, чем в UTC
    ("2026-08-14 20:30", "Europe/Moscow",       date(2026, 8, 14), "23:30 местного"),
    ("2026-08-14 21:30", "Europe/Moscow",       date(2026, 8, 15), "00:30 местного"),
    # тот самый час, на котором дефект и поймали: 00:57 по Москве
    ("2026-08-14 21:57", "Europe/Moscow",       date(2026, 8, 15), "00:57 местного"),
    # отрицательное смещение: полночь наступает ПОЗЖЕ, чем в UTC
    ("2026-08-15 06:30", "America/Los_Angeles", date(2026, 8, 14), "23:30 местного"),
    ("2026-08-15 07:30", "America/Los_Angeles", date(2026, 8, 15), "00:30 местного"),
    # UTC+12: местная дата обгоняет UTC почти на полсуток
    ("2026-08-14 11:30", "Asia/Kamchatka",      date(2026, 8, 14), "23:30 местного"),
    ("2026-08-14 12:30", "Asia/Kamchatka",      date(2026, 8, 15), "00:30 местного"),
])
def test_граница_суток(момент, зона, ожидание, что):
    assert main._день_в_поясе(utc(момент), ZoneInfo(зона)) == ожидание, что


def test_один_момент_даёт_разные_дни_в_разных_поясах():
    """Отрицательный контроль к тестам выше: если бы пояс не учитывался,
    все три ответа совпали бы и тесты границы проходили бы по случайности."""
    м = utc("2026-08-14 21:57")          # 00:57 по Москве
    дни = {з: main._день_в_поясе(м, ZoneInfo(з))
           for з in ("UTC", "Europe/Moscow", "America/Los_Angeles")}
    assert дни["UTC"] == date(2026, 8, 14)
    assert дни["Europe/Moscow"] == date(2026, 8, 15)
    assert дни["America/Los_Angeles"] == date(2026, 8, 14)
    assert len(set(дни.values())) == 2, "пояс обязан менять ответ"


# ── Разбор пояса из профиля ──────────────────────────────────────────────────

def test_пояс_берётся_из_профиля():
    assert main._пояс(Человек("Europe/Moscow")) == ZoneInfo("Europe/Moscow")


@pytest.mark.parametrize("значение", [None, "", "   "])
def test_пустой_пояс_это_utc(значение):
    """Прежнее поведение для тех, у кого пояс не выбран. Не «пояс сервера»,
    а именно UTC: пояс сервера меняется от машины к машине, и дневник
    у одного человека зависел бы от того, где его считают."""
    assert main._пояс(Человек(значение)) == ZoneInfo("UTC")


def test_неизвестный_пояс_не_роняет_и_говорит_об_этом(capsys):
    """Мусор в колонке уводится в UTC, но С СООБЩЕНИЕМ. Молча подменённый
    пояс дал бы тот же сдвиг на сутки, только необъяснимый (§6.0.1)."""
    assert main._пояс(Человек("Мордор/Барад-дур")) == ZoneInfo("UTC")
    вывод = capsys.readouterr().out
    assert "часовой пояс" in вывод and "Мордор/Барад-дур" in вывод


def test_сегодня_согласовано_с_чистой_функцией():
    """`_сегодня` не имеет права считать день вторым способом: он обязан
    быть тем же `_день_в_поясе` от текущего момента."""
    человек = Человек("Asia/Kamchatka")
    сейчас = datetime.now(ZoneInfo("UTC"))
    assert main._сегодня(человек) == main._день_в_поясе(сейчас, ZoneInfo("Asia/Kamchatka"))


# ── Окно дат считается от пояса, а не от процесса ────────────────────────────

def test_окно_считается_от_переданного_дня():
    """`_нут_дата` больше не спрашивает время сама. Раньше она сверяла окно
    с `datetime.now().date()` — то есть с UTC, — и в ночные часы отвергала
    ровно тот день, который человек видел на экране крайним."""
    сегодня = date(2026, 8, 15)
    R = main.NUT_DAY_RANGE
    assert main._нут_дата("2026-08-15", сегодня) == "2026-08-15"
    assert main._нут_дата("2026-08-22", сегодня) == "2026-08-22"          # +7
    with pytest.raises(ValueError):
        main._нут_дата("2026-08-23", сегодня)                             # +8
    assert R == 7


def test_сегодня_обязателен_а_не_умолчание():
    """Умолчание вернуло бы пояс процесса любому, кто забыл аргумент, —
    то есть починка держалась бы на внимательности каждого вызова."""
    with pytest.raises(TypeError):
        main._нут_дата("2026-08-15")


def test_пустое_значение_берёт_переданный_день():
    """Ключа нет — берём переданное «сегодня», а не своё."""
    assert main._нут_дата(None, date(2026, 8, 15)) == "2026-08-15"
    assert main._нут_дата("", date(2026, 8, 15)) == "2026-08-15"


def test_все_вызовы_нут_даты_передают_пояс():
    """Место вызова, забывшее `_сегодня(user)`, вернуло бы UTC — и дефект
    воскрес бы в одном эндпоинте из четырёх, то есть незаметно.
    Проверяется исходником: подсчёт вызовов дешевле, чем поднятие
    приложения ради каждого маршрута."""
    исходник = (Path(__file__).resolve().parent.parent / "main.py").read_text(encoding="utf-8")
    вызовы = [с for с in исходник.splitlines() if "_нут_дата(" in с and "def " not in с]
    assert вызовы, "вызовов не найдено — проверка сломана, а не код исправен"
    плохие = [с.strip() for с in вызовы if "_сегодня(user)" not in с]
    assert not плохие, f"вызов без пояса пользователя: {плохие}"


def test_страница_дневника_отдаёт_серверное_сегодня():
    """Разметка обязана получать день от сервера. Считать его в браузере —
    это и есть второе мнение, из-за которого сайдбар и полоска расходились."""
    шаблон = (Path(__file__).resolve().parent.parent
              / "templates" / "nutrition.html").read_text(encoding="utf-8")
    assert "today: '{{ nut_today }}'" in шаблон
    assert "date: '{{ nut_today }}'" in шаблон
    # И обратная сторона: прежнего способа в состоянии дневника больше нет.
    # Комментарии вырезаются — прежний способ НАЗВАН в комментарии рядом
    # («так было и почему это неверно»), и без вырезания проверка ловила бы
    # собственное объяснение вместо кода
    голова = шаблон.split("histDate")[0].splitlines()
    код = [с for с in голова if not с.strip().startswith("//")]
    assert not [с for с in код if "new Date().toISOString()" in с], \
        "день дневника снова считается в браузере по UTC"

# -*- coding: utf-8 -*-
"""Вкладки «Вес» и «Ассистент» держатся на токенах, а не на числах.

Задача 79, вторая половина. Без этих проверок работа расползается обратно
тихо: следующий припишет `margin-bottom: 10px` рядом с существующей
строкой, ничего не сломается, и заметить это будет нечем — ни одна
из девяти проверок §6.0.2 чисел в CSS не ищет.

ИСКЛЮЧЕНИЯ ПЕРЕЧИСЛЕНЫ ПОИМЁННО, а не порогом. Порог («не больше десяти
чисел») пропускает замену одного числа другим и врёт ровно в тот день,
когда его превысят на единицу.
"""
import re
import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
CSS = (КОРЕНЬ / "static" / "nutrition.css").read_text(encoding="utf-8")
HTML = (КОРЕНЬ / "templates" / "nutrition.html").read_text(encoding="utf-8")
STYLE = (КОРЕНЬ / "static" / "style.css").read_text(encoding="utf-8")

# Семейства классов, которыми нарисованы две вкладки. Список тот же, что
# у диагностики захода: имена собраны по объявлениям в nutrition.css.
СЕМЕЙСТВА = ("wt-", "as-", "chat-", "attach-", "voice-", "vw-bar", "fd-",
             "chart-", "meas-grid", "w-cols", "assistant-mode")
ИДЕНТИФИКАТОРЫ = ("#wt-tooltip", "#tab-assistant", "#tab-weight")

ОТСТУПЫ = {"margin", "margin-top", "margin-bottom", "margin-left", "margin-right",
           "padding", "padding-top", "padding-bottom", "padding-left", "padding-right",
           "gap", "row-gap", "column-gap"}

# Кегль числом разрешён ровно одному селектору — числу-витрине на вкладке
# «Вес». Ступени под «одно крупное число во всю ширину узкой колонки»
# в системе нет: --text-h1 даёт 28px на 390px, --text-display — 40px.
КЕГЛЬ_ЧИСЛОМ_РАЗРЕШЁН = {".wt-big"}

# Отступ числом разрешён: шаг штрихов рисунка звуковой волны. Ближайшая
# ступень --space-1 удваивает просвет и превращает волну в пунктир.
ОТСТУП_ЧИСЛОМ_РАЗРЕШЁН = {".voice-wave-static"}


def _без_комментариев(текст):
    """Комментарии гасятся, а переводы строк сохраняются — номера строк честные."""
    куски, i = [], 0
    while True:
        j = текст.find("/*", i)
        if j < 0:
            куски.append(текст[i:])
            break
        куски.append(текст[i:j])
        k = текст.find("*/", j)
        k = len(текст) - 2 if k < 0 else k
        куски.append("\n" * текст.count("\n", j, k + 2))
        i = k + 2
    return "".join(куски)


def _правила(текст):
    """(селектор, тело) по всему файлу, включая содержимое @media."""
    итог, i, n = [], 0, len(текст)
    while i < n:
        j = текст.find("{", i)
        if j < 0:
            break
        голова, глубина, k = текст[i:j].strip(), 1, j + 1
        while k < n and глубина:
            if текст[k] == "{":
                глубина += 1
            elif текст[k] == "}":
                глубина -= 1
            k += 1
        тело = текст[j + 1:k - 1]
        if голова.startswith("@"):
            if голова.startswith(("@media", "@supports")):
                итог += _правила(тело)
        else:
            итог.append((голова, тело))
        i = k
    return итог


def _в_области(селектор):
    if any(re.search(r"\.(" + re.escape(с) + r")", селектор) for с in СЕМЕЙСТВА):
        return True
    return any(и in селектор for и in ИДЕНТИФИКАТОРЫ)


ПРАВИЛА = [(с, т) for с, т in _правила(_без_комментариев(CSS)) if _в_области(с)]


def test_область_не_пуста():
    """Отрицательный контроль самой проверки: разбор обязан что-то найти.

    Без него переименование семейства классов превратило бы все проверки
    ниже в тихо проходящие — они бы просто ничего не смотрели.
    """
    assert len(ПРАВИЛА) > 50, f"правил в области всего {len(ПРАВИЛА)} — разбор сломан"


def test_кегли_только_через_токен():
    нарушители = []
    for селектор, тело in ПРАВИЛА:
        for м in re.finditer(r"(?:^|;)\s*font-size\s*:\s*([^;{}]+)", тело):
            значение = м.group(1).strip()
            if "var(" in значение:
                continue
            если_разрешён = any(р in селектор for р in КЕГЛЬ_ЧИСЛОМ_РАЗРЕШЁН)
            if не_calc(значение) and not если_разрешён:
                нарушители.append(f"{селектор.strip()} -> font-size: {значение}")
    assert not нарушители, "кегль числом мимо шкалы:\n" + "\n".join(нарушители)


def не_calc(значение):
    """calc(… * var(--nut-u)) — масштаб раздела, осознанное исключение (CLAUDE.md §2.3)."""
    return "var(" not in значение


def test_отступы_только_через_токен():
    нарушители = []
    for селектор, тело in ПРАВИЛА:
        for м in re.finditer(r"(?:^|;)\s*([a-z-]+)\s*:\s*([^;{}]+)", тело):
            свойство, значение = м.group(1).strip(), м.group(2).strip()
            if свойство not in ОТСТУПЫ or not не_calc(значение):
                continue
            # сброс в ноль токена не имеет: `--space-0` в системе нет
            if not re.search(r"[1-9]", значение):
                continue
            if any(р in селектор for р in ОТСТУП_ЧИСЛОМ_РАЗРЕШЁН):
                continue
            нарушители.append(f"{селектор.strip()} -> {свойство}: {значение}")
    assert not нарушители, "отступ числом мимо шкалы:\n" + "\n".join(нарушители)


def test_box_title_удалён():
    """Копия системного `.field-label` не должна вернуться.

    Проверка 7 этого не ловит и не может: список её исключений говорит
    «про имя написано, что его нет», и возвращение имени в код она
    пропускает (граница названа в шапке check_docs.py).
    """
    # Сравнение ПОСЛОВНОЕ, а не вхождением: на экране «Добавить» живёт
    # `.a-box-title`, и подстрока `box-title` в нём есть. Первая версия
    # этой проверки падала именно на нём — то есть врала бы всегда.
    имена = set()
    for значение in re.findall(r'class="([^"]*)"', HTML):
        имена.update(значение.split())
    assert "box-title" not in имена, \
        "`.box-title` вернулся в разметку — это третья копия .field-label"
    assert not re.search(r"(^|[\s,}])\.box-title\s*[,{]", _без_комментариев(CSS)), \
        "правило `.box-title` вернулось в nutrition.css"


def test_полосы_заполнения_системные():
    """Все шесть полос страницы носят системный `.meter`."""
    assert ".meter {" in STYLE and ".meter-fill {" in STYLE, \
        "компонент .meter пропал из системы"
    for имя in ("macro-bar", "water-bar", "hd-bar", "cal-bar", "wt-prog-bar", "as-bar"):
        for м in re.finditer(r'class="([^"]*\b' + имя + r'\b[^"]*)"', HTML):
            assert "meter" in м.group(1), \
                f"полоса .{имя} нарисована мимо системного .meter: {м.group(1)}"


def test_кнопки_чата_системные():
    """Отправка и скрепка — системные кнопки-значки, а не свои 42×42."""
    assert ".btn-icon-accent {" in STYLE and ".btn-icon-outline {" in STYLE
    for м in re.finditer(r'class="([^"]*\bchat-(?:send|attach-btn)\b[^"]*)"', HTML):
        assert "btn-icon" in м.group(1), \
            f"кнопка чата мимо системного .btn-icon: {м.group(1)}"
    # и своих размеров у них не осталось
    for правило, тело in _правила(_без_комментариев(CSS)):
        if re.search(r"\.chat-(send|attach-btn)\s*[,{]", правило + "{"):
            assert "width" not in тело and "height" not in тело, \
                f"свой размер вернулся кнопке чата: {правило.strip()}"

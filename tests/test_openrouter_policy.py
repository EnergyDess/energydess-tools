ИСХОДНИК = io.open(КОРЕНЬ / "main.py", encoding="utf-8").read()

# АДРЕС ИЩЕТСЯ ПО ИМЕНИ, А НЕ ПО СТРОКЕ — с 2026-08-21 (BACKLOG №128).
# Адрес вынесен в переменную окружения (`OPENROUTER_URL`), потому что
# ветку «сервис ответил не так» иначе нечем прогнать; литерала на месте
# вызова больше нет ни одного, и прежний поиск по строке молча нашёл бы
# НОЛЬ вызовов — то есть тест печатал бы «политика везде» про пустой
# список. Тот же немой отказ, ради которого он и написан, только внутри
# самой проверки.
ЧАТ = "OPENROUTER_URL"
ГОЛОС = "OPENROUTER_AUDIO_URL"


def _вызовы(имя):
    """Вызовы, где первым позиционным аргументом стоит эта переменная.

    Обходим ДЕРЕВО, а не грепаем: греп по строке считает адресом
    и упоминание в комментарии — ровно то, что чинила задача 99
    у проверки 7. В дереве комментариев нет вовсе.
    """
    дерево = ast.parse(ИСХОДНИК)
    итог = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        if not узел.args:
            continue
        первый = узел.args[0]
        if isinstance(первый, ast.Name) and первый.id == имя:
            итог.append(узел)
    return итог


def test_литерала_адреса_на_месте_вызова_НЕТ():
    """Вернётся строка на место вызова — `_вызовы` перестанет её видеть,
    и охват молча упадёт. Поэтому литерал запрещён везде, кроме одного
    места: умолчания у `os.getenv`."""
    строки = [с for с in ИСХОДНИК.splitlines()
              if "openrouter.ai/api/v1" in с and not с.lstrip().startswith("#")]
    assert len(строки) == 2, строки
    assert all("os.getenv" in с or 'OPENROUTER' in с for с in строки), строки



def test_у_распознавания_речи_политики_НЕТ_и_это_решение():
    """Голос — названная дыра, а не забытое место.

    Замер 2026-08-20: /api/v1/audio/transcriptions отвечает HTTP 200
    и с `zdr: true`, и с заведомо несуществующим провайдером — то есть
    поле игнорируется. Тело при этом читается: подложенная модель даёт
    HTTP 400. Поле, которое выглядит защитой и ею не является, хуже
    отсутствующего, поэтому его там НЕТ, а причина записана рядом.

    Тест сторожит именно это: появится политика у голосового вызова —
    значит, кто-то решил, что она работает, и обязан предъявить замер.
    """
    вызовы = _вызовы(ГОЛОС)
    assert len(вызовы) == 1
    тело = next((k.value for k in вызовы[0].keywords if k.arg == "json"), None)
    assert isinstance(тело, ast.Dict)
    имена = [ast.unparse(v) for k, v in zip(тело.keys, тело.values) if k is None]
    assert "ПОЛИТИКА_ЗАПРОСА" not in имена
    ключи = [k.value for k in тело.keys if isinstance(k, ast.Constant)]
    assert "provider" not in ключи


def test_отрицательный_контроль_разбора():
    """Проверка обязана НАЙТИ вызов без политики в подложенном коде.

    Без этого «нет находок» неотличимо от «разбор ничего не читал»:
    ast.walk по битому дереву дал бы тот же пустой список.
    """
    подлог = (
        "import httpx\n"
        "async def f(client, тело):\n"
        "    return await client.post(\n"
        "        %r,\n"
        "        headers={}, json={'model': 'x', 'messages': []})\n" % ЧАТ)
    дерево = ast.parse(подлог)
    найдено = []
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Call) and узел.args:
            п = узел.args[0]
            if isinstance(п, ast.Constant) and п.value == ЧАТ:
                тело = next((k.value for k in узел.keywords if k.arg == "json"),
                            None)
                имена = ([ast.unparse(v)
                          for k, v in zip(тело.keys, тело.values) if k is None]
                         if isinstance(тело, ast.Dict) else [])
                if "ПОЛИТИКА_ЗАПРОСА" not in имена:
                    найдено.append(узел.lineno)
    assert найдено, ("разбор не увидел вызова без политики — сломан он, "
                     "а не код проекта")

def test_политика_уходит_в_каждое_тело_чата():
    """У каждого вызова в `json=` распакована ПОЛИТИКА_ЗАПРОСА."""
    без_политики = []
    for узел in _вызовы(ЧАТ):
        тело = next((k.value for k in узел.keywords if k.arg == "json"), None)
        строка = f"{узел.файл}:{узел.lineno}"
        if тело is None:
            без_политики.append((строка, "нет аргумента json="))
            continue
        if not isinstance(тело, ast.Dict):
            без_политики.append((строка, "json= не словарь-литерал"))
            continue
        # распаковка `**X` в ast.Dict — ключ None, значение = выражение;
        # из модуля вне `main` это атрибут (`**м.ПОЛИТИКА_ЗАПРОСА`)
        имена = [ast.unparse(v).rsplit(".", 1)[-1]
                 for k, v in zip(тело.keys, тело.values) if k is None]
        if "ПОЛИТИКА_ЗАПРОСА" not in имена:
            без_политики.append((строка, "нет **ПОЛИТИКА_ЗАПРОСА"))
    assert not без_политики, (
        "вызовы OpenRouter без политики данных: %s" % без_политики)



def _вызовы(имя):
    """Вызовы, где первым позиционным аргументом стоит эта переменная.

    Обходим ДЕРЕВО, а не грепаем: греп по строке считает адресом
    и упоминание в комментарии — ровно то, что чинила задача 99
    у проверки 7. В дереве комментариев нет вовсе.
    """
    итог = []
    for файл, текст in исходники_приложения().items():
        for узел in ast.walk(ast.parse(текст)):
            if not isinstance(узел, ast.Call):
                continue
            if not узел.args:
                continue
            # С 2026-09-18 (BACKLOG №346) вызов идёт через обёртку учёта
            # расхода `_модель_post(client, инструмент, user_id, URL, …)` —
            # адрес там ЧЕТВЁРТЫЙ. Ищем обе формы: иначе охват молча упал бы
            # до нуля, и тест печатал бы «политика везде» про пустой список.
            # Из модуля вне `main` обёртка и адрес — атрибуты (`м._модель_post`,
            # `м.OPENROUTER_URL`), и это та же форма.
            обёртка = ((isinstance(узел.func, ast.Name) and узел.func.id == "_модель_post")
                       or (isinstance(узел.func, ast.Attribute)
                           and узел.func.attr == "_модель_post"))
            позиция = 3 if обёртка else 0
            if len(узел.args) <= позиция:
                continue
            адрес = узел.args[позиция]
            if ((isinstance(адрес, ast.Name) and адрес.id == имя)
                    or (isinstance(адрес, ast.Attribute) and адрес.attr == имя)):
                узел.файл = файл
                итог.append(узел)
    return итог



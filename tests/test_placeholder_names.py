# -*- coding: utf-8 -*-
"""УСЛОВНОЕ ИМЯ НЕ СПРАШИВАЮТ У ЧУЖОГО СПРАВОЧНИКА (BACKLOG №234, E.1).

═══════════════════════════════════════════════════════════════════════
КЛАСС, А НЕ ЭКЗЕМПЛЯР
═══════════════════════════════════════════════════════════════════════

Обезличивание захода 202 (§5.1: названия лекарств живого человека —
сведения о здоровье, репозиторий публичный) заменило настоящие имена
на условные «Препарат А», «Препарат Б». Правка верная и обязательная —
а вместе с ней МОЛЧА сломалось ПЯТЬ мест, и каждое чинилось отдельным
заходом:

  · эталоны `check_medkit_dosage` — задача 219;
  · сцена пиксельного дифа, не снималась ни разу;
  · сцена окна способа приёма в `check_hover`, не открывалась с №173;
  · эталон разведки источников — задача 230;
  · селекторы `data-find` — задача 232, F.3.

Пять раз подряд один дефект — значит закрывается КЛАСС (§6.0.7).

═══════════════════════════════════════════════════════════════════════
ПРИЗНАК: КТО СПРАШИВАЕТ ЧУЖОЙ ИСТОЧНИК
═══════════════════════════════════════════════════════════════════════

Условное имя опасно НЕ ВЕЗДЕ. В комментарии оно законно и нужно;
в подлоге контроля — тоже (там оно и должно не находиться); в seed
стенда оно ЗАКОННО ВДВОЙНЕ, потому что seed сам эти позиции и заводит,
то есть имя адресует существующее.

Опасно ровно одно сочетание: **файл ходит в ЧУЖУЮ СЕТЬ и ищет там
по литеральному имени.** Чужой справочник условного имени не знает
по построению — проба отвечает «не найдено» про несуществующее
и не проверяет НИЧЕГО, оставаясь зелёной по коду возврата (разведки
возвращают 0 всегда).

Признак СТРУКТУРНЫЙ и состоит из двух половин, обе обязательны:

  1. файл ходит наружу — импортирует `httpx` либо `requests`;
  2. условное имя стоит в СТРОКОВОМ ЛИТЕРАЛЕ КОДА, а не в комментарии
     и не в docstring.

Комментарии в синтаксическое дерево не попадают вовсе, поэтому разбор
идёт деревом, а не грепом: греп объявил бы находкой каждое пояснение
(их в проекте 270 в 18 файлах — замер 2026-09-01).

═══════════════════════════════════════════════════════════════════════
ЧЕГО ПРОВЕРКА НЕ ЛОВИТ, И ЭТО НАЗВАНО
═══════════════════════════════════════════════════════════════════════

  · имя, собранное в рантайме (`"Препарат " + буква`) — такой строки
    в исходнике нет;
  · обратный случай: НАСТОЯЩЕЕ имя владельца, уехавшее в эталон.
    Его ловит проверка 26 (`check_health_leak.py`), и это её работа —
    здесь второго заслона не заводится;
  · условное имя в СТЕНДОВОЙ пробе, которая наружу не ходит: там оно
    адресует позицию, заведённую seed, и это законно.
"""
import ast
import io
import re
import os
import subprocess
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)

# «Препарат А», «Препараты В» и прочие условные имена обезличивания.
УСЛОВНОЕ = re.compile(r"Препарат[ыа]? [А-Я](?![а-яё])")

# Ходит наружу — значит спрашивает ЧУЖОЙ источник.
НАРУЖУ = ("httpx", "requests", "urllib.request")


def _файлы():
    из = subprocess.run(["git", "ls-files", "*.py"], cwd=КОРЕНЬ,
                        capture_output=True, text=True,
                        encoding="utf-8").stdout.split("\n")
    return [f for f in из if f.strip().endswith(".py")]


def _ходит_наружу(дерево):
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            if any(a.name.split(".")[0] in НАРУЖУ for a in узел.names):
                return True
        elif isinstance(узел, ast.ImportFrom):
            if (узел.module or "").split(".")[0] in НАРУЖУ:
                return True
    return False


def _литералы(дерево):
    """Строковые литералы КОДА: docstring и голые строки-выражения — мимо.

    Docstring — это `Expr(Constant(str))`, то есть строка, ничего
    не делающая. Именно так пишут пояснения, и объявлять их находкой
    значило бы запретить объяснять правило рядом с правилом.
    """
    прозаические = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Expr) and isinstance(узел.value, ast.Constant) \
                and isinstance(узел.value.value, str):
            прозаические.add(id(узел.value))
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str) \
                and id(узел) not in прозаические:
            yield узел


def test_условное_имя_не_уходит_в_чужой_справочник():
    находки = []
    for отн in _файлы():
        путь = os.path.join(КОРЕНЬ, отн)
        if not os.path.exists(путь):
            continue
        текст = io.open(путь, encoding="utf-8").read()
        try:
            дерево = ast.parse(текст)
        except SyntaxError:
            continue
        if not _ходит_наружу(дерево):
            continue
        for узел in _литералы(дерево):
            # ИМЯ В НАЧАЛЕ ЛИТЕРАЛА, А НЕ ГДЕ УГОДНО В НЁМ.
            #
            # Первая версия искала вхождение и дала ЛОЖНУЮ находку
            # на строке-пояснении внутри данных: «знает «Препарат Б
            # таблетки 200 мг», которого у Видаля нет» — это ОПИСАНИЕ
            # отсева источника, оно печатается человеку и запросом
            # не является. Проба, называющая находкой законную строку,
            # перестаёт читаться на третий раз (§6.0.2, довод
            # проверки 4).
            #
            # Признак «литерал НАЧИНАЕТСЯ с имени» отделяет запрос
            # («Препарат Ж») от упоминания внутри фразы.
            if УСЛОВНОЕ.match(узел.value):
                находки.append("%s:%d  %r"
                               % (отн, узел.lineno, узел.value[:60]))
    assert not находки, (
        "УСЛОВНОЕ ИМЯ УХОДИТ В ЧУЖОЙ ИСТОЧНИК — справочник его не знает,\n"
        "и проба отвечает «не найдено» про несуществующее:\n  "
        + "\n  ".join(находки))


def test_ОБРАТНЫЙ_КОНТРОЛЬ_признак_находит_подложенное():
    """Без этой половины «ноль находок» не значит ничего (§6.0.3).

    Проба, которая не смотрит никуда, прошла бы предыдущий тест
    и молчала бы про настоящую поломку. Подлог кладётся ВО ВРЕМЕННЫЙ
    исходник — рабочее дерево не трогается.
    """
    исходник = ("import httpx\n"
                "ЗАПРОСЫ = ['Препарат А', 'Цитрамон']\n")
    дерево = ast.parse(исходник)
    assert _ходит_наружу(дерево), "признак «ходит наружу» не сработал"
    нашли = [у.value for у in _литералы(дерево) if УСЛОВНОЕ.match(у.value)]
    assert нашли == ["Препарат А"], нашли


def test_ОБРАТНЫЙ_КОНТРОЛЬ_проза_и_стенд_проходят():
    """Комментарий, docstring и файл БЕЗ сети находкой не являются.

    Замер 2026-09-01: условных имён в репозитории 270 в 18 файлах,
    и почти все — пояснения. Признак, объявляющий их находкой,
    перестал бы читаться на третий раз (§6.0.2, довод проверки 4).
    """
    с_прозой = ('import httpx\n'
                '"""Разбор: «Препарат А таб. п/о 10мг» → «Препарат А»."""\n'
                '# Препарат Б Ретард — пример пролонга\n'
                'ЗАПРОСЫ = ["Цитрамон"]\n')
    дерево = ast.parse(с_прозой)
    нашли = [у.value for у in _литералы(дерево) if УСЛОВНОЕ.match(у.value)]
    assert not нашли, нашли

    # ИМЯ ВНУТРИ ФРАЗЫ — ТОЖЕ НЕ НАХОДКА: это пояснение в данных,
    # печатается человеку и запросом не является
    в_данных = ("import httpx" + chr(10)
                + 'ИСТОРИЯ = {"wer.ru": "знает «Препарат Б таблетки 200 мг»"}' + chr(10))
    внутри = [у.value for у in _литералы(ast.parse(в_данных))
              if УСЛОВНОЕ.match(у.value)]
    assert not внутри, внутри

    без_сети = 'ПОЗИЦИИ = ["Препарат А"]\n'
    assert not _ходит_наружу(ast.parse(без_сети)), (
        "файл без сети объявлен ходящим наружу — признак не разделяет")


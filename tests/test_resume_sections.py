"""ПРАВКА РАЗДЕЛА РЕЗЮМЕ: ЧТО ЛОЖИТСЯ В БАЗУ (BACKLOG №352, письмо 3, блок 3).

Разделение с `check_resume_sections.py` такое: там спрашивается РАЗБОР —
побайтное совпадение склейки с исходником на выдуманных резюме и на копии
боевой базы. Здесь — ЭНДПОИНТ: что именно он кладёт в `resumes.resume_text`
и как отвечает на негодный запрос. Сети, браузера и модели не требует.

ГЛАВНОЕ СВОЙСТВО: в базу ложится ПОЛНЫЙ текст, а изменяется в нём ровно
кусок названного раздела. Источник правды не меняется — генерация писем
по-прежнему берёт `resume_text` целиком, и разделы на неё не влияют
ни одним знаком.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ.setdefault("DB_PATH", "test_resume_sections.db")

import asyncio                                               # noqa: E402

import main                                                  # noqa: E402
import resume_sections as rs                                 # noqa: E402

# Выдуманное резюме в формате выгрузки hh.ru. Резюме человека сюда
# не попадает ни при каких условиях (§5.1).
РЕЗЮМЕ = """Иванов Иван
Мужчина, 30 лет

ivanov@example.com

Желаемая должность и зарплата
Монтажёр видео

Опыт работы — 2 года

Январь 2024
по настоящее время
2 года

ООО «Пример»
Монтажёр
Монтаж роликов.

Навыки
Premiere Pro      After Effects
"""


class ФейкЗапрос:
    def __init__(с, строка):
        с.строка = строка

    def filter(с, условие):
        return с

    def first(с):
        return с.строка


class ФейкБаза:
    """Коммит считается: «сохранили» и «ответили 200» — разные факты."""

    def __init__(с, строка):
        с.строка = строка
        с.коммитов = 0

    def query(с, модель):
        return ФейкЗапрос(с.строка)

    def commit(с):
        с.коммитов += 1


class ФейкРезюме:
    def __init__(с, текст):
        с.resume_text = текст


class ФейкЗапросHTTP:
    def __init__(с, тело):
        с._тело = тело

    async def json(с):
        return с._тело


class ФейкПользователь:
    id = 1
    is_admin = False


def _позвать(тело, резюме=РЕЗЮМЕ, монки=None):
    база = ФейкБаза(ФейкРезюме(резюме))
    # Разметку рисует шаблон — здесь проверяется ЗАПИСЬ, поэтому отдачу
    # подменяем. Что разметку отдаёт тот же файл, что и первый кадр,
    # сторожит отдельный тест ниже.
    ответ = asyncio.run(main.save_resume_section(
        ФейкЗапросHTTP(тело), user=ФейкПользователь(), db=база))
    return ответ, база


def test_правка_меняет_только_свой_кусок(monkeypatch):
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    разделы = rs.разобрать(РЕЗЮМЕ)
    for индекс, р in enumerate(разделы):
        новое = р["тело"] + "ДОПИСАНО\n"
        _, база = _позвать({"index": индекс, "text": новое})
        лёг = база.строка.resume_text
        assert лёг[:р["начало"]] == РЕЗЮМЕ[:р["начало"]]
        assert лёг[р["начало"] + len(новое):] == РЕЗЮМЕ[р["конец"]:]
        assert лёг[р["начало"]:р["начало"] + len(новое)] == новое
        assert база.коммитов == 1


def test_в_базу_ложится_ПОЛНЫЙ_текст(monkeypatch):
    """Не кусок и не разметка: генерация писем берёт отсюда всё резюме."""
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    _, база = _позвать({"index": 1, "text": "Желаемая должность и зарплата\nРежиссёр\n\n"})
    лёг = база.строка.resume_text
    assert "Иванов Иван" in лёг and "Premiere Pro" in лёг
    assert "Режиссёр" in лёг and "Монтажёр видео" not in лёг
    # Склейка по-прежнему равна тексту — разбор нового текста ничего не теряет
    assert rs.собрать(rs.разобрать(лёг)) == лёг


def test_правка_тем_же_текстом_не_меняет_ни_знака(monkeypatch):
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    разделы = rs.разобрать(РЕЗЮМЕ)
    _, база = _позвать({"index": 2, "text": разделы[2]["тело"]})
    assert база.строка.resume_text == РЕЗЮМЕ


def test_раздел_вне_набора_даёт_409_и_НЕ_сохраняет(monkeypatch):
    """Разделы пересчитались в соседней вкладке — сохранить не тот кусок
    хуже отказа: человек не узнал бы, что переписал чужую часть резюме."""
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    ответ, база = _позвать({"index": 99, "text": "что угодно"})
    assert ответ.status_code == 409
    assert база.коммитов == 0
    assert база.строка.resume_text == РЕЗЮМЕ


def test_негодное_тело_запроса_отвергается(monkeypatch):
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    for тело, код in (({"text": "x"}, 400),
                      ({"index": "не число", "text": "x"}, 400),
                      ({"index": 0}, 400),
                      ({"index": 0, "text": 42}, 400)):
        ответ, база = _позвать(тело)
        assert ответ.status_code == код, тело
        assert база.коммитов == 0


def test_пустое_резюме_править_нечего(monkeypatch):
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    ответ, база = _позвать({"index": 0, "text": "x"}, резюме="   ")
    assert ответ.status_code == 400
    assert база.коммитов == 0


def test_без_сессии_401(monkeypatch):
    ответ = asyncio.run(main.save_resume_section(
        ФейкЗапросHTTP({"index": 0, "text": "x"}), user=None,
        db=ФейкБаза(ФейкРезюме(РЕЗЮМЕ))))
    assert ответ.status_code == 401


def test_разметку_рисует_ТОТ_ЖЕ_файл_что_и_первый_кадр():
    """Второго построителя разделов нет: разошлись бы они молча, а первый
    кадр приезжал бы пустым (§6.0.15, довод `_medkit_grid.html`)."""
    import inspect
    исходник = inspect.getsource(main._резюме_разметка)
    assert "_hh_resume.html" in исходник
    шаблон = open("templates/hh.html", encoding="utf-8").read()
    assert "_hh_resume.html" in шаблон, "первый кадр берёт другой файл"


def test_разбор_для_показа_и_текст_для_генерации_не_расходятся():
    """`_резюме_по_разделам` отдаёт на экран то же, что лежит в базе."""
    вид = main._резюме_по_разделам(ФейкРезюме(РЕЗЮМЕ))
    assert вид["есть"] and not вид["запасной"]
    assert "".join(р["тело"] for р in вид["разделы"]) == РЕЗЮМЕ
    assert вид["знаков"] == len(РЕЗЮМЕ)


def test_резюме_без_заголовков_отдаётся_запасным_видом():
    """«Разделов нет» и «резюме пустое» — разные факты, и подменять один
    другим нельзя: текст обязан дойти до экрана целиком."""
    текст = "Просто текст резюме одной простынёй.\nБез заголовков hh.ru.\n"
    вид = main._резюме_по_разделам(ФейкРезюме(текст))
    assert вид["есть"] and вид["запасной"]
    assert len(вид["разделы"]) == 1
    assert вид["разделы"][0]["тело"] == текст

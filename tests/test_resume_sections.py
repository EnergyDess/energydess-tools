def test_правка_места_меняет_ТОЛЬКО_его_кусок():
    разделы = rs.разобрать(РЕЗЮМЕ_HH)
    i = [n for n, р in enumerate(разделы) if р["имя"] == "Опыт работы"][0]
    места = rs.места_работы(разделы[i]["тело"])
    новый = rs.заменить_место(РЕЗЮМЕ_HH, i, 0,
                              места[0]["тело"] + "Дописанная строка.\n")
    assert "Дописанная строка." in новый
    # остальные места не тронуты ни на знак
    места2 = rs.места_работы(
        [р for р in rs.разобрать(новый) if р["имя"] == "Опыт работы"][0]["тело"])
    assert места2[1]["тело"] == места[1]["тело"]
    assert места2[2]["тело"] == места[2]["тело"]



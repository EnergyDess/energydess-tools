# Выдуманное резюме в формате выгрузки hh.ru. Резюме человека сюда
# не попадает ни при каких условиях (§5.1).
РЕЗЮМЕ = """Иванов Иван
Мужчина, 30 лет

ivanov@example.com

Желаемая должность и зарплата
Монтажёр видео

Опыт работы — 2 года

Январь 2024
по настоящее время
2 года

ООО «Пример»
Монтажёр
Монтаж роликов.

Навыки
Premiere Pro      After Effects
"""


class ФейкЗапрос:
    def __init__(с, строка):
        с.строка = строка

    def filter(с, условие):
        return с

    def first(с):
        return с.строка


class ФейкБаза:
    """Коммит считается: «сохранили» и «ответили 200» — разные факты."""

    def __init__(с, строка):
        с.строка = строка
        с.коммитов = 0

    def query(с, модель):
        return ФейкЗапрос(с.строка)

    def commit(с):
        с.коммитов += 1


class ФейкРезюме:
    def __init__(с, текст):
        с.resume_text = текст


class ФейкЗапросHTTP:
    def __init__(с, тело):
        с._тело = тело

    async def json(с):
        return с._тело


class ФейкПользователь:
    id = 1
    is_admin = False


def _позвать(тело, резюме=РЕЗЮМЕ, монки=None):
    база = ФейкБаза(ФейкРезюме(резюме))
    # Разметку рисует шаблон — здесь проверяется ЗАПИСЬ, поэтому отдачу
    # подменяем. Что разметку отдаёт тот же файл, что и первый кадр,
    # сторожит отдельный тест ниже.
    ответ = asyncio.run(main.save_resume_section(
        ФейкЗапросHTTP(тело), user=ФейкПользователь(), db=база))
    return ответ, база


def test_правка_меняет_только_свой_кусок(monkeypatch):
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    разделы = rs.разобрать(РЕЗЮМЕ)
    for индекс, р in enumerate(разделы):
        новое = р["тело"] + "ДОПИСАНО\n"
        _, база = _позвать({"index": индекс, "text": новое})
        лёг = база.строка.resume_text
        assert лёг[:р["начало"]] == РЕЗЮМЕ[:р["начало"]]
        assert лёг[р["начало"] + len(новое):] == РЕЗЮМЕ[р["конец"]:]
        assert лёг[р["начало"]:р["начало"] + len(новое)] == новое
        assert база.коммитов == 1


def test_в_базу_ложится_ПОЛНЫЙ_текст(monkeypatch):
    """Не кусок и не разметка: генерация писем берёт отсюда всё резюме."""
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    _, база = _позвать({"index": 1, "text": "Желаемая должность и зарплата\nРежиссёр\n\n"})
    лёг = база.строка.resume_text
    assert "Иванов Иван" in лёг and "Premiere Pro" in лёг
    assert "Режиссёр" in лёг and "Монтажёр видео" not in лёг
    # Склейка по-прежнему равна тексту — разбор нового текста ничего не теряет
    assert rs.собрать(rs.разобрать(лёг)) == лёг


def test_правка_тем_же_текстом_не_меняет_ни_знака(monkeypatch):
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    разделы = rs.разобрать(РЕЗЮМЕ)
    _, база = _позвать({"index": 2, "text": разделы[2]["тело"]})
    assert база.строка.resume_text == РЕЗЮМЕ


def test_раздел_вне_набора_даёт_409_и_НЕ_сохраняет(monkeypatch):
    """Разделы пересчитались в соседней вкладке — сохранить не тот кусок
    хуже отказа: человек не узнал бы, что переписал чужую часть резюме."""
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    ответ, база = _позвать({"index": 99, "text": "что угодно"})
    assert ответ.status_code == 409
    assert база.коммитов == 0
    assert база.строка.resume_text == РЕЗЮМЕ


def test_негодное_тело_запроса_отвергается(monkeypatch):
    monkeypatch.setattr(main, "_резюме_разметка", lambda r, res: "<div></div>")
    for тело, код in (({"text": "x"}, 400),
                      ({"index": "не число", "text": "x"}, 400),
                      ({"index": 0}, 400),
                      ({"index": 0, "text": 42}, 400)):
        ответ, база = _позвать(тело)
        assert ответ.status_code == код, тело
        assert база.коммитов == 0



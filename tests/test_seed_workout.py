def _семя():
    """Справочник упражнений — из `exercises_seed.json`, а не из базы.

    Файл и есть источник, из которого справочник наполняется на пустой
    базе; сверяться с ним честнее, чем с локальной базой, где могло
    остаться что угодно от прошлых прогонов.
    """
    import json
    путь = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "exercises_seed.json")
    with open(путь, encoding="utf-8") as ф:
        return {е["id"] for е in json.load(ф)}


def test_все_упражнения_программы_есть_в_справочнике():
    """Опечатка в id молча съедает карточку — сервер пропускает слот."""
    известные = _семя()
    из_программы = {е[0] for д in сид.ПРОГРАММА_ДНИ for е in д}
    нет = sorted(из_программы - известные)
    assert not нет, "в справочнике нет упражнений: " + ", ".join(нет)


def test_у_каждого_упражнения_назван_вес_или_его_отсутствие():
    """`ВЕСА[eid]` спрашивается без `.get` — пропуск уронил бы seed."""
    из_программы = {е[0] for д in сид.ПРОГРАММА_ДНИ for е in д}
    assert из_программы == set(сид.ВЕСА), (
        "разошлись: в программе нет %s, в весах нет %s"
        % (sorted(set(сид.ВЕСА) - из_программы),
           sorted(из_программы - set(сид.ВЕСА))))


def test_обе_формы_карточки_подхода_на_экране_есть():
    """Упражнение с весом рисует ДВЕ колонки, без веса — одну.

    Если бы все упражнения программы были с весом, одноколоночная форма
    (`setRowHTML` при `progression.kind === 'reps'`) не снималась бы ни
    разу — то же самое пятно, что и с пустым состоянием приёма пищи.
    """
    с_весом = [e for e, v in сид.ВЕСА.items() if v is not None]
    без_веса = [e for e, v in сид.ВЕСА.items() if v is None]
    assert с_весом and без_веса, (
        "нужны обе формы: с весом %d, без веса %d" % (len(с_весом), len(без_веса)))


def test_застрявшее_упражнение_удовлетворяет_правилу_main():
    """`_is_stuck`: 3+ завершённых подряд, верх диапазона, вес не растёт,
    и всё это растянуто на STUCK_MIN_SPAN_DAYS дней.

    Проверяется арифметика ОБЪЯВЛЕНИЙ: нулевой шаг веса плюс расстояние
    между сессиями одного дня программы. Сами сессии кладутся в базу,
    но условие наступает или не наступает уже здесь.
    """
    import main

    assert сид.ВЕСА[сид.ЗАСТРЯЛО] is not None, "у застрявшего должен быть вес"
    старт, шаг = сид.ВЕСА[сид.ЗАСТРЯЛО]
    assert шаг == 0, "вес застрявшего не должен расти, а шаг %s" % шаг

    # день программы, в котором оно стоит
    дни = [н for н, д in enumerate(сид.ПРОГРАММА_ДНИ)
           if any(е[0] == сид.ЗАСТРЯЛО for е in д)]
    assert len(дни) == 1, "застрявшее упражнение должно стоять ровно в одном дне"
    индекс = дни[0]

    # сдвиги сессий ЭТОГО дня: каждая третья, начиная с его индекса
    сдвиги = [с for н, с in enumerate(сид.СДВИГИ_ТРЕНИРОВОК) if н % 3 == индекс]
    сдвиги = [с for с in сдвиги
              if с not in (сид.СДВИГ_ПРОПУСКА, сид.СДВИГ_ЛЁГКОГО)]
    assert len(сдвиги) >= main.STUCK_MIN_SESSIONS, (
        "завершённых тренировок этого дня %d, а нужно %d"
        % (len(сдвиги), main.STUCK_MIN_SESSIONS))

    последние = sorted(сдвиги)[:main.STUCK_MIN_SESSIONS]   # ближайшие к сегодня
    размах = max(последние) - min(последние)
    assert размах >= main.STUCK_MIN_SPAN_DAYS, (
        "три последние тренировки укладываются в %d дней, а нужно %d"
        % (размах, main.STUCK_MIN_SPAN_DAYS))


def test_дожавшее_упражнение_не_совпадает_с_застрявшим():
    """Иначе одно состояние закроет собой другое.

    `_is_stuck` и `_progression_suggestion` смотрят на одни и те же
    подходы. Дожми одно и то же упражнение три раза подряд — покажется
    «застряло», и подсказка «поднимите до X кг» не снимется ни разу.
    """
    assert сид.ДОЖАЛ != сид.ЗАСТРЯЛО
    assert сид.ДОЖАЛ in сид.ВЕСА
    старт, шаг = сид.ВЕСА[сид.ДОЖАЛ]
    assert шаг > 0, "у дожавшего вес обязан расти, иначе это второе «застряло»"


def test_замена_не_прячет_застрявшее():
    """day-state спрашивает признаки у АКТИВНОГО упражнения.

    Замена стояла на слоте 3 и прятала значок застоя — замерено
    2026-08-22. Слот замены обязан отличаться от слота застрявшего.
    """
    индекс_сегодня = len(сид.СДВИГИ_ТРЕНИРОВОК) % 3
    состав = сид.ПРОГРАММА_ДНИ[индекс_сегодня]
    застрявший = [н for н, е in enumerate(состав) if е[0] == сид.ЗАСТРЯЛО]
    if not застрявший:
        return   # застрявшее не в сегодняшнем дне — прятать нечего
    # слот замены зашит в `_сид_тренировок` как (индекс_сегодня, 2)
    assert застрявший[0] != 2, (
        "замена стоит на слоте 2, а застрявшее — тоже на нём: "
        "признак застоя не покажется")


def test_один_приём_сегодняшней_тренировки_заполнен_частично():
    """Состояние «частично» у значка статуса иначе не снимается.

    У завершённой тренировки заполнены все поля, у будущей — ни одного.
    Seed заполняет первое упражнение целиком, второе — не целиком.
    """
    индекс_сегодня = len(сид.СДВИГИ_ТРЕНИРОВОК) % 3
    состав = сид.ПРОГРАММА_ДНИ[индекс_сегодня]
    assert len(состав) >= 2, "в сегодняшнем дне нужно хотя бы два упражнения"
    подходов_второго = состав[1][1]
    assert max(1, подходов_второго - 1) < подходов_второго, (
        "второе упражнение дня имеет %d подход(ов) — «частично» не выразить"
        % подходов_второго)

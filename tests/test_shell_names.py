"""Проверка 34: разбор оболочки находит кириллическое имя переменной
и не находит кириллицу там, где она законна (заход 298)."""
import check_shell_names as c


def _имена(текст):
    return sorted({ф["имя"] for ф in c.найти(текст)})


def test_присваивание_и_подстановка_НАЙДЕНЫ():
    assert _имена("py x.py; код=$?; echo \"$код\"") == ["код"]
    assert _имена("echo ${итог}") == ["итог"]
    assert _имена("for пара in a b; do echo $пара; done") == ["пара"]
    assert _имена("n=$(( счёт + 1 ))") == ["счёт"]


def test_heredoc_без_кавычек_оболочка_с_кавычками_НЕТ():
    assert _имена("cat <<EOF\n$итог\nEOF\n") == ["итог"]
    # тело с кавычками у разделителя — Python, а не оболочка
    assert _имена("py - <<'EOF'\nимя = 1\nprint(имя)\nEOF\n") == []


def test_кириллица_в_тексте_и_аргументах_ЗАКОННА():
    """Обратный контроль: проверка, находящая всё подряд, неотличима
    от сломанной — и заблокировала бы обычную работу хуком."""
    assert _имена('py check_docs.py; echo "код=$?"') == []
    assert _имена('grep -n "имя=" CLAUDE.md') == []
    assert _имена('KOD="значение"; echo "$KOD"') == []
    # имя внутри вложенной подстановки в кавычках — текст, а не переменная:
    # первая версия разбора арифметики объявляла его находкой
    assert _имена("sed -n \"$(( $(grep -n 'СТОП' main.py | cut -d: -f1) + 4 )),+2p\" main.py") == []


def test_репозиторий_ЧИСТ():
    код, находки = c.проверить(тихо=True)
    assert код == 0, находки

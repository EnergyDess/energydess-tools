"""Политика `|tojson`: кириллица не экранируется, безопасность цела.

BACKLOG №159. Умолчание `json.dumps` — `ensure_ascii=True`, то есть
каждая русская буква уезжает в разметку шестью байтами вместо двух.
Замер на `/admin/exercises`: 445 197 таких последовательностей,
+1.70 МБ к одной странице — 59.6% её веса.

ПОЧЕМУ НА ЭТО НУЖЕН ТЕСТ, А НЕ ЗАМЕР ОДИН РАЗ. Снятие `ensure_ascii`
выглядит как правка про вес, а трогает она ЭКРАНИРОВАНИЕ — то есть
ровно тот механизм, которым `|tojson` защищает от подмены разметки
изнутри данных. Проверять надо не то, что стало легче (это видно),
а то, что НЕ СТАЛО опаснее: закрывающий тег, апостроф и разделители
строк Unicode обязаны уезжать экранированными, как и раньше.

Отказ здесь был бы немой в худшем виде: страница отрисуется, данные
покажутся, а скрипт закроется на середине чужой строкой.
"""

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


@pytest.fixture(scope="module")
def окружение():
    import main
    return main.templates.env


def дамп(env, значение):
    """Через РЕНДЕР, а не через `env.filters['tojson']` напрямую: у фильтра
    первым аргументом идёт eval-контекст, и прямой вызов проверял бы
    не тот путь, каким идёт настоящая страница."""
    return env.from_string("{{ значение|tojson }}").render(значение=значение)


def test_политика_объявлена_и_снимает_экранирование(окружение):
    настройки = окружение.policies["json.dumps_kwargs"]
    assert настройки["ensure_ascii"] is False, (
        "снятое экранирование — вся суть правки: с ним русская буква "
        "весит шесть байт вместо двух")


def test_кириллица_едет_буквами_а_не_кодами(окружение):
    вышло = дамп(окружение, {"имя": "Приседания"})
    assert "Приседания" in вышло, "буквы обязаны остаться буквами"
    # ИМЕННО через chr(92): запись вида "\\u041f" в исходнике Python —
    # это сама буква «П», и проверка утверждала бы, что буквы в выводе нет.
    assert chr(92) + "u041f" not in вышло, "экранирования быть не должно"


ОПАСНОЕ = [
    ("закрывающий тег", "</script>", "<"),
    ("открывающий тег", "<script>", "<"),
    ("апостроф", "it's", "'"),
    ("амперсанд", "a&b", "&"),
    ("разделитель строк U+2028", "a\u2028b", "\u2028"),
    ("разделитель абзацев U+2029", "a\u2029b", "\u2029"),
]


@pytest.mark.parametrize("имя,данные,знак", ОПАСНОЕ)
def test_опасное_по_прежнему_экранируется(окружение, имя, данные, знак):
    """Экранирование опасного делает `htmlsafe_json_dumps` ПОСЛЕ дампа,
    и от `ensure_ascii` оно не зависит. Это свойство Jinja, а не наше
    допущение, — потому и проверяется, а не принимается на веру."""
    вышло = дамп(окружение, {"поле": данные})
    assert знак not in вышло, (
        "%s уехал в разметку СЫРЫМ — данные могут закрыть тег скрипта" % имя)


def test_литерал_не_закрывает_тег_скрипта(окружение):
    вышло = дамп(окружение, [{"n": "</script><b>подмена"}])
    assert "</script>" not in вышло
    б = chr(92) + "u003c"      # текст, а не сам знак «<»
    assert б + "/script" + chr(92) + "u003e" in вышло


def test_значение_читается_обратно_без_потерь(окружение):
    исход = {"шаги": ["Встаньте ровно", "Согните колени"], "n": 3,
             "знаки": "«ёлка» — 5% & 'кавычки'"}
    вышло = дамп(окружение, исход)
    # Разэкранируем то, что htmlsafe добавил поверх JSON, и разберём.
    сырое = (вышло.replace("\u003c", "<").replace("\u003e", ">")
                  .replace("\u0026", "&").replace("\u0027", "'"))
    assert json.loads(сырое) == исход, "смысл данных изменился — это дефект"

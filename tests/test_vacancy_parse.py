"""Разбор страницы вакансии и проверка того, что разобралось именно описание.

Почему тесты вообще есть. Отказ здесь немой по построению: страница
загрузилась, текст извлёкся, счётчик показал тысячи символов — и всё это
верно, только текст был куки-баннером и служебными плашками. Ни исключения,
ни кода ошибки. Единственный способ такое поймать — сверять содержимое.

База не поднимается: DB_PATH уводится в tmp ДО импорта main, иначе импорт
прогнал бы миграции по рабочему app.db (см. tests/conftest.py, та же причина).
"""

import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
os.environ["DB_PATH"] = str(Path(tempfile.gettempdir()) / "hh_tests_разбор.db")

import main  # noqa: E402


# ── Заготовки страниц ────────────────────────────────────────────────────────

ОПИСАНИЕ = (
    "&lt;p&gt;&lt;strong&gt;Обязанности:&lt;/strong&gt;&lt;/p&gt;"
    "&lt;ul&gt;&lt;li&gt;Строить агентные пайплайны на LLM&lt;/li&gt;"
    "&lt;li&gt;Собирать конвейер генерации видео&lt;/li&gt;&lt;/ul&gt;"
    "&lt;p&gt;&lt;strong&gt;Требования:&lt;/strong&gt;&lt;/p&gt;"
    "&lt;ul&gt;&lt;li&gt;Python и опыт с ComfyUI&lt;/li&gt;&lt;/ul&gt;"
    "&lt;p&gt;Условия: удалённо, оформление по трудовому договору.&lt;/p&gt;"
)


def страница_hh(описание: str = ОПИСАНИЕ) -> str:
    """Страница hh: в DOM только шапка, описание — в JSON начального состояния.

    Так устроен и настоящий hh: React рисует описание уже в браузере, поэтому
    в разметке, которую отдаёт сервер, его нет вовсе.
    """
    состояние = (
        '{"vacancyView": {'
        '"name": "AI-инженер",'
        '"company": {"visibleName": "Убей скуку"},'
        '"area": {"name": "Минск"},'
        '"compensation": {"from": 4000, "to": 6000, "currencyCode": "RUR", "gross": false},'
        '"workExperience": "between1And3",'
        '"employmentForm": "FULL",'
        '"workFormats": ["REMOTE"],'
        '"keySkills": {"keySkill": ["Python", "ComfyUI"]},'
        f'"description": "{описание}"'
        '}}'
    )
    return f"""<!DOCTYPE html><html><body>
      <h1>Вакансия AI-инженер в Минске, работа в компании Убей скуку</h1>
      <div>Мы используем файлы cookie, чтобы обеспечивать правильную работу сайта.</div>
      <div>Правила использования файлов cookie</div>
      <div>Понятно</div>
      <div>Уровень дохода не указан</div>
      <div>Опыт работы</div>
      <div>1–3 года</div>
      <div>Полная занятость</div>
      <div>Оформление</div>
      <div>Трудовой договор</div>
      <div>Откликнуться</div>
      <template id="HH-Lux-InitialState">{состояние}</template>
    </body></html>"""


# ── Разбор hh ────────────────────────────────────────────────────────────────

def test_описание_берётся_из_json_а_не_из_разметки():
    текст = main._extract_hh_vacancy(страница_hh())
    assert текст is not None
    assert "Строить агентные пайплайны на LLM" in текст
    assert "Требования:" in текст
    assert "Python и опыт с ComfyUI" in текст


def test_служебные_плашки_в_текст_не_попадают():
    текст = main._extract_hh_vacancy(страница_hh())
    assert "файлы cookie" not in текст
    assert "Откликнуться" not in текст


def test_шапка_вакансии_собрана_из_полей():
    текст = main._extract_hh_vacancy(страница_hh())
    for ожидаемое in ("Должность: AI-инженер", "Компания: Убей скуку", "Город: Минск",
                      "Требуемый опыт: 1–3 года", "Занятость: полная занятость",
                      "Формат работы: удалённо", "Ключевые навыки: Python, ComfyUI"):
        assert ожидаемое in текст, ожидаемое


def test_пункты_списка_не_склеиваются_в_строку():
    текст = main._extract_hh_vacancy(страница_hh())
    assert "— Строить агентные пайплайны на LLM" in текст
    assert "— Собирать конвейер генерации видео" in текст


def test_зарплата_вилкой_и_без_неё():
    текст = main._extract_hh_vacancy(страница_hh())
    assert "Зарплата: 4 000–6 000 ₽ на руки" in текст
    без = страница_hh().replace(
        '"compensation": {"from": 4000, "to": 6000, "currencyCode": "RUR", "gross": false}',
        '"compensation": {"noCompensation": {}}')
    assert "Зарплата: не указана" in main._extract_hh_vacancy(без)


def test_страница_без_json_отдаётся_общему_разбору():
    """Не-hh страница: точный разбор обязан вернуть None, а не пустую строку —
    иначе вызывающий не отличит «не моя страница» от «моя, но пустая»."""
    assert main._extract_hh_vacancy("<html><body><p>Обычная страница</p></body></html>") is None


def test_json_без_описания_считается_неудачей_разбора():
    """Шапка вакансии есть, описания нет. Отдать одну шапку хуже, чем
    отказаться: общий разбор хотя бы попробует достать текст из разметки."""
    assert main._extract_hh_vacancy(страница_hh(описание="&lt;p&gt;.&lt;/p&gt;")) is None


def test_битый_json_не_роняет_разбор():
    страница = '<html><body><template id="HH-Lux-InitialState">{не json</template></body></html>'
    assert main._extract_hh_vacancy(страница) is None


# ── Общий разбор (не hh) ─────────────────────────────────────────────────────

def test_общий_разбор_режет_куки_баннер_и_хвост():
    страница = """<html><body>
      <p>Мы используем файлы cookie, чтобы сайт работал.</p>
      <p>Понятно</p>
      <p>Требования: Python, SQL. Обязанности: писать сервисы.</p>
      <p>Похожие вакансии</p>
      <p>Грузчик</p>
      <p>Курьер</p>
    </body></html>"""
    текст = main._extract_text(страница)
    assert "Требования: Python, SQL" in текст
    assert "файлы cookie" not in текст
    assert "Грузчик" not in текст, "хвост со чужими вакансиями должен отрезаться"


# ── Признак того, что перед нами описание ────────────────────────────────────

def test_описание_проходит_проверку():
    assert main._vacancy_quality(main._extract_hh_vacancy(страница_hh())) is None


def test_одни_плашки_не_проходят():
    мусор = "\n".join(["Вакансия AI-инженер в Минске, работа в компании Убей скуку",
                       "Уровень дохода не указан", "Опыт работы", "1–3 года",
                       "Полная занятость", "Стажировка", "Оформление",
                       "Трудовой договор", "Договор ГПХ с самозанятым"] * 6)
    причина = main._vacancy_quality(мусор)
    assert причина and "плашки" in причина


def test_короткий_текст_не_проходит():
    причина = main._vacancy_quality("AI-инженер, Минск, удалённо")
    assert причина and "короткий" in причина


def test_связный_текст_без_ключевых_слов_проходит():
    """Вакансия может быть написана прозой, без слов «требования» и
    «обязанности». Признак — длинный абзац: служебные плашки всегда короткие."""
    проза = ("Мы небольшая студия, которая делает генеративное видео, и ищем "
             "человека, который заберёт на себя весь конвейер: от разбора "
             "референса до готового ролика, включая выбор моделей, сборку "
             "агентов и контроль качества на каждом шаге пайплайна. " * 2)
    assert main._vacancy_quality(проза) is None

# ── МЕТКА: ──────────────────────────────────────────────────────────────────

СПИСОК = {"Жим ногами", "Гакк-присед"}


def _разобрать_метку(текст):
    """Повторяет решение обработчика, чтобы проверять правило, а не разметку."""
    метки = main._МЕТКА_RE.findall(текст)
    if len(метки) != 1:
        return None, main._МЕТКА_RE.sub("", текст).strip(), len(метки)
    к = метки[0].strip().rstrip(".")
    return (к if к in СПИСОК else None), main._МЕТКА_RE.sub("", текст).strip(), 1


def test_метки_нет():
    принято, текст, сколько = _разобрать_метку("Это тренажёр для жима ногами.")
    assert (принято, сколько) == (None, 0)
    assert текст == "Это тренажёр для жима ногами."


def test_одна_метка_из_списка():
    принято, текст, _ = _разобрать_метку("Это жим ногами.\nМЕТКА: Жим ногами")
    assert принято == "Жим ногами"
    assert текст == "Это жим ногами."


def test_две_метки_не_принимаются_молча():
    """Прежний код брал первую и молчал. Две метки значат, что модель
    сама не выбрала, — принимать одну из них наугад нельзя."""
    принято, _текст, сколько = _разобрать_метку(
        "Похоже на два.\nМЕТКА: Жим ногами\nМЕТКА: Гакк-присед")
    assert сколько == 2
    assert принято is None


def test_метка_не_из_списка_не_принимается():
    принято, _т, _с = _разобрать_метку("Не уверен.\nМЕТКА: Тренажёр Кегеля")
    assert принято is None


def test_метка_посреди_фразы_НЕ_режет_текст():
    """Второй главный тест. Раньше `МЕТКА:` посреди предложения забирала
    хвост фразы в кандидаты И вырезала его из текста пользователю."""
    сырой = "Ответ. МЕТКА: Жим ногами. И ещё вот что важно знать."
    принято, текст, сколько = _разобрать_метку(сырой)
    assert сколько == 0, "подпись опознана не по отдельной строке"
    assert принято is None
    assert текст == сырой, "хвост предложения вырезан из текста пользователю"


def test_нет_как_подпись_не_шумит_в_лог(capsys):
    """«МЕТКА: нет» — штатный ответ по промпту, а не расхождение."""
    принято, _т, сколько = _разобрать_метку("Не уверен, что это.\nМЕТКА: нет")
    assert (принято, сколько) == (None, 1)

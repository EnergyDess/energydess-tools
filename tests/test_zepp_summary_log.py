def test_состав_тела_печатается_строками(monkeypatch):
    """ГЛАВНЫЙ тест файла: строки существуют и печатаются."""
    summary = {н: 1 for н in z.РАЗБИРАЕМ.values()}
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, summary)]}),
        Ответ(json_тело={"items": []}),
    ])
    assert "[zepp] состав тела: есть у" in лог
    assert "[zepp] поля summary по ВСЕЙ выборке" in лог


def test_поля_собираются_со_ВСЕХ_записей_а_не_с_первой(monkeypatch):
    """ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ НА НОВОЙ ФОРМУЛИРОВКЕ — тот самый случай,
    на котором прежняя врала.

    Ответ ровно такой, какой пришёл владельцу: первой идёт запись БЕЗ
    состава (телефон, Health Connect), за ней — запись с весов с полным
    составом. Прежний код брал первую и печатал «мы ждём, а их нет (8)»,
    то есть отчитывался об отсутствии того, что лежало в ответе строкой ниже.

    Тест обязан упасть на прежнем коде и пройти на новом."""
    голая = {"weight": 80.5, "deviceType": 1, "source": 1, "syncHealthConnect": 1}
    полная = {н: 1 for н in z.РАЗБИРАЕМ.values()}
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [
            _запись(1_700_000_100, голая),      # новее — приходит первой
            _запись(1_700_000_000, полная),
        ]}),
        Ответ(json_тело={"items": []}),
    ])
    # Ни один наш показатель не смеет попасть в «их нет»: они есть
    пропали = [с for с in лог.splitlines() if "мы ждём, а их нет" in с]
    assert not пропали, f"поля объявлены отсутствующими, хотя они в ответе: {пропали}"
    # И число записей с составом названо
    assert "состав тела: есть у 1 записей из 2 с summary" in лог


def test_число_записей_с_составом_отличает_ноль_от_ошибки(monkeypatch):
    """Ноль записей с составом при непустой выборке — законный случай
    (простые весы, ручной ввод). Он обязан быть НАЗВАН, а не выглядеть
    как отсутствие диагностики."""
    голая = {"weight": 80.5, "deviceType": 1, "source": 1}
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, голая)]}),
        Ответ(json_тело={"items": []}),
    ])
    assert "состав тела: есть у 0 записей из 1 с summary" in лог
    assert "состава нет ни в одной записи" in лог
    # impedance не приходил — значит это не «приложение не посчитало»
    assert "не с весов с анализом состава" in лог


def test_impedance_без_состава_называется_отдельно(monkeypatch):
    """Запись С impedance, но БЕЗ состава — другая причина и другое
    лечение: весы состав мерили, посчитать его должно было приложение.
    Схлопнуть эти два случая в один ноль значило бы снова не знать,
    куда смотреть."""
    сырая = {"weight": 80.5, "impedance": 451, "deviceType": 1}
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, сырая)]}),
        Ответ(json_тело={"items": []}),
    ])
    assert "весы состав мерили" in лог


def test_лишнее_поле_названо_поимённо(monkeypatch):
    """Поле, которого мы не разбираем, обязано быть НАЗВАНО, а не сосчитано:
    по числу «мы не разбираем 4» решить нечего.

    Служебные поля (deviceType, impedance, height…) в эту строку не идут:
    они известны и намеренно не хранятся, а проверка, кричащая при каждой
    выборке, не читается на третий раз."""
    summary = {н: 1 for н in z.РАЗБИРАЕМ.values()}
    summary["somethingNew"] = 1
    summary["ещёОдно"] = 2
    summary["deviceType"] = 1          # служебное — в строку попасть НЕ должно
    summary["impedance"] = 451         # тоже служебное
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, summary)]}),
        Ответ(json_тело={"items": []}),
    ])
    строка = next(с for с in лог.splitlines() if "НЕЗНАКОМЫЕ поля" in с)
    assert "somethingNew" in строка and "ещёОдно" in строка
    assert "deviceType" not in строка and "impedance" not in строка
    assert "(2)" in строка


def test_summary_строкой_с_JSON_разбирается(monkeypatch):
    """Второй формат того же поля: summary приезжает СТРОКОЙ с JSON внутри.
    Прежний код звал `.get` прямо на ней — состав пропал бы целиком
    и молча, без единой ошибки."""
    import json as _j
    summary = {н: 3 for н in z.РАЗБИРАЕМ.values()}
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, _j.dumps(summary))]}),
        Ответ(json_тело={"items": []}),
    ])
    assert "состав тела: есть у 1 записей" in лог
    assert _итог["records"][0]["body_fat_pct"] == 3


def test_summary_строкой_но_не_JSON_говорит_об_этом(monkeypatch):
    """А негодную строку не проглатываем: пропавший состав обязан оставить
    след, иначе это немой отказ (§6.0.1)."""
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, "не json вовсе")]}),
        Ответ(json_тело={"items": []}),
    ])
    assert "summary пришёл строкой, но это не JSON" in лог


def test_недостающее_поле_названо_поимённо(monkeypatch):
    """Обратная сторона: величина, которую мы ждём, а её нет. Это и есть
    проверка девяти имён, взятых на веру из чужого репозитория."""
    summary = {н: 1 for н in z.РАЗБИРАЕМ.values()}
    пропало = sorted(z.РАЗБИРАЕМ.values())[0]
    summary.pop(пропало)
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, summary)]}),
        Ответ(json_тело={"items": []}),
    ])
    строка = next(с for с in лог.splitlines() if "мы ждём, а их нет ни у одной" in с)
    assert пропало in строка


def test_запись_без_summary_говорит_об_этом(monkeypatch):
    """Ручной ввод в приложении приходит с summary: null. Тогда состава
    не будет вовсе, и это надо сказать, а не напечатать пустой список."""
    _итог, лог = _выборка(monkeypatch, [
        Ответ(json_тело={"items": [_запись(1_700_000_000, None)]}),
        Ответ(json_тело={"items": []}),
    ])
    assert "ни у одной записи нет summary" in лог
    assert "только вес" in лог


# ── Классификатор: незнакомое остаётся незнакомым ───────────────────────────

class _ОдинОтвет:
    def __init__(с, о):
        с._о = о

    def post(с, *a, **k):
        return с._о


@pytest.mark.parametrize("имя,ответ", [
    ("незнакомый код отказа",
     Ответ(303, location="https://x/?error=90210&state=REDIRECTION")),
    ("429 вместо редиректа",
     Ответ(429, тело='{"error":"rate limited"}')),
    ("303 без access и без error",
     Ответ(303, location="https://x/?state=REDIRECTION&region=eu-central-1")),
    ("200 с JSON вместо редиректа",
     Ответ(200, тело='{"code":0,"message":"ok"}')),
])
def test_чужой_ответ_не_схлопывается_в_неверный_пароль(имя, ответ):
    """Классификатор трижды в истории этого модуля выбирал ближайший
    известный класс вместо «не опознан» — и человек шёл менять пароль,
    который был верным. Ни один из этих ответов не смеет стать
    ZeppAuthError."""
    поток = io.StringIO()
    with redirect_stdout(поток):
        with pytest.raises(z.ZeppProtocolError):
            z._код_доступа(_ОдинОтвет(ответ), "x@y.z", "п")


def test_известный_отказ_остаётся_отказом_по_паролю():
    """Положительный контроль к предыдущему: если бы ZeppAuthError
    не возникал НИКОГДА, тест выше проходил бы и на сломанном коде."""
    ответ = Ответ(303, location="https://x/?error=401&state=REDIRECTION")
    поток = io.StringIO()
    with redirect_stdout(поток):
        with pytest.raises(z.ZeppAuthError):
            z._код_доступа(_ОдинОтвет(ответ), "x@y.z", "п")

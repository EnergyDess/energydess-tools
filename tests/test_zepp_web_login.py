# ── 5. Экран пользователя ───────────────────────────────────────────────────

def test_на_экране_нет_диагностики():
    """§2.2. Человеку показывали `HTTP 429 вместо 303 ({"code":12,…})`
    и слово «tokens». Диагностике место в журнале."""
    исходник = (Path(__file__).resolve().parent.parent / "main.py").read_text(
        encoding="utf-8")
    начало = исходник.index("except zepp_client.ZeppProtocolError as e:")
    # окно обрывается на следующем except: дальше идут ДРУГИЕ ветки,
    # и «{e}» из них засчиталось бы этой — тот же класс ошибки, что
    # ловит вся эта задача, только в самом тесте
    хвост = исходник[начало:]
    кусок = хвост[:хвост.index("except httpx.HTTPError")]
    ответ = кусок[кусок.index("JSONResponse"):]
    assert "{e}" not in ответ, "техническая причина уезжает пользователю на экран"
    assert "вручную" in ответ, "не сказано, что делать вместо весов"


def test_ни_одна_ветка_привязки_весов_не_печатает_класс_исключения():
    """`AttributeError` на экране — это диагностика, и человеку она читается
    как его вина. Живой вход 2026-08-18 отдал бы ровно её."""
    исходник = (Path(__file__).resolve().parent.parent / "main.py").read_text(
        encoding="utf-8")
    начало = исходник.index("async def scale_connect")
    кусок = исходник[начало:исходник.index("conn = db.query(ScaleConnection)", начало)]
    ответы = [с for с in кусок.splitlines()
              if "JSONResponse" in с or ('"error"' in с and "status_code" not in с)]
    for строка in ответы:
        assert "type(e).__name__" not in строка, строка

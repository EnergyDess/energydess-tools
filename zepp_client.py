def трасса(включить: bool = True) -> None:
    """Включить/выключить подробный лог обмена из кода (тесты, разбор)."""
    global _ТРАССА
    _ТРАССА = bool(включить)


def трасса_включена() -> bool:
    return _ТРАССА


def _скрыть(данные):
    """Копия структуры с заменой значений секретных ключей на метку."""
    if isinstance(данные, dict):
        return {к: (МЕТКА if str(к).lower() in СКРЫТЬ_ЗНАЧЕНИЯ else _скрыть(з))
                for к, з in данные.items()}
    if isinstance(данные, (list, tuple)):
        return [_скрыть(з) for з in данные]
    return данные


def _адрес_без_почты(адрес: str, почта: str = "") -> str:
    """Путь шага tokens несёт почту прямо в себе — заменяем меткой.

    Не «обрезаем до домена»: остальной путь (`/registrations/…/tokens`)
    как раз и нужен, чтобы видеть, куда мы ходили."""
    if почта:
        for вариант in (quote(почта, safe=""), почта):
            if вариант and вариант in адрес:
                адрес = адрес.replace(вариант, "<почта скрыта>")
    return адрес


def _скрыть_в_адресе(адрес: str) -> str:
    """Location несёт код доступа параметром `access` — прячем значение,
    сам параметр оставляем: важно ВИДЕТЬ, что он пришёл."""
    if not адрес or "?" not in адрес:
        return адрес
    голова, _, запрос = адрес.partition("?")
    поля = parse_qs(запрос, keep_blank_values=True)
    безопасно = {к: [МЕТКА] if к.lower() in СКРЫТЬ_ЗНАЧЕНИЯ else з
                 for к, з in поля.items()}
    return голова + "?" + urlencode(безопасно, doseq=True)


def _тело_для_лога(текст: str) -> str:
    """Тело ответа ЦЕЛИКОМ. JSON — разобранный и с закрытыми секретами,
    прочее — как пришло. Обрезки нет намеренно: обрезанное тело и есть
    причина, по которой прошлую диагностику пришлось делать заново."""
    if not текст:
        return "<пустое тело>"
    try:
        return _json.dumps(_скрыть(_json.loads(текст)), ensure_ascii=True)
    except ValueError:
        return ascii(текст)


def _трасса_запроса(метод: str, адрес: str, поля=None, заголовки=None,
                    почта: str = "") -> None:
    if not _ТРАССА:
        return
    _печать(f"[zepp-trace] --> {метод} {_адрес_без_почты(адрес, почта)}")
    if поля is not None:
        показ = _скрыть(поля)
        _печать(f"[zepp-trace]     поля ({len(показ)}): "
              + ", ".join(f"{к}={ascii(з)}" for к, з in sorted(показ.items())))
    if заголовки:
        показ = _скрыть(dict(заголовки))
        _печать(f"[zepp-trace]     заголовки запроса ({len(показ)}): "
              + ", ".join(f"{к}={ascii(з)}" for к, з in sorted(показ.items())))


def _трасса_ответа(шаг: str, код: int, заголовки, тело: str,
                   мс: float) -> None:
    if not _ТРАССА:
        return
    ш = dict(заголовки or {})
    if "location" in {к.lower() for к in ш}:
        for к in list(ш):
            if к.lower() == "location":
                ш[к] = _скрыть_в_адресе(ш[к])
    ш = _скрыть(ш)
    _печать(f"[zepp-trace] <-- {шаг}: HTTP {код} за {мс:.0f} мс")
    _печать(f"[zepp-trace]     заголовки ответа ({len(ш)}): "
          + ", ".join(f"{к}={ascii(з)}" for к, з in sorted(ш.items())))
    _печать(f"[zepp-trace]     тело: {_тело_для_лога(тело)}")


def _обмен(client, метод: str, адрес: str, шаг: str, *, почта: str = "",
           **kw):
    """Один запрос с трассировкой до и после. Время меряется здесь, а не
    берётся из `response.elapsed`: подставные ответы в тестах его не имеют,
    и трассировка не должна их ронять."""
    _трасса_запроса(метод, адрес, поля=kw.get("data"),
                    заголовки=kw.get("headers"), почта=почта)
    t0 = time.perf_counter()
    r = getattr(client, метод.lower())(адрес, **kw)
    мс = (time.perf_counter() - t0) * 1000
    _трасса_ответа(шаг, getattr(r, "status_code", 0),
                   getattr(r, "headers", {}) or {},
                   getattr(r, "text", "") or "", мс)
    return r


def _печать(строка: str) -> None:
    """print, который НЕ МОЖЕТ уронить вход.

    ЗАМЕР 2026-08-18, сквозная проба через настоящий эндпоинт. Живой вход
    прошёл целиком — код доступа получен, токен получен, `result: ok`, —
    а следом весь обработчик упал `UnicodeEncodeError: 'charmap' codec
    can't encode character '→'`: в моей же новой строке разбора
    стояла стрелка `->` символом U+2192, которого нет в cp1251. Наружу
    ушло 502, в базе не появилось ничего.

    То есть диагностика сломала ровно то, что диагностировала, — и это
    ВТОРОЙ раз в этом файле (первый — китайский ответ сервиса, см. `_след`).
    Одного правила «не писать таких символов» мало: оно держится
    на внимательности каждого следующего.

    Кодировка потока вывода зависит от того, куда он направлен: консоль
    Windows отдаёт cp1251, файл журнала и Fly — utf-8. Поэтому строка
    прогоняется через фактическую кодировку с заменой непредставимого,
    а не проверяется на список символов.
    """
    try:
        print(строка)
    except UnicodeEncodeError:
        кодировка = getattr(sys.stdout, "encoding", None) or "ascii"
        print(строка.encode(кодировка, errors="replace").decode(кодировка,
                                                                errors="replace"))


def _след(шаг: str, поля: dict, отметить: tuple = ()) -> None:
    """Одна строка в лог про форму ответа: имена непустых полей и значения
    тех, что назвать безопасно.

    Именно имена, а не значения: в ответе шага входа лежат `access`,
    `app_token`, `login_token` — ключи к чужому аккаунту. Печатать их
    значит положить их в лог, который читают глазами и пересылают.

    Значения печатаются через `ascii()`. Сервис отвечает и по-китайски,
    а поток вывода не всегда UTF-8: на консоли cp1251 обычный `!r` роняет
    `print` с UnicodeEncodeError — и валит им ВЕСЬ вход, потому что строка
    стоит в его цепочке. Диагностика, способная сломать то, что она
    диагностирует, — это §6.0.1 наизнанку."""
    непустые = sorted(k for k, v in поля.items() if v not in (None, "", [], {}))
    названо = " ".join(f"{k}={ascii(поля.get(k))}" for k in отметить if k in поля)
    _печать(f"[zepp] {шаг}: непустые поля ({len(непустые)}): "
          f"{', '.join(непустые) or 'нет'}{(' | ' + названо) if названо else ''}")


def устройство(ключ: str) -> str:
    """Стабильный `device_id` — один и тот же у одного человека всегда.

    Форма MAC-адреса, а не 16 знаков hex, как было у мёртвой схемы Xiaomi:
    там это значение уходило кукой `deviceId` в Xiaomi, здесь — полем
    `device_id` в Huami, и все открытые реализации родной схемы шлют
    сюда MAC-подобную строку.

    Постоянство важно и без проверки личности, ради которой оно вводилось:
    Huami держит сессию на устройство, и новый идентификатор при каждом
    входе означает новую сессию каждый раз. Считается от ключа шифрования
    и id пользователя — отдельной колонки не нужно, миграции нет,
    при удалении аккаунта подчищать нечего."""
    сырое = hashlib.sha256(ключ.encode()).hexdigest()[:12]
    return ":".join(сырое[i:i + 2] for i in range(0, 12, 2))


def _код_доступа(client: httpx.Client, почта: str, пароль: str) -> tuple:
    """Шаг 1: почта и пароль -> код доступа. Возвращает (код, страна, регион).

    Единственный шаг, на котором вообще уместен вывод про учётные данные:
    выше него пароль ещё не отправлен, ниже — уже принят."""
    r = _обмен(
        client, "POST",
        f"https://{ХОСТ_ТОКЕНА}/registrations/{quote(почта, safe='')}/tokens",
        "tokens", почта=почта,
        data={
            "state": "REDIRECTION",
            "client_id": "HuaMi",
            "password": пароль,
            "redirect_uri": АДРЕС_ВОЗВРАТА,
            "token": "access",
        },
        headers=ЗАГОЛОВКИ_ВЕБ_КАБИНЕТА,
        follow_redirects=False,
    )
    адрес = r.headers.get("location")
    _печать(f"[zepp] tokens: HTTP {r.status_code} location={'есть' if адрес else 'НЕТ'}")

    if r.status_code != 303 or not адрес:
        # Ответ не той формы. ЧТО ИМЕННО СЛОМАЛОСЬ — НЕ УТВЕРЖДАЕМ.
        #
        # Здесь стояло «— изменился флоу», и это была наша догадка, которую
        # сервис не подтверждал ничем. Она же уезжала пользователю на экран.
        # Живой разбор 2026-08-18 показал, что догадка была НЕВЕРНА: 429
        # приходил не от смены протокола и не от частоты запросов, а оттого,
        # что мы не представлялись веб-кабинетом. Утверждение о причине,
        # выведенное из формы ответа, — это тот же немой отказ, только
        # словами: выглядит как диагноз, а диагнозом не является.
        код_сервиса, текст_сервиса = _код_из_тела(r.text)
        известно = КОДЫ_ШАГА.get(код_сервиса)
        подробно = (f"шаг tokens: HTTP {r.status_code} вместо 303"
                    + (f", location {'есть' if адрес else 'НЕТ'}")
                    + (f", код сервиса {код_сервиса}" if код_сервиса else "")
                    + (f", сообщение {ascii(текст_сервиса)}" if текст_сервиса else "")
                    + (f"; тело {ascii(r.text[:200])}" if r.text and not код_сервиса
                       else ""))
        if известно:
            raise ZeppProtocolError(f"{известно} [{подробно}]")
        raise ZeppProtocolError(f"ответ не опознан [{подробно}]")

    параметры = parse_qs(urlparse(адрес).query)
    _след("tokens", {k: v[0] for k, v in параметры.items()},
          отметить=("error", "region", "country_code", "state"))
    код = (параметры.get("access") or [""])[0]

    if not код:
        отказ = (параметры.get("error") or [""])[0]
        if отказ in КОДЫ_ТОКЕНА:
            raise ZeppAuthError(f"{КОДЫ_ТОКЕНА[отказ]} (код {отказ})")
        if отказ:
            # Незнакомый код наружу как есть. В том числе поэтому здесь нет
            # ветки «наверное, требуется подтверждение»: если сервис однажды
            # такое пришлёт, мы увидим его настоящий код, а не нашу догадку
            raise ZeppProtocolError(
                f"ответ не опознан [Zepp Life отказал незнакомым кодом "
                f"{отказ}; поля ответа: "
                f"{', '.join(sorted(параметры)) or 'нет'}]")
        # Причину НЕ называем: 303 без обоих полей мы вживую не видели
        # ни разу, и «изменился флоу» здесь было бы такой же непроверенной
        # догадкой, как та, что стояла выше до 2026-08-18
        raise ZeppProtocolError(
            f"ответ не опознан [шаг tokens: HTTP 303, но нет ни кода доступа, "
            f"ни кода отказа; поля: {', '.join(sorted(параметры)) or 'нет'}]")

    страна = (параметры.get("country_code") or [""])[0]
    if not страна:
        страна = СТРАНА_ПО_УМОЛЧАНИЮ
        _печать(f"[zepp] tokens: страны в ответе нет, подставлена {страна} — "
              f"если вход дальше не пройдёт, причина может быть здесь")
    регион = (параметры.get("region") or [""])[0]
    return код, страна, регион


def _хост_данных(домены) -> tuple:
    """Где лежат измерения ИМЕННО ЭТОГО аккаунта. Возвращает (хост, разбор).

    ФОРМА ПОЛЯ ПРИШЛА ЖИВЫМ ОТВЕТОМ, А НЕ ИЗ ЧУЖОГО РЕПОЗИТОРИЯ.
    До 2026-08-18 код читал `domains` как словарь `{"api-mifit": "хост"}` —
    это предположение, взятое на веру, и оно НЕВЕРНО. Настоящий ответ:

        "domains": [{"cnames": ["api-mifit-cn3.zepp.com"],
                     "host": "api-mifit.zepp.com"}, …]

    то есть СПИСОК записей. Прежний код падал на нём `AttributeError:
    'list' object has no attribute 'get'` — и падал уже ПОСЛЕ успешного
    входа, то есть вход выглядел сломанным ровно там, где он сработал.

    Словарная форма всё же обрабатывается: у нас нет доказательства, что
    её не бывает у других регионов, а стоит она три строки. Незнакомая
    форма не молчит — она возвращается в разборе строкой, и её видно
    в логе рядом с подставленным хостом по умолчанию.
    """
    if isinstance(домены, list):
        for запись in домены:
            if not isinstance(запись, dict):
                continue
            хост = запись.get("host") or ""
            if "api-mifit" not in хост:
                continue
            # cname — региональное имя того же хоста. Берём его, когда есть:
            # общий `api-mifit.zepp.com` отвечает не для всех регионов
            cnames = [c for c in (запись.get("cnames") or []) if c]
            выбран = cnames[0] if cnames else хост
            return выбран, (f"список из {len(домены)}, api-mifit -> {выбран}"
                            + (f" (общий {хост})" if cnames else ""))
        return (ХОСТ_ДАННЫХ_ПО_УМОЛЧАНИЮ,
                f"список из {len(домены)}, записи про api-mifit НЕТ")
    if isinstance(домены, dict):
        хост = домены.get("api-mifit") or ХОСТ_ДАННЫХ_ПО_УМОЛЧАНИЮ
        return хост, f"словарь из {len(домены)}, api-mifit -> {хост}"
    return (ХОСТ_ДАННЫХ_ПО_УМОЛЧАНИЮ,
            f"НЕЗНАКОМАЯ форма {type(домены).__name__}, подставлен хост по умолчанию")


def login(username: str, password: str, ключ_устройства: str = "") -> dict:
    """Полный вход по паролю. Возвращает
    {"app_token": …, "zepp_user_id": …, "data_host": …}.

    Зовётся только при подключении весов и при повторном подключении после
    протухшего токена: пароль нигде не хранится, и сами мы перелогиниться
    не можем (см. main.ScaleReauthNeeded).

    `ключ_устройства` — то, из чего считается постоянный `device_id`
    (см. `устройство`). Пустой означает «устройство от пустого ключа»:
    так вызывать не надо, но и падать из-за этого незачем."""
    device_id = устройство(ключ_устройства)
    _печать(f"[zepp] устройство …{device_id[-5:]} (постоянное для пользователя)")
    with httpx.Client(timeout=30.0) as client:
        код, страна, регион = _код_доступа(client, username, password)
        _печать(f"[zepp] код доступа получен, страна={страна} регион={регион or 'не назван'}")

        r = _обмен(
            client, "POST", f"https://{ХОСТ_ВХОДА}/v2/client/login",
            "client/login",
            headers=ЗАГОЛОВКИ_ВЕБ_КАБИНЕТА,
            data={
                "app_name": "com.xiaomi.hm.health",
                "app_version": "6.14.0",
                "code": код,
                "country_code": страна,
                "device_id": device_id,
                "device_model": "android_phone",
                # Список доменов, которые сервис должен разложить по региону.
                # Ответ на него — поле `domains`, и это ЕДИНСТВЕННЫЙ способ
                # узнать, на каком хосте лежат данные именно этого аккаунта
                "dn": "api-user.zepp.com,api-mifit.zepp.com,app-analytics.zepp.com",
                "grant_type": "access_token",
                # Родная схема Huami. У мёртвой схемы Xiaomi тут стояло
                # "xiaomi-hm-mifit" — это и есть отличие двух входов в одном поле
                "third_name": "huami",
                "source": "com.xiaomi.hm.health",
                "allow_registration": "false",
                "lang": "ru",
            },
            follow_redirects=False,
        )
        try:
            data = r.json()
        except ValueError:
            raise ZeppStepError(
                f"шаг client/login ответил HTTP {r.status_code} не в JSON "
                f"({ascii(r.text[:120])})")

        token_info = data.get("token_info") or {}
        _след("client/login", data, отметить=("error_code", "result", "msg"))

        app_token = token_info.get("app_token")
        zepp_user_id = token_info.get("user_id")
        if not app_token or not zepp_user_id:
            # Пароль ПРИНЯТ — код доступа мы уже получили. Что бы здесь ни
            # сломалось, сказать про пароль нельзя ни одним словом
            код_ошибки = data.get("error_code")
            raise ZeppStepError(
                f"почта и пароль приняты, но шаг client/login не отдал токен "
                f"(HTTP {r.status_code}"
                f"{', error_code ' + str(код_ошибки) if код_ошибки else ''}; "
                f"поля ответа: {', '.join(sorted(data)) or 'нет'}; "
                f"token_info: {', '.join(sorted(token_info)) or 'нет'})")

        # Где лежат данные ИМЕННО ЭТОГО аккаунта. Замер 2026-08-14 показал,
        # что все хосты api-mifit* отвечают на негодный токен одинаково, —
        # то есть проверить регион снаружи нечем, и единственный источник
        # правды здесь этот. Без него европейский аккаунт отдавал бы 401
        # на живом токене, а это в интерфейсе выглядит как «протух токен»,
        # то есть предложение вводить пароль по кругу (§6.0.1)
        хост, разбор = _хост_данных(data.get("domains"))
        _печать(f"[zepp] domains: {разбор}; хост данных = {хост}")
        return {"app_token": app_token, "zepp_user_id": str(zepp_user_id),
                "data_host": хост}


def fetch_weight_records(app_token: str, zepp_user_id: str, limit: int = 30,
                         data_host: str = "") -> dict:
    """Измерения главного пользователя аккаунта (member -1 — без привязки
    к «членам семьи» в Zepp).

    ВОЗВРАЩАЕТ СЛОВАРЬ, А НЕ СПИСОК, и это не косметика. Пустой список
    отвечал сразу на два разных вопроса: «в аккаунте нет измерений»
    и «измерения есть, но ни одно не разобралось». Первое — норма, второе —
    отказ, и в интерфейсе они выглядели одинаково («синхронизировано: 0»).

    Разделено так:
      · сбой формы ответа (нет поля `items` вовсе) — исключение, не пустота;
      · пустая история — `total = 0`, и это НЕ ошибка;
      · записи есть, но отброшены — видно по `dropped`.
    """
    записи = []
    to_time = int(time.time())
    хост = data_host or ХОСТ_ДАННЫХ_ПО_УМОЛЧАНИЮ
    всего = страниц = 0
    отброшено = {"weightType": 0, "без summary": 0, "без веса": 0}
    напечатан_состав = False    # список полей — один раз за выборку, а не за страницу

    with httpx.Client(timeout=30.0, headers={"apptoken": app_token}) as client:
        while len(записи) < limit:
            r = _обмен(
                client, "GET",
                f"https://{хост}/users/{zepp_user_id}/members/-1/weightRecords",
                "weightRecords",
                params={"limit": 200, "toTime": to_time},
            )
            if r.status_code == 401:
                # Тело печатаем: замер даёт {"code":0,"message":"invalid token",
                # "data":{"code":"0102"}}, и если однажды придёт другое, будет
                # видно, что 401 не про токен, а про что-то ещё
                raise ZeppApiError(
                    f"токен не принят хостом {хост} "
                    f"({ascii(r.text[:160])}) — нужен повторный вход")
            r.raise_for_status()
            data = r.json()
            страниц += 1

            if "items" not in data:
                # Пустая история приходит как items: [] — отсутствие самого
                # поля означает, что изменился формат. Молча вернуть отсюда
                # пустой список значило бы показать поломку как «нет измерений»
                raise ZeppProtocolError(
                    f"в ответе weightRecords нет поля items "
                    f"(поля: {', '.join(sorted(data)) or 'нет'}) — изменился формат")
            items = data.get("items") or []
            всего += len(items)
            if not items:
                break

            # Какие поля состава тела реально пришли — печатаем ОДИН раз
            # за выборку. Живого ответа у разработчика нет (аккаунт весов
            # только у владельца), и до этой строки список показателей
            # приходилось брать из чужого репозитория и верить ему
            if not напечатан_состав:
                образец = next((i.get("summary") for i in items if i.get("summary")), None)
                if образец:
                    поля = sorted(образец.keys())
                    мимо = [п for п in поля if п not in РАЗБИРАЕМ.values()]
                    нет_у_них = [н for н in РАЗБИРАЕМ.values() if н not in поля]
                    _печать(f"[zepp] поля summary в ответе ({len(поля)}): {', '.join(поля)}")
                    _печать(f"[zepp] из них мы НЕ разбираем ({len(мимо)}): {', '.join(мимо) or 'нет'}")
                    _печать(f"[zepp] мы ждём, а их нет ({len(нет_у_них)}): "
                          f"{', '.join(нет_у_них) or 'нет'}")
                    напечатан_состав = True
                else:
                    _печать(f"[zepp] на странице {страниц} ни у одной записи нет summary — "
                          f"состава тела в них не будет, только вес")

            for item in items:
                if item.get("weightType") != 0:
                    отброшено["weightType"] += 1
                    continue    # повреждённые значения, см. weightType в API
                # `or {}`, а не `get("summary", {})`. Разница не косметическая:
                # у записи, заведённой в приложении РУКАМИ (а такие есть у всех,
                # кто вводил вес до покупки весов), поле приходит как null,
                # и прежний код падал на нём AttributeError — то есть одна
                # старая запись роняла синхронизацию целиком
                s = item.get("summary") or {}
                if not s:
                    отброшено["без summary"] += 1
                if s.get("weight") is None:
                    отброшено["без веса"] += 1
                    continue
                записи.append({
                    "timestamp": item.get("generatedTime"),
                    **{наше: s.get(ихнее) for наше, ихнее in РАЗБИРАЕМ.items()},
                })

            next_ts = data.get("next", 0)
            if not next_ts or next_ts >= to_time:
                break
            to_time = next_ts

    _печать(f"[zepp] выборка с {хост}: страниц {страниц}, записей получено {всего}, "
          f"годных {len(записи)}, отброшено "
          f"{', '.join(f'{k} {v}' for k, v in отброшено.items() if v) or 'нет'}")
    if всего == 0:
        # Прямо в лог, словами: иначе следующий разбор начнётся с вопроса,
        # был ли это пустой аккаунт или отказ, который мы проглотили
        _печать("[zepp] история измерений пуста — это НЕ сбой, аккаунт отвечает исправно")
    return {"records": записи[:limit], "total": всего, "pages": страниц,
            "dropped": отброшено, "host": хост}

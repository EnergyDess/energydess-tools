def _код_из_тела(текст: str) -> tuple:
    """(код, сообщение) из тела ответа. Оба None, если тело не JSON.

    Нужно затем, что Huami кладёт причину отказа В ТЕЛО, а не в параметр
    `error`: `{"code":12,"message":"too many requests"}`. Прежний разбор
    тела не читал вовсе и печатал первые 120 символов как есть."""
    if not текст:
        return None, None
    try:
        данные = _json.loads(текст)
    except ValueError:
        return None, None
    if not isinstance(данные, dict):
        return None, None
    код = данные.get("code")
    return (код if isinstance(код, int) else None), данные.get("message")



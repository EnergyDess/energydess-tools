# -*- coding: utf-8 -*-
"""Неофициальный клиент Zepp Life (Huami) для получения измерений с умных
весов (Mi Body Composition Scale). Официального API не существует.

С 2026-08-14 здесь ТОЛЬКО родная схема Huami: почта + пароль аккаунта
Zepp Life. Схема через аккаунт Xiaomi (OAuth2 на account.xiaomi.com,
проверка личности, обмен кода) удалена целиком — не отключена флагом,
не оставлена запасной, а удалена.

ПОЧЕМУ УДАЛЕНА, А НЕ ОСТАВЛЕНА ЗАПАСНОЙ. Она упиралась в замкнутый круг,
пройденный живым пользователем дважды: вход → «подтвердите личность» →
проверка по ссылке с кодом из почты → 404 `routes not found` → повторный
вход → снова «подтвердите личность». 404 при этом отдавал НАШ же
`redirect_uri` (`api-mifit-cn.huami.com/huami.health.loginview.do`) —
адрес возврата в мобильное приложение Zepp, которого у нас нет. Отметка
«устройству доверяем» привязывается к сессии браузера, в котором человек
проходил проверку, и на наш сервер не переносится; поток рассчитан на
собственные приложения Xiaomi.

Держать её второй веткой было нельзя по отдельной причине: почта
у пользователя на аккаунте Xiaomi и на аккаунте Zepp Life ОДНА И ТА ЖЕ,
то есть выбрать схему по адресу невозможно. Любой автовыбор вернул бы
в тот же круг, и — главное — стало бы неотличимо, схема виновата или
что-то ещё (§6.0.1: отказ, который выглядит как другой отказ).

ЧЕМ РОДНАЯ СХЕМА ОТЛИЧАЕТСЯ ПО УСТРОЙСТВУ. Браузер пользователя
в обмене не участвует вообще: два серверных POST через httpx,
`follow_redirects=False`, ответ читается из заголовка `Location`.
Проверки личности в ней нет — ни капчи, ни кода из почты, ни страницы
Xiaomi (замер 2026-08-14: неверные данные дают ровно `error=401`
и больше ничего).

Замеры формы ответов (2026-08-14, живые запросы с заведомо
несуществующим адресом — учётных данных у разработчика нет):

    POST https://api-user.zepp.com/registrations/{почта}/tokens
      верные данные   → 303, Location …?access=<токен>&country_code=..&region=..
      неверные        → 303, Location …?error=401&state=REDIRECTION&region=eu-central-1
      кривой запрос   → 400, тело '"HuaMi Oauth / User Registration 2.0.2"'
    POST https://account.zepp.com/v2/client/login
      негодный code   → 400, тело {"error_code":"0104"}
    GET  https://api-mifit.zepp.com/users/{id}/members/-1/weightRecords
      негодный токен  → 401, тело {"code":0,"message":"invalid token","data":{"code":"0102"}}

`redirect_uri` и `client_id` ОБЯЗАТЕЛЬНЫ (без любого из них — 400,
проверено обоими вариантами), и `redirect_uri` возвращается эхом
в `Location`. Он не является маршрутом, который кто-то открывает:
мы читаем заголовок и по адресу не ходим — проверено подстановкой
своего адреса, ответ не изменился. Это ровно то, чем он отличается
от `redirect_uri` мёртвой схемы Xiaomi, куда УПИРАЛСЯ БРАУЗЕР человека.
"""
import hashlib
import time
from urllib.parse import parse_qs, quote, urlparse

import httpx

# Хосты. Домены zepp.com и huami.com отвечают одинаково (замер: обе пары
# дают побайтово тот же ответ) — берём zepp.com, как и остальной проект.
ХОСТ_ТОКЕНА = "api-user.zepp.com"       # шаг 1: почта+пароль → код доступа
ХОСТ_ВХОДА = "account.zepp.com"         # шаг 2: код доступа → app_token
ХОСТ_ДАННЫХ_ПО_УМОЛЧАНИЮ = "api-mifit.zepp.com"   # шаг 3: измерения

# Адрес возврата. Никем не открывается (см. шапку), но обязателен: без него
# сервис отвечает 400. Значение — то же, что у всех открытых реализаций
# родной схемы; своё подставлять незачем, ответ от этого не меняется.
АДРЕС_ВОЗВРАТА = "https://s3-us-west-2.amazonaws.com/hm-registration/successsignin.html"

# Соответствие «наше имя → имя в API». Отдельной картой, а не россыпью
# по коду: тот же список нужен диагностике, чтобы напечатать, каких
# ожидаемых полей в ответе НЕ оказалось.
# «Возраст тела» в API называется muscleAge — это не опечатка.
РАЗБИРАЕМ = {
    "weight_kg": "weight",
    "bmi": "bmi",
    "body_fat_pct": "fatRate",
    "water_pct": "bodyWaterRate",
    "muscle_rate_pct": "muscleRate",
    "bone_mass_kg": "boneMass",
    "visceral_fat": "visceralFat",
    "bmr": "metabolism",
    "body_age": "muscleAge",
}

# Страна нужна шагу входа. Обычно приходит сама с шагом 1; если не пришла,
# подставляем это и ГОВОРИМ об этом в лог — молчаливая подстановка сделала бы
# отказ входа необъяснимым.
СТРАНА_ПО_УМОЛЧАНИЮ = "RU"


class ZeppLoginError(Exception):
    """База для всех отказов входа. Ловить её одну можно только там, где
    различие между причинами действительно не нужно."""


class ZeppAuthError(ZeppLoginError):
    """Сервис назвал причину, и причина в учётных данных: не та почта,
    не тот пароль. Единственный класс, при котором «проверьте логин
    и пароль» — правда."""


class ZeppProtocolError(ZeppLoginError):
    """Ответ не разобрался: не тот код HTTP, нет Location, нет ни `access`,
    ни `error`, либо код отказа нам незнаком. Реверс-инжиниринг разошёлся
    с реальностью — чинится правкой этого файла, а не действиями человека.

    Сюда же уходит НЕЗНАКОМЫЙ код отказа, вместе с самим кодом. Схлопывать
    его в «неверный пароль» нельзя: следующая причина отказа стала бы
    неотличима от опечатки, и разбирать её было бы нечем."""


class ZeppStepError(ZeppLoginError):
    """Почту и пароль сервис ПРИНЯЛ, а дальше цепочка не поехала.

    Отдельный класс нужен затем, что ниже него ни одна ветка не вправе
    сказать «проверьте пароль»: пароль уже проверен и принят. Несёт имя
    шага — человеку оно бесполезно, но именно оно отличает «сервис просит
    ещё одно действие» от «наш код разошёлся с флоу»."""


class ZeppApiError(Exception):
    """Вход прошёл, но запрос данных не удался (истёк токен и т. п.)."""


# Коды отказа шага 1. Список заведомо неполный — именно поэтому незнакомый
# код НЕ схлопывается в «неверный пароль», а уезжает наружу как есть.
КОДЫ_ТОКЕНА = {
    "401": "Zepp Life не принял почту или пароль",
}


def _след(шаг: str, поля: dict, отметить: tuple = ()) -> None:
    """Одна строка в лог про форму ответа: имена непустых полей и значения
    тех, что назвать безопасно.

    Именно имена, а не значения: в ответе шага входа лежат `access`,
    `app_token`, `login_token` — ключи к чужому аккаунту. Печатать их
    значит положить их в лог, который читают глазами и пересылают.

    Значения печатаются через `ascii()`. Сервис отвечает и по-китайски,
    а поток вывода не всегда UTF-8: на консоли cp1251 обычный `!r` роняет
    `print` с UnicodeEncodeError — и валит им ВЕСЬ вход, потому что строка
    стоит в его цепочке. Диагностика, способная сломать то, что она
    диагностирует, — это §6.0.1 наизнанку."""
    непустые = sorted(k for k, v in поля.items() if v not in (None, "", [], {}))
    названо = " ".join(f"{k}={ascii(поля.get(k))}" for k in отметить if k in поля)
    print(f"[zepp] {шаг}: непустые поля ({len(непустые)}): "
          f"{', '.join(непустые) or 'нет'}{(' | ' + названо) if названо else ''}")


def устройство(ключ: str) -> str:
    """Стабильный `device_id` — один и тот же у одного человека всегда.

    Форма MAC-адреса, а не 16 знаков hex, как было у мёртвой схемы Xiaomi:
    там это значение уходило кукой `deviceId` в Xiaomi, здесь — полем
    `device_id` в Huami, и все открытые реализации родной схемы шлют
    сюда MAC-подобную строку.

    Постоянство важно и без проверки личности, ради которой оно вводилось:
    Huami держит сессию на устройство, и новый идентификатор при каждом
    входе означает новую сессию каждый раз. Считается от ключа шифрования
    и id пользователя — отдельной колонки не нужно, миграции нет,
    при удалении аккаунта подчищать нечего."""
    сырое = hashlib.sha256(ключ.encode()).hexdigest()[:12]
    return ":".join(сырое[i:i + 2] for i in range(0, 12, 2))


def _код_доступа(client: httpx.Client, почта: str, пароль: str) -> tuple:
    """Шаг 1: почта и пароль → код доступа. Возвращает (код, страна, регион).

    Единственный шаг, на котором вообще уместен вывод про учётные данные:
    выше него пароль ещё не отправлен, ниже — уже принят."""
    r = client.post(
        f"https://{ХОСТ_ТОКЕНА}/registrations/{quote(почта, safe='')}/tokens",
        data={
            "state": "REDIRECTION",
            "client_id": "HuaMi",
            "password": пароль,
            "redirect_uri": АДРЕС_ВОЗВРАТА,
            "token": "access",
        },
        follow_redirects=False,
    )
    адрес = r.headers.get("location")
    print(f"[zepp] tokens: HTTP {r.status_code} location={'есть' if адрес else 'НЕТ'}")

    if r.status_code != 303 or not адрес:
        # Замер: так отвечает кривой запрос (нет redirect_uri, нет client_id) —
        # тело '"HuaMi Oauth / User Registration 2.0.2"'. То есть это ВСЕГДА
        # наша поломка, а не пароль пользователя
        raise ZeppProtocolError(
            f"шаг tokens ответил HTTP {r.status_code} вместо 303 "
            f"({ascii(r.text[:120]) if r.text else 'пустое тело'}) — изменился флоу")

    параметры = parse_qs(urlparse(адрес).query)
    _след("tokens", {k: v[0] for k, v in параметры.items()},
          отметить=("error", "region", "country_code", "state"))
    код = (параметры.get("access") or [""])[0]

    if not код:
        отказ = (параметры.get("error") or [""])[0]
        if отказ in КОДЫ_ТОКЕНА:
            raise ZeppAuthError(f"{КОДЫ_ТОКЕНА[отказ]} (код {отказ})")
        if отказ:
            # Незнакомый код наружу как есть. В том числе поэтому здесь нет
            # ветки «наверное, требуется подтверждение»: если сервис однажды
            # такое пришлёт, мы увидим его настоящий код, а не нашу догадку
            raise ZeppProtocolError(
                f"Zepp Life отказал незнакомым кодом {отказ} "
                f"(поля ответа: {', '.join(sorted(параметры)) or 'нет'})")
        raise ZeppProtocolError(
            f"в ответе шага tokens нет ни кода доступа, ни кода отказа "
            f"(поля: {', '.join(sorted(параметры)) or 'нет'}) — изменился флоу")

    страна = (параметры.get("country_code") or [""])[0]
    if not страна:
        страна = СТРАНА_ПО_УМОЛЧАНИЮ
        print(f"[zepp] tokens: страны в ответе нет, подставлена {страна} — "
              f"если вход дальше не пройдёт, причина может быть здесь")
    регион = (параметры.get("region") or [""])[0]
    return код, страна, регион


def login(username: str, password: str, ключ_устройства: str = "") -> dict:
    """Полный вход по паролю. Возвращает
    {"app_token": …, "zepp_user_id": …, "data_host": …}.

    Зовётся только при подключении весов и при повторном подключении после
    протухшего токена: пароль нигде не хранится, и сами мы перелогиниться
    не можем (см. main.ScaleReauthNeeded).

    `ключ_устройства` — то, из чего считается постоянный `device_id`
    (см. `устройство`). Пустой означает «устройство от пустого ключа»:
    так вызывать не надо, но и падать из-за этого незачем."""
    device_id = устройство(ключ_устройства)
    print(f"[zepp] устройство …{device_id[-5:]} (постоянное для пользователя)")
    with httpx.Client(timeout=30.0) as client:
        код, страна, регион = _код_доступа(client, username, password)
        print(f"[zepp] код доступа получен, страна={страна} регион={регион or 'не назван'}")

        r = client.post(
            f"https://{ХОСТ_ВХОДА}/v2/client/login",
            data={
                "app_name": "com.xiaomi.hm.health",
                "app_version": "6.14.0",
                "code": код,
                "country_code": страна,
                "device_id": device_id,
                "device_model": "android_phone",
                # Список доменов, которые сервис должен разложить по региону.
                # Ответ на него — поле `domains`, и это ЕДИНСТВЕННЫЙ способ
                # узнать, на каком хосте лежат данные именно этого аккаунта
                "dn": "api-user.zepp.com,api-mifit.zepp.com,app-analytics.zepp.com",
                "grant_type": "access_token",
                # Родная схема Huami. У мёртвой схемы Xiaomi тут стояло
                # "xiaomi-hm-mifit" — это и есть отличие двух входов в одном поле
                "third_name": "huami",
                "source": "com.xiaomi.hm.health",
                "allow_registration": "false",
                "lang": "ru",
            },
            follow_redirects=False,
        )
        try:
            data = r.json()
        except ValueError:
            raise ZeppStepError(
                f"шаг client/login ответил HTTP {r.status_code} не в JSON "
                f"({ascii(r.text[:120])})")

        token_info = data.get("token_info") or {}
        _след("client/login", data, отметить=("error_code", "result", "msg"))

        app_token = token_info.get("app_token")
        zepp_user_id = token_info.get("user_id")
        if not app_token or not zepp_user_id:
            # Пароль ПРИНЯТ — код доступа мы уже получили. Что бы здесь ни
            # сломалось, сказать про пароль нельзя ни одним словом
            код_ошибки = data.get("error_code")
            raise ZeppStepError(
                f"почта и пароль приняты, но шаг client/login не отдал токен "
                f"(HTTP {r.status_code}"
                f"{', error_code ' + str(код_ошибки) if код_ошибки else ''}; "
                f"поля ответа: {', '.join(sorted(data)) or 'нет'}; "
                f"token_info: {', '.join(sorted(token_info)) or 'нет'})")

        # Где лежат данные ИМЕННО ЭТОГО аккаунта. Замер 2026-08-14 показал,
        # что все хосты api-mifit* отвечают на негодный токен одинаково, —
        # то есть проверить регион снаружи нечем, и единственный источник
        # правды здесь этот. Без него европейский аккаунт отдавал бы 401
        # на живом токене, а это в интерфейсе выглядит как «протух токен»,
        # то есть предложение вводить пароль по кругу (§6.0.1)
        домены = data.get("domains") or {}
        хост = домены.get("api-mifit") or ХОСТ_ДАННЫХ_ПО_УМОЛЧАНИЮ
        print(f"[zepp] domains в ответе ({len(домены)}): "
              f"{', '.join(f'{k}={v}' for k, v in sorted(домены.items())) or 'поля нет'}; "
              f"хост данных = {хост}")
        return {"app_token": app_token, "zepp_user_id": str(zepp_user_id),
                "data_host": хост}


def fetch_weight_records(app_token: str, zepp_user_id: str, limit: int = 30,
                         data_host: str = "") -> dict:
    """Измерения главного пользователя аккаунта (member -1 — без привязки
    к «членам семьи» в Zepp).

    ВОЗВРАЩАЕТ СЛОВАРЬ, А НЕ СПИСОК, и это не косметика. Пустой список
    отвечал сразу на два разных вопроса: «в аккаунте нет измерений»
    и «измерения есть, но ни одно не разобралось». Первое — норма, второе —
    отказ, и в интерфейсе они выглядели одинаково («синхронизировано: 0»).

    Разделено так:
      · сбой формы ответа (нет поля `items` вовсе) — исключение, не пустота;
      · пустая история — `total = 0`, и это НЕ ошибка;
      · записи есть, но отброшены — видно по `dropped`.
    """
    записи = []
    to_time = int(time.time())
    хост = data_host or ХОСТ_ДАННЫХ_ПО_УМОЛЧАНИЮ
    всего = страниц = 0
    отброшено = {"weightType": 0, "без summary": 0, "без веса": 0}
    напечатан_состав = False    # список полей — один раз за выборку, а не за страницу

    with httpx.Client(timeout=30.0, headers={"apptoken": app_token}) as client:
        while len(записи) < limit:
            r = client.get(
                f"https://{хост}/users/{zepp_user_id}/members/-1/weightRecords",
                params={"limit": 200, "toTime": to_time},
            )
            if r.status_code == 401:
                # Тело печатаем: замер даёт {"code":0,"message":"invalid token",
                # "data":{"code":"0102"}}, и если однажды придёт другое, будет
                # видно, что 401 не про токен, а про что-то ещё
                raise ZeppApiError(
                    f"токен не принят хостом {хост} "
                    f"({ascii(r.text[:160])}) — нужен повторный вход")
            r.raise_for_status()
            data = r.json()
            страниц += 1

            if "items" not in data:
                # Пустая история приходит как items: [] — отсутствие самого
                # поля означает, что изменился формат. Молча вернуть отсюда
                # пустой список значило бы показать поломку как «нет измерений»
                raise ZeppProtocolError(
                    f"в ответе weightRecords нет поля items "
                    f"(поля: {', '.join(sorted(data)) or 'нет'}) — изменился формат")
            items = data.get("items") or []
            всего += len(items)
            if not items:
                break

            # Какие поля состава тела реально пришли — печатаем ОДИН раз
            # за выборку. Живого ответа у разработчика нет (аккаунт весов
            # только у владельца), и до этой строки список показателей
            # приходилось брать из чужого репозитория и верить ему
            if not напечатан_состав:
                образец = next((i.get("summary") for i in items if i.get("summary")), None)
                if образец:
                    поля = sorted(образец.keys())
                    мимо = [п for п in поля if п not in РАЗБИРАЕМ.values()]
                    нет_у_них = [н for н in РАЗБИРАЕМ.values() if н not in поля]
                    print(f"[zepp] поля summary в ответе ({len(поля)}): {', '.join(поля)}")
                    print(f"[zepp] из них мы НЕ разбираем ({len(мимо)}): {', '.join(мимо) or 'нет'}")
                    print(f"[zepp] мы ждём, а их нет ({len(нет_у_них)}): "
                          f"{', '.join(нет_у_них) or 'нет'}")
                    напечатан_состав = True
                else:
                    print(f"[zepp] на странице {страниц} ни у одной записи нет summary — "
                          f"состава тела в них не будет, только вес")

            for item in items:
                if item.get("weightType") != 0:
                    отброшено["weightType"] += 1
                    continue    # повреждённые значения, см. weightType в API
                # `or {}`, а не `get("summary", {})`. Разница не косметическая:
                # у записи, заведённой в приложении РУКАМИ (а такие есть у всех,
                # кто вводил вес до покупки весов), поле приходит как null,
                # и прежний код падал на нём AttributeError — то есть одна
                # старая запись роняла синхронизацию целиком
                s = item.get("summary") or {}
                if not s:
                    отброшено["без summary"] += 1
                if s.get("weight") is None:
                    отброшено["без веса"] += 1
                    continue
                записи.append({
                    "timestamp": item.get("generatedTime"),
                    **{наше: s.get(ихнее) for наше, ихнее in РАЗБИРАЕМ.items()},
                })

            next_ts = data.get("next", 0)
            if not next_ts or next_ts >= to_time:
                break
            to_time = next_ts

    print(f"[zepp] выборка с {хост}: страниц {страниц}, записей получено {всего}, "
          f"годных {len(записи)}, отброшено "
          f"{', '.join(f'{k} {v}' for k, v in отброшено.items() if v) or 'нет'}")
    if всего == 0:
        # Прямо в лог, словами: иначе следующий разбор начнётся с вопроса,
        # был ли это пустой аккаунт или отказ, который мы проглотили
        print("[zepp] история измерений пуста — это НЕ сбой, аккаунт отвечает исправно")
    return {"records": записи[:limit], "total": всего, "pages": страниц,
            "dropped": отброшено, "host": хост}
